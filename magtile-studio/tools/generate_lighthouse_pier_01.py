#!/usr/bin/env python3
"""生成模型 data/models/lighthouse_pier_01.json (灯塔栈桥)。

水下/海洋主题: 与 lighthouse_01 (六边形/扇形扩展片圆塔) 刻意区分 ——
本作只用核心九片型 (core-9), 结构逻辑是 "岸-桥-台-塔" 一条动线:
岸端 2x3 石砌岸台上安置看守小屋 (门朝栈桥, 双山墙), 一条 1 格宽
的箱形栈桥 (闭环侧壁 + 满铺桥面) 伸进海里, 桥头展宽成 2x2 灯塔
平台, 方形灯塔从平台拔起三层 (顶层四面窗格方灯室), 再戴等腰
四坡尖顶 (塔尖 5.94); 桥面与平台沿口列女儿墙护齿, 岸边立航标
高塔尖与防波礁石, 海面用长方形水面板向东铺开。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 岸台 (x [0,2], y [0,3]): 石板满铺 x6                          6 片
  - 海面: 长方形水面板 x4 (栈桥两侧各 2, 短边吸岸台)               4 片
  - 看守小屋 (x [0,1], y [0,2], z 0..1): 墙环 x6 (含门框方 x1
    + 窗格方 x1) + 屋顶板 x2 + 山墙尖 x2                         10 片
  - 栈桥 (x [2,7], y [1,2], z 0..1): 侧壁 x11 + 桥面 x5          16 片
  - 灯塔平台 (x [7,9], y [0,2], z 0..1): 环壁 x7 + 台面 x4       11 片
  - 灯塔 (x [7,8], y [0,1], z 1..4): 三层墙环 x12 (门框方塔门
    x1 + 窗格方 x5, 顶层四面灯室) + 等腰四坡尖顶 x4 (塔尖 5.94)  16 片
  - 女儿墙护齿: 等边三角 x6 (桥面南沿 x2 + 平台东/北沿 x4)         6 片
  - 航标塔尖: 等腰高塔尖 x1 (岸台拼缝, 标尖 2.0)                   1 片
  - 防波礁石: 直角三角 x2 (岸台北沿拼缝)                           2 片
  合计 72 片, 16 个教程步骤, 7 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点:
  - 栈桥与平台的侧壁连成一条闭环 (桥口两角竖边互吸), 桥面/台面
    每片同时压壁顶与邻板拼缝;
  - 灯塔三层墙环层层互吸, 底层踩台面拼缝, 尖顶四棱互吸自锁;
  - 水面板短边整边吸岸台, 长边互吸, 与栈桥侧壁只共线不相交;
  - 护齿/山墙尖/航标/礁石全部骑整边沿口, 共面零力矩。

用法: python3 tools/generate_lighthouse_pier_01.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

APRON = "gray"      # 岸台石板
SEA = "cyan"        # 海面
HUT = "green"       # 看守小屋
DOOR = "orange"     # 门框方
WIN = "clear"       # 窗格方
ROOF = "gray"       # 小屋屋顶
GABLE = "red"       # 山墙尖
PIER = "gray"       # 栈桥侧壁
DECKP = "yellow"    # 桥面/台面
TOWER1 = "red"      # 灯塔第 1 层
TOWER2 = "gray"     # 灯塔第 2 层 (红白相间的"白"用灰代)
SPIRE = "red"       # 灯塔尖顶
CREST = "yellow"    # 女儿墙护齿
MARK = "purple"     # 航标塔尖
ROCK = "gray"       # 防波礁石

# =================================================================
# 1. 岸台 (x [0,2], y [0,3]): 石板满铺
# =================================================================
for x in range(2):
    for y in range(3):
        b.flat(f"ap_{x}_{y}", x, y, 0.0, APRON)

# =================================================================
# 2. 海面: 长方形水面板 (栈桥两侧各 2, 短边吸岸台)
# =================================================================
b.flat_rect("sea_s1", 2, 0, 0.0, SEA)
b.flat_rect("sea_s2", 4, 0, 0.0, SEA)
b.flat_rect("sea_n1", 2, 2, 0.0, SEA)
b.flat_rect("sea_n2", 4, 2, 0.0, SEA)

# =================================================================
# 3. 看守小屋 (x [0,1], y [0,2], z 0..1): 门朝栈桥, 双山墙尖
# =================================================================
b.wall_ns("hb_s", 0, 0.0, 0, HUT)
b.wall_ns("hb_n", 0, 2.0, 0, HUT)
b.wall_ew("hb_w1", 0.0, 0, 0, HUT)
b.wall_ew("hb_w2", 0.0, 1, 0, HUT)
b.add("hb_win", "window_square", (1.0, 0.5, 0.5), (90, 0, 90), WIN)
b.add("hb_door", "door_frame", (1.0, 1.5, 0.5), (90, 0, 90), DOOR)
b.flat("hb_r1", 0, 0, 1.0, ROOF)
b.flat("hb_r2", 0, 1, 1.0, ROOF)
b.crest_ns("hb_g_s", 0, 0.0, 1.0, GABLE)
b.crest_ns("hb_g_n", 0, 2.0, 1.0, GABLE)

# =================================================================
# 4. 栈桥 (x [2,7], y [1,2], z 0..1): 箱形侧壁 + 满铺桥面
# =================================================================
for x in range(2, 7):
    b.wall_ns(f"pr_s_{x}", x, 1.0, 0, PIER)
    b.wall_ns(f"pr_n_{x}", x, 2.0, 0, PIER)
b.wall_ew("pr_w", 2.0, 1, 0, PIER)
for x in range(2, 7):
    b.flat(f"pr_d_{x}", x, 1, 1.0, DECKP)

# =================================================================
# 5. 灯塔平台 (x [7,9], y [0,2], z 0..1): 环壁 (西留桥口) + 台面
# =================================================================
b.wall_ns("pf_s_7", 7, 0.0, 0, PIER)
b.wall_ns("pf_s_8", 8, 0.0, 0, PIER)
b.wall_ns("pf_n_7", 7, 2.0, 0, PIER)
b.wall_ns("pf_n_8", 8, 2.0, 0, PIER)
b.wall_ew("pf_e_0", 9.0, 0, 0, PIER)
b.wall_ew("pf_e_1", 9.0, 1, 0, PIER)
b.wall_ew("pf_w_0", 7.0, 0, 0, PIER)
for x in (7, 8):
    for y in (0, 1):
        b.flat(f"pf_d_{x}_{y}", x, y, 1.0, DECKP)

# =================================================================
# 6. 灯塔 (x [7,8], y [0,1], z 1..4): 三层墙环 + 等腰四坡尖顶
#    第 1 层北面开门框方塔门 (正对平台台面)
# =================================================================
b.wall_ns("lt1_s", 7, 0.0, 1, TOWER1)
b.add("lt1_n", "door_frame", (7.5, 1.0, 1.5), (90, 0, 0), DOOR)
b.wall_ew("lt1_w", 7.0, 0, 1, TOWER1)
b.wall_ew("lt1_e", 8.0, 0, 1, TOWER1)
b.wall_ns("lt2_s", 7, 0.0, 2, TOWER2)
b.wall_ns("lt2_n", 7, 1.0, 2, TOWER2)
b.add("lt2_w", "window_square", (7.0, 0.5, 2.5), (90, 0, 90), WIN)
b.wall_ew("lt2_e", 8.0, 0, 2, TOWER2)
b.add("lt3_s", "window_square", (7.5, 0.0, 3.5), (90, 0, 0), WIN)
b.add("lt3_n", "window_square", (7.5, 1.0, 3.5), (90, 0, 0), WIN)
b.add("lt3_w", "window_square", (7.0, 0.5, 3.5), (90, 0, 90), WIN)
b.add("lt3_e", "window_square", (8.0, 0.5, 3.5), (90, 0, 90), WIN)
SPIRE_IDS = b.hat4("lt_spire", 7, 0, 4.0, SPIRE)

# =================================================================
# 7. 女儿墙护齿 + 航标塔尖 + 防波礁石
# =================================================================
b.crest_ns("pc_p1", 3, 1.0, 1.0, CREST)
b.crest_ns("pc_p2", 5, 1.0, 1.0, CREST)
b.crest_ew("pc_e1", 9.0, 0, 1.0, CREST)
b.crest_ew("pc_e2", 9.0, 1, 1.0, CREST)
b.crest_ns("pc_n1", 7, 2.0, 1.0, CREST)
b.crest_ns("pc_n2", 8, 2.0, 1.0, CREST)
b.spire_ew("mark", 1.0, 2, 0.0, MARK)
b.place_tri("rock_w", "right_triangle", (0, 3, 0), (1, 3, 0), (0, 3, 1), ROCK)
b.place_tri("rock_e", "right_triangle", (2, 3, 0), (1, 3, 0), (2, 3, 1), ROCK)

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺岸台 (x [0,2], y [0,3]): 6 片石板满铺。",
    [f"ap_{x}_{y}" for x in range(2) for y in range(3)],
    tip="岸台是整条动线的起点 —— 小屋、栈桥、航标都从这里生根。",
)
b.step(
    "铺海面: 4 片青色长方形水面板, 短边吸岸台、长边互吸。",
    ["sea_s1", "sea_s2", "sea_n1", "sea_n2"],
    highlight=["ap_1_0", "ap_1_2"],
    tip="水面板夹住栈桥走线 —— 大海就位。",
)
b.step(
    "立小屋南墙与西墙: 3 片绿色立墙踩岸台拼缝。",
    ["hb_s", "hb_w1", "hb_w2"],
    highlight=["ap_0_0"],
    tip="看守小屋 1x2 落位岸台西侧。",
)
b.step(
    "立小屋北墙与东墙: 3 片, 墙环闭合 (东面窗格方 + 门框方, 门朝栈桥)。",
    ["hb_n", "hb_win", "hb_door"],
    highlight=["hb_s", "hb_w2"],
    tip="看守员推门就上栈桥 —— 动线从门开始。",
)
b.step(
    "盖小屋屋顶 + 立山墙尖: 2 片平顶压墙顶, 2 片红色三角骑南北沿。",
    ["hb_r1", "hb_r2", "hb_g_s", "hb_g_n"],
    highlight=["hb_win", "hb_door"],
    tip="山墙尖与墙共面, 重心正压沿口。",
)
b.step(
    "砌栈桥南壁: 5 片灰色侧壁踩岸台与水面的走线。",
    [f"pr_s_{x}" for x in range(2, 7)],
    highlight=["ap_1_1"],
    tip="箱形栈桥先立南壁 —— 每片底边接地, 侧边互咬。",
)
b.step(
    "砌栈桥北壁与桥口: 6 片, 侧壁在岸台边合口。",
    [f"pr_n_{x}" for x in range(2, 7)] + ["pr_w"],
    highlight=["pr_s_2"],
    tip="桥口西壁与岸台整边吸合 —— 栈桥从岸上长出来。",
)
b.step(
    "铺桥面: 5 片黄色方板压侧壁顶。",
    [f"pr_d_{x}" for x in range(2, 7)],
    highlight=["pr_s_4", "pr_n_4"],
    tip="每片同时吸两段壁顶与邻板拼缝 —— 走上去稳稳当当。",
)
b.step(
    "砌灯塔平台环壁: 7 片, 西侧留桥口与栈桥合龙。",
    ["pf_s_7", "pf_s_8", "pf_n_7", "pf_n_8", "pf_e_0", "pf_e_1", "pf_w_0"],
    highlight=["pr_s_6", "pr_n_6"],
    tip="平台环壁与栈桥侧壁连成一条闭环 —— 桥头展宽成 2x2。",
)
b.step(
    "铺平台台面: 4 片方板压壁顶。",
    ["pf_d_7_0", "pf_d_7_1", "pf_d_8_0", "pf_d_8_1"],
    highlight=["pf_s_7", "pf_e_1"],
    tip="台面就是灯塔的新地面 —— 桥头堡完工。",
)
b.step(
    "起灯塔第 1 层: 4 片红色墙环踩台面拼缝, 北面开门框方塔门。",
    ["lt1_s", "lt1_n", "lt1_w", "lt1_e"],
    highlight=["pf_d_7_0", "pf_d_8_1"],
    tip="塔门正对台面 —— 上桥、过台、进塔一条动线。",
)
b.step(
    "叠灯塔第 2 层: 4 片灰色墙环, 西面嵌窗格方了望窗。",
    ["lt2_s", "lt2_n", "lt2_w", "lt2_e"],
    highlight=["lt1_n"],
    tip="红灰相间是灯塔的经典涂装 —— 白天也认得出。",
)
b.step(
    "装灯室: 4 片窗格方围出第 3 层全景灯室。",
    ["lt3_s", "lt3_n", "lt3_w", "lt3_e"],
    highlight=["lt2_s", "lt2_e"],
    tip="四面通透的灯室 —— 灯光射向每个方向。",
)
b.step(
    "戴等腰四坡尖顶: 塔尖 5.94, 全场最高。",
    SPIRE_IDS,
    highlight=["lt3_s", "lt3_e"],
    tip="四条斜棱两两互吸自锁 —— 红色塔尖就是海上坐标。",
)
b.step(
    "列女儿墙护齿: 6 片黄色等边三角骑上桥面南沿与平台东/北沿。",
    ["pc_p1", "pc_p2", "pc_e1", "pc_e2", "pc_n1", "pc_n2"],
    highlight=["pr_d_3", "pf_d_8_0"],
    tip="护齿守住临水沿口 —— 大浪来了也不怕。",
)
b.step(
    "立航标塔尖 + 放防波礁石: 紫色高塔尖立岸台拼缝, 2 片礁石守北沿 —— 灯塔栈桥落成!",
    ["mark", "rock_w", "rock_e"],
    highlight=["ap_0_2", "ap_1_2"],
    tip="航标 (标尖 2.0) 与灯塔遥相呼应; 直角礁石斜边朝海。",
)

b.finalize(
    model_id="lighthouse_pier_01",
    name="灯塔栈桥",
    name_en="Lighthouse Pier 01",
    description=(
        "只用核心九片型的岸-桥-台-塔一条动线: 岸台安置看守小屋"
        " (门朝栈桥 + 双山墙尖), 1 格宽箱形栈桥 (闭环侧壁 + 满铺"
        "桥面) 伸进海里, 桥头展宽成 2x2 灯塔平台; 方形灯塔三层"
        "拔起 —— 红灰相间塔身、四面窗格方全景灯室, 再戴等腰四坡"
        "尖顶 (塔尖 5.94 全场最高); 桥面与平台沿口列黄色护齿,"
        " 岸边立紫色航标塔尖与防波礁石, 长方形水面板向东铺开。"
        "箱形栈桥与平台环壁连成一条闭环 —— 海上工程的骨架一课学会。"
    ),
    difficulty=3,
    tags=["海岸", "灯塔", "栈桥", "航标", "进阶"],
    min_pieces=70,
    min_steps=16,
)
