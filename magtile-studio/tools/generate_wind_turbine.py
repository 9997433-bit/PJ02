#!/usr/bin/env python3
"""生成模型 data/models/wind_turbine_01.json (风力发电机)。

第三批模型: 新能源主题 —— 全库第一个"六边形轮毂转子": 三层方塔
直上 z=3, 塔根四片直角三角护撑与地坪锁成闭环; 机舱骑在塔顶,
一整片六边形轮毂竖立在机舱迎风面上 (重心正压铰链线), 3 片菱形
叶片吸在轮毂的顶边与两条下斜边上, 呈 120 度风车旋位 —— 与
"风车磨坊"的方毂柱四叶 X 完全不同的转子拓扑。场景配变压小屋、
测风塔与围栏。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 环形机坪 8 + 检修道 2 + 小屋地坪 2                            12 片
  - 塔身 3 层 x 4 墙 + 塔根护撑 4 + 塔顶平台                      17 片
  - 机舱 (4 墙 + 顶)                                               5 片
  - 转子: 六边形轮毂 1 + 菱形叶片 3                                4 片
  - 测风塔 (2 方 + 等腰尖)                                         3 片
  - 变压小屋 (4 墙 + 等腰四坡顶)                                   8 片
  - 围栏脊板 4                                                     4 片
  合计 53 片, 16 个教程步骤, 6 种磁力片形状。

物理要点 (通过 R1~R8 全部校验):
  - 轮毂底边整边吸机舱迎风墙顶, 重心正压铰链线 (力臂 0);
  - 三片叶片各吸轮毂一条边: 顶叶重心在铰链正上方、下斜双叶重心
    恰在铰链端点正下方 —— 绕铰链轴力矩均为零;
  - 塔根护撑 + 机坪 + 塔身围成三角闭环, 高塔不做纯树状拓扑。

坐标约定与 C++ 端一致: 旋转为欧拉角 (度), R = Rz * Ry * Rx。
用法: python3 tools/generate_wind_turbine.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

mb = ModelBuilder()

APRON = "green"     # 草坪机坪
TOWER = "clear"     # 塔身 (白色钢塔)
NAC = "blue"        # 机舱
HUB = "gray"        # 轮毂
BLADE = "clear"     # 叶片
HUT = "orange"      # 变压小屋

# =================================================================
# 1. 环形机坪 (围绕塔基 [3,4]x[3,4]) + 检修道 + 小屋地坪
# =================================================================
for tid, (x0, y0) in {
    "ap_sw": (2, 2), "ap_s": (3, 2), "ap_se": (4, 2), "ap_w": (2, 3),
    "ap_e": (4, 3), "ap_nw": (2, 4), "ap_n": (3, 4), "ap_ne": (4, 4),
}.items():
    mb.flat(tid, x0, y0, 0.0, APRON)
mb.flat("path0", 3, 1, 0.0, "gray")                # 检修道
mb.flat("path1", 3, 0, 0.0, "gray")
mb.flat("hp_bridge", 1, 4, 0.0, "gray")            # 小屋地坪
mb.flat("hp_base", 0, 4, 0.0, "gray")

# =================================================================
# 2. 塔身 3 层 ([3,4]x[3,4]) + 塔根护撑 + 塔顶平台
# =================================================================
for lv in range(3):
    mb.wall_ns(f"tw{lv}_s", 3, 3.0, lv, TOWER)
    mb.wall_ns(f"tw{lv}_n", 3, 4.0, lv, TOWER)
    mb.wall_ew(f"tw{lv}_w", 3.0, 3, lv, TOWER)
    mb.wall_ew(f"tw{lv}_e", 4.0, 3, lv, TOWER)
mb.brace("tb_sw", (3.0, 3.0, 0.0), "-x", "gray")
mb.brace("tb_se", (4.0, 3.0, 0.0), "+x", "gray")
mb.brace("tb_nw", (3.0, 4.0, 0.0), "-x", "gray")
mb.brace("tb_ne", (4.0, 4.0, 0.0), "+x", "gray")
mb.flat("t_deck", 3, 3, 3.0, "gray")               # 塔顶平台

# =================================================================
# 3. 机舱 (4 墙 + 顶, z 3..4)
# =================================================================
mb.wall_ns("nc_s", 3, 3.0, 3, NAC)                 # 迎风墙 (轮毂挂此)
mb.wall_ns("nc_n", 3, 4.0, 3, NAC)
mb.wall_ew("nc_w", 3.0, 3, 3, NAC)
mb.wall_ew("nc_e", 4.0, 3, 3, NAC)
mb.flat("nc_roof", 3, 3, 4.0, NAC)

# =================================================================
# 4. 转子: 六边形轮毂竖立迎风面 + 3 片菱形叶片 (120 度旋位)
#    轮毂中心 (3.5, 3, 4.866); 顶边 e1 与两条下斜边 e3/e5 挂叶片
# =================================================================
mb.place_edge("hub", "hexagon", 4,
              (3.0, 3.0, 4.0), (4.0, 3.0, 4.0), (0.0, 0.0, 1.0), HUB)
mb.place_edge("blade_top", "rhombus", 0,
              (4.0, 3.0, 5.732051), (3.0, 3.0, 5.732051),
              (0.0, 0.0, 1.0), BLADE)
mb.place_edge("blade_ll", "rhombus", 0,
              (2.5, 3.0, 4.866025), (3.0, 3.0, 4.0),
              (-0.866025, 0.0, -0.5), BLADE)
mb.place_edge("blade_lr", "rhombus", 0,
              (4.0, 3.0, 4.0), (4.5, 3.0, 4.866025),
              (0.866025, 0.0, -0.5), BLADE)

# =================================================================
# 5. 测风塔 + 变压小屋 + 围栏
# =================================================================
mb.wall_ns("mast0", 4, 2.0, 0, "yellow")
mb.wall_ns("mast1", 4, 2.0, 1, "yellow")
mb.spire_ns("mast_tip", 4, 2.0, 2.0, "red")

mb.wall_ns("hut_s", 0, 4.0, 0, HUT)
mb.wall_ns("hut_n", 0, 5.0, 0, HUT)
mb.wall_ew("hut_w", 0.0, 4, 0, HUT)
mb.wall_ew("hut_e", 1.0, 4, 0, HUT)
mb.hat4("hut_roof", 0, 4, 1.0, "red")

mb.crest_ns("fn_s", 2, 2.0, 0.0, "purple")
mb.crest_ew("fn_w", 2.0, 3, 0.0, "purple")
mb.crest_ns("fn_n", 2, 5.0, 0.0, "purple")
mb.crest_ew("fn_e", 5.0, 3, 0.0, "purple")

# =================================================================
# 教程步骤 (16 步)
# =================================================================
mb.step(
    "机坪南半: 塔基南、西两侧铺 4 片草坪机坪。",
    ["ap_sw", "ap_s", "ap_se", "ap_w"],
    tip="塔基 [3,4]x[3,4] 空在中央 —— 塔身直接落地。",
)
mb.step(
    "机坪北半: 补齐北、东两侧 4 片, 环形机坪合围。",
    ["ap_e", "ap_nw", "ap_n", "ap_ne"],
    highlight=["ap_sw", "ap_se"],
)
mb.step(
    "检修道: 机坪南沿向外接 2 片灰色道板。",
    ["path0", "path1"],
    highlight=["ap_s"],
)
mb.step(
    "小屋地坪: 机坪西北角向外接 2 片灰色地坪 —— 变压小屋的地基。",
    ["hp_bridge", "hp_base"],
    highlight=["ap_nw"],
)
mb.step(
    "塔身第一层: 4 面白色方墙围合, 墙底整边吸机坪内沿。",
    ["tw0_s", "tw0_n", "tw0_w", "tw0_e"],
    highlight=["ap_s", "ap_n"],
)
mb.step(
    "塔根护撑: 四角各加 1 片灰色直角三角 —— 竖边吸塔身竖边, "
    "横边吸机坪板边, 塔、撑、坪锁成三角闭环。",
    ["tb_sw", "tb_se", "tb_nw", "tb_ne"],
    highlight=["tw0_w", "tw0_e"],
)
mb.step(
    "塔身第二层: 4 面方墙压顶续高。",
    ["tw1_s", "tw1_n", "tw1_w", "tw1_e"],
    highlight=["tw0_s"],
)
mb.step(
    "塔身第三层与塔顶平台: 再起一层, 顶上盖灰色平台板 (z=3)。",
    ["tw2_s", "tw2_n", "tw2_w", "tw2_e", "t_deck"],
    highlight=["tw1_s"],
)
mb.step(
    "机舱墙身: 平台上围 4 面蓝色机舱墙, 南面是迎风墙。",
    ["nc_s", "nc_n", "nc_w", "nc_e"],
    highlight=["t_deck"],
)
mb.step(
    "机舱顶与轮毂: 盖机舱顶板; 一整片灰色六边形轮毂竖立在迎风墙"
    "顶线上 —— 重心正压铰链, 力臂为零。",
    ["nc_roof", "hub"],
    highlight=["nc_s", "nc_n"],
    tip="轮毂底边与机舱顶板南缘、迎风墙顶三线合一, 一条铰链三重吸合。",
)
mb.step(
    "三片叶片: 菱形叶片依次吸上轮毂顶边与两条下斜边, 呈 120 度"
    "风车旋位 —— 每片重心都落在自家铰链的正上/正下方。",
    ["blade_top", "blade_ll", "blade_lr"],
    highlight=["hub"],
    tip="菱形 60 度的天然斜度让叶尖自带后掠角, 像正在旋转。",
)
mb.step(
    "测风塔: 机坪东南角叠 2 方 1 尖的黄色测风塔。",
    ["mast0", "mast1", "mast_tip"],
    highlight=["ap_se"],
)
mb.step(
    "变压小屋墙身: 西北地坪上围 4 面橙色小屋墙。",
    ["hut_s", "hut_n", "hut_w", "hut_e"],
    highlight=["hp_base"],
)
mb.step(
    "小屋四坡顶: 4 片红色等腰三角对锥合拢, 斜棱互吸自锁。",
    ["hut_roof_s", "hut_roof_e", "hut_roof_n", "hut_roof_w"],
    highlight=["hut_s", "hut_n"],
)
mb.step(
    "围栏 (南/西): 机坪外沿立 2 片紫色围栏脊板。",
    ["fn_s", "fn_w"],
    highlight=["ap_sw"],
)
mb.step(
    "围栏 (北/东): 再立 2 片, 风机并网发电。",
    ["fn_n", "fn_e"],
    highlight=["ap_ne"],
)

mb.finalize(
    model_id="wind_turbine_01",
    name="风力发电机",
    name_en="Wind Turbine 01",
    description=(
        "现代三叶风机: 三层白色方塔直上, 塔根四片直角护撑与机坪"
        "锁成三角闭环; 机舱骑在塔顶平台上, 一整片六边形轮毂竖立在"
        "迎风墙顶线 (重心正压铰链、力臂为零), 3 片菱形叶片各吸轮毂"
        "一条边, 借菱形 60 度天然斜度甩出 120 度旋位的后掠叶尖 —— "
        "与传统风车磨坊的方毂四叶完全不同的转子拓扑。场景配变压"
        "小屋、测风塔与围栏, 新能源田园一景。"
    ),
    difficulty=3,
    tags=["风力发电", "新能源", "转子", "六边形轮毂", "工业"],
    min_pieces=50,
    min_steps=16,
)
