#!/usr/bin/env python3
"""生成模型 data/models/windmill_01.json (风车磨坊)。

第三批模型 ①: 田园主题 —— 全库第一个把菱形当"风车叶片"用的模型:
2x2 磨坊塔身之上是无压顶的梯形四坡裙檐 (裙檐收出 1x1 洞口),
洞口戴等腰四坡锥帽; 南面沿口立起两格高的方形毂柱, 4 片菱形叶片
分别吸在毂柱上下两段的左右竖边上, 借菱形 60 度的天然斜置拼出
一面正在旋转的 X 形大风车。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 田园地台 4x4: 南侧石板路 4 方 + 西/东草地长方形 + 北排     13 片
  - 磨坊塔身 2x2 两层: 一层留 2 格宽大门, 二层长方形门楣横跨    13 片
  - 裙檐: 4 片梯形收分 (2x2 -> 1x1, 无压顶)                     4 片
  - 锥帽: 1x1 洞口等腰四坡锥顶                                  4 片
  - 风车: 毂柱 2 方 + 菱形叶片 4 + 毂顶尖饰 1                    7 片
  - 场景: 栅栏 4 + 水井 (4 墙 + 锥顶 4) + 灌木 2 + 花朵 2       16 片
  合计 57 片, 16 个教程步骤, 6 种磁力片形状。

几何要点:
  - 菱形四条边均长 1, 吸上毂柱竖边后天然斜置 60 度 —— 上段叶片
    向斜上方甩出、下段叶片向斜下方收拢, 四片合成风车 X;
  - 上下两段叶片沿毂柱竖边错层布置, 同平面内互不重叠;
  - 裙檐顶沿与锥帽底边、毂柱底边三者共线互吸, 一条铰链线三重加固。

用法: python3 tools/generate_windmill.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import EQ_APEX, ModelBuilder

b = ModelBuilder()

RIM_Z = 2.0 + EQ_APEX          # 裙檐顶沿高度 2.707107
HUB0 = RIM_Z                   # 毂柱下段底
HUB1 = RIM_Z + 1.0             # 毂柱上段底
HUB2 = RIM_Z + 2.0             # 毂柱顶

# =================================================================
# 1. 田园地台 4x4 ([0,4]x[0,4]), 磨坊占中央 [1,3]x[1,3]
# =================================================================
for i in range(4):                       # 南排石板路 (承栅栏, 边长 1)
    b.flat(f"path_{i}", i, 0, 0, "gray")
b.flat("well_base", 0, 3, 0, "gray")     # 西北角水井地基
b.flat_rect("lawn_n", 1, 3, 0, "green")  # 北排草地
b.flat("lawn_ne", 3, 3, 0, "green")
b.flat_rect("lawn_w", 0, 1, 0, "green", axis="y")   # 西列草地
b.flat_rect("lawn_e", 3, 1, 0, "green", axis="y")   # 东列草地
for dx, dy in ((0, 0), (1, 0), (0, 1), (1, 1)):     # 磨坊室内地板
    b.flat(f"floor_{dx}{dy}", 1 + dx, 1 + dy, 0, "yellow")

# =================================================================
# 2. 磨坊塔身 2x2 两层: 南面一层整个留作 2 格宽大门
# =================================================================
for i in range(2):
    b.wall_ew(f"w1_w_{i}", 1, 1 + i, 0, "orange")   # 一层西墙
    b.wall_ew(f"w1_e_{i}", 3, 1 + i, 0, "orange")   # 一层东墙
    b.wall_ns(f"w1_n_{i}", 1 + i, 3, 0, "orange")   # 一层北墙
for i in range(2):
    b.wall_ew(f"w2_w_{i}", 1, 1 + i, 1, "orange")   # 二层西墙
    b.wall_ew(f"w2_e_{i}", 3, 1 + i, 1, "orange")   # 二层东墙
    b.wall_ns(f"w2_n_{i}", 1 + i, 3, 1, "clear")    # 二层北窗
b.lintel_ns("lintel", 1, 1, 1, "yellow")            # 南面门楣横跨大门

# =================================================================
# 3. 裙檐: 4 片梯形从 2x2 塔口收分到 1x1 (不放压顶, 洞口留给锥帽)
# =================================================================
SKIRT = {
    "s": ((1.0, 1.0, 2.0), (3.0, 1.0, 2.0), (2.0, 1.5, RIM_Z)),
    "e": ((3.0, 1.0, 2.0), (3.0, 3.0, 2.0), (2.5, 2.0, RIM_Z)),
    "n": ((3.0, 3.0, 2.0), (1.0, 3.0, 2.0), (2.0, 2.5, RIM_Z)),
    "w": ((1.0, 3.0, 2.0), (1.0, 1.0, 2.0), (1.5, 2.0, RIM_Z)),
}
for side, (b0, b1, top_mid) in SKIRT.items():
    bottom_mid = tuple((b0[i] + b1[i]) / 2 for i in range(3))
    hint = tuple(top_mid[i] - bottom_mid[i] for i in range(3))
    b.place_edge(f"skirt_{side}", "trapezoid", 0, b0, b1, hint, "red")

# 锥帽: 1x1 洞口 [1.5,2.5]^2 的等腰四坡锥顶
b.hat4("hat", 1.5, 1.5, RIM_Z, "red")

# =================================================================
# 4. 风车: 毂柱两段 + 4 片菱形叶片 (X 形) + 毂顶尖饰
# =================================================================
b.wall_ns("hub_lo", 1.5, 1.5, HUB0, "blue")
b.wall_ns("hub_hi", 1.5, 1.5, HUB1, "blue")
# 下段叶片: 沿毂柱下段左右竖边向斜下方甩出
b.place_edge("blade_dl", "rhombus", 0,
             (1.5, 1.5, HUB1), (1.5, 1.5, HUB0), (-1, 0, 0), "clear")
b.place_edge("blade_dr", "rhombus", 0,
             (2.5, 1.5, HUB1), (2.5, 1.5, HUB0), (1, 0, 0), "clear")
# 上段叶片: 沿毂柱上段左右竖边向斜上方甩出
b.place_edge("blade_ul", "rhombus", 0,
             (1.5, 1.5, HUB1), (1.5, 1.5, HUB2), (-1, 0, 0), "clear")
b.place_edge("blade_ur", "rhombus", 0,
             (2.5, 1.5, HUB1), (2.5, 1.5, HUB2), (1, 0, 0), "clear")
b.spire_ns("hub_cap", 1.5, 1.5, HUB2, "blue")

# =================================================================
# 5. 场景: 栅栏 / 水井 / 灌木 / 花朵
# =================================================================
for i in range(4):
    b.crest_ns(f"fence_{i}", i, 0, 0, "yellow")     # 南侧栅栏
b.wall_ns("well_s", 0, 3, 0, "gray")                # 水井四壁
b.wall_ns("well_n", 0, 4, 0, "gray")
b.wall_ew("well_w", 0, 3, 0, "gray")
b.wall_ew("well_e", 1, 3, 0, "gray")
b.hat4("well_hat", 0, 3, 1.0, "blue")               # 水井锥顶
b.crest_ns("bush_w", 0, 1, 0, "green")              # 西侧灌木
b.crest_ns("bush_e", 3, 1, 0, "green")              # 东侧灌木
b.spire_ns("flower_w", 1, 1, 0, "pink")             # 门前花朵
b.spire_ns("flower_e", 2, 1, 0, "pink")

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺设田园地台外圈: 南排 4 片灰色石板路平铺在最前, 西北角放 1 片"
    "灰色水井地基, 北排与东西两列铺绿色草地长方形与方板。",
    ["path_0", "path_1", "path_2", "path_3", "well_base",
     "lawn_n", "lawn_ne", "lawn_w", "lawn_e"],
    tip="先摆南排再逆时针合拢, 每片至少一条边与邻片整边吸合。",
)
b.step(
    "铺设磨坊室内地板: 4 片黄色正方形填满中央 2x2, 这是塔身的地基。",
    ["floor_00", "floor_10", "floor_01", "floor_11"],
    highlight=["lawn_w", "lawn_e"],
    tip="地板与四周草地整边吸合, 之后所有墙都立在它的边上。",
)
b.step(
    "竖立一层西墙与东墙: 各 2 片橙色正方形沿室内地板边缘立起。",
    ["w1_w_0", "w1_w_1", "w1_e_0", "w1_e_1"],
    highlight=["floor_00", "floor_11"],
    tip="墙底边吸地板边, 相邻两片墙的竖边在中缝互吸。",
)
b.step(
    "竖立一层北墙: 2 片橙色正方形, 南面整面留空 —— 那是磨坊大门。",
    ["w1_n_0", "w1_n_1"],
    highlight=["w1_w_1", "w1_e_1"],
    tip="北墙两端的竖边分别吸住西墙与东墙, 一层围成 U 形。",
)
b.step(
    "叠加二层西墙与东墙: 各 2 片橙色正方形叠在一层墙顶。",
    ["w2_w_0", "w2_w_1", "w2_e_0", "w2_e_1"],
    highlight=["w1_w_0", "w1_e_0"],
    tip="上下两层墙的横边完全对齐, 竖缝也要对齐才结实。",
)
b.step(
    "封二层北窗并横跨门楣: 2 片透明正方形做北窗, 1 片黄色长方形横跨"
    "南面大门上方, 两端竖边吸住西墙与东墙的二层。",
    ["w2_n_0", "w2_n_1", "lintel"],
    highlight=["w2_w_0", "w2_e_0"],
    tip="门楣下方是 2 格宽的负空间大门 —— 全靠两端竖边传力。",
)
b.step(
    "安装裙檐: 4 片红色梯形下底吸塔口沿边, 腰两两互吸, "
    "向内收分出 1x1 的顶部洞口。",
    ["skirt_s", "skirt_e", "skirt_n", "skirt_w"],
    highlight=["w2_n_0", "lintel"],
    tip="先放南片再顺时针合拢, 最后一片卡进去整圈自锁。",
)
b.step(
    "扣上锥帽: 4 片红色等腰三角形在裙檐洞口上方合拢成尖顶。",
    ["hat_s", "hat_e", "hat_n", "hat_w"],
    highlight=["skirt_s", "skirt_n"],
    tip="四条斜棱两两互吸, 锥尖在洞口正上方 0.87 格处会合。",
)
b.step(
    "竖立风车毂柱: 2 片蓝色正方形在南面裙檐沿口上下叠成两格高的毂柱。",
    ["hub_lo", "hub_hi"],
    highlight=["skirt_s", "hat_s"],
    tip="毂柱底边与裙檐顶沿、锥帽底边共线互吸 —— 一条线三重加固。",
)
b.step(
    "挂下段叶片: 2 片透明菱形分别吸在毂柱下段的左右竖边上, "
    "顺着菱形的斜度向斜下方甩出。",
    ["blade_dl", "blade_dr"],
    highlight=["hub_lo"],
    tip="菱形整条边贴住毂柱竖边, 斜置 60 度是它的天然角度。",
)
b.step(
    "挂上段叶片并戴毂顶尖饰: 2 片透明菱形吸在毂柱上段左右竖边向斜上方"
    "甩出, 1 片蓝色等腰三角形立在毂柱顶边收尾 —— 风车 X 成形!",
    ["blade_ul", "blade_ur", "hub_cap"],
    highlight=["blade_dl", "blade_dr"],
    tip="上下叶片沿竖边错层布置, 同一平面内互不相碰。",
)
b.step(
    "竖起南侧栅栏: 4 片黄色等边三角形立在石板路前沿。",
    ["fence_0", "fence_1", "fence_2", "fence_3"],
    highlight=["path_0", "path_3"],
    tip="底边与石板路外沿整边吸合, 像一排小小的木栅栏。",
)
b.step(
    "砌水井四壁: 4 片灰色正方形沿西北角地基边缘立起围成井筒。",
    ["well_s", "well_n", "well_w", "well_e"],
    highlight=["well_base"],
    tip="四片墙的竖边在四角两两互吸, 围成一个结实的方筒。",
)
b.step(
    "盖水井锥顶: 4 片蓝色等腰三角形在井筒上方合拢成小尖顶。",
    ["well_hat_s", "well_hat_e", "well_hat_n", "well_hat_w"],
    highlight=["well_s", "well_n"],
    tip="和磨坊锥帽同款技法 —— 四条斜棱互吸自锁。",
)
b.step(
    "种两丛灌木: 2 片绿色等边三角形立在草地拼缝上。",
    ["bush_w", "bush_e"],
    highlight=["lawn_w", "lawn_e"],
    tip="底边正好吸在草地与石板路的拼缝边上。",
)
b.step(
    "种两株门前花: 2 片粉色等腰三角形立在大门两侧 —— 风车磨坊落成!",
    ["flower_w", "flower_e"],
    highlight=["fence_1", "fence_2"],
    tip="从南面看: 大门、门楣、裙檐、锥帽与风车 X 排成一条中轴线。",
)

b.finalize(
    model_id="windmill_01",
    name="风车磨坊",
    name_en="Windmill 01",
    description=(
        "田园风车磨坊: 2x2 塔身留 2 格宽负空间大门, 门楣横跨传力; "
        "塔顶梯形裙檐收分出 1x1 洞口再戴等腰锥帽; 南面沿口立起两格高"
        "毂柱, 4 片透明菱形叶片吸在毂柱上下两段的左右竖边上, 借菱形 "
        "60 度天然斜置拼出正在旋转的 X 形风车 —— 全库第一次把菱形"
        "当叶片用。场边配石板路、栅栏、锥顶水井与花丛。"
    ),
    difficulty=3,
    tags=["田园", "风车", "菱形叶片", "进阶"],
    min_pieces=50,
    min_steps=16,
)
