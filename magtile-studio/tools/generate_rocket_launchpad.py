#!/usr/bin/env python3
"""生成模型 data/models/rocket_launchpad_01.json (火箭发射台)。

第二批模型 ③: 航天主题旗舰 —— 5x5 发射场上, 三级火箭由 4 片
风车状尾翼锁定, 旁边的勤务塔以登舱桥与箭体相连, 角落立着
燃料罐与 4 座避雷塔, 场地四周一圈警戒火焰旗。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 发射场坪: 5x5 灰青棋盘格                                    25 片
  - 火箭: 1x1 箭体三级 (z 0..3) + 等腰三角锥形整流罩             16 片
  - 尾翼 x4: 直角三角形风车状分布, 双边吸场坪与箭体竖边           4 片
  - 勤务塔: 1x1 塔身三级 + 塔顶平台 + 登舱桥 + 2 根底部斜撑      16 片
  - 燃料罐: 1x1 罐体 + 锥形罐顶                                   8 片
  - 避雷塔 x4: 角楼 L 形双墙 + 等腰塔尖                          12 片
  - 警戒火焰旗: 场坪四沿 8 片橙红三角                             8 片
  合计 89 片, 19 个教程步骤, 4 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 尾翼与斜撑均为"两条直角边都吸牢"的三角刚性节点;
  - 登舱桥两侧分别压在箭体墙顶与塔顶平台上, 形成闭环 (双向支撑);
  - 整流罩四片等腰三角形斜棱两两互吸, 自锁成环 (摩天大楼金顶同款)。

用法: python3 tools/generate_rocket_launchpad.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

# =================================================================
# 1. 发射场坪: 5x5 灰青棋盘格
# =================================================================
for j in range(5):
    for i in range(5):
        b.flat(f"pad_{i}_{j}", i, j, 0.0, "gray" if (i + j) % 2 == 0 else "cyan")

# =================================================================
# 2. 火箭: 箭体占格 (1..2, 2..3), 三级墙 + 整流罩
# =================================================================
STAGE_COLOR = {0: "clear", 1: "clear", 2: "red"}
for lv in range(3):
    c = STAGE_COLOR[lv]
    b.wall_ns(f"rk{lv}_s", 1, 2.0, lv, c)
    b.wall_ew(f"rk{lv}_e", 2.0, 2, lv, c)
    b.wall_ns(f"rk{lv}_n", 1, 3.0, lv, c)
    b.wall_ew(f"rk{lv}_w", 1.0, 2, lv, c)
nose_ids = b.hat4("nose", 1, 2, 3.0, "red")  # 整流罩, 锥尖 z=3.866

# 尾翼: 4 片直角三角形绕箭体风车状分布
b.brace("fin_w", (1.0, 2.0, 0.0), "-x", "red")
b.brace("fin_s", (2.0, 2.0, 0.0), "-y", "red")
b.brace("fin_e", (2.0, 3.0, 0.0), "+x", "red")
b.brace("fin_n", (1.0, 3.0, 0.0), "+y", "red")

# =================================================================
# 3. 勤务塔: 塔身占格 (3..4, 2..3), 三级墙 + 塔顶平台 + 登舱桥
# =================================================================
for lv in range(3):
    c = "yellow" if lv % 2 == 0 else "orange"
    b.wall_ns(f"tw{lv}_s", 3, 2.0, lv, c)
    b.wall_ew(f"tw{lv}_e", 4.0, 2, lv, c)
    b.wall_ns(f"tw{lv}_n", 3, 3.0, lv, c)
    b.wall_ew(f"tw{lv}_w", 3.0, 2, lv, c)
b.flat("tw_top", 3, 2, 3.0, "yellow")     # 塔顶平台
b.flat("bridge", 2, 2, 3.0, "orange")     # 登舱桥: 西压箭体墙顶, 东压塔顶
b.brace("twb_s", (4.0, 2.0, 0.0), "+x", "orange")   # 塔底斜撑 x2
b.brace("twb_n", (4.0, 3.0, 0.0), "+x", "orange")

# =================================================================
# 4. 燃料罐: 罐体占格 (0..1, 0..1) 一层 + 锥形罐顶
# =================================================================
b.wall_ns("tk_s", 0, 0.0, 0, "green")
b.wall_ew("tk_e", 1.0, 0, 0, "green")
b.wall_ns("tk_n", 0, 1.0, 0, "green")
b.wall_ew("tk_w", 0.0, 0, 0, "green")
tank_ids = b.hat4("tk_roof", 0, 0, 1.0, "green")

# =================================================================
# 5. 避雷塔 x4: 其余三个场角 + 东南角, L 形双墙 + 等腰塔尖
#    (西南角已被燃料罐占用, 避雷塔布在其余三角 + 东沿中点北角)
# =================================================================
b.wall_ns("lt_se_a", 4, 0.0, 0, "purple")
b.wall_ew("lt_se_b", 5.0, 0, 0, "purple")
b.spire_ns("lt_se_t", 4, 0.0, 1.0, "yellow")
b.wall_ns("lt_ne_a", 4, 5.0, 0, "purple")
b.wall_ew("lt_ne_b", 5.0, 4, 0, "purple")
b.spire_ns("lt_ne_t", 4, 5.0, 1.0, "yellow")
b.wall_ns("lt_nw_a", 0, 5.0, 0, "purple")
b.wall_ew("lt_nw_b", 0.0, 4, 0, "purple")
b.spire_ns("lt_nw_t", 0, 5.0, 1.0, "yellow")
b.wall_ns("lt_sw_a", 1, 0.0, 0, "purple")   # 西南角避雷塔贴燃料罐东侧
b.wall_ew("lt_sw_b", 2.0, 0, 0, "purple")
b.spire_ns("lt_sw_t", 1, 0.0, 1.0, "yellow")

# =================================================================
# 6. 警戒火焰旗: 场坪四沿 8 片橙红三角
# =================================================================
b.crest_ns("fl_s_2", 2, 0.0, 0.0, "orange")
b.crest_ns("fl_s_3", 3, 0.0, 0.0, "red")
b.crest_ew("fl_e_1", 5.0, 1, 0.0, "orange")
b.crest_ew("fl_e_2", 5.0, 2, 0.0, "red")
b.crest_ns("fl_n_1", 1, 5.0, 0.0, "orange")
b.crest_ns("fl_n_2", 2, 5.0, 0.0, "red")
b.crest_ew("fl_w_1", 0.0, 1, 0.0, "orange")
b.crest_ew("fl_w_2", 0.0, 2, 0.0, "red")

# =================================================================
# 教程步骤 (19 步)
# =================================================================
b.step(
    "铺设发射场坪南半部: 平放 5x2 共 10 片正方形 (灰青棋盘格)。",
    [f"pad_{i}_{j}" for j in range(2) for i in range(5)],
    tip="发射场务必铺在平整桌面正中 —— 它是全场所有设施的地基。",
)
b.step(
    "铺设场坪中部两排 (10 片)。",
    [f"pad_{i}_{j}" for j in range(2, 4) for i in range(5)],
    highlight=[f"pad_{i}_1" for i in range(5)],
    tip="每片新地砖至少与一片已铺地砖整边吸合, 棋盘格颜色交替。",
)
b.step(
    "铺设场坪最北一排 (5 片), 5x5 发射场完工。",
    [f"pad_{i}_4" for i in range(5)],
    highlight=[f"pad_{i}_3" for i in range(5)],
    tip="从上往下看应是完整的 5x5 棋盘 —— 数一数每边正好 5 格。",
)
b.step(
    "竖立火箭第一级: 在场坪 (1..2, 2..3) 格四周立 4 片透明墙, 围成箭体底舱。",
    ["rk0_s", "rk0_e", "rk0_n", "rk0_w"],
    highlight=["pad_1_2"],
    tip="四片按 南-东-北-西 顺序合围, 每个转角竖边互吸。",
)
b.step(
    "安装 4 片红色尾翼: 直角三角形绕箭体风车状分布, 竖直边吸箭体竖边、"
    "水平边吸场坪接缝。",
    ["fin_w", "fin_s", "fin_e", "fin_n"],
    highlight=["rk0_w", "rk0_s"],
    tip="风车状(而不是十字对称)是有讲究的: 每片尾翼各锁一个箭体转角。",
)
b.step(
    "叠火箭第二级: 4 片透明墙对齐第一级墙顶。",
    ["rk1_s", "rk1_e", "rk1_n", "rk1_w"],
    highlight=["rk0_s", "rk0_e"],
    tip="上下墙完整贴合磁力才最强; 箭体要垂直, 从侧面看不歪。",
)
b.step(
    "叠火箭第三级: 4 片红色墙, 箭体升到三级高。",
    ["rk2_s", "rk2_e", "rk2_n", "rk2_w"],
    highlight=["rk1_s", "rk1_e"],
    tip="越往高处越要轻放: 一手扶住下级箭体, 另一手放片。",
)
b.step(
    "合拢整流罩: 4 片红色等腰三角形底边吸在第三级墙顶, 全部向内倾斜, "
    "四条斜棱两两互吸, 锥尖在正中交汇。",
    nose_ids,
    highlight=["rk2_s", "rk2_e", "rk2_n", "rk2_w"],
    tip="按 南-东-北-西 顺序合拢, 最后一片要同时吸住底边和两条斜棱。",
)
b.step(
    "竖立勤务塔第一层: 在 (3..4, 2..3) 格四周立 4 片黄色墙。",
    ["tw0_s", "tw0_e", "tw0_n", "tw0_w"],
    highlight=["pad_3_2"],
    tip="勤务塔在火箭正东一格 —— 中间留出的走廊将架设登舱桥。",
)
b.step(
    "安装塔底斜撑: 2 根橙色直角三角形锁住勤务塔东侧墙根。",
    ["twb_s", "twb_n"],
    highlight=["tw0_e"],
    tip="竖直边吸塔身竖边、水平边吸场坪接缝, 双边都要吸牢。",
)
b.step(
    "叠勤务塔第二层 (4 片橙色墙)。",
    ["tw1_s", "tw1_e", "tw1_n", "tw1_w"],
    highlight=["tw0_s", "tw0_e"],
    tip="与火箭第二级同高 —— 两座塔在并肩长高。",
)
b.step(
    "叠勤务塔第三层 (4 片黄色墙)。",
    ["tw2_s", "tw2_e", "tw2_n", "tw2_w"],
    highlight=["tw1_s", "tw1_e"],
    tip="塔身合围后轻推应整体联动。",
)
b.step(
    "盖塔顶平台并架设登舱桥: 平台压住塔身四面墙顶; 登舱桥一边压箭体墙顶、"
    "一边压塔顶平台, 横跨走廊。",
    ["tw_top", "bridge"],
    highlight=["rk2_e", "tw2_w"],
    tip="登舱桥两侧都有支撑, 是火箭与勤务塔之间的结构闭环 —— 宇航员从这里进舱。",
)
b.step(
    "竖立燃料罐罐体: 在西南角 (0..1, 0..1) 格立 4 片绿色墙。",
    ["tk_s", "tk_e", "tk_n", "tk_w"],
    highlight=["pad_0_0"],
    tip="燃料罐离火箭最远的一角 —— 发射场的安全距离布置。",
)
b.step(
    "合拢燃料罐锥顶: 4 片绿色等腰三角形, 装法与整流罩相同。",
    tank_ids,
    highlight=["tk_s", "tk_n"],
    tip="小锥顶与火箭整流罩遥相呼应, 一大一小两座锥塔。",
)
b.step(
    "建东侧两座避雷塔: 东南、东北角各立 L 形双墙 + 黄色等腰塔尖。",
    ["lt_se_a", "lt_se_b", "lt_se_t", "lt_ne_a", "lt_ne_b", "lt_ne_t"],
    highlight=["pad_4_0", "pad_4_4"],
    tip="L 形双墙转角竖边互吸后非常稳固, 塔尖底边吸在南北向那片墙顶。",
)
b.step(
    "建西侧两座避雷塔: 西北角与燃料罐东侧各一座, 与东侧对称。",
    ["lt_nw_a", "lt_nw_b", "lt_nw_t", "lt_sw_a", "lt_sw_b", "lt_sw_t"],
    highlight=["pad_0_4", "tk_e"],
    tip="四座避雷塔围出发射安全区 —— 真实发射场的标准配置。",
)
b.step(
    "插南沿与东沿警戒火焰旗: 4 片橙红三角立在场坪外沿。",
    ["fl_s_2", "fl_s_3", "fl_e_1", "fl_e_2"],
    highlight=["pad_2_0", "pad_4_2"],
    tip="火焰旗底边吸场坪沿口即可站稳, 橙红相间。",
)
b.step(
    "插北沿与西沿警戒火焰旗, 发射台准备就绪 —— 点火倒计时!",
    ["fl_n_1", "fl_n_2", "fl_w_1", "fl_w_2"],
    highlight=["pad_1_4", "pad_0_2"],
    tip="全部完成后从正上方看: 火箭居中偏西, 勤务塔紧邻, 四角高塔守卫。",
)

b.finalize(
    model_id="rocket_launchpad_01",
    name="火箭发射台",
    name_en="Rocket Launchpad 01",
    description=(
        "航天主题旗舰: 5x5 发射场上, 三级透明箭体由 4 片风车状红色尾翼锁定, "
        "锥形整流罩四片斜棱自锁成环; 勤务塔与箭体之间架起登舱桥形成结构闭环, "
        "西南角燃料罐、四座避雷塔与一圈警戒火焰旗把发射场围得像真的一样 —— "
        "点火倒计时, 5、4、3、2、1!"
    ),
    difficulty=4,
    tags=["航天", "火箭", "发射场", "旗舰"],
    min_pieces=80,
    min_steps=18,
)
