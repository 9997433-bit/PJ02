#!/usr/bin/env python3
"""生成模型 data/models/corn_maze_01.json (玉米迷宫)。

农场/农业主题批 2/4: 全库第一座"负空间即玩法"的迷宫 —— 与
farm_barn_01 (谷仓) / greenhouse_dome_01 (温室) 等"围合建筑"刻意
区分, 本作的主角不是墙围出来的房间, 而是墙留出来的**路**: 6x5
玉米田上 21 片绿色玉米墙沿田垄拼缝立成迷宫阵, 橙色土路蜿蜒出
唯一通路 (从南门进 -> 西绕 -> 北折 -> 东进中央瞭望塔), 另有三条
死胡同与两处封闭玉米荡等着迷路的小朋友; 南门是双柱托楣的红色
门楼 (横楣两端竖边与门柱竖棱纯剪互锁), 迷宫中心 1x1 两层瞭望塔
(一层门框方开向迷宫终点, 二层四面窗格方 360 度找路), 四株等腰
玉米高杆骑墙顶直上 3.0 —— 走错了别急, 上塔看一眼再来!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 门楼朝南):
  - 玉米田 6x5: 方板 x30 (橙=土路 / 绿=玉米地 / 灰=塔基)       30 片
  - 迷宫墙: 绿色方墙 x21 骑田垄拼缝 (一缝双吸)                 21 片
  - 南门楼: 门柱 x4 (两层) + 横楣 x1 + 门旗 x2                  7 片
  - 瞭望塔: 门框方 + 方墙 x3 (一层) + 窗格方 x4 (二层)
    + 塔顶方板 + 塔旗                                          10 片
  - 玉米高杆: 等腰三角 x4 骑墙顶 + 玉米丛: 等边三角 x2 骑缝     6 片
  合计 74 片, 13 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 迷宫墙骑缝: 底边落在两片田板的公共拼缝上 (一缝双吸),
    重心正压铰链线力矩为零; 拐角/丁字处相邻墙竖边互咬加固;
  - 门楼横楣: 两端竖直短边与两侧门柱竖棱纯剪互锁 (竖直铰链轴
    的重力力矩恒为零), 柱-楣-柱连成门式闭环;
  - 瞭望塔: 两层圈层四角竖边互吸, 塔顶方板四边压墙顶多铰链
    互为保险, 塔旗底边"塔顶沿 + 二层窗顶"一线双吸;
  - 玉米高杆 (顶 3.0) 触发 R8 高层检查: 底边整边吸墙顶, 重心
    正压铰链, 全场闭环拓扑天然通过。

用法: python3 tools/generate_corn_maze_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

DIRT = "orange"      # 土路 (可走的负空间)
CORN = "green"       # 玉米地块
BASE = "gray"        # 瞭望塔塔基
WALL = "green"       # 玉米墙
GATE = "red"         # 门楼
FLAG = "yellow"      # 门旗
TOWER = "gray"       # 瞭望塔
GLASS = "clear"      # 瞭望窗
STALK = "yellow"     # 玉米高杆

# =================================================================
# 1. 玉米田 6x5 (x [0,6], y [0,5]): 全方板咬缝 —— 每一条田垄
#    拼缝都是迷宫墙的地基。橙=路, 绿=玉米, 灰=塔基。
# =================================================================
PATH_CELLS = {
    (2, 0), (3, 0), (4, 0), (5, 0),
    (0, 1), (1, 1), (2, 1), (3, 1), (4, 1), (5, 1),
    (0, 2), (2, 2),
    (0, 3), (1, 3), (2, 3), (3, 3), (4, 3), (5, 3),
}
TOWER_CELL = (3, 2)
for y in range(5):
    for x in range(6):
        if (x, y) == TOWER_CELL:
            color = BASE
        elif (x, y) in PATH_CELLS:
            color = DIRT
        else:
            color = CORN
        b.flat(f"fd_{x}_{y}", x, y, 0.0, color)

# =================================================================
# 2. 南门楼 (y=0, 门洞 x [2,4]): 双层门柱 + 横楣 + 门旗
# =================================================================
b.wall_ns("gt_w_lo", 1, 0.0, 0, GATE)
b.wall_ns("gt_e_lo", 4, 0.0, 0, GATE)
b.wall_ns("gt_w_hi", 1, 0.0, 1, GATE)
b.wall_ns("gt_e_hi", 4, 0.0, 1, GATE)
b.lintel_ns("gt_lintel", 2, 0.0, 1, GATE)          # 跨 2 格门洞
b.crest_ns("gt_flag_w", 1, 0.0, 2.0, FLAG)
b.crest_ns("gt_flag_e", 4, 0.0, 2.0, FLAG)

# =================================================================
# 3. 迷宫墙 x21: 绿色方墙骑田垄拼缝
#    唯一通路: 进门 (2,0) -> (2,1) -> 西行 (0,1) -> 北上 (0,3)
#    -> 东行 (2,3) -> 南折 (2,2) -> 东推塔门 (3,2)。
# =================================================================
# 东西向墙 (骑 y=k 拼缝)
for x in (0, 1, 3, 4):
    b.wall_ns(f"mw_y1_{x}", x, 1.0, 0, WALL)
for x in (1, 2, 4, 5):
    b.wall_ns(f"mw_y2_{x}", x, 2.0, 0, WALL)
for x in (1, 4, 5):
    b.wall_ns(f"mw_y3_{x}", x, 3.0, 0, WALL)
for x in range(6):
    b.wall_ns(f"mw_y4_{x}", x, 4.0, 0, WALL)       # 北背篱一整排
# 南北向墙 (骑 x=k 拼缝)
b.wall_ew("mw_x2_0", 2.0, 0, 0, WALL)              # 封西侧玉米荡
b.wall_ew("mw_x3_0", 3.0, 0, 0, WALL)              # 分开两条入口道
b.wall_ew("mw_x3_1", 3.0, 1, 0, WALL)              # 死胡同尽头
b.wall_ew("mw_x1_2", 1.0, 2, 0, WALL)              # 封中部玉米荡 (西)
b.wall_ew("mw_x2_2", 2.0, 2, 0, WALL)              # 封中部玉米荡 (东)

# =================================================================
# 4. 瞭望塔 (3,2): 一层门框方朝西 (迷宫终点), 二层四面瞭望窗,
#    塔顶方板 + 塔旗
# =================================================================
b.add("tw_door", "door_frame", (3.0, 2.5, 0.5), (90, 0, 90), TOWER)
b.wall_ns("tw_s1", 3, 2.0, 0, TOWER)
b.wall_ew("tw_e1", 4.0, 2, 0, TOWER)
b.wall_ns("tw_n1", 3, 3.0, 0, TOWER)
b.add("tw_s2", "window_square", (3.5, 2.0, 1.5), (90, 0, 0), GLASS)
b.add("tw_w2", "window_square", (3.0, 2.5, 1.5), (90, 0, 90), GLASS)
b.add("tw_e2", "window_square", (4.0, 2.5, 1.5), (90, 0, 90), GLASS)
b.add("tw_n2", "window_square", (3.5, 3.0, 1.5), (90, 0, 0), GLASS)
b.flat("tw_cap", 3, 2, 2.0, TOWER)
b.crest_ns("tw_flag", 3, 3.0, 2.0, "red")          # 塔旗 (塔顶沿+窗顶一线双吸)

# =================================================================
# 5. 玉米高杆 x4 (等腰骑墙顶, 顶 3.0) + 玉米丛 x2 (等边骑缝)
# =================================================================
b.spire_ns("corn_a", 0, 1.0, 1.0, STALK)           # 骑 y=1 西端墙顶
b.spire_ns("corn_b", 5, 2.0, 1.0, STALK)           # 骑 y=2 东端墙顶
b.spire_ns("corn_c", 1, 4.0, 1.0, STALK)           # 骑北背篱
b.spire_ns("corn_d", 4, 4.0, 1.0, STALK)
b.crest_ew("corn_e", 1.0, 0, 0.0, CORN)            # 西南玉米荡骑缝
b.crest_ew("corn_f", 5.0, 2, 0.0, CORN)            # 中部玉米荡骑缝

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺玉米田南两行 (y [0,2]): 12 片方板咬缝, 橙色是能走的土路。",
    [f"fd_{x}_{y}" for y in (0, 1) for x in range(6)],
    tip="迷宫全靠拼缝: 每一条田垄缝都是玉米墙的地基。",
)
b.step(
    "铺玉米田中两行 (y [2,4]): 灰色方板是瞭望塔的塔基。",
    [f"fd_{x}_{y}" for y in (2, 3) for x in range(6)],
    highlight=["fd_2_1", "fd_3_1"],
    tip="橙色土路只有一条真的通到塔基 —— 现在还看不出来。",
)
b.step(
    "铺玉米田北行 (y [4,5]): 6 片合拢, 6x5 田块就绪。",
    [f"fd_{x}_4" for x in range(6)],
    highlight=["fd_0_3", "fd_5_3"],
    tip="最北一行整行留给玉米 —— 它是迷宫的绿色背景板。",
)
b.step(
    "立南门楼: 双层门柱 x4 + 横楣跨 2 格门洞, 迷宫从这里进。",
    ["gt_w_lo", "gt_e_lo", "gt_w_hi", "gt_e_hi", "gt_lintel"],
    highlight=["fd_2_0", "fd_3_0"],
    tip="横楣两端竖边与门柱竖棱纯剪互锁 —— 竖直铰链轴力矩恒为零。",
)
b.step(
    "栽入口区玉米墙: y=1 拼缝 4 片 + 入口分道墙 3 片。",
    ["mw_y1_0", "mw_y1_1", "mw_y1_3", "mw_y1_4",
     "mw_x2_0", "mw_x3_0", "mw_x3_1"],
    highlight=["gt_lintel"],
    tip="底边一缝双吸、重心正压铰链 —— 每面墙都站得笔直。",
)
b.step(
    "栽中部玉米墙: y=2 拼缝 4 片 + 玉米荡封口墙 2 片。",
    ["mw_y2_1", "mw_y2_2", "mw_y2_4", "mw_y2_5", "mw_x1_2", "mw_x2_2"],
    highlight=["mw_y1_1"],
    tip="丁字口的墙竖边互咬 —— 迷宫阵越连越稳。",
)
b.step(
    "栽北折段玉米墙: y=3 拼缝 3 片, 唯一通路在这里拐弯。",
    ["mw_y3_1", "mw_y3_4", "mw_y3_5"],
    highlight=["mw_y2_1", "mw_y2_4"],
    tip="从西边上来的路在 (2,3) 向南一折 —— 别被死胡同骗了。",
)
b.step(
    "栽北背篱: 6 片一整排封住北缘, 迷宫阵合拢。",
    [f"mw_y4_{x}" for x in range(6)],
    highlight=["mw_y3_1", "mw_y3_5"],
    tip="相邻墙竖边全部互咬 —— 一整面绿篱比单片墙稳得多。",
)
b.step(
    "立瞭望塔一层: 门框方朝西开向迷宫终点, 其余三面灰墙合环。",
    ["tw_door", "tw_s1", "tw_e1", "tw_n1"],
    highlight=["fd_3_2", "fd_2_2"],
    tip="走完迷宫的人正对塔门 —— 推门就能上塔领奖。",
)
b.step(
    "叠瞭望塔二层: 4 面窗格方 360 度瞭望, 四角竖边互吸。",
    ["tw_s2", "tw_w2", "tw_e2", "tw_n2"],
    highlight=["tw_door"],
    tip="迷路的小朋友看这里 —— 上塔一眼就能望穿全阵。",
)
b.step(
    "封塔顶 + 升塔旗: 方板四边压窗顶, 红旗骑塔顶北沿。",
    ["tw_cap", "tw_flag"],
    highlight=["tw_n2"],
    tip="塔旗底边'塔顶沿+窗顶'一线双吸 —— 迷宫的终点旗。",
)
b.step(
    "种玉米高杆 + 挂门旗: 4 株等腰高杆骑墙顶直上 3.0, 门楼"
    "两侧黄旗就位。",
    ["corn_a", "corn_b", "corn_c", "corn_d", "gt_flag_w", "gt_flag_e"],
    highlight=["mw_y4_1", "gt_w_hi"],
    tip="高杆重心正压墙顶铰链零力矩 —— 玉米比墙还高才像迷宫。",
)
b.step(
    "补玉米丛: 2 片等边三角骑进封闭玉米荡 —— 开园!",
    ["corn_e", "corn_f"],
    highlight=["mw_x2_0", "mw_x2_2"],
    tip="从门楼进, 西绕北折东进塔 —— 走错了就上塔看一眼再来!",
)

b.finalize(
    model_id="corn_maze_01",
    name="玉米迷宫",
    name_en="Corn Maze 01",
    description=(
        "只用核心九片型的负空间迷宫: 主角不是墙围出的房间, 而是墙"
        "留出的路 —— 6x5 玉米田上 21 片绿色玉米墙骑田垄拼缝立成"
        "迷宫阵 (一缝双吸重心正压铰链零力矩, 拐角丁字竖边互咬),"
        " 橙色土路蜿蜒出唯一通路, 三条死胡同两处玉米荡守株待兔;"
        " 南门楼双柱托楣纯剪互锁, 迷宫中心 1x1 两层瞭望塔一层门框"
        "方开向终点、二层四面窗格方 360 度找路, 塔旗一线双吸; 四株"
        "等腰玉米高杆骑墙顶直上 3.0 —— 走错了别急, 上塔看一眼再来!"
    ),
    difficulty=3,
    tags=["田园", "农场", "农业", "迷宫", "进阶"],
    min_pieces=74,
    min_steps=13,
)
