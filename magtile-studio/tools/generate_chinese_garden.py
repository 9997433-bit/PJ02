#!/usr/bin/env python3
"""生成模型 data/models/chinese_garden_01.json (中式园林 · 水榭石桥)。

田园园林主题: 与五重塔 (垂直旋位挑檐) 完全不同的中式意境 ——
水平铺陈的一进园林: 敞口大水榭 (南面整面开门, 上环梁圈两端竖边
互吸悬跨门洞) 戴梯形四坡青瓦顶; 一条四墩石桥横跨莲池, 桥面长板
两端同时压住相邻桥墩顶边 (双端受力零悬挑), 桥栏三角对立; 对岸
假山锥峰、迎客松与一座四坡攒尖小亭收景。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 大水榭 [0,2]x[0,2]: 地板长板 2 + 下层三面环墙 3 (南面敞开) +
    上层环梁圈 4 + 梯形四坡顶 4 + 攒尖压顶 1                     14 片
  - 榭前石径 [2,3]x[0,2] + 一对石灯笼                              3 片
  - 莲池 [3,6]x[0,2]: 3 片长板碧水                                 3 片
  - 四墩石桥: 桥墩 4 (立式长板) + 桥面长板 3 (z=1) + 桥栏 6      13 片
  - 对岸: 东岸长板 + 岸边园地 4 方板                               5 片
  - 假山: 四坡锥峰 4 + 山石 1 + 迎客松 1                           6 片
  - 攒尖小亭 [6,7]x[2,3]: 四壁 (西面透明观景) + 四坡锥顶           8 片
  合计 52 片, 17 个教程步骤, 5 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 水榭南面整面敞开 (2 格宽负空间): 上层南梁两端竖边吸东西梁
    竖边, 与北/东/西梁合成自锁环, 环顶再收梯形四坡顶;
  - 石桥每跨桥面长板两端同时吸左右桥墩顶边 (罗马水道桥同款
    双端受力), 桥墩底边整边吸莲池长板边线;
  - 地板/石径/莲池/东岸全部用纵铺长板, x 整数线上的长边 (长 2)
    与桥墩底边、榭墙底边逐段等长整边贴合。

用法: python3 tools/generate_chinese_garden.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

WOOD = "red"        # 榭身朱红
TILE = "cyan"       # 青瓦
WATER = "blue"      # 莲池
STONE = "gray"      # 石桥石径
PINE = "green"      # 松与园地

# =================================================================
# 1. 大水榭 [0,2]x[0,2]: 地板 + 下层三面环墙 (南面敞开) + 上层环梁圈
# =================================================================
b.flat_rect("pav_fl_w", 0, 0, 0.0, "yellow", axis="y")   # [0,1]x[0,2]
b.flat_rect("pav_fl_e", 1, 0, 0.0, "yellow", axis="y")   # [1,2]x[0,2]
b.lintel_ew("pw0_w", 0.0, 0, 0, WOOD)               # 下层西墙 (整片长板)
b.lintel_ew("pw0_e", 2.0, 0, 0, WOOD)               # 下层东墙
b.lintel_ns("pw0_n", 0, 2.0, 0, WOOD)               # 下层北墙; 南面敞开
b.lintel_ew("pw1_w", 0.0, 0, 1, WOOD)               # 上层环梁圈
b.lintel_ew("pw1_e", 2.0, 0, 1, WOOD)
b.lintel_ns("pw1_n", 0, 2.0, 1, WOOD)
b.lintel_ns("pw1_s", 0, 0.0, 1, WOOD)               # 南梁悬跨门洞 (两端受力)
ROOF, ROOF_CAP = b.hip_roof2("pav_rf", 0, 0, 2.0, TILE, cap_color="yellow")

# =================================================================
# 2. 榭前石径 [2,3]x[0,2] + 一对石灯笼
# =================================================================
b.flat_rect("path", 2, 0, 0.0, STONE, axis="y")
b.spire_ns("lant_s", 2, 0.0, 0.0, "orange")         # 石灯笼 (南)
b.spire_ns("lant_n", 2, 2.0, 0.0, "orange")         # 石灯笼 (北)

# =================================================================
# 3. 莲池 [3,6]x[0,2] + 四墩石桥 (桥面 z=1) + 桥栏
# =================================================================
for x in range(3, 6):
    b.flat_rect(f"pond_{x}", x, 0, 0.0, WATER, axis="y")
for x in range(3, 7):                               # 桥墩: 立式长板
    b.lintel_ew(f"pier_{x}", float(x), 0, 0, STONE)
for x in range(3, 6):                               # 桥面: 双端压墩顶
    b.flat_rect(f"deck_{x}", x, 0, 1.0, STONE, axis="y")
for x in range(3, 6):                               # 桥栏: 三角对立
    b.crest_ns(f"rail_s_{x}", x, 0.0, 1.0, WOOD)
    b.crest_ns(f"rail_n_{x}", x, 2.0, 1.0, WOOD)

# =================================================================
# 4. 对岸: 东岸长板 + 岸边园地 (y 2..3 一排方板)
# =================================================================
b.flat_rect("shore", 6, 0, 0.0, PINE, axis="y")     # [6,7]x[0,2]
for x in range(3, 7):
    b.flat(f"gdn_{x}", x, 2, 0.0, PINE)

# =================================================================
# 5. 假山锥峰 + 山石 + 迎客松
# =================================================================
ROCK = b.hat4("rock", 4, 2.0, 0.0, STONE)           # 四坡假山 (等腰锥峰)
b.crest_ns("stone", 3, 3.0, 0.0, STONE)             # 山石
b.spire_ns("pine", 5, 3.0, 0.0, PINE)               # 迎客松

# =================================================================
# 6. 攒尖小亭 [6,7]x[2,3]: 四壁 (西面透明观景) + 四坡锥顶
# =================================================================
b.wall_ns("kio_s", 6, 2.0, 0, WOOD)
b.wall_ns("kio_n", 6, 3.0, 0, WOOD)
b.wall_ew("kio_w", 6.0, 2, 0, "clear")              # 观景面正对石桥
b.wall_ew("kio_e", 7.0, 2, 0, WOOD)
KIO_HAT = b.hat4("kio_hat", 6, 2.0, 1.0, TILE, shape="equilateral_triangle")

# =================================================================
# 教程步骤 (17 步)
# =================================================================
b.step(
    "铺水榭地板与石径: 2 片黄色长板纵铺成榭底, 东侧再接 1 片灰色石径长板。",
    ["pav_fl_w", "pav_fl_e", "path"],
    tip="三片长板的长边都落在 x 整数线上 —— 之后墙和桥墩全靠这些边。",
)
b.step(
    "立水榭下层环墙: 西、东、北三面各立 1 片整幅长板墙, 南面整面敞开。",
    ["pw0_w", "pw0_e", "pw0_n"],
    highlight=["pav_fl_w", "pav_fl_e"],
    tip="墙底边 (长 2) 与地板长边逐段等长整边贴合; 敞开的南面就是水榭的看台。",
)
b.step(
    "架上层环梁圈: 西、东、北三面先叠, 南梁最后悬跨门洞, "
    "两端竖边吸东西梁竖边 —— 四片合成自锁环。",
    ["pw1_w", "pw1_e", "pw1_n", "pw1_s"],
    highlight=["pw0_w", "pw0_e"],
    tip="南梁下面没有墙, 全靠两端竖边受力 —— 这就是敞口水榭的门脸。",
)
b.step(
    "收梯形四坡顶: 4 片青瓦梯形下底整边吸环梁顶边, 四腰两两互吸。",
    ROOF,
    highlight=["pw1_s", "pw1_n"],
    tip="梯形下底长 2, 恰与环梁顶边等长 —— 一片压一面。",
)
b.step(
    "盖攒尖压顶: 1 片黄色方片盖住四坡顶围出的天窗口, 大水榭落成。",
    [ROOF_CAP],
    highlight=ROOF[:2],
    tip="压顶四边同时吸四片梯形上底 —— 咔哒一声整顶锁死。",
)
b.step(
    "立石灯笼: 石径南北两端各立 1 座橙色等腰石灯笼。",
    ["lant_s", "lant_n"],
    highlight=["path"],
    tip="灯笼底边吸石径短边, 是入园的第一重仪式感。",
)
b.step(
    "铺莲池: 3 片蓝色长板纵铺 ([3,6]x[0,2]), 与石径长边相吸。",
    ["pond_3", "pond_4", "pond_5"],
    highlight=["path"],
    tip="池水的每条 x 整数线马上都要站上一座桥墩。",
)
b.step(
    "立四座桥墩: 4 片灰色长板立在 x = 3/4/5/6 四条边线上, "
    "底边与池板长边整边贴合。",
    ["pier_3", "pier_4", "pier_5", "pier_6"],
    highlight=["pond_3", "pond_5"],
    tip="桥墩是立式长板 —— 一片顶两根柱子, 稳而通透。",
)
b.step(
    "铺桥面: 3 片灰色长板依次压上, 每片两端同时吸左右桥墩顶边。",
    ["deck_3", "deck_4", "deck_5"],
    highlight=["pier_3", "pier_6"],
    tip="双端受力零悬挑 —— 罗马水道桥同款的过跨手法。",
)
b.step(
    "装南侧桥栏: 3 片朱红三角立在桥面南沿。",
    ["rail_s_3", "rail_s_4", "rail_s_5"],
    highlight=["deck_4"],
    tip="桥栏立在桥面短边正上方, 力臂为零纯压不弯。",
)
b.step(
    "装北侧桥栏: 再立 3 片, 石桥合栏。",
    ["rail_n_3", "rail_n_4", "rail_n_5"],
    highlight=["rail_s_4"],
    tip="过桥赏莲, 两侧都要有栏 —— 安全第一。",
)
b.step(
    "铺东岸与岸边园地东段: 东岸长板吸池板东沿, 上方园地方板接岸铺开。",
    ["shore", "gdn_6"],
    highlight=["pond_5", "pier_6"],
    tip="东岸是绿色草坡, 小亭马上要立在它的园地上。",
)
b.step(
    "铺岸边园地西段: 沿莲池北沿再铺 3 片绿色方板。",
    ["gdn_3", "gdn_4", "gdn_5"],
    highlight=["gdn_6", "pond_3"],
    tip="园地方板南边吸池板短边 —— 池与园无缝相接。",
)
b.step(
    "堆假山锥峰: 4 片灰色等腰三角在园地上收成一座锥峰, 斜棱互吸自锁。",
    ROCK,
    highlight=["gdn_4"],
    tip="假山就是一顶落地的四坡尖 —— 中式园林的骨。",
)
b.step(
    "点山石与迎客松: 峰旁立 1 片山石, 松立峰东。",
    ["stone", "pine"],
    highlight=ROCK[:1],
    tip="一峰一石一松 —— 三笔点出园林的画意。",
)
b.step(
    "立攒尖小亭四壁: 园地东端立 4 片亭壁, 朝桥的西面用透明片。",
    ["kio_s", "kio_n", "kio_e", "kio_w"],
    highlight=["gdn_6"],
    tip="透明观景面正对石桥 —— 坐在亭里看桥上人。",
)
b.step(
    "收攒尖锥顶: 4 片青瓦等边三角锁成攒尖顶, 水榭石桥一进园林完工!",
    KIO_HAT,
    highlight=["kio_s", "kio_n"],
    tip="隔水相望: 大水榭四坡顶与小亭攒尖顶一大一小遥相呼应。",
)

b.finalize(
    model_id="chinese_garden_01",
    name="中式园林水榭",
    name_en="Chinese Garden Pavilion 01",
    description=(
        "水平铺陈的一进中式园林: 敞口大水榭南面整面开门 (上层南梁两端竖边"
        "互吸悬跨 2 格门洞), 头戴梯形四坡青瓦顶; 四墩石桥横跨莲池, 每跨桥面"
        "长板两端同时压住相邻桥墩顶边 (双端受力零悬挑), 桥栏三角对立; 对岸"
        "假山锥峰、山石迎客松与透明观景面的攒尖小亭收景 —— 一桥一榭一亭, "
        "隔水相望。"
    ),
    difficulty=3,
    tags=["田园", "园林", "亭台", "石桥", "四坡顶"],
    min_pieces=50,
    min_steps=16,
)
