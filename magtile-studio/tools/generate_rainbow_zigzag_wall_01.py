#!/usr/bin/env python3
"""生成模型 data/models/rainbow_zigzag_wall_01.json (彩虹之字折墙)。

D1 补员批 4 模型 3/4 (难度配额解冻线 D1 >= 20, 路径 B1): 入门档
几何艺术选题 —— 桌面上的彩虹之字折墙。结构签名是"开放折线屏风":
六片立墙沿对角线一横一纵交替行进, 相邻墙竖棱 90 度角缝互吸 ——
每一道折角就是一根天然的角柱, 这是"折纸为什么站得住"的几何
启蒙; 折线两侧铺台阶状地板锁住墙脚, 两端直角三角斜撑当书挡,
墙顶六面彩虹小旗依次排开。与凉亭 (围院中心亭)、板桥 (墩-梁-板)
和小黄鸭 (叠层动物) 的结构逻辑完全不同 —— 本批唯一不合围的
开放结构, 靠折角而不是环圈获得刚度。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 台阶地板 6 片方板 (沿折线两侧棋盘错落)                   6 片
  - 之字立墙 6 片方板 (一横一纵交替, 竖棱 90 度互吸)         6 片
  - 两端直角三角斜撑 (竖直角边完整吸住端墙竖棱)              2 片
  - 墙顶彩虹小旗 6 面 (等边三角, 与墙顶整边重合)             6 片
  合计 20 片, 5 个教程步骤, 3 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 每片立墙墙脚整边骑住地板边 (R2), 与前一片墙竖棱 90 度
    角缝互吸 —— 折角即角柱, 出平面方向互为斜撑;
  - 全结构接地受压, 无悬挑无吊挂, 逐片放置时刻有依托 (R7a);
  - 两端斜撑竖直角边完整贴合端墙自由竖棱, 封住折线的开口端;
  - 最高点 1.58 (彩虹小旗) < 2.5, 不触发 R8 高层结构判定。

用法: python3 tools/generate_rainbow_zigzag_wall_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

FLOOR_A = "gray"    # 台阶地板 (深)
FLOOR_B = "clear"   # 台阶地板 (浅)
WALL = "blue"       # 之字立墙
BRACE = "gray"      # 两端斜撑
RAINBOW = ["red", "orange", "yellow", "green", "cyan", "purple"]  # 墙顶小旗

# =================================================================
# 1. 台阶地板: 沿折线两侧棋盘错落 (每格都被两段墙脚骑住)
# =================================================================
b.flat("floor_a", 0, 0, 0.0, FLOOR_A)   # [0,1] x [0,1]
b.flat("floor_b", 1, 0, 0.0, FLOOR_B)   # [1,2] x [0,1]
b.flat("floor_c", 1, 1, 0.0, FLOOR_A)   # [1,2] x [1,2]
b.flat("floor_d", 2, 1, 0.0, FLOOR_B)   # [2,3] x [1,2]
b.flat("floor_e", 2, 2, 0.0, FLOOR_A)   # [2,3] x [2,3]
b.flat("floor_f", 3, 2, 0.0, FLOOR_B)   # [3,4] x [2,3]

# =================================================================
# 2. 之字立墙: 一横一纵交替行进, 相邻竖棱 90 度角缝互吸
# =================================================================
b.wall_ns("wall_1", 0, 0.0, 0, WALL)    # x [0,1], y=0
b.wall_ew("wall_2", 1.0, 0, 0, WALL)    # y [0,1], x=1
b.wall_ns("wall_3", 1, 1.0, 0, WALL)    # x [1,2], y=1
b.wall_ew("wall_4", 2.0, 1, 0, WALL)    # y [1,2], x=2
b.wall_ns("wall_5", 2, 2.0, 0, WALL)    # x [2,3], y=2
b.wall_ew("wall_6", 3.0, 2, 0, WALL)    # y [2,3], x=3

# =================================================================
# 3. 两端斜撑 (直角三角书挡, 竖直角边吸端墙自由竖棱)
# =================================================================
b.brace("brace_w", (0.0, 0.0, 0.0), "-x", BRACE)
b.brace("brace_e", (3.0, 3.0, 0.0), "+y", BRACE)

# =================================================================
# 4. 墙顶彩虹小旗 (等边三角, 与墙顶整边重合, 依次六色)
# =================================================================
b.crest_ns("flag_1", 0, 0.0, 1.0, RAINBOW[0])
b.crest_ew("flag_2", 1.0, 0, 1.0, RAINBOW[1])
b.crest_ns("flag_3", 1, 1.0, 1.0, RAINBOW[2])
b.crest_ew("flag_4", 2.0, 1, 1.0, RAINBOW[3])
b.crest_ns("flag_5", 2, 2.0, 1.0, RAINBOW[4])
b.crest_ew("flag_6", 3.0, 2, 1.0, RAINBOW[5])

# =================================================================
# 教程步骤 (5 步)
# =================================================================
b.step(
    "铺台阶地板: 六片方板深浅相间, 沿对角线一格一格错着往上铺。",
    ["floor_a", "floor_b", "floor_c", "floor_d", "floor_e", "floor_f"],
    tip="地板本身就是台阶图案 —— 之字墙待会儿正好踩在格线上。",
)
b.step(
    "立前三段折墙: 蓝色立墙一横一纵交替, 相邻两片竖棱 90 度角缝互吸。",
    ["wall_1", "wall_2", "wall_3"],
    highlight=["floor_a", "floor_b"],
    tip="试着推一推 —— 折过角的墙比直墙难推倒, 折角就是柱子。",
)
b.step(
    "立后三段折墙: 再折两个角, 之字形一路走到东北端。",
    ["wall_4", "wall_5", "wall_6"],
    highlight=["wall_3", "floor_d"],
)
b.step(
    "装两端书挡: 两片灰色直角三角竖直角边完整吸住端墙竖棱, 封住折线开口。",
    ["brace_w", "brace_e"],
    highlight=["wall_1", "wall_6"],
)
b.step(
    "升彩虹小旗: 红橙黄绿青紫六面小旗依次骑上墙顶, 彩虹折墙完工!",
    ["flag_1", "flag_2", "flag_3", "flag_4", "flag_5", "flag_6"],
    highlight=["wall_1", "wall_6"],
)

b.finalize(
    model_id="rainbow_zigzag_wall_01",
    name="彩虹之字折墙",
    name_en="Rainbow Zigzag Wall 01",
    description=(
        "入门档几何艺术: 桌面上的彩虹之字折墙, 结构签名是'开放折线"
        "屏风' —— 六片蓝色立墙沿对角线一横一纵交替行进, 相邻墙竖棱 "
        "90 度角缝互吸, 每道折角就是一根天然角柱, 出平面方向互为"
        "斜撑; 墙脚整边骑住深浅相间的台阶地板, 两端直角三角书挡封住"
        "开口, 墙顶红橙黄绿青紫六面小旗依次排开。20 片全程接地受压, "
        "不用合围也站得稳 —— 这就是'折纸为什么站得住'的几何启蒙。"
    ),
    difficulty=1,
    tags=["几何艺术", "折墙", "屏风", "对称", "入门"],
    min_pieces=20,
    min_steps=5,
    series="geometric_art",
)
print("已写入 series=geometric_art")
