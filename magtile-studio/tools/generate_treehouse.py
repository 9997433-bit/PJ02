#!/usr/bin/env python3
"""生成模型 data/models/treehouse_01.json (树屋)。

第四批模型 ⑤: 自然居住主题 —— 全库第一座架空平台居所:
草地院子中央留出 2x2 树池, 橙色空心树干从树池四沿长到 z=2;
平台不是悬挑 —— 树干顶托住中枢长板, 四角立柱撑住平台四角,
柱脚各抵一片直角三角斜撑; 平台上的小屋用长方形横楣围成
两环 (上环透明当窗), 梯形四坡顶压顶; 绿色树冠从平台四沿
探出来兼作护栏, 灰色爬梯板贴着东舷上下 —— 树屋建成入住。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 草地院子: 4x4 网格挖去中央 2x2 树池, 环形 12 片        12 片
  - 树干: 2x2 空心墙环 x 2 层                              16 片
  - 四角立柱: 4 根 x 2 段                                   8 片
  - 柱脚斜撑: 4 片直角三角形                                 4 片
  - 爬梯: 2 片灰色立板 (东侧)                                2 片
  - 平台: 中枢长板 2 (骑树干顶) + 外圈正方形 12             14 片
  - 小屋: 长方形横楣双环 (下环红墙, 上环透明窗)              8 片
  - 屋顶: 梯形四坡 + 正方形压顶                              5 片
  - 树冠护栏: 7 片绿色等边三角形                             7 片
  - 花丛: 3 片粉色等边三角形                                 3 片
  合计 79 片, 18 个教程步骤, 5 种磁力片形状。

几何要点:
  - 中枢长板短边 (长 1) 吸树干东西墙顶, 长边 (长 2) 供小屋
    横楣整边落座 —— 正方形接单位边, 长方形接长边, 分段用料;
  - 立柱顶边与平台角板底边整边互吸, 树干+四柱+平台+院子
    围成多重力学环路, 平台外圈没有一片是悬挑;
  - 树冠护栏与立柱同面错高零重叠 (共用平台沿口棱线)。

用法: python3 tools/generate_treehouse.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

# =================================================================
# 1. 草地院子 (z=0): 4x4 网格挖去中央 2x2 树池, 环形 12 片
# =================================================================
YARD_RING = [(x, y) for x in (1, 2, 3, 4) for y in (1, 2, 3, 4)
             if not (x in (2, 3) and y in (2, 3))]
for x, y in YARD_RING:
    b.flat(f"yard_{x}_{y}", x, y, 0.0, "green")

# =================================================================
# 2. 树干 (z 0..2): 2x2 空心墙环 x 2 层, 站在树池四沿
# =================================================================
for lv in (0, 1):
    for x in (2, 3):
        b.wall_ns(f"trk_s{lv}_{x}", x, 2.0, lv, "orange")
    for x in (2, 3):
        b.wall_ns(f"trk_n{lv}_{x}", x, 4.0, lv, "orange")
    for y in (2, 3):
        b.wall_ew(f"trk_w{lv}_{y}", 2.0, y, lv, "orange")
    for y in (2, 3):
        b.wall_ew(f"trk_e{lv}_{y}", 4.0, y, lv, "orange")

# =================================================================
# 3. 四角立柱 (z 0..2) + 柱脚斜撑
# =================================================================
STILTS = {"sw": (1, 1.0), "se": (4, 1.0), "nw": (1, 5.0), "ne": (4, 5.0)}
for key, (x0, y) in STILTS.items():
    for lv in (0, 1):
        b.wall_ns(f"stilt_{key}_{lv}", x0, y, lv, "orange")
b.brace("brc_sw", (2.0, 1.0, 0.0), "+x", "orange")
b.brace("brc_se", (4.0, 1.0, 0.0), "-x", "orange")
b.brace("brc_nw", (2.0, 5.0, 0.0), "+x", "orange")
b.brace("brc_ne", (4.0, 5.0, 0.0), "-x", "orange")

# =================================================================
# 4. 爬梯 (东侧, z 0..2): 2 片灰色立板
# =================================================================
b.wall_ew("ladder_0", 5.0, 2, 0, "gray")
b.wall_ew("ladder_1", 5.0, 2, 1, "gray")

# =================================================================
# 5. 平台 (z=2): 中枢长板 2 + 外圈正方形 12
# =================================================================
b.flat_rect("plat_ra", 2, 2, 2.0, "yellow", axis="x")   # x 2..4, y 2..3
b.flat_rect("plat_rb", 2, 3, 2.0, "yellow", axis="x")   # x 2..4, y 3..4
for y in (1, 2, 3, 4):
    b.flat(f"plat_w_{y}", 1, y, 2.0, "yellow")          # 西列
for y in (1, 2, 3, 4):
    b.flat(f"plat_e_{y}", 4, y, 2.0, "yellow")          # 东列
for x in (2, 3):
    b.flat(f"plat_s_{x}", x, 1, 2.0, "yellow")          # 南补条
for x in (2, 3):
    b.flat(f"plat_n_{x}", x, 4, 2.0, "yellow")          # 北补条

# =================================================================
# 6. 小屋 (x 2..4, y 2..4): 横楣双环 + 梯形四坡顶
# =================================================================
b.lintel_ns("cab_s_lo", 2, 2.0, 2, "red")
b.lintel_ns("cab_n_lo", 2, 4.0, 2, "red")
b.lintel_ew("cab_w_lo", 2.0, 2, 2, "red")
b.lintel_ew("cab_e_lo", 4.0, 2, 2, "red")
b.lintel_ns("cab_s_hi", 2, 2.0, 3, "clear")
b.lintel_ns("cab_n_hi", 2, 4.0, 3, "clear")
b.lintel_ew("cab_w_hi", 2.0, 2, 3, "clear")
b.lintel_ew("cab_e_hi", 4.0, 2, 3, "clear")
roof_ids, roof_cap = b.hip_roof2("roof", 2, 2, 4.0, "red", cap_color="yellow")

# =================================================================
# 7. 树冠护栏 (z=2 沿口) + 花丛 (z=0 院沿)
# =================================================================
for x in (2, 3):
    b.crest_ns(f"cnp_s_{x}", x, 1.0, 2.0, "green")
for x in (2, 3):
    b.crest_ns(f"cnp_n_{x}", x, 5.0, 2.0, "green")
for y in (2, 3):
    b.crest_ew(f"cnp_w_{y}", 1.0, y, 2.0, "green")
b.crest_ew("cnp_e_3", 5.0, 3, 2.0, "green")             # 东侧留爬梯口
b.crest_ew("flw_w_1", 1.0, 1, 0.0, "pink")
b.crest_ew("flw_w_4", 1.0, 4, 0.0, "pink")
b.crest_ew("flw_e_1", 5.0, 1, 0.0, "pink")

# =================================================================
# 教程步骤 (18 步)
# =================================================================
b.step(
    "铺前院草地: 6 片绿色正方形拼出院子南半圈。",
    ["yard_1_1", "yard_2_1", "yard_3_1", "yard_4_1", "yard_1_2", "yard_4_2"],
    tip="院子中央要留 2x2 树池, 先沿南沿和两侧铺。",
)
b.step(
    "铺后院草地: 再 6 片合拢成环形院子, 中央树池空着。",
    ["yard_1_3", "yard_4_3", "yard_1_4", "yard_2_4", "yard_3_4", "yard_4_4"],
    highlight=["yard_1_2", "yard_4_2"],
    tip="12 片草地围成一圈 —— 树就从中间的树池里长出来。",
)
b.step(
    "立树干下环: 8 片橙色正方形沿树池四沿围成空心方筒。",
    ["trk_s0_2", "trk_s0_3", "trk_n0_2", "trk_n0_3",
     "trk_w0_2", "trk_w0_3", "trk_e0_2", "trk_e0_3"],
    highlight=["yard_2_1", "yard_1_2"],
    tip="墙底整边吸草地内沿, 相邻竖边互锁 —— 树干是承重核心。",
)
b.step(
    "立树干上环: 再 8 片叠到 z=2, 树干长到平台高度。",
    ["trk_s1_2", "trk_s1_3", "trk_n1_2", "trk_n1_3",
     "trk_w1_2", "trk_w1_3", "trk_e1_2", "trk_e1_3"],
    highlight=["trk_s0_2"],
    tip="上下环逐片对缝, 空心方筒抗弯远胜单片墙。",
)
b.step(
    "立四角柱下段: 4 根立柱站上院子四角的边沿。",
    ["stilt_sw_0", "stilt_se_0", "stilt_nw_0", "stilt_ne_0"],
    highlight=["yard_1_1", "yard_4_4"],
    tip="柱底整边吸草地边沿 —— 平台四角将来落在柱顶上。",
)
b.step(
    "接四角柱上段: 每根柱再叠一片, 柱顶到 z=2。",
    ["stilt_sw_1", "stilt_se_1", "stilt_nw_1", "stilt_ne_1"],
    highlight=["stilt_sw_0"],
    tip="柱顶边与树干顶同高, 等着一起托平台。",
)
b.step(
    "抵柱脚斜撑: 4 片橙色直角三角形, 直角边分别吸院沿与柱竖边。",
    ["brc_sw", "brc_se", "brc_nw", "brc_ne"],
    highlight=["stilt_sw_1"],
    tip="斜撑朝院子中线倒, 立柱从此不怕侧向晃动。",
)
b.step(
    "挂东侧爬梯: 2 片灰色立板贴着院子东沿叠到 z=2。",
    ["ladder_0", "ladder_1"],
    highlight=["yard_4_2"],
    tip="梯板顶边将来吸住平台东沿 —— 这是上树的唯一通道。",
)
b.step(
    "架平台中枢长板: 2 片黄色长方形骑上树干顶, 短边吸东西墙顶。",
    ["plat_ra", "plat_rb"],
    highlight=["trk_w1_2", "trk_e1_2"],
    tip="长板两端都坐在树干顶上, 长边留给小屋横楣落座。",
)
b.step(
    "铺平台西列: 4 片正方形从西南角柱顶接到西北角柱顶。",
    ["plat_w_1", "plat_w_2", "plat_w_3", "plat_w_4"],
    highlight=["plat_ra", "stilt_sw_1"],
    tip="角板底边吸柱顶边, 中段吸中枢长板短边 —— 没有一片悬挑。",
)
b.step(
    "铺平台东列: 再 4 片, 爬梯顶边同时被吸住。",
    ["plat_e_1", "plat_e_2", "plat_e_3", "plat_e_4"],
    highlight=["ladder_1", "stilt_se_1"],
    tip="东列压住爬梯板顶边, 上树通道从此受力闭环。",
)
b.step(
    "补平台南北条: 4 片正方形补齐 4x4 平台。",
    ["plat_s_2", "plat_s_3", "plat_n_2", "plat_n_3"],
    highlight=["plat_w_1", "plat_e_4"],
    tip="补条两端吸住东西列 —— 平台成为一整张受力网。",
)
b.step(
    "围小屋下环: 4 根红色横楣站上中枢长板长边, 转角竖边互吸。",
    ["cab_s_lo", "cab_n_lo", "cab_w_lo", "cab_e_lo"],
    highlight=["plat_ra", "plat_rb"],
    tip="横楣整条长边落座 —— 长方形接长边, 正方形接单位边。",
)
b.step(
    "叠小屋上环: 4 根透明横楣当环形大窗。",
    ["cab_s_hi", "cab_n_hi", "cab_w_hi", "cab_e_hi"],
    highlight=["cab_s_lo"],
    tip="透明窗环让屋里看得见四面树冠。",
)
b.step(
    "盖梯形四坡顶: 4 片红梯形下底吸横楣顶边, 腰两两互锁, "
    "黄色压顶封口。",
    roof_ids + [roof_cap],
    highlight=["cab_s_hi"],
    tip="四坡自锁成环, 压顶一扣, 屋顶纹丝不动。",
)
b.step(
    "插南北树冠: 4 片绿色三角形立上平台南北沿口。",
    ["cnp_s_2", "cnp_s_3", "cnp_n_2", "cnp_n_3"],
    highlight=["plat_s_2", "plat_n_3"],
    tip="树冠从平台沿口探出来, 兼作护栏。",
)
b.step(
    "插西东树冠: 再 3 片, 东侧留出爬梯口。",
    ["cnp_w_2", "cnp_w_3", "cnp_e_3"],
    highlight=["cnp_s_2", "ladder_1"],
    tip="爬梯口不装护栏 —— 上下树屋就走这里。",
)
b.step(
    "种院沿花丛: 3 片粉色三角形立上院子边沿 —— 树屋建成入住!",
    ["flw_w_1", "flw_w_4", "flw_e_1"],
    highlight=["yard_1_1"],
    tip="花丛贴着院沿开放, 树屋的春天到了。",
)

b.finalize(
    model_id="treehouse_01",
    name="树屋",
    name_en="Treehouse 01",
    description=(
        "自然居住主题: 全库第一座架空平台居所 —— 草地院子中央留出 "
        "2x2 树池, 橙色空心树干方筒从树池四沿长到 z=2; 平台没有一片"
        "悬挑: 树干顶托住中枢长板 (短边接墙顶单位边), 四角立柱撑住"
        "平台四角, 柱脚直角三角斜撑抵住侧晃; 小屋用长方形横楣围成"
        "双环 (长边整条落座长板长边, 上环透明当窗), 梯形四坡顶自锁"
        "压顶; 绿色树冠从平台四沿探出兼作护栏, 灰色爬梯板贴东舷"
        "上下, 粉色花丛沿院沿开放 —— 树屋建成入住。"
    ),
    difficulty=4,
    tags=["自然", "树屋", "居住", "平台", "田园"],
    min_pieces=75,
    min_steps=18,
)
