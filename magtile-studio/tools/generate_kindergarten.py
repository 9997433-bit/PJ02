#!/usr/bin/env python3
"""生成模型 data/models/kindergarten_01.json (彩虹幼儿园)。

城市生活主题: 全库第一座为孩子设计的校园 —— 7x5 园区里,
一排 3x1 彩色教室戴 60 度人字坡屋顶 (橙色屋面对脊互吸,
两端等边山花严丝合缝), 红色大门正对青色入园步道; 园里
滑梯平台四墙自锁、青色滑道从平台北沿俯冲进后草坪,
黄色沙坑三面粉色围边, 两只直角三角摇摇马一红一蓝,
粉色迎宾板立在门口, 大树成荫、园旗高扬 —— 放学啦,
再玩十分钟!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 大门朝南):
  - 园区地坪 7x5: 草坪/操场/步道/沙坑混铺                      28 片
  - 教室 [1,4]x[3,4]: 北墙彩板 x3 + 山墙 x2 + 南脸 门x1/窗x2    8 片
  - 人字坡屋顶: 等边山花 x2 + 60 度屋面 长板x2/方板x2           6 片
  - 滑梯: 平台四墙 x4 + 甲板 x1 + 30 度滑道 x1 + 护栏三角 x2    8 片
  - 沙坑围边: 等边三角 x3                                       3 片
  - 迎宾板 x1 + 园旗等腰三角 x1                                 2 片
  - 摇摇马: 直角三角 x2                                         2 片
  - 大树: 方板树干 x2 + 等边树冠 x2                             4 片
  合计 61 片, 16 个教程步骤, 7 种磁力片形状 (CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验):
  - 人字坡屋面对脊互吸自锁: 屋面片沿墙顶眼线 60 度斜起,
    短边与山花斜边精确互吸, 脊线两坡相抵纯受压;
  - 滑道顶边同时吸平台甲板北边与北墙顶 (共线双连接),
    坡尾自然落地 —— 接地斜撑零悬臂;
  - 迎宾板/摇摇马/园旗/树干全部底边整边吸地坪格线,
    重心正压铰链零力矩。

用法: python3 tools/generate_kindergarten.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

LAWN = "green"      # 草坪
PLAY = "gray"       # 操场地坪
PATH = "cyan"       # 入园步道
SAND = "yellow"     # 沙坑
ROOF = "orange"     # 屋面
WIN = "clear"       # 教室窗
DOOR = "red"        # 教室大门
SLIDE = "cyan"      # 滑道
DECK = "red"        # 平台甲板
TOWER = "yellow"    # 平台墙
PINK = "pink"
RED = "red"
BLUE = "blue"
TRUNK = "gray"      # 树干
LEAF = "green"      # 树冠

# =================================================================
# 1. 园区地坪 7x5
# =================================================================
b.flat_rect("gl_a", 0, 4, 0.0, LAWN)                # 后草坪 [0,2]
b.flat_rect("gl_b", 2, 4, 0.0, LAWN)                # 后草坪 [2,4]
b.flat_rect("gl_c", 4, 4, 0.0, LAWN)                # 后草坪 [4,6]
b.flat("gl_d", 6, 4, 0.0, LAWN)                     # 后草坪 [6,7]
for x in range(7):
    color = PLAY if 1 <= x <= 4 else LAWN
    b.flat(f"g3_{x}", x, 3, 0.0, color)             # 教室行
b.flat("g2_0", 0, 2, 0.0, PLAY)
b.flat("g2_1", 1, 2, 0.0, PATH)                     # 步道
b.flat_rect("g2_r1", 2, 2, 0.0, PLAY)               # [2,4]
b.flat_rect("g2_r2", 4, 2, 0.0, PLAY)               # [4,6]
b.flat("g2_6", 6, 2, 0.0, PLAY)
b.flat("g1_0", 0, 1, 0.0, LAWN)
b.flat("g1_1", 1, 1, 0.0, PATH)                     # 步道
b.flat("g1_2", 2, 1, 0.0, SAND)                     # 沙坑西
b.flat("g1_3", 3, 1, 0.0, SAND)                     # 沙坑东
b.flat("g1_4", 4, 1, 0.0, PLAY)
b.flat("g1_5", 5, 1, 0.0, PLAY)                     # 平台底
b.flat("g1_6", 6, 1, 0.0, PLAY)
b.flat_rect("g0_a", 0, 0, 0.0, PATH)                # 入园口 [0,2]
b.flat("g0_2", 2, 0, 0.0, PLAY)
b.flat("g0_3", 3, 0, 0.0, PLAY)
b.flat_rect("g0_b", 4, 0, 0.0, PLAY)                # [4,6]
b.flat("g0_6", 6, 0, 0.0, LAWN)

# =================================================================
# 2. 教室 [1,4]x[3,4]: 北墙彩板 + 山墙 + 南脸门窗
# =================================================================
for x, c in ((1, RED), (2, "yellow"), (3, BLUE)):
    b.wall_ns(f"cw_n{x}", x, 4.0, 0, c)             # 北墙彩板
b.wall_ew("cw_w", 1.0, 3, 0, PINK)                  # 西山墙
b.wall_ew("cw_e", 4.0, 3, 0, SLIDE)                 # 东山墙
b.add("c_door", "door_frame", (1.5, 3.0, 0.5), (90, 0, 0), DOOR)
b.add("c_win1", "window_square", (2.5, 3.0, 0.5), (90, 0, 0), WIN)
b.add("c_win2", "window_square", (3.5, 3.0, 0.5), (90, 0, 0), WIN)

# =================================================================
# 3. 人字坡屋顶: 山花 + 60 度屋面 (脊线 y=3.5, z=1.866)
# =================================================================
RIDGE_Z = 1.0 + 0.866025
b.place_tri("gable_w", "equilateral_triangle",
            (1.0, 3.0, 1.0), (1.0, 4.0, 1.0), (1.0, 3.5, RIDGE_Z), ROOF)
b.place_tri("gable_e", "equilateral_triangle",
            (4.0, 4.0, 1.0), (4.0, 3.0, 1.0), (4.0, 3.5, RIDGE_Z), ROOF)
b.place_edge("rs_a", "rectangle", 0,
             (1.0, 3.0, 1.0), (3.0, 3.0, 1.0), (0.0, 0.5, 0.866025), ROOF)
b.place_edge("rs_b", "square", 0,
             (3.0, 3.0, 1.0), (4.0, 3.0, 1.0), (0.0, 0.5, 0.866025), ROOF)
b.place_edge("rn_a", "rectangle", 0,
             (4.0, 4.0, 1.0), (2.0, 4.0, 1.0), (0.0, -0.5, 0.866025), ROOF)
b.place_edge("rn_b", "square", 0,
             (2.0, 4.0, 1.0), (1.0, 4.0, 1.0), (0.0, -0.5, 0.866025), ROOF)

# =================================================================
# 4. 滑梯: 平台 [5,6]x[1,2] + 北向滑道 + 护栏
# =================================================================
b.wall_ns("sl_s", 5, 1.0, 0, TOWER)
b.wall_ns("sl_n", 5, 2.0, 0, TOWER)
b.wall_ew("sl_w", 5.0, 1, 0, TOWER)
b.wall_ew("sl_e", 6.0, 1, 0, TOWER)
b.flat("sl_deck", 5, 1, 1.0, DECK)
b.ramp("sl_ramp", "+y", 2.0, 5, 1.0, SLIDE)         # 滑道向北俯冲落草坪
b.crest_ns("sl_hr_s", 5, 1.0, 1.0, RED)             # 南护栏
b.crest_ew("sl_hr_e", 6.0, 1, 1.0, BLUE)            # 东护栏

# =================================================================
# 5. 沙坑围边 + 迎宾板 + 园旗 + 摇摇马 + 大树
# =================================================================
b.crest_ns("sb_1", 2, 1.0, 0.0, PINK)               # 沙坑南边
b.crest_ns("sb_2", 3, 1.0, 0.0, PINK)
b.crest_ew("sb_3", 4.0, 1, 0.0, PINK)               # 沙坑东边
b.lintel_ns("welcome", 0, 1.0, 0, PINK)             # 迎宾板 [0,2]
b.spire_ns("flag", 6, 0.0, 0.0, "yellow")           # 园旗
b.brace("horse_r", (0.0, 2.0, 0.0), "+x", RED)      # 红摇摇马
b.brace("horse_b", (6.0, 2.0, 0.0), "+x", BLUE)     # 蓝摇摇马
b.wall_ns("tr1_t", 5, 4.0, 0, TRUNK)                # 西树干
b.crest_ns("tr1_c", 5, 4.0, 1.0, LEAF)              # 西树冠
b.wall_ns("tr2_t", 6, 4.0, 0, TRUNK)                # 东树干
b.crest_ns("tr2_c", 6, 4.0, 1.0, LEAF)              # 东树冠

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺后草坪: 3 片绿色长板加 1 片方板沿 y=4 排开。",
    ["gl_a", "gl_b", "gl_c", "gl_d"],
    tip="草坪在最北面 —— 滑梯的落点和大树都在这里。",
)
b.step(
    "铺教室行地坪: 7 片方板, 中段灰色是教室的地基。",
    [f"g3_{x}" for x in range(7)],
    highlight=["gl_a", "gl_d"],
    tip="教室四面墙都会踩在这一排的格线上, 每片都要对齐。",
)
b.step(
    "铺操场与沙坑行: 步道青色向北延伸, 黄色两格就是沙坑。",
    ["g2_0", "g2_1", "g2_r1", "g2_r2", "g2_6",
     "g1_0", "g1_1", "g1_2", "g1_3", "g1_4", "g1_5", "g1_6"],
    highlight=["g3_1"],
    tip="长板与方板拼缝错开 —— 操场要经得起小朋友天天跑。",
)
b.step(
    "铺入园口: 青色长板大门口, 两侧操场与草坪收边。",
    ["g0_a", "g0_2", "g0_3", "g0_b", "g0_6"],
    highlight=["g1_1"],
    tip="青色步道从园门一直通到教室大门 —— 入园动线完成。",
)
b.step(
    "立教室北墙与山墙: 红黄蓝三片彩墙 + 粉青两片山墙。",
    ["cw_n1", "cw_n2", "cw_n3", "cw_w", "cw_e"],
    highlight=["g3_1", "g3_3"],
    tip="拐角竖边互吸 —— 彩色墙板是幼儿园的第一眼招牌。",
)
b.step(
    "装教室南脸: 红色大门正对步道, 两片透明大窗采光。",
    ["c_door", "c_win1", "c_win2"],
    highlight=["cw_w", "cw_e"],
    tip="门窗与山墙竖边互吸, 教室一层合龙成筒。",
)
b.step(
    "立两端山花: 2 片橙色等边三角立上东西山墙顶。",
    ["gable_w", "gable_e"],
    highlight=["cw_w", "cw_e"],
    tip="山花底边整边吸山墙顶 —— 它们定下屋脊的高度 1.87。",
)
b.step(
    "盖南坡屋面: 长板加方板沿墙顶 60 度斜起, 短边吸住山花斜边。",
    ["rs_a", "rs_b"],
    highlight=["gable_w", "gable_e"],
    tip="先装靠西的长板 (短边贴山花), 再补东端方板。",
)
b.step(
    "盖北坡屋面: 再上 2 片, 两坡在脊线两两相抵纯受压自锁。",
    ["rn_a", "rn_b"],
    highlight=["rs_a", "rs_b"],
    tip="对脊互吸 —— 越压越紧, 这就是人字坡的力学秘密。",
)
b.step(
    "起滑梯平台: 1x1 四面黄墙拐角互吸自锁。",
    ["sl_s", "sl_n", "sl_w", "sl_e"],
    highlight=["g1_5"],
    tip="平台墙要立正 —— 它们马上要托住甲板和滑道。",
)
b.step(
    "盖平台甲板并装护栏: 红色甲板四边压墙顶, 南东两面立护栏。",
    ["sl_deck", "sl_hr_s", "sl_hr_e"],
    highlight=["sl_s", "sl_e"],
    tip="甲板四边全吸 —— 护栏底边整边吸甲板沿口。",
)
b.step(
    "装滑道: 青色长板从平台北沿 30 度俯冲, 坡尾落进后草坪。",
    ["sl_ramp"],
    highlight=["sl_deck", "sl_n"],
    tip="顶边同时吸甲板北边与北墙顶, 坡尾自己踩地 —— 零悬臂。",
)
b.step(
    "围沙坑: 3 片粉色等边三角给黄沙坑镶边。",
    ["sb_1", "sb_2", "sb_3"],
    highlight=["g1_2", "g1_3"],
    tip="底边整边吸沙坑格线 —— 沙子不会漏出来啦。",
)
b.step(
    "立迎宾板与园旗: 粉色迎宾板立在步道西侧, 黄色园旗守东南角。",
    ["welcome", "flag"],
    highlight=["g0_a"],
    tip="迎宾板底边整条吸长板北边 —— 欢迎小朋友入园!",
)
b.step(
    "放摇摇马: 红蓝两只直角三角摇摇马分守操场两角。",
    ["horse_r", "horse_b"],
    highlight=["g2_0", "g2_6"],
    tip="直角边一横一竖双边吸合 —— 骑上去摇一摇。",
)
b.step(
    "种两棵大树: 灰色树干顶起绿色树冠, 给草坪撑起树荫。",
    ["tr1_t", "tr1_c", "tr2_t", "tr2_c"],
    highlight=["gl_c", "gl_d"],
    tip="树冠重心正压树干顶铰链 —— 彩虹幼儿园开园!",
)

b.finalize(
    model_id="kindergarten_01",
    name="彩虹幼儿园",
    name_en="Kindergarten 01",
    description=(
        "全库第一座为孩子设计的校园: 3x1 彩色教室 (红黄蓝北墙, 透明大窗, "
        "红色大门正对青色步道) 戴 60 度人字坡屋顶 —— 橙色屋面沿墙顶斜起, "
        "短边与等边山花斜边精确互吸, 脊线两坡相抵纯受压自锁; 园里滑梯平台"
        "四墙自锁, 青色滑道从北沿 30 度俯冲落草坪 (接地斜撑零悬臂), 黄色"
        "沙坑粉边围护, 红蓝摇摇马双边吸合, 迎宾板与园旗守门, 大树成荫 "
        "—— 放学啦, 再玩十分钟!"
    ),
    difficulty=3,
    tags=["城市", "幼儿园", "校园", "人字坡", "游乐场", "进阶"],
    min_pieces=50,
    min_steps=16,
)
