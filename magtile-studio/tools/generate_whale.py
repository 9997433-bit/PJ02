#!/usr/bin/env python3
"""生成模型 data/models/whale_01.json (蓝鲸)。

第三批模型 ②: 海洋生物主题 —— 浮出水面的蓝鲸: 7x6 海面
(长板涌浪与方片浪花相间), 海面中央隆起 4x2 箱形鲸背,
额头两片 30 度斜坡俯冲入水, 尾部两片菱形尾鳍呈 V 形展开,
背上一柱青色喷泉, 两侧胸鳍以 45 度拍出水花。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 海面 7x6: 长板涌浪行 (3 长板 + 1 方片) x3 与方片行 x3 相间   33 片
  - 鲸身: 4x2 围墙 12 + 鲸背甲板 8                               20 片
  - 额头斜坡: 2 片 30 度长方形俯冲入水                            2 片
  - 尾鳍: 2 片菱形立在鲸背尾沿, V 形外展                          2 片
  - 喷泉 + 胸鳍: 青色等边三角 x1 + 45 度外倾等边三角 x2           3 片
  合计 60 片, 16 个教程步骤, 4 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 鲸背甲板四周全部坐在围墙顶上, 箱形受力;
  - 额头斜坡顶边整边吸甲板西沿, 坡尾自然落在海面上 (R7a 接地);
  - 尾鳍菱形立于竖直平面内 (力矩为零), 在面内向外斜展成 V;
  - 胸鳍以 45 度外倾, 底边同时吸住海面板边与鲸身墙底。

用法: python3 tools/generate_whale.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

# =================================================================
# 1. 海面 7x6: 偶数行用长板拼涌浪 (3 长板 + 东端 1 方片),
#    奇数行用 7 片方片拼浪花, 蓝青相间
# =================================================================
SEA_ROWS = []
for j in range(6):
    row = []
    if j % 2 == 0:                       # 涌浪行: 长板为主
        for k in range(3):
            tid = f"sea_r_{j}_{k}"
            b.flat_rect(tid, 2 * k, j, 0.0, "blue" if k % 2 == 0 else "cyan")
            row.append(tid)
        tid = f"sea_s_{j}"
        b.flat(tid, 6, j, 0.0, "cyan")
        row.append(tid)
    else:                                # 浪花行: 方片
        for i in range(7):
            tid = f"sea_{i}_{j}"
            b.flat(tid, i, j, 0.0, "cyan" if (i + j) % 3 == 0 else "blue")
            row.append(tid)
    SEA_ROWS.append(row)

# =================================================================
# 2. 鲸身: 4x2 围墙 (x 2..6, y 2..4), 西端南墙留一片透明 "鲸眼"
# =================================================================
for i in range(4):
    color = "clear" if i == 0 else "blue"
    b.wall_ns(f"wh_s_{i}", 2 + i, 2.0, 0, color)     # 南侧体壁 (西端为鲸眼)
for i in range(4):
    b.wall_ns(f"wh_n_{i}", 2 + i, 4.0, 0, "blue")    # 北侧体壁
for j in range(2):
    b.wall_ew(f"wh_w_{j}", 2.0, 2 + j, 0, "blue")    # 额头端壁
    b.wall_ew(f"wh_e_{j}", 6.0, 2 + j, 0, "blue")    # 尾柄端壁

# 鲸背甲板 4x2 (z=1)
for j in range(2):
    for i in range(4):
        b.flat(f"wh_d_{i}_{j}", 2 + i, 2 + j, 1.0, "blue")

# =================================================================
# 3. 额头斜坡: 2 片 30 度长方形从鲸背西沿俯冲入水
# =================================================================
b.ramp("head_s", "-x", 2.0, 2, 1.0, "blue")
b.ramp("head_n", "-x", 2.0, 3, 1.0, "blue")

# =================================================================
# 4. 尾鳍: 2 片菱形立在鲸背尾沿 (x=6), 面内向外斜展成 V
# =================================================================
b.place_edge("fluke_s", "rhombus", 0, (6.0, 3.0, 1.0), (6.0, 2.0, 1.0),
             (0.0, 0.0, 1.0), "blue")
b.place_edge("fluke_n", "rhombus", 0, (6.0, 3.0, 1.0), (6.0, 4.0, 1.0),
             (0.0, 0.0, 1.0), "blue")

# =================================================================
# 5. 喷泉 + 胸鳍
# =================================================================
b.crest_ns("spout", 2, 3.0, 1.0, "cyan")             # 背脊喷泉 (x 2..3)
b.place_tri("fin_s", "equilateral_triangle",
            (3.0, 2.0, 0.0), (4.0, 2.0, 0.0),
            (3.5, 1.387628, 0.612372), "cyan")       # 南胸鳍 45 度外倾
b.place_tri("fin_n", "equilateral_triangle",
            (5.0, 4.0, 0.0), (4.0, 4.0, 0.0),
            (4.5, 4.612372, 0.612372), "cyan")       # 北胸鳍 45 度外倾

# =================================================================
# 教程步骤 (16 步): 海面 -> 鲸身 -> 鲸背 -> 头尾 -> 鳍与喷泉
# =================================================================
b.step(
    "铺海面第 1 行 (y 0..1): 3 片长板拼涌浪, 东端补 1 片青色方片。",
    SEA_ROWS[0],
    tip="长板的长边与两片方片等长 —— 涌浪行与浪花行可以无缝相咬。",
)
b.step(
    "铺海面第 2 行: 7 片方片拼浪花, 与第 1 行整边吸合。",
    SEA_ROWS[1],
    highlight=[SEA_ROWS[0][0]],
    tip="青色方片是浪花翻白的地方, 请按图错落分布。",
)
b.step(
    "铺海面第 3 行: 又是一行长板涌浪。鲸鱼即将从这一带浮出。",
    SEA_ROWS[2],
    highlight=[SEA_ROWS[1][0]],
    tip="每片长板两端都要与上一行对齐格线。",
)
b.step(
    "铺海面第 4 行: 7 片方片浪花行。",
    SEA_ROWS[3],
    highlight=[SEA_ROWS[2][0]],
    tip="海面已过半 —— 中间两行就是鲸背破水的位置。",
)
b.step(
    "铺海面第 5 行: 长板涌浪行。",
    SEA_ROWS[4],
    highlight=[SEA_ROWS[3][0]],
    tip="保持整张海面平整, 不要留缝。",
)
b.step(
    "铺完海面第 6 行 —— 7x6 大海就绪, 请鲸鱼入场!",
    SEA_ROWS[5],
    highlight=[SEA_ROWS[4][0]],
    tip="从上往下看, 涌浪行与浪花行应蓝青相间。",
)
b.step(
    "立鲸身南侧体壁: 沿 y=2 立 4 片, 最西一片用透明片当鲸眼。",
    [f"wh_s_{i}" for i in range(4)],
    highlight=["sea_2_3"],
    tip="底边吸海面格线, 竖边两两互吸 —— 鲸鱼的左舷成形。",
)
b.step(
    "立鲸身北侧体壁: 沿 y=4 再立 4 片蓝色正方形。",
    [f"wh_n_{i}" for i in range(4)],
    highlight=["wh_s_0"],
    tip="与南侧体壁平行相距 2 格, 中间就是鲸鱼厚实的身体。",
)
b.step(
    "封额头与尾柄端壁: 西端 (x=2) 与东端 (x=6) 各立 2 片, 鲸身合围。",
    ["wh_w_0", "wh_w_1", "wh_e_0", "wh_e_1"],
    highlight=["wh_s_0", "wh_n_3"],
    tip="四角竖边两两互吸后, 轻捏体壁上口应感觉整体联动。",
)
b.step(
    "铺鲸背南半: 4 片蓝色方板压在体壁顶上 (y 2..3)。",
    [f"wh_d_{i}_0" for i in range(4)],
    highlight=["wh_s_1", "wh_w_0"],
    tip="甲板边要同时吸住墙顶边与相邻甲板片。",
)
b.step(
    "铺鲸背北半: 再压 4 片, 鲸背完全封合 —— 一条箱形大鲸浮在海面。",
    [f"wh_d_{i}_1" for i in range(4)],
    highlight=[f"wh_d_{i}_0" for i in range(4)],
    tip="轻压甲板四角检查: 鲸背应结实得能托住喷泉和尾鳍。",
)
b.step(
    "装额头斜坡: 2 片 30 度长方形从鲸背西沿俯冲, 坡尾落在海面上。",
    ["head_s", "head_n"],
    highlight=["wh_d_0_0", "wh_d_0_1"],
    tip="顶边整边吸住甲板西沿再松手 —— 这就是蓝鲸圆润的大额头。",
)
b.step(
    "立尾鳍: 2 片蓝色菱形立在鲸背尾沿 (x=6), 在竖直面内向外斜展成 V。",
    ["fluke_s", "fluke_n"],
    highlight=["wh_d_3_0", "wh_d_3_1"],
    tip="菱形底边同时吸住甲板尾沿与尾柄端壁顶边, V 形开口朝外。",
)
b.step(
    "喷泉登场: 1 片青色等边三角形立在鲸背前段正中 —— 鲸鱼换气啦!",
    ["spout"],
    highlight=["wh_d_0_0", "wh_d_0_1"],
    tip="底边吸住鲸背中缝, 三角尖直指天空。",
)
b.step(
    "装南侧胸鳍: 1 片青色等边三角形以 45 度外倾, 底边同时吸住海面"
    "格线与鲸身墙底。",
    ["fin_s"],
    highlight=["wh_s_1"],
    tip="鳍尖斜指水面, 像正在拍出一朵水花。",
)
b.step(
    "装北侧胸鳍, 与南侧镜像 —— 蓝鲸巡游开始!",
    ["fin_n"],
    highlight=["fin_s", "wh_n_2"],
    tip="两侧胸鳍对称外倾, 从正前方看是一个大大的 V。",
)

b.finalize(
    model_id="whale_01",
    name="蓝鲸",
    name_en="Blue Whale 01",
    description=(
        "海洋生物主题: 7x6 海面用长板涌浪与方片浪花相间铺成, 中央隆起 4x2 "
        "箱形鲸背 (体壁合围 + 甲板封顶), 额头两片 30 度斜坡俯冲入水, 尾部"
        "两片菱形尾鳍在竖直面内向外斜展成 V, 背脊喷起一柱青色喷泉, 两侧"
        "胸鳍以 45 度外倾拍出水花 —— 透明鲸眼正望着你, 一起下海巡游吧。"
    ),
    difficulty=3,
    tags=["海洋", "鲸鱼", "动物世界", "进阶"],
    min_pieces=50,
    min_steps=16,
)
