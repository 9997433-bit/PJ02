#!/usr/bin/env python3
"""生成模型 data/models/bakery_shop_01.json (面包店)。

城市生活主题: 街角面包店 —— 一层店堂开门框方大门与两扇窗格方
橱窗 (刚出炉的面包就摆在橱窗里), 屋顶前沿升起女儿墙, 女儿墙竖边
挂出 5 片直角三角遮阳篷肋 (红白相间的条纹雨棚), 双等腰招牌塔尖
直插天际; 屋顶后部烟囱吐着橙色"烟火", 后院砖炉房连着店堂北墙;
门前人行道上两张悬挑小圆桌 —— 出炉铃一响, 香气飘满整条街。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 店堂地坪 [0,4]x[0,3]: 4x3 方板                            12 片
  - 门前人行道 (y=-1): 6 片                                     6 片
  - 店堂一层: 前墙 (门框方 + 窗格方 x2 + 方墙), 西/东/北墙     14 片
  - 店堂平顶: 4x3 方板                                         12 片
  - 女儿墙 (前檐 z 1..2): 4 片                                  4 片
  - 遮阳篷肋: 5 片直角三角挂女儿墙竖边 (红白相间)               5 片
  - 招牌塔尖: 双等腰 x2                                         2 片
  - 烟囱 (屋顶后部): 四壁 4 + 等边"烟火" 1                      5 片
  - 砖炉房 (后院 [1,3]x[3,4]): 地板 2 + 三面墙 4 + 顶板 2       8 片
  - 悬挑小圆桌 x2 (人行道两端): 各 腿墙 1 + 桌板 1              4 片
  合计 72 片, 16 个教程步骤, 6 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 遮阳篷肋竖直角边整边吸女儿墙竖边: 竖直铰链的重力矩恒为零,
    单片仅 15g, 远低于悬挂预算 (风雨廊桥花窗同款竖边受力);
  - 女儿墙底边同时吸屋顶板前沿与前墙顶边 (双铰链互为保险);
  - 砖炉房南面直接借用店堂北墙 (共墙不重叠), 炉顶板两头受力;
  - 小圆桌桌板单片悬挑: 力矩 15 <= 严格档预算 17.5。

用法: python3 tools/generate_bakery_shop.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

SLAB = "gray"       # 地坪
WALK = "gray"       # 人行道
WALL = "yellow"     # 店堂墙 (奶油黄)
DOOR = "green"      # 门框方
WIN = "clear"       # 窗格方橱窗
ROOF = "orange"     # 平顶
PARA = "yellow"     # 女儿墙
FIN_A = "red"       # 遮阳篷肋 (红)
FIN_B = "clear"     # 遮阳篷肋 (白)
SIGN = "red"        # 招牌塔尖
CHIM = "purple"     # 烟囱
FLAME = "orange"    # 烟火
OVEN = "red"        # 砖炉房
TABLE = "blue"      # 小圆桌

# =================================================================
# 1. 店堂地坪与门前人行道
# =================================================================
for x in range(4):
    for y in range(3):
        b.flat(f"sl_{x}_{y}", x, y, 0.0, SLAB)
for x in range(-1, 5):
    b.flat(f"wk_{x}", x, -1, 0.0, WALK)

# =================================================================
# 2. 店堂一层: 前墙 (大门 + 双橱窗) + 西/东/北墙
# =================================================================
b.wall_ns("f_w", 0, 0.0, 0, WALL)
b.add("f_door", "door_frame", (1.5, 0.0, 0.5), (90, 0, 0), DOOR)
b.add("f_win0", "window_square", (2.5, 0.0, 0.5), (90, 0, 0), WIN)
b.add("f_win1", "window_square", (3.5, 0.0, 0.5), (90, 0, 0), WIN)
for y in range(3):
    b.wall_ew(f"w_w_{y}", 0.0, y, 0, WALL)
    b.wall_ew(f"w_e_{y}", 4.0, y, 0, WALL)
for x in range(4):
    b.wall_ns(f"w_n_{x}", x, 3.0, 0, WALL)

# =================================================================
# 3. 店堂平顶 (z=1): 4x3 方板
# =================================================================
for x in range(4):
    for y in range(3):
        b.flat(f"rf_{x}_{y}", x, y, 1.0, ROOF)

# =================================================================
# 4. 女儿墙 (前檐 y=0, z 1..2) + 遮阳篷肋 + 招牌塔尖
# =================================================================
for x in range(4):
    b.wall_ns(f"pp_{x}", x, 0.0, 1, PARA)
# 遮阳篷肋: 直角三角竖直角边吸女儿墙竖边, 水平直角边向南挑出
for i, x in enumerate(range(5)):
    b.brace(f"fin_{x}", (float(x), 0.0, 1.0), "-y", FIN_A if i % 2 == 0 else FIN_B)
b.spire_ns("sg_w", 1, 0.0, 2.0, SIGN)
b.spire_ns("sg_e", 2, 0.0, 2.0, SIGN)

# =================================================================
# 5. 烟囱 (屋顶后部 [1,2]x[2,3], z 1..2) + 烟火
# =================================================================
b.wall_ns("ch_s", 1, 2.0, 1, CHIM)
b.wall_ns("ch_n", 1, 3.0, 1, CHIM)
b.wall_ew("ch_w", 1.0, 2, 1, CHIM)
b.wall_ew("ch_e", 2.0, 2, 1, CHIM)
b.crest_ns("ch_fire", 1, 3.0, 2.0, FLAME)

# =================================================================
# 6. 砖炉房 (后院 [1,3]x[3,4], 南借店堂北墙)
# =================================================================
b.flat("ov_f0", 1, 3, 0.0, SLAB)
b.flat("ov_f1", 2, 3, 0.0, SLAB)
b.wall_ns("ov_n0", 1, 4.0, 0, OVEN)
b.wall_ns("ov_n1", 2, 4.0, 0, OVEN)
b.wall_ew("ov_w", 1.0, 3, 0, OVEN)
b.wall_ew("ov_e", 3.0, 3, 0, OVEN)
b.flat("ov_r0", 1, 3, 1.0, OVEN)
b.flat("ov_r1", 2, 3, 1.0, OVEN)

# =================================================================
# 7. 悬挑小圆桌 x2 (人行道两端)
# =================================================================
b.wall_ns("tb_w_leg", -1, -1.0, 0, TABLE)
b.flat("tb_w_top", -1, -2, 1.0, TABLE)
b.wall_ns("tb_e_leg", 4, -1.0, 0, TABLE)
b.flat("tb_e_top", 4, -2, 1.0, TABLE)

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺设店堂地坪南半: 6 片灰色方板 (y 0..1 排 + y 1..2 排西半)。",
    [f"sl_{x}_0" for x in range(4)] + ["sl_0_1", "sl_1_1"],
    tip="地坪按 4x3 铺满 —— 店堂要摆下烤炉和长长的面包架。",
)
b.step(
    "补齐店堂地坪: 再铺 6 片, 4x3 地坪完工。",
    ["sl_2_1", "sl_3_1"] + [f"sl_{x}_2" for x in range(4)],
    highlight=["sl_0_0"],
    tip="12 片地坪板缝缝相吸, 铺完是严丝合缝的一整块。",
)
b.step(
    "铺设门前人行道: 6 片方板沿店面南沿排开。",
    [f"wk_{x}" for x in range(-1, 5)],
    highlight=["sl_0_0", "sl_3_0"],
    tip="人行道比店面宽出两格 —— 排队的客人站得下。",
)
b.step(
    "竖立店面: 西端 1 片方墙 + 绿色门框方大门 + 2 扇透明窗格方橱窗。",
    ["f_w", "f_door", "f_win0", "f_win1"],
    highlight=["sl_0_0", "sl_3_0"],
    tip="橱窗要透亮 —— 刚出炉的法棍和可颂就摆在里面。",
)
b.step(
    "竖立西墙与东墙: 各 3 片奶油黄方墙, 与店面拐角互吸。",
    ["w_w_0", "w_w_1", "w_w_2", "w_e_0", "w_e_1", "w_e_2"],
    highlight=["f_w", "f_win1"],
    tip="墙底边吸地坪边, 拐角竖边互吸锁定。",
)
b.step(
    "竖立北墙: 4 片方墙, 店堂一层围合成筒。",
    [f"w_n_{x}" for x in range(4)],
    highlight=["w_w_2", "w_e_2"],
    tip="北墙将来还要借给砖炉房当南墙 —— 一墙两用。",
)
b.step(
    "铺设平顶前后两排: 8 片橙色顶板压住墙顶边。",
    [f"rf_{x}_0" for x in range(4)] + [f"rf_{x}_2" for x in range(4)],
    highlight=["f_door", "w_n_1"],
    tip="每片顶板的外沿边都要吸牢正下方的墙顶边。",
)
b.step(
    "补齐平顶中排: 4 片, 店堂封顶。",
    [f"rf_{x}_1" for x in range(4)],
    highlight=["rf_0_0", "rf_3_2"],
    tip="中排顶板两侧拼缝互吸, 平顶严丝合缝。",
)
b.step(
    "升起女儿墙: 前檐 4 片方墙, 底边同时吸顶板前沿与前墙顶边。",
    [f"pp_{x}" for x in range(4)],
    highlight=["rf_0_0", "rf_3_0"],
    tip="女儿墙是雨棚和招牌的挂靠点, 双铰链互为保险。",
)
b.step(
    "挂出条纹遮阳篷: 5 片红白相间的直角三角肋, 竖直角边整边"
    "吸女儿墙竖边、直角边水平向南挑出。",
    [f"fin_{x}" for x in range(5)],
    highlight=["pp_0", "pp_3"],
    tip="竖直铰链的重力矩为零 —— 雨棚肋轻若无物却纹丝不动。",
)
b.step(
    "立起招牌塔尖: 2 支红色等腰塔尖立上女儿墙顶边正中。",
    ["sg_w", "sg_e"],
    highlight=["pp_1", "pp_2"],
    tip="双塔尖就是店招 —— 全街最高的香气坐标。",
)
b.step(
    "砌烟囱并点烟火: 屋顶后部 4 片紫色方墙围成 1x1 烟囱, "
    "顶边立 1 片橙色等边烟火。",
    ["ch_s", "ch_n", "ch_w", "ch_e", "ch_fire"],
    highlight=["rf_1_2"],
    tip="烟囱底边吸顶板拼缝, 四角竖边互吸自锁成筒。",
)
b.step(
    "铺设砖炉房地板并围墙: 后院 2 片地板 + 北/西/东 4 片红墙, "
    "南面借用店堂北墙。",
    ["ov_f0", "ov_f1", "ov_n0", "ov_n1", "ov_w", "ov_e"],
    highlight=["w_n_1", "w_n_2"],
    tip="共墙不重复 —— 炉房的南面就是店堂的北墙。",
)
b.step(
    "盖砖炉房顶板: 2 片红色顶板, 一边搭店堂北墙、一边搭炉房北墙。",
    ["ov_r0", "ov_r1"],
    highlight=["ov_n0", "w_n_1"],
    tip="顶板两头受力最稳 —— 砖炉的余温从这里散出去。",
)
b.step(
    "摆西侧小圆桌: 腿墙立人行道南沿, 桌板压腿顶向南悬挑。",
    ["tb_w_leg", "tb_w_top"],
    highlight=["wk_-1"],
    tip="单片桌板悬挑力矩 15, 在严格档预算之内 —— 放心落座。",
)
b.step(
    "摆东侧小圆桌: 面包店开张!",
    ["tb_e_leg", "tb_e_top"],
    highlight=["tb_w_leg"],
    tip="出炉铃一响, 香气飘满整条街。",
)

b.finalize(
    model_id="bakery_shop_01",
    name="面包店",
    name_en="Bakery Shop",
    description=(
        "街角面包店: 门框方大门与两扇透明窗格方橱窗组成敞亮店面, 女儿墙"
        "竖边挂出 5 片红白相间的直角三角遮阳篷肋 (竖直铰链重力矩为零), "
        "双等腰招牌塔尖直插天际; 屋顶紫色烟囱吐着橙色烟火, 后院砖炉房借"
        "店堂北墙一墙两用, 门前人行道两张悬挑小圆桌 —— 出炉铃一响, "
        "香气飘满整条街。"
    ),
    difficulty=3,
    tags=["城市", "商店", "职业体验", "进阶"],
    min_pieces=72,
    min_steps=16,
)
