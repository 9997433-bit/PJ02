#!/usr/bin/env python3
"""生成模型 data/models/ice_cream_truck_01.json (冰淇淋车)。

第三批模型: 街景载具主题 —— 全库第一辆"餐车": 车身架空在四片
方轮上 (轮顶托起 4x2 底盘板), 后厢两层、驾驶舱一层错高; 面向
人行道的后厢上半留作售卖窗 (负空间), 窗顶长板遮阳篷外挑 0.5
力臂, 窗下小吧台再挑一片; 车头两片透明挡风玻璃以 45 度斜披,
车顶一对扇形圆弧招牌像两球冰淇淋 —— 街边排队的灯柱与菜单牌
把场景补完整。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 街道三排 (长方形沥青 + 方板车道) + 人行道                    28 片
  - 车轮 4 方 + 底盘板 8 方                                       12 片
  - 后厢墙身两层 (含售卖窗负空间) + 车顶长板 2                    13 片
  - 遮阳篷 1 + 售卖吧台 1                                          2 片
  - 驾驶舱 (5 墙 + 4 顶板) + 挡风玻璃 2                           11 片
  - 车顶扇形招牌 2 + 菜单牌 2 + 街灯/排队柱 3                      7 片
  合计 73 片, 16 个教程步骤, 5 种磁力片形状。

物理要点 (通过 R1~R8 全部校验):
  - 底盘板中排两端压轮顶 (力臂为零), 遮阳篷长边整边吸车顶北缘
    (弯矩 30 < 预算 40), 吧台单片外挑 (弯矩 15 < 20);
  - 挡风玻璃 45 度斜披, 顶边吸舱顶板短边, 悬挂质量 30g 远低于
    120g 预算;
  - 扇形招牌直径边吸车顶短边, 重心正落铰链线上方 (力臂 0)。

坐标约定与 C++ 端一致: 旋转为欧拉角 (度), R = Rz * Ry * Rx。
用法: python3 tools/generate_ice_cream_truck.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

mb = ModelBuilder()

ROAD = "gray"
WALK = "pink"       # 人行道
WHEEL = "gray"
CHASSIS = "blue"    # 底盘
BODY = "pink"       # 后厢
CAB = "cyan"        # 驾驶舱
GLASS = "clear"

# =================================================================
# 1. 街道 [0,8]x[0,3] + 人行道 [0,8]x[3,4]
# =================================================================
for i in range(4):
    # 斑马线长板: 竖放 1x2, 北短边正好吸车道方板南边
    mb.flat_rect(f"rd0_{i}", 2 * i, -1, 0.0, "clear", axis="y")
for i in range(8):
    mb.flat(f"rd1_{i}", i, 1, 0.0, ROAD)
for i in range(8):
    mb.flat(f"rd2_{i}", i, 2, 0.0, ROAD)
for i in range(8):
    mb.flat(f"wk_{i}", i, 3, 0.0, WALK)

# =================================================================
# 2. 车轮 (方板竖立) + 底盘 z=1 ([1,5]x[1,3])
# =================================================================
mb.wall_ns("wh_fs", 1, 1.0, 0, WHEEL)              # 前轮对 (西)
mb.wall_ns("wh_fn", 1, 3.0, 0, WHEEL)
mb.wall_ns("wh_rs", 4, 1.0, 0, WHEEL)              # 后轮对 (东)
mb.wall_ns("wh_rn", 4, 3.0, 0, WHEEL)
for i in range(4):
    mb.flat(f"ch_s{i}", 1 + i, 1, 1.0, CHASSIS)
for i in range(4):
    mb.flat(f"ch_n{i}", 1 + i, 2, 1.0, CHASSIS)

# =================================================================
# 3. 后厢 [1,3]x[1,3] (z 1..3): 北面上半留售卖窗
# =================================================================
mb.lintel_ew("bd1_w", 1.0, 1, 1, BODY)             # 一层西墙 (整片)
mb.wall_ns("bd1_s0", 1, 1.0, 1, BODY)
mb.wall_ns("bd1_s1", 2, 1.0, 1, BODY)
mb.wall_ns("bd1_n0", 1, 3.0, 1, BODY)              # 一层北墙 (窗台)
mb.wall_ns("bd1_n1", 2, 3.0, 1, BODY)
mb.wall_ew("bd1_p0", 3.0, 1, 1, BODY)              # 后厢/驾驶舱隔墙
mb.wall_ew("bd1_p1", 3.0, 2, 1, BODY)
mb.lintel_ew("bd2_w", 1.0, 1, 2, BODY)             # 二层西墙
mb.lintel_ns("bd2_s", 1, 1.0, 2, BODY)             # 二层南墙 (整片)
mb.wall_ew("bd2_p0", 3.0, 1, 2, BODY)              # 二层隔墙
mb.wall_ew("bd2_p1", 3.0, 2, 2, BODY)
mb.flat_rect("roof_s", 1, 1, 3.0, BODY)            # 车顶南半 [1,3]x[1,2]
mb.flat_rect("roof_n", 1, 2, 3.0, BODY)            # 车顶北半 [1,3]x[2,3]

# =================================================================
# 4. 遮阳篷 (车顶北缘外挑) + 售卖吧台 (窗台外挑)
# =================================================================
mb.flat_rect("awning", 1, 3, 3.0, "red")           # [1,3]x[3,4]
mb.flat("counter", 1, 3, 1.0, "yellow")            # [1,2]x[3,4]

# =================================================================
# 5. 驾驶舱 [3,5]x[1,3] (z 1..2) + 挡风玻璃
# =================================================================
mb.wall_ns("cb_s0", 3, 1.0, 1, CAB)
mb.wall_ns("cb_s1", 4, 1.0, 1, CAB)
mb.wall_ns("cb_n0", 3, 3.0, 1, CAB)
mb.wall_ns("cb_n1", 4, 3.0, 1, CAB)
mb.lintel_ew("cb_e", 5.0, 1, 1, CAB)               # 车头东墙
for i, (x0, y0) in enumerate(((3, 1), (4, 1), (3, 2), (4, 2))):
    mb.flat(f"cbr_{i}", x0, y0, 2.0, CAB)          # 舱顶 4 板
mb.place_edge("ws_s", "square", 0,
              (5.0, 1.0, 2.0), (5.0, 2.0, 2.0), (0.707107, 0.0, -0.707107),
              GLASS)
mb.place_edge("ws_n", "square", 0,
              (5.0, 2.0, 2.0), (5.0, 3.0, 2.0), (0.707107, 0.0, -0.707107),
              GLASS)

# =================================================================
# 6. 车顶扇形招牌 + 菜单牌 + 街灯/排队柱
# =================================================================
mb.place_edge("scoop_s", "sector", 0,
              (1.0, 1.0, 3.0), (1.0, 2.0, 3.0), (0.0, 0.0, 1.0), "yellow")
mb.place_edge("scoop_n", "sector", 0,
              (1.0, 3.0, 3.0), (1.0, 2.0, 3.0), (0.0, 0.0, 1.0), "red")
mb.wall_ns("menu", 6, 4.0, 0, "yellow")            # 菜单牌
mb.crest_ns("menu_top", 6, 4.0, 1.0, "red")
mb.spire_ns("lamp", 0, 3.0, 0.0, "yellow")         # 街灯
mb.spire_ns("q_a", 5, 3.0, 0.0, "orange")          # 排队柱
mb.spire_ns("q_b", 6, 3.0, 0.0, "orange")

# =================================================================
# 教程步骤 (16 步)
# =================================================================
mb.step(
    "车道: 8 片灰色方板铺出行车道 —— 冰淇淋车就停这里。",
    [f"rd1_{i}" for i in range(8)],
)
mb.step(
    "斑马线: 4 片透明长板间隔竖铺在车道南侧, 北短边逐一吸住"
    "车道板边。",
    ["rd0_0", "rd0_1", "rd0_2", "rd0_3"],
    highlight=["rd1_0", "rd1_6"],
)
mb.step(
    "街道北排: 再铺 8 片, 路面合拢。",
    [f"rd2_{i}" for i in range(8)],
    highlight=["rd1_0", "rd1_7"],
)
mb.step(
    "人行道: 沿路北铺 8 片粉色步道砖 —— 顾客从这里排队。",
    [f"wk_{i}" for i in range(8)],
    highlight=["rd2_0", "rd2_7"],
)
mb.step(
    "四只车轮: 前后各一对灰色方轮竖立在车道边线上 (平面 y=1 与 "
    "y=3), 轮底整边吸路板边。",
    ["wh_fs", "wh_fn", "wh_rs", "wh_rn"],
    highlight=["rd1_1", "rd2_4"],
    tip="轮顶 (z=1) 稍后托起整块底盘 —— 车身是架空的。",
)
mb.step(
    "底盘轮上段: 前后轮顶各铺一对蓝色底盘板 (南北成列), 每列"
    "两端同时压住南北轮顶 —— 力臂为零。",
    ["ch_s0", "ch_n0", "ch_s3", "ch_n3"],
    highlight=["wh_fs", "wh_rn"],
    tip="先铺轮顶正上方的板, 底盘从四个支点向中间合拢。",
)
mb.step(
    "底盘中段: 中间两列 4 片补齐, 4x2 底盘完工。",
    ["ch_s1", "ch_n1", "ch_s2", "ch_n2"],
    highlight=["ch_s0", "ch_n3"],
)
mb.step(
    "后厢一层: 西墙整片竖放, 南墙 2 方、北墙 2 方 (这排是窗台), "
    "东侧 2 方隔墙把后厢与驾驶舱分开。",
    ["bd1_s0", "bd1_s1", "bd1_n0", "bd1_n1", "bd1_w", "bd1_p0", "bd1_p1"],
    highlight=["ch_s0", "ch_n0"],
)
mb.step(
    "后厢二层: 西墙、南墙均用整片长方形竖放, 隔墙再上 2 方 —— "
    "北面上半整个留空, 这就是售卖窗 (负空间)。",
    ["bd2_w", "bd2_s", "bd2_p0", "bd2_p1"],
    highlight=["bd1_n0", "bd1_n1"],
    tip="售卖窗不用拼: 留出来的洞就是它。",
)
mb.step(
    "车顶: 2 片粉色长板盖上 z=3 —— 南板长边吸二层南墙顶, 北板"
    "吸中缝与隔墙顶。",
    ["roof_s", "roof_n"],
    highlight=["bd2_s", "bd2_p1"],
)
mb.step(
    "遮阳篷与吧台: 红色长板从车顶北缘向人行道挑出 (弯矩 30 < "
    "预算 40); 窗台下再挑 1 片黄色售卖吧台。",
    ["awning", "counter"],
    highlight=["roof_n", "bd1_n0"],
    tip="篷用长边整边吸 (铰链长 2), 吧台只挑半格 —— 都在弯矩预算内。",
)
mb.step(
    "驾驶舱墙身: 南北各 2 方, 车头东墙整片竖放。",
    ["cb_s0", "cb_s1", "cb_n0", "cb_n1", "cb_e"],
    highlight=["bd1_p0", "ch_s3"],
)
mb.step(
    "舱顶: 4 片青色板盖上 z=2, 西缘同时吸后厢隔墙顶。",
    ["cbr_0", "cbr_1", "cbr_2", "cbr_3"],
    highlight=["cb_s0", "cb_n0"],
)
mb.step(
    "挡风玻璃: 2 片透明方板从舱顶前缘以 45 度斜披向车头 —— "
    "顶边整边吸舱顶板短边。",
    ["ws_s", "ws_n"],
    highlight=["cbr_1", "cbr_3"],
)
mb.step(
    "车顶招牌: 2 片扇形 (黄+红) 直径边吸车顶西端短边, 圆弧相背 "
    "—— 像刚挖好的两球冰淇淋。",
    ["scoop_s", "scoop_n"],
    highlight=["roof_s", "roof_n"],
)
mb.step(
    "街景收尾: 人行道上立菜单牌 (方板 + 三角顶)、街灯与 2 根"
    "排队柱 —— 冰淇淋车开张了。",
    ["menu", "menu_top", "lamp", "q_a", "q_b"],
    highlight=["wk_6", "wk_0"],
)

mb.finalize(
    model_id="ice_cream_truck_01",
    name="冰淇淋车",
    name_en="Ice Cream Truck 01",
    description=(
        "街边营业的架空餐车: 四片方轮托起 4x2 底盘, 后厢两层与"
        "单层驾驶舱错高; 面向人行道的后厢上半整个留作售卖窗 "
        "(负空间), 窗顶红色遮阳篷长边整边外挑、窗下再挑一片售卖"
        "吧台; 车头两片透明挡风玻璃 45 度斜披, 车顶一对扇形圆弧"
        "招牌像两球刚挖好的冰淇淋。人行道上菜单牌、街灯与排队柱"
        "一应俱全 —— 叮铃铃, 开张了。"
    ),
    difficulty=3,
    tags=["餐车", "街景", "载具", "负空间", "扇形招牌"],
    min_pieces=70,
    min_steps=16,
)
