#!/usr/bin/env python3
"""生成模型 data/models/igloo_01.json (极地冰屋)。

极地主题: 全库第一座冰屋 —— 冰原上一座层叠式冰穹: 3x3 冰砖
环墙 (透明/青色相间), 顶板九宫格中央嵌一扇窗格方冰天窗,
再叠 1x1 二层冰环、戴等边四坡冰帽 (穹顶 2.71); 南面一条
短短的入口隧道, 隧道口立门框方拱门 —— 猫着腰才钻得进去;
屋旁一盏黄色四坡雪灯、两块冰砖立在冻湖沿上 —— 极夜里,
冰屋暖光融融。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 冰原 (x [0,6], y [0,5]): 方板 x24 + 长板 x3 (含冻湖青斑) 27 片
  - 冰穹环墙 (x [1,4], y [1,4], z 0~1): 冰砖立墙 x12         12 片
  - 穹顶板 (z=1): 方板 x8 + 中央窗格方冰天窗 x1               9 片
  - 二层冰环 (x [2,3], y [2,3], z 1~2): 立墙 x4               4 片
  - 等边四坡冰帽 (穹顶 2.71): x4                              4 片
  - 入口隧道 (x [2,3], y [0,1]): 侧墙 x2 + 顶板 x1
    + 门框方拱门 x1                                           4 片
  - 雪灯 (x [5,6], y [0,1]): 等边四坡锥 x4                    4 片
  - 冰砖: 等边三角 x2 (立冻湖拼缝)                            2 片
  合计 66 片, 14 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, strict 档同样全绿):
  - 环墙四角竖边互吸闭环; 穹顶板每片同时吸墙顶与相邻板缝
    (多路受力), 中央天窗四边全吸八宫格板缝;
  - 二层冰环踩九宫格中央拼缝再叠一环, 冰帽四棱互吸自锁;
  - 隧道侧墙竖边吸环墙竖边、顶板三边受力 (两墙顶+穹顶板缝),
    门框拱门两条竖边吸隧道侧墙 —— 隧道自成小环;
  - 雪灯/冰砖重心正压拼缝铰链 (力矩 0), 全模型无悬挑链。

用法: python3 tools/generate_igloo.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

ICE = "clear"       # 冰原 / 冰砖 / 冰帽
POND = "cyan"       # 冻湖
BRICK_A = "clear"   # 冰砖墙 (亮)
BRICK_B = "cyan"    # 冰砖墙 (暗)
SKY = "clear"       # 冰天窗
UPPER = "cyan"      # 二层冰环
TUNNEL = "cyan"     # 隧道
LAMP = "yellow"     # 雪灯

# =================================================================
# 1. 冰原 (x [0,6], y [0,5]): 四行方板 + 北沿长板, 冻湖青斑
# =================================================================
POND_CELLS = {(4, 2), (5, 2), (4, 3), (5, 3)}
for y in range(4):
    for x in range(6):
        color = POND if (x, y) in POND_CELLS else ICE
        b.flat(f"gr_{x}_{y}", x, y, 0.0, color)
for k in range(3):
    b.flat_rect(f"gr_n_{k}", 2 * k, 4, 0.0, ICE)

# =================================================================
# 2. 冰穹环墙 (x [1,4], y [1,4], z 0~1): 冰砖相间闭环
# =================================================================
for i, x in enumerate((1, 2, 3)):
    b.wall_ns(f"ig_s_{x}", x, 1.0, 0, BRICK_A if i % 2 == 0 else BRICK_B)
    b.wall_ns(f"ig_n_{x}", x, 4.0, 0, BRICK_A if i % 2 == 0 else BRICK_B)
for i, y in enumerate((1, 2, 3)):
    b.wall_ew(f"ig_w_{y}", 1.0, y, 0, BRICK_B if i % 2 == 0 else BRICK_A)
    b.wall_ew(f"ig_e_{y}", 4.0, y, 0, BRICK_B if i % 2 == 0 else BRICK_A)

# =================================================================
# 3. 穹顶板 (z=1): 九宫格, 中央冰天窗
# =================================================================
for x in (1, 2, 3):
    for y in (1, 2, 3):
        if (x, y) == (2, 2):
            continue
        b.flat(f"lid_{x}_{y}", x, y, 1.0, BRICK_A if (x + y) % 2 else BRICK_B)
b.add("skylight", "window_square", (2.5, 2.5, 1.0), (0, 0, 0), SKY)

# =================================================================
# 4. 二层冰环 + 等边四坡冰帽
# =================================================================
b.wall_ns("up_s", 2, 2.0, 1, UPPER)
b.wall_ns("up_n", 2, 3.0, 1, UPPER)
b.wall_ew("up_w", 2.0, 2, 1, UPPER)
b.wall_ew("up_e", 3.0, 2, 1, UPPER)
CAP = b.hat4("cap", 2, 2, 2.0, ICE, shape="equilateral_triangle")

# =================================================================
# 5. 入口隧道 (x [2,3], y [0,1]) + 雪灯 + 冰砖
# =================================================================
b.wall_ew("tn_w", 2.0, 0, 0, TUNNEL)
b.wall_ew("tn_e", 3.0, 0, 0, TUNNEL)
b.flat("tn_roof", 2, 0, 1.0, ICE)
b.add("tn_arch", "door_frame", (2.5, 0.0, 0.5), (90, 0, 0), TUNNEL)
LANTERN = b.hat4("lantern", 5, 0, 0.0, LAMP,
                 shape="equilateral_triangle")
b.crest_ew("block_a", 5.0, 2, 0.0, ICE)
b.crest_ns("block_b", 4, 4.0, 0.0, ICE)

# =================================================================
# 教程步骤 (14 步)
# =================================================================
b.step(
    "铺冰原第一行 (y [0,1]): 6 片, 隧道与雪灯都踩这行。",
    [f"gr_{x}_0" for x in range(6)],
    tip="冰原方板拼缝对齐网格 —— 一切从冰面开始。",
)
b.step(
    "铺第二行 (y [1,2]): 6 片, 冰穹南墙踩这行北缝。",
    [f"gr_{x}_1" for x in range(6)],
    highlight=["gr_0_0"],
    tip="冰穹 3x3 的南墙脚就落在 y=1 这条拼缝上。",
)
b.step(
    "铺第三行 (y [2,3]): 6 片, 东边两片换冻湖青色。",
    [f"gr_{x}_2" for x in range(6)],
    highlight=["gr_0_1"],
    tip="冻湖就在冰屋家门口 —— 凿个冰洞钓鱼去。",
)
b.step(
    "铺第四行 (y [3,4]): 6 片, 冻湖补齐。",
    [f"gr_{x}_3" for x in range(6)],
    highlight=["gr_4_2"],
    tip="四行方板铺满 —— 冰原平整无缝。",
)
b.step(
    "铺北沿: 3 片透明长板, 冰原合拢。",
    ["gr_n_0", "gr_n_1", "gr_n_2"],
    highlight=["gr_0_3"],
    tip="北沿外是无边极夜 —— 冰砖等会儿立在湖沿。",
)
b.step(
    "砌冰穹南墙与西墙: 6 片冰砖踩拼缝, 转角竖边互吸。",
    ["ig_s_1", "ig_s_2", "ig_s_3", "ig_w_1", "ig_w_2", "ig_w_3"],
    highlight=["gr_1_1", "gr_1_2"],
    tip="透明与青色相间 —— 这就是冰砖的纹理。",
)
b.step(
    "砌北墙与东墙: 再来 6 片, 环墙闭合。",
    ["ig_n_1", "ig_n_2", "ig_n_3", "ig_e_1", "ig_e_2", "ig_e_3"],
    highlight=["ig_s_1", "ig_w_3"],
    tip="四角竖边两两互吸 —— 闭合环是冰屋的骨架。",
)
b.step(
    "接入口隧道: 两片侧墙竖边吸环墙, 门框拱门封隧道口。",
    ["tn_w", "tn_e", "tn_arch"],
    highlight=["ig_s_2"],
    tip="猫着腰钻隧道 —— 极地的风一点吹不进来。",
)
b.step(
    "盖穹顶板外圈: 8 片压墙顶, 板缝互吸。",
    ["lid_1_1", "lid_2_1", "lid_3_1", "lid_1_2", "lid_3_2",
     "lid_1_3", "lid_2_3", "lid_3_3"],
    highlight=["ig_s_1", "ig_n_3"],
    tip="每片顶板同时吸墙顶与相邻板缝 —— 多路受力。",
)
b.step(
    "嵌中央冰天窗 + 盖隧道顶板。",
    ["skylight", "tn_roof"],
    highlight=["lid_2_1", "tn_w"],
    tip="天窗四边全吸板缝 —— 极光从头顶洒进屋里。",
)
b.step(
    "叠二层冰环: 4 片踩九宫格中央拼缝。",
    ["up_s", "up_n", "up_w", "up_e"],
    highlight=["skylight"],
    tip="二层环墙正好围住天窗 —— 光柱直通穹顶。",
)
b.step(
    "戴等边四坡冰帽: 穹顶 2.71 收尖。",
    CAP,
    highlight=["up_s", "up_e"],
    tip="四条斜棱两两互吸自锁 —— 冰穹完工。",
)
b.step(
    "点亮雪灯: 4 片黄色等边四坡锥。",
    LANTERN,
    highlight=["gr_5_0"],
    tip="雪灯四棱自锁 —— 极夜里的一团暖光。",
)
b.step(
    "立两块冰砖在冻湖沿 —— 冰屋暖光融融!",
    ["block_a", "block_b"],
    highlight=["gr_4_2", "gr_n_2"],
    tip="冰砖重心正压拼缝铰链, 力矩为零。",
)

b.finalize(
    model_id="igloo_01",
    name="极地冰屋",
    name_en="Igloo 01",
    description=(
        "全库第一座冰屋: 3x3 透明/青色相间冰砖环墙四角互吸闭环,"
        " 穹顶九宫格每片同时吸墙顶与板缝、中央嵌窗格方冰天窗,"
        " 再叠 1x1 二层冰环戴等边四坡冰帽 (穹顶 2.71); 南面入口"
        "隧道侧墙吸环墙、门框方拱门封口自成小环; 屋旁黄色四坡"
        "雪灯与冻湖沿冰砖点景 —— 极夜里, 冰屋暖光融融。"
    ),
    difficulty=3,
    tags=["极地", "冰屋", "雪原", "穹顶建筑", "进阶"],
    min_pieces=64,
    min_steps=14,
)
