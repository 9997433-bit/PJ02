#!/usr/bin/env python3
"""生成模型 data/models/forklift_01.json (叉车).

城市生活主题: 全库第一台叉车 —— 灰色货场上, 一台经典黄色叉车
正在作业: 两片车轮底座 (wheel_base) 咬住地坪拼缝组成底盘,
甲板长板压顶锁成箱形; 车尾三面司机棚罩着驾驶位, 棚顶红色
警示灯高高竖起; 车头门架升起, 货叉平伸插进托盘垛 —— 叉尖
稳稳搭在托盘墙顶 (双端受力), 绿色四坡货箱已经离地 1 格;
一旁蓝色集装箱上还码着橙色货堆, 四枚橙色雪糕筒围出作业区
—— 起升, 转运, 落位!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 车头朝东):
  - 货场地坪 7x4: 方板 + 长板混铺 (拼缝落在轮距与托盘线上)   18 片
  - 底盘: 车轮底座 x2 (南北各 1, 底边整边吸地坪拼缝)           2 片
  - 甲板: 长板 x1 (两条长边整边压轮组顶, 箱形合龙)             1 片
  - 司机棚: 车尾三面方墙 + 方板棚顶 + 警示灯三角               5 片
  - 门架与货叉: 方墙门架 x1 + 货叉方板 x1 (z=1 平伸)           2 片
  - 托盘垛: 方墙 x1 (货叉远端的第二支点) + 四坡货箱 x4         5 片
  - 集装箱: 立墙闭环 x4 + 方板箱顶 x1 + 四坡货堆 x4            9 片
  - 雪糕筒: 等边三角 x4 (立地坪格边围出作业区)                 4 片
  合计 46 片, 10 个教程步骤, 5 种磁力片形状 (含车轮底座)。

物理规则要点 (通过 R1~R8 全部校验, default + strict 双档):
  - 轮组 + 甲板锁成箱形环 (火星探测车同款底盘纪律), 甲板
    长边与车轮底座顶边等长整边贴合;
  - 货叉先单边铰链平伸 (力矩 15 <= strict 预算 17.5), 托盘墙
    立起后叉尖双端受力, 绿色货箱再上叉 —— 装载顺序即教程
    顺序, 任何中间状态都不超悬臂预算;
  - 司机棚三面墙 + 棚顶三边受力, 警示灯重心正压棚顶铰链;
  - 集装箱四面竖边互吸闭环, 箱顶四边整边压墙顶。

用法: python3 tools/generate_forklift.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

YARD = "gray"       # 货场地坪
LANE = "yellow"     # 叉车工作道
BODY = "yellow"     # 车身 / 司机棚
WHEEL = "gray"      # 车轮底座
MAST = "orange"     # 门架 / 货叉
BEACON = "red"      # 警示灯
CARGO = "green"     # 被举升的货箱
BOX = "blue"        # 集装箱
PILE = "orange"     # 集装箱顶货堆
CONE = "red"        # 雪糕筒

# =================================================================
# 1. 货场地坪 7x4: 拼缝设计
#    y=1/2 线 x[1,3] 是轮距缝; x=4/5/6 缝是托盘与集装箱脚
# =================================================================
b.flat("yd_a0", 0, 0, 0.0, YARD)                    # [0,1]x[0,1]
b.flat_rect("yd_b0", 1, 0, 0.0, YARD)               # [1,3]x[0,1]
b.flat_rect("yd_c0", 3, 0, 0.0, YARD)               # [3,5]x[0,1]
b.flat_rect("yd_d0", 5, 0, 0.0, YARD)               # [5,7]x[0,1]
b.flat("yd_a1", 0, 1, 0.0, LANE)                    # [0,1]x[1,2]
b.flat_rect("yd_b1", 1, 1, 0.0, LANE)               # [1,3]x[1,2]
b.flat("yd_c1", 3, 1, 0.0, LANE)                    # [3,4]x[1,2]
b.flat("yd_d1", 4, 1, 0.0, LANE)                    # [4,5]x[1,2]
b.flat("yd_e1", 5, 1, 0.0, LANE)                    # [5,6]x[1,2]
b.flat("yd_f1", 6, 1, 0.0, LANE)                    # [6,7]x[1,2]
b.flat_rect("yd_a2", 0, 2, 0.0, YARD)               # [0,2]x[2,3]
b.flat_rect("yd_b2", 2, 2, 0.0, YARD)               # [2,4]x[2,3]
b.flat_rect("yd_c2", 4, 2, 0.0, YARD)               # [4,6]x[2,3]
b.flat("yd_d2", 6, 2, 0.0, YARD)                    # [6,7]x[2,3]
b.flat_rect("yd_a3", 0, 3, 0.0, YARD)               # [0,2]x[3,4]
b.flat_rect("yd_b3", 2, 3, 0.0, YARD)               # [2,4]x[3,4]
b.flat_rect("yd_c3", 4, 3, 0.0, YARD)               # [4,6]x[3,4]
b.flat("yd_d3", 6, 3, 0.0, YARD)                    # [6,7]x[3,4]

# =================================================================
# 2. 底盘: 2 片车轮底座沿 y=1 / y=2 拼缝立起 (x[1,3])
# =================================================================
b.add("wh_s", "wheel_base", (2.0, 1.0, 0.5), (90, 0, 0), WHEEL)
b.add("wh_n", "wheel_base", (2.0, 2.0, 0.5), (90, 0, 0), WHEEL)

# =================================================================
# 3. 甲板: 长板长边整边压两侧轮组顶 (箱形合龙)
# =================================================================
b.flat_rect("deck", 1, 1, 1.0, BODY)                # [1,3]x[1,2] z=1

# =================================================================
# 4. 司机棚 (车尾): 西墙 + 南北侧墙 + 棚顶 + 警示灯
# =================================================================
b.wall_ew("cab_w", 1.0, 1, 1, BODY)                 # 尾墙 (甲板西短边)
b.wall_ns("cab_s", 1, 1.0, 1, BODY)                 # 南侧墙
b.wall_ns("cab_n", 1, 2.0, 1, BODY)                 # 北侧墙
b.flat("cab_roof", 1, 1, 2.0, BODY)                 # 棚顶 [1,2]x[1,2]
b.crest_ew("beacon", 1.0, 1, 2.0, BEACON)           # 警示灯 (棚顶西沿)

# =================================================================
# 5. 门架与货叉: 门架立甲板东短边, 货叉 z=1 平伸 [3,4]
# =================================================================
b.wall_ew("mast", 3.0, 1, 1, MAST)                  # 门架 z1..2
b.flat("fork", 3, 1, 1.0, MAST)                     # 货叉 [3,4]x[1,2]

# =================================================================
# 6. 托盘垛: x=4 缝立托盘墙 (叉尖第二支点) + 四坡货箱上叉
# =================================================================
b.wall_ew("pallet", 4.0, 1, 0, WHEEL)               # 托盘墙 z0..1
CARGO_IDS = b.hat4("cargo", 3, 1, 1.0, CARGO,
                   shape="equilateral_triangle")    # 货箱在叉上

# =================================================================
# 7. 集装箱: [5,6]x[1,2] 闭合环 + 箱顶 + 顶上四坡货堆
# =================================================================
b.wall_ns("bx_s", 5, 1.0, 0, BOX)
b.wall_ns("bx_n", 5, 2.0, 0, BOX)
b.wall_ew("bx_w", 5.0, 1, 0, BOX)
b.wall_ew("bx_e", 6.0, 1, 0, BOX)
b.flat("bx_top", 5, 1, 1.0, BOX)                    # 箱顶 z=1
PILE_IDS = b.hat4("pile", 5, 1, 1.0, PILE,
                  shape="equilateral_triangle")     # 箱顶货堆

# =================================================================
# 8. 雪糕筒: 4 片红色三角立地坪格边, 围出作业区
# =================================================================
b.crest_ns("cn_sw", 0, 0.0, 0.0, CONE)              # 南 [0,1]
b.crest_ew("cn_w", 0.0, 1, 0.0, CONE)               # 西 [1,2]
b.crest_ns("cn_ne", 6, 4.0, 0.0, CONE)              # 北 [6,7]
b.crest_ew("cn_e", 7.0, 1, 0.0, CONE)               # 东 [1,2]

# =================================================================
# 教程步骤 (10 步)
# =================================================================
b.step(
    "铺货场南半: 南沿行 4 片 + 黄色工作道 6 片。",
    ["yd_a0", "yd_b0", "yd_c0", "yd_d0",
     "yd_a1", "yd_b1", "yd_c1", "yd_d1", "yd_e1", "yd_f1"],
    tip="黄色工作道的 x=4/5/6 拼缝就是托盘与集装箱的落点。",
)
b.step(
    "铺货场北半: 长板 8 片收边, 地坪合拢成 7x4。",
    ["yd_a2", "yd_b2", "yd_c2", "yd_d2",
     "yd_a3", "yd_b3", "yd_c3", "yd_d3"],
    highlight=["yd_b1", "yd_f1"],
    tip="轮距缝 y=1 与 y=2 已经铺好 —— 底盘马上就位。",
)
b.step(
    "装底盘: 2 片车轮底座沿轮距缝立起, 底边整边吸合。",
    ["wh_s", "wh_n"],
    highlight=["yd_b0", "yd_b2"],
    tip="车轮底座一片顶两格 —— 叉车的四个轮子稳稳咬住地缝。",
)
b.step(
    "压甲板、立司机棚: 长板两条长边整边压轮组顶, 车尾再立 "
    "尾墙与两面侧墙。",
    ["deck", "cab_w", "cab_s", "cab_n"],
    highlight=["wh_s", "wh_n"],
    tip="轮组+甲板锁成箱形环 —— 侧墙竖边与尾墙互吸。",
)
b.step(
    "盖棚顶、点警示灯: 方板三边压墙顶, 西沿立红色三角。",
    ["cab_roof", "beacon"],
    highlight=["cab_w", "cab_s"],
    tip="警示灯重心正压棚顶铰链 —— 倒车请注意!",
)
b.step(
    "升门架、伸货叉: 门架立甲板东短边, 货叉 z=1 向东平伸。",
    ["mast", "fork"],
    highlight=["deck"],
    tip="货叉此刻单边铰链: 力矩 15 <= strict 预算 17.5, 稳!",
)
b.step(
    "立托盘垛: x=4 拼缝立起托盘墙, 叉尖稳稳搭上墙顶。",
    ["pallet"],
    highlight=["fork", "yd_d1"],
    tip="叉尖有了第二支点 —— 双端受力, 重货随便上。",
)
b.step(
    "货箱上叉: 4 片绿色三角在货叉上四棱互吸, 合拢成货箱。",
    CARGO_IDS,
    highlight=["fork"],
    tip="四坡自锁 —— 货箱已经离地 1 格, 起升成功!",
)
b.step(
    "砌集装箱: 4 片蓝色立墙闭环, 箱顶压平, 再码一垛橙色货堆。",
    ["bx_s", "bx_n", "bx_w", "bx_e", "bx_top"] + PILE_IDS,
    highlight=["yd_e1"],
    tip="四角竖边互吸锁死 —— 下一趟就往这儿卸货。",
)
b.step(
    "摆雪糕筒: 4 枚红色三角立地坪格边, 围出叉车作业区。",
    ["cn_sw", "cn_w", "cn_ne", "cn_e"],
    highlight=["yd_a0", "yd_d3"],
    tip="行人止步 —— 叉车转运中, 作业区封闭!",
)

b.finalize(
    model_id="forklift_01",
    name="叉车",
    name_en="Forklift 01",
    description=(
        "全库第一台叉车: 两片车轮底座咬住货场拼缝组成底盘, 甲板长板整边"
        "压顶锁成箱形环; 车尾三面司机棚顶着红色警示灯, 车头门架升起、"
        "货叉平伸插进托盘垛 —— 叉尖搭上托盘墙顶双端受力, 绿色四坡货箱"
        "已离地 1 格; 一旁蓝色集装箱码着橙色货堆, 四枚雪糕筒围出作业区 "
        "—— 起升, 转运, 落位!"
    ),
    difficulty=2,
    tags=["城市", "叉车", "车轮底座", "物流", "职业体验"],
    min_pieces=44,
    min_steps=10,
)
