#!/usr/bin/env python3
"""生成模型 data/models/octopus_01.json (八爪章鱼)。

内容批 I 模型 3/4: 全库第一只章鱼 —— 海洋货架此前有鲸鱼/海龟/
珊瑚礁, 却还没有八条腿的软体明星。与回收站 (三条并排滑道)/
救援总部 (单条出动坡道) 刻意区分, 本作的招牌是"radial 八爪辐射":
八条 30 度长板触手从头箱顶沿向四面八方辐射落地 —— 东西南北每面
两条, 顶边整边吸头顶板沿, 坡尾压住海床; 两层头箱四角互咬一通到
顶, 南脸两扇透亮窗格方是圆溜溜的大眼睛, 一层藏着门框方小嘴
(就藏在触手后面, 章鱼的嘴本来就长在腿中间!); 头顶梯形四坡圆顶
自锁成环, 粉色压顶方板上还骑着两颗透明泡泡; 海床四角点缀海草/
珊瑚/海星 —— 咕噜咕噜, 海底最聪明的小家伙来了!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 头箱居中 x [2,4] y [2,4]):
  - 海床环带 + 头箱地板 (x [1,5], y [1,5]): 方板 + 长板     14 片
  - 头箱一层 (z 0..1): 墙环 7 + 门框方小嘴 1                 8 片
  - 头顶板 (z=1): 方板 x4, 四边入扣墙顶                      4 片
  - 头箱二层 (z 1..2): 墙 4 + 北横楣 + 窗格方大眼睛 x2       7 片
  - 梯形四坡圆顶 + 粉色压顶 (z 2..2.71)                      5 片
  - 八爪触手 x8 (30 度长板, 顶边吸头顶板沿, 坡尾压海床)      8 片
  - 海草 x2 + 珊瑚 x2 + 海星 + 泡泡 x2                       7 片
  合计 53 片, 10 个教程步骤, 7 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告 + jitter 全绿):
  - 八条触手顶边分别整边吸头顶板外沿 (与一层墙顶/二层墙脚共线),
    坡尾压海床 —— 顶铰链 + 接地坡尾, 悬臂力矩为零, 每面两条对称;
  - 头箱两层墙环四角竖边互咬闭环, 顶板/圆顶四边入扣多路吸合;
  - 梯形四坡腰边两两互吸自锁成环, 压顶方板四边锁住上洞口;
  - 海床环带外圈四角全用单位方板, 给海草/珊瑚/海星留整边沿口;
  - 泡泡骑压顶板沿口, 重心正压铰链线力矩为零;
  - 海床拼缝纪律: 头箱墙脚全部落在地板方板整边上。

用法: python3 tools/generate_octopus_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

SAND = "yellow"     # 海床沙地
SEA = "cyan"        # 海床浅水
BODY = "purple"     # 章鱼头箱 / 触手
EYE = "clear"       # 窗格方大眼睛
MOUTH = "pink"      # 门框方小嘴
CAP = "pink"        # 圆顶压顶
WEED = "green"      # 海草
CORAL = "red"       # 珊瑚
STAR = "orange"     # 海星
BUBBLE = "clear"    # 泡泡

# =================================================================
# 1. 海床 (x [1,5], y [1,5]): 环带 10 + 头箱地板 4
# =================================================================
# 南环带 (y [1,2]): 角上方板给海草/海星留整边沿口
b.flat("sea_s_w", 1, 1, 0.0, SAND)
b.flat_rect("sea_s_m", 2, 1, 0.0, SEA)
b.flat("sea_s_e", 4, 1, 0.0, SAND)
# 北环带 (y [4,5])
b.flat("sea_n_w", 1, 4, 0.0, SEA)
b.flat_rect("sea_n_m", 2, 4, 0.0, SAND)
b.flat("sea_n_e", 4, 4, 0.0, SAND)
# 西环带 (x [1,2], y [2,4])
b.flat("sea_w_s", 1, 2, 0.0, SAND)
b.flat("sea_w_n", 1, 3, 0.0, SEA)
# 东环带 (x [4,5], y [2,4])
b.flat("sea_e_s", 4, 2, 0.0, SEA)
b.flat("sea_e_n", 4, 3, 0.0, SAND)
# 头箱地板 (x [2,4], y [2,4])
b.flat("floor_sw", 2, 2, 0.0, SAND)
b.flat("floor_se", 3, 2, 0.0, SAND)
b.flat("floor_nw", 2, 3, 0.0, SAND)
b.flat("floor_ne", 3, 3, 0.0, SAND)

# =================================================================
# 2. 头箱一层 (z 0..1): 墙环 + 门框方小嘴 (南脸东格)
# =================================================================
b.wall_ns("w1_s_w", 2, 2.0, 0, BODY)
b.add("mouth", "door_frame", (3.5, 2.0, 0.5), (90, 0, 0), MOUTH)
b.wall_ns("w1_n_w", 2, 4.0, 0, BODY)
b.wall_ns("w1_n_e", 3, 4.0, 0, BODY)
b.wall_ew("w1_w_s", 2.0, 2, 0, BODY)
b.wall_ew("w1_w_n", 2.0, 3, 0, BODY)
b.wall_ew("w1_e_s", 4.0, 2, 0, BODY)
b.wall_ew("w1_e_n", 4.0, 3, 0, BODY)

# =================================================================
# 3. 头顶板 (z=1): 四片方板四边入扣墙顶, 外沿就是触手挂点
# =================================================================
b.flat("top_sw", 2, 2, 1.0, BODY)
b.flat("top_se", 3, 2, 1.0, BODY)
b.flat("top_nw", 2, 3, 1.0, BODY)
b.flat("top_ne", 3, 3, 1.0, BODY)

# =================================================================
# 4. 头箱二层 (z 1..2): 墙环 + 南脸两扇窗格方大眼睛
# =================================================================
b.add("eye_w", "window_square", (2.5, 2.0, 1.5), (90, 0, 0), EYE)
b.add("eye_e", "window_square", (3.5, 2.0, 1.5), (90, 0, 0), EYE)
b.wall_ew("w2_w_s", 2.0, 2, 1, BODY)
b.wall_ew("w2_w_n", 2.0, 3, 1, BODY)
b.wall_ew("w2_e_s", 4.0, 2, 1, BODY)
b.wall_ew("w2_e_n", 4.0, 3, 1, BODY)
# 北脸整条横楣: 墙顶 2.0 长整边正好给梯形圆顶的下底整边吸合
b.lintel_ns("w2_n", 2, 4.0, 1, BODY)

# =================================================================
# 5. 梯形四坡圆顶 + 粉色压顶 (z 2..2.71)
# =================================================================
dome_ids, dome_cap = b.hip_roof2("dome", 2, 2, 2.0, BODY, cap_color=CAP)

# =================================================================
# 6. 八爪触手 (30 度长板, 顶边吸头顶板沿 z=1, 坡尾压海床)
# =================================================================
b.ramp("arm_e_s", "+x", 4.0, 2, 1.0, BODY)
b.ramp("arm_e_n", "+x", 4.0, 3, 1.0, BODY)
b.ramp("arm_w_s", "-x", 2.0, 2, 1.0, BODY)
b.ramp("arm_w_n", "-x", 2.0, 3, 1.0, BODY)
b.ramp("arm_n_w", "+y", 4.0, 2, 1.0, BODY)
b.ramp("arm_n_e", "+y", 4.0, 3, 1.0, BODY)
b.ramp("arm_s_w", "-y", 2.0, 2, 1.0, BODY)
b.ramp("arm_s_e", "-y", 2.0, 3, 1.0, BODY)

# =================================================================
# 7. 海底点缀: 海草 x2 (西南角) + 珊瑚 x2 (东北角) + 海星 + 泡泡 x2
# =================================================================
b.spire_ns("weed_a", 1, 1.0, 0.0, WEED)
b.crest_ew("weed_b", 1.0, 1, 0.0, WEED)
b.crest_ns("coral_a", 4, 5.0, 0.0, CORAL)
b.crest_ew("coral_b", 5.0, 4, 0.0, CORAL)
b.crest_ew("star", 5.0, 1, 0.0, STAR)
b.crest_ns("bub_n", 2.5, 3.5, 2.707107, BUBBLE)
b.crest_ew("bub_e", 3.5, 2.5, 2.707107, BUBBLE)

# =================================================================
# 教程步骤 (10 步)
# =================================================================
b.step(
    "铺海床环带: 沙地浅水一圈十片, 板板等边互吸围出头箱位。",
    ["sea_s_w", "sea_s_m", "sea_s_e", "sea_n_w", "sea_n_m", "sea_n_e",
     "sea_w_s", "sea_w_n", "sea_e_s", "sea_e_n"],
    tip="潜到海底啦 —— 先把章鱼家的院子围出来。",
)
b.step(
    "铺头箱地板: 四片沙地方板补齐中央, 头箱墙脚全踩它的整边。",
    ["floor_sw", "floor_se", "floor_nw", "floor_ne"],
    highlight=["sea_s_m"],
)
b.step(
    "立头箱一层南墙与西墙: 南脸东格嵌粉色门框方, 是章鱼的小嘴。",
    ["w1_s_w", "mouth", "w1_w_s", "w1_w_n"],
    highlight=["floor_sw"],
    tip="章鱼的嘴本来就长在八条腿中间 —— 待会儿会被触手挡住哟。",
)
b.step(
    "合头箱一层北墙与东墙: 八片墙环四角竖边互咬闭环。",
    ["w1_n_w", "w1_n_e", "w1_e_s", "w1_e_n"],
    highlight=["w1_s_w"],
)
b.step(
    "盖头顶板: 四片紫色方板四边入扣墙顶 —— 板外沿就是触手挂点。",
    ["top_sw", "top_se", "top_nw", "top_ne"],
    highlight=["w1_e_s"],
    tip="这一圈板沿要拼整齐, 八条触手全靠它整边吸合。",
)
b.step(
    "起头箱二层: 南脸两扇透亮窗格方当大眼睛, 北脸一条整横楣合环。",
    ["eye_w", "eye_e", "w2_w_s", "w2_w_n", "w2_e_s", "w2_e_n", "w2_n"],
    highlight=["top_sw"],
    tip="两只圆眼睛朝南看 —— 谁来和章鱼打招呼呀?",
)
b.step(
    "扣梯形四坡圆顶: 四片梯形腰边两两互吸自锁, 粉色方板压顶锁环。",
    ["dome_n", "dome_e", "dome_w", "dome_s", "dome_cap"],
    highlight=["w2_n"],
    tip="四坡自锁成环 —— 圆滚滚的章鱼脑袋成形啦。",
)
b.step(
    "挂东西四条触手: 30 度长板顶边整边吸板沿, 坡尾稳稳压住海床。",
    ["arm_e_s", "arm_e_n", "arm_w_s", "arm_w_n"],
    highlight=["top_se"],
    tip="顶铰链 + 接地坡尾, 重量走两条路 —— 触手又稳又神气。",
)
b.step(
    "挂南北四条触手: 八爪辐射就位, 每面两条对称受力。",
    ["arm_n_w", "arm_n_e", "arm_s_w", "arm_s_e"],
    highlight=["top_nw"],
    tip="数一数 —— 一二三四五六七八, 一条都不少!",
)
b.step(
    "点缀海底: 海草/珊瑚/海星骑上海床沿口, 两颗泡泡骑压顶板沿。",
    ["weed_a", "weed_b", "coral_a", "coral_b", "star", "bub_n", "bub_e"],
    highlight=["dome_cap"],
    tip="咕噜咕噜 —— 泡泡升起来, 海底最聪明的小家伙来了!",
)

b.finalize(
    model_id="octopus_01",
    name="八爪章鱼",
    name_en="Octopus 01",
    description=(
        "只用核心九片型的全库第一只章鱼: 与回收站的三条并排滑道不同, "
        "本作的招牌是'八爪辐射' —— 八条 30 度长板触手从头箱顶沿向四面"
        "八方辐射落地, 东西南北每面两条, 顶边整边吸头顶板沿, 坡尾压住"
        "海床, 重量走两条路; 两层头箱四角互咬一通到顶, 南脸两扇透亮"
        "窗格方是圆溜溜的大眼睛, 一层还藏着门框方小嘴 (章鱼的嘴本来"
        "就长在腿中间); 头顶梯形四坡圆顶自锁成环, 粉色压顶上骑着两颗"
        "透明泡泡, 海床四角点缀海草/珊瑚/海星 —— 咕噜咕噜, 海底最"
        "聪明的小家伙来了!"
    ),
    difficulty=3,
    tags=["海洋", "章鱼", "动物世界", "海底", "进阶"],
    min_pieces=53,
    min_steps=10,
)
