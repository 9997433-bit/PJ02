#!/usr/bin/env python3
"""生成模型 data/models/police_station_01.json (社区派出所)。

城市生活主题: 与消防站 (双车库 + 瞭望塔) 完全不同的政务小楼 ——
7x4 警务大院里, 一栋 4x2 两层派出所小楼正面朝南: 一层户籍窗口
与蓝色值班大门, 二层整排透明办案窗; 平屋顶南沿立起两片发光的
窗格招牌, 顶上红蓝警灯一左一右; 大院南门是双柱横楣的岗门,
柱顶也顶着红蓝灯; 东侧 1x1 治安岗亭戴四坡尖顶, 西侧绿篱围边
—— 有事找警察, 24 小时不打烊。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 大门朝南):
  - 警务大院 7x4: 后两排方板 x14 + 前院方板/长板 x10          24 片
  - 一层 (z0..1): 后墙/侧墙方板 x8 + 前脸 窗x2/门x1/方x1      12 片
  - 二层 (z1..2): 后墙/侧墙方板 x8 + 前脸窗格方 x4            12 片
  - 屋顶 (z=2): 长板 x4 (1x2 纵铺, 南北双边压墙顶)             4 片
  - 门头招牌: 窗格方 x2 立南沿 + 红蓝警灯等边三角 x2           4 片
  - 通讯天线: 等腰三角 x1 立北沿                               1 片
  - 岗门: 方柱 x4 + 横楣长板 x1 + 红蓝门灯等边三角 x2          7 片
  - 治安岗亭 1x1: 方墙 x4 + 等边四坡尖顶 x4                    8 片
  - 西侧绿篱: 等边三角 x3                                      3 片
  合计 75 片, 17 个教程步骤, 6 种磁力片形状 (CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验):
  - 小楼两层全部圈层砌法: 拐角竖边互吸, 屋顶长板南北双边
    同时压前后墙顶, 楼体锁成多环箱形结构;
  - 招牌窗格方立在屋顶长板南边 + 二层前墙顶的双铰链线上,
    重心正压铰链零力矩; 警灯/天线同理纯竖向传力;
  - 岗门横楣两端竖边吸柱顶方板竖边 (双端受力), 剪断任一端
    力可绕行另一端;
  - 岗亭四墙拐角互吸自锁, 四坡等边尖顶斜棱两两互吸成环。

用法: python3 tools/generate_police_station.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

PLAZA = "gray"      # 大院地坪
LAWN = "green"      # 草坪
PATH = "cyan"       # 进门步道
WALL = "gray"       # 楼体墙面
DOOR = "blue"       # 值班大门
WIN = "clear"       # 办案窗
ROOF = "blue"       # 屋顶
SIGN = "blue"       # 门头招牌
RED = "red"         # 红警灯
BLUE = "blue"       # 蓝警灯
ANT = "gray"        # 天线
BOX = "cyan"        # 岗亭
HEDGE = "green"     # 绿篱

# =================================================================
# 1. 警务大院 7x4: 后两排全方板 (墙脚线), 前院方板+长板混铺
# =================================================================
for x in range(7):
    b.flat(f"g3_{x}", x, 3, 0.0, LAWN if x in (0, 5, 6) else PLAZA)
for x in range(7):
    b.flat(f"g2_{x}", x, 2, 0.0, LAWN if x == 0 else PLAZA)
b.flat("g1_0", 0, 1, 0.0, LAWN)
b.flat("g1_1", 1, 1, 0.0, PLAZA)
b.flat("g1_p", 2, 1, 0.0, PATH)
b.flat("g1_3", 3, 1, 0.0, PLAZA)
b.flat("g1_4", 4, 1, 0.0, PLAZA)
b.flat_rect("g1_r", 5, 1, 0.0, PLAZA)
b.flat_rect("g0_a", 0, 0, 0.0, PLAZA)
b.flat("g0_p", 2, 0, 0.0, PATH)
b.flat_rect("g0_b", 3, 0, 0.0, PLAZA)
b.flat_rect("g0_c", 5, 0, 0.0, PLAZA)

# =================================================================
# 2. 一层 (z0..1): 楼体 [1,5]x[2,4], 后墙 y=4 / 侧墙 / 前脸 y=2
# =================================================================
for x in range(1, 5):
    b.wall_ns(f"bw1_{x}", x, 4.0, 0, WALL)          # 后墙
for y in (2, 3):
    b.wall_ew(f"ww1_{y}", 1.0, y, 0, WALL)          # 西山墙
    b.wall_ew(f"ew1_{y}", 5.0, y, 0, WALL)          # 东山墙
b.add("fwin1_a", "window_square", (1.5, 2.0, 0.5), (90, 0, 0), WIN)   # 户籍窗口
b.add("fdoor", "door_frame", (2.5, 2.0, 0.5), (90, 0, 0), DOOR)       # 值班大门
b.add("fwin1_b", "window_square", (3.5, 2.0, 0.5), (90, 0, 0), WIN)   # 接警窗口
b.wall_ns("fsq1", 4, 2.0, 0, WALL)                  # 前脸实墙

# =================================================================
# 3. 二层 (z1..2): 后墙/侧墙方板, 前脸整排窗格方
# =================================================================
for x in range(1, 5):
    b.wall_ns(f"bw2_{x}", x, 4.0, 1, WALL)
for y in (2, 3):
    b.wall_ew(f"ww2_{y}", 1.0, y, 1, WALL)
    b.wall_ew(f"ew2_{y}", 5.0, y, 1, WALL)
for x in range(1, 5):
    b.add(f"fw2_{x}", "window_square", (x + 0.5, 2.0, 1.5), (90, 0, 0), WIN)

# =================================================================
# 4. 屋顶 (z=2): 4 片长板 1x2 纵铺, 南北两端双边压墙顶
# =================================================================
for x in range(1, 5):
    b.flat_rect(f"rf_{x}", x, 2, 2.0, ROOF, axis="y")

# =================================================================
# 5. 门头招牌 + 警灯 + 天线
# =================================================================
b.add("sign_w", "window_square", (2.5, 2.0, 2.5), (90, 0, 0), SIGN)
b.add("sign_e", "window_square", (3.5, 2.0, 2.5), (90, 0, 0), SIGN)
b.crest_ns("light_r", 2, 2.0, 3.0, RED)             # 红警灯
b.crest_ns("light_b", 3, 2.0, 3.0, BLUE)            # 蓝警灯
b.spire_ns("ant", 3, 4.0, 2.0, ANT)                 # 通讯天线 (北沿)

# =================================================================
# 6. 岗门 (y=1 线): 双柱两层 + 横楣 + 门灯
# =================================================================
b.wall_ns("gp_w1", 1, 1.0, 0, WALL)                 # 西柱下段
b.wall_ns("gp_e1", 4, 1.0, 0, WALL)                 # 东柱下段
b.wall_ns("gp_w2", 1, 1.0, 1, DOOR)                 # 西柱上段
b.wall_ns("gp_e2", 4, 1.0, 1, DOOR)                 # 东柱上段
b.lintel_ns("g_lintel", 2, 1.0, 1, SIGN)            # 岗门横楣 (跨 x2..4)
b.crest_ns("gl_r", 1, 1.0, 2.0, RED)                # 岗门红灯
b.crest_ns("gl_b", 4, 1.0, 2.0, BLUE)               # 岗门蓝灯

# =================================================================
# 7. 治安岗亭 1x1 [6,7]x[2,3]: 四墙 + 等边四坡尖顶
# =================================================================
b.wall_ns("gb_s", 6, 2.0, 0, BOX)
b.wall_ns("gb_n", 6, 3.0, 0, BOX)
b.wall_ew("gb_w", 6.0, 2, 0, BOX)
b.wall_ew("gb_e", 7.0, 2, 0, BOX)
GB_ROOF = b.hat4("gbr", 6, 2, 1.0, ROOF, shape="equilateral_triangle")

# =================================================================
# 8. 西侧绿篱: 等边三角 x3 立在大院西沿
# =================================================================
for y in (1, 2, 3):
    b.crest_ew(f"hg_{y}", 0.0, y, 0.0, HEDGE)

# =================================================================
# 教程步骤 (17 步)
# =================================================================
b.step(
    "铺大院后排: 7 片地坪沿 y=3 排开, 两端与东角留草坪。",
    [f"g3_{x}" for x in range(7)],
    tip="后排格线就是小楼后墙的落脚线 —— 每片都要对齐格子。",
)
b.step(
    "铺大院中排: 再铺 7 片, 小楼与岗亭的地基完成。",
    [f"g2_{x}" for x in range(7)],
    highlight=["g3_0", "g3_6"],
    tip="中排与后排整边互吸 —— 楼体四面墙都会踩在这两排的格线上。",
)
b.step(
    "铺前院与步道: 10 片铺满前院, 青色步道从大门直通院门。",
    ["g1_0", "g1_1", "g1_p", "g1_3", "g1_4", "g1_r",
     "g0_a", "g0_p", "g0_b", "g0_c"],
    highlight=["g2_2"],
    tip="长板拼缝错开受力 —— 青色步道正对将要立起的值班大门。",
)
b.step(
    "立一层后墙与山墙: 后墙 4 片沿 y=4, 东西山墙各 2 片。",
    [f"bw1_{x}" for x in range(1, 5)] + ["ww1_2", "ww1_3", "ew1_2", "ew1_3"],
    highlight=["g3_1", "g2_1"],
    tip="拐角竖边互吸 —— 圈层砌法从第一层就开始自锁。",
)
b.step(
    "装一层前脸: 户籍窗口 + 蓝色值班大门 + 接警窗口 + 实墙。",
    ["fwin1_a", "fdoor", "fwin1_b", "fsq1"],
    highlight=["ww1_2", "ew1_2"],
    tip="大门正对青色步道 —— 前脸四片与山墙竖边互吸合龙一层。",
)
b.step(
    "立二层后墙与山墙: 沿一层墙顶再起一圈 8 片。",
    [f"bw2_{x}" for x in range(1, 5)] + ["ww2_2", "ww2_3", "ew2_2", "ew2_3"],
    highlight=["bw1_1", "ww1_2"],
    tip="上环整边压下环 —— 越按越紧, 这就是圈层砌法的力气。",
)
b.step(
    "装二层办案窗: 4 片透明窗格方一字排开, 二层合龙。",
    [f"fw2_{x}" for x in range(1, 5)],
    highlight=["fwin1_a", "fdoor"],
    tip="整排透明大窗 —— 阳光照进办案区, 警务公开透明。",
)
b.step(
    "盖屋顶: 4 片长板纵向铺过楼顶, 南北两端同时压住前后墙顶。",
    [f"rf_{x}" for x in range(1, 5)],
    highlight=["bw2_1", "fw2_1"],
    tip="每片长板双端受力零悬挑 —— 屋顶把两层墙圈锁成整体。",
)
b.step(
    "立门头招牌: 2 片蓝色窗格方立在屋顶南沿正中。",
    ["sign_w", "sign_e"],
    highlight=["rf_2", "rf_3"],
    tip="底边同时吸住屋顶板边与二层墙顶 —— 双铰链线互为保险。",
)
b.step(
    "装楼顶警灯: 招牌顶上红灯在西、蓝灯在东。",
    ["light_r", "light_b"],
    highlight=["sign_w", "sign_e"],
    tip="重心正压铰链线, 力臂为零 —— 红蓝灯昼夜值班。",
)
b.step(
    "竖通讯天线: 屋顶北沿立起 1 片等腰高塔尖。",
    ["ant"],
    highlight=["rf_3"],
    tip="尖端高出屋面 2 格 —— 110 指挥中心的信号从这里进出。",
)
b.step(
    "立岗门柱基: 步道两侧沿 y=1 各立 1 片灰色方柱。",
    ["gp_w1", "gp_e1"],
    highlight=["g1_1", "g1_4"],
    tip="两柱正好隔出 2 格门洞 —— 底边整边吸住地坪格线。",
)
b.step(
    "加柱顶与横楣: 蓝色柱顶方板压柱, 长板横楣跨过门洞两端竖边互吸。",
    ["gp_w2", "gp_e2", "g_lintel"],
    highlight=["gp_w1", "gp_e1"],
    tip="横楣两端竖边传力 —— 剪断任何一端, 力还能从另一端绕行。",
)
b.step(
    "装岗门门灯: 柱顶红蓝双灯遥相呼应。",
    ["gl_r", "gl_b"],
    highlight=["gp_w2", "gp_e2"],
    tip="进出大院一抬头就能看见 —— 警灯是最醒目的路标。",
)
b.step(
    "起治安岗亭四墙: 东侧 1x1 格子上四面青色方墙拐角互吸。",
    ["gb_s", "gb_n", "gb_w", "gb_e"],
    highlight=["g2_6", "g3_6"],
    tip="四墙竖边两两互吸自锁成筒 —— 单人岗亭也要有结构冗余。",
)
b.step(
    "盖岗亭尖顶: 4 片等边三角四坡合拢, 斜棱两两互吸。",
    GB_ROOF,
    highlight=["gb_s", "gb_n"],
    tip="锥尖高 0.707, 四条斜棱一圈装完自锁成环。",
)
b.step(
    "种西侧绿篱: 大院西沿立 3 片绿色等边三角收边。",
    ["hg_1", "hg_2", "hg_3"],
    highlight=["g1_0", "g2_0"],
    tip="绿篱底边整边吸大院西沿 —— 派出所建成, 社区更安心!",
)

b.finalize(
    model_id="police_station_01",
    name="社区派出所",
    name_en="Police Station 01",
    description=(
        "城市守护者系列的政务小楼: 7x4 警务大院里, 4x2 两层派出所圈层砌法"
        "起楼 —— 一层户籍窗口与蓝色值班大门, 二层整排透明办案窗, 屋顶长板"
        "南北双边压墙顶锁成多环箱体; 门头两片发光窗格招牌顶着红蓝警灯 "
        "(重心正压铰链零力矩), 北沿通讯天线直指 4 格高; 大院南门双柱横楣"
        "岗门 (两端竖边传力) 也戴红蓝门灯, 东侧治安岗亭四墙自锁加等边四坡"
        "尖顶, 西侧绿篱收边 —— 有事找警察, 24 小时不打烊。"
    ),
    difficulty=3,
    tags=["城市", "职业体验", "派出所", "建筑", "进阶"],
    min_pieces=50,
    min_steps=16,
)
