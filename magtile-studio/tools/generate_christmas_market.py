#!/usr/bin/env python3
"""生成模型 data/models/christmas_market_01.json (圣诞集市)。

节日/庆典主题 2/4: 全库第一座节日露天集市 —— 与商铺批
(bakery_shop_01 / supermarket_01 的封闭门面房) 刻意区分, 本作的
结构逻辑是 "开口货亭 + 塔式圣诞树 + 礼盒方块" 三种箱式变体同场:
雪白广场上两座三面围合的货亭南向敞开 —— 后墙嵌门框方储货门,
雪顶长板两短边分别压东西侧墙顶 (双端受力零悬挑), 侧墙顶骑招牌
三角; 广场正中塔式圣诞树两层绿墙环拔起, 戴等腰四坡树冠 (树尖
3.94 全场最高); 树旁与街南三只彩色礼盒方块 (四壁一盖箱式自锁),
入口一对糖果柱红白相映。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 集市朝南):
  - 地面 (x [0,10], y [0,4]): 雪场 + 石板街 + 货亭木地板     28 片
  - 货亭 x2 (x [1,3] / x [7,9], y [2,3]): 后墙 (门框方 x1 +
    方 x1) + 双侧墙 + 雪顶长板 + 招牌三角 (每座 6 片)        12 片
  - 圣诞树 (x [4,5], y [2,3]): 两层绿墙环 + 两层盖板 +
    等腰四坡树冠                                             14 片
  - 礼盒方块 x2 (x [2,3] / x [7,8], y [0,1]): 四壁 + 缎带盖  10 片
  - 糖果柱 x2 (南界 y=0): 红柱壁 + 骑顶白糖霜三角             4 片
  合计 68 片, 14 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 货亭后墙-侧墙四条转角竖边互咬, 雪顶两短边整边压侧墙顶
    (双端受力), 墙-顶-墙-地板锁成箱形闭环, 南面留购物口;
  - 圣诞树两层墙环四角竖边互吸闭环, 盖板四边压四墙顶, 树冠
    四棱两两互吸自锁 (树尖 3.94, 环环相扣通过 R8 高层检查);
  - 礼盒四壁互咬 + 缎带盖四边压顶, 五片锁成整箱;
  - 招牌三角 / 糖霜三角重心正压铰链线, 力矩为零。

用法: python3 tools/generate_christmas_market.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

SNOW = "clear"      # 雪场 / 雪顶 / 糖霜
STREET = "gray"     # 石板街 / 树座
WOOD = "orange"     # 货亭木地板
STALL_W = "red"     # 西货亭墙
STALL_E = "green"   # 东货亭墙
DOOR = "orange"     # 储货门
SIGN_W = "yellow"   # 西招牌
SIGN_E = "red"      # 东招牌
TREE = "green"      # 圣诞树
GIFT_W = "red"      # 西礼盒
RIB_W = "yellow"    # 西缎带盖
GIFT_E = "blue"     # 东礼盒
RIB_E = "pink"      # 东缎带盖
CANE = "red"        # 糖果柱

# =================================================================
# 1. 地面南行 (y [0,1]): 糖果柱础 + 礼盒底板 + 雪场
# =================================================================
b.flat("ga_0", 0, 0, 0.0, STREET)
b.flat("ga_1", 1, 0, 0.0, SNOW)
b.flat("ga_2", 2, 0, 0.0, SNOW)
b.flat_rect("ga_3", 3, 0, 0.0, SNOW)
b.flat_rect("ga_4", 5, 0, 0.0, SNOW)
b.flat("ga_5", 7, 0, 0.0, SNOW)
b.flat("ga_6", 8, 0, 0.0, SNOW)
b.flat("ga_7", 9, 0, 0.0, STREET)

# =================================================================
# 2. 石板街 (y [1,2]): 5 片灰长板
# =================================================================
for k, x0 in enumerate((0, 2, 4, 6, 8)):
    b.flat_rect(f"gb_{k}", x0, 1, 0.0, STREET)

# =================================================================
# 3. 地面铺位行 (y [2,3]): 货亭木地板 + 树座, 全部方板 (留出墙脚整边)
# =================================================================
b.flat("gc_0", 0, 2, 0.0, SNOW)
b.flat("gc_1", 1, 2, 0.0, WOOD)
b.flat("gc_2", 2, 2, 0.0, WOOD)
b.flat("gc_3", 3, 2, 0.0, SNOW)
b.flat("gc_4", 4, 2, 0.0, STREET)
b.flat("gc_5", 5, 2, 0.0, SNOW)
b.flat("gc_6", 6, 2, 0.0, SNOW)
b.flat("gc_7", 7, 2, 0.0, WOOD)
b.flat("gc_8", 8, 2, 0.0, WOOD)
b.flat("gc_9", 9, 2, 0.0, SNOW)

# =================================================================
# 4. 地面北行 (y [3,4]): 5 片雪长板
# =================================================================
for k, x0 in enumerate((0, 2, 4, 6, 8)):
    b.flat_rect(f"gd_{k}", x0, 3, 0.0, SNOW)

# =================================================================
# 5. 货亭 x2: 后墙 (门框方 + 方) + 双侧墙 + 雪顶长板 + 招牌三角
# =================================================================
b.add("sw_bk_d", "door_frame", (1.5, 3.0, 0.5), (90, 0, 0), DOOR)
b.wall_ns("sw_bk", 2, 3.0, 0, STALL_W)
b.wall_ew("sw_sw", 1.0, 2, 0, STALL_W)
b.wall_ew("sw_se", 3.0, 2, 0, STALL_W)
b.flat_rect("sw_roof", 1, 2, 1.0, SNOW)
b.crest_ew("sw_sign", 1.0, 2, 1.0, SIGN_W)

b.add("se_bk_d", "door_frame", (7.5, 3.0, 0.5), (90, 0, 0), DOOR)
b.wall_ns("se_bk", 8, 3.0, 0, STALL_E)
b.wall_ew("se_sw", 7.0, 2, 0, STALL_E)
b.wall_ew("se_se", 9.0, 2, 0, STALL_E)
b.flat_rect("se_roof", 7, 2, 1.0, SNOW)
b.crest_ew("se_sign", 9.0, 2, 1.0, SIGN_E)

# =================================================================
# 6. 圣诞树 (x [4,5], y [2,3]): 两层墙环 + 盖板 + 等腰四坡树冠
# =================================================================
b.wall_ns("tr1_s", 4, 2.0, 0, TREE)
b.wall_ew("tr1_w", 4.0, 2, 0, TREE)
b.wall_ew("tr1_e", 5.0, 2, 0, TREE)
b.wall_ns("tr1_n", 4, 3.0, 0, TREE)
b.flat("tr_cap1", 4, 2, 1.0, TREE)
b.wall_ns("tr2_s", 4, 2.0, 1, TREE)
b.wall_ew("tr2_w", 4.0, 2, 1, TREE)
b.wall_ew("tr2_e", 5.0, 2, 1, TREE)
b.wall_ns("tr2_n", 4, 3.0, 1, TREE)
b.flat("tr_cap2", 4, 2, 2.0, TREE)
TR_CROWN = b.hat4("tr_crown", 4, 2, 2.0, TREE)

# =================================================================
# 7. 礼盒方块 x2 (x [2,3] / x [7,8], y [0,1]): 四壁 + 缎带盖
# =================================================================
b.wall_ns("gw_s", 2, 0.0, 0, GIFT_W)
b.wall_ew("gw_w", 2.0, 0, 0, GIFT_W)
b.wall_ew("gw_e", 3.0, 0, 0, GIFT_W)
b.wall_ns("gw_n", 2, 1.0, 0, GIFT_W)
b.flat("gw_cap", 2, 0, 1.0, RIB_W)

b.wall_ns("ge_s", 7, 0.0, 0, GIFT_E)
b.wall_ew("ge_w", 7.0, 0, 0, GIFT_E)
b.wall_ew("ge_e", 8.0, 0, 0, GIFT_E)
b.wall_ns("ge_n", 7, 1.0, 0, GIFT_E)
b.flat("ge_cap", 7, 0, 1.0, RIB_E)

# =================================================================
# 8. 糖果柱 x2 (南界 y=0): 红柱壁 + 骑顶白糖霜三角
# =================================================================
b.wall_ns("cn_w", 0, 0.0, 0, CANE)
b.crest_ns("cn_w_top", 0, 0.0, 1.0, SNOW)
b.wall_ns("cn_e", 9, 0.0, 0, CANE)
b.crest_ns("cn_e_top", 9, 0.0, 1.0, SNOW)

# =================================================================
# 教程步骤 (14 步)
# =================================================================
b.step(
    "铺地面南行 (y [0,1]): 两端灰色柱础方板, 中段雪板, 礼盒底板"
    "落在 x [2,3] 与 x [7,8]。",
    ["ga_0", "ga_1", "ga_2", "ga_3", "ga_4", "ga_5", "ga_6", "ga_7"],
    tip="两端柱础的南沿留给糖果柱 —— 方板的整边才吸得住柱脚。",
)
b.step(
    "铺石板街 (y [1,2]): 5 片灰长板横贯集市。",
    ["gb_0", "gb_1", "gb_2", "gb_3", "gb_4"],
    highlight=["ga_0", "ga_7"],
    tip="逛集市的人从这条街上走 —— 两侧就是货亭与礼盒。",
)
b.step(
    "铺铺位行 (y [2,3]): 10 片方板一字排开, 木地板给货亭, 灰座给"
    "圣诞树。",
    ["gc_0", "gc_1", "gc_2", "gc_3", "gc_4", "gc_5", "gc_6", "gc_7",
     "gc_8", "gc_9"],
    highlight=["gb_0"],
    tip="这一行全用方板 —— 每面墙脚都要有一条整边可吸。",
)
b.step(
    "铺地面北行 (y [3,4]): 5 片雪长板, 广场合拢。",
    ["gd_0", "gd_1", "gd_2", "gd_3", "gd_4"],
    highlight=["gc_1", "gc_8"],
    tip="货亭后墙就立在这两行地板的拼缝上。",
)
b.step(
    "立西货亭三面墙: 后墙橙色储货门 + 红墙, 东西侧墙围合, 南面"
    "敞开做柜台口。",
    ["sw_bk_d", "sw_bk", "sw_sw", "sw_se"],
    highlight=["gc_1", "gc_2"],
    tip="转角竖边互咬 —— 三面墙也能锁成刚环, 全靠地板整边兜底。",
)
b.step(
    "盖西货亭雪顶并骑招牌: 雪顶长板两短边分别压东西侧墙顶, 黄色"
    "招牌骑上西侧墙顶。",
    ["sw_roof", "sw_sign"],
    highlight=["sw_sw", "sw_se"],
    tip="雪顶双端受力零悬挑 —— 招牌重心正压铰链线, 力臂为零。",
)
b.step(
    "立东货亭三面墙: 与西货亭对称, 绿墙配橙门。",
    ["se_bk_d", "se_bk", "se_sw", "se_se"],
    highlight=["gc_7", "gc_8"],
    tip="红亭卖热红酒, 绿亭卖姜饼 —— 圣诞集市的老规矩。",
)
b.step(
    "盖东货亭雪顶并骑招牌: 红色招牌骑上东侧墙顶。",
    ["se_roof", "se_sign"],
    highlight=["se_sw", "se_se"],
    tip="两座货亭隔街对望, 购物口都朝着石板街。",
)
b.step(
    "立圣诞树第 1 层: 4 片绿墙环踩住灰座四条边。",
    ["tr1_s", "tr1_w", "tr1_e", "tr1_n"],
    highlight=["gc_4"],
    tip="每片底边吸树座板边、转角竖边互咬 —— 墙环闭合才稳。",
)
b.step(
    "盖第 1 层盖板, 再叠第 2 层绿墙环。",
    ["tr_cap1", "tr2_s", "tr2_w", "tr2_e", "tr2_n"],
    highlight=["tr1_s"],
    tip="盖板四边压四墙顶; 第 2 层每片同时吸盖板沿与邻片竖边。",
)
b.step(
    "封树顶并戴等腰四坡树冠: 4 片瘦高三角斜棱两两互吸自锁。",
    ["tr_cap2"] + TR_CROWN,
    highlight=["tr2_s"],
    tip="树冠四棱互吸成环, 越推越紧 —— 树尖 3.94, 全场最高。",
)
b.step(
    "拼西礼盒: 4 片红壁互咬 + 黄色缎带盖压顶, 五片锁成整箱。",
    ["gw_s", "gw_w", "gw_e", "gw_n", "gw_cap"],
    highlight=["ga_2"],
    tip="礼盒就是最小的箱式结构 —— 盖子一压, 四壁全锁死。",
)
b.step(
    "拼东礼盒: 蓝箱粉盖, 与西礼盒隔街相望。",
    ["ge_s", "ge_w", "ge_e", "ge_n", "ge_cap"],
    highlight=["gw_cap"],
    tip="拆礼物要等平安夜 —— 现在先摆在雪地上馋一馋。",
)
b.step(
    "立糖果柱 x2 (南界 y=0): 红柱壁骑方板南沿, 柱顶各骑一片白"
    "糖霜三角 —— 圣诞集市开市!",
    ["cn_w", "cn_w_top", "cn_e", "cn_e_top"],
    highlight=["ga_0", "ga_7"],
    tip="红柱白霜就是大号拐杖糖 —— 圣诞快乐, 欢迎光临!",
)

b.finalize(
    model_id="christmas_market_01",
    name="圣诞集市",
    name_en="Christmas Market 01",
    description=(
        "只用核心九片型的节日露天集市: 雪白广场上两座三面围合的"
        "货亭南向敞开 —— 后墙嵌门框方储货门, 转角竖边互咬, 雪顶"
        "长板两短边分别压东西侧墙顶 (双端受力零悬挑), 侧墙顶骑"
        "招牌三角; 广场正中塔式圣诞树两层绿墙环四角互吸拔起, 戴"
        "等腰四坡树冠 (树尖 3.94 全场最高, 环环相扣); 街旁两只"
        "彩色礼盒方块四壁一盖箱式自锁, 入口一对糖果柱红柱白霜 —— "
        "开口货亭、塔式墙环、礼盒方块, 三种箱式变体一场集市学会。"
    ),
    difficulty=3,
    tags=["节日", "圣诞", "集市", "货亭", "进阶"],
    min_pieces=68,
    min_steps=14,
)
