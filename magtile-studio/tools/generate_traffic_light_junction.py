#!/usr/bin/env python3
"""生成模型 data/models/traffic_light_junction_01.json (红绿灯路口)。

城市交通主题批 4/4: 全库第一座以"信号灯塔"为主角的十字路口 ——
与 railway_crossing_01 (门式栏杆锁道口) 刻意区分: 道口靠"杆"拦车,
路口靠"灯"指挥 —— 本作的招牌是两座四层墙环信号灯塔: 每层 4 片
墙合环 (环环相扣, 塔高 4.0 靠闭环拓扑通过 R8 无桁架高墙检查),
第 2/3/4 层朝路口的两面嵌绿/黄/红窗格方信号窗, 红黄绿自上而下
纵列 —— 就是教科书里的信号灯排布; 两塔对角布置 (西南 + 东北),
四个方向来车各看各的灯; 十字路口四向全铺透明斑马线, 西北角
交警岗亭窗格方了望窗正对路口、门框方侧门朝人行道, 顶戴红色
四坡尖顶; 一辆紫色小车停在南引道停止线前 —— 红灯亮了,
车头正好压线不越线, 等绿灯。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 四角草坪 (2x2, 每角双长板对拼): 长板 x8                        8 片
  - 中央路口 (x [2,4], y [2,4]): 长板 x2                           2 片
  - 四向斑马线: 透明方板 x8                                        8 片
  - 东西北引道方板 x6 + 南引道长板 x2 (y [-1,1])                   8 片
  - 信号灯塔 x2 (西南/东北, 四层墙环 + 压顶): 每塔 16 墙 + 1 顶   34 片
  - 交警岗亭 (西北角): 墙环 4 (含了望窗/侧门) + 四坡尖顶 4         8 片
  - 紫色小车 (南引道候灯): 车轮底座 x2 + 长板车顶 + 三角驾驶舱     4 片
  - 街角绿篱 x2 (东南角)                                           2 片
  合计 74 片, 13 个教程步骤, 7 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 信号灯塔逐层合环: 每层 4 片墙四角竖边互吸自锁, 上层墙底边
    整边吸下层墙顶边 (每层接口 4 条连接互为冗余), 压顶方板四边
    咬墙顶 —— 塔高 4.0 触发 R8 高层检查, 全塔无一处单点失效;
  - 窗格方信号窗物理上按实心方片拼接, 颜色即灯色 (绿/黄/红
    自上而下纵列), 不改变墙环受力;
  - 岗亭四坡尖顶四条斜棱两两互吸自锁成环 (亭尖 2.94);
  - 小车车顶长板双长边压两片车轮底座顶边, 东轮底边吸引道路板
    东沿 (全场连通), 车头驾驶舱骑车顶北沿 —— 压线不越线;
  - 全部平铺件横平竖直整边互吸, 斑马线与路板同层零重叠。

用法: python3 tools/generate_traffic_light_junction.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

LAWN = "green"      # 四角草坪
ROAD = "gray"       # 路面
ZEBRA = "clear"     # 斑马线
TOWER = "gray"      # 灯塔墙体
SIG_G = "green"     # 信号窗: 绿
SIG_Y = "yellow"    # 信号窗: 黄
SIG_R = "red"       # 信号窗: 红
CAP = "gray"        # 塔顶压顶
HUT = "blue"        # 岗亭墙
WIN = "clear"       # 岗亭了望窗
DOOR = "red"        # 岗亭侧门
HAT = "red"         # 岗亭尖顶
CAR = "purple"      # 紫色小车
WHEEL = "gray"      # 车轮底座
HEDGE = "green"     # 街角绿篱

# =================================================================
# 1. 四角草坪 (2x2, 双长板对拼) + 中央路口 + 斑马线 + 引道
# =================================================================
for corner, (x0, y0) in (("sw", (0, 0)), ("se", (4, 0)),
                         ("nw", (0, 4)), ("ne", (4, 4))):
    b.flat_rect(f"lawn_{corner}_a", x0, y0, 0.0, LAWN)
    b.flat_rect(f"lawn_{corner}_b", x0, y0 + 1, 0.0, LAWN)
# 中央路口 (x [2,4], y [2,4]): 双长板对拼
b.flat_rect("ctr_s", 2, 2, 0.0, ROAD)
b.flat_rect("ctr_n", 2, 3, 0.0, ROAD)
# 四向斑马线 (透明方板)
b.flat("zb_s_2", 2, 1, 0.0, ZEBRA)
b.flat("zb_s_3", 3, 1, 0.0, ZEBRA)
b.flat("zb_n_2", 2, 4, 0.0, ZEBRA)
b.flat("zb_n_3", 3, 4, 0.0, ZEBRA)
b.flat("zb_w_2", 1, 2, 0.0, ZEBRA)
b.flat("zb_w_3", 1, 3, 0.0, ZEBRA)
b.flat("zb_e_2", 4, 2, 0.0, ZEBRA)
b.flat("zb_e_3", 4, 3, 0.0, ZEBRA)
# 引道: 东西北方板 + 南长板 (南引道加长, 小车要在停止线前候灯)
b.flat("ap_w_2", 0, 2, 0.0, ROAD)
b.flat("ap_w_3", 0, 3, 0.0, ROAD)
b.flat("ap_e_2", 5, 2, 0.0, ROAD)
b.flat("ap_e_3", 5, 3, 0.0, ROAD)
b.flat("ap_n_2", 2, 5, 0.0, ROAD)
b.flat("ap_n_3", 3, 5, 0.0, ROAD)
b.flat_rect("ap_s_0", 2, 0, 0.0, ROAD)
b.flat_rect("ap_s_1", 2, -1, 0.0, ROAD)

# =================================================================
# 2. 信号灯塔 x2: 四层墙环, 红黄绿信号窗自上而下纵列
# =================================================================
def signal_tower(prefix, x0, y0, face):
    """1x1 四层信号灯塔: 一层灰基座, 2/3/4 层朝路口两面嵌信号窗。

    face: 'ne' 表示信号窗开在北面与东面 (塔在路口西南角);
          'sw' 表示开在南面与西面 (塔在路口东北角)。
    """
    x1, y1 = x0 + 1, y0 + 1
    colors = {2: SIG_G, 3: SIG_Y, 4: SIG_R}   # 绿 / 黄 / 红 自下而上? 不 ——
    # 交通信号灯自上而下是 红-黄-绿: 第 4 层红, 第 3 层黄, 第 2 层绿。
    for lv in range(1, 5):
        z0 = lv - 1
        sig = colors.get(lv)
        if sig and face == "ne":
            b.wall_ns(f"{prefix}{lv}_s", x0, y0 + 0.0, z0, TOWER)
            b.add(f"{prefix}{lv}_n", "window_square",
                  (x0 + 0.5, y1 + 0.0, z0 + 0.5), (90, 0, 0), sig)
            b.wall_ew(f"{prefix}{lv}_w", x0 + 0.0, y0, z0, TOWER)
            b.add(f"{prefix}{lv}_e", "window_square",
                  (x1 + 0.0, y0 + 0.5, z0 + 0.5), (90, 0, 90), sig)
        elif sig and face == "sw":
            b.add(f"{prefix}{lv}_s", "window_square",
                  (x0 + 0.5, y0 + 0.0, z0 + 0.5), (90, 0, 0), sig)
            b.wall_ns(f"{prefix}{lv}_n", x0, y1 + 0.0, z0, TOWER)
            b.add(f"{prefix}{lv}_w", "window_square",
                  (x0 + 0.0, y0 + 0.5, z0 + 0.5), (90, 0, 90), sig)
            b.wall_ew(f"{prefix}{lv}_e", x1 + 0.0, y0, z0, TOWER)
        else:
            b.wall_ns(f"{prefix}{lv}_s", x0, y0 + 0.0, z0, TOWER)
            b.wall_ns(f"{prefix}{lv}_n", x0, y1 + 0.0, z0, TOWER)
            b.wall_ew(f"{prefix}{lv}_w", x0 + 0.0, y0, z0, TOWER)
            b.wall_ew(f"{prefix}{lv}_e", x1 + 0.0, y0, z0, TOWER)
    b.flat(f"{prefix}_cap", x0, y0, 4.0, CAP)


signal_tower("tw", 1, 1, "ne")      # 西南塔 (信号窗朝北/朝东)
signal_tower("te", 4, 4, "sw")      # 东北塔 (信号窗朝南/朝西)

# =================================================================
# 3. 交警岗亭 (西北角 x [1,2], y [4,5])
# =================================================================
b.add("hut_s", "window_square", (1.5, 4.0, 0.5), (90, 0, 0), WIN)  # 了望窗正对路口
b.wall_ns("hut_n", 1, 5.0, 0, HUT)
b.wall_ew("hut_w", 1.0, 4, 0, HUT)
b.add("hut_door", "door_frame", (2.0, 4.5, 0.5), (90, 0, 90), DOOR)  # 侧门朝斑马线
b.hat4("hut_hat", 1, 4, 1.0, HAT)

# =================================================================
# 4. 紫色小车 (南引道候灯, x [3,4], y [-1,1]): 车头压停止线
# =================================================================
b.add("car_wh_w", "wheel_base", (3.0, 0.0, 0.5), (90, 0, 90), WHEEL)
b.add("car_wh_e", "wheel_base", (4.0, 0.0, 0.5), (90, 0, 90), WHEEL)
b.flat_rect("car_top", 3, -1, 1.0, CAR, axis="y")   # 车顶长板 (双长边压轮顶)
b.crest_ns("car_cab", 3, 1.0, 1.0, CAR)             # 驾驶舱 (骑车顶北沿, 压线不越线)

# =================================================================
# 5. 街角绿篱 (东南角草坪东缘)
# =================================================================
b.crest_ew("hedge_a", 6.0, 0, 0.0, HEDGE)
b.crest_ew("hedge_b", 6.0, 1, 0.0, HEDGE)

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺中央路口与四向斑马线: 路口双长板对拼, 8 片透明方板就是斑马线。",
    ["ctr_s", "ctr_n", "zb_s_2", "zb_s_3", "zb_n_2", "zb_n_3",
     "zb_w_2", "zb_w_3", "zb_e_2", "zb_e_3"],
    tip="行人走斑马线 —— 四个方向都要留, 十字的骨架先落地。",
)
b.step(
    "铺四角草坪: 每角两片绿色长板对拼成 2x2 街角, 短边吸住斑马线沿边。",
    ["lawn_sw_a", "lawn_sw_b", "lawn_se_a", "lawn_se_b",
     "lawn_nw_a", "lawn_nw_b", "lawn_ne_a", "lawn_ne_b"],
    highlight=["zb_s_2", "zb_n_3"],
    tip="四个街角围住十字 —— 灯塔和岗亭都要站在这些草坪上。",
)
b.step(
    "接四向引道: 东西北各 2 片方板, 南引道 2 片长板加长 (小车要在这里候灯)。",
    ["ap_w_2", "ap_w_3", "ap_e_2", "ap_e_3", "ap_n_2", "ap_n_3",
     "ap_s_0", "ap_s_1"],
    highlight=["zb_s_2", "zb_w_2"],
    tip="南引道故意修长一点 —— 停止线前要留出一辆车的位置。",
)
b.step(
    "立西南灯塔基座: 4 片灰墙合环 (x [1,2], y [1,2]), 四角竖边互吸自锁。",
    ["tw1_s", "tw1_n", "tw1_w", "tw1_e"],
    highlight=["lawn_sw_a"],
    tip="灯塔要长到 4 层高 —— 每一层都必须是闭环。",
)
b.step(
    "西南塔绿灯层与黄灯层: 朝北/朝东两面嵌信号窗, 背面灰墙合环。",
    ["tw2_s", "tw2_n", "tw2_w", "tw2_e",
     "tw3_s", "tw3_n", "tw3_w", "tw3_e"],
    highlight=["tw1_s"],
    tip="上层墙底边整边吸下层墙顶 —— 每层接口 4 条连接互为冗余。",
)
b.step(
    "西南塔红灯层并压顶: 红窗在最上 —— 红黄绿自上而下, 教科书排布。",
    ["tw4_s", "tw4_n", "tw4_w", "tw4_e", "tw_cap"],
    highlight=["tw3_n"],
    tip="压顶方板四边咬墙顶, 塔高 4.0 —— 闭环拓扑稳稳通过高层检查。",
)
b.step(
    "立东北灯塔基座: 与西南塔对角相望 (x [4,5], y [4,5])。",
    ["te1_s", "te1_n", "te1_w", "te1_e"],
    highlight=["lawn_ne_a"],
    tip="两塔对角布置 —— 四个方向来车各看各的灯。",
)
b.step(
    "东北塔绿灯层与黄灯层: 信号窗朝南/朝西, 正对来车。",
    ["te2_s", "te2_n", "te2_w", "te2_e",
     "te3_s", "te3_n", "te3_w", "te3_e"],
    highlight=["te1_s"],
    tip="信号窗物理上按实心方片拼接 —— 灯色不改变墙环受力。",
)
b.step(
    "东北塔红灯层并压顶: 双塔同高 4.0, 隔着路口红灯对红灯。",
    ["te4_s", "te4_n", "te4_w", "te4_e", "te_cap"],
    highlight=["te3_s"],
    tip="现在红灯亮 —— 南引道的车该停下了。",
)
b.step(
    "立交警岗亭 (西北角): 了望窗正对路口, 侧门朝斑马线, 墙环合拢。",
    ["hut_s", "hut_n", "hut_w", "hut_door"],
    highlight=["lawn_nw_a"],
    tip="交警从了望窗看着全路口 —— 有情况推门就到斑马线。",
)
b.step(
    "戴岗亭尖顶: 4 片红色等腰三角四坡收尖 (亭尖 2.94)。",
    ["hut_hat_s", "hut_hat_e", "hut_hat_n", "hut_hat_w"],
    highlight=["hut_s"],
    tip="四条斜棱两两互吸自锁成环 —— 岗亭的小红帽。",
)
b.step(
    "紫色小车候灯: 车轮底座立在南引道, 长板车顶压轮顶, 车头压停止线不越线。",
    ["car_wh_w", "car_wh_e", "car_top", "car_cab"],
    highlight=["tw4_e", "zb_s_3"],
    tip="东轮底边吸着路板东沿 —— 红灯停, 绿灯行, 黄灯亮了等一等。",
)
b.step(
    "种街角绿篱: 东南角草坪东缘 2 片绿色三角收边。",
    ["hedge_a", "hedge_b"],
    highlight=["lawn_se_a"],
    tip="路口一角的小绿意 —— 等灯的时候也有得看。",
)

b.finalize(
    model_id="traffic_light_junction_01",
    name="红绿灯路口",
    name_en="Traffic Light Junction 01",
    description=(
        "只用核心九片型的信号灯路口: 与靠'杆'拦车的铁路道口不同, "
        "路口靠'灯'指挥 —— 招牌是两座四层墙环信号灯塔: 每层 4 片墙"
        "合环环环相扣 (塔高 4.0 靠闭环拓扑通过高层检查, 每层接口 4 条"
        "连接互为冗余), 第 2/3/4 层朝路口两面嵌绿/黄/红窗格方信号窗,"
        " 红黄绿自上而下纵列即教科书排布; 两塔对角布置四个方向各看"
        "各的灯; 四向透明斑马线铺满路口, 西北角交警岗亭了望窗正对"
        "路口、侧门朝斑马线、顶戴红色四坡尖顶; 一辆紫色小车停在南"
        "引道停止线前 —— 红灯亮了, 车头压线不越线, 安静等绿灯。"
    ),
    difficulty=3,
    tags=["城市", "交通", "红绿灯", "街景", "进阶"],
    min_pieces=74,
    min_steps=13,
)
