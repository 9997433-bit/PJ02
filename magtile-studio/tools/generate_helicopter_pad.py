#!/usr/bin/env python3
"""生成模型 data/models/helicopter_pad_01.json (楼顶停机坪)。

城市生活主题: 全库第一座楼顶停机坪 —— 三层玻璃门厅办公楼的
屋顶向东西两侧各挑出一排停机坪甲板 (悬挑力矩在预算内, 再由
四片直角三角膝撑锁成刚性节点), 一架小型直升机停在坪心:
透明风挡朝东, 尾梁双端受力搭在尾撑柱顶, 旋翼盘立在舱顶;
坪边透明安全网, 西角风向袋, 楼下玻璃门厅带雨棚, 广场东北角
还有一座四坡通信设备房 —— 城市上空的第 16 个航站!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 大门朝东):
  - 广场 (x 1..5, y 0..4): 方板 x16                              16 片
  - 塔楼 (x 2..4, y 1..3, z 0..3): 每层 8 片围壁 x3 层           24 片
  - 门厅雨棚 (z=1): 透明方板 x2 (单排平挑, 力矩 15<=17.5)        2 片
  - 停机坪 (z=3): 坪心方板 x4 + 东西挑板 x4 + 膝撑 x4            12 片
  - 直升机: 舱壁 x2 + 风挡 + 舱顶 + 尾撑 + 尾梁 + 尾鳍 + 旋翼盘  8 片
  - 安全网 x4 + 风向袋 x1 + 通信设备房 hat4 x4                    9 片
  合计 71 片, 17 个教程步骤, 5 种片形。

物理规则要点 (通过 R1~R8 全部校验):
  - 挑板悬挑预算: 东西挑板成对共铰 (铰链线长 2), 力矩 60x0.5=30
    <= 严格档预算 35; 四片膝撑再把铰链变成刚性节点 (双保险);
  - 尾梁不是悬挑: 西端整边吸舱顶板缝, 东端落在尾撑柱顶,
    双端受力如桥; 旋翼盘重心正压舱顶铰链, 力矩为零;
  - 塔楼三层箱形环层层互锁, 停机坪四边吸满顶层墙顶;
  - 雨棚透明方板单排平挑: 力矩 15 <= 严格档 17.5, 双片拼缝互吸。

用法: python3 tools/generate_helicopter_pad.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

PLAZA = "gray"      # 广场
TOWER = "gray"      # 塔楼
MID = "yellow"      # 塔楼中层
GLASS = "clear"     # 玻璃门厅 / 风挡 / 安全网
PAD_C = "clear"     # 坪心 (白色触地区)
PAD_E = "green"     # 坪边挑板
HELI = "red"        # 直升机
SOCK = "orange"     # 风向袋
BEACON = "red"      # 通信设备房

# =================================================================
# 1. 广场 (z=0): 中带 8 片 + 南北带 8 片
# =================================================================
for x0 in (1, 2, 3, 4):
    for y0 in (1, 2):
        b.flat(f"pz_{x0}_{y0}", x0, y0, 0.0, PLAZA)
for x0 in (1, 2, 3, 4):
    for y0 in (0, 3):
        b.flat(f"pz_{x0}_{y0}", x0, y0, 0.0, PLAZA)

# =================================================================
# 2. 塔楼 (x 2..4, y 1..3): 三层箱形围壁, 底层东面玻璃门厅
# =================================================================
LEVEL_COLOR = {0: TOWER, 1: MID, 2: TOWER}
for lv in (0, 1, 2):
    c = LEVEL_COLOR[lv]
    for x0 in (2, 3):
        b.wall_ns(f"tw_s{lv}_{x0}", x0, 1.0, lv, c)     # 南墙
        b.wall_ns(f"tw_n{lv}_{x0}", x0, 3.0, lv, c)     # 北墙
    for y0 in (1, 2):
        b.wall_ew(f"tw_w{lv}_{y0}", 2.0, y0, lv, c)     # 西墙
        east = GLASS if lv == 0 else c                  # 底层玻璃门厅
        b.wall_ew(f"tw_e{lv}_{y0}", 4.0, y0, lv, east)  # 东墙

# =================================================================
# 3. 门厅雨棚 (z=1): 2 片透明方板从底层东墙顶平挑
# =================================================================
b.flat("awn_0", 4, 1, 1.0, GLASS)
b.flat("awn_1", 4, 2, 1.0, GLASS)

# =================================================================
# 4. 停机坪 (z=3): 坪心 4 片 + 东西挑板 4 片 + 膝撑 4 片
# =================================================================
for x0 in (2, 3):
    for y0 in (1, 2):
        b.flat(f"pad_c_{x0}_{y0}", x0, y0, 3.0, PAD_C)
for y0 in (1, 2):
    b.flat(f"pad_w_{y0}", 1, y0, 3.0, PAD_E)            # 西挑板
    b.flat(f"pad_e_{y0}", 4, y0, 3.0, PAD_E)            # 东挑板
b.place_tri("kb_ws", "right_triangle",
            (2.0, 1.0, 3.0), (1.0, 1.0, 3.0), (2.0, 1.0, 2.0), PAD_E)
b.place_tri("kb_wn", "right_triangle",
            (2.0, 3.0, 3.0), (1.0, 3.0, 3.0), (2.0, 3.0, 2.0), PAD_E)
b.place_tri("kb_es", "right_triangle",
            (4.0, 1.0, 3.0), (5.0, 1.0, 3.0), (4.0, 1.0, 2.0), PAD_E)
b.place_tri("kb_en", "right_triangle",
            (4.0, 3.0, 3.0), (5.0, 3.0, 3.0), (4.0, 3.0, 2.0), PAD_E)

# =================================================================
# 5. 直升机: 舱体 + 尾梁 (双端受力) + 尾鳍 + 旋翼盘
# =================================================================
b.wall_ns("hc_s", 2, 1.0, 3, HELI)                      # 舱壁南
b.wall_ns("hc_n", 2, 2.0, 3, HELI)                      # 舱壁北
b.wall_ew("hc_ws", 3.0, 1, 3, GLASS)                    # 风挡朝东
b.flat("hc_top", 2, 1, 4.0, HELI)                       # 舱顶
b.wall_ew("tail_post", 1.0, 1, 3, HELI)                 # 尾撑柱
b.flat("tail_boom", 1, 1, 4.0, HELI)                    # 尾梁
b.crest_ew("tail_fin", 1.0, 1, 4.0, HELI)               # 尾鳍
b.place_edge("rotor", "hexagon", 4,
             (2.0, 2.0, 4.0), (3.0, 2.0, 4.0), (0.0, 0.0, 1.0), "gray")

# =================================================================
# 6. 安全网 + 风向袋 + 通信设备房
# =================================================================
b.crest_ns("net_s", 3, 1.0, 3.0, GLASS)                 # 南沿安全网
b.crest_ns("net_n", 3, 3.0, 3.0, GLASS)                 # 北沿安全网
b.crest_ew("net_e1", 5.0, 1, 3.0, GLASS)                # 东沿安全网
b.crest_ew("net_e2", 5.0, 2, 3.0, GLASS)
b.crest_ew("windsock", 1.0, 2, 3.0, SOCK)               # 风向袋 (西沿)
BEACON_IDS = b.hat4("beacon", 4, 3, 0.0, BEACON,
                    shape="equilateral_triangle")       # 通信设备房

# =================================================================
# 教程步骤 (17 步)
# =================================================================
b.step(
    "铺广场中带: 8 片灰色方板双列并进 (y 1..3), 这是塔楼的地基。",
    [f"pz_{x0}_{y0}" for x0 in (1, 2, 3, 4) for y0 in (1, 2)],
    tip="方板逐格拼缝互吸 —— 塔楼墙脚全踩在这些缝上。",
)
b.step(
    "补广场南北带: 再铺 8 片, 5x4 广场合拢。",
    [f"pz_{x0}_{y0}" for x0 in (1, 2, 3, 4) for y0 in (0, 3)],
    highlight=["pz_1_1", "pz_4_2"],
    tip="城市街角的一整块场坪 —— 直升机的家就盖在正中。",
)
b.step(
    "塔楼一层·南北墙: 4 片灰色方墙立在广场拼缝上。",
    ["tw_s0_2", "tw_s0_3", "tw_n0_2", "tw_n0_3"],
    highlight=["pz_2_1", "pz_3_2"],
    tip="墙脚踩缝, 底边同时吸住两片广场板 —— 双铰链保险。",
)
b.step(
    "塔楼一层·西墙与玻璃门厅: 西面 2 片方墙, 东面 2 片透明玻璃门。",
    ["tw_w0_1", "tw_w0_2", "tw_e0_1", "tw_e0_2"],
    highlight=["tw_s0_2", "tw_n0_2"],
    tip="拐角竖边互吸, 一层箱形合龙 —— 玻璃门厅朝东迎客。",
)
b.step(
    "挑门厅雨棚: 2 片透明方板从玻璃门顶向东平挑。",
    ["awn_0", "awn_1"],
    highlight=["tw_e0_1", "tw_e0_2"],
    tip="单片力矩 15 <= 严格档预算 17.5, 双片拼缝互吸 —— 雨天不湿身。",
)
b.step(
    "塔楼二层·南北墙: 黄色方墙对缝叠上一层墙顶。",
    ["tw_s1_2", "tw_s1_3", "tw_n1_2", "tw_n1_3"],
    highlight=["tw_s0_2", "tw_n0_3"],
    tip="上下层严格对缝 —— 荷载顺墙身直落地基。",
)
b.step(
    "塔楼二层·东西墙: 再立 4 片, 二层箱形合龙。",
    ["tw_w1_1", "tw_w1_2", "tw_e1_1", "tw_e1_2"],
    highlight=["tw_s1_2"],
    tip="黄色办公层 —— 窗后是空管值班室。",
)
b.step(
    "塔楼三层·南北墙: 灰色方墙再叠一层。",
    ["tw_s2_2", "tw_s2_3", "tw_n2_2", "tw_n2_3"],
    highlight=["tw_s1_2", "tw_n1_3"],
    tip="第三层是设备层 —— 电梯机房与消防水箱都在这里。",
)
b.step(
    "塔楼三层·东西墙: 4 片合龙, 塔楼封顶前的最后一圈。",
    ["tw_w2_1", "tw_w2_2", "tw_e2_1", "tw_e2_2"],
    highlight=["tw_s2_2"],
    tip="三层箱形环层层互锁 —— 楼顶要扛住一整座停机坪。",
)
b.step(
    "铺坪心: 4 片白色方板四边吸满三层墙顶 —— 这是触地区。",
    ["pad_c_2_1", "pad_c_2_2", "pad_c_3_1", "pad_c_3_2"],
    highlight=["tw_s2_2", "tw_e2_1"],
    tip="每片都要听到与墙顶的咔哒声再松手。",
)
b.step(
    "挑东西坪板: 绿色挑板向两翼各挑 2 片, 停机坪扩成 4x2。",
    ["pad_w_1", "pad_w_2", "pad_e_1", "pad_e_2"],
    highlight=["pad_c_2_1", "pad_c_3_1"],
    tip="成对共铰: 铰链线长 2, 力矩 30 <= 严格档预算 35。",
)
b.step(
    "锁四片膝撑: 直角三角形横边托挑板、竖边吸墙角, 悬挑变刚性节点。",
    ["kb_ws", "kb_wn", "kb_es", "kb_en"],
    highlight=["pad_w_1", "pad_e_2"],
    tip="膝撑是高空挑板的保险绳 —— 四角都要锁上。",
)
b.step(
    "立坪边安全网: 4 片透明三角立在坪沿 —— 高空作业规矩第一条。",
    ["net_s", "net_n", "net_e1", "net_e2"],
    highlight=["pad_e_1", "pad_c_3_1"],
    tip="透明网不挡视线, 底边整边吸坪板沿边。",
)
b.step(
    "落直升机舱体: 2 片红色舱壁踩坪缝立起, 透明风挡朝东。",
    ["hc_s", "hc_n", "hc_ws"],
    highlight=["pad_c_2_1", "pad_c_3_1"],
    tip="舱壁就是滑橇 —— 稳稳踩在触地区正中。",
)
b.step(
    "盖舱顶接尾梁: 舱顶压住舱壁, 尾撑柱立坪西沿, 尾梁西端吸"
    "舱顶板缝、东端落尾撑柱顶 —— 双端受力如桥。",
    ["hc_top", "tail_post", "tail_boom"],
    highlight=["hc_s", "hc_ws"],
    tip="尾梁不是悬挑 —— 两端都有依托才叫工程。",
)
b.step(
    "装尾鳍与旋翼盘: 尾鳍立尾梁末端, 六边形旋翼盘立上舱顶。",
    ["tail_fin", "rotor"],
    highlight=["tail_boom", "hc_top"],
    tip="旋翼盘重心正压舱顶铰链, 力矩为零 —— 随时可以启动。",
)
b.step(
    "风向袋与通信设备房: 坪西沿插橙色风向袋, 广场东北角扣 4 片"
    "四坡设备房 —— 楼顶停机坪正式启用!",
    ["windsock"] + BEACON_IDS,
    highlight=["pad_w_2", "pz_4_3"],
    tip="风向袋告诉飞行员往哪边压杆 —— 塔台呼叫, 可以降落!",
)

b.finalize(
    model_id="helicopter_pad_01",
    name="楼顶停机坪",
    name_en="Rooftop Helipad 01",
    description=(
        "全库第一座楼顶停机坪: 三层玻璃门厅办公楼层层箱形互锁, 楼顶向"
        "东西两翼挑出停机坪甲板 (成对共铰力矩 30 <= 严格档 35, 四片直角"
        "三角膝撑再锁成刚性节点); 坪心停着小型直升机 —— 尾梁双端受力"
        "搭在尾撑柱顶, 六边形旋翼盘立在舱顶铰链正上; 透明安全网、风向袋"
        "与四坡通信设备房点齐高空作业细节 —— 塔台呼叫, 可以降落!"
    ),
    difficulty=3,
    tags=["城市生活", "建筑", "直升机", "停机坪", "进阶"],
    min_pieces=65,
    min_steps=17,
)
