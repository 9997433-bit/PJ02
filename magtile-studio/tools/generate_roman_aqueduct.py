#!/usr/bin/env python3
"""生成模型 data/models/roman_aqueduct_01.json (罗马水道桥)。

第二批模型 ⑦: 古代工程主题 —— 仿加尔水道桥 (Pont du Gard) 的
双层石砌拱廊: 下层 4 座高墩跨 3 个大拱洞, 上层小拱廊压顶,
最顶上是一条真正能"通水"的 U 形水槽, 两端封头、垛口点缀。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 石基: 4 片方基座 + 3 片连接板, 连成 10 格长的整条地梁     7 片
  - 下层拱廊 (z 0..2): 4 座双壁石墩, 每墩 4 片立墙            16 片
  - 底角斜撑: 两端石墩外脚各 1 根直角三角斜撑 (防倾覆)         4 片
  - 下层桥面 (z=2): 墩顶方板 x4 + 跨洞长板 x3                  7 片
  - 上层拱廊 (z 2..3): 4 座矮墩 (8 片立墙) + 6 片跨洞横楣     14 片
  - 上层桥面 (z=3): 方板 x4 + 长板 x3                          7 片
  - 水槽 (z 3..4): 南北槽壁各 7 片 + 两端封头 2 片            16 片
  - 垛口: 水槽沿口 8 片等边三角装饰                             8 片
  合计 79 片, 18 个教程步骤, 4 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 每座石墩是"双壁 + 底部地梁 + 顶部桥面"的闭合箱形环, 冗余充足;
  - 上层横楣底边整边吸跨洞长板长边 (都是 2 格长), 两端竖边再吸
    矮墩竖边 —— 一片横楣三边受力;
  - 水槽壁片宽与其下桥面板逐段等宽 (方对方、长对长), 保证整边吸合。

用法: python3 tools/generate_roman_aqueduct.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

PIERS = (0, 3, 6, 9)      # 石墩西端 x 坐标 (每墩宽 1)
GAPS = (1, 4, 7)          # 拱洞西端 x 坐标 (每洞宽 2)

# =================================================================
# 1. 石基地梁: 墩位方基座 + 洞下连接板, 连成 10 格整条
# =================================================================
for x in PIERS:
    b.flat(f"base_{x}", x, 0, 0.0, "gray")
for x in GAPS:
    b.flat_rect(f"base_g_{x}", x, 0, 0.0, "gray")

# =================================================================
# 2. 下层拱廊 (z 0..2): 每墩南北双壁, 各叠 2 层
# =================================================================
for x in PIERS:
    b.wall_ns(f"p1s_{x}", x, 0.0, 0, "orange")   # 南壁下层
    b.wall_ns(f"p1n_{x}", x, 1.0, 0, "orange")   # 北壁下层
    b.wall_ns(f"p2s_{x}", x, 0.0, 1, "yellow")   # 南壁上层
    b.wall_ns(f"p2n_{x}", x, 1.0, 1, "yellow")   # 北壁上层

# =================================================================
# 3. 底角斜撑: 两端石墩外脚 4 根直角三角形 (防倾覆分水尖)
# =================================================================
b.brace("but_ws", (0.0, 0.0, 0.0), "-x", "gray")
b.brace("but_wn", (0.0, 1.0, 0.0), "-x", "gray")
b.brace("but_es", (10.0, 0.0, 0.0), "+x", "gray")
b.brace("but_en", (10.0, 1.0, 0.0), "+x", "gray")

# =================================================================
# 4. 下层桥面 (z=2): 墩顶方板 + 跨洞长板, 铺通全桥
# =================================================================
for x in PIERS:
    b.flat(f"d1_{x}", x, 0, 2.0, "gray")
for x in GAPS:
    b.flat_rect(f"d1_g_{x}", x, 0, 2.0, "gray")

# =================================================================
# 5. 上层拱廊 (z 2..3): 矮墩双壁 + 跨洞横楣 (小拱层)
# =================================================================
for x in PIERS:
    b.wall_ns(f"u_s_{x}", x, 0.0, 2, "orange")
    b.wall_ns(f"u_n_{x}", x, 1.0, 2, "orange")
for x in GAPS:
    b.lintel_ns(f"lin_s_{x}", x, 0.0, 2, "yellow")
    b.lintel_ns(f"lin_n_{x}", x, 1.0, 2, "yellow")

# =================================================================
# 6. 上层桥面 (z=3): 与下层同款, 方板压墩、长板压横楣
# =================================================================
for x in PIERS:
    b.flat(f"d2_{x}", x, 0, 3.0, "gray")
for x in GAPS:
    b.flat_rect(f"d2_g_{x}", x, 0, 3.0, "gray")

# =================================================================
# 7. 水槽 (z 3..4): 南北槽壁逐段等宽吸桥面, 两端封头
# =================================================================
for x in PIERS:
    b.wall_ns(f"ch_s_{x}", x, 0.0, 3, "cyan")
    b.wall_ns(f"ch_n_{x}", x, 1.0, 3, "cyan")
for x in GAPS:
    b.lintel_ns(f"ch_s_g_{x}", x, 0.0, 3, "cyan")
    b.lintel_ns(f"ch_n_g_{x}", x, 1.0, 3, "cyan")
b.wall_ew("cap_w", 0.0, 0, 3, "blue")     # 西端封头
b.wall_ew("cap_e", 10.0, 0, 3, "blue")    # 东端封头

# =================================================================
# 8. 垛口: 水槽沿口 8 片等边三角装饰 (墩位正上方)
# =================================================================
for x in PIERS:
    b.crest_ns(f"cr_s_{x}", x, 0.0, 4.0, "red")
for x in PIERS:
    b.crest_ns(f"cr_n_{x}", x, 1.0, 4.0, "red")

# =================================================================
# 教程步骤 (18 步)
# =================================================================
b.step(
    "铺设石基地梁: 方基座与长板交替平铺 (方-长-方-长-方-长-方), "
    "连成 10 格长的整条地梁, 方基座落在 x = 0/3/6/9 (石墩落点)。",
    ["base_0", "base_g_1", "base_3", "base_g_4", "base_6", "base_g_7", "base_9"],
    tip="长板短边与方基座边整边吸合, 铺完地梁应笔直不断线; "
        "4 片方基座间距均为 2 格 —— 那是 3 个大拱洞的位置。",
)
b.step(
    "竖立石墩南壁下层: 4 片橙色正方形立在各基座南沿 (y=0), "
    "底边吸基座边缘。",
    [f"p1s_{x}" for x in PIERS],
    highlight=["base_0"],
    tip="4 面墙都立在同一条南沿直线上, 从侧面看等距如琴柱。",
)
b.step(
    "竖立石墩北壁下层: 4 片橙色正方形立在各基座北沿 (y=1), 与南壁平行。",
    [f"p1n_{x}" for x in PIERS],
    highlight=["p1s_0"],
    tip="每座石墩都是南北双壁 —— 双壁墩远比单壁结实。",
)
b.step(
    "安装底角斜撑: 两端石墩外脚各 2 根灰色直角三角形, "
    "竖直边吸墩壁竖边、水平边落地。",
    ["but_ws", "but_wn", "but_es", "but_en"],
    highlight=["p1s_0", "p1s_9"],
    tip="像大坝的分水尖: 两条直角边都吸牢, 桥头再也推不倒。",
)
b.step(
    "石墩南壁加高: 4 片黄色正方形叠上南壁, 墩高到 2 层。",
    [f"p2s_{x}" for x in PIERS],
    highlight=["p1s_0"],
    tip="上下两片墙的横边要完全对齐吸合, 不能错缝。",
)
b.step(
    "石墩北壁加高: 4 片黄色正方形叠上北壁, 与南壁同高。",
    [f"p2n_{x}" for x in PIERS],
    highlight=["p2s_0"],
    tip="8 面墩壁全部到位, 大拱洞的轮廓已经出现。",
)
b.step(
    "铺下层桥面墩顶段: 4 片灰色方板逐一压在各石墩顶上, "
    "南北两边分别吸住双壁顶边。",
    [f"d1_{x}" for x in PIERS],
    highlight=["p2s_0", "p2n_0"],
    tip="方板一压, 每座石墩就变成闭合的箱形环 —— 这是罗马工程的秘诀。",
)
b.step(
    "铺下层桥面跨洞段: 3 片灰色长板架过 3 个大拱洞, 短边吸两侧方板。",
    [f"d1_g_{x}" for x in GAPS],
    highlight=["d1_0", "d1_3"],
    tip="长板两端都有方板托住, 跨洞不悬空。",
)
b.step(
    "竖立上层矮墩南壁: 4 片橙色正方形立在下层桥面南沿, 与下层石墩正对。",
    [f"u_s_{x}" for x in PIERS],
    highlight=["d1_0"],
    tip="上下墩必须对齐成一根通柱, 力才能直传到地梁。",
)
b.step(
    "竖立上层矮墩北壁: 4 片橙色正方形与南壁镜像。",
    [f"u_n_{x}" for x in PIERS],
    highlight=["u_s_0"],
    tip="上层拱廊比下层矮一半 —— 这正是双层水道桥的经典比例。",
)
b.step(
    "安装南侧横楣: 3 片黄色长方形竖立跨过上层南侧洞口, "
    "底边整边吸跨洞长板长边、两端竖边吸矮墩竖边。",
    [f"lin_s_{x}" for x in GAPS],
    highlight=["u_s_0", "u_s_3"],
    tip="一片横楣三边受力: 底边 + 两竖边, 这就是小拱层的过梁。",
)
b.step(
    "安装北侧横楣: 3 片黄色长方形与南侧镜像, 小拱层合拢。",
    [f"lin_n_{x}" for x in GAPS],
    highlight=["lin_s_1"],
    tip="从侧面看: 下层 3 个大洞、上层 3 道过梁, 层次分明。",
)
b.step(
    "铺上层桥面墩顶段: 4 片灰色方板压在上层矮墩顶上。",
    [f"d2_{x}" for x in PIERS],
    highlight=["u_s_0", "u_n_0"],
    tip="与下层做法相同: 方板压墩, 箱形环再锁一层。",
)
b.step(
    "铺上层桥面跨洞段: 3 片灰色长板压在横楣顶边上, 桥面贯通。",
    [f"d2_g_{x}" for x in GAPS],
    highlight=["d2_0", "d2_3"],
    tip="长板长边与横楣顶边整边吸合, 上层桥面就是水槽的槽底。",
)
b.step(
    "竖立水槽南壁: 沿桥面南沿立 4 片方形 + 3 片长形青色槽壁, "
    "每片底边与其正下方桥面板等宽吸合。",
    [f"ch_s_{x}" for x in PIERS] + [f"ch_s_g_{x}" for x in GAPS],
    highlight=["d2_0"],
    tip="方对方、长对长 —— 槽壁分段与桥面板一一对应才能整边吸牢。",
)
b.step(
    "竖立水槽北壁: 7 片青色槽壁与南壁镜像, 水槽成 U 形。",
    [f"ch_n_{x}" for x in PIERS] + [f"ch_n_g_{x}" for x in GAPS],
    highlight=["ch_s_0"],
    tip="从桥头望进去是一条笔直的 U 形水道 —— 罗马城的自来水管。",
)
b.step(
    "安装两端封头: 2 片蓝色正方形竖立堵住水槽两端槽口, "
    "底边吸桥面、两竖边吸槽壁。",
    ["cap_w", "cap_e"],
    highlight=["ch_s_0", "ch_n_9"],
    tip="封头装好, U 形水槽变成一条闭合水道。",
)
b.step(
    "安装垛口: 槽沿墩位正上方立 8 片红色等边三角垛口, 水道桥完工!",
    [f"cr_s_{x}" for x in PIERS] + [f"cr_n_{x}" for x in PIERS],
    highlight=["cap_w"],
    tip="放一颗弹珠从西端封头内侧滚向东端, 检验你的水道是否笔直。",
)

b.finalize(
    model_id="roman_aqueduct_01",
    name="罗马水道桥",
    name_en="Roman Aqueduct 01",
    description=(
        "仿加尔水道桥的双层石砌拱廊: 下层 4 座双壁石墩跨出 3 个大拱洞, 上层"
        "矮墩与横楣组成小拱层, 顶上是一条能通水的 U 形水槽, 两端封头、垛口"
        "点缀 —— 每座石墩都是地梁、双壁、桥面锁成的箱形环, 结实得像真石头。"
    ),
    difficulty=4,
    tags=["古代工程", "桥梁", "双层结构", "进阶"],
    min_pieces=75,
    min_steps=18,
)
