#!/usr/bin/env python3
"""生成模型 data/models/marble_run_spiral_01.json (弹珠螺旋滑道)。

滚珠乐园系列第二作 (主技法 T08 滚珠轨道集成 + T12 层叠 + T14 斜撑):
与 ball_run_tower_01 (方塔外挂东西镜像双轨) 的结构逻辑刻意区分 ——
本模型是 "单珠盘旋": 一条连续轨道绕四层高塔顺时针盘旋 3/4 圈,
弹珠转过三个直角弯后从最后一段冲线坡道射进南端接珠池。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 塔基广场 2x2 + 四角直角三角斜撑 (T14, 双边吸合)          4 + 4 片
  - 中央高塔: 2x2 占地四层墙 (全库最高发球台 z=4)            32 片
  - 塔顶发球台 2x2 + 七片围栏 (北侧双塔尖, 东侧留出珠口)      4 + 7 片
  - 螺旋轨道: 三段 30 度坡道 + 三块转角平台 (各配一片台下
    斜撑) + 阶梯桥墩 (3/2/1 层) + 六片转向挡珠三角,
    最后一段冲线坡道落地                                     22 片
  - 南端接珠池: 2 片池底 + 四面围墙 + 六边形靶标               7 片
  合计 80 片, 18 个教程步骤。

滚珠动线: 发球台 (z=4) --东坡道--> 转角台 A (z=3) 右转
  --南坡道--> 转角台 B (z=2) 右转 --西坡道--> 转角台 C (z=1)
  右转 --南向冲线坡道--> 落地滚进接珠池撞响六边形靶标。

物理规则要点 (通过 R1~R8 全部校验 + R9 抖动仿真):
  - 每段坡道顶边整边吸平台沿口, 坡尾由阶梯桥墩顶边接住,
    坡道-桥墩-转角台三件互吸成三角刚性节点;
  - 每块转角台下挂一片直角三角斜撑 (T14, 双边吸合): 水平直角边
    吸台底侧缘, 竖直直角边吸桥墩侧竖边 —— 转角台与桥墩锁成门式
    框架环, 台面不再是单铰链外挑悬臂 (旧几何绕桥墩顶铰链的力矩
    34.5 g·单位贴着 strict 弱磁档抗弯预算 35.0 的边, ±1.5mm/±2°
    放置误差即越限, 见 docs/PHYSICS_RULES.md R6/R9 节);
  - 塔基四角直角三角斜撑双边吸合 (广场边 + 塔墙竖边), 抗侧向剪力;
  - 冲线坡道坡尾自然落地, 接珠池全部接地。

用法: python3 tools/generate_marble_run_spiral.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import SQ3, ModelBuilder  # noqa: E402

b = ModelBuilder()

# ---- 关键坐标 (螺旋每绕四分之一圈下降一层) -----------------------
XA = 2 + SQ3          # 转角台 A 西缘 = 东坡道坡尾 x = 3.732051
YB = -SQ3             # 转角台 B 北缘 = 南坡道坡尾 y = -1.732051
XC = XA - SQ3         # 转角台 C 东缘 = 西坡道坡尾 x = 2.0
Y_POND = YB - 1 - SQ3  # 冲线坡道坡尾 y = -4.464102

# =================================================================
# 1. 塔基广场 2x2 + 四角斜撑 (T14: 广场边与塔墙竖边双边吸合)
# =================================================================
for j in range(2):
    for i in range(2):
        b.flat(f"g_{i}_{j}", i, j, 0.0, "gray" if (i + j) % 2 == 0 else "green")

# 斜撑呈风车状分布: 每根竖直角边吸住塔角竖边, 水平直角边贴地外伸
BRACES = [
    ("br_sw", (0.0, 0.0, 0.0), "-x"),
    ("br_se", (2.0, 0.0, 0.0), "-y"),
    ("br_ne", (2.0, 2.0, 0.0), "+x"),
    ("br_nw", (0.0, 2.0, 0.0), "+y"),
]

# =================================================================
# 2. 中央高塔: 2x2 占地四层墙 (逐层绿青交替)
# =================================================================
LEVEL_COLOR = {0: "green", 1: "cyan", 2: "green", 3: "cyan"}
for lv in range(4):
    c = LEVEL_COLOR[lv]
    for i in range(2):
        b.wall_ns(f"tw{lv}_s_{i}", i, 0.0, lv, c)
    for j in range(2):
        b.wall_ew(f"tw{lv}_e_{j}", 2.0, j, lv, c)
    for i in range(2):
        b.wall_ns(f"tw{lv}_n_{i}", i, 2.0, lv, c)
    for j in range(2):
        b.wall_ew(f"tw{lv}_w_{j}", 0.0, j, lv, c)

for tid, corner, hdir in BRACES:
    b.brace(tid, corner, hdir, "purple")

# 塔顶发球台 (z=4)
for j in range(2):
    for i in range(2):
        b.flat(f"plat_{i}_{j}", i, j, 4.0, "yellow")

# 发球台围栏: 北缘双塔尖 (等腰), 南/西各两片红三角,
# 东缘只拦 y1..2 —— y0..1 是螺旋轨道唯一的出珠口
b.spire_ns("prail_n_0", 0, 2.0, 4.0, "purple")
b.spire_ns("prail_n_1", 1, 2.0, 4.0, "purple")
b.crest_ns("prail_s_0", 0, 0.0, 4.0, "red")
b.crest_ns("prail_s_1", 1, 0.0, 4.0, "red")
b.crest_ew("prail_w_0", 0.0, 0, 4.0, "red")
b.crest_ew("prail_w_1", 0.0, 1, 4.0, "red")
b.crest_ew("prail_e", 2.0, 1, 4.0, "red")

# =================================================================
# 3. 螺旋轨道第 1 段: 东坡道 z4->z3, 三层阶梯桥墩, 转角台 A
# =================================================================
# 台下斜撑 (T14): 直角顶点顶住转角台底角, 水平直角边吸台底侧缘,
# 竖直直角边吸桥墩侧竖边 —— 转角台-斜撑-桥墩锁成门式框架环,
# 剪断桥墩顶铰链后台面仍有支撑路径, 悬臂力矩分析自然消失
# (旧几何该悬臂 34.5 g·单位, 贴着 strict 档抗弯预算 35.0 的边)。
for lv in range(3):
    b.wall_ew(f"pierA_{lv}", XA, 0, lv, "gray")
b.ramp("ramp_1", "+x", 2.0, 0, 4.0, "orange")
b.flat("corner_a", XA, 0, 3.0, "yellow")
b.place_tri("braceA", "right_triangle",
            (XA, 0.0, 3.0), (XA + 1, 0.0, 3.0), (XA, 0.0, 2.0), "purple")
b.crest_ew("railA_out", XA + 1, 0, 3.0, "red")   # 外缘挡珠
b.crest_ns("railA_n", XA, 1.0, 3.0, "red")       # 北缘挡珠, 逼珠南转

# =================================================================
# 4. 第 2 段: 南坡道 z3->z2, 双层桥墩, 转角台 B
# =================================================================
for lv in range(2):
    b.wall_ns(f"pierB_{lv}", XA, YB, lv, "gray")
b.ramp("ramp_2", "-y", 0.0, XA, 3.0, "orange")
b.flat("corner_b", XA, YB - 1, 2.0, "yellow")
b.place_tri("braceB", "right_triangle",
            (XA, YB, 2.0), (XA, YB - 1, 2.0), (XA, YB, 1.0), "purple")
b.crest_ns("railB_out", XA, YB - 1, 2.0, "red")      # 南缘挡珠, 逼珠西转
b.crest_ew("railB_e", XA + 1, YB - 1, 2.0, "red")    # 东缘防弹跳

# =================================================================
# 5. 第 3 段: 西坡道 z2->z1, 单层桥墩, 转角台 C
# =================================================================
b.wall_ew("pierC_0", XC, YB - 1, 0, "gray")
b.ramp("ramp_3", "-x", XA, YB - 1, 2.0, "orange")
b.flat("corner_c", XC - 1, YB - 1, 1.0, "yellow")
b.place_tri("braceC", "right_triangle",
            (XC, YB, 1.0), (XC - 1, YB, 1.0), (XC, YB, 0.0), "purple")
b.crest_ew("railC_out", XC - 1, YB - 1, 1.0, "red")  # 西缘挡珠, 逼珠南转
b.crest_ns("railC_n", XC - 1, YB, 1.0, "red")        # 北缘防弹跳

# =================================================================
# 6. 冲线坡道 z1->落地 + 南端接珠池
# =================================================================
b.ramp("ramp_4", "-y", YB - 1, XC - 1, 1.0, "orange")

b.flat("pond_e", XC - 1, Y_POND - 1, 0.0, "blue")    # 迎珠池底
b.flat("pond_w", XC - 2, Y_POND - 1, 0.0, "blue")
b.wall_ns("pondw_s_e", XC - 1, Y_POND - 1, 0, "cyan")
b.wall_ns("pondw_s_w", XC - 2, Y_POND - 1, 0, "cyan")
b.wall_ew("pondw_w", XC - 2, Y_POND - 1, 0, "cyan")
b.wall_ew("pondw_e", XC, Y_POND - 1, 0, "cyan")
b.add("pond_hex", "hexagon", (XC - 0.5, Y_POND - 1, 1.866025), (90, 0, 0), "yellow")

# =================================================================
# 教程步骤 (18 步): 轨道按 "桥墩 -> 坡道 -> 转角台" 整段成组安装
# =================================================================
b.step(
    "铺设塔基广场: 桌面中央平放 2x2 共 4 片正方形, 相邻边互相吸合。",
    [f"g_{i}_{j}" for j in range(2) for i in range(2)],
    tip="塔的东、南两侧要留足空地: 螺旋轨道要绕塔盘旋大半圈才落地。",
)
b.step(
    "高塔第 1 层: 沿广场四周立 8 片绿色正方形, 底边吸广场边, 转角竖边两两互吸。",
    [f"tw0_{s}_{k}" for s in ("s", "e", "n", "w") for k in range(2)],
    highlight=[f"g_{i}_{j}" for j in range(2) for i in range(2)],
    tip="四个转角都要吸牢; 合围完成后轻推塔身应整体联动。",
)
b.step(
    "安装塔基斜撑: 四角各装 1 片紫色直角三角形, 竖直角边吸塔角竖边, "
    "水平直角边贴地外伸, 呈风车状分布。",
    [tid for tid, _, _ in BRACES],
    highlight=["tw0_s_0", "tw0_e_0", "tw0_n_1", "tw0_w_1"],
    tip="斜撑必须两条直角边同时吸合才起作用 —— 这座塔有四层高, 全靠它们抗侧撞。",
)
b.step(
    "高塔第 2 层: 在第 1 层墙顶再立 8 片青色正方形, 上下边完整贴合。",
    [f"tw1_{s}_{k}" for s in ("s", "e", "n", "w") for k in range(2)],
    highlight=["tw0_s_0", "tw0_e_0"],
    tip="第二层与第一层完全对齐, 磁条整边贴合吸力才最强。",
)
b.step(
    "高塔第 3 层: 再向上立 8 片绿色正方形。",
    [f"tw2_{s}_{k}" for s in ("s", "e", "n", "w") for k in range(2)],
    highlight=["tw1_s_0", "tw1_e_0"],
    tip="塔越高越要轻放: 一手扶住下层塔身, 另一手放片。",
)
b.step(
    "高塔第 4 层: 立最后 8 片青色正方形, 塔身升到四层 —— 这是全库最高的发球塔。",
    [f"tw3_{s}_{k}" for s in ("s", "e", "n", "w") for k in range(2)],
    highlight=["tw2_s_0", "tw2_e_0"],
    tip="第四层放完先环视四角: 任何一角没吸牢都要立刻扶正。",
)
b.step(
    "盖上发球台: 塔顶平铺 4 片黄色正方形, 四周边缘都吸在第 4 层墙顶上。",
    ["plat_0_0", "plat_1_0", "plat_0_1", "plat_1_1"],
    highlight=["tw3_s_0", "tw3_n_0", "tw3_w_0", "tw3_e_0"],
    tip="发球台就是赛道起点 —— 弹珠将从 z=4 的高度一路盘旋到地面。",
)
b.step(
    "安装发球台围栏: 北缘立 2 根紫色高塔尖, 南缘与西缘各 2 片红三角, "
    "东缘只拦北半格 —— 空出的东南缺口就是螺旋轨道的出珠口。",
    ["prail_n_0", "prail_n_1", "prail_s_0", "prail_s_1",
     "prail_w_0", "prail_w_1", "prail_e"],
    highlight=["plat_1_0", "plat_0_1"],
    tip="只留一个出珠口: 弹珠没有别的路可走, 必然滑进螺旋轨道。",
)
b.step(
    "轨道第 1 段 (整段成组安装): 塔东侧立三层灰色阶梯桥墩, 橙色坡道顶边整边"
    "吸在发球台东缘出珠口, 坡尾搭上墩顶, 铺黄色转角台 A 压住墩顶与坡尾, "
    "再在台底南缘挂 1 片紫色直角三角斜撑: 水平直角边吸台底边, 竖直直角边吸墩身侧边。",
    ["pierA_0", "pierA_1", "pierA_2", "ramp_1", "corner_a", "braceA"],
    highlight=["plat_1_0", "tw3_e_0"],
    tip="坡道-桥墩-转角台三件互相吸住才算装好; 台下斜撑给转角台加上第二条支撑路径, "
        "弹珠反复冲撞也不松。",
)
b.step(
    "转角台 A 挡珠: 外缘与北缘各装 1 片红色挡珠三角, 逼弹珠向南拐进第 2 段。",
    ["railA_out", "railA_n"],
    highlight=["corner_a"],
    tip="挡珠三角立在弹珠冲来的方向, 弹珠撞上它就会拐弯 —— 这是螺旋的第一个直角弯。",
)
b.step(
    "轨道第 2 段: 塔东南立双层桥墩, 南向坡道从转角台 A 南缘下探, "
    "铺转角台 B 压住墩顶与坡尾, 台底西缘再挂 1 片紫色直角三角斜撑吸牢墩身侧边。",
    ["pierB_0", "pierB_1", "ramp_2", "corner_b", "braceB"],
    highlight=["corner_a", "pierA_2"],
    tip="仍是桥墩-坡道-转角台三件互吸加台下斜撑; 螺旋每转过四分之一圈就下降一层。",
)
b.step(
    "转角台 B 挡珠: 南缘与东缘各装 1 片红色挡珠三角, 逼弹珠向西拐 —— 第二个直角弯。",
    ["railB_out", "railB_e"],
    highlight=["corner_b"],
    tip="装完可以先用手指模拟弹珠走一遍: 东来 -> 南下 -> 西拐。",
)
b.step(
    "轨道第 3 段: 塔正南立单层桥墩, 西向坡道从转角台 B 西缘下探, 铺转角台 C, "
    "台底北缘挂上最后 1 片紫色直角三角斜撑, 竖直角边一直吸到落地桥墩的侧边。",
    ["pierC_0", "ramp_3", "corner_c", "braceC"],
    highlight=["corner_b", "pierB_1"],
    tip="轨道已绕塔盘旋了半圈多; 转角台 C 离地只剩一层高。",
)
b.step(
    "转角台 C 挡珠: 西缘与北缘各装 1 片红色挡珠三角, 逼弹珠向南冲线 —— 最后一个弯。",
    ["railC_out", "railC_n"],
    highlight=["corner_c"],
    tip="三个直角弯全部就位, 弹珠的盘旋路线已经完整闭合。",
)
b.step(
    "安装冲线坡道: 最后一片橙色坡道从转角台 C 南缘直落地面, 坡尾自然贴地, "
    "不需要任何支撑。",
    ["ramp_4"],
    highlight=["corner_c", "railC_out"],
    tip="顶边先整边吸住台缘再松手; 弹珠将沿它冲出赛道终点。",
)
b.step(
    "铺设接珠池底: 冲线坡道坡尾南侧平铺 2 片蓝色正方形, 东片北缘恰好吸住坡尾。",
    ["pond_e", "pond_w"],
    highlight=["ramp_4"],
    tip="池底与坡尾整边贴合, 弹珠落地不弹跳、直接滚进池子。",
)
b.step(
    "竖起接珠池围墙: 南面 2 片、东西各 1 片青色矮墙, 北面敞开迎接冲线弹珠。",
    ["pondw_s_e", "pondw_s_w", "pondw_w", "pondw_e"],
    highlight=["pond_e", "pond_w"],
    tip="围墙底边吸池底边缘; 三面围合后弹珠冲进来就跑不掉了。",
)
b.step(
    "挂上六边形靶标: 立在南墙顶上正对冲线方向 —— 弹珠螺旋滑道完工, 放珠开滑!",
    ["pond_hex"],
    highlight=["pondw_s_e", "pondw_s_w"],
    tip="从发球台放珠: 东出 -> 南拐 -> 西拐 -> 南冲, 听弹珠撞响靶标才算通关。",
)

b.finalize(
    model_id="marble_run_spiral_01",
    name="弹珠螺旋滑道",
    name_en="Marble Spiral Slide 01",
    description=(
        "单珠盘旋弹珠机: 一条连续轨道绕四层高塔顺时针盘旋 3/4 圈, 每段 30 度"
        "坡道顶边整边吸平台沿口、坡尾由阶梯桥墩接住, 弹珠从 z=4 的发球台出发, "
        "转过三个直角弯后沿冲线坡道射进接珠池撞响六边形靶标。每块转角台下的"
        "直角三角斜撑把台面与桥墩锁成门式框架, 塔基四角的直角三角斜撑双边"
        "吸合, 让全库最高的发球塔抗得住反复开赛的碰撞。"
    ),
    difficulty=4,
    tags=["滚珠", "轨道", "螺旋", "滚珠乐园", "挑战"],
    min_pieces=65,
    min_steps=16,
)
