#!/usr/bin/env python3
"""生成模型 data/models/canal_lock_01.json (运河船闸)。

内容批 B 2/5: 全库第一座运河船闸 —— 与水电站大坝 (线性阶梯坝体)
刻意错开: 本作的主角是"两级水位差"本身 —— 上游水面铺在箱形高台
的顶上 (高一整层), 下游水面贴地, 中间的闸室里一条橙色驳船正等着
水位上涨; 上游闸门双片灰墙紧闭顶住高水位, 下游闸门两扇绿叶已经
拉开贴在闸墙外侧; 北岸控制塔借用高台北墙合环 (共墙技法), 二层
窗格方了望窗正对闸室 —— 全库唯一的"高低双水位 + 开闭双闸门"。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 运河沿 x 向东流):
  - 南北河岸 (y [0,1] / [3,4], x [0,6]): 单位方板 x12          12 片
  - 下游水面 (x [0,2], y [1,3], z=0): 蓝色方板 x4               4 片
  - 闸室水面 (x [2,4], y [1,3], z=0): 蓝色 x3 + 驳船底 x1       4 片
  - 驳船: 清色驾驶舱 + 红色桅旗 (骑水面拼缝)                    2 片
  - 闸室高墙 (y=1 / y=3, x [2,4], z 0..1): 灰墙 x4              4 片
  - 下游闸门 (已开, y=1 / y=3, x [1,2]): 绿叶 x2                2 片
  - 上游高水位池 (x [4,6], y [1,3]): 箱形墙环 x8 (西侧两片即
    紧闭的上游闸门) + 顶面蓝色水板 x4                          12 片
  - 控制塔 (x [4,5], y [3,4]): 借高台北墙合环 x3 + 二层环 x4 +
    压顶 + 塔旗                                                  9 片
  - 系船柱 x2: 黄色等边三角骑岸线拼缝                            2 片
  合计 51 片, 12 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 上游水面是"铺在墙顶上的地面": 箱形墙环四角竖边互咬闭环,
    四片水板每片两条外边整边压墙顶、两条内边彼此互吸, 墙-水面
    锁成箱形闭环;
  - 控制塔南墙就是高台北墙 (共墙即共保险), 二层墙环整边骑
    一层墙顶, R8 高层检查由闭环拓扑天然通过; 塔旗底边"压顶
    北沿 + 塔北墙顶"一线双吸, 重心正压铰链线;
  - 闸墙/闸门/系船柱全部踩岸线拼缝整边吸合; 驳船驾驶舱与桅旗
    骑水面拼缝, 一缝双吸重心正压铰链零力矩。

用法: python3 tools/generate_canal_lock_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

BANK = "gray"       # 河岸步道
LAWN = "green"      # 河岸草地
WATER = "blue"      # 水面
HULL = "orange"     # 驳船底
CABIN = "clear"     # 驾驶舱
MASTFLAG = "red"    # 桅旗
WALL = "gray"       # 闸室高墙
GATE_UP = "gray"    # 上游闸门 (紧闭)
GATE_DN = "green"   # 下游闸门 (已开)
POOL = "gray"       # 高水位池壁
TOWER = "clear"     # 控制塔一层
LOOKOUT = "cyan"    # 控制塔了望窗
CAP = "gray"        # 塔顶压顶
FLAG = "red"        # 塔旗
BOLLARD = "yellow"  # 系船柱


def wall_ns_t(tid, tile_type, x0, y, z0, color):
    b.add(tid, tile_type, (x0 + 0.5, y, z0 + 0.5), (90, 0, 0), color)


def wall_ew_t(tid, tile_type, x, y0, z0, color):
    b.add(tid, tile_type, (x, y0 + 0.5, z0 + 0.5), (90, 0, 90), color)


# =================================================================
# 1. 南北河岸 (y [0,1] / [3,4], x [0,6])
# =================================================================
for x0 in range(6):
    b.flat(f"bank_s_{x0}", x0, 0, 0.0, BANK if x0 % 2 == 0 else LAWN)
for x0 in range(6):
    b.flat(f"bank_n_{x0}", x0, 3, 0.0, LAWN if x0 % 2 == 0 else BANK)

# =================================================================
# 2. 下游水面 + 闸室水面 + 驳船
# =================================================================
b.flat("low_0_1", 0, 1, 0.0, WATER)
b.flat("low_0_2", 0, 2, 0.0, WATER)
b.flat("low_1_1", 1, 1, 0.0, WATER)
b.flat("low_1_2", 1, 2, 0.0, WATER)
b.flat("ch_2_1", 2, 1, 0.0, WATER)
b.flat("ch_2_2", 2, 2, 0.0, WATER)
b.flat("ch_3_2", 3, 2, 0.0, WATER)
b.flat("ch_hull", 3, 1, 0.0, HULL)             # 驳船底就位闸室
b.crest_ns("boat_cabin", 3, 2.0, 0.0, CABIN)   # 驾驶舱骑船-水拼缝
b.spire_ew("boat_mast", 3.0, 1, 0.0, MASTFLAG) # 桅旗骑水面拼缝, 尖 2.0

# =================================================================
# 3. 闸室高墙 (y=1 / y=3, x [2,4]) + 下游闸门 (已开) + 系船柱
# =================================================================
b.wall_ns("lk_s_2", 2, 1.0, 0, WALL)
b.wall_ns("lk_s_3", 3, 1.0, 0, WALL)
b.wall_ns("lk_n_2", 2, 3.0, 0, WALL)
b.wall_ns("lk_n_3", 3, 3.0, 0, WALL)
b.wall_ns("gate_dn_s", 1, 1.0, 0, GATE_DN)     # 开启的闸叶贴墙外侧
b.wall_ns("gate_dn_n", 1, 3.0, 0, GATE_DN)
b.crest_ns("bollard_s", 0, 1.0, 0.0, BOLLARD)
b.crest_ns("bollard_n", 0, 3.0, 0.0, BOLLARD)

# =================================================================
# 4. 上游高水位池 (x [4,6], y [1,3]): 箱形墙环 + 顶面水板
#    西侧两片墙 = 紧闭的上游闸门
# =================================================================
b.wall_ns("pl_s_4", 4, 1.0, 0, POOL)
b.wall_ns("pl_s_5", 5, 1.0, 0, POOL)
b.wall_ns("pl_n_4", 4, 3.0, 0, POOL)
b.wall_ns("pl_n_5", 5, 3.0, 0, POOL)
b.wall_ew("gate_up_s", 4.0, 1, 0, GATE_UP)     # 上游闸门 (紧闭)
b.wall_ew("gate_up_n", 4.0, 2, 0, GATE_UP)
b.wall_ew("pl_e_1", 6.0, 1, 0, POOL)
b.wall_ew("pl_e_2", 6.0, 2, 0, POOL)
b.flat("up_4_1", 4, 1, 1.0, WATER)             # 高水位水面 (z=1)
b.flat("up_5_1", 5, 1, 1.0, WATER)
b.flat("up_4_2", 4, 2, 1.0, WATER)
b.flat("up_5_2", 5, 2, 1.0, WATER)

# =================================================================
# 5. 控制塔 (x [4,5], y [3,4]): 南墙借高台北墙 (共墙技法)
# =================================================================
wall_ns_t("ct0_n", "door_frame", 4, 4.0, 0, TOWER)  # 北门朝岸
b.wall_ew("ct0_w", 4.0, 3, 0, TOWER)
b.wall_ew("ct0_e", 5.0, 3, 0, TOWER)
wall_ns_t("ct1_s", "window_square", 4, 3.0, 1, LOOKOUT)  # 了望窗正对闸室
b.wall_ns("ct1_n", 4, 4.0, 1, TOWER)
b.wall_ew("ct1_w", 4.0, 3, 1, TOWER)
b.wall_ew("ct1_e", 5.0, 3, 1, TOWER)
b.flat("ct_cap", 4, 3, 2.0, CAP)
b.crest_ns("ct_flag", 4, 4.0, 2.0, FLAG)       # 塔旗一线双吸

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺南岸: 六片灰绿相间的方板沿运河排开。",
    [f"bank_s_{x0}" for x0 in range(6)],
    tip="运河沿着东西向流, 两岸步道就是全场的地基。",
)
b.step(
    "铺下游水面: 四片蓝色方板贴着南岸拼开, 这是低的那级水位。",
    ["low_0_1", "low_1_1", "low_0_2", "low_1_2"],
    highlight=["bank_s_0"],
    tip="下游的水贴着地面 —— 记住这个高度, 一会儿要和上游比一比。",
)
b.step(
    "铺闸室水面, 橙色驳船底就位闸室东南格。",
    ["ch_2_1", "ch_2_2", "ch_hull", "ch_3_2"],
    highlight=["low_1_1"],
    tip="驳船开进闸室, 就停在两道闸门之间。",
)
b.step(
    "铺北岸: 六片方板贴着水面北沿排开, 与南岸隔河对望。",
    [f"bank_n_{x0}" for x0 in range(6)],
    highlight=["ch_2_2"],
    tip="岸线上的每一道拼缝, 待会都要接住闸墙的墙脚。",
)
b.step(
    "驳船上装清色驾驶舱与红色桅旗, 都骑在水面拼缝上。",
    ["boat_cabin", "boat_mast"],
    highlight=["ch_hull"],
    tip="底边整边吸住拼缝, 重心正压铰链线 —— 船稳稳当当。",
)
b.step(
    "立闸室高墙: 南北各两片灰墙踩住岸线拼缝。",
    ["lk_s_2", "lk_s_3", "lk_n_2", "lk_n_3"],
    highlight=["ch_2_1"],
    tip="闸室的墙要挡住涨起来的水, 墙脚整边吸缝一片不能歪。",
)
b.step(
    "挂下游闸门与系船柱: 两扇绿叶已经拉开贴在墙外侧。",
    ["gate_dn_s", "gate_dn_n", "bollard_s", "bollard_n"],
    highlight=["lk_s_2"],
    tip="船进来之后闸门就会合上; 黄色系船柱先把缆绳挂好。",
)
b.step(
    "围上游高水位池的南北壁: 四片灰墙踩岸线拼缝。",
    ["pl_s_4", "pl_s_5", "pl_n_4", "pl_n_5"],
    highlight=["lk_n_3"],
    tip="上游的水位比下游高一整层, 池壁就是它的堤坝。",
)
b.step(
    "合上游闸门与东壁: 西侧两片灰墙紧闭顶住高水位, 箱环锁死。",
    ["gate_up_s", "gate_up_n", "pl_e_1", "pl_e_2"],
    highlight=["pl_s_4"],
    tip="四角竖边互咬, 墙环闭合 —— 高水位这就装得住了。",
)
b.step(
    "铺上游水面: 四片蓝色水板压上池壁顶, 高水位亮相!",
    ["up_4_1", "up_5_1", "up_4_2", "up_5_2"],
    highlight=["gate_up_s"],
    tip="每片水板两条外边压墙顶、两条内边彼此互吸 —— 上下游水面"
        "正好差一层, 这就是船闸要填平的高度差。",
)
b.step(
    "起控制塔一层: 借高台北墙当南墙, 北门朝岸再补东西两片。",
    ["ct0_n", "ct0_w", "ct0_e"],
    highlight=["pl_n_4"],
    tip="共墙技法: 一片墙同时属于高台和塔, 两个环共用一道保险。",
)
b.step(
    "塔二层了望窗正对闸室, 压顶四边全吸, 红旗骑顶收尾。",
    ["ct1_s", "ct1_n", "ct1_w", "ct1_e", "ct_cap", "ct_flag"],
    highlight=["ct0_n"],
    tip="管理员在窗后盯着水位 —— 开闸放水, 驳船要升起来啦!",
)

b.finalize(
    model_id="canal_lock_01",
    name="运河船闸",
    name_en="Canal Lock 01",
    description=(
        "只用核心九片型的水利工程场景: 主角是两级水位差本身 —— "
        "上游水面铺在箱形高台的顶上, 整整高出下游一层; 闸室里橙色"
        "驳船骑缝立着驾驶舱与桅旗, 正等水位上涨。上游闸门双片灰墙"
        "紧闭顶住高水位, 下游闸门两扇绿叶已拉开贴在闸墙外侧; 北岸"
        "控制塔借高台北墙合环 (共墙技法), 二层窗格方了望窗正对闸室, "
        "红旗一线双吸骑顶 —— 开闸放水, 看驳船跟着水面慢慢升高!"
    ),
    difficulty=3,
    tags=["工程", "运河", "船闸", "水利", "驳船"],
    min_pieces=51,
    min_steps=12,
)
