#!/usr/bin/env python3
"""生成模型 data/models/merry_go_round_01.json (旋转木马底座场景)。

游乐园主题: 与 carousel_01 (地面回字转台 + 梯形大帐篷) 刻意区分 ——
本模型的主角是**架高的鼓身底座**: 3x3 机房鼓身把整个转台抬高一层,
9 片黄色甲板铺成高台转盘, 8 只木马立在高台沿口翩翩起舞 (等边小马
与等腰独角兽相间), 转盘正中再起一层红色机芯塔戴四坡锥冠; 底座四周
一圈灰色环形广场, 南侧仪门 (双柱托长方形横楣) + 四角绿篱围栏收边。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 转台中心 (3.5, 3.5)):
  - 环形广场: [1,6]x[1,6] 去中心 3x3 的一圈 16 片            16 片
  - 机房鼓身: [2,5]x[2,5] 四面立墙各 3 片                    12 片
  - 高台甲板: 3x3 方板铺满鼓身顶口 (z=1)                      9 片
  - 机芯塔: 中心 1x1 四壁 (z 1..2) + 压顶 + 等腰四坡锥冠       9 片
  - 木马: 高台沿口 8 只 (等边小马 4 + 等腰独角兽 4)            8 片
  - 南门广场: 门前 4 片方板                                    4 片
  - 仪门: 双柱 x2 层 + 长方形横楣                              5 片
  - 绿篱围栏: 四角 L 形 8 片 + 角旗 4 片                      12 片
  合计 75 片, 16 个教程步骤, 4 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 鼓身立墙底边整边吸环形广场内沿, 拐角竖边互吸自锁成筒;
  - 甲板逐片压墙顶边, 机芯塔立在甲板拼缝上 (拼缝两侧双吸),
    锥冠斜棱两两互吸自锁 (摩天大楼金顶同款);
  - 木马立在"甲板边 + 墙顶边"三线合一的沿口铰链上, 重心正压;
  - 仪门横楣两端竖边吸双柱上层竖边 (消防站门楣同款三边受力)。

用法: python3 tools/generate_merry_go_round.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

PLAZA = "gray"      # 环形广场
DRUM = "purple"     # 机房鼓身
DECK = "yellow"     # 高台甲板
CROWN = "red"       # 机芯塔
HAT = "orange"      # 锥冠
PONY = "pink"       # 等边小马
UNICORN = "blue"    # 等腰独角兽
FENCE = "green"     # 绿篱围栏
GATE = "orange"     # 仪门

# =================================================================
# 1. 环形广场 (z=0): [1,6]x[1,6] 去中心 3x3, 一圈 16 片
# =================================================================
ring_south = [(x, 1) for x in range(1, 6)]
ring_north = [(x, 5) for x in range(1, 6)]
ring_west = [(1, y) for y in range(2, 5)]
ring_east = [(5, y) for y in range(2, 5)]
for x, y in ring_south + ring_north + ring_west + ring_east:
    b.flat(f"pl_{x}_{y}", x, y, 0.0, PLAZA)

# =================================================================
# 2. 机房鼓身 (z 0..1): [2,5]x[2,5] 四面立墙各 3 片
# =================================================================
for x in range(2, 5):
    b.wall_ns(f"dr_s_{x}", x, 2.0, 0, DRUM)   # 南壁
    b.wall_ns(f"dr_n_{x}", x, 5.0, 0, DRUM)   # 北壁
for y in range(2, 5):
    b.wall_ew(f"dr_w_{y}", 2.0, y, 0, DRUM)   # 西壁
    b.wall_ew(f"dr_e_{y}", 5.0, y, 0, DRUM)   # 东壁

# =================================================================
# 3. 高台甲板 (z=1): 3x3 方板铺满鼓身顶口
# =================================================================
for x in range(2, 5):
    for y in range(2, 5):
        b.flat(f"dk_{x}_{y}", x, y, 1.0, DECK)

# =================================================================
# 4. 机芯塔 (z 1..2) + 等腰四坡锥冠: 立在甲板中心 [3,4]x[3,4]
# =================================================================
b.wall_ns("cr_s", 3, 3.0, 1, CROWN)
b.wall_ns("cr_n", 3, 4.0, 1, CROWN)
b.wall_ew("cr_w", 3.0, 3, 1, CROWN)
b.wall_ew("cr_e", 4.0, 3, 1, CROWN)
b.flat("cr_top", 3, 3, 2.0, CROWN)
HAT_IDS = b.hat4("cr_hat", 3, 3, 2.0, HAT)

# =================================================================
# 5. 木马: 高台沿口 8 只 (等边小马与等腰独角兽相间, 旋转对称)
# =================================================================
b.crest_ns("po_s", 2, 2.0, 1.0, PONY)         # 南沿西端小马
b.spire_ns("un_s", 4, 2.0, 1.0, UNICORN)      # 南沿东端独角兽
b.crest_ew("po_e", 5.0, 2, 1.0, PONY)         # 东沿南端小马
b.spire_ew("un_e", 5.0, 4, 1.0, UNICORN)      # 东沿北端独角兽
b.crest_ns("po_n", 4, 5.0, 1.0, PONY)         # 北沿东端小马
b.spire_ns("un_n", 2, 5.0, 1.0, UNICORN)      # 北沿西端独角兽
b.crest_ew("po_w", 2.0, 4, 1.0, PONY)         # 西沿北端小马
b.spire_ew("un_w", 2.0, 2, 1.0, UNICORN)      # 西沿南端独角兽

# =================================================================
# 6. 南门广场 (z=0, y0=0): 4 片方板
# =================================================================
for x in range(2, 6):
    b.flat(f"fc_{x}", x, 0, 0.0, PLAZA)

# =================================================================
# 7. 仪门 (y=0 立面): 双柱 x2 层 + 长方形横楣 (跨 x 3..5)
# =================================================================
b.wall_ns("gp_w1", 2, 0.0, 0, GATE)
b.wall_ns("gp_w2", 2, 0.0, 1, GATE)
b.wall_ns("gp_e1", 5, 0.0, 0, GATE)
b.wall_ns("gp_e2", 5, 0.0, 1, GATE)
b.lintel_ns("gate_lin", 3, 0.0, 1, CROWN)

# =================================================================
# 8. 绿篱围栏: 广场四角 L 形 (每角 2 片) + 角旗 4 片
# =================================================================
b.wall_ns("fn_sw_s", 1, 1.0, 0, FENCE)
b.wall_ew("fn_sw_w", 1.0, 1, 0, FENCE)
b.wall_ns("fn_se_s", 5, 1.0, 0, FENCE)
b.wall_ew("fn_se_e", 6.0, 1, 0, FENCE)
b.wall_ns("fn_nw_n", 1, 6.0, 0, FENCE)
b.wall_ew("fn_nw_w", 1.0, 5, 0, FENCE)
b.wall_ns("fn_ne_n", 5, 6.0, 0, FENCE)
b.wall_ew("fn_ne_e", 6.0, 5, 0, FENCE)
b.crest_ns("fl_sw", 1, 1.0, 1.0, PONY)
b.crest_ns("fl_se", 5, 1.0, 1.0, PONY)
b.crest_ns("fl_nw", 1, 6.0, 1.0, PONY)
b.crest_ns("fl_ne", 5, 6.0, 1.0, PONY)

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺设环形广场南排与西列: 8 片灰色方板拼成 L 形 (南排 5 + 西列 3)。",
    [f"pl_{x}_{1}" for x in range(1, 6)] + [f"pl_{1}_{y}" for y in range(2, 5)],
    tip="广场中间要留一个 3x3 的空洞 —— 那是鼓身底座的地基口。",
)
b.step(
    "铺设环形广场东列与北排: 再补 8 片, 广场围成一圈回字环。",
    [f"pl_{5}_{y}" for y in range(2, 5)] + [f"pl_{x}_{5}" for x in range(1, 6)],
    highlight=["pl_5_1", "pl_1_4"],
    tip="16 片广场板缝缝相吸, 中心留出 [2,5] 见方的地基口。",
)
b.step(
    "竖立鼓身南壁与西壁: 紫色正方形各 3 片, 底边吸广场内沿, "
    "拐角竖边互吸。",
    [f"dr_s_{x}" for x in range(2, 5)] + [f"dr_w_{y}" for y in range(2, 5)],
    highlight=["pl_2_1", "pl_1_2"],
    tip="立墙底边要恰好压在广场板的内侧边上 —— 整边贴合才吸得牢。",
)
b.step(
    "竖立鼓身北壁与东壁: 再立 6 片, 机房鼓身合围成筒。",
    [f"dr_n_{x}" for x in range(2, 5)] + [f"dr_e_{y}" for y in range(2, 5)],
    highlight=["dr_s_2", "dr_w_2"],
    tip="四面墙在四个拐角竖边互吸, 合围后的方筒稳得像一只鼓。",
)
b.step(
    "铺设高台甲板外圈: 8 片黄色方板压住鼓身墙顶边 (中心暂留空)。",
    [f"dk_{x}_{y}" for x in range(2, 5) for y in range(2, 5)
     if not (x == 3 and y == 3)],
    highlight=["dr_s_2", "dr_n_4"],
    tip="每片甲板的外沿边都要吸住正下方的墙顶边, 逐片压实。",
)
b.step(
    "盖上甲板中心板: 转台台面完工, 高出广场整整一层。",
    ["dk_3_3"],
    highlight=["dk_2_2", "dk_4_4"],
    tip="中心板四边同时吸住四邻甲板 —— 转盘从此严丝合缝。",
)
b.step(
    "竖立机芯塔四壁: 红色正方形 4 片立在甲板中心拼缝上, 围成 1x1 方筒。",
    ["cr_s", "cr_n", "cr_w", "cr_e"],
    highlight=["dk_3_3"],
    tip="塔壁底边正压甲板拼缝, 缝两侧的甲板边同时吸住它。",
)
b.step(
    "机芯塔压顶并合拢锥冠: 压顶方板盖口, 4 片橙色等腰三角斜棱两两"
    "互吸、锥尖自锁。",
    ["cr_top"] + HAT_IDS,
    highlight=["cr_s"],
    tip="最后一片锥面卡进去时会咔哒一声 —— 那是四条斜棱同时锁定。",
)
b.step(
    "南沿与东沿上木马: 粉色等边小马与蓝色等腰独角兽各就各位。",
    ["po_s", "un_s", "po_e", "un_e"],
    highlight=["dk_2_2"],
    tip="木马立在甲板沿口的铰链线上, 底边整边吸合、重心正压。",
)
b.step(
    "北沿与西沿上木马: 8 只木马到齐, 绕着机芯塔正要起舞。",
    ["po_n", "un_n", "po_w", "un_w"],
    highlight=["po_s", "un_s"],
    tip="小马与独角兽相间排布 —— 旋转起来颜色才会流动。",
)
b.step(
    "铺设南门广场: 门前 4 片灰色方板与环形广场南沿吸合。",
    [f"fc_{x}" for x in range(2, 6)],
    highlight=["pl_2_1", "pl_5_1"],
    tip="这是游客入场的红毯大道, 与广场缝缝相吸连成整体。",
)
b.step(
    "竖立仪门双柱下层: 橙色正方形 2 片立在门前广场南沿两端。",
    ["gp_w1", "gp_e1"],
    highlight=["fc_2", "fc_5"],
    tip="双柱相距 2 格 —— 中间正好留给长方形横楣合龙。",
)
b.step(
    "双柱加高并架横楣: 双柱各叠 1 片, 红色长方形横楣两端竖边"
    "分别吸住双柱竖边。",
    ["gp_w2", "gp_e2", "gate_lin"],
    highlight=["gp_w1", "gp_e1"],
    tip="横楣是三边受力的过梁: 先叠柱、再合龙, 一次到位。",
)
b.step(
    "种植南侧绿篱: 广场西南与东南角各 2 片绿色围栏 L 形收边。",
    ["fn_sw_s", "fn_sw_w", "fn_se_s", "fn_se_e"],
    highlight=["pl_1_1", "pl_5_1"],
    tip="围栏底边吸广场外沿, 拐角竖边互吸 —— L 形自己站得稳。",
)
b.step(
    "种植北侧绿篱: 西北与东北角各 2 片围栏就位, 四角合围。",
    ["fn_nw_n", "fn_nw_w", "fn_ne_n", "fn_ne_e"],
    highlight=["fn_sw_s", "fn_se_s"],
    tip="四角 L 形绿篱像四只护角, 把广场稳稳圈在中间。",
)
b.step(
    "升起四面角旗: 粉色等边三角立上四角围栏顶边, 旋转木马底座场景落成!",
    ["fl_sw", "fl_se", "fl_nw", "fl_ne"],
    highlight=["fn_sw_s", "fn_ne_n"],
    tip="角旗底边吸住围栏顶边, 重心正压 —— 音乐响起, 转台开动!",
)

b.finalize(
    model_id="merry_go_round_01",
    name="旋转木马底座场景",
    name_en="Merry-Go-Round Base",
    description=(
        "架高一层的旋转木马底座: 3x3 紫色机房鼓身立在环形广场中央, 9 片"
        "黄色甲板铺成高台转盘, 8 只木马 (等边小马与等腰独角兽相间) 立在"
        "沿口铰链上绕塔起舞, 转盘正中的红色机芯塔戴橙色四坡锥冠; 南侧"
        "仪门双柱托横楣, 四角绿篱升起粉色角旗 —— 音乐响起, 转台开动!"
    ),
    difficulty=3,
    tags=["游乐园", "建筑", "进阶"],
    min_pieces=75,
    min_steps=16,
)
