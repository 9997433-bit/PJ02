#!/usr/bin/env python3
"""生成模型 data/models/hospital_01.json (医院).

城市公共建筑主题: 全库第一座医疗建筑 —— 白色板楼医院: 两层
主楼 7 格宽, 立面整圈窗格方病房窗; 中央急诊入口是一扇红色
门框方, 门顶两片透明雨棚外挑; 三层中央塔楼退台升起, 塔顶
长板封顶、南沿立红十字灯箱。立面中央用红色磁力片拼出一个
完整的"十"字 —— 底臂是急诊门、横臂在二层、顶臂在塔楼,
救护车远远就能认出这里。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 大门朝南):
  - 前广场 + 楼基两排地坪                               23 片
  - 一层: 窗格方 x13 + 红色门框方急诊门 + 角墙 x4        18 片
  - 二层楼板 (方板 + 长板混铺, 门顶留单位边给雨棚)        9 片
  - 急诊雨棚: 透明方板 x2 (单位边铰链外挑)                2 片
  - 二层: 窗格方 x11 + 红十字横臂 x3 + 角墙 x4           18 片
  - 翼楼屋面 + 塔楼楼板                                  14 片
  - 塔楼: 窗格方 x4 + 红十字顶臂 x1 + 角墙 x4 + 底缘 x1  10 片
  - 塔顶长板 x3 + 红十字灯箱三角 x1                       4 片
  合计 98 片, 18 个教程步骤, 6 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验, 常规+strict 双档):
  - 全楼逐层箱形围合: 每层四面墙竖边互吸成环, 楼板四边
    压墙顶 —— 层层都是闭合环, 无单点失效;
  - 上层墙底边与下层墙顶边单位边对单位边整边吸合,
    荷载沿墙身直落地面;
  - 急诊雨棚两片方板各自铰在二层楼板南缘单位边上,
    合计弯矩 30 < 双单位铰链预算 35 (strict 档)。

用法: python3 tools/generate_hospital.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

PLAZA = "gray"      # 前广场
BASE = "gray"       # 楼基地坪
WALL = "clear"      # 白色墙身
WIN = "cyan"        # 窗格方病房窗
RED = "red"         # 红十字
ROOF = "gray"       # 屋面
CANOPY = "clear"    # 雨棚

# =================================================================
# 1. 地坪: 前广场 [1,8]x[0,1] + 楼基两排 [0,9]x[1,3]
# =================================================================
b.flat_rect("pz_a", 1, 0, 0.0, PLAZA)
b.flat("pz_b", 3, 0, 0.0, "clear")            # 救护车导流白格
b.flat("pz_c", 4, 0, 0.0, "clear")
b.flat_rect("pz_d", 5, 0, 0.0, PLAZA)
b.flat("pz_e", 7, 0, 0.0, PLAZA)
for x in range(9):
    b.flat(f"g1_{x}", x, 1, 0.0, BASE)
for x in range(9):
    b.flat(f"g2_{x}", x, 2, 0.0, BASE)

# =================================================================
# 2. 一层 z0..1: 南立面 (窗 x3 + 红门框方 + 窗 x3), 北窗 x7, 角墙 x4
# =================================================================
for x in (1, 2, 3):
    b.add(f"f1_s{x}", "window_square", (x + 0.5, 1.0, 0.5), (90, 0, 0), WIN)
b.add("f1_door", "door_frame", (4.5, 1.0, 0.5), (90, 0, 0), RED)
for x in (5, 6, 7):
    b.add(f"f1_s{x}", "window_square", (x + 0.5, 1.0, 0.5), (90, 0, 0), WIN)
for x in range(1, 8):
    b.add(f"f1_n{x}", "window_square", (x + 0.5, 3.0, 0.5), (90, 0, 0), WIN)
b.wall_ew("f1_w0", 1.0, 1, 0, WALL)
b.wall_ew("f1_w1", 1.0, 2, 0, WALL)
b.wall_ew("f1_e0", 8.0, 1, 0, WALL)
b.wall_ew("f1_e1", 8.0, 2, 0, WALL)

# =================================================================
# 3. 二层楼板 z=1: 南排门顶留方板 (雨棚要吸单位边), 其余长板
# =================================================================
b.flat_rect("dk_s_a", 1, 1, 1.0, WALL)
b.flat("dk_s_b", 3, 1, 1.0, WALL)
b.flat("dk_s_c", 4, 1, 1.0, WALL)
b.flat_rect("dk_s_d", 5, 1, 1.0, WALL)
b.flat("dk_s_e", 7, 1, 1.0, WALL)
b.flat_rect("dk_n_a", 1, 2, 1.0, WALL)
b.flat_rect("dk_n_b", 3, 2, 1.0, WALL)
b.flat_rect("dk_n_c", 5, 2, 1.0, WALL)
b.flat("dk_n_d", 7, 2, 1.0, WALL)

# 急诊雨棚: 两片透明方板从楼板南缘单位边外挑
b.flat("canopy_w", 3, 0, 1.0, CANOPY)
b.flat("canopy_e", 4, 0, 1.0, CANOPY)

# =================================================================
# 4. 二层 z1..2: 南立面红十字横臂 (x3~5 红), 北窗整排, 角墙 x4
# =================================================================
for x in (1, 2):
    b.add(f"f2_s{x}", "window_square", (x + 0.5, 1.0, 1.5), (90, 0, 0), WIN)
for x in (3, 4, 5):
    b.wall_ns(f"f2_c{x}", x, 1.0, 1, RED)
for x in (6, 7):
    b.add(f"f2_s{x}", "window_square", (x + 0.5, 1.0, 1.5), (90, 0, 0), WIN)
for x in range(1, 8):
    b.add(f"f2_n{x}", "window_square", (x + 0.5, 3.0, 1.5), (90, 0, 0), WIN)
b.wall_ew("f2_w0", 1.0, 1, 1, WALL)
b.wall_ew("f2_w1", 1.0, 2, 1, WALL)
b.wall_ew("f2_e0", 8.0, 1, 1, WALL)
b.wall_ew("f2_e1", 8.0, 2, 1, WALL)

# =================================================================
# 5. 屋面 z=2: 西翼 [1,3] / 东翼 [6,8] 各 4 方, 塔楼楼板 [3,6] 6 方
# =================================================================
for x0, y0 in ((1, 1), (2, 1), (1, 2), (2, 2)):
    b.flat(f"rw_{x0}_{y0}", x0, y0, 2.0, ROOF)
for x0, y0 in ((6, 1), (7, 1), (6, 2), (7, 2)):
    b.flat(f"re_{x0}_{y0}", x0, y0, 2.0, ROOF)
for x0, y0 in ((3, 1), (4, 1), (5, 1), (3, 2), (4, 2), (5, 2)):
    b.flat(f"td_{x0}_{y0}", x0, y0, 2.0, WALL)

# =================================================================
# 6. 塔楼 z2..3: 南面 窗+红十字顶臂+窗, 北窗 x3, 角墙 x4
# =================================================================
b.add("t_s3", "window_square", (3.5, 1.0, 2.5), (90, 0, 0), WIN)
b.wall_ns("t_c4", 4, 1.0, 2, RED)
b.add("t_s5", "window_square", (5.5, 1.0, 2.5), (90, 0, 0), WIN)
for x in (3, 4, 5):
    b.add(f"t_n{x}", "window_square", (x + 0.5, 3.0, 2.5), (90, 0, 0), WIN)
b.wall_ew("t_w0", 3.0, 1, 2, WALL)
b.wall_ew("t_w1", 3.0, 2, 2, WALL)
b.wall_ew("t_e0", 6.0, 1, 2, WALL)
b.wall_ew("t_e1", 6.0, 2, 2, WALL)

# =================================================================
# 7. 塔顶 z=3: 3 条纵向长板 + 南沿红十字灯箱三角
# =================================================================
for x in (3, 4, 5):
    b.flat_rect(f"tr_{x}", x, 1, 3.0, ROOF, axis="y")
b.crest_ns("beacon", 4, 1.0, 3.0, RED)

# =================================================================
# 教程步骤 (18 步)
# =================================================================
b.step(
    "前广场: 救护车道两块白色导流格镶在急诊门正前方, 两侧灰色"
    "长板与方板补齐。",
    ["pz_a", "pz_b", "pz_c", "pz_d", "pz_e"],
    tip="导流格正对 x=3~5 —— 上方就是急诊门与雨棚。",
)
b.step(
    "楼基南排: 9 片灰色方板铺出 y=1~2, 医院的墙都立在方板格边上。",
    [f"g1_{x}" for x in range(9)],
    highlight=["pz_a", "pz_e"],
)
b.step(
    "楼基北排: 再铺 9 片, 地坪合拢。",
    [f"g2_{x}" for x in range(9)],
    highlight=["g1_0", "g1_8"],
)
b.step(
    "一层南立面西段: 3 扇窗格方病房窗立在 y=1 格边上。",
    ["f1_s1", "f1_s2", "f1_s3"],
    highlight=["g1_1", "g1_3"],
)
b.step(
    "急诊门与南立面东段: 红色门框方立在正中 x=4~5, 东侧再排 "
    "3 扇窗 —— 这扇红门就是红十字的底臂。",
    ["f1_door", "f1_s5", "f1_s6", "f1_s7"],
    highlight=["f1_s3", "pz_b"],
    tip="救护车拉响警笛直奔这扇红门。",
)
b.step(
    "一层北立面: 7 扇窗格方一字排开。",
    [f"f1_n{x}" for x in range(1, 8)],
    highlight=["g2_1", "g2_7"],
)
b.step(
    "一层角墙: 东西山墙各 2 片白色方板, 竖边与南北墙互吸, "
    "一层箱形围合。",
    ["f1_w0", "f1_w1", "f1_e0", "f1_e1"],
    highlight=["f1_s1", "f1_n7"],
)
b.step(
    "二层楼板南排: 门顶 x=3~5 用两块方板 (雨棚要吸它们的南缘"
    "单位边), 其余用长板。",
    ["dk_s_a", "dk_s_b", "dk_s_c", "dk_s_d", "dk_s_e"],
    highlight=["f1_w0", "f1_e0"],
)
b.step(
    "二层楼板北排: 长板补齐, 楼板四边压墙顶合拢。",
    ["dk_n_a", "dk_n_b", "dk_n_c", "dk_n_d"],
    highlight=["dk_s_a", "f1_n4"],
)
b.step(
    "急诊雨棚: 两片透明方板从楼板南缘向广场外挑, 正罩急诊门。",
    ["canopy_w", "canopy_e"],
    highlight=["dk_s_b", "dk_s_c"],
    tip="每片各铰一条单位边, 合计弯矩 30 < 预算 35 —— 雨天不淋。",
)
b.step(
    "二层南立面: 中央 x=3~5 三片红色方板拼出红十字横臂, "
    "两侧各 2 扇窗格方。",
    ["f2_s1", "f2_s2", "f2_c3", "f2_c4", "f2_c5", "f2_s6", "f2_s7"],
    highlight=["f1_s1", "f1_door"],
    tip="横臂正压在红门上方 —— 十字开始成形。",
)
b.step(
    "二层北立面: 再排 7 扇窗格方。",
    [f"f2_n{x}" for x in range(1, 8)],
    highlight=["f1_n1", "f1_n7"],
)
b.step(
    "二层角墙: 东西山墙各 2 片, 二层箱形围合。",
    ["f2_w0", "f2_w1", "f2_e0", "f2_e1"],
    highlight=["f2_s1", "f2_n7"],
)
b.step(
    "翼楼屋面: 西翼与东翼各 4 片灰色方板盖上 z=2。",
    ["rw_1_1", "rw_2_1", "rw_1_2", "rw_2_2",
     "re_6_1", "re_7_1", "re_6_2", "re_7_2"],
    highlight=["f2_w0", "f2_e0"],
)
b.step(
    "塔楼楼板: 中央 [3,6] 铺 6 片白色方板, 与两翼屋面拼成整层。",
    ["td_3_1", "td_4_1", "td_5_1", "td_3_2", "td_4_2", "td_5_2"],
    highlight=["rw_2_1", "re_6_1"],
)
b.step(
    "塔楼墙身: 南面 窗+红十字顶臂+窗, 北面 3 窗, 东西角墙各 2 "
    "—— 第三层箱形围合, 十字五格拼齐。",
    ["t_s3", "t_c4", "t_s5", "t_n3", "t_n4", "t_n5",
     "t_w0", "t_w1", "t_e0", "t_e1"],
    highlight=["f2_c4", "td_4_1"],
    tip="顶臂 + 横臂 + 红门: 一个完整的红十字挂上立面。",
)
b.step(
    "塔顶: 3 条纵向长板封顶, 短边压塔墙顶。",
    ["tr_3", "tr_4", "tr_5"],
    highlight=["t_w0", "t_e0"],
)
b.step(
    "红十字灯箱: 红色三角立上塔顶南沿 —— 医院落成, 昼夜亮灯!",
    ["beacon"],
    highlight=["tr_4"],
)

b.finalize(
    model_id="hospital_01",
    name="医院",
    name_en="Hospital 01",
    description=(
        "全库第一座医疗建筑: 白色板楼医院两层主楼 7 格宽, 立面整圈 "
        "30 扇窗格方病房窗; 立面中央用红色磁力片拼出完整的十字 —— "
        "底臂是红色门框方急诊门、横臂横贯二层、顶臂嵌在三层塔楼上; "
        "门顶两片透明雨棚从楼板南缘单位边外挑 (弯矩 30 < 35), 中央"
        "塔楼退台升起、塔顶长板封顶再立红十字灯箱。逐层箱形围合、"
        "上下墙单位边对吸 —— 救护车远远就能认出这里。"
    ),
    difficulty=4,
    tags=["医院", "城市", "公共建筑", "职业体验", "窗格方"],
    min_pieces=95,
    min_steps=18,
)
