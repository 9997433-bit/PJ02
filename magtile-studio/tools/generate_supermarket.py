#!/usr/bin/env python3
"""生成模型 data/models/supermarket_01.json (阳光超市)。

城市生活主题: 全库第一家大卖场 —— 7x4 街区上一栋 5x2 单层大盒子
卖场: 南脸中央留 2 格宽的负空间大门 (橙色门楣横跨洞口, 两端竖边
传力), 门旁整排透明橱窗; 屋顶长板南北双边压墙顶, 门头一排红黄绿蓝
四色招牌拼出超市的热闹, 招牌脚下两片橙色雨棚平挑遮住入口 (力矩
30 <= 双边预算 40); 西侧果蔬摊双墙架起长板柜台 (双端受力零悬挑),
绿棚迎客; 东南角购物车排队入位, 东沿回收栏杆收边, 楼顶黄旗高扬
—— 开门营业, 今日特价!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 大门朝南):
  - 街区地坪 7x4: 卖场两排方板 x14 + 步行道 x7 + 停车位 x5     26 片
  - 一层墙 (z0..1): 橱窗 x3 + 北墙 长板x2/方x1 + 山墙 x4       10 片
  - 二层墙带 (z1..2): 方x3 + 门楣长板 x1 + 北墙 长板x2/方x1
    + 山墙 x4                                                   11 片
  - 屋顶 (z=2): 长板 x5 (1x2 纵铺双边压墙顶)                     5 片
  - 门头招牌: 四色方板 x4 立屋顶南沿                             4 片
  - 入口雨棚: 橙色方板 x2 平挑 + 楼顶黄旗等腰 x1                 3 片
  - 果蔬摊: 方墙 x2 + 长板柜台 x1 + 绿棚等边 x1                  4 片
  - 购物车等边 x2 + 回收栏杆等边 x2                              4 片
  合计 67 片, 16 个教程步骤, 5 种磁力片形状 (CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验):
  - 大门 2 格负空间: 门楣长板两端竖边吸邻墙竖边, 上环整边压
    下环, 卖场墙圈锁成多环箱体;
  - 北墙用长板横砌 (竖边走拐角传力), 与南脸方板错开片形节奏;
  - 雨棚 2 片各自单边铰链平挑 (力矩 15 <= 20), 且互相整边
    吸合共担; 招牌重心正压铰链线零力矩;
  - 果蔬摊柜台长板双端压墙顶 (双端受力), 东边整条贴住卖场
    西山墙顶 —— 三路支撑互为保险。

用法: python3 tools/generate_supermarket.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

WALK = "gray"       # 步行道
PARK = "gray"       # 停车位
DIV = "cyan"        # 车位分隔
BASE = "gray"       # 卖场地基
WALL = "yellow"     # 卖场墙
BACK = "gray"       # 北墙与山墙
WIN = "clear"       # 橱窗
LINTEL = "orange"   # 门楣
ROOF = "gray"       # 屋顶
CANOPY = "orange"   # 雨棚
STALL = "green"     # 果蔬摊
CART = "gray"       # 购物车
FLAG = "yellow"     # 楼顶旗

# =================================================================
# 1. 街区地坪 7x4
# =================================================================
for x in range(7):
    b.flat(f"g3_{x}", x, 3, 0.0, BASE)              # 卖场后排
for x in range(7):
    b.flat(f"g2_{x}", x, 2, 0.0, BASE)              # 卖场前排
for x in range(7):
    b.flat(f"g1_{x}", x, 1, 0.0, WALK)              # 步行道
b.flat_rect("g0_a", 0, 0, 0.0, PARK)                # 停车位 [0,2]
b.flat("g0_d1", 2, 0, 0.0, DIV)                     # 分隔线
b.flat_rect("g0_b", 3, 0, 0.0, PARK)                # 停车位 [3,5]
b.flat("g0_d2", 5, 0, 0.0, DIV)                     # 分隔线
b.flat("g0_c", 6, 0, 0.0, PARK)

# =================================================================
# 2. 一层墙 (z0..1): 卖场 [1,6]x[2,4], 南脸留 2 格大门 (x2..4)
# =================================================================
b.wall_ew("ww1_2", 1.0, 2, 0, BACK)                 # 西山墙
b.wall_ew("ww1_3", 1.0, 3, 0, BACK)
b.wall_ew("ew1_2", 6.0, 2, 0, BACK)                 # 东山墙
b.wall_ew("ew1_3", 6.0, 3, 0, BACK)
b.lintel_ns("nw1_a", 1, 4.0, 0, BACK)               # 北墙长板 [1,3]
b.lintel_ns("nw1_b", 3, 4.0, 0, BACK)               # 北墙长板 [3,5]
b.wall_ns("nw1_c", 5, 4.0, 0, BACK)                 # 北墙方板 [5,6]
b.add("fw1_1", "window_square", (1.5, 2.0, 0.5), (90, 0, 0), WIN)  # 橱窗
b.add("fw1_4", "window_square", (4.5, 2.0, 0.5), (90, 0, 0), WIN)
b.add("fw1_5", "window_square", (5.5, 2.0, 0.5), (90, 0, 0), WIN)

# =================================================================
# 3. 二层墙带 (z1..2): 门楣横跨大门洞
# =================================================================
b.wall_ew("ww2_2", 1.0, 2, 1, BACK)
b.wall_ew("ww2_3", 1.0, 3, 1, BACK)
b.wall_ew("ew2_2", 6.0, 2, 1, BACK)
b.wall_ew("ew2_3", 6.0, 3, 1, BACK)
b.lintel_ns("nw2_a", 1, 4.0, 1, BACK)
b.lintel_ns("nw2_b", 3, 4.0, 1, BACK)
b.wall_ns("nw2_c", 5, 4.0, 1, BACK)
b.wall_ns("fw2_1", 1, 2.0, 1, WALL)
b.lintel_ns("f_lintel", 2, 2.0, 1, LINTEL)          # 门楣 [2,4]
b.wall_ns("fw2_4", 4, 2.0, 1, WALL)
b.wall_ns("fw2_5", 5, 2.0, 1, WALL)

# =================================================================
# 4. 屋顶 (z=2): 5 片长板纵铺
# =================================================================
for x in range(1, 6):
    b.flat_rect(f"rf_{x}", x, 2, 2.0, ROOF, axis="y")

# =================================================================
# 5. 门头招牌 + 雨棚 + 楼顶旗
# =================================================================
for x, c in ((1, "red"), (2, "yellow"), (3, "green"), (4, "blue")):
    b.wall_ns(f"sign_{x}", x, 2.0, 2, c)            # 四色招牌
b.flat("cp_w", 2, 1, 2.0, CANOPY)                   # 雨棚西
b.flat("cp_e", 3, 1, 2.0, CANOPY)                   # 雨棚东
b.spire_ns("flag", 3, 4.0, 2.0, FLAG)               # 楼顶旗 (北沿)

# =================================================================
# 6. 果蔬摊 [0,1]x[2,4] + 购物车 + 回收栏杆
# =================================================================
b.wall_ns("st_s", 0, 2.0, 0, STALL)                 # 摊位南墙
b.wall_ns("st_n", 0, 4.0, 0, STALL)                 # 摊位北墙
b.flat_rect("st_top", 0, 2, 1.0, BASE, axis="y")    # 柜台 [0,1]x[2,4]
b.crest_ns("st_awn", 0, 2.0, 1.0, STALL)            # 绿棚
b.crest_ns("cart_1", 5, 1.0, 0.0, CART)             # 购物车
b.crest_ns("cart_2", 6, 1.0, 0.0, CART)
b.crest_ew("rail_1", 7.0, 2, 0.0, CART)             # 回收栏杆
b.crest_ew("rail_2", 7.0, 3, 0.0, CART)

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺卖场后排: 7 片灰色方板沿 y=3 排开。",
    [f"g3_{x}" for x in range(7)],
    tip="卖场的北墙与山墙都会踩在这一排格线上。",
)
b.step(
    "铺卖场前排: 再铺 7 片, 大盒子卖场的地基完成。",
    [f"g2_{x}" for x in range(7)],
    highlight=["g3_0", "g3_6"],
    tip="前排与后排整边互吸 —— 南脸大门就开在这排格线上。",
)
b.step(
    "铺门前步行道: 7 片方板一字排开。",
    [f"g1_{x}" for x in range(7)],
    highlight=["g2_2"],
    tip="步行道留给行人和购物车 —— 车辆止步。",
)
b.step(
    "铺停车位: 2 片灰色长板车位, 青色方板是分隔线。",
    ["g0_a", "g0_d1", "g0_b", "g0_d2", "g0_c"],
    highlight=["g1_0"],
    tip="停车位在最外侧 —— 逛超市先找车位。",
)
b.step(
    "立一层山墙: 东西两端各 2 片灰色方墙。",
    ["ww1_2", "ww1_3", "ew1_2", "ew1_3"],
    highlight=["g2_1", "g2_5"],
    tip="山墙底边整边吸地坪格线 —— 大盒子从两端立起。",
)
b.step(
    "砌一层北墙: 2 片长板横砌加 1 片方板, 竖边吸进山墙拐角。",
    ["nw1_a", "nw1_b", "nw1_c"],
    highlight=["ww1_3", "ew1_3"],
    tip="长板横砌拼缝更少 —— 竖边在拐角与山墙互吸传力。",
)
b.step(
    "装一层橱窗: 大门两侧 3 片透明橱窗落位, 中间留 2 格大门洞。",
    ["fw1_1", "fw1_4", "fw1_5"],
    highlight=["ww1_2", "ew1_2"],
    tip="负空间大门 —— 超市的门永远为顾客敞开。",
)
b.step(
    "立二层山墙: 沿一层山墙顶再起 4 片。",
    ["ww2_2", "ww2_3", "ew2_2", "ew2_3"],
    highlight=["ww1_2", "ew1_2"],
    tip="上环整边压下环 —— 圈层砌法越按越紧。",
)
b.step(
    "砌二层北墙: 长板整边压一层北墙顶, 拐角竖边互吸。",
    ["nw2_a", "nw2_b", "nw2_c"],
    highlight=["nw1_a", "ww2_3"],
    tip="长板压长板, 整条边受力 —— 北墙是卖场的脊梁。",
)
b.step(
    "装门楣合龙二层: 橙色门楣横跨大门洞, 两端竖边吸邻墙。",
    ["fw2_1", "f_lintel", "fw2_4", "fw2_5"],
    highlight=["fw1_1", "fw1_4"],
    tip="先装西侧方板, 门楣两端竖边传力 —— 剪断一端力走另一端。",
)
b.step(
    "盖屋顶: 5 片长板纵向铺过卖场, 南北两端同时压墙顶。",
    [f"rf_{x}" for x in range(1, 6)],
    highlight=["nw2_a", "f_lintel"],
    tip="每片双端受力零悬挑 —— 屋顶把墙圈锁成整体箱体。",
)
b.step(
    "立门头招牌: 红黄绿蓝四色方板沿屋顶南沿一字排开。",
    [f"sign_{x}" for x in range(1, 5)],
    highlight=["rf_1", "rf_4"],
    tip="底边同吸屋顶板边与墙顶双铰链 —— 四色招牌就是超市的脸。",
)
b.step(
    "挑入口雨棚并升旗: 2 片橙色方板从门楣顶平挑, 北沿黄旗升起。",
    ["cp_w", "cp_e", "flag"],
    highlight=["f_lintel", "sign_2"],
    tip="每片力矩 15 <= 预算 20, 两片再整边互吸共担 —— 风雨不进门。",
)
b.step(
    "搭果蔬摊: 西侧双墙架起长板柜台, 双端受力零悬挑。",
    ["st_s", "st_n", "st_top"],
    highlight=["ww1_2"],
    tip="柜台东边还整条贴着卖场山墙顶 —— 三路支撑互为保险。",
)
b.step(
    "撑摊位绿棚: 柜台南沿立起绿色三角遮阳棚。",
    ["st_awn"],
    highlight=["st_top"],
    tip="新鲜蔬果最怕晒 —— 绿棚底边整边吸柜台沿口。",
)
b.step(
    "摆购物车与回收栏: 门口两辆购物车排队, 东沿栏杆收边。",
    ["cart_1", "cart_2", "rail_1", "rail_2"],
    highlight=["g1_5", "g2_6"],
    tip="购物车用完请归位 —— 阳光超市, 开门营业!",
)

b.finalize(
    model_id="supermarket_01",
    name="阳光超市",
    name_en="Supermarket 01",
    description=(
        "全库第一家大卖场: 5x2 单层大盒子南脸留 2 格负空间大门, 橙色门楣"
        "两端竖边传力横跨洞口, 整排透明橱窗晒出货架; 北墙长板横砌与南脸"
        "方板错开节奏, 屋顶长板双边压墙顶锁成多环箱体; 门头红黄绿蓝四色"
        "招牌重心正压铰链, 两片橙色雨棚平挑护住入口 (单片力矩 15 <= 20 "
        "且整边互吸共担); 西侧果蔬摊双墙架长板柜台 (双端受力+山墙顶三路"
        "保险) 绿棚迎客, 门口购物车排队、东沿回收栏收边, 楼顶黄旗高扬 "
        "—— 开门营业, 今日特价!"
    ),
    difficulty=3,
    tags=["城市", "超市", "商业街", "负空间", "进阶"],
    min_pieces=50,
    min_steps=16,
)
