#!/usr/bin/env python3
"""生成模型 data/models/moon_festival_altar_01.json (中秋拜月台)。

节日限定主题扩充 (库内此前只有 元宵/圣诞/生日/焰火 四作, 中秋空缺):
T12 层叠退台的节日演绎 —— 与金字塔/梯田的"逐层居中收分"不同,
本作的第二层整层退到台基北缘 (单侧退台), 空出的前半层是拜月的
"月台": 六边形满月立在高台南沿正中, 玉兔双耳高高竖起望着它,
供桌上摆着刚出炉的月饼 —— 全库唯一的"单侧退台 + 立月造景"。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 正门朝南):
  - 庭院地台 (x [0,3], y [-2,0]): 两排清灰方板                  6 片
  - 一层台基 (x [0,3], y [0,3], z 0..1): 红墙四面合围 x12 +
    黄色台面 x9                                                 21 片
  - 二层月台 (x [0,3], y [2,3], z 1..2): 整层退到北缘,
    红墙 x8 + 黄色台面 x3                                       11 片
  - 满月: 黄色六边形立在二层台面南沿正中 (顶高 2.87)             1 片
  - 玉兔: 两片清色方板并肩立在一层台面拼缝上 +
    两根清色瘦高尖耳 (耳尖 4.0, 全模型最高点)                    4 片
  - 供桌 (x [2,3], y [0,1], z 1..2): 橙色四墙 + 黄色桌面 +
    桌沿一片黄色三角"月饼"                                       6 片
  - 庭院: 桂花树 x2 (橙干绿冠) + 红灯笼三角 x2                   6 片
  合计 55 片, 12 个教程步骤, 5 种磁力片形状 (满月用六边形扩展片)。

招牌技法: 第二层不居中收分而是整层退到北缘, 空出的前半层高台
就是拜月台 —— 退台退出来的不是造型, 是给满月和玉兔的舞台。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 两层均为四墙合围的盒式环, 台面周边整边压墙顶, 中心板四邻互吸;
  - 二层墙脚: 南墙踩台面拼缝, 北/东/西墙底边同时吸台面边缘与
    一层墙顶 (墙上墙连续传力);
  - 满月/月饼底边整边吸台面沿口, 竖立纯受压, 力矩为零;
  - 玉兔身板踩台面拼缝且竖边互吸, 剪断任何单条连接不失联;
  - 桂花树干与灯笼底边整边吸庭院拼缝/沿口, 单点剪断最多失联 1 片。

用法: python3 tools/generate_moon_festival_altar.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import HEX_APOTHEM, ModelBuilder  # noqa: E402

b = ModelBuilder()

YARD_A = "clear"    # 庭院地台
YARD_B = "gray"
WALL = "red"        # 台基墙
DECK = "yellow"     # 台面
MOON = "yellow"     # 满月
RABBIT = "clear"    # 玉兔
TABLE = "orange"    # 供桌
CAKE = "yellow"     # 月饼
TRUNK = "orange"    # 桂花树干
LEAF = "green"      # 桂花树冠
LANTERN = "red"     # 灯笼

# =================================================================
# 1. 庭院地台 (x [0,3], y [-2,0]): 两排清灰相间方板
# =================================================================
for i in range(3):
    b.flat(f"yard_{i}_f", i, -2, 0.0, YARD_A if i % 2 == 0 else YARD_B)
for i in range(3):
    b.flat(f"yard_{i}_n", i, -1, 0.0, YARD_B if i % 2 == 0 else YARD_A)

# =================================================================
# 2. 一层台基 (x [0,3], y [0,3], z 0..1): 四墙合围 + 3x3 台面
# =================================================================
for i in range(3):
    b.wall_ns(f"t1_s_{i}", i, 0.0, 0, WALL)
    b.wall_ns(f"t1_n_{i}", i, 3.0, 0, WALL)
for j in range(3):
    b.wall_ew(f"t1_w_{j}", 0.0, j, 0, WALL)
    b.wall_ew(f"t1_e_{j}", 3.0, j, 0, WALL)
# 台面: 周边 8 片先压墙顶, 中心板最后放 (四邻互吸)
for j in range(3):
    for i in range(3):
        b.flat(f"deck1_{i}_{j}", i, j, 1.0, DECK)

# =================================================================
# 3. 二层月台 (x [0,3], y [2,3], z 1..2): 整层退到北缘
# =================================================================
for i in range(3):
    b.wall_ns(f"t2_s_{i}", i, 2.0, 1, WALL)   # 南墙踩台面拼缝 y=2
    b.wall_ns(f"t2_n_{i}", i, 3.0, 1, WALL)   # 北墙骑一层北墙顶
b.wall_ew("t2_w", 0.0, 2, 1, WALL)
b.wall_ew("t2_e", 3.0, 2, 1, WALL)
for i in range(3):
    b.flat(f"deck2_{i}", i, 2, 2.0, DECK)

# =================================================================
# 4. 满月 + 玉兔 + 供桌
# =================================================================
b.add("moon", "hexagon", (1.5, 2.0, 2.0 + HEX_APOTHEM), (90, 0, 0), MOON)

b.wall_ns("rabbit_w", 0, 1.0, 1, RABBIT)      # 兔身踩一层台面拼缝 y=1
b.wall_ns("rabbit_e", 1, 1.0, 1, RABBIT)
b.spire_ns("rabbit_ear_w", 0, 1.0, 2.0, RABBIT)
b.spire_ns("rabbit_ear_e", 1, 1.0, 2.0, RABBIT)

b.wall_ns("tbl_s", 2, 0.0, 1, TABLE)          # 供桌骑一层南墙顶/台面沿
b.wall_ns("tbl_n", 2, 1.0, 1, TABLE)
b.wall_ew("tbl_w", 2.0, 0, 1, TABLE)
b.wall_ew("tbl_e", 3.0, 0, 1, TABLE)
b.flat("tbl_top", 2, 0, 2.0, DECK)
b.crest_ns("cake", 2, 0.0, 2.0, CAKE)         # 月饼立在桌面南沿

# =================================================================
# 5. 庭院: 桂花树 x2 + 灯笼 x2
# =================================================================
b.wall_ns("tree_w_trunk", 0, -1.0, 0, TRUNK)  # 树干踩庭院拼缝 y=-1
b.crest_ns("tree_w_leaf", 0, -1.0, 1.0, LEAF)
b.wall_ns("tree_e_trunk", 2, -1.0, 0, TRUNK)
b.crest_ns("tree_e_leaf", 2, -1.0, 1.0, LEAF)
b.crest_ns("lant_w", 0, -2.0, 0.0, LANTERN)   # 灯笼立在庭院南沿
b.crest_ns("lant_e", 2, -2.0, 0.0, LANTERN)

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺庭院地台: 两排清灰相间的方板, 中间留出走向拜月台的甬道视线。",
    [f"yard_{i}_f" for i in range(3)] + [f"yard_{i}_n" for i in range(3)],
    tip="中秋夜全家在庭院集合 —— 地台边缘就是待会儿立灯笼的地方。",
)
b.step(
    "立一层台基的南墙与东墙: 红色方板沿庭院北缝立起, 转角竖边互咬。",
    ["t1_s_0", "t1_s_1", "t1_s_2", "t1_e_0", "t1_e_1", "t1_e_2"],
    highlight=["yard_0_n", "yard_2_n"],
    tip="南墙墙脚正好踩住庭院拼缝, 台基和庭院从此连成一体。",
)
b.step(
    "立一层台基的北墙与西墙: 四面红墙合围, 轻推整圈应一起联动。",
    ["t1_n_0", "t1_n_1", "t1_n_2", "t1_w_0", "t1_w_1", "t1_w_2"],
    highlight=["t1_s_0", "t1_e_0"],
    tip="四角竖边两两互咬 —— 合围的环比四面单墙结实得多。",
)
b.step(
    "铺一层台面: 周边八片黄色方板整边压住墙顶, 中心一片最后落位四邻互吸。",
    [f"deck1_{i}_{j}" for j in (0, 2) for i in range(3)]
    + ["deck1_0_1", "deck1_2_1", "deck1_1_1"],
    highlight=["t1_s_1", "t1_n_1"],
    tip="先铺贴墙的, 再补中心 —— 每片都有现成的边可以吸。",
)
b.step(
    "立二层月台的南墙与东西短墙: 南墙踩台面拼缝, 短墙底边同时吸台面边缘与一层墙顶。",
    ["t2_s_0", "t2_s_1", "t2_s_2", "t2_w", "t2_e"],
    highlight=["deck1_0_2", "deck1_2_2"],
    tip="二层不盖满整层 —— 它整个退到北缘, 前面空出来的就是拜月台。",
)
b.step(
    "立二层北墙: 三片红墙骑上一层北墙顶, 墙上墙上下边完整贴合。",
    ["t2_n_0", "t2_n_1", "t2_n_2"],
    highlight=["t1_n_0", "t1_n_2"],
    tip="北面从地面数上来足足两层高 —— 这是拜月台的靠山。",
)
b.step(
    "铺二层台面: 三片黄色方板压住二层墙顶, 高台落成。",
    ["deck2_0", "deck2_1", "deck2_2"],
    highlight=["t2_s_1", "t2_n_1"],
    tip="台面四边都吸在墙顶上, 高台稳稳当当。",
)
b.step(
    "请出满月: 黄色六边形立在二层台面南沿正中, 底边整边吸住沿口。",
    ["moon"],
    highlight=["deck2_1"],
    tip="六边形立起来就是挂在高台上的一轮满月 —— 今晚月亮最圆!",
)
b.step(
    "玉兔登台: 两片清色方板并肩踩上一层台面拼缝, 两根瘦高尖耳竖在头顶。",
    ["rabbit_w", "rabbit_e", "rabbit_ear_w", "rabbit_ear_e"],
    highlight=["deck1_0_1", "deck1_1_1"],
    tip="兔耳是全模型最高点 —— 玉兔仰着头, 正好望向身后的满月。",
)
b.step(
    "搭供桌: 四片橙色方板在台面东南角合围成方桌腿。",
    ["tbl_s", "tbl_e", "tbl_n", "tbl_w"],
    highlight=["deck1_2_0"],
    tip="桌腿南、东两面骑在一层墙顶上, 北、西两面踩台面拼缝。",
)
b.step(
    "摆上月饼: 黄色桌面压住四条桌腿顶边, 一片黄色三角月饼立在桌沿。",
    ["tbl_top", "cake"],
    highlight=["tbl_s"],
    tip="先吃月饼还是先赏月? 当然是先摆好再说!",
)
b.step(
    "布置庭院收尾: 两棵桂花树立在庭院拼缝上, 两盏红灯笼立在南沿 —— 开始赏月!",
    ["tree_w_trunk", "tree_w_leaf", "tree_e_trunk", "tree_e_leaf",
     "lant_w", "lant_e"],
    highlight=["yard_0_f", "yard_2_f"],
    tip="桂花香, 灯笼亮, 月亮圆 —— 中秋快乐, 阖家团圆!",
)

b.finalize(
    model_id="moon_festival_altar_01",
    name="中秋拜月台",
    name_en="Moon Festival Altar 01",
    description=(
        "节日限定·中秋: 两层红墙黄面的拜月高台 —— 第二层不居中收分, 整层退到"
        "北缘, 空出的前半层正是拜月的月台。黄色六边形满月立在高台南沿正中, "
        "清色玉兔竖着两根瘦高尖耳仰头望月, 供桌上的三角月饼刚刚摆好; 庭院里"
        "桂花树影婆娑, 两盏红灯笼守在门口。把它摆上窗台, 全家一起赏月吧!"
    ),
    difficulty=3,
    tags=["节日", "中秋", "拜月台", "玉兔", "团圆"],
    min_pieces=55,
    min_steps=12,
)
