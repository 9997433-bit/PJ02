#!/usr/bin/env python3
"""生成模型 data/models/climbing_wall_01.json (攀岩训练塔)。

运动健身主题批 1/3: 全库第一座攀岩馆 —— 与既有运动模型全部错开:
篮球/网球/泳池是"场地 + 器械"的平面场景, 跳台滑雪/滑板公园靠
30 度坡道, 操场看台是退台箱体; 本作的主角是"往上爬"这件事本身:
一座 2x2 足印、三层墙环逐环收拢咬合的立式岩塔, 难度色阶从下到
上红-橙-黄, 塔身嵌观察窗与入口门框, 塔基四角直角三角斜撑抗侧倾,
东侧一格"起步石"箱体是孩子的第一脚, 塔顶等腰四坡锥尖直指 4.94
高 —— 全库没有第二座这样的"色阶爬塔"。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 场地软垫 5x4 (x [0,5], y [1,5]): 全单位方板, 内圈红色缓冲垫  20 片
  - 岩塔 (x [1,3], y [2,4], z 0..3): 三层墙环 x8/环, 红橙黄色阶,
    含入口门框方 x1 + 观察窗格方 x4                               24 片
  - 塔顶盖板 x4 (z=3) + 等腰四坡锥顶 x4 (锥尖 4.94)               8 片
  - 起步石 (x [3,4], y [3,4], z 0..1): 借塔东墙, 墙 x3 + 盖 x1    4 片
  - 塔基斜撑 x4: 南面两端 + 西面两端, 直角边分吸墙竖棱与垫缝      4 片
  - 登顶彩旗 x2: 等边三角骑塔顶沿口                                2 片
  合计 62 片, 14 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 三层墙环层层整边共线吸合, 处处闭环, R8 高层检查由环拓扑通过;
  - 塔基四片直角三角斜撑: 竖直角边吸一层墙环的角竖棱, 水平直角边
    吸场地软垫拼缝 (双边受力零悬挑, 摩天大楼同款);
  - 等腰四坡锥顶四条斜棱两两互吸自锁成环, 底边各吸一条盖板沿;
  - 起步石与塔共用一面东墙 (一墙两用), 盖板西沿再吸二层墙脚
    (一线双吸); 彩旗骑顶沿重心正压铰链线力矩为零;
  - 地坪拼缝纪律: 全部软垫为单位方板, 墙脚线与斜撑横边处处有
    等长拼缝可吸。

用法: python3 tools/generate_climbing_wall_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

MAT_IN = "red"       # 塔脚缓冲垫 (内圈)
MAT_OUT = "green"    # 外圈草坪垫
L1 = "red"           # 一层墙 (初级线)
L2 = "orange"        # 二层墙 (中级线)
L3 = "yellow"        # 三层墙 (高级线)
DOOR = "clear"       # 入口门框
WIN = "cyan"         # 观察窗
CAP = "gray"         # 塔顶盖板
PEAK = "red"         # 锥顶
STEP_BOX = "cyan"    # 起步石墙
STEP_CAP = "gray"    # 起步石盖
BRACE = "purple"     # 塔基斜撑
FLAG_A = "blue"      # 登顶旗
FLAG_B = "green"


# ---- 带片型的立墙辅助 (窗格方 / 门框方与 wall_ns/ew 同姿态) ------
def wall_ns_t(tid, tile_type, x0, y, z0, color):
    b.add(tid, tile_type, (x0 + 0.5, y, z0 + 0.5), (90, 0, 0), color)


def wall_ew_t(tid, tile_type, x, y0, z0, color):
    b.add(tid, tile_type, (x, y0 + 0.5, z0 + 0.5), (90, 0, 90), color)


# =================================================================
# 1. 场地软垫 5x4 (x [0,5], y [1,5]): 全单位方板 —— 塔脚线、斜撑
#    横边线处处是等长拼缝; 内圈 (紧贴塔身一圈) 用红色缓冲垫。
# =================================================================
for y0 in range(1, 5):
    for x0 in range(5):
        inner = 0 <= x0 <= 3 and 1 <= y0 <= 4
        b.flat(f"mat_{x0}_{y0}", x0, y0, 0.0, MAT_IN if inner else MAT_OUT)

# =================================================================
# 2. 岩塔三层墙环 (x [1,3], y [2,4]): 红橙黄难度色阶
#    一层南墙西格是入口门框; 二三层各嵌两扇观察窗。
# =================================================================
# 一层 (z 0..1)
wall_ns_t("t1_s_1", "door_frame", 1, 2.0, 0, DOOR)   # 入口
b.wall_ns("t1_s_2", 2, 2.0, 0, L1)
b.wall_ns("t1_n_1", 1, 4.0, 0, L1)
b.wall_ns("t1_n_2", 2, 4.0, 0, L1)
b.wall_ew("t1_w_2", 1.0, 2, 0, L1)
b.wall_ew("t1_w_3", 1.0, 3, 0, L1)
b.wall_ew("t1_e_2", 3.0, 2, 0, L1)
b.wall_ew("t1_e_3", 3.0, 3, 0, L1)
# 二层 (z 1..2)
b.wall_ns("t2_s_1", 1, 2.0, 1, L2)
wall_ns_t("t2_s_2", "window_square", 2, 2.0, 1, WIN)
b.wall_ns("t2_n_1", 1, 4.0, 1, L2)
b.wall_ns("t2_n_2", 2, 4.0, 1, L2)
wall_ew_t("t2_w_2", "window_square", 1.0, 2, 1, WIN)
b.wall_ew("t2_w_3", 1.0, 3, 1, L2)
b.wall_ew("t2_e_2", 3.0, 2, 1, L2)
b.wall_ew("t2_e_3", 3.0, 3, 1, L2)
# 三层 (z 2..3)
wall_ns_t("t3_s_1", "window_square", 1, 2.0, 2, WIN)
b.wall_ns("t3_s_2", 2, 2.0, 2, L3)
b.wall_ns("t3_n_1", 1, 4.0, 2, L3)
b.wall_ns("t3_n_2", 2, 4.0, 2, L3)
b.wall_ew("t3_w_2", 1.0, 2, 2, L3)
wall_ew_t("t3_w_3", "window_square", 1.0, 3, 2, WIN)
b.wall_ew("t3_e_2", 3.0, 2, 2, L3)
b.wall_ew("t3_e_3", 3.0, 3, 2, L3)

# =================================================================
# 3. 起步石 (x [3,4], y [3,4], z 0..1): 借塔一层东墙合环
# =================================================================
b.wall_ns("sb_s", 3, 3.0, 0, STEP_BOX)
b.wall_ns("sb_n", 3, 4.0, 0, STEP_BOX)
b.wall_ew("sb_e", 4.0, 3, 0, STEP_BOX)
b.flat("sb_cap", 3, 3, 1.0, STEP_CAP)

# =================================================================
# 4. 塔基斜撑 x4: 南面两端 (平面 y=2) + 西面两端 (平面 x=1)
# =================================================================
b.brace("br_sw", (1.0, 2.0, 0.0), "-x", BRACE)
b.brace("br_se", (3.0, 2.0, 0.0), "+x", BRACE)
b.brace("br_ws", (1.0, 2.0, 0.0), "-y", BRACE)
b.brace("br_wn", (1.0, 4.0, 0.0), "+y", BRACE)

# =================================================================
# 5. 塔顶: 盖板 x4 + 等腰四坡锥顶 (骑东北盖格) + 登顶彩旗 x2
# =================================================================
b.flat("cap_sw", 1, 2, 3.0, CAP)
b.flat("cap_se", 2, 2, 3.0, CAP)
b.flat("cap_nw", 1, 3, 3.0, CAP)
b.flat("cap_ne", 2, 3, 3.0, CAP)
PEAK_IDS = b.hat4("peak", 2, 3, 3.0, PEAK)          # 锥尖 (2.5, 3.5, 4.94)
b.crest_ns("flag_s", 1, 2.0, 3.0, FLAG_A)           # 骑西南盖格南沿
b.crest_ew("flag_w", 1.0, 2, 3.0, FLAG_B)           # 骑西南盖格西沿

# =================================================================
# 教程步骤 (14 步)
# =================================================================
b.step(
    "铺南半场软垫 (y [1,3]): 两行单位方板, 塔脚一圈用红色缓冲垫。",
    [f"mat_{x0}_{y0}" for y0 in (1, 2) for x0 in range(5)
     if (x0, y0) != (4, 1)],
    tip="攀岩馆的第一条安全规则: 垫子先到位, 岩塔才开工。",
)
b.step(
    "铺北半场软垫 (y [3,5]): 再两行, 每片与邻片等边互吸连成一张网。",
    [f"mat_{x0}_{y0}" for y0 in (3, 4) for x0 in range(5)],
    highlight=["mat_0_2"],
    tip="全部用单位方板 —— 墙脚与斜撑要吸的拼缝一格都不能少。",
)
b.step(
    "立一层南墙与西墙: 入口门框方在西南角, 红色初级线从这里出发。",
    ["t1_s_1", "t1_s_2", "t1_w_2", "t1_w_3"],
    highlight=["mat_1_1"],
    tip="拐角两片竖边一咬, 排墙就变成了立得住的直角。",
)
b.step(
    "立一层北墙与东墙合环: 四角竖边互咬, 一层箱体闭环。",
    ["t1_n_1", "t1_n_2", "t1_e_2", "t1_e_3"],
    highlight=["t1_s_1", "t1_w_2"],
    tip="闭环的墙比一字排开的墙结实得多 —— 这是岩塔的地基环。",
)
b.step(
    "装起步石: 借塔东墙围一格小箱, 再盖上灰色石面。",
    ["sb_s", "sb_n", "sb_e", "sb_cap"],
    highlight=["t1_e_3"],
    tip="塔的东墙同时也是起步石的西墙 —— 一墙两用, 第一脚踩这里。",
)
b.step(
    "装塔基斜撑: 南面两端 + 西面两端, 竖直角边吸墙角竖棱、"
    "水平直角边吸软垫拼缝。",
    ["br_sw", "br_se", "br_ws", "br_wn"],
    highlight=["t1_s_1", "t1_w_3"],
    tip="斜撑双边受力零悬挑 —— 有人攀爬的塔更要抗得住侧向晃动。",
)
b.step(
    "立二层南墙与西墙: 橙色中级线, 整边骑上一层墙顶, 各嵌一扇观察窗。",
    ["t2_s_1", "t2_s_2", "t2_w_2", "t2_w_3"],
    highlight=["t1_s_2"],
    tip="上下两层墙整边共线吸合 —— 色阶换成橙色, 难度升一级。",
)
b.step(
    "立二层北墙与东墙合环: 二层箱体闭环。",
    ["t2_n_1", "t2_n_2", "t2_e_2", "t2_e_3"],
    highlight=["t2_s_1", "sb_cap"],
    tip="二层东墙脚顺带压住起步石盖板西沿 —— 一线双吸。",
)
b.step(
    "立三层南墙与西墙: 黄色高级线, 观察窗换到南面与西面高处。",
    ["t3_s_1", "t3_s_2", "t3_w_2", "t3_w_3"],
    highlight=["t2_s_2"],
    tip="最高一段留给黄色 —— 从楼下看, 红橙黄就是攀爬路线图。",
)
b.step(
    "立三层北墙与东墙合环: 三层箱体闭环, 塔身到顶。",
    ["t3_n_1", "t3_n_2", "t3_e_2", "t3_e_3"],
    highlight=["t3_s_1"],
    tip="三个闭环叠成塔 —— 每一环都是一道保险。",
)
b.step(
    "盖塔顶: 四片灰色盖板压顶, 每片吸墙顶又互吸拼缝。",
    ["cap_sw", "cap_se", "cap_nw", "cap_ne"],
    highlight=["t3_n_2"],
    tip="盖板把第三环锁成箱体 —— 塔顶就是登顶平台。",
)
b.step(
    "起等腰四坡锥顶: 四片瘦高等腰三角骑东北盖格, 斜棱两两互吸。",
    PEAK_IDS,
    highlight=["cap_ne"],
    tip="四条斜棱互咬自锁成环 —— 锥尖 4.94, 全场最高点。",
)
b.step(
    "挂登顶彩旗: 蓝绿两面等边三角骑西南盖格沿口。",
    ["flag_s", "flag_w"],
    highlight=[PEAK_IDS[0]],
    tip="旗子重心正压沿口铰链线, 力矩为零 —— 登顶成功!",
)
b.step(
    "绕塔检查: 三环闭合、四撑到位、锥顶自锁 —— 开爬!",
    ["mat_4_1"],
    highlight=["br_se", "peak_n", "sb_cap"],
    tip="最后补上东南角草坪垫, 检查每条拼缝都吸紧了再开放入场。",
)

b.finalize(
    model_id="climbing_wall_01",
    name="攀岩训练塔",
    name_en="Climbing Wall Tower 01",
    description=(
        "只用核心九片型的攀岩馆立式岩塔: 与篮球场/泳池的平面场地和"
        "滑雪跳台的坡道模型都不同, 这座塔的主角是'往上爬'本身 —— "
        "2x2 足印的三层墙环层层整边咬合, 难度色阶自下而上红-橙-黄, "
        "塔身嵌四扇观察窗与入口门框, 塔基四片紫色直角三角斜撑竖边吸"
        "墙角竖棱、横边吸软垫拼缝 (双边受力零悬挑), 东侧起步石与塔"
        "共用一面墙, 塔顶四片瘦高等腰三角斜棱互咬自锁成 4.94 高的"
        "锥尖, 登顶彩旗骑沿口力矩为零 —— 红线起步, 黄线登顶!"
    ),
    difficulty=3,
    tags=["运动", "健身", "攀岩", "训练塔", "进阶"],
    min_pieces=62,
    min_steps=14,
)
