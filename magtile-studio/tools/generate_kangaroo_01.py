#!/usr/bin/env python3
"""生成模型 data/models/kangaroo_01.json (袋鼠妈妈)。

内容批 I 模型 1/4: 全库第一只袋鼠 —— 与竹林大熊猫 (矮宽坐姿箱体) /
四柱大象 / 图腾柱猫头鹰的结构语言都不同, 本作的招牌是"尾巴当第三条腿":
红色大尾巴是一块 30 度长板, 顶边整边吸在身体箱顶西沿, 坡尾稳稳压地
(顶铰链 + 接地坡尾双路受力, 投石机长臂同款), 正是袋鼠休息时
"双脚 + 尾巴"三点着地的经典姿势; 身前育儿袋是一扇门框方,
小袋鼠就从袋口前跳出来玩。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 袋鼠面朝东):
  - 荒原地面 4 行 (x [0,7], y [0,4]): 沙地 + 红土       21 片
  - 身体 (x [3,5], y [1,3], z 0..1): 墙环 8 (含育儿袋
    门框方) + 箱顶方板 4                                12 片
  - 头部 (x [4,5], y [1,2], z 1..2): 墙 3 + 脸窗格方 1
    + 头顶板 1                                           5 片
  - 长耳朵 x2 (瘦高等腰骑头顶东西沿)                      2 片
  - 大尾巴 (30 度长板, 顶边吸箱顶西沿, 坡尾压地)          1 片
  - 大脚掌 x2 + 小袋鼠 x1 (等边三角骑地面拼缝)            3 片
  - 桉树 (L 形互咬墙 x2 + 树冠叶 x2)                     4 片
  合计 48 片, 10 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告 + jitter 全绿):
  - 尾巴顶边整边吸箱顶方板西沿与身体西墙顶 (三线共吸),
    坡尾压地 —— 顶铰链 + 接地坡尾, 悬臂力矩为零;
  - 身体墙环四角竖边互咬闭环, 箱顶方板四边入扣墙顶;
  - 头部墙脚压箱顶拼缝, 荷载沿墙面层层直下;
  - 耳/脚/小袋鼠都是单片骑沿口, 剪断任何一条装饰连接
    最多失联 1 片, R8 单点失效通过;
  - 桉树两片墙竖边直角互咬 (L 形), 薄墙抗侧靠直角折边;
  - 地坪拼缝纪律: 身体墙脚 / 脚掌 / 小袋鼠底下全单位方板。

用法: python3 tools/generate_kangaroo_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

SAND = "yellow"     # 荒原沙地
EARTH = "orange"    # 红土
FUR = "orange"      # 袋鼠皮毛
BELLY = "clear"     # 白肚皮 (清色)
POUCH = "orange"    # 育儿袋门框方
FACE = "clear"      # 脸 (窗格方当眼睛)
EAR = "red"         # 长耳朵
TAIL = "red"        # 大尾巴
PAW = "gray"        # 大脚掌
JOEY = "pink"       # 小袋鼠
TRUNK = "gray"      # 桉树干
LEAF = "green"      # 树冠

# =================================================================
# 1. 荒原地面 4 行 (x [0,7], y [0,4]): 身体与脚掌底下全单位方板
# =================================================================
# 南行 (y [0,1])
b.flat_rect("g0_a", 0, 0, 0.0, SAND)
b.flat_rect("g0_b", 2, 0, 0.0, EARTH)
b.flat_rect("g0_c", 4, 0, 0.0, SAND)
b.flat("g0_d", 6, 0, 0.0, EARTH)
# 身前行 (y [1,2]): 身体南脚 + 脚掌 / 小袋鼠的单位方板都在这行
b.flat_rect("g1_a", 0, 1, 0.0, EARTH)
b.flat("g1_2", 2, 1, 0.0, SAND)
b.flat("g1_3", 3, 1, 0.0, SAND)
b.flat("g1_4", 4, 1, 0.0, EARTH)
b.flat("g1_5", 5, 1, 0.0, SAND)
b.flat("g1_6", 6, 1, 0.0, SAND)
# 身后行 (y [2,3])
b.flat_rect("g2_a", 0, 2, 0.0, SAND)
b.flat("g2_2", 2, 2, 0.0, EARTH)
b.flat("g2_3", 3, 2, 0.0, EARTH)
b.flat("g2_4", 4, 2, 0.0, SAND)
b.flat("g2_5", 5, 2, 0.0, EARTH)
b.flat("g2_6", 6, 2, 0.0, EARTH)
# 北行 (y [3,4]): 桉树脚下留两块单位方板
b.flat("g3_0", 0, 3, 0.0, SAND)
b.flat("g3_1", 1, 3, 0.0, EARTH)
b.flat_rect("g3_b", 2, 3, 0.0, SAND)
b.flat_rect("g3_c", 4, 3, 0.0, EARTH)
b.flat("g3_6", 6, 3, 0.0, SAND)

# =================================================================
# 2. 身体墙环 (x [3,5], y [1,3], z 0..1): 东面下格是育儿袋门框方
# =================================================================
b.wall_ns("body_s_w", 3, 1.0, 0, FUR)
b.wall_ns("body_s_e", 4, 1.0, 0, BELLY)
b.wall_ns("body_n_w", 3, 3.0, 0, FUR)
b.wall_ns("body_n_e", 4, 3.0, 0, FUR)
b.wall_ew("body_w_s", 3.0, 1, 0, FUR)
b.wall_ew("body_w_n", 3.0, 2, 0, FUR)
b.add("pouch", "door_frame", (5.0, 1.5, 0.5), (90, 0, 90), POUCH)
b.wall_ew("body_e_n", 5.0, 2, 0, FUR)

# 箱顶方板 (z=1): 四片方板四边入扣墙顶
b.flat("back_sw", 3, 1, 1.0, FUR)
b.flat("back_se", 4, 1, 1.0, FUR)
b.flat("back_nw", 3, 2, 1.0, FUR)
b.flat("back_ne", 4, 2, 1.0, FUR)

# =================================================================
# 3. 头部 (x [4,5], y [1,2], z 1..2): 墙脚压箱顶拼缝, 脸朝东
# =================================================================
b.wall_ns("head_s", 4, 1.0, 1, FUR)
b.wall_ns("head_n", 4, 2.0, 1, FUR)
b.wall_ew("head_w", 4.0, 1, 1, FUR)
b.add("head_face", "window_square", (5.0, 1.5, 1.5), (90, 0, 90), FACE)
b.flat("head_top", 4, 1, 2.0, FUR)

# 长耳朵: 瘦高等腰骑头顶东西沿
b.spire_ew("ear_w", 4.0, 1, 2.0, EAR)
b.spire_ew("ear_e", 5.0, 1, 2.0, EAR)

# =================================================================
# 4. 大尾巴: 30 度长板, 顶边吸箱顶西沿, 坡尾压地
# =================================================================
b.ramp("tail", "-x", 3.0, 2, 1.0, TAIL)

# =================================================================
# 5. 大脚掌 x2 + 小袋鼠 (骑地面拼缝)
# =================================================================
b.crest_ns("paw_s", 5, 1.0, 0.0, PAW)
b.crest_ns("paw_n", 5, 3.0, 0.0, PAW)
b.crest_ns("joey", 5, 2.0, 0.0, JOEY)

# =================================================================
# 6. 桉树: L 形互咬墙 + 树冠叶 (西北角)
# =================================================================
b.wall_ns("tree_a", 0, 4.0, 0, TRUNK)
b.wall_ew("tree_b", 1.0, 3, 0, TRUNK)
b.crest_ns("leaf_a", 0, 4.0, 1.0, LEAF)
b.crest_ew("leaf_b", 1.0, 3, 1.0, LEAF)

# =================================================================
# 教程步骤 (10 步)
# =================================================================
b.step(
    "铺荒原南行与身前行: 长板打底, 中段六块单位方板一字排开。",
    ["g0_a", "g0_b", "g0_c", "g0_d",
     "g1_a", "g1_2", "g1_3", "g1_4", "g1_5", "g1_6"],
    tip="澳洲大荒原的清晨 —— 袋鼠妈妈的墙脚要踩在单位方板的拼缝上。",
)
b.step(
    "铺身后行与北行: 行行等边互吸, 西北角留两块单位方板给桉树。",
    ["g2_a", "g2_2", "g2_3", "g2_4", "g2_5", "g2_6",
     "g3_0", "g3_1", "g3_b", "g3_c", "g3_6"],
    highlight=["g1_a"],
    tip="树脚下必须是单位方板 —— 墙底边要和方板边等长吸合。",
)
b.step(
    "立身体南墙与西墙: 清色那片是白肚皮。",
    ["body_s_w", "body_s_e", "body_w_s", "body_w_n"],
    highlight=["g1_3"],
    tip="袋鼠妈妈的身体是 2x2 的墙环 —— 墙脚踩住拼缝才站得稳。",
)
b.step(
    "合身体北墙与东墙: 东面下格嵌门框方, 这就是育儿袋的袋口!",
    ["body_n_w", "body_n_e", "pouch", "body_e_n"],
    highlight=["body_s_w"],
    tip="墙环四角竖边互咬闭环 —— 育儿袋是袋鼠妈妈的随身摇篮。",
)
b.step(
    "盖箱顶: 四片方板四边入扣墙顶, 板板互吸。",
    ["back_sw", "back_se", "back_nw", "back_ne"],
    highlight=["body_s_e"],
    tip="每片方板都咬住墙顶 —— 脑袋和尾巴都要靠这层箱顶。",
)
b.step(
    "起头部: 三片墙加一扇窗格方的脸, 墙脚压住箱顶拼缝。",
    ["head_s", "head_n", "head_w", "head_face"],
    highlight=["back_se"],
    tip="窗格方朝东 —— 袋鼠妈妈的大眼睛正望着日出的方向。",
)
b.step(
    "盖头顶并竖长耳朵: 两片瘦高等腰一东一西骑住头顶沿。",
    ["head_top", "ear_w", "ear_e"],
    highlight=["head_s"],
    tip="长耳朵是袋鼠的雷达 —— 一有动静立刻转过来。",
)
b.step(
    "搭大尾巴: 红色 30 度长板顶边整边吸箱顶西沿, 坡尾稳稳压地。",
    ["tail"],
    highlight=["back_nw", "g2_a"],
    tip="顶铰链 + 接地坡尾 —— 尾巴就是袋鼠的第三条腿!",
)
b.step(
    "放大脚掌与小袋鼠: 两片灰色大脚一前一后, 粉色小袋鼠蹦到袋口前。",
    ["paw_s", "paw_n", "joey"],
    highlight=["pouch"],
    tip="双脚加尾巴三点着地 —— 这是袋鼠最省力的休息姿势。",
)
b.step(
    "种桉树: 两片灰墙竖边直角互咬, 树冠挂上两片绿叶。",
    ["tree_a", "tree_b", "leaf_a", "leaf_b"],
    highlight=["g3_0"],
    tip="L 形折边就是树干的靠山 —— 桉树叶可是袋鼠邻居考拉的最爱。",
)

b.finalize(
    model_id="kangaroo_01",
    name="袋鼠妈妈",
    name_en="Kangaroo Mum 01",
    description=(
        "只用核心九片型的全库第一只袋鼠: 与坐姿箱体的大熊猫不同, "
        "本作的招牌是'尾巴当第三条腿' —— 红色大尾巴是一块 30 度长板, "
        "顶边整边吸在身体箱顶西沿, 坡尾稳稳压地 (顶铰链 + 接地坡尾, "
        "重量走两条路), 配上两片灰色大脚掌, 正是袋鼠'双脚 + 尾巴'"
        "三点着地的经典休息姿势; 身前育儿袋是一扇门框方袋口, 粉色"
        "小袋鼠蹦到袋口前玩耍, 头顶两只瘦高长耳朵一竖 —— 澳洲大荒原"
        "的清晨, 袋鼠妈妈带宝宝出门啦!"
    ),
    difficulty=2,
    tags=["自然", "动物世界", "袋鼠", "澳洲", "亲子"],
    min_pieces=48,
    min_steps=10,
)
