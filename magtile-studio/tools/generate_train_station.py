#!/usr/bin/env python3
"""生成模型 data/models/train_station_01.json (中央火车站)。

第二批模型 ⑩: 交通枢纽主题 —— 中央火车站: 站台 + 雨棚 + 带
人字坡屋顶的候车大厅, 站线上停着一列蓝色小火车 (车头 + 货厢),
站台两端还有无障碍坡道, 轨旁立着红绿信号旗。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 轨道: 6 片灰色方板一字排开                                 6 片
  - 站台 (高 1): 前后挡墙 12 + 台面 6 + 两端坡道 2            20 片
  - 雨棚: 站台上 3 根立柱 + 2 片透明棚顶                        5 片
  - 候车大厅 (x 1..5, y 0..1): 地板 4 + 墙体 15 + 檐口 4      23 片
  - 人字坡屋顶: 4 片 60 度斜置长方形 + 2 片等边三角山花         6 片
  - 小火车: 车头 (含烟囱) 7 + 货厢 6 (北壁借用站台挡墙)       13 片
  - 信号旗: 轨旁红绿等腰三角 2                                  2 片
  合计 75 片, 18 个教程步骤, 4 种磁力片形状。

几何要点 (全部整边精确吸合):
  - 人字坡屋顶: 长方形以 60 度斜置, 底长边吸檐口横楣顶边,
    脊线两长边互吸; 山花正好是等边三角形 (底 1, 高 0.866),
    两腰与坡面短边完全重合;
  - 大厅南墙下层直接借用站台后挡墙 (共墙不重叠);
  - 火车车厢立墙直接吸在轨道板边上, 车顶与站台台面同高互吸。

用法: python3 tools/generate_train_station.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

RIDGE_H = 0.866025          # 等边山花高 = 60 度坡面竖直投影

# =================================================================
# 1. 轨道 (y -2..-1): 6 片灰色方板
# =================================================================
for x in range(6):
    b.flat(f"trk_{x}", x, -2, 0.0, "gray")

# =================================================================
# 2. 站台 (y -1..0, 高 1): 前后挡墙 + 台面 + 两端坡道
# =================================================================
for x in range(6):
    b.wall_ns(f"pf_f_{x}", x, -1.0, 0, "yellow")     # 前挡墙 (轨道侧)
    b.wall_ns(f"pf_b_{x}", x, 0.0, 0, "yellow")      # 后挡墙 (大厅侧)
for x in range(6):
    b.flat(f"pf_d_{x}", x, -1, 1.0, "gray")          # 台面
b.ramp("pf_rw", "-x", 0.0, -1, 1.0, "orange")        # 西端无障碍坡道
b.ramp("pf_re", "+x", 6.0, -1, 1.0, "orange")        # 东端无障碍坡道

# =================================================================
# 3. 雨棚: 台面接缝处 3 根立柱 (x=1/3/5) + 2 片透明棚顶
# =================================================================
for x in (1, 3, 5):
    b.wall_ew(f"cn_c_{x}", float(x), -1, 1, "gray")
b.add("cn_r_w", "rectangle", (2.0, -0.5, 2.0), (0, 0, 0), "clear")   # 棚顶 x 1..3
b.add("cn_r_e", "rectangle", (4.0, -0.5, 2.0), (0, 0, 0), "clear")   # 棚顶 x 3..5

# =================================================================
# 4. 候车大厅 (x 1..5, y 0..1, z 0..3): 南墙下层借用站台后挡墙
# =================================================================
for x in range(1, 5):
    b.flat(f"h_fl_{x}", x, 0, 0.0, "gray")           # 大厅地板
for x in range(1, 5):
    b.wall_ns(f"h_s2_{x}", x, 0.0, 1, "orange")      # 南墙上层 (下层=后挡墙)
b.wall_ns("h_n1_w", 1, 1.0, 0, "orange")             # 北墙下层西段
b.wall_ns("h_n1_e", 4, 1.0, 0, "orange")             # 北墙下层东段 (中间 2 格大门)
for x in (1, 4):
    b.wall_ns(f"h_n2_{x}", x, 1.0, 1, "orange")      # 北墙上层两端
b.lintel_ns("h_n2_lin", 2, 1.0, 1, "yellow")         # 大门门楣 (跨 x 2..4)
for z in range(3):
    b.wall_ew(f"h_w_{z}", 1.0, 0, z, "orange")       # 西山墙 3 层
    b.wall_ew(f"h_e_{z}", 5.0, 0, z, "orange")       # 东山墙 3 层
b.lintel_ns("h_ev_s_w", 1, 0.0, 2, "yellow")         # 南檐口西段 (z 2..3)
b.lintel_ns("h_ev_s_e", 3, 0.0, 2, "yellow")         # 南檐口东段
b.lintel_ns("h_ev_n_w", 1, 1.0, 2, "yellow")         # 北檐口西段
b.lintel_ns("h_ev_n_e", 3, 1.0, 2, "yellow")         # 北檐口东段

# =================================================================
# 5. 人字坡屋顶: 60 度斜置长方形 x4 + 等边三角山花 x2
# =================================================================
for tid, x0 in (("rf_s_w", 1.0), ("rf_s_e", 3.0)):   # 南坡面
    b.place_edge(tid, "rectangle", 0, (x0, 0.0, 3.0), (x0 + 2, 0.0, 3.0),
                 (0.0, 0.5, RIDGE_H), "red")
for tid, x0 in (("rf_n_w", 3.0), ("rf_n_e", 1.0)):   # 北坡面
    b.place_edge(tid, "rectangle", 0, (x0 + 2, 1.0, 3.0), (x0, 1.0, 3.0),
                 (0.0, -0.5, RIDGE_H), "red")
b.crest_ew("gab_w", 1.0, 0, 3.0, "yellow")           # 西山花
b.crest_ew("gab_e", 5.0, 0, 3.0, "yellow")           # 东山花

# =================================================================
# 6. 小火车 (立墙箱式车身直接吸轨道板边): 车头 x 0..2, 货厢 x 3..5
# =================================================================
for x in (0, 1):
    b.wall_ns(f"en_s_{x}", x, -2.0, 0, "blue")       # 车头南壁 (北壁=站台前挡墙)
b.wall_ew("en_w", 0.0, -2, 0, "clear")               # 车头挡风玻璃
b.wall_ew("en_e", 2.0, -2, 0, "blue")                # 车头尾板
for x in (0, 1):
    b.flat(f"en_rf_{x}", x, -2, 1.0, "blue")         # 车头顶
b.crest_ns("en_fun", 0, -2.0, 1.0, "gray")           # 烟囱
for x in (3, 4):
    b.wall_ns(f"wg_s_{x}", x, -2.0, 0, "green")      # 货厢南壁 (北壁=站台前挡墙)
b.wall_ew("wg_w", 3.0, -2, 0, "green")               # 货厢前板
b.wall_ew("wg_e", 5.0, -2, 0, "green")               # 货厢后板
for x in (3, 4):
    b.flat(f"wg_rf_{x}", x, -2, 1.0, "green")        # 货厢顶

# =================================================================
# 7. 信号旗: 轨旁红绿等腰三角
# =================================================================
b.spire_ns("sig_w", 2, -2.0, 0.0, "red")             # 停车信号 (车头后方)
b.spire_ns("sig_e", 5, -2.0, 0.0, "green")           # 通行信号 (货厢后方)

# =================================================================
# 教程步骤 (19 步)
# =================================================================
b.step(
    "铺设轨道: 6 片灰色方板沿东西向一字排开, 相邻边互相吸合。",
    [f"trk_{x}" for x in range(6)],
    tip="这条 6 格长的轨道就是火车站的中轴线, 请沿桌面摆直。",
)
b.step(
    "竖立站台前挡墙: 6 片黄色正方形沿轨道北沿立起 (y=-1)。",
    [f"pf_f_{x}" for x in range(6)],
    highlight=["trk_0", "trk_5"],
    tip="挡墙底边吸轨道板边, 竖边两两互吸 —— 站台的第一道边。",
)
b.step(
    "竖立站台后挡墙并铺台面: 6 片黄色正方形与前挡墙平行立起 (y=0), "
    "随即用 6 片灰色方板压在前后挡墙顶上, 站台升起 1 格高。",
    [f"pf_b_{x}" for x in range(6)] + [f"pf_d_{x}" for x in range(6)],
    highlight=["pf_f_0"],
    tip="台面两长边分别吸住前后挡墙顶边 —— 前墙、后墙、台面锁成箱形梁。",
)
b.step(
    "安装无障碍坡道: 站台两端各 1 片 30 度橙色坡道, 顶边吸台面边、"
    "坡尾自然落地。",
    ["pf_rw", "pf_re"],
    highlight=["pf_d_0", "pf_d_5"],
    tip="婴儿车和行李箱都能顺着坡道上站台。",
)
b.step(
    "铺设大厅地板: 站台后方平铺 4 片灰色方板 (x 1..5)。",
    [f"h_fl_{x}" for x in range(1, 5)],
    highlight=["pf_b_1"],
    tip="地板前边与后挡墙底边同缝吸合, 大厅与站台连为一体。",
)
b.step(
    "竖立大厅北墙下层与山墙下层: 北墙两端各 1 片 (中间留 2 格大门), "
    "东西山墙各 1 片。",
    ["h_n1_w", "h_n1_e", "h_w_0", "h_e_0"],
    highlight=["h_fl_1", "h_fl_4"],
    tip="大门开在北面正中, 宽 2 格 —— 旅客从街边直接进大厅。",
)
b.step(
    "大厅升到 2 层: 南墙上层 4 片 (直接叠在站台后挡墙顶上), "
    "北墙上层两端 2 片, 山墙各叠 1 片。",
    [f"h_s2_{x}" for x in range(1, 5)] + ["h_n2_1", "h_n2_4", "h_w_1", "h_e_1"],
    highlight=["pf_b_1"],
    tip="南墙下层就是站台后挡墙 —— 共墙不重复, 一墙两用。",
)
b.step(
    "安装大门门楣: 1 片黄色长方形横跨大门上方, 两端竖边吸北墙上层竖边。",
    ["h_n2_lin"],
    highlight=["h_n2_1", "h_n2_4"],
    tip="门楣底边悬空不用怕, 两端竖边 + 顶上檐口共同受力。",
)
b.step(
    "山墙加到 3 层并安装檐口横楣: 先叠山墙第 3 层, 再在南北沿各竖立 "
    "2 片黄色长方形 (z 2..3), 横楣竖边吸山墙竖边。",
    ["h_w_2", "h_e_2", "h_ev_s_w", "h_ev_s_e", "h_ev_n_w", "h_ev_n_e"],
    highlight=["h_s2_1"],
    tip="檐口顶边是 2 格长的整边 —— 那是给坡屋顶准备的着床。",
)
b.step(
    "架南坡屋面: 2 片红色长方形以 60 度斜置, 底长边整边吸南檐口顶边, "
    "顶长边悬向屋脊。",
    ["rf_s_w", "rf_s_e"],
    highlight=["h_ev_s_w", "h_ev_s_e"],
    tip="坡面先别松手 —— 等北坡架上, 脊线两长边一吸就稳了。",
)
b.step(
    "架北坡屋面并合脊: 2 片红色长方形从北侧斜置, 脊线处两坡长边互吸, "
    "人字屋顶合拢。",
    ["rf_n_w", "rf_n_e"],
    highlight=["rf_s_w"],
    tip="咔哒一声, 四片坡面在屋脊锁成一体 —— 这就是人字坡。",
)
b.step(
    "封山花: 东西山墙顶各立 1 片黄色等边三角形, 两腰恰好吸住坡面端边。",
    ["gab_w", "gab_e"],
    highlight=["rf_s_w", "rf_n_e"],
    tip="等边三角形底 1 高 0.866, 和 60 度坡面严丝合缝 —— 几何的魔法。",
)
b.step(
    "竖立雨棚立柱: 台面接缝处立 3 根灰色立柱 (x=1/3/5)。",
    ["cn_c_1", "cn_c_3", "cn_c_5"],
    highlight=["pf_d_1", "pf_d_3"],
    tip="立柱底边吸台面接缝, 间距均为 2 格。",
)
b.step(
    "盖雨棚棚顶: 2 片透明长方形平放在立柱顶上, 短边吸柱顶边。",
    ["cn_r_w", "cn_r_e"],
    highlight=["cn_c_3"],
    tip="透明棚顶挡雨不挡光, 站台上亮堂堂。",
)
b.step(
    "拼装车头: 轨道西段立起南壁 2 片、透明挡风玻璃与尾板 "
    "(北壁直接借用站台前挡墙)。",
    ["en_s_0", "en_s_1", "en_w", "en_e"],
    highlight=["trk_0", "trk_1"],
    tip="车壁底边直接吸轨道板边, 端板竖边还吸住站台挡墙 —— 火车稳稳靠站。",
)
b.step(
    "封车头顶并装烟囱: 2 片蓝色车顶盖住车身, 车顶前端立 1 片灰色"
    "三角烟囱。",
    ["en_rf_0", "en_rf_1", "en_fun"],
    highlight=["en_s_0"],
    tip="车顶北边正好与站台台面同高互吸 —— 上下车零落差。",
)
b.step(
    "拼装货厢: 车头后方 1 格空隙外, 再拼一节 2 格长的绿色货厢并封顶 "
    "(北壁同样借用站台前挡墙)。",
    ["wg_s_3", "wg_s_4", "wg_w", "wg_e", "wg_rf_3", "wg_rf_4"],
    highlight=["en_e"],
    tip="车头与货厢之间留 1 格当车钩 —— 像真火车一样分节。",
)
b.step(
    "插信号旗: 轨旁立红绿两面等腰三角旗, 中央火车站发车!",
    ["sig_w", "sig_e"],
    highlight=["trk_2", "trk_5"],
    tip="红旗停、绿旗行 —— 小站长, 该你值班了。",
)

b.finalize(
    model_id="train_station_01",
    name="中央火车站",
    name_en="Train Station 01",
    description=(
        "交通枢纽全景: 6 格长轨道上停着蓝色车头与绿色货厢, 1 格高的箱形站台"
        "两端接无障碍坡道, 站台上 3 柱透明雨棚; 候车大厅开 2 格宽大门, 顶上是"
        "4 片 60 度斜置长方形合脊的人字坡屋顶, 两端等边三角山花严丝合缝 —— "
        "红旗停、绿旗行, 小站长快来值班。"
    ),
    difficulty=4,
    tags=["交通", "火车", "建筑", "进阶"],
    min_pieces=75,
    min_steps=18,
)
