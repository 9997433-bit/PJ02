#!/usr/bin/env python3
"""生成模型 data/models/freight_yard_01.json (驼峰货运编组场)。

铁路/火车站主题: 全库第一座驼峰编组场 —— 与中央火车站 (客运站台+
候车大厅) 和单轨列车段 (高架墩柱+跨座列车) 刻意区分, 本作的结构
逻辑是 "驼峰放坡 + 三线并行 + 轮上货列 + 箱区堆场":
西端 2x2 箱形驼峰台从场坪拔起, 一条 30 度溜放坡道顺着调车线
滑下; 调车线/分类线两条股道夹着中央理货平台带向东铺开;
调车线上一节满载棚车 (车轮底座托底盘, 箱式货厢锁在底盘上),
分类线上一节空敞车溜放到位; 场坪东南角集装箱堆场两箱叠高;
理货平台东端 1x1 两层调度塔 (四面窗格方了望层) 戴等边四坡
锥顶; 两条股道尽头各立缓冲挡板, 驼峰顶与场中信号塔尖对望。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 场坪 (x [0,10], y [0,1]): 灰色长板 x5                         5 片
  - 调车线 (y [1,2]) / 理货平台 (y [2,3]) / 分类线 (y [3,4]):
    各 6 片方板 (x [4,10])                                       18 片
  - 驼峰台 (x [0,2], y [1,3], z 0..1): 墙环 8 + 台面 4 +
    30 度溜放坡道 1                                              13 片
  - 满载棚车 (x [5,7], 调车线): 车轮底座 2 + 底盘长板 1 +
    货厢墙环 6 + 厢顶 2                                          11 片
  - 空敞车 (x [6,8], 分类线): 车轮底座 2 + 底盘长板 1 + 端板 2    5 片
  - 集装箱堆场 (x [8,10], y [0,1]): 两箱叠高, 每箱墙环 6 + 顶 2  16 片
  - 调度塔 (x [9,10], y [2,3]): 一层墙环 4 (东面门框方) +
    二层窗格方 x4 + 塔台板 1 + 等边四坡锥顶 4 (锥尖 2.71)        13 片
  - 缓冲挡板 x2 + 信号塔尖 x2                                     4 片
  合计 85 片, 20 个教程步骤, 7 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 溜放坡道顶短边同吸驼峰台面沿与东墙顶边 (一线双吸), 坡尾
    自然落地 —— 剪断顶铰链坡道自身仍接地;
  - 货车是 "轮上箱": 底盘长板双长边整边压两片车轮底座顶边,
    货厢墙环踩底盘沿边、厢顶双边压墙顶 —— 轮-盘-厢锁成箱形闭环;
  - 集装箱两箱叠高: 上箱墙脚整边吸下箱顶板沿边, 层层墙环闭合;
  - 调度塔锥尖 2.71 触发 R8 高层检查: 塔身层层墙环 + 锥顶四棱
    互吸自锁, 连接图处处成环, 无单点失效;
  - 信号塔尖/缓冲挡板重心正压铰链线, 力矩为零。

用法: python3 tools/generate_freight_yard.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

APRON = "gray"      # 场坪
TRACK = "gray"      # 股道
MID = "yellow"      # 理货平台带
HUMP = "orange"     # 驼峰台墙体
HDECK = "gray"      # 驼峰台面
RAMP = "orange"     # 溜放坡道
WHEEL = "gray"      # 车轮底座
CHASSIS = "blue"    # 车辆底盘
BOX = "red"         # 棚车货厢
BOARD = "blue"      # 敞车端板
CT1 = "blue"        # 集装箱下箱
CT2 = "green"       # 集装箱上箱
TOWER = "orange"    # 调度塔一层
DOOR = "red"        # 塔门
WIN = "clear"       # 了望窗
TDECK = "gray"      # 塔台板
TROOF = "red"       # 塔锥顶
BUF = "red"         # 缓冲挡板
SIG_H = "yellow"    # 驼峰信号
SIG_Y = "green"     # 场中信号

# =================================================================
# 1. 场坪 (x [0,10], y [0,1]): 5 片灰色长板
# =================================================================
for k in range(5):
    b.flat_rect(f"ap_{k}", 2 * k, 0, 0.0, APRON)

# =================================================================
# 2. 三线并行 (x [4,10]): 调车线 / 理货平台带 / 分类线
# =================================================================
for x in range(4, 10):
    b.flat(f"tk_a_{x}", x, 1, 0.0, TRACK)       # 调车线 y [1,2]
for x in range(4, 10):
    b.flat(f"mid_{x}", x, 2, 0.0, MID)          # 理货平台 y [2,3]
for x in range(4, 10):
    b.flat(f"tk_b_{x}", x, 3, 0.0, TRACK)       # 分类线 y [3,4]

# =================================================================
# 3. 驼峰台 (x [0,2], y [1,3], z 0..1): 墙环 + 台面 + 溜放坡道
# =================================================================
b.wall_ns("hp_s_0", 0, 1.0, 0, HUMP)
b.wall_ns("hp_s_1", 1, 1.0, 0, HUMP)
b.wall_ew("hp_w_0", 0.0, 1, 0, HUMP)
b.wall_ew("hp_w_1", 0.0, 2, 0, HUMP)
b.wall_ns("hp_n_0", 0, 3.0, 0, HUMP)
b.wall_ns("hp_n_1", 1, 3.0, 0, HUMP)
b.wall_ew("hp_e_0", 2.0, 1, 0, HUMP)
b.wall_ew("hp_e_1", 2.0, 2, 0, HUMP)
for x in range(2):
    for y in (1, 2):
        b.flat(f"hp_d_{x}_{y}", x, y, 1.0, HDECK)
b.ramp("hp_ramp", "+x", 2.0, 1, 1.0, RAMP)      # 溜放坡道 (顺调车线)
b.spire_ns("sig_hump", 0, 1.0, 1.0, SIG_H)      # 驼峰信号 (骑台面南沿)

# =================================================================
# 4. 满载棚车 (x [5,7], 调车线): 轮-盘-厢锁成箱形闭环
# =================================================================
b.add("fw_wh_s", "wheel_base", (6.0, 1.0, 0.5), (90, 0, 0), WHEEL)
b.add("fw_wh_n", "wheel_base", (6.0, 2.0, 0.5), (90, 0, 0), WHEEL)
b.flat_rect("fw_deck", 5, 1, 1.0, CHASSIS)
b.wall_ew("fw_c_w", 5.0, 1, 1, BOX)
b.wall_ns("fw_c_s0", 5, 1.0, 1, BOX)
b.wall_ns("fw_c_s1", 6, 1.0, 1, BOX)
b.wall_ew("fw_c_e", 7.0, 1, 1, BOX)
b.wall_ns("fw_c_n0", 5, 2.0, 1, BOX)
b.wall_ns("fw_c_n1", 6, 2.0, 1, BOX)
b.flat("fw_rf_0", 5, 1, 2.0, BOX)
b.flat("fw_rf_1", 6, 1, 2.0, BOX)

# =================================================================
# 5. 空敞车 (x [6,8], 分类线): 溜放到位
# =================================================================
b.add("ew_wh_s", "wheel_base", (7.0, 3.0, 0.5), (90, 0, 0), WHEEL)
b.add("ew_wh_n", "wheel_base", (7.0, 4.0, 0.5), (90, 0, 0), WHEEL)
b.flat_rect("ew_deck", 6, 3, 1.0, CHASSIS)
b.wall_ew("ew_b_w", 6.0, 3, 1, BOARD)
b.wall_ew("ew_b_e", 8.0, 3, 1, BOARD)

# =================================================================
# 6. 集装箱堆场 (x [8,10], y [0,1]): 两箱叠高
# =================================================================
b.wall_ew("st1_w", 8.0, 0, 0, CT1)
b.wall_ns("st1_s0", 8, 0.0, 0, CT1)
b.wall_ns("st1_s1", 9, 0.0, 0, CT1)
b.wall_ew("st1_e", 10.0, 0, 0, CT1)
b.wall_ns("st1_n0", 8, 1.0, 0, CT1)
b.wall_ns("st1_n1", 9, 1.0, 0, CT1)
b.flat("st1_rf_0", 8, 0, 1.0, CT1)
b.flat("st1_rf_1", 9, 0, 1.0, CT1)
b.wall_ew("st2_w", 8.0, 0, 1, CT2)
b.wall_ns("st2_s0", 8, 0.0, 1, CT2)
b.wall_ns("st2_s1", 9, 0.0, 1, CT2)
b.wall_ew("st2_e", 10.0, 0, 1, CT2)
b.wall_ns("st2_n0", 8, 1.0, 1, CT2)
b.wall_ns("st2_n1", 9, 1.0, 1, CT2)
b.flat("st2_rf_0", 8, 0, 2.0, CT2)
b.flat("st2_rf_1", 9, 0, 2.0, CT2)

# =================================================================
# 7. 调度塔 (x [9,10], y [2,3]): 两层塔身 + 塔台板 + 等边四坡锥顶
# =================================================================
b.wall_ns("tw_s", 9, 2.0, 0, TOWER)
b.wall_ew("tw_w", 9.0, 2, 0, TOWER)
b.wall_ns("tw_n", 9, 3.0, 0, TOWER)
b.add("tw_door", "door_frame", (10.0, 2.5, 0.5), (90, 0, 90), DOOR)
b.add("tw_w2_s", "window_square", (9.5, 2.0, 1.5), (90, 0, 0), WIN)
b.add("tw_w2_w", "window_square", (9.0, 2.5, 1.5), (90, 0, 90), WIN)
b.add("tw_w2_n", "window_square", (9.5, 3.0, 1.5), (90, 0, 0), WIN)
b.add("tw_w2_e", "window_square", (10.0, 2.5, 1.5), (90, 0, 90), WIN)
b.flat("tw_deck", 9, 2, 2.0, TDECK)
TW_ROOF = b.hat4("tw_roof", 9, 2, 2.0, TROOF, shape="equilateral_triangle")

# =================================================================
# 8. 缓冲挡板 + 场中信号
# =================================================================
b.wall_ew("buf_a", 10.0, 1, 0, BUF)             # 调车线尽头
b.wall_ew("buf_b", 10.0, 3, 0, BUF)             # 分类线尽头
b.spire_ns("sig_yard", 4, 2.0, 0.0, SIG_Y)      # 场中信号 (骑股道拼缝)

# =================================================================
# 教程步骤 (20 步)
# =================================================================
b.step(
    "铺场坪: 5 片灰色长板沿南沿一字排开 (x [0,10], y [0,1])。",
    [f"ap_{k}" for k in range(5)],
    tip="场坪是整座编组场的基准线 —— 驼峰、堆场、股道都从它生根。",
)
b.step(
    "铺调车线: 6 片方板 (x [4,10], y [1,2]), 南边整边吸场坪。",
    [f"tk_a_{x}" for x in range(4, 10)],
    highlight=["ap_2", "ap_4"],
    tip="调车线正对驼峰坡道 —— 车辆从坡上溜下来就走这条线。",
)
b.step(
    "铺理货平台带: 6 片黄色方板 (y [2,3]) 夹在两线之间。",
    [f"mid_{x}" for x in range(4, 10)],
    highlight=["tk_a_4"],
    tip="理货员站在这条带上, 左右两线装卸两不误。",
)
b.step(
    "铺分类线: 再排 6 片方板 (y [3,4]), 三线并行。",
    [f"tk_b_{x}" for x in range(4, 10)],
    highlight=["mid_4", "mid_9"],
    tip="编组场的样子出来了 —— 三条带子并排向东。",
)
b.step(
    "立驼峰台南墙与西墙: 4 片橙色立墙踩场坪沿边 (x [0,2])。",
    ["hp_s_0", "hp_s_1", "hp_w_0", "hp_w_1"],
    highlight=["ap_0"],
    tip="墙脚整边吸场坪北沿, 竖边两两互咬。",
)
b.step(
    "合驼峰台墙环: 北墙与东墙各 2 片, 8 片墙锁成 2x2 箱形。",
    ["hp_n_0", "hp_n_1", "hp_e_0", "hp_e_1"],
    highlight=["hp_s_0", "hp_w_1"],
    tip="箱形墙环是驼峰台的骨架 —— 处处成环, 剪一条不塌。",
)
b.step(
    "盖驼峰台面: 4 片灰色方板压墙顶, 台面升到 1 格高。",
    ["hp_d_0_1", "hp_d_1_1", "hp_d_0_2", "hp_d_1_2"],
    highlight=["hp_s_0", "hp_n_1"],
    tip="每片台面同时吸墙顶与邻板拼缝 —— 调车员站上去稳稳的。",
)
b.step(
    "架溜放坡道并立驼峰信号: 30 度橙色坡道顶短边同吸台面沿与东墙顶 "
    "(一线双吸), 坡尾自然落地; 黄色信号塔尖骑上台面南沿。",
    ["hp_ramp", "sig_hump"],
    highlight=["hp_d_1_1", "hp_e_0"],
    tip="驼峰的精髓就是这条坡 —— 车辆靠重力溜进调车线。",
)
b.step(
    "满载棚车落轮上盘: 2 片车轮底座立在调车线上 (x [5,7]), 蓝色底盘"
    "长板双长边压轮顶。",
    ["fw_wh_s", "fw_wh_n", "fw_deck"],
    highlight=["tk_a_5", "tk_a_6"],
    tip="车轮底座就是货车的转向架 —— 底盘一压, 轮盘锁成整体。",
)
b.step(
    "起货厢前半环: 西端板 + 南墙 2 片 + 东端板踩底盘沿边。",
    ["fw_c_w", "fw_c_s0", "fw_c_s1", "fw_c_e"],
    highlight=["fw_deck"],
    tip="墙脚吸底盘边, 端板与南墙竖边互咬 —— 先围三面。",
)
b.step(
    "合货厢盖厢顶: 北墙 2 片合环, 2 片红色厢顶双边压墙顶。",
    ["fw_c_n0", "fw_c_n1", "fw_rf_0", "fw_rf_1"],
    highlight=["fw_c_w", "fw_c_e"],
    tip="轮-盘-厢锁成箱形闭环 —— 这节棚车拎起来都不散。",
)
b.step(
    "空敞车溜放到位: 分类线上 (x [6,8]) 再落一组轮上底盘, 前后端板"
    "立在底盘短边上。",
    ["ew_wh_s", "ew_wh_n", "ew_deck", "ew_b_w", "ew_b_e"],
    highlight=["tk_b_6", "tk_b_7"],
    tip="敞车不带顶 —— 它刚从驼峰溜下来, 等着装货。",
)
b.step(
    "砌下层集装箱墙环: 场坪东南角 (x [8,10]) 6 片蓝色立墙锁成箱形。",
    ["st1_w", "st1_s0", "st1_s1", "st1_e", "st1_n0", "st1_n1"],
    highlight=["ap_4"],
    tip="堆场的第一层 —— 墙脚整边吸场坪沿边与拼缝。",
)
b.step(
    "封下箱顶板: 2 片蓝色方板压墙顶。",
    ["st1_rf_0", "st1_rf_1"],
    highlight=["st1_w", "st1_e"],
    tip="顶板就是上一箱的地基 —— 集装箱天生为叠高而生。",
)
b.step(
    "叠上层集装箱墙环: 6 片绿色立墙踩下箱顶板沿边。",
    ["st2_w", "st2_s0", "st2_s1", "st2_e", "st2_n0", "st2_n1"],
    highlight=["st1_rf_0", "st1_rf_1"],
    tip="上箱墙脚与下箱顶沿整边吸合 —— 层层墙环闭合。",
)
b.step(
    "封上箱顶板: 2 片绿色方板压顶, 双层堆场完工。",
    ["st2_rf_0", "st2_rf_1"],
    highlight=["st2_w", "st2_e"],
    tip="两箱叠高 2.0 —— 龙门吊来了也认得整整齐齐。",
)
b.step(
    "起调度塔一层: 理货平台东端 (x [9,10]) 3 片橙色墙 + 东面门框方塔门。",
    ["tw_s", "tw_w", "tw_n", "tw_door"],
    highlight=["mid_9"],
    tip="塔门朝东开在场外 —— 调度员不用横穿股道。",
)
b.step(
    "叠了望层: 4 片窗格方围出二层全景了望窗。",
    ["tw_w2_s", "tw_w2_w", "tw_w2_n", "tw_w2_e"],
    highlight=["tw_s", "tw_door"],
    tip="四面通透 —— 驼峰、股道、堆场尽收眼底。",
)
b.step(
    "封塔台板、戴等边四坡锥顶: 锥尖 2.71 全场最高, 四棱互吸自锁。",
    ["tw_deck"] + TW_ROOF,
    highlight=["tw_w2_s", "tw_w2_e"],
    tip="锥顶四条斜棱两两互吸 —— 高塔顶上也处处成环。",
)
b.step(
    "立缓冲挡板与场中信号: 两条股道尽头各立红色挡板, 绿色信号塔尖"
    "骑上股道拼缝 —— 驼峰放坡, 编组开始!",
    ["buf_a", "buf_b", "sig_yard"],
    highlight=["tk_a_9", "tk_b_9"],
    tip="挡板底边整边吸道床边, 重心正压铰链 —— 溜放的车辆稳稳停住。",
)

b.finalize(
    model_id="freight_yard_01",
    name="驼峰货运编组场",
    name_en="Freight Yard 01",
    description=(
        "只用核心九片型的驼峰编组场: 西端 2x2 箱形驼峰台放出 30 度"
        "溜放坡道, 调车线/理货平台/分类线三线并行向东铺开; 调车线上"
        "一节满载棚车 —— 车轮底座托底盘长板, 货厢墙环与厢顶锁成箱形"
        "闭环, 分类线上空敞车溜放到位; 场坪东南角集装箱两箱叠高,"
        " 理货平台东端 1x1 调度塔四面窗格方了望层戴等边四坡锥顶"
        " (锥尖 2.71); 两线尽头缓冲挡板把守, 驼峰信号与场中信号"
        "对望 —— 驼峰放坡, 车辆靠重力溜进分类线, 编组开始!"
    ),
    difficulty=4,
    tags=["交通", "火车", "货运", "城市", "挑战"],
    min_pieces=85,
    min_steps=20,
)
