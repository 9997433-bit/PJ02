#!/usr/bin/env python3
"""生成模型 data/models/sandbox_park_01.json (沙坑公园)。

城市生活主题: 社区街角的沙坑公园 —— 主角是一方 3x3 金黄大沙坑
(四面矮挡板围合), 沙坑正中还堆着一座戴等边锥顶的小沙堡; 南侧
步道边有一张悬挑坐板的长椅, 东侧凉亭两面开敞 (南北矮墙托平顶),
西侧草坪上两棵行道树亭亭如盖, 沙坑挡板上还插着两把等腰小沙铲。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 南侧步道: 6 片方板 (x 0..6)                                6 片
  - 西侧草坪: 4 片方板 (y 1..5)                                4 片
  - 大沙坑 [1,4]x[1,4]: 3x3 沙板                               9 片
  - 沙坑挡板: 四面各 3 片矮墙                                 12 片
  - 小沙堡: 中心 1x1 四壁 + 等边四坡锥顶                       8 片
  - 沙铲装饰: 南北挡板顶各插 1 把等腰沙铲                      2 片
  - 长椅: 2 片腿墙 + 2 片悬挑坐板                              4 片
  - 凉亭 [5,7]x[1,3]: 地板 4 + 南北矮墙 4 + 平顶 4 + 檐花 2   14 片
  - 行道树: 树干 + 等边树冠, 共 2 棵                           4 片
  合计 63 片, 16 个教程步骤, 3 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 沙坑挡板底边整边吸沙板外沿, 四角竖边互吸围合成框;
  - 小沙堡立在沙板拼缝上, 等边锥顶斜棱两两互吸自锁;
  - 长椅坐板悬挑: 两片坐板共线铰链合并受力 (力矩 30 <= 严格档
    预算 35), 且坐板之间coplanar互吸成整面;
  - 凉亭南北矮墙托平顶, 顶板-矮墙-地板闭合成环, 东西两面开敞。

用法: python3 tools/generate_sandbox_park.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

PATH = "gray"       # 步道
LAWN = "green"      # 草坪
SAND = "yellow"     # 沙坑
BOARD = "orange"    # 沙坑挡板
CASTLE = "yellow"   # 小沙堡 (与沙同色但立起)
SHOVEL = "red"      # 沙铲
BENCH = "blue"      # 长椅
KIOSK = "purple"    # 凉亭
TRUNK = "gray"      # 树干
LEAF = "green"      # 树冠

# =================================================================
# 1. 南侧步道 (y0=0) 与西侧草坪 (x0=0)
# =================================================================
for x in range(6):
    b.flat(f"pa_{x}", x, 0, 0.0, PATH)
for y in range(1, 5):
    b.flat(f"lw_{y}", 0, y, 0.0, LAWN)

# =================================================================
# 2. 大沙坑 [1,4]x[1,4]: 3x3 沙板
# =================================================================
for x in range(1, 4):
    for y in range(1, 4):
        b.flat(f"sa_{x}_{y}", x, y, 0.0, SAND)

# =================================================================
# 3. 沙坑挡板: 四面各 3 片矮墙, 底边吸沙板外沿
# =================================================================
for x in range(1, 4):
    b.wall_ns(f"bd_s_{x}", x, 1.0, 0, BOARD)
    b.wall_ns(f"bd_n_{x}", x, 4.0, 0, BOARD)
for y in range(1, 4):
    b.wall_ew(f"bd_w_{y}", 1.0, y, 0, BOARD)
    b.wall_ew(f"bd_e_{y}", 4.0, y, 0, BOARD)

# =================================================================
# 4. 小沙堡: 沙坑中心 [2,3]x[2,3] 四壁 + 等边四坡锥顶
# =================================================================
b.wall_ns("ca_s", 2, 2.0, 0, CASTLE)
b.wall_ns("ca_n", 2, 3.0, 0, CASTLE)
b.wall_ew("ca_w", 2.0, 2, 0, CASTLE)
b.wall_ew("ca_e", 3.0, 2, 0, CASTLE)
CASTLE_HAT = b.hat4("ca_hat", 2, 2, 1.0, BOARD, shape="equilateral_triangle")

# 沙铲装饰: 南北挡板顶各插 1 把等腰沙铲
b.spire_ns("sv_s", 2, 1.0, 1.0, SHOVEL)
b.spire_ns("sv_n", 2, 4.0, 1.0, SHOVEL)

# =================================================================
# 5. 长椅 (步道南沿): 2 片腿墙 + 2 片悬挑坐板
# =================================================================
b.wall_ns("bn_l0", 1, 0.0, 0, BENCH)
b.wall_ns("bn_l1", 2, 0.0, 0, BENCH)
b.flat("bn_s0", 1, -1, 1.0, BENCH)
b.flat("bn_s1", 2, -1, 1.0, BENCH)

# =================================================================
# 6. 凉亭 [5,7]x[1,3]: 地板 + 南北矮墙 + 平顶 + 檐花
# =================================================================
for x in range(5, 7):
    for y in range(1, 3):
        b.flat(f"ki_f_{x}_{y}", x, y, 0.0, PATH)
for x in range(5, 7):
    b.wall_ns(f"ki_s_{x}", x, 1.0, 0, KIOSK)
    b.wall_ns(f"ki_n_{x}", x, 3.0, 0, KIOSK)
for x in range(5, 7):
    for y in range(1, 3):
        b.flat(f"ki_r_{x}_{y}", x, y, 1.0, KIOSK)
b.crest_ew("ki_c0", 5.0, 1, 1.0, SHOVEL)
b.crest_ew("ki_c1", 5.0, 2, 1.0, SHOVEL)

# =================================================================
# 7. 行道树 (西侧草坪): 树干 + 等边树冠 x2
# =================================================================
b.wall_ew("tr0_t", 0.0, 1, 0, TRUNK)
b.crest_ew("tr0_c", 0.0, 1, 1.0, LEAF)
b.wall_ew("tr1_t", 0.0, 3, 0, TRUNK)
b.crest_ew("tr1_c", 0.0, 3, 1.0, LEAF)

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺设南侧步道: 6 片灰色方板沿南边一字排开。",
    [f"pa_{x}" for x in range(6)],
    tip="步道是公园的入口动线, 6 片板缝缝相吸。",
)
b.step(
    "铺设西侧草坪: 4 片绿色方板沿西边接上步道。",
    [f"lw_{y}" for y in range(1, 5)],
    highlight=["pa_0"],
    tip="草坪与步道拐角相接, 公园的 L 形边界出来了。",
)
b.step(
    "铺满大沙坑: 3x3 共 9 片金黄沙板, 与步道和草坪整边吸合。",
    [f"sa_{x}_{y}" for x in range(1, 4) for y in range(1, 4)],
    highlight=["pa_1", "lw_1"],
    tip="沙板拼成正方形大沙坑 —— 公园的主角登场。",
)
b.step(
    "竖立沙坑南面与西面挡板: 橙色矮墙各 3 片, 底边吸沙板外沿。",
    [f"bd_s_{x}" for x in range(1, 4)] + [f"bd_w_{y}" for y in range(1, 4)],
    highlight=["sa_1_1"],
    tip="挡板在西南角竖边互吸 —— 沙子再也跑不出来。",
)
b.step(
    "竖立沙坑北面与东面挡板: 再围 6 片, 四面挡板合拢成框。",
    [f"bd_n_{x}" for x in range(1, 4)] + [f"bd_e_{y}" for y in range(1, 4)],
    highlight=["bd_s_1", "bd_w_1"],
    tip="四角竖边两两互吸, 挡板框自锁成一体。",
)
b.step(
    "插上两把沙铲: 红色等腰三角立上南北挡板顶边正中。",
    ["sv_s", "sv_n"],
    highlight=["bd_s_2", "bd_n_2"],
    tip="沙铲立在挡板顶的铰链线上, 重心正压、力臂为零。",
)
b.step(
    "堆小沙堡四壁: 沙坑正中 4 片方墙立在沙板拼缝上, 围成 1x1 城堡。",
    ["ca_s", "ca_n", "ca_w", "ca_e"],
    highlight=["sa_2_2"],
    tip="城堡墙底边正压沙板拼缝, 缝两侧的沙板边同时吸住它。",
)
b.step(
    "合拢沙堡锥顶: 4 片橙色等边三角斜棱两两互吸、锥尖自锁。",
    CASTLE_HAT,
    highlight=["ca_s"],
    tip="最后一片卡进去的瞬间, 锥顶咔哒一声锁成一体。",
)
b.step(
    "竖立长椅腿墙: 2 片蓝色方墙立在步道南沿。",
    ["bn_l0", "bn_l1"],
    highlight=["pa_1", "pa_2"],
    tip="椅腿底边吸步道板南沿, 两片竖边互吸并肩。",
)
b.step(
    "搭上长椅坐板: 2 片蓝色方板压住椅腿顶边、向南悬挑。",
    ["bn_s0", "bn_s1"],
    highlight=["bn_l0", "bn_l1"],
    tip="两片坐板拼缝互吸成整面 —— 共线铰链一起受力才坐得稳。",
)
b.step(
    "铺设凉亭地板: 步道东端北侧 4 片灰色方板。",
    [f"ki_f_{x}_{y}" for x in range(5, 7) for y in range(1, 3)],
    highlight=["pa_5"],
    tip="凉亭地板与步道整边吸合, 公园东区开工。",
)
b.step(
    "竖立凉亭南北矮墙: 紫色方墙各 2 片, 东西两面留空开敞。",
    [f"ki_s_{x}" for x in range(5, 7)] + [f"ki_n_{x}" for x in range(5, 7)],
    highlight=["ki_f_5_1"],
    tip="只砌南北两面墙 —— 穿堂风才凉快。",
)
b.step(
    "盖凉亭平顶: 4 片紫色顶板压住南北墙顶边。",
    [f"ki_r_{x}_{y}" for x in range(5, 7) for y in range(1, 3)],
    highlight=["ki_s_5", "ki_n_6"],
    tip="顶板南北两沿吸墙顶、拼缝互吸 —— 墙顶板闭环最稳。",
)
b.step(
    "凉亭西檐插檐花: 2 片红色等边三角立上顶板西沿。",
    ["ki_c0", "ki_c1"],
    highlight=["ki_r_5_1"],
    tip="檐花立在顶板沿口, 是凉亭的小小桂冠。",
)
b.step(
    "种下第一棵行道树: 树干立草坪西沿, 等边树冠戴顶。",
    ["tr0_t", "tr0_c"],
    highlight=["lw_1"],
    tip="树干底边吸草坪板边, 树冠底边吸树干顶边。",
)
b.step(
    "种下第二棵行道树: 沙坑公园落成!",
    ["tr1_t", "tr1_c"],
    highlight=["tr0_t"],
    tip="两棵小树排成行 —— 拎上小桶小铲, 开挖!",
)

b.finalize(
    model_id="sandbox_park_01",
    name="沙坑公园",
    name_en="Sandbox Park",
    description=(
        "社区街角的沙坑公园: 3x3 金黄大沙坑四面橙色挡板围合, 坑心小沙堡"
        "戴等边锥顶, 挡板上插着两把红色沙铲; 南侧步道边一张悬挑坐板的"
        "蓝色长椅, 东侧紫色凉亭南北矮墙托平顶、东西开敞, 西侧草坪上两棵"
        "行道树亭亭如盖 —— 拎上小桶小铲, 开挖!"
    ),
    difficulty=3,
    tags=["城市", "公园", "进阶"],
    min_pieces=63,
    min_steps=16,
)
