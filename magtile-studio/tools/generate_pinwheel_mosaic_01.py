#!/usr/bin/env python3
"""生成模型 data/models/pinwheel_mosaic_01.json (旋风万花砖, D1 入门)。

D1 补员批 3 模型 2/4 (几何艺术): 一块四重旋转对称 (C4) 的桌面
万花拼砖。结构签名是"大方核心 + 旋转叶阵": 大正方形居中, 四片
长板十字环抱, 四角方板补角, 直角三角叶片与等边三角光芒按 90 度
旋转规律绕圈排布, 最后四片等边三角立在四条"轴缝"上当立体风叶 ——
与库内镶嵌屏风 (42 片站立屏) 的结构逻辑完全不同: 这是以旋转
对称为主题的平铺曼陀罗。

结构总览 (世界单位 1.0 = 正方形磁力片边长):
  - 核心: 大正方形 1 片 ([2,4] x [2,4])                  1 片
  - 十字环: 长板 4 片, 长边与大方边等长整边贴合          4 片
  - 四角: 方板 4 片, 两条边分别吸两片长板短边            4 片
  - 旋转叶片: 直角三角 4 片, 每角一片按 C4 旋转排布      4 片
  - 光芒: 等边三角 4 片, 与叶片错位 90 度                4 片
  - 立体风叶: 等边三角 4 片立在长板短边与角板的轴缝上    4 片
  合计 21 片, 5 个教程步骤, 5 种片形 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 平铺件全部接地 (R7a); 大方每条边 (长 2) 与长板长边
    等长整边贴合 (R2 长短边完整贴合的教科书案例);
  - 立体风叶底边与轴缝两侧的角板边/长板短边完整重合,
    纯受压零力矩; 最高点 0.87 (风叶尖), 无 R8 拓扑告警;
  - 全图严格 C4 旋转对称 —— 每一步都是"转 90 度再来一遍"。

用法: python3 tools/generate_pinwheel_mosaic_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

CORE = "yellow"      # 大方核心
RING_S, RING_E, RING_N, RING_W = "red", "green", "blue", "orange"
CORNER = "cyan"      # 四角方板
BLADE = "purple"     # 旋转叶片
RAY = "pink"         # 光芒

EQ_H = 0.866025      # 等边三角形高

# =================================================================
# 1. 核心与十字环: 大方居中, 四片长板长边等长贴合
# =================================================================
b.add("core", "large_square", (3.0, 3.0, 0.0), (0, 0, 0), CORE)
b.flat_rect("ring_s", 2, 1, 0.0, RING_S)             # [2,4] x [1,2]
b.flat_rect("ring_e", 4, 2, 0.0, RING_E, axis="y")   # [4,5] x [2,4]
b.flat_rect("ring_n", 2, 4, 0.0, RING_N)             # [2,4] x [4,5]
b.flat_rect("ring_w", 1, 2, 0.0, RING_W, axis="y")   # [1,2] x [2,4]

# =================================================================
# 2. 四角方板: 每片两条边分别吸住两片长板的短边
# =================================================================
b.flat("corner_sw", 1, 1, 0.0, CORNER)
b.flat("corner_se", 4, 1, 0.0, CORNER)
b.flat("corner_ne", 4, 4, 0.0, CORNER)
b.flat("corner_nw", 1, 4, 0.0, CORNER)

# =================================================================
# 3. 旋转叶片: 直角三角每角一片, 位置按 C4 旋转 90 度递推
# =================================================================
b.place_tri("blade_se", "right_triangle",
            (5.0, 1.0, 0.0), (4.0, 1.0, 0.0), (5.0, 0.0, 0.0), BLADE)
b.place_tri("blade_ne", "right_triangle",
            (5.0, 5.0, 0.0), (5.0, 4.0, 0.0), (6.0, 5.0, 0.0), BLADE)
b.place_tri("blade_nw", "right_triangle",
            (1.0, 5.0, 0.0), (2.0, 5.0, 0.0), (1.0, 6.0, 0.0), BLADE)
b.place_tri("blade_sw", "right_triangle",
            (1.0, 1.0, 0.0), (1.0, 2.0, 0.0), (0.0, 1.0, 0.0), BLADE)

# =================================================================
# 4. 光芒: 等边三角贴四角方板的另一条外沿, 与叶片错位 90 度
# =================================================================
b.place_tri("ray_e", "equilateral_triangle",
            (5.0, 2.0, 0.0), (5.0, 1.0, 0.0), (5.0 + EQ_H, 1.5, 0.0), RAY)
b.place_tri("ray_n", "equilateral_triangle",
            (4.0, 5.0, 0.0), (5.0, 5.0, 0.0), (4.5, 5.0 + EQ_H, 0.0), RAY)
b.place_tri("ray_w", "equilateral_triangle",
            (1.0, 4.0, 0.0), (1.0, 5.0, 0.0), (1.0 - EQ_H, 4.5, 0.0), RAY)
b.place_tri("ray_s", "equilateral_triangle",
            (2.0, 1.0, 0.0), (1.0, 1.0, 0.0), (1.5, 1.0 - EQ_H, 0.0), RAY)

# =================================================================
# 5. 立体风叶: 等边三角立在长板短边与角板的轴缝上 (C4 对称)
# =================================================================
b.crest_ew("crown_s", 2.0, 1, 0.0, RING_S)   # 缝 (2,1)-(2,2)
b.crest_ns("crown_e", 4, 2.0, 0.0, RING_E)   # 缝 (4,2)-(5,2)
b.crest_ew("crown_n", 4.0, 4, 0.0, RING_N)   # 缝 (4,4)-(4,5)
b.crest_ns("crown_w", 1, 4.0, 0.0, RING_W)   # 缝 (1,4)-(2,4)

# =================================================================
# 教程步骤 (5 步)
# =================================================================
b.step(
    "铺核心十字: 黄色大方居中, 四片彩色长板长边整边贴住大方四边。",
    ["core", "ring_s", "ring_e", "ring_n", "ring_w"],
    tip="大方一条边正好吸满一片长板的长边 —— 长短边完整贴合最稳。",
)
b.step(
    "补四角: 四片青色方板卡进角落, 每片同时吸住两片长板的短边。",
    ["corner_sw", "corner_se", "corner_ne", "corner_nw"],
    highlight=["ring_s", "ring_w"],
)
b.step(
    "摆旋转叶片: 四片紫色直角三角绕圈排 —— 每转 90 度就换一条边贴。",
    ["blade_se", "blade_ne", "blade_nw", "blade_sw"],
    highlight=["corner_se", "corner_ne"],
    tip="盯住斜边的朝向: 四片斜边追着圈跑, 风车就转起来了。",
)
b.step(
    "加光芒: 四片粉色等边三角贴在角板的另一条外沿, 与叶片错开 90 度。",
    ["ray_e", "ray_n", "ray_w", "ray_s"],
    highlight=["blade_se", "blade_sw"],
)
b.step(
    "立起风叶: 四片彩色等边三角站上轴缝, 平面万花砖长出立体风车!",
    ["crown_s", "crown_e", "crown_n", "crown_w"],
    highlight=["core"],
    tip="底边压住缝两侧的两条板边, 站得又正又稳。",
)

b.finalize(
    model_id="pinwheel_mosaic_01",
    name="旋风万花砖",
    name_en="Pinwheel Mosaic 01",
    description=(
        "D1 入门几何艺术: 四重旋转对称的桌面万花拼砖 —— 黄色大方居中, "
        "红绿蓝橙四片长板十字环抱 (长短边完整贴合), 青色角板补角, 紫色"
        "直角三角叶片与粉色等边光芒按'每转 90 度换条边'的旋转规律绕圈"
        "排布, 最后四片彩色三角立上轴缝, 平面图案瞬间长出立体风叶。"
        "拼的过程就是一堂旋转对称启蒙课: 摆完一角, 转 90 度再来一遍。"
    ),
    difficulty=1,
    tags=["几何艺术", "旋转对称", "拼砖", "亲子入门"],
    min_pieces=21,
    min_steps=5,
    series="geometric_art",
)
