#!/usr/bin/env python3
"""生成模型 data/models/coral_reef_02.json (海底珊瑚花园)。

水下/海洋主题: 与 coral_reef_01 (扇形/菱形/梯形扩展片造景) 刻意区分 ——
本作只用核心九片型 (core-9), 结构逻辑是 "满铺沙床 + 双珊瑚塔 + 群落
点缀": 6x4 金色沙床满铺后, 西侧起一座 2x2 桌珊瑚 (环墙 + 长方形
双拼台面 + 四角尖齿), 东侧起一座 1x1 双层烟囱管珊瑚戴等边四坡
锥顶; 沙床拼缝上再立扇珊瑚 (等边三角)、鹿角海草 (等腰高塔尖) 与
礁石鳍 (直角三角), 立片全部与沙床整边吸合、共面零力矩。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 沙床 (x [0,6], y [0,4]): 单位方板满铺 4 行                   24 片
  - 桌珊瑚 (x [1,3], y [1,3], z 0..1): 环墙 x8 + 长方形台面 x2
    + 沿口尖齿等边三角 x4                                        14 片
  - 烟囱管珊瑚 (x [4,5], y [2,3], z 0..2): 两层墙环 x8
    + 等边四坡锥顶 x4 (锥尖 2.71)                                12 片
  - 扇珊瑚: 等边三角立在沙床拼缝 x3                               3 片
  - 鹿角海草: 等腰高塔尖立在沙床沿口 x2 (草尖 2.0)                 2 片
  - 礁石鳍: 直角三角立在沙床拼缝 x2                               2 片
  合计 57 片, 14 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点:
  - 桌珊瑚环墙四角竖边互吸闭环, 长方形台面短边整边吸墙顶,
    两片台面长边互吸, 尖齿骑沿口共面零力矩;
  - 烟囱两层墙环层层互吸, 锥顶四棱两两互吸自锁;
  - 全部立片 (扇珊瑚/海草/礁石鳍) 底边与沙床单位拼缝整边吸合。

用法: python3 tools/generate_coral_reef_02.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

SAND = "yellow"     # 沙床
TABLE = "pink"      # 桌珊瑚
DECKC = "pink"      # 桌珊瑚台面
TIP = "red"         # 桌珊瑚尖齿
CHIM = "orange"     # 烟囱管珊瑚
HAT = "yellow"      # 烟囱锥顶
FAN = "purple"      # 扇珊瑚
GRASS = "green"     # 鹿角海草
ROCK = "gray"       # 礁石鳍

# =================================================================
# 1. 沙床 (x [0,6], y [0,4]): 单位方板满铺, 拼缝就是珊瑚的根
# =================================================================
for y in range(4):
    for x in range(6):
        b.flat(f"sb_{x}_{y}", x, y, 0.0, SAND)

# =================================================================
# 2. 桌珊瑚 (x [1,3], y [1,3], z 0..1): 环墙 + 长方形双拼台面 + 尖齿
# =================================================================
b.wall_ns("tc_s_1", 1, 1.0, 0, TABLE)
b.wall_ns("tc_s_2", 2, 1.0, 0, TABLE)
b.wall_ew("tc_w_1", 1.0, 1, 0, TABLE)
b.wall_ew("tc_w_2", 1.0, 2, 0, TABLE)
b.wall_ns("tc_n_1", 1, 3.0, 0, TABLE)
b.wall_ns("tc_n_2", 2, 3.0, 0, TABLE)
b.wall_ew("tc_e_1", 3.0, 1, 0, TABLE)
b.wall_ew("tc_e_2", 3.0, 2, 0, TABLE)
# 台面: 两片长方形横跨 2x2 洞口, 短边整边吸墙顶, 长边互吸
b.flat_rect("tc_top_s", 1, 1, 1.0, DECKC)
b.flat_rect("tc_top_n", 1, 2, 1.0, DECKC)
# 沿口尖齿: 南/北骑墙顶, 西/东骑台面短边
b.crest_ns("tc_tip_s", 1, 1.0, 1.0, TIP)
b.crest_ns("tc_tip_n", 2, 3.0, 1.0, TIP)
b.crest_ew("tc_tip_w", 1.0, 2, 1.0, TIP)
b.crest_ew("tc_tip_e", 3.0, 1, 1.0, TIP)

# =================================================================
# 3. 烟囱管珊瑚 (x [4,5], y [2,3], z 0..2): 两层墙环 + 等边锥顶
# =================================================================
for lv, z in (("1", 0), ("2", 1)):
    b.wall_ns(f"ch{lv}_s", 4, 2.0, z, CHIM)
    b.wall_ns(f"ch{lv}_n", 4, 3.0, z, CHIM)
    b.wall_ew(f"ch{lv}_w", 4.0, 2, z, CHIM)
    b.wall_ew(f"ch{lv}_e", 5.0, 2, z, CHIM)
CHIM_HAT = b.hat4("ch_hat", 4, 2, 2.0, HAT, shape="equilateral_triangle")

# =================================================================
# 4. 群落点缀: 扇珊瑚 / 鹿角海草 / 礁石鳍 (全部立在沙床拼缝上)
# =================================================================
b.crest_ns("fan_w", 0, 2.0, 0.0, FAN)
b.crest_ns("fan_e", 5, 3.0, 0.0, FAN)
b.crest_ew("fan_c", 1.0, 3, 0.0, FAN)
b.spire_ns("grass_n", 2, 4.0, 0.0, GRASS)
b.spire_ew("grass_e", 6.0, 1, 0.0, GRASS)
b.place_tri("rock_w", "right_triangle", (0, 1, 0), (1, 1, 0), (0, 1, 1), ROCK)
b.place_tri("rock_e", "right_triangle", (5, 1, 0), (4, 1, 0), (5, 1, 1), ROCK)

# =================================================================
# 教程步骤 (14 步)
# =================================================================
b.step(
    "铺沙床南行 (y [0,1]): 6 片金色方板一字排开。",
    [f"sb_{x}_0" for x in range(6)],
    tip="沙床拼缝就是珊瑚的根 —— 从南向北逐行铺满。",
)
b.step(
    "铺沙床第二行 (y [1,2]): 6 片, 与南行拼缝对齐。",
    [f"sb_{x}_1" for x in range(6)],
    highlight=["sb_0_0"],
    tip="y=1 这条缝一会儿要立礁石鳍和桌珊瑚南墙。",
)
b.step(
    "铺沙床第三行 (y [2,3]): 6 片。",
    [f"sb_{x}_2" for x in range(6)],
    highlight=["sb_0_1"],
    tip="桌珊瑚与烟囱管珊瑚都踩这一行的拼缝。",
)
b.step(
    "铺沙床北行 (y [3,4]): 6 片, 沙床合拢。",
    [f"sb_{x}_3" for x in range(6)],
    highlight=["sb_0_2"],
    tip="6x4 沙床铺满 —— 海底花园的地基完工。",
)
b.step(
    "立桌珊瑚南墙与西墙: 4 片粉色立墙踩拼缝, 转角竖边互吸。",
    ["tc_s_1", "tc_s_2", "tc_w_1", "tc_w_2"],
    highlight=["sb_1_1", "sb_1_2"],
    tip="每片底边整边吸沙床拼缝, 转角互咬才立得稳。",
)
b.step(
    "立桌珊瑚北墙与东墙: 再 4 片, 环墙闭合。",
    ["tc_n_1", "tc_n_2", "tc_e_1", "tc_e_2"],
    highlight=["tc_s_1", "tc_w_2"],
    tip="闭合环墙是桌珊瑚的茎 —— 轻推应整体联动。",
)
b.step(
    "架桌珊瑚台面: 2 片长方形横跨洞口, 短边吸墙顶、长边互吸。",
    ["tc_top_s", "tc_top_n"],
    highlight=["tc_w_1", "tc_e_1"],
    tip="长方形当桌板 —— 两端墙顶受力, 中缝互吸锁死。",
)
b.step(
    "装桌珊瑚尖齿: 4 片红色等边三角骑上台面四沿。",
    ["tc_tip_s", "tc_tip_n", "tc_tip_w", "tc_tip_e"],
    highlight=["tc_top_s", "tc_top_n"],
    tip="尖齿与墙共面, 重心正压沿口, 力矩为零。",
)
b.step(
    "立烟囱管珊瑚第 1 层: 4 片橙色墙环踩沙床拼缝。",
    ["ch1_s", "ch1_n", "ch1_w", "ch1_e"],
    highlight=["sb_4_2"],
    tip="1x1 管状墙环 —— 烟囱管珊瑚是真实存在的海洋生物!",
)
b.step(
    "叠烟囱管珊瑚第 2 层: 4 片墙环层层互吸。",
    ["ch2_s", "ch2_n", "ch2_w", "ch2_e"],
    highlight=["ch1_s", "ch1_e"],
    tip="上层底边吸下层顶边, 四角再互咬一遍。",
)
b.step(
    "戴等边四坡锥顶: 锥尖 2.71, 烟囱管珊瑚封顶。",
    CHIM_HAT,
    highlight=["ch2_s", "ch2_n"],
    tip="四条斜棱两两互吸, 自锁成环。",
)
b.step(
    "立扇珊瑚: 3 片紫色等边三角插在沙床拼缝上。",
    ["fan_w", "fan_e", "fan_c"],
    highlight=["sb_0_1", "sb_5_2"],
    tip="扇珊瑚迎着洋流展开 —— 底边整边吸缝, 立着不倒。",
)
b.step(
    "种鹿角海草: 2 片绿色等腰高塔尖立在沙床沿口 (草尖 2.0)。",
    ["grass_n", "grass_e"],
    highlight=["sb_2_3", "sb_5_1"],
    tip="瘦高的等腰三角像随浪摆动的海草。",
)
b.step(
    "放礁石鳍: 2 片灰色直角三角立在南侧拼缝 —— 海底花园完工!",
    ["rock_w", "rock_e"],
    highlight=["sb_0_0", "sb_4_0"],
    tip="直角边贴缝、斜边朝天, 像露出沙面的礁石。",
)

b.finalize(
    model_id="coral_reef_02",
    name="海底珊瑚花园",
    name_en="Coral Garden 02",
    description=(
        "只用核心九片型的海底珊瑚花园: 6x4 金色沙床满铺后, 西侧起"
        " 2x2 桌珊瑚 (环墙互吸 + 长方形双拼台面 + 四沿红色尖齿),"
        " 东侧起 1x1 双层烟囱管珊瑚戴等边四坡锥顶 (锥尖 2.71);"
        " 沙床拼缝上再立紫色扇珊瑚、绿色鹿角海草 (草尖 2.0) 与"
        "灰色礁石鳍 —— 满铺打底、双塔对望、群落点缀, 一座基础"
        "套装就能搭的海底花园。"
    ),
    difficulty=3,
    tags=["海洋", "珊瑚礁", "海底花园", "自然", "进阶"],
    min_pieces=55,
    min_steps=14,
)
