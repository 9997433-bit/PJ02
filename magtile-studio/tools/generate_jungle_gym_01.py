#!/usr/bin/env python3
"""生成模型 data/models/jungle_gym_01.json (操场攀爬架)。

校园/学校主题批 3/4: 全库第一座操场攀爬架 —— 与
slide_playground_01 (滑道塔: 两层主塔甩滑道) 和 corn_maze_01
(平面迷宫墙阵) 刻意区分: 本作的结构签名是"窗格方攀爬墙阵 +
云梯双端桥" —— 2x2 田字格攀爬墙阵, 四道墙在十字中心共一条
竖线四片互咬 (全库第一次四墙共线锁扣), 墙面大量窗格方就是
攀爬洞; 墙阵二层收成外圈环, 顶上瞭望平台开 1x1 天窗洞由黄色
四坡瞭望帽封住; 云梯桥从瞭望台双端受力跨到东侧独立爬塔
(两短边各'墙顶+台沿'一线双吸), 桥沿两道透明护栏整长边压桥面;
西侧 30 度攀爬坡道顶边吸墙顶、坡尾落地生根。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 软垫地坪 8x4: 粉绿相间安全垫 + 墙脚线处单位方板         25 片
  - 攀爬墙阵一层 (x [2,4], y [1,3], z 0..1): 田字 12 墙
    (窗格方 x8 + 彩色方 x4)                                  12 片
  - 墙阵二层外圈环 (z 1..2): 窗格方 x4 + 彩色方 x4            8 片
  - 瞭望平台 (z=2): 长板 + 方板 + 1x1 天窗洞 + 瞭望帽 x4      6 片
  - 东爬塔 (x [6,7], y [1,2], 高 2): 两层墙环 x8 + 压顶        9 片
  - 云梯桥 (x [4,6], z=2): 桥面长板 + 透明护栏 x2              3 片
  - 攀爬坡道 (30 度) + 塔顶红旗                                2 片
  合计 65 片, 13 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 田字墙阵: 十字中心 (3,2) 处四片墙共一条竖线两两互咬,
    每个 1x1 格都是闭环 —— 四格四环, 拆掉任何一片仍有环路;
  - 二层外圈环整边骑一层墙顶, 瞭望平台两片板短边吸环墙顶、
    彼此长边互吸; 瞭望帽三边吸沿 (南边临空) + 四棱自锁;
  - 云梯桥两短边各同吸'塔墙顶 + 台/顶沿'双共线连接, 双端
    受力零悬挑 (过街天桥同款), 护栏 2.0 对 2.0 整长边压桥沿;
  - 攀爬坡道顶边吸墙阵西墙顶, 坡尾自己落地 —— 顶铰链 +
    接地斜撑两条路径;
  - 红旗骑塔顶'压顶北沿 + 塔北墙顶'一线双吸, 力矩为零;
  - 地坪拼缝纪律: 墙脚线处全单位方板, 相邻行等长边互吸。

用法: python3 tools/generate_jungle_gym_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

MAT_P = "pink"       # 安全软垫
MAT_G = "green"      # 安全软垫
CLIMB_R = "red"      # 攀爬墙 (彩色)
CLIMB_B = "blue"
CLIMB_Y = "yellow"
HOLE = "clear"       # 窗格方攀爬洞
DECK = "orange"      # 瞭望平台 / 云梯桥
HAT = "yellow"       # 瞭望帽
TOWER = "cyan"       # 东爬塔
RAIL = "clear"       # 云梯护栏
RAMP = "purple"      # 攀爬坡道
FLAG = "red"         # 塔顶红旗


def climb_ns(tid, x0, y, z0, color):
    """南北向窗格方攀爬墙。"""
    b.add(tid, "window_square", (x0 + 0.5, y, z0 + 0.5), (90, 0, 0), color)


def climb_ew(tid, x, y0, z0, color):
    """东西向窗格方攀爬墙。"""
    b.add(tid, "window_square", (x, y0 + 0.5, z0 + 0.5), (90, 0, 90), color)


# =================================================================
# 1. 软垫地坪 8x4 (x [0,8], y [0,4]): 拼缝纪律 —— 墙脚线处全单位
#    方板, 相邻行至少一对等长边互吸。
# =================================================================
# 南缘 (y [0,1])
b.flat_rect("g_0_w", 0, 0, 0.0, MAT_G)
b.flat_rect("g_0_m", 2, 0, 0.0, MAT_P)
b.flat("g_0_4", 4, 0, 0.0, MAT_G)
b.flat("g_0_5", 5, 0, 0.0, MAT_P)
b.flat_rect("g_0_e", 6, 0, 0.0, MAT_G)
# 墙阵/爬塔行 (y [1,2]): 全单位方板
for x in range(8):
    b.flat(f"g_1_{x}", x, 1, 0.0, MAT_P if x % 2 == 0 else MAT_G)
# 墙阵后排行 (y [2,3])
b.flat("g_2_0", 0, 2, 0.0, MAT_G)
b.flat("g_2_1", 1, 2, 0.0, MAT_P)
b.flat("g_2_2", 2, 2, 0.0, MAT_G)
b.flat("g_2_3", 3, 2, 0.0, MAT_P)
b.flat("g_2_4", 4, 2, 0.0, MAT_G)
b.flat_rect("g_2_e", 5, 2, 0.0, MAT_P)
b.flat("g_2_7", 7, 2, 0.0, MAT_G)
# 北缘 (y [3,4])
b.flat("g_3_0", 0, 3, 0.0, MAT_P)
b.flat_rect("g_3_w", 1, 3, 0.0, MAT_G)
b.flat_rect("g_3_m", 3, 3, 0.0, MAT_P)
b.flat_rect("g_3_e", 5, 3, 0.0, MAT_G)
b.flat("g_3_7", 7, 3, 0.0, MAT_P)

# =================================================================
# 2. 攀爬墙阵一层 (x [2,4], y [1,3], z 0..1): 田字 12 墙,
#    十字中心 (3,2) 四片墙共一条竖线
# =================================================================
climb_ns("cw_s_2", 2, 1.0, 0, HOLE)                # 南排
climb_ns("cw_s_3", 3, 1.0, 0, HOLE)
climb_ns("cw_m_2", 2, 2.0, 0, HOLE)                # 中排 (十字横杆)
climb_ns("cw_m_3", 3, 2.0, 0, HOLE)
climb_ns("cw_n_2", 2, 3.0, 0, HOLE)                # 北排
climb_ns("cw_n_3", 3, 3.0, 0, HOLE)
b.wall_ew("cw_w_1", 2.0, 1, 0, CLIMB_R)            # 西列
b.wall_ew("cw_w_2", 2.0, 2, 0, CLIMB_R)
climb_ew("cw_c_1", 3.0, 1, 0, HOLE)                # 中列 (十字竖杆)
climb_ew("cw_c_2", 3.0, 2, 0, HOLE)
b.wall_ew("cw_e_1", 4.0, 1, 0, CLIMB_B)            # 东列
b.wall_ew("cw_e_2", 4.0, 2, 0, CLIMB_B)

# =================================================================
# 3. 墙阵二层外圈环 (z 1..2): 收掉内墙只留外圈
# =================================================================
climb_ns("up_s_2", 2, 1.0, 1, HOLE)
b.wall_ns("up_s_3", 3, 1.0, 1, CLIMB_Y)
b.wall_ns("up_n_2", 2, 3.0, 1, CLIMB_Y)
climb_ns("up_n_3", 3, 3.0, 1, HOLE)
b.wall_ew("up_w_1", 2.0, 1, 1, CLIMB_R)
climb_ew("up_w_2", 2.0, 2, 1, HOLE)
climb_ew("up_e_1", 4.0, 1, 1, HOLE)
b.wall_ew("up_e_2", 4.0, 2, 1, CLIMB_B)

# =================================================================
# 4. 瞭望平台 (z=2): 长板 + 方板 + 1x1 天窗洞 + 黄色瞭望帽
# =================================================================
b.flat_rect("deck_s", 2, 1, 2.0, DECK)             # 南半跨长板
b.flat("deck_nw", 2, 2, 2.0, DECK)                 # 西北角方板
b.hat4("hat", 3, 2, 2.0, HAT, shape="equilateral_triangle")

# =================================================================
# 5. 东爬塔 (x [6,7], y [1,2], 高 2): 两层墙环 + 压顶
# =================================================================
b.wall_ns("tw1_s", 6, 1.0, 0, TOWER)
b.wall_ns("tw1_n", 6, 2.0, 0, TOWER)
b.wall_ew("tw1_w", 6.0, 1, 0, TOWER)
b.wall_ew("tw1_e", 7.0, 1, 0, TOWER)
climb_ns("tw2_s", 6, 1.0, 1, HOLE)                 # 二层南面开爬洞
b.wall_ns("tw2_n", 6, 2.0, 1, TOWER)
b.wall_ew("tw2_w", 6.0, 1, 1, TOWER)
b.wall_ew("tw2_e", 7.0, 1, 1, TOWER)
b.flat("tw_cap", 6, 1, 2.0, TOWER)

# =================================================================
# 6. 云梯桥 (x [4,6], y [1,2], z=2) + 护栏 + 坡道 + 红旗
# =================================================================
b.flat_rect("bridge", 4, 1, 2.0, DECK)             # 双端受力桥
b.lintel_ns("rail_s", 4, 1.0, 2, RAIL)             # 透明护栏
b.lintel_ns("rail_n", 4, 2.0, 2, RAIL)
b.ramp("climb_ramp", "-x", 2, 1, 1.0, RAMP)        # 30 度攀爬坡道
b.crest_ns("flag", 6, 2.0, 2.0, FLAG)              # 塔顶红旗

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺南缘软垫: 粉绿相间的安全垫先围出南边。",
    ["g_0_w", "g_0_m", "g_0_4", "g_0_5", "g_0_e"],
    tip="攀爬架下面必须是软软的安全垫 —— 摔下来也不疼。",
)
b.step(
    "铺墙阵与爬塔行 (y [1,2]): 8 格全单位方板。",
    ["g_1_0", "g_1_1", "g_1_2", "g_1_3", "g_1_4", "g_1_5", "g_1_6", "g_1_7"],
    highlight=["g_0_4"],
    tip="攀爬墙的每一段墙脚都要有等长的方板拼缝可吸。",
)
b.step(
    "铺后排行 (y [2,3]): 墙阵北半的地基。",
    ["g_2_0", "g_2_1", "g_2_2", "g_2_3", "g_2_4", "g_2_e", "g_2_7"],
    highlight=["g_1_0"],
    tip="十字中心那条缝就落在这两行方板之间。",
)
b.step(
    "铺北缘收口: 8x4 软垫合拢。",
    ["g_3_0", "g_3_w", "g_3_m", "g_3_e", "g_3_7"],
    highlight=["g_2_0"],
    tip="操场角落围好了 —— 开始搭攀爬架!",
)
b.step(
    "立墙阵南排与西列: 窗格方就是攀爬洞, 拐角竖边互咬。",
    ["cw_s_2", "cw_s_3", "cw_w_1", "cw_w_2"],
    highlight=["g_1_2", "g_2_2"],
    tip="窗格方物理上按实心方片拼接 —— 洞是给手脚抓的。",
)
b.step(
    "立中排与中列: 四片墙在十字中心共一条竖线两两互咬。",
    ["cw_m_2", "cw_m_3", "cw_c_1", "cw_c_2"],
    highlight=["cw_s_2", "cw_w_2"],
    tip="全库第一次四墙共线锁扣 —— 田字四格, 格格成环。",
)
b.step(
    "立北排与东列合环: 12 片墙锁成田字墙阵。",
    ["cw_n_2", "cw_n_3", "cw_e_1", "cw_e_2"],
    highlight=["cw_m_2", "cw_c_2"],
    tip="拆掉任何一片, 其余仍然环环相扣 —— 这就是结构冗余。",
)
b.step(
    "立二层外圈环: 8 片整边骑一层墙顶, 内墙收掉只留外圈。",
    ["up_s_2", "up_s_3", "up_n_2", "up_n_3",
     "up_w_1", "up_w_2", "up_e_1", "up_e_2"],
    highlight=["cw_s_2", "cw_n_3"],
    tip="上下两层墙整边共线吸合 —— 攀爬架长到两格高。",
)
b.step(
    "盖瞭望平台并封瞭望帽: 两板短边吸环墙顶、长边互吸, 天窗洞"
    "先北/东/西后南封四坡帽。",
    ["deck_s", "deck_nw", "hat_n", "hat_e", "hat_w", "hat_s"],
    highlight=["up_w_1", "up_e_2"],
    tip="爬到顶从天窗探出头 —— 黄帽子三边吸沿四棱自锁。",
)
b.step(
    "砌东爬塔: 两层墙环 + 压顶, 二层南面开一个爬洞。",
    ["tw1_s", "tw1_n", "tw1_w", "tw1_e",
     "tw2_s", "tw2_n", "tw2_w", "tw2_e", "tw_cap"],
    highlight=["g_1_6"],
    tip="闭环墙比单面墙稳得多 —— 这座塔要接住云梯桥。",
)
b.step(
    "架云梯桥: 橙色长板两短边各同吸'墙顶+台沿'双共线连接。",
    ["bridge"],
    highlight=["up_e_1", "tw_cap"],
    tip="双端受力零悬挑 —— 剪断任一端, 另一端仍拉着桥面。",
)
b.step(
    "装透明护栏: 两道护栏 2.0 对 2.0 整长边压桥沿。",
    ["rail_s", "rail_n"],
    highlight=["bridge"],
    tip="云梯桥有护栏 —— 手脚并用爬过去也不怕。",
)
b.step(
    "搭攀爬坡道 + 升塔顶红旗: 紫色 30 度坡顶边吸墙阵西墙顶、"
    "坡尾落地; 红旗骑塔顶沿口 —— 谁先爬到旗下谁赢!",
    ["climb_ramp", "flag"],
    highlight=["up_w_1", "tw_cap"],
    tip="坡道顶铰链 + 接地斜撑两条路径; 红旗重心正压铰链线。",
)

b.finalize(
    model_id="jungle_gym_01",
    name="操场攀爬架",
    name_en="Jungle Gym 01",
    description=(
        "只用核心九片型的操场攀爬架, 结构签名是'窗格方攀爬墙阵 + "
        "云梯双端桥': 2x2 田字格攀爬墙阵四道墙在十字中心共一条竖线"
        "四片互咬 (全库第一次四墙共线锁扣), 格格成环拆一片不倒, "
        "满墙窗格方就是攀爬洞; 二层收成外圈环整边骑一层墙顶, 瞭望"
        "平台开 1x1 天窗洞由黄色四坡瞭望帽三边吸沿四棱自锁封住; "
        "云梯桥两短边各同吸'塔墙顶+台沿'双共线连接双端受力跨到东侧"
        "两层爬塔, 透明护栏整长边压桥沿; 西侧 30 度攀爬坡道顶边吸"
        "墙顶坡尾落地, 塔顶红旗骑沿力矩为零 —— 谁先爬到旗下谁赢!"
    ),
    difficulty=3,
    tags=["校园", "操场", "攀爬架", "游乐设施", "进阶"],
    min_pieces=65,
    min_steps=13,
)
