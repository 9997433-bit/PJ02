#!/usr/bin/env python3
"""生成模型 data/models/control_tower_01.json (机场管制塔台)。

机场航空主题 1/4: 全库第一座独立式机场管制塔台 —— 与
airport_terminal_01 的贴建方塔 (1x1 借山墙)、water_tower_01 的
2x2 纯受压水塔、crane_tower_01 的 1x1 独柱吊塔刻意区分: 塔身是
1x2 长方形截面的 "长板筒" (长边整片长板横楣、短边正方形端墙,
四角竖边互吸层层闭环), 顶部先向四方挑出十字瞭望平台 (南北挑板
成对共铰, 力矩 30 <= 严格档预算 70), 平台上再立整圈透明塔台,
塔台顶盖西半戴红色等边四坡雷达锥、东沿立等腰指挥天线 (尖端
6.0); 塔脚东面门框方值机门, 场边气象站小屋顶飘风向袋, 东跑道
沿一排黄色进近灯标 —— 塔台在此, 放行起飞!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 塔门朝东):
  - 塔场 6x6 (x [0,6], y [0,6]): 方板 + 长板混铺              20 片
  - 塔身 (x [2,4], y [3,4], z 0..3): 每层 南北长板横楣 x2 +
    东西端墙 x2, 共 3 层 (底层东端为门框方, 中层端墙为窗格方)  12 片
  - 十字瞭望平台 (z=3): 筒顶方板 x2 + 东西挑板 x2 +
    南北挑板 x4 (成对共铰)                                     8 片
  - 透明塔台 (z 3..4): 窗格方整圈 x6                           6 片
  - 塔台顶盖 (z=4): 方板 x2                                    2 片
  - 雷达锥: 等边四坡锥 x4 (锥尖 4.71)                          4 片
  - 指挥天线: 等腰三角 x1 (尖端 6.0)                           1 片
  - 气象站小屋: 立墙 x4 + 顶板 x1 + 风向袋等腰 x1              6 片
  - 进近灯标: 等边三角 x3 (骑跑道东沿)                         3 片
  合计 62 片, 14 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, strict 档同样全绿):
  - 塔身每层 4 片四角竖边互吸闭环, 层间长边/短边等长整边叠合,
    全塔纯受压筒体;
  - 瞭望平台挑板全部 "一线双吸" (端墙顶边 + 筒顶方板边), 南北
    挑板成对共铰: 剪断整条铰链线, 力矩 30 <= 铰链总长 4 x 17.5
    x ... 的严格档预算; 东西挑板单片力矩 15 <= 35;
  - 透明塔台整圈骑平台拼缝, 顶盖压圈, 雷达锥四棱两两互吸自锁,
    指挥天线底边同时吸顶盖东边与塔台东墙顶边 (双吸);
  - 高层 R8: 全塔处处成环, 剪断任意单条磁力连接都有绕行路径。

用法: python3 tools/generate_control_tower.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

APRON = "gray"      # 停机坪
GRASS = "green"     # 草坪
MARK = "yellow"     # 跑道引导标线
BODY = "gray"       # 塔身
BAND = "orange"     # 塔身航空警示色带
WIN = "clear"       # 窗格方 / 透明塔台
DOOR = "blue"       # 值机门
DECK = "yellow"     # 瞭望平台挑板
DECKC = "gray"      # 平台中心
CAP = "blue"        # 塔台顶盖
RADAR = "red"       # 雷达锥
ANT = "red"         # 指挥天线
SHED = "cyan"       # 气象站小屋
SOCK = "orange"     # 风向袋
LIGHT = "yellow"    # 进近灯标

# =================================================================
# 1. 塔场 6x6 (x [0,6], y [0,6]): 拼缝全部落在塔身与小屋墙线上
# =================================================================
b.flat_rect("g0_a", 0, 0, 0.0, GRASS)
b.flat_rect("g0_b", 2, 0, 0.0, APRON)
b.flat("g0_c", 4, 0, 0.0, APRON)        # 气象站地坪
b.flat("g0_d", 5, 0, 0.0, APRON)

b.flat_rect("g1_a", 0, 1, 0.0, GRASS)
b.flat_rect("g1_b", 2, 1, 0.0, APRON)
b.flat_rect("g1_c", 4, 1, 0.0, APRON)

b.flat_rect("g2_a", 0, 2, 0.0, GRASS)
b.flat_rect("g2_b", 2, 2, 0.0, APRON)   # 塔身南沿
b.flat_rect("g2_c", 4, 2, 0.0, MARK)    # 引导标线

b.flat_rect("g3_a", 0, 3, 0.0, GRASS)
b.flat("g3_b", 2, 3, 0.0, BODY)         # 塔基
b.flat("g3_c", 3, 3, 0.0, BODY)
b.flat_rect("g3_d", 4, 3, 0.0, APRON)   # 值机门前

b.flat_rect("g4_a", 0, 4, 0.0, GRASS)
b.flat_rect("g4_b", 2, 4, 0.0, APRON)   # 塔身北沿
b.flat_rect("g4_c", 4, 4, 0.0, MARK)    # 引导标线

b.flat_rect("g5_a", 0, 5, 0.0, GRASS)
b.flat_rect("g5_b", 2, 5, 0.0, APRON)
b.flat_rect("g5_c", 4, 5, 0.0, GRASS)

# =================================================================
# 2. 气象站小屋 (x [4,5], y [0,1], z 0..1) + 风向袋
# =================================================================
b.wall_ns("shed_s", 4, 0.0, 0, SHED)
b.wall_ew("shed_w", 4.0, 0, 0, SHED)
b.wall_ew("shed_e", 5.0, 0, 0, SHED)
b.wall_ns("shed_n", 4, 1.0, 0, SHED)
b.flat("shed_r", 4, 0, 1.0, SHED)

# =================================================================
# 3. 塔身 (x [2,4], y [3,4], z 0..3): 1x2 长板筒, 每层 4 片闭环
# =================================================================
# 底层 (z 0..1): 东端门框方值机门
b.lintel_ns("t1_s", 2, 3.0, 0, BODY)
b.lintel_ns("t1_n", 2, 4.0, 0, BODY)
b.wall_ew("t1_w", 2.0, 3, 0, BODY)
b.add("t1_door", "door_frame", (4.0, 3.5, 0.5), (90, 0, 90), DOOR)

# 中层 (z 1..2): 航空警示色带 + 窗格方端墙
b.lintel_ns("t2_s", 2, 3.0, 1, BAND)
b.lintel_ns("t2_n", 2, 4.0, 1, BAND)
b.add("t2_w", "window_square", (2.0, 3.5, 1.5), (90, 0, 90), WIN)
b.add("t2_e", "window_square", (4.0, 3.5, 1.5), (90, 0, 90), WIN)

# 顶层 (z 2..3)
b.lintel_ns("t3_s", 2, 3.0, 2, BODY)
b.lintel_ns("t3_n", 2, 4.0, 2, BODY)
b.wall_ew("t3_w", 2.0, 3, 2, BODY)
b.wall_ew("t3_e", 4.0, 3, 2, BODY)

# =================================================================
# 4. 十字瞭望平台 (z=3): 筒顶 2 片 + 四方挑板 6 片
# =================================================================
b.flat("d_c1", 2, 3, 3.0, DECKC)        # 筒顶西
b.flat("d_c2", 3, 3, 3.0, DECKC)        # 筒顶东
b.flat("d_w", 1, 3, 3.0, DECK)          # 西挑板
b.flat("d_e", 4, 3, 3.0, DECK)          # 东挑板
b.flat("d_sw", 2, 2, 3.0, DECK)         # 南挑板 (成对共铰)
b.flat("d_se", 3, 2, 3.0, DECK)
b.flat("d_nw", 2, 4, 3.0, DECK)         # 北挑板 (成对共铰)
b.flat("d_ne", 3, 4, 3.0, DECK)

# =================================================================
# 5. 透明塔台 (z 3..4): 窗格方整圈 x6, 骑平台拼缝
# =================================================================
b.add("cab_s1", "window_square", (2.5, 3.0, 3.5), (90, 0, 0), WIN)
b.add("cab_s2", "window_square", (3.5, 3.0, 3.5), (90, 0, 0), WIN)
b.add("cab_w", "window_square", (2.0, 3.5, 3.5), (90, 0, 90), WIN)
b.add("cab_n1", "window_square", (2.5, 4.0, 3.5), (90, 0, 0), WIN)
b.add("cab_n2", "window_square", (3.5, 4.0, 3.5), (90, 0, 0), WIN)
b.add("cab_e", "window_square", (4.0, 3.5, 3.5), (90, 0, 90), WIN)

# =================================================================
# 6. 顶盖 (z=4) + 雷达锥 + 指挥天线
# =================================================================
b.flat("cap_w", 2, 3, 4.0, CAP)
b.flat("cap_e", 3, 3, 4.0, CAP)
RADAR_IDS = b.hat4("radar", 2, 3, 4.0, RADAR, shape="equilateral_triangle")
b.spire_ew("antenna", 4.0, 3, 4.0, ANT)

# =================================================================
# 7. 风向袋 + 进近灯标
# =================================================================
b.spire_ns("windsock", 4, 0.0, 1.0, SOCK)
b.crest_ew("app_1", 6.0, 2, 0.0, LIGHT)
b.crest_ew("app_2", 6.0, 3, 0.0, LIGHT)
b.crest_ew("app_3", 6.0, 4, 0.0, LIGHT)

# =================================================================
# 教程步骤 (14 步)
# =================================================================
b.step(
    "铺塔场南部 (y [0,2]): 7 片, 东南角留出气象站地坪。",
    ["g0_a", "g0_b", "g0_c", "g0_d", "g1_a", "g1_b", "g1_c"],
    tip="两片正方形地坪的拼缝就是气象站小屋的墙线。",
)
b.step(
    "铺塔场中部 (y [2,4]): 7 片, 正中两片灰色方板是塔基。",
    ["g2_a", "g2_b", "g2_c", "g3_a", "g3_b", "g3_c", "g3_d"],
    highlight=["g1_b"],
    tip="塔基方板四周的拼缝将咬住塔身第一层的每一条底边。",
)
b.step(
    "铺塔场北部 (y [4,6]): 6 片, 黄色长板是跑道引导标线。",
    ["g4_a", "g4_b", "g4_c", "g5_a", "g5_b", "g5_c"],
    highlight=["g3_b", "g3_c"],
    tip="6x6 塔场铺满 —— 管制塔台的地基比塔身宽一圈才稳。",
)
b.step(
    "立气象站小屋: 4 片立墙四角互吸闭环, 顶板四边压圈。",
    ["shed_s", "shed_w", "shed_e", "shed_n", "shed_r"],
    highlight=["g0_c"],
    tip="小屋是塔台的迷你练习: 先闭环再封顶, 大塔同一个道理。",
)
b.step(
    "砌塔身底层: 南北长板横楣 + 西端墙 + 东门框方值机门, 四角闭环。",
    ["t1_s", "t1_n", "t1_w", "t1_door"],
    highlight=["g3_b", "g3_c"],
    tip="1x2 长板筒是这座塔的独门骨架 —— 长边一整片, 竖缝只在四角。",
)
b.step(
    "砌塔身中层: 橙色警示色带 + 东西窗格方, 层间整边叠合。",
    ["t2_s", "t2_n", "t2_w", "t2_e"],
    highlight=["t1_s", "t1_door"],
    tip="橙白相间是机场塔台的国际配色 —— 远远就能认出来。",
)
b.step(
    "砌塔身顶层: 4 片再闭一环, 筒体升到 3.0。",
    ["t3_s", "t3_n", "t3_w", "t3_e"],
    highlight=["t2_s", "t2_n"],
    tip="三层筒体处处成环, 轻推塔身应整体联动。",
)
b.step(
    "盖筒顶并挑东西瞭望板: 中心 2 片压筒 + 东西挑板一线双吸。",
    ["d_c1", "d_c2", "d_w", "d_e"],
    highlight=["t3_s", "t3_n"],
    tip="挑板的内边同时吸端墙顶边与筒顶方板边 —— 一条缝两路力。",
)
b.step(
    "挑南北瞭望板: 4 片成对共铰, 十字平台合拢。",
    ["d_sw", "d_se", "d_nw", "d_ne"],
    highlight=["d_c1", "d_c2"],
    tip="每对挑板共用一条铰链线还互咬拼缝, 力矩远在预算之内。",
)
b.step(
    "立塔台南墙与西墙: 3 片窗格方骑平台拼缝。",
    ["cab_s1", "cab_s2", "cab_w"],
    highlight=["d_sw", "d_se"],
    tip="塔台整圈全透明 —— 管制员的视野一格都不能挡。",
)
b.step(
    "立塔台北墙与东墙: 3 片窗格方, 整圈闭合。",
    ["cab_n1", "cab_n2", "cab_e"],
    highlight=["cab_s1", "cab_w"],
    tip="四角竖边互吸闭环, 透明塔台与塔身一样结实。",
)
b.step(
    "盖塔台顶盖: 2 片蓝色方板四边压圈。",
    ["cap_w", "cap_e"],
    highlight=["cab_n1", "cab_e"],
    tip="顶盖压住整圈墙顶, 塔台成为刚性的玻璃盒子。",
)
b.step(
    "架雷达锥: 4 片红色等边三角四棱互吸自锁 (锥尖 4.71)。",
    RADAR_IDS,
    highlight=["cap_w"],
    tip="雷达锥骑在顶盖拼缝与沿口上, 四条斜棱两两吸成一体。",
)
b.step(
    "立指挥天线、挂风向袋、摆进近灯标 —— 塔台开始指挥!",
    ["antenna", "windsock", "app_1", "app_2", "app_3"],
    highlight=["cap_e", "shed_r"],
    tip="天线底边双吸顶盖东边与塔台东墙顶, 尖端直上 6.0 全场最高。",
)

b.finalize(
    model_id="control_tower_01",
    name="机场管制塔台",
    name_en="Airport Control Tower 01",
    description=(
        "全库第一座独立式机场管制塔台: 1x2 长板筒塔身三层四角闭环纯受压"
        " (长边整片长板横楣, 短边端墙嵌门框方值机门与窗格方), 顶部十字"
        "瞭望平台四方挑板一线双吸、南北成对共铰 (力矩 30 远低于预算),"
        " 整圈透明塔台骑平台拼缝, 顶盖西半戴红色等边四坡雷达锥、东沿"
        "立等腰指挥天线 (尖端 6.0); 塔下气象站小屋飘风向袋, 跑道东沿"
        "三盏进近灯标 —— 高层 R8 处处成环, 剪断任意单条连接都有绕行。"
    ),
    difficulty=3,
    tags=["机场", "航空", "塔台", "空管", "进阶"],
    min_pieces=60,
    min_steps=14,
)
