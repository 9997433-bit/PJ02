#!/usr/bin/env python3
"""生成模型 data/models/space_probe_01.json (深空小探测器)。

D1 收官批 4 模型 1/4 (难度配额解冻线 D1 >= 20, 路径 B1): 入门档
航天器选题 —— 落在外星平原上的深空小探测器, 也是航天器主题的
第一个 D1。结构签名是"十字着陆架 + 方舱 + 风车斜撑": 九片方板
铺成十字着陆架, 正中一座 1x1 仪器舱 (南面舱门、三面舷窗),
四片直角三角斜撑一角一片按风车方向旋转排布 —— 每片竖直角边
吸住舱角竖棱、水平直角边压住着陆架板边, 这是"斜撑为什么能
锁死方舱"的入门课; 四条臂末端各贴一片信标三角, 舱顶立一面
通讯天线小旗。与库内 D3 着陆器 (60+ 片箱体堆叠) 及本批巨石
门环 (三石塔)、滚珠起步坡 (塔-坡-槽)、魔法风车坊 (塔楼十字翼)
的结构逻辑完全不同 —— 全批唯一的十字对称平铺 + 斜撑结构。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 舱门朝南 -y):
  - 十字着陆架: 中心方板 1 + 四臂各 2 片方板             9 片
  - 仪器舱一圈 (z 0..1): 门框方舱门 + 3 片窗格方舷窗      4 片
  - 舱顶方板 (z=1, 四边整边锁住墙顶)                      1 片
  - 风车斜撑 4 片 (直角三角, 竖边吸舱角竖棱)              4 片
  - 信标三角 4 片 (等边三角平贴臂端板边)                  4 片
  - 通讯天线 1 面 (等边三角, 骑舱顶北沿)                  1 片
  合计 23 片, 6 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 着陆架九片方板整边互吸并全部接地, 舱墙墙脚整边骑中心板边;
  - 舱顶四边整边锁墙顶, 先合围后封顶 (R7b 无包围放置);
  - 斜撑竖直角边同时吸住两面舱墙的竖棱, 水平直角边压臂板边 ——
    一片三角三处受抓 (R2 环环相扣);
  - 最高点 1.87 (天线尖) < 2.5, 不触发 R8 高层结构判定。

用法: python3 tools/generate_space_probe_01.py  (在 magtile-studio 目录下运行)
"""

import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

PAD = "gray"        # 着陆架
PAD2 = "yellow"     # 着陆架臂端 (警示色)
HATCH = "orange"    # 舱门
PORT = "clear"      # 舷窗
CAP = "gray"        # 舱顶
LEG = "red"         # 风车斜撑
BEACON = "cyan"     # 信标
ANT = "blue"        # 通讯天线

TRI_H = round(math.sqrt(3) / 2, 6)   # 等边三角形高 0.866025

# =================================================================
# 1. 十字着陆架 (全部接地, 板板整边互吸; 中心格 [2,3]x[2,3])
# =================================================================
b.flat("pad_c", 2, 2, 0.0, PAD)
b.flat("arm_w1", 1, 2, 0.0, PAD)
b.flat("arm_w2", 0, 2, 0.0, PAD2)
b.flat("arm_e1", 3, 2, 0.0, PAD)
b.flat("arm_e2", 4, 2, 0.0, PAD2)
b.flat("arm_s1", 2, 1, 0.0, PAD)
b.flat("arm_s2", 2, 0, 0.0, PAD2)
b.flat("arm_n1", 2, 3, 0.0, PAD)
b.flat("arm_n2", 2, 4, 0.0, PAD2)

# =================================================================
# 2. 仪器舱一圈 (z 0..1): 南门框方 + 三面窗格方, 墙脚骑中心板边
# =================================================================
b.add("hatch_s", "door_frame", (2.5, 2.0, 0.5), (90, 0, 0), HATCH)
b.add("port_n", "window_square", (2.5, 3.0, 0.5), (90, 0, 0), PORT)
b.add("port_w", "window_square", (2.0, 2.5, 0.5), (90, 0, 90), PORT)
b.add("port_e", "window_square", (3.0, 2.5, 0.5), (90, 0, 90), PORT)

# =================================================================
# 3. 舱顶 (z=1) 与通讯天线 (骑舱顶北沿)
# =================================================================
b.flat("cap", 2, 2, 1.0, CAP)
b.crest_ns("antenna", 2, 3.0, 1.0, ANT)

# =================================================================
# 4. 风车斜撑 (直角三角, 一角一片按风车方向旋转排布)
# =================================================================
b.brace("leg_sw", (2.0, 2.0, 0.0), "-x", LEG)   # 平面 y=2, 压西臂板边
b.brace("leg_se", (3.0, 2.0, 0.0), "-y", LEG)   # 平面 x=3, 压南臂板边
b.brace("leg_ne", (3.0, 3.0, 0.0), "+x", LEG)   # 平面 y=3, 压东臂板边
b.brace("leg_nw", (2.0, 3.0, 0.0), "+y", LEG)   # 平面 x=2, 压北臂板边

# =================================================================
# 5. 信标三角 (等边三角平贴臂端外沿, 全部接地)
# =================================================================
b.place_tri("beacon_w", "equilateral_triangle",
            (0.0, 3.0, 0.0), (0.0, 2.0, 0.0), (-TRI_H, 2.5, 0.0), BEACON)
b.place_tri("beacon_e", "equilateral_triangle",
            (5.0, 2.0, 0.0), (5.0, 3.0, 0.0), (5.0 + TRI_H, 2.5, 0.0), BEACON)
b.place_tri("beacon_s", "equilateral_triangle",
            (2.0, 0.0, 0.0), (3.0, 0.0, 0.0), (2.5, -TRI_H, 0.0), BEACON)
b.place_tri("beacon_n", "equilateral_triangle",
            (3.0, 5.0, 0.0), (2.0, 5.0, 0.0), (2.5, 5.0 + TRI_H, 0.0), BEACON)

# =================================================================
# 教程步骤 (6 步)
# =================================================================
b.step(
    "铺十字着陆架内圈: 灰色方板放正中当舱底, 东南西北各贴一片, 拼成小十字。",
    ["pad_c", "arm_w1", "arm_e1", "arm_s1", "arm_n1"],
    tip="板与板整边完整贴合 —— 探测器落地要四平八稳。",
)
b.step(
    "接长四条臂: 四片黄色警示板接在臂端, 十字着陆架伸展完成。",
    ["arm_w2", "arm_e2", "arm_s2", "arm_n2"],
    highlight=["arm_w1", "arm_e1"],
)
b.step(
    "立仪器舱: 橙色门框方是舱门朝南, 三面透明窗格方是舷窗, 墙脚整边骑住中心板边围成一圈。",
    ["hatch_s", "port_w", "port_n", "port_e"],
    highlight=["pad_c"],
    tip="相邻舱墙竖棱手拉手 —— 拉成一圈方舱就推不倒了。",
)
b.step(
    "封舱顶立天线: 灰色方板四边整边锁住墙顶, 蓝色天线小旗骑上舱顶北沿。",
    ["cap", "antenna"],
    highlight=["port_n"],
    tip="先合围再封顶 —— 装配顺序也是设计的一部分。",
)
b.step(
    "装风车斜撑: 四片红色直角三角一角一片, 竖边吸住舱角竖棱, 横边压住臂上板边。",
    ["leg_sw", "leg_se", "leg_ne", "leg_nw"],
    highlight=["hatch_s", "arm_w1"],
    tip="斜撑像四条着陆腿 —— 一片三角同时被三处抓住, 方舱就锁死了。",
)
b.step(
    "点亮信标: 四片青色小三角平贴在臂端外沿, 深空小探测器开始工作!",
    ["beacon_w", "beacon_e", "beacon_s", "beacon_n"],
    highlight=["arm_w2", "arm_e2"],
)

b.finalize(
    model_id="space_probe_01",
    name="深空小探测器",
    name_en="Space Probe 01",
    description=(
        "入门档航天器: 落在外星平原上的深空小探测器, 结构签名是"
        "'十字着陆架 + 方舱 + 风车斜撑' —— 九片方板铺成十字着陆架, "
        "正中 1x1 仪器舱南面开橙色舱门、三面透明舷窗, 舱顶方板四边"
        "整边锁墙顶; 四片红色直角三角斜撑按风车方向一角一片, 竖直角边"
        "吸住舱角竖棱、水平直角边压住臂上板边, 一片三角同时被三处抓住; "
        "臂端四片青色信标三角平贴板边, 舱顶北沿立一面蓝色通讯天线。"
        "23 片全程接地受压零悬挑, 天线尖 1.87 不触发高层判定, "
        "搭完就能向桌面深空发回第一条信号。"
    ),
    difficulty=1,
    tags=["航天器", "探测器", "着陆架", "亲子入门"],
    min_pieces=23,
    min_steps=6,
    series="spacecraft",
)
print("已写入 series=spacecraft")
