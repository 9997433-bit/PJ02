#!/usr/bin/env python3
"""生成模型 data/models/astronaut_training_01.json (宇航员训练中心)。

太空探索主题批 2/4: 全库第一台"离心机" —— 与旋转木马 (中柱撑伞盖)
和各类车辆完全不同, 主角是一条横躺的旋转训练臂: 中央红色转轴塔
四墙合环、灰色转盘压顶, 两条黄色旋臂长板从转盘两侧水平伸出,
臂端各接一座蓝色乘员吊舱 (舷窗朝外) —— 塔-臂-舱-地锁成东西
两个门式大环, 剪断任何一端旋臂照样稳稳站住; 旁边绿色蹦床
练平衡, 橙色打卡旗与青色计时牌立在垫缝上 —— 抓稳了, 开转!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 离心机东西向横躺):
  - 南北草坪 (y [0,1] / [3,4]): 长板 x3 + 方板 x1 每侧            8 片
  - 缓冲垫 (y [1,3]): 青色单位方板 x14                           14 片
  - 转轴塔 (x [3,4], z 0..1): 红墙四片合环 + 灰色转盘压顶         5 片
  - 旋臂 x2: 黄色长板水平伸出 (z=1), 两端整边双吸                 2 片
  - 乘员吊舱 x2 (x [0,1] / [6,7], z 0..1): 三墙 + 舷窗窗格方
    朝外 + 清色舱盖                                              10 片
  - 转轴信标: 红色等边三角骑转盘北缘 (尖端 1.87)                  1 片
  - 蹦床 (x [1,2], y [2,3]): 绿墙四片合环 + 清色弹面              5 片
  - 打卡旗 x2 + 计时牌 x1                                         3 片
  合计 48 片, 10 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 旋臂是"两端整边双吸"的水平长板: 西端短边同线双吸转轴墙顶与
    转盘边, 东端短边同线双吸吊舱墙顶与舱盖边 —— 塔-臂-舱-地构成
    门式大环, 剪断任何一条铰链线, 旋臂都还有另一端撑着, 零悬挂;
  - 转轴塔与吊舱都是四墙合环 (四角竖边互咬), 转盘/舱盖四边全吸
    墙顶 —— 环上加盖, 连接图环路充足;
  - 蹦床同款四墙合环 + 弹面压顶; 打卡旗/计时牌底边整边吸垫缝,
    剪断任何一条装饰连接最多失联 1 片;
  - 最高点 1.87 (转轴信标尖), 低重心横向布局天生抗碰撞。

用法: python3 tools/generate_astronaut_training_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

GRASS = "green"     # 草坪
MAT = "cyan"        # 缓冲垫
HUB = "red"         # 转轴塔
DISC = "gray"       # 转盘
ARM = "yellow"      # 旋臂
POD = "blue"        # 乘员吊舱
PORT = "clear"      # 舷窗 (窗格方)
CAP = "clear"       # 舱盖 / 弹面
BEACON = "red"      # 转轴信标
TRAMP = "green"     # 蹦床围墙
FLAG = "orange"     # 打卡旗
SIGN = "cyan"       # 计时牌


def wall_ns_t(tid, tile_type, x0, y, z0, color):
    b.add(tid, tile_type, (x0 + 0.5, y, z0 + 0.5), (90, 0, 0), color)


def wall_ew_t(tid, tile_type, x, y0, z0, color):
    b.add(tid, tile_type, (x, y0 + 0.5, z0 + 0.5), (90, 0, 90), color)


# =================================================================
# 1. 场地: 南北草坪 (长板为主) + 中间两行青色缓冲垫 (单位方板)
# =================================================================
for i, x0 in enumerate((0, 2, 4)):
    b.flat_rect(f"gs_{i}", x0, 0, 0.0, GRASS)
b.flat("gs_3", 6, 0, 0.0, GRASS)
for x0 in range(7):
    b.flat(f"m_{x0}_1", x0, 1, 0.0, MAT)
for x0 in range(7):
    b.flat(f"m_{x0}_2", x0, 2, 0.0, MAT)
for i, x0 in enumerate((0, 2, 4)):
    b.flat_rect(f"gn_{i}", x0, 3, 0.0, GRASS)
b.flat("gn_3", 6, 3, 0.0, GRASS)

# =================================================================
# 2. 转轴塔 (x [3,4], y [1,2], z 0..1): 四墙合环 + 灰色转盘压顶
# =================================================================
b.wall_ns("hub_s", 3, 1.0, 0, HUB)
b.wall_ns("hub_n", 3, 2.0, 0, HUB)
b.wall_ew("hub_w", 3.0, 1, 0, HUB)
b.wall_ew("hub_e", 4.0, 1, 0, HUB)
b.flat("hub_disc", 3, 1, 1.0, DISC)

# =================================================================
# 3. 乘员吊舱 x2 (x [0,1] / [6,7], z 0..1): 三墙 + 舷窗朝外 + 舱盖
# =================================================================
b.wall_ns("gw_s", 0, 1.0, 0, POD)
b.wall_ns("gw_n", 0, 2.0, 0, POD)
wall_ew_t("gw_w", "window_square", 0.0, 1, 0, PORT)   # 舷窗朝西
b.wall_ew("gw_e", 1.0, 1, 0, POD)
b.flat("gw_cap", 0, 1, 1.0, CAP)

b.wall_ns("ge_s", 6, 1.0, 0, POD)
b.wall_ns("ge_n", 6, 2.0, 0, POD)
b.wall_ew("ge_w", 6.0, 1, 0, POD)
wall_ew_t("ge_e", "window_square", 7.0, 1, 0, PORT)   # 舷窗朝东
b.flat("ge_cap", 6, 1, 1.0, CAP)

# =================================================================
# 4. 旋臂 x2 (z=1 水平长板) + 转轴信标
# =================================================================
b.flat_rect("arm_w", 1, 1, 1.0, ARM)     # [1,3]: 转轴 <-> 西吊舱
b.flat_rect("arm_e", 4, 1, 1.0, ARM)     # [4,6]: 转轴 <-> 东吊舱
b.crest_ns("hub_beacon", 3, 2.0, 1.0, BEACON)

# =================================================================
# 5. 蹦床 (x [1,2], y [2,3]): 四墙合环 + 清色弹面
# =================================================================
b.wall_ns("tr_s", 1, 2.0, 0, TRAMP)
b.wall_ns("tr_n", 1, 3.0, 0, TRAMP)
b.wall_ew("tr_w", 1.0, 2, 0, TRAMP)
b.wall_ew("tr_e", 2.0, 2, 0, TRAMP)
b.flat("tr_top", 1, 2, 1.0, CAP)

# =================================================================
# 6. 打卡旗 x2 + 计时牌
# =================================================================
b.crest_ns("flag_a", 5, 2.0, 0.0, FLAG)
b.crest_ns("flag_b", 5, 3.0, 0.0, FLAG)
wall_ns_t("timer", "window_square", 4, 3.0, 0, SIGN)

# =================================================================
# 教程步骤 (10 步)
# =================================================================
b.step(
    "铺南草坪: 三条绿色长板加一片方板, 短边互吸连成一排。",
    ["gs_0", "gs_1", "gs_2", "gs_3"],
    tip="宇航员训练第一课: 先把场地铺平整。",
)
b.step(
    "铺缓冲垫南行: 七片青色方板贴着草坪北边排开。",
    [f"m_{x0}_1" for x0 in range(7)],
    highlight=["gs_0"],
    tip="离心机脚下全是软垫 —— 训练安全第一。",
)
b.step(
    "铺缓冲垫北行: 再来七片, 行行等边互吸。",
    [f"m_{x0}_2" for x0 in range(7)],
    highlight=["m_0_1"],
    tip="转轴塔、吊舱、蹦床全要踩这张垫网的拼缝。",
)
b.step(
    "铺北草坪: 场地合拢, 训练中心占地 7x4。",
    ["gn_0", "gn_1", "gn_2", "gn_3"],
    highlight=["m_0_2"],
    tip="草坪长板与垫行整边互吸, 全场连成一张网。",
)
b.step(
    "立转轴塔: 红墙四片合环踩正中垫缝, 灰色转盘压顶四边全吸。",
    ["hub_s", "hub_n", "hub_w", "hub_e", "hub_disc"],
    highlight=["m_3_1"],
    tip="四角竖边互咬 + 转盘压顶 —— 离心机的心脏必须最结实。",
)
b.step(
    "搭西吊舱: 三面蓝墙合上朝西的舷窗窗格方, 乘员位一号就绪。",
    ["gw_s", "gw_n", "gw_w", "gw_e"],
    highlight=["hub_disc"],
    tip="舷窗朝外 —— 转起来的时候能看见整个训练场飞快掠过。",
)
b.step(
    "搭东吊舱: 对称再来一座, 舷窗朝东。",
    ["ge_s", "ge_n", "ge_w", "ge_e"],
    highlight=["gw_w"],
    tip="两座吊舱对称配重, 离心机转起来才不偏心。",
)
b.step(
    "架旋臂盖舱盖: 黄色长板两端整边双吸, 塔-臂-舱-地锁成大环。",
    ["arm_w", "arm_e", "gw_cap", "ge_cap"],
    highlight=["hub_disc", "gw_s", "ge_s"],
    tip="旋臂西端吸转盘边、东端吸舱盖边 —— 剪断一端另一端还撑着。",
)
b.step(
    "插转轴信标, 围蹦床: 红色三角骑转盘北缘, 绿墙合环弹面压顶。",
    ["hub_beacon", "tr_s", "tr_n", "tr_w", "tr_e", "tr_top"],
    highlight=["arm_w"],
    tip="信标亮了就是开转警告; 蹦床练的是失重前的平衡感。",
)
b.step(
    "立打卡旗与计时牌收尾: 今天的成绩 —— 8 个 G, 坚持 30 秒!",
    ["flag_a", "flag_b", "timer"],
    highlight=["tr_top", "hub_beacon"],
    tip="旗子底边整边吸垫缝 —— 通过考核的宇航员来这里插旗!",
)

b.finalize(
    model_id="astronaut_training_01",
    name="宇航员训练中心",
    name_en="Astronaut Training Center 01",
    description=(
        "只用核心九片型的太空探索训练场: 主角是全库第一台横躺的离心机 "
        "—— 中央红色转轴塔四墙合环、灰色转盘压顶, 两条黄色旋臂长板从"
        "转盘两侧水平伸出, 臂端各接一座蓝色乘员吊舱 (舷窗窗格方朝外), "
        "塔-臂-舱-地锁成东西两个门式大环, 剪断任何一端旋臂照样站得住; "
        "旁边绿色蹦床四墙合环、清色弹面压顶练平衡, 橙色打卡旗与青色"
        "计时牌立在缓冲垫拼缝上 —— 抓稳了, 开转!"
    ),
    difficulty=2,
    tags=["航天", "宇航员", "训练", "离心机"],
    min_pieces=48,
    min_steps=10,
)
