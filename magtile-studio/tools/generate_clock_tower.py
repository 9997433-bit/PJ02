#!/usr/bin/env python3
"""生成模型 data/models/clock_tower_01.json (中央大钟楼)。

城市地标主题: 全库第一个使用扇形磁力片的模型 —— 钟面是 2 片
四分之一圆扇形在檐口上合成的半圆日晷钟, 南北双面报时;
钟面之上是 2 片长方形横楣围成的开敞钟亭 (东西向), 再上
长方形顶板转换层接梯形四坡 + 等腰四坡尖顶, 层层收分。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 钟楼广场: 4x4 外环 12 片 + 大门南侧走道 2 片                 14 片
  - 塔身 (x 1..3, y 1..3, z 0..4): 四层方墙, 底层南面留门
    (第 2 层黄色门楣横跨), 第 3 层四面透明观景窗                 30 片
  - 檐口转换层 (z=4): 2 片平铺长方形                               2 片
  - 半圆大钟面: 南北各 2 片扇形, 弧顶朝天                          4 片
  - 开敞钟亭 (z 4..5): 东西 2 片长方形横楣, 底边吸檐口长边         2 片
  - 亭顶转换层 (z=5): 2 片平铺长方形                               2 片
  - 攒尖顶: 4 片梯形四坡 + 方形压顶 + 4 片等腰尖顶 (z 至 6.57)     9 片
  - 广场灯柱: 四角 4 片等腰三角灯尖                                4 片
  合计 67 片, 16 个教程步骤。

物理规则要点 (通过 R1~R8 全部校验):
  - 扇形只有两条直边带磁: 水平半径边整边吸檐口板边, 竖直半径边
    与同伴扇形互吸 —— 两片合成的半圆完全自锁, 弧边只作装饰;
  - 钟亭横楣底边 (长 2) 吸檐口长方形长边, 顶边再被亭顶长方形
    压住 —— 两级长方形转换层把方墙世界与梯形四坡精确缝合;
  - 扇形与横楣是竖直立件 (重心在铰链正上方), 力矩为零。

用法: python3 tools/generate_clock_tower.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import EQ_APEX, ModelBuilder, _sub  # noqa: E402

b = ModelBuilder()

BRICK = "red"        # 塔身砖墙
TRIM = "yellow"      # 门楣/檐口点缀
ROOF = "blue"        # 亭顶与攒尖

# =================================================================
# 1. 钟楼广场: 4x4 外环 12 片 + 大门南侧走道 2 片
# =================================================================
RING = [(x, y) for x in range(4) for y in range(4)
        if not (1 <= x <= 2 and 1 <= y <= 2)]
for x0, y0 in RING:
    b.flat(f"pz_{x0}_{y0}", x0, y0, 0.0,
           "gray" if (x0 + y0) % 2 == 0 else "green")
b.flat("wk_1", 1, -1, 0.0, "gray")       # 大门走道西片
b.flat("wk_2", 2, -1, 0.0, "green")      # 大门走道东片

# =================================================================
# 2. 塔身 (x 1..3, y 1..3): 四层方墙
#    L0 南面 x 1..2 留门; L1 南面黄色门楣; L2 四面透明观景窗
# =================================================================
b.wall_ns("t0_s2", 2, 1.0, 0, BRICK)
for lv in (0, 1):
    for y0 in (1, 2):
        b.wall_ew(f"t{lv}_w{y0}", 1.0, y0, lv, BRICK)
        b.wall_ew(f"t{lv}_e{y0}", 3.0, y0, lv, BRICK)
    for x0 in (1, 2):
        b.wall_ns(f"t{lv}_n{x0}", x0, 3.0, lv, BRICK)
b.lintel_ns("t1_lintel", 1, 1.0, 1, TRIM)      # 大门门楣 (跨 x 1..3)
for x0 in (1, 2):                              # L2 观景层 (透明窗带)
    b.wall_ns(f"t2_s{x0}", x0, 1.0, 2, "clear")
    b.wall_ns(f"t2_n{x0}", x0, 3.0, 2, "clear")
for y0 in (1, 2):
    b.wall_ew(f"t2_w{y0}", 1.0, y0, 2, BRICK)
    b.wall_ew(f"t2_e{y0}", 3.0, y0, 2, BRICK)
for x0 in (1, 2):                              # L3 钟机层
    b.wall_ns(f"t3_s{x0}", x0, 1.0, 3, BRICK)
    b.wall_ns(f"t3_n{x0}", x0, 3.0, 3, BRICK)
for y0 in (1, 2):
    b.wall_ew(f"t3_w{y0}", 1.0, y0, 3, BRICK)
    b.wall_ew(f"t3_e{y0}", 3.0, y0, 3, BRICK)

# =================================================================
# 3. 檐口转换层 (z=4): 2 片平铺长方形 (短边吸南北墙顶)
# =================================================================
b.flat_rect("cor_w", 1, 1, 4.0, TRIM, axis="y")   # x 1..2, y 1..3
b.flat_rect("cor_e", 2, 1, 4.0, TRIM, axis="y")   # x 2..3, y 1..3

# =================================================================
# 4. 半圆大钟面: 南北各 2 片扇形 (水平半径边吸檐口板边,
#    竖直半径边两片互吸, 弧顶朝天)
# =================================================================
b.place_edge("clk_s_e", "sector", 0, (2.0, 1.0, 4.0), (3.0, 1.0, 4.0),
             (0, 0, 1), "clear")
b.place_edge("clk_s_w", "sector", 0, (2.0, 1.0, 4.0), (1.0, 1.0, 4.0),
             (0, 0, 1), "clear")
b.place_edge("clk_n_e", "sector", 0, (2.0, 3.0, 4.0), (3.0, 3.0, 4.0),
             (0, 0, 1), "clear")
b.place_edge("clk_n_w", "sector", 0, (2.0, 3.0, 4.0), (1.0, 3.0, 4.0),
             (0, 0, 1), "clear")

# =================================================================
# 5. 开敞钟亭 (z 4..5): 东西 2 片长方形横楣
# =================================================================
b.lintel_ew("bel_w", 1.0, 1, 4, ROOF)      # 底边吸 cor_w 西长边
b.lintel_ew("bel_e", 3.0, 1, 4, ROOF)      # 底边吸 cor_e 东长边

# =================================================================
# 6. 亭顶转换层 (z=5) + 攒尖顶 (梯形四坡 + 压顶 + 等腰尖顶)
# =================================================================
b.flat_rect("top_w", 1, 1, 5.0, "gray", axis="y")   # 西长边吸 bel_w 顶边
b.flat_rect("top_e", 2, 1, 5.0, "gray", axis="y")   # 东长边吸 bel_e 顶边

ZT = 5.0 + EQ_APEX                                  # 梯形上底高度 5.707
HIP_FACES = [
    ("hip_e", (3.0, 1.0, 5.0), (3.0, 3.0, 5.0), (2.5, 2.0, ZT)),
    ("hip_w", (1.0, 3.0, 5.0), (1.0, 1.0, 5.0), (1.5, 2.0, ZT)),
    ("hip_s", (1.0, 1.0, 5.0), (3.0, 1.0, 5.0), (2.0, 1.5, ZT)),
    ("hip_n", (3.0, 3.0, 5.0), (1.0, 3.0, 5.0), (2.0, 2.5, ZT)),
]
for tid, b0, b1, top_mid in HIP_FACES:
    bottom_mid = tuple((b0[i] + b1[i]) / 2 for i in range(3))
    b.place_edge(tid, "trapezoid", 0, b0, b1, _sub(top_mid, bottom_mid), ROOF)
b.flat("hip_cap", 1.5, 1.5, ZT, "gray")
SPIRE = b.hat4("spire", 1.5, 1.5, ZT, TRIM)         # 金色等腰尖顶, 顶尖 6.57

# =================================================================
# 7. 广场灯柱: 四角 4 片等腰三角灯尖
# =================================================================
b.spire_ns("lamp_sw", 0, 0.0, 0.0, "purple")
b.spire_ns("lamp_se", 3, 0.0, 0.0, "purple")
b.spire_ns("lamp_nw", 0, 4.0, 0.0, "purple")
b.spire_ns("lamp_ne", 3, 4.0, 0.0, "purple")

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "广场南排与走道: 铺 4 片广场板 (y 0..1), 大门前再接 2 片走道。",
    ["pz_0_0", "pz_1_0", "pz_2_0", "pz_3_0", "wk_1", "wk_2"],
    tip="灰绿相间的棋盘格 —— 中央 2x2 空位留给塔身。",
)
b.step(
    "广场合围: 东西各 2 片、北排 4 片, 外环合拢。",
    ["pz_0_1", "pz_0_2", "pz_3_1", "pz_3_2",
     "pz_0_3", "pz_1_3", "pz_2_3", "pz_3_3"],
    highlight=["pz_0_0", "pz_3_0"],
    tip="12 片外环是钟楼的裙边, 也是塔墙的地锚。",
)
b.step(
    "塔身底层: 7 片红砖墙立在广场内沿 —— 南面只装东段 1 片, "
    "x 1..2 留作大门。",
    ["t0_w1", "t0_w2", "t0_s2", "t0_e1", "t0_e2", "t0_n1", "t0_n2"],
    highlight=["pz_1_0", "pz_2_0"],
    tip="墙底边吸广场板边, 拐角竖边两两互吸围出塔身。",
)
b.step(
    "塔身第 2 层与门楣: 先叠西/东/北 6 片砖墙, 再让黄色门楣横跨"
    "大门上方 —— 两端竖边吸东西墙竖边。",
    ["t1_w1", "t1_w2", "t1_e1", "t1_e2", "t1_n1", "t1_n2", "t1_lintel"],
    highlight=["t0_s2", "t0_w1"],
    tip="门楣下方是 2 格宽的空门洞, 全靠两端竖边受力 —— 先立邻墙。",
)
b.step(
    "第 3 层观景窗带: 南北 4 片透明窗 + 东西 4 片砖墙, 游客在这层"
    "俯瞰全城。",
    ["t2_w1", "t2_w2", "t2_e1", "t2_e2",
     "t2_s1", "t2_s2", "t2_n1", "t2_n2"],
    highlight=["t1_lintel", "t1_n1"],
    tip="透明片和砖墙一样有磁边 —— 上下对缝叠齐。",
)
b.step(
    "第 4 层钟机层: 8 片红砖墙再上一层, 塔身到 4 格高。",
    ["t3_w1", "t3_w2", "t3_e1", "t3_e2",
     "t3_s1", "t3_s2", "t3_n1", "t3_n2"],
    highlight=["t2_s1", "t2_w1"],
    tip="这层里住着大钟的齿轮 (想象一下), 墙要格外方正。",
)
b.step(
    "檐口转换层: 2 片黄色长方形平铺塔顶, 短边吸南北墙顶, "
    "中缝互吸 —— 长边留给钟亭横楣。",
    ["cor_w", "cor_e"],
    highlight=["t3_s1", "t3_n2"],
    tip="方墙顶接不住 2 格长的横楣底 —— 长方形檐口就是转换层。",
)
b.step(
    "南面大钟: 2 片透明扇形立在檐口南沿 —— 水平半径边吸檐口板边, "
    "竖直半径边两片互吸, 合成弧顶朝天的半圆钟面。",
    ["clk_s_e", "clk_s_w"],
    highlight=["cor_w", "cor_e"],
    tip="扇形只有两条直边带磁, 弧边是装饰 —— 半圆一合就自锁。",
)
b.step(
    "北面大钟: 同法再合 2 片扇形, 南北双面报时。",
    ["clk_n_e", "clk_n_w"],
    highlight=["clk_s_e"],
    tip="两面钟共用一根竖直中轴线 —— 从东西侧看是对称的双弧。",
)
b.step(
    "开敞钟亭: 东西 2 片蓝色长方形横楣立上檐口 —— 底边整边吸"
    "檐口长边, 南北两面完全开敞。",
    ["bel_w", "bel_e"],
    highlight=["cor_w", "cor_e"],
    tip="钟亭四面来风, 钟声才能传遍全城。",
)
b.step(
    "亭顶转换层: 2 片灰色长方形压住横楣顶边, 中缝互吸 —— 钟亭"
    "锁成门式刚架。",
    ["top_w", "top_e"],
    highlight=["bel_w", "bel_e"],
    tip="上压下、缝互吸, 两条横楣从此不会向内倒。",
)
b.step(
    "攒尖顶·东西坡: 2 片蓝色梯形下底整边吸亭顶长边, 向内倾斜。",
    ["hip_e", "hip_w"],
    highlight=["top_w", "top_e"],
    tip="梯形下底与亭顶长边等长 —— 转换层的接力棒交到屋顶。",
)
b.step(
    "攒尖顶·南北坡与压顶: 南北 2 片梯形腰边卡进东西坡, 顶口盖"
    "灰色压顶。",
    ["hip_s", "hip_n", "hip_cap"],
    highlight=["hip_e", "hip_w"],
    tip="四腰两两互吸自锁, 压顶同时吸住四片上底。",
)
b.step(
    "金色尖顶: 4 片黄色等腰三角形斜棱互吸锁尖, 塔尖冲到 6.57 格高 "
    "—— 全城都看得见。",
    SPIRE,
    highlight=["hip_cap"],
    tip="最后一片卡进去的咔哒声, 就是钟楼封顶的礼炮。",
)
b.step(
    "广场灯柱: 四角各立 1 片紫色等腰灯尖。",
    ["lamp_sw", "lamp_se", "lamp_nw", "lamp_ne"],
    highlight=["pz_0_0", "pz_3_3"],
    tip="灯尖底边吸广场板边 —— 夜里为看钟的人照路。",
)
b.step(
    "对时巡检: 绕广场一圈, 检查南北钟面的竖直中缝是否严丝合缝 —— "
    "中央大钟楼正式报时!",
    ["pz_1_0" if False else "wk_1"] if False else ["lamp_dummy"] if False
    else [],
    tip="",
)

b.finalize(
    model_id="clock_tower_01",
    name="中央大钟楼",
    name_en="Central Clock Tower 01",
    description=(
        "全库第一个用上扇形磁力片的模型: 南北两面各由 2 片透明扇形在"
        "檐口上合成弧顶朝天的半圆大钟, 只靠两条直磁边自锁; 四层红砖"
        "塔身底层开 2 格大门 (黄色门楣三边受力), 檐口与亭顶两级长方形"
        "转换层, 中间夹着东西向开敞钟亭, 最上层梯形攒尖 + 金色等腰"
        "尖顶收分到 6.57 格 —— 一座层层收分的城市地标。"
    ),
    difficulty=3,
    tags=["城市地标", "建筑", "钟楼", "扇形首秀"],
    min_pieces=60,
    min_steps=16,
)
