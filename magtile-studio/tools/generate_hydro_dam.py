#!/usr/bin/env python3
"""生成模型 data/models/hydro_dam_01.json (水电站大坝)。

工程结构主题: 全库第一座挡水建筑 —— 一道 7 格长的两级阶梯重力坝
横锁河谷: 下级坝体是 双面立墙 + 压顶板 的箱形环 (每片压顶同时锁
上下游两面墙), 上级挡水墙沿上游沿口退台升起, 下游侧直角三角扶壁
逐座锁定 (斜撑 + 阶梯 = 重力坝剖面); 坝身中段留 2 格溢洪道,
两条透明泄流水舌从坝肩俯冲入消力池、溅起浪花; 西端水轮机厂房
经引水桥板与坝体相接, 东端输电塔顶着六边形变压线圈 —— 合闸,
送电!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 坝轴沿 +x, 上游朝北):
  - 下游河床: 厂房区方板 4 + 长板 x4 + 方板 x2                   10 片
  - 水库 (上游): 长板 x7                                          7 片
  - 下级坝体: 下游墙 7 + 上游墙 7 + 压顶板 7                     21 片
  - 上级挡水墙: 立墙 5 (中段留 2 格溢洪道) + 护栏三角 3           8 片
  - 扶壁: 直角三角斜撑 x3 (竖边吸上级墙, 横边吸压顶拼缝)          3 片
  - 溢洪道: 30 度泄流水舌 x2 + 消力池浪花 x2                      4 片
  - 水轮机厂房: 圈层箱体 4 + 厂房顶长板 1 + 引水桥板 1            6 片
  - 输电塔: 立墙 x2 层 + 六边形变压线圈                           3 片
  合计 62 片, 16 个教程步骤, 6 种磁力片形状 (迁移期不使用等腰片)。

物理规则要点 (通过 R1~R8 全部校验, 严格档零警告):
  - 施工顺序先坝后库, 全程保持单一连通组 (无 disconnected_assembly
    分组警告): 压顶先单边吸下游墙顶 (7 片合计力矩 105 g·单位 <=
    严格档共线铰链预算 122.5), 上游墙随即合铰、水库长板最后贴上
    上游墙底边 —— 每一步放下的片都吸得住已有结构;
  - 下级坝体是连续箱形环: 每片压顶同时吸上下游墙顶 (双铰链
    互为保险), 剪断任何一条铰链线, 压顶仍搭在另一面墙上;
  - 上级挡水墙退台立在压顶北沿 (墙顶-压顶共线铰链), 下游侧
    扶壁竖边吸墙身竖边、横边吸压顶拼缝 —— 三角刚性节点;
  - 泄流水舌顶边整边吸坝肩沿口, 坡尾自然落入消力池 (接地斜撑);
  - 引水桥板长边整边吸厂房顶北长边 (力矩 30 <= 预算 40);
  - 六边形线圈竖立在塔顶线上, 重心正压铰链、力臂为零。

用法: python3 tools/generate_hydro_dam.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder, SQ3

b = ModelBuilder()

DAM = "gray"        # 坝体
WATER = "blue"      # 水库
FLOW = "clear"      # 泄流水舌
BASIN = "cyan"      # 消力池
HOUSE = "yellow"    # 厂房
PYLON = "red"       # 输电塔

# =================================================================
# 1. 下游河床 y[0,2]: 厂房区方板 + 消力池长板 + 输电塔区方板
# =================================================================
for x in range(2):
    for y in range(2):
        b.flat(f"yd_{x}_{y}", x, y, 0.0, "gray")    # 厂房区
for x in range(2, 6):
    color = BASIN if 3 <= x <= 4 else "green"
    b.flat_rect(f"dn_{x}", x, 0, 0.0, color, axis="y")  # [x,x+1]x[0,2]
b.flat("pt_0", 6, 0, 0.0, "green")                  # 输电塔区
b.flat("pt_1", 6, 1, 0.0, "green")

# =================================================================
# 2. 水库 (上游) y[3,5]: 7 片蓝色长板
# =================================================================
for x in range(7):
    b.flat_rect(f"rs_{x}", x, 3, 0.0, WATER, axis="y")

# =================================================================
# 3. 下级坝体 y[2,3] (z0..1): 双面立墙 + 压顶板
# =================================================================
for x in range(7):
    b.wall_ns(f"dw_s_{x}", x, 2.0, 0, DAM)          # 下游墙
    b.wall_ns(f"dw_n_{x}", x, 3.0, 0, DAM)          # 上游墙
for x in range(7):
    b.flat(f"cap_{x}", x, 2, 1.0, DAM)              # 压顶板

# =================================================================
# 4. 上级挡水墙 (y=3, z1..2): 中段留 2 格溢洪道 + 护栏三角
# =================================================================
for x in (0, 1, 2, 5, 6):
    b.wall_ns(f"uw_{x}", x, 3.0, 1, DAM)
for x in (0, 2, 5):
    b.crest_ns(f"rail_{x}", x, 3.0, 2.0, PYLON)     # 坝顶护栏
# 扶壁: 竖直角边吸上级墙竖边, 水平直角边吸压顶拼缝
for x in (1, 2, 6):
    b.place_tri(f"bt_{x}", "right_triangle",
                (float(x), 3.0, 1.0), (float(x), 2.0, 1.0),
                (float(x), 3.0, 2.0), DAM)

# =================================================================
# 5. 溢洪道 x[3,5]: 泄流水舌俯冲入消力池 + 浪花
# =================================================================
b.ramp("sp_w", "-y", 2.0, 3, 1.0, FLOW)             # 顶边吸坝肩 (y=2, z=1)
b.ramp("sp_e", "-y", 2.0, 4, 1.0, FLOW)
TAIL_Y = 2.0 - SQ3                                  # 坡尾 y = 0.267949
b.crest_ns("fm_w", 3, TAIL_Y, 0.0, FLOW)            # 消力池浪花
b.crest_ns("fm_e", 4, TAIL_Y, 0.0, FLOW)

# =================================================================
# 6. 水轮机厂房 [0,2]x[0,1] + 引水桥板
# =================================================================
b.lintel_ns("th_s", 0, 0.0, 0, HOUSE)               # 厂房南墙
b.wall_ew("th_w", 0.0, 0, 0, HOUSE)                 # 西山墙
b.lintel_ns("th_n", 0, 1.0, 0, HOUSE)               # 北墙
b.wall_ew("th_e", 2.0, 0, 0, "clear")               # 东观察窗
b.flat_rect("th_rf", 0, 0, 1.0, PYLON)              # 厂房顶
b.flat_rect("th_br", 0, 1, 1.0, DAM)                # 引水桥板 (吸厂房顶北长边)

# =================================================================
# 7. 输电塔 [6,7] (x=6 线): 立墙 x2 层 + 六边形变压线圈
# =================================================================
b.wall_ew("py_0", 6.0, 0, 0, PYLON)
b.wall_ew("py_1", 6.0, 0, 1, PYLON)
b.place_edge("py_coil", "hexagon", 4,
             (6.0, 0.0, 2.0), (6.0, 1.0, 2.0), (0.0, 0.0, 1.0), HOUSE)

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺厂房区地坪: 河谷西端铺 4 片灰色方板 ([0,2]x[0,2])。",
    [f"yd_{x}_{y}" for x in range(2) for y in range(2)],
    tip="水轮机厂房将坐在这块地坪上。",
)
b.step(
    "铺下游河床: 4 片长板竖铺 (中段青色是消力池), 东端再补 2 片"
    "输电塔区方板。",
    [f"dn_{x}" for x in range(2, 6)] + ["pt_0", "pt_1"],
    highlight=["yd_1_0"],
    tip="长板短边吸地坪边 —— 下游河床一次铺通。",
)
b.step(
    "立下游墙西段: y=2 线上立 4 片灰色立墙。",
    [f"dw_s_{x}" for x in range(4)],
    highlight=["dn_2", "dn_3"],
    tip="底边吸河床板边 —— 这是大坝的下游脸面。",
)
b.step(
    "立下游墙东段: 再立 3 片, 下游面贯通。",
    [f"dw_s_{x}" for x in range(4, 7)],
    highlight=["dw_s_3"],
    tip="一字排开不留缝 —— 重力坝靠身板挡水。",
)
b.step(
    "盖坝顶压顶: 7 片灰色压顶板逐格盖上, 南长边先整边吸住下游墙顶沿。",
    [f"cap_{x}" for x in range(7)],
    highlight=["dw_s_0", "dw_s_6"],
    tip="压顶暂时单边悬挑半格 (在力矩预算内) —— 上游墙一立就变双保险。",
)
b.step(
    "立上游墙: y=3 线上立 7 片, 墙顶吸住压顶北沿, 与下游墙夹出 1 格厚"
    "的坝芯。",
    [f"dw_n_{x}" for x in range(7)],
    highlight=["cap_0", "cap_6"],
    tip="每片压顶从此同时压住上下游两面墙 —— 双铰链互为保险, 下级坝体"
        "锁成连续箱形环。",
)
b.step(
    "铺水库西半: 上游 y[3,5] 竖铺 4 片蓝色长板, 南边先吸上游墙底边。",
    [f"rs_{x}" for x in range(4)],
    highlight=["dw_n_0", "yd_0_1"],
    tip="上游是一整片深水库 —— 大坝就横锁在河床与水库之间。",
)
b.step(
    "铺水库东半: 再铺 3 片, 水库贯通 7 格。",
    [f"rs_{x}" for x in range(4, 7)],
    highlight=["rs_3"],
    tip="上游面直接泡在水里 —— 这正是重力坝的日常。",
)
b.step(
    "退台起上级挡水墙西段: 压顶北沿 x[0,3] 立 3 片立墙。",
    ["uw_0", "uw_1", "uw_2"],
    highlight=["cap_0", "cap_2"],
    tip="墙脚踩在 墙顶-压顶 的共线铰链上 —— 一条铰链三重吸合。",
)
b.step(
    "起上级挡水墙东段并装护栏: x[5,7] 再立 2 片, 墙顶点 3 片红色"
    "护栏三角 —— 中段留出的 2 格就是溢洪道。",
    ["uw_5", "uw_6", "rail_0", "rail_2", "rail_5"],
    highlight=["uw_0", "cap_4"],
    tip="溢洪道不是缺陷, 是设计: 洪水从这里过坝。",
)
b.step(
    "锁扶壁: 3 片直角三角在下游侧竖边吸上级墙、横边吸压顶拼缝。",
    ["bt_1", "bt_2", "bt_6"],
    highlight=["uw_1", "uw_6"],
    tip="斜撑 + 阶梯 = 重力坝剖面 —— 三角刚性节点抗水推力。",
)
b.step(
    "放泄流水舌: 2 片透明 30 度水舌顶边整边吸坝肩沿口, 俯冲入消力池。",
    ["sp_w", "sp_e"],
    highlight=["cap_3", "cap_4"],
    tip="坡尾自然落地就是接地斜撑 —— 水舌越冲越稳。",
)
b.step(
    "溅浪花: 消力池里 2 片透明三角立在水舌尾线上。",
    ["fm_w", "fm_e"],
    highlight=["sp_w", "sp_e"],
    tip="消力池的使命就是把水的力气消掉 —— 浪花是它的勋章。",
)
b.step(
    "砌水轮机厂房: 长方形前后墙 + 方形山墙圈层围合 (东面透明观察窗)。",
    ["th_s", "th_w", "th_n", "th_e"],
    highlight=["yd_0_0", "yd_1_1"],
    tip="长边给前后墙、短边给山墙 —— 圈层砌法的长短分工。",
)
b.step(
    "盖厂房顶接引水桥: 红色厂房顶压住四面墙, 灰色引水桥板长边整边"
    "吸厂房顶北长边、伸向坝身。",
    ["th_rf", "th_br"],
    highlight=["th_s", "th_n"],
    tip="桥板力矩 30 <= 长边铰链预算 40 —— 水从坝底引进厂房发电。",
)
b.step(
    "立输电塔: 东端 2 片红色立墙直上, 塔顶竖起六边形变压线圈 —— "
    "合闸, 送电!",
    ["py_0", "py_1", "py_coil"],
    highlight=["pt_0", "pt_1"],
    tip="六边形重心正压塔顶铰链, 力臂为零 —— 电流已经出发。",
)

b.finalize(
    model_id="hydro_dam_01",
    name="水电站大坝",
    name_en="Hydroelectric Dam 01",
    description=(
        "全库第一座挡水建筑: 7 格长的两级阶梯重力坝横锁河谷 —— 下级坝体"
        "双面立墙加压顶板锁成连续箱形环 (每片压顶双铰链互为保险), 上级"
        "挡水墙沿上游沿口退台升起、下游侧直角三角扶壁锁成刚性节点; 坝身"
        "中段 2 格溢洪道泻下两条透明水舌俯冲入消力池 (坡尾接地斜撑), "
        "西端水轮机厂房经引水桥板与坝体相接, 东端输电塔顶着六边形变压"
        "线圈 —— 合闸, 送电!"
    ),
    difficulty=3,
    tags=["工程", "大坝", "水电站", "溢洪道", "进阶"],
    min_pieces=55,
    min_steps=16,
)
