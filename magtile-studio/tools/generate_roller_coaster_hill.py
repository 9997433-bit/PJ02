#!/usr/bin/env python3
"""生成模型 data/models/roller_coaster_hill_01.json (过山车爬升段)。

第三批模型: 游乐园主题 —— 与"回环"不同, 本模型是过山车的
"链式爬升丘": 三层峰顶塔居中, 东西两侧各一串三段 30 度长方形
坡道 (提升段与俯冲段) 沿桥墩逐级降到地面; 东端是站台与四坡顶
候车亭, 西端是冲出段与缓冲挡板 —— 一条完整的"爬升-越顶-俯冲"
剖面。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 峰顶塔环形广场 8                                               8 片
  - 峰顶塔 3 层 (每层 4 墙 + 楼板)                                15 片
  - 东侧提升段: 桥墩 3 + 坡道 3 + 直角护撑 3                       9 片
  - 西侧俯冲段: 桥墩 3 + 坡道 3 + 直角护撑 3                       9 片
  - 西端冲出段 2 + 缓冲挡板 1                                      3 片
  - 东端站台 4 + 候车亭 (4 墙 + 等腰四坡顶 4) + 排队栏 2          14 片
  - 广场立牌塔尖 2                                                 2 片
  合计 60 片, 16 个教程步骤, 5 种磁力片形状。

物理要点 (通过 R1~R8 全部校验):
  - 每段坡道两端都有依托: 顶短边吸上一级桥墩顶 (或塔楼板边),
    尾短边吸下一级桥墩顶 (或自然落地) —— 剪断任何一条节点铰链
    线, 坡道仍经由另一端传力, 全程无悬臂;
  - 桥墩与坡道同步成链 (墩-道-墩-道), 每步结束时全场连通;
  - 桥墩根部直角三角护撑与墩身、坡尾围成三角闭环。

坐标约定与 C++ 端一致: 旋转为欧拉角 (度), R = Rz * Ry * Rx。
用法: python3 tools/generate_roller_coaster_hill.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import SQ3, ModelBuilder

mb = ModelBuilder()

PLAZA = "green"     # 游园草坪
TOWER = "red"       # 峰顶塔架
TRACK = "yellow"    # 轨道坡板
PIER = "gray"       # 桥墩

# 东侧节点 x 坐标 (提升段), 西侧对称
E1 = 3.0 + SQ3      # 4.732051  (z=2 节点)
E2 = 3.0 + 2 * SQ3  # 6.464102  (z=1 节点)
E3 = 3.0 + 3 * SQ3  # 8.196152  (落地点)
W1 = 2.0 - SQ3      # 0.267949
W2 = 2.0 - 2 * SQ3  # -1.464102
W3 = 2.0 - 3 * SQ3  # -3.196152

# =================================================================
# 1. 峰顶塔环形广场 (围绕 [2,3]x[2,3])
# =================================================================
for tid, (x0, y0) in {
    "pz_s0": (1, 1), "pz_s1": (2, 1), "pz_s2": (3, 1), "pz_w": (1, 2),
    "pz_e": (3, 2), "pz_n0": (1, 3), "pz_n1": (2, 3), "pz_n2": (3, 3),
}.items():
    mb.flat(tid, x0, y0, 0.0, PLAZA)

# =================================================================
# 2. 峰顶塔 3 层: 每层 4 墙 + 1 楼板 (z=1/2/3)
# =================================================================
for lv in range(3):
    mb.wall_ns(f"tw{lv}_s", 2, 2.0, lv, TOWER)
    mb.wall_ns(f"tw{lv}_n", 2, 3.0, lv, TOWER)
    mb.wall_ew(f"tw{lv}_w", 2.0, 2, lv, TOWER)
    mb.wall_ew(f"tw{lv}_e", 3.0, 2, lv, TOWER)
    mb.flat(f"tf{lv}", 2, 2, lv + 1.0, "orange")

# =================================================================
# 3. 东侧提升段: 桥墩 + 坡道成链 (墩顶与坡道短边同线互吸)
# =================================================================
mb.wall_ew("pe1_0", E1, 2, 0, PIER)
mb.wall_ew("pe1_1", E1, 2, 1, PIER)
mb.wall_ew("pe2_0", E2, 2, 0, PIER)
mb.ramp("lift_c", "+x", E2, 2, 1.0, TRACK)         # 落地段
mb.ramp("lift_b", "+x", E1, 2, 2.0, TRACK)
mb.ramp("lift_a", "+x", 3.0, 2, 3.0, TRACK)        # 越顶段
mb.brace("be1_s", (E1, 2.0, 0.0), "-y", TOWER)
mb.brace("be1_n", (E1, 3.0, 0.0), "+y", TOWER)
mb.brace("be2_s", (E2, 2.0, 0.0), "-y", TOWER)

# =================================================================
# 4. 西侧俯冲段: 对称成链
# =================================================================
mb.wall_ew("pw1_0", W1, 2, 0, PIER)
mb.wall_ew("pw1_1", W1, 2, 1, PIER)
mb.wall_ew("pw2_0", W2, 2, 0, PIER)
mb.ramp("dive_c", "-x", W2, 2, 1.0, TRACK)
mb.ramp("dive_b", "-x", W1, 2, 2.0, TRACK)
mb.ramp("dive_a", "-x", 2.0, 2, 3.0, TRACK)
mb.brace("bw1_s", (W1, 2.0, 0.0), "-y", TOWER)
mb.brace("bw1_n", (W1, 3.0, 0.0), "+y", TOWER)
mb.brace("bw2_s", (W2, 2.0, 0.0), "-y", TOWER)

# =================================================================
# 5. 西端冲出段 + 缓冲挡板
# =================================================================
mb.flat("run_a", W3 - 1.0, 2, 0.0, TRACK)          # [W3-1, W3]
mb.flat("run_b", W3 - 2.0, 2, 0.0, TRACK)
mb.crest_ew("bumper", W3 - 2.0, 2, 0.0, "purple")  # 缓冲挡板立西缘

# =================================================================
# 6. 东端站台 + 候车亭 + 排队栏
# =================================================================
mb.flat("st_t0", E3, 2, 0.0, PIER)                 # 轨道延长段
mb.flat("st_t1", E3 + 1.0, 2, 0.0, PIER)
mb.flat("st_p0", E3, 1, 0.0, "cyan")               # 站台
mb.flat("st_p1", E3 + 1.0, 1, 0.0, "cyan")
mb.wall_ns("sh_s", E3 + 1.0, 1.0, 0, "blue")       # 候车亭 4 墙
mb.wall_ns("sh_n", E3 + 1.0, 2.0, 0, "blue")
mb.wall_ew("sh_w", E3 + 1.0, 1, 0, "blue")
mb.wall_ew("sh_e", E3 + 2.0, 1, 0, "blue")
mb.hat4("sh_roof", E3 + 1.0, 1, 1.0, "blue")       # 等腰四坡顶
mb.crest_ns("queue_a", E3, 1.0, 0.0, "orange")     # 排队栏
mb.crest_ew("queue_b", E3, 1, 0.0, "orange")

# =================================================================
# 7. 广场立牌塔尖
# =================================================================
mb.spire_ns("sign_w", 1, 1.0, 0.0, "purple")
mb.spire_ns("sign_e", 3, 1.0, 0.0, "purple")

# =================================================================
# 教程步骤 (16 步)
# =================================================================
mb.step(
    "广场南半: 峰顶塔基南、西两侧铺 4 片草坪板。",
    ["pz_s0", "pz_s1", "pz_s2", "pz_w"],
    tip="塔基 [2,3]x[2,3] 空在中央 —— 峰顶塔直接落地。",
)
mb.step(
    "广场北半: 补齐北、东两侧 4 片, 环形广场合围。",
    ["pz_n0", "pz_n1", "pz_n2", "pz_e"],
    highlight=["pz_s0", "pz_w"],
)
mb.step(
    "峰顶塔第一层: 4 面红色方墙围合, 顶上盖橙色楼板。",
    ["tw0_s", "tw0_n", "tw0_w", "tw0_e", "tf0"],
    highlight=["pz_s1"],
    tip="四角竖边两两互吸, 楼板四边压墙顶 —— 一层一环, 抗晃动。",
)
mb.step(
    "峰顶塔第二层: 同法再起一层。",
    ["tw1_s", "tw1_n", "tw1_w", "tw1_e", "tf1"],
    highlight=["tf0"],
)
mb.step(
    "峰顶塔第三层: 塔顶楼板 z=3 就位 —— 这是全线最高点。",
    ["tw2_s", "tw2_n", "tw2_w", "tw2_e", "tf2"],
    highlight=["tf1"],
)
mb.step(
    "东侧提升链: 先立两级灰色桥墩 (双层墩 + 单层墩), 再从远端把 "
    "3 段黄色坡道逐级挂上来 —— 每段坡道两端都正好落在墩顶或塔沿。",
    ["pe1_0", "pe1_1", "pe2_0", "lift_c", "lift_b", "lift_a"],
    highlight=["tf2"],
    tip="顺序: 先落地段 (坡尾自己接地), 再中段, 最后越顶段 —— "
        "每段放下时两端都有依托。",
)
mb.step(
    "东墩护撑: 桥墩根部加 3 片红色直角三角护撑, 竖边吸墩身竖边。",
    ["be1_s", "be1_n", "be2_s"],
    highlight=["pe1_0", "pe2_0"],
)
mb.step(
    "西侧俯冲链: 对称立两级桥墩, 再挂 3 段俯冲坡道 —— 列车从塔顶"
    "一冲到底。",
    ["pw1_0", "pw1_1", "pw2_0", "dive_c", "dive_b", "dive_a"],
    highlight=["tf2"],
)
mb.step(
    "西墩护撑: 同法加 3 片护撑, 西链成桁。",
    ["bw1_s", "bw1_n", "bw2_s"],
    highlight=["pw1_0", "pw2_0"],
)
mb.step(
    "冲出段与缓冲挡板: 俯冲落地点向西接 2 片黄色轨道板, 尽头立 "
    "1 片紫色缓冲挡板。",
    ["run_a", "run_b", "bumper"],
    highlight=["dive_c"],
)
mb.step(
    "东端轨道延长段: 提升链落地点向东接 2 片灰色轨道板。",
    ["st_t0", "st_t1"],
    highlight=["lift_c"],
)
mb.step(
    "站台: 轨道南侧铺 2 片青色站台板。",
    ["st_p0", "st_p1"],
    highlight=["st_t0", "st_t1"],
)
mb.step(
    "候车亭墙身: 站台东段立 4 面蓝色亭墙。",
    ["sh_s", "sh_n", "sh_w", "sh_e"],
    highlight=["st_p1"],
)
mb.step(
    "候车亭四坡顶: 4 片等腰三角对锥合拢, 斜棱两两互吸自锁。",
    ["sh_roof_s", "sh_roof_e", "sh_roof_n", "sh_roof_w"],
    highlight=["sh_s", "sh_n"],
)
mb.step(
    "排队栏: 站台西段立 2 片橙色三角围栏。",
    ["queue_a", "queue_b"],
    highlight=["st_p0"],
)
mb.step(
    "广场立牌: 广场南沿立 2 根紫色立牌塔尖 —— 爬升丘开闸放行。",
    ["sign_w", "sign_e"],
    highlight=["pz_s0", "pz_s2"],
)

mb.finalize(
    model_id="roller_coaster_hill_01",
    name="过山车爬升段",
    name_en="Roller Coaster Lift Hill 01",
    description=(
        "过山车的链式爬升丘剖面 (不是回环): 三层峰顶塔居中, 东侧"
        "提升链与西侧俯冲链各由 3 段 30 度坡道沿桥墩逐级降到地面 "
        "—— 每段坡道两端都落在墩顶或塔沿上, 剪断任何一处节点铰链, "
        "坡道仍经由另一端传力; 桥墩根部直角护撑锁成三角。东端是"
        "带四坡顶候车亭的站台, 西端冲出段以缓冲挡板收尾 —— 一条"
        "完整的爬升-越顶-俯冲动线。"
    ),
    difficulty=3,
    tags=["过山车", "游乐园", "爬升段", "坡道链", "桥墩"],
    min_pieces=58,
    min_steps=16,
)
