#!/usr/bin/env python3
"""生成模型 data/models/volcano_base_01.json (火山科考站)。

第三批模型 ⑧: 自然奇观主题 —— 活火山下的科考站: 6x6 熔岩台地
北侧隆起两级火山锥 —— 3x3 一级火山体上环着一圈火山口平台,
中央再起 1x1 二级火山口 (顶口敞开), 口沿窜出两簇红色火舌,
两片熔岩瀑以 45 度挂下山肩, 两条 30 度熔岩流一路淌到台地;
东南角一座 2x2 科考站 (平屋顶 + 雷达罩 + 通讯天线) 隔着
安全距离观测, 台地四角插着红黄警戒旗。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 熔岩台地 6x6 (灰岩 + 熔岩纹)                            36 片
  - 一级火山体: 3x3 围墙 12 + 火山口环形平台 8              20 片
  - 二级火山口: 1x1 围墙 4 (顶口敞开)                        4 片
  - 火舌 x2 + 熔岩瀑 x2 (45 度外挂) + 熔岩流 x2 (30 度)      6 片
  - 科考站: 墙体 7 (北面留门) + 平屋顶 4 + 雷达罩 1 + 天线 1 13 片
  - 警戒旗 x4                                                4 片
  合计 83 片, 18 个教程步骤, 5 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 火山口环形平台 8 片全部坐在一级围墙顶上 (先四角后四边),
    二级火山口墙底边吸环形平台内沿 —— 逐级收分;
  - 熔岩瀑等边三角以 45 度外倾挂在二级口沿, 悬挑力矩 2.7 g·单位,
    远低于抗弯预算 20 (R6 放行); 火舌与火山口墙共面吸合;
  - 熔岩流 30 度坡道顶边整边吸环形平台外沿, 坡尾自然落在台地上;
  - 科考站方片墙体直接吸台地格线, 全场磁力连通。

用法: python3 tools/generate_volcano_base.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import HEX_APOTHEM, ModelBuilder  # noqa: E402

b = ModelBuilder()

# =================================================================
# 1. 熔岩台地 6x6: 灰岩为主, 红色熔岩纹从火山脚蜿蜒而出
# =================================================================
LAVA_VEIN = {(2, 1), (2, 0), (5, 3), (0, 4)}
for j in range(6):
    for i in range(6):
        b.flat(f"pd_{i}_{j}", i, j, 0.0,
               "red" if (i, j) in LAVA_VEIN else "gray")

# =================================================================
# 2. 一级火山体: 3x3 (x 1..4, y 2..5) 围墙 + 火山口环形平台
# =================================================================
for i in range(3):
    b.wall_ns(f"v1_s_{i}", 1 + i, 2.0, 0, "gray")    # 南坡
for j in range(3):
    b.wall_ew(f"v1_e_{j}", 4.0, 2 + j, 0, "gray")    # 东坡
for i in range(3):
    b.wall_ns(f"v1_n_{i}", 1 + i, 5.0, 0, "gray")    # 北坡
for j in range(3):
    b.wall_ew(f"v1_w_{j}", 1.0, 2 + j, 0, "gray")    # 西坡

RIM_CORNERS = [("rim_sw", 1, 2), ("rim_se", 3, 2), ("rim_nw", 1, 4), ("rim_ne", 3, 4)]
RIM_MIDS = [("rim_s", 2, 2), ("rim_w", 1, 3), ("rim_e", 3, 3), ("rim_n", 2, 4)]
for tid, i, j in RIM_CORNERS:
    b.flat(tid, i, j, 1.0, "gray")
for tid, i, j in RIM_MIDS:
    b.flat(tid, i, j, 1.0, "orange")                 # 环形平台内圈已被熔岩烤红

# =================================================================
# 3. 二级火山口: 1x1 (x 2..3, y 3..4) 围墙, 顶口敞开
# =================================================================
b.wall_ns("v2_s", 2, 3.0, 1, "orange")
b.wall_ew("v2_e", 3.0, 3, 1, "red")
b.wall_ns("v2_n", 2, 4.0, 1, "orange")
b.wall_ew("v2_w", 2.0, 3, 1, "red")

# =================================================================
# 4. 火舌 (共面立在口沿) + 熔岩瀑 (45 度外挂) + 熔岩流 (30 度坡道)
# =================================================================
b.crest_ns("fire_n", 2, 4.0, 2.0, "red")             # 北口沿火舌
b.crest_ew("fire_w", 2.0, 3, 2.0, "red")             # 西口沿火舌
b.place_tri("lf_s", "equilateral_triangle",
            (2.0, 3.0, 2.0), (3.0, 3.0, 2.0),
            (2.5, 2.387628, 1.387628), "orange")     # 南熔岩瀑 (45 度挂下)
b.place_tri("lf_e", "equilateral_triangle",
            (3.0, 4.0, 2.0), (3.0, 3.0, 2.0),
            (3.612372, 3.5, 1.387628), "orange")     # 东熔岩瀑
b.ramp("lv_s", "-y", 2.0, 2, 1.0, "red")             # 南熔岩流 (淌向台地)
b.ramp("lv_e", "+x", 4.0, 3, 1.0, "orange")          # 东熔岩流

# =================================================================
# 5. 科考站 2x2 (x 4..6, y 0..2): 北面西段留门正对火山
# =================================================================
b.wall_ns("st_s_0", 4, 0.0, 0, "cyan")
b.wall_ns("st_s_1", 5, 0.0, 0, "cyan")
b.wall_ew("st_e_0", 6.0, 0, 0, "cyan")
b.wall_ew("st_e_1", 6.0, 1, 0, "clear")              # 东面观测窗
b.wall_ns("st_n", 5, 2.0, 0, "cyan")                 # 北面东段 (西段 x 4..5 为门)
b.wall_ew("st_w_0", 4.0, 0, 0, "cyan")
b.wall_ew("st_w_1", 4.0, 1, 0, "clear")              # 西面观测窗
for j in range(2):
    for i in range(2):
        b.flat(f"st_r_{i}_{j}", 4 + i, j, 1.0, "gray")
b.add("radar", "hexagon", (4.5, 2.0, 1 + HEX_APOTHEM), (90, 0, 0), "clear")
b.spire_ns("st_ant", 5, 1.0, 1.0, "red")             # 通讯天线

# =================================================================
# 6. 警戒旗 x4: 台地四角
# =================================================================
b.crest_ns("wf_sw", 0, 0.0, 0.0, "red")
b.crest_ew("wf_se", 6.0, 5, 0.0, "yellow")
b.crest_ns("wf_nw", 0, 6.0, 0.0, "yellow")
b.crest_ns("wf_ne", 5, 6.0, 0.0, "red")

# =================================================================
# 教程步骤 (18 步): 台地 -> 一级火山体 -> 火山口 -> 熔岩 -> 科考站
# =================================================================
b.step(
    "铺台地最南 1 排 6 片: 灰岩间一条红色熔岩纹淌出画面。",
    [f"pd_{i}_0" for i in range(6)],
    tip="台地铺在桌面中央 —— 火山在北, 科考站在东南。",
)
b.step(
    "铺台地第 2 排 6 片: 熔岩纹继续向北延伸。",
    [f"pd_{i}_1" for i in range(6)],
    highlight=["pd_2_0"],
    tip="红色熔岩纹将一直连到火山脚下。",
)
b.step(
    "铺台地中部 2 排 12 片: 这里就是火山体的地基。",
    [f"pd_{i}_{j}" for j in range(2, 4) for i in range(6)],
    highlight=["pd_2_1"],
    tip="每片先对准一条边再松手, 台地中间不能留缝。",
)
b.step(
    "铺完台地最北 2 排 12 片 —— 6x6 熔岩台地就绪。",
    [f"pd_{i}_{j}" for j in range(4, 6) for i in range(6)],
    highlight=["pd_0_3", "pd_5_3"],
    tip="从上往下看, 熔岩纹应从台地北部蜿蜒到南缘。",
)
b.step(
    "一级火山体起坡: 台地北部立南坡 3 片与西坡 3 片灰色正方形。",
    [f"v1_s_{i}" for i in range(3)] + [f"v1_w_{j}" for j in range(3)],
    highlight=["pd_1_2", "pd_1_4"],
    tip="底边吸台地格线, 转角竖边互吸 —— 火山从这里隆起。",
)
b.step(
    "一级火山体合围: 补北坡 3 片与东坡 3 片, 3x3 山体锁成筒。",
    [f"v1_n_{i}" for i in range(3)] + [f"v1_e_{j}" for j in range(3)],
    highlight=["v1_s_2", "v1_w_2"],
    tip="四角竖边两两互吸后, 轻捏山口应感觉整体联动。",
)
b.step(
    "火山口平台四角就位: 4 片灰色方板压在山体墙顶四角, "
    "每片同时坐住两段墙顶。",
    [tid for tid, _, _ in RIM_CORNERS],
    highlight=["v1_s_0", "v1_n_2"],
    tip="角片是环形平台的承重锚点。",
)
b.step(
    "补平台四边中片: 4 片烤红的橙色方板嵌进角片之间, "
    "围出 1x1 火山口洞口。",
    [tid for tid, _, _ in RIM_MIDS],
    highlight=[tid for tid, _, _ in RIM_CORNERS],
    tip="中片底边还坐在墙顶上, 两侧整边吸角片 —— 环形平台锁死。",
)
b.step(
    "二级火山口起圈: 洞口沿上立南墙与西墙各 1 片。",
    ["v2_s", "v2_w"],
    highlight=["rim_s", "rim_w"],
    tip="底边吸环形平台内沿 —— 火山锥逐级收分。",
)
b.step(
    "二级火山口合围: 补北墙与东墙, 1x1 口体锁定, 顶口敞开 —— "
    "这就是随时会喷发的活火山口。",
    ["v2_n", "v2_e"],
    highlight=["v2_s", "v2_w"],
    tip="顶口不封盖 —— 岩浆需要出口, 教程也需要负空间。",
)
b.step(
    "窜火舌: 北、西口沿各立 1 片红色等边三角形, 与口壁共面向上。",
    ["fire_n", "fire_w"],
    highlight=["v2_n", "v2_w"],
    tip="火舌底边吸口沿顶边 —— 火山正在冒火!",
)
b.step(
    "挂熔岩瀑: 南、东口沿各挂 1 片橙色等边三角形, 以 45 度外倾"
    "垂向环形平台。",
    ["lf_s", "lf_e"],
    highlight=["v2_s", "v2_e"],
    tip="底边整边吸口沿顶边, 尖端悬在平台上方 —— 岩浆溢出来了。",
)
b.step(
    "淌熔岩流: 两条 30 度红橙坡道从环形平台外沿淌下, 坡尾落在台地上。",
    ["lv_s", "lv_e"],
    highlight=["rim_s", "rim_e"],
    tip="顶边整边吸平台外沿再松手 —— 熔岩一路淌到台地熔岩纹上。",
)
b.step(
    "科考站起墙: 东南角立南墙 2 片与西墙 2 片 (西面上段透明观测窗)。",
    ["st_s_0", "st_s_1", "st_w_0", "st_w_1"],
    highlight=["pd_4_0", "pd_4_1"],
    tip="科考站与火山隔着安全距离 —— 观测窗正对熔岩流。",
)
b.step(
    "科考站合围: 补东墙 2 片与北墙东段 1 片, 北面西段留 1 格大门。",
    ["st_e_0", "st_e_1", "st_n"],
    highlight=["st_s_1", "st_w_1"],
    tip="大门朝北正对火山 —— 科考队员出门就能取样。",
)
b.step(
    "盖科考站平屋顶: 4 片灰色方板压在墙顶上 (z=1)。",
    [f"st_r_{i}_{j}" for j in range(2) for i in range(2)],
    highlight=["st_s_0", "st_n"],
    tip="门上方那片两侧整边吸相邻屋顶片 —— 屋面自然成楣。",
)
b.step(
    "装雷达罩与通讯天线: 透明六边形立在屋顶北沿门楣上方, "
    "红色等腰天线立在屋顶中缝。",
    ["radar", "st_ant"],
    highlight=["st_r_0_1", "st_r_1_0"],
    tip="雷达紧盯火山口, 数据实时回传 —— 预警就靠它。",
)
b.step(
    "插警戒旗: 台地四角红黄旗各就各位 —— 火山科考站正式运转!",
    ["wf_sw", "wf_se", "wf_nw", "wf_ne"],
    highlight=["radar"],
    tip="警戒线内注意安全 —— 火山监测, 一刻不停。",
)

b.finalize(
    model_id="volcano_base_01",
    name="火山科考站",
    name_en="Volcano Research Base 01",
    description=(
        "自然奇观主题: 6x6 熔岩台地北侧隆起两级火山锥 —— 3x3 一级火山体"
        "顶着 8 片环形火山口平台 (先四角后四边锁死), 中央 1x1 二级火山口"
        "顶口敞开, 口沿窜出共面火舌、挂下 45 度熔岩瀑, 两条 30 度熔岩流"
        "一路淌到台地熔岩纹上; 东南角 2x2 科考站戴平屋顶、透明雷达罩与"
        "通讯天线隔着安全距离观测, 四角警戒旗围场 —— 逐级收分 + 负空间"
        "火山口 + 三种熔岩挂件, 一座会冒火的山。"
    ),
    difficulty=4,
    tags=["自然", "火山", "科考", "熔岩", "挑战"],
    min_pieces=50,
    min_steps=16,
)
