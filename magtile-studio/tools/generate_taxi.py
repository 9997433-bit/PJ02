#!/usr/bin/env python3
"""生成模型 data/models/taxi_01.json (城市出租车)。

城市交通主题: 与高箱救护车完全相反的低矮轿车 —— 4 片车轮底座
双侧轮组托起 4 格长的黄色底盘, 玻璃座舱只占中段两格: 前后挡
都是 45 度斜置的透明方板 (从车顶沿口斜披向底盘, 溜背轿跑
剪影), 车顶中缝立着黄色顶灯 —— TAXI 亮灯即空车; 车头黄色
大灯朝东, 正对斑马线礼让行人。街边出租车站牌发光, 路灯与
红绿灯守着路口, 西侧绿篱、道旁花丛 —— 招手即停, 请上车!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 车头朝东):
  - 街道 8x4: 马路三排 (含透明斑马线) x18 + 人行道 x6         24 片
  - 出租车: 车轮底座 x4 + 底盘长板 x2 + 座舱前后壁 x2
    + 侧窗 x4 + 车顶 x2 + 45 度前后挡 x2 + 顶灯/大灯 x2      18 片
  - 出租车站牌: 方柱 x1 + 发光窗格牌 x1                        2 片
  - 路灯 x2 + 红绿灯 x2                                        4 片
  - 西侧绿篱 x3 + 道旁花丛 x2                                  5 片
  合计 53 片, 16 个教程步骤, 6 种磁力片形状 (CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验):
  - 车轮底座底边 (长 2) 整边吸马路长板拼缝, 两片底盘长板
    长边整边压双侧轮顶、彼此在 x=3 缝互吸 —— 门式框架 x2;
  - 座舱后壁踩底盘西短边、前壁踩 x=3 拼缝 (双板同缝受力),
    侧窗竖边吸进前后壁拐角, 车顶方板压顶 —— 座舱箱形环;
  - 45 度前后挡底边同吸车顶沿口与端壁顶 (双铰链共线),
    斜置质心力臂 0.354, 力矩 10.6 <= 预算 20;
  - 站牌/红绿灯为两片小塔 (< 3 片), 重心正压铰链零力矩。

用法: python3 tools/generate_taxi.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

ROAD = "gray"       # 马路
ZEBRA = "clear"     # 斑马线亮条
WALK = "gray"       # 人行道
TAXI = "yellow"     # 车身
GLASS = "clear"     # 玻璃
WHEEL = "gray"      # 车轮
SIGN = "yellow"     # 站牌
LAMP = "yellow"     # 路灯
POLE = "gray"       # 灯柱
GO = "green"        # 绿灯
HEDGE = "green"     # 绿篱
FLOWER = "pink"     # 花丛

# =================================================================
# 1. 街道 8x4: 马路三排 (x5..8 为斑马线) + 人行道
# =================================================================
for y in range(3):
    b.flat(f"r{y}_0", 0, y, 0.0, ROAD)
    b.flat_rect(f"r{y}_a", 1, y, 0.0, ROAD)         # [1,3] 轮缝板
    b.flat_rect(f"r{y}_b", 3, y, 0.0, ROAD)         # [3,5] 轮缝板
    b.flat(f"r{y}_z1", 5, y, 0.0, ZEBRA)            # 斑马线
    b.flat(f"r{y}_z2", 6, y, 0.0, ROAD)
    b.flat(f"r{y}_z3", 7, y, 0.0, ZEBRA)
b.flat_rect("wk_a", 0, 3, 0.0, WALK)                # 人行道 [0,2]
b.flat("wk_2", 2, 3, 0.0, WALK)
b.flat("wk_3", 3, 3, 0.0, WALK)
b.flat("wk_4", 4, 3, 0.0, WALK)
b.flat("wk_5", 5, 3, 0.0, WALK)
b.flat_rect("wk_b", 6, 3, 0.0, WALK)                # [6,8]

# =================================================================
# 2. 出租车: 轮组 + 底盘 + 玻璃座舱 (车头朝东)
# =================================================================
b.add("wh_s1", "wheel_base", (2.0, 1.0, 0.5), (90, 0, 0), WHEEL)
b.add("wh_s2", "wheel_base", (4.0, 1.0, 0.5), (90, 0, 0), WHEEL)
b.add("wh_n1", "wheel_base", (2.0, 2.0, 0.5), (90, 0, 0), WHEEL)
b.add("wh_n2", "wheel_base", (4.0, 2.0, 0.5), (90, 0, 0), WHEEL)
b.flat_rect("deck_w", 1, 1, 1.0, TAXI)              # 底盘西 [1,3]x[1,2]
b.flat_rect("deck_e", 3, 1, 1.0, TAXI)              # 底盘东 [3,5]x[1,2]
b.wall_ew("cab_rear", 1.0, 1, 1, GLASS)             # 座舱后壁
b.wall_ew("cab_front", 3.0, 1, 1, GLASS)            # 座舱前壁
b.wall_ns("cab_s1", 1, 1.0, 1, GLASS)               # 南侧窗
b.wall_ns("cab_s2", 2, 1.0, 1, GLASS)
b.wall_ns("cab_n1", 1, 2.0, 1, GLASS)               # 北侧窗
b.wall_ns("cab_n2", 2, 2.0, 1, GLASS)
b.flat("roof_w", 1, 1, 2.0, TAXI)                   # 车顶西
b.flat("roof_e", 2, 1, 2.0, TAXI)                   # 车顶东
b.place_edge("wind_f", "square", 0,
             (3.0, 1.0, 2.0), (3.0, 2.0, 2.0), (1.0, 0.0, -1.0), GLASS)  # 前挡 45 度
b.place_edge("wind_r", "square", 0,
             (1.0, 2.0, 2.0), (1.0, 1.0, 2.0), (-1.0, 0.0, -1.0), GLASS)  # 后挡 45 度
b.crest_ew("dome", 2.0, 1, 2.0, TAXI)               # TAXI 顶灯 (车顶中缝)
b.crest_ew("headlight", 5.0, 1, 1.0, TAXI)          # 车头大灯

# =================================================================
# 3. 站牌 + 路灯 + 红绿灯 + 绿篱花丛
# =================================================================
b.wall_ns("stand_post", 2, 3.0, 0, SIGN)            # 站牌柱
b.add("stand_sign", "window_square", (2.5, 3.0, 1.5), (90, 0, 0), SIGN)
b.wall_ns("lamp_post", 5, 3.0, 0, POLE)             # 路灯柱
b.crest_ns("lamp_top", 5, 3.0, 1.0, LAMP)           # 路灯
b.wall_ns("tl_post", 7, 3.0, 0, POLE)               # 红绿灯柱
b.add("tl_light", "window_square", (7.5, 3.0, 1.5), (90, 0, 0), GO)
for y in range(3):
    b.crest_ew(f"hedge_{y}", 0.0, y, 0.0, HEDGE)    # 西侧绿篱
b.crest_ns("fl_1", 3, 4.0, 0.0, FLOWER)             # 道旁花丛
b.crest_ns("fl_2", 4, 4.0, 0.0, FLOWER)

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺马路南排: 轮缝长板对齐 y=1 线, 东端两条透明斑马线。",
    ["r0_0", "r0_a", "r0_b", "r0_z1", "r0_z2", "r0_z3"],
    tip="两片长板拼缝在 x=3 —— 前后轮组都靠这排格线吸合。",
)
b.step(
    "铺行车道: 中排 6 片, 出租车就停在这条车道上。",
    ["r1_0", "r1_a", "r1_b", "r1_z1", "r1_z2", "r1_z3"],
    highlight=["r0_a"],
    tip="车底长板的两条长边就是南北轮组的吸合线。",
)
b.step(
    "铺马路北排: 再铺 6 片, 斑马线三条亮纹贯通路口。",
    ["r2_0", "r2_a", "r2_b", "r2_z1", "r2_z2", "r2_z3"],
    highlight=["r1_a"],
    tip="透明斑马线让行人一眼看到 —— 车头正对着它。",
)
b.step(
    "铺人行道: 长板收两端, 方板留出站牌与灯柱的格线。",
    ["wk_a", "wk_2", "wk_3", "wk_4", "wk_5", "wk_b"],
    highlight=["r2_0"],
    tip="站牌、路灯、红绿灯都要踩在方板格线上。",
)
b.step(
    "装南侧轮组: 2 片车轮底座沿 y=1 拼缝立起。",
    ["wh_s1", "wh_s2"],
    highlight=["r0_a", "r0_b"],
    tip="底边 (长 2) 整边吸长板拼缝 —— 前后轮一次就位。",
)
b.step(
    "装北侧轮组: y=2 拼缝再立 2 片, 四轮底盘对位。",
    ["wh_n1", "wh_n2"],
    highlight=["wh_s1", "wh_s2"],
    tip="南北轮组严格对齐 —— 底盘长板要同时压住它们。",
)
b.step(
    "架底盘: 2 片黄色长板长边压轮顶, 在 x=3 缝彼此互吸。",
    ["deck_w", "deck_e"],
    highlight=["wh_s1", "wh_n2"],
    tip="轮组+底盘锁成两跨门式框架 —— 轿车的地板完成。",
)
b.step(
    "立座舱前后壁: 2 片透明端壁踩住底盘西短边与 x=3 拼缝。",
    ["cab_rear", "cab_front"],
    highlight=["deck_w", "deck_e"],
    tip="前壁踩在双板拼缝上, 两条短边同时受力。",
)
b.step(
    "合玻璃侧窗: 4 片透明侧窗竖边吸进前后壁拐角。",
    ["cab_s1", "cab_s2", "cab_n1", "cab_n2"],
    highlight=["cab_rear", "cab_front"],
    tip="圈层砌法合龙 —— 全景玻璃座舱一眼望穿。",
)
b.step(
    "盖车顶: 2 片黄色方板四边压舱顶。",
    ["roof_w", "roof_e"],
    highlight=["cab_s1", "cab_n2"],
    tip="车顶把玻璃座舱锁成箱形环 —— 越压越紧。",
)
b.step(
    "披前后挡风: 2 片透明方板从车顶沿口 45 度斜披。",
    ["wind_f", "wind_r"],
    highlight=["roof_w", "roof_e"],
    tip="底边同吸车顶沿与端壁顶, 力矩 10.6 <= 20 —— 溜背剪影。",
)
b.step(
    "点亮顶灯与大灯: 顶灯立车顶中缝, 大灯朝东守车头。",
    ["dome", "headlight"],
    highlight=["roof_w", "deck_e"],
    tip="顶灯底边同吸两片车顶的拼缝 —— TAXI 亮灯即空车。",
)
b.step(
    "立出租车站牌: 黄柱顶起发光窗格牌。",
    ["stand_post", "stand_sign"],
    highlight=["wk_2"],
    tip="重心正压铰链零力矩 —— 在这里排队上车。",
)
b.step(
    "立路灯与红绿灯: 路灯照斑马线, 绿灯亮起放行。",
    ["lamp_post", "lamp_top", "tl_post", "tl_light"],
    highlight=["wk_5", "r2_z3"],
    tip="红绿灯柱踩着斑马线格线 —— 行人先行。",
)
b.step(
    "种西侧绿篱: 3 片绿色等边三角沿路口收边。",
    ["hedge_0", "hedge_1", "hedge_2"],
    highlight=["r0_0", "r2_0"],
    tip="绿篱底边整边吸马路西沿 —— 街景有了呼吸感。",
)
b.step(
    "栽道旁花丛: 人行道北沿开出 2 丛粉花 —— 招手即停, 请上车!",
    ["fl_1", "fl_2"],
    highlight=["wk_3", "wk_4"],
    tip="花丛底边整边吸人行道格线 —— 城市出租车交付运营。",
)

b.finalize(
    model_id="taxi_01",
    name="城市出租车",
    name_en="Taxi 01",
    description=(
        "与高箱救护车完全相反的低矮轿车: 4 片车轮底座双侧轮组整边吸马路"
        "拼缝, 2 片黄色底盘长板长边压轮顶锁成两跨门式框架; 玻璃座舱只占"
        "中段 —— 透明端壁踩底盘短边与拼缝, 侧窗竖边吸进拐角, 黄色车顶"
        "压成箱形环; 前后挡都是 45 度斜披的透明方板 (底边同吸车顶沿与"
        "端壁顶, 力矩 10.6 <= 20), 溜背轿跑剪影一气呵成, 车顶中缝 TAXI "
        "顶灯亮起、车头大灯正对透明斑马线礼让行人; 街边发光站牌、路灯"
        "红绿灯、绿篱花丛点满路口 —— 招手即停, 请上车!"
    ),
    difficulty=3,
    tags=["城市", "交通", "出租车", "载具", "车轮底座", "进阶"],
    min_pieces=50,
    min_steps=16,
)
