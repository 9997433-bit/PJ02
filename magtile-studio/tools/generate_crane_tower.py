#!/usr/bin/env python3
"""生成模型 data/models/crane_tower_01.json (塔式起重机)。

第三批模型 ⑦: 工程主题 —— 与港口门吊 (四腿门架平台) 完全不同的
起重机: 细长的 1x1 独柱塔身直上 4 格, 塔顶回转台上再起塔尖小楼;
大臂向东悬挑两格、平衡臂向西悬挑一格, 每条臂根都由一对直角三角
拉杆与塔尖锁成三角环 —— 剪断任何一条铰链线, 力都能从另一条路
走回塔身; 平衡臂尾端立双层配重块, 大臂中缝下倒挂等腰吊钩,
塔身四角直角三角护撑锁根。场边配钢梁堆、在建小楼与围挡。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 工地地坪 6x4: 方板与长方形混铺                              19 片
  - 塔身: 1x1 独柱 4 层 (16 墙) + 根部直角护撑 x4               20 片
  - 塔顶: 回转台板 1 + 塔尖小楼 4 (含司机室) + 四坡锥顶 4        9 片
  - 平衡臂: 臂板 1 + 拉杆 x2 + 双层配重 x2                       5 片
  - 大臂: 臂板 x2 + 拉杆 x2 + 倒挂吊钩 1                         5 片
  - 工地场景: 钢梁堆 2 + 在建小楼 4 + 围挡 3                     9 片
  合计 67 片, 16 个教程步骤, 5 种磁力片形状。

几何要点:
  - 拉杆是直角三角形: 竖直角边吸塔尖小楼的竖棱, 水平直角边吸
    臂板侧沿, 与塔身构成三角刚性环 —— 悬臂靠它免于超弯矩;
  - 吊钩倒挂在大臂两板的公共拼缝正下方, 纯受拉零力矩;
  - 双层配重正压平衡臂尾沿铰链线上方, 力矩为零, 却把整机
    重心拉回塔身正上方。

用法: python3 tools/generate_crane_tower.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

# 塔身占 [2,3]x[1,2]; 大臂向东 (+x), 平衡臂向西 (-x)
# =================================================================
# 1. 工地地坪 6x4 ([0,6]x[0,4])
# =================================================================
b.flat("pad_s0", 0, 0, 0, "gray")
b.flat("pad_s1", 1, 0, 0, "gray")
b.flat("pad_s2", 2, 0, 0, "gray")
b.flat_rect("pad_s3", 3, 0, 0, "gray")
b.flat("pad_s4", 5, 0, 0, "gray")
for i in range(6):                        # 塔身行 (y 1..2): 全单格
    b.flat(f"pad_m{i}", i, 1, 0, "yellow" if 2 <= i <= 3 else "gray")
b.flat("pad_n0", 0, 2, 0, "gray")
b.flat("pad_n1", 1, 2, 0, "gray")
b.flat("pad_n2", 2, 2, 0, "gray")
b.flat_rect("pad_n3", 3, 2, 0, "gray")
b.flat("pad_n4", 5, 2, 0, "gray")
b.flat("pad_b0", 0, 3, 0, "green")        # 北排绿化带 (方-长-长-方)
b.flat_rect("pad_b1", 1, 3, 0, "green")
b.flat_rect("pad_b2", 3, 3, 0, "green")
b.flat("pad_b3", 5, 3, 0, "green")

# =================================================================
# 2. 塔身: 1x1 独柱 4 层 + 根部直角护撑
# =================================================================
for lv in range(4):
    b.wall_ns(f"mast{lv}_s", 2, 1, lv, "orange")
    b.wall_ns(f"mast{lv}_n", 2, 2, lv, "orange")
    b.wall_ew(f"mast{lv}_w", 2, 1, lv, "clear")
    b.wall_ew(f"mast{lv}_e", 3, 1, lv, "clear")
b.brace("root_w", (2.0, 1.0, 0.0), "-x", "red")     # 根部护撑 (风车形)
b.brace("root_e", (3.0, 2.0, 0.0), "+x", "red")
b.brace("root_s", (3.0, 1.0, 0.0), "-y", "red")
b.brace("root_n", (2.0, 2.0, 0.0), "+y", "red")

# =================================================================
# 3. 塔顶: 回转台板 + 塔尖小楼 (司机室) + 四坡锥顶
# =================================================================
b.flat("deck", 2, 1, 4, "yellow")
b.wall_ns("apex_s", 2, 1, 4, "orange")    # 南面司机室
b.wall_ns("apex_n", 2, 2, 4, "gray")
b.wall_ew("apex_w", 2, 1, 4, "clear")
b.wall_ew("apex_e", 3, 1, 4, "clear")
b.hat4("apex_hat", 2, 1, 5.0, "red")

# =================================================================
# 4. 平衡臂 (向西) + 双层配重
# =================================================================
b.flat("cjib", 1, 1, 4, "gray")
b.brace("ctie_s", (2.0, 1.0, 4.0), "-x", "red")
b.brace("ctie_n", (2.0, 2.0, 4.0), "-x", "red")
b.wall_ew("cw_lo", 1, 1, 4, "blue")       # 配重块
b.wall_ew("cw_hi", 1, 1, 5, "blue")

# =================================================================
# 5. 大臂 (向东两格) + 拉杆 + 倒挂吊钩
# =================================================================
b.flat("jib_1", 3, 1, 4, "gray")
b.brace("jtie_s", (3.0, 1.0, 4.0), "+x", "red")
b.brace("jtie_n", (3.0, 2.0, 4.0), "+x", "red")
b.flat("jib_2", 4, 1, 4, "gray")
b.place_edge("hook", "isosceles_triangle", 0,
             (4.0, 2.0, 4.0), (4.0, 1.0, 4.0), (0, 0, -1), "yellow")

# =================================================================
# 6. 工地场景: 钢梁堆 + 在建小楼 + 围挡
# =================================================================
b.crest_ns("steel_s", 4, 1, 0, "gray")    # 吊装区钢梁堆
b.crest_ns("steel_n", 4, 2, 0, "gray")
b.wall_ns("site_s", 5, 2, 0, "cyan")      # 在建小楼 [5,6]x[2,3]
b.wall_ew("site_e", 6, 2, 0, "cyan")
b.wall_ns("site_n", 5, 3, 0, "cyan")
b.wall_ns("site_up", 5, 3, 1, "cyan")     # 刚吊上去的第二层墙
for i in range(3):
    b.crest_ns(f"hoard_{i}", i, 0, 0, "yellow")   # 南侧围挡

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺工地南半: 南排与塔身行混铺灰色地坪, 塔位两格用黄色标出。",
    ["pad_s0", "pad_s1", "pad_s2", "pad_s3", "pad_s4",
     "pad_m0", "pad_m1", "pad_m2", "pad_m3", "pad_m4", "pad_m5"],
    tip="塔身行全部用单格方板 —— 塔身墙与护撑都要吸在这行的拼缝上。",
)
b.step(
    "铺工地北半: 第三行地坪与北排绿化带合拢成 6x4。",
    ["pad_n0", "pad_n1", "pad_n2", "pad_n3", "pad_n4",
     "pad_b0", "pad_b1", "pad_b2", "pad_b3"],
    highlight=["pad_m0"],
    tip="绿化带按 方-长-长-方 铺, 两端方板与地坪对缝吸合。",
)
b.step(
    "立塔身第一层: 4 片墙围成 1x1 独柱 (南北橙色, 东西透明格构)。",
    ["mast0_s", "mast0_n", "mast0_w", "mast0_e"],
    highlight=["pad_m2", "pad_m3"],
    tip="四片墙的竖边两两咬合, 独柱其实是根方管。",
)
b.step(
    "锁塔根: 4 片红色直角三角护撑绕塔根风车形布置, "
    "竖直角边吸塔身竖棱、水平直角边吸地坪拼缝。",
    ["root_w", "root_e", "root_s", "root_n"],
    highlight=["mast0_w", "mast0_s"],
    tip="风车形四向受力, 塔根从此纹丝不动。",
)
b.step(
    "叠塔身第二层: 再上 4 片, 竖缝与下层对齐。",
    ["mast1_s", "mast1_n", "mast1_w", "mast1_e"],
    highlight=["mast0_s"],
    tip="橙白相间是塔吊的标准涂装。",
)
b.step(
    "叠塔身第三层: 塔身到 3 格高, 立墙时用手从内侧轻扶。",
    ["mast2_s", "mast2_n", "mast2_w", "mast2_e"],
    highlight=["mast1_s"],
    tip="每一层都是一圈闭环 —— 方管天生抗扭。",
)
b.step(
    "叠塔身第四层: 塔身封顶 4 格, 全库最细的高塔完成。",
    ["mast3_s", "mast3_n", "mast3_w", "mast3_e"],
    highlight=["mast2_s"],
    tip="下一步就要在这根细柱顶上架回转台了。",
)
b.step(
    "架回转台与塔尖小楼: 黄色台板盖住塔口, 四片墙起塔尖小楼 —— "
    "南面橙色是司机室, 东西透明看得见操作员。",
    ["deck", "apex_s", "apex_n", "apex_w", "apex_e"],
    highlight=["mast3_s"],
    tip="台板四边同时吸住塔身四墙顶边, 塔尖小楼再压住台板。",
)
b.step(
    "戴塔尖锥顶: 4 片红色等腰三角形合拢自锁。",
    ["apex_hat_s", "apex_hat_e", "apex_hat_n", "apex_hat_w"],
    highlight=["apex_s"],
    tip="锥尖高 5.87 格 —— 它是整个工地的最高点。",
)
b.step(
    "挑平衡臂并锁拉杆: 臂板向西悬挑一格, 2 片红色直角三角拉杆"
    "把臂根与塔尖小楼锁成三角环。",
    ["cjib", "ctie_s", "ctie_n"],
    highlight=["deck", "apex_w"],
    tip="拉杆竖边吸小楼竖棱、横边吸臂板侧沿 —— 悬臂全靠这对三角。",
)
b.step(
    "压双层配重: 2 片蓝色配重块在平衡臂尾沿上下叠放。",
    ["cw_lo", "cw_hi"],
    highlight=["cjib"],
    tip="配重正压铰链线上方, 力矩为零, 却把整机重心拉回塔身。",
)
b.step(
    "挑大臂第一节并锁拉杆: 臂板向东悬挑, 又一对红色拉杆锁根。",
    ["jib_1", "jtie_s", "jtie_n"],
    highlight=["deck", "apex_e"],
    tip="东西两对拉杆对称受力, 塔尖小楼就是力的中转站。",
)
b.step(
    "接大臂第二节并倒挂吊钩: 臂板再向东一格, 黄色等腰吊钩"
    "倒挂在两节臂板的公共拼缝正下方。",
    ["jib_2", "hook"],
    highlight=["jib_1"],
    tip="吊钩纯受拉零力矩 —— 尖端正对下方的吊装区。",
)
b.step(
    "码钢梁堆: 2 片灰色等边三角形立在吊钩正下方的吊装区拼缝上。",
    ["steel_s", "steel_n"],
    highlight=["pad_m4"],
    tip="下一钩就吊它 —— 塔吊与货物在一条铅垂线上。",
)
b.step(
    "砌在建小楼: 东北角三面墙起第一层, 第二层刚吊上去一片。",
    ["site_s", "site_e", "site_n", "site_up"],
    highlight=["pad_n4"],
    tip="半成品才是工地的样子 —— 剩下的墙等塔吊慢慢吊。",
)
b.step(
    "竖南侧围挡: 3 片黄色等边三角形围出工地大门 —— 塔吊开工!",
    ["hoard_0", "hoard_1", "hoard_2"],
    highlight=["pad_s0", "pad_s2"],
    tip="仰头看: 独柱塔身、三角拉杆、平衡配重 —— 一台真正的塔吊。",
)

b.finalize(
    model_id="crane_tower_01",
    name="工地塔式起重机",
    name_en="Tower Crane 01",
    description=(
        "工程主题: 与港口门吊 (四腿门架) 完全不同的独柱塔吊 —— "
        "1x1 方管塔身直上 4 格, 根部直角护撑风车形锁地; 塔顶回转台"
        "上起塔尖小楼, 大臂向东两格、平衡臂向西一格, 每条臂根都由"
        "一对直角三角拉杆与塔尖锁成三角环, 剪断任何一条铰链线力都"
        "能绕行; 平衡臂尾双层配重正压铰链零力矩, 大臂中缝下倒挂"
        "等腰吊钩纯受拉。场边钢梁堆正等着起吊, 在建小楼刚砌半层。"
    ),
    difficulty=3,
    tags=["工程", "塔吊", "拉杆三角", "平衡悬臂", "挑战"],
    min_pieces=65,
    min_steps=16,
)
