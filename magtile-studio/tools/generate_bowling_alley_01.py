#!/usr/bin/env python3
"""生成模型 data/models/bowling_alley_01.json (保龄球馆)。

运动健身主题批 2/3: 全库第一条保龄球道 —— 与既有运动模型的结构
词汇完全错开: 篮球场/网球场是围栏场地, 攀岩塔是立式爬塔, 保龄球
馆的主角是"一条冲向球瓶阵的长球道": 橙色木纹球道两侧灰色沟墙
夹护直通北端加高的瓶台, 台上六只白色球瓶以 3-2-1 三角阵立在
盖板拼缝上 (等边三角骑缝, 正是保龄球瓶的排阵语言), 台侧计分牌
窗格方挑旗 —— 全库没有第二个"长道 + 瓶阵"的模型。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 球道朝北掷向瓶阵):
  - 球道 (x [2,4], y [0,5]): 橙色长板 x4 + 犯规线清色方板 x2      6 片
  - 两侧回球廊地板 (x [1,2] / x [4,5], y [0,5]): 单位方板 x10    10 片
  - 沟墙 (x=2 / x=4, y [0,5], z 0..1): 灰色立墙 x10              10 片
  - 瓶台 (x [1,4], y [5,7], z 0..1): 台下地板 x6 + 环墙 x10 +
    盖板 x6                                                      22 片
  - 球瓶阵 x6: 白色等边三角 3-2-1 立在盖板拼缝上                  6 片
  - 计分牌: 窗格方骑瓶台东墙顶 x1 + 红旗 x1                       2 片
  合计 56 片, 13 个教程步骤, 4 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 沟墙脚线两侧都是等长拼缝: 西沟墙吸回球廊方板东沿, 东沟墙吸
    另一侧方板西沿, 墙与墙竖边成链;
  - 瓶台为"环墙合环 + 盖板压顶"的闭环箱体, 六片盖板互吸拼缝;
  - 球瓶 (等边三角) 骑盖板拼缝: 后排三只骑北沿 (同吸环墙顶),
    中排两只骑中缝 (两侧盖板双吸), 前排一只骑南沿 —— 每只重心
    正压铰链线, 力矩为零;
  - 计分牌窗格方骑东墙顶整边吸合, 顶上红旗同理; 剪断计分牌连接
    只失联 2 片 (< 3), 高层单点失效检查天然通过;
  - 全场高度主体 2.0, 仅计分牌旗尖 2.87 —— 环拓扑处处闭合。

用法: python3 tools/generate_bowling_alley_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

LANE = "orange"     # 球道木纹
FOUL = "clear"      # 犯规线
WALK = "yellow"     # 回球廊地板
GUTTER = "gray"     # 沟墙
DECK_F = "blue"     # 瓶台地板
DECK_W = "blue"     # 瓶台环墙
DECK_C = "cyan"     # 瓶台盖板
PIN = "clear"       # 球瓶 (白)
BOARD = "green"     # 计分牌 (窗格方)
FLAG = "red"        # 计分牌顶旗

# =================================================================
# 1. 球道与回球廊 (y [0,5]): 中央 2 格宽球道 + 两侧单位方板廊道
#    廊道全用单位方板 —— 沟墙脚线 (x=2 / x=4) 处处有等长拼缝。
# =================================================================
b.flat("lane_foul_w", 2, 0, 0.0, FOUL)              # 犯规线 (南端)
b.flat("lane_foul_e", 3, 0, 0.0, FOUL)
b.flat_rect("lane_w_1", 2, 1, 0.0, LANE, axis="y")  # 球道西列
b.flat_rect("lane_w_3", 2, 3, 0.0, LANE, axis="y")
b.flat_rect("lane_e_1", 3, 1, 0.0, LANE, axis="y")  # 球道东列
b.flat_rect("lane_e_3", 3, 3, 0.0, LANE, axis="y")
for y0 in range(5):
    b.flat(f"walk_w_{y0}", 1, y0, 0.0, WALK)        # 西回球廊
    b.flat(f"walk_e_{y0}", 4, y0, 0.0, WALK)        # 东回球廊

# =================================================================
# 2. 沟墙 (z 0..1): 球道两侧各 5 片灰墙, 竖边成链
# =================================================================
for y0 in range(5):
    b.wall_ew(f"gut_w_{y0}", 2.0, y0, 0, GUTTER)
    b.wall_ew(f"gut_e_{y0}", 4.0, y0, 0, GUTTER)

# =================================================================
# 3. 瓶台 (x [1,4], y [5,7], z 0..1): 台下地板 + 环墙合环 + 盖板
# =================================================================
for x0 in (1, 2, 3):
    b.flat(f"deck_f_{x0}_5", x0, 5, 0.0, DECK_F)
    b.flat(f"deck_f_{x0}_6", x0, 6, 0.0, DECK_F)
for x0 in (1, 2, 3):
    b.wall_ns(f"deck_s_{x0}", x0, 5.0, 0, DECK_W)   # 南墙 (正对球道)
    b.wall_ns(f"deck_n_{x0}", x0, 7.0, 0, DECK_W)   # 北墙
b.wall_ew("deck_w_5", 1.0, 5, 0, DECK_W)
b.wall_ew("deck_w_6", 1.0, 6, 0, DECK_W)
b.wall_ew("deck_e_5", 4.0, 5, 0, DECK_W)
b.wall_ew("deck_e_6", 4.0, 6, 0, DECK_W)
for x0 in (1, 2, 3):
    b.flat(f"deck_c_{x0}_5", x0, 5, 1.0, DECK_C)
    b.flat(f"deck_c_{x0}_6", x0, 6, 1.0, DECK_C)

# =================================================================
# 4. 球瓶阵 3-2-1: 白色等边三角立在盖板拼缝上
# =================================================================
b.crest_ns("pin_b_1", 1, 7.0, 1.0, PIN)             # 后排三只 (骑北沿)
b.crest_ns("pin_b_2", 2, 7.0, 1.0, PIN)
b.crest_ns("pin_b_3", 3, 7.0, 1.0, PIN)
b.crest_ns("pin_m_1", 1, 6.0, 1.0, PIN)             # 中排两只 (骑中缝)
b.crest_ns("pin_m_3", 3, 6.0, 1.0, PIN)
b.crest_ns("pin_f_2", 2, 5.0, 1.0, PIN)             # 前排一只 (骑南沿)

# =================================================================
# 5. 计分牌: 窗格方骑东墙顶 + 顶旗
# =================================================================
b.add("board", "window_square", (4.0, 5.5, 1.5), (90, 0, 90), BOARD)
b.crest_ew("board_flag", 4.0, 5, 2.0, FLAG)

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺球道: 南端两片清色犯规线方板, 向北接四条橙色木纹长板。",
    ["lane_foul_w", "lane_foul_e", "lane_w_1", "lane_w_3",
     "lane_e_1", "lane_e_3"],
    tip="脚不能越过犯规线 —— 球道从这里一直铺到瓶台脚下。",
)
b.step(
    "铺西回球廊: 五片黄色单位方板贴着球道西沿排成一列。",
    [f"walk_w_{y0}" for y0 in range(5)],
    highlight=["lane_foul_w"],
    tip="必须用单位方板 —— 沟墙的每段墙脚都要有等长拼缝可吸。",
)
b.step(
    "铺东回球廊: 五片黄色单位方板贴着球道东沿排成一列。",
    [f"walk_e_{y0}" for y0 in range(5)],
    highlight=["walk_w_0"],
    tip="打完的球从这两条廊道滚回来 —— 东西各一条。",
)
b.step(
    "立西沟墙: 五片灰墙踩 x=2 拼缝, 竖边逐片相咬成链。",
    [f"gut_w_{y0}" for y0 in range(5)],
    highlight=["walk_w_2"],
    tip="沟墙挡住歪球 —— 掉沟的球就沿着墙根滚到底。",
)
b.step(
    "立东沟墙: 五片灰墙踩 x=4 拼缝, 与西沟墙隔道相望。",
    [f"gut_e_{y0}" for y0 in range(5)],
    highlight=["gut_w_0"],
    tip="两道沟墙夹住球道 —— 直球才能冲到瓶阵。",
)
b.step(
    "铺瓶台地板 (y [5,7]): 六片蓝色单位方板与球道北端等边互吸。",
    [f"deck_f_{x0}_{y0}" for x0 in (1, 2, 3) for y0 in (5, 6)],
    highlight=["lane_w_3"],
    tip="瓶台的十道墙脚全踩在这六片方板的拼缝上。",
)
b.step(
    "立瓶台南北墙: 南墙三片正对球道, 北墙三片压住底线。",
    ["deck_s_1", "deck_s_2", "deck_s_3", "deck_n_1", "deck_n_2", "deck_n_3"],
    highlight=["deck_f_2_5"],
    tip="南墙就是球道的终点挡板 —— 球瓶要站在它头顶上。",
)
b.step(
    "立瓶台东西墙合环: 四片侧墙把瓶台锁成闭环箱体。",
    ["deck_w_5", "deck_w_6", "deck_e_5", "deck_e_6"],
    highlight=["deck_s_1", "deck_n_3"],
    tip="四角竖边互咬 —— 环墙合环, 瓶台稳如磐石。",
)
b.step(
    "盖瓶台盖板: 六片青色方板压顶, 每片吸墙顶又互吸拼缝。",
    [f"deck_c_{x0}_{y0}" for x0 in (1, 2, 3) for y0 in (5, 6)],
    highlight=["deck_w_5"],
    tip="盖板锁箱 —— 台面上的每条拼缝都是球瓶的立足线。",
)
b.step(
    "立后排球瓶: 三只白瓶骑台面北沿, 底边同吸盖板沿与北墙顶。",
    ["pin_b_1", "pin_b_2", "pin_b_3"],
    highlight=["deck_c_2_6"],
    tip="球瓶重心正压铰链线, 力矩为零 —— 站得直才倒得脆。",
)
b.step(
    "立中排与前排球瓶: 中排两只骑中缝, 前排一只骑南沿 —— "
    "3-2-1 三角阵成形。",
    ["pin_m_1", "pin_m_3", "pin_f_2"],
    highlight=["pin_b_2"],
    tip="中排骑缝的瓶两侧盖板双吸 —— 三角阵尖朝球道。",
)
b.step(
    "挂计分牌: 绿色窗格方骑瓶台东墙顶, 整边吸合。",
    ["board"],
    highlight=["deck_e_5"],
    tip="窗格里贴比分 —— 谁打出全中, 名字就写在这里。",
)
b.step(
    "升顶旗收尾: 红旗骑计分牌顶沿 —— 保龄球馆开张!",
    ["board_flag"],
    highlight=["board"],
    tip="旗尖 2.87 全场最高 —— 助跑, 出手, 全中!",
)

b.finalize(
    model_id="bowling_alley_01",
    name="保龄球馆",
    name_en="Bowling Alley 01",
    description=(
        "只用核心九片型的保龄球馆: 与围栏式球场和立式攀岩塔都不同, "
        "主角是一条冲向瓶阵的长球道 —— 橙色木纹长板从清色犯规线一路"
        "铺到北端, 两侧灰色沟墙踩等长拼缝竖边成链夹护直球; 加高瓶台"
        "是环墙合环加盖板压顶的闭环箱体, 六只白色等边三角球瓶以"
        " 3-2-1 三角阵骑在盖板拼缝上 (后排同吸墙顶, 中排两侧双吸, "
        "重心正压铰链线力矩为零), 台侧绿色窗格方计分牌骑墙顶挑起"
        "红旗 —— 助跑, 出手, 全中!"
    ),
    difficulty=3,
    tags=["运动", "健身", "保龄球", "球馆", "进阶"],
    min_pieces=56,
    min_steps=13,
)
