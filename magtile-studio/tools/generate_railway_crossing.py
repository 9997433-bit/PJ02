#!/usr/bin/env python3
"""生成模型 data/models/railway_crossing_01.json (看守铁路道口)。

铁路/火车站主题: 全库第一座平交道口 —— 与中央火车站 (站台+大厅+列车)
刻意区分, 本作的结构逻辑是 "两条动线在地面十字相交 + 门式栏杆锁路口":
双线铁路东西向横贯, 南北向公路穿过道口 (道口铺面换黄色警示板);
公路两侧各立一座门式道口栏杆 —— 两根立柱顶起一根水平横杆,
横杆两短边同吸柱顶 (双端受力零悬挑), 落杆状态锁住路口;
路西看守小屋窗朝铁路、门朝人行道, 屋顶双山尖; 道口两侧红绿
信号高塔尖对望, 轨旁四面警示三角把守, 一辆蓝色小轿车停在
落下的栏杆前等火车通过。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 双线铁路 (x [0,8], y [2,4]): 灰色道床 12 + 黄色道口铺面 4   16 片
  - 公路 (x [3,5]): 南段 y [-1,2] 6 + 北段 y [4,6] 4            10 片
  - 人行道 (x [2,3], y [0,2]): 2                                  2 片
  - 看守小屋 (x [0,2], y [0,2], z 0..1): 地板 4 + 墙环 8
    (北墙嵌窗格方了望窗, 东墙嵌门框方, 门朝人行道) +
    屋顶 4 + 双山尖 2                                            18 片
  - 门式道口栏杆 x2: 立柱 2 + 水平横杆 1 (每座)                   6 片
  - 信号高塔尖: 红 (东南) + 绿 (西北) 等腰三角 x2                 2 片
  - 警示三角: 轨旁红色等边三角 x4                                 4 片
  - 小轿车 (沿路纵向): 车轮底座 x2 + 长板车顶 + 三角驾驶舱        4 片
  合计 62 片, 13 个教程步骤, 7 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点:
  - 栏杆横杆平放 z=1, 两条短边分别整边吸两根立柱顶边 ——
    双端受力零悬挑 (剪断任一端, 另一端立柱仍接地);
  - 立柱底边同时吸公路板边与人行道/路板拼缝, 柱-杆-柱-路面
    锁成门式闭环;
  - 小轿车沿路纵向: 车顶长板双长边压两片车轮底座顶边, 车头
    短边恰与落下的横杆南沿同缝相接 —— 车等火车, 全场连通;
  - 信号塔尖/警示三角/山尖全部骑整边沿口, 重心正压铰链力矩为零;
  - 全场最高点 2.0 (信号塔尖), 不触发 R8 高层检查。

用法: python3 tools/generate_railway_crossing.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

RAIL = "gray"       # 道床
PANEL = "yellow"    # 道口铺面
ROAD = "gray"       # 公路
WALK = "yellow"     # 人行道
HUT = "orange"      # 看守小屋墙体
WIN = "clear"       # 了望窗
DOOR = "red"        # 小屋门
HROOF = "gray"      # 小屋屋顶
GABLE = "red"       # 山尖
POST = "red"        # 栏杆立柱
ARM = "yellow"      # 栏杆横杆
SIG_S = "red"       # 南信号塔尖
SIG_N = "green"     # 北信号塔尖
WARN = "red"        # 警示三角
CAR = "blue"        # 小轿车
WHEEL = "gray"      # 车轮底座

# =================================================================
# 1. 双线铁路 (x [0,8], y [2,4]): 道口段 (x [3,5]) 换黄色铺面
# =================================================================
for x in range(8):
    color = PANEL if x in (3, 4) else RAIL
    b.flat(f"trk_s_{x}", x, 2, 0.0, color)      # 南线 y [2,3]
for x in range(8):
    color = PANEL if x in (3, 4) else RAIL
    b.flat(f"trk_n_{x}", x, 3, 0.0, color)      # 北线 y [3,4]

# =================================================================
# 2. 公路 (x [3,5]) + 人行道 (x [2,3])
# =================================================================
for y in (-1, 0, 1):
    b.flat(f"rd_s_{y}", 3, y, 0.0, ROAD)
    b.flat(f"rd_s_{y}e", 4, y, 0.0, ROAD)
for y in (4, 5):
    b.flat(f"rd_n_{y}", 3, y, 0.0, ROAD)
    b.flat(f"rd_n_{y}e", 4, y, 0.0, ROAD)
b.flat("wk_0", 2, 0, 0.0, WALK)
b.flat("wk_1", 2, 1, 0.0, WALK)

# =================================================================
# 3. 看守小屋 (x [0,2], y [0,2], z 0..1)
# =================================================================
for x in range(2):
    for y in range(2):
        b.flat(f"hut_fl_{x}_{y}", x, y, 0.0, RAIL)
b.wall_ns("hut_s_0", 0, 0.0, 0, HUT)
b.wall_ns("hut_s_1", 1, 0.0, 0, HUT)
b.add("hut_win", "window_square", (0.5, 2.0, 0.5), (90, 0, 0), WIN)   # 北墙了望窗
b.wall_ns("hut_n_1", 1, 2.0, 0, HUT)
b.wall_ew("hut_w_0", 0.0, 0, 0, HUT)
b.wall_ew("hut_w_1", 0.0, 1, 0, HUT)
b.wall_ew("hut_e_0", 2.0, 0, 0, HUT)
b.add("hut_door", "door_frame", (2.0, 1.5, 0.5), (90, 0, 90), DOOR)   # 东墙门朝人行道
for x in range(2):
    for y in range(2):
        b.flat(f"hut_rf_{x}_{y}", x, y, 1.0, HROOF)
b.crest_ns("hut_g_s", 0, 0.0, 1.0, GABLE)       # 南山尖
b.crest_ns("hut_g_n", 1, 2.0, 1.0, GABLE)       # 北山尖

# =================================================================
# 4. 门式道口栏杆: 南座 (y [1,2]) + 北座 (y [4,5])
# =================================================================
b.wall_ew("gt_s_w", 3.0, 1, 0, POST)            # 南座西柱
b.wall_ew("gt_s_e", 5.0, 1, 0, POST)            # 南座东柱
b.flat_rect("gt_s_arm", 3, 1, 1.0, ARM)         # 南横杆 (短边吸柱顶)
b.wall_ew("gt_n_w", 3.0, 4, 0, POST)            # 北座西柱
b.wall_ew("gt_n_e", 5.0, 4, 0, POST)            # 北座东柱
b.flat_rect("gt_n_arm", 3, 4, 1.0, ARM)         # 北横杆

# =================================================================
# 5. 信号塔尖 + 警示三角
# =================================================================
b.spire_ew("sig_s", 5.0, 0, 0.0, SIG_S)         # 东南信号 (骑公路东沿)
b.spire_ew("sig_n", 3.0, 5, 0.0, SIG_N)         # 西北信号 (骑公路西沿)
b.crest_ns("warn_sw", 2, 2.0, 0.0, WARN)        # 南沿西警示
b.crest_ns("warn_se", 6, 2.0, 0.0, WARN)        # 南沿东警示
b.crest_ns("warn_nw", 2, 4.0, 0.0, WARN)        # 北沿西警示
b.crest_ns("warn_ne", 6, 4.0, 0.0, WARN)        # 北沿东警示

# =================================================================
# 6. 小轿车 (x [3,4], y [-1,1], 沿路纵向): 停在落杆前等火车
# =================================================================
b.add("car_wh_w", "wheel_base", (3.0, 0.0, 0.5), (90, 0, 90), WHEEL)
b.add("car_wh_e", "wheel_base", (4.0, 0.0, 0.5), (90, 0, 90), WHEEL)
b.flat_rect("car_top", 3, -1, 1.0, CAR, axis="y")   # 车顶长板 (双长边压轮顶)
b.crest_ns("car_cab", 3, 1.0, 1.0, CAR)         # 驾驶舱 (骑车顶北短边)

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺南线道床: 8 片方板沿东西向排开 (y [2,3]), 道口段 (x [3,5]) 用黄色铺面。",
    [f"trk_s_{x}" for x in range(8)],
    tip="黄色铺面就是火车与汽车共用的道口地带 —— 先把它记住。",
)
b.step(
    "铺北线道床: 再排 8 片 (y [3,4]), 双线铁路贯通。",
    [f"trk_n_{x}" for x in range(8)],
    highlight=["trk_s_3", "trk_s_4"],
    tip="两线道床长边整边互吸, 道口铺面上下对齐。",
)
b.step(
    "铺公路南段: 6 片方板从南边接上道口 (x [3,5], y [-1,2])。",
    ["rd_s_1", "rd_s_1e", "rd_s_0", "rd_s_0e", "rd_s_-1", "rd_s_-1e"],
    highlight=["trk_s_3", "trk_s_4"],
    tip="公路北沿与南线道床整边吸合 —— 十字动线交上了。",
)
b.step(
    "铺公路北段与人行道: 北段 4 片 (y [4,6]), 路西人行道 2 片 (x [2,3])。",
    ["rd_n_4", "rd_n_4e", "rd_n_5", "rd_n_5e", "wk_0", "wk_1"],
    highlight=["trk_n_3", "trk_n_4"],
    tip="人行道贴着公路西沿 —— 看守员上下班走这条道。",
)
b.step(
    "铺小屋地板: 4 片方板贴人行道西沿 (x [0,2], y [0,2])。",
    ["hut_fl_0_0", "hut_fl_0_1", "hut_fl_1_0", "hut_fl_1_1"],
    highlight=["wk_0", "wk_1"],
    tip="地板东边与人行道整边吸合, 小屋在这里生根。",
)
b.step(
    "立小屋南墙与西墙: 4 片橙色立墙踩地板沿边。",
    ["hut_s_0", "hut_s_1", "hut_w_0", "hut_w_1"],
    highlight=["hut_fl_0_0"],
    tip="墙脚整边吸地板边, 竖边两两互咬。",
)
b.step(
    "合小屋墙环: 北墙嵌窗格方了望窗 (正对铁路), 东墙嵌门框方 (门朝人行道)。",
    ["hut_win", "hut_n_1", "hut_e_0", "hut_door"],
    highlight=["hut_s_0", "hut_w_1"],
    tip="看守员从了望窗盯着火车, 推门就到人行道 —— 动线闭环。",
)
b.step(
    "盖屋顶立山尖: 4 片平顶压墙顶, 南北沿各骑 1 片红色三角山尖。",
    ["hut_rf_0_0", "hut_rf_0_1", "hut_rf_1_0", "hut_rf_1_1", "hut_g_s", "hut_g_n"],
    highlight=["hut_win", "hut_door"],
    tip="山尖与墙共面, 重心正压沿口 —— 力矩为零。",
)
b.step(
    "立南座道口栏杆: 公路两侧各立 1 根红色立柱, 黄色横杆平放柱顶 —— "
    "两短边同吸柱顶边, 落杆锁住路口。",
    ["gt_s_w", "gt_s_e", "gt_s_arm"],
    highlight=["rd_s_1", "rd_s_1e"],
    tip="横杆双端受力零悬挑 —— 剪断任一端, 另一端立柱还稳稳接地。",
)
b.step(
    "立北座道口栏杆: 与南座隔轨对望, 柱-杆-柱-路面锁成门式闭环。",
    ["gt_n_w", "gt_n_e", "gt_n_arm"],
    highlight=["rd_n_4", "rd_n_4e"],
    tip="两座门式栏杆同起同落 —— 火车来了, 路口两头一起锁。",
)
b.step(
    "立信号塔尖: 红绿两面等腰高塔尖对角骑上公路沿边, 与栏杆联动。",
    ["sig_s", "sig_n"],
    highlight=["gt_s_e", "gt_n_w"],
    tip="红灯亮 = 栏杆落; 塔尖 2.0 是全场最高点。",
)
b.step(
    "布警示三角: 轨旁四面红色等边三角把守道口两侧。",
    ["warn_sw", "warn_se", "warn_nw", "warn_ne"],
    highlight=["trk_s_2", "trk_n_6"],
    tip="警示三角骑整边沿口 —— 提醒大家道口注意安全。",
)
b.step(
    "停一辆小轿车: 2 片车轮底座沿路纵向立在公路南段 (x [3,4]), 蓝色长板"
    "车顶双长边压轮顶, 车头北短边再骑上三角驾驶舱 —— 恰好顶到落下的横杆。",
    ["car_wh_w", "car_wh_e", "car_top", "car_cab"],
    highlight=["gt_s_arm"],
    tip="车头短边与横杆南沿同缝相接 —— 安静等火车通过, 别抢行!",
)

b.finalize(
    model_id="railway_crossing_01",
    name="看守铁路道口",
    name_en="Railway Crossing 01",
    description=(
        "只用核心九片型的平交道口: 双线铁路东西向横贯, 南北公路穿过"
        "黄色道口铺面, 公路两侧各立一座门式道口栏杆 —— 水平横杆两短边"
        "同吸柱顶, 双端受力零悬挑, 落杆锁住路口; 路西看守小屋窗格方了望"
        "窗正对铁路、门框方大门朝人行道, 屋顶双山尖; 红绿信号塔尖对角"
        "对望, 轨旁四面警示三角把守, 一辆蓝色小轿车 (车轮底座 + 长板"
        "车顶) 沿路停在落杆前 —— 红灯亮、栏杆落, 安静等火车通过。"
    ),
    difficulty=3,
    tags=["交通", "火车", "道口", "城市", "进阶"],
    min_pieces=62,
    min_steps=13,
)
