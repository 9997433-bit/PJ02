#!/usr/bin/env python3
"""生成模型 data/models/canal_lock_01.json (运河船闸)。

内容批 E 模型 3/5: 全库第一座运河船闸 —— 与 hydro_dam_01 (拦水
大坝) / 各类桥梁 (跨越水面) 刻意区分: 本作的结构签名是"两级水位
+ 闸室夹船": 西端高位蓄水池的水面整整比下游高出一层 (z=1 对 z=0),
一片池水一片下游摆在一起就是教科书级的水位落差剖面; 中段闸室由
两道钢闸门与两侧闸墙锁成闭环箱体, 一艘挂着高桅杆的小拖船正泊在
闸室里等待放水 —— 桅杆从闸墙顶探出头, 是全场制高点。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 水道东西向):
  - 南北岸堤 (y [0,1] / y [4,5]): 绿茵长板 + 闸墙脚单位方板     13 片
  - 高位蓄水池 (x [0,3], y [1,4]): 石砌墙环 9 + 高位水面 9      18 片
  - 闸室 (x [3,6], y [1,4]): 闸墙 x6 + 双钢闸门 x6 (含观察窗)   12 片
  - 闸室水底 3x3 单位方板                                        9 片
  - 小拖船 (x [4,5], y [2,3]): 船体环 4 + 甲板 + 等腰高桅杆      6 片
  - 下游水道 (x [6,8], y [1,4]): 低位水面长板 x3                 3 片
  - 闸控小屋 (x [7,8], y [4,5]): 箱体 + 压顶 + 四坡锥顶          9 片
  - 通航信号旗 x2 (红=禁行骑上游闸门顶, 绿=通行骑下游闸门顶)     2 片
  合计 72 片, 14 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 蓄水池墙环与闸室墙环共用上游闸门一道墙 (共墙即共保险),
    两环相扣, 全部墙体四角竖边互咬、墙脚踩地缝或单位方板边;
  - 高位水面 3x3 全用单位方板: 周圈八片吸墙顶, 中心一片四边
    与邻板共面互吸 —— 环撑板面, 拆一片不塌;
  - 闸室是'闸墙 + 双闸门'的闭环箱体, 拆开任何一门, 力沿环绕行;
  - 桅杆'甲板北沿 + 船体北墙顶'一线双吸, 重心正压铰链线;
  - 信号旗骑闸门顶边, 迎风力矩为零。

用法: python3 tools/generate_canal_lock_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

BANK = "green"       # 岸堤
STONE = "gray"       # 石砌闸墙 / 池墙
WATER = "blue"       # 水面 / 水底
GATE = "orange"      # 钢闸门
GATE_WIN = "cyan"    # 闸门观察窗
HULL = "red"         # 船体
DECK = "clear"       # 甲板
MAST = "gray"        # 桅杆
HOUSE = "clear"      # 闸控小屋墙
DOOR = "orange"      # 小屋门
WIN = "cyan"         # 小屋窗
ROOF = "red"         # 小屋锥顶
CAP = "gray"         # 小屋压顶
FLAG_STOP = "red"    # 禁行旗
FLAG_GO = "green"    # 通行旗

# =================================================================
# 1. 南北岸堤: 闸墙脚处全单位方板, 其余绿茵长板
# =================================================================
# 南岸 (y [0,1])
b.flat_rect("bs_w", 0, 0, 0.0, BANK)
b.flat("bs_2", 2, 0, 0.0, BANK)
b.flat("bs_3", 3, 0, 0.0, BANK)
b.flat("bs_4", 4, 0, 0.0, BANK)
b.flat("bs_5", 5, 0, 0.0, BANK)
b.flat_rect("bs_e", 6, 0, 0.0, BANK)
# 北岸 (y [4,5])
b.flat_rect("bn_w", 0, 4, 0.0, BANK)
b.flat("bn_2", 2, 4, 0.0, BANK)
b.flat("bn_3", 3, 4, 0.0, BANK)
b.flat("bn_4", 4, 4, 0.0, BANK)
b.flat("bn_5", 5, 4, 0.0, BANK)
b.flat("bn_6", 6, 4, 0.0, BANK)
b.flat("bn_7", 7, 4, 0.0, BANK)                    # 闸控小屋脚下

# =================================================================
# 2. 高位蓄水池 (x [0,3], y [1,4]): 石砌墙环 + 高位水面
# =================================================================
for x in (0, 1, 2):
    b.wall_ns(f"pw_s_{x}", x, 1.0, 0, STONE)
    b.wall_ns(f"pw_n_{x}", x, 4.0, 0, STONE)
for y in (1, 2, 3):
    b.wall_ew(f"pw_w_{y}", 0.0, y, 0, STONE)
# 高位水面 3x3 (z=1): 周圈吸墙顶, 中心与邻板共面互吸
for x in (0, 1, 2):
    for y in (1, 2, 3):
        b.flat(f"pool_{x}_{y}", x, y, 1.0, WATER)

# =================================================================
# 3. 闸室 (x [3,6], y [1,4]): 水底 + 闸墙 + 双钢闸门
# =================================================================
for x in (3, 4, 5):
    for y in (1, 2, 3):
        b.flat(f"cf_{x}_{y}", x, y, 0.0, WATER)    # 闸室水底
for x in (3, 4, 5):
    b.wall_ns(f"cw_s_{x}", x, 1.0, 0, STONE)       # 南闸墙
    b.wall_ns(f"cw_n_{x}", x, 4.0, 0, STONE)       # 北闸墙
# 上游闸门 (x=3, 兼蓄水池东墙): 中间一片观察窗
b.wall_ew("gu_1", 3.0, 1, 0, GATE)
b.add("gu_2", "window_square", (3.0, 2.5, 0.5), (90, 0, 90), GATE_WIN)
b.wall_ew("gu_3", 3.0, 3, 0, GATE)
# 下游闸门 (x=6): 中间一片观察窗
b.wall_ew("gd_1", 6.0, 1, 0, GATE)
b.add("gd_2", "window_square", (6.0, 2.5, 0.5), (90, 0, 90), GATE_WIN)
b.wall_ew("gd_3", 6.0, 3, 0, GATE)

# =================================================================
# 4. 小拖船 (x [4,5], y [2,3]): 船体环 + 甲板 + 高桅杆
# =================================================================
b.wall_ns("bt_s", 4, 2.0, 0, HULL)
b.wall_ns("bt_n", 4, 3.0, 0, HULL)
b.wall_ew("bt_w", 4.0, 2, 0, HULL)
b.wall_ew("bt_e", 5.0, 2, 0, HULL)
b.flat("bt_deck", 4, 2, 1.0, DECK)
b.spire_ns("bt_mast", 4, 3.0, 1.0, MAST)           # 桅尖 3.0 全场制高

# =================================================================
# 5. 下游水道 (x [6,8], y [1,4]): 低位水面
# =================================================================
b.flat_rect("dw_1", 6, 1, 0.0, WATER)
b.flat_rect("dw_2", 6, 2, 0.0, WATER)
b.flat_rect("dw_3", 6, 3, 0.0, WATER)

# =================================================================
# 6. 闸控小屋 (x [7,8], y [4,5]): 箱体 + 压顶 + 锥顶
# =================================================================
b.add("hs_s", "door_frame", (7.5, 4.0, 0.5), (90, 0, 0), DOOR)
b.wall_ns("hs_n", 7, 5.0, 0, HOUSE)
b.wall_ew("hs_w", 7.0, 4, 0, HOUSE)
b.add("hs_e", "window_square", (8.0, 4.5, 0.5), (90, 0, 90), WIN)
b.flat("hs_cap", 7, 4, 1.0, CAP)
b.hat4("hs_roof", 7, 4, 1.0, ROOF, shape="equilateral_triangle")

# =================================================================
# 7. 通航信号旗: 红旗骑上游闸门顶 (禁行), 绿旗骑下游闸门顶 (通行)
# =================================================================
b.crest_ew("flag_stop", 3.0, 2, 1.0, FLAG_STOP)
b.crest_ew("flag_go", 6.0, 2, 1.0, FLAG_GO)

# =================================================================
# 教程步骤 (14 步)
# =================================================================
b.step(
    "铺南岸堤: 闸墙脚下四格用单位方板, 两端绿茵长板收口。",
    ["bs_w", "bs_2", "bs_3", "bs_4", "bs_5", "bs_e"],
    tip="船闸工程从岸堤放线开始 —— 闸墙的脚要踩在方板拼缝上。",
)
b.step(
    "铺北岸堤: 与南岸对缝, 东端多留一格给闸控小屋。",
    ["bn_w", "bn_2", "bn_3", "bn_4", "bn_5", "bn_6", "bn_7"],
    highlight=["bs_2"],
    tip="东北角那格方板就是闸控小屋的地基 —— 管闸员视野最好的位置。",
)
b.step(
    "砌蓄水池南墙与西墙: 六片石砌立墙, 转角竖边互咬。",
    ["pw_s_0", "pw_s_1", "pw_s_2", "pw_w_1", "pw_w_2", "pw_w_3"],
    highlight=["bs_w"],
    tip="石墙沿平面内竖边一片咬一片 —— 高位水就靠这圈墙兜住。",
)
b.step(
    "砌蓄水池北墙并立上游闸门: 闸门中间嵌观察窗, 与池墙合成闭环。",
    ["pw_n_0", "pw_n_1", "pw_n_2", "gu_1", "gu_2", "gu_3"],
    highlight=["pw_s_0"],
    tip="上游闸门身兼两职 —— 它既是池墙的东边, 也是闸室的西门。",
)
b.step(
    "铺高位水面西列与中列: 六片蓝色方板吸上墙顶。",
    ["pool_0_1", "pool_0_2", "pool_0_3", "pool_1_1", "pool_1_2", "pool_1_3"],
    highlight=["pw_w_2"],
    tip="水面铺在 z=1 —— 整整比下游高出一层, 这就是船闸的落差。",
)
b.step(
    "铺高位水面东列: 靠闸门一列方板, 北角与闸门顶整边互吸。",
    ["pool_2_1", "pool_2_2", "pool_2_3"],
    highlight=["gu_3"],
    tip="中心那片四边全靠邻板共面互吸 —— 环撑板面, 拆一片不塌。",
)
b.step(
    "铺闸室水底: 3x3 蓝色方板, 闸墙与船体的脚都踩在这些拼缝上。",
    ["cf_3_1", "cf_3_2", "cf_3_3", "cf_4_1", "cf_4_2", "cf_4_3",
     "cf_5_1", "cf_5_2", "cf_5_3"],
    highlight=["bs_3"],
    tip="闸室放空了水 —— 水底比蓄水池水面低一整层。",
)
b.step(
    "砌闸室南北闸墙: 各三片石砌立墙, 墙脚踩水底与岸堤双拼缝。",
    ["cw_s_3", "cw_s_4", "cw_s_5", "cw_n_3", "cw_n_4", "cw_n_5"],
    highlight=["cf_3_1"],
    tip="闸墙与上游闸门竖边互咬 —— 两个墙环共用一道墙。",
)
b.step(
    "立下游闸门: 中间嵌观察窗, 闸室锁成闭环箱体。",
    ["gd_1", "gd_2", "gd_3"],
    highlight=["cw_s_5"],
    tip="双门合拢, 闸室成环 —— 拆开任何一门, 力都沿环绕行。",
)
b.step(
    "拼小拖船船体: 四片红色船壳围环, 泊进闸室正中。",
    ["bt_s", "bt_n", "bt_w", "bt_e"],
    highlight=["cf_4_2"],
    tip="船壳脚踩水底拼缝, 与闸墙留出整格水路 —— 好戏就要开场。",
)
b.step(
    "盖甲板并立桅杆: 桅杆'甲板北沿+船壳北墙顶'一线双吸, 桅尖 3.0。",
    ["bt_deck", "bt_mast"],
    highlight=["bt_n"],
    tip="桅杆从闸墙顶探出头 —— 等水位升起来, 船就跟着长高。",
)
b.step(
    "铺下游水道: 三片蓝色长板长边互吸, 低位水面直通东端。",
    ["dw_1", "dw_2", "dw_3"],
    highlight=["gd_1"],
    tip="下游水面在 z=0 —— 和高位水面并排一看, 落差一目了然。",
)
b.step(
    "砌闸控小屋: 门朝运河, 东墙嵌观察窗, 压顶四边吸墙顶。",
    ["hs_s", "hs_n", "hs_w", "hs_e", "hs_cap"],
    highlight=["bn_7"],
    tip="管闸员从这扇门出来摇绞盘 —— 观察窗正对下游闸门。",
)
b.step(
    "合小屋锥顶并挂通航信号旗: 红旗骑上游闸门顶 (禁行), 绿旗骑"
    "下游闸门顶 (通行)。",
    ["hs_roof_s", "hs_roof_e", "hs_roof_n", "hs_roof_w",
     "flag_stop", "flag_go"],
    highlight=["hs_cap"],
    tip="旗子重心正压闸门顶铰链线 —— 绿旗一挂, 开闸放行!",
)

b.finalize(
    model_id="canal_lock_01",
    name="运河船闸",
    name_en="Canal Lock 01",
    description=(
        "只用核心九片型的运河船闸, 结构签名是'两级水位 + 闸室夹船': "
        "西端高位蓄水池的水面整整比下游高出一层 (z=1 对 z=0), 3x3 "
        "高位水面周圈吸墙顶、中心一片靠邻板共面互吸环撑成板; 中段"
        "闸室由两道钢闸门 (中嵌观察窗) 与两侧闸墙锁成闭环箱体, 与"
        "蓄水池墙环共用上游闸门一道墙; 一艘挂着等腰高桅杆的红色小"
        "拖船泊在闸室水底等待放水, 桅尖 3.0 从闸墙顶探出全场制高; "
        "闸控小屋守在东北角, 红绿信号旗分骑两道闸门顶 —— 绿旗一挂, "
        "开闸放行!"
    ),
    difficulty=3,
    tags=["工程", "运河", "船闸", "水利", "挑战"],
    min_pieces=72,
    min_steps=14,
)
