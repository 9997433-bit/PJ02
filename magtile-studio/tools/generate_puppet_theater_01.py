#!/usr/bin/env python3
"""生成模型 data/models/puppet_theater_01.json (木偶剧场)。

内容批 E 补位模型 (顶替与批 C apiary_01 同题撤下的 bee_farm_01):
全库第一座木偶剧场 —— 与 piano_stage_01 (露天演奏台) /
open_air_cinema_01 与 drive_in_cinema_01 (平面银幕墙) 刻意区分:
本作的结构签名是"台中台": 剧场亭是一座二层箱楼, 二层正面两扇
窗格方就是演出窗 —— 镂空窗框天然是舞台口; 亭子肚子里藏着一层
黄色戏台板 (南北两边分别吸前后墙顶, 双端受力), 橙色小木偶就
骑在戏台板正中的拼缝上, 从演出窗里探出来向观众鞠躬。台前两条
长凳共用中间一根凳腿 (共柱技法), 凳板短边各吸一柱顶零悬挑。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 演出窗朝南):
  - 广场地坪 4 行 (x [0,6], y [0,4]): 广场砖 + 红毯             20 片
  - 剧场亭 (x [2,4], y [2,3], z 0..2): 一层台围 (含后台门框方)
    + 戏台板 x2 + 二层演出窗墙环 + 压顶 x2                      16 片
  - 幕檐红三角 x2 + 顶旗 + 台上小木偶                            4 片
  - 观众长凳: 凳腿 x3 (共柱) + 凳板 x2                           5 片
  - 前排小观众 (青色三角骑地缝)                                  1 片
  合计 46 片, 10 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告 + jitter 全绿):
  - 剧场亭两节墙环整边共线上叠, 四角竖边互咬 (箱楼受压无悬挂链);
  - 戏台板两片南北边分别吸一层前后墙顶, 彼此再长边互吸 —— 双端
    受力零悬挑; 小木偶骑戏台板拼缝, 重心正压铰链线;
  - 长凳凳板短边各整边吸一根凳腿顶, 中间凳腿一柱两用 (共柱),
    双端受力零悬挑 (急诊连廊顶同款);
  - 幕檐三角骑'压顶南沿 + 演出窗顶'一线双吸, 顶旗骑压顶拼缝;
  - 地坪拼缝纪律: 亭墙脚与凳腿处全单位方板。

用法: python3 tools/generate_puppet_theater_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

PLAZA = "gray"       # 广场砖
CARPET = "red"       # 红毯
BOOTH = "red"        # 剧场亭墙体
DOOR = "orange"      # 后台门
STAGE = "yellow"     # 戏台板
WIN = "cyan"         # 演出窗
CAP = "gray"         # 压顶
EAVE = "red"         # 幕檐
FLAG = "yellow"      # 顶旗
PUPPET = "orange"    # 小木偶
BENCH_L = "orange"   # 凳腿
BENCH_S = "yellow"   # 凳板
KID = "cyan"         # 小观众

# =================================================================
# 1. 广场地坪 4 行 (x [0,6], y [0,4])
# =================================================================
# 长凳行 (y [0,1]): 凳腿脚下全单位方板
for x in range(6):
    b.flat(f"p0_{x}", x, 0, 0.0, PLAZA)
# 走道行 (y [1,2]): 红毯居中
b.flat_rect("p1_w", 0, 1, 0.0, PLAZA)
b.flat("p1_2", 2, 1, 0.0, CARPET)
b.flat("p1_3", 3, 1, 0.0, CARPET)
b.flat_rect("p1_e", 4, 1, 0.0, PLAZA)
# 剧场亭行 (y [2,3]): 亭墙脚全单位方板
for x in range(6):
    b.flat(f"p2_{x}", x, 2, 0.0, PLAZA)
# 后台行 (y [3,4])
b.flat_rect("p3_w", 0, 3, 0.0, PLAZA)
b.flat("p3_2", 2, 3, 0.0, PLAZA)
b.flat("p3_3", 3, 3, 0.0, PLAZA)
b.flat_rect("p3_e", 4, 3, 0.0, PLAZA)

# =================================================================
# 2. 剧场亭一层 (z 0..1): 台围 + 后台门框方
# =================================================================
b.wall_ns("bt1_s_2", 2, 2.0, 0, BOOTH)
b.wall_ns("bt1_s_3", 3, 2.0, 0, BOOTH)
b.add("bt1_n_2", "door_frame", (2.5, 3.0, 0.5), (90, 0, 0), DOOR)  # 后台门
b.wall_ns("bt1_n_3", 3, 3.0, 0, BOOTH)
b.wall_ew("bt1_w", 2.0, 2, 0, BOOTH)
b.wall_ew("bt1_e", 4.0, 2, 0, BOOTH)

# =================================================================
# 3. 戏台板 (z=1) + 台上小木偶
# =================================================================
b.flat("stage_w", 2, 2, 1.0, STAGE)
b.flat("stage_e", 3, 2, 1.0, STAGE)
b.crest_ew("puppet", 3.0, 2, 1.0, PUPPET)          # 骑戏台板拼缝

# =================================================================
# 4. 剧场亭二层 (z 1..2): 演出窗墙环 + 压顶
# =================================================================
b.add("bt2_s_2", "window_square", (2.5, 2.0, 1.5), (90, 0, 0), WIN)
b.add("bt2_s_3", "window_square", (3.5, 2.0, 1.5), (90, 0, 0), WIN)
b.wall_ns("bt2_n_2", 2, 3.0, 1, BOOTH)
b.wall_ns("bt2_n_3", 3, 3.0, 1, BOOTH)
b.wall_ew("bt2_w", 2.0, 2, 1, BOOTH)
b.wall_ew("bt2_e", 4.0, 2, 1, BOOTH)
b.flat("cap_w", 2, 2, 2.0, CAP)
b.flat("cap_e", 3, 2, 2.0, CAP)

# =================================================================
# 5. 幕檐 + 顶旗
# =================================================================
b.crest_ns("eave_w", 2, 2.0, 2.0, EAVE)            # 骑压顶南沿
b.crest_ns("eave_e", 3, 2.0, 2.0, EAVE)
b.crest_ew("flag", 3.0, 2, 2.0, FLAG)              # 骑压顶拼缝

# =================================================================
# 6. 观众长凳 (共柱技法) + 前排小观众
# =================================================================
b.wall_ew("leg_w", 1.0, 0, 0, BENCH_L)
b.wall_ew("leg_m", 3.0, 0, 0, BENCH_L)             # 一柱两用
b.wall_ew("leg_e", 5.0, 0, 0, BENCH_L)
b.flat_rect("seat_w", 1, 0, 1.0, BENCH_S)          # 短边各吸一柱顶
b.flat_rect("seat_e", 3, 0, 1.0, BENCH_S)
b.crest_ns("kid", 2, 1.0, 0.0, KID)                # 骑 y=1 地缝

# =================================================================
# 教程步骤 (10 步)
# =================================================================
b.step(
    "铺长凳行: 六片单位方板一字排开, 三根凳腿的脚都在这行。",
    ["p0_0", "p0_1", "p0_2", "p0_3", "p0_4", "p0_5"],
    tip="今晚有演出! 先把观众席的地坪铺平整。",
)
b.step(
    "铺走道行: 红毯两格正对戏台, 两侧广场砖长板收边。",
    ["p1_w", "p1_2", "p1_3", "p1_e"],
    highlight=["p0_2"],
    tip="红毯到哪儿, 舞台就在哪儿 —— 演员走红毯进后台。",
)
b.step(
    "铺剧场亭行: 六片单位方板, 亭子的墙脚全踩这行拼缝。",
    ["p2_0", "p2_1", "p2_2", "p2_3", "p2_4", "p2_5"],
    highlight=["p1_2"],
    tip="亭脚下必须是单位方板 —— 墙底边要和方板边等长吸合。",
)
b.step(
    "铺后台行收口: 广场地坪围合完成。",
    ["p3_w", "p3_2", "p3_3", "p3_e"],
    highlight=["p2_2"],
    tip="相邻行等长边互吸 —— 剧场的地基连成一体。",
)
b.step(
    "砌剧场亭一层台围: 后台门框方朝北, 四角竖边互咬成环。",
    ["bt1_s_2", "bt1_s_3", "bt1_n_2", "bt1_n_3", "bt1_w", "bt1_e"],
    highlight=["p2_2", "p2_3"],
    tip="演员从北面的后台门钻进亭子 —— 观众可看不见。",
)
b.step(
    "铺戏台板并请小木偶登台: 两片黄色台板南北边吸前后墙顶, "
    "橙色小木偶骑上台板正中拼缝。",
    ["stage_w", "stage_e", "puppet"],
    highlight=["bt1_s_2"],
    tip="台板双端受力零悬挑 —— 小木偶站台中央, 重心正压铰链。",
)
b.step(
    "摞二层演出窗墙环: 两扇窗格方朝南就是舞台口, 底边与一层"
    "墙顶整边共线吸合。",
    ["bt2_s_2", "bt2_s_3", "bt2_n_2", "bt2_n_3", "bt2_w", "bt2_e"],
    highlight=["stage_w"],
    tip="镂空窗框天然是舞台口 —— 小木偶正好从窗里探出来。",
)
b.step(
    "盖压顶并挂幕檐顶旗: 两片幕檐红三角骑'压顶南沿+演出窗顶', "
    "黄旗骑压顶拼缝。",
    ["cap_w", "cap_e", "eave_w", "eave_e", "flag"],
    highlight=["bt2_s_2"],
    tip="幕檐一线双吸 —— 像拉开的大幕定格在开演一刻。",
)
b.step(
    "立三根凳腿: 中间那根一柱两用, 全部立在地缝上。",
    ["leg_w", "leg_m", "leg_e"],
    highlight=["p0_1", "p0_3"],
    tip="共柱技法 —— 两条长凳合用一根腿, 省片又稳当。",
)
b.step(
    "架凳板并请小观众入座: 凳板短边各吸一柱顶, 青色小观众"
    "骑地缝站在红毯边。",
    ["seat_w", "seat_e", "kid"],
    highlight=["leg_m"],
    tip="双端受力零悬挑 —— 铛铛铛, 好戏开场!",
)

b.finalize(
    model_id="puppet_theater_01",
    name="木偶剧场",
    name_en="Puppet Theater 01",
    description=(
        "只用核心九片型的木偶剧场, 结构签名是'台中台': 剧场亭是一座"
        "二层箱楼 (两节墙环整边共线上叠, 后台门框方朝北), 二层正面两"
        "扇窗格方就是演出窗 —— 镂空窗框天然是舞台口; 亭子肚子里藏着"
        "一层黄色戏台板 (南北两边分别吸前后墙顶, 双端受力零悬挑), 橙"
        "色小木偶骑在台板正中拼缝上从演出窗里探出来鞠躬; 压顶南沿两"
        "片幕檐红三角一线双吸像拉开的大幕, 台前两条长凳共用中间一根"
        "凳腿 (共柱技法), 青色小观众已在红毯边站好 —— 铛铛铛, 好戏"
        "开场!"
    ),
    difficulty=2,
    tags=["城市", "剧场", "木偶戏", "亲子", "进阶"],
    min_pieces=46,
    min_steps=10,
)
