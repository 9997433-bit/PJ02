#!/usr/bin/env python3
"""生成模型 data/models/bridge_wood_01.json (乡间木桥)。

田园乡村主题: 一条蓝色小河南北穿过 9x5 河谷, 两岸绿草如茵 ——
四片灰色桥墩立在河床格缝上, 五片橙色桥板首尾相吸铺成桥面,
两端 30 度引桥板斜下到岸, 桥沿十片等边护栏一字排开; 西岸
东岸各一棵等腰绿树, 桥头灌木四坡自锁, 河里青鱼跃波、
绿头鸭浮水 —— 过河不湿鞋, 全靠这座木桥!

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 河谷 9x5: 西岸 10 + 河面 11 + 东岸 10                   31 片
  - 桥墩: 方板 x4 (立在河床格缝上, 东西朝向)                 4 片
  - 桥面: 方板 x5 (z=1, 首尾整边互吸, 边沿压墩顶)            5 片
  - 引桥: 30 度长方形 x2 (顶边吸桥板短边, 坡尾落岸)          2 片
  - 护栏: 等边三角 x10 (南北桥沿各 5)                       10 片
  - 岸树: 等腰三角 x2 + 灌木四坡锥 x2 (8 片)                10 片
  - 河中生灵: 青鱼 + 绿头鸭 (等边三角 x2)                    2 片
  合计 64 片, 16 个教程步骤, 5 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 桥墩底边整边吸河床方板格边, 墩顶边与桥板侧边整边吸合 ——
    桥板 + 桥墩 + 相邻桥板锁成连续多跨;
  - 引桥顶端短边整边吸桥板端边, 坡尾落地接地 —— 双端受力,
    剪断任何一条铰链桥面仍有支撑路径;
  - 护栏底边整边吸桥板边沿, 重心正压铰链零力矩;
  - 全桥最高点 2 格 (树梢), 低重心宽基座, 重心稳稳落在河谷内。

用法: python3 tools/generate_bridge_wood.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

GRASS = "green"
RIVER = "blue"
PIER = "gray"
PLANK = "orange"
RAIL = "orange"
TREE = "green"
FISH = "cyan"

# =================================================================
# 1. 西岸 (x 0..3): 方板 + 长板混铺
# =================================================================
b.flat("wb_0_0", 0, 0, 0.0, GRASS)
b.flat_rect("wb_r_0", 1, 0, 0.0, GRASS, axis="x")
b.flat("wb_0_1", 0, 1, 0.0, GRASS)
b.flat_rect("wb_r_1", 1, 1, 0.0, GRASS, axis="x")
b.flat_rect("wb_r_2", 0, 2, 0.0, GRASS, axis="x")     # 桥头 [0,2]x[2,3]
b.flat("wb_2_2", 2, 2, 0.0, GRASS)                    # 引桥落坡处
b.flat("wb_0_3", 0, 3, 0.0, GRASS)
b.flat_rect("wb_r_3", 1, 3, 0.0, GRASS, axis="x")
b.flat("wb_0_4", 0, 4, 0.0, GRASS)
b.flat_rect("wb_r_4", 1, 4, 0.0, GRASS, axis="x")

# =================================================================
# 2. 河面 (x 3..6): 桥下一行用方板 (桥墩要吸格缝), 其余长板
# =================================================================
b.flat_rect("rv_s_0", 3, 0, 0.0, RIVER, axis="x")
b.flat("rv_5_0", 5, 0, 0.0, RIVER)
b.flat_rect("rv_s_1", 3, 1, 0.0, RIVER, axis="x")
b.flat("rv_5_1", 5, 1, 0.0, RIVER)
b.flat("rv_3_2", 3, 2, 0.0, RIVER)                    # 桥下河床
b.flat("rv_4_2", 4, 2, 0.0, RIVER)
b.flat("rv_5_2", 5, 2, 0.0, RIVER)
b.flat_rect("rv_n_3", 3, 3, 0.0, RIVER, axis="x")
b.flat("rv_5_3", 5, 3, 0.0, RIVER)
b.flat_rect("rv_n_4", 3, 4, 0.0, RIVER, axis="x")
b.flat("rv_5_4", 5, 4, 0.0, RIVER)

# =================================================================
# 3. 东岸 (x 6..9)
# =================================================================
b.flat_rect("eb_r_0", 6, 0, 0.0, GRASS, axis="x")
b.flat("eb_8_0", 8, 0, 0.0, GRASS)
b.flat_rect("eb_r_1", 6, 1, 0.0, GRASS, axis="x")
b.flat("eb_8_1", 8, 1, 0.0, GRASS)
b.flat("eb_6_2", 6, 2, 0.0, GRASS)                    # 引桥落坡处
b.flat_rect("eb_r_2", 7, 2, 0.0, GRASS, axis="x")
b.flat_rect("eb_r_3", 6, 3, 0.0, GRASS, axis="x")
b.flat("eb_8_3", 8, 3, 0.0, GRASS)
b.flat_rect("eb_r_4", 6, 4, 0.0, GRASS, axis="x")
b.flat("eb_8_4", 8, 4, 0.0, GRASS)

# =================================================================
# 4. 桥墩 x4 (东西朝向, 立在河床格缝 x=3/4/5/6 上)
# =================================================================
b.wall_ew("pier_3", 3.0, 2, 0, PIER)
b.wall_ew("pier_4", 4.0, 2, 0, PIER)
b.wall_ew("pier_5", 5.0, 2, 0, PIER)
b.wall_ew("pier_6", 6.0, 2, 0, PIER)

# =================================================================
# 5. 桥面 x5 (z=1): 首尾整边互吸, 侧边压墩顶
# =================================================================
for x0 in range(2, 7):
    b.flat(f"dk_{x0}", x0, 2, 1.0, PLANK)

# =================================================================
# 6. 引桥 x2 (30 度): 顶边吸桥板端边, 坡尾落岸
# =================================================================
b.ramp("ap_w", "-x", 2.0, 2, 1.0, PLANK)
b.ramp("ap_e", "+x", 7.0, 2, 1.0, PLANK)

# =================================================================
# 7. 护栏 x10: 南北桥沿各 5 片等边三角
# =================================================================
for x0 in range(2, 7):
    b.crest_ns(f"rl_s_{x0}", x0, 2.0, 1.0, RAIL)
    b.crest_ns(f"rl_n_{x0}", x0, 3.0, 1.0, RAIL)

# =================================================================
# 8. 岸树 + 灌木 + 河中生灵
# =================================================================
b.spire_ns("tree_w", 0, 5.0, 0.0, TREE)               # 西岸树
b.spire_ns("tree_e", 8, 5.0, 0.0, TREE)               # 东岸树
BUSH_W = b.hat4("bush_w", 0, 0, 0.0, TREE,
                shape="equilateral_triangle")         # 西南灌木
BUSH_E = b.hat4("bush_e", 8, 0, 0.0, TREE,
                shape="equilateral_triangle")         # 东南灌木
b.crest_ns("fish", 5, 1.0, 0.0, FISH)                 # 跃波青鱼
b.crest_ns("duck", 5, 4.0, 0.0, FISH)                 # 浮水绿头鸭

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺西岸: 10 片绿色地坪铺出西岸草地, 桥头留在正中一行。",
    ["wb_0_0", "wb_r_0", "wb_0_1", "wb_r_1", "wb_r_2",
     "wb_2_2", "wb_0_3", "wb_r_3", "wb_0_4", "wb_r_4"],
    tip="河谷从西岸铺起 —— 正中一行就是过河的路线。",
)
b.step(
    "铺河面南半: 4 片蓝色河水接上西岸。",
    ["rv_s_0", "rv_5_0", "rv_s_1", "rv_5_1"],
    highlight=["wb_r_0"],
    tip="河水由南向北流 —— 蓝色长板是平静的深水区。",
)
b.step(
    "铺桥下河床: 3 片蓝色方板一字排开, 格缝就是桥墩的立足线。",
    ["rv_3_2", "rv_4_2", "rv_5_2"],
    highlight=["wb_2_2"],
    tip="这一行必须用方板 —— x=3/4/5/6 四条格缝马上要立桥墩。",
)
b.step(
    "铺河面北半: 4 片河水合拢, 小河贯通南北。",
    ["rv_n_3", "rv_5_3", "rv_n_4", "rv_5_4"],
    highlight=["rv_3_2"],
    tip="哗啦啦 —— 河水到位, 就差一座桥了。",
)
b.step(
    "铺东岸: 10 片绿色地坪, 9x5 河谷两岸合拢。",
    ["eb_r_0", "eb_8_0", "eb_r_1", "eb_8_1", "eb_6_2",
     "eb_r_2", "eb_r_3", "eb_8_3", "eb_r_4", "eb_8_4"],
    highlight=["rv_5_2"],
    tip="两岸就位 —— 各回各家前, 先把桥修好。",
)
b.step(
    "立西侧桥墩: 2 片灰色方板立在 x=3 与 x=4 格缝上, "
    "底边整边吸河床格边。",
    ["pier_3", "pier_4"],
    highlight=["rv_3_2", "rv_4_2"],
    tip="桥墩顺着水流方向立 —— 挡水面最小, 冲不倒。",
)
b.step(
    "立东侧桥墩: x=5 与 x=6 格缝再立 2 片, 四墩一线。",
    ["pier_5", "pier_6"],
    highlight=["pier_3", "pier_4"],
    tip="四墩等距, 桥板的每条接缝都有墩顶托着。",
)
b.step(
    "铺桥面西段: 2 片橙色桥板, 侧边整边压墩顶、首尾互吸。",
    ["dk_2", "dk_3"],
    highlight=["pier_3", "pier_4"],
    tip="桥板接缝正落在墩顶 —— 多跨连续桥的标准做法。",
)
b.step(
    "铺桥面东段: 再铺 3 片, 桥面贯通两岸。",
    ["dk_4", "dk_5", "dk_6"],
    highlight=["dk_3", "pier_5"],
    tip="五板连吸, 走上去咚咚响 —— 这就是木桥的声音。",
)
b.step(
    "架西引桥: 30 度桥板顶端短边整边吸桥板端边, 坡尾落在西岸。",
    ["ap_w"],
    highlight=["dk_2", "wb_2_2"],
    tip="双端受力 —— 上桥的坡道要缓, 推车也能过。",
)
b.step(
    "架东引桥: 东端同法斜下, 过河通道全线贯通。",
    ["ap_e"],
    highlight=["dk_6", "eb_6_2"],
    tip="两端引桥一对称, 木桥的弧线就完整了。",
)
b.step(
    "立南侧护栏: 5 片等边三角沿南桥沿一字排开。",
    ["rl_s_2", "rl_s_3", "rl_s_4", "rl_s_5", "rl_s_6"],
    highlight=["dk_2", "dk_6"],
    tip="护栏底边整边吸桥板边沿, 重心正压铰链 —— 靠着也不倒。",
)
b.step(
    "立北侧护栏: 北沿再立 5 片, 桥面两侧都有了扶手。",
    ["rl_n_2", "rl_n_3", "rl_n_4", "rl_n_5", "rl_n_6"],
    highlight=["rl_s_2"],
    tip="过桥不扶栏, 掉进河里别怪桥。",
)
b.step(
    "种岸树: 两岸北头各立 1 棵等腰绿树。",
    ["tree_w", "tree_e"],
    highlight=["wb_0_4", "eb_8_4"],
    tip="树梢 2 格高, 是河谷的制高点 —— 夏天桥头好乘凉。",
)
b.step(
    "栽灌木: 两岸南头各 4 片等边三角合拢成四坡灌木球。",
    BUSH_W + BUSH_E,
    highlight=["wb_0_0", "eb_8_0"],
    tip="四片斜棱互吸自锁 —— 灌木球滚不走。",
)
b.step(
    "放河中生灵: 青鱼在南河跃波, 绿头鸭在北河浮水 —— 木桥通行!",
    ["fish", "duck"],
    highlight=["rv_5_1", "rv_5_4"],
    tip="从桥心往下望: 鱼游鸭浮, 流水从四个桥墩间穿过。",
)

b.finalize(
    model_id="bridge_wood_01",
    name="乡间木桥",
    name_en="Country Wood Bridge 01",
    description=(
        "多跨连续木桥的入门教科书: 四片桥墩顺水流立在河床格缝上, 五片"
        "橙色桥板首尾整边互吸、接缝正压墩顶, 两端 30 度引桥顶边吸桥板"
        "端边、坡尾落岸 —— 双端受力, 剪断任何一条铰链桥面仍有支撑路径; "
        "十片等边护栏重心正压铰链零力矩; 蓝色小河穿谷而过, 两岸绿树"
        "灌木、河里青鱼绿头鸭 —— 过河不湿鞋, 全靠这座桥。"
    ),
    difficulty=3,
    tags=["田园", "桥梁", "木桥", "河流", "进阶"],
    min_pieces=50,
    min_steps=16,
)
