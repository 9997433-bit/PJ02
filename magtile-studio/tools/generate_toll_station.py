#!/usr/bin/env python3
"""生成模型 data/models/toll_station_01.json (高速收费站)。

城市交通主题批 3/4: 全库第一座"亭即墩"的跨车道雨棚 —— 与
gas_station_01 (独立门架托雨棚 + 加油机) 刻意区分: 收费站没有一根
专职立柱, 两片雨棚长板的短边直接压在三座收费亭的墙顶上 —— 亭子
本身就是桥墩, 亭-棚-亭锁成两个门式闭环; 三座 1x1 两层收费亭分立
两条车道之间: 一层收费窗 (透明窗格方正对司机) + 背门 (门框方朝
北, 员工从后场进出), 二层嵌信号窗 —— 人工道两侧亮红 (停车缴费),
ETC 道两侧亮绿 (直接通行); 人工道一根红色落杆横锁车道 (底边整边
吸路面拼缝, 两竖边同吸两亭墙棱), 蓝色小车车头正顶着落杆等抬杆;
ETC 道绿色小车已经开过亭线扬长而去; 雨棚上三片'收费站'招牌墙
+ 红色徽记直上 3.87 —— 一停一过, 两条车道讲完两种通行方式。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 路面 (x [0,7], y [0,5]): 方板 x15 + 长板 x10                  25 片
  - 收费亭 x3 (x [0,1]/[3,4]/[6,7], y [2,3], 两层): 每亭 8 墙
    (含收费窗/背门/信号窗) + 压顶方板                             27 片
  - 雨棚长板 x2 (短边直接压亭墙顶, 亭即墩)                         2 片
  - 招牌墙 x3 (骑雨棚前沿) + 红色徽记三角                          4 片
  - 人工道落杆 (底边吸路面 + 两竖边吸亭墙棱) x1                    1 片
  - 站徽三角 x2 (骑亭顶外沿)                                       2 片
  - 蓝色小车 (人工道候杆) + 绿色小车 (ETC 道通过) 各 4 片           8 片
  合计 69 片, 12 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 雨棚长板双端受力零悬挑: 每片短边分别整边吸相邻两亭的二层墙顶,
    剪断任一端另一端仍拉在亭上; 亭墙环 + 雨棚 + 邻亭构成门式闭环;
  - 落杆三边受力: 底边与路面长板南沿整边贴合, 两条竖短边分别与
    两亭南墙竖棱互咬 —— 剪断任何一条, 其余两条仍锁着它;
  - 招牌墙站上雨棚前沿: 中央墙底边整边吸亭顶南沿, 两侧墙竖边与
    中央墙互咬再借雨棚沿边分力, 重心正压铰链线力矩为零;
  - 两辆小车车顶长板双长边压车轮底座顶边, 蓝车驾驶舱底边同时骑
    车顶北沿并与落杆顶沿同线相接 (车头顶杆, 全场连通);
  - 亭高 2.0 + 招牌 3.87 触发 R8 高层检查, 闭环拓扑天然通过。

用法: python3 tools/generate_toll_station.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

LANE = "gray"       # 车道
ISLE = "orange"     # 收费岛 (亭基)
WARN = "yellow"     # 岛头导流块
BOOTH = "blue"      # 亭墙
WIN = "clear"       # 收费窗
DOOR = "red"        # 亭背门
STOP = "red"        # 信号窗: 人工道红灯
GO = "green"        # 信号窗: ETC 道绿灯
CAP = "gray"        # 亭顶压顶
CANOPY = "red"      # 雨棚
SIGN_W = "blue"     # 招牌墙 (两侧)
SIGN_C = "yellow"   # 招牌墙 (中央)
CREST = "red"       # 徽记
BAR = "red"         # 落杆
BADGE = "cyan"      # 站徽三角
CAR_A = "blue"      # 人工道小车
CAR_B = "green"     # ETC 道小车
WHEEL = "gray"      # 车轮底座

# =================================================================
# 1. 路面 (x [0,7], y [0,5]): 南北向双车道, 亭基橙色, 岛头黄色
#    车道 x [1,3] (人工) 与 x [4,6] (ETC), 岛柱 x [0,1]/[3,4]/[6,7]
# =================================================================
# 南半路面 (y [0,2]): 岛柱脚下用方板 (小车车轮要吸拼缝)
for y in (0, 1):
    color = WARN if y == 1 else LANE
    b.flat(f"rd_{y}_0", 0, y, 0.0, color)
    b.flat(f"rd_{y}_1", 1, y, 0.0, LANE)
    b.flat_rect(f"rd_{y}_2", 2, y, 0.0, LANE)
    b.flat_rect(f"rd_{y}_4", 4, y, 0.0, LANE)
    b.flat(f"rd_{y}_6", 6, y, 0.0, color)
# 收费岛行 (y [2,3]): 三座亭基橙色, 车道长板灰色
b.flat("rd_2_0", 0, 2, 0.0, ISLE)
b.flat_rect("rd_2_1", 1, 2, 0.0, LANE)
b.flat("rd_2_3", 3, 2, 0.0, ISLE)
b.flat_rect("rd_2_4", 4, 2, 0.0, LANE)
b.flat("rd_2_6", 6, 2, 0.0, ISLE)
# 北半路面 (y [3,5]): ETC 道用方板 (绿车车轮要吸拼缝)
for y in (3, 4):
    color = WARN if y == 3 else LANE
    b.flat_rect(f"rd_{y}_0", 0, y, 0.0, LANE)
    b.flat_rect(f"rd_{y}_2", 2, y, 0.0, LANE)
    b.flat(f"rd_{y}_4", 4, y, 0.0, LANE)
    b.flat(f"rd_{y}_5", 5, y, 0.0, LANE)
    b.flat(f"rd_{y}_6", 6, y, 0.0, color)

# =================================================================
# 2. 三座收费亭 (y [2,3], 两层)
# =================================================================
def booth(prefix, x0, win_w, win_e, sig_w, sig_e):
    """1x1 两层收费亭: 一层收费窗/背门, 二层信号窗, 压顶方板。

    win_w / win_e: 一层西/东面是否开收费窗 (否则实心墙);
    sig_w / sig_e: 二层西/东面信号窗颜色 (None 为实心墙)。
    """
    x1 = x0 + 1
    # 一层
    b.wall_ns(f"{prefix}1_s", x0, 2.0, 0, BOOTH)
    b.add(f"{prefix}1_n", "door_frame", (x0 + 0.5, 3.0, 0.5), (90, 0, 0), DOOR)
    if win_w:
        b.add(f"{prefix}1_w", "window_square", (x0 + 0.0, 2.5, 0.5), (90, 0, 90), WIN)
    else:
        b.wall_ew(f"{prefix}1_w", x0 + 0.0, 2, 0, BOOTH)
    if win_e:
        b.add(f"{prefix}1_e", "window_square", (x1 + 0.0, 2.5, 0.5), (90, 0, 90), WIN)
    else:
        b.wall_ew(f"{prefix}1_e", x1 + 0.0, 2, 0, BOOTH)
    # 二层
    b.wall_ns(f"{prefix}2_s", x0, 2.0, 1, BOOTH)
    b.wall_ns(f"{prefix}2_n", x0, 3.0, 1, BOOTH)
    if sig_w:
        b.add(f"{prefix}2_w", "window_square", (x0 + 0.0, 2.5, 1.5), (90, 0, 90), sig_w)
    else:
        b.wall_ew(f"{prefix}2_w", x0 + 0.0, 2, 1, BOOTH)
    if sig_e:
        b.add(f"{prefix}2_e", "window_square", (x1 + 0.0, 2.5, 1.5), (90, 0, 90), sig_e)
    else:
        b.wall_ew(f"{prefix}2_e", x1 + 0.0, 2, 1, BOOTH)
    # 压顶
    b.flat(f"{prefix}_cap", x0, 2, 2.0, CAP)


booth("bw", 0, win_w=False, win_e=True, sig_w=None, sig_e=STOP)   # 西亭
booth("bm", 3, win_w=True, win_e=True, sig_w=STOP, sig_e=GO)      # 中亭
booth("be", 6, win_w=True, win_e=False, sig_w=GO, sig_e=None)     # 东亭

# =================================================================
# 3. 雨棚 (z=2): 两片长板短边直接压亭墙顶 —— 亭即墩
# =================================================================
b.flat_rect("can_w", 1, 2, 2.0, CANOPY)             # 人工道上空 (x [1,3])
b.flat_rect("can_e", 4, 2, 2.0, CANOPY)             # ETC 道上空 (x [4,6])

# =================================================================
# 4. 招牌墙 + 徽记 (骑雨棚/亭顶前沿, y=2, z [2,3])
# =================================================================
b.wall_ns("sign_c", 3, 2.0, 2, SIGN_C)              # 中央墙 (底边吸中亭顶南沿)
b.wall_ns("sign_w", 2, 2.0, 2, SIGN_W)              # 西墙 (竖边咬中央墙)
b.wall_ns("sign_e", 4, 2.0, 2, SIGN_W)              # 东墙
b.crest_ns("sign_crest", 3, 2.0, 3.0, CREST)        # 红色徽记 (顶高 3.87)

# =================================================================
# 5. 人工道落杆 + 站徽三角
# =================================================================
b.lintel_ns("bar", 1, 2.0, 0, BAR)                  # 落杆横锁人工道 (x [1,3])
b.crest_ew("badge_w", 0.0, 2, 2.0, BADGE)           # 西亭顶站徽
b.crest_ew("badge_e", 7.0, 2, 2.0, BADGE)           # 东亭顶站徽

# =================================================================
# 6. 两辆小车: 蓝车候杆 (人工道) + 绿车通过 (ETC 道)
# =================================================================
b.add("ca_wh_w", "wheel_base", (1.0, 1.0, 0.5), (90, 0, 90), WHEEL)
b.add("ca_wh_e", "wheel_base", (2.0, 1.0, 0.5), (90, 0, 90), WHEEL)
b.flat_rect("ca_top", 1, 0, 1.0, CAR_A, axis="y")   # 蓝车车顶 (y [0,2])
b.crest_ns("ca_cab", 1, 2.0, 1.0, CAR_A)            # 驾驶舱 (车头顶着落杆)
b.add("cb_wh_w", "wheel_base", (4.0, 4.0, 0.5), (90, 0, 90), WHEEL)
b.add("cb_wh_e", "wheel_base", (5.0, 4.0, 0.5), (90, 0, 90), WHEEL)
b.flat_rect("cb_top", 4, 3, 1.0, CAR_B, axis="y")   # 绿车车顶 (y [3,5])
b.crest_ns("cb_cab", 4, 5.0, 1.0, CAR_B)            # 驾驶舱 (车头朝北扬长而去)

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺南半路面 (y [0,2]): 岛柱脚下方板、车道长板, 黄色导流块指向岛头。",
    ["rd_0_0", "rd_0_1", "rd_0_2", "rd_0_4", "rd_0_6",
     "rd_1_0", "rd_1_1", "rd_1_2", "rd_1_4", "rd_1_6"],
    tip="黄色导流块提醒司机: 前方分道 —— 人工靠左, ETC 靠右。",
)
b.step(
    "铺收费岛行 (y [2,3]): 三块橙色亭基分立两条车道之间。",
    ["rd_2_0", "rd_2_1", "rd_2_3", "rd_2_4", "rd_2_6"],
    highlight=["rd_1_0", "rd_1_6"],
    tip="亭基 - 车道 - 亭基 - 车道 - 亭基, 岛式布局一目了然。",
)
b.step(
    "铺北半路面 (y [3,5]): ETC 道脚下用方板 (绿车车轮要吸拼缝)。",
    ["rd_3_0", "rd_3_2", "rd_3_4", "rd_3_5", "rd_3_6",
     "rd_4_0", "rd_4_2", "rd_4_4", "rd_4_5", "rd_4_6"],
    highlight=["rd_2_1", "rd_2_4"],
    tip="过了亭线就是高速 —— 北半路面留给通过的车。",
)
b.step(
    "立西亭一层: 收费窗朝人工道, 背门朝北, 墙脚整边吸亭基沿边。",
    ["bw1_s", "bw1_n", "bw1_w", "bw1_e"],
    highlight=["rd_2_0"],
    tip="司机在西侧驾驶座上递卡 —— 收费窗永远开在车道那一面。",
)
b.step(
    "立中亭一层: 两面都是收费窗 —— 一座亭同时服务两条车道。",
    ["bm1_s", "bm1_n", "bm1_w", "bm1_e"],
    highlight=["rd_2_3"],
    tip="中亭是全站最忙的一座 —— 左手人工道, 右手 ETC 道。",
)
b.step(
    "立东亭一层: 收费窗朝 ETC 道, 三亭一线排开。",
    ["be1_s", "be1_n", "be1_w", "be1_e"],
    highlight=["rd_2_6"],
    tip="三座亭就是三座桥墩 —— 雨棚就要压在它们头顶。",
)
b.step(
    "人工道落杆 + 蓝车候杆: 红色落杆底边整边吸路面、两竖边咬两亭墙棱; "
    "蓝色小车车头顶着落杆, 驾驶舱底边与杆顶沿同线相接。",
    ["bar", "ca_wh_w", "ca_wh_e", "ca_top", "ca_cab"],
    highlight=["bw1_e", "bm1_w"],
    tip="落杆三边受力 —— 剪断任何一条, 其余两条仍锁着它。",
)
b.step(
    "立西亭与中亭二层: 信号窗亮灯 —— 人工道两侧亮红 (停车缴费), "
    "中亭东面亮绿 (ETC 请通行)。",
    ["bw2_s", "bw2_n", "bw2_w", "bw2_e",
     "bm2_s", "bm2_n", "bm2_w", "bm2_e"],
    highlight=["bw1_s", "bm1_s"],
    tip="红灯停绿灯行 —— 信号窗嵌在二层, 司机远远就看见。",
)
b.step(
    "立东亭二层并给三亭压顶: 东亭西面亮绿, 三块灰色压顶方板四边咬墙顶。",
    ["be2_s", "be2_n", "be2_w", "be2_e", "bw_cap", "bm_cap", "be_cap"],
    highlight=["be1_s"],
    tip="压顶把二层墙环锁成箱 —— 亭子这就成了结实的桥墩。",
)
b.step(
    "架雨棚: 两片红色长板短边直接压亭墙顶 (亭即墩, 双端受力零悬挑)。",
    ["can_w", "can_e"],
    highlight=["bw_cap", "bm_cap", "be_cap"],
    tip="没有一根专职立柱 —— 亭-棚-亭锁成两个门式闭环。",
)
b.step(
    "立招牌墙: 中央黄墙底边先吸中亭顶南沿, 两侧蓝墙竖边互咬再借雨棚"
    "前沿分力, 红色徽记骑上墙顶 (顶高 3.87, 全场最高)。",
    ["sign_c", "sign_w", "sign_e", "sign_crest"],
    highlight=["can_w", "can_e"],
    tip="先立中央再立两侧 —— 招牌墙重心正压铰链线, 力矩为零。",
)
b.step(
    "绿车通过 ETC 道 + 亭顶站徽: 绿色小车已过亭线扬长而去, "
    "青色站徽三角骑上东西亭顶外沿。",
    ["cb_wh_w", "cb_wh_e", "cb_top", "cb_cab", "badge_w", "badge_e"],
    highlight=["bm2_e", "be2_w"],
    tip="一停一过 —— 两条车道, 两种通行方式, 一眼看懂。",
)

b.finalize(
    model_id="toll_station_01",
    name="高速收费站",
    name_en="Toll Station 01",
    description=(
        "只用核心九片型的岛式收费站: 与独立门架托雨棚的加油站不同, "
        "收费站没有一根专职立柱 —— 两片雨棚长板的短边直接压在三座"
        "收费亭的墙顶上, 亭子本身就是桥墩, 亭-棚-亭锁成两个门式闭环;"
        " 三座 1x1 两层收费亭分立两条车道之间, 一层收费窗正对司机、"
        "背门朝北, 二层信号窗人工道亮红/ETC 道亮绿; 人工道红色落杆"
        "三边受力横锁车道 (底边吸路面 + 两竖边咬亭墙棱), 蓝色小车"
        "车头正顶着落杆, ETC 道绿色小车已过亭线扬长而去; 雨棚前沿"
        "三片招牌墙托红色徽记直上 3.87 —— 一停一过, 两条车道讲完"
        "两种通行方式。"
    ),
    difficulty=3,
    tags=["城市", "交通", "收费站", "街景", "进阶"],
    min_pieces=69,
    min_steps=12,
)
