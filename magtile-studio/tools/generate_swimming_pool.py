#!/usr/bin/env python3
"""生成模型 data/models/swimming_pool_01.json (游泳池)。

运动主题批 ②: 全库第一座标准泳道游泳池 —— 与滑冰场 (大正方形冰面 +
挡板环) 和水滑梯乐园 (滑梯塔) 的结构逻辑都不同: 水面由 12 片**长方形
泳道板**拼成 6x4 四条泳道 (青/透明相间就是水线), 一圈方板池岸环绕;
西端一座**双柱门架跳水台** (两座双层墙柱托起 2x1 平台, 透明跳板向池面
悬挑), 东端三只直角三角**出发台**踏上池岸, 南岸横楣桥式救生员椅
(两柱托一板), 北岸粉色四坡遮阳伞, 四角泳旗迎风 —— 预备, 跳!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 水面 [0,6]x[0,4]):
  - 泳道水面: 长方形 x12 (四条泳道, 青/透明相间)              12 片
  - 池岸环: 方板 x24 (含四个黄色转角)                         24 片
  - 跳水台 [-2,-1]x[1,3]: 底板 2 + 双柱 4 + 平台 2 + 跳板 1
    + 护栏三角 2                                              11 片
  - 出发台 (东岸): 直角三角楔块 x3                             3 片
  - 救生员椅 (南岸): 底板 2 + 双柱 2 + 桥式座板 1 + 靠背 1      6 片
  - 遮阳伞 (北岸): 等腰四坡伞 x4                               4 片
  - 四角泳旗: 瘦高等腰旗 x4                                    4 片
  合计 64 片, 16 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, 常规+strict 双档零警告):
  - 泳道长方形长边彼此等长互吸 (2 = 2), 水面连成刚性整板;
  - 跳水台是门架结构: 两座双层墙柱 + 平台双片跨接 (南北边各吸
    一柱顶、中缝互吸), 剪断任何一条铰链平台仍有第二条传力路径;
  - 透明跳板单片悬挑: 力矩 15 <= strict 预算 17.5;
  - 救生员椅座板双端简支 (两条短边各吸一柱顶), 是桥不是悬臂;
  - 出发台直角三角双边受力: 竖直角边贴岸沿、水平直角边整边吸
    池岸拼缝, 楔块想翻都翻不动;
  - 最高点跳台护栏尖 2.87 触发 R8 —— 门架 + 中缝环路零单点失效。

用法: python3 tools/generate_swimming_pool.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

LANE_A = "cyan"     # 泳道水面 A
LANE_B = "clear"    # 泳道水面 B (水线相间)
DECK = "gray"       # 池岸
CORNER = "yellow"   # 池岸转角
TOWER = "blue"      # 跳水台柱
PLAT = "gray"       # 跳台平台
SPRING = "clear"    # 透明跳板
RAIL = "red"        # 跳台护栏
BLOCK = "red"       # 出发台楔块
CHAIR = "orange"    # 救生员椅
UMB = "pink"        # 遮阳伞

# =================================================================
# 1. 泳道水面 [0,6]x[0,4]: 四条泳道, 每条 3 片长方形
# =================================================================
for lane in range(4):
    color = LANE_A if lane % 2 == 0 else LANE_B
    for i, x0 in enumerate((0, 2, 4)):
        b.flat_rect(f"wa_{lane}_{i}", x0, lane, 0.0, color, axis="x")

# =================================================================
# 2. 池岸环: 南/北排 (含转角) + 东/西列
# =================================================================
for i, x0 in enumerate(range(-1, 7)):
    b.flat(f"dk_s_{i}", x0, -1, 0.0, CORNER if x0 in (-1, 6) else DECK)
for i, x0 in enumerate(range(-1, 7)):
    b.flat(f"dk_n_{i}", x0, 4, 0.0, CORNER if x0 in (-1, 6) else DECK)
for i, y0 in enumerate(range(4)):
    b.flat(f"dk_w_{i}", -1, y0, 0.0, DECK)
    b.flat(f"dk_e_{i}", 6, y0, 0.0, DECK)

# =================================================================
# 3. 跳水台 [-2,-1]x[1,3]: 底板 + 双柱 (各两层) + 平台 + 跳板 + 护栏
# =================================================================
b.flat("tw_f0", -2, 1, 0.0, DECK)                    # 塔底板
b.flat("tw_f1", -2, 2, 0.0, DECK)
for z0 in (0, 1):
    b.wall_ns(f"tw_s_{z0}", -2, 1.0, z0, TOWER)      # 南柱 (双层)
    b.wall_ns(f"tw_n_{z0}", -2, 3.0, z0, TOWER)      # 北柱 (双层)
b.flat("tw_p0", -2, 1, 2.0, PLAT)                    # 跳台平台 (双片跨接)
b.flat("tw_p1", -2, 2, 2.0, PLAT)
b.flat("board", -1, 1, 2.0, SPRING)                  # 透明跳板 (悬挑向池面)
b.crest_ew("tw_r0", -2.0, 1, 2.0, RAIL)              # 西侧护栏三角
b.crest_ew("tw_r1", -2.0, 2, 2.0, RAIL)

# =================================================================
# 4. 出发台 (东岸): 直角三角楔块, 竖边朝外、斜面朝池
# =================================================================
for i, yl in enumerate((1, 2, 3)):
    b.brace(f"blk_{i}", (7.0, float(yl), 0.0), "-x", BLOCK)

# =================================================================
# 5. 救生员椅 (南岸外 [2,4]x[-2,-1]): 底板 + 双柱 + 桥式座板 + 靠背
# =================================================================
b.flat("ch_f0", 2, -2, 0.0, DECK)
b.flat("ch_f1", 3, -2, 0.0, DECK)
b.wall_ew("ch_w_w", 2.0, -2, 0, CHAIR)               # 西柱
b.wall_ew("ch_w_e", 3.0, -2, 0, CHAIR)               # 东柱
b.flat("ch_seat", 2, -2, 1.0, CHAIR)                 # 座板 (双端简支)
b.crest_ew("ch_back", 3.0, -2, 1.0, RAIL)            # 靠背三角

# =================================================================
# 6. 遮阳伞 (北岸 [4,5]x[4,5]) + 四角泳旗
# =================================================================
UMB_IDS = b.hat4("umb", 4, 4, 0.0, UMB)
b.spire_ns("fl_sw", -1, -1.0, 0.0, "red")
b.spire_ns("fl_se", 6, -1.0, 0.0, "yellow")
b.spire_ns("fl_nw", -1, 5.0, 0.0, "yellow")
b.spire_ns("fl_ne", 6, 5.0, 0.0, "red")

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺泳道 1、2: 6 片长方形水面板, 青色与透明相间就是水线。",
    [f"wa_{lane}_{i}" for lane in (0, 1) for i in range(3)],
    tip="长方形长边彼此等长互吸 (2 = 2), 水面平得能照出人影。",
)
b.step(
    "铺泳道 3、4: 再 6 片, 6x4 四泳道水面合拢。",
    [f"wa_{lane}_{i}" for lane in (2, 3) for i in range(3)],
    highlight=["wa_1_0"],
    tip="四条泳道各就各位 —— 蛙泳、自由泳随便挑。",
)
b.step(
    "铺南池岸: 8 片方板沿水面南沿排开, 两端黄色转角。",
    [f"dk_s_{i}" for i in range(8)],
    highlight=["wa_0_0"],
    tip="池岸方板缝缝相吸, 湿脚也不打滑。",
)
b.step(
    "铺北池岸: 再 8 片, 与南岸对称。",
    [f"dk_n_{i}" for i in range(8)],
    highlight=["wa_3_0"],
    tip="黄色转角是池岸环的四个路标。",
)
b.step(
    "合拢东西池岸: 各 4 片方板, 池岸连成一整圈。",
    [f"dk_w_{i}" for i in range(4)] + [f"dk_e_{i}" for i in range(4)],
    highlight=["dk_s_0", "dk_s_7"],
    tip="池岸环一合拢, 整座泳池连成一个刚性大环。",
)
b.step(
    "铺跳水台底板: 2 片方板贴在西岸外, 中缝互吸。",
    ["tw_f0", "tw_f1"],
    highlight=["dk_w_1"],
    tip="底板就是跳水台的地基, 与池岸整边相连。",
)
b.step(
    "立跳水台一层双柱: 南北各 1 片墙, 底边吸底板边。",
    ["tw_s_0", "tw_n_0"],
    highlight=["tw_f0", "tw_f1"],
    tip="双柱门架是跳水台的骨架 —— 先立稳一层。",
)
b.step(
    "叠跳水台二层双柱: 再 2 片墙, 底边整边吸一层柱顶。",
    ["tw_s_1", "tw_n_1"],
    highlight=["tw_s_0", "tw_n_0"],
    tip="上下柱缝对缝, 高度升到 2 层。",
)
b.step(
    "架跳台平台: 2 片方板跨接双柱顶, 南北边各吸一柱、中缝互吸。",
    ["tw_p0", "tw_p1"],
    highlight=["tw_s_1", "tw_n_1"],
    tip="平台像桥一样双端受力, 剪断一边也不掉 —— 门架的底气。",
)
b.step(
    "搭透明跳板: 1 片方板吸平台东边、向池面悬挑。",
    ["board"],
    highlight=["tw_p0"],
    tip="单片悬挑力矩 15 <= 预算 17.5 —— 跳板弹性十足又不折。",
)
b.step(
    "立跳台护栏: 2 片红色等边三角立上平台西沿。",
    ["tw_r0", "tw_r1"],
    highlight=["tw_p0", "tw_p1"],
    tip="护栏立在平台边铰链线上, 重心正压。",
)
b.step(
    "放出发台: 3 只红色直角三角楔块踏上东岸, 竖边朝外、斜面朝池。",
    ["blk_0", "blk_1", "blk_2"],
    highlight=["dk_e_1"],
    tip="直角三角两条直角边分别吸岸沿拼缝与地面 —— 楔块想翻都翻不动。",
)
b.step(
    "搭救生员椅底架: 南岸外 2 片底板 + 2 片橙色柱墙。",
    ["ch_f0", "ch_f1", "ch_w_w", "ch_w_e"],
    highlight=["dk_s_3"],
    tip="两柱相距一格, 正好架一片座板。",
)
b.step(
    "架救生员椅座板与靠背: 座板两条边各吸一柱顶 (桥式双端受力), "
    "靠背三角立上座板东沿。",
    ["ch_seat", "ch_back"],
    highlight=["ch_w_w", "ch_w_e"],
    tip="居高临下看全场 —— 救生员的位置最安心。",
)
b.step(
    "撑北岸遮阳伞: 4 片粉色等腰三角四坡互吸、伞尖自锁。",
    UMB_IDS,
    highlight=["dk_n_5"],
    tip="四条斜棱两两互吸 —— 伞下是最凉快的观赛位。",
)
b.step(
    "升四角泳旗: 4 面瘦高泳旗立上池岸转角 —— 预备, 跳!",
    ["fl_sw", "fl_se", "fl_nw", "fl_ne"],
    highlight=["dk_s_0", "dk_n_7"],
    tip="泳旗立在转角方板边上, 红黄相映猎猎作响。",
)

b.finalize(
    model_id="swimming_pool_01",
    name="游泳池",
    name_en="Swimming Pool",
    description=(
        "标准泳道游泳池: 12 片长方形拼出 6x4 青透相间的四条泳道, 一圈方板"
        "池岸环绕 (黄色转角升起四面泳旗); 西端双柱门架跳水台托起跨接平台, "
        "透明跳板向池面悬挑, 东端三只直角三角出发台踏上岸沿, 南岸桥式"
        "救生员椅居高守望, 北岸粉色四坡遮阳伞自锁合拢 —— 预备, 跳!"
    ),
    difficulty=3,
    tags=["运动", "游泳", "夏日", "场景"],
    min_pieces=64,
    min_steps=16,
)
