#!/usr/bin/env python3
"""生成模型 data/models/medieval_gate_01.json (中世纪瓮城城门)。

中世纪/城堡主题: 全库第一座瓮城 (barbican) —— 与 castle_drawbridge_01
的 "双塔门楼 + 横楣负空间" 刻意区分, 本作的主角是 "双重城门的纵深
防御": 外郭墙与内城墙前后两道, 各嵌一扇门框方城门, 两道墙之间由
东西短墙合围出瓮城天井 —— 敌人破了外门也只是掉进瓮里; 外墙二层
三扇窗格方箭窗封锁大道, 内墙正中再拔一层门楼戴双等腰尖旗,
天井里一座四棱自锁的橙色烽火炬昼夜不熄。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 城门朝南, 进深沿 +y):
  - 地面 (x [0,7], y [0,4]): 城外大道 / 瓮城天井 / 城内街 4 行     20 片
  - 外郭墙 (y=1): 第 1 层 6 方 + 1 门框方城门, 第 2 层 4 方 +
    3 窗格方箭窗, 顶沿 4 片等边城齿                               18 片
  - 瓮城侧墙 (x=1 / x=6, y 1..3): 单层立墙 x4                      4 片
  - 内城墙 (y=3): 第 1 层 4 方 + 1 门框方, 第 2 层 4 方 + 1 窗格方,
    第 3 层门楼 3 方, 城齿 x3 + 等腰尖旗 x2                       18 片
  - 瓮城烽火炬: 等边四坡锥 x4                                      4 片
  - 城外灌木: 等边三角 x2                                          2 片
  合计 66 片, 12 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, strict 档同样全绿):
  - 两道城墙的第 2 层每片同时吸下层墙顶与左右邻片竖边, 墙体
    连接图处处成环 (下-横-上绕行), 剪断任一条连接力都能绕行;
  - 侧墙竖边吸进外墙/内墙端头墙片的竖边, 外墙-侧墙-内墙锁成
    一个大矩形环 —— 瓮城天井四面受力;
  - 城齿/尖旗重心正压墙顶铰链线 (全部构件与墙共面, 力矩为零);
  - 烽火炬四条斜棱两两互吸自锁成环, 三条基线踩天井拼缝。

用法: python3 tools/generate_medieval_gate.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

GRASS = "green"     # 城外草地
ROAD = "gray"       # 石板大道
COURT = "gray"      # 瓮城天井
STONE = "gray"      # 城墙石砌
UPPER = "blue"      # 城墙第 2 层
GATE = "orange"     # 门框方城门
SLIT = "clear"      # 窗格方箭窗
CREST = "yellow"    # 城齿
FLAG = "red"        # 尖旗
TORCH = "orange"    # 烽火炬

# =================================================================
# 1. 地面 (x [0,7], y [0,4]): 4 行, 城门大道纵贯正中 (x [3,5])
# =================================================================
# 行 y0 (城外大道) 与 行 y3 (城内街): 拼缝布局相同
for r, ys in (("g0", 0), ("g3", 3)):
    field = GRASS
    b.flat_rect(f"{r}_a", 0, ys, 0.0, field)             # [0,2]
    b.flat(f"{r}_b", 2, ys, 0.0, field)                  # [2,3]
    b.flat_rect(f"{r}_c", 3, ys, 0.0, ROAD)              # [3,5] 大道
    b.flat(f"{r}_d", 5, ys, 0.0, field)                  # [5,6]
    b.flat(f"{r}_e", 6, ys, 0.0, field)                  # [6,7]
# 行 y1 / y2 (瓮城天井): 需要 x=1 / x=6 拼缝支侧墙
for r, ys in (("g1", 1), ("g2", 2)):
    b.flat(f"{r}_a", 0, ys, 0.0, GRASS)                  # [0,1]
    b.flat_rect(f"{r}_b", 1, ys, 0.0, COURT)             # [1,3]
    b.flat(f"{r}_c", 3, ys, 0.0, ROAD)                   # [3,4]
    b.flat_rect(f"{r}_d", 4, ys, 0.0, COURT)             # [4,6]
    b.flat(f"{r}_e", 6, ys, 0.0, GRASS)                  # [6,7]

# =================================================================
# 2. 外郭墙 (y=1, x [0,7]): 两层 + 城齿, 正中门框方城门
# =================================================================
for x in (0, 1, 2, 4, 5, 6):
    b.wall_ns(f"ow1_{x}", x, 1.0, 0, STONE)
b.add("ow1_gate", "door_frame", (3.5, 1.0, 0.5), (90, 0, 0), GATE)
for x in (0, 2, 4, 6):
    b.wall_ns(f"ow2_{x}", x, 1.0, 1, UPPER)
for x in (1, 3, 5):
    b.add(f"ow2_{x}", "window_square", (x + 0.5, 1.0, 1.5), (90, 0, 0), SLIT)
for x in (0, 2, 4, 6):
    b.crest_ns(f"oc_{x}", x, 1.0, 2.0, CREST)

# =================================================================
# 3. 瓮城侧墙 (x=1 / x=6, y 1..3): 单层, 与两道城墙锁成大矩形环
# =================================================================
for y in (1, 2):
    b.wall_ew(f"sw_w_{y}", 1.0, y, 0, STONE)
    b.wall_ew(f"sw_e_{y}", 6.0, y, 0, STONE)

# =================================================================
# 4. 内城墙 (y=3, x [1,6]): 两层 + 第 3 层门楼 + 尖旗
# =================================================================
for x in (1, 2, 4, 5):
    b.wall_ns(f"iw1_{x}", x, 3.0, 0, STONE)
b.add("iw1_gate", "door_frame", (3.5, 3.0, 0.5), (90, 0, 0), GATE)
for x in (1, 2, 4, 5):
    b.wall_ns(f"iw2_{x}", x, 3.0, 1, UPPER)
b.add("iw2_3", "window_square", (3.5, 3.0, 1.5), (90, 0, 0), SLIT)
b.crest_ns("ic_1", 1, 3.0, 2.0, CREST)
b.crest_ns("ic_5", 5, 3.0, 2.0, CREST)
for x in (2, 3, 4):
    b.wall_ns(f"iw3_{x}", x, 3.0, 2, STONE)
b.spire_ns("isp_w", 2, 3.0, 3.0, FLAG)
b.crest_ns("ic_3", 3, 3.0, 3.0, CREST)
b.spire_ns("isp_e", 4, 3.0, 3.0, FLAG)

# =================================================================
# 5. 瓮城烽火炬 (天井 [5,6]x[1,2]) + 城外灌木
# =================================================================
TORCH_IDS = b.hat4("torch", 5, 1, 0.0, TORCH, shape="equilateral_triangle")
b.crest_ns("bush_w", 2, 0.0, 0.0, GRASS)
b.crest_ns("bush_e", 5, 0.0, 0.0, GRASS)

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺城外大道一行 (y [0,1]): 5 片, 灰色石板道正对城门。",
    ["g0_a", "g0_b", "g0_c", "g0_d", "g0_e"],
    tip="大道居中 (x [3,5]) —— 外门、内门都会开在这条轴线上。",
)
b.step(
    "铺瓮城天井第一行 (y [1,2]): 5 片, 外郭墙就踩这条南缝。",
    ["g1_a", "g1_b", "g1_c", "g1_d", "g1_e"],
    highlight=["g0_c"],
    tip="x=1 与 x=6 的拼缝留给瓮城侧墙 —— 布局从地面就开始。",
)
b.step(
    "铺天井第二行 (y [2,3]): 5 片, 与第一行拼缝完全对齐。",
    ["g2_a", "g2_b", "g2_c", "g2_d", "g2_e"],
    highlight=["g1_b"],
    tip="两行天井合成瓮城的瓮底 —— 敌人破了外门就掉进这里。",
)
b.step(
    "铺城内街一行 (y [3,4]): 5 片, 内城墙踩它的南缝。",
    ["g3_a", "g3_b", "g3_c", "g3_d", "g3_e"],
    highlight=["g2_c"],
    tip="城里城外各一行, 两道城墙夹住中间的天井。",
)
b.step(
    "立外郭墙第 1 层: 6 片石墙 + 正中 1 扇门框方外城门。",
    ["ow1_0", "ow1_1", "ow1_2", "ow1_gate", "ow1_4", "ow1_5", "ow1_6"],
    highlight=["g0_c", "g1_c"],
    tip="每片底边吸大道拼缝、侧竖边吸邻片 —— 门框方就是外城门。",
)
b.step(
    "叠外郭墙第 2 层: 4 片蓝墙与 3 扇透明窗格方箭窗相间。",
    ["ow2_0", "ow2_1", "ow2_2", "ow2_3", "ow2_4", "ow2_5", "ow2_6"],
    highlight=["ow1_gate"],
    tip="每片同时吸下层墙顶与邻片竖边 —— 连接处处成环。",
)
b.step(
    "装外墙城齿: 4 片黄色等边三角骑上墙顶。",
    ["oc_0", "oc_2", "oc_4", "oc_6"],
    highlight=["ow2_0", "ow2_6"],
    tip="城齿与墙共面, 重心正压墙顶铰链 —— 力矩为零。",
)
b.step(
    "立瓮城侧墙: 东西各 2 片, 竖边咬住外墙端头。",
    ["sw_w_1", "sw_w_2", "sw_e_1", "sw_e_2"],
    highlight=["ow1_0", "ow1_6"],
    tip="侧墙把外墙与内墙锁成一个大矩形环 —— 瓮城四面受力。",
)
b.step(
    "立内城墙第 1 层: 4 片石墙 + 正中 1 扇门框方内城门。",
    ["iw1_1", "iw1_2", "iw1_gate", "iw1_4", "iw1_5"],
    highlight=["sw_w_2", "sw_e_2"],
    tip="内门与外门同轴 —— 两道门框方一进一出, 纵深防御。",
)
b.step(
    "叠内城墙第 2 层并装两角城齿: 门洞正上是窗格方了望窗。",
    ["iw2_1", "iw2_2", "iw2_3", "iw2_4", "iw2_5", "ic_1", "ic_5"],
    highlight=["iw1_gate"],
    tip="了望窗紧盯外门 —— 瓮城里的一举一动尽收眼底。",
)
b.step(
    "起门楼第 3 层: 正中 3 片再拔一层, 顶上双尖旗夹一片城齿。",
    ["iw3_2", "iw3_3", "iw3_4", "isp_w", "ic_3", "isp_e"],
    highlight=["iw2_3"],
    tip="第 3 层三片竖边互咬, 尖旗直上 5 格 —— 全城最高点。",
)
b.step(
    "点烽火炬 + 栽城外灌木 —— 瓮城城门落成!",
    TORCH_IDS + ["bush_w", "bush_e"],
    highlight=["g1_d", "g0_a"],
    tip="烽火炬四棱互吸自锁; 手指当信使, 穿外门-过瓮城-进内门!",
)

b.finalize(
    model_id="medieval_gate_01",
    name="中世纪瓮城城门",
    name_en="Medieval Barbican Gate 01",
    description=(
        "全库第一座瓮城: 外郭墙与内城墙前后两道、各嵌一扇门框方城门,"
        " 东西短墙把两道墙锁成大矩形环围出瓮城天井 —— 破了外门也只是"
        "掉进瓮里; 外墙二层三扇窗格方箭窗封锁大道, 内墙正中再拔一层"
        "门楼戴双等腰尖旗, 天井烽火炬四棱自锁昼夜不熄。双重城门、"
        "矩形大环、箭窗封锁 —— 中世纪纵深防御一课学会。"
    ),
    difficulty=3,
    tags=["中世纪", "城堡", "瓮城", "城门", "进阶"],
    min_pieces=64,
    min_steps=12,
)
