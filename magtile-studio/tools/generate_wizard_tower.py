#!/usr/bin/env python3
"""生成模型 data/models/wizard_tower_01.json (魔法师观星塔)。

童话/奇幻主题 4/4: 全库第一座 "玻璃观星室" 高塔 —— 与
castle_tower_01 (土丘城塞 + 角楼) / observatory_01 / clock_tower_01
的结构逻辑刻意区分: 本作的主角是 "塔顶全透明", 2x2 方塔三层平地
拔起 (南门 + 三面窗格方魔法窗), 塔顶平台的东北角再起一间 1x1
观星室 —— 四面全部用窗格方, 360 度透明视野, 戴等腰四坡巫师帽
(帽尖 5.94 全场最高); 平台西南角一支等腰水晶星径尖碑直上 5.0,
两片星芒骑沿口; 塔前一座独立的两层星门 —— 双柱托双方板门楣
(竖边纯剪互锁), 楣顶双星旗, 门下石板道直通塔门。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 塔门朝南):
  - 地面 (x [0,6], y [0,6]): 草地 + 石板道 6 行                 26 片
  - 塔身 (x [2,4], y [3,5], z 0..3): 三层墙环 (门框方塔门 x1 +
    窗格方魔法窗 x4)                                            24 片
  - 塔顶平台 (z=3): 方板 x4                                      4 片
  - 观星室 (x [3,4], y [4,5], z 3..4): 窗格方 x4 (全透明)         4 片
  - 巫师帽: 等腰四坡锥 x4 (帽尖 5.94)                             4 片
  - 星径尖碑 x1 (顶 5.0) + 星芒 x2                                3 片
  - 星门 (y=1): 双柱 x4 (两层) + 方板门楣 x2 (纯剪) + 星旗 x2     8 片
  - 灌木 x2                                                      2 片
  合计 75 片, 12 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, strict 档同样全绿):
  - 塔身每层 8 片墙环四角互吸, 层层成环; 平台每片同时吸两段
    墙顶与邻板拼缝 —— 多路受力无单点失效;
  - 观星室四扇窗格方竖边互咬成环, 底边一线双吸 (平台沿 + 第 3
    层墙顶); 窗格方外框物理与实心方全同, 透明只是视觉;
  - 星门两片方板门楣外端竖边吸进双柱上节竖棱 (纯剪), 中缝互吸,
    柱-楣-柱-地面锁成门式刚架环, 剪断任一端仍可绕行;
  - 尖碑/星芒/星旗与承托面共面, 重心正压铰链线, 力矩为零。

用法: python3 tools/generate_wizard_tower.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

GRASS = "green"     # 草地
PATH = "gray"       # 石板道
BODY = "blue"       # 塔身 1~2 层
BODY3 = "purple"    # 塔身第 3 层
DOOR = "orange"     # 门框方塔门
WIN = "clear"       # 窗格方魔法窗
DECK = "gray"       # 塔顶平台
GLASS = "clear"     # 观星室
HAT = "purple"      # 巫师帽
SPIKE = "cyan"      # 星径尖碑
STAR = "yellow"     # 星芒 / 星旗
GATE = "blue"       # 星门双柱
BEAM = "cyan"       # 星门门楣
BUSH = "green"      # 灌木

# =================================================================
# 1. 地面 (x [0,6], y [0,6]): 6 行, 石板道纵贯正中 (x [2,4])
# =================================================================
b.flat_rect("wz0_a", 0, 0, 0.0, GRASS)
b.flat_rect("wz0_b", 2, 0, 0.0, PATH)
b.flat_rect("wz0_c", 4, 0, 0.0, GRASS)

b.flat("wz1_a", 0, 1, 0.0, GRASS)
b.flat("wz1_b", 1, 1, 0.0, GRASS)
b.flat_rect("wz1_c", 2, 1, 0.0, PATH)
b.flat("wz1_d", 4, 1, 0.0, GRASS)
b.flat("wz1_e", 5, 1, 0.0, GRASS)

b.flat_rect("wz2_a", 0, 2, 0.0, GRASS)
b.flat_rect("wz2_b", 2, 2, 0.0, PATH)
b.flat_rect("wz2_c", 4, 2, 0.0, GRASS)

for x in range(6):
    b.flat(f"wz3_{chr(97 + x)}", x, 3, 0.0, GRASS)
for x in range(6):
    b.flat(f"wz4_{chr(97 + x)}", x, 4, 0.0, GRASS)

b.flat_rect("wz5_a", 0, 5, 0.0, GRASS)
b.flat_rect("wz5_b", 2, 5, 0.0, GRASS)
b.flat_rect("wz5_c", 4, 5, 0.0, GRASS)

# =================================================================
# 2. 塔身 (x [2,4], y [3,5], z 0..3): 三层墙环
# =================================================================
b.add("tw1_s1", "door_frame", (2.5, 3.0, 0.5), (90, 0, 0), DOOR)
b.wall_ns("tw1_s2", 3, 3.0, 0, BODY)
b.wall_ew("tw1_e1", 4.0, 3, 0, BODY)
b.wall_ew("tw1_e2", 4.0, 4, 0, BODY)
b.wall_ns("tw1_n1", 2, 5.0, 0, BODY)
b.wall_ns("tw1_n2", 3, 5.0, 0, BODY)
b.wall_ew("tw1_w1", 2.0, 3, 0, BODY)
b.wall_ew("tw1_w2", 2.0, 4, 0, BODY)

b.wall_ns("tw2_s1", 2, 3.0, 1, BODY)
b.add("tw2_s2", "window_square", (3.5, 3.0, 1.5), (90, 0, 0), WIN)
b.wall_ew("tw2_e1", 4.0, 3, 1, BODY)
b.wall_ew("tw2_e2", 4.0, 4, 1, BODY)
b.add("tw2_n1", "window_square", (2.5, 5.0, 1.5), (90, 0, 0), WIN)
b.wall_ns("tw2_n2", 3, 5.0, 1, BODY)
b.wall_ew("tw2_w1", 2.0, 3, 1, BODY)
b.wall_ew("tw2_w2", 2.0, 4, 1, BODY)

b.wall_ns("tw3_s1", 2, 3.0, 2, BODY3)
b.wall_ns("tw3_s2", 3, 3.0, 2, BODY3)
b.add("tw3_e1", "window_square", (4.0, 3.5, 2.5), (90, 0, 90), WIN)
b.wall_ew("tw3_e2", 4.0, 4, 2, BODY3)
b.wall_ns("tw3_n1", 2, 5.0, 2, BODY3)
b.wall_ns("tw3_n2", 3, 5.0, 2, BODY3)
b.wall_ew("tw3_w1", 2.0, 3, 2, BODY3)
b.add("tw3_w2", "window_square", (2.0, 4.5, 2.5), (90, 0, 90), WIN)

# =================================================================
# 3. 塔顶平台 (z=3) + 观星室 (x [3,4], y [4,5], z 3..4) + 巫师帽
# =================================================================
b.flat("dk_sw", 2, 3, 3.0, DECK)
b.flat("dk_se", 3, 3, 3.0, DECK)
b.flat("dk_nw", 2, 4, 3.0, DECK)
b.flat("dk_ne", 3, 4, 3.0, DECK)

b.add("ob_s", "window_square", (3.5, 4.0, 3.5), (90, 0, 0), GLASS)
b.add("ob_w", "window_square", (3.0, 4.5, 3.5), (90, 0, 90), GLASS)
b.add("ob_n", "window_square", (3.5, 5.0, 3.5), (90, 0, 0), GLASS)
b.add("ob_e", "window_square", (4.0, 4.5, 3.5), (90, 0, 90), GLASS)
HAT_IDS = b.hat4("hat", 3, 4, 4.0, HAT)

# =================================================================
# 4. 星径尖碑 + 星芒 (平台西南沿口)
# =================================================================
b.spire_ns("spike", 2, 3.0, 3.0, SPIKE)
b.crest_ns("star_s", 3, 3.0, 3.0, STAR)
b.crest_ew("star_w", 2.0, 4, 3.0, STAR)

# =================================================================
# 5. 星门 (y=1): 双柱两层 + 双方板门楣 (纯剪) + 星旗
# =================================================================
b.wall_ns("gp_w0", 1, 1.0, 0, GATE)
b.wall_ns("gp_w1", 1, 1.0, 1, GATE)
b.wall_ns("gp_e0", 4, 1.0, 0, GATE)
b.wall_ns("gp_e1", 4, 1.0, 1, GATE)
b.wall_ns("gb_w", 2, 1.0, 1, BEAM)
b.wall_ns("gb_e", 3, 1.0, 1, BEAM)
b.crest_ns("gflag_w", 2, 1.0, 2.0, STAR)
b.crest_ns("gflag_e", 3, 1.0, 2.0, STAR)

# =================================================================
# 6. 灌木
# =================================================================
b.crest_ns("bush_w", 0, 1.0, 0.0, BUSH)
b.crest_ns("bush_e", 5, 1.0, 0.0, BUSH)

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺场地南段两行 (y [0,2]): 8 片, 石板道从场边一直铺向塔门。",
    ["wz0_a", "wz0_b", "wz0_c", "wz1_a", "wz1_b", "wz1_c", "wz1_d", "wz1_e"],
    tip="石板道 (x [2,4]) 上会先跨一座星门, 再进塔门。",
)
b.step(
    "铺中段两行 (y [2,4]): 9 片, 塔基一行全用小方板留出格线。",
    ["wz2_a", "wz2_b", "wz2_c",
     "wz3_a", "wz3_b", "wz3_c", "wz3_d", "wz3_e", "wz3_f"],
    highlight=["wz1_c"],
    tip="x=2/3/4 的拼缝就是塔身墙脚 —— 布局从地面开始。",
)
b.step(
    "铺北段两行 (y [4,6]): 9 片, 场地合拢。",
    ["wz4_a", "wz4_b", "wz4_c", "wz4_d", "wz4_e", "wz4_f",
     "wz5_a", "wz5_b", "wz5_c"],
    highlight=["wz3_c"],
    tip="6x6 场地铺满 —— 高塔和星门都有了地基。",
)
b.step(
    "立塔身第 1 层: 8 片墙环, 南面是橙色门框方塔门。",
    ["tw1_s1", "tw1_s2", "tw1_e1", "tw1_e2",
     "tw1_n1", "tw1_n2", "tw1_w1", "tw1_w2"],
    highlight=["wz2_b", "wz3_c"],
    tip="每片底边吸格线、转角竖边互咬 —— 2x2 墙环闭合。",
)
b.step(
    "叠塔身第 2 层: 南面与北面各嵌一扇窗格方魔法窗。",
    ["tw2_s1", "tw2_s2", "tw2_e1", "tw2_e2",
     "tw2_n1", "tw2_n2", "tw2_w1", "tw2_w2"],
    highlight=["tw1_s1"],
    tip="每片同时吸下层墙顶与邻片竖边 —— 连接处处成环。",
)
b.step(
    "叠塔身第 3 层: 东面与西面各嵌一扇魔法窗, 塔身升到 3 格。",
    ["tw3_s1", "tw3_s2", "tw3_e1", "tw3_e2",
     "tw3_n1", "tw3_n2", "tw3_w1", "tw3_w2"],
    highlight=["tw2_s2", "tw2_n1"],
    tip="四面窗户各朝一方 —— 魔法师在每层都要看星星。",
)
b.step(
    "盖塔顶平台: 4 片方板, 每片同时吸两段墙顶与邻板拼缝。",
    ["dk_sw", "dk_se", "dk_nw", "dk_ne"],
    highlight=["tw3_s1", "tw3_n2"],
    tip="平台就是观星室的新地面 —— 多路受力无单点失效。",
)
b.step(
    "起观星室: 东北角 4 扇窗格方竖边互咬成环, 360 度全透明。",
    ["ob_s", "ob_w", "ob_n", "ob_e"],
    highlight=["dk_ne"],
    tip="每扇底边一线双吸 (平台沿 + 墙顶) —— 玻璃房也要成环。",
)
b.step(
    "戴巫师帽: 4 片等腰三角斜棱两两互吸自锁 (帽尖 5.94)。",
    HAT_IDS,
    highlight=["ob_s", "ob_e"],
    tip="紫色尖帽是全场最高点 —— 巫师的帽子永远最尖。",
)
b.step(
    "立星径尖碑与星芒: 平台西南沿口一碑两星。",
    ["spike", "star_s", "star_w"],
    highlight=["dk_sw"],
    tip="尖碑直上 5.0, 与帽尖遥相呼应; 三件全部重心正压沿口。",
)
b.step(
    "立星门双柱: 东西各 2 片叠两层, 夹住石板道。",
    ["gp_w0", "gp_w1", "gp_e0", "gp_e1"],
    highlight=["wz1_b", "wz1_d"],
    tip="柱脚吸道旁拼缝 —— 星门是进塔前的第一道仪式。",
)
b.step(
    "架星门门楣、插星旗、栽灌木 —— 魔法师观星塔落成!",
    ["gb_w", "gb_e", "gflag_w", "gflag_e", "bush_w", "bush_e"],
    highlight=["gp_w1", "gp_e1"],
    tip="两片门楣外端竖边纯剪锁进柱身、中缝互吸 —— 门式刚架成环。",
)

b.finalize(
    model_id="wizard_tower_01",
    name="魔法师观星塔",
    name_en="Wizard Stargazing Tower 01",
    description=(
        "全库第一座玻璃观星室高塔: 2x2 方塔三层平地拔起 (门框方塔门"
        " + 四扇窗格方魔法窗各朝一方), 塔顶平台东北角再起 1x1 观星室"
        " —— 四面全用窗格方, 360 度透明视野, 戴等腰四坡巫师帽 (帽尖"
        " 5.94 全场最高); 平台西南一支水晶尖碑直上 5.0, 星芒骑沿;"
        " 塔前独立星门双柱托双方板门楣 (竖边纯剪互锁), 楣顶双星旗。"
        "全透明顶室、门式刚架星门、层层墙环 —— 一座塔学会三种环。"
    ),
    difficulty=3,
    tags=["童话", "奇幻", "魔法师", "高塔", "进阶"],
    min_pieces=72,
    min_steps=12,
)
