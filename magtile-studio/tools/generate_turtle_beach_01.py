#!/usr/bin/env python3
"""生成模型 data/models/turtle_beach_01.json (海龟孵化保护站)。

海洋探险主题批 3/3: 全库第一座野生动物保护场景 —— 与救生站
(高脚椅 + 遮阳伞) 和海底实验室 (舱体廊道) 再次错开: 本作的主角
是"三窝正在孵化的海龟卵": 三座开顶孵化围栏排成一列 (只围不盖,
清色卵床铺在栏心), 三只绿色小海龟正沿着岸线拼缝排队爬向大海;
北侧红白警示护栏拦住游客, 科普牌窗格方立在沙缝上, 值班小屋
瘦高四坡尖顶望着整片沙滩 —— 全库唯一的"开顶围栏阵 + 下海队列"。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 海在南, 沙滩在北):
  - 海面 (y [0,1]): 蓝色长板 x3                                   3 片
  - 小海龟 x3: 绿色等边三角骑岸线拼缝, 排队下海                   3 片
  - 沙滩 (x [0,6], y [1,4]): 三行单位方板 x18 (含清色卵床 x3)    18 片
  - 孵化围栏 x3 (1x1 开顶, z 0..1): 每座四墙合环                 12 片
  - 值班小屋 (x [0,1], y [3,4], z 0..1): 四墙 (含门框) + 瘦高
    四坡尖顶 (顶尖 2.94)                                          8 片
  - 警示护栏 x3 (y=4, 红白相间) + 科普牌窗格方 x1                 4 片
  合计 48 片, 8 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 孵化围栏是开顶墙环: 只围不盖, 四角竖边互咬照样闭环, 墙脚
    踩单位方板拼缝整边吸合;
  - 值班小屋四墙合环, 瘦高四坡锥顶直接骑墙顶: 四条斜棱两两互吸
    自锁成环, 底边各吸一道墙顶 —— 无盖板照样封顶;
  - 小海龟/科普牌/护栏底边整边吸沙缝, 护栏竖边逐片成链;
    剪断任何一条装饰连接最多失联 1 片 (< 3), R8 单点失效通过;
  - 沙滩拼缝纪律: 全部沙板为单位方板, 围栏/小屋/护栏墙脚线
    处处有等长拼缝可吸, 行行等边互吸全场连通。

用法: python3 tools/generate_turtle_beach_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

SEA = "blue"        # 海面
TURTLE = "green"    # 小海龟
SAND = "yellow"     # 沙滩
EGG = "clear"       # 卵床
PEN = "green"       # 孵化围栏
HUT = "clear"       # 值班小屋墙
DOOR = "orange"     # 小屋门
ROOF = "green"      # 小屋尖顶
FENCE_A = "red"     # 警示护栏 (红白相间)
FENCE_B = "clear"
SIGN = "cyan"       # 科普牌


def wall_ns_t(tid, tile_type, x0, y, z0, color):
    b.add(tid, tile_type, (x0 + 0.5, y, z0 + 0.5), (90, 0, 0), color)


# =================================================================
# 1. 海面 (y [0,1]) + 沙滩三行 (y [1,4]): 全单位方板
# =================================================================
b.flat_rect("sea_0", 0, 0, 0.0, SEA)
b.flat_rect("sea_2", 2, 0, 0.0, SEA)
b.flat_rect("sea_4", 4, 0, 0.0, SEA)
for x0 in range(6):
    b.flat(f"sand_{x0}_1", x0, 1, 0.0, SAND)          # 岸线行
for x0 in range(6):
    color = EGG if x0 in (1, 3, 5) else SAND          # 卵床铺在栏心
    b.flat(f"sand_{x0}_2", x0, 2, 0.0, color)         # 围栏行
for x0 in range(6):
    b.flat(f"sand_{x0}_3", x0, 3, 0.0, SAND)          # 护栏行
b.crest_ns("turtle_a", 1, 1.0, 0.0, TURTLE)           # 排队下海
b.crest_ns("turtle_b", 3, 1.0, 0.0, TURTLE)
b.crest_ns("turtle_c", 5, 1.0, 0.0, TURTLE)

# =================================================================
# 2. 孵化围栏 x3 (x [1,2] / [3,4] / [5,6], y [2,3], z 0..1):
#    开顶墙环, 四角竖边互咬
# =================================================================
for i, x0 in enumerate((1, 3, 5), start=1):
    b.wall_ns(f"pen{i}_s", x0, 2.0, 0, PEN)
    b.wall_ns(f"pen{i}_n", x0, 3.0, 0, PEN)
    b.wall_ew(f"pen{i}_w", float(x0), 2, 0, PEN)
    b.wall_ew(f"pen{i}_e", float(x0 + 1), 2, 0, PEN)

# =================================================================
# 3. 值班小屋 (x [0,1], y [3,4], z 0..1): 四墙 + 瘦高四坡尖顶
# =================================================================
wall_ns_t("hut_s", "door_frame", 0, 3.0, 0, DOOR)     # 门朝围栏
b.wall_ns("hut_n", 0, 4.0, 0, HUT)
b.wall_ew("hut_w", 0.0, 3, 0, HUT)
b.wall_ew("hut_e", 1.0, 3, 0, HUT)
HUT_ROOF = b.hat4("hut_roof", 0, 3, 1.0, ROOF)        # 顶尖 2.94

# =================================================================
# 4. 警示护栏 x3 (y=4) + 科普牌 (y=3 沙缝)
# =================================================================
b.wall_ns("fence_3", 3, 4.0, 0, FENCE_A)
b.wall_ns("fence_4", 4, 4.0, 0, FENCE_B)
b.wall_ns("fence_5", 5, 4.0, 0, FENCE_A)
wall_ns_t("sign", "window_square", 2, 3.0, 0, SIGN)   # 科普牌

# =================================================================
# 教程步骤 (8 步)
# =================================================================
b.step(
    "铺海面: 三条蓝色长板短边互吸, 海在南边等着小海龟。",
    ["sea_0", "sea_2", "sea_4"],
    tip="孵化季的夜晚, 小海龟破壳后会朝着大海的方向爬。",
)
b.step(
    "铺岸线行沙板, 三只小海龟骑上拼缝: 排队下海!",
    [f"sand_{x0}_1" for x0 in range(6)]
    + ["turtle_a", "turtle_b", "turtle_c"],
    highlight=["sea_0"],
    tip="海龟底边整边吸住岸线拼缝 —— 一二三, 冲向大海!",
)
b.step(
    "铺围栏行: 栏心三格用清色卵床, 其余黄色沙板。",
    [f"sand_{x0}_2" for x0 in range(6)],
    highlight=["sand_1_1"],
    tip="清色方板就是卵床 —— 每窝一百多枚卵埋在温暖的沙里。",
)
b.step(
    "铺护栏行沙板: 再来六片, 行行等边互吸。",
    [f"sand_{x0}_3" for x0 in range(6)],
    highlight=["sand_0_2"],
    tip="沙滩连成一整张网 —— 围栏、小屋、护栏都要踩它的拼缝。",
)
b.step(
    "围前两窝孵化栏: 每座四墙合环, 开顶不盖 —— 卵要晒太阳。",
    ["pen1_s", "pen1_n", "pen1_w", "pen1_e",
     "pen2_s", "pen2_n", "pen2_w", "pen2_e"],
    highlight=["sand_1_2"],
    tip="开顶墙环四角竖边互咬照样闭合 —— 是保护罩, 不是盖子。",
)
b.step(
    "围第三窝孵化栏, 立科普牌: 窗格方插在沙缝上面向游客。",
    ["pen3_s", "pen3_n", "pen3_w", "pen3_e", "sign"],
    highlight=["pen1_s"],
    tip="牌上写着: 请勿靠近卵床, 夜间请关灯 —— 灯光会带偏小海龟。",
)
b.step(
    "搭值班小屋: 四墙合环门朝围栏, 瘦高四坡尖顶骑墙顶自锁。",
    ["hut_s", "hut_n", "hut_w", "hut_e"] + HUT_ROOF,
    highlight=["sand_0_3"],
    tip="尖顶四条斜棱两两互咬 —— 顶尖 2.94, 巡护员在这里值夜班。",
)
b.step(
    "装警示护栏收尾: 红白相间三片, 竖边成链拦住游客。",
    ["fence_3", "fence_4", "fence_5"],
    highlight=["sign", "turtle_a"],
    tip="护栏挡住人, 挡不住海风 —— 保护站开站, 等第一窝破壳!",
)

b.finalize(
    model_id="turtle_beach_01",
    name="海龟孵化保护站",
    name_en="Turtle Beach Station 01",
    description=(
        "只用核心九片型的野生动物保护场景: 与救生站的高脚瞭望椅和"
        "海底实验室的舱体廊道都不同, 主角是三窝正在孵化的海龟卵 —— "
        "三座开顶孵化围栏排成一列 (只围不盖, 四角竖边互咬照样闭环, "
        "清色卵床铺在栏心), 三只绿色小海龟骑着岸线拼缝排队爬向大海; "
        "北侧红白警示护栏竖边成链拦住游客, 青色科普牌窗格方插在沙缝"
        "上, 值班小屋门框朝栏、瘦高四坡尖顶斜棱互咬自锁 —— 嘘, "
        "第一窝马上就要破壳了!"
    ),
    difficulty=2,
    tags=["海洋", "探险", "海龟", "自然", "保护站"],
    min_pieces=48,
    min_steps=8,
)
