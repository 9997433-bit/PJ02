#!/usr/bin/env python3
"""生成模型 data/models/greenhouse_01.json (温室花房)。

第三批模型 ⑥: 田园主题 —— 全库第一座"屋顶即墙"的建筑:
没有一面竖直的墙, 8 片透明长方形从地面直接斜起 60 度, 在 1.73 格
高处对脊合掌, 组成四榀连跨的 A 字帐篷玻璃房; 北山墙用 4 片等边
三角形拼成"三角力"(大三角剖成 4 个小三角), 南山墙只留两角、
中央是菱形负空间大门。屋里 8 块彩色苗床已经种上一排番茄,
屋外配冷床箱、雨水桶、围栏与花丛。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 花园地面: 前院 4 + 东西小路 8 + 后檐 2 + 苗床 8            22 片
  - 苗床作物: 中缝一排 番茄/幼苗 交替 4 株                       4 片
  - A 字玻璃顶: 东西各 4 片透明长方形斜起 60 度对脊合掌           8 片
  - 山墙: 北面三角力 4 片 + 南面门角 2 片 (中央菱形门洞)          6 片
  - 冷床箱: 4 墙 + 透明盖板;  雨水桶: 4 墙 + 盖板               10 片
  - 围栏 4 + 花丛 2                                              6 片
  合计 56 片, 16 个教程步骤, 4 种磁力片形状。

几何要点:
  - 长方形短边 (长 1) 落地吸住地砖拼缝, 长边 (长 2) 做斜脊:
    水平投影恰 1 格、脊高 2*sin60 = 1.732, 两坡顶边在脊线互吸;
  - 大三角山墙边长 2, 恰好 = 4 片单位等边三角形 (三正一倒),
    倒三角是"三角力"的锁芯; 南面省去锁芯与顶角就得到菱形门洞;
  - 山墙斜边与玻璃坡长边共线贴合 (长度 1 对 2, 不吸但严丝合缝)。

用法: python3 tools/generate_greenhouse.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

RIDGE_Z = 1.732051         # 脊高 2*sin60
MID_Z = RIDGE_Z / 2        # 山墙腰线高 0.866025
# 温室占 [3,5] x [1,5]: 西檐线 x=3, 脊线 x=4, 东檐线 x=5, 四跨 y 1..5

# =================================================================
# 1. 花园地面
# =================================================================
for i in range(4):                       # 前院 (y 0..1)
    b.flat(f"yard_{i}", 2 + i, 0, 0, "green")
for j in range(4):                       # 西小路 + 东小路 (y 1..5)
    b.flat(f"path_w{j}", 2, 1 + j, 0, "gray")
    b.flat(f"path_e{j}", 5, 1 + j, 0, "gray")
for i in range(4):                       # 后檐草地 (y 5..6)
    b.flat(f"back_{i}", 2 + i, 5, 0, "green")
BED_COLORS = ["red", "yellow", "pink", "green"]
for j in range(4):                       # 苗床两列 (x 3..4 / 4..5)
    b.flat(f"bed_w{j}", 3, 1 + j, 0, BED_COLORS[j])
    b.flat(f"bed_e{j}", 4, 1 + j, 0, BED_COLORS[(j + 1) % 4])

# =================================================================
# 2. 苗床作物: 沿中缝 x=4 立一排 (脊线正下方, 高度富余)
# =================================================================
b.crest_ew("plant_0", 4, 1, 0, "green")
b.spire_ew("plant_1", 4, 2, 0, "red")     # 结果的番茄
b.crest_ew("plant_2", 4, 3, 0, "green")
b.spire_ew("plant_3", 4, 4, 0, "red")

# =================================================================
# 3. A 字玻璃顶: 每跨东西两片透明长方形对脊合掌
# =================================================================
for j in range(4):
    y0, y1 = 1.0 + j, 2.0 + j
    b.place_edge(f"glass_w{j}", "rectangle", 1,
                 (3.0, y0, 0.0), (3.0, y1, 0.0), (0.5, 0, 0.866025), "clear")
    b.place_edge(f"glass_e{j}", "rectangle", 1,
                 (5.0, y1, 0.0), (5.0, y0, 0.0), (-0.5, 0, 0.866025), "clear")

# =================================================================
# 4. 山墙: 北面三角力 (4 片合成边长 2 的大三角), 南面菱形门洞
# =================================================================
b.place_tri("gable_n_l", "equilateral_triangle",
            (3.0, 5.0, 0.0), (4.0, 5.0, 0.0), (3.5, 5.0, MID_Z), "green")
b.place_tri("gable_n_r", "equilateral_triangle",
            (4.0, 5.0, 0.0), (5.0, 5.0, 0.0), (4.5, 5.0, MID_Z), "green")
b.place_tri("gable_n_c", "equilateral_triangle",
            (4.5, 5.0, MID_Z), (3.5, 5.0, MID_Z), (4.0, 5.0, 0.0), "clear")
b.place_tri("gable_n_t", "equilateral_triangle",
            (3.5, 5.0, MID_Z), (4.5, 5.0, MID_Z), (4.0, 5.0, RIDGE_Z),
            "yellow")
b.place_tri("gable_s_l", "equilateral_triangle",
            (3.0, 1.0, 0.0), (4.0, 1.0, 0.0), (3.5, 1.0, MID_Z), "green")
b.place_tri("gable_s_r", "equilateral_triangle",
            (4.0, 1.0, 0.0), (5.0, 1.0, 0.0), (4.5, 1.0, MID_Z), "green")

# =================================================================
# 5. 冷床箱 (西南) 与雨水桶 (东南)
# =================================================================
b.wall_ns("frame_s", 2, 0, 0, "orange")     # 冷床箱 [2,3]x[0,1]
b.wall_ns("frame_n", 2, 1, 0, "orange")
b.wall_ew("frame_w", 2, 0, 0, "orange")
b.wall_ew("frame_e", 3, 0, 0, "orange")
b.flat("frame_lid", 2, 0, 1, "clear")
b.wall_ns("barrel_s", 5, 0, 0, "blue")      # 雨水桶 [5,6]x[0,1]
b.wall_ns("barrel_n", 5, 1, 0, "blue")
b.wall_ew("barrel_w", 5, 0, 0, "blue")
b.wall_ew("barrel_e", 6, 0, 0, "blue")
b.flat("barrel_lid", 5, 0, 1, "gray")

# =================================================================
# 6. 围栏与花丛
# =================================================================
b.crest_ns("fence_0", 3, 0, 0, "yellow")    # 大门正前的两段围栏
b.crest_ns("fence_1", 4, 0, 0, "yellow")
b.crest_ew("flower_w", 2, 1, 0, "purple")   # 小路外沿花丛
b.crest_ew("flower_e", 6, 1, 0, "pink")

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺前院: 4 片绿色方板沿南边排开, 这是温室的门前院子。",
    ["yard_0", "yard_1", "yard_2", "yard_3"],
    tip="先铺地再起屋 —— 所有立起的片都要吸在地砖拼缝上。",
)
b.step(
    "铺东西小路与后檐: 两列灰色小路夹住温室地块, 北面 4 片绿色"
    "方板收边。",
    ["path_w0", "path_w1", "path_w2", "path_w3",
     "path_e0", "path_e1", "path_e2", "path_e3",
     "back_0", "back_1", "back_2", "back_3"],
    highlight=["yard_1"],
    tip="小路的内沿 (x=3 与 x=5) 就是玻璃坡将要落地的檐线。",
)
b.step(
    "铺苗床西列: 4 片彩色方板从南到北排进温室。",
    ["bed_w0", "bed_w1", "bed_w2", "bed_w3"],
    highlight=["path_w0"],
    tip="红-黄-粉-绿, 每块苗床种不同的菜。",
)
b.step(
    "铺苗床东列: 再排 4 片, 两列苗床间留出 x=4 的中缝。",
    ["bed_e0", "bed_e1", "bed_e2", "bed_e3"],
    highlight=["bed_w0"],
    tip="这条中缝在脊线正下方 —— 下一步作物就种在缝上。",
)
b.step(
    "种作物: 沿中缝立 4 株 幼苗-番茄-幼苗-番茄 (等边/等腰交替)。"
    "务必先种菜再盖顶 —— 盖完顶手就伸不进去了!",
    ["plant_0", "plant_1", "plant_2", "plant_3"],
    highlight=["bed_w1", "bed_e1"],
    tip="作物在脊线正下方, 头顶还有富余不会顶到玻璃。",
)
b.step(
    "立第一、二跨玻璃: 4 片透明长方形短边落地吸住檐线拼缝, "
    "东西两两在脊线对脊合掌。",
    ["glass_w0", "glass_e0", "glass_w1", "glass_e1"],
    highlight=["path_w0", "path_e0"],
    tip="像搭帐篷: 先扶稳西片, 东片一合掌顶边互吸就稳了。",
)
b.step(
    "立第三、四跨玻璃: 再合掌两跨, 相邻跨的长边整边互吸, "
    "四榀连成通长玻璃顶。",
    ["glass_w2", "glass_e2", "glass_w3", "glass_e3"],
    highlight=["glass_w1", "glass_e1"],
    tip="每片新玻璃同时吸住地缝与邻跨长边 —— 越搭越稳。",
)
b.step(
    "起北山墙下排: 2 片绿色等边三角形立在北檐线上, 尖朝上。",
    ["gable_n_l", "gable_n_r"],
    highlight=["back_1", "back_2"],
    tip="两片的斜边正好躺在玻璃坡的斜线上, 严丝合缝。",
)
b.step(
    "嵌北山墙锁芯: 1 片透明倒三角尖朝下卡进两片之间 —— "
    "这就是'三角力'拼法的锁芯。",
    ["gable_n_c"],
    highlight=["gable_n_l", "gable_n_r"],
    tip="倒三角两条边同时吸住左右两片的内斜边。",
)
b.step(
    "封北山墙顶角: 1 片黄色等边三角形骑上锁芯, 尖顶正抵脊线 —— "
    "边长 2 的大三角由 4 片小三角拼成!",
    ["gable_n_t"],
    highlight=["gable_n_c"],
    tip="大三角剖四小片, 是磁力片放大形状的标准技法。",
)
b.step(
    "立南山墙门角: 只放左右 2 片绿色三角形, 中央不放 —— "
    "留出一个菱形的负空间大门。",
    ["gable_s_l", "gable_s_r"],
    highlight=["yard_1", "yard_2"],
    tip="从大门望进去: 苗床、番茄、玻璃顶一览无余。",
)
b.step(
    "砌冷床箱四壁: 4 片橙色正方形在前院西侧围成育苗箱。",
    ["frame_s", "frame_n", "frame_w", "frame_e"],
    highlight=["yard_0", "path_w0"],
    tip="四片墙的竖边两两互吸, 围成结实的方箱。",
)
b.step(
    "盖冷床玻璃盖: 1 片透明方板盖住箱口, 四边同时吸合。",
    ["frame_lid"],
    highlight=["frame_s", "frame_n"],
    tip="冷床箱是温室的'幼儿园', 小苗先在这里过冬。",
)
b.step(
    "砌雨水桶: 前院东侧 4 片蓝色正方形围桶, 灰色盖板封口。",
    ["barrel_s", "barrel_n", "barrel_w", "barrel_e", "barrel_lid"],
    highlight=["yard_3", "path_e0"],
    tip="屋檐的雨水顺坡流进桶里 —— 浇菜全靠它。",
)
b.step(
    "竖大门围栏: 2 片黄色等边三角形立在菱形大门正前方的院沿上。",
    ["fence_0", "fence_1"],
    highlight=["yard_1", "yard_2"],
    tip="底边与院沿整边吸合, 冷床箱与雨水桶就是两端的'门柱'。",
)
b.step(
    "种路边花丛: 紫、粉两株花立在小路外沿拼缝上 —— 温室花房开张!",
    ["flower_w", "flower_e"],
    highlight=["path_w0", "path_e0"],
    tip="从南面看: 菱形大门两侧花丛相迎, A 字玻璃顶闪闪发光。",
)

b.finalize(
    model_id="greenhouse_01",
    name="温室花房",
    name_en="Greenhouse 01",
    description=(
        "田园主题: 全库第一座'屋顶即墙'的建筑 —— 没有一面竖直的墙, "
        "8 片透明长方形短边落地、斜起 60 度在 1.73 格高处对脊合掌, "
        "组成四榀连跨的 A 字帐篷玻璃房; 北山墙是 4 片小等边拼成的"
        "边长 2 大三角 (倒三角锁芯), 南山墙省去锁芯留出菱形负空间"
        "大门。苗床上番茄与幼苗必须先种后盖顶 —— 一堂装配顺序课。"
        "屋外配冷床箱、雨水桶、围栏与花丛。"
    ),
    difficulty=3,
    tags=["田园", "温室", "A字帐篷", "三角力", "进阶"],
    min_pieces=55,
    min_steps=16,
)
