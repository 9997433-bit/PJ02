#!/usr/bin/env python3
"""生成模型 data/models/art_gallery_01.json (白盒双光庭美术馆)。

博物馆/艺术主题 1/4: 全库第一座 L 形平面建筑 —— 与 museum_01
(玻璃金字塔 + 古典三段式) 和 library_building_01 (方盒大厅 + 东端书塔)
的结构逻辑刻意区分: 美术馆不用金字塔也不起塔楼, 而是把两翼展厅折成
一个 L, 转角内侧凹出前庭广场; 屋面开出两个 1x1 负空间光庭,
每个光庭由 4 片透明窗格方在洞口四沿立成采光鼓身、顶上等边四坡锥
自锁收头 —— 天光正对馆内展品; 外墙嵌红黄蓝窗格方色块 (蒙德里安
式立面), 馆内两面彩色展墙与迎宾三角雕塑先布展后封顶 (R7b 装配
顺序即策展顺序); 门口一片透明雨棚单边铰链外挑 (力矩 15 < strict
预算 17.5)。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 入口朝东):
  - 地面 (x [0,6], y [0,6]): 广场 + 两翼展厅地板 6 行         25 片
  - L 形外墙 (z 0..1): 南翼 4 + 主翼东南 4 + 北墙 4 + 西墙 4  16 片
  - 馆内布展: 彩色展墙 x2 + 迎宾三角雕塑 x1 (先布展后封顶)     3 片
  - 屋面 (z=1): L 形屋面留两个 1x1 光庭洞口                    6 片
  - 光庭 x2: 采光鼓身窗格方 x4 + 等边四坡锥 x4 (锥尖 2.71)    16 片
  - 入口雨棚 x1 + 前庭雕塑 (等边三角 + 等腰尖塔) x2            3 片
  合计 69 片, 13 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (R1~R8 全绿, strict 档零警告):
  - L 形墙体在转角处竖边互吸, 屋面每片同时压墙顶与邻板拼缝,
    墙-屋面-展墙顶缝处处成环;
  - 光庭鼓身: 南/西两面直接竖叠外墙顶 (纯压), 东/北两面吸屋面
    洞口沿边, 四角竖边互吸closed环; 四坡锥四棱两两自锁;
  - 展墙底边吸地板拼缝、顶边吸屋面拼缝 (双边受力), 先布展后
    封顶满足 R7b 装配可达;
  - 雨棚单边铰链: 力矩 30x0.5=15 g·单位 < strict 预算 17.5。

用法: python3 tools/generate_art_gallery.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

PLAZA = "gray"      # 前庭广场
FLOOR = "cyan"      # 展厅地板
PATH = "orange"     # 入馆步道
WALL = "gray"       # 白盒外墙
ART_R = "red"       # 蒙德里安色块 / 展墙
ART_B = "blue"
ART_Y = "yellow"
GLASS = "clear"     # 光庭玻璃 / 雨棚
ROOF = "gray"       # 屋面

# =================================================================
# 1. 地面 (x [0,6], y [0,6]): 广场 + 展厅地板, 拼缝对准全部墙线
# =================================================================
b.flat_rect("g0_a", 0, 0, 0.0, PLAZA)
b.flat_rect("g0_b", 2, 0, 0.0, PLAZA)
b.flat("g0_c", 4, 0, 0.0, PLAZA)          # 单方: 拼缝给前庭三角雕塑
b.flat("g0_d", 5, 0, 0.0, PLAZA)

b.flat("g1_a", 0, 1, 0.0, PLAZA)
b.flat("g1_b", 1, 1, 0.0, FLOOR)          # 南翼展厅 (拼缝给三角雕塑)
b.flat("g1_c", 2, 1, 0.0, FLOOR)
b.flat_rect("g1_d", 3, 1, 0.0, PATH)      # 入馆步道
b.flat("g1_e", 5, 1, 0.0, PLAZA)

b.flat("g2_a", 0, 2, 0.0, PLAZA)
b.flat_rect("g2_b", 1, 2, 0.0, FLOOR)
b.flat("g2_c", 3, 2, 0.0, PLAZA)
b.flat("g2_d", 4, 2, 0.0, PLAZA)          # 单方: 拼缝给等腰尖塔
b.flat("g2_e", 5, 2, 0.0, PLAZA)

b.flat("g3_a", 0, 3, 0.0, PLAZA)
b.flat_rect("g3_b", 1, 3, 0.0, FLOOR)     # 主翼展厅
b.flat_rect("g3_c", 3, 3, 0.0, FLOOR)
b.flat("g3_d", 5, 3, 0.0, PLAZA)

b.flat("g4_a", 0, 4, 0.0, PLAZA)
b.flat_rect("g4_b", 1, 4, 0.0, FLOOR)
b.flat_rect("g4_c", 3, 4, 0.0, FLOOR)
b.flat("g4_d", 5, 4, 0.0, PLAZA)

b.flat_rect("g5_a", 0, 5, 0.0, PLAZA)
b.flat_rect("g5_b", 2, 5, 0.0, PLAZA)
b.flat_rect("g5_c", 4, 5, 0.0, PLAZA)

# =================================================================
# 2. L 形外墙 (z 0..1): 蒙德里安式立面, 入口门框方朝东
# =================================================================
# 南翼 (x [1,3], y [1,3]): 南墙 + 东墙 (门)
b.wall_ns("wS_1", 1, 1.0, 0, WALL)
b.add("wS_2", "window_square", (2.5, 1.0, 0.5), (90, 0, 0), ART_R)
b.add("door", "door_frame", (3.0, 1.5, 0.5), (90, 0, 90), GLASS)
b.add("wE_b", "window_square", (3.0, 2.5, 0.5), (90, 0, 90), ART_B)
# 主翼东南角 (x [3,5], y [3,5]): 南墙 + 东墙
b.wall_ns("wA_s1", 3, 3.0, 0, WALL)
b.add("wA_s2", "window_square", (4.5, 3.0, 0.5), (90, 0, 0), ART_Y)
b.wall_ew("wA_e1", 5.0, 3, 0, WALL)
b.add("wA_e2", "window_square", (5.0, 4.5, 0.5), (90, 0, 90), ART_R)
# 北墙 (y=5, x [1,5])
b.wall_ns("wN_1", 1, 5.0, 0, WALL)
b.add("wN_2", "window_square", (2.5, 5.0, 0.5), (90, 0, 0), ART_B)
b.wall_ns("wN_3", 3, 5.0, 0, WALL)
b.wall_ns("wN_4", 4, 5.0, 0, WALL)
# 西墙 (x=1, y [1,5])
b.wall_ew("wW_1", 1.0, 1, 0, WALL)
b.add("wW_2", "window_square", (1.0, 2.5, 0.5), (90, 0, 90), ART_Y)
b.wall_ew("wW_3", 1.0, 3, 0, WALL)
b.wall_ew("wW_4", 1.0, 4, 0, WALL)

# =================================================================
# 3. 馆内布展 (先布展后封顶): 两面彩色展墙 + 迎宾三角雕塑
# =================================================================
b.wall_ns("exhib_r", 2, 4.0, 0, ART_R)    # 主翼红展墙
b.wall_ns("exhib_b", 3, 4.0, 0, ART_B)    # 主翼蓝展墙
b.crest_ns("statue", 1, 2.0, 0.0, ART_R)  # 南翼光庭下的三角雕塑

# =================================================================
# 4. 屋面 (z=1): L 形屋面, 留两个 1x1 光庭洞口
#    光庭 A (x [3,4], y [4,5]) / 光庭 B (x [1,2], y [1,2])
# =================================================================
b.flat("rfB1", 2, 1, 1.0, ROOF)
b.flat_rect("rfB2", 1, 2, 1.0, ROOF)
b.flat_rect("rfA1", 1, 3, 1.0, ROOF)
b.flat_rect("rfA2", 3, 3, 1.0, ROOF)
b.flat_rect("rfA3", 1, 4, 1.0, ROOF)
b.flat("rfA4", 4, 4, 1.0, ROOF)

# =================================================================
# 5. 光庭 x2: 透明窗格方鼓身 + 等边四坡锥收头 (锥尖 2.71)
# =================================================================
# 光庭 B (南翼): 南/西面竖叠外墙顶, 东/北面吸屋面洞口沿
b.add("lantB_s", "window_square", (1.5, 1.0, 1.5), (90, 0, 0), GLASS)
b.add("lantB_e", "window_square", (2.0, 1.5, 1.5), (90, 0, 90), GLASS)
b.add("lantB_n", "window_square", (1.5, 2.0, 1.5), (90, 0, 0), GLASS)
b.add("lantB_w", "window_square", (1.0, 1.5, 1.5), (90, 0, 90), GLASS)
LANTB_HAT = b.hat4("lantB_hat", 1, 1, 2.0, ART_B, shape="equilateral_triangle")
# 光庭 A (主翼): 北面竖叠北墙顶, 其余三面吸屋面洞口沿
b.add("lantA_s", "window_square", (3.5, 4.0, 1.5), (90, 0, 0), GLASS)
b.add("lantA_e", "window_square", (4.0, 4.5, 1.5), (90, 0, 90), GLASS)
b.add("lantA_n", "window_square", (3.5, 5.0, 1.5), (90, 0, 0), GLASS)
b.add("lantA_w", "window_square", (3.0, 4.5, 1.5), (90, 0, 90), GLASS)
LANTA_HAT = b.hat4("lantA_hat", 3, 4, 2.0, ART_Y, shape="equilateral_triangle")

# =================================================================
# 6. 入口雨棚 + 前庭雕塑
# =================================================================
b.flat("canopy", 3, 1, 1.0, GLASS)        # 单边铰链外挑, 力矩 15
b.crest_ns("plaza_tri", 4, 1.0, 0.0, ART_R)
b.spire_ns("plaza_spire", 4, 2.0, 0.0, ART_B)

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺南侧地面 (y [0,2]): 9 片, 橙色步道直指入口。",
    ["g0_a", "g0_b", "g0_c", "g0_d", "g1_a", "g1_b", "g1_c", "g1_d", "g1_e"],
    tip="青色是展厅地板, 灰色是室外广场 —— 步道尽头就是大门。",
)
b.step(
    "铺中部地面 (y [2,4]): 9 片, 主翼展厅地板开始出现。",
    ["g2_a", "g2_b", "g2_c", "g2_d", "g2_e", "g3_a", "g3_b", "g3_c", "g3_d"],
    highlight=["g1_b"],
    tip="美术馆平面是一个 L: 南翼窄、主翼宽, 转角凹出前庭。",
)
b.step(
    "铺北侧地面 (y [4,6]): 7 片, 场地合拢。",
    ["g4_a", "g4_b", "g4_c", "g4_d", "g5_a", "g5_b", "g5_c"],
    highlight=["g3_b"],
    tip="6x6 场地铺满, 所有墙线都压在地板拼缝上。",
)
b.step(
    "立南翼墙与入口: 门框方大门朝东, 红蓝色块嵌进立面。",
    ["wS_1", "wS_2", "door", "wE_b"],
    highlight=["g1_c"],
    tip="彩色窗格方就是蒙德里安式的立面构成 —— 墙即作品。",
)
b.step(
    "立主翼东南墙: 4 片, 黄色与红色色块继续排布。",
    ["wA_s1", "wA_s2", "wA_e1", "wA_e2"],
    highlight=["wS_1"],
    tip="南翼与主翼的墙在 (3,3) 转角竖边互吸。",
)
b.step(
    "立北墙 (y=5): 4 片, 蓝色色块居中。",
    ["wN_1", "wN_2", "wN_3", "wN_4"],
    highlight=["wA_e1"],
    tip="x [3,4] 这片墙顶稍后要竖叠光庭鼓身 —— 位置别放错。",
)
b.step(
    "立西墙 (x=1): 4 片, L 形外墙闭合。",
    ["wW_1", "wW_2", "wW_3", "wW_4"],
    highlight=["wN_1"],
    tip="转角竖边互吸闭环, 轻推整圈墙应一起联动。",
)
b.step(
    "馆内布展: 红蓝展墙立上主翼, 三角雕塑放进南翼光庭正下方。",
    ["exhib_r", "exhib_b", "statue"],
    highlight=["g4_b", "g2_b"],
    tip="先布展后封顶 —— 装配顺序就是策展顺序 (R7b)。",
)
b.step(
    "盖南翼屋面: 2 片, 留出 1x1 光庭洞口 (x [1,2], y [1,2])。",
    ["rfB1", "rfB2"],
    highlight=["wS_1", "wW_1"],
    tip="洞口是负空间 —— 天光从这里落到三角雕塑上。",
)
b.step(
    "盖主翼屋面: 4 片, 留出光庭洞口 (x [3,4], y [4,5])。",
    ["rfA1", "rfA2", "rfA3", "rfA4"],
    highlight=["exhib_r", "exhib_b"],
    tip="每片屋面同时压墙顶与邻板拼缝, 展墙顶边也被锁进屋面。",
)
b.step(
    "起南翼光庭: 4 片透明鼓身 + 4 片等边锥自锁收头。",
    ["lantB_s", "lantB_w", "lantB_e", "lantB_n"] + LANTB_HAT,
    highlight=["rfB1", "rfB2"],
    tip="南/西两面竖叠外墙顶, 东/北两面吸屋面洞口沿 —— 四角闭环。",
)
b.step(
    "起主翼光庭: 4 片透明鼓身 + 4 片等边锥自锁收头。",
    ["lantA_n", "lantA_e", "lantA_s", "lantA_w"] + LANTA_HAT,
    highlight=["rfA2", "rfA4"],
    tip="两个光庭一蓝一黄 —— 从外面看, 屋顶长出两颗水晶。",
)
b.step(
    "挂入口雨棚、立前庭雕塑 —— 白盒双光庭美术馆开馆!",
    ["canopy", "plaza_tri", "plaza_spire"],
    highlight=["door"],
    tip="雨棚单边铰链外挑一格, 前庭三角与尖塔是馆外的第一件展品。",
)

b.finalize(
    model_id="art_gallery_01",
    name="白盒双光庭美术馆",
    name_en="Art Gallery 01",
    description=(
        "全库第一座 L 形平面建筑: 两翼展厅折成 L, 转角凹出前庭广场; "
        "屋面开两个 1x1 负空间光庭, 透明窗格方鼓身四角闭环、等边四坡锥"
        "自锁收头, 天光正对馆内展品; 外墙嵌红黄蓝窗格方色块 (蒙德里安式"
        "立面), 馆内彩色展墙与三角雕塑先布展后封顶 —— 装配顺序即策展"
        "顺序; 门口透明雨棚单边铰链外挑, 前庭立着馆外第一件雕塑。"
    ),
    difficulty=3,
    tags=["博物馆", "艺术", "美术馆", "光庭", "进阶"],
    min_pieces=66,
    min_steps=13,
)
