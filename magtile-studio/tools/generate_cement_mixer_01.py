#!/usr/bin/env python3
"""生成模型 data/models/cement_mixer_01.json (混凝土搅拌车)。

建筑/工地主题: 与自卸卡车 (尾梁桥 + 双铰链斗板) 完全不同的载具
结构 —— 搅拌车的核心是 "满罐体 + 双进料斗 + 卸料溜槽" 三件套:
3x2 罐体墙环压在四轮底盘上, 罐顶两座等边四坡进料斗对缝互锁,
车尾 30 度溜槽从底盘南沿直下浇筑仓 —— 仓位是地坪上预留的三格
空位, 三面模板墙围出正在浇筑的条形基础。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 车头朝东):
  - 工地地坪 8x5 (x [0,8], y [0,5]): 南缘 x [3,6] 留浇筑仓      22 片
  - 浇筑仓模板: 三面立墙 (西/南 x3/东) 围出条形基础             5 片
  - 车轮底座 x4 + 底盘 (方板 x2 + 长板 x3)                      9 片
  - 罐体 (x [3,6], y [2,4], z 1..2): 墙环 x10 + 罐顶板 x3       13 片
  - 进料斗: 等边四坡斗 x2 (对缝互锁)                            8 片
  - 驾驶室 (x [6,7], y [2,4], z 1..2): 挡风 x2 + 车门窗 x2 +
    舱顶 x2 + 警灯 x1                                           7 片
  - 卸料溜槽: 30 度长板 x1 (顶边吸底盘南沿, 坡尾落浇筑仓)        1 片
  - 场景: 雪糕筒 x2 + 告示牌 (方板+红三角)                      4 片
  合计 69 片, 14 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点:
  - 底盘五板中长板两端整边压轮组顶, 方板对缝互吸 —— 溜槽顶边
    正好独占一条方板南沿的单位边;
  - 罐体墙环四角互吸闭环, 罐顶板同时压墙顶与邻板拼缝;
  - 进料斗四条斜棱两两互吸自锁, 双斗在罐顶中缝对底互吸;
  - 溜槽顶边一线双吸 (底盘方板南沿 + 轮组顶), 坡尾落在预留
    浇筑仓的实地上, 不与模板墙相碰。

用法: python3 tools/generate_cement_mixer_01.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

YARD = "gray"       # 工地地坪
LAWN = "green"      # 北缘绿化带
MOLD = "yellow"     # 浇筑仓模板墙
WHEEL = "gray"      # 车轮底座
CHASSIS = "gray"    # 底盘
CAB = "blue"        # 驾驶室
GLASS = "clear"     # 挡风 / 车门窗
DRUM = "orange"     # 搅拌罐体
DRUMTOP = "gray"    # 罐顶板
HOPPER = "orange"   # 进料斗
CHUTE = "gray"      # 卸料溜槽
CONE = "red"        # 雪糕筒
SIGN = "yellow"     # 告示牌

# =================================================================
# 1. 工地地坪 8x5: 南缘 x [3,6] 留浇筑仓 (溜槽坡尾落位)
# =================================================================
b.flat_rect("g0_a", 0, 0, 0.0, YARD)
b.flat("g0_b", 2, 0, 0.0, YARD)
b.flat("g0_c", 6, 0, 0.0, YARD)
b.flat("g0_d", 7, 0, 0.0, YARD)
b.flat("g1_a", 0, 1, 0.0, YARD)
b.flat_rect("g1_b", 1, 1, 0.0, YARD)
b.flat_rect("g1_c", 3, 1, 0.0, YARD)
b.flat_rect("g1_d", 5, 1, 0.0, YARD)
b.flat("g1_e", 7, 1, 0.0, YARD)
b.flat_rect("g2_a", 0, 2, 0.0, YARD)
b.flat_rect("g2_b", 2, 2, 0.0, YARD)
b.flat_rect("g2_c", 4, 2, 0.0, YARD)
b.flat_rect("g2_d", 6, 2, 0.0, YARD)
b.flat_rect("g3_a", 0, 3, 0.0, YARD)
b.flat_rect("g3_b", 2, 3, 0.0, YARD)
b.flat_rect("g3_c", 4, 3, 0.0, YARD)
b.flat_rect("g3_d", 6, 3, 0.0, YARD)
b.flat("g4_a", 0, 4, 0.0, LAWN)
b.flat_rect("g4_b", 1, 4, 0.0, LAWN)
b.flat_rect("g4_c", 3, 4, 0.0, LAWN)
b.flat_rect("g4_d", 5, 4, 0.0, LAWN)
b.flat("g4_e", 7, 4, 0.0, LAWN)

# =================================================================
# 2. 浇筑仓模板 (x [3,6], y [0,1]): 三面立墙, 北面敞口迎溜槽
# =================================================================
b.wall_ew("pw_w", 3.0, 0, 0, MOLD)
b.wall_ns("pw_s0", 3, 0.0, 0, MOLD)
b.wall_ns("pw_s1", 4, 0.0, 0, MOLD)
b.wall_ns("pw_s2", 5, 0.0, 0, MOLD)
b.wall_ew("pw_e", 6.0, 0, 0, MOLD)

# =================================================================
# 3. 车轮底座 x4 + 底盘 z=1 (车身 [3,7] x [2,4])
# =================================================================
b.add("wb_ws", "wheel_base", (4.0, 2.0, 0.5), (90, 0, 0), WHEEL)
b.add("wb_wn", "wheel_base", (4.0, 4.0, 0.5), (90, 0, 0), WHEEL)
b.add("wb_es", "wheel_base", (6.0, 2.0, 0.5), (90, 0, 0), WHEEL)
b.add("wb_en", "wheel_base", (6.0, 4.0, 0.5), (90, 0, 0), WHEEL)
b.flat_rect("ch_c", 5, 2, 1.0, CHASSIS)
b.flat_rect("ch_d", 5, 3, 1.0, CHASSIS)
b.flat("ch_a2", 4, 2, 1.0, CHASSIS)
b.flat("ch_a1", 3, 2, 1.0, CHASSIS)
b.flat_rect("ch_b", 3, 3, 1.0, CHASSIS)

# =================================================================
# 4. 罐体 (x [3,6], y [2,4], z 1..2): 墙环 x10
# =================================================================
b.wall_ew("dr_w1", 3.0, 2, 1, DRUM)
b.wall_ew("dr_w2", 3.0, 3, 1, DRUM)
b.wall_ns("dr_s3", 3, 2.0, 1, DRUM)
b.wall_ns("dr_s4", 4, 2.0, 1, DRUM)
b.wall_ns("dr_s5", 5, 2.0, 1, DRUM)
b.wall_ns("dr_n3", 3, 4.0, 1, DRUM)
b.wall_ns("dr_n4", 4, 4.0, 1, DRUM)
b.wall_ns("dr_n5", 5, 4.0, 1, DRUM)
b.wall_ew("dr_e1", 6.0, 2, 1, DRUM)
b.wall_ew("dr_e2", 6.0, 3, 1, DRUM)

# =================================================================
# 5. 驾驶室 (x [6,7], y [2,4], z 1..2): 罐体东墙兼驾驶室后壁
# =================================================================
b.wall_ew("cb_e1", 7.0, 2, 1, GLASS)
b.wall_ew("cb_e2", 7.0, 3, 1, GLASS)
b.add("cb_s", "window_square", (6.5, 2.0, 1.5), (90, 0, 0), GLASS)
b.add("cb_n", "window_square", (6.5, 4.0, 1.5), (90, 0, 0), GLASS)

# =================================================================
# 6. 罐顶板 x3 + 驾驶室舱顶 x2 + 警灯
# =================================================================
b.flat_rect("dt_3", 3, 2, 2.0, DRUMTOP, axis="y")
b.flat_rect("dt_4", 4, 2, 2.0, DRUMTOP, axis="y")
b.flat_rect("dt_5", 5, 2, 2.0, DRUMTOP, axis="y")
b.flat("cr_1", 6, 2, 2.0, CAB)
b.flat("cr_2", 6, 3, 2.0, CAB)
b.crest_ns("beacon", 6, 2.0, 2.0, "red")

# =================================================================
# 7. 进料斗: 双等边四坡斗对缝互锁 (罐顶西段)
# =================================================================
b.hat4("hop_a", 3, 2, 2.0, HOPPER, shape="equilateral_triangle")
b.hat4("hop_b", 3, 3, 2.0, HOPPER, shape="equilateral_triangle")

# =================================================================
# 8. 卸料溜槽: 顶边吸底盘南沿, 坡尾落浇筑仓
# =================================================================
b.ramp("chute", "-y", 2.0, 4, 1.0, CHUTE)

# =================================================================
# 9. 场景: 雪糕筒 + 告示牌
# =================================================================
b.crest_ns("cone_a", 0, 2.0, 0.0, CONE)
b.crest_ns("cone_b", 7, 1.0, 0.0, CONE)
b.wall_ns("sign", 0, 5.0, 0, SIGN)
b.crest_ns("sign_top", 0, 5.0, 1.0, "red")

# =================================================================
# 教程步骤 (14 步)
# =================================================================
b.step(
    "铺地坪南两行 (y [0,2]): 9 片, 南缘 x [3,6] 留出三格浇筑仓。",
    ["g0_a", "g0_b", "g0_c", "g0_d",
     "g1_a", "g1_b", "g1_c", "g1_d", "g1_e"],
    tip="留空的三格是条形基础的位置 —— 溜槽坡尾一会儿正落在这里。",
)
b.step(
    "铺地坪中两行 (y [2,4]): 8 片长板对缝铺开, 搅拌车就停在这两行上。",
    ["g2_a", "g2_b", "g2_c", "g2_d",
     "g3_a", "g3_b", "g3_c", "g3_d"],
    highlight=["g1_b", "g1_d"],
    tip="长板端缝错开铺, 轮组的吸附线就在这两行的行缝上。",
)
b.step(
    "铺北缘绿化带 (y [4,5]): 5 片, 地坪合拢成 8x5。",
    ["g4_a", "g4_b", "g4_c", "g4_d", "g4_e"],
    highlight=["g3_a"],
    tip="工地北缘的一线绿 —— 文明施工从围挡内开始。",
)
b.step(
    "立浇筑仓模板: 三面黄色立墙围出条形基础, 北面敞口迎溜槽。",
    ["pw_w", "pw_s0", "pw_s1", "pw_s2", "pw_e"],
    highlight=["g0_b", "g0_c"],
    tip="西/东模板底边吸地坪格边, 南排三片竖边逐片咬合。",
)
b.step(
    "装四只车轮: 两对车轮底座立在行缝上, 底边整边咬住长板拼缝。",
    ["wb_ws", "wb_wn", "wb_es", "wb_en"],
    highlight=["g1_c", "g4_c"],
    tip="车头朝东 —— 东侧一对轮上将架驾驶室。",
)
b.step(
    "架底盘: 先压东段两条长板, 再对缝补西段两方板与北长板。",
    ["ch_c", "ch_d", "ch_a2", "ch_a1", "ch_b"],
    highlight=["wb_ws", "wb_en"],
    tip="长板长边整边压轮组顶; 西段用方板 —— 南沿留出溜槽的单位吸附边。",
)
b.step(
    "砌罐体西墙与南墙: 5 片橙色立墙踩底盘拼缝。",
    ["dr_w1", "dr_w2", "dr_s3", "dr_s4", "dr_s5"],
    highlight=["ch_a1", "ch_a2"],
    tip="罐体是搅拌车的主角 —— 每片底边吸缝、竖边咬邻片。",
)
b.step(
    "砌罐体北墙与东墙: 5 片, 罐体墙环闭合。",
    ["dr_n3", "dr_n4", "dr_n5", "dr_e1", "dr_e2"],
    highlight=["dr_w2", "dr_s5"],
    tip="东墙一墙两用: 朝西是罐尾, 朝东就是驾驶室后壁。",
)
b.step(
    "装驾驶室: 车头两片透明挡风, 南北两扇窗格方车门窗。",
    ["cb_e1", "cb_e2", "cb_s", "cb_n"],
    highlight=["ch_c", "dr_e1"],
    tip="挡风底边吸底盘长板短边, 车门窗竖边与前后壁互咬。",
)
b.step(
    "盖罐顶与舱顶: 3 条罐顶板横跨罐体, 2 片舱顶盖驾驶室。",
    ["dt_3", "dt_4", "dt_5", "cr_1", "cr_2"],
    highlight=["dr_s4", "cb_s"],
    tip="罐顶板两端压南北墙顶, 板板对缝互吸 —— 罐体锁成箱形环。",
)
b.step(
    "戴双进料斗: 罐顶西段两座等边四坡斗合拢自锁, 中缝对底互吸。",
    ["hop_a_s", "hop_a_e", "hop_a_n", "hop_a_w",
     "hop_b_s", "hop_b_e", "hop_b_n", "hop_b_w"],
    highlight=["dt_3"],
    tip="四条斜棱两两互吸 —— 这是全库反复验证过的自锁锥顶。",
)
b.step(
    "装警灯: 红色三角骑在舱顶南沿。",
    ["beacon"],
    highlight=["cr_1"],
    tip="搅拌车进场, 警灯先亮。",
)
b.step(
    "搭卸料溜槽: 30 度长板顶边吸底盘南沿, 坡尾正落浇筑仓中。",
    ["chute"],
    highlight=["ch_a2", "pw_s1"],
    tip="顶边一线双吸 (底盘方板南沿 + 轮组顶), 混凝土顺槽而下。",
)
b.step(
    "摆场景收尾: 2 只红色雪糕筒立在拼缝上, 西北角立告示牌 —— 开始浇筑!",
    ["cone_a", "cone_b", "sign", "sign_top"],
    highlight=["g1_a", "g4_a"],
    tip="雪糕筒围住作业半径 —— 罐车卸料, 闲人免进。",
)

b.finalize(
    model_id="cement_mixer_01",
    name="混凝土搅拌车",
    name_en="Cement Mixer 01",
    description=(
        "建筑/工地主题: 与自卸卡车完全不同的载具结构 —— 搅拌车的"
        "核心是满罐体 + 双进料斗 + 卸料溜槽三件套: 四只车轮底座托起"
        "方板留边的五板底盘, 3x2 橙色罐体墙环四角闭合, 罐顶三条横板"
        "压环成箱; 罐顶西段两座等边四坡进料斗对缝互锁, 车尾 30 度"
        "溜槽从底盘南沿一线双吸直下浇筑仓 —— 地坪南缘预留的三格"
        "空位由三面黄色模板墙围成条形基础, 坡尾正落仓中。透明挡风"
        "加窗格方车门窗的驾驶室借罐体东墙作后壁, 一墙两用。"
    ),
    difficulty=3,
    tags=["工程", "搅拌车", "载具", "浇筑", "车轮底座"],
    min_pieces=69,
    min_steps=14,
)
