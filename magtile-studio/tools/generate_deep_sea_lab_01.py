#!/usr/bin/env python3
"""生成模型 data/models/deep_sea_lab_01.json (海底实验室)。

海洋探险主题批 1/3: 全库第一座水下科研基地 —— 与既有海洋模型
全部错开: 珊瑚礁是海底造景, 潜艇/渔船是船体壳身, 观鲸站是岸上
瞭望塔; 本作的主角是"住在海底"这件事: 深蓝海床上一座双层主舱
(舷窗环列, 顶起声呐罩与红色天线), 一条舷窗观景廊道向东接到
橙色气闸舱 (双门框方进出舱, 四坡警示穹顶), 海藻塔尖摇曳、珊瑚
礁石点缀 —— 全库没有第二个"舱体 + 廊道 + 气闸"的水下基地。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 深海床 7x4 (x [0,7], y [0,4]): 蓝灰拼铺, 模块脚下全单位方板 21 片
  - 主舱 (x [1,3], y [1,3], z 0..2): 双层墙环 x16 (含舱门门框 x1
    + 舷窗窗格 x3) + 舱顶盖板 x4                                 20 片
  - 声呐罩: 等边四坡锥 x4 (罩尖 2.71) + 红色天线等腰塔尖 x1       5 片
  - 观景廊道 (x [3,5], y [1,2], z 0..1): 舷窗墙 x2 + 实墙 x2 +
    廊顶盖板 x2                                                   6 片
  - 气闸舱 (x [5,6], y [1,2], z 0..1): 双门框方 + 实墙 x2 +
    四坡警示穹顶 x4 (穹尖 1.71)                                   8 片
  - 海藻 x2 (等腰塔尖, 藻尖 2.0) + 珊瑚 x2 (等边/直立骑海床缝)    4 片
  合计 64 片, 13 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 主舱双层墙环层层整边咬合闭环, 盖板压顶锁箱;
  - 廊顶盖板一物三吸: 吸廊道墙顶、互吸拼缝、西沿再垫住主舱二层
    东墙脚 (一线双吸), 廊道把两舱刚性连成一体;
  - 气闸舱四坡穹顶直接骑墙顶: 四条斜棱两两互吸自锁成环, 底边
    各吸一道墙顶 —— 无盖板照样闭环;
  - 声呐罩四坡锥骑舱顶西北盖格, 天线塔尖骑盖板沿口 (同吸二层
    墙顶), 重心正压铰链线力矩为零;
  - 海藻/珊瑚立在海床单位方板拼缝上, 底边整边吸合, 剪断只失联
    1 片 (< 3), 高层单点失效检查天然通过。

用法: python3 tools/generate_deep_sea_lab_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

SEA_D = "blue"      # 深海床
SEA_R = "gray"      # 海床岩带
HULL = "gray"       # 主舱壳体
WIN = "cyan"        # 舷窗 (窗格方)
DOOR = "clear"      # 舱门 (门框方)
CAP = "clear"       # 舱顶盖板
SONAR = "clear"     # 声呐罩
ANT = "red"         # 天线
LOCK = "orange"     # 气闸舱
KELP = "green"      # 海藻
CORAL_A = "pink"    # 珊瑚
CORAL_B = "purple"  # 珊瑚


def wall_ns_t(tid, tile_type, x0, y, z0, color):
    b.add(tid, tile_type, (x0 + 0.5, y, z0 + 0.5), (90, 0, 0), color)


def wall_ew_t(tid, tile_type, x, y0, z0, color):
    b.add(tid, tile_type, (x, y0 + 0.5, z0 + 0.5), (90, 0, 90), color)


# =================================================================
# 1. 深海床 7x4 (x [0,7], y [0,4]): 模块脚下与立件拼缝全单位方板
# =================================================================
# 南缘岩带 (y [0,1]): 三条长板 + 东端单位方板
b.flat_rect("sea_0_0", 0, 0, 0.0, SEA_R)
b.flat_rect("sea_2_0", 2, 0, 0.0, SEA_R)
b.flat_rect("sea_4_0", 4, 0, 0.0, SEA_R)
b.flat("sea_6_0", 6, 0, 0.0, SEA_R)
# 模块行 (y [1,2]): 全单位方板 (主舱/廊道/气闸的墙脚线)
for x0 in range(7):
    b.flat(f"sea_{x0}_1", x0, 1, 0.0, SEA_D)
# 主舱行 (y [2,3]): 主舱脚下单位方板 + 东段长板
b.flat("sea_0_2", 0, 2, 0.0, SEA_D)
b.flat("sea_1_2", 1, 2, 0.0, SEA_D)
b.flat("sea_2_2", 2, 2, 0.0, SEA_D)
b.flat_rect("sea_3_2", 3, 2, 0.0, SEA_D)
b.flat_rect("sea_5_2", 5, 2, 0.0, SEA_D)
# 北缘 (y [3,4]): 海藻拼缝两端用单位方板
b.flat("sea_0_3", 0, 3, 0.0, SEA_D)
b.flat_rect("sea_1_3", 1, 3, 0.0, SEA_D)
b.flat_rect("sea_3_3", 3, 3, 0.0, SEA_D)
b.flat("sea_5_3", 5, 3, 0.0, SEA_D)
b.flat("sea_6_3", 6, 3, 0.0, SEA_D)

# =================================================================
# 2. 主舱一层 (x [1,3], y [1,3], z 0..1): 舱门门框朝廊道
# =================================================================
b.wall_ns("h1_s_1", 1, 1.0, 0, HULL)
b.wall_ns("h1_s_2", 2, 1.0, 0, HULL)
b.wall_ns("h1_n_1", 1, 3.0, 0, HULL)
b.wall_ns("h1_n_2", 2, 3.0, 0, HULL)
b.wall_ew("h1_w_1", 1.0, 1, 0, HULL)
b.wall_ew("h1_w_2", 1.0, 2, 0, HULL)
wall_ew_t("h1_door", "door_frame", 3.0, 1, 0, DOOR)   # 舱门 (接廊道)
b.wall_ew("h1_e_2", 3.0, 2, 0, HULL)

# =================================================================
# 3. 观景廊道 (x [3,5], y [1,2], z 0..1): 舷窗墙 + 廊顶盖板
# =================================================================
wall_ns_t("c_s_3", "window_square", 3, 1.0, 0, WIN)   # 南舷窗
wall_ns_t("c_s_4", "window_square", 4, 1.0, 0, WIN)
b.wall_ns("c_n_3", 3, 2.0, 0, HULL)
b.wall_ns("c_n_4", 4, 2.0, 0, HULL)
b.flat("c_cap_3", 3, 1, 1.0, CAP)
b.flat("c_cap_4", 4, 1, 1.0, CAP)

# =================================================================
# 4. 气闸舱 (x [5,6], y [1,2], z 0..1): 双门框方 + 四坡警示穹顶
# =================================================================
wall_ew_t("a_door_w", "door_frame", 5.0, 1, 0, DOOR)  # 内门 (接廊道)
b.wall_ns("a_s", 5, 1.0, 0, LOCK)
b.wall_ns("a_n", 5, 2.0, 0, LOCK)
wall_ew_t("a_door_e", "door_frame", 6.0, 1, 0, DOOR)  # 出舱门
A_DOME = b.hat4("a_dome", 5, 1, 1.0, LOCK, shape="equilateral_triangle")

# =================================================================
# 5. 主舱二层 (z 1..2): 舷窗环列 + 盖板压顶
# =================================================================
wall_ns_t("h2_s_1", "window_square", 1, 1.0, 1, WIN)
b.wall_ns("h2_s_2", 2, 1.0, 1, HULL)
b.wall_ns("h2_n_1", 1, 3.0, 1, HULL)
b.wall_ns("h2_n_2", 2, 3.0, 1, HULL)
wall_ew_t("h2_w_1", "window_square", 1.0, 1, 1, WIN)
b.wall_ew("h2_w_2", 1.0, 2, 1, HULL)
b.wall_ew("h2_e_1", 3.0, 1, 1, HULL)
b.wall_ew("h2_e_2", 3.0, 2, 1, HULL)
b.flat("h_cap_sw", 1, 1, 2.0, CAP)
b.flat("h_cap_se", 2, 1, 2.0, CAP)
b.flat("h_cap_nw", 1, 2, 2.0, CAP)
b.flat("h_cap_ne", 2, 2, 2.0, CAP)

# =================================================================
# 6. 声呐罩 + 天线: 等边四坡锥骑西北盖格, 红色塔尖骑东沿
# =================================================================
SONAR_IDS = b.hat4("sonar", 1, 2, 2.0, SONAR, shape="equilateral_triangle")
b.spire_ew("antenna", 3.0, 1, 2.0, ANT)               # 天线尖 4.0

# =================================================================
# 7. 海藻 x2 + 珊瑚 x2: 立在海床拼缝上
# =================================================================
b.spire_ns("kelp_w", 0, 4.0, 0.0, KELP)               # 藻尖 2.0
b.spire_ns("kelp_e", 5, 4.0, 0.0, KELP)
b.crest_ns("coral_a", 6, 2.0, 0.0, CORAL_A)
b.crest_ew("coral_b", 7.0, 0, 0.0, CORAL_B)

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺南缘岩带与模块行海床: 灰色岩带三长板一方板, 模块行七片"
    "深蓝单位方板。",
    ["sea_0_0", "sea_2_0", "sea_4_0", "sea_6_0"]
    + [f"sea_{x0}_1" for x0 in range(7)],
    tip="主舱、廊道、气闸的墙脚全踩在这一行单位方板的拼缝上。",
)
b.step(
    "铺北半海床: 主舱行与北缘, 海藻要立的拼缝两端用单位方板。",
    ["sea_0_2", "sea_1_2", "sea_2_2", "sea_3_2", "sea_5_2",
     "sea_0_3", "sea_1_3", "sea_3_3", "sea_5_3", "sea_6_3"],
    highlight=["sea_0_1"],
    tip="行行等边互吸 —— 海床连成一整片, 基地才有地基。",
)
b.step(
    "立主舱一层南墙与西墙: 灰色壳体墙踩拼缝, 拐角竖边互咬。",
    ["h1_s_1", "h1_s_2", "h1_w_1", "h1_w_2"],
    highlight=["sea_1_1"],
    tip="深海水压大 —— 舱体从第一环就要合得严丝合缝。",
)
b.step(
    "立主舱一层北墙与东墙合环: 东南角留舱门门框, 正对廊道。",
    ["h1_n_1", "h1_n_2", "h1_door", "h1_e_2"],
    highlight=["h1_s_1", "h1_w_1"],
    tip="门框方外框与正方形完全一致 —— 舱门就是通向廊道的入口。",
)
b.step(
    "立观景廊道: 南面两扇舷窗窗格方, 北面两片实墙。",
    ["c_s_3", "c_s_4", "c_n_3", "c_n_4"],
    highlight=["h1_door"],
    tip="趴在舷窗前看鱼群游过 —— 廊道是基地最受欢迎的地方。",
)
b.step(
    "立气闸舱: 东西双门框方 + 南北橙色实墙, 与廊道墙竖边互咬。",
    ["a_door_w", "a_s", "a_n", "a_door_e"],
    highlight=["c_s_4"],
    tip="潜水员从东门出舱 —— 进出都要经过这间橙色小舱。",
)
b.step(
    "盖廊道顶: 两片盖板压廊道墙顶又互吸拼缝。",
    ["c_cap_3", "c_cap_4"],
    highlight=["c_s_3", "a_door_w"],
    tip="廊顶西沿还要垫住主舱二层墙脚 —— 一线双吸的伏笔。",
)
b.step(
    "起气闸穹顶: 四片等边三角骑墙顶, 斜棱两两互吸自锁。",
    A_DOME,
    highlight=["a_door_e"],
    tip="四坡穹顶不用盖板照样闭环 —— 橙色是深海的警示色。",
)
b.step(
    "立主舱二层南墙与西墙: 舷窗窗格方环列高处。",
    ["h2_s_1", "h2_s_2", "h2_w_1", "h2_w_2"],
    highlight=["h1_s_2"],
    tip="二层墙整边骑一层墙顶 —— 舷窗越高, 看得越远。",
)
b.step(
    "立主舱二层北墙与东墙合环: 东墙脚同时压住廊顶盖板西沿。",
    ["h2_n_1", "h2_n_2", "h2_e_1", "h2_e_2"],
    highlight=["c_cap_3"],
    tip="一线双吸: 墙脚吸一层墙顶, 又吸廊顶沿 —— 两舱连成一体。",
)
b.step(
    "盖主舱顶: 四片盖板压顶锁箱。",
    ["h_cap_sw", "h_cap_se", "h_cap_nw", "h_cap_ne"],
    highlight=["h2_n_1"],
    tip="盖板互吸拼缝 —— 双层舱体处处闭环。",
)
b.step(
    "架声呐罩与天线: 四坡锥骑西北盖格, 红色塔尖骑东沿直指海面。",
    SONAR_IDS + ["antenna"],
    highlight=["h_cap_nw"],
    tip="天线尖 4.0 全场最高 —— 基地靠它跟海面的科考船通话。",
)
b.step(
    "种海藻立珊瑚收尾: 两株海藻骑北缘拼缝, 粉紫珊瑚点缀东侧。",
    ["kelp_w", "kelp_e", "coral_a", "coral_b"],
    highlight=["antenna"],
    tip="底边整边吸住海床 —— 海底花园环绕, 实验室开站!",
)

b.finalize(
    model_id="deep_sea_lab_01",
    name="海底实验室",
    name_en="Deep Sea Lab 01",
    description=(
        "只用核心九片型的水下科研基地: 与珊瑚礁造景、潜艇壳身和岸上"
        "观鲸塔都不同, 主角是'住在海底'这件事 —— 深蓝海床上双层主舱"
        "墙环层层咬合, 舷窗窗格环列高处, 顶起等边四坡声呐罩与 4.0 高"
        "的红色天线塔尖; 一条舷窗观景廊道向东接到橙色气闸舱, 双门框"
        "方进出舱, 四坡警示穹顶斜棱互咬自锁; 廊顶盖板一物三吸把两舱"
        "刚性连成一体, 海藻塔尖与粉紫珊瑚立在海床拼缝上 —— 舱门"
        "合拢, 下潜开始!"
    ),
    difficulty=3,
    tags=["海洋", "探险", "海底基地", "科学探索", "进阶"],
    min_pieces=64,
    min_steps=13,
)
