#!/usr/bin/env python3
"""生成模型 data/models/trex_skeleton_01.json (霸王龙化石骨架 · 博物馆立姿)。

技法: T10 骨架框架 (主) + T03 悬臂外挑 + T14 斜撑加固; 范式 skeleton_first。
招牌技法: 脊柱是左右两片墙夹一排背板的"箱形梁", 从后腿顶向头尾双向
悬挑贯穿全身 —— 全模型没有一面"房子墙", 形体完全由骨骼定义。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 体轴沿 x, 头朝东):
  - 展台基座: 6 片平铺基座 + 铭牌展板                                  8 片
  - 后腿: 左右腿各 2 层立片踩在展台边上, 直角三角"脚爪"斜撑前伸        6 片
  - 脊柱箱形梁: 左右壁各 10 片 (x 1..11, z 2..3) + 10 片背板压顶,
    尾段与颈段都是纯悬臂 —— 但箱形截面把力矩化为面内力, 稳如磐石     30 片
  - 尾尖: 2 片等腰三角形水平收尖 (x=1 竖边向西悬挑)                    2 片
  - 肋骨: 3 对等腰三角形从脊柱下缘倒挂, 胸腔镂空                       6 片
  - 前肢: 1 对等边三角形小短手 (霸王龙的标志性萌点)                    2 片
  - 颈与头骨: 颈箱 2 段上叠, 头骨箱 3 段前伸 + 吻部直角尖 + 倒挂下颌  19 片
  合计 73 片, 16 个教程步骤。

物理规则要点 (通过 R1~R8 全部校验):
  - 脊柱左右壁全部立在平面 y=0 / y=1 内, 重力对面内铰链线的力矩
    恒为零; 背板把两壁锁成箱形闭环, 剪断任何一条铰链线后子结构
    仍经另一侧壁接地 (R6 悬臂预算天然满足);
  - 肋骨/下颌/前肢是倒挂件, 单片 13~15g 远低于 120g 悬挂预算 (R5);
  - 头尾配重: 教程先向头侧推进再补尾段, 全程重心都落在展台凸包内
    (R4), 最终重心 x≈7.4, 展台覆盖 x 3..9;
  - 尾尖挂在竖直铰链边上, 重力对竖直轴无力矩 —— 水平收尖零代价。

坐标约定与 C++ 端一致: 旋转为欧拉角 (度), R = Rz * Ry * Rx。
用法: python3 tools/generate_trex_skeleton.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

mb = ModelBuilder()

SPINE_Z = 2          # 脊柱下缘高度
BONE = "gray"        # 骨骼主色
BONE2 = "pink"       # 骨骼亚色 (背板)

# =================================================================
# 1. 展台基座 (x 3..9) + 铭牌展板
# =================================================================
for x0 in range(3, 9):
    mb.flat(f"ped_{x0}", x0, 0, 0.0, "green" if x0 % 2 else "cyan")
mb.flat("plaque", 8, -1, 0.0, "yellow")               # 铭牌台
mb.crest_ns("plaque_sign", 8, -1.0, 0.0, "red")       # 立式铭牌

# =================================================================
# 2. 后腿 (x 5..6, 左腿平面 y=0, 右腿平面 y=1) + 脚爪斜撑
# =================================================================
for lv in range(2):
    mb.wall_ns(f"leg_l_{lv}", 5, 0.0, lv, BONE)
    mb.wall_ns(f"leg_r_{lv}", 5, 1.0, lv, BONE)
mb.brace("toe_l", (6.0, 0.0, 0.0), "+x", BONE)        # 脚爪: 竖边吸腿, 横边落地
mb.brace("toe_r", (6.0, 1.0, 0.0), "+x", BONE)

# =================================================================
# 3. 脊柱箱形梁 (x 1..11): 左右壁 z 2..3 + 背板 z=3
# =================================================================
for x0 in range(1, 11):
    mb.wall_ns(f"sp_l_{x0}", x0, 0.0, SPINE_Z, BONE)
    mb.wall_ns(f"sp_r_{x0}", x0, 1.0, SPINE_Z, BONE)
    mb.flat(f"cap_{x0}", x0, 0, 3.0, BONE2)

# ---- 尾尖: 等腰三角形水平收尖, 底边吸脊柱西端竖边 ------------------
mb.place_tri("tail_l", "isosceles_triangle",
             (1.0, 0.0, 3.0), (1.0, 0.0, 2.0), (0.0, 0.0, 2.5), BONE)
mb.place_tri("tail_r", "isosceles_triangle",
             (1.0, 1.0, 3.0), (1.0, 1.0, 2.0), (0.0, 1.0, 2.5), BONE)

# ---- 肋骨: 等腰三角形从脊柱下缘倒挂 (x 6..9 胸腔段) ----------------
for x0 in (6, 7, 8):
    mb.place_tri(f"rib_l_{x0}", "isosceles_triangle",
                 (float(x0), 0.0, 2.0), (float(x0 + 1), 0.0, 2.0),
                 (x0 + 0.5, 0.0, 1.0), BONE)
    mb.place_tri(f"rib_r_{x0}", "isosceles_triangle",
                 (float(x0), 1.0, 2.0), (float(x0 + 1), 1.0, 2.0),
                 (x0 + 0.5, 1.0, 1.0), BONE)

# ---- 前肢: 等边三角形小短手 (x 9..10 倒挂) -------------------------
mb.place_tri("arm_l", "equilateral_triangle",
             (9.0, 0.0, 2.0), (10.0, 0.0, 2.0), (9.5, 0.0, 1.133975), BONE2)
mb.place_tri("arm_r", "equilateral_triangle",
             (9.0, 1.0, 2.0), (10.0, 1.0, 2.0), (9.5, 1.0, 1.133975), BONE2)

# =================================================================
# 4. 颈 (x 9..11, z 3..4) 与头骨箱 (x 10..13, z 4..5)
# =================================================================
for x0 in (9, 10):
    mb.wall_ns(f"nk_l_{x0}", x0, 0.0, 3, BONE)
    mb.wall_ns(f"nk_r_{x0}", x0, 1.0, 3, BONE)
    mb.flat(f"ncap_{x0}", x0, 0, 4.0, BONE2)

for x0 in (10, 11, 12):
    mb.wall_ns(f"sk_l_{x0}", x0, 0.0, 4, BONE)
    mb.wall_ns(f"sk_r_{x0}", x0, 1.0, 4, BONE)
    mb.flat(f"scap_{x0}", x0, 0, 5.0, BONE2)

# ---- 吻部: 直角三角形前伸收尖 (竖边吸头骨箱前缘竖边) ----------------
mb.place_tri("snout_l", "right_triangle",
             (13.0, 0.0, 5.0), (14.0, 0.0, 5.0), (13.0, 0.0, 4.0), BONE)
mb.place_tri("snout_r", "right_triangle",
             (13.0, 1.0, 5.0), (14.0, 1.0, 5.0), (13.0, 1.0, 4.0), BONE)

# ---- 下颌: 等腰三角形从头骨下缘倒挂 --------------------------------
mb.place_tri("jaw_l", "isosceles_triangle",
             (12.0, 0.0, 4.0), (13.0, 0.0, 4.0), (12.5, 0.0, 3.0), "red")
mb.place_tri("jaw_r", "isosceles_triangle",
             (12.0, 1.0, 4.0), (13.0, 1.0, 4.0), (12.5, 1.0, 3.0), "red")

# =================================================================
# 教程步骤 (16 步): skeleton_first —— 先立骨盆立柱, 脊柱向头尾双向悬挑
# =================================================================
mb.step(
    "博物馆展台: 桌面上一字铺开 6 片基座 (x 3..9), 相邻边互吸。",
    [f"ped_{x0}" for x0 in range(3, 9)],
    tip="骨架全长 14 格, 展台居中偏后 —— 头尾都要留出悬挑空间。",
)
mb.step(
    "后腿与脚爪: 左右腿各 2 片立在展台南北沿上 (x 5..6), 前方各加 1 片"
    "直角三角脚爪 —— 竖边吸腿骨、横边落地, 是全身的斜撑地锚。",
    ["leg_l_0", "leg_l_1", "leg_r_0", "leg_r_1", "toe_l", "toe_r"],
    highlight=["ped_5", "ped_6"],
    tip="两条腿分立展台两侧沿口, 中间空出的就是骨盆下方的镂空。",
)
mb.step(
    "骨盆节: 脊柱第一节 —— 左右壁各 1 片压上腿顶, 1 片背板把两壁锁成"
    "箱形。之后的每一节都重复这个'两壁一盖'的手法。",
    ["sp_l_5", "sp_r_5", "cap_5"],
    highlight=["leg_l_1", "leg_r_1"],
    tip="背板同时吸住左右壁顶边 —— 箱形闭环是整条脊柱的力学核心。",
)
mb.step(
    "胸椎两节: 脊柱向头侧悬挑 x 6..8, 每节仍是两壁一盖。",
    ["sp_l_6", "sp_r_6", "cap_6", "sp_l_7", "sp_r_7", "cap_7"],
    highlight=["cap_5"],
    tip="悬挑节先吸竖边再压背板, 箱形梁会把悬挑力矩化成面内力。",
)
mb.step(
    "肩椎一节: 继续向头侧推进 x 8..9。",
    ["sp_l_8", "sp_r_8", "cap_8"],
    highlight=["cap_7"],
    tip="脊柱每节都与上一节竖边整边互吸, 别留半格错位。",
)
mb.step(
    "颈根两节: 脊柱前段到位 (x 9..11), 霸王龙的上半身骨架成形。",
    ["sp_l_9", "sp_r_9", "cap_9", "sp_l_10", "sp_r_10", "cap_10"],
    highlight=["cap_8"],
    tip="此时头侧悬挑已 5 节 —— 下一步开始补尾段配重。",
)
mb.step(
    "尾椎两节: 回到骨盆向尾侧悬挑 x 3..5。",
    ["sp_l_4", "sp_r_4", "cap_4", "sp_l_3", "sp_r_3", "cap_3"],
    highlight=["cap_5"],
    tip="尾巴是天然配重, 把重心拉回展台正中。",
)
mb.step(
    "尾梢两节: 尾段延伸到 x 1..3, 脊柱箱形梁全线贯通。",
    ["sp_l_2", "sp_r_2", "cap_2", "sp_l_1", "sp_r_1", "cap_1"],
    highlight=["cap_3"],
    tip="尾尖离桌面始终两格高 —— 霸王龙尾巴是平举的, 不拖地。",
)
mb.step(
    "尾尖收形: 2 片等腰三角形底边吸在尾端竖边上, 水平向西收出尖尾。",
    ["tail_l", "tail_r"],
    highlight=["sp_l_1", "sp_r_1"],
    tip="挂在竖直磁边上的水平尖件不产生重力力矩, 放心悬挑。",
)
mb.step(
    "肋骨笼: 3 对等腰三角形从胸腔段脊柱下缘倒挂 (x 6..9), 尖端朝下, "
    "肋间留空 —— 化石骨架的镂空胸腔。",
    ["rib_l_6", "rib_r_6", "rib_l_7", "rib_r_7", "rib_l_8", "rib_r_8"],
    highlight=["cap_6", "cap_7", "cap_8"],
    tip="倒挂件靠磁条受拉, 单片远在悬挂预算内; 左右成对交替安装。",
)
mb.step(
    "小短手: 1 对等边三角形倒挂在颈根下缘 (x 9..10) —— 霸王龙标志性的"
    "小前肢。",
    ["arm_l", "arm_r"],
    highlight=["sp_l_9", "sp_r_9"],
    tip="是的, 它真的就这么短。",
)
mb.step(
    "颈箱: 颈部两节双壁 + 双背板叠在脊柱前段之上 (x 9..11, z 3..4), "
    "脖颈开始抬升。",
    ["nk_l_9", "nk_r_9", "nk_l_10", "nk_r_10", "ncap_9", "ncap_10"],
    highlight=["cap_9", "cap_10"],
    tip="颈箱直接踩在脊柱背板与壁顶上, 上下两层箱梁错半格更稳。",
)
mb.step(
    "头骨箱: 3 节双壁再上一层 (x 10..13, z 4..5), 向前悬挑出下颚以上的"
    "整个头颅侧影。",
    ["sk_l_10", "sk_r_10", "sk_l_11", "sk_r_11", "sk_l_12", "sk_r_12"],
    highlight=["ncap_9", "ncap_10"],
    tip="头骨箱第 1 节踩在颈箱顶上, 后 2 节靠竖边互吸向前悬挑。",
)
mb.step(
    "颅顶与吻尖: 3 片背板锁住头骨箱, 2 片直角三角形竖边吸箱前缘, "
    "斜边向前下方收出吻部。",
    ["scap_10", "scap_11", "scap_12", "snout_l", "snout_r"],
    highlight=["sk_l_12", "sk_r_12"],
    tip="背板先锁箱再装吻尖, 头骨箱合环后前端才有足够刚度。",
)
mb.step(
    "血盆大口: 2 片红色等腰三角形从头骨下缘倒挂成下颌, 尖端朝下 —— "
    "与肋骨同款倒挂手法。",
    ["jaw_l", "jaw_r"],
    highlight=["sk_l_12", "sk_r_12"],
    tip="下颌与颈箱之间留出的负空间就是张开的大嘴。",
)
mb.step(
    "博物馆铭牌: 展台前侧接 1 片黄色铭牌台, 立 1 片红色三角铭牌 —— "
    "'霸王龙 Tyrannosaurus rex', 布展完成!",
    ["plaque", "plaque_sign"],
    highlight=["ped_8"],
    tip="绕着展台走一圈: 从任何角度都只看到骨骼, 没有一面墙。",
)

mb.finalize(
    model_id="trex_skeleton_01",
    name="霸王龙化石骨架",
    name_en="T-Rex Fossil Skeleton 01",
    description=(
        "博物馆立姿霸王龙: 脊柱是'左右壁 + 背板'的箱形梁, 从后腿顶向头尾"
        "双向悬挑贯穿全身; 肋骨、小短手与下颌全部倒挂在脊柱下缘, 胸腔与"
        "大嘴都是负空间。头尾互为配重, 尾椎补齐前重心始终不越出展台 —— "
        "全模型没有一面墙, 形体完全由骨骼定义, 搭完就是一件博物馆展品。"
    ),
    difficulty=3,
    tags=["恐龙", "骨架", "动物世界", "博物馆", "悬挑"],
    min_pieces=55,
    min_steps=16,
)
