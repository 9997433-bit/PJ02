#!/usr/bin/env python3
"""生成模型 data/models/dental_clinic_01.json (牙科诊所)。

医院健康主题: 全库第一座"长得像自己招牌"的建筑 —— 巨型磨牙楼:
诊所本体就是一颗大白牙! 两条空心牙根 (1x1 箱形筒, 西根南面开
门框方诊所大门) 分立两侧, 根间留一条能走人的穿堂; 三片桥板在
z=1 合龙 —— 中央桥板西边吸西根东壁顶、东边吸东根西壁顶, 双端
受力跨过穿堂; 桥板上再起一圈 3x1 牙冠箱体 (南面两扇窗格方
大眼睛), 长板封顶后四角各立一片白等边 —— 正是磨牙的四个牙尖。
院里一把巨型牙刷平躺: 三格刷头顶着三根立起的刷毛, 蓝色长板
刷柄伸出老远; 牙刷旁一只粉色漱口杯 (四壁开口朝天的方筒),
候诊长凳摆在门前, 牙冠北檐红旗高扬 —— 刷牙上下刷, 牙医笑哈哈。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 大门朝南):
  - 院子地坪 7x4 (含门前步道/穿堂地/根内地板)                21 片
  - 巨型牙刷 (y[4,5] 整排): 刷头方板 x3 + 刷柄长板 x2
    + 立起的刷毛等边 x3                                        8 片
  - 磨牙楼: 牙根箱形筒 x2 (含门框方大门 1)                     8 片
  -          桥板方板 x3 (中央板双端受力跨穿堂)                 3 片
  -          牙冠圈层 x8 (含窗格方大眼睛 2) + 长板压顶 x2      10 片
  -          牙尖白等边 x4 + 北檐红旗等腰 x1                    5 片
  - 漱口杯: 粉色方筒四壁 (开口朝天)                             4 片
  - 候诊长凳: 等边 x2                                           2 片
  合计 61 片, 12 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, 常规+strict 双档零警告):
  - 中央桥板是全楼关键一跨: 西边整边吸西根东壁顶、东边整边吸
    东根西壁顶, 又与两侧桥板长边互吸 —— 三面受力零悬臂;
  - 牙根/牙冠全部箱形闭环: 四壁竖边互吸, 顶板四边压壁顶,
    荷载沿双根直落地面, 无单点失效;
  - 牙尖底边整边吸牙冠壁顶边 (与压顶长板边共线双吸),
    重心正压铰链零力矩;
  - 刷毛/长凳/漱口杯壁底边全部整边吸地坪格线。

用法: python3 tools/generate_dental_clinic.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

LAWN = "green"      # 院子草坪
PATH = "orange"     # 门前步道 / 穿堂地
PAVE = "gray"       # 硬化地坪
ROOM = "clear"      # 根内地板
TOOTH = "clear"     # 牙体 (白)
DOOR = "blue"       # 诊所大门
EYE = "cyan"        # 牙冠大眼睛
FLAG = "red"        # 北檐红旗
HEAD = "clear"      # 刷头
BRISTLE = "clear"   # 刷毛
HANDLE = "blue"     # 刷柄
CUP = "pink"        # 漱口杯
BENCH = "orange"    # 候诊长凳

# =================================================================
# 1. 院子地坪 7x4 (行 y0..3)
# =================================================================
# 行 y[0,1]: 门前步道 + 长凳落脚方板
b.flat("g0_w", 0, 0, 0.0, LAWN)
b.flat("g0_path", 1, 0, 0.0, PATH)              # 正对西根大门
b.flat_rect("g0_a", 2, 0, 0.0, PAVE)
b.flat("g0_b", 4, 0, 0.0, PAVE)
b.flat("g0_c", 5, 0, 0.0, PAVE)
b.flat("g0_e", 6, 0, 0.0, LAWN)
# 行 y[1,2]: 牙根落脚行 (根内地板 + 穿堂地)
b.flat("g1_w", 0, 1, 0.0, LAWN)
b.flat("g1_ra", 1, 1, 0.0, ROOM)                # 西根内地板
b.flat("g1_pass", 2, 1, 0.0, PATH)              # 穿堂地
b.flat("g1_rb", 3, 1, 0.0, ROOM)                # 东根内地板
b.flat("g1_a", 4, 1, 0.0, PAVE)
b.flat_rect("g1_e", 5, 1, 0.0, LAWN)
# 行 y[2,3]: 牙楼背后
b.flat_rect("g2_a", 0, 2, 0.0, LAWN)
b.flat_rect("g2_b", 2, 2, 0.0, LAWN)
b.flat_rect("g2_c", 4, 2, 0.0, LAWN)
b.flat("g2_e", 6, 2, 0.0, LAWN)
# 行 y[3,4]: 漱口杯落脚行
b.flat_rect("g3_a", 0, 3, 0.0, LAWN)
b.flat_rect("g3_b", 2, 3, 0.0, LAWN)
b.flat("g3_c", 4, 3, 0.0, LAWN)
b.flat("g3_cup", 5, 3, 0.0, PAVE)               # 杯底
b.flat("g3_e", 6, 3, 0.0, LAWN)

# =================================================================
# 2. 巨型牙刷 (y[4,5] 整排): 刷头在西, 刷柄伸向东
# =================================================================
b.flat("bh_0", 0, 4, 0.0, HEAD)
b.flat("bh_1", 1, 4, 0.0, HEAD)
b.flat("bh_2", 2, 4, 0.0, HEAD)
b.flat_rect("bd_a", 3, 4, 0.0, HANDLE)
b.flat_rect("bd_b", 5, 4, 0.0, HANDLE)
b.crest_ns("br_0", 0, 5.0, 0.0, BRISTLE)        # 立起的刷毛
b.crest_ns("br_1", 1, 5.0, 0.0, BRISTLE)
b.crest_ns("br_2", 2, 5.0, 0.0, BRISTLE)

# =================================================================
# 3. 磨牙楼: 双牙根箱形筒 (z0..1)
# =================================================================
b.add("ra_door", "door_frame", (1.5, 1.0, 0.5), (90, 0, 0), DOOR)  # 西根大门
b.wall_ns("ra_n", 1, 2.0, 0, TOOTH)
b.wall_ew("ra_w", 1.0, 1, 0, TOOTH)
b.wall_ew("ra_e", 2.0, 1, 0, TOOTH)
b.wall_ns("rb_s", 3, 1.0, 0, TOOTH)
b.wall_ns("rb_n", 3, 2.0, 0, TOOTH)
b.wall_ew("rb_w", 3.0, 1, 0, TOOTH)
b.wall_ew("rb_e", 4.0, 1, 0, TOOTH)

# 桥板 z=1: 西根顶 + 东根顶 + 中央跨穿堂
b.flat("dk_w", 1, 1, 1.0, TOOTH)
b.flat("dk_e", 3, 1, 1.0, TOOTH)
b.flat("dk_mid", 2, 1, 1.0, TOOTH)              # 双端受力跨穿堂

# 牙冠圈层 z1..2: 南面 眼-墙-眼, 北面 x3, 东西壁
b.add("cr_eye_w", "window_square", (1.5, 1.0, 1.5), (90, 0, 0), EYE)
b.wall_ns("cr_s_mid", 2, 1.0, 1, TOOTH)
b.add("cr_eye_e", "window_square", (3.5, 1.0, 1.5), (90, 0, 0), EYE)
for x in (1, 2, 3):
    b.wall_ns(f"cr_n_{x}", x, 2.0, 1, TOOTH)
b.wall_ew("cr_w", 1.0, 1, 1, TOOTH)
b.wall_ew("cr_e", 4.0, 1, 1, TOOTH)

# 牙冠压顶 z=2: 长板 + 方板
b.flat_rect("cap_w", 1, 1, 2.0, TOOTH)
b.flat("cap_e", 3, 1, 2.0, TOOTH)

# 牙尖 x4 (南北檐各 2) + 北檐红旗
b.crest_ns("cusp_sw", 1, 1.0, 2.0, TOOTH)
b.crest_ns("cusp_se", 3, 1.0, 2.0, TOOTH)
b.crest_ns("cusp_nw", 1, 2.0, 2.0, TOOTH)
b.crest_ns("cusp_ne", 3, 2.0, 2.0, TOOTH)
b.spire_ns("flag", 2, 2.0, 2.0, FLAG)

# =================================================================
# 4. 漱口杯 (开口朝天的粉方筒) + 候诊长凳
# =================================================================
b.wall_ns("cup_s", 5, 3.0, 0, CUP)
b.wall_ns("cup_n", 5, 4.0, 0, CUP)
b.wall_ew("cup_w", 5.0, 3, 0, CUP)
b.wall_ew("cup_e", 6.0, 3, 0, CUP)
b.crest_ns("bench_w", 4, 0.0, 0.0, BENCH)
b.crest_ns("bench_e", 5, 0.0, 0.0, BENCH)

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺院子南排: 橙色步道方板正对西牙根的大门位, 东段两片方板"
    "给候诊长凳留落脚边。",
    ["g0_w", "g0_path", "g0_a", "g0_b", "g0_c", "g0_e"],
    tip="磨牙楼的大门开在西牙根上 —— 步道先把位置标出来。",
)
b.step(
    "铺牙根落脚行: 两片白色根内地板夹住橙色穿堂地, 全部用方板 "
    "—— 牙根四壁要吸这些格线。",
    ["g1_w", "g1_ra", "g1_pass", "g1_rb", "g1_a", "g1_e"],
    highlight=["g0_path"],
    tip="根与根之间留一格穿堂 —— 从牙缝里穿过去!",
)
b.step(
    "铺后院两排: 长板混方板合拢, 杯底方板落在东北角。",
    ["g2_a", "g2_b", "g2_c", "g2_e",
     "g3_a", "g3_b", "g3_c", "g3_cup", "g3_e"],
    highlight=["g1_ra", "g1_rb"],
)
b.step(
    "摆巨型牙刷: 三格白刷头贴北沿排开, 两条蓝长板刷柄伸向东, "
    "三根刷毛等边在刷头北边立起来。",
    ["bh_0", "bh_1", "bh_2", "bd_a", "bd_b", "br_0", "br_1", "br_2"],
    highlight=["g3_a"],
    tip="刷毛底边整边吸刷头北格边 —— 上下刷才刷得干净。",
)
b.step(
    "起西牙根: 蓝色门框方大门朝南, 其余三壁围成箱形筒。",
    ["ra_door", "ra_n", "ra_w", "ra_e"],
    highlight=["g0_path", "g1_ra"],
    tip="四壁竖边互吸成环 —— 牙根是全楼的承重腿。",
)
b.step(
    "起东牙根: 四片白壁再围一筒, 与西根隔穿堂相望。",
    ["rb_s", "rb_n", "rb_w", "rb_e"],
    highlight=["ra_e", "g1_pass"],
)
b.step(
    "合龙桥板: 先盖两根顶板, 中央桥板最后落 —— 西边吸西根东壁"
    "顶、东边吸东根西壁顶, 双端受力跨过穿堂。",
    ["dk_w", "dk_e", "dk_mid"],
    highlight=["ra_e", "rb_w"],
    tip="这一跨把两条牙根连成一颗牙 —— 关键的一步!",
)
b.step(
    "起牙冠南立面与东西壁: 两扇青色窗格方大眼睛分居两侧, "
    "白壁居中, 东西壁封边。",
    ["cr_eye_w", "cr_s_mid", "cr_eye_e", "cr_w", "cr_e"],
    highlight=["dk_mid"],
    tip="大眼睛正对院子 —— 这颗牙在朝你笑。",
)
b.step(
    "合牙冠北壁: 三片白壁对缝立起, 牙冠箱形闭环。",
    ["cr_n_1", "cr_n_2", "cr_n_3"],
    highlight=["cr_w", "cr_e"],
)
b.step(
    "牙冠压顶: 长板 + 方板盖住 3x1 冠口, 短边整边压东西壁顶。",
    ["cap_w", "cap_e"],
    highlight=["cr_n_2"],
)
b.step(
    "立牙尖与红旗: 四片白等边立上四角檐口 —— 磨牙的四个牙尖, "
    "北檐正中红色等腰旗杆高扬。",
    ["cusp_sw", "cusp_se", "cusp_nw", "cusp_ne", "flag"],
    highlight=["cap_w", "cap_e"],
    tip="牙尖底边吸壁顶边, 与压顶板边共线双吸。",
)
b.step(
    "摆漱口杯与候诊长凳: 粉色方筒开口朝天, 两片橙等边长凳"
    "面朝大门 —— 牙科诊所开诊!",
    ["cup_s", "cup_n", "cup_w", "cup_e", "bench_w", "bench_e"],
    highlight=["g3_cup", "g0_b"],
    tip="刷牙上下刷, 牙医笑哈哈。",
)

b.finalize(
    model_id="dental_clinic_01",
    name="牙科诊所",
    name_en="Dental Clinic 01",
    description=(
        "全库第一座'长得像自己招牌'的建筑 —— 诊所本体就是一颗巨型磨牙: "
        "两条空心牙根箱形筒分立两侧 (西根南面开蓝色门框方大门), 根间留"
        "一条能走人的穿堂; 中央桥板西吸西根东壁顶、东吸东根西壁顶, "
        "双端受力跨过穿堂把双根连成一颗牙; 桥板上再起 3x1 牙冠箱体, "
        "南面两扇窗格方大眼睛朝院子笑, 长板压顶后四角各立一片白等边 "
        "—— 磨牙的四个牙尖, 北檐红旗高扬。院里巨型牙刷平躺 (三格刷头"
        "+三根立毛+蓝长板刷柄), 粉色漱口杯四壁开口朝天, 候诊长凳面朝"
        "大门 —— 刷牙上下刷, 牙医笑哈哈。"
    ),
    difficulty=3,
    tags=["医院", "城市", "职业体验", "牙医", "进阶"],
    min_pieces=61,
    min_steps=12,
)
