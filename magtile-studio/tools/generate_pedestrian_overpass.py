#!/usr/bin/env python3
"""生成模型 data/models/pedestrian_overpass_01.json (人行过街天桥)。

城市交通主题批 1/4: 全库第一座"人在车上走"的过街天桥 —— 与
suspension_bridge_01 (斜拉索跨河) / covered_bridge_01 (三亭连廊跨河) /
bridge_wood_01 (多跨墩柱跨河) 刻意区分: 那些桥跨的是水, 本作跨的是
"正在通车的马路" —— 桥下必须留出整整 2 格净空让汽车通过, 因此桥面
被顶到 z=2, 结构逻辑变成"先把人送上两层楼, 再让他走过一块单跨板":
南北两座 2x1 两层梯塔 (墙环环环相扣, 二层嵌透明窗格方候梯厅窗),
塔顶压顶长板即登桥平台; 塔旁 1 格梯箱 (z=1) 作半程踏步, 箱外
30 度无障碍坡道落地 —— 地面->坡道->梯箱->梯塔->桥面, 一条完整的
无障碍动线; 桥面单跨长板两短边同吸南北梯塔墙顶 (双端受力, 跨中
零铰链缝), 桥沿两片透明长方形防风屏整长边压桥沿; 一辆小红车正从
桥下东行 —— 人车分流, 谁也不用等谁。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 马路双车道 (x [0,7], y [2,4]): 长板 x6 + 方板 x2               8 片
  - 南北人行道 (y [1,2] / [4,5]): 长板 x2 + 方板 x10              12 片
  - 南梯塔 (x [3,5], y [1,2], 两层墙环 + 压顶长板)                13 片
  - 南梯箱 (x [5,6], z 0..1) + 30 度无障碍坡道                     5 片
  - 北梯塔 + 北梯箱 + 北坡道 (镜像)                               18 片
  - 桥面单跨长板 + 透明防风屏 x2                                   3 片
  - 天桥标志牌: 蓝色等腰高塔尖 x2 (骑压顶沿口, 顶高 4.0)           2 片
  - 小红车 (桥下东行): 车轮底座 x2 + 长板车顶 + 三角驾驶舱         4 片
  合计 65 片, 13 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 桥面长板两短边分别同吸南北梯塔墙顶 + 压顶沿边 (每端两条共线
    连接), 剪断任一端整条铰链线, 另一端仍把桥面拉在塔上 —— 双端
    受力零悬挑, 跨中刻意零铰链缝 (廊桥同款纪律);
  - 梯塔两层墙环四角竖边互吸自锁 (闭环拓扑), 塔高 2.0 + 标志牌
    4.0 触发 R8 高层检查, 环状结构天然通过;
  - 坡道顶边同吸梯箱压顶沿边与梯箱东墙顶边, 坡尾自己落地 ——
    剪断顶铰链坡道也掉不下来;
  - 防风屏长边与桥面长边等长整边贴合, 重心正压铰链线力矩为零;
  - 标志牌骑整边沿口 (压顶沿 + 墙顶双共线连接), 力矩为零;
  - 小车车顶长板双长边压两片车轮底座顶边, 轮底整边吸车道拼缝,
    全场磁力图连通零 disconnected 警告。

用法: python3 tools/generate_pedestrian_overpass.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

ROAD = "gray"        # 马路
WALK = "green"       # 人行道
TOWER = "blue"       # 梯塔墙体
WIN = "clear"        # 候梯厅窗
CAP = "gray"         # 压顶 / 桥面
BOX = "cyan"         # 梯箱
RAMP = "orange"      # 无障碍坡道
RAIL = "clear"       # 桥沿透明防风屏
SIGN = "blue"        # 天桥标志牌
CAR = "red"          # 小红车
WHEEL = "gray"       # 车轮底座

# =================================================================
# 1. 马路双车道 (x [0,7], y [2,4]): 每车道 3 长板 + 1 方板
# =================================================================
for lane, y0 in (("s", 2), ("n", 3)):
    b.flat_rect(f"rd_{lane}_0", 0, y0, 0.0, ROAD)
    b.flat_rect(f"rd_{lane}_2", 2, y0, 0.0, ROAD)
    b.flat_rect(f"rd_{lane}_4", 4, y0, 0.0, ROAD)
    b.flat(f"rd_{lane}_6", 6, y0, 0.0, ROAD)

# =================================================================
# 2. 南北人行道 (y [1,2] / [4,5]): 西段长板, 梯塔梯箱脚下全用方板
#    (墙脚与坡道都要整边踩在拼缝上)
# =================================================================
b.flat_rect("wk_s_w", 0, 1, 0.0, WALK)
for x in range(2, 7):
    b.flat(f"wk_s_{x}", x, 1, 0.0, WALK)
b.flat_rect("wk_n_w", 0, 4, 0.0, WALK)
for x in range(2, 7):
    b.flat(f"wk_n_{x}", x, 4, 0.0, WALK)

# =================================================================
# 3. 南梯塔 (x [3,5], y [1,2]): 两层墙环 + 压顶长板
# =================================================================
def stair_tower(prefix, y_s, y_n, y0):
    """2x1 两层梯塔: 6 墙/层, 二层东西嵌透明窗格方, 压顶长板。"""
    # 一层墙环 (z 0..1)
    b.wall_ns(f"{prefix}1_s3", 3, y_s, 0, TOWER)
    b.wall_ns(f"{prefix}1_s4", 4, y_s, 0, TOWER)
    b.wall_ns(f"{prefix}1_n3", 3, y_n, 0, TOWER)
    b.wall_ns(f"{prefix}1_n4", 4, y_n, 0, TOWER)
    b.wall_ew(f"{prefix}1_w", 3.0, y0, 0, TOWER)
    b.wall_ew(f"{prefix}1_e", 5.0, y0, 0, TOWER)
    # 二层墙环 (z 1..2): 东西两面透明候梯厅窗
    b.wall_ns(f"{prefix}2_s3", 3, y_s, 1, TOWER)
    b.wall_ns(f"{prefix}2_s4", 4, y_s, 1, TOWER)
    b.wall_ns(f"{prefix}2_n3", 3, y_n, 1, TOWER)
    b.wall_ns(f"{prefix}2_n4", 4, y_n, 1, TOWER)
    b.add(f"{prefix}2_w", "window_square", (3.0, y0 + 0.5, 1.5), (90, 0, 90), WIN)
    b.add(f"{prefix}2_e", "window_square", (5.0, y0 + 0.5, 1.5), (90, 0, 90), WIN)
    # 压顶长板 (z=2, 即登桥平台)
    b.flat_rect(f"{prefix}_cap", 3, y0, 2.0, CAP)


def stair_box(prefix, y_s, y_n, y0):
    """1x1 梯箱 (x [5,6], z 0..1): 西墙借梯塔东墙, 压顶方板 + 坡道。"""
    b.wall_ns(f"{prefix}b_s", 5, y_s, 0, BOX)
    b.wall_ns(f"{prefix}b_n", 5, y_n, 0, BOX)
    b.wall_ew(f"{prefix}b_e", 6.0, y0, 0, BOX)
    b.flat(f"{prefix}b_cap", 5, y0, 1.0, CAP)
    b.ramp(f"{prefix}_ramp", "+x", 6, y0, 1.0, RAMP)


stair_tower("s", 1.0, 2.0, 1)
stair_box("s", 1.0, 2.0, 1)
stair_tower("n", 4.0, 5.0, 4)
stair_box("n", 4.0, 5.0, 4)

# =================================================================
# 4. 桥面单跨 + 透明防风屏 + 标志牌
# =================================================================
b.flat_rect("deck", 3, 2, 2.0, CAP, axis="y")       # 单跨长板横跨双车道
b.lintel_ew("rail_w", 3.0, 2, 2, RAIL)              # 西防风屏 (整长边压桥沿)
b.lintel_ew("rail_e", 4.0, 2, 2, RAIL)              # 东防风屏
b.spire_ns("sign_s", 3, 1.0, 2.0, SIGN)             # 南标志牌 (骑压顶南沿)
b.spire_ns("sign_n", 4, 5.0, 2.0, SIGN)             # 北标志牌 (骑压顶北沿)

# =================================================================
# 5. 小红车 (x [0,2], 南车道东行): 正从桥下通过
# =================================================================
b.add("car_wh_s", "wheel_base", (1.0, 2.0, 0.5), (90, 0, 0), WHEEL)
b.add("car_wh_n", "wheel_base", (1.0, 3.0, 0.5), (90, 0, 0), WHEEL)
b.flat_rect("car_top", 0, 2, 1.0, CAR)              # 车顶长板 (双长边压轮顶)
b.crest_ew("car_cab", 2.0, 2, 1.0, CAR)             # 驾驶舱 (骑车顶东短边, 车头朝桥)

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺南车道: 3 片灰色长板 + 1 片方板沿东西向排开 (y [2,3])。",
    ["rd_s_0", "rd_s_2", "rd_s_4", "rd_s_6"],
    tip="桥下要过汽车 —— 马路先通, 天桥后架。",
)
b.step(
    "铺北车道: 再排 4 片 (y [3,4]), 双车道长边整边互吸。",
    ["rd_n_0", "rd_n_2", "rd_n_4", "rd_n_6"],
    highlight=["rd_s_0"],
    tip="两条车道拼成 7 格长的马路 —— 天桥就跨在正中间。",
)
b.step(
    "铺南人行道 (y [1,2]): 西段长板, 梯塔脚下 5 片方板。",
    ["wk_s_w", "wk_s_2", "wk_s_3", "wk_s_4", "wk_s_5", "wk_s_6"],
    highlight=["rd_s_2"],
    tip="梯塔与梯箱的墙脚都要整边踩在方板拼缝上 —— 方板一格都不能省。",
)
b.step(
    "铺北人行道 (y [4,5]): 与南侧镜像。",
    ["wk_n_w", "wk_n_2", "wk_n_3", "wk_n_4", "wk_n_5", "wk_n_6"],
    highlight=["rd_n_2"],
    tip="南上北下 —— 两条人行道就是天桥的起点和终点。",
)
b.step(
    "立南梯塔一层 (x [3,5]): 6 片蓝墙合环, 四角竖边互吸自锁。",
    ["s1_s3", "s1_s4", "s1_n3", "s1_n4", "s1_w", "s1_e"],
    highlight=["wk_s_3", "wk_s_4"],
    tip="闭环墙比单面墙稳得多 —— 这座塔要托起整块桥面。",
)
b.step(
    "立南梯塔二层并压顶: 东西两面换透明窗格方 (候梯厅窗), 灰色长板压顶即登桥平台。",
    ["s2_s3", "s2_s4", "s2_n3", "s2_n4", "s2_w", "s2_e", "s_cap"],
    highlight=["s1_s3", "s1_e"],
    tip="压顶长板四边都咬着墙顶 —— 二层环 + 压顶锁成一只结实的箱子。",
)
b.step(
    "搭南梯箱与无障碍坡道: 梯箱借梯塔东墙合环, 方板压顶, 橙色坡道顶边吸箱沿、坡尾落地。",
    ["sb_s", "sb_n", "sb_e", "sb_cap", "s_ramp"],
    highlight=["s1_e"],
    tip="地面->坡道->梯箱->梯塔, 一条完整的无障碍动线 —— 推婴儿车也能上桥。",
)
b.step(
    "立北梯塔一层: 与南塔隔马路对望。",
    ["n1_s3", "n1_s4", "n1_n3", "n1_n4", "n1_w", "n1_e"],
    highlight=["wk_n_3", "wk_n_4"],
    tip="两座塔正对齐 —— 桥面两端就搭在它们头顶。",
)
b.step(
    "立北梯塔二层并压顶: 与南塔完全镜像。",
    ["n2_s3", "n2_s4", "n2_n3", "n2_n4", "n2_w", "n2_e", "n_cap"],
    highlight=["n1_s3", "n1_e"],
    tip="两块压顶板同高 z=2 —— 桥面一放就是水平的。",
)
b.step(
    "搭北梯箱与坡道: 镜像收尾, 北侧动线贯通。",
    ["nb_s", "nb_n", "nb_e", "nb_cap", "n_ramp"],
    highlight=["n1_e"],
    tip="两条坡道都朝东 —— 上桥下桥各走各的, 不打架。",
)
b.step(
    "架桥面装防风屏: 灰色长板两短边同吸南北塔墙顶 (双端受力零悬挑, "
    "跨中零铰链缝), 两片透明防风屏整长边压上桥沿。",
    ["deck", "rail_w", "rail_e"],
    highlight=["s_cap", "n_cap"],
    tip="剪断任一端铰链, 另一端仍把桥面拉在塔上 —— 这就是双端受力。",
)
b.step(
    "立天桥标志牌: 两面蓝色等腰高牌骑上压顶沿口 (顶高 4.0, 全场最高)。",
    ["sign_s", "sign_n"],
    highlight=["s_cap", "n_cap"],
    tip="标志牌重心正压铰链线 —— 力矩为零, 站得笔直。",
)
b.step(
    "小红车从桥下通过: 车轮底座整边吸车道拼缝, 长板车顶压轮顶, 车头朝东。",
    ["car_wh_s", "car_wh_n", "car_top", "car_cab"],
    highlight=["deck"],
    tip="桥下净空整整 2 格 —— 人在桥上走, 车在桥下跑, 谁也不用等谁。",
)

b.finalize(
    model_id="pedestrian_overpass_01",
    name="人行过街天桥",
    name_en="Pedestrian Overpass 01",
    description=(
        "只用核心九片型的过街天桥: 与跨河的悬索桥/廊桥/木桥不同, 它跨"
        "的是正在通车的马路 —— 桥下留足 2 格净空, 桥面被顶到 z=2, 于是"
        "结构逻辑变成'先把人送上两层楼': 南北两座 2x1 两层梯塔墙环环环"
        "相扣, 二层嵌透明窗格方候梯厅窗, 压顶长板即登桥平台; 塔旁梯箱"
        "作半程踏步, 30 度无障碍坡道坡尾自己落地 —— 地面->坡道->梯箱->"
        "梯塔->桥面一条完整动线; 桥面单跨长板两短边同吸两塔墙顶 (双端"
        "受力, 跨中零铰链缝), 透明防风屏整长边压桥沿, 蓝色标志牌直上"
        " 4.0; 一辆小红车正从桥下东行 —— 人车分流, 谁也不用等谁。"
    ),
    difficulty=3,
    tags=["城市", "交通", "天桥", "街景", "进阶"],
    min_pieces=65,
    min_steps=13,
)
