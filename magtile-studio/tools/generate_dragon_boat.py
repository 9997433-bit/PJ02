#!/usr/bin/env python3
"""生成模型 data/models/dragon_boat_01.json (龙舟)。

第三批模型 ⑤: 民俗节庆主题 —— 端午龙舟: 8x5 江面上一条
6 格长的箱形龙舟破浪而行, 船艏立着六边形大龙头 (头顶黄色
龙角), 船艉一片等腰龙尾高高翘起, 两舷各 3 支菱形船桨以
45 度外倾齐齐入水, 船腰红色鼓亭助威, 江面浪花点点。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 江面 8x5                                                40 片
  - 船体: 两舷 12 + 艏艉端板 2 + 甲板 6                     20 片
  - 龙头 + 龙角: 六边形 x1 + 等边三角 x1                     2 片
  - 龙尾 + 鼓亭: 等腰三角 x1 + 等边三角 x1                   2 片
  - 船桨: 菱形 x6 (两舷各 3, 45 度外倾)                      6 片
  - 浪花: 等边三角 x2                                        2 片
  合计 72 片, 17 个教程步骤, 5 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 甲板两长边坐在两舷墙顶上, 船体是完整箱形梁;
  - 龙头六边形立于竖直平面 (力矩为零), 底边整边吸甲板艏沿,
    龙角底边吸龙头顶边 (共面吸合, 不重叠);
  - 船桨菱形以 45 度外倾, 底边同时吸住江面格线与船舷墙底;
  - 全部立件在放置瞬间接地或有整边吸合 (R7a)。

用法: python3 tools/generate_dragon_boat.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import HEX_APOTHEM, ModelBuilder  # noqa: E402

b = ModelBuilder()

# =================================================================
# 1. 江面 8x5: 蓝色为主, 青色浪涌错落
# =================================================================
for j in range(5):
    for i in range(8):
        b.flat(f"rv_{i}_{j}", i, j, 0.0,
               "cyan" if (i * 2 + j * 3) % 7 == 0 else "blue")

# =================================================================
# 2. 船体: 6 格长箱形 (x 1..7, y 2..3), 红舷黄甲板
# =================================================================
for i in range(6):
    b.wall_ns(f"bt_s_{i}", 1 + i, 2.0, 0, "red")     # 南舷
for i in range(6):
    b.wall_ns(f"bt_n_{i}", 1 + i, 3.0, 0, "red")     # 北舷
b.wall_ew("bt_bow", 1.0, 2, 0, "red")                # 艏板
b.wall_ew("bt_stern", 7.0, 2, 0, "red")              # 艉板
for i in range(6):
    b.flat(f"bt_d_{i}", 1 + i, 2, 1.0, "yellow" if i % 2 == 0 else "orange")

# =================================================================
# 3. 龙头 (船艏 x=1 竖直面) + 龙角 + 龙尾 + 鼓亭
# =================================================================
b.add("head", "hexagon", (1.0, 2.5, 1 + HEX_APOTHEM), (90, 0, 90), "red")
b.crest_ew("horn", 1.0, 2, round(1 + 2 * HEX_APOTHEM, 6), "yellow")  # 龙角
b.spire_ew("tail", 7.0, 2, 1.0, "purple")            # 龙尾 (艉沿上翘)
b.crest_ew("drum", 4.0, 2, 1.0, "orange")            # 船腰鼓亭

# =================================================================
# 4. 船桨: 两舷各 3 支菱形, 45 度外倾入水
# =================================================================
OARS_S, OARS_N = [], []
for k, x in enumerate((2, 4, 6)):
    tid = f"oar_s_{k}"
    b.place_edge(tid, "rhombus", 0, (float(x), 2.0, 0.0),
                 (float(x + 1), 2.0, 0.0), (0.0, -1.0, 1.0), "yellow")
    OARS_S.append(tid)
for k, x in enumerate((2, 4, 6)):
    tid = f"oar_n_{k}"
    b.place_edge(tid, "rhombus", 0, (float(x), 3.0, 0.0),
                 (float(x + 1), 3.0, 0.0), (0.0, 1.0, 1.0), "yellow")
    OARS_N.append(tid)

# =================================================================
# 5. 浪花: 艏前与艉后各 1 片青色等边三角立在江面格线上
# =================================================================
b.crest_ns("wave_w", 0, 2.0, 0.0, "cyan")
b.crest_ns("wave_e", 7, 4.0, 0.0, "cyan")

# =================================================================
# 教程步骤 (17 步): 江面 -> 船体 -> 甲板 -> 龙头龙尾 -> 桨与浪
# =================================================================
for j in range(5):
    tips = [
        "江面铺在桌面中央, 龙舟要从西向东破浪。",
        "青色是浪涌翻起的地方, 请按图错落分布。",
        "这一排正是龙舟下水的航道。",
        "江面已过大半, 保持整片平整不留缝。",
        "8x5 大江就绪 —— 擂鼓, 龙舟进场!",
    ]
    b.step(
        f"铺江面第 {j + 1} 排: 8 片方板沿东西向整边吸合。",
        [f"rv_{i}_{j}" for i in range(8)],
        highlight=[f"rv_0_{j - 1}"] if j > 0 else [],
        tip=tips[j],
    )
b.step(
    "立南舷: 沿 y=2 立 6 片红色正方形, 底边吸江面格线。",
    [f"bt_s_{i}" for i in range(6)],
    highlight=["rv_1_2"],
    tip="竖边两两互吸 —— 船身越长, 越要一片片扣紧。",
)
b.step(
    "立北舷: 沿 y=3 再立 6 片, 与南舷平行相距 1 格。",
    [f"bt_n_{i}" for i in range(6)],
    highlight=["bt_s_0"],
    tip="两舷之间的窄槽就是龙舟修长的船腹。",
)
b.step(
    "封艏艉端板: 西端 (x=1) 与东端 (x=7) 各立 1 片, 船体合围。",
    ["bt_bow", "bt_stern"],
    highlight=["bt_s_0", "bt_n_5"],
    tip="端板竖边与两舷竖边互吸, 箱形船体一次锁定。",
)
b.step(
    "铺甲板西段: 3 片黄橙相间的方板压在两舷墙顶上 (x 1..4)。",
    [f"bt_d_{i}" for i in range(3)],
    highlight=["bt_bow"],
    tip="甲板两长边分别吸住两舷顶边 —— 划手就站在这上面。",
)
b.step(
    "铺甲板东段: 再压 3 片, 甲板通长贯通 (x 4..7)。",
    [f"bt_d_{i}" for i in range(3, 6)],
    highlight=["bt_d_2"],
    tip="轻压甲板检查: 应结实得能托住龙头龙尾。",
)
b.step(
    "请龙头: 红色六边形立在甲板艏沿 (x=1) 竖直面内, 面朝前方。",
    ["head"],
    highlight=["bt_d_0"],
    tip="底边整边吸住甲板艏沿与艏板顶边 —— 龙头昂起 1.7 格高。",
)
b.step(
    "装龙角: 黄色等边三角形底边吸在龙头顶边上, 与龙头共面。",
    ["horn"],
    highlight=["head"],
    tip="龙角越尖越神气 —— 顶点升到 3.6 格高, 全船最高点。",
)
b.step(
    "翘龙尾: 紫色等腰三角形立在甲板艉沿 (x=7), 尾尖直指天空。",
    ["tail"],
    highlight=["bt_d_5"],
    tip="底边同时吸甲板艉沿与艉板顶边, 龙尾高高翘起。",
)
b.step(
    "搭鼓亭: 橙色等边三角形立在船腰甲板缝上 (x=4) —— 鼓手就位!",
    ["drum"],
    highlight=["bt_d_2", "bt_d_3"],
    tip="底边吸住甲板中缝, 亭尖朝上 —— 咚! 咚! 咚!",
)
b.step(
    "插南舷船桨: 3 支黄色菱形桨以 45 度外倾, 底边同时吸江面格线"
    "与船舷墙底。",
    OARS_S,
    highlight=["bt_s_1", "bt_s_3"],
    tip="三支桨间隔均匀, 桨叶斜斜切入江面。",
)
b.step(
    "插北舷船桨: 与南舷镜像, 3 支桨齐齐入水。",
    OARS_N,
    highlight=["oar_s_0"],
    tip="从船艏望去, 两舷桨叶展开像龙的爪子。",
)
b.step(
    "点浪花: 艏前与艉后各立 1 片青色等边三角浪花 —— 鼓声起, 龙舟夺标!",
    ["wave_w", "wave_e"],
    highlight=["head", "tail"],
    tip="浪花底边吸江面格线 —— 端午安康, 冲线!",
)

b.finalize(
    model_id="dragon_boat_01",
    name="龙舟",
    name_en="Dragon Boat 01",
    description=(
        "民俗节庆主题: 8x5 江面上一条 6 格长的箱形龙舟破浪而行 —— 两舷 + "
        "艏艉端板 + 通长甲板锁成箱形梁; 船艏六边形大龙头昂起 1.7 格高, "
        "头顶黄色龙角直指 3.6 格, 船艉紫色龙尾高翘, 船腰鼓亭助威; 两舷"
        "各 3 支菱形船桨以 45 度外倾齐齐入水, 底边同时吸住江面与船舷 —— "
        "咚咚鼓声里, 这是全库第一条节庆之船。"
    ),
    difficulty=3,
    tags=["民俗", "龙舟", "船", "端午", "进阶"],
    min_pieces=50,
    min_steps=16,
)
