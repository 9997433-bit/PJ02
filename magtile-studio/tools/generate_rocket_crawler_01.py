#!/usr/bin/env python3
"""生成模型 data/models/rocket_crawler_01.json (火箭转运车)。

太空探索主题批 3/4: 全库第一次"整箭移动转运" —— 与火箭发射台的
盒式发射架 + 勤务塔 (垂直总装) 完全不同, 本作的火箭是"在路上"的:
四片车轮底座驮起平台甲板, 三级白-青-橙箭体立在甲板拼缝上层层
合环, 红色四坡整流罩尖端 4.71; 甲板东半是蓝色驾驶指挥舱,
与箭体一级共用一片橙色登舱门 (共墙技法), 舱顶长板反手咬住
二级箭体底边把舱-箭锁成一体; 灰色转运道旁草坪上, 护送旗与
信号灯杆目送火箭走向发射区 —— 慢一点, 稳一点, 就快到了!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 转运道东西向):
  - 转运道 (y [0,3]): 灰色长板三行 x12                          12 片
  - 草坪 (y [3,4]): 绿色长板 x4                                   4 片
  - 车轮底座 x4: 双轴双列, 底边与道面长板整边精确贴合             4 片
  - 平台甲板 (z=1): 长板 x1 + 方板 x2 (拼缝正好卡出箭位)          3 片
  - 箭体三级 (x [3,4], z 1..4): 一级白墙 x3 + 橙色登舱门框 x1,
    二级白墙 x3 + 青色徽标舷窗 x1, 三级橙墙 x4                  12 片
  - 整流罩: 红色等边四坡锥, 尖端 4.71                             4 片
  - 驾驶指挥舱 (x [4,6], z 1..2): 清色驾驶窗 x2 + 蓝墙 x3 +
    舱顶长板 (西短边反手咬二级箭体底边)                           6 片
  - 护送旗 x2 + 信号灯杆 (方柱 + 黄灯)                            4 片
  合计 49 片, 12 个教程步骤, 7 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 车轮底座底边 (长 2) 与道面长板北/南长边完全等长精确贴合,
    甲板长板长边整边压双轮顶 —— 轮组-甲板锁成门式框架;
  - 箭体逐级四墙合环 (四角竖边互咬), 一级墙脚踩甲板拼缝,
    级间横边整边互吸 —— 高塔满环路, R8 冗余通过;
  - 驾驶舱与箭体一级共用登舱门框那片墙 (共墙技法, 杜绝共面重叠),
    舱顶长板四边受力且西短边反手咬住二级箭体底边 (空间电梯同款);
  - 剪断甲板任何一条铰链线: 甲板经另一列车轮接地, 箭体墙经
    拐角竖边互咬保持成环 —— 零悬挂零超限力矩;
  - 灯杆立柱底边吸草坪拼缝且自身接地, 黄灯/护送旗都是单片装饰,
    剪断最多失联 1 片 (< 3), 单点失效通过。

用法: python3 tools/generate_rocket_crawler_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

ROAD = "gray"       # 转运道
GRASS = "green"     # 草坪
WHEEL = "gray"      # 车轮底座
DECK = "yellow"     # 平台甲板
STAGE1 = "clear"    # 一级箭体 (白)
HATCH = "orange"    # 登舱门
STAGE2 = "clear"    # 二级箭体 (白)
EMBLEM = "cyan"     # 徽标舷窗
STAGE3 = "orange"   # 三级箭体
NOSE = "red"        # 整流罩
CAB = "blue"        # 驾驶指挥舱
SHIELD = "clear"    # 驾驶窗
FLAG = "red"        # 护送旗
POLE = "gray"       # 信号灯杆
LAMP = "yellow"     # 信号黄灯


def wall_ns_t(tid, tile_type, x0, y, z0, color):
    b.add(tid, tile_type, (x0 + 0.5, y, z0 + 0.5), (90, 0, 0), color)


def wall_ew_t(tid, tile_type, x, y0, z0, color):
    b.add(tid, tile_type, (x, y0 + 0.5, z0 + 0.5), (90, 0, 90), color)


# =================================================================
# 1. 场地: 灰色转运道三行 (y [0,3]) + 绿色草坪 (y [3,4]),
#    全部 [0,2]/[2,4]/[4,6]/[6,8] 对齐 —— 车轮底边有等长道缝可吸
# =================================================================
for row, y0 in (("s", 0), ("m", 1), ("n", 2)):
    for i, x0 in enumerate((0, 2, 4, 6)):
        b.flat_rect(f"rd_{row}{i}", x0, y0, 0.0, ROAD)
for i, x0 in enumerate((0, 2, 4, 6)):
    b.flat_rect(f"gr_{i}", x0, 3, 0.0, GRASS)

# =================================================================
# 2. 转运车: 双轴双列车轮底座 x4 + 平台甲板 (z=1)
# =================================================================
b.add("wh_sw", "wheel_base", (3.0, 1.0, 0.5), (90, 0, 0), WHEEL)
b.add("wh_se", "wheel_base", (5.0, 1.0, 0.5), (90, 0, 0), WHEEL)
b.add("wh_nw", "wheel_base", (3.0, 2.0, 0.5), (90, 0, 0), WHEEL)
b.add("wh_ne", "wheel_base", (5.0, 2.0, 0.5), (90, 0, 0), WHEEL)
b.flat_rect("deck_e", 4, 1, 1.0, DECK)   # 长板长边整边压东列双轮顶
b.flat("deck_m", 3, 1, 1.0, DECK)        # 两片方板拼缝卡出箭位
b.flat("deck_w", 2, 1, 1.0, DECK)

# =================================================================
# 3. 箭体三级 (x [3,4], y [1,2]): 逐级四墙合环
# =================================================================
b.wall_ns("r1_s", 3, 1.0, 1, STAGE1)
b.wall_ns("r1_n", 3, 2.0, 1, STAGE1)
b.wall_ew("r1_w", 3.0, 1, 1, STAGE1)
wall_ew_t("r1_hatch", "door_frame", 4.0, 1, 1, HATCH)   # 登舱门 (与驾驶舱共墙)

wall_ns_t("r2_s", "window_square", 3, 1.0, 2, EMBLEM)   # 徽标舷窗朝南
b.wall_ns("r2_n", 3, 2.0, 2, STAGE2)
b.wall_ew("r2_w", 3.0, 1, 2, STAGE2)
b.wall_ew("r2_e", 4.0, 1, 2, STAGE2)

b.wall_ns("r3_s", 3, 1.0, 3, STAGE3)
b.wall_ns("r3_n", 3, 2.0, 3, STAGE3)
b.wall_ew("r3_w", 3.0, 1, 3, STAGE3)
b.wall_ew("r3_e", 4.0, 1, 3, STAGE3)

NOSE_IDS = b.hat4("nose", 3, 1, 4.0, NOSE, shape="equilateral_triangle")

# =================================================================
# 4. 驾驶指挥舱 (x [4,6], y [1,2], z 1..2): 与箭体共用登舱门那片墙
# =================================================================
b.wall_ew("cab_e", 6.0, 1, 1, CAB)
wall_ns_t("cab_s2", "window_square", 5, 1.0, 1, SHIELD)   # 驾驶窗朝南
wall_ns_t("cab_s1", "window_square", 4, 1.0, 1, SHIELD)
b.wall_ns("cab_n2", 5, 2.0, 1, CAB)
b.wall_ns("cab_n1", 4, 2.0, 1, CAB)
b.flat_rect("cab_top", 4, 1, 2.0, CAB)   # 西短边反手咬二级箭体底边

# =================================================================
# 5. 护送旗 x2 + 信号灯杆 (立在草坪拼缝上)
# =================================================================
b.crest_ew("flag_w", 2.0, 3, 0.0, FLAG)
b.crest_ew("flag_e", 6.0, 3, 0.0, FLAG)
b.wall_ew("pole", 4.0, 3, 0, POLE)
b.crest_ew("lamp", 4.0, 3, 1.0, LAMP)

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺转运道南行: 四条灰色长板短边互吸连成路。",
    ["rd_s0", "rd_s1", "rd_s2", "rd_s3"],
    tip="从总装厂房到发射区有一条专用转运道 —— 今天火箭要搬家。",
)
b.step(
    "铺转运道中行: 车轮就压在这行与邻行的长缝上。",
    ["rd_m0", "rd_m1", "rd_m2", "rd_m3"],
    highlight=["rd_s0"],
    tip="长板行行对齐, 每条长缝都是等长磁边 —— 车轮的轨道。",
)
b.step(
    "铺转运道北行: 三行道面合拢。",
    ["rd_n0", "rd_n1", "rd_n2", "rd_n3"],
    highlight=["rd_m0"],
    tip="道面越宽越稳 —— 转运车是发射场里最慢也最稳的车。",
)
b.step(
    "铺草坪行: 四条绿色长板沿道北排开。",
    ["gr_0", "gr_1", "gr_2", "gr_3"],
    highlight=["rd_n0"],
    tip="护送队就站在草坪上, 目送火箭走完全程。",
)
b.step(
    "装车轮底座: 双轴双列四片, 底边与道缝完全等长精确贴合。",
    ["wh_sw", "wh_se", "wh_nw", "wh_ne"],
    highlight=["rd_m1", "rd_m2"],
    tip="车轮底座长 2, 道面长板也长 2 —— 整边对整边, 一格不差。",
)
b.step(
    "架平台甲板: 长板长边整边压东列双轮顶, 两片方板向西拼缝。",
    ["deck_e", "deck_m", "deck_w"],
    highlight=["wh_se", "wh_ne"],
    tip="轮组加甲板锁成门式框架 —— 方板拼缝正好卡出箭体的位置。",
)
b.step(
    "立箭体一级: 白墙三片合上橙色登舱门框, 四角竖边互咬成环。",
    ["r1_s", "r1_n", "r1_w", "r1_hatch"],
    highlight=["deck_m"],
    tip="墙脚踩甲板拼缝 —— 登舱门朝东, 等会儿驾驶舱就贴在门外。",
)
b.step(
    "搭驾驶指挥舱: 东墙先立, 南北墙拐角互咬, 舱顶长板盖严。",
    ["cab_e", "cab_s2", "cab_s1", "cab_n2", "cab_n1", "cab_top"],
    highlight=["r1_hatch"],
    tip="驾驶舱与箭体一级共用登舱门那片墙 —— 司机敲敲门就能问好。",
)
b.step(
    "立箭体二级: 青色徽标舷窗朝南, 级间横边整边互吸。",
    ["r2_s", "r2_n", "r2_w", "r2_e"],
    highlight=["cab_top"],
    tip="二级底边还被舱顶长板反手咬住一口 —— 舱与箭锁成一体。",
)
b.step(
    "立箭体三级: 橙色整流段四墙合环, 箭体越来越高。",
    ["r3_s", "r3_n", "r3_w", "r3_e"],
    highlight=["r2_s"],
    tip="每一级都是完整的环 —— 高塔的秘密就是层层闭环。",
)
b.step(
    "戴整流罩: 红色等边四坡锥四棱互咬自锁, 尖端 4.71。",
    NOSE_IDS,
    highlight=["r3_s"],
    tip="整流罩里包着真正的乘客 —— 一颗崭新的探测器。",
)
b.step(
    "护送队就位收尾: 红旗两面插草缝, 信号灯杆亮起黄灯。",
    ["flag_w", "flag_e", "pole", "lamp"],
    highlight=["nose_s"],
    tip="黄灯亮 —— 全线放行! 明天清晨, 它就从这条路的尽头起飞。",
)

b.finalize(
    model_id="rocket_crawler_01",
    name="火箭转运车",
    name_en="Rocket Crawler 01",
    description=(
        "只用核心九片型的整箭转运现场: 与发射台的盒式发射架 + 勤务塔"
        "不同, 这枚火箭是'在路上'的 —— 四片车轮底座底边与道面长板"
        "整边精确贴合, 驮起平台甲板锁成门式框架; 三级白-青-橙箭体"
        "立在甲板拼缝上逐级四墙合环, 红色四坡整流罩尖端 4.71; 蓝色"
        "驾驶指挥舱与箭体一级共用一片橙色登舱门 (共墙技法), 舱顶长板"
        "反手咬住二级底边把舱-箭锁成一体; 道旁护送旗与信号黄灯放行 "
        "—— 慢一点, 稳一点, 发射区就快到了!"
    ),
    difficulty=3,
    tags=["航天", "火箭", "转运车", "发射场", "进阶"],
    min_pieces=49,
    min_steps=12,
)
