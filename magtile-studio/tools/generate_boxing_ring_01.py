#!/usr/bin/env python3
"""生成模型 data/models/boxing_ring_01.json (拳击台)。

运动健身主题批 3/3: 全库第一座格斗擂台 —— 与攀岩塔 (立式爬塔)、
保龄球馆 (长道瓶阵) 再次错开结构词汇: 本作的主角是"抬升的正方形
擂台 + 一圈开顶围绳": 2x2 擂台箱体先合环压顶, 台面上再骑一圈
红白相间的开顶围绳环 (只围不盖, 全库唯一的开顶二层环), 四角
角旗红蓝白各就各位; 台边红色训练锥立在灰色底柱上, 青色计时台
面朝擂台 —— 没有第二个模型用"箱体 + 开顶环"这对组合。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 场地垫 (x [1,6], y [1,5]): 台下方板 x4 + 东西廊 x4 + 训练角
    方板 x2 + 南北长板 x4                                        14 片
  - 擂台 (x [2,4], y [2,4], z 0..1): 环墙 x8 + 台面 x4           12 片
  - 围绳环 (z 1..2): 红白相间开顶环 x8                            8 片
  - 角旗 x4: 红角/蓝角/两白 (等边三角骑围绳顶沿)                  4 片
  - 立式训练锥 (x [5,6], y [2,3]): 底柱环墙 x4 + 红锥 x1          5 片
  - 计时台 (x [1,2], y [4,5]): 立墙 x2 + 台面 x1                  3 片
  合计 46 片, 10 个教程步骤, 4 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 擂台为"环墙合环 + 台面压顶"闭环箱体, 台面四片互吸拼缝;
  - 围绳环 8 片整边骑台面沿口 (同吸台面边与下层墙顶, 一线双吸),
    四角竖边互咬合环 —— 开顶不封盖, 环拓扑照样闭合;
  - 角旗骑围绳顶沿, 重心正压铰链线力矩为零, 剪断只失联 1 片;
  - 训练锥底柱四墙踩单位方板拼缝合环, 红色等腰锥骑柱顶 (锥尖
    3.0); 计时台两墙夹一盖, 盖板两边各吸一道墙顶;
  - 场地垫拼缝纪律: 擂台与底柱墙脚线处处是单位方板等长拼缝,
    南北长板与邻板短边互吸保证全场连通。

用法: python3 tools/generate_boxing_ring_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

MAT_U = "gray"      # 台下方板
MAT_S = "green"     # 场边地垫
APRON = "blue"      # 擂台围裙 (环墙)
CANVAS = "clear"    # 台面帆布
ROPE_A = "red"      # 围绳 (红)
ROPE_B = "clear"    # 围绳 (白)
FLAG_R = "red"      # 红角
FLAG_B = "blue"     # 蓝角
FLAG_N = "clear"    # 中立角 (白)
POST = "gray"       # 训练锥底柱
CONE = "red"        # 训练锥
DESK = "cyan"       # 计时台

# =================================================================
# 1. 场地垫: 台下 2x2 方板 + 东西廊方板 + 训练角方板 + 南北长板
# =================================================================
for x0 in (2, 3):
    for y0 in (2, 3):
        b.flat(f"mat_u_{x0}_{y0}", x0, y0, 0.0, MAT_U)   # 台下
for y0 in (2, 3):
    b.flat(f"mat_w_{y0}", 1, y0, 0.0, MAT_S)             # 西廊
    b.flat(f"mat_e_{y0}", 4, y0, 0.0, MAT_S)             # 东廊
    b.flat(f"mat_t_{y0}", 5, y0, 0.0, MAT_S)             # 训练角
b.flat_rect("mat_s_w", 1, 1, 0.0, MAT_S)                 # 南排长板
b.flat_rect("mat_s_e", 3, 1, 0.0, MAT_S)
b.flat_rect("mat_n_w", 1, 4, 0.0, MAT_S)                 # 北排长板
b.flat_rect("mat_n_e", 3, 4, 0.0, MAT_S)

# =================================================================
# 2. 擂台箱体 (x [2,4], y [2,4], z 0..1): 环墙合环 + 台面压顶
# =================================================================
for x0 in (2, 3):
    b.wall_ns(f"ring_s_{x0}", x0, 2.0, 0, APRON)
    b.wall_ns(f"ring_n_{x0}", x0, 4.0, 0, APRON)
for y0 in (2, 3):
    b.wall_ew(f"ring_w_{y0}", 2.0, y0, 0, APRON)
    b.wall_ew(f"ring_e_{y0}", 4.0, y0, 0, APRON)
for x0 in (2, 3):
    for y0 in (2, 3):
        b.flat(f"canvas_{x0}_{y0}", x0, y0, 1.0, CANVAS)

# =================================================================
# 3. 围绳环 (z 1..2): 红白相间, 开顶合环
# =================================================================
b.wall_ns("rope_s_2", 2, 2.0, 1, ROPE_A)
b.wall_ns("rope_s_3", 3, 2.0, 1, ROPE_B)
b.wall_ns("rope_n_2", 2, 4.0, 1, ROPE_B)
b.wall_ns("rope_n_3", 3, 4.0, 1, ROPE_A)
b.wall_ew("rope_w_2", 2.0, 2, 1, ROPE_B)
b.wall_ew("rope_w_3", 2.0, 3, 1, ROPE_A)
b.wall_ew("rope_e_2", 4.0, 2, 1, ROPE_A)
b.wall_ew("rope_e_3", 4.0, 3, 1, ROPE_B)

# =================================================================
# 4. 角旗 x4: 红角西南, 蓝角东北, 两个中立角白色
# =================================================================
b.crest_ns("flag_red", 2, 2.0, 2.0, FLAG_R)      # 红角 (南沿西格)
b.crest_ns("flag_blue", 3, 4.0, 2.0, FLAG_B)     # 蓝角 (北沿东格)
b.crest_ew("flag_nw", 2.0, 3, 2.0, FLAG_N)       # 中立角 (西沿北格)
b.crest_ew("flag_se", 4.0, 2, 2.0, FLAG_N)       # 中立角 (东沿南格)

# =================================================================
# 5. 立式训练锥 (x [5,6], y [2,3]): 底柱合环 + 红锥骑顶
# =================================================================
b.wall_ns("post_s", 5, 2.0, 0, POST)
b.wall_ns("post_n", 5, 3.0, 0, POST)
b.wall_ew("post_w", 5.0, 2, 0, POST)
b.wall_ew("post_e", 6.0, 2, 0, POST)
b.spire_ns("cone", 5, 2.0, 1.0, CONE)            # 锥尖 3.0

# =================================================================
# 6. 计时台 (x [1,2], y [4,5]): 两墙夹一盖
# =================================================================
b.wall_ns("desk_s", 1, 4.0, 0, DESK)
b.wall_ns("desk_n", 1, 5.0, 0, DESK)
b.flat("desk_top", 1, 4, 1.0, DESK)

# =================================================================
# 教程步骤 (10 步)
# =================================================================
b.step(
    "铺台下与两廊地垫: 台下四片灰色方板, 东西两廊与训练角绿色方板。",
    ["mat_u_2_2", "mat_u_3_2", "mat_u_2_3", "mat_u_3_3",
     "mat_w_2", "mat_w_3", "mat_e_2", "mat_e_3", "mat_t_2", "mat_t_3"],
    tip="擂台的八道墙脚全踩在灰色方板的拼缝上 —— 先把地基铺方正。",
)
b.step(
    "铺南北长板: 四条绿色长板短边互吸, 场地垫连成一整张。",
    ["mat_s_w", "mat_s_e", "mat_n_w", "mat_n_e"],
    highlight=["mat_u_2_2"],
    tip="长板与方板行行相咬 —— 观众区和擂台区从此连成一体。",
)
b.step(
    "立擂台南墙与西墙: 蓝色围裙墙踩灰板拼缝, 拐角竖边互咬。",
    ["ring_s_2", "ring_s_3", "ring_w_2", "ring_w_3"],
    highlight=["mat_u_2_2"],
    tip="拐角一咬, 排墙就立成了直角 —— 擂台从西南角长起。",
)
b.step(
    "立擂台北墙与东墙合环: 环墙处处闭合, 箱体成形。",
    ["ring_n_2", "ring_n_3", "ring_e_2", "ring_e_3"],
    highlight=["ring_s_2", "ring_w_2"],
    tip="闭环的墙才扛得住冠军的重拳 —— 四角都要咬紧。",
)
b.step(
    "盖台面帆布: 四片白色方板压顶, 每片吸墙顶又互吸拼缝。",
    ["canvas_2_2", "canvas_3_2", "canvas_2_3", "canvas_3_3"],
    highlight=["ring_n_2"],
    tip="台面锁住环墙 —— 擂台抬高一层, 观众才看得清。",
)
b.step(
    "骑南沿与西沿围绳: 红白相间整边骑台面沿口, 同吸下层墙顶。",
    ["rope_s_2", "rope_s_3", "rope_w_2", "rope_w_3"],
    highlight=["canvas_2_2"],
    tip="围绳一线双吸: 台面边 + 墙顶边, 两条保险。",
)
b.step(
    "骑北沿与东沿围绳合环: 开顶围绳环四角竖边互咬。",
    ["rope_n_2", "rope_n_3", "rope_e_2", "rope_e_3"],
    highlight=["rope_s_2"],
    tip="只围不盖 —— 开顶的环照样闭合, 拳手从绳间钻进场。",
)
b.step(
    "插四面角旗: 红角对蓝角, 两个中立角白色, 骑围绳顶沿。",
    ["flag_red", "flag_blue", "flag_nw", "flag_se"],
    highlight=["rope_w_3"],
    tip="旗子重心正压铰链线, 力矩为零 —— 红角蓝角, 各就各位!",
)
b.step(
    "装立式训练锥: 灰色底柱四墙合环踩拼缝, 红锥骑柱顶。",
    ["post_s", "post_n", "post_w", "post_e", "cone"],
    highlight=["mat_t_2"],
    tip="赛前先打十组锥靶 —— 锥尖 3.0, 比角旗还高半头。",
)
b.step(
    "搭计时台收尾: 两道青墙夹一片台面, 面朝擂台 —— 开赛!",
    ["desk_s", "desk_n", "desk_top"],
    highlight=["flag_red"],
    tip="台面两边各吸一道墙顶 —— 铃声一响, 第一回合开始!",
)

b.finalize(
    model_id="boxing_ring_01",
    name="拳击台",
    name_en="Boxing Ring 01",
    description=(
        "只用核心九片型的格斗擂台: 与围栏球场和立式攀岩塔都不同, "
        "主角是'抬升箱体 + 开顶围绳环'这对全库唯一的组合 —— 2x2 "
        "擂台先环墙合环再白帆布台面压顶, 台面沿口整边骑上一圈红白"
        "相间的开顶围绳 (同吸台面边与下层墙顶, 一线双吸, 只围不盖"
        "照样闭环), 红角蓝角与两个中立角的角旗重心正压铰链线; 台边"
        "灰色底柱托起 3.0 高的红色训练锥, 青色计时台两墙夹一盖面朝"
        "擂台 —— 铃声一响, 第一回合开始!"
    ),
    difficulty=2,
    tags=["运动", "健身", "拳击", "擂台", "格斗"],
    min_pieces=46,
    min_steps=10,
)
