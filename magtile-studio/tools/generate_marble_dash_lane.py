#!/usr/bin/env python3
"""生成模型 data/models/marble_dash_lane_01.json (弹珠冲关大道)。

滚珠乐园主题扩充 (库内此前仅两作且全为 D4, 本作补 D3 档):
与螺旋滚珠塔 (双轨绕塔盘旋) 和螺旋峡谷 (塔身自旋出坡) 的结构逻辑
都不同 —— 本作是"直线冲刺": 三段 30 度坡道从三层发射塔一路接力
放平到地面, 弹珠不拐一个弯, 全速冲进保龄球道, 撞倒站在拼缝上的
三角球瓶, 最后撞响道底的窗格铃靶 —— 全库唯一的"直线三连坡 +
地面球道"。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 弹珠自西向东冲刺):
  - 发射塔 (x [0,1], y [0,2], z 0..3): 地台 x2 + 三层墙环 x18 +
    发射台 x2 + 台沿挡珠三角 x5 (东缘南半格是出珠口)          27 片
  - 冲刺段一 (z3 -> z2): 双层栈桥墩 + 30 度坡道 + 转接台 +
    双层门式立柱 + 台沿挡珠三角 x2                             8 片
  - 冲刺段二 (z2 -> z1): 单层桥墩 + 坡道 + 转接台 +
    单层立柱 + 挡珠三角 x2                                     6 片
  - 冲线坡道 (z1 -> 落地): 坡尾自身落地, 零支撑                1 片
  - 保龄球道 (地面): 球道方板 x4 + 两侧护栏矮墙 x4 +
    球瓶三角 x2 (立在球道拼缝上, 弹珠一撞就倒) +
    道底窗格铃靶 x1                                           11 片
  合计 53 片, 12 个教程步骤, 4 种磁力片形状 (全部 CORE-9 之内)。

招牌技法: 三段坡道排成一条直线接力, 每段坡尾由"桥墩-坡道-转接台"
三件互吸的刚性节点接住, 弹珠零转弯全速冲进地面球道撞瓶。

物理规则要点 (通过 R1~R9 全部校验, strict --jitter 50 全绿):
  - 每段坡道顶边整边吸上一级台面沿口, 坡尾与桥墩顶、转接台西缘
    三件互吸; 转接台东缘再由门式立柱从地面顶住 —— 与螺旋滚珠塔
    R9 加固批同款门式框架, 剪断任何铰链台面仍有支撑路径;
  - 冲线坡道坡尾直接落地, 球道方板西缘与坡尾整边互吸;
  - 球瓶与铃靶底边整边吸球道拼缝/沿口, 竖立纯受压;
    剪断单点最多失联 1 片;
  - 发射塔为 1x2 盒式墙环, 最高点 (台沿挡珠三角顶) 3.87,
    低于 R8 无桁架高墙红线 4.0。

用法: python3 tools/generate_marble_dash_lane.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import SQ3, ModelBuilder  # noqa: E402

b = ModelBuilder()

BASE = "gray"      # 塔基地台
TOWER = "blue"     # 发射塔墙
TOWER_TOP = "cyan" # 发射塔第三层
DECK = "yellow"    # 发射台 / 转接台
RAIL = "red"       # 挡珠三角
PIER = "gray"      # 栈桥墩 / 门式立柱
RAMP = "orange"    # 坡道
LANE = "clear"     # 球道
GUARD = "green"    # 球道护栏
PIN = "purple"     # 球瓶
BELL = "pink"      # 铃靶

X1 = 1 + SQ3       # 转接台一西缘 2.732051
X2 = X1 + 1 + SQ3  # 转接台二西缘 5.464102
X3 = X2 + 1 + SQ3  # 球道西缘 8.196153


def wall_ew_t(tid, tile_type, x, y0, z0, color):
    b.add(tid, tile_type, (x, y0 + 0.5, z0 + 0.5), (90, 0, 90), color)


# =================================================================
# 1. 发射塔 (x [0,1], y [0,2]): 地台 + 三层墙环 + 发射台 + 挡珠沿
# =================================================================
b.flat("base_0", 0, 0, 0.0, BASE)
b.flat("base_1", 0, 1, 0.0, BASE)
for lv in range(3):
    c = TOWER_TOP if lv == 2 else TOWER
    b.wall_ns(f"tw{lv}_s", 0, 0.0, lv, c)
    b.wall_ns(f"tw{lv}_n", 0, 2.0, lv, c)
    for j in range(2):
        b.wall_ew(f"tw{lv}_w_{j}", 0.0, j, lv, c)
        b.wall_ew(f"tw{lv}_e_{j}", 1.0, j, lv, c)
b.flat("deck_0", 0, 0, 3.0, DECK)
b.flat("deck_1", 0, 1, 3.0, DECK)
# 台沿挡珠: 东缘南半格 (y 0..1) 是出珠口, 其余五段全拦
b.crest_ew("drail_w_0", 0.0, 0, 3.0, RAIL)
b.crest_ew("drail_w_1", 0.0, 1, 3.0, RAIL)
b.crest_ns("drail_s", 0, 0.0, 3.0, RAIL)
b.crest_ns("drail_n", 0, 2.0, 3.0, RAIL)
b.crest_ew("drail_e_1", 1.0, 1, 3.0, RAIL)

# =================================================================
# 2. 冲刺段一 (z3 -> z2): 双层桥墩 + 坡道 + 转接台 + 双层门式立柱
# =================================================================
b.wall_ew("p1a", X1, 0, 0, PIER)
b.wall_ew("p1b", X1, 0, 1, PIER)
b.wall_ew("p1c", X1 + 1, 0, 0, PIER)
b.wall_ew("p1d", X1 + 1, 0, 1, PIER)
b.ramp("ramp_1", "+x", 1.0, 0, 3.0, RAMP)
b.flat("plat_1", X1, 0, 2.0, DECK)
b.crest_ns("rail1_s", X1, 0.0, 2.0, RAIL)
b.crest_ns("rail1_n", X1, 1.0, 2.0, RAIL)

# =================================================================
# 3. 冲刺段二 (z2 -> z1): 单层桥墩 + 坡道 + 转接台 + 单层立柱
# =================================================================
b.wall_ew("p2a", X2, 0, 0, PIER)
b.wall_ew("p2b", X2 + 1, 0, 0, PIER)
b.ramp("ramp_2", "+x", X1 + 1, 0, 2.0, RAMP)
b.flat("plat_2", X2, 0, 1.0, DECK)
b.crest_ns("rail2_s", X2, 0.0, 1.0, RAIL)
b.crest_ns("rail2_n", X2, 1.0, 1.0, RAIL)

# =================================================================
# 4. 冲线坡道 (z1 -> 落地) + 保龄球道
# =================================================================
b.ramp("ramp_3", "+x", X2 + 1, 0, 1.0, RAMP)
for k in range(4):
    b.flat(f"lane_{k}", X3 + k, 0, 0.0, LANE)
b.wall_ns("guard_s_0", X3, 0.0, 0, GUARD)
b.wall_ns("guard_n_0", X3, 1.0, 0, GUARD)
b.wall_ns("guard_s_1", X3 + 1, 0.0, 0, GUARD)
b.wall_ns("guard_n_1", X3 + 1, 1.0, 0, GUARD)
b.crest_ew("pin_1", X3 + 2, 0, 0.0, PIN)      # 球瓶立在球道拼缝上
b.crest_ew("pin_2", X3 + 3, 0, 0.0, PIN)
wall_ew_t("bell", "window_square", X3 + 4, 0, 0, BELL)  # 道底铃靶

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺塔基地台并立发射塔第一层: 两片灰色方板打底, 六片蓝色方板沿地台边缘合围。",
    ["base_0", "base_1",
     "tw0_s", "tw0_w_0", "tw0_w_1", "tw0_n", "tw0_e_0", "tw0_e_1"],
    tip="塔基东边要留出一整条直线场地 —— 弹珠将从这里一冲到底。",
)
b.step(
    "发射塔第二层: 六片蓝色方板骑上第一层墙顶, 上下边完整贴合。",
    ["tw1_s", "tw1_w_0", "tw1_w_1", "tw1_n", "tw1_e_0", "tw1_e_1"],
    highlight=["tw0_s", "tw0_e_0"],
    tip="墙环四角竖边两两互咬, 一层一层像穿糖葫芦一样往上叠。",
)
b.step(
    "发射塔第三层: 六片青色方板封顶层, 塔身升到三层高。",
    ["tw2_s", "tw2_w_0", "tw2_w_1", "tw2_n", "tw2_e_0", "tw2_e_1"],
    highlight=["tw1_s", "tw1_e_0"],
    tip="塔越高越要轻放 —— 一手扶塔身, 一手放片。",
)
b.step(
    "盖发射台: 两片黄色方板压住第三层墙顶, 四边都要吸在墙顶上。",
    ["deck_0", "deck_1"],
    highlight=["tw2_s", "tw2_n"],
    tip="发射台就是赛道起点 —— 弹珠从这里出发一冲到底。",
)
b.step(
    "装台沿挡珠: 五片红色挡珠三角围住台沿, 东缘南半格空着不拦 —— 那是出珠口。",
    ["drail_w_0", "drail_w_1", "drail_s", "drail_n", "drail_e_1"],
    highlight=["deck_0", "deck_1"],
    tip="出珠口对准正东 —— 从这里望出去就是弹珠的整条冲刺跑道。",
)
b.step(
    "冲刺段一 (整段成组安装): 塔东侧先立双层栈桥墩与双层门式立柱, 橙色坡道"
    "顶边整边吸住出珠口沿、坡尾搭上墩顶, 黄色转接台西缘压住墩顶与坡尾、"
    "东缘压住立柱顶。",
    ["p1a", "p1b", "p1c", "p1d", "ramp_1", "plat_1"],
    highlight=["deck_0", "tw2_e_0"],
    tip="桥墩-坡道-转接台三件互吸, 立柱像门框一样顶住台缘 —— 装完轻摇应纹丝不动。",
)
b.step(
    "转接台一装挡珠三角: 南北各一片红三角, 弹珠只能乖乖直行。",
    ["rail1_s", "rail1_n"],
    highlight=["plat_1"],
    tip="直线冲刺不拐弯 —— 挡珠三角是跑道两侧的护栏。",
)
b.step(
    "冲刺段二: 立单层桥墩与立柱, 第二段坡道从转接台东缘下探, 再铺第二块转接台"
    "与两片挡珠三角。",
    ["p2a", "p2b", "ramp_2", "plat_2", "rail2_s", "rail2_n"],
    highlight=["plat_1", "p1d"],
    tip="海拔又降一层 —— 弹珠每过一段都更快一分。",
)
b.step(
    "架冲线坡道: 最后一段橙色坡道从转接台二东缘直落地面, 坡尾自然着地。",
    ["ramp_3"],
    highlight=["plat_2"],
    tip="冲线坡道顶边吸台缘, 坡尾落地不需要任何支撑。",
)
b.step(
    "铺保龄球道: 四片清色方板从坡尾向东一字排开, 西缘与坡尾整边互吸。",
    ["lane_0", "lane_1", "lane_2", "lane_3"],
    highlight=["ramp_3"],
    tip="球道要铺得笔直 —— 弹珠落地后就在这条道上滑行减速。",
)
b.step(
    "装球道护栏: 前两片球道南北各立两片绿色矮墙, 弹珠出不了界。",
    ["guard_s_0", "guard_n_0", "guard_s_1", "guard_n_1"],
    highlight=["lane_0", "lane_1"],
    tip="护栏墙脚踩住球道边缘整边吸合 —— 落点附近最容易弹跳出界。",
)
b.step(
    "摆球瓶与铃靶: 两片紫色球瓶立在球道拼缝上, 道底立粉色窗格铃靶 —— 放珠开冲!",
    ["pin_1", "pin_2", "bell"],
    highlight=["lane_2", "lane_3"],
    tip="球瓶只吸一条缝, 弹珠一撞就倒 —— 全倒再撞响铃靶才算满分!",
)

b.finalize(
    model_id="marble_dash_lane_01",
    name="弹珠冲关大道",
    name_en="Marble Dash Lane 01",
    description=(
        "滚珠乐园 D3 新作: 与绕塔盘旋的螺旋滚珠塔完全不同的直线玩法 —— 三段"
        " 30 度坡道从三层发射塔一路接力放平到地面, 每段坡尾由桥墩-坡道-转接台"
        "三件互吸的刚性节点接住, 转接台外缘再加门式立柱; 弹珠零转弯全速冲进"
        "清色保龄球道, 撞倒站在拼缝上的两只紫色球瓶, 最后撞响道底的粉色窗格"
        "铃靶。摆好球瓶, 从出珠口放珠 —— 一杆全倒!"
    ),
    difficulty=3,
    tags=["滚珠", "轨道", "弹珠", "保龄球", "冲刺"],
    min_pieces=53,
    min_steps=12,
)
