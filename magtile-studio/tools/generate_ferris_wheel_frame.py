#!/usr/bin/env python3
"""生成模型 data/models/ferris_wheel_frame_01.json (游乐园摩天轮)。

第二批模型 ⑤: 游乐园主题 —— 竖立在游乐场正中的六角星摩天轮:
六边形轮毂 + 5 片等边三角轮辐 + 4 片菱形辐间板拼成一面大星轮,
由 3 根立墙塔架托举; 场边配登轮台 (带下客坡道)、售票亭与入园
拱门。全库第一个把 菱形 用作结构件的模型。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 游乐场地坪: 5x3 (x -0.5..4.5, y -1..2)                      15 片
  - 塔架: 3 根双层立墙 (中柱托轮毂, 两侧柱各托一片下轮辐)         6 片
  - 星轮: 六边形轮毂 + 5 片轮辐三角 + 4 片菱形辐间板             10 片
  - 登轮台: 三面矮墙 + 台面 + 下客坡道 + 护栏三角                 6 片
  - 售票亭: 1x1 亭身 + 锥形亭顶                                   8 片
  - 入园拱门: 双层门柱 x2 + 长方形门楣 + 2 片门旗                 7 片
  - 场地围栏: 北沿 4 片三角旗                                     4 片
  合计 56 片, 16 个教程步骤, 6 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 星轮在 y=1 竖直平面内: 轮毂底边吸中柱顶边, 两片下轮辐的
    水平底边分别吸左右侧柱顶边 —— 三点托举, 剪断任一条不塌;
  - 菱形辐间板两条边分别与相邻轮辐三角的侧边互吸, 星轮成环;
  - 登轮台北墙由右侧柱兼任 (台面直接吸柱身顶边), 避免共面重叠。

用法: python3 tools/generate_ferris_wheel_frame.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder, HEX_APOTHEM

b = ModelBuilder()

# =================================================================
# 1. 游乐场地坪: 5x3, x 列在半格网 (-0.5 起) 上 —— 使轮毂底边
#    (长 1, 中心 x=2) 恰好落在中柱顶边上
# =================================================================
COLS = [-0.5, 0.5, 1.5, 2.5, 3.5]
ROWS = [-1, 0, 1]
for k, x0 in enumerate(COLS):
    for j, y0 in enumerate(ROWS):
        b.flat(f"base_{k}_{j}", x0, y0, 0.0, "green" if (k + j) % 2 == 0 else "gray")

# =================================================================
# 2. 塔架: 3 根双层立墙 (平面 y=1), 相邻柱竖边互吸成一面桁架墙
# =================================================================
for k, x0 in enumerate((0.5, 1.5, 2.5)):
    b.wall_ns(f"col_{k}_1", x0, 1.0, 0, "gray")
    b.wall_ns(f"col_{k}_2", x0, 1.0, 1, "gray")

# =================================================================
# 3. 星轮 (竖直平面 y=1): 轮毂中心 (2, 1, 2.866)
#    六边形顶点 (世界坐标): v0 东 -> v1 东北 -> ... 逆时针
# =================================================================
HUB = (2.0, 1.0, 2.0 + HEX_APOTHEM)
b.add("hub", "hexagon", HUB, (90, 0, 0), "yellow")

HV = [(3.0, 2.866025), (2.5, 3.732051), (1.5, 3.732051),
      (1.0, 2.866025), (1.5, 2.0), (2.5, 2.0)]          # (x, z), y=1
HV = [(x, 1.0, z) for x, z in HV]

def star_apex(p0, p1):
    """轮辐三角外顶点: 2*边中点 - 轮毂中心 (六边形边心距 = 三角形高)。"""
    mx, my, mz = ((p0[0] + p1[0]) / 2, 1.0, (p0[2] + p1[2]) / 2)
    return (2 * mx - HUB[0], 1.0, 2 * mz - HUB[2])

SPOKE_EDGES = [0, 1, 2, 3, 5]            # 底边 e4 (v4->v5) 由中柱顶边占用
apex = {}
for e in SPOKE_EDGES:
    p0, p1 = HV[e], HV[(e + 1) % 6]
    apex[e] = star_apex(p0, p1)
    b.place_tri(f"spoke_{e}", "equilateral_triangle", p0, p1, apex[e], "red")

# 菱形辐间板: 填在相邻轮辐之间的 60 度豁口 (顶点 v1/v2/v3/v0 处)
for e in (0, 1, 2, 5):                   # 豁口位于 spoke_e 与 spoke_e+1 之间
    v = HV[(e + 1) % 6]
    a_prev, a_next = apex[e], apex[(e + 1) % 6]
    outer = tuple(a_prev[i] + a_next[i] - v[i] for i in range(3))
    b.place_edge(f"rhomb_{e}", "rhombus", 0, v, a_prev,
                 tuple((a_prev[i] + outer[i] + a_next[i]) / 3 - v[i] for i in range(3)),
                 "purple")

# =================================================================
# 4. 登轮台 (2.5..3.5, 0..1): 北墙由右侧柱身兼任
# =================================================================
b.wall_ns("pf_s", 2.5, 0.0, 0, "orange")
b.wall_ew("pf_w", 2.5, 0, 0, "orange")
b.wall_ew("pf_e", 3.5, 0, 0, "orange")
b.flat("pf_deck", 2.5, 0, 1.0, "yellow")
b.ramp("pf_ramp", "+x", 3.5, 0, 1.0, "orange")   # 下客坡道, 坡尾自落地
b.crest_ns("pf_rail", 2.5, 0.0, 1.0, "red")       # 台面南沿护栏

# =================================================================
# 5. 售票亭 (-0.5..0.5, -1..0): 1x1 亭身 + 锥形亭顶
# =================================================================
b.wall_ns("bt_s", -0.5, -1.0, 0, "cyan")
b.wall_ew("bt_e", 0.5, -1, 0, "cyan")
b.wall_ns("bt_n", -0.5, 0.0, 0, "cyan")
b.wall_ew("bt_w", -0.5, -1, 0, "cyan")
booth_roof = b.hat4("bt_roof", -0.5, -1, 1.0, "blue")

# =================================================================
# 6. 入园拱门 (南沿 y=-1): 双层门柱 + 长方形门楣 + 门旗
# =================================================================
b.wall_ns("gate_w1", 0.5, -1.0, 0, "blue")
b.wall_ns("gate_w2", 0.5, -1.0, 1, "blue")
b.wall_ns("gate_e1", 3.5, -1.0, 0, "blue")
b.wall_ns("gate_e2", 3.5, -1.0, 1, "blue")
b.lintel_ns("gate_top", 1.5, -1.0, 1, "yellow")   # 横跨 x 1.5..3.5 门洞
b.crest_ns("gate_fl_w", 0.5, -1.0, 2.0, "pink")
b.crest_ns("gate_fl_e", 3.5, -1.0, 2.0, "pink")

# =================================================================
# 7. 场地围栏: 北沿 4 片三角旗
# =================================================================
for k, x0 in enumerate((-0.5, 0.5, 2.5, 3.5)):
    b.crest_ns(f"fence_{k}", x0, 2.0, 0.0, "cyan" if k % 2 == 0 else "pink")

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺设游乐场南排: 5 片正方形 (绿灰相间) 沿直线平放吸合。",
    [f"base_{k}_0" for k in range(5)],
    tip="注意场地网格从 -0.5 起 —— 摆放时以第一片为基准即可, 后续全部对齐它。",
)
b.step(
    "铺设中排 5 片。",
    [f"base_{k}_1" for k in range(5)],
    highlight=["base_0_0", "base_4_0"],
    tip="中排与北排的接缝线就是摩天轮星轮所在的竖直平面。",
)
b.step(
    "铺设北排 5 片, 5x3 游乐场完工。",
    [f"base_{k}_2" for k in range(5)],
    highlight=["base_0_1"],
    tip="从上往下看是整齐的 5x3 棋盘格。",
)
b.step(
    "竖立塔架下层: 3 片灰色立墙并排立在中排与北排的接缝上, 相邻竖边互吸。",
    ["col_0_1", "col_1_1", "col_2_1"],
    highlight=["base_1_1", "base_2_1", "base_3_1"],
    tip="三片连成一面 3 格宽的桁架墙 —— 摩天轮的全部重量都压在它上面。",
)
b.step(
    "叠塔架上层: 再叠 3 片, 上下完整贴合、左右竖边互吸。",
    ["col_0_2", "col_1_2", "col_2_2"],
    highlight=["col_0_1", "col_2_1"],
    tip="塔架顶边 (高度 2) 将同时托住轮毂和两片下轮辐 —— 三点托举。",
)
b.step(
    "安装六边形轮毂: 竖立在中柱顶边正上方, 底边整边吸合。",
    ["hub"],
    highlight=["col_1_2"],
    tip="轮毂是整面星轮的心脏; 放稳后轻碰不应晃动。",
)
b.step(
    "安装 2 片下轮辐: 红色等边三角形贴着轮毂左下、右下两条边, "
    "水平底边分别吸在左右侧柱的顶边上。",
    ["spoke_3", "spoke_5"],
    highlight=["hub", "col_0_2", "col_2_2"],
    tip="每片下轮辐同时吸住轮毂斜边和侧柱顶边 —— 星轮从此三点着力。",
)
b.step(
    "安装 3 片上轮辐: 贴着轮毂左上、正上、右上三条边向外辐射。",
    ["spoke_2", "spoke_1", "spoke_0"],
    highlight=["hub"],
    tip="先左上、再正上、最后右上, 每片底边与轮毂边完全贴合。",
)
b.step(
    "嵌入 4 片紫色菱形辐间板: 填进相邻轮辐之间的豁口, 两条边分别与"
    "两侧轮辐的侧边互吸 —— 星轮锁成一个整环。",
    ["rhomb_5", "rhomb_0", "rhomb_1", "rhomb_2"],
    highlight=["spoke_0", "spoke_1"],
    tip="菱形的锐角朝轮心、钝角朝外; 装完后星轮任何一片都有两条以上支撑路径。",
)
b.step(
    "搭登轮台三面矮墙: 右侧柱前方围出 1x1 站台 (北面由塔架侧柱兼任)。",
    ["pf_s", "pf_w", "pf_e"],
    highlight=["col_2_1"],
    tip="三片矮墙与塔架侧柱围成口字形 —— 乘客从这里登上摩天轮。",
)
b.step(
    "盖登轮台台面, 接下客坡道, 装护栏: 台面四边压住矮墙与侧柱, "
    "坡道顶边吸台面东沿、坡尾自然落地, 护栏立在台面南沿。",
    ["pf_deck", "pf_ramp", "pf_rail"],
    highlight=["pf_s", "pf_e"],
    tip="台面要同时压住三面矮墙和塔架侧柱的下层顶边, 四边受力才稳。",
)
b.step(
    "搭售票亭亭身: 场地西南角立 1x1 四面青色墙。",
    ["bt_s", "bt_e", "bt_n", "bt_w"],
    highlight=["base_0_0"],
    tip="四片按 南-东-北-西 合围, 转角竖边互吸。",
)
b.step(
    "合拢售票亭锥顶: 4 片蓝色等腰三角形斜棱两两互吸。",
    booth_roof,
    highlight=["bt_s", "bt_n"],
    tip="最后一片要同时吸住底边和两条斜棱, 轻压到位。",
)
b.step(
    "竖立入园拱门双柱: 南沿两端各叠 2 片蓝色门柱。",
    ["gate_w1", "gate_w2", "gate_e1", "gate_e2"],
    highlight=["base_1_0", "base_4_0"],
    tip="两柱间空出 2 格宽门洞 —— 下一步的长方形门楣正好跨过它。",
)
b.step(
    "架门楣、挂门旗: 黄色长方形横跨门洞, 两条短边吸住左右门柱上层竖边; "
    "柱顶各立 1 片粉色门旗。",
    ["gate_top", "gate_fl_w", "gate_fl_e"],
    highlight=["gate_w2", "gate_e2"],
    tip="门楣要水平: 先吸一侧短边, 再轻压另一侧到位。",
)
b.step(
    "插北沿围栏旗 4 片, 游乐园开园 —— 摩天轮转起来!",
    [f"fence_{k}" for k in range(4)],
    highlight=["base_0_2", "base_4_2"],
    tip="全部完成后从侧面看: 六角星轮悬在塔架正上方, 轮缘离地正好一格。",
)

b.finalize(
    model_id="ferris_wheel_frame_01",
    name="游乐园摩天轮",
    name_en="Ferris Wheel Frame 01",
    description=(
        "游乐园主题: 六边形轮毂、5 片等边三角轮辐与 4 片菱形辐间板在竖直平面内"
        "拼成一面六角星大轮, 由 3 根双层立墙塔架三点托举 (轮毂吸中柱, 两片下"
        "轮辐吸侧柱), 剪断任一条铰链线星轮都不塌; 场边配登轮台与下客坡道、"
        "锥顶售票亭和挂着门旗的入园拱门 —— 全库第一个把菱形用作结构件的模型。"
    ),
    difficulty=3,
    tags=["游乐园", "摩天轮", "星形", "进阶"],
    min_pieces=52,
    min_steps=16,
)
