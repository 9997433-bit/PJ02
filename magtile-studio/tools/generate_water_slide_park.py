#!/usr/bin/env python3
"""生成模型 data/models/water_slide_park_01.json (水上滑梯乐园)。

夏日乐园主题: 全库第一座"入水滑道"模型 —— 与滚珠系列 (轨道绕塔、
珠走全程) 刻意区分: 这里的主角是一条从 2 层跳台俯冲、穿过泳池
西侧开口、直插池心的两段式大滑梯 (中继桥墩接力), 北岸还有一条
儿童缓滑道; 泳池四面围墙、券门入口、救生员高椅一应俱全。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 大泳池 (x 2..6, y 0..3): 池底 12 片 + 围墙 13 片 (西面留
    滑道入水口)                                                  25 片
  - 出发步道: 南北两条 3 片步道把跳台锚进泳池                      6 片
  - 主跳台 (x -1..0, y 1..2): 两层塔身 + 跳台板 + 双护栏尖        11 片
  - 大滑梯: 上段坡道 -> 中继桥墩 -> 下段坡道直插池心                3 片
  - 儿童滑道区 (泳池北岸): 连接板 + 1 层小塔 + 台板 + 缓滑道        7 片
  - 券门入口 (泳池南岸): 门前铺装 4 + 双柱 + 门桥板                 7 片
  - 池畔点缀: 池墙旗饰 2 + 救生员高椅 (铺装/椅身/座板/遮阳尖) 4    6 片
  合计 65 片, 16 个教程步骤。

物理规则要点 (通过 R1~R8 全部校验):
  - 两段式滑梯: 中继桥墩先立 (接地), 上段坡道顶边吸跳台沿口、
    坡尾吸桥墩顶边 —— 三件互吸后剪断任何一条铰链都还有支撑路径;
    下段坡道顶边吸同一条铰链线, 坡尾自然落地 (直插池心, 与池底
    斜交不共面, 不触发重叠);
  - 跳台与泳池由南北步道 (地面板链) 连成一个连通整体;
  - 券门双柱底边吸门前铺装板边, 门桥板短边吸双柱顶边合龙。

用法: python3 tools/generate_water_slide_park.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import SQ3, ModelBuilder  # noqa: E402

b = ModelBuilder()

WATER = "cyan"
TILE = "blue"
TOWER = "orange"
SLIDE = "yellow"

PIER_X = SQ3          # 中继桥墩平面 x = 1.732051

# =================================================================
# 1. 大泳池 (x 2..6, y 0..3): 池底 12 片 + 围墙 (西面 y 1..2 留口)
# =================================================================
for x0 in range(2, 6):
    for y0 in range(3):
        b.flat(f"pool_{x0}_{y0}", x0, y0, 0.0, WATER)
for x0 in range(2, 6):
    b.wall_ns(f"pw_s_{x0}", x0, 0.0, 0, TILE)     # 南墙 4
    b.wall_ns(f"pw_n_{x0}", x0, 3.0, 0, TILE)     # 北墙 4
for y0 in range(3):
    b.wall_ew(f"pw_e_{y0}", 6.0, y0, 0, TILE)     # 东墙 3
b.wall_ew("pw_w_s", 2.0, 0, 0, TILE)              # 西墙南段 (y 0..1)
b.wall_ew("pw_w_n", 2.0, 2, 0, TILE)              # 西墙北段 (y 2..3)

# =================================================================
# 2. 出发步道: 南北两条 (x -1..2), 把跳台锚进泳池
# =================================================================
for x0 in (-1, 0, 1):
    b.flat(f"path_s_{x0}", x0, 0, 0.0, "gray")    # 南步道 (y 0..1)
    b.flat(f"path_n_{x0}", x0, 2, 0.0, "gray")    # 北步道 (y 2..3)

# =================================================================
# 3. 主跳台 (x -1..0, y 1..2): 两层塔身 + 跳台板 + 双护栏尖
# =================================================================
for lv in range(2):
    b.wall_ns(f"tw_s_{lv}", -1, 1.0, lv, TOWER)
    b.wall_ns(f"tw_n_{lv}", -1, 2.0, lv, TOWER)
    b.wall_ew(f"tw_w_{lv}", -1.0, 1, lv, TOWER)
    b.wall_ew(f"tw_e_{lv}", 0.0, 1, lv, "clear" if lv else TOWER)
b.flat("tw_deck", -1, 1, 2.0, SLIDE)              # 跳台板 (z=2)
b.spire_ns("tw_rail_s", -1, 1.0, 2.0, "red")      # 南护栏尖
b.spire_ns("tw_rail_n", -1, 2.0, 2.0, "red")      # 北护栏尖

# =================================================================
# 4. 大滑梯: 上段坡道 (z2->z1) -> 中继桥墩 -> 下段坡道 (z1->z0)
# =================================================================
b.wall_ew("pier", PIER_X, 1, 0, TILE)             # 中继桥墩 (接地)
b.ramp("slide_hi", "+x", 0.0, 1, 2.0, SLIDE)      # 顶边吸跳台沿口
b.ramp("slide_lo", "+x", PIER_X, 1, 1.0, SLIDE)   # 坡尾落在池心 (z=0)

# =================================================================
# 5. 儿童滑道区 (泳池北岸): 连接板 + 1 层小塔 + 台板 + 缓滑道
# =================================================================
b.flat("kd_link", 4, 3, 0.0, "gray")              # 连接板 (y 3..4)
b.wall_ns("kd_s", 4, 4.0, 0, "pink")
b.wall_ns("kd_n", 4, 5.0, 0, "pink")
b.wall_ew("kd_w", 4.0, 4, 0, "pink")
b.wall_ew("kd_e", 5.0, 4, 0, "pink")
b.flat("kd_deck", 4, 4, 1.0, SLIDE)               # 台板 (z=1)
b.ramp("kd_slide", "+y", 5.0, 4, 1.0, "pink")     # 缓滑道, 坡尾落地

# =================================================================
# 6. 券门入口 (泳池南岸): 门前铺装 + 双柱 + 门桥板
# =================================================================
b.flat("gt_p1", 3, -1, 0.0, "gray")               # 紧贴池墙的铺装
b.flat("gt_p2", 4, -1, 0.0, "gray")
b.flat("gt_p3", 3, -2, 0.0, "gray")
b.flat("gt_p4", 4, -2, 0.0, "gray")
b.wall_ew("gt_col_w", 3.0, -2, 0, "purple")       # 西门柱 (平面 x=3)
b.wall_ew("gt_col_e", 5.0, -2, 0, "purple")       # 东门柱 (平面 x=5)
b.flat_rect("gt_beam", 3, -2, 1.0, "purple", axis="x")  # 门桥板合龙

# =================================================================
# 7. 池畔点缀: 池墙旗饰 + 救生员高椅
# =================================================================
b.crest_ns("flag_w", 3, 0.0, 1.0, "red")          # 南池墙顶旗
b.crest_ns("flag_e", 4, 0.0, 1.0, "green")
b.flat("lg_pave", 6, 1, 0.0, "gray")              # 高椅铺装 (x 6..7)
b.wall_ew("lg_back", 7.0, 1, 0, TOWER)            # 椅身
b.flat("lg_seat", 6, 1, 1.0, "red")               # 座板 (桥在池墙与椅身上)
b.spire_ew("lg_shade", 7.0, 1, 1.0, "green")      # 遮阳尖

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "池底西半: 平铺 6 片青色池底 (x 2..4), 相邻边互吸。",
    [f"pool_{x0}_{y0}" for x0 in (2, 3) for y0 in range(3)],
    tip="青色就是水面 —— 池底铺得平, 水花才溅得欢。",
)
b.step(
    "池底东半: 再铺 6 片, 4x3 大泳池成形。",
    [f"pool_{x0}_{y0}" for x0 in (4, 5) for y0 in range(3)],
    highlight=["pool_3_1"],
    tip="12 片池底缝缝相吸, 是全场最大的一块地锚。",
)
b.step(
    "泳池南墙: 立 4 片蓝色池墙, 底边吸池底南沿边。",
    [f"pw_s_{x0}" for x0 in range(2, 6)],
    highlight=["pool_2_0", "pool_5_0"],
    tip="池墙立直, 相邻竖边互吸 —— 别让池水漏出去。",
)
b.step(
    "泳池北墙: 同法再立 4 片, 南北池岸相对而立。",
    [f"pw_n_{x0}" for x0 in range(2, 6)],
    highlight=["pw_s_2"],
    tip="北墙中段 (x 4..5) 待会儿要借给儿童区当靠山。",
)
b.step(
    "泳池东墙与西口: 东面 3 片合拢, 西面只装南北两段 —— 中间"
    "留 1 格宽的滑道入水口。",
    ["pw_e_0", "pw_e_1", "pw_e_2", "pw_w_s", "pw_w_n"],
    highlight=["pw_s_5", "pw_n_5"],
    tip="西口正对跳台 —— 大滑梯要从这里俯冲进池心。",
)
b.step(
    "出发步道: 南北各铺 3 片灰色步道 (x -1..2), 东端吸池墙底边。",
    ["path_s_1", "path_s_0", "path_s_-1",
     "path_n_1", "path_n_0", "path_n_-1"],
    highlight=["pw_w_s", "pw_w_n"],
    tip="两条步道是跳台与泳池之间的地面纽带, 先从池边往西铺。",
)
b.step(
    "跳台塔身下层: 4 片橙色墙围成 1x1 塔基, 底边吸步道板边。",
    ["tw_s_0", "tw_n_0", "tw_w_0", "tw_e_0"],
    highlight=["path_s_-1", "path_n_-1"],
    tip="塔基南北墙正好立在两条步道的内沿上 —— 一墙两吸。",
)
b.step(
    "跳台塔身上层: 再叠 4 片 (东面用透明片), 塔身到 2 格高。",
    ["tw_s_1", "tw_n_1", "tw_w_1", "tw_e_1"],
    highlight=["tw_s_0"],
    tip="透明的东面朝着泳池 —— 排队的小朋友能看到前一位入水。",
)
b.step(
    "跳台板与护栏: 黄色跳台板盖住塔口, 南北沿各立 1 片红色护栏尖。",
    ["tw_deck", "tw_rail_s", "tw_rail_n"],
    highlight=["tw_s_1", "tw_e_1"],
    tip="跳台板四边吸满塔墙顶边 —— 站上去蹦两下都稳。",
)
b.step(
    "两段大滑梯: 先在 x=1.73 平面立起中继桥墩 (30 度坡道的水平"
    "投影正是 1.73 格), 随即上段坡道顶边吸跳台沿口、坡尾吸桥墩"
    "顶边; 下段坡道顶边吸同一条边线, 坡尾直插池心水面!",
    ["pier", "slide_hi", "slide_lo"],
    highlight=["tw_deck", "pw_w_s"],
    tip="桥墩-坡道-坡道三件互吸成一条折线 —— 立墩后先上段再下段。",
)
b.step(
    "儿童区连接板: 泳池北墙外接 1 片灰色连接板。",
    ["kd_link"],
    highlight=["pw_n_4"],
    tip="连接板南边吸池墙底边 —— 儿童区从这里长出来。",
)
b.step(
    "儿童小塔: 4 片粉色墙围成 1 层小塔, 台板盖顶。",
    ["kd_s", "kd_w", "kd_e", "kd_n", "kd_deck"],
    highlight=["kd_link"],
    tip="南墙底边吸连接板北边, 其余三面沿拐角吸过去。",
)
b.step(
    "儿童缓滑道: 粉色坡道顶边吸台板北沿, 坡尾稳稳落草地。",
    ["kd_slide"],
    highlight=["kd_deck"],
    tip="只有一层高的缓坡 —— 小小朋友的第一课。",
)
b.step(
    "券门铺装与双柱: 泳池南岸铺 4 片门前铺装, 东西立 2 根紫色门柱 "
    "(柱底吸铺装板边)。",
    ["gt_p1", "gt_p2", "gt_p3", "gt_p4", "gt_col_w", "gt_col_e"],
    highlight=["pw_s_3", "pw_s_4"],
    tip="铺装北边吸池墙底边 —— 入口与泳池连成一体。",
)
b.step(
    "券门合龙: 紫色门桥板横跨双柱, 两短边分别吸柱顶 —— 欢迎"
    "光临水上乐园!",
    ["gt_beam"],
    highlight=["gt_col_w", "gt_col_e"],
    tip="门桥板一搭, 双柱从此互相扶持 —— 这就是门式刚架。",
)
b.step(
    "池畔点缀: 南池墙顶插 2 面小旗, 东岸搭救生员高椅 (铺装 + "
    "椅身 + 座板 + 遮阳尖) —— 乐园开园!",
    ["flag_w", "flag_e", "lg_pave", "lg_back", "lg_seat", "lg_shade"],
    highlight=["pw_s_3", "pw_e_1"],
    tip="座板一头搭池墙顶、一头搭椅身顶 —— 救生员看得见每朵水花。",
)

b.finalize(
    model_id="water_slide_park_01",
    name="水上滑梯乐园",
    name_en="Water Slide Park 01",
    description=(
        "全库第一座入水滑道乐园: 两层跳台上一条 30 度大滑梯经中继桥墩"
        "接力俯冲, 穿过泳池西侧留口直插池心水面; 4x3 大泳池四面围墙、"
        "券门双柱合龙、北岸儿童缓滑道、东岸救生员高椅 —— 跳台、泳池、"
        "儿童区与入口全部由地面板链连成一个连通整体。"
    ),
    difficulty=3,
    tags=["夏日乐园", "滑梯", "泳池", "游乐场"],
    min_pieces=60,
    min_steps=16,
)
