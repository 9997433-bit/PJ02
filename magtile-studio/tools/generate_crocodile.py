#!/usr/bin/env python3
"""生成模型 data/models/crocodile_01.json (大嘴鳄鱼)。

动物世界主题: 与剑龙 (腿柱托起悬空躯干) 和霸王龙骨架 (悬挑箱形梁)
都不同的动物搭法 —— 鳄鱼是一只"贴地爬行"的低姿动物: 箱形躯干
直接坐在河滩上, 血盆大口由两片 30 度坡道当上颚斜挑张开 (坡尾
自然落地 = 接地斜撑, 零悬臂), 尾巴用 长方形 -> 梯形 -> 等边三角
三段逐级收窄, 背脊立起一排锯齿背棘。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 躯干占 [2,6]x[0,2]):
  - 腹底: 4 片长方形纵铺, 长边互吸连成整块                       4 片
  - 躯干四壁: 南北侧壁 8 + 前胸 2 + 后臀 2                       12 片
  - 背甲: 8 片方板盖顶 + 4 片背棘 + 2 片眼睛                     14 片
  - 血盆大口: 下颚 4 方板 + 上颚 2 坡道 + 獠牙 2                  8 片
  - 尾巴: 长方形尾根 + 梯形尾节 + 三角尾尖 + 2 片尾棘             5 片
  - 四肢: 4 片方板脚掌 + 4 片三角爪                               8 片
  合计 51 片, 16 个教程步骤, 4 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 上颚坡道顶边整边吸前胸墙顶, 坡尾自然落地 —— 接地斜撑,
    张开的大嘴不吃任何悬臂预算;
  - 尾巴三段逐级收窄: 长方形长边 (2) 吸腹底长边, 梯形下底 (2)
    吸长方形长边, 三角底边 (1) 吸梯形上底 —— 每段都整边贴合;
  - 背棘/眼睛/尾棘全部竖立在拼缝正上方, 力臂为零纯压不弯。

用法: python3 tools/generate_crocodile.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder, SQ3

b = ModelBuilder()

HIDE = "green"       # 鳄鱼皮
BELLY = "yellow"     # 腹部
RIDGE = "orange"     # 背棘
WATER = "cyan"       # 河水

# =================================================================
# 1. 腹底 ([2,6]x[0,2], z=0): 4 片长方形纵铺 (1x2), 长边互吸
# =================================================================
for x in range(2, 6):
    b.flat_rect(f"bel_{x}", x, 0, 0.0, BELLY, axis="y")

# =================================================================
# 2. 躯干四壁 (z 0..1): 南北侧壁 + 前胸 (x=2) + 后臀 (x=6)
# =================================================================
for x in range(2, 6):
    b.wall_ns(f"bs_{x}", x, 0.0, 0, HIDE)       # 南侧壁
    b.wall_ns(f"bn_{x}", x, 2.0, 0, HIDE)       # 北侧壁
for y in range(2):
    b.wall_ew(f"chest_{y}", 2.0, y, 0, HIDE)    # 前胸 (上颚将吸在其顶边)
    b.wall_ew(f"rump_{y}", 6.0, y, 0, HIDE)     # 后臀

# =================================================================
# 3. 背甲 (z=1): 8 片方板 + 脊缝上 4 片背棘 + 前沿 2 片眼睛
# =================================================================
for x in range(2, 6):
    b.flat(f"dk_{x}_0", x, 0, 1.0, HIDE)
    b.flat(f"dk_{x}_1", x, 1, 1.0, HIDE)
for x in range(2, 6):
    b.crest_ns(f"ridge_{x}", x, 1.0, 1.0, RIDGE)    # 背棘立在脊缝 y=1 上
b.crest_ew("eye_s", 2.0, 0, 1.0, "yellow")          # 眼睛立在背甲前沿
b.crest_ew("eye_n", 2.0, 1, 1.0, "yellow")

# =================================================================
# 4. 血盆大口 ([0,2] 区域): 下颚 4 方板 + 上颚 2 坡道 + 獠牙 2
#    上颚顶边吸前胸墙顶 (z=1), 坡尾落地于 x = 2 - sqrt(3)
# =================================================================
for x in range(2):
    b.flat(f"jaw_{x}_0", x, 0, 0.0, HIDE)
    b.flat(f"jaw_{x}_1", x, 1, 0.0, HIDE)
b.ramp("ujaw_0", "-x", 2.0, 0, 1.0, HIDE)
b.ramp("ujaw_1", "-x", 2.0, 1, 1.0, HIDE)
b.crest_ew("fang_s", 0.0, 0, 0.0, "clear")          # 獠牙立在吻端
b.crest_ew("fang_n", 0.0, 1, 0.0, "clear")

# =================================================================
# 5. 尾巴 (x >= 6): 长方形尾根 -> 梯形尾节 -> 三角尾尖, 逐级收窄
# =================================================================
b.flat_rect("tail_a", 6, 0, 0.0, HIDE, axis="y")    # [6,7]x[0,2]
b.place_edge("tail_b", "trapezoid", 0,
             (7.0, 0.0, 0.0), (7.0, 2.0, 0.0), (1.0, 0.0, 0.0), HIDE)
TIP_X = 7.0 + 0.866025
b.place_tri("tail_c", "equilateral_triangle",
            (TIP_X, 0.5, 0.0), (TIP_X, 1.5, 0.0),
            (TIP_X + 0.866025, 1.0, 0.0), HIDE)
b.crest_ns("spk_s", 6, 0.0, 0.0, RIDGE)             # 尾棘 (南)
b.crest_ns("spk_n", 6, 2.0, 0.0, RIDGE)             # 尾棘 (北)

# =================================================================
# 6. 四肢: 脚掌方板向躯干两侧伸出 + 三角爪; 腿间点缀 2 片河水
# =================================================================
LEGS = {
    "fs": (2, -1, -1.0), "rs": (5, -1, -1.0),       # 南侧前/后腿 (爪朝南)
    "fn": (2, 2, 1.0), "rn": (5, 2, 1.0),           # 北侧前/后腿 (爪朝北)
}
for name, (x0, y0, sign) in LEGS.items():
    b.flat(f"leg_{name}", x0, y0, 0.0, HIDE)
    edge_y = y0 if sign < 0 else y0 + 1             # 脚掌外沿
    b.place_tri(f"claw_{name}", "equilateral_triangle",
                (x0, edge_y, 0.0), (x0 + 1, edge_y, 0.0),
                (x0 + 0.5, edge_y + sign * 0.866025, 0.0), "yellow")
b.flat("wat_0", 3, -1, 0.0, WATER)                  # 南侧腿间河水
b.flat("wat_1", 4, -1, 0.0, WATER)

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺设腹底: 4 片黄色长方形纵向平铺 ([2,6]x[0,2]), 长边逐片互吸成一整块。",
    [f"bel_{x}" for x in range(2, 6)],
    tip="鳄鱼是贴地爬行的动物 —— 腹底就是它贴住河滩的肚皮。",
)
b.step(
    "竖立南侧壁: 4 片绿色正方形沿腹底南沿一字立起, 底边吸腹底短边。",
    [f"bs_{x}" for x in range(2, 6)],
    highlight=["bel_2", "bel_5"],
    tip="相邻侧壁的竖边也要两两吸牢, 躯干才结实。",
)
b.step(
    "竖立北侧壁: 4 片绿色正方形沿北沿立起, 与南侧壁隔腹相望。",
    [f"bn_{x}" for x in range(2, 6)],
    highlight=["bs_2"],
    tip="南北侧壁完全对称, 中间就是鳄鱼厚实的身体。",
)
b.step(
    "封前胸与后臀: 头尾两端各立 2 片绿色正方形, 竖边与侧壁拐角互吸。",
    ["chest_0", "chest_1", "rump_0", "rump_1"],
    highlight=["bs_2", "bs_5", "bn_2", "bn_5"],
    tip="前胸墙顶马上要吸住张开的上颚 —— 位置务必摆正。",
)
b.step(
    "盖背甲南排: 4 片绿色方板压住南侧壁与前后墙顶边。",
    [f"dk_{x}_0" for x in range(2, 6)],
    highlight=["bs_2", "chest_0"],
    tip="背甲每片都要同时吸住墙顶边与相邻背甲边。",
)
b.step(
    "盖背甲北排: 再压 4 片, 躯干合拢成结实的箱形。",
    [f"dk_{x}_1" for x in range(2, 6)],
    highlight=["dk_2_0"],
    tip="箱形躯干剪断任何一条缝都塌不了 —— 这就是鳄鱼的铠甲。",
)
b.step(
    "立起背棘: 4 片橙色等边三角沿背脊拼缝一字立起, 底边吸背甲缝。",
    [f"ridge_{x}" for x in range(2, 6)],
    highlight=["dk_2_0", "dk_5_1"],
    tip="背棘立在拼缝正上方, 一条缝同时咬住左右两片背甲。",
)
b.step(
    "铺下颚: 头前平铺 4 片绿色方板, 东沿吸前胸墙底边。",
    ["jaw_0_0", "jaw_1_0", "jaw_0_1", "jaw_1_1"],
    highlight=["chest_0", "chest_1"],
    tip="下颚贴地摊开 —— 鳄鱼正准备张开血盆大口。",
)
b.step(
    "斜挑上颚: 2 片绿色坡道顶边整边吸前胸墙顶, 坡尾自然落地。",
    ["ujaw_0", "ujaw_1"],
    highlight=["chest_0", "jaw_0_0"],
    tip="坡尾落地就是支撑 —— 张开的大嘴一点也不吃悬臂预算。",
)
b.step(
    "装獠牙与眼睛: 吻端立 2 片透明獠牙, 背甲前沿立 2 片黄色眼睛。",
    ["fang_s", "fang_n", "eye_s", "eye_n"],
    highlight=["jaw_0_0", "dk_2_0"],
    tip="獠牙立在下颚最前端, 从侧面看大嘴咬合线正好错开。",
)
b.step(
    "接尾根: 1 片绿色长方形纵铺在躯干后方, 长边吸腹底长边。",
    ["tail_a"],
    highlight=["bel_5", "rump_0"],
    tip="尾根与腹底同宽 —— 鳄鱼的尾巴根部和身体一样粗壮。",
)
b.step(
    "立尾棘: 尾根两侧立 2 片橙色等边三角。",
    ["spk_s", "spk_n"],
    highlight=["tail_a"],
    tip="尾棘立在尾根短边上, 和背棘遥相呼应。",
)
b.step(
    "接尾节: 1 片绿色梯形下底整边吸尾根东沿, 尾巴开始收窄。",
    ["tail_b"],
    highlight=["tail_a"],
    tip="梯形下底长 2、上底长 1 —— 一片就把尾巴收窄一半。",
)
b.step(
    "装尾尖: 1 片绿色等边三角底边吸梯形上底, 尾巴完美收尖。",
    ["tail_c"],
    highlight=["tail_b"],
    tip="长方形-梯形-三角形三段收窄, 这是收尾巴的标准手法。",
)
b.step(
    "装四肢: 躯干两侧各伸出 2 片方板脚掌, 掌沿吸侧壁底边。",
    ["leg_fs", "leg_rs", "leg_fn", "leg_rn"],
    highlight=["bs_2", "bn_5"],
    tip="四条短腿贴地撑开 —— 鳄鱼的招牌爬行姿态。",
)
b.step(
    "装爪子与河水: 每只脚掌外沿吸 1 片黄色三角爪, 南侧腿间再铺 "
    "2 片青色河水, 大嘴鳄鱼上岸完工!",
    ["claw_fs", "claw_rs", "claw_fn", "claw_rn", "wat_0", "wat_1"],
    highlight=["leg_fs", "leg_rn"],
    tip="爪尖朝外摆平, 河水贴着腿间 —— 它刚从河里爬上来。",
)

b.finalize(
    model_id="crocodile_01",
    name="大嘴鳄鱼",
    name_en="Crocodile 01",
    description=(
        "贴地爬行的低姿猛兽: 箱形躯干直接坐在河滩上, 血盆大口由两片 30 度"
        "坡道当上颚斜挑张开 (坡尾落地 = 接地斜撑, 零悬臂), 吻端立着透明獠牙; "
        "尾巴用 长方形-梯形-三角 三段逐级收窄, 背脊一排橙色背棘, 四肢带爪"
        "向两侧撑开 —— 与腿柱式恐龙完全不同的动物搭法。"
    ),
    difficulty=3,
    tags=["动物世界", "鳄鱼", "自然", "河滩", "接地斜撑"],
    min_pieces=50,
    min_steps=16,
)
