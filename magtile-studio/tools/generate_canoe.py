#!/usr/bin/env python3
"""生成模型 data/models/canoe_01.json (湖上独木舟)。

自然湖泊主题: 9x5 大湖西岸一条金黄沙滩, 湖心浮着一条 4 格长的
橙色独木舟 —— 船底两片长板嵌进水面, 八片方板舷墙竖边连吸成
船帮, 两端方板封舱后各竖一片等边翘头 (船首船尾昂起 1.87 格);
舱内两片黄色座板横跨船帮如桥, 船头座上红色行囊四坡自锁;
湖面两座青色浮标锥、鸭妈妈带小鸭浮水、青鱼跃波, 岸上绿树
芦苇花丛点景 —— 桨声欸乃, 湖光十里。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 西岸草地 8 + 沙滩 5 + 湖面 16                           29 片
  - 独木舟: 船底长板 x2 + 舷墙方板 x8 + 端墙 x2 +
    翘头等边三角 x2 + 座板方板 x2 + 行囊四坡锥 (4 片)       20 片
  - 浮标: 等边四坡锥 x2 (8 片)                               8 片
  - 生灵与植被: 鸭 x2 + 鱼 x1 + 树 x2 + 芦苇 x1 +
    灌木四坡锥 (4 片) + 花丛 x1                             11 片
  合计 68 片, 16 个教程步骤, 5 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 船底长板嵌进水面同层平铺: 西短边整边吸沙滩格边、南北长边
    整边吸湖面长板 —— 船与湖锁成一张连续水面 (零重叠);
  - 舷墙方板底边完整落在船底长边内 (长短边贴合), 相邻竖边
    两两互吸, 与端墙四角咬合成环;
  - 座板三边整边吸舷墙/端墙顶边, 横跨船帮如桥; 行囊四片
    等边三角斜棱互吸自锁, 底边整边吸座板四边;
  - 翘头等边三角底边整边吸端墙顶边, 重心正压铰链零力矩。

用法: python3 tools/generate_canoe.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

GRASS = "green"
SAND = "yellow"
LAKE = "blue"
HULL = "orange"
SEAT = "yellow"
CARGO = "red"
BUOY = "cyan"
DUCK = "yellow"
FISH = "cyan"
TREE = "green"
FLOWER = "pink"

# =================================================================
# 1. 西岸草地 (x 0..2) + 沙滩 (x 2..3)
# =================================================================
b.flat("sh_0_0", 0, 0, 0.0, GRASS)
b.flat("sh_1_0", 1, 0, 0.0, GRASS)
b.flat_rect("sh_r_1", 0, 1, 0.0, GRASS, axis="x")
b.flat("sh_0_2", 0, 2, 0.0, GRASS)
b.flat("sh_1_2", 1, 2, 0.0, GRASS)
b.flat_rect("sh_r_3", 0, 3, 0.0, GRASS, axis="x")
b.flat("sh_0_4", 0, 4, 0.0, GRASS)
b.flat("sh_1_4", 1, 4, 0.0, GRASS)
for y in range(5):
    b.flat(f"sd_{y}", 2, y, 0.0, SAND)                # 沙滩一列方板

# =================================================================
# 2. 湖面 (x 3..9): 船位 [3,7]x[2,3] 留给船底, 鸭群一行用方板
# =================================================================
b.flat_rect("lk_a0", 3, 0, 0.0, LAKE, axis="x")
b.flat_rect("lk_b0", 5, 0, 0.0, LAKE, axis="x")
b.flat("lk_7_0", 7, 0, 0.0, LAKE)                     # 浮标位
b.flat("lk_8_0", 8, 0, 0.0, LAKE)
b.flat_rect("lk_a1", 3, 1, 0.0, LAKE, axis="x")
b.flat_rect("lk_b1", 5, 1, 0.0, LAKE, axis="x")
b.flat_rect("lk_c1", 7, 1, 0.0, LAKE, axis="x")
b.flat_rect("lk_c2", 7, 2, 0.0, LAKE, axis="x")       # 船尾外湖面
b.flat("lk_3_3", 3, 3, 0.0, LAKE)                     # 鸭群一行 (方板)
b.flat("lk_4_3", 4, 3, 0.0, LAKE)
b.flat_rect("lk_b3", 5, 3, 0.0, LAKE, axis="x")
b.flat("lk_7_3", 7, 3, 0.0, LAKE)                     # 浮标位
b.flat("lk_8_3", 8, 3, 0.0, LAKE)
b.flat_rect("lk_a4", 3, 4, 0.0, LAKE, axis="x")
b.flat_rect("lk_b4", 5, 4, 0.0, LAKE, axis="x")
b.flat_rect("lk_c4", 7, 4, 0.0, LAKE, axis="x")

# =================================================================
# 3. 船底 (z=0, 嵌进水面): 2 片长板 [3,7]x[2,3]
# =================================================================
b.flat_rect("hl_w", 3, 2, 0.0, HULL, axis="x")        # 船底前半 [3,5]
b.flat_rect("hl_e", 5, 2, 0.0, HULL, axis="x")        # 船底后半 [5,7]

# =================================================================
# 4. 舷墙 (z 0..1): 南北各 4 片方板, 相邻竖边互吸
# =================================================================
for x0 in range(3, 7):
    b.wall_ns(f"gw_s_{x0}", x0, 2.0, 0, HULL)         # 南舷
for x0 in range(3, 7):
    b.wall_ns(f"gw_n_{x0}", x0, 3.0, 0, HULL)         # 北舷
b.wall_ew("gw_bow", 3.0, 2, 0, HULL)                  # 船首端墙
b.wall_ew("gw_stn", 7.0, 2, 0, HULL)                  # 船尾端墙

# =================================================================
# 5. 翘头 + 座板 + 行囊
# =================================================================
b.crest_ew("bow_tip", 3.0, 2, 1.0, HULL)              # 船首翘头 (1.87 格)
b.crest_ew("stn_tip", 7.0, 2, 1.0, HULL)              # 船尾翘头
b.flat("seat_bow", 3, 2, 1.0, SEAT)                   # 船头座板
b.flat("seat_stn", 6, 2, 1.0, SEAT)                   # 船尾座板
PACK = b.hat4("pack", 3, 2, 1.0, CARGO,
              shape="equilateral_triangle")           # 红色行囊

# =================================================================
# 6. 浮标 + 生灵 + 植被
# =================================================================
BUOY_S = b.hat4("buoy_s", 7, 0, 0.0, BUOY,
                shape="equilateral_triangle")         # 南浮标
BUOY_N = b.hat4("buoy_n", 7, 3, 0.0, BUOY,
                shape="equilateral_triangle")         # 北浮标
b.crest_ns("duck_a", 3, 4.0, 0.0, DUCK)               # 鸭妈妈
b.crest_ns("duck_b", 4, 4.0, 0.0, DUCK)               # 小鸭
b.crest_ns("fish", 8, 1.0, 0.0, FISH)                 # 跃波青鱼
b.spire_ns("tr_a", 0, 1.0, 0.0, TREE)                 # 西南岸树
b.spire_ns("tr_b", 1, 5.0, 0.0, TREE)                 # 西北岸树
b.crest_ns("reed", 2, 5.0, 0.0, TREE)                 # 芦苇
BUSH = b.hat4("bush", 0, 2, 0.0, TREE,
              shape="equilateral_triangle")           # 岸边灌木
b.crest_ns("fl", 1, 0.0, 0.0, FLOWER)                 # 南沿花丛

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺西岸草地: 8 片绿色地坪铺出湖岸。",
    ["sh_0_0", "sh_1_0", "sh_r_1", "sh_0_2", "sh_1_2",
     "sh_r_3", "sh_0_4", "sh_1_4"],
    tip="岸边角落交替用方板 —— 树和灌木都要吸方板格边。",
)
b.step(
    "铺沙滩: 5 片金黄方板一列排开, 这是下水的地方。",
    ["sd_0", "sd_1", "sd_2", "sd_3", "sd_4"],
    highlight=["sh_1_0", "sh_1_4"],
    tip="沙滩东格边就是湖岸线 —— 船底马上要吸这条边。",
)
b.step(
    "铺湖面南半: 7 片蓝色湖水由岸向湖心铺开。",
    ["lk_a0", "lk_b0", "lk_7_0", "lk_8_0", "lk_a1", "lk_b1", "lk_c1"],
    highlight=["sd_0"],
    tip="浮标位 (7,0) 要用方板 —— 四坡锥的底边要吸格边。",
)
b.step(
    "铺湖面北半: 8 片合拢, 湖心留出 [3,7] 一条船位。",
    ["lk_3_3", "lk_4_3", "lk_b3", "lk_7_3", "lk_8_3",
     "lk_a4", "lk_b4", "lk_c4"],
    highlight=["lk_a1"],
    tip="鸭群一行用方板 —— 母鸭小鸭都要站格边。",
)
b.step(
    "嵌船底: 2 片橙色长板嵌进船位, 西短边吸沙滩格边、长边吸"
    "湖面长板, 再补船尾外 1 片湖水。",
    ["hl_w", "hl_e", "lk_c2"],
    highlight=["sd_2", "lk_b1"],
    tip="船底与湖面同层平铺零重叠 —— 船就是湖面的一部分。",
)
b.step(
    "立南舷墙: 4 片橙色方板沿 y=2 一字排开, 相邻竖边互吸。",
    ["gw_s_3", "gw_s_4", "gw_s_5", "gw_s_6"],
    highlight=["hl_w", "hl_e"],
    tip="底边完整落在船底长边内 —— 长短边贴合同样牢固。",
)
b.step(
    "立北舷墙: 北侧再立 4 片, 船帮两舷成形。",
    ["gw_n_3", "gw_n_4", "gw_n_5", "gw_n_6"],
    highlight=["gw_s_3"],
    tip="两舷平行如轨 —— 座板要横跨在它们顶上。",
)
b.step(
    "封船首船尾: 2 片端墙方板, 竖边与两舷四角咬合成环。",
    ["gw_bow", "gw_stn"],
    highlight=["gw_s_3", "gw_n_6"],
    tip="端墙一封, 船体锁成一只不进水的浅盒。",
)
b.step(
    "竖翘头: 船首船尾端墙顶上各立 1 片等边三角, 昂起 1.87 格。",
    ["bow_tip", "stn_tip"],
    highlight=["gw_bow", "gw_stn"],
    tip="独木舟的招牌翘头 —— 重心正压铰链, 劈波不低头。",
)
b.step(
    "架座板: 2 片黄色方板横跨船帮, 三边整边吸舷墙与端墙顶边。",
    ["seat_bow", "seat_stn"],
    highlight=["gw_s_3", "gw_s_6"],
    tip="座板如桥双边受力 —— 一前一后, 双人划桨的位置。",
)
b.step(
    "绑行囊: 船头座板上 4 片红色等边三角合拢成四坡行囊。",
    PACK,
    highlight=["seat_bow"],
    tip="露营装备打成锥形包 —— 斜棱互吸, 浪再大也不散。",
)
b.step(
    "抛南浮标: 湖面 (7,0) 方板上 4 片青色等边三角合拢成航标锥。",
    BUOY_S,
    highlight=["lk_7_0"],
    tip="浮标锥立在航道南侧 —— 独木舟从两标之间穿过。",
)
b.step(
    "抛北浮标: 同法再抛一座, 航道画定。",
    BUOY_N,
    highlight=["lk_7_3", "buoy_s_s"],
    tip="两座浮标一南一北, 湖心的水路有了规矩。",
)
b.step(
    "放鸭群与青鱼: 鸭妈妈带小鸭浮水, 青鱼在东南跃波。",
    ["duck_a", "duck_b", "fish"],
    highlight=["lk_3_3", "lk_8_0"],
    tip="嘎嘎嘎 —— 鸭群给独木舟让出航道。",
)
b.step(
    "种岸树与芦苇: 2 棵等腰绿树立岸边, 芦苇守在沙滩北头。",
    ["tr_a", "tr_b", "reed"],
    highlight=["sh_0_0", "sd_4"],
    tip="树梢 2 格是湖岸制高点 —— 芦苇丛里藏着蜻蜓。",
)
b.step(
    "栽灌木与花丛: 灌木四坡合拢, 花丛点在南沿 —— 独木舟启航!",
    BUSH + ["fl"],
    highlight=["sh_0_2", "sh_1_0"],
    tip="从沙滩望去: 翘头、行囊、浮标、鸭群一线排开 —— 欸乃一声山水绿。",
)

b.finalize(
    model_id="canoe_01",
    name="湖上独木舟",
    name_en="Lake Canoe 01",
    description=(
        "全库第一条独木舟: 船底长板嵌进水面同层平铺 (与湖面锁成连续水面), "
        "八片舷墙方板竖边连吸、与端墙四角咬合成环, 船首船尾等边翘头昂起 "
        "1.87 格; 舱内座板三边整边吸船帮顶边横跨如桥, 船头行囊四坡自锁; "
        "湖面两座浮标锥画定航道, 鸭妈妈带小鸭让路, 岸上沙滩、绿树、芦苇"
        "点景 —— 桨声欸乃, 湖光十里。"
    ),
    difficulty=3,
    tags=["自然", "湖泊", "独木舟", "海洋", "进阶"],
    min_pieces=50,
    min_steps=16,
)
