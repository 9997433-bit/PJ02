#!/usr/bin/env python3
"""生成模型 data/models/storage_chest_01.json (翻盖百宝盒)。

内容批 L 模型 1/4: 实用功能主题首个 D1 —— 翻盖百宝盒结构签名:
2x2 闭环箱框 + 展示垫平拼翻盖 + 磁吸边铰链 + 盒内百宝。

用法: python3 tools/generate_storage_chest_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

WOOD = "orange"
GOLD = "yellow"
PAD = "gray"
CLASP = "orange"

# =================================================================
# 1. 展示垫 (x [2,5], y [0,2]) —— 经连桥与盒底互连
# =================================================================
b.flat("link_20", 2, 0, 0.0, PAD)
b.flat("pad_3_0", 3, 0, 0.0, PAD)
b.flat("pad_4_0", 4, 0, 0.0, PAD)
b.flat("pad_4_1", 4, 1, 0.0, PAD)

# =================================================================
# 2. 盒底 2x2 (x [0,2], y [0,2])
# =================================================================
b.flat("base_00", 0, 0, 0.0, WOOD)
b.flat("base_01", 0, 1, 0.0, WOOD)
b.flat("base_10", 1, 0, 0.0, WOOD)
b.flat("base_11", 1, 1, 0.0, WOOD)

# =================================================================
# 3. 盒身墙环 (z 0..1)
# =================================================================
b.wall_ns("wall_s", 0, 0.0, 0, WOOD)
b.wall_ns("wall_n", 0, 2.0, 0, WOOD)
b.wall_ew("wall_w", 0.0, 0, 0, WOOD)
b.wall_ew("wall_e", 2.0, 0, 0, WOOD)

# =================================================================
# 4. 盒内百宝 (居中, 不压墙脚)
# =================================================================
b.crest_ns("coin_a", 1, 0.0, 0.0, GOLD)
b.crest_ns("coin_b", 1, 1.0, 0.0, GOLD)
b.crest_ew("coin_c", 1.0, 1, 0.0, GOLD)
b.spire_ns("key", 1, 2.0, 0.0, GOLD)

# =================================================================
# 5. 翻盖 2x2 + 后沿铰链长板
# =================================================================
b.flat("lid_00", 0, 0, 1.0, GOLD)
b.flat("lid_01", 0, 1, 1.0, GOLD)
b.flat("lid_10", 1, 0, 1.0, GOLD)
b.flat("lid_11", 1, 1, 1.0, GOLD)
b.wall_ew("hinge", 0.0, 0, 1, GOLD)

# =================================================================
# 6. 锁扣与把手
# =================================================================
b.crest_ns("clasp", 0, 0.0, 1.0, CLASP)
b.crest_ew("rivet_e", 2.0, 1, 1.0, CLASP)
b.crest_ew("handle", 1.0, 1, 1.0, GOLD)

# =================================================================
# 教程步骤 (8 步)
# =================================================================
b.step(
    "铺展示垫: 连桥方板把百宝盒与右侧工作台接成一体。",
    ["link_20", "pad_3_0", "pad_4_0", "pad_4_1"],
    tip="实用功能 D1 开工! 展示垫就是盖板平拼的工作台。",
)
b.step(
    "拼盒底: 四片胡桃木方板 2x2 整边互吸, 角对角对齐。",
    ["base_00", "base_01", "base_10", "base_11"],
    highlight=["link_20"],
    tip="盒底拼缝对齐, 墙脚才有整边可吸。",
)
b.step(
    "围盒身: 四片方墙踩住盒底四沿, 四角竖边互咬成环。",
    ["wall_s", "wall_n", "wall_w", "wall_e"],
    highlight=["base_00", "base_11"],
    tip="闭环箱框 —— 荷载沿墙面直下, 百宝才装得稳。",
)
b.step(
    "装入金币: 三枚金色三角放进盒内中央。",
    ["coin_a", "coin_b", "coin_c"],
    highlight=["wall_s"],
    tip="金币底边吸盒底拼缝 —— 关盖前先收好宝贝!",
)
b.step(
    "放入钥匙: 一把金色瘦高尖靠在盒内北半。",
    ["key"],
    highlight=["coin_a"],
    tip="钥匙也是百宝 —— 开盒靠它!",
)
b.step(
    "平拼翻盖并扣合: 四片金色方板 2x2 整边互吸, 沿后沿铰链翻折;"
    " 可先于垫板上平拼再整体搬回 —— 磁吸边即铰链。",
    ["lid_00", "lid_01", "lid_10", "lid_11", "hinge"],
    highlight=["pad_4_0", "wall_w"],
    tip="T05 平面翻折 —— 先在桌面平拼, 再沿后沿磁吸边整体翻折扣合。",
)
b.step(
    "扣上前锁: 前扣三角整边吸前墙顶与盖板前沿。",
    ["clasp"],
    highlight=["lid_00", "wall_s"],
    tip="前扣一片锁三件 —— 盖板被锁死了。",
)
b.step(
    "收角钉与顶把手: 角钉锁住盖板东沿, 金色把手一提就开 —— 百宝盒封箱!",
    ["rivet_e", "handle"],
    highlight=["clasp", "lid_11"],
    tip="翻盖百宝盒完工, 钥匙还在里面呢!",
)

b.finalize(
    model_id="storage_chest_01",
    name="翻盖百宝盒",
    name_en="Storage Chest 01",
    description=(
        "实用功能首个 D1: 结构签名是'翻盖百宝盒' —— 2x2 胡桃木闭环"
        "箱框内藏着三枚金币与一把钥匙; 盖板先在展示垫上平拼成 2x2 "
        "金色整板, 后沿长板与后墙顶共线互吸形成铰链, 再沿磁吸边整体"
        "翻折扣合 (T05 平面翻折, 磁吸边即铰链); 正面金扣三角同时吸"
        "前墙顶与盖板前沿, 角钉收边, 顶把手一提就开 —— "
        "与敞口格架收纳站的开合方式完全不同!"
    ),
    difficulty=1,
    tags=["实用功能", "收纳", "翻盖", "百宝盒", "入门"],
    min_pieces=24,
    min_steps=8,
    series="practical_utility",
)
