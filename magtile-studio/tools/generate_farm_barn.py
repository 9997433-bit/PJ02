#!/usr/bin/env python3
"""生成模型 data/models/farm_barn_01.json (农场谷仓)。

田园农场主题: 8x5 农家院里, 一座 4 格长的红色大谷仓拔地而起 ——
两层长方形墙体叠出高挑仓身, 南面开着木门 (门框方) 与采光窗
(窗格方), 顶上 60 度人字坡大屋面横跨四格, 东西山花封脊;
北侧接一间单坡?? 不, 平顶披屋当饲料棚, 棚顶两长板双端搭在
谷仓北墙顶与披屋北墙顶上如桥; 东院草料场上两座金黄干草堆
四坡自锁, 稻草人守在院北, 橙色栅栏围出牲口栏 —— 丰收啦!

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 农家院 8x5: 方板 + 长板混铺 (拼缝全部落在墙线上)        25 片
  - 谷仓首层: 长楣 x3 + 门框方 + 窗格方 + 端墙 x2            7 片
  - 谷仓二层: 长楣 x4 + 端墙 x2                              6 片
  - 人字坡大屋面: 60 度长方形 x4 + 等边山花 x2               6 片
  - 北披屋: 长楣 x2 + 端墙 x2 + 平顶长板 x2                  6 片
  - 干草堆: 等边四坡锥 x2                                    8 片
  - 稻草人 1 + 栅栏等边三角 x6                               7 片
  合计 65 片, 17 个教程步骤, 7 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 谷仓墙体整边吸地坪长板/方板拼缝, 门框方与窗格方外框按
    实心正方形拼接, 两端竖边与长楣/端墙竖边咬合成环;
  - 60 度人字坡: 4 片长方形下长边整边吸二层墙顶边, 脊线两两
    互吸, 等边山花底边吸端墙顶边、两腰吸坡面短边 (别墅同款);
  - 披屋平顶长板南沿吸谷仓北墙顶、北沿吸披屋北墙顶 —— 双端
    受力如桥, 同时把披屋与仓身锁成闭环;
  - 干草堆四片等边三角斜棱两两互吸自锁成环, 底边吸方板格边。

用法: python3 tools/generate_farm_barn.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

RIDGE_H = 0.866025          # 60 度坡面竖直投影 = 等边山花高

GRASS = "green"
PATH = "gray"
BARN = "red"
ROOF = "gray"
SHED = "orange"
HAY = "yellow"
FENCE = "orange"

# =================================================================
# 1. 农家院 8x5 (x 0..8, y 0..5): 拼缝纪律 —— 谷仓墙线 (y=1/2/3,
#    x=1/3/5) 处必须有等长地坪边给墙底整边吸合
# =================================================================
# 南排 y[0,1]: 门前小路 (灰) 开在大门正南
b.flat("g_0_0", 0, 0, 0.0, GRASS)
b.flat_rect("g_r_s", 1, 0, 0.0, GRASS, axis="x")      # [1,3] 谷仓南墙地基
b.flat("g_3_0", 3, 0, 0.0, PATH)                      # 大门正南小路
b.flat("g_4_0", 4, 0, 0.0, GRASS)
b.flat_rect("g_r_se", 5, 0, 0.0, GRASS, axis="x")     # [5,7] 草料场南
b.flat("g_7_0", 7, 0, 0.0, GRASS)
# 仓内地坪 y[1,2]
b.flat("g_0_1", 0, 1, 0.0, GRASS)
b.flat_rect("g_f_w", 1, 1, 0.0, PATH, axis="x")       # 仓内西半 [1,3]
b.flat_rect("g_f_e", 3, 1, 0.0, PATH, axis="x")       # 仓内东半 [3,5]
b.flat_rect("g_c_s", 5, 1, 0.0, GRASS, axis="x")      # 草料场 [5,7]
b.flat("g_7_1", 7, 1, 0.0, GRASS)                     # 干草堆基座 1
# 披屋地坪 y[2,3]
b.flat("g_0_2", 0, 2, 0.0, GRASS)
b.flat_rect("g_l_w", 1, 2, 0.0, PATH, axis="x")       # 披屋内西半 [1,3]
b.flat_rect("g_l_e", 3, 2, 0.0, PATH, axis="x")       # 披屋内东半 [3,5]
b.flat_rect("g_c_n", 5, 2, 0.0, GRASS, axis="x")      # 草料场 [5,7]
b.flat("g_7_2", 7, 2, 0.0, GRASS)
# 院北 y[3,4]
b.flat("g_0_3", 0, 3, 0.0, GRASS)
b.flat_rect("g_n_w", 1, 3, 0.0, GRASS, axis="x")      # [1,3] 披屋北墙地基
b.flat_rect("g_n_e", 3, 3, 0.0, GRASS, axis="x")      # [3,5]
b.flat_rect("g_c_f", 5, 3, 0.0, GRASS, axis="x")      # [5,7]
b.flat("g_7_3", 7, 3, 0.0, GRASS)                     # 干草堆基座 2
# 最北排 y[4,5]
b.flat_rect("g_t_0", 0, 4, 0.0, GRASS, axis="x")
b.flat_rect("g_t_2", 2, 4, 0.0, GRASS, axis="x")
b.flat_rect("g_t_4", 4, 4, 0.0, GRASS, axis="x")
b.flat_rect("g_t_6", 6, 4, 0.0, GRASS, axis="x")

# =================================================================
# 2. 谷仓首层 (x 1..5, y 1..2, z 0..1): 南面 长楣+门框方+窗格方,
#    北面长楣 x2, 东西端墙
# =================================================================
b.lintel_ns("bw_s1", 1, 1.0, 0, BARN)                 # 南墙西段 [1,3]
b.wall_ns("bw_door", 3, 1.0, 0, SHED)                 # 大门 (门框方外框=正方形)
b.tiles[-1]["type"] = "door_frame"
b.wall_ns("bw_win", 4, 1.0, 0, "clear")               # 采光窗 (窗格方)
b.tiles[-1]["type"] = "window_square"
b.lintel_ns("bw_n1w", 1, 2.0, 0, BARN)                # 北墙西段
b.lintel_ns("bw_n1e", 3, 2.0, 0, BARN)                # 北墙东段
b.wall_ew("bw_w1", 1.0, 1, 0, BARN)                   # 西端墙
b.wall_ew("bw_e1", 5.0, 1, 0, BARN)                   # 东端墙

# =================================================================
# 3. 谷仓二层 (z 1..2): 长楣 x4 + 端墙 x2
# =================================================================
b.lintel_ns("bw_s2w", 1, 1.0, 1, BARN)
b.lintel_ns("bw_s2e", 3, 1.0, 1, BARN)
b.lintel_ns("bw_n2w", 1, 2.0, 1, BARN)
b.lintel_ns("bw_n2e", 3, 2.0, 1, BARN)
b.wall_ew("bw_w2", 1.0, 1, 1, BARN)
b.wall_ew("bw_e2", 5.0, 1, 1, BARN)

# =================================================================
# 4. 人字坡大屋面 (檐口 z=2, 脊线 z=2.866): 60 度长方形 x4 +
#    等边山花 x2
# =================================================================
b.place_edge("rf_s_w", "rectangle", 0, (1.0, 1.0, 2.0), (3.0, 1.0, 2.0),
             (0.0, 0.5, RIDGE_H), ROOF)               # 南坡西段
b.place_edge("rf_s_e", "rectangle", 0, (3.0, 1.0, 2.0), (5.0, 1.0, 2.0),
             (0.0, 0.5, RIDGE_H), ROOF)               # 南坡东段
b.place_edge("rf_n_e", "rectangle", 0, (5.0, 2.0, 2.0), (3.0, 2.0, 2.0),
             (0.0, -0.5, RIDGE_H), ROOF)              # 北坡东段
b.place_edge("rf_n_w", "rectangle", 0, (3.0, 2.0, 2.0), (1.0, 2.0, 2.0),
             (0.0, -0.5, RIDGE_H), ROOF)              # 北坡西段
b.crest_ew("gb_w", 1.0, 1, 2.0, BARN)                 # 西山花
b.crest_ew("gb_e", 5.0, 1, 2.0, BARN)                 # 东山花

# =================================================================
# 5. 北披屋 (x 1..5, y 2..3, z 0..1): 饲料棚, 平顶长板双端如桥
# =================================================================
b.lintel_ns("sh_n_w", 1, 3.0, 0, SHED)                # 披屋北墙西段
b.lintel_ns("sh_n_e", 3, 3.0, 0, SHED)                # 披屋北墙东段
b.wall_ew("sh_w", 1.0, 2, 0, SHED)                    # 披屋西端墙
b.wall_ew("sh_e", 5.0, 2, 0, SHED)                    # 披屋东端墙
b.flat_rect("sh_rf_w", 1, 2, 1.0, ROOF, axis="x")     # 棚顶西半 [1,3]x[2,3]
b.flat_rect("sh_rf_e", 3, 2, 1.0, ROOF, axis="x")     # 棚顶东半 [3,5]x[2,3]

# =================================================================
# 6. 草料场: 两座金黄干草堆 (等边四坡锥自锁)
# =================================================================
HAY_S = b.hat4("hay_s", 7, 1, 0.0, HAY, shape="equilateral_triangle")
HAY_N = b.hat4("hay_n", 7, 3, 0.0, HAY, shape="equilateral_triangle")

# =================================================================
# 7. 稻草人 + 栅栏: 等腰高塔尖立院北, 等边三角围出牲口栏
# =================================================================
b.spire_ns("scare", 0, 4.0, 0.0, HAY)                 # 稻草人 (院西北)
b.crest_ns("fn_s0", 4, 0.0, 0.0, FENCE)               # 南栅栏 (留门口)
b.crest_ns("fn_s1", 7, 0.0, 0.0, FENCE)
b.crest_ew("fn_e0", 8.0, 0, 0.0, FENCE)               # 东栅栏
b.crest_ew("fn_e1", 8.0, 1, 0.0, FENCE)
b.crest_ew("fn_e2", 8.0, 2, 0.0, FENCE)
b.crest_ew("fn_e3", 8.0, 3, 0.0, FENCE)

# =================================================================
# 教程步骤 (17 步): 院子 -> 仓身 -> 屋面 -> 披屋 -> 草料场 -> 收尾
# =================================================================
b.step(
    "铺院子南排: 6 片地坪沿南沿排开, 灰色方板是大门正南的小路, "
    "长板拼缝正落在谷仓南墙线上。",
    ["g_0_0", "g_r_s", "g_3_0", "g_4_0", "g_r_se", "g_7_0"],
    tip="长板 [1,3] 的北长边就是谷仓南墙的地基线 —— 拼缝纪律从第一步开始。",
)
b.step(
    "铺仓内与披屋地坪: 灰色长板铺出仓内两进地面, 东侧再补草料场地坪。",
    ["g_0_1", "g_f_w", "g_f_e", "g_c_s", "g_7_1",
     "g_0_2", "g_l_w", "g_l_e", "g_c_n", "g_7_2"],
    highlight=["g_r_s", "g_3_0"],
    tip="仓内 y=2 拼缝是谷仓北墙线, y=3 拼缝是披屋北墙线 —— 一缝不差。",
)
b.step(
    "铺院北两排: 9 片地坪合拢, 8x5 农家院就绪。",
    ["g_0_3", "g_n_w", "g_n_e", "g_c_f", "g_7_3",
     "g_t_0", "g_t_2", "g_t_4", "g_t_6"],
    highlight=["g_l_w", "g_c_n"],
    tip="院子铺满, 谷仓马上动工 —— 农场的一天从地基开始。",
)
b.step(
    "立谷仓南墙首层: 红色长楣起西段, 木门 (门框方) 与采光窗 (窗格方) "
    "依次向东排开, 竖边两两咬合。",
    ["bw_s1", "bw_door", "bw_win"],
    highlight=["g_r_s", "g_3_0"],
    tip="门框方外框与正方形完全一致 —— 底边吸方板格边, 竖边吸长楣短边。",
)
b.step(
    "立谷仓北墙与端墙首层: 北面 2 片长楣, 东西各 1 片端墙方板, "
    "首层围合成环。",
    ["bw_n1w", "bw_n1e", "bw_w1", "bw_e1"],
    highlight=["bw_s1", "bw_win"],
    tip="端墙竖边同时咬住南北墙的竖边 —— 一圈锁定, 仓身不晃。",
)
b.step(
    "叠谷仓二层: 4 片长楣 + 2 片端墙再叠一圈, 仓身升到 2 格高。",
    ["bw_s2w", "bw_s2e", "bw_n2w", "bw_n2e", "bw_w2", "bw_e2"],
    highlight=["bw_s1", "bw_n1w"],
    tip="上下圈层竖缝对齐, 墙顶留出两条 2 格长的整边给大屋面。",
)
b.step(
    "架南坡屋面: 2 片灰色长方形 60 度斜置, 下长边整边吸南墙顶边。",
    ["rf_s_w", "rf_s_e"],
    highlight=["bw_s2w", "bw_s2e"],
    tip="坡面先扶稳别松手 —— 等北坡上来, 脊线一吸就锁死。",
)
b.step(
    "北坡合脊: 再上 2 片, 脊线处两两长边互吸, 人字大屋面合拢。",
    ["rf_n_e", "rf_n_w"],
    highlight=["rf_s_w", "rf_s_e"],
    tip="咔哒两声 —— 四片坡面在 2.87 格高的屋脊锁成一体。",
)
b.step(
    "封山花: 东西各立 1 片红色等边三角形, 底边吸端墙顶边, "
    "两腰恰好吸住坡面短边。",
    ["gb_w", "gb_e"],
    highlight=["rf_s_w", "rf_n_w"],
    tip="等边三角底 1 高 0.866, 与 60 度坡面严丝合缝 —— 谷仓封顶!",
)
b.step(
    "起北披屋墙: 北墙 2 片橙色长楣 + 东西 2 片端墙, 饲料棚围出一进。",
    ["sh_n_w", "sh_n_e", "sh_w", "sh_e"],
    highlight=["bw_n1w", "bw_n1e"],
    tip="披屋北墙立在 y=3 拼缝上, 端墙竖边咬住北墙短边。",
)
b.step(
    "盖披屋平顶: 2 片灰色长板, 南沿吸谷仓北墙顶、北沿吸披屋北墙顶。",
    ["sh_rf_w", "sh_rf_e"],
    highlight=["sh_n_w", "bw_n1w"],
    tip="双端受力如桥 —— 棚顶同时把披屋与仓身锁成闭环。",
)
b.step(
    "堆南干草堆: 草料场方板上 4 片金黄等边三角形斜棱互吸, "
    "合拢成四坡草垛。",
    HAY_S,
    highlight=["g_7_1"],
    tip="先立相对两片再补另外两片 —— 草垛自锁成环, 风吹不倒。",
)
b.step(
    "堆北干草堆: 同法再堆一座, 今年收成真不错。",
    HAY_N,
    highlight=["hay_s_s"],
    tip="两座草垛一南一北, 牲口栏的冬粮备齐了。",
)
b.step(
    "立稻草人: 金黄等腰高塔尖立在院北地坪格边上。",
    ["scare"],
    highlight=["g_t_0"],
    tip="稻草人 2 格高, 底边整边吸方板格边 —— 麻雀们请自觉绕道。",
)
b.step(
    "插南栅栏: 2 片橙色等边三角立南沿, 中间留出进场口。",
    ["fn_s0", "fn_s1"],
    highlight=["g_4_0"],
    tip="栅栏底边吸地坪格边, 三角形站得稳稳的。",
)
b.step(
    "插东栅栏南段: 2 片等边三角沿东沿排开。",
    ["fn_e0", "fn_e1"],
    highlight=["fn_s1"],
    tip="牲口栏从这里开始围合。",
)
b.step(
    "插东栅栏北段: 最后 2 片就位 —— 红顶谷仓、饲料棚、草垛与"
    "稻草人一起交付, 丰收的农场开张!",
    ["fn_e2", "fn_e3"],
    highlight=["fn_e1"],
    tip="从南边小路望去: 木门、采光窗、人字大屋顶一线排开 —— 欢迎来农场。",
)

b.finalize(
    model_id="farm_barn_01",
    name="农场谷仓",
    name_en="Farm Barn 01",
    description=(
        "田园农场的当家建筑: 4 格长的红色大谷仓用两层长楣圈层叠出高挑仓身, "
        "南面木门 (门框方) 与采光窗 (窗格方) 竖边咬合入墙, 60 度人字大屋面"
        "四片坡板脊线互吸、等边山花封脊; 北侧披屋平顶长板双端受力如桥, "
        "把饲料棚与仓身锁成闭环; 草料场上两座等边四坡干草堆自锁成环, "
        "稻草人与橙色栅栏围出牲口栏 —— 丰收季的农场从这里开张。"
    ),
    difficulty=3,
    tags=["田园", "农场", "谷仓", "人字坡", "进阶"],
    min_pieces=50,
    min_steps=16,
)
