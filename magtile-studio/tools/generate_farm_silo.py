#!/usr/bin/env python3
"""生成模型 data/models/farm_silo_01.json (农场筒仓)。

田园农场主题: 6x5 场院里, 两座三层高的灰色筒仓塔并肩而立 ——
每座都是 1x1 方形圈层 x3 叠成的粮塔, 蓝色压顶方板封口,
红色等腰四坡锥顶冲天 (锥尖 4.94 格, 全场最高); 两塔之间
z=3 处一片黄色天桥方板双端搭在塔顶墙沿如桥, 桥沿再立
等边护栏; 塔脚下橙色卸粮溜槽斜贴塔壁, 场院南头金黄粮堆
四坡自锁, 栅栏围出晒谷场 —— 今年的玉米装满两塔!

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 场院 6x5: 方板 + 长板混铺                               23 片
  - 双塔: 方形圈层 x3 层 x2 塔 (每层 4 片)                  24 片
  - 塔顶: 压顶方板 x2 + 等腰四坡锥 x2 (每座 4 片)           10 片
  - 天桥: 方板 x1 + 等边护栏 x2                              3 片
  - 卸粮溜槽: 直角三角 x1                                    1 片
  - 粮堆: 等边四坡锥 x1 (4 片) + 栅栏等边三角 x4             8 片
  合计 69 片, 16 个教程步骤, 5 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 塔身方形圈层砌法: 每层 4 片方板四角竖边咬合成环 (闭环
    加固), 层层竖缝对齐, 底层底边整边吸场院方板格边;
  - 压顶方板四边整边吸顶层墙顶, 等腰锥四片斜棱两两互吸
    自锁成环, 底边整边吸压顶四边 —— 摩天大楼金顶同款;
  - 天桥方板西沿吸西塔东墙顶、东沿吸东塔西墙顶, 双端受力
    如桥, 同时把双塔锁成一个大环; 护栏底边整边吸桥沿;
  - 溜槽直角边分别吸地坪格边与塔壁竖边, 斜边即滑道。

用法: python3 tools/generate_farm_silo.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

YARD = "green"
PAVE = "gray"
SILO = "gray"
CAP = "blue"
CONE = "red"
BRIDGE = "yellow"
GRAIN = "yellow"
CHUTE = "orange"
FENCE = "orange"

# =================================================================
# 1. 场院 6x5 (x 0..6, y 0..5): 塔基 (1,2) 与 (3,2) 必须是完整
#    方板, 四条格边给塔身底层整边吸合
# =================================================================
b.flat("y_0_0", 0, 0, 0.0, YARD)
b.flat_rect("y_r_s", 1, 0, 0.0, PAVE, axis="x")       # 晒谷场 [1,3]
b.flat("y_3_0", 3, 0, 0.0, PAVE)
b.flat("y_4_0", 4, 0, 0.0, GRAIN)                     # 粮堆基座
b.flat("y_5_0", 5, 0, 0.0, YARD)
for x in range(4):
    b.flat(f"y_{x}_1", x, 1, 0.0, PAVE if x in (1, 3) else YARD)
b.flat_rect("y_r_1", 4, 1, 0.0, YARD, axis="x")       # [4,6]x[1,2]
b.flat("y_0_2", 0, 2, 0.0, YARD)
b.flat("y_1_2", 1, 2, 0.0, PAVE)                      # 西塔塔基
b.flat("y_2_2", 2, 2, 0.0, PAVE)                      # 双塔之间
b.flat("y_3_2", 3, 2, 0.0, PAVE)                      # 东塔塔基
b.flat_rect("y_r_2", 4, 2, 0.0, YARD, axis="x")       # [4,6]x[2,3]
for x in range(4):
    b.flat(f"y_{x}_3", x, 3, 0.0, YARD)
b.flat_rect("y_r_3", 4, 3, 0.0, YARD, axis="x")       # [4,6]x[3,4]
b.flat_rect("y_t_0", 0, 4, 0.0, YARD, axis="x")
b.flat_rect("y_t_2", 2, 4, 0.0, YARD, axis="x")
b.flat_rect("y_t_4", 4, 4, 0.0, YARD, axis="x")

# =================================================================
# 2. 双塔塔身: 1x1 方形圈层 x3 层 x2 塔 (西塔 [1,2]x[2,3],
#    东塔 [3,4]x[2,3])
# =================================================================
for tag, x0 in (("w", 1), ("e", 3)):
    for z0 in range(3):
        b.wall_ns(f"t{tag}_s_{z0}", x0, 2.0, z0, SILO)     # 南壁
        b.wall_ns(f"t{tag}_n_{z0}", x0, 3.0, z0, SILO)     # 北壁
        b.wall_ew(f"t{tag}_w_{z0}", float(x0), 2, z0, SILO)      # 西壁
        b.wall_ew(f"t{tag}_e_{z0}", float(x0 + 1), 2, z0, SILO)  # 东壁

# =================================================================
# 3. 塔顶: 蓝色压顶 + 红色等腰四坡锥 (锥尖 z=4.94)
# =================================================================
b.flat("tw_cap", 1, 2, 3.0, CAP)
b.flat("te_cap", 3, 2, 3.0, CAP)
CONE_W = b.hat4("tw_cone", 1, 2, 3.0, CONE)
CONE_E = b.hat4("te_cone", 3, 2, 3.0, CONE)

# =================================================================
# 4. 天桥 (z=3): 方板双端搭双塔墙顶 + 等边护栏
# =================================================================
b.flat("br_deck", 2, 2, 3.0, BRIDGE)                  # [2,3]x[2,3]
b.crest_ns("br_rl_s", 2, 2.0, 3.0, BRIDGE)            # 南护栏
b.crest_ns("br_rl_n", 2, 3.0, 3.0, BRIDGE)            # 北护栏

# =================================================================
# 5. 卸粮溜槽 + 粮堆 + 栅栏
# =================================================================
b.brace("chute", (2.0, 2.0, 0.0), "+x", CHUTE)        # 西塔脚溜槽
GRAIN_PILE = b.hat4("grain", 4, 0, 0.0, GRAIN,
                    shape="equilateral_triangle")     # 金黄粮堆
b.crest_ns("fn_s", 3, 0.0, 0.0, FENCE)                # 南栅栏
b.crest_ew("fn_e1", 6.0, 1, 0.0, FENCE)               # 东栅栏
b.crest_ew("fn_e2", 6.0, 2, 0.0, FENCE)
b.crest_ew("fn_e3", 6.0, 3, 0.0, FENCE)

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺场院南排: 5 片地坪排开, 灰色是晒谷场, 金黄方板给粮堆留位。",
    ["y_0_0", "y_r_s", "y_3_0", "y_4_0", "y_5_0"],
    tip="场院从南沿铺起, 晒谷场长板的拼缝对准塔基列。",
)
b.step(
    "铺场院中部: 两行合拢, 灰色方板标出双塔塔基与塔间通道。",
    ["y_0_1", "y_1_1", "y_2_1", "y_3_1", "y_r_1",
     "y_0_2", "y_1_2", "y_2_2", "y_3_2", "y_r_2"],
    highlight=["y_r_s", "y_3_0"],
    tip="塔基 (1,2) 与 (3,2) 必须是完整方板 —— 四条格边都要给塔身吸。",
)
b.step(
    "铺场院北部: 8 片合拢, 6x5 场院就绪。",
    ["y_0_3", "y_1_3", "y_2_3", "y_3_3", "y_r_3",
     "y_t_0", "y_t_2", "y_t_4"],
    highlight=["y_1_2", "y_3_2"],
    tip="场院铺好, 该起塔了 —— 双塔并肩, 一西一东。",
)
b.step(
    "起西塔首层: 4 片灰色方板围塔基一圈, 四角竖边咬合成环。",
    ["tw_s_0", "tw_n_0", "tw_w_0", "tw_e_0"],
    highlight=["y_1_2"],
    tip="方形圈层砌法 —— 每个转角两片竖边互吸, 一圈锁定。",
)
b.step(
    "起东塔首层: 同法再围一圈, 双塔同步生长。",
    ["te_s_0", "te_n_0", "te_w_0", "te_e_0"],
    highlight=["tw_s_0", "y_3_2"],
    tip="两塔之间隔一格通道 —— 天桥将来就架在这里。",
)
b.step(
    "叠西塔二层: 竖缝对齐再叠一圈。",
    ["tw_s_1", "tw_n_1", "tw_w_1", "tw_e_1"],
    highlight=["tw_s_0"],
    tip="上下圈层竖缝对齐, 塔身才站得直。",
)
b.step(
    "叠东塔二层: 东塔跟上, 齐头并进。",
    ["te_s_1", "te_n_1", "te_w_1", "te_e_1"],
    highlight=["te_s_0", "tw_s_1"],
    tip="搭双塔要轮流叠层 —— 单塔冒进容易碰倒邻居。",
)
b.step(
    "叠西塔三层: 西塔到顶, 3 格高。",
    ["tw_s_2", "tw_n_2", "tw_w_2", "tw_e_2"],
    highlight=["tw_s_1"],
    tip="第三圈上墙, 粮塔的容量就是这么叠出来的。",
)
b.step(
    "叠东塔三层: 东塔到顶, 双塔等高。",
    ["te_s_2", "te_n_2", "te_w_2", "te_e_2"],
    highlight=["te_s_1", "tw_s_2"],
    tip="两塔墙顶齐平 —— 天桥的桥墩已经就位。",
)
b.step(
    "封双塔压顶: 2 片蓝色方板四边整边吸顶层墙顶。",
    ["tw_cap", "te_cap"],
    highlight=["tw_s_2", "te_s_2"],
    tip="压顶一放, 整圈墙顶纹丝不动 —— 粮塔封舱。",
)
b.step(
    "架天桥: 1 片黄色方板西沿吸西塔东墙顶、东沿吸东塔西墙顶, "
    "桥沿再立 2 片等边护栏。",
    ["br_deck", "br_rl_s", "br_rl_n"],
    highlight=["tw_cap", "te_cap"],
    tip="双端受力如桥 —— 天桥同时把双塔锁成一个大环。",
)
b.step(
    "起西塔锥顶: 4 片红色等腰三角斜棱两两互吸, 锥尖直指 4.94 格。",
    CONE_W,
    highlight=["tw_cap"],
    tip="先立相对两片再补另外两片 —— 四坡锥自锁成环。",
)
b.step(
    "起东塔锥顶: 同法合拢, 双锥齐天 —— 筒仓的天际线完成!",
    CONE_E,
    highlight=["te_cap", "tw_cone_s"],
    tip="红色双锥是农场最高点, 十里外就能望见。",
)
b.step(
    "装卸粮溜槽: 1 片橙色直角三角斜贴西塔东壁, 直角边分别"
    "吸地坪格边与塔壁竖边。",
    ["chute"],
    highlight=["tw_e_0"],
    tip="斜边就是滑道 —— 开闸, 玉米哗啦啦滑进料车。",
)
b.step(
    "堆粮堆: 晒谷场东头 4 片金黄等边三角合拢成四坡粮山。",
    GRAIN_PILE,
    highlight=["y_4_0"],
    tip="装不下的粮食先堆在场院里 —— 这是丰收的烦恼。",
)
b.step(
    "插栅栏: 南沿 1 片、东沿 3 片等边三角围出晒谷场 —— 双塔"
    "筒仓交付使用!",
    ["fn_s", "fn_e1", "fn_e2", "fn_e3"],
    highlight=["grain_s"],
    tip="从场院南头望去: 粮堆、溜槽、双塔、天桥、红锥一线排开。",
)

b.finalize(
    model_id="farm_silo_01",
    name="农场筒仓",
    name_en="Farm Silo 01",
    description=(
        "农场的粮食摩天楼: 两座 1x1 方形圈层粮塔并肩叠起三层, 蓝色压顶"
        "封口, 红色等腰四坡锥顶自锁冲天 (锥尖 4.94 格全场最高); 塔间"
        "天桥方板双端搭墙顶如桥, 把双塔锁成一个大环, 桥沿等边护栏"
        "守住高空通道; 塔脚橙色溜槽斜贴塔壁, 晒谷场上粮堆四坡自锁, "
        "栅栏围场 —— 圈层塔身、双端天桥、四坡锥顶三大技法一次学会。"
    ),
    difficulty=3,
    tags=["田园", "农场", "筒仓", "双塔", "进阶"],
    min_pieces=50,
    min_steps=16,
)
