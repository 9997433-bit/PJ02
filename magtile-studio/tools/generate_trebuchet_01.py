#!/usr/bin/env python3
"""生成模型 data/models/trebuchet_01.json (城堡投石机)。

内容批 E 补位模型 (顶替与批 B aquarium_tunnel_01 同题撤下的 aquarium_01):
全库第一台攻城器械 —— 城堡家族 (castle_tower / castle_drawbridge /
medieval_gate / knight_armor) 里只有城没有"械", 本作补上演武场一景;
与 dragon_cave_01 (洞窟藏宝) / ball_run_tower_01 (滚珠滑道) 刻意区分:
结构签名是"上弦待发的 30 度斜臂" —— 投石长臂是一块 30 度长板,
顶边铰在机架箱东沿 (与机架墙顶/台板沿/配重箱脚四线共吸),
坡尾稳稳压地 (顶铰链 + 接地坡尾, 海滩小屋栈道同款受力);
配重石箱高高摞在机架箱顶 —— 配重在上、长臂在下, 正是投石机
上好弦的一瞬间。西端靶楼二层嵌两扇窗格方当靶窗, 城堡运动会
的投准表演马上开场!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 长臂指向东):
  - 演武场地坪 4 行 (x [0,7], y [0,4]): 碎石场 + 北侧草坪      22 片
  - 靶楼 (x [0,1], y [1,3], z 0..2): 一层墙环 + 二层靶窗环
    + 步道盖板 x2 + 城垛红三角 x2 + 守垛小骑士                  17 片
  - 投石机 (x [3,4], y [1,2]): 机架箱 + 台板 + 配重石箱
    + 箱顶盖 + 30 度投石长臂 + 队旗                             12 片
  - 彩色石弹金字塔 (四棱自锁) + 绞盘手 + 裁判官                  6 片
  合计 57 片, 12 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告 + jitter 全绿):
  - 长臂顶边整边吸机架箱东墙顶, 坡尾压地 —— 顶铰链 + 接地坡尾,
    重量走两条路, 悬臂力矩为零;
  - 机架箱与配重石箱都是四墙闭环 + 盖板的箱楼 (整边共线上叠);
  - 靶楼两节墙环四角竖边互咬, 二层靶窗物理上按实心正方形处理;
  - 石弹金字塔四棱自锁 (等边四坡锥), 底边整边吸地坪方板;
  - 地坪拼缝纪律: 靶楼墙脚 / 机架墙脚 / 石弹堆底下全单位方板。

用法: python3 tools/generate_trebuchet_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

PLAZA = "gray"      # 演武场碎石地
LAWN = "green"      # 北侧草坪
TWALL = "gray"      # 靶楼石墙
TWIN = "cyan"       # 靶窗
TCAP = "gray"       # 靶楼步道
MERLON = "red"      # 城垛
KNIGHT = "blue"     # 守垛小骑士
FRAME = "orange"    # 投石机木机架
DECK = "orange"     # 机架台板
CRATE = "purple"    # 配重石箱
ARM = "red"         # 投石长臂
FLAG = "yellow"     # 队旗
BOULDER = "pink"    # 彩色石弹
WINCH = "cyan"      # 绞盘手
REF = "green"       # 裁判官

# =================================================================
# 1. 演武场地坪 4 行 (x [0,7], y [0,4])
# =================================================================
# 石弹行 (y [0,1]): 石弹堆底与机架南脚下全单位方板
b.flat_rect("g0_w", 0, 0, 0.0, PLAZA)
for x in (2, 3, 4, 5, 6):
    b.flat(f"g0_{x}", x, 0, 0.0, PLAZA)
# 靶墙行 (y [1,2]): 靶楼脚 / 机架脚 / 坡尾全在这一行
for x in (0, 1, 2, 3):
    b.flat(f"g1_{x}", x, 1, 0.0, PLAZA)
b.flat_rect("g1_e", 4, 1, 0.0, PLAZA)
b.flat("g1_6", 6, 1, 0.0, PLAZA)
# 靶墙后行 (y [2,3])
for x in (0, 1, 2, 3):
    b.flat(f"g2_{x}", x, 2, 0.0, PLAZA)
b.flat_rect("g2_e", 4, 2, 0.0, PLAZA)
b.flat("g2_6", 6, 2, 0.0, PLAZA)
# 草坪行 (y [3,4])
b.flat_rect("g3_w", 0, 3, 0.0, LAWN)
b.flat_rect("g3_m", 2, 3, 0.0, LAWN)
b.flat_rect("g3_e", 4, 3, 0.0, LAWN)
b.flat("g3_6", 6, 3, 0.0, LAWN)

# =================================================================
# 2. 靶楼一层墙环 (x [0,1], y [1,3], z 0..1)
# =================================================================
b.wall_ew("t1_w_1", 0.0, 1, 0, TWALL)
b.wall_ew("t1_w_2", 0.0, 2, 0, TWALL)
b.wall_ew("t1_e_1", 1.0, 1, 0, TWALL)
b.wall_ew("t1_e_2", 1.0, 2, 0, TWALL)
b.wall_ns("t1_s", 0, 1.0, 0, TWALL)
b.wall_ns("t1_n", 0, 3.0, 0, TWALL)

# =================================================================
# 3. 靶楼二层靶窗环 (z 1..2): 东面两扇窗格方正对投石机
# =================================================================
b.wall_ew("t2_w_1", 0.0, 1, 1, TWALL)
b.wall_ew("t2_w_2", 0.0, 2, 1, TWALL)
b.add("t2_e_1", "window_square", (1.0, 1.5, 1.5), (90, 0, 90), TWIN)
b.add("t2_e_2", "window_square", (1.0, 2.5, 1.5), (90, 0, 90), TWIN)
b.wall_ns("t2_s", 0, 1.0, 1, TWALL)
b.wall_ns("t2_n", 0, 3.0, 1, TWALL)

# =================================================================
# 4. 靶楼步道 + 城垛 + 守垛小骑士 (z=2)
# =================================================================
b.flat("tcap_s", 0, 1, 2.0, TCAP)
b.flat("tcap_n", 0, 2, 2.0, TCAP)
b.crest_ew("merlon_s", 0.0, 1, 2.0, MERLON)   # 骑步道西沿
b.crest_ew("merlon_n", 0.0, 2, 2.0, MERLON)
b.crest_ns("knight", 0, 2.0, 2.0, KNIGHT)     # 骑步道拼缝

# =================================================================
# 5. 投石机机架箱 (x [3,4], y [1,2], z 0..1) + 台板
# =================================================================
b.wall_ew("f_w", 3.0, 1, 0, FRAME)
b.wall_ew("f_e", 4.0, 1, 0, FRAME)
b.wall_ns("f_s", 3, 1.0, 0, FRAME)
b.wall_ns("f_n", 3, 2.0, 0, FRAME)
b.flat("f_deck", 3, 1, 1.0, DECK)

# =================================================================
# 6. 配重石箱 (z 1..2) + 箱顶盖 + 队旗
# =================================================================
b.wall_ew("c_w", 3.0, 1, 1, CRATE)
b.wall_ew("c_e", 4.0, 1, 1, CRATE)
b.wall_ns("c_s", 3, 1.0, 1, CRATE)
b.wall_ns("c_n", 3, 2.0, 1, CRATE)
b.flat("c_cap", 3, 1, 2.0, CRATE)
b.spire_ns("flag", 3, 1.0, 2.0, FLAG)         # 骑箱顶南沿, 尖 3.94 全场制高

# =================================================================
# 7. 投石长臂: 30 度长板, 顶边铰机架东沿, 坡尾压地
# =================================================================
b.ramp("arm", "+x", 4.0, 1, 1.0, ARM)

# =================================================================
# 8. 彩色石弹金字塔 + 绞盘手 + 裁判官
# =================================================================
b.hat4("boulder", 5, 0, 0.0, BOULDER, shape="equilateral_triangle")
b.crest_ns("winch", 2, 1.0, 0.0, WINCH)       # 绞盘手骑地缝, 守在机架西侧
b.crest_ew("referee", 6.0, 2, 0.0, REF)       # 裁判官骑地缝, 在东边观赛

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺靶墙行: 四片单位方板 + 长板 + 单位方板, 靶楼和机架的脚都踩这行。",
    ["g1_0", "g1_1", "g1_2", "g1_3", "g1_e", "g1_6"],
    tip="城堡运动会要开投准表演啦! 先把演武场的地坪铺平整。",
)
b.step(
    "铺靶墙后行: 和上一行等长边互吸, 靶楼的北脚也要落在单位方板上。",
    ["g2_0", "g2_1", "g2_2", "g2_3", "g2_e", "g2_6"],
    highlight=["g1_0"],
    tip="墙脚下必须是单位方板 —— 墙底边要和方板边等长吸合。",
)
b.step(
    "铺石弹行: 石弹金字塔底下那格一定要是单位方板。",
    ["g0_w", "g0_2", "g0_3", "g0_4", "g0_5", "g0_6"],
    highlight=["g1_2"],
    tip="石弹堆的四条底边都要整边吸住脚下的方板。",
)
b.step(
    "铺北侧草坪收口: 三块绿色长板 + 一片方板, 演武场围合完成。",
    ["g3_w", "g3_m", "g3_e", "g3_6"],
    highlight=["g2_0"],
    tip="相邻行等长边互吸 —— 演武场的地基连成一体。",
)
b.step(
    "砌靶楼一层墙环: 六片石墙四角竖边互咬, 围成 1x2 的闭环。",
    ["t1_w_1", "t1_w_2", "t1_e_1", "t1_e_2", "t1_s", "t1_n"],
    highlight=["g1_0", "g2_0"],
    tip="闭环墙才站得稳 —— 每个拐角都有两条竖边互相咬住。",
)
b.step(
    "摞二层靶窗环: 东面两扇窗格方正对投石机, 就是今天的靶窗。",
    ["t2_w_1", "t2_w_2", "t2_e_1", "t2_e_2", "t2_s", "t2_n"],
    highlight=["t1_e_1"],
    tip="底边与一层墙顶整边共线吸合 —— 看谁能把彩弹投进靶窗!",
)
b.step(
    "盖靶楼步道并列城垛: 两片盖板封顶, 红三角骑西沿, 小骑士骑拼缝守垛。",
    ["tcap_s", "tcap_n", "merlon_s", "merlon_n", "knight"],
    highlight=["t2_w_1"],
    tip="城垛红三角一片骑一沿 —— 小骑士负责喊'预备'!",
)
b.step(
    "砌投石机机架箱: 四片橙色木墙围成闭环, 这是整台机器的底座。",
    ["f_w", "f_e", "f_s", "f_n"],
    highlight=["g1_3", "g1_e"],
    tip="机架箱四角竖边互咬 —— 投石机的劲儿全从这里传到地上。",
)
b.step(
    "盖机架台板并砌配重石箱: 台板四边吸墙顶, 紫色石箱直接摞上去。",
    ["f_deck", "c_w", "c_e", "c_s", "c_n"],
    highlight=["f_e"],
    tip="配重箱要装满石头才够沉 —— 箱脚与台板边整边共线吸合。",
)
b.step(
    "封配重箱顶并立队旗: 黄色瘦高旗尖骑箱顶南沿, 3.94 全场最高。",
    ["c_cap", "flag"],
    highlight=["c_s"],
    tip="旗子一竖, 全场都看得见 —— 城堡红队入场!",
)
b.step(
    "挂投石长臂: 红色 30 度长板顶边整边吸机架东沿, 坡尾稳稳压地。",
    ["arm"],
    highlight=["f_e", "g1_e"],
    tip="顶铰链 + 接地坡尾, 重量走两条路 —— 这就是上好弦的长臂。",
)
b.step(
    "堆石弹金字塔并请炮组就位: 四片粉色等边斜棱互吸自锁成锥, "
    "绞盘手守机架西侧, 裁判官在东边看台。",
    ["boulder_s", "boulder_e", "boulder_n", "boulder_w", "winch", "referee"],
    highlight=["g0_5", "arm"],
    tip="石弹装上长臂兜, 配重一落 —— 咻! 彩弹飞向靶窗!",
)

b.finalize(
    model_id="trebuchet_01",
    name="城堡投石机",
    name_en="Trebuchet 01",
    description=(
        "只用核心九片型的城堡运动会一景, 全库第一台攻城器械, 给城堡家族"
        "补上演武场: 结构签名是'上弦待发的 30 度斜臂' —— 红色投石长臂"
        "顶边整边铰在机架箱东沿, 坡尾稳稳压地 (顶铰链 + 接地坡尾, 重量"
        "走两条路, 悬臂力矩为零), 紫色配重石箱高高摞在机架箱顶, 正是"
        "上好弦等待发射的一瞬间; 西端靶楼二层嵌两扇青色窗格方当靶窗, "
        "城垛红三角一片骑一沿, 小骑士喊'预备', 粉色石弹金字塔四棱自锁"
        "堆在长臂坡尾旁, 绞盘手与裁判官各就各位 —— 咻! 看谁能把彩弹"
        "投进靶窗!"
    ),
    difficulty=3,
    tags=["中世纪", "城堡", "投石机", "演武场", "进阶"],
    min_pieces=57,
    min_steps=12,
)
