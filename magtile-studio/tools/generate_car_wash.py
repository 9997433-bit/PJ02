#!/usr/bin/env python3
"""生成模型 data/models/car_wash_01.json (自动洗车馆)。

城市交通主题批 2/4: 全库第一座"车从楼里穿过去"的贯通式建筑 ——
与 hangar_01 (单开口大棚) / covered_bridge_01 (桥上加廊) 刻意区分:
洗车隧道两端全开、中间三道刷位, 结构逻辑是"门式刚架串成筒 +
筒里挂设备": 南北两面 2 层高墙 (二层嵌透明观察窗) 被 8 片屋顶板
以砖缝错拼锁成四榀门式刚架; 隧道里立刷/吊刷交替 —— 两对立刷
底边整边吸湿地坪拼缝夹住车道, 一对粉色吊刷顶边整边吸屋顶板沿
"挂"在半空 (strict 档悬挂预算 84g/边 >> 单刷 30g), 正好擦到
车顶; 一辆小黄车开在隧道正中, 车轮紧贴立刷; 屋顶冒出三颗透明
泡泡, 檐口黄色三角警示条, 入口西南角红色高招牌直上 4.0 ——
唰唰唰, 三分钟洗出一辆亮晶晶。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 湿地坪 (x [2,6], y [2,5]): 青色方板 x12                       12 片
  - 入口/出口引道 (x [0,2] / [6,8]): 灰色长板 x6                   6 片
  - 南北隧道墙 (y=2 / y=5, 两层): 方板 x12 + 透明窗格方 x4        16 片
  - 屋顶 (z=2, 砖缝错拼): 长板 x4 + 方板 x4                        8 片
  - 立刷 x4 (x=3 / x=5, 底边吸地坪拼缝) + 吊刷 x2 (x=4, 顶边
    吸屋顶板沿倒挂)                                                6 片
  - 小黄车: 车轮底座 x2 + 长板车顶 + 三角驾驶舱                    4 片
  - 泡泡 x3 (透明等边骑屋顶板缝) + 檐口警示条 x2 + 招牌塔 x1       6 片
  合计 58 片, 12 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 每片屋顶板一端整边压墙顶、另一端与邻板对缝互吸, 相邻两列
    接缝刻意错开半跨 (砖缝错拼) —— 不存在贯通全宽的空中铰链线;
  - 吊刷是全模型唯一的受拉构件: 顶边与屋顶方板西/东沿整边贴合,
    单刷 30g << strict 档悬挂预算 84g/单位边长, 且单边悬挂仅 1 片
    (上限 4 片), 剪断吊边只掉它自己;
  - 立刷底边整边吸湿地坪拼缝, 竖边再与隧道墙竖棱互咬;
  - 小黄车先于屋顶进场 (R7b 装配可达), 车顶长板双长边压两片车轮
    底座顶边, 轮底整边吸地坪拼缝全场连通;
  - 泡泡/警示条/招牌全部骑整边沿口, 重心正压铰链线力矩为零。

用法: python3 tools/generate_car_wash.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

WET = "cyan"        # 隧道湿地坪
ROAD = "gray"       # 引道
WALL = "blue"       # 隧道墙
WIN = "clear"       # 观察窗
ROOF = "blue"       # 屋顶板
ROOF2 = "gray"      # 屋顶板 (相间)
BRUSH_S = "purple"  # 立刷 (第一道)
BRUSH_G = "green"   # 立刷 (第三道)
BRUSH_H = "pink"    # 吊刷 (第二道)
CAR = "yellow"      # 小黄车
WHEEL = "gray"      # 车轮底座
BUBBLE = "clear"    # 泡泡
TRIM = "yellow"     # 檐口警示条
SIGN = "red"        # 招牌塔

# =================================================================
# 1. 湿地坪 (x [2,6], y [2,5]): 12 片青色方板
#    (立刷底边与车轮都要整边吸在这些拼缝上)
# =================================================================
for x in range(2, 6):
    for y in range(2, 5):
        b.flat(f"fl_{x}_{y}", x, y, 0.0, WET)

# =================================================================
# 2. 入口 / 出口引道 (x [0,2] / [6,8]): 各 3 片灰色长板
# =================================================================
for y in range(2, 5):
    b.flat_rect(f"in_{y}", 0, y, 0.0, ROAD)
    b.flat_rect(f"out_{y}", 6, y, 0.0, ROAD)

# =================================================================
# 3. 南北隧道墙 (y=2 / y=5): 两层, 二层中段嵌透明观察窗
# =================================================================
for side, yw in (("s", 2.0), ("n", 5.0)):
    for x in range(2, 6):
        b.wall_ns(f"w{side}1_{x}", x, yw, 0, WALL)          # 一层
    for x in range(2, 6):
        if x in (3, 4):
            b.add(f"w{side}2_{x}", "window_square",
                  (x + 0.5, yw, 1.5), (90, 0, 0), WIN)       # 二层观察窗
        else:
            b.wall_ns(f"w{side}2_{x}", x, yw, 1, WALL)

# =================================================================
# 4. 屋顶 (z=2): 每列 1 长板 + 1 方板, 相邻列接缝错开半跨 (砖缝错拼)
#    B 列: 方板在南 (y [2,3]) + 长板在北 (y [3,5])
#    A 列: 长板在南 (y [2,4]) + 方板在北 (y [4,5])
# =================================================================
b.flat("rf_sq_2", 2, 2, 2.0, ROOF2)                  # x [2,3]: B 列
b.flat_rect("rf_re_2", 2, 3, 2.0, ROOF, axis="y")
b.flat_rect("rf_re_3", 3, 2, 2.0, ROOF, axis="y")    # x [3,4]: A 列
b.flat("rf_sq_3", 3, 4, 2.0, ROOF2)
b.flat("rf_sq_4", 4, 2, 2.0, ROOF2)                  # x [4,5]: B 列
b.flat_rect("rf_re_4", 4, 3, 2.0, ROOF, axis="y")
b.flat_rect("rf_re_5", 5, 2, 2.0, ROOF, axis="y")    # x [5,6]: A 列
b.flat("rf_sq_5", 5, 4, 2.0, ROOF2)

# =================================================================
# 5. 三道刷位: 立刷 (x=3 / x=5) + 吊刷 (x=4)
# =================================================================
b.add("br_s3", "square", (3.0, 2.5, 0.5), (90, 0, 90), BRUSH_S)   # 第一道立刷
b.add("br_n3", "square", (3.0, 4.5, 0.5), (90, 0, 90), BRUSH_S)
b.add("br_s5", "square", (5.0, 2.5, 0.5), (90, 0, 90), BRUSH_G)   # 第三道立刷
b.add("br_n5", "square", (5.0, 4.5, 0.5), (90, 0, 90), BRUSH_G)
b.add("br_h_s", "square", (4.0, 2.5, 1.5), (90, 0, 90), BRUSH_H)  # 吊刷 (倒挂)
b.add("br_h_n", "square", (4.0, 4.5, 1.5), (90, 0, 90), BRUSH_H)

# =================================================================
# 6. 小黄车 (x [3,5], y [3,4]): 正在第二道刷位下冲洗
# =================================================================
b.add("car_wh_s", "wheel_base", (4.0, 3.0, 0.5), (90, 0, 0), WHEEL)
b.add("car_wh_n", "wheel_base", (4.0, 4.0, 0.5), (90, 0, 0), WHEEL)
b.flat_rect("car_top", 3, 3, 1.0, CAR)               # 车顶长板 (双长边压轮顶)
b.crest_ew("car_cab", 5.0, 3, 1.0, CAR)              # 驾驶舱 (骑东短边, 车头朝出口)

# =================================================================
# 7. 泡泡 + 檐口警示条 + 招牌塔
# =================================================================
b.crest_ew("bub_1", 3.0, 2, 2.0, BUBBLE)             # 泡泡 (骑屋顶板缝)
b.crest_ew("bub_2", 5.0, 4, 2.0, BUBBLE)
b.crest_ew("bub_3", 6.0, 4, 2.0, BUBBLE)
b.crest_ns("trim_n", 3, 5.0, 2.0, TRIM)              # 北檐警示条
b.crest_ns("trim_s", 4, 2.0, 2.0, TRIM)              # 南檐警示条
b.spire_ew("sign", 2.0, 2, 2.0, SIGN)                # 入口招牌塔 (顶高 4.0)

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺湿地坪: 12 片青色方板铺满洗车隧道 (x [2,6], y [2,5])。",
    [f"fl_{x}_{y}" for x in range(2, 6) for y in range(2, 5)],
    tip="立刷和车轮都要整边吸在这些拼缝上 —— 一格都不能错位。",
)
b.step(
    "铺入口与出口引道: 东西各 3 片灰色长板, 车道贯通 8 格。",
    ["in_2", "in_3", "in_4", "out_2", "out_3", "out_4"],
    highlight=["fl_2_3", "fl_5_3"],
    tip="西进东出 —— 洗车馆是一条流水线, 不走回头路。",
)
b.step(
    "立南墙一层: 4 片蓝墙沿 y=2 排开, 墙脚整边吸地坪南沿。",
    ["ws1_2", "ws1_3", "ws1_4", "ws1_5"],
    highlight=["fl_2_2"],
    tip="相邻墙片竖边互咬 —— 整面墙比单片墙稳得多。",
)
b.step(
    "立北墙一层: 与南墙隔 3 格车道对望。",
    ["wn1_2", "wn1_3", "wn1_4", "wn1_5"],
    highlight=["fl_2_4"],
    tip="中间留足 3 格宽 —— 车身加两排刷子刚刚好。",
)
b.step(
    "装两道立刷: 紫色/绿色方片底边整边吸地坪拼缝 (x=3 与 x=5), "
    "竖边与墙棱互咬, 中间让出车道。",
    ["br_s3", "br_n3", "br_s5", "br_n5"],
    highlight=["fl_2_2", "fl_4_4"],
    tip="立刷成对夹住车道 —— 车身两侧一次刷干净。",
)
b.step(
    "小黄车开进刷位: 车轮底座整边吸地坪拼缝, 长板车顶压轮顶, 车头朝出口。",
    ["car_wh_s", "car_wh_n", "car_top", "car_cab"],
    highlight=["br_s3", "br_n3"],
    tip="车轮正好贴着立刷 —— 记住: 车要赶在封顶之前开进来!",
)
b.step(
    "立南墙二层: 中段两扇透明观察窗, 看得见车在里面洗。",
    ["ws2_2", "ws2_3", "ws2_4", "ws2_5"],
    highlight=["ws1_2"],
    tip="窗格方物理上按实心方片拼接 —— 隔窗看泡泡翻滚。",
)
b.step(
    "立北墙二层: 双墙同高 z=2, 屋顶一放就平。",
    ["wn2_2", "wn2_3", "wn2_4", "wn2_5"],
    highlight=["wn1_2"],
    tip="八片二层墙就位 —— 四榀门式刚架只差屋顶合龙。",
)
b.step(
    "盖屋顶 (砖缝错拼): 每列 1 长板 + 1 方板, 相邻列接缝错开半跨。",
    ["rf_sq_2", "rf_re_2", "rf_re_3", "rf_sq_3",
     "rf_sq_4", "rf_re_4", "rf_re_5", "rf_sq_5"],
    highlight=["ws2_2", "wn2_5"],
    tip="接缝错开就没有贯通全宽的空中铰链 —— 砌砖师傅的老规矩。",
)
b.step(
    "挂吊刷: 两片粉色方片顶边整边吸屋顶板沿, 倒挂在车顶两侧 (x=4)。",
    ["br_h_s", "br_h_n"],
    highlight=["rf_sq_4", "rf_sq_3"],
    tip="单刷 30g, 吊边预算 84g —— 挂得稳稳的, 正好擦到车顶。",
)
b.step(
    "冒泡泡贴警示条: 3 颗透明泡泡骑屋顶板缝, 檐口南北各 1 片黄色警示三角。",
    ["bub_1", "bub_2", "bub_3", "trim_n", "trim_s"],
    highlight=["rf_sq_2"],
    tip="泡泡重心正压板缝 —— 洗车馆屋顶咕嘟咕嘟冒泡。",
)
b.step(
    "立招牌塔: 红色等腰高牌骑入口西南角屋顶沿 (顶高 4.0, 全场最高)。",
    ["sign"],
    highlight=["rf_sq_2"],
    tip="大红招牌一立 —— 三分钟洗出一辆亮晶晶!",
)

b.finalize(
    model_id="car_wash_01",
    name="自动洗车馆",
    name_en="Auto Car Wash 01",
    description=(
        "只用核心九片型的贯通式洗车隧道: 两端全开、车从楼里穿过去 ——"
        " 南北两面 2 层高墙 (二层透明观察窗) 被 8 片屋顶板以砖缝错拼"
        "锁成四榀门式刚架, 相邻列接缝错开半跨, 不存在贯通全宽的空中"
        "铰链线; 隧道里立刷/吊刷交替: 两对立刷底边整边吸湿地坪拼缝"
        "夹住车道, 一对粉色吊刷顶边整边吸屋顶板沿倒挂半空 (单刷 30g"
        " 远低于 strict 档 84g 悬挂预算), 正好擦到车顶; 小黄车赶在封顶"
        "之前开进刷位 (装配可达的秩序), 车轮紧贴立刷; 屋顶三颗透明"
        "泡泡骑板缝, 檐口黄色警示条, 入口红色招牌塔直上 4.0 ——"
        " 唰唰唰, 三分钟洗出一辆亮晶晶。"
    ),
    difficulty=3,
    tags=["城市", "交通", "洗车", "街景", "进阶"],
    min_pieces=58,
    min_steps=12,
)
