#!/usr/bin/env python3
"""生成模型 data/models/city_bus_stop_01.json (公交站).

城市生活主题: 全库第一座街头公交站 —— 灰色马路上斑马线
两道透明横杠直通站台: 蓝色候车亭三片背墙 + 两根门柱托起
三片透明玻璃雨棚 (每片至少两条整边受力, 中片最后合拢);
两柱之间斜嵌一面橙色广告牌 (竖边吸门柱棱), 路缘黄色站牌
塔尖直上 3 格; 亭旁红色自动售货机整点亮灯, 粉色花坛四坡
簇拥, 街口两盏路灯对望 —— 3 路车进站, 请排队上车!

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 街区地坪 7x4: 马路 (含斑马线) 1 行 + 人行道 3 行          22 片
  - 候车亭: 背墙 x3 + 门柱 x2 + 透明雨棚 x3 (z=1)              8 片
  - 广告牌: 直角三角 x1 (竖边吸门柱棱, 水平边咬地坪缝)         1 片
  - 站牌: 方墙杆 x1 + 黄色等腰塔尖 x1 (尖端 3.0)               2 片
  - 售货机: 立墙闭环 x4 + 方板顶 x1                            5 片
  - 花坛: 等边四坡花丘 x4                                      4 片
  - 路灯: 方墙杆 x2 + 等边灯冠 x2 (东西街口各 1 盏)            4 片
  合计 46 片, 10 个教程步骤, 5 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验, default + strict 双档):
  - 雨棚每片双支点: 两侧片南搭门柱顶、北压背墙顶, 中片最后
    合拢时北压背墙、东西长边吸邻片 —— 任何中间状态零悬臂;
  - 广告牌竖直角边与门柱竖棱等长贴合 (竖直铰链重力力矩为零),
    水平直角边整边咬人行道拼缝;
  - 站牌塔尖 3.0 触发 R8 高层检查: 杆上仅 1 片塔尖 (重心正压
    铰链), 候车亭门柱-雨棚-背墙-地坪成环, 零警告;
  - 售货机闭合环压顶, 花坛四坡自锁, 路灯灯冠正压杆顶。

用法: python3 tools/generate_city_bus_stop.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

ROAD = "gray"       # 马路
ZEBRA = "clear"     # 斑马线
WALK = "green"      # 人行道
SHELTER = "blue"    # 候车亭
CANOPY = "clear"    # 玻璃雨棚
AD = "orange"       # 广告牌
POLE = "gray"       # 站牌杆 / 灯杆
SIGN = "yellow"     # 站牌塔尖 / 灯冠
VEND = "red"        # 自动售货机
FLOWER = "pink"     # 花坛

# =================================================================
# 1. 街区地坪 7x4: 南沿马路行 (斑马线两道) + 人行道 3 行
# =================================================================
b.flat_rect("rd_a", 0, 0, 0.0, ROAD)                # [0,2]x[0,1]
b.flat("rd_z1", 2, 0, 0.0, ZEBRA)                   # 斑马线
b.flat("rd_m", 3, 0, 0.0, ROAD)
b.flat("rd_z2", 4, 0, 0.0, ZEBRA)                   # 斑马线
b.flat_rect("rd_b", 5, 0, 0.0, ROAD)                # [5,7]
b.flat_rect("wk_a1", 0, 1, 0.0, WALK)               # [0,2]x[1,2]
for x in range(2, 7):
    b.flat(f"wk_{x}_1", x, 1, 0.0, WALK)
b.flat_rect("wk_a2", 0, 2, 0.0, WALK)               # [0,2]x[2,3]
for x in range(2, 7):
    b.flat(f"wk_{x}_2", x, 2, 0.0, WALK)
b.flat_rect("wk_a3", 0, 3, 0.0, WALK)               # [0,2]x[3,4]
b.flat("wk_2_3", 2, 3, 0.0, WALK)
b.flat("wk_3_3", 3, 3, 0.0, WALK)
b.flat("wk_4_3", 4, 3, 0.0, WALK)
b.flat_rect("wk_b3", 5, 3, 0.0, WALK)               # [5,7]x[3,4]

# =================================================================
# 2. 候车亭: 背墙 (y=3) x3 + 门柱 (y=2) x2 + 玻璃雨棚 x3
# =================================================================
for x in (2, 3, 4):
    b.wall_ns(f"bk_{x}", x, 3.0, 0, SHELTER)        # 背墙
b.wall_ns("post_w", 2, 2.0, 0, SHELTER)             # 西门柱 [2,3]
b.wall_ns("post_e", 4, 2.0, 0, SHELTER)             # 东门柱 [4,5]
b.flat("cp_w", 2, 2, 1.0, CANOPY)                   # 雨棚西片
b.flat("cp_e", 4, 2, 1.0, CANOPY)                   # 雨棚东片
b.flat("cp_m", 3, 2, 1.0, CANOPY)                   # 雨棚中片 (合拢)

# =================================================================
# 3. 广告牌: 竖直角边吸西门柱东棱, 水平边咬 y=2 拼缝
# =================================================================
b.place_tri("ad_panel", "right_triangle",
            (3.0, 2.0, 0.0), (4.0, 2.0, 0.0), (3.0, 2.0, 1.0), AD)

# =================================================================
# 4. 站牌: 路缘方墙杆 + 黄色等腰塔尖 (尖端 3.0)
# =================================================================
b.wall_ns("sg_pole", 5, 1.0, 0, POLE)
b.spire_ns("sg_tip", 5, 1.0, 1.0, SIGN)

# =================================================================
# 5. 自动售货机: [5,6]x[2,3] 闭合环 + 方板顶
# =================================================================
b.wall_ns("vd_s", 5, 2.0, 0, VEND)
b.wall_ns("vd_n", 5, 3.0, 0, VEND)
b.wall_ew("vd_w", 5.0, 2, 0, VEND)
b.wall_ew("vd_e", 6.0, 2, 0, VEND)
b.flat("vd_top", 5, 2, 1.0, VEND)

# =================================================================
# 6. 花坛: [6,7]x[1,2] 粉色四坡花丘
# =================================================================
FLOWER_IDS = b.hat4("fw", 6, 1, 0.0, FLOWER,
                    shape="equilateral_triangle")

# =================================================================
# 7. 路灯: 东西街口各 1 盏 (方墙杆 + 等边灯冠)
# =================================================================
b.wall_ew("lp_w", 0.0, 2, 0, POLE)
b.crest_ew("lc_w", 0.0, 2, 1.0, SIGN)
b.wall_ew("lp_e", 7.0, 2, 0, POLE)
b.crest_ew("lc_e", 7.0, 2, 1.0, SIGN)

# =================================================================
# 教程步骤 (10 步)
# =================================================================
b.step(
    "铺马路: 南沿一行 5 片, 两片透明方板就是斑马线。",
    ["rd_a", "rd_z1", "rd_m", "rd_z2", "rd_b"],
    tip="斑马线正对站台 —— 下车的乘客从这里过街。",
)
b.step(
    "铺人行道第一行: 长板 + 方板x5, 共 6 片。",
    ["wk_a1"] + [f"wk_{x}_1" for x in range(2, 7)],
    highlight=["rd_z1", "rd_z2"],
    tip="路缘拼缝 y=1 是站牌杆的落脚线。",
)
b.step(
    "铺人行道第二行: 再铺 6 片。",
    ["wk_a2"] + [f"wk_{x}_2" for x in range(2, 7)],
    highlight=["wk_2_1", "wk_6_1"],
    tip="y=2 拼缝上要立候车亭的两根门柱。",
)
b.step(
    "铺人行道第三行: 5 片收边, 街区地坪合拢成 7x4。",
    ["wk_a3", "wk_2_3", "wk_3_3", "wk_4_3", "wk_b3"],
    highlight=["wk_2_2", "wk_4_2"],
    tip="y=3 拼缝是候车亭背墙的基准线。",
)
b.step(
    "立候车亭骨架: 3 片蓝色背墙一字排开, 前排再立 2 根门柱。",
    ["bk_2", "bk_3", "bk_4", "post_w", "post_e"],
    highlight=["wk_2_2", "wk_4_2"],
    tip="背墙相邻竖边互吸; 门柱与背墙相距 1 格 —— 雨棚的跨度。",
)
b.step(
    "盖玻璃雨棚: 先东西两片 (柱顶+墙顶双支点), 中片最后合拢。",
    ["cp_w", "cp_e", "cp_m"],
    highlight=["post_w", "bk_3"],
    tip="每片至少两条整边受力 —— 雨棚零悬臂。",
)
b.step(
    "嵌广告牌、竖站牌: 橙色直角牌竖边吸西门柱棱, 路缘杆顶"
    "升起黄色塔尖。",
    ["ad_panel", "sg_pole", "sg_tip"],
    highlight=["post_w", "wk_5_1"],
    tip="广告牌绕竖轴力矩为零; 塔尖 3 格高 —— 一眼认出 3 路站。",
)
b.step(
    "装自动售货机: 4 片红色立墙闭环, 方板压顶。",
    ["vd_s", "vd_n", "vd_w", "vd_e", "vd_top"],
    highlight=["wk_5_2"],
    tip="四角竖边互吸锁死 —— 等车渴了来一瓶。",
)
b.step(
    "堆花坛: 4 片粉色三角四棱互吸, 合拢成一畦花丘。",
    FLOWER_IDS,
    highlight=["wk_6_1"],
    tip="四坡自锁 —— 站台边的一点春色。",
)
b.step(
    "点路灯: 东西街口各立灯杆、点亮灯冠 —— 3 路车进站!",
    ["lp_w", "lc_w", "lp_e", "lc_e"],
    highlight=["wk_a2", "wk_6_2"],
    tip="灯冠重心正压杆顶铰链 —— 夜班车也看得清站牌。",
)

b.finalize(
    model_id="city_bus_stop_01",
    name="街头公交站",
    name_en="City Bus Stop 01",
    description=(
        "全库第一座街头公交站: 蓝色候车亭三片背墙与两根门柱托起三片透明"
        "玻璃雨棚 (每片双支点、中片最后合拢, 零悬臂), 两柱间斜嵌橙色广告牌"
        " (竖边吸门柱棱、绕竖轴零力矩), 路缘站牌塔尖直上 3 格; 斑马线过街, "
        "红色售货机、粉色花坛与东西两盏路灯点亮街角 —— 3 路车进站, "
        "请排队上车!"
    ),
    difficulty=2,
    tags=["城市", "交通", "公交站", "街景", "入门进阶"],
    min_pieces=44,
    min_steps=10,
)
