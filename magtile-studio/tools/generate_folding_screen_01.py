#!/usr/bin/env python3
"""生成模型 data/models/folding_screen_01.json (彩虹折角屏风)。

几何艺术主题的第一件密铺立作: 密铺艺术必须"立起来"才有入库
资格 (CONTENT_STRATEGY.md 2.4 节 J4), 本作就是它的标杆示范 ——
方片与三角片的密铺色带不铺地砖, 而是立成一面 S 形折角屏风:
三扇两层高的彩虹墙板在拐角处竖边互咬, 折角本身就是薄屏的
抗侧稳定来源 (直墙会晃, 折墙自稳); 每扇屏风顶部一条
"上三角-倒三角-上三角"的密铺齿带, 倒三角两条斜边悬吸在相邻
上三角之间 —— 全库唯一的"密铺齿带 + 折角自稳"。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, S 形自西向东折三折):
  - 广场地坪 (x [0,4], y [0,3]): 单位方板 x12 (清灰棋盘格)     12 片
  - 屏风一 (y=1, x [0,2]): 红/橙两层立墙 4 + 密铺齿带 3          7 片
  - 屏风二 (x=2, y [1,3]): 黄/绿两层立墙 4 + 密铺齿带 3          7 片
  - 屏风三 (y=3, x [2,4]): 蓝/紫两层立墙 4 + 密铺齿带 3          7 片
  - 花坛 (x [3,4], y [0,1]): 开顶墙环 4 + 瘦高花 (顶尖 3.0)      5 片
  - 东西入口步道: 长板 x2 + 迎宾三角 x2                          4 片
  合计 42 片, 11 个教程步骤, 4 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 三扇屏风在 (2,1) 与 (2,3) 两个拐角竖边互咬 (底层咬底层,
    上层咬上层), S 形折角把三面薄墙锁成一个自稳整体;
  - 密铺齿带: 上三角底边整边吸墙顶; 倒三角不接地, 两条斜边
    分别与左右上三角的斜边整边互吸 —— 双边悬吸, 剪断任一边
    仍有另一条支撑路径;
  - 花坛开顶墙环四角竖边互咬, 墙脚踩地坪拼缝; 瘦高花底边
    整边吸花坛北墙墙顶;
  - 步道长板短边整边吸广场沿, 迎宾三角骑步道外缘短边;
    剪断任何一条装饰连接最多失联 2 片 (< 3), R8 单点失效通过。

用法: python3 tools/generate_folding_screen_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

PLAZA_A = "clear"    # 广场棋盘格
PLAZA_B = "gray"
P1_LO, P1_HI = "red", "orange"      # 屏风一 (西)
P2_LO, P2_HI = "yellow", "green"    # 屏风二 (中)
P3_LO, P3_HI = "blue", "purple"     # 屏风三 (东)
TOOTH_UP = "cyan"    # 齿带上三角
TOOTH_DOWN = "pink"  # 齿带倒三角
PLANTER = "green"    # 花坛
FLOWER = "pink"      # 瘦高花
WALK = "gray"        # 入口步道
WELCOME = "yellow"   # 迎宾三角

APEX = 2.866025      # 齿带三角顶高 (2 + sqrt(3)/2)


# =================================================================
# 1. 广场地坪 (x [0,4], y [0,3]): 清灰棋盘格
# =================================================================
for y0 in range(3):
    for x0 in range(4):
        color = PLAZA_A if (x0 + y0) % 2 == 0 else PLAZA_B
        b.flat(f"plaza_{x0}_{y0}", x0, y0, 0.0, color)

# =================================================================
# 2. 屏风一 (y=1, x [0,2]): 两层立墙 + 密铺齿带
# =================================================================
b.wall_ns("p1_lo_0", 0, 1.0, 0, P1_LO)
b.wall_ns("p1_lo_1", 1, 1.0, 0, P1_LO)
b.wall_ns("p1_hi_0", 0, 1.0, 1, P1_HI)
b.wall_ns("p1_hi_1", 1, 1.0, 1, P1_HI)
b.crest_ns("p1_up_0", 0, 1.0, 2.0, TOOTH_UP)
b.crest_ns("p1_up_1", 1, 1.0, 2.0, TOOTH_UP)
b.place_tri("p1_down", "equilateral_triangle",
            (1.5, 1.0, APEX), (0.5, 1.0, APEX), (1.0, 1.0, 2.0),
            TOOTH_DOWN)

# =================================================================
# 3. 屏风二 (x=2, y [1,3]): 拐角竖边互咬屏风一
# =================================================================
b.wall_ew("p2_lo_1", 2.0, 1, 0, P2_LO)
b.wall_ew("p2_lo_2", 2.0, 2, 0, P2_LO)
b.wall_ew("p2_hi_1", 2.0, 1, 1, P2_HI)
b.wall_ew("p2_hi_2", 2.0, 2, 1, P2_HI)
b.crest_ew("p2_up_1", 2.0, 1, 2.0, TOOTH_UP)
b.crest_ew("p2_up_2", 2.0, 2, 2.0, TOOTH_UP)
b.place_tri("p2_down", "equilateral_triangle",
            (2.0, 2.5, APEX), (2.0, 1.5, APEX), (2.0, 2.0, 2.0),
            TOOTH_DOWN)

# =================================================================
# 4. 屏风三 (y=3, x [2,4]): 拐角竖边互咬屏风二
# =================================================================
b.wall_ns("p3_lo_2", 2, 3.0, 0, P3_LO)
b.wall_ns("p3_lo_3", 3, 3.0, 0, P3_LO)
b.wall_ns("p3_hi_2", 2, 3.0, 1, P3_HI)
b.wall_ns("p3_hi_3", 3, 3.0, 1, P3_HI)
b.crest_ns("p3_up_2", 2, 3.0, 2.0, TOOTH_UP)
b.crest_ns("p3_up_3", 3, 3.0, 2.0, TOOTH_UP)
b.place_tri("p3_down", "equilateral_triangle",
            (3.5, 3.0, APEX), (2.5, 3.0, APEX), (3.0, 3.0, 2.0),
            TOOTH_DOWN)

# =================================================================
# 5. 花坛 (x [3,4], y [0,1]): 开顶墙环 + 瘦高花
# =================================================================
b.wall_ns("planter_s", 3, 0.0, 0, PLANTER)
b.wall_ns("planter_n", 3, 1.0, 0, PLANTER)
b.wall_ew("planter_w", 3.0, 0, 0, PLANTER)
b.wall_ew("planter_e", 4.0, 0, 0, PLANTER)
b.spire_ns("flower", 3, 1.0, 1.0, FLOWER)       # 顶尖 3.0

# =================================================================
# 6. 东西入口步道 + 迎宾三角
# =================================================================
b.flat_rect("walk_w", -2, 1, 0.0, WALK)         # x [-2,0]
b.flat_rect("walk_e", 4, 1, 0.0, WALK)          # x [4,6]
b.crest_ew("welcome_w", -2.0, 1, 0.0, WELCOME)
b.crest_ew("welcome_e", 6.0, 1, 0.0, WELCOME)

# =================================================================
# 教程步骤 (11 步)
# =================================================================
b.step(
    "铺广场南行: 清灰棋盘格四片, 边边互吸。",
    [f"plaza_{x0}_0" for x0 in range(4)],
    tip="密铺艺术的第一课: 同样的形状, 排出不一样的节奏。",
)
b.step(
    "铺广场中行: 棋盘格颜色错开一格。",
    [f"plaza_{x0}_1" for x0 in range(4)],
    highlight=["plaza_0_0"],
    tip="清色和灰色轮流坐庄 —— 屏风的墙脚就踩这些拼缝。",
)
b.step(
    "铺广场北行: 十二片地坪合成一整张网。",
    [f"plaza_{x0}_2" for x0 in range(4)],
    highlight=["plaza_0_1"],
    tip="行行等边互吸 —— 接下来轮到屏风登场了。",
)
b.step(
    "立屏风一: 红色底层加橙色上层, 墙脚踩拼缝, 层层压顶。",
    ["p1_lo_0", "p1_lo_1", "p1_hi_0", "p1_hi_1"],
    highlight=["plaza_0_0", "plaza_0_1"],
    tip="上层墙脚整边压住下层墙顶 —— 彩虹从红色开始。",
)
b.step(
    "给屏风一装密铺齿带: 两片上三角骑墙顶, 一片倒三角悬吸中间。",
    ["p1_up_0", "p1_up_1", "p1_down"],
    highlight=["p1_hi_0"],
    tip="倒三角不落地 —— 两条斜边分别吸住左右上三角, 双边都要咬紧。",
)
b.step(
    "折出屏风二: 黄绿两层朝北拐, 拐角竖边咬住屏风一。",
    ["p2_lo_1", "p2_lo_2", "p2_hi_1", "p2_hi_2"],
    highlight=["p1_lo_1", "p1_hi_1"],
    tip="折角是屏风的秘密: 直墙会晃, 折过弯的墙自己站得稳。",
)
b.step(
    "给屏风二装密铺齿带: 手法和屏风一一样。",
    ["p2_up_1", "p2_up_2", "p2_down"],
    highlight=["p2_hi_1"],
    tip="齿带沿着折角转弯 —— 密铺的节奏一路不断。",
)
b.step(
    "再折出屏风三: 蓝紫两层朝东拐, S 形完工。",
    ["p3_lo_2", "p3_lo_3", "p3_hi_2", "p3_hi_3"],
    highlight=["p2_lo_2", "p2_hi_2"],
    tip="第二个拐角朝反方向折 —— 从空中看, 屏风是一个大 S。",
)
b.step(
    "给屏风三装密铺齿带: 三条齿带到齐。",
    ["p3_up_2", "p3_up_3", "p3_down"],
    highlight=["p3_hi_2"],
    tip="上三角青色、倒三角粉色 —— 遮住颜色只看剪影也认得出它。",
)
b.step(
    "砌花坛立瘦高花: 开顶墙环四角互咬, 花儿吸在北墙墙顶。",
    ["planter_s", "planter_n", "planter_w", "planter_e", "flower"],
    highlight=["plaza_3_0"],
    tip="花坛只围不盖 —— 粉色瘦高花从墙顶一直长到 3.0 高。",
)
b.step(
    "铺东西入口步道, 摆迎宾三角: 展览开幕!",
    ["walk_w", "walk_e", "welcome_w", "welcome_e"],
    highlight=["p1_lo_0", "p3_lo_3"],
    tip="从哪头走进来, 都会先看到一整面彩虹 —— 慢慢逛, 细细看。",
)

b.finalize(
    model_id="folding_screen_01",
    name="彩虹折角屏风",
    name_en="Rainbow Folding Screen 01",
    description=(
        "只用核心九片型的密铺立作: 密铺艺术不铺地砖 —— 方片与"
        "三角片的彩虹色带立成一面 S 形折角屏风: 三扇两层高的"
        "墙板 (红橙/黄绿/蓝紫) 在两个拐角处竖边互咬, 折角本身"
        "就是薄屏的抗侧稳定来源; 每扇屏顶一条'上三角-倒三角-"
        "上三角'的密铺齿带, 粉色倒三角不落地, 两条斜边悬吸在"
        "青色上三角之间; 花坛瘦高花与东西迎宾步道给广场收边 "
        "—— 遮住颜色只看剪影, 它也是全库独一份的锯齿 S。"
    ),
    difficulty=2,
    tags=["几何艺术", "密铺", "屏风", "彩虹", "广场", "入门"],
    min_pieces=42,
    min_steps=11,
)
