#!/usr/bin/env python3
"""生成模型 data/models/skate_park_01.json (滑板公园)。

运动主题批 ④: 全库第一座滑板公园 —— 与滑雪跳台 (单一大坡道) 和
水滑梯乐园 (滑梯塔) 的结构逻辑都不同: 一块 8x4 水泥板场上摆开
**四件互不重样的街式道具**: 中央方箱跳台 (八墙围筒 + 四板台面 +
东侧双 30 度下坡), 西侧靠墙斜坡区 (墙顶挂双坡道), 东南角**火山
跳包** (四墙围筒直接戴等边四坡锥, 不铺台面), 东北高低台 (三墙
半围 + 台面 + 单坡道); 方箱前一条**桥式磨杆** (两柱托长板, 板边
还与方箱墙顶共线互吸) —— 助跑、起跳、尖翻上杆, 稳稳落地!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 场地 [0,8]x[0,4]):
  - 水泥板场: 方板 x10 + 长方形 x11 (涂鸦带青色)              21 片
  - 方箱跳台 [3,5]x[1,3]: 围墙 x8 + 台面 x4 + 东侧坡道 x2     14 片
  - 靠墙斜坡区 (西): 背墙 x2 + 坡道 x2                         4 片
  - 火山跳包 [6,7]x[0,1]: 围墙 x4 + 等边四坡锥 x4              8 片
  - 高低台 [7,8]x[3,4]: 半围墙 x3 + 台面 x1 + 坡道 x1          5 片
  - 磨杆: 双柱 x2 + 长板 x1                                    3 片
  - 入场旗 x2 + 雪糕筒 x3                                      5 片
  合计 60 片, 15 个教程步骤, 4 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, 常规+strict 双档零警告):
  - 所有 30 度坡道均为双端受力: 顶边整边吸墙顶/台面边, 坡尾
    落地 (滚珠塔坡道同款), 剪断顶边铰链坡道仍自行接地;
  - 方箱八墙拐角竖边互吸成环, 台面四板压顶再加一圈水平环;
  - 磨杆长板两条短边各吸一柱顶 (桥式), 北长边还与方箱南墙顶
    共线互吸 —— 三点受力, 尖翻上杆也震不掉;
  - 磨杆双柱竖边与方箱角墙竖边锁扣, 道具连成一个刚性群;
  - 火山跳包四坡锥四条斜棱两两互吸自锁 (锥尖 1.71);
  - 全场最高点入场旗尖 2.0, 不触发 R8 高层检查。

用法: python3 tools/generate_skate_park.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

FLOOR = "gray"      # 水泥板
GRAF = "cyan"       # 涂鸦带
BOX = "orange"      # 方箱跳台围墙
DECK = "red"        # 方箱台面
RAMP = "cyan"       # 30 度坡道
BANK = "gray"       # 靠墙斜坡背墙
VOLC = "red"        # 火山跳包围墙
VHAT = "orange"     # 火山四坡锥
LEDGE = "purple"    # 高低台
RAIL = "yellow"     # 磨杆长板
POST = "gray"       # 磨杆柱
CONE = "yellow"     # 雪糕筒
FLAG = "red"        # 入场旗

# =================================================================
# 1. 水泥板场 [0,8]x[0,4]: 南排密缝方板 (道具落柱线多), 中部涂鸦
#    长方形带, 北排长方形
# =================================================================
b.flat_rect("f0_w", 0, 0, 0.0, FLOOR, axis="x")          # 南排西段 [0,2]
for x0 in range(2, 8):
    b.flat(f"f0_{x0}", x0, 0, 0.0, FLOOR)                # 南排方板 [2,8]
for y0 in (1, 2):
    b.flat(f"f{y0}_w", 0, y0, 0.0, FLOOR)
    b.flat_rect(f"f{y0}_a", 1, y0, 0.0, GRAF, axis="x")  # 涂鸦带
    b.flat_rect(f"f{y0}_b", 3, y0, 0.0, GRAF, axis="x")
    b.flat_rect(f"f{y0}_c", 5, y0, 0.0, GRAF, axis="x")
    b.flat(f"f{y0}_e", 7, y0, 0.0, FLOOR)
for i, x0 in enumerate((0, 2, 4, 6)):
    b.flat_rect(f"f3_{i}", x0, 3, 0.0, FLOOR, axis="x")  # 北排 [0,8]

# =================================================================
# 2. 方箱跳台 [3,5]x[1,3]: 八墙围筒 + 四板台面 + 东侧双坡道
# =================================================================
for i, x0 in enumerate((3, 4)):
    b.wall_ns(f"bx_s_{i}", x0, 1.0, 0, BOX)
    b.wall_ns(f"bx_n_{i}", x0, 3.0, 0, BOX)
for i, y0 in enumerate((1, 2)):
    b.wall_ew(f"bx_w_{i}", 3.0, y0, 0, BOX)
    b.wall_ew(f"bx_e_{i}", 5.0, y0, 0, BOX)
for x0 in (3, 4):
    for y0 in (1, 2):
        b.flat(f"bx_d_{x0}_{y0}", x0, y0, 1.0, DECK)     # 台面
b.ramp("bx_r0", "+x", 5.0, 1, 1.0, RAMP)                 # 东侧下坡
b.ramp("bx_r1", "+x", 5.0, 2, 1.0, RAMP)

# =================================================================
# 3. 靠墙斜坡区 (西 x=0, y[2,4]): 背墙 + 坡道挂墙顶
# =================================================================
for i, y0 in enumerate((2, 3)):
    b.wall_ew(f"bk_w_{i}", 0.0, y0, 0, BANK)
b.ramp("bk_r0", "+x", 0.0, 2, 1.0, RAMP)
b.ramp("bk_r1", "+x", 0.0, 3, 1.0, RAMP)

# =================================================================
# 4. 火山跳包 [6,7]x[0,1]: 四墙围筒 + 等边四坡锥 (不铺台面)
# =================================================================
b.wall_ns("vc_s", 6, 0.0, 0, VOLC)
b.wall_ns("vc_n", 6, 1.0, 0, VOLC)
b.wall_ew("vc_w", 6.0, 0, 0, VOLC)
b.wall_ew("vc_e", 7.0, 0, 0, VOLC)
VHAT_IDS = b.hat4("vc_hat", 6, 0, 1.0, VHAT, shape="equilateral_triangle")

# =================================================================
# 5. 高低台 [7,8]x[3,4]: 三墙半围 + 台面 + 西向坡道
# =================================================================
b.wall_ns("lg_s", 7, 3.0, 0, LEDGE)
b.wall_ns("lg_n", 7, 4.0, 0, LEDGE)
b.wall_ew("lg_e", 8.0, 3, 0, LEDGE)
b.flat("lg_d", 7, 3, 1.0, LEDGE)
b.ramp("lg_r", "-x", 7.0, 3, 1.0, RAMP)

# =================================================================
# 6. 磨杆 [3,5]x[0,1]: 双柱 + 桥式长板 (北长边与方箱墙顶共线互吸)
# =================================================================
b.wall_ew("rl_p_w", 3.0, 0, 0, POST)
b.wall_ew("rl_p_e", 5.0, 0, 0, POST)
b.flat_rect("rl_bar", 3, 0, 1.0, RAIL, axis="x")

# =================================================================
# 7. 入场旗 + 雪糕筒
# =================================================================
b.spire_ns("fl_w", 2, 0.0, 0.0, FLAG)
b.spire_ns("fl_e", 7, 0.0, 0.0, FLAG)
b.crest_ew("cn_w", 0.0, 1, 0.0, CONE)
b.crest_ew("cn_e0", 8.0, 1, 0.0, CONE)
b.crest_ew("cn_e1", 8.0, 2, 0.0, CONE)

# =================================================================
# 教程步骤 (15 步)
# =================================================================
b.step(
    "铺场地南排: 西段长方形 + 6 片方板密缝排开 (道具柱线都落在这排缝上)。",
    ["f0_w"] + [f"f0_{x0}" for x0 in range(2, 8)],
    tip="南排用方板密缝 —— 磨杆柱和火山围墙都要吸在这些拼缝上。",
)
b.step(
    "铺涂鸦带第一排: 方板收两端, 3 片青色长方形居中。",
    ["f1_w", "f1_a", "f1_b", "f1_c", "f1_e"],
    highlight=["f0_w"],
    tip="青色涂鸦带是公园的招牌 —— 轮子擦过就是一道弧线。",
)
b.step(
    "铺涂鸦带第二排: 与第一排对称。",
    ["f2_w", "f2_a", "f2_b", "f2_c", "f2_e"],
    highlight=["f1_a"],
    tip="长方形长边彼此等长互吸 (2 = 2)。",
)
b.step(
    "铺场地北排: 4 片长方形合拢 8x4 水泥板场。",
    ["f3_0", "f3_1", "f3_2", "f3_3"],
    highlight=["f2_w"],
    tip="场地连成刚性整板, 道具才有稳固地基。",
)
b.step(
    "立方箱跳台南墙与西墙: 4 片橙色墙板, 拐角竖边互吸。",
    ["bx_s_0", "bx_s_1", "bx_w_0", "bx_w_1"],
    highlight=["f1_b"],
    tip="墙底边吸场地拼缝, 拐角一锁就不晃。",
)
b.step(
    "合拢方箱北墙与东墙: 再 4 片, 八墙围筒成环。",
    ["bx_n_0", "bx_n_1", "bx_e_0", "bx_e_1"],
    highlight=["bx_w_0", "bx_s_0"],
    tip="围筒是最结实的箱形结构 —— 跳台的全部底气。",
)
b.step(
    "压方箱台面: 4 片红色方板压住围墙顶边、中缝互吸。",
    ["bx_d_3_1", "bx_d_4_1", "bx_d_3_2", "bx_d_4_2"],
    highlight=["bx_s_0", "bx_n_1"],
    tip="台面四板再加一圈水平环, 箱顶稳如平地。",
)
b.step(
    "挂方箱东坡道: 2 片青色长方形 30 度下坡, 顶边整边吸台面东沿、"
    "坡尾落地。",
    ["bx_r0", "bx_r1"],
    highlight=["bx_e_0", "bx_e_1"],
    tip="双端受力的坡道 (滚珠塔同款) —— 冲下去就是加速度。",
)
b.step(
    "搭西侧靠墙斜坡: 2 片背墙立上场地西沿, 2 片坡道顶边挂墙顶、"
    "坡尾落地。",
    ["bk_w_0", "bk_w_1", "bk_r0", "bk_r1"],
    highlight=["f2_w"],
    tip="背墙竖边互吸, 双坡道并排成一面大斜坡。",
)
b.step(
    "立火山跳包围墙: 4 片红色墙板在东南角围成 1x1 方筒。",
    ["vc_s", "vc_n", "vc_w", "vc_e"],
    highlight=["f0_6"],
    tip="四面墙四角互吸闭环 —— 火山的山脚。",
)
b.step(
    "合拢火山锥: 4 片橙色等边三角斜棱两两互吸、锥尖自锁在墙顶。",
    VHAT_IDS,
    highlight=["vc_s", "vc_e"],
    tip="从两边冲上火山口再飞出去 —— 这是全场最帅的跳包。",
)
b.step(
    "架磨杆: 2 片灰柱竖边与方箱角墙锁扣, 黄色长板两端各吸一柱顶、"
    "北长边还与方箱南墙顶共线互吸。",
    ["rl_p_w", "rl_p_e", "rl_bar"],
    highlight=["bx_s_0", "bx_s_1"],
    tip="桥式三点受力 —— 尖翻上杆也震不掉。",
)
b.step(
    "搭东北高低台: 3 片紫色墙板半围, 台面压顶, 坡道向西放下。",
    ["lg_s", "lg_n", "lg_e", "lg_d", "lg_r"],
    highlight=["f3_3"],
    tip="台面三边吸墙顶, 西边留给坡道 —— 上台走坡、下台走沿。",
)
b.step(
    "升入场旗: 2 面红色瘦高旗立上南排板缝。",
    ["fl_w", "fl_e"],
    highlight=["f0_2", "f0_7"],
    tip="旗杆立在方板边上, 远远就能看见公园开门了。",
)
b.step(
    "摆雪糕筒: 3 只黄色三角锥立上场地东西边沿 —— 开滑!",
    ["cn_w", "cn_e0", "cn_e1"],
    highlight=["f1_w", "f1_e"],
    tip="雪糕筒画出练习区 —— 新手先绕桩, 高手上磨杆。",
)

b.finalize(
    model_id="skate_park_01",
    name="滑板公园",
    name_en="Skate Park",
    description=(
        "街式滑板公园: 8x4 水泥板场上四件道具各不重样 —— 中央八墙围筒"
        "方箱跳台挂双 30 度下坡, 西侧靠墙斜坡双坡道挂墙顶, 东南角四墙"
        "围筒直接戴等边四坡锥成火山跳包, 东北高低台半围压顶再放单坡; "
        "方箱前双柱桥式磨杆三点受力, 入场双旗与雪糕筒画出练习区 —— "
        "助跑、起跳、尖翻上杆, 稳稳落地!"
    ),
    difficulty=3,
    tags=["运动", "滑板", "公园", "坡道"],
    min_pieces=60,
    min_steps=15,
)
