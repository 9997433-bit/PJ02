#!/usr/bin/env python3
"""生成模型 data/models/cabin_lake_01.json (湖边木屋)。

自然田园主题: 8x5 湖畔草地上, 一间橙色原木小屋面南而立 ——
木门 (门框方) 与观湖窗 (窗格方) 并肩, 60 度人字坡灰瓦压顶;
东山墙外一座 1x1 石砌烟囱塔叠两层戴压顶, 高过屋脊半头;
东侧蓝湖伸出一条木栈桥: 两片桥桩立在湖床格缝上, 三片桥板
连吸成道, 30 度跳板从草地缓缓接上桥头, 桥尾竖起系船桩 ——
炊烟起, 湖水静, 这就是周末的家。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 湖畔草地 + 蓝湖 8x5: 方板 + 长板混铺                    31 片
  - 木屋: 门框方 + 窗格方 + 长楣 + 端墙 x2                   5 片
  - 屋面: 60 度坡面 x2 + 等边山花 x2                         4 片
  - 烟囱塔: 方板圈层 x2 层 (西面借山墙/山花) + 压顶          7 片
  - 柴堆: 等边三角 x2 (屋西墙根)                             2 片
  - 栈桥: 桥桩 x2 + 桥板 x3 + 30 度跳板 + 护栏 x2 + 系船桩   9 片
  - 岸树 x2 + 灌木四坡锥 (4 片) + 花丛 x2                    8 片
  合计 66 片, 17 个教程步骤, 7 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 门框方/窗格方外框按实心正方形拼接, 竖边与端墙竖边咬合;
  - 人字坡先架北坡 (下长边整边吸北墙长楣顶), 再架南坡合脊,
    等边山花两腰吸坡面短边;
  - 烟囱塔首层西墙即木屋东端墙 (共墙), 二层西面正是东山花
    所在的负空间 —— 三面圈层 + 压顶三边整边吸合, 稳如磐石;
  - 栈桥板接缝正压桥桩顶边, 跳板顶边吸桥头短边、坡尾落草地;
    桥尾板单边悬挑力矩 28 <= 预算 40 (strict 档 35 也过)。

用法: python3 tools/generate_cabin_lake.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

RIDGE_H = 0.866025

GRASS = "green"
LAKE = "blue"
LOG = "orange"
ROOF = "gray"
STONE = "gray"
DOCK = "orange"
POST = "gray"
TREE = "green"
FLOWER = "pink"

# =================================================================
# 1. 湖畔草地 (x 0..5) + 蓝湖 (x 5..8), 8x5
# =================================================================
b.flat("g_0_0", 0, 0, 0.0, GRASS)
b.flat_rect("g_r_0", 1, 0, 0.0, GRASS, axis="x")
b.flat("g_3_0", 3, 0, 0.0, GRASS)
b.flat("g_4_0", 4, 0, 0.0, GRASS)
b.flat_rect("lk_r_0", 5, 0, 0.0, LAKE, axis="x")
b.flat("lk_7_0", 7, 0, 0.0, LAKE)
# y[1,2]: 栈桥一行, 湖面必须用方板 (桥桩要吸格缝)
b.flat("g_0_1", 0, 1, 0.0, GRASS)
b.flat_rect("g_r_1", 1, 1, 0.0, GRASS, axis="x")      # 木屋南墙地基 [1,3]
b.flat("g_3_1", 3, 1, 0.0, "gray")                    # 门前小路
b.flat("g_4_1", 4, 1, 0.0, GRASS)
b.flat("lk_5_1", 5, 1, 0.0, LAKE)
b.flat("lk_6_1", 6, 1, 0.0, LAKE)
b.flat("lk_7_1", 7, 1, 0.0, LAKE)
# y[2,3]: 木屋地坪 + 烟囱塔基
b.flat("g_0_2", 0, 2, 0.0, GRASS)
b.flat_rect("g_f", 1, 2, 0.0, LOG, axis="x")          # 木屋地板 [1,3]
b.flat("g_3_2", 3, 2, 0.0, STONE)                     # 烟囱塔基
b.flat("g_4_2", 4, 2, 0.0, GRASS)
b.flat_rect("lk_r_2", 5, 2, 0.0, LAKE, axis="x")
b.flat("lk_7_2", 7, 2, 0.0, LAKE)
# y[3,4]
b.flat("g_0_3", 0, 3, 0.0, GRASS)
b.flat_rect("g_r_3", 1, 3, 0.0, GRASS, axis="x")      # 木屋北墙地基
b.flat("g_3_3", 3, 3, 0.0, GRASS)
b.flat("g_4_3", 4, 3, 0.0, GRASS)
b.flat_rect("lk_r_3", 5, 3, 0.0, LAKE, axis="x")
b.flat("lk_7_3", 7, 3, 0.0, LAKE)
# y[4,5]
b.flat_rect("g_t_0", 0, 4, 0.0, GRASS, axis="x")
b.flat("g_2_4", 2, 4, 0.0, GRASS)
b.flat("g_3_4", 3, 4, 0.0, GRASS)
b.flat("g_4_4", 4, 4, 0.0, GRASS)
b.flat_rect("lk_t", 5, 4, 0.0, LAKE, axis="x")
b.flat("lk_7_4", 7, 4, 0.0, LAKE)

# =================================================================
# 2. 木屋 (x 1..3, y 2..3, z 0..1): 木门 + 观湖窗 + 长楣 + 端墙
# =================================================================
b.wall_ns("cb_door", 1, 2.0, 0, LOG)                  # 木门 (门框方)
b.tiles[-1]["type"] = "door_frame"
b.wall_ns("cb_win", 2, 2.0, 0, "clear")               # 观湖窗 (窗格方)
b.tiles[-1]["type"] = "window_square"
b.lintel_ns("cb_n", 1, 3.0, 0, LOG)                   # 北墙
b.wall_ew("cb_w", 1.0, 2, 0, LOG)                     # 西端墙
b.wall_ew("cb_e", 3.0, 2, 0, LOG)                     # 东端墙 (兼烟囱塔西壁)

# =================================================================
# 3. 屋面: 先北坡 (整边吸北墙顶) 再南坡合脊, 山花封两端
# =================================================================
b.place_edge("cb_rf_n", "rectangle", 0, (3.0, 3.0, 1.0), (1.0, 3.0, 1.0),
             (0.0, -0.5, RIDGE_H), ROOF)              # 北坡面
b.place_edge("cb_rf_s", "rectangle", 0, (1.0, 2.0, 1.0), (3.0, 2.0, 1.0),
             (0.0, 0.5, RIDGE_H), ROOF)               # 南坡面
b.crest_ew("cb_gb_w", 1.0, 2, 1.0, LOG)               # 西山花
b.crest_ew("cb_gb_e", 3.0, 2, 1.0, LOG)               # 东山花

# =================================================================
# 4. 烟囱塔 (x 3..4, y 2..3): 首层三面 (西面共用木屋东端墙),
#    二层三面 (西面是东山花的负空间), 压顶收口
# =================================================================
b.wall_ns("ch_s_0", 3, 2.0, 0, STONE)
b.wall_ns("ch_n_0", 3, 3.0, 0, STONE)
b.wall_ew("ch_e_0", 4.0, 2, 0, STONE)
b.wall_ns("ch_s_1", 3, 2.0, 1, STONE)
b.wall_ns("ch_n_1", 3, 3.0, 1, STONE)
b.wall_ew("ch_e_1", 4.0, 2, 1, STONE)
b.flat("ch_cap", 3, 2, 2.0, STONE)                    # 压顶 (z=2, 高过屋脊)

# =================================================================
# 5. 柴堆: 2 片等边三角贴屋西墙根
# =================================================================
b.crest_ns("wd_a", 0, 2.0, 0.0, LOG)                  # 柴堆 (门西侧)
b.crest_ns("wd_b", 0, 3.0, 0.0, LOG)

# =================================================================
# 6. 栈桥 (y 1..2, z 0..1): 桥桩 + 桥板 + 跳板 + 护栏 + 系船桩
# =================================================================
b.wall_ew("dk_p6", 6.0, 1, 0, POST)                   # 桥桩 x=6
b.wall_ew("dk_p7", 7.0, 1, 0, POST)                   # 桥桩 x=7
b.flat("dk_5", 5, 1, 1.0, DOCK)                       # 桥板
b.flat("dk_6", 6, 1, 1.0, DOCK)
b.flat("dk_7", 7, 1, 1.0, DOCK)
b.ramp("dk_ramp", "-x", 5.0, 1, 1.0, DOCK)            # 30 度跳板 (坡尾落草地)
b.crest_ns("dk_rl_5", 5, 1.0, 1.0, DOCK)              # 南护栏
b.crest_ns("dk_rl_6", 6, 1.0, 1.0, DOCK)
b.crest_ew("dk_moor", 8.0, 1, 1.0, POST)              # 桥尾系船桩

# =================================================================
# 7. 岸树 + 灌木 + 花丛
# =================================================================
b.spire_ns("tr_a", 0, 1.0, 0.0, TREE)                 # 西南岸树
b.spire_ns("tr_b", 2, 5.0, 0.0, TREE)                 # 北岸树
BUSH = b.hat4("bush", 0, 3, 0.0, TREE,
              shape="equilateral_triangle")           # 西北灌木
b.crest_ns("fl_a", 0, 0.0, 0.0, FLOWER)               # 南沿花丛
b.crest_ns("fl_b", 4, 0.0, 0.0, FLOWER)

# =================================================================
# 教程步骤 (17 步)
# =================================================================
b.step(
    "铺南沿: 草地 4 片接蓝湖 2 片, 湖岸线画在 x=5。",
    ["g_0_0", "g_r_0", "g_3_0", "g_4_0", "lk_r_0", "lk_7_0"],
    tip="西边是草地, 东边是湖 —— 岸线从第一排就定下。",
)
b.step(
    "铺栈桥一行: 草地 4 片 (灰色是门前小路) + 湖面 3 片方板。",
    ["g_0_1", "g_r_1", "g_3_1", "g_4_1", "lk_5_1", "lk_6_1", "lk_7_1"],
    highlight=["lk_r_0"],
    tip="这一行湖面必须用方板 —— x=6 与 x=7 格缝马上要立桥桩。",
)
b.step(
    "铺木屋一行: 原木色长板是木屋地板, 灰色方板是烟囱塔基。",
    ["g_0_2", "g_f", "g_3_2", "g_4_2", "lk_r_2", "lk_7_2"],
    highlight=["g_r_1"],
    tip="地板 [1,3] 的南北两条长边就是木屋前后墙的地基线。",
)
b.step(
    "铺北部两行: 12 片合拢, 8x5 湖畔就绪。",
    ["g_0_3", "g_r_3", "g_3_3", "g_4_3", "lk_r_3", "lk_7_3",
     "g_t_0", "g_2_4", "g_3_4", "g_4_4", "lk_t", "lk_7_4"],
    highlight=["g_f", "g_3_2"],
    tip="湖畔铺好 —— 该起屋、砌烟囱、搭栈桥了。",
)
b.step(
    "立木屋南面: 木门 (门框方) 与观湖窗 (窗格方) 并肩, 竖边互吸。",
    ["cb_door", "cb_win"],
    highlight=["g_f", "g_3_1"],
    tip="门朝小路, 窗朝湖 —— 醒来第一眼就是湖面。",
)
b.step(
    "立北墙与端墙: 北面长楣 + 东西端墙, 首层围合。",
    ["cb_n", "cb_w", "cb_e"],
    highlight=["cb_door", "cb_win"],
    tip="端墙竖边同时咬住门窗与长楣的竖边 —— 一圈锁定。",
)
b.step(
    "架人字坡: 先架北坡 (下长边整边吸北墙顶), 再架南坡, "
    "脊线两长边互吸合拢。",
    ["cb_rf_n", "cb_rf_s"],
    highlight=["cb_n"],
    tip="先北后南 —— 第一片有整边可吸, 第二片合脊即锁。",
)
b.step(
    "封山花: 东西各 1 片等边三角, 底边吸端墙顶、两腰吸坡面短边。",
    ["cb_gb_w", "cb_gb_e"],
    highlight=["cb_rf_n", "cb_rf_s"],
    tip="山花一封, 木屋成形 —— 烟囱塔就贴着东山花砌。",
)
b.step(
    "砌烟囱首层: 石墙三面围塔基 (西面借木屋东端墙), 四角竖边咬合。",
    ["ch_s_0", "ch_n_0", "ch_e_0"],
    highlight=["cb_e", "g_3_2"],
    tip="共墙砌法 —— 一面墙同时属于木屋和烟囱。",
)
b.step(
    "砌烟囱二层: 三面再叠一层, 西面正是东山花的负空间。",
    ["ch_s_1", "ch_n_1", "ch_e_1"],
    highlight=["ch_s_0", "cb_gb_e"],
    tip="烟囱要高过屋脊, 炊烟才不倒灌 —— 老木匠的规矩。",
)
b.step(
    "封烟囱压顶: 灰色方板三边整边吸墙顶, 烟囱塔完工。",
    ["ch_cap"],
    highlight=["ch_s_1", "ch_e_1"],
    tip="压顶 2 格高, 比 1.87 格的屋脊高出半头 —— 完美。",
)
b.step(
    "码柴堆: 2 片等边三角贴着西墙根一字码好。",
    ["wd_a", "wd_b"],
    highlight=["cb_w"],
    tip="过冬的柴火要码在屋檐下 —— 底边吸草地格边。",
)
b.step(
    "立桥桩: 2 片灰色方板立在湖床 x=6 与 x=7 格缝上。",
    ["dk_p6", "dk_p7"],
    highlight=["lk_5_1", "lk_6_1"],
    tip="桥桩顺着桥的方向立, 底边整边吸湖床格边。",
)
b.step(
    "铺桥板: 3 片橙色桥板首尾互吸, 接缝正压桩顶。",
    ["dk_5", "dk_6", "dk_7"],
    highlight=["dk_p6", "dk_p7"],
    tip="板缝落在桩顶上 —— 木桥的老规矩, 湖上也一样。",
)
b.step(
    "接跳板与桥头: 30 度跳板顶边吸桥头短边、坡尾落草地; "
    "桥尾竖系船桩, 南沿立 2 片护栏。",
    ["dk_ramp", "dk_rl_5", "dk_rl_6", "dk_moor"],
    highlight=["dk_5", "dk_7"],
    tip="跳板双端受力; 系船桩迎着湖心 —— 小船回来就拴在这。",
)
b.step(
    "种岸树: 西南与北岸各 1 棵等腰绿树。",
    ["tr_a", "tr_b"],
    highlight=["g_0_0", "g_2_4"],
    tip="树梢 2 格, 与烟囱压顶同高 —— 湖畔的天际线。",
)
b.step(
    "栽灌木与花丛: 西北灌木四坡合拢, 南沿两簇粉色花丛收尾 —— "
    "湖边木屋交房!",
    BUSH + ["fl_a", "fl_b"],
    highlight=["g_0_3", "g_4_0"],
    tip="从栈桥回望: 花丛、木门、人字顶、烟囱、炊烟一线排开。",
)

b.finalize(
    model_id="cabin_lake_01",
    name="湖边木屋",
    name_en="Lakeside Cabin 01",
    description=(
        "湖畔度假小屋三件套: 原木小屋 (门框方木门 + 窗格方观湖窗, 60 度"
        "人字坡先北后南合脊, 等边山花封两端); 石砌烟囱塔与木屋共墙, "
        "二层西面恰好嵌着东山花的负空间, 压顶 2 格高过屋脊半头; 蓝湖上"
        "两桩三板搭出栈桥, 30 度跳板缓接草地, 桥尾系船桩迎着湖心 —— "
        "桥尾板单边悬挑力矩 28 在预算 40 之内, strict 档也稳稳通过。"
    ),
    difficulty=3,
    tags=["田园", "自然", "木屋", "湖泊", "进阶"],
    min_pieces=50,
    min_steps=16,
)
