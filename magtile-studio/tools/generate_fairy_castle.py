#!/usr/bin/env python3
"""生成模型 data/models/fairy_castle_01.json (仙子天桥城堡)。

童话/奇幻主题 1/4: 全库第一座 "天桥双塔" 城堡 —— 与既有城堡批
(castle_foundation_01 平地围墙 / castle_drawbridge_01 双塔门楼+平放
桥板 / castle_tower_01 土丘城塞 / medieval_gate_01 双重墙瓮城) 的
结构逻辑刻意区分: 本作的主角是 "高处相连", 两座纤细的 1x1 三层
仙子塔各自拔地而起, 塔顶由一条横跨 2 格的天桥相连 —— 塔-桥-塔-
地面锁成全场最大的门式刚架环; 半空中另有一道彩虹拱楣双端竖边
纯剪锁进两塔塔身, 楣底倒挂一盏魔法吊灯 (受拉悬垂); 双塔各戴
等腰四坡童话锥顶 (塔尖 4.94), 天桥南沿立两面粉色小旗。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 城堡朝南):
  - 地面 (x [0,6], y [0,5]): 草坪 + 石板道 5 行                 20 片
  - 西塔 (x [1,2], y [2,3], z 0..3): 三层墙环 (门框方塔门 x1 +
    窗格方精灵窗 x1)                                            12 片
  - 东塔 (x [4,5], y [2,3], z 0..3): 镜像三层墙环               12 片
  - 塔顶盖板 x2 + 等腰四坡锥顶 x8 (塔尖 4.94)                   10 片
  - 天桥: 方形桥板 x2 (z=3 双端各一线双吸) + 粉旗 x2             4 片
  - 彩虹拱楣 x2 (z 1..2 双端竖边纯剪) + 魔法吊灯 x2 (倒挂受拉)    4 片
  - 花丛: 等边三角 x4                                            4 片
  合计 66 片, 13 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, strict 档同样全绿):
  - 双塔每层 4 片墙环四角竖边互吸闭环, 层与层水平缝上下互吸;
  - 天桥两片方板短边分别同时吸塔顶盖板沿与第 3 层墙顶 (一线双吸),
    桥中缝互吸; 剪断任一端, 桥体仍经另一端-塔身-地面绕行;
  - 彩虹拱楣两片方板外端竖边吸进两塔第 2 层墙身竖棱 (纯剪, 吊桥
    门楣同款), 中缝互吸; 每片楣板底沿各倒挂一盏魔法吊灯, 底边
    整边吸合、重心正下受拉 (13g << strict 预算 84g);
  - 小旗/花丛与承托面共面, 重心正压铰链线, 力矩为零。

用法: python3 tools/generate_fairy_castle.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

LAWN = "green"      # 草坪
PATH = "gray"       # 石板道
TOWER = "pink"      # 塔身 1~2 层
TOWER3 = "purple"   # 塔身第 3 层
DOOR = "orange"     # 门框方塔门
WIN = "clear"       # 窗格方精灵窗
CAP = "purple"      # 塔顶盖板
CONE = "red"        # 童话锥顶
BRIDGE = "cyan"     # 天桥 / 彩虹拱楣
FLAG = "pink"       # 天桥小旗
LAMP = "yellow"     # 魔法吊灯
FLOWER_A = "red"    # 花丛
FLOWER_B = "yellow"

# =================================================================
# 1. 地面 (x [0,6], y [0,5]): 5 行, 石板道纵贯正中 (x [2,4])
# =================================================================
b.flat_rect("fg0_a", 0, 0, 0.0, LAWN)
b.flat_rect("fg0_b", 2, 0, 0.0, PATH)
b.flat_rect("fg0_c", 4, 0, 0.0, LAWN)
for r, ys in (("fg1", 1), ("fg2", 2)):
    b.flat(f"{r}_a", 0, ys, 0.0, LAWN)
    b.flat(f"{r}_b", 1, ys, 0.0, LAWN)
    b.flat_rect(f"{r}_c", 2, ys, 0.0, PATH)
    b.flat(f"{r}_d", 4, ys, 0.0, LAWN)
    b.flat(f"{r}_e", 5, ys, 0.0, LAWN)
b.flat("fg3_a", 0, 3, 0.0, LAWN)
b.flat_rect("fg3_b", 1, 3, 0.0, LAWN)
b.flat_rect("fg3_c", 3, 3, 0.0, LAWN)
b.flat("fg3_d", 5, 3, 0.0, LAWN)
b.flat_rect("fg4_a", 0, 4, 0.0, LAWN)
b.flat_rect("fg4_b", 2, 4, 0.0, LAWN)
b.flat_rect("fg4_c", 4, 4, 0.0, LAWN)

# =================================================================
# 2. 西塔 (x [1,2], y [2,3], z 0..3): 三层墙环
#    第 1 层南面门框方塔门, 第 2 层南面窗格方精灵窗
# =================================================================
b.add("wt1_s", "door_frame", (1.5, 2.0, 0.5), (90, 0, 0), DOOR)
b.wall_ew("wt1_w", 1.0, 2, 0, TOWER)
b.wall_ew("wt1_e", 2.0, 2, 0, TOWER)
b.wall_ns("wt1_n", 1, 3.0, 0, TOWER)

b.add("wt2_s", "window_square", (1.5, 2.0, 1.5), (90, 0, 0), WIN)
b.wall_ew("wt2_w", 1.0, 2, 1, TOWER)
b.wall_ew("wt2_e", 2.0, 2, 1, TOWER)
b.wall_ns("wt2_n", 1, 3.0, 1, TOWER)

b.wall_ns("wt3_s", 1, 2.0, 2, TOWER3)
b.wall_ew("wt3_w", 1.0, 2, 2, TOWER3)
b.wall_ew("wt3_e", 2.0, 2, 2, TOWER3)
b.wall_ns("wt3_n", 1, 3.0, 2, TOWER3)

# =================================================================
# 3. 东塔 (x [4,5], y [2,3], z 0..3): 镜像三层墙环
# =================================================================
b.add("et1_s", "door_frame", (4.5, 2.0, 0.5), (90, 0, 0), DOOR)
b.wall_ew("et1_w", 4.0, 2, 0, TOWER)
b.wall_ew("et1_e", 5.0, 2, 0, TOWER)
b.wall_ns("et1_n", 4, 3.0, 0, TOWER)

b.add("et2_s", "window_square", (4.5, 2.0, 1.5), (90, 0, 0), WIN)
b.wall_ew("et2_w", 4.0, 2, 1, TOWER)
b.wall_ew("et2_e", 5.0, 2, 1, TOWER)
b.wall_ns("et2_n", 4, 3.0, 1, TOWER)

b.wall_ns("et3_s", 4, 2.0, 2, TOWER3)
b.wall_ew("et3_w", 4.0, 2, 2, TOWER3)
b.wall_ew("et3_e", 5.0, 2, 2, TOWER3)
b.wall_ns("et3_n", 4, 3.0, 2, TOWER3)

# =================================================================
# 4. 彩虹拱楣 (y=2, x [2,4], z 1..2) + 魔法吊灯 (楣底倒挂受拉)
# =================================================================
b.wall_ns("arch_w", 2, 2.0, 1, BRIDGE)
b.wall_ns("arch_e", 3, 2.0, 1, BRIDGE)
b.place_tri("lamp_w", "equilateral_triangle",
            (3.0, 2.0, 1.0), (2.0, 2.0, 1.0), (2.5, 2.0, 0.133975), LAMP)
b.place_tri("lamp_e", "equilateral_triangle",
            (4.0, 2.0, 1.0), (3.0, 2.0, 1.0), (3.5, 2.0, 0.133975), LAMP)

# =================================================================
# 5. 塔顶盖板 + 天桥 + 小旗 + 锥顶
# =================================================================
b.flat("wt_cap", 1, 2, 3.0, CAP)
b.flat("et_cap", 4, 2, 3.0, CAP)
b.flat("bridge_w", 2, 2, 3.0, BRIDGE)
b.flat("bridge_e", 3, 2, 3.0, BRIDGE)
b.crest_ns("br_flag_w", 2, 2.0, 3.0, FLAG)
b.crest_ns("br_flag_e", 3, 2.0, 3.0, FLAG)
WT_CONE = b.hat4("wt_cone", 1, 2, 3.0, CONE)
ET_CONE = b.hat4("et_cone", 4, 2, 3.0, CONE)

# =================================================================
# 6. 花丛 (草坪拼缝上)
# =================================================================
b.crest_ns("fl_sw", 0, 1.0, 0.0, FLOWER_A)
b.crest_ns("fl_se", 5, 1.0, 0.0, FLOWER_B)
b.crest_ns("fl_nw", 0, 3.0, 0.0, FLOWER_B)
b.crest_ns("fl_ne", 5, 3.0, 0.0, FLOWER_A)

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺前院一行 (y [0,1]): 3 片长板, 石板道居中正对两塔之间。",
    ["fg0_a", "fg0_b", "fg0_c"],
    tip="石板道 (x [2,4]) 正上方将架起彩虹拱楣与天桥。",
)
b.step(
    "铺草坪第二行 (y [1,2]): 5 片, 塔脚拼缝就位。",
    ["fg1_a", "fg1_b", "fg1_c", "fg1_d", "fg1_e"],
    highlight=["fg0_b"],
    tip="x=1/2 与 x=4/5 的拼缝是两座仙子塔的墙脚。",
)
b.step(
    "铺塔基行 (y [2,3]): 5 片, 两塔就踩这一行的格线。",
    ["fg2_a", "fg2_b", "fg2_c", "fg2_d", "fg2_e"],
    highlight=["fg1_b"],
    tip="中间的石板道穿过两塔之间 —— 那是城堡的仙径。",
)
b.step(
    "铺后院两行 (y [3,5]): 7 片, 草坪合拢。",
    ["fg3_a", "fg3_b", "fg3_c", "fg3_d", "fg4_a", "fg4_b", "fg4_c"],
    highlight=["fg2_c"],
    tip="6x5 草坪铺满 —— 仙子的城堡从一片花园开始。",
)
b.step(
    "立西塔第 1 层: 4 片墙环, 南面是橙色门框方塔门。",
    ["wt1_s", "wt1_w", "wt1_e", "wt1_n"],
    highlight=["fg1_b", "fg2_b"],
    tip="每片底边吸草坪拼缝、转角竖边互咬 —— 墙环闭合才稳。",
)
b.step(
    "立东塔第 1 层: 镜像 4 片墙环, 塔门同样朝南。",
    ["et1_s", "et1_w", "et1_e", "et1_n"],
    highlight=["wt1_s"],
    tip="两扇塔门一左一右, 中间留出 2 格宽的仙径门洞。",
)
b.step(
    "叠两塔第 2 层: 各 4 片, 南面嵌窗格方精灵窗。",
    ["wt2_s", "wt2_w", "wt2_e", "wt2_n",
     "et2_s", "et2_w", "et2_e", "et2_n"],
    highlight=["wt1_s", "et1_s"],
    tip="每片同时吸下层墙顶与邻片竖边 —— 连接处处成环。",
)
b.step(
    "架彩虹拱楣并倒挂双魔法吊灯: 两片楣板外端竖边纯剪锁进塔身。",
    ["arch_w", "arch_e", "lamp_w", "lamp_e"],
    highlight=["wt2_e", "et2_w"],
    tip="吊灯底边整边吸楣底沿, 重心正下受拉 —— 磁力最擅长的方向。",
)
b.step(
    "叠两塔第 3 层: 各 4 片紫色墙环, 塔身升到 3 格高。",
    ["wt3_s", "wt3_w", "wt3_e", "wt3_n",
     "et3_s", "et3_w", "et3_e", "et3_n"],
    highlight=["arch_w"],
    tip="第 3 层墙顶就是天桥的桥墩 —— 越往上越要对齐。",
)
b.step(
    "盖塔顶盖板并架天桥: 两片桥板外端各一线双吸两塔塔顶, 桥中缝互吸。",
    ["wt_cap", "et_cap", "bridge_w", "bridge_e"],
    highlight=["wt3_e", "et3_w"],
    tip="塔-桥-塔-地面锁成全场最大的环 —— 剪断一端也塌不了。",
)
b.step(
    "戴西塔锥顶: 4 片等腰三角斜棱两两互吸自锁。",
    WT_CONE,
    highlight=["wt_cap", "bridge_w"],
    tip="童话城堡的标志就是这顶红色尖帽 (塔尖 4.94)。",
)
b.step(
    "戴东塔锥顶: 再 4 片, 双塔尖帽遥遥相对。",
    ET_CONE,
    highlight=["wt_cone_s"],
    tip="四条斜棱互吸成环, 越推越紧。",
)
b.step(
    "插天桥小旗 + 栽花丛 —— 仙子天桥城堡落成!",
    ["br_flag_w", "br_flag_e", "fl_sw", "fl_se", "fl_nw", "fl_ne"],
    highlight=["bridge_e", "fg0_a"],
    tip="小旗重心正压桥沿铰链; 让小仙子从天桥上飞过去吧!",
)

b.finalize(
    model_id="fairy_castle_01",
    name="仙子天桥城堡",
    name_en="Fairy Sky-bridge Castle 01",
    description=(
        "全库第一座天桥双塔城堡: 两座纤细的 1x1 三层仙子塔各自拔地"
        "而起, 塔顶两片方形桥板双端一线双吸架成天桥 —— 塔-桥-塔-"
        "地面锁成全场最大的门式刚架环; 半空彩虹拱楣双端竖边纯剪锁进"
        "塔身, 楣底倒挂一对受拉魔法吊灯; 双塔各戴等腰四坡童话锥顶"
        " (塔尖 4.94), 桥沿粉旗迎风。高处相连、纯剪锁楣、倒挂受拉"
        " —— 三种连接方式一座城堡学会。"
    ),
    difficulty=3,
    tags=["童话", "奇幻", "仙子城堡", "天桥", "进阶"],
    min_pieces=64,
    min_steps=13,
)
