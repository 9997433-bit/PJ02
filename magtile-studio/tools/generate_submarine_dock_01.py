#!/usr/bin/env python3
"""生成模型 data/models/submarine_dock_01.json (潜艇维修船坞)。

水下/海洋主题: 与 submarine_01 (纯潜艇造型) / ferry_terminal_01
(候船楼码头) / harbor_crane_01 (门式起重机) 的结构逻辑刻意区分:
本作是全库第一座 "双岸夹一坞" 的干船坞 —— 南北两条闭环码头岸壁
隔出 6x3 水湾, 湾底满铺水面板, 一艘 3x1 潜艇 (壳体环墙 + 甲板 +
指挥塔 + 潜望镜) 停泊正中; 南岸上再起 1x1 调度塔戴等边四坡顶,
一条 30 度检修坡道从南岸直下坞底 (坡尾落在预留的空水格)。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 南岸码头 (x [0,6], y [0,1], z 0..1): 环墙 x14 (含门框方
    坞门 x1 + 窗格方值班窗 x1) + 岸面满铺 x6                     20 片
  - 北岸码头 (x [0,6], y [4,5], z 0..1): 环墙 x14 (含窗格方 x1)
    + 岸面满铺 x6                                                20 片
  - 坞底水面 (x [0,6], y [1,4]): 青色方板 x17 (x [0,1] x y [2,3]
    留空给坡道坡尾落地)                                          17 片
  - 潜艇 (x [2,5], y [2,3], z 0..2): 壳体环墙 x8 + 甲板 x3 +
    指挥塔环 x4 (含窗格方舷窗) + 塔顶盖板 x1 + 潜望镜等腰
    塔尖 x1 (镜尖 4.0) + 艏艉等边三角 x2                          19 片
  - 调度塔 (x [5,6], y [0,1], z 1..3): 两层墙环 x8 (含窗格方 x2)
    + 等边四坡锥顶 x4 (塔尖 3.71)                                12 片
  - 检修坡道: 30 度长方形 x1 (顶边吸南岸沿, 坡尾落空水格)          1 片
  合计 89 片, 18 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点:
  - 两岸环墙四角互吸闭环, 岸面每片同时压墙顶与邻板拼缝;
  - 岸壁底边与坞底水面板整边吸合, 全场连成一体 (无孤岛);
  - 潜艇壳体环墙踩水面拼缝, 甲板压壳顶, 指挥塔踩甲板拼缝再起
    一环, 潜望镜与艏艉三角骑沿口共面零力矩;
  - 坡道顶边一线双吸 (岸面沿 + 岸壁顶), 坡尾落在预留空水格的
    实地上, 不与任何水面板相交。

用法: python3 tools/generate_submarine_dock_01.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

QUAY = "gray"       # 码头岸壁
DECKQ = "gray"      # 岸面
DOOR = "orange"     # 门框方坞门
WIN = "clear"       # 窗格方
WATER = "cyan"      # 坞底水面
HULL = "blue"       # 潜艇壳体
SDECK = "gray"      # 潜艇甲板
SAIL = "blue"       # 指挥塔
PERI = "red"        # 潜望镜
BOW = "yellow"      # 艏艉三角
TOWER = "orange"    # 调度塔
THAT = "red"        # 调度塔锥顶
RAMP = "gray"       # 检修坡道

# =================================================================
# 1. 南岸码头 (x [0,6], y [0,1], z 0..1): 环墙 + 岸面
#    南墙 x [2,3] 开门框方坞门, x [4,5] 嵌窗格方值班窗
# =================================================================
b.wall_ns("sq_s_0", 0, 0.0, 0, QUAY)
b.wall_ns("sq_s_1", 1, 0.0, 0, QUAY)
b.add("sq_gate", "door_frame", (2.5, 0.0, 0.5), (90, 0, 0), DOOR)
b.wall_ns("sq_s_3", 3, 0.0, 0, QUAY)
b.add("sq_win", "window_square", (4.5, 0.0, 0.5), (90, 0, 0), WIN)
b.wall_ns("sq_s_5", 5, 0.0, 0, QUAY)
b.wall_ew("sq_w", 0.0, 0, 0, QUAY)
for x in range(6):
    b.wall_ns(f"sq_n_{x}", x, 1.0, 0, QUAY)
b.wall_ew("sq_e", 6.0, 0, 0, QUAY)
for x in range(6):
    b.flat(f"sq_d_{x}", x, 0, 1.0, DECKQ)

# =================================================================
# 2. 调度塔 (x [5,6], y [0,1], z 1..3): 两层墙环 + 等边锥顶
# =================================================================
b.wall_ns("tw1_s", 5, 0.0, 1, TOWER)
b.wall_ns("tw1_n", 5, 1.0, 1, TOWER)
b.wall_ew("tw1_w", 5.0, 0, 1, TOWER)
b.wall_ew("tw1_e", 6.0, 0, 1, TOWER)
b.add("tw2_s", "window_square", (5.5, 0.0, 2.5), (90, 0, 0), WIN)
b.wall_ns("tw2_n", 5, 1.0, 2, TOWER)
b.add("tw2_w", "window_square", (5.0, 0.5, 2.5), (90, 0, 90), WIN)
b.wall_ew("tw2_e", 6.0, 0, 2, TOWER)
TOWER_HAT = b.hat4("tw_hat", 5, 0, 3.0, THAT, shape="equilateral_triangle")

# =================================================================
# 3. 北岸码头 (x [0,6], y [4,5], z 0..1): 环墙 (南墙嵌窗) + 岸面
# =================================================================
for x in range(6):
    b.wall_ns(f"nq_n_{x}", x, 5.0, 0, QUAY)
b.wall_ew("nq_w", 0.0, 4, 0, QUAY)
b.wall_ns("nq_s_0", 0, 4.0, 0, QUAY)
b.wall_ns("nq_s_1", 1, 4.0, 0, QUAY)
b.add("nq_win", "window_square", (2.5, 4.0, 0.5), (90, 0, 0), WIN)
b.wall_ns("nq_s_3", 3, 4.0, 0, QUAY)
b.wall_ns("nq_s_4", 4, 4.0, 0, QUAY)
b.wall_ns("nq_s_5", 5, 4.0, 0, QUAY)
b.wall_ew("nq_e", 6.0, 4, 0, QUAY)
for x in range(6):
    b.flat(f"nq_d_{x}", x, 4, 1.0, DECKQ)

# =================================================================
# 4. 坞底水面 (x [0,6], y [1,4]): x [0,1] x y [2,3] 留空给坡尾
# =================================================================
for x in range(6):
    b.flat(f"wa_{x}_1", x, 1, 0.0, WATER)
for x in range(1, 6):
    b.flat(f"wa_{x}_2", x, 2, 0.0, WATER)
for x in range(6):
    b.flat(f"wa_{x}_3", x, 3, 0.0, WATER)

# =================================================================
# 5. 潜艇 (x [2,5], y [2,3], z 0..2): 壳体 + 甲板 + 指挥塔 + 潜望镜
# =================================================================
for x in (2, 3, 4):
    b.wall_ns(f"hu_s_{x}", x, 2.0, 0, HULL)
    b.wall_ns(f"hu_n_{x}", x, 3.0, 0, HULL)
b.wall_ew("hu_w", 2.0, 2, 0, HULL)
b.wall_ew("hu_e", 5.0, 2, 0, HULL)
for x in (2, 3, 4):
    b.flat(f"hu_d_{x}", x, 2, 1.0, SDECK)
b.wall_ns("sa_s", 3, 2.0, 1, SAIL)
b.wall_ns("sa_n", 3, 3.0, 1, SAIL)
b.wall_ew("sa_w", 3.0, 2, 1, SAIL)
b.add("sa_e", "window_square", (4.0, 2.5, 1.5), (90, 0, 90), WIN)
b.flat("sa_cap", 3, 2, 2.0, SDECK)
b.spire_ns("peri", 3, 3.0, 2.0, PERI)
b.crest_ew("bow", 2.0, 2, 1.0, BOW)
b.crest_ew("stern", 5.0, 2, 1.0, BOW)

# =================================================================
# 6. 检修坡道: 顶边吸南岸北沿, 坡尾落在预留空水格 (x [0,1])
# =================================================================
b.ramp("ramp", "+y", 1.0, 0, 1.0, RAMP)

# =================================================================
# 教程步骤 (18 步)
# =================================================================
b.step(
    "砌南岸南墙与西墙: 7 片灰色岸壁, 坞门朝南、值班窗朝航道。",
    ["sq_s_0", "sq_s_1", "sq_gate", "sq_s_3", "sq_win", "sq_s_5", "sq_w"],
    tip="橙色门框方是船坞大门 —— 检修班组从这里进出。",
)
b.step(
    "砌南岸北墙与东墙: 7 片, 南岸环墙闭合。",
    [f"sq_n_{x}" for x in range(6)] + ["sq_e"],
    highlight=["sq_s_0", "sq_w"],
    tip="北墙就是坞壁 —— 潜艇一会儿停在它脚下。",
)
b.step(
    "铺南岸岸面: 6 片方板压墙顶, 邻板拼缝互吸。",
    [f"sq_d_{x}" for x in range(6)],
    highlight=["sq_s_1", "sq_n_2"],
    tip="每片同时吸两段墙顶 —— 岸面就是调度塔的地基。",
)
b.step(
    "起调度塔第 1 层: 4 片橙色墙环踩岸面东端拼缝。",
    ["tw1_s", "tw1_n", "tw1_w", "tw1_e"],
    highlight=["sq_d_5"],
    tip="调度塔踞守东端, 俯瞰整个船坞。",
)
b.step(
    "叠调度塔第 2 层: 4 片, 南面与西面嵌窗格方了望窗。",
    ["tw2_s", "tw2_n", "tw2_w", "tw2_e"],
    highlight=["tw1_s", "tw1_e"],
    tip="两扇了望窗盯住坞门与坞底 —— 调度员的视野。",
)
b.step(
    "戴调度塔锥顶: 等边四坡, 塔尖 3.71。",
    TOWER_HAT,
    highlight=["tw2_n", "tw2_e"],
    tip="四条斜棱两两互吸自锁 —— 红顶十里可见。",
)
b.step(
    "铺坞底水面南行 (y [1,2]): 6 片青色方板贴着南岸壁脚。",
    [f"wa_{x}_1" for x in range(6)],
    highlight=["sq_n_0"],
    tip="水面板与岸壁底边整边吸合 —— 全场连成一体。",
)
b.step(
    "铺坞底水面中行 (y [2,3]): 5 片, 西端留一格空水面。",
    [f"wa_{x}_2" for x in range(1, 6)],
    highlight=["wa_0_1"],
    tip="留空的水格是检修坡道的落脚点 —— 先留位, 后搭桥。",
)
b.step(
    "铺坞底水面北行 (y [3,4]): 6 片, 水面合拢。",
    [f"wa_{x}_3" for x in range(6)],
    highlight=["wa_1_2"],
    tip="17 片水面板铺满坞湾, 潜艇的泊位就绪。",
)
b.step(
    "砌北岸南墙与东墙: 7 片岸壁贴着水面北沿起 (南墙嵌窗格方)。",
    ["nq_s_0", "nq_s_1", "nq_win", "nq_s_3", "nq_s_4", "nq_s_5", "nq_e"],
    highlight=["wa_0_3", "wa_5_3"],
    tip="坞壁底边与水面板整边吸合 —— 窗格方朝向坞底。",
)
b.step(
    "砌北岸北墙与西墙: 7 片, 北岸环墙闭合。",
    [f"nq_n_{x}" for x in range(6)] + ["nq_w"],
    highlight=["nq_s_0", "nq_e"],
    tip="北岸与南岸隔水相望, 中间就是 6x3 的坞湾。",
)
b.step(
    "铺北岸岸面: 6 片方板压墙顶。",
    [f"nq_d_{x}" for x in range(6)],
    highlight=["nq_n_2", "nq_s_3"],
    tip="两岸岸面同高 —— 船坞的骨架完成。",
)
b.step(
    "立潜艇壳体南墙与艇艏: 4 片蓝色立墙踩水面拼缝。",
    ["hu_s_2", "hu_s_3", "hu_s_4", "hu_w"],
    highlight=["wa_2_2", "wa_3_2"],
    tip="3x1 壳体是潜艇的耐压艇身。",
)
b.step(
    "立潜艇壳体北墙与艇艉: 4 片, 壳体环闭合。",
    ["hu_n_2", "hu_n_3", "hu_n_4", "hu_e"],
    highlight=["hu_s_2", "hu_w"],
    tip="壳体四角互吸 —— 潜艇稳稳坐进坞位。",
)
b.step(
    "盖潜艇甲板: 3 片方板压壳顶。",
    ["hu_d_2", "hu_d_3", "hu_d_4"],
    highlight=["hu_s_3", "hu_n_3"],
    tip="每片同时吸两段壳顶与邻板拼缝。",
)
b.step(
    "起指挥塔: 4 片墙环踩甲板拼缝, 东面嵌窗格方舷窗。",
    ["sa_s", "sa_n", "sa_w", "sa_e"],
    highlight=["hu_d_3"],
    tip="指挥塔在艇身正中 —— 潜艇的眼睛和大脑。",
)
b.step(
    "封塔顶 + 竖潜望镜: 盖板压塔顶, 等腰塔尖直上 4.0。",
    ["sa_cap", "peri"],
    highlight=["sa_s", "sa_n"],
    tip="潜望镜骑塔顶北沿, 与塔墙共面零力矩。",
)
b.step(
    "装艏艉三角 + 架检修坡道: 坡道顶边吸南岸沿, 坡尾落空水格 —— 船坞落成!",
    ["bow", "stern", "ramp"],
    highlight=["hu_d_2", "sq_d_0"],
    tip="黄色艏艉三角是流线艇首; 坡道一线双吸 (岸面沿 + 岸壁顶)。",
)

b.finalize(
    model_id="submarine_dock_01",
    name="潜艇维修船坞",
    name_en="Submarine Dock 01",
    description=(
        "全库第一座双岸夹一坞的潜艇干船坞: 南北两条闭环码头岸壁"
        " (坞门 + 值班窗) 隔出 6x3 坞湾, 坞底青色水面板满铺并与"
        "岸壁整边吸合; 一艘 3x1 蓝色潜艇停泊正中 —— 壳体环墙 +"
        " 甲板 + 指挥塔舷窗 + 潜望镜等腰塔尖 (镜尖 4.0) + 艏艉"
        "流线三角; 南岸东端再起调度塔戴等边四坡红顶 (塔尖 3.71),"
        " 一条 30 度检修坡道从岸面直下坞底预留空水格。双岸合围、"
        "艇坞分明 —— 港口工程一课学会。"
    ),
    difficulty=4,
    tags=["海洋", "港口", "潜艇", "船坞", "进阶"],
    min_pieces=85,
    min_steps=18,
)
