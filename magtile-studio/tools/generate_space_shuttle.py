#!/usr/bin/env python3
"""生成模型 data/models/space_shuttle_01.json (航天飞机)。

太空主题: 全库第一架航天飞机 —— 刚刚着陆, 停在跑道正中:
机身用独木舟同款 "嵌地" 技法 —— 白色机腹长板嵌进跑道同层
平铺, 侧墙从机腹拼缝立起锁成细长箱体; 招牌动作是四扇货舱门
绕侧墙顶铰链向外翻开 30 度 (相邻门竖边互吸, 每扇双连接),
舱里还躺着一颗待部署的青色卫星; 三角翼不占高度 —— 白色方板
与直角三角嵌进跑道平面, 与灰色道面直角三角沿斜边互吸拼出
后掠角; 尾部双垂尾 (等腰塔尖 3.0) 骑侧墙顶纵向立起, 机尾
两簇橙色喷焰, 机头风挡窗格方 + 直角三角骨架鼻锥; 跑道尽头
黄色地勤拖车 (车轮底座轮组) 已经赶到 —— 欢迎回家!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 机头朝东):
  - 跑道 8x5: 方板 x22 + 长板 x8 + 三角翼直角三角 x4
    (含白色机腹嵌板 x5 + 白色翼板 x4)                        34 片
  - 机身侧墙 (z 0~1): 南北各 5 片透明墙                      10 片
  - 尾墙 + 风挡 (窗格方): 各 1 片                             2 片
  - 机背顶板 (z=1): 尾段/中段/机头段 x3 (货舱留空)            3 片
  - 货舱门: 方板 x4 绕墙顶外翻 30 度 + 舱内卫星 x1            5 片
  - 鼻锥骨架: 直角三角 x2 (与侧墙共面)                        2 片
  - 双垂尾: 等腰塔尖 x2 (尖 3.0) + 喷焰等边 x2                4 片
  - 地勤拖车: 车轮底座 x2 + 长板车顶 + 警灯                   4 片
  - 跑道端灯: 等边三角 x4 (西绿 2 + 东红 2)                   4 片
  合计 68 片, 15 个教程步骤, 7 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, strict 档同样全绿):
  - 机腹与三角翼全部嵌进跑道同层 (与道面锁成连续平面, 零重
    叠零悬空); 翼板斜边与道面直角三角斜边整边互吸;
  - 货舱门是全模型唯一的悬挑: 方板质量 30g, 绕墙顶铰链外翻
    30 度, 力臂 0.25 -> 力矩 7.5 <= strict 预算 17.5; 相邻
    两扇门竖边还互吸一道, 剪断铰链也有旁路;
  - 双垂尾底边同时吸侧墙顶与机背顶板沿 (双连接), 竖直平面
    重心正压铰链力矩 0; 尖 3.0 触发 R8 高层检查, 箱体闭环
    处处冗余, 零警告;
  - 鼻锥直角三角与侧墙共面: 竖直角边同时吸侧墙竖棱与风挡
    竖棱, 水平直角边吸跑道拼缝;
  - 拖车车顶长板双长边各吸一面轮组墙顶, 双端受力如桥。

用法: python3 tools/generate_space_shuttle.py  (在 magtile-studio 目录下运行)
"""

import math

from magtile_gen import ModelBuilder

b = ModelBuilder()

S30 = 0.5
C30 = round(math.cos(math.radians(30)), 6)   # 0.866025

RUNWAY = "gray"     # 跑道
BODY = "clear"      # 机身 (白)
WING = "clear"      # 三角翼
DOOR = "clear"      # 货舱门
SAT = "cyan"        # 舱内卫星
FIN = "red"         # 垂尾
FLAME = "orange"    # 喷焰
GLASS = "clear"     # 风挡
TUG = "yellow"      # 地勤拖车
BEACON = "red"      # 拖车警灯
L_GREEN = "green"   # 跑道边灯
L_RED = "red"       # 跑道端灯

# =================================================================
# 1. 跑道 8x5 (x [0,8], y [0,5]): 机腹与三角翼嵌进道面同层
#    机身占 y [2,3] 的 x [1,6]; 翼板贴机身两侧, 斜边收后掠角
# =================================================================
for k in range(4):
    b.flat_rect(f"rw_s_{k}", 2 * k, 0, 0.0, RUNWAY)
# 第二行 (y [1,2]): 南翼 —— (2,1)(3,1) 白方板, (4,1) 斜边对拼
for x in (0, 1, 5, 6, 7):
    b.flat(f"rw_{x}_1", x, 1, 0.0, RUNWAY)
b.flat("wing_s_a", 2, 1, 0.0, WING)
b.flat("wing_s_b", 3, 1, 0.0, WING)
b.place_tri("wing_s_tip", "right_triangle",
            (4.0, 2.0, 0.0), (4.0, 1.0, 0.0), (5.0, 2.0, 0.0), WING)
b.place_tri("rw_s_tri", "right_triangle",
            (5.0, 1.0, 0.0), (5.0, 2.0, 0.0), (4.0, 1.0, 0.0), RUNWAY)
# 第三行 (y [2,3]): 机腹嵌板 x [1,6]
b.flat("rw_0_2", 0, 2, 0.0, RUNWAY)
for x in range(1, 6):
    b.flat(f"belly_{x}", x, 2, 0.0, BODY)
b.flat("rw_6_2", 6, 2, 0.0, RUNWAY)
b.flat("rw_7_2", 7, 2, 0.0, RUNWAY)
# 第四行 (y [3,4]): 北翼 (镜像)
for x in (0, 1, 5, 6, 7):
    b.flat(f"rw_{x}_3", x, 3, 0.0, RUNWAY)
b.flat("wing_n_a", 2, 3, 0.0, WING)
b.flat("wing_n_b", 3, 3, 0.0, WING)
b.place_tri("wing_n_tip", "right_triangle",
            (4.0, 3.0, 0.0), (5.0, 3.0, 0.0), (4.0, 4.0, 0.0), WING)
b.place_tri("rw_n_tri", "right_triangle",
            (5.0, 4.0, 0.0), (4.0, 4.0, 0.0), (5.0, 3.0, 0.0), RUNWAY)
for k in range(4):
    b.flat_rect(f"rw_n_{k}", 2 * k, 4, 0.0, RUNWAY)

# =================================================================
# 2. 机身侧墙 (z 0~1, x [1,6]) + 尾墙 + 风挡
# =================================================================
for x0 in range(1, 6):
    b.wall_ns(f"hs_{x0}", x0, 2.0, 0, BODY)   # 南侧墙
    b.wall_ns(f"hn_{x0}", x0, 3.0, 0, BODY)   # 北侧墙
b.wall_ew("tail_wall", 1.0, 2, 0, BODY)
b.add("windshield", "window_square", (6.0, 2.5, 0.5), (90, 0, 90), GLASS)

# =================================================================
# 3. 机背顶板 (z=1): 货舱 (x [2,4]) 敞开 + 舱内卫星
# =================================================================
b.flat("rf_aft", 1, 2, 1.0, BODY)
b.flat("rf_mid", 4, 2, 1.0, BODY)
b.flat("rf_nose", 5, 2, 1.0, BODY)
b.crest_ew("payload", 3.0, 2, 0.0, SAT)

# =================================================================
# 4. 货舱门: 每侧两扇方板绕侧墙顶铰链向外翻开 30 度, 门缝互吸
# =================================================================
b.place_edge("bay_s_a", "square", 0, (2.0, 2.0, 1.0), (3.0, 2.0, 1.0),
             (0.0, -S30, C30), DOOR)
b.place_edge("bay_s_b", "square", 0, (3.0, 2.0, 1.0), (4.0, 2.0, 1.0),
             (0.0, -S30, C30), DOOR)
b.place_edge("bay_n_a", "square", 0, (4.0, 3.0, 1.0), (3.0, 3.0, 1.0),
             (0.0, S30, C30), DOOR)
b.place_edge("bay_n_b", "square", 0, (3.0, 3.0, 1.0), (2.0, 3.0, 1.0),
             (0.0, S30, C30), DOOR)

# =================================================================
# 5. 鼻锥骨架 + 双垂尾 + 喷焰
# =================================================================
b.brace("nose_s", (6.0, 2.0, 0.0), "+x", BODY)
b.brace("nose_n", (6.0, 3.0, 0.0), "+x", BODY)
b.spire_ns("fin_s", 1, 2.0, 1.0, FIN)
b.spire_ns("fin_n", 1, 3.0, 1.0, FIN)
b.crest_ns("flame_s", 0, 2.0, 0.0, FLAME)
b.crest_ns("flame_n", 0, 3.0, 0.0, FLAME)

# =================================================================
# 6. 地勤拖车 (x [6,8], y [0,1]) + 跑道边灯
# =================================================================
b.add("tug_s", "wheel_base", (7.0, 0.0, 0.5), (90, 0, 0), TUG)
b.add("tug_n", "wheel_base", (7.0, 1.0, 0.5), (90, 0, 0), TUG)
b.add("tug_top", "rectangle", (7.0, 0.5, 1.0), (0, 0, 0), TUG)
b.crest_ew("tug_beacon", 6.0, 0, 1.0, BEACON)
b.crest_ew("lt_w_a", 0.0, 1, 0.0, L_GREEN)
b.crest_ew("lt_w_b", 0.0, 3, 0.0, L_GREEN)
b.crest_ew("lt_e_a", 8.0, 1, 0.0, L_RED)
b.crest_ew("lt_e_b", 8.0, 3, 0.0, L_RED)

# =================================================================
# 教程步骤 (15 步)
# =================================================================
b.step(
    "铺跑道南沿: 4 片灰长板 (y [0,1])。",
    [f"rw_s_{k}" for k in range(4)],
    tip="跑道从南沿铺起 —— 地勤拖车一会儿停在东头。",
)
b.step(
    "铺第二行 (y [1,2]): 南翼白板嵌进道面, 斜边直角三角对拼。",
    ["rw_0_1", "rw_1_1", "wing_s_a", "wing_s_b", "wing_s_tip",
     "rw_s_tri", "rw_5_1", "rw_6_1", "rw_7_1"],
    highlight=["rw_s_0"],
    tip="翼板斜边与道面斜边整边互吸 —— 后掠角就这么拼出来。",
)
b.step(
    "铺第三行 (y [2,3]): 白色机腹长条嵌进跑道正中。",
    ["rw_0_2"] + [f"belly_{x}" for x in range(1, 6)] + ["rw_6_2", "rw_7_2"],
    highlight=["rw_0_1"],
    tip="机腹与道面锁成连续平面 —— 独木舟的嵌地技法。",
)
b.step(
    "铺第四行 (y [3,4]): 北翼镜像嵌板。",
    ["rw_0_3", "rw_1_3", "wing_n_a", "wing_n_b", "wing_n_tip",
     "rw_n_tri", "rw_5_3", "rw_6_3", "rw_7_3"],
    highlight=["belly_1"],
    tip="两翼展开 —— 从空中看已经是航天飞机的剪影。",
)
b.step(
    "铺跑道北沿: 4 片长板, 道面合拢。",
    [f"rw_n_{k}" for k in range(4)],
    highlight=["rw_0_3"],
    tip="八五跑道铺满 —— 机身要立体起来了。",
)
b.step(
    "立南侧墙: 5 片透明墙踩机腹拼缝, 竖边连吸。",
    [f"hs_{x0}" for x0 in range(1, 6)],
    highlight=["belly_1", "belly_5"],
    tip="侧墙立在机腹与翼板的拼缝上 —— 双连接生根。",
)
b.step(
    "立北侧墙: 再来 5 片, 机身成箱。",
    [f"hn_{x0}" for x0 in range(1, 6)],
    highlight=["hs_1"],
    tip="南北墙隔舱相望 —— 货舱空间出来了。",
)
b.step(
    "封尾墙 + 装机头风挡 (窗格方), 舱里放好待部署卫星。",
    ["tail_wall", "windshield", "payload"],
    highlight=["hs_1", "hn_5"],
    tip="风挡竖边与两侧墙互吸 —— 卫星踩舱底拼缝。",
)
b.step(
    "盖机背顶板: 尾段/中段/机头段 3 片, 货舱留空。",
    ["rf_aft", "rf_mid", "rf_nose"],
    highlight=["tail_wall", "windshield"],
    tip="顶板压两侧墙顶 —— 机头段还搭上了风挡顶边。",
)
b.step(
    "开货舱门: 每侧两扇方板绕墙顶铰链向外翻开 30 度, 门缝互吸。",
    ["bay_s_a", "bay_s_b", "bay_n_a", "bay_n_b"],
    highlight=["rf_aft", "rf_mid"],
    tip="单扇力矩仅 7.5, 相邻门竖边还互吸一道 —— 双保险。",
)
b.step(
    "拼鼻锥骨架: 2 片直角三角与侧墙共面, 斜边收出机鼻。",
    ["nose_s", "nose_n"],
    highlight=["windshield"],
    tip="竖直角边同时咬侧墙竖棱与风挡竖棱 —— 一边双吸。",
)
b.step(
    "竖双垂尾: 2 片等腰塔尖骑侧墙顶纵向立起, 尖 3.0。",
    ["fin_s", "fin_n"],
    highlight=["rf_aft"],
    tip="垂尾底边同时吸墙顶与顶板沿 —— 双连接零力矩。",
)
b.step(
    "点尾部喷焰: 2 簇橙色等边三角踩机尾拼缝。",
    ["flame_s", "flame_n"],
    highlight=["tail_wall"],
    tip="着陆滑跑的余温 —— 喷口还烫着呢。",
)
b.step(
    "地勤拖车进场: 车轮底座轮组 + 长板车顶 + 红色警灯。",
    ["tug_s", "tug_n", "tug_top", "tug_beacon"],
    highlight=["rw_s_3"],
    tip="车顶长板双长边各压一面轮组墙顶 —— 双端受力如桥。",
)
b.step(
    "亮跑道端灯 —— 欢迎回家!",
    ["lt_w_a", "lt_w_b", "lt_e_a", "lt_e_b"],
    highlight=["rw_0_1", "rw_7_1"],
    tip="西端绿灯进近, 东端红灯到头 —— 端灯重心正压道沿铰链。",
)

b.finalize(
    model_id="space_shuttle_01",
    name="航天飞机",
    name_en="Space Shuttle 01",
    description=(
        "全库第一架航天飞机, 刚着陆停在跑道正中: 白色机腹长条"
        "用独木舟嵌地技法嵌进道面同层, 侧墙从拼缝立起锁成细长"
        "箱体; 招牌是四扇货舱门绕墙顶铰链向外翻开 30 度 (单扇"
        "力矩 7.5 <= strict 预算 17.5, 相邻门竖边互吸), 舱内躺着"
        "待部署的青色卫星; 三角翼嵌进跑道平面、斜边与道面直角三角"
        "整边互吸拼出后掠角; 双垂尾等腰塔尖 3.0 骑墙顶纵向立起,"
        " 窗格方风挡 + 直角三角鼻锥骨架收出机头, 尾喷焰、地勤"
        "拖车与红绿跑道边灯列队 —— 欢迎回家!"
    ),
    difficulty=3,
    tags=["航天", "航天器", "航天飞机", "跑道", "进阶"],
    min_pieces=64,
    min_steps=15,
)
