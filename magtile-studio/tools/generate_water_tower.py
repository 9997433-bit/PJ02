#!/usr/bin/env python3
"""生成模型 data/models/water_tower_01.json (水塔).

工程结构主题: 全库第一座市政水塔 —— 绿色镇口空地上, 2x2
闭合环塔身两层叠起 (每层 8 片, 四角竖边互吸), 塔脚四片
橙色直角斜撑风车形外展 (竖直角边吸塔角竖棱、水平直角边咬
地坪拼缝); 塔顶平台托起青色储水箱环, 蓝色箱盖四边压顶,
四片蓝色山墙饰与中央透明避雷尖收冠 —— 尖端直上 5 格,
全库最高的纯受压结构; 塔下一眼老井静静照着塔影 ——
水压来自高度, 高度来自秩序!

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 镇口空地 6x6: 方板咬缝 + 长板收边                         29 片
  - 塔身: 2x2 闭合环 x2 层 (每层 8 片, z0..2)                 16 片
  - 斜撑: 直角三角 x4 (风车形外展, 竖边吸塔角竖棱)             4 片
  - 塔顶平台: 方板 x4 (每片两条整边压环顶)                     4 片
  - 储水箱: 2x2 闭合环 x1 层 (z2..3)                           8 片
  - 箱盖: 方板 x4 (z=3)                                        4 片
  - 冠饰: 等边山墙饰 x4 (四面各 1) + 透明避雷尖 x1 (尖端 5.0)   5 片
  - 老井: 立墙闭环 x4 (井口开敞, 井水就是地坪的青色方板)        4 片
  合计 74 片, 12 个教程步骤, 5 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验, default + strict 双档):
  - 全塔纯受压: 每一层都是闭合环, 上环底边整边吸下环顶边,
    没有任何悬挑与悬挂 —— R5/R6 预算零占用;
  - 风车形斜撑: 竖直角边与塔角竖棱等长贴合, 水平直角边整边
    咬地坪拼缝, 且各自外展进四个不同的墙面平面 (不与塔身
    共面, R3 零穿插) —— 塔脚抗震裕量翻倍;
  - 尖端 5.0 触发 R8 高层检查: 逐层闭合环 + 四角斜撑冗余
    充足, 单点失效/无环拓扑零警告;
  - 平台/箱盖每片至少两条整边受力, 装配自外向内合拢 (R7b)。

用法: python3 tools/generate_water_tower.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

LAWN = "green"      # 镇口空地
PAVE = "gray"       # 石板
SHAFT = "gray"      # 塔身
BRACE = "orange"    # 斜撑
DECK = "blue"       # 塔顶平台
TANK = "cyan"       # 储水箱
LID = "blue"        # 箱盖 / 山墙饰
ROD = "clear"       # 避雷尖
WELL = "gray"       # 老井
WATER = "cyan"      # 井水

# =================================================================
# 1. 镇口空地 6x6: 塔基与斜撑落点全部方板咬缝
# =================================================================
b.flat_rect("gd_a0", 0, 0, 0.0, LAWN)               # [0,2]x[0,1]
b.flat_rect("gd_b0", 2, 0, 0.0, LAWN)               # [2,4]
b.flat("gd_c0", 4, 0, 0.0, PAVE)                    # [4,5] 井台前
b.flat("gd_d0", 5, 0, 0.0, WATER)                   # [5,6] 井水
for x in range(6):
    b.flat(f"gd_{x}_1", x, 1, 0.0, LAWN if x in (0, 5) else PAVE)
b.flat_rect("gd_a2", 0, 2, 0.0, LAWN)               # [0,2]x[2,3]
for x in (2, 3, 4, 5):
    b.flat(f"gd_{x}_2", x, 2, 0.0, PAVE if x in (2, 3) else LAWN)
for x in (0, 1, 2, 3):
    b.flat(f"gd_{x}_3", x, 3, 0.0, PAVE if x in (2, 3) else LAWN)
b.flat_rect("gd_e3", 4, 3, 0.0, LAWN)               # [4,6]x[3,4]
for x in range(6):
    b.flat(f"gd_{x}_4", x, 4, 0.0, LAWN if x in (0, 5) else PAVE)
b.flat_rect("gd_a5", 0, 5, 0.0, LAWN)               # [0,2]x[5,6]
b.flat_rect("gd_b5", 2, 5, 0.0, LAWN)               # [2,4]
b.flat_rect("gd_c5", 4, 5, 0.0, LAWN)               # [4,6]

# =================================================================
# 2. 塔身: 2x2 闭合环 x2 层, 围合 [2,4]x[2,4] (z0..2)
# =================================================================
for lv in (0, 1):
    for x in (2, 3):
        b.wall_ns(f"sh_s{x}_{lv}", x, 2.0, lv, SHAFT)   # 南
        b.wall_ns(f"sh_n{x}_{lv}", x, 4.0, lv, SHAFT)   # 北
    for y in (2, 3):
        b.wall_ew(f"sh_w{y}_{lv}", 2.0, y, lv, SHAFT)   # 西
        b.wall_ew(f"sh_e{y}_{lv}", 4.0, y, lv, SHAFT)   # 东

# =================================================================
# 3. 斜撑: 四角风车形外展 (竖边吸塔角竖棱, 不与塔身共面)
# =================================================================
b.brace("br_sw", (2.0, 2.0, 0.0), "-y", BRACE)      # 平面 x=2
b.brace("br_se", (4.0, 2.0, 0.0), "+x", BRACE)      # 平面 y=2
b.brace("br_ne", (4.0, 4.0, 0.0), "+y", BRACE)      # 平面 x=4
b.brace("br_nw", (2.0, 4.0, 0.0), "-x", BRACE)      # 平面 y=4

# =================================================================
# 4. 塔顶平台 (z=2) + 储水箱环 (z2..3) + 箱盖 (z=3)
# =================================================================
for x in (2, 3):
    for y in (2, 3):
        b.flat(f"dk_{x}_{y}", x, y, 2.0, DECK)
for x in (2, 3):
    b.wall_ns(f"tk_s{x}", x, 2.0, 2, TANK)
    b.wall_ns(f"tk_n{x}", x, 4.0, 2, TANK)
for y in (2, 3):
    b.wall_ew(f"tk_w{y}", 2.0, y, 2, TANK)
    b.wall_ew(f"tk_e{y}", 4.0, y, 2, TANK)
for x in (2, 3):
    for y in (2, 3):
        b.flat(f"ld_{x}_{y}", x, y, 3.0, LID)

# =================================================================
# 5. 冠饰: 四面山墙饰 + 中央避雷尖 (尖端 5.0)
# =================================================================
b.crest_ns("cr_s", 2, 2.0, 3.0, LID)                # 南 [2,3]
b.crest_ew("cr_e", 4.0, 2, 3.0, LID)                # 东 [2,3]
b.crest_ns("cr_n", 3, 4.0, 3.0, LID)                # 北 [3,4]
b.crest_ew("cr_w", 2.0, 3, 3.0, LID)                # 西 [3,4]
b.spire_ew("rod", 3.0, 2, 3.0, ROD)                 # 避雷尖

# =================================================================
# 6. 老井: [5,6]x[0,1] 立墙闭环, 井口开敞见水
# =================================================================
b.wall_ns("wl_s", 5, 0.0, 0, WELL)
b.wall_ns("wl_n", 5, 1.0, 0, WELL)
b.wall_ew("wl_w", 5.0, 0, 0, WELL)
b.wall_ew("wl_e", 6.0, 0, 0, WELL)

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺空地南段: 南沿行 4 片 + 第二行方板 6 片。",
    ["gd_a0", "gd_b0", "gd_c0", "gd_d0"]
    + [f"gd_{x}_1" for x in range(6)],
    tip="东南角青色方板是井水 —— 井壁将围着它升起。",
)
b.step(
    "铺空地中段: 2 行共 10 片, 塔基方板咬缝就位。",
    ["gd_a2", "gd_2_2", "gd_3_2", "gd_4_2", "gd_5_2",
     "gd_0_3", "gd_1_3", "gd_2_3", "gd_3_3", "gd_e3"],
    highlight=["gd_2_1", "gd_3_1"],
    tip="塔身 2x2 的四条边线全落在方板拼缝上。",
)
b.step(
    "铺空地北段: 方板行 6 片 + 北沿长板 3 片, 空地合拢 6x6。",
    [f"gd_{x}_4" for x in range(6)] + ["gd_a5", "gd_b5", "gd_c5"],
    highlight=["gd_2_3", "gd_3_3"],
    tip="镇口空地铺齐 —— 全镇最高的建筑马上动工。",
)
b.step(
    "砌塔身下环: 8 片灰墙围合 2x2, 四角竖边互吸闭环。",
    ["sh_s2_0", "sh_s3_0", "sh_e2_0", "sh_e3_0",
     "sh_n2_0", "sh_n3_0", "sh_w2_0", "sh_w3_0"],
    highlight=["gd_2_2", "gd_3_3"],
    tip="闭合环纯受压 —— 水塔的全部秘密就是一环压一环。",
)
b.step(
    "装四角斜撑: 4 片橙色直角三角风车形外展, 竖边吸塔角竖棱。",
    ["br_sw", "br_se", "br_ne", "br_nw"],
    highlight=["sh_s2_0", "sh_n3_0"],
    tip="每片斜撑独占一个墙面平面 —— 抗震裕量翻倍。",
)
b.step(
    "砌塔身上环: 再叠 8 片, 底边整边吸下环顶边。",
    ["sh_s2_1", "sh_s3_1", "sh_e2_1", "sh_e3_1",
     "sh_n2_1", "sh_n3_1", "sh_w2_1", "sh_w3_1"],
    highlight=["sh_s2_0", "sh_w2_0"],
    tip="两环精确对位 —— 塔身升到 2 格高。",
)
b.step(
    "铺塔顶平台: 4 片蓝色方板, 每片两条整边压环顶。",
    ["dk_2_2", "dk_3_2", "dk_2_3", "dk_3_3"],
    highlight=["sh_s2_1", "sh_e2_1"],
    tip="平台即隔板 —— 它把塔身与水箱焊成一体。",
)
b.step(
    "砌储水箱环: 平台上再围 8 片青色立墙 (z2..3)。",
    ["tk_s2", "tk_s3", "tk_e2", "tk_e3",
     "tk_n2", "tk_n3", "tk_w2", "tk_w3"],
    highlight=["dk_2_2", "dk_3_3"],
    tip="青色的就是水 —— 一整箱水悬在 2 格高处。",
)
b.step(
    "盖箱盖: 4 片蓝色方板压顶, 水箱封仓。",
    ["ld_2_2", "ld_3_2", "ld_2_3", "ld_3_3"],
    highlight=["tk_s2", "tk_n3"],
    tip="先外圈后合拢 —— 盖上盖子, 水就不怕落叶了。",
)
b.step(
    "装山墙饰: 箱盖四沿各立 1 片蓝色三角。",
    ["cr_s", "cr_e", "cr_n", "cr_w"],
    highlight=["ld_2_2", "ld_3_3"],
    tip="重心正压沿口铰链 —— 老水塔的一圈花边。",
)
b.step(
    "竖避雷尖: 箱盖中缝立起透明等腰尖, 直上 5 格!",
    ["rod"],
    highlight=["ld_2_2", "ld_3_2"],
    tip="全库最高的纯受压结构 —— 雷电从这里入地。",
)
b.step(
    "围老井: 东南角 4 片井壁四角竖边互吸, 井口开敞见水 —— 供水开阀!",
    ["wl_s", "wl_n", "wl_w", "wl_e"],
    highlight=["gd_d0"],
    tip="塔影落进井水里 —— 水压来自高度, 高度来自秩序!",
)

b.finalize(
    model_id="water_tower_01",
    name="市政水塔",
    name_en="Water Tower 01",
    description=(
        "全库第一座市政水塔与最高纯受压结构: 2x2 闭合环塔身两层叠起, "
        "塔脚四片橙色直角斜撑风车形外展 (竖边吸塔角竖棱、各占一个墙面"
        "平面), 塔顶平台托起青色储水箱环, 箱盖四沿山墙饰环立, 中央透明"
        "避雷尖直上 5 格 —— 逐层闭环 + 四角斜撑, R8 高层检查零警告; "
        "塔下老井静照塔影 —— 水压来自高度, 高度来自秩序!"
    ),
    difficulty=3,
    tags=["工程", "水塔", "市政", "供水", "高塔"],
    min_pieces=70,
    min_steps=12,
)
