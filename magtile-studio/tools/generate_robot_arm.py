#!/usr/bin/env python3
"""生成模型 data/models/robot_arm_01.json (机械臂工位).

工程结构主题: 全库第一座工业机器人工位 —— 灰色车间地坪上,
蓝色双层立柱肩座 (闭合环 x2 层) 顶起橙色水平大臂, 大臂远端
稳稳搭在前臂立柱顶上 (双端受力零悬挑); 大臂腹下垂挂一枚
红色三角夹爪, 正对下方绿色待加工件四坡料堆; 塔顶红色警示灯
竖起, 紫色斜面控制台立在一旁, 黄色安全围栏三面把守 ——
机械臂就位, 开始作业!

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 车间地坪 6x4: 每行 方板x2 + 长板 + 方板x2                 20 片
  - 肩座立柱: 1x1 闭合环 x2 层 (四角竖边互吸, z0..2)           8 片
  - 肩顶平台: 方板 x1 (四边整边压环顶)                          1 片
  - 水平大臂: 方板 x2 (西端吸平台, 东端搭前臂柱顶)              2 片
  - 前臂立柱: 方墙 x2 (z0..2, 大臂远端的第二支点)               2 片
  - 夹爪: 倒挂等边三角 x1 (悬挂 13g <= 预算 84g, strict 档)     1 片
  - 警示灯: 等边三角 x1 (立前臂柱顶, 重心正压铰链)              1 片
  - 待加工件: 等边四坡料堆 x4                                   4 片
  - 控制台: 直角三角斜面 x1 (两条直角边分别吸地坪缝)            1 片
  - 安全围栏: 等边三角 x6 (南北东三面, 底边整边吸地坪格边)      6 片
  合计 46 片, 10 个教程步骤, 4 种磁力片形状 (核心片型 x4)。

物理规则要点 (通过 R1~R8 全部校验, default + strict 双档):
  - 大臂逐片双端受力: 先立前臂柱, 大臂第 1 片放下瞬间力矩
    30x0.5=15 <= strict 预算 17.5, 第 2 片西吸第 1 片、东搭
    柱顶 —— 任何中间状态都不存在超预算悬臂;
  - 夹爪倒挂大臂南沿 (悬挂 13g, 远低于 strict 预算 84g/边),
    警示灯重心正压柱顶铰链线 (力臂为零);
  - 肩座两层闭合环 + 地坪网格提供充足结构冗余, 高点 2.87
    的 R8 检查零警告。

用法: python3 tools/generate_robot_arm.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

FLOOR = "gray"      # 车间地坪
ZONE = "yellow"     # 作业区地坪 / 围栏
PED = "blue"        # 肩座立柱
ARM = "orange"      # 水平大臂 / 肩顶平台
TOWER = "gray"      # 前臂立柱
CLAW = "red"        # 夹爪 / 警示灯
PART = "green"      # 待加工件
DESK = "purple"     # 控制台

# =================================================================
# 1. 车间地坪 6x4: 每行 方板x2 + 长板[2,4] + 方板x2
#    (拼缝 x=1,2,4,5 正是立柱脚与控制台的落点)
# =================================================================
for y in range(4):
    zone = ZONE if y in (1, 2) else FLOOR
    b.flat(f"fl_a_{y}", 0, y, 0.0, FLOOR)           # [0,1]
    b.flat(f"fl_b_{y}", 1, y, 0.0, zone)            # [1,2] 肩座格
    b.flat_rect(f"fl_c_{y}", 2, y, 0.0, FLOOR)      # [2,4]
    b.flat(f"fl_d_{y}", 4, y, 0.0, zone)            # [4,5] 前臂格
    b.flat(f"fl_e_{y}", 5, y, 0.0, FLOOR)           # [5,6]

# =================================================================
# 2. 肩座立柱: 1x1 闭合环 x2 层, 围合 [1,2]x[2,3] (z0..2)
# =================================================================
for lv in (0, 1):
    b.wall_ns(f"pd_s_{lv}", 1, 2.0, lv, PED)        # 南
    b.wall_ns(f"pd_n_{lv}", 1, 3.0, lv, PED)        # 北
    b.wall_ew(f"pd_w_{lv}", 1.0, 2, lv, PED)        # 西
    b.wall_ew(f"pd_e_{lv}", 2.0, 2, lv, PED)        # 东

# =================================================================
# 3. 前臂立柱: x=4 线立 2 层方墙 (z0..2), 大臂远端的第二支点
# =================================================================
b.wall_ew("fa_0", 4.0, 2, 0, TOWER)
b.wall_ew("fa_1", 4.0, 2, 1, TOWER)

# =================================================================
# 4. 肩顶平台 + 水平大臂 (z=2): 西端吸平台, 东端搭前臂柱顶
# =================================================================
b.flat("shoulder", 1, 2, 2.0, ARM)                  # 平台 [1,2]x[2,3]
b.flat("arm_a", 2, 2, 2.0, ARM)                     # 大臂内节 [2,3]
b.flat("arm_b", 3, 2, 2.0, ARM)                     # 大臂外节 [3,4]

# =================================================================
# 5. 夹爪 (倒挂大臂外节南沿) + 警示灯 (立前臂柱顶)
# =================================================================
b.place_edge("claw", "equilateral_triangle", 0,
             (4.0, 2.0, 2.0), (3.0, 2.0, 2.0), (0.0, 0.0, -1.0), CLAW)
b.crest_ew("beacon", 4.0, 2, 2.0, CLAW)

# =================================================================
# 6. 待加工件: 等边四坡料堆 [4,5]x[0,1]
# =================================================================
PART_IDS = b.hat4("part", 4, 0, 0.0, PART, shape="equilateral_triangle")

# =================================================================
# 7. 控制台: 直角三角斜面, 直角边吸 x=5 拼缝与竖直向上
# =================================================================
b.brace("console", (5.0, 1.0, 0.0), "+y", DESK)

# =================================================================
# 8. 安全围栏: 南北东三面各 2 片等边三角
# =================================================================
b.crest_ns("fn_s0", 0, 0.0, 0.0, ZONE)              # 南面 [0,1]
b.crest_ns("fn_s1", 1, 0.0, 0.0, ZONE)              # 南面 [1,2]
b.crest_ns("fn_n0", 0, 4.0, 0.0, ZONE)              # 北面 [0,1]
b.crest_ns("fn_n1", 1, 4.0, 0.0, ZONE)              # 北面 [1,2]
b.crest_ew("fn_e0", 6.0, 2, 0.0, ZONE)              # 东面 [2,3]
b.crest_ew("fn_e1", 6.0, 3, 0.0, ZONE)              # 东面 [3,4]

# =================================================================
# 教程步骤 (10 步)
# =================================================================
b.step(
    "铺地坪南半: 2 行各 5 片 (方板x2 + 长板 + 方板x2), 黄色格是设备落点。",
    [f"fl_{k}_{y}" for y in (0, 1) for k in "abcde"],
    tip="拼缝 x=1,2,4,5 一条都不能错 —— 立柱脚全踩在这些缝上。",
)
b.step(
    "铺地坪北半: 再铺 2 行, 车间地坪合拢成 6x4。",
    [f"fl_{k}_{y}" for y in (2, 3) for k in "abcde"],
    highlight=["fl_b_1", "fl_d_1"],
    tip="机械臂的世界坐标系原点, 就定在这块地坪上。",
)
b.step(
    "砌肩座下环: 围合黄色肩座格, 4 片蓝色立墙四角竖边互吸。",
    ["pd_s_0", "pd_n_0", "pd_w_0", "pd_e_0"],
    highlight=["fl_b_2"],
    tip="闭合环是最强的结构 —— 肩座要扛起整条大臂。",
)
b.step(
    "砌肩座上环: 再叠 4 片, 底边整边吸下环顶边。",
    ["pd_s_1", "pd_n_1", "pd_w_1", "pd_e_1"],
    highlight=["pd_s_0", "pd_e_0"],
    tip="两层环精确对位 —— 肩座升到 2 格高。",
)
b.step(
    "立前臂柱: x=4 拼缝上叠 2 片灰色方墙, 与肩座同高。",
    ["fa_0", "fa_1"],
    highlight=["fl_d_2"],
    tip="先立远端支点 —— 大臂伸过来时才有地方落脚。",
)
b.step(
    "架肩顶平台与大臂: 平台四边压环顶, 大臂 2 片向东接力, "
    "远端稳稳搭上前臂柱顶。",
    ["shoulder", "arm_a", "arm_b"],
    highlight=["pd_s_1", "fa_1"],
    tip="大臂第 1 片力矩 15 <= 预算 17.5, 第 2 片双端受力 —— 零悬挑。",
)
b.step(
    "挂夹爪、点警示灯: 红色三角倒挂大臂南沿, 柱顶再立警示灯。",
    ["claw", "beacon"],
    highlight=["arm_b", "fa_1"],
    tip="夹爪悬挂仅 13 克, 远低于磁力边 84 克的 strict 承重预算。",
)
b.step(
    "码待加工件: 夹爪正下方 4 片绿色三角四棱互吸, 合拢成料堆。",
    PART_IDS,
    highlight=["fl_d_0"],
    tip="四坡自锁 —— 这就是机械臂今天要抓的工件。",
)
b.step(
    "立控制台: 紫色直角三角斜面, 两条直角边分别吸拼缝与竖直立起。",
    ["console"],
    highlight=["fl_e_1"],
    tip="斜面朝向操作员 —— 一键启动, 大臂开始巡回。",
)
b.step(
    "围安全栏: 南北东三面各 2 片黄色三角, 底边整边吸地坪格边。",
    ["fn_s0", "fn_s1", "fn_n0", "fn_n1", "fn_e0", "fn_e1"],
    highlight=["fl_a_0", "fl_e_3"],
    tip="人机隔离 —— 黄色警示三角一圈立好, 工位验收合格!",
)

b.finalize(
    model_id="robot_arm_01",
    name="机械臂工位",
    name_en="Robot Arm Workcell 01",
    description=(
        "全库第一座工业机器人工位: 蓝色双层闭合环肩座顶起橙色水平大臂, "
        "大臂远端稳稳搭在前臂立柱顶上 (逐片双端受力零悬挑), 腹下倒挂红色"
        "三角夹爪 (悬挂 13g 远低于 strict 预算), 正对下方绿色四坡料堆; "
        "柱顶警示灯、紫色斜面控制台与三面黄色安全围栏把工位围出真实的"
        "车间秩序 —— 机械臂就位, 开始作业!"
    ),
    difficulty=2,
    tags=["工程", "工业机器人", "机械臂", "职业体验", "入门进阶"],
    min_pieces=44,
    min_steps=10,
)
