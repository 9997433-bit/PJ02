#!/usr/bin/env python3
"""生成模型 data/models/police_car_01.json (警车).

城市街景载具主题: 全库第一辆"轿车"轮廓的车 —— 白车身蓝警条的
警车停在临检点前: 前后两对车轮底座 (wheel_base) 托起 三段式
轿车车身 (发动机盖长板 / 座舱 / 后备箱方板), 座舱南北两条蓝色
警条整片长方形竖放 (底边整边同时吸轮组顶与底盘边), 前挡风与
后窗 45 度斜披, 车头再斜披一片青色车鼻; 车顶前沿立红色警灯。
人行道上一座蓝色临检岗亭 (门框方岗门 + 窗格方值班窗 + 屋脊
警徽三角), 路口红白拦截桩与橙色雪糕筒围出临检通道。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 车头朝西):
  - 街道三排 (南车道 / 临检车道 / 北车道) + 人行道       22 片
  - 车轮底座 x4 (前后各一对, 底边整边吸车道拼缝)          4 片
  - 车身三段: 发动机盖长板 + 座舱底板 + 后备箱方板         3 片
  - 座舱: 蓝色警条整片 x2 + 车顶长板 x1                    3 片
  - 玻璃: 前挡风 + 后窗 + 车鼻斜板 (45 度)                 3 片
  - 车顶警灯 (红色等边三角)                                1 片
  - 临检岗亭: 门框方+窗格方+方墙 x4 + 顶板 x2 + 警徽 x1    9 片
  - 街景: 拦截桩 x2 + 雪糕筒 x2 + 路灯 + 告示牌 x2         7 片
  合计 54 片, 16 个教程步骤, 8 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验, 常规+strict 双档):
  - 警条整片长方形竖放: 底边 (长 2) 整边同时吸轮组顶边与
    底盘长边, 顶边被车顶长板整边压住 —— 轮组+警条+车顶锁
    成箱形环 (结构冗余);
  - 前挡风 / 后窗 / 车鼻均为 45 度悬挂斜板: 单片 30g 远低
    于悬挂预算 (strict 84g/单位边长), 弯矩 10.6 < 17.5;
  - 警灯三角立在车顶前沿短边上, 重心正压铰链线 (力臂 0);
  - 岗亭四墙互吸成环, 顶板短边压墙顶。

用法: python3 tools/generate_police_car.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

ROAD = "gray"       # 沥青路面
WALK = "orange"     # 人行道砖
WHEEL = "gray"      # 车轮底座
BODY = "clear"      # 白色车身
STRIPE = "blue"     # 蓝色警条
GLASS = "cyan"      # 车窗玻璃
LIGHT = "red"       # 警灯
BOOTH = "blue"      # 岗亭

# =================================================================
# 1. 街道 [0,8]x[0,3] + 人行道 [0,8]x[3,4]
#    拼缝纪律: 车轮底座底边 (长 2) 只吸长方形长边;
#    立墙 / 三角底边 (长 1) 只吸正方形格边。
# =================================================================
# 南车道 y[0,1]: 长板拼缝落在 x[1,3] 与 [3,5] —— 轮组线
b.flat("r0_a", 0, 0, 0.0, ROAD)
b.flat_rect("r0_b", 1, 0, 0.0, ROAD)
b.flat_rect("r0_c", 3, 0, 0.0, ROAD)
b.flat("r0_d", 5, 0, 0.0, ROAD)
b.flat("r0_e", 6, 0, 0.0, ROAD)
b.flat("r0_f", 7, 0, 0.0, ROAD)
# 临检车道 y[1,2]: 警车就停在这排上
b.flat("r1_a", 0, 1, 0.0, ROAD)
b.flat_rect("r1_b", 1, 1, 0.0, ROAD)
b.flat_rect("r1_c", 3, 1, 0.0, ROAD)
b.flat("r1_d", 5, 1, 0.0, ROAD)
b.flat("r1_e", 6, 1, 0.0, ROAD)
b.flat("r1_f", 7, 1, 0.0, ROAD)
# 北车道 y[2,3]: x[2,4] 留两格方板 —— 拦截桩要吸在它们的北边
b.flat_rect("r2_a", 0, 2, 0.0, ROAD)
b.flat("r2_b", 2, 2, 0.0, "clear")          # 白色导流格
b.flat("r2_c", 3, 2, 0.0, "clear")
b.flat_rect("r2_d", 4, 2, 0.0, ROAD)
b.flat_rect("r2_e", 6, 2, 0.0, ROAD)
# 人行道 y[3,4]: 岗亭与告示牌所在的 x[4,8] 用方砖
b.flat_rect("wk_a", 0, 3, 0.0, WALK)
b.flat_rect("wk_b", 2, 3, 0.0, WALK)
b.flat("wk_c", 4, 3, 0.0, WALK)
b.flat("wk_d", 5, 3, 0.0, WALK)
b.flat("wk_e", 6, 3, 0.0, WALK)
b.flat("wk_f", 7, 3, 0.0, WALK)

# =================================================================
# 2. 车轮底座 x4: 前对 x[1,3] / 后对 x[3,5], 立在 y=1 与 y=2 线
# =================================================================
b.add("wb_fs", "wheel_base", (2.0, 1.0, 0.5), (90, 0, 0), WHEEL)
b.add("wb_fn", "wheel_base", (2.0, 2.0, 0.5), (90, 0, 0), WHEEL)
b.add("wb_rs", "wheel_base", (4.0, 1.0, 0.5), (90, 0, 0), WHEEL)
b.add("wb_rn", "wheel_base", (4.0, 2.0, 0.5), (90, 0, 0), WHEEL)

# =================================================================
# 3. 车身三段 (z=1): 发动机盖 [1,3] / 座舱底板 [3,5] / 后备箱 [5,6]
# =================================================================
b.flat_rect("hood", 1, 1, 1.0, BODY)
b.flat_rect("cabin_floor", 3, 1, 1.0, BODY)
b.flat("trunk", 5, 1, 1.0, BODY)

# =================================================================
# 4. 座舱 (z1..2): 南北蓝色警条整片 + 车顶长板
# =================================================================
b.lintel_ns("stripe_s", 3, 1.0, 1, STRIPE)
b.lintel_ns("stripe_n", 3, 2.0, 1, STRIPE)
b.flat_rect("roof", 3, 1, 2.0, BODY)

# =================================================================
# 5. 玻璃与警灯: 前挡风 / 后窗 / 车鼻 45 度斜披 + 车顶红警灯
# =================================================================
b.place_edge("windshield", "square", 0,
             (3.0, 1.0, 2.0), (3.0, 2.0, 2.0), (-0.707107, 0.0, -0.707107),
             GLASS)
b.place_edge("rear_glass", "square", 0,
             (5.0, 1.0, 2.0), (5.0, 2.0, 2.0), (0.707107, 0.0, -0.707107),
             GLASS)
b.place_edge("nose", "square", 0,
             (1.0, 1.0, 1.0), (1.0, 2.0, 1.0), (-0.707107, 0.0, -0.707107),
             GLASS)
b.crest_ew("beacon", 3.0, 1, 2.0, LIGHT)

# =================================================================
# 6. 临检岗亭 [5,7]x[3,4] (z0..1): 门框方岗门 + 窗格方值班窗
# =================================================================
b.add("bo_door", "door_frame", (5.5, 3.0, 0.5), (90, 0, 0), BOOTH)
b.add("bo_win", "window_square", (6.5, 3.0, 0.5), (90, 0, 0), "clear")
b.wall_ew("bo_w", 5.0, 3, 0, BOOTH)
b.wall_ew("bo_e", 7.0, 3, 0, BOOTH)
b.wall_ns("bo_n0", 5, 4.0, 0, BOOTH)
b.wall_ns("bo_n1", 6, 4.0, 0, BOOTH)
b.flat("bo_r0", 5, 3, 1.0, "clear")
b.flat("bo_r1", 6, 3, 1.0, "clear")
b.crest_ew("bo_crest", 6.0, 3, 1.0, LIGHT)

# =================================================================
# 7. 街景: 拦截桩 / 雪糕筒 / 路灯 / 告示牌
# =================================================================
b.crest_ns("bar_a", 2, 3.0, 0.0, "red")
b.crest_ns("bar_b", 3, 3.0, 0.0, "clear")
b.crest_ns("cone_a", 6, 2.0, 0.0, "orange")
b.crest_ns("cone_b", 7, 2.0, 0.0, "orange")
b.spire_ns("lamp", 4, 4.0, 0.0, "yellow")
b.wall_ns("sign", 7, 4.0, 0, "clear")
b.crest_ns("sign_top", 7, 4.0, 1.0, "red")

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "南车道: 方板+长板+长板+方板 x3 铺出第一排路面, 长板拼缝"
    "正好落在 x=1~3 与 3~5 —— 车轮底座马上要吸在这两条缝上。",
    ["r0_a", "r0_b", "r0_c", "r0_d", "r0_e", "r0_f"],
    tip="长板放准了, 后面的轮子才有整边可吸。",
)
b.step(
    "临检车道: 同样的板序再铺一排 —— 警车就停这排接受检查。",
    ["r1_a", "r1_b", "r1_c", "r1_d", "r1_e", "r1_f"],
    highlight=["r0_b", "r0_c"],
)
b.step(
    "北车道: 两块白色导流格镶在 x=2~4, 其余用灰色长板补齐。",
    ["r2_a", "r2_b", "r2_c", "r2_d", "r2_e"],
    highlight=["r1_a", "r1_f"],
    tip="白色导流格的北边是拦截桩的落脚点。",
)
b.step(
    "人行道: 西段两块橙色长砖, 东段 x=4~8 改用四块方砖 —— "
    "岗亭与告示牌都要立在方砖的格边上。",
    ["wk_a", "wk_b", "wk_c", "wk_d", "wk_e", "wk_f"],
    highlight=["r2_b", "r2_e"],
)
b.step(
    "四只车轮: 前对吸 x=1~3 拼缝, 后对吸 x=3~5 拼缝, 分别立在 "
    "y=1 与 y=2 线上 —— 车轮底座一片顶两格, 底边整边咬住路缝。",
    ["wb_fs", "wb_fn", "wb_rs", "wb_rn"],
    highlight=["r0_b", "r1_c"],
    tip="轮顶 (z=1) 稍后要托起整个车身。",
)
b.step(
    "车身三段: 发动机盖长板压前轮顶, 座舱底板长板压后轮顶, "
    "后备箱方板短边吸座舱底板东端。",
    ["hood", "cabin_floor", "trunk"],
    highlight=["wb_fs", "wb_rn"],
    tip="长板长边与轮顶整边等长贴合 —— 力全部直落车轮。",
)
b.step(
    "蓝色警条: 两条整片长方形竖立在座舱两侧, 底边同时吸住"
    "轮组顶边与座舱底板长边。",
    ["stripe_s", "stripe_n"],
    highlight=["cabin_floor", "wb_rs"],
    tip="警条就是座舱墙 —— 白车身蓝警条, 一眼认出警车。",
)
b.step(
    "车顶: 白色长板盖上 z=2, 两条长边整边压住南北警条顶。",
    ["roof"],
    highlight=["stripe_s", "stripe_n"],
    tip="轮组+警条+车顶锁成箱形环, 这就是车身的刚度。",
)
b.step(
    "玻璃: 前挡风从车顶西沿 45 度斜披向发动机盖, 后窗从东沿"
    "斜披向后备箱, 车鼻再从机盖前缘斜披一片 —— 轿车轮廓出来了。",
    ["windshield", "rear_glass", "nose"],
    highlight=["roof", "hood"],
    tip="每片玻璃 30g, 远低于悬挂预算 —— 稳稳挂住。",
)
b.step(
    "车顶警灯: 红色等边三角立上车顶前沿短边 —— 嘀嘟嘀嘟!",
    ["beacon"],
    highlight=["roof"],
    tip="三角重心正压铰链线, 力臂为零。",
)
b.step(
    "岗亭正面: 门框方岗门 + 窗格方值班窗立在人行道 y=3 格边上。",
    ["bo_door", "bo_win"],
    highlight=["wk_d", "wk_e"],
)
b.step(
    "岗亭两侧: 东西两片蓝色方墙立起, 竖边与正面墙互吸。",
    ["bo_w", "bo_e"],
    highlight=["bo_door", "bo_win"],
)
b.step(
    "岗亭背面: 北墙两片立在人行道北缘, 四面墙锁成方环。",
    ["bo_n0", "bo_n1"],
    highlight=["bo_w", "bo_e"],
)
b.step(
    "岗亭顶: 两片白色方板盖上 z=1, 四边压住墙顶; 屋脊中缝"
    "再立一片红色警徽三角。",
    ["bo_r0", "bo_r1", "bo_crest"],
    highlight=["bo_n0", "bo_n1"],
)
b.step(
    "临检通道: 红白拦截桩立在导流格北边, 两只橙色雪糕筒"
    "在车尾后方收窄车道。",
    ["bar_a", "bar_b", "cone_a", "cone_b"],
    highlight=["r2_b", "r1_e"],
    tip="三角底边整边吸方板格边 —— 摆得正才立得稳。",
)
b.step(
    "街景收尾: 黄色路灯立在人行道北缘, 告示牌方板戴红顶 —— "
    "前方临检, 请减速慢行!",
    ["lamp", "sign", "sign_top"],
    highlight=["wk_c", "wk_f"],
)

b.finalize(
    model_id="police_car_01",
    name="警车",
    name_en="Police Car 01",
    description=(
        "全库第一辆轿车轮廓的载具: 前后两对车轮底座托起三段式车身 "
        "(发动机盖长板 / 座舱 / 后备箱方板), 南北两条蓝色警条整片"
        "竖放 —— 底边整边同时吸轮组顶与底盘长边, 车顶长板再把它们"
        "锁成箱形环; 前挡风、后窗与车鼻三片 45 度斜披勾出轿车流线, "
        "车顶前沿立红色警灯。人行道上门框方岗门、窗格方值班窗的"
        "临检岗亭, 配红白拦截桩与雪糕筒围出临检通道 —— 前方临检, "
        "请减速慢行!"
    ),
    difficulty=3,
    tags=["警车", "城市", "载具", "职业体验", "车轮底座"],
    min_pieces=50,
    min_steps=16,
)
