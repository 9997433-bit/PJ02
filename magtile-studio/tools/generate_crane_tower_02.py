#!/usr/bin/env python3
"""生成模型 data/models/crane_tower_02.json (双塔井架提升机)。

建筑/工地主题: 与独柱悬臂塔吊 crane_tower_01 (拉杆三角 + 平衡配重)
刻意区分 —— 本作的主角是 "楼-塔-桥" 这组附着提升系统: 西侧一栋
2x2 双层在建小楼 (门框方大门 + 窗格方窗洞 + 两层满铺楼板), 中部
1x1 井架主塔直上 3 格并用附墙板与小楼二层锁成刚性环, 东侧再立
一座 1x1 窗格井架副塔; 塔顶天桥长板双端简支横跨两塔, 桥缝下倒挂
等腰吊钩 —— 物料就从这条天桥吊进小楼。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 工地地坪 7x4 (x [0,7], y [0,4]): 长板方板混铺              18 片
  - 在建小楼 (x [1,3], y [1,3], z 0..2): 两层墙环 x16 (含门框方
    与窗格方) + 两层满铺楼板 x8                                 24 片
  - 井架主塔 (x [4,5], y [1,2], z 0..3): 三层墙环 x12 + 根部
    直角护撑 x2 + 塔顶台板 x1                                  15 片
  - 附墙板: 小楼二层楼板与主塔间的水平锁板 x1                    1 片
  - 井架副塔 (x [6,7], y [1,2], z 0..3): 三层窗格墙环 x12       12 片
  - 塔顶天桥: 双桥板对缝互吸跨 [5,7] x2 + 倒挂等腰吊钩 x1        3 片
  - 工地场景: 钢筋捆高塔尖 x1 + 南侧围挡 x1                      2 片
  合计 75 片, 16 个教程步骤, 7 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点:
  - 附墙板西边吸小楼二层楼板东沿与二层墙顶, 东边吸主塔二层墙顶
    与三层墙底 —— 楼、塔从两个独立柱体锁成一个大环;
  - 天桥西板整边吸主塔台板东沿, 东板四边压副塔墙顶, 两板对缝
    互吸 —— 双端简支, 剪断任何一条铰链线力都能绕行;
  - 吊钩倒挂在天桥南长边的跨中段正下方, 纯受拉零力矩;
  - 主塔根部一对直角护撑分别咬地坪拼缝与塔身竖棱, 锁死塔根。

用法: python3 tools/generate_crane_tower_02.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

PAD = "gray"        # 工地地坪
LAWN = "green"      # 北侧绿化带
BUILDING = "cyan"   # 在建小楼墙体
DOOR = "blue"       # 门框方大门
WIN = "clear"       # 窗格方窗洞
DECK = "gray"       # 楼板 / 塔顶台板
MAST = "orange"     # 井架主塔
LATTICE = "clear"   # 井架格构面
BRACE = "red"       # 根部护撑
TIE = "yellow"      # 附墙板 / 塔顶台板
HOIST = "gray"      # 井架副塔
BRIDGE = "gray"     # 塔顶天桥
HOOK = "yellow"     # 吊钩
REBAR = "gray"      # 钢筋捆
FENCE = "yellow"    # 围挡

# =================================================================
# 1. 工地地坪 7x4 (x [0,7], y [0,4]): 小楼行多用单格方板留拼缝
# =================================================================
b.flat_rect("gd0_a", 0, 0, 0.0, PAD)
b.flat_rect("gd0_b", 2, 0, 0.0, PAD)
b.flat_rect("gd0_c", 4, 0, 0.0, PAD)
b.flat("gd0_d", 6, 0, 0.0, PAD)
b.flat("gd1_a", 0, 1, 0.0, PAD)
b.flat_rect("gd1_b", 1, 1, 0.0, PAD)
b.flat("gd1_c", 3, 1, 0.0, PAD)
b.flat("gd1_d", 4, 1, 0.0, "yellow")
b.flat("gd1_e", 5, 1, 0.0, PAD)
b.flat("gd1_f", 6, 1, 0.0, "yellow")
b.flat("gd2_a", 0, 2, 0.0, PAD)
b.flat_rect("gd2_b", 1, 2, 0.0, PAD)
b.flat_rect("gd2_c", 3, 2, 0.0, PAD)
b.flat_rect("gd2_d", 5, 2, 0.0, PAD)
b.flat_rect("gd3_a", 0, 3, 0.0, LAWN)
b.flat_rect("gd3_b", 2, 3, 0.0, LAWN)
b.flat_rect("gd3_c", 4, 3, 0.0, LAWN)
b.flat("gd3_d", 6, 3, 0.0, LAWN)

# =================================================================
# 2. 在建小楼第一层 (x [1,3], y [1,3], z 0..1): 门框方开在南面
# =================================================================
b.add("bd1_door", "door_frame", (1.5, 1.0, 0.5), (90, 0, 0), DOOR)
b.wall_ns("bd1_s2", 2, 1.0, 0, BUILDING)
b.wall_ew("bd1_w1", 1.0, 1, 0, BUILDING)
b.wall_ew("bd1_w2", 1.0, 2, 0, BUILDING)
b.wall_ns("bd1_n1", 1, 3.0, 0, BUILDING)
b.wall_ns("bd1_n2", 2, 3.0, 0, BUILDING)
b.wall_ew("bd1_e1", 3.0, 1, 0, BUILDING)
b.wall_ew("bd1_e2", 3.0, 2, 0, BUILDING)
for x in (1, 2):
    for y in (1, 2):
        b.flat(f"bd1_f_{x}_{y}", x, y, 1.0, DECK)

# =================================================================
# 3. 在建小楼第二层 (z 1..2): 南/西窗格方窗洞, 顶层满铺楼板
# =================================================================
b.add("bd2_s1", "window_square", (1.5, 1.0, 1.5), (90, 0, 0), WIN)
b.add("bd2_s2", "window_square", (2.5, 1.0, 1.5), (90, 0, 0), WIN)
b.wall_ew("bd2_w1", 1.0, 1, 1, BUILDING)
b.add("bd2_w2", "window_square", (1.0, 2.5, 1.5), (90, 0, 90), WIN)
b.wall_ns("bd2_n1", 1, 3.0, 1, BUILDING)
b.wall_ns("bd2_n2", 2, 3.0, 1, BUILDING)
b.wall_ew("bd2_e1", 3.0, 1, 1, BUILDING)
b.wall_ew("bd2_e2", 3.0, 2, 1, BUILDING)
for x in (1, 2):
    for y in (1, 2):
        b.flat(f"bd2_f_{x}_{y}", x, y, 2.0, DECK)

# =================================================================
# 4. 井架主塔 (x [4,5], y [1,2], z 0..3): 三层墙环 + 根部护撑 + 台板
# =================================================================
for lv in range(3):
    b.wall_ns(f"mast{lv}_s", 4, 1.0, lv, MAST)
    b.wall_ns(f"mast{lv}_n", 4, 2.0, lv, MAST)
    b.wall_ew(f"mast{lv}_w", 4.0, 1, lv, LATTICE)
    b.wall_ew(f"mast{lv}_e", 5.0, 1, lv, LATTICE)
b.brace("mast_brace_w", (4.0, 1.0, 0.0), "-x", BRACE)
b.brace("mast_brace_e", (5.0, 1.0, 0.0), "+x", BRACE)
b.flat("mast_deck", 4, 1, 3.0, TIE)

# =================================================================
# 5. 附墙板 (x [3,4], y [1,2], z=2): 把小楼二层与主塔锁成大环
# =================================================================
b.flat("tie_beam", 3, 1, 2.0, TIE)

# =================================================================
# 6. 井架副塔 (x [6,7], y [1,2], z 0..3): 三层窗格墙环
# =================================================================
for lv in range(3):
    b.add(f"hoist{lv}_s", "window_square", (6.5, 1.0, lv + 0.5), (90, 0, 0), HOIST)
    b.add(f"hoist{lv}_n", "window_square", (6.5, 2.0, lv + 0.5), (90, 0, 0), HOIST)
    b.wall_ew(f"hoist{lv}_w", 6.0, 1, lv, LATTICE)
    b.wall_ew(f"hoist{lv}_e", 7.0, 1, lv, LATTICE)

# =================================================================
# 7. 塔顶天桥 (x [5,7], y [1,2], z=3) + 倒挂吊钩
# =================================================================
b.flat("bridge_w", 5, 1, 3.0, BRIDGE)
b.flat("bridge_e", 6, 1, 3.0, BRIDGE)
b.place_edge("hook", "isosceles_triangle", 0,
             (5.0, 1.0, 3.0), (6.0, 1.0, 3.0), (0, 0, -1), HOOK)

# =================================================================
# 8. 工地场景: 钢筋捆 + 南侧围挡
# =================================================================
b.spire_ns("rebar", 0, 3.0, 0.0, REBAR)
b.crest_ns("fence_a", 6, 0.0, 0.0, FENCE)

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺地坪南半 (y [0,2]): 10 片长板方板混铺, 小楼行多用单格方板留拼缝。",
    ["gd0_a", "gd0_b", "gd0_c", "gd0_d",
     "gd1_a", "gd1_b", "gd1_c", "gd1_d", "gd1_e", "gd1_f"],
    tip="黄色两格标出主塔与副塔的塔位 —— 塔身墙都要吸在它们的拼缝上。",
)
b.step(
    "铺地坪北半 (y [2,4]): 8 片, 北排是绿化带, 地坪合拢成 7x4。",
    ["gd2_a", "gd2_b", "gd2_c", "gd2_d",
     "gd3_a", "gd3_b", "gd3_c", "gd3_d"],
    highlight=["gd1_a"],
    tip="西侧大块地坪是小楼的地基, 每条拼缝都是墙的吸附线。",
)
b.step(
    "砌小楼第一层南墙与西墙: 门框方大门开在南面, 共 4 片。",
    ["bd1_door", "bd1_s2", "bd1_w1", "bd1_w2"],
    highlight=["gd1_b", "gd2_a"],
    tip="门框方外框与正方形完全一致 —— 底边吸缝、竖边咬邻片。",
)
b.step(
    "砌小楼第一层北墙与东墙: 4 片, 首层墙环闭合。",
    ["bd1_n1", "bd1_n2", "bd1_e1", "bd1_e2"],
    highlight=["bd1_door", "bd1_w2"],
    tip="闭合环墙天生抗扭 —— 轻推应整体联动。",
)
b.step(
    "铺一层楼板: 4 片方板压墙顶, 每片同时吸两段墙顶与邻板拼缝。",
    ["bd1_f_1_1", "bd1_f_2_1", "bd1_f_1_2", "bd1_f_2_2"],
    highlight=["bd1_s2", "bd1_n1"],
    tip="楼板就是第二层的新地面。",
)
b.step(
    "砌小楼第二层南墙与西墙: 三扇窗格方窗洞朝南朝西, 共 4 片。",
    ["bd2_s1", "bd2_s2", "bd2_w1", "bd2_w2"],
    highlight=["bd1_f_1_1"],
    tip="窗洞对着工地大门 —— 施工员从这里看吊装。",
)
b.step(
    "砌小楼第二层北墙与东墙: 4 片, 二层墙环闭合。",
    ["bd2_n1", "bd2_n2", "bd2_e1", "bd2_e2"],
    highlight=["bd2_s1", "bd2_w1"],
    tip="东墙顶就是附墙板的西支点 —— 先把环砌牢。",
)
b.step(
    "铺二层楼板: 4 片方板封顶, 在建小楼两层成形。",
    ["bd2_f_1_1", "bd2_f_2_1", "bd2_f_1_2", "bd2_f_2_2"],
    highlight=["bd2_n2", "bd2_e1"],
    tip="楼板东沿留给附墙板 —— 塔一会儿就锁在这里。",
)
b.step(
    "立主塔第一层并锁塔根: 4 片墙围成 1x1 井架, 2 片红色直角护撑"
    "分别咬地坪拼缝与塔身竖棱。",
    ["mast0_s", "mast0_n", "mast0_w", "mast0_e",
     "mast_brace_w", "mast_brace_e"],
    highlight=["gd1_d"],
    tip="护撑东西对置, 塔根从此纹丝不动。",
)
b.step(
    "叠主塔第二层 + 装附墙板: 4 片墙对缝上叠, 黄色附墙板西吸楼板"
    "东沿、东吸塔身墙顶。",
    ["mast1_s", "mast1_n", "mast1_w", "mast1_e", "tie_beam"],
    highlight=["bd2_f_2_1", "mast0_s"],
    tip="附墙板把楼与塔锁成一个大环 —— 这是附着式井架的关键一手。",
)
b.step(
    "叠主塔第三层 + 盖塔顶台板: 塔身到 3 格高, 黄色台板四边压墙顶。",
    ["mast2_s", "mast2_n", "mast2_w", "mast2_e", "mast_deck"],
    highlight=["mast1_s", "tie_beam"],
    tip="台板东沿是天桥的西支点。",
)
b.step(
    "立副塔第一层: 4 片窗格墙围成东侧井架。",
    ["hoist0_s", "hoist0_n", "hoist0_w", "hoist0_e"],
    highlight=["gd1_f"],
    tip="窗格方就是井架的格构面 —— 透过它能看见吊笼上下。",
)
b.step(
    "叠副塔第二层: 4 片, 竖缝与下层对齐。",
    ["hoist1_s", "hoist1_n", "hoist1_w", "hoist1_e"],
    highlight=["hoist0_s"],
    tip="每层都是闭环, 井架天生是根方管。",
)
b.step(
    "叠副塔第三层: 副塔与主塔齐高, 双塔对望。",
    ["hoist2_s", "hoist2_n", "hoist2_w", "hoist2_e"],
    highlight=["hoist1_s"],
    tip="下一步天桥就要横跨这两座塔。",
)
b.step(
    "架塔顶天桥 + 倒挂吊钩: 西桥板吸台板东沿, 东桥板四边压副塔墙顶, "
    "黄色等腰吊钩倒挂在跨中桥板的南沿正下方。",
    ["bridge_w", "bridge_e", "hook"],
    highlight=["mast_deck", "hoist2_s"],
    tip="双端简支加对缝互吸 —— 剪断任何一条铰链线, 力都能绕行; 吊钩纯受拉零力矩。",
)
b.step(
    "布工地场景: 钢筋捆高塔尖立在西北拼缝, 黄色围挡立在南门口 "
    "—— 双塔井架开工!",
    ["rebar", "fence_a"],
    highlight=["gd3_a", "gd0_d"],
    tip="仰头看: 楼、塔、桥锁成一体 —— 这就是附着式提升机的骨架。",
)

b.finalize(
    model_id="crane_tower_02",
    name="双塔井架提升机",
    name_en="Tower Crane 02",
    description=(
        "建筑/工地主题: 与独柱悬臂塔吊完全不同的附着式提升系统 —— "
        "西侧 2x2 双层在建小楼 (门框方大门 + 窗格方窗洞 + 两层满铺"
        "楼板), 中部 1x1 井架主塔直上 3 格, 黄色附墙板把楼与塔锁成"
        "刚性大环, 根部一对直角护撑咬死塔根; 东侧再立 1x1 三层窗格"
        "井架副塔, 塔顶天桥长板双端简支横跨双塔、长边四点搭接, "
        "桥缝下倒挂等腰吊钩纯受拉零力矩。楼-塔-桥连成一体, 物料"
        "沿天桥直送楼顶 —— 一台会讲结构课的井架提升机。"
    ),
    difficulty=3,
    tags=["工程", "塔吊", "井架", "在建小楼", "挑战"],
    min_pieces=75,
    min_steps=16,
)
