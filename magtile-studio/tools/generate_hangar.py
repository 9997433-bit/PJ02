#!/usr/bin/env python3
"""生成模型 data/models/hangar_01.json (飞机维修机库)。

机场航空主题 4/4: 全库第一座宽门维修机库 —— 与 warehouse_01
(三排墙列双跨屋面)、fire_station_01 (双门楣车库 + 瞭望塔)、
farm_barn_01 (60 度人字坡) 刻意区分: 机库正面是一道 4 格宽的
无柱大门洞 —— 三段长板门梁在洞口上方首尾竖边纯剪接力 (中段
悬在门洞正上, 重力平行竖直铰链轴力矩为零), 两端压进门垛;
平屋面正中再升起一条透明采光脊 (高侧窗天窗环 + 压顶 + 双排
风锥), 库内车轮底座牵引车与金色油桶垛趁封顶前就位, 场外
风向袋与滑行引导标点齐机务作业 —— 大门常开, 随时进机!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 大门朝南):
  - 场坪 8x5 (x [0,8], y [0,5]): 长板为主, 库内嵌牵引车
    车轮底座与油桶地格                                         25 片
  - 门垛 (z 0..1): 立墙 x2 (x [1,2] 与 [6,7])                   2 片
  - 门梁 (z 1..2): 长板 x3 (中段双端竖边纯剪, 洞口 4 格无柱)     3 片
  - 侧墙 (x=1 / x=7): 底层立墙 x3 + 上层窗格方带 x3, 每侧 6 片  12 片
  - 后墙 (y=5): 底层长楣/立墙/门框方检修门 x5 + 上层长楣 x3      8 片
  - 平屋面 (z=2): 长板 x9 (三行, 每行 3 片)                      9 片
  - 采光脊 (x [3,5], z 2..3): 透明长板 x2 + 透明端墙 x2 +
    长板压顶 x1 + 排风锥等边 x2                                  7 片
  - 库内设备: 油桶等边四坡垛 x4 + 牵引车驾驶棚 x1                5 片
  - 风向袋等腰 x1 + 滑行引导标等边 x2                            3 片
  合计 74 片, 14 个教程步骤, 7 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, strict 档同样全绿):
  - 门梁中段两端竖边分别吸进东西段门梁竖棱 (纯剪传力): 重力
    平行竖直铰链轴, 绕轴力矩为零; 剪断任一端仍经另一端绕行;
  - 屋面前排南长边整边压门梁顶, 后排压后墙长楣顶, 每片同时
    咬侧墙顶/邻板拼缝 —— 门式框架处处成环;
  - 采光脊骑屋面拼缝 (底边与屋面板整边等长贴合), 压顶再锁环,
    排风锥底边同吸压顶短边与端墙顶边;
  - 油桶垛与牵引车都在地面层、大门 4 格常开 —— R7b 装配可达
    天然满足; 高层 R8 单条连接剪断均可绕行。

用法: python3 tools/generate_hangar.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

APRON = "gray"      # 场坪
FLOOR = "gray"      # 库内地坪
MARK = "yellow"     # 滑行标线
PIER = "orange"     # 门垛
BEAM = "orange"     # 门梁
WALL = "blue"       # 侧墙 / 后墙
WIN = "clear"       # 窗格方带
DOOR = "yellow"     # 检修门
ROOF = "gray"       # 平屋面
SKY = "clear"       # 采光脊
CAPC = "blue"       # 采光脊压顶
VENT = "orange"     # 排风锥
DRUM = "yellow"     # 油桶垛
TUG = "red"         # 牵引车
SOCK = "orange"     # 风向袋
GUIDE = "yellow"    # 引导标

# =================================================================
# 1. 场坪 8x5 (x [0,8], y [0,5]): 库区 y [2,5], 门前坪 y [0,2]
# =================================================================
b.flat_rect("a0_a", 0, 0, 0.0, APRON)
b.flat_rect("a0_b", 2, 0, 0.0, MARK)    # 进港滑行标线
b.flat_rect("a0_c", 4, 0, 0.0, MARK)
b.flat("a0_d", 6, 0, 0.0, APRON)
b.flat("a0_e", 7, 0, 0.0, APRON)

b.flat_rect("a1_a", 0, 1, 0.0, APRON)
b.flat_rect("a1_b", 2, 1, 0.0, APRON)
b.flat_rect("a1_c", 4, 1, 0.0, APRON)
b.flat_rect("a1_d", 6, 1, 0.0, APRON)

b.flat("f2_a", 0, 2, 0.0, APRON)
b.flat_rect("f2_b", 1, 2, 0.0, FLOOR)
b.flat_rect("f2_c", 3, 2, 0.0, FLOOR)
b.flat_rect("f2_d", 5, 2, 0.0, FLOOR)
b.flat("f2_e", 7, 2, 0.0, APRON)

b.flat("f3_a", 0, 3, 0.0, APRON)
b.flat_rect("f3_b", 1, 3, 0.0, FLOOR)
b.add("tug", "wheel_base", (4.0, 3.5, 0.0), (0, 0, 0), TUG)  # 牵引车 x [3,5]
b.flat("f3_c", 5, 3, 0.0, FLOOR)        # 油桶地格
b.flat("f3_d", 6, 3, 0.0, FLOOR)
b.flat("f3_e", 7, 3, 0.0, APRON)

b.flat("f4_a", 0, 4, 0.0, APRON)
b.flat_rect("f4_b", 1, 4, 0.0, FLOOR)
b.flat_rect("f4_c", 3, 4, 0.0, FLOOR)
b.flat_rect("f4_d", 5, 4, 0.0, FLOOR)
b.flat("f4_e", 7, 4, 0.0, APRON)

# =================================================================
# 2. 库内设备: 油桶垛 + 牵引车驾驶棚 (趁大门方向敞开先就位)
# =================================================================
DRUM_IDS = b.hat4("drum", 5, 3, 0.0, DRUM, shape="equilateral_triangle")
b.crest_ew("tug_cab", 3.0, 3, 0.0, TUG)

# =================================================================
# 3. 门垛 (z 0..1) + 侧墙底层 + 后墙底层
# =================================================================
b.wall_ns("pier_w", 1, 2.0, 0, PIER)
b.wall_ns("pier_e", 6, 2.0, 0, PIER)

b.wall_ew("sw_1", 1.0, 2, 0, WALL)
b.wall_ew("sw_2", 1.0, 3, 0, WALL)
b.wall_ew("sw_3", 1.0, 4, 0, WALL)
b.wall_ew("se_1", 7.0, 2, 0, WALL)
b.wall_ew("se_2", 7.0, 3, 0, WALL)
b.wall_ew("se_3", 7.0, 4, 0, WALL)

b.lintel_ns("rw_1", 1, 5.0, 0, WALL)
b.wall_ns("rw_2", 3, 5.0, 0, WALL)
b.add("rw_door", "door_frame", (4.5, 5.0, 0.5), (90, 0, 0), DOOR)
b.wall_ns("rw_3", 5, 5.0, 0, WALL)
b.wall_ns("rw_4", 6, 5.0, 0, WALL)

# =================================================================
# 4. 上层: 窗格方带 + 门梁 (纯剪接力) + 后墙长楣
# =================================================================
b.add("swin_1", "window_square", (1.0, 2.5, 1.5), (90, 0, 90), WIN)
b.add("swin_2", "window_square", (1.0, 3.5, 1.5), (90, 0, 90), WIN)
b.add("swin_3", "window_square", (1.0, 4.5, 1.5), (90, 0, 90), WIN)
b.add("sein_1", "window_square", (7.0, 2.5, 1.5), (90, 0, 90), WIN)
b.add("sein_2", "window_square", (7.0, 3.5, 1.5), (90, 0, 90), WIN)
b.add("sein_3", "window_square", (7.0, 4.5, 1.5), (90, 0, 90), WIN)

b.lintel_ns("beam_w", 1, 2.0, 1, BEAM)
b.lintel_ns("beam_e", 5, 2.0, 1, BEAM)
b.lintel_ns("beam_m", 3, 2.0, 1, BEAM)   # 中段: 双端竖边纯剪

b.lintel_ns("rt_1", 1, 5.0, 1, WALL)
b.lintel_ns("rt_2", 3, 5.0, 1, WALL)
b.lintel_ns("rt_3", 5, 5.0, 1, WALL)

# =================================================================
# 5. 平屋面 (z=2): 三行长板
# =================================================================
b.flat_rect("rf_s1", 1, 2, 2.0, ROOF)
b.flat_rect("rf_s2", 3, 2, 2.0, ROOF)
b.flat_rect("rf_s3", 5, 2, 2.0, ROOF)
b.flat_rect("rf_m1", 1, 3, 2.0, ROOF)
b.flat_rect("rf_m2", 3, 3, 2.0, ROOF)
b.flat_rect("rf_m3", 5, 3, 2.0, ROOF)
b.flat_rect("rf_n1", 1, 4, 2.0, ROOF)
b.flat_rect("rf_n2", 3, 4, 2.0, ROOF)
b.flat_rect("rf_n3", 5, 4, 2.0, ROOF)

# =================================================================
# 6. 采光脊 (x [3,5], y [3,4], z 2..3) + 排风锥
# =================================================================
b.lintel_ns("sky_s", 3, 3.0, 2, SKY)
b.lintel_ns("sky_n", 3, 4.0, 2, SKY)
b.wall_ew("sky_w", 3.0, 3, 2, SKY)
b.wall_ew("sky_e", 5.0, 3, 2, SKY)
b.flat_rect("sky_cap", 3, 3, 3.0, CAPC)
b.crest_ew("vent_w", 3.0, 3, 3.0, VENT)
b.crest_ew("vent_e", 5.0, 3, 3.0, VENT)

# =================================================================
# 7. 风向袋 + 滑行引导标
# =================================================================
b.spire_ns("windsock", 7, 1.0, 0.0, SOCK)
b.crest_ew("guide_w", 2.0, 0, 0.0, GUIDE)
b.crest_ew("guide_e", 6.0, 0, 0.0, GUIDE)

# =================================================================
# 教程步骤 (14 步)
# =================================================================
b.step(
    "铺门前坪 (y [0,2]): 9 片, 黄色长板是进港滑行标线。",
    ["a0_a", "a0_b", "a0_c", "a0_d", "a0_e", "a1_a", "a1_b", "a1_c", "a1_d"],
    tip="标线正对 4 格大门 —— 飞机将顺着它滑进机库。",
)
b.step(
    "铺库内地坪前两行 (y [2,4]): 11 片, 红色车轮底座是牵引车。",
    ["f2_a", "f2_b", "f2_c", "f2_d", "f2_e",
     "f3_a", "f3_b", "tug", "f3_c", "f3_d", "f3_e"],
    highlight=["a1_b"],
    tip="牵引车与油桶地格嵌进地坪 —— 库内设备天生与场坪一体。",
)
b.step(
    "铺库内地坪后行 (y [4,5]): 5 片, 8x5 场坪合拢。",
    ["f4_a", "f4_b", "f4_c", "f4_d", "f4_e"],
    highlight=["f3_b"],
    tip="后墙与侧墙的底边都踩这几条拼缝。",
)
b.step(
    "库内设备就位: 金色油桶垛四棱自锁 + 牵引车驾驶棚。",
    DRUM_IDS + ["tug_cab"],
    highlight=["f3_c", "tug"],
    tip="大门方向永远敞开, 但先装内部再起高墙是好习惯。",
)
b.step(
    "立门垛与侧墙底层: 2 片门垛 + 每侧 3 片立墙。",
    ["pier_w", "sw_1", "sw_2", "sw_3", "pier_e", "se_1", "se_2", "se_3"],
    highlight=["f2_b", "f2_d"],
    tip="门垛在 x [1,2] 与 [6,7] —— 中间 4 格全部留给大门。",
)
b.step(
    "砌后墙底层: 长楣 + 立墙 + 门框方检修门。",
    ["rw_1", "rw_2", "rw_door", "rw_3", "rw_4"],
    highlight=["f4_b"],
    tip="检修门是人走的小门, 竖边与邻墙互吸成排。",
)
b.step(
    "装侧墙窗格方带: 每侧 3 片高侧窗。",
    ["swin_1", "swin_2", "swin_3", "sein_1", "sein_2", "sein_3"],
    highlight=["sw_1", "se_1"],
    tip="窗带底边整边压底层墙顶 —— 机库里白天不用开灯。",
)
b.step(
    "架门梁: 东西段先压门垛, 中段双端竖边纯剪接力。",
    ["beam_w", "beam_e", "beam_m"],
    highlight=["pier_w", "pier_e", "swin_1"],
    tip="中段悬在门洞正上: 重力平行竖直铰链轴, 力矩为零纯剪传力。",
)
b.step(
    "砌后墙上层: 3 片长楣一线排开。",
    ["rt_1", "rt_2", "rt_3"],
    highlight=["rw_1"],
    tip="长楣竖缝首尾互吸, 与侧窗带同高合圈。",
)
b.step(
    "盖屋面前排 (y [2,3]): 3 片长板南长边整边压门梁顶。",
    ["rf_s1", "rf_s2", "rf_s3"],
    highlight=["beam_w", "beam_m"],
    tip="屋面板一头压门梁、一头等中排来咬 —— 门式框架开始闭环。",
)
b.step(
    "盖屋面中排与后排: 6 片, 后排北长边压后墙长楣顶。",
    ["rf_m1", "rf_m2", "rf_m3", "rf_n1", "rf_n2", "rf_n3"],
    highlight=["rf_s2", "rt_2"],
    tip="每片同时咬侧墙顶与邻板拼缝, 大平屋面锁成整体。",
)
b.step(
    "起采光脊: 透明长板骑屋面拼缝, 端墙封口。",
    ["sky_s", "sky_n", "sky_w", "sky_e"],
    highlight=["rf_s2", "rf_m2"],
    tip="采光脊底边与屋面板整边等长贴合, 四角竖边互吸闭环。",
)
b.step(
    "压顶并立排风锥: 长板压圈 + 两只等边排风锥。",
    ["sky_cap", "vent_w", "vent_e"],
    highlight=["sky_s", "sky_n"],
    tip="排风锥底边同吸压顶短边与端墙顶边 —— 一线双吸。",
)
b.step(
    "立风向袋与滑行引导标 —— 维修机库开工!",
    ["windsock", "guide_w", "guide_e"],
    highlight=["a0_b", "a0_c"],
    tip="风向袋告诉机务今天的风, 引导标指着大门的方向。",
)

b.finalize(
    model_id="hangar_01",
    name="飞机维修机库",
    name_en="Aircraft Hangar 01",
    description=(
        "全库第一座宽门维修机库: 正面 4 格宽无柱大门洞 —— 三段长板门梁"
        "首尾竖边纯剪接力 (中段悬在门洞正上, 重力平行竖直铰链轴力矩为零,"
        " 剪断任一端仍经另一端绕行), 两端压进门垛; 侧墙上层整圈窗格方"
        "高侧窗带, 后墙嵌门框方检修门; 平屋面九片长板压门梁/后墙长楣/"
        "侧窗带合成门式框架, 正中升起透明采光脊 (压顶锁环 + 双排风锥"
        "一线双吸); 库内车轮底座牵引车与金色油桶垛趁封顶前就位, 场外"
        "风向袋与滑行引导标点齐机务作业 —— 高层 R8 处处成环。"
    ),
    difficulty=3,
    tags=["机场", "航空", "机库", "建筑", "进阶"],
    min_pieces=70,
    min_steps=14,
)
