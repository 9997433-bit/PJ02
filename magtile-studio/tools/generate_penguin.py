#!/usr/bin/env python3
"""生成模型 data/models/penguin_01.json (帝企鹅一家)。

自然世界主题: 全库第一只"直立行走"的鸟类 —— 与长颈鹿 (腿柱梯架)、
剑龙 (腿柱箱体) 完全不同的塔式动物搭法: 2x1 箱形身躯用 长方形前后壁
+ 方形侧壁 的圈层直上两层 (透明前壁就是白肚皮), 双肩方板压顶后,
头颅小箱四边全吸落座 (四重连接, 无单点失效), 吻端一片橙色等边扁喙
水平收尖; 两片菱形鳍肢从冰面斜撑身侧 (60 度天然斜度), 像正要摆动;
旁边毛茸茸的灰色企鹅宝宝戴着等边四坡绒帽; 东侧一座冰台连着 30 度冰滑梯
直插水面、溅起透明浪花 —— 排队, 下水!

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 浮冰 [0,5]x[0,3] 15 + 海水 [5,7]x[0,3] 长板 x3               18 片
  - 大企鹅 [1,3]x[1,2]: 圈层身躯 x2 层 8 + 双肩方板 2 +
    头颅小箱 5 + 等边扁喙 1 + 菱形鳍肢 2                             18 片
  - 企鹅宝宝 [4,5]x[2,3]: 立墙 4 + 绒帽四棱锥 4                   8 片
  - 冰滑梯: 冰台立墙 2 + 台面 1 + 30 度滑梯 1 + 浪花 1            5 片
  - 冰景: 六边形冰山 x2 + 冰凌尖 x2 + 跃出水面的菱形小鱼 x1       5 片
  合计 54 片, 16 个教程步骤, 5 种磁力片形状 (迁移期不使用等腰片)。

物理规则要点 (通过 R1~R8 全部校验):
  - 身躯圈层: 长方形前后壁 + 方形侧壁拐角竖边互吸自锁成环,
    上环整边压下环 (长边给前后壁、短边给侧壁的长短分工);
  - 双肩用 2 片方板而非 1 片长板 —— 头颅小箱四条底边才能
    边边落吸 (四重连接), 高塔身躯没有任何单点失效;
  - 鳍肢底边吸浮冰边, 斜倚身侧 (接地斜撑); 扁喙水平悬挑
    力矩 5 <= 预算 20;
  - 滑梯顶边整边吸冰台沿, 坡尾自然落在水面上 (接地斜撑)。

用法: python3 tools/generate_penguin.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder, COS30

b = ModelBuilder()

ICE = "clear"       # 浮冰
SEA = "blue"        # 海水
BODY = "blue"       # 企鹅背羽
BELLY = "clear"     # 白肚皮
CHICK = "gray"      # 宝宝绒羽

# =================================================================
# 1. 浮冰 [0,5]x[0,3] + 海水 [5,7]x[0,3]
# =================================================================
for x in range(5):
    for y in range(3):
        b.flat(f"fl_{x}_{y}", x, y, 0.0, ICE if (x + y) % 2 == 0 else "cyan")
for y in range(3):
    b.flat_rect(f"sea_{y}", 5, y, 0.0, SEA)

# =================================================================
# 2. 大企鹅 [1,3]x[1,2]: 圈层身躯 + 双肩 + 头颅 + 扁喙 + 鳍肢
# =================================================================
for z in range(2):
    b.lintel_ns(f"pg_s_{z}", 1, 1.0, z, BELLY)      # 前壁 (白肚皮)
    b.wall_ew(f"pg_w_{z}", 1.0, 1, z, BODY)         # 西侧壁
    b.lintel_ns(f"pg_n_{z}", 1, 2.0, z, BODY)       # 后壁 (背羽)
    b.wall_ew(f"pg_e_{z}", 3.0, 1, z, BODY)         # 东侧壁
b.flat("sh_w", 1, 1, 2.0, BODY)                     # 西肩
b.flat("sh_e", 2, 1, 2.0, BODY)                     # 东肩
b.wall_ns("hd_s", 2, 1.0, 2, BELLY)                 # 头颅 (脸颊朝南)
b.wall_ew("hd_w", 2.0, 1, 2, BODY)
b.wall_ns("hd_n", 2, 2.0, 2, BODY)
b.wall_ew("hd_e", 3.0, 1, 2, BODY)
b.flat("hd_top", 2, 1, 3.0, BODY)                   # 头顶
b.place_tri("beak", "equilateral_triangle",
            (3.0, 1.0, 3.0), (3.0, 2.0, 3.0), (3.866025, 1.5, 3.0), "orange")
b.place_edge("fin_s", "rhombus", 0,
             (2.0, 1.0, 0.0), (1.0, 1.0, 0.0), (0.0, -1.0, 1.2), BODY)
b.place_edge("fin_n", "rhombus", 0,
             (1.0, 2.0, 0.0), (2.0, 2.0, 0.0), (0.0, 1.0, 1.2), BODY)

# =================================================================
# 3. 企鹅宝宝 [4,5]x[2,3]: 立墙 + 绒帽四棱锥
# =================================================================
b.wall_ns("ck_s", 4, 2.0, 0, CHICK)
b.wall_ew("ck_w", 4.0, 2, 0, CHICK)
b.wall_ns("ck_n", 4, 3.0, 0, CHICK)
b.wall_ew("ck_e", 5.0, 2, 0, CHICK)
CHICK_HAT = b.hat4("ck_hat", 4, 2, 1.0, CHICK, shape="equilateral_triangle")

# =================================================================
# 4. 冰滑梯: 冰台 [4,5]x[0,1] + 30 度滑梯直插水面 + 浪花
# =================================================================
b.wall_ew("lg_w", 4.0, 0, 0, "cyan")                # 冰台西壁
b.wall_ew("lg_e", 5.0, 0, 0, "cyan")                # 冰台东壁
b.flat("lg_top", 4, 0, 1.0, ICE)                    # 冰台台面
b.ramp("slide", "+x", 5.0, 0, 1.0, "cyan")          # 冰滑梯, 坡尾落水面
SPLASH_X = 5.0 + 2 * COS30                          # 坡尾 x = 6.73205
b.crest_ew("splash", SPLASH_X, 0, 0.0, ICE)         # 透明浪花

# =================================================================
# 5. 冰景: 六边形冰山 x2 + 冰凌尖 x2 + 跃出水面的小鱼
# =================================================================
b.place_edge("berg_w", "hexagon", 4,
             (0.0, 3.0, 0.0), (1.0, 3.0, 0.0), (0.0, 0.0, 1.0), ICE)
b.place_edge("berg_w2", "hexagon", 4,
             (0.0, 3.0, 0.0), (0.0, 2.0, 0.0), (0.0, 0.0, 1.0), ICE)
b.crest_ns("icicle_n", 2, 3.0, 0.0, ICE)            # 冰凌尖 (北沿)
b.crest_ew("icicle_w", 0.0, 0, 0.0, ICE)            # 冰凌尖 (西沿)
b.place_edge("fish", "rhombus", 0,
             (7.0, 1.0, 0.0), (7.0, 2.0, 0.0), (0.0, 0.0, 1.0), "cyan")

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺浮冰南列: [0,5]x[0,1] 铺 5 片透明青色相间方板。",
    [f"fl_{x}_0" for x in range(5)],
    tip="浮冰是全家的舞台, 透明片就是新结的亮冰。",
)
b.step(
    "铺浮冰中列: 再铺 5 片, 大企鹅将站在这一列上。",
    [f"fl_{x}_1" for x in range(5)],
    highlight=["fl_0_0"],
    tip="拼缝对齐, 冰面才平整。",
)
b.step(
    "铺浮冰北列: 5 片补齐, 浮冰成型。",
    [f"fl_{x}_2" for x in range(5)],
    highlight=["fl_0_1"],
    tip="北沿留给冰山背景 —— 一会儿它们会立起来。",
)
b.step(
    "铺海水: 浮冰东侧 3 片蓝色长板拼出海面。",
    ["sea_0", "sea_1", "sea_2"],
    highlight=["fl_4_0", "fl_4_2"],
    tip="长板短边吸浮冰边 —— 冰与海从此连成整体。",
)
b.step(
    "砌身躯第 1 层: 透明前壁 (白肚皮) + 蓝色后壁两片长方形, 加两片"
    "方形侧壁, 拐角竖边互吸自锁成环。",
    ["pg_s_0", "pg_w_0", "pg_n_0", "pg_e_0"],
    highlight=["fl_1_1", "fl_2_1"],
    tip="长边给前后壁、短边给侧壁 —— 圈层砌法的长短分工。",
)
b.step(
    "砌身躯第 2 层: 再叠一环, 上环整边压下环。",
    ["pg_s_1", "pg_w_1", "pg_n_1", "pg_e_1"],
    highlight=["pg_s_0"],
    tip="帝企鹅站起来有一米多高 —— 塔式身躯要对缝直叠。",
)
b.step(
    "压双肩: 2 片蓝色方板并排盖住身躯顶口。",
    ["sh_w", "sh_e"],
    highlight=["pg_w_1", "pg_e_1"],
    tip="用 2 片方板而不是 1 片长板 —— 头颅的四条底边才有处可吸。",
)
b.step(
    "落头颅: 东肩上四面立墙围出头颅小箱, 脸颊朝南是透明的。",
    ["hd_s", "hd_w", "hd_n", "hd_e"],
    highlight=["sh_e", "sh_w"],
    tip="四条底边边边落吸 —— 四重连接, 头颅没有单点失效。",
)
b.step(
    "封头顶接扁喙: 头顶方板四边压墙顶, 橙色等边扁喙从东沿水平收尖。",
    ["hd_top", "beak"],
    highlight=["hd_s", "hd_e"],
    tip="扁喙悬挑力矩 5 <= 预算 20 —— 正望着滑梯的方向。",
)
b.step(
    "撑鳍肢: 两片蓝色菱形从冰面斜倚身躯前后两侧, 底边整边吸浮冰边。",
    ["fin_s", "fin_n"],
    highlight=["pg_s_0", "pg_n_0"],
    tip="菱形 60 度的天然斜度就是鳍肢摆动的角度 —— 接地斜撑, 越靠越稳。",
)
b.step(
    "搭企鹅宝宝: 浮冰东北角四面灰色立墙围出毛茸茸的小身子。",
    ["ck_s", "ck_w", "ck_n", "ck_e"],
    highlight=["fl_4_2"],
    tip="宝宝紧挨着大企鹅 —— 帝企鹅是全世界最顾家的鸟。",
)
b.step(
    "戴绒帽: 4 片灰色等边三角四棱互吸, 合拢成宝宝的圆锥绒帽。",
    CHICK_HAT,
    highlight=["ck_s", "ck_e"],
    tip="四条斜棱两两精确互吸自锁成环 —— 圆滚滚才可爱。",
)
b.step(
    "筑冰台: 浮冰东南角两片青色立墙, 顶上盖一片透明台面。",
    ["lg_w", "lg_e", "lg_top"],
    highlight=["fl_4_0", "sea_0"],
    tip="台面两端压双壁 —— 这是跳水队的出发台。",
)
b.step(
    "架冰滑梯: 30 度滑梯顶边整边吸冰台东沿, 坡尾直插水面, 尾端立起"
    "透明浪花。",
    ["slide", "splash"],
    highlight=["lg_top"],
    tip="坡尾落在海面上就是接地斜撑 —— 出发!",
)
b.step(
    "立冰山背景: 浮冰北沿与西沿各竖 1 片透明六边形大冰山。",
    ["berg_w", "berg_w2"],
    highlight=["fl_0_2", "fl_4_2"],
    tip="六边形重心正压冰沿铰链, 力臂为零 —— 极地的天际线。",
)
b.step(
    "点冰凌与小鱼: 北沿与西沿各立 1 片透明冰凌尖, 海面东缘一条青色"
    "菱形小鱼跃出水面 —— 帝企鹅一家, 开饭啦!",
    ["icicle_n", "icicle_w", "fish"],
    highlight=["berg_w", "sea_1"],
    tip="冰凌立在冰沿铰链线上, 小鱼斜身出水 —— 全场收官。",
)

b.finalize(
    model_id="penguin_01",
    name="帝企鹅一家",
    name_en="Emperor Penguin Family 01",
    description=(
        "全库第一只直立行走的鸟类: 2x1 箱形身躯用长方形前后壁+方形侧壁"
        "圈层直上两层 (透明前壁就是白肚皮), 双肩方板压顶后头颅小箱四边"
        "全吸落座 (四重连接无单点失效), 橙色等边扁喙水平收尖; 两片菱形"
        "鳍肢 60 度斜撑身侧, 灰色企鹅宝宝戴四棱自锁绒帽; 东侧冰台连 30 度"
        "冰滑梯直插水面溅起浪花, 六边形冰山守着西北两沿 —— 排队, 下水!"
    ),
    difficulty=3,
    tags=["动物世界", "企鹅", "极地", "自然", "进阶"],
    min_pieces=50,
    min_steps=16,
)
