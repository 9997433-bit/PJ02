#!/usr/bin/env python3
"""生成模型 data/models/kangaroo_01.json (袋鼠妈妈)。

内容批 G 模型 2/4: 全库第一只袋鼠, 也是动物世界第一个"五点着地"
的体态范式 —— 与坐姿箱体大熊猫 / 图腾柱猫头鹰 / 四柱大象 / 梯架
长颈鹿全部错开: 袋鼠妈妈俯身吃草, 双后腿墙环 + 双前爪矮墙 + 两条
30 度尾巴长板共五点分担体重 (真袋鼠慢走时就是这种 pentapod 步态);
胸前的育儿袋是一块双端受力的口袋搁板 (南沿吸前爪墙顶, 北沿吸
后腿墙顶, 零悬挑), 小袋鼠骑着搁板拼缝从两只小手之间探出头来;
头顶两只瘦高等腰大耳朵分立头箱东西沿, 全场制高点 5.0。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 袋鼠面朝南, 尾巴向北):
  - 草原地坪 6 行 (x [0,6], y [0,6]): 草地 + 沙地拼花        24 片
  - 后腿墙环 (x [2,4], y [2,4], z 0..1): 8 片墙环             8 片
  - 前爪矮墙 x2 (y=1, z 0..1) + 育儿袋搁板 x2 (z=1)           4 片
  - 腹部楼板 4 + 躯干墙环 8 (z 1..2) + 肩部楼板 4 (z=2)      16 片
  - 头箱 (y [2,3], z 2..3): 墙环 6 + 头顶长板 1 + 大耳朵 x2    9 片
  - 尾巴: 两条 30 度长板从腰际斜撑到地 (第四第五个着地点)      2 片
  - 小手 x2 + 小袋鼠 x1 (骑育儿袋拼缝)                        3 片
  - 岩石 + 草丛 x2 + 山花                                     4 片
  合计 70 片, 13 个教程步骤, 4 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告 + jitter 50 全绿):
  - 育儿袋搁板双端受力 (前爪墙顶 + 后腿墙顶), 零悬挑零悬挂;
  - 两条尾巴长板顶边整边吸后腿墙顶与腹板北沿, 坡尾压地 ——
    顶铰链 + 接地坡尾双路受力, 与双前爪、双后腿构成五点着地;
  - 躯干墙环墙脚全部踩腹部楼板拼缝, 头箱墙脚踩肩部楼板拼缝,
    荷载沿墙面层层直下;
  - 头顶长板东西短边入扣头箱墙顶, 大耳朵底边整边吸墙顶沿;
  - 小手/小袋鼠/岩石/草丛全部骑拼缝, 剪任一装饰最多失联 1 片。

用法: python3 tools/generate_kangaroo_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

GRASS = "green"     # 草地
SAND = "yellow"     # 沙地
FUR = "orange"      # 袋鼠毛色
BELLY = "yellow"    # 浅色肚皮与育儿袋
JOEY = "orange"     # 小袋鼠
ROCK = "gray"       # 岩石
TUFT = "green"      # 草丛
FLOWER = "red"      # 山花

# =================================================================
# 1. 草原地坪 6 行 (x [0,6], y [0,6]): 草地与沙地拼花
#    袋鼠脚下 (x [2,4]) 全部用单位方板, 两侧长板收边
# =================================================================
for row, (wc, c0, c1, ec) in enumerate([
    (GRASS, SAND, GRASS, GRASS),
    (SAND, GRASS, GRASS, SAND),     # y [1,2]: 前爪行
    (GRASS, SAND, GRASS, GRASS),    # y [2,3]: 后腿南行
    (GRASS, GRASS, SAND, SAND),     # y [3,4]: 后腿北行
    (SAND, GRASS, SAND, GRASS),     # y [4,5]: 尾巴行
    (GRASS, SAND, GRASS, GRASS),    # y [5,6]: 尾尖行
]):
    b.flat_rect(f"g{row}_w", 0, row, 0.0, wc)
    b.flat(f"g{row}_2", 2, row, 0.0, c0)
    b.flat(f"g{row}_3", 3, row, 0.0, c1)
    b.flat_rect(f"g{row}_e", 4, row, 0.0, ec)

# =================================================================
# 2. 后腿墙环 (x [2,4], y [2,4], z 0..1): 大长腿是承重主环
# =================================================================
b.wall_ns("leg_s_w", 2, 2.0, 0, FUR)
b.wall_ns("leg_s_e", 3, 2.0, 0, FUR)
b.wall_ns("leg_n_w", 2, 4.0, 0, FUR)
b.wall_ns("leg_n_e", 3, 4.0, 0, FUR)
b.wall_ew("leg_w_s", 2.0, 2, 0, FUR)
b.wall_ew("leg_w_n", 2.0, 3, 0, FUR)
b.wall_ew("leg_e_s", 4.0, 2, 0, FUR)
b.wall_ew("leg_e_n", 4.0, 3, 0, FUR)

# =================================================================
# 3. 前爪矮墙 x2 (y=1, z 0..1) + 育儿袋搁板 (z=1, 双端受力)
# =================================================================
b.wall_ns("paw_w", 2, 1.0, 0, FUR)
b.wall_ns("paw_e", 3, 1.0, 0, FUR)
b.flat("pouch_w", 2, 1, 1.0, BELLY)   # 南沿吸前爪墙顶, 北沿吸后腿墙顶
b.flat("pouch_e", 3, 1, 1.0, BELLY)

# =================================================================
# 4. 腹部楼板 (z=1) + 躯干墙环 (z 1..2) + 肩部楼板 (z=2)
# =================================================================
b.flat("belly_sw", 2, 2, 1.0, BELLY)
b.flat("belly_se", 3, 2, 1.0, BELLY)
b.flat("belly_nw", 2, 3, 1.0, BELLY)
b.flat("belly_ne", 3, 3, 1.0, BELLY)

b.wall_ns("torso_s_w", 2, 2.0, 1, BELLY)   # 胸口浅色
b.wall_ns("torso_s_e", 3, 2.0, 1, BELLY)
b.wall_ns("torso_n_w", 2, 4.0, 1, FUR)
b.wall_ns("torso_n_e", 3, 4.0, 1, FUR)
b.wall_ew("torso_w_s", 2.0, 2, 1, FUR)
b.wall_ew("torso_w_n", 2.0, 3, 1, FUR)
b.wall_ew("torso_e_s", 4.0, 2, 1, FUR)
b.wall_ew("torso_e_n", 4.0, 3, 1, FUR)

b.flat("shoulder_sw", 2, 2, 2.0, FUR)
b.flat("shoulder_se", 3, 2, 2.0, FUR)
b.flat("shoulder_nw", 2, 3, 2.0, FUR)
b.flat("shoulder_ne", 3, 3, 2.0, FUR)

# =================================================================
# 5. 头箱 (x [2,4], y [2,3], z 2..3): 探向育儿袋上方的前倾头颅
# =================================================================
b.wall_ns("head_s_w", 2, 2.0, 2, FUR)
b.wall_ns("head_s_e", 3, 2.0, 2, FUR)
b.wall_ns("head_n_w", 2, 3.0, 2, FUR)
b.wall_ns("head_n_e", 3, 3.0, 2, FUR)
b.wall_ew("head_w", 2.0, 2, 2, FUR)
b.wall_ew("head_e", 4.0, 2, 2, FUR)
b.flat_rect("head_top", 2, 2, 3.0, FUR, axis="x")   # 东西短边入扣墙顶
b.spire_ew("ear_w", 2.0, 2, 3.0, FUR)               # 大耳朵分立东西沿
b.spire_ew("ear_e", 4.0, 2, 3.0, FUR)

# =================================================================
# 6. 尾巴: 两条 30 度长板从腰际 (z=1) 斜撑到地, 尾尖向北
# =================================================================
b.ramp("tail_w", "+y", 4.0, 2, 1.0, FUR)
b.ramp("tail_e", "+y", 4.0, 3, 1.0, FUR)

# =================================================================
# 7. 小手 x2 (骑育儿袋口沿) + 小袋鼠 (骑搁板拼缝探头)
# =================================================================
b.crest_ns("hand_w", 2, 1.0, 1.0, FUR)
b.crest_ns("hand_e", 3, 1.0, 1.0, FUR)
b.crest_ew("joey", 3.0, 1, 1.0, JOEY)

# =================================================================
# 8. 岩石 + 草丛 x2 + 山花 (全部骑前院拼缝, 避开尾巴落区)
# =================================================================
b.crest_ew("rock", 2.0, 0, 0.0, ROCK)
b.crest_ew("tuft_w", 3.0, 0, 0.0, TUFT)
b.crest_ew("tuft_e", 4.0, 0, 0.0, TUFT)
b.crest_ew("flower", 4.0, 1, 0.0, FLOWER)

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺草原南两行: 长板收边, 袋鼠脚下的格子全用单位方板。",
    ["g0_w", "g0_2", "g0_3", "g0_e", "g1_w", "g1_2", "g1_3", "g1_e"],
    tip="澳洲草原的清晨 —— 袋鼠妈妈要来吃草啦, 先铺出她的地盘。",
)
b.step(
    "铺草原中两行: 行行等边互吸, 后腿墙脚要踩这些拼缝。",
    ["g2_w", "g2_2", "g2_3", "g2_e", "g3_w", "g3_2", "g3_3", "g3_e"],
    highlight=["g1_2"],
    tip="墙脚下必须有拼缝 —— 草地和沙地交错拼花, 像被太阳晒出的斑点。",
)
b.step(
    "铺草原北两行: 尾巴的落点也要有方板接住。",
    ["g4_w", "g4_2", "g4_3", "g4_e", "g5_w", "g5_2", "g5_3", "g5_e"],
    highlight=["g3_2"],
    tip="袋鼠的大尾巴待会儿要斜撑到北边这两行上。",
)
b.step(
    "立后腿墙环: 八片橙墙围成 2x2 闭环, 这是袋鼠的两条大长腿。",
    ["leg_s_w", "leg_s_e", "leg_n_w", "leg_n_e",
     "leg_w_s", "leg_w_n", "leg_e_s", "leg_e_n"],
    highlight=["g2_2", "g3_2"],
    tip="四角竖边互咬闭环 —— 袋鼠妈妈全身的重量大半都压在后腿上。",
)
b.step(
    "立前爪矮墙: 两片橙墙踩住前爪行拼缝, 与后腿隔出育儿袋的位置。",
    ["paw_w", "paw_e"],
    highlight=["g1_2", "g1_3"],
    tip="袋鼠慢走时前爪也落地 —— 现在她有四个着地点了。",
)
b.step(
    "架育儿袋搁板: 两片黄板南沿吸前爪墙顶、北沿吸后腿墙顶。",
    ["pouch_w", "pouch_e"],
    highlight=["paw_w", "leg_s_w"],
    tip="搁板两头都有墙接住 —— 双端受力, 小袋鼠的摇篮稳稳当当。",
)
b.step(
    "铺腹部楼板: 四片黄板边边入扣后腿墙顶, 板板互吸。",
    ["belly_sw", "belly_se", "belly_nw", "belly_ne"],
    highlight=["leg_s_w"],
    tip="浅色的是袋鼠的肚皮 —— 躯干的墙脚要踩这些拼缝。",
)
b.step(
    "起躯干墙环: 八片墙环骑在腹板上, 胸口两片用浅色。",
    ["torso_s_w", "torso_s_e", "torso_n_w", "torso_n_e",
     "torso_w_s", "torso_w_n", "torso_e_s", "torso_e_n"],
    highlight=["belly_sw"],
    tip="墙脚压住拼缝, 荷载沿墙面一路传到地面 —— 身体挺起来了。",
)
b.step(
    "搭尾巴: 两条 30 度长板顶边整边吸腰际墙顶, 尾尖稳稳压地。",
    ["tail_w", "tail_e"],
    highlight=["torso_n_w", "g4_2"],
    tip="顶铰链 + 接地尾尖, 重量走两条路 —— 加上四条腿, 五点着地!",
)
b.step(
    "铺肩部楼板: 四片橙板封住躯干顶, 头箱要骑在正中拼缝上。",
    ["shoulder_sw", "shoulder_se", "shoulder_nw", "shoulder_ne"],
    highlight=["torso_s_w"],
    tip="板板互吸 —— 袋鼠妈妈耸起了肩膀。",
)
b.step(
    "砌头箱盖头顶: 六片墙环探向南侧, 长板东西短边入扣墙顶。",
    ["head_s_w", "head_s_e", "head_n_w", "head_n_e",
     "head_w", "head_e", "head_top"],
    highlight=["shoulder_sw"],
    tip="头箱压在肩膀前半 —— 袋鼠妈妈正低头看着育儿袋呢。",
)
b.step(
    "竖大耳朵: 两片瘦高等腰分立头顶东西沿, 尖到 5.0 全场最高。",
    ["ear_w", "ear_e"],
    highlight=["head_top"],
    tip="袋鼠的耳朵能各自转来转去 —— 草原上一有动静立刻听到。",
)
b.step(
    "小手扶袋口, 小袋鼠探头, 摆岩石草丛山花: 母子平安!",
    ["hand_w", "hand_e", "joey", "rock", "tuft_w", "tuft_e", "flower"],
    highlight=["pouch_w"],
    tip="小袋鼠骑着搁板拼缝, 从妈妈的两只小手之间探出头来 —— 你好呀!",
)

b.finalize(
    model_id="kangaroo_01",
    name="袋鼠妈妈",
    name_en="Kangaroo Mom 01",
    description=(
        "只用核心九片型的全库第一只袋鼠, 动物世界第一个'五点着地'"
        "体态: 俯身吃草的袋鼠妈妈用双后腿墙环 + 双前爪矮墙 + 两条 "
        "30 度尾巴长板共五点分担体重 (真袋鼠慢走时就是这种步态), "
        "尾巴顶边整边吸腰际墙顶、尾尖压地, 重量走两条路; 胸前的"
        "育儿袋是一块双端受力的口袋搁板 —— 南沿吸前爪墙顶北沿吸"
        "后腿墙顶零悬挑, 小袋鼠骑着搁板拼缝从妈妈两只小手之间探出"
        "头来; 头顶两只瘦高大耳朵分立东西沿, 尖到 5.0 全场最高 —— "
        "澳洲草原的清晨, 母子俩出门散步啦!"
    ),
    difficulty=3,
    tags=["自然", "动物世界", "袋鼠", "草原", "育儿袋", "进阶"],
    min_pieces=70,
    min_steps=13,
)
