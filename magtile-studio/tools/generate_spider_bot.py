#!/usr/bin/env python3
"""生成模型 data/models/spider_bot_01.json (六足机器人)。

第三批模型: 科幻机甲主题 —— 全库第一个"腿式载具": 机身是架空
一层的 4x2 装甲舱 (地坪 + 墙圈 + 中脊隔墙 + 甲板), 六条 30 度
长方形斜腿从甲板边线甩向外侧落地, 每只脚掌垫一片平铺等边三角;
甲板上立四坡传感锥与双脊警示灯炮塔, 尾部竖起一整片六边形雷达
面板, 两根等腰天线斜指前方。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 机库地坪 [2,6]x[2,4] (机腹正下方)                              8 片
  - 机腹墙圈 12 方 + 中脊隔墙 4 方                                16 片
  - 装甲甲板 z=1: 8 方                                             8 片
  - 六条斜腿 (30 度长方形坡板) + 6 片三角脚掌                     12 片
  - 肩部装甲外挑板 4                                               4 片
  - 传感锥 (等腰四坡) 4 + 炮塔 (4 墙 + 顶 + 双脊灯) 7             11 片
  - 六边形雷达面板 1 + 等腰天线 2                                  3 片
  合计 62 片, 16 个教程步骤, 5 种磁力片形状。

物理要点 (通过 R1~R8 全部校验):
  - 六条腿本身接地: 剪断任何一条甲板边铰链线, 相连的腿与脚掌
    仍是接地子结构, 不构成悬挂/悬臂;
  - 肩部装甲板单片外挑 0.5 力臂 (弯矩 15 < 预算 20);
  - 雷达面板重心正压在甲板东缘铰链线上方, 力臂为零;
  - 甲板每片至少吸一条墙顶边 + 相邻板边, 冗余充足。

坐标约定与 C++ 端一致: 旋转为欧拉角 (度), R = Rz * Ry * Rx。
用法: python3 tools/generate_spider_bot.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import SQ3, ModelBuilder

mb = ModelBuilder()

PAD = "gray"        # 机库地坪
HULL = "purple"     # 机腹装甲
DECK = "gray"       # 甲板
LEG = "blue"        # 斜腿
FOOT = "yellow"     # 脚掌
POD = "red"         # 传感锥

# =================================================================
# 1. 机库地坪 [2,6]x[2,4] (机腹正下方 8 格)
# =================================================================
for i in range(4):
    mb.flat(f"pad_s{i}", 2 + i, 2, 0.0, PAD)
for i in range(4):
    mb.flat(f"pad_n{i}", 2 + i, 3, 0.0, PAD)

# =================================================================
# 2. 机腹: 中脊隔墙 (y=3) + 四面墙圈
# =================================================================
for i in range(4):
    mb.wall_ns(f"spine{i}", 2 + i, 3.0, 0, HULL)
for i in range(4):
    mb.wall_ns(f"hw_s{i}", 2 + i, 2.0, 0, HULL)
for i in range(4):
    mb.wall_ns(f"hw_n{i}", 2 + i, 4.0, 0, HULL)
mb.wall_ew("hw_w0", 2.0, 2, 0, HULL)
mb.wall_ew("hw_w1", 2.0, 3, 0, HULL)
mb.wall_ew("hw_e0", 6.0, 2, 0, HULL)
mb.wall_ew("hw_e1", 6.0, 3, 0, HULL)

# =================================================================
# 3. 装甲甲板 z=1: [2,6]x[2,4] 8 方
# =================================================================
for i in range(4):
    mb.flat(f"dk_s{i}", 2 + i, 2, 1.0, DECK)
for i in range(4):
    mb.flat(f"dk_n{i}", 2 + i, 3, 1.0, DECK)

# =================================================================
# 4. 六条斜腿 (30 度长方形) + 三角脚掌
#    南 2 (x [2,3]/[5,6]) + 北 2 + 前 (西) 2 (y [2,3]/[3,4])
# =================================================================
FOOT_S = 2.0 - SQ3          # 0.267949
FOOT_N = 4.0 + SQ3          # 5.732051
FOOT_W = 2.0 - SQ3

for tag, lane in (("a", 2), ("b", 5)):
    mb.ramp(f"leg_s{tag}", "-y", 2.0, lane, 1.0, LEG)
    mb.place_edge(f"foot_s{tag}", "equilateral_triangle", 0,
                  (lane + 1.0, FOOT_S, 0.0), (lane + 0.0, FOOT_S, 0.0),
                  (0.0, -1.0, 0.0), FOOT)
for tag, lane in (("a", 2), ("b", 5)):
    mb.ramp(f"leg_n{tag}", "+y", 4.0, lane, 1.0, LEG)
    mb.place_edge(f"foot_n{tag}", "equilateral_triangle", 0,
                  (lane + 0.0, FOOT_N, 0.0), (lane + 1.0, FOOT_N, 0.0),
                  (0.0, 1.0, 0.0), FOOT)
for tag, lane in (("a", 2), ("b", 3)):
    mb.ramp(f"leg_w{tag}", "-x", 2.0, lane, 1.0, LEG)
    mb.place_edge(f"foot_w{tag}", "equilateral_triangle", 0,
                  (FOOT_W, lane + 0.0, 0.0), (FOOT_W, lane + 1.0, 0.0),
                  (-1.0, 0.0, 0.0), FOOT)

# =================================================================
# 5. 肩部装甲外挑板 (南北各 2, 力臂 0.5)
# =================================================================
mb.flat("arm_s0", 3, 1, 1.0, HULL)
mb.flat("arm_s1", 4, 1, 1.0, HULL)
mb.flat("arm_n0", 3, 4, 1.0, HULL)
mb.flat("arm_n1", 4, 4, 1.0, HULL)

# =================================================================
# 6. 传感锥 (等腰四坡, [3,4]x[3,4]) + 炮塔 ([4,5]x[3,4])
# =================================================================
mb.hat4("pod", 3, 3, 1.0, POD)
mb.wall_ns("tur_s", 4, 3.0, 1, HULL)
mb.wall_ns("tur_n", 4, 4.0, 1, HULL)
mb.wall_ew("tur_w", 4.0, 3, 1, HULL)
mb.wall_ew("tur_e", 5.0, 3, 1, HULL)
mb.flat("tur_roof", 4, 3, 2.0, HULL)
mb.crest_ew("tur_lamp_w", 4.0, 3, 2.0, "orange")
mb.crest_ew("tur_lamp_e", 5.0, 3, 2.0, "orange")

# =================================================================
# 7. 六边形雷达面板 (机尾 x=6 竖立) + 等腰天线
# =================================================================
mb.place_edge("radar", "hexagon", 4,
              (6.0, 2.0, 1.0), (6.0, 3.0, 1.0), (0.0, 0.0, 1.0), "cyan")
mb.spire_ns("ant_s", 5, 2.0, 1.0, "yellow")
mb.spire_ns("ant_n", 5, 4.0, 1.0, "yellow")

# =================================================================
# 教程步骤 (16 步)
# =================================================================
mb.step(
    "机库地坪南排: 铺 4 片灰色地坪, 机器人将架空立在它正上方。",
    ["pad_s0", "pad_s1", "pad_s2", "pad_s3"],
)
mb.step(
    "机库地坪北排: 再铺 4 片, 地坪合成 4x2。",
    ["pad_n0", "pad_n1", "pad_n2", "pad_n3"],
    highlight=["pad_s0", "pad_s3"],
)
mb.step(
    "中脊隔墙: 地坪中缝立 4 片紫色方墙 —— 机腹的龙骨。",
    ["spine0", "spine1", "spine2", "spine3"],
    highlight=["pad_s1", "pad_n1"],
    tip="中脊墙底吸地坪中缝, 顶边稍后同时接住南北两排甲板。",
)
mb.step(
    "机腹南墙: 沿地坪南沿立 4 片方墙。",
    ["hw_s0", "hw_s1", "hw_s2", "hw_s3"],
    highlight=["spine0"],
)
mb.step(
    "机腹北墙: 沿地坪北沿立 4 片方墙。",
    ["hw_n0", "hw_n1", "hw_n2", "hw_n3"],
    highlight=["spine3"],
)
mb.step(
    "机腹东西封墙: 两端各立 2 片, 墙圈与中脊连成日字形 —— "
    "机腹装甲舱合拢。",
    ["hw_w0", "hw_w1", "hw_e0", "hw_e1"],
    highlight=["hw_s0", "hw_n3"],
)
mb.step(
    "甲板南排: 4 片灰色方板铺上 z=1, 每片同时吸南墙顶与中脊顶。",
    ["dk_s0", "dk_s1", "dk_s2", "dk_s3"],
    highlight=["hw_s0", "spine0"],
)
mb.step(
    "甲板北排: 4 片合拢, 装甲甲板成形 —— 机身完工。",
    ["dk_n0", "dk_n1", "dk_n2", "dk_n3"],
    highlight=["dk_s0", "spine0"],
)
mb.step(
    "南侧双腿: 2 片蓝色长板从甲板南缘以 30 度甩向外侧落地, "
    "脚下各垫 1 片黄色三角脚掌 (底边吸腿板落地短边)。",
    ["leg_sa", "foot_sa", "leg_sb", "foot_sb"],
    highlight=["dk_s0", "dk_s3"],
    tip="腿板顶短边吸甲板边, 坡尾自己接地 —— 腿本身就是支撑。",
)
mb.step(
    "北侧双腿: 同法在北缘甩出 2 条腿, 四足着地。",
    ["leg_na", "foot_na", "leg_nb", "foot_nb"],
    highlight=["dk_n0", "dk_n3"],
)
mb.step(
    "前侧双腿: 西缘 (机首) 再甩出 2 条前腿, 六足站稳。",
    ["leg_wa", "foot_wa", "leg_wb", "foot_wb"],
    highlight=["dk_s0", "dk_n0"],
)
mb.step(
    "肩部装甲: 南北空档各外挑 2 片紫色装甲板 (力臂仅 0.5)。",
    ["arm_s0", "arm_s1", "arm_n0", "arm_n1"],
    highlight=["dk_s1", "dk_n1"],
)
mb.step(
    "传感锥: 甲板中部 [3,4]x[3,4] 合拢 4 片红色等腰四坡锥, "
    "四条斜棱两两互吸自锁。",
    ["pod_s", "pod_e", "pod_n", "pod_w"],
    highlight=["dk_n1"],
)
mb.step(
    "炮塔墙身: 传感锥东侧立 4 面紫色炮塔墙。",
    ["tur_s", "tur_n", "tur_w", "tur_e"],
    highlight=["pod_e"],
)
mb.step(
    "炮塔顶与警示灯: 盖顶板, 东西两缘各立 1 片橙色三角警示灯。",
    ["tur_roof", "tur_lamp_w", "tur_lamp_e"],
    highlight=["tur_s", "tur_n"],
)
mb.step(
    "雷达面板与天线: 机尾东缘竖起 1 整片青色六边形雷达, 重心正压"
    "铰链线; 尾部两角再斜立 2 根黄色等腰天线 —— 六足机器人启动。",
    ["radar", "ant_s", "ant_n"],
    highlight=["dk_s3", "dk_n3"],
)

mb.finalize(
    model_id="spider_bot_01",
    name="六足机器人",
    name_en="Spider Bot 01",
    description=(
        "架空一层的六足机甲: 机腹装甲舱由墙圈加中脊隔墙拼成日字形, "
        "8 片甲板同时压住墙顶与中脊; 六条 30 度长方形斜腿从甲板边线"
        "甩向外侧自行落地, 每只脚掌垫一片平铺三角 —— 腿本身就是"
        "接地支撑, 剪断任何一条甲板铰链线机身都不塌。甲板上红色"
        "传感锥四棱自锁, 炮塔双脊警示灯朝天, 机尾一整片六边形雷达"
        "面板重心正压铰链线, 两根天线斜指前方。"
    ),
    difficulty=3,
    tags=["机器人", "科幻", "六足", "斜腿", "机甲"],
    min_pieces=60,
    min_steps=16,
)
