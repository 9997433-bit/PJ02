#!/usr/bin/env python3
"""生成模型 data/models/campfire_site_01.json (篝火营地)。

自然露营主题: 7x5 林间空地正中, 一堆篝火熊熊燃起 —— 四片
灰色等边三角围成火塘石圈, 圈内四片红色等腰火舌斜棱互吸,
火尖蹿到 1.94 格; 火塘南侧与东侧各一条原木坐凳, 西北角
一顶紫色人字帐篷直接落地扎营 (60 度坡面 + 等边山墙),
东北角野餐桌两桩一板如桥、南北条凳相伴; 四棵绿树围出
林间空地, 灌木、花丛、柴堆点缀其间 —— 今晚谁讲鬼故事?

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 林间空地 7x5: 方板 + 长板混铺                           30 片
  - 篝火: 火塘石圈等边三角 x4 + 等腰火舌四坡锥 (4 片)        8 片
  - 原木坐凳: 等边三角 x4 (南凳 2 + 东凳 2)                  4 片
  - 帐篷: 60 度坡面 x2 + 等边山墙 x2 (直接落地)              4 片
  - 野餐桌: 桌桩方板 x2 + 桌面方板 x1 + 条凳等边三角 x2      5 片
  - 绿树 x4 + 灌木四坡锥 x2 (8 片) + 花丛 x2 + 柴堆 x1      15 片
  合计 66 片, 16 个教程步骤, 5 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 火塘石圈四片竖立等边三角与四片 75.5 度内倾等腰火舌共享
    同一圈格边 —— 两组片面夹角不同互不穿插, 各自整边吸地;
  - 帐篷即最小人字屋: 两片 60 度坡面下长边整边吸地坪长板边,
    脊线互吸, 等边山墙底边吸方板格边、两腰吸坡面短边;
  - 野餐桌面两短边整边压桌桩顶边, 双端受力如桥; 条凳重心
    正压铰链零力矩;
  - 全场最高点 2 格 (树梢), 低重心宽基座, 稳如营地。

用法: python3 tools/generate_campfire_site.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

RIDGE_H = 0.866025

GRASS = "green"
STONE = "gray"
FLAME = "red"
LOGSEAT = "orange"
TENT = "purple"
TABLE = "yellow"
TREE = "green"
FLOWER = "pink"

# =================================================================
# 1. 林间空地 7x5 (x 0..7, y 0..5): 火塘 (3,2) 是灰色方板,
#    帐篷基线与桌桩格边全部落在拼缝上
# =================================================================
for x in range(5):
    b.flat(f"c_{x}_0", x, 0, 0.0, GRASS)
b.flat_rect("c_r_0", 5, 0, 0.0, GRASS, axis="x")      # [5,7]x[0,1]
b.flat("c_0_1", 0, 1, 0.0, GRASS)
b.flat_rect("c_r_1", 1, 1, 0.0, GRASS, axis="x")      # [1,3]x[1,2]
for x in (3, 4, 5, 6):
    b.flat(f"c_{x}_1", x, 1, 0.0, GRASS)
b.flat("c_0_2", 0, 2, 0.0, GRASS)
b.flat_rect("c_r_2", 1, 2, 0.0, GRASS, axis="x")      # [1,3]x[2,3] 帐篷南基线
b.flat("c_3_2", 3, 2, 0.0, STONE)                     # 火塘
for x in (4, 5, 6):
    b.flat(f"c_{x}_2", x, 2, 0.0, GRASS)
for x in range(7):
    b.flat(f"c_{x}_3", x, 3, 0.0, GRASS)              # 帐篷/桌桩一行全方板
b.flat("c_0_4", 0, 4, 0.0, GRASS)
b.flat_rect("c_r_4", 1, 4, 0.0, GRASS, axis="x")      # [1,3]x[4,5] 帐篷北基线
b.flat("c_3_4", 3, 4, 0.0, GRASS)
b.flat("c_4_4", 4, 4, 0.0, GRASS)
b.flat_rect("c_r_4e", 5, 4, 0.0, GRASS, axis="x")     # [5,7]x[4,5]

# =================================================================
# 2. 篝火: 火塘石圈 (竖立等边 x4) + 火舌 (等腰四坡锥, 75.5 度内倾)
# =================================================================
b.crest_ns("ring_s", 3, 2.0, 0.0, STONE)
b.crest_ns("ring_n", 3, 3.0, 0.0, STONE)
b.crest_ew("ring_w", 3.0, 2, 0.0, STONE)
b.crest_ew("ring_e", 4.0, 2, 0.0, STONE)
FIRE = b.hat4("fire", 3, 2, 0.0, FLAME)               # 火舌锥 (尖 1.94 格)

# =================================================================
# 3. 原木坐凳: 南凳 2 片 + 东凳 2 片
# =================================================================
b.crest_ns("log_s0", 2, 1.0, 0.0, LOGSEAT)
b.crest_ns("log_s1", 3, 1.0, 0.0, LOGSEAT)
b.crest_ew("log_e0", 5.0, 1, 0.0, LOGSEAT)
b.crest_ew("log_e1", 5.0, 2, 0.0, LOGSEAT)

# =================================================================
# 4. 帐篷 (x 1..3, y 3..4): 60 度人字坡直接落地 + 等边山墙
# =================================================================
b.place_edge("tt_s", "rectangle", 0, (1.0, 3.0, 0.0), (3.0, 3.0, 0.0),
             (0.0, 0.5, RIDGE_H), TENT)               # 南坡面
b.place_edge("tt_n", "rectangle", 0, (3.0, 4.0, 0.0), (1.0, 4.0, 0.0),
             (0.0, -0.5, RIDGE_H), TENT)              # 北坡面
b.crest_ew("tt_gb_w", 1.0, 3, 0.0, TENT)              # 西山墙
b.crest_ew("tt_gb_e", 3.0, 3, 0.0, TENT)              # 东山墙 (帐篷门)

# =================================================================
# 5. 野餐桌 (x 5..6, y 3..4): 两桩一板如桥 + 南北条凳
# =================================================================
b.wall_ew("tb_p_w", 5.0, 3, 0, LOGSEAT)               # 西桌桩
b.wall_ew("tb_p_e", 6.0, 3, 0, LOGSEAT)               # 东桌桩
b.flat("tb_top", 5, 3, 1.0, TABLE)                    # 桌面 (z=1)
b.crest_ns("tb_b_s", 5, 3.0, 0.0, LOGSEAT)            # 南条凳
b.crest_ns("tb_b_n", 5, 4.0, 0.0, LOGSEAT)            # 北条凳

# =================================================================
# 6. 绿树 x4 + 灌木 x2 + 花丛 x2 + 柴堆 x1
# =================================================================
b.spire_ns("tr_sw", 0, 1.0, 0.0, TREE)                # 西南树
b.spire_ns("tr_se", 6, 2.0, 0.0, TREE)                # 东南树
b.spire_ns("tr_nw", 0, 4.0, 0.0, TREE)                # 西北树
b.spire_ns("tr_ne", 4, 5.0, 0.0, TREE)                # 东北树
BUSH_W = b.hat4("bush_w", 0, 2, 0.0, TREE,
                shape="equilateral_triangle")         # 西灌木
BUSH_E = b.hat4("bush_e", 6, 3, 0.0, TREE,
                shape="equilateral_triangle")         # 东灌木
b.crest_ns("fl_a", 1, 0.0, 0.0, FLOWER)               # 南沿花丛
b.crest_ns("fl_b", 4, 0.0, 0.0, FLOWER)
b.crest_ns("wood", 4, 1.0, 0.0, LOGSEAT)              # 柴堆

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺空地南沿: 5 片方板加 1 片长板排开。",
    ["c_0_0", "c_1_0", "c_2_0", "c_3_0", "c_4_0", "c_r_0"],
    tip="营地从南沿铺起 —— 方板格边留给花丛和坐凳。",
)
b.step(
    "铺第二行: 坐凳一行, 长板拼缝落在帐篷基线上。",
    ["c_0_1", "c_r_1", "c_3_1", "c_4_1", "c_5_1", "c_6_1"],
    highlight=["c_2_0"],
    tip="火塘南边这一行, 就是围炉夜话的地方。",
)
b.step(
    "铺第三行: 正中灰色方板是火塘 —— 篝火就生在它上面。",
    ["c_0_2", "c_r_2", "c_3_2", "c_4_2", "c_5_2", "c_6_2"],
    highlight=["c_r_1"],
    tip="火塘四条格边一会儿要同时吸住石圈和火舌。",
)
b.step(
    "铺第四行: 7 片全方板 —— 帐篷山墙和桌桩都要吸这一行的格边。",
    ["c_0_3", "c_1_3", "c_2_3", "c_3_3", "c_4_3", "c_5_3", "c_6_3"],
    highlight=["c_3_2"],
    tip="全方板的一行, 格缝最密 —— 立什么都有边可吸。",
)
b.step(
    "铺北沿: 5 片合拢, 7x5 林间空地就绪。",
    ["c_0_4", "c_r_4", "c_3_4", "c_4_4", "c_r_4e"],
    highlight=["c_0_3"],
    tip="空地铺好 —— 先生火, 再扎营, 露营的老规矩。",
)
b.step(
    "垒火塘石圈: 4 片灰色等边三角竖立在火塘四条格边上。",
    ["ring_s", "ring_n", "ring_w", "ring_e"],
    highlight=["c_3_2"],
    tip="石圈挡风又防火星 —— 底边整边吸格边, 一圈站定。",
)
b.step(
    "点篝火: 石圈内 4 片红色等腰火舌斜棱两两互吸, 火尖蹿到 1.94 格。",
    FIRE,
    highlight=["ring_s", "ring_e"],
    tip="火舌 75.5 度内倾与竖直石圈共享格边却互不穿插 —— 噼啪作响!",
)
b.step(
    "摆原木坐凳: 火塘南侧 2 片、东侧 2 片橙色等边三角一字排开。",
    ["log_s0", "log_s1", "log_e0", "log_e1"],
    highlight=["fire_s"],
    tip="坐凳围着火塘摆 —— 谁先坐下谁先讲故事。",
)
b.step(
    "扎帐篷坡面: 2 片紫色长方形 60 度对斜, 下长边整边吸地坪"
    "长板边, 脊线互吸合拢。",
    ["tt_s", "tt_n"],
    highlight=["c_r_2", "c_r_4"],
    tip="帐篷就是最小的人字屋 —— 先南后北, 合脊即锁。",
)
b.step(
    "封帐篷山墙: 东西各 1 片等边三角, 底边吸方板格边、两腰吸坡面短边。",
    ["tt_gb_w", "tt_gb_e"],
    highlight=["tt_s", "tt_n"],
    tip="东山墙就是帐篷门 —— 拉链一拉, 晚安。",
)
b.step(
    "立野餐桌桩: 2 片橙色方板立在 x=5 与 x=6 格缝上。",
    ["tb_p_w", "tb_p_e"],
    highlight=["c_5_3"],
    tip="桌桩顺格缝立, 底边整边吸方板格边。",
)
b.step(
    "架桌面配条凳: 黄色桌面两短边整边压桩顶如桥, 南北条凳相伴。",
    ["tb_top", "tb_b_s", "tb_b_n"],
    highlight=["tb_p_w", "tb_p_e"],
    tip="双端受力如桥 —— 烤棉花糖就在这张桌上。",
)
b.step(
    "种南侧绿树: 西南与东南各 1 棵等腰绿树。",
    ["tr_sw", "tr_se"],
    highlight=["c_0_0", "c_6_1"],
    tip="树梢 2 格是营地制高点 —— 吊床就拴在这两棵树上?",
)
b.step(
    "种北侧绿树: 西北与东北再各 1 棵, 四树围出林间空地。",
    ["tr_nw", "tr_ne"],
    highlight=["tr_sw", "tr_se"],
    tip="四棵树四个角 —— 营地的天然围墙。",
)
b.step(
    "栽灌木: 东西各 4 片等边三角合拢成四坡灌木球。",
    BUSH_W + BUSH_E,
    highlight=["c_0_2", "c_6_3"],
    tip="斜棱互吸自锁 —— 灌木丛里住着刺猬一家。",
)
b.step(
    "点花丛与柴堆: 南沿 2 簇粉色花丛, 火塘东南码好备用柴 —— "
    "营地开张, 今晚谁讲鬼故事?",
    ["fl_a", "fl_b", "wood"],
    highlight=["c_1_0", "log_e0"],
    tip="从南沿望去: 花丛、坐凳、篝火、帐篷一线排开 —— 晚风正好。",
)

b.finalize(
    model_id="campfire_site_01",
    name="篝火营地",
    name_en="Campfire Site 01",
    description=(
        "林间露营三件套一次学会: 篝火 = 竖直石圈与 75.5 度内倾火舌共享"
        "同一圈格边互不穿插 (火尖 1.94 格); 帐篷 = 最小人字屋, 60 度"
        "坡面直接落地、脊线互吸、等边山墙封门; 野餐桌 = 两桩一板双端"
        "受力如桥; 原木坐凳围炉、四树定界、灌木花丛点景 —— 低重心"
        "宽基座, 全场最高 2 格, 稳如营地。"
    ),
    difficulty=3,
    tags=["自然", "露营", "篝火", "帐篷", "进阶"],
    min_pieces=50,
    min_steps=16,
)
