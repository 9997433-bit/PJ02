#!/usr/bin/env python3
"""生成模型 data/models/tractor_01.json (农用拖拉机)。

田园农场主题: 全库第一台农用拖拉机 —— 橙绿相间的耕地上,
一台红色拖拉机正拖着三片犁刀翻土: 两片车轮底座当大后轮,
两片方板当小前轮, 底盘长板压轮成桥; 驾驶室透明圈层 x1 +
红色圈层 x1 叠出高驾驶楼, 引擎舱低一头在前方, 舱顶前沿
竖起等腰排气管; 车尾三片直角犁刀斜插进土里, 田东一排
金黄麦浪等着下一趟收割 —— 突突突, 开耕啦!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 车头朝东):
  - 耕地 8x4: 方板 + 长板混铺, 橙色垄沟成行                 22 片
  - 轮组: 车轮底座大后轮 x2 + 方板小前轮 x2                  4 片
  - 底盘: 长板 x4 (后段压后轮顶, 前段短边接龙)               4 片
  - 驾驶室: 透明圈层 x4 + 红色圈层 x4 + 顶板长板 x2         10 片
  - 引擎舱: 长楣 x3 (含前格栅) + 舱顶长板 x2                 5 片
  - 排气管: 等腰高塔尖 x1 (立舱顶东沿短边)                   1 片
  - 犁刀: 直角三角 x3 (车尾斜插)                             3 片
  - 麦浪: 等边三角 x6 (田东成排)                             6 片
  合计 55 片, 16 个教程步骤, 6 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 后轮车轮底座底边 (长 2) 整边吸耕地长板拼缝; 底盘长板
    长边整边压后轮顶边, 前段短边与后段短边接龙, 前轮顶边
    完整落在前段长边内 (长短边贴合, R2 扩展);
  - 驾驶室与引擎舱均为长方形圈层砌法, 四角竖边咬合成环,
    引擎舱西墙即驾驶室东墙 —— 两舱共墙锁成双环;
  - 排气管等腰底边整边吸舱顶长板东短边, 重心正压铰链零力矩;
  - 犁刀直角边分别吸地坪格边与后轮竖短边, 斜边如犁尖入土。

用法: python3 tools/generate_tractor.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

SOIL = "green"      # 未翻的草皮
FURROW = "orange"   # 翻好的垄沟
DIRT = "gray"       # 车底土路
BODY = "red"        # 车身
WHEEL = "gray"      # 轮组
GLASS = "clear"     # 驾驶室玻璃
WHEAT = "yellow"    # 麦浪

# =================================================================
# 1. 耕地 8x4 (x 0..8, y 0..4): 拼缝纪律 —— 后轮线 (y=1/3, x 1..3)
#    与前轮线 (x 4..5) 处必须有等长地坪边
# =================================================================
b.flat("f_0_0", 0, 0, 0.0, SOIL)
b.flat_rect("f_r0", 1, 0, 0.0, FURROW, axis="x")      # 垄沟 [1,3]
b.flat("f_3_0", 3, 0, 0.0, SOIL)
b.flat("f_4_0", 4, 0, 0.0, SOIL)                      # 前轮地基 (南)
b.flat_rect("f_r1", 5, 0, 0.0, FURROW, axis="x")      # 垄沟 [5,7]
b.flat("f_7_0", 7, 0, 0.0, SOIL)
for y in (1, 2):
    b.flat(f"f_0_{y}", 0, y, 0.0, SOIL)
    b.flat_rect(f"f_a_{y}", 1, y, 0.0, DIRT, axis="x")    # 车底 [1,3]
    b.flat_rect(f"f_b_{y}", 3, y, 0.0, DIRT, axis="x")    # 车底 [3,5]
    b.flat_rect(f"f_c_{y}", 5, y, 0.0, FURROW, axis="x")  # 垄沟 [5,7]
    b.flat(f"f_7_{y}", 7, y, 0.0, SOIL)
b.flat("f_0_3", 0, 3, 0.0, SOIL)
b.flat_rect("f_r3", 1, 3, 0.0, SOIL, axis="x")        # [1,3] 后轮地基 (北)
b.flat("f_3_3", 3, 3, 0.0, SOIL)
b.flat("f_4_3", 4, 3, 0.0, SOIL)                      # 前轮地基 (北)
b.flat_rect("f_r4", 5, 3, 0.0, SOIL, axis="x")
b.flat("f_7_3", 7, 3, 0.0, SOIL)

# =================================================================
# 2. 轮组: 大后轮 (车轮底座) + 小前轮 (方板), 底边吸地坪拼缝
# =================================================================
b.add("wh_rs", "wheel_base", (2.0, 1.0, 0.5), (90, 0, 0), WHEEL)   # 南后轮
b.add("wh_rn", "wheel_base", (2.0, 3.0, 0.5), (90, 0, 0), WHEEL)   # 北后轮
b.wall_ns("wh_fs", 4, 1.0, 0, WHEEL)                  # 南前轮 [4,5]
b.wall_ns("wh_fn", 4, 3.0, 0, WHEEL)                  # 北前轮

# =================================================================
# 3. 底盘 (z=1): 后段长板压后轮顶, 前段短边接龙、长边内吸前轮顶
# =================================================================
b.flat_rect("ch_rs", 1, 1, 1.0, BODY, axis="x")       # 后段南半 [1,3]x[1,2]
b.flat_rect("ch_rn", 1, 2, 1.0, BODY, axis="x")       # 后段北半 [1,3]x[2,3]
b.flat_rect("ch_fs", 3, 1, 1.0, BODY, axis="x")       # 前段南半 [3,5]x[1,2]
b.flat_rect("ch_fn", 3, 2, 1.0, BODY, axis="x")       # 前段北半 [3,5]x[2,3]

# =================================================================
# 4. 驾驶室 (x 1..3, y 1..3): 透明圈层 z1..2 + 红色圈层 z2..3 +
#    顶板长板 x2 (z=3)
# =================================================================
for z0, color, tag in ((1, GLASS, "g"), (2, BODY, "t")):
    b.lintel_ns(f"cb_s_{tag}", 1, 1.0, z0, color)     # 南窗/南墙
    b.lintel_ns(f"cb_n_{tag}", 1, 3.0, z0, color)     # 北窗/北墙
    b.lintel_ew(f"cb_w_{tag}", 1.0, 1, z0, color)     # 后窗/后墙
    b.lintel_ew(f"cb_e_{tag}", 3.0, 1, z0, color)     # 前风挡/前墙
b.flat_rect("cb_rf_s", 1, 1, 3.0, BODY, axis="x")     # 驾驶室顶南半
b.flat_rect("cb_rf_n", 1, 2, 3.0, BODY, axis="x")     # 驾驶室顶北半

# =================================================================
# 5. 引擎舱 (x 3..5, y 1..3, z 1..2): 西墙即驾驶室前风挡, 共墙双环
# =================================================================
b.lintel_ns("hd_s", 3, 1.0, 1, BODY)                  # 舱南墙
b.lintel_ns("hd_n", 3, 3.0, 1, BODY)                  # 舱北墙
b.lintel_ew("hd_e", 5.0, 1, 1, BODY)                  # 前格栅
b.flat_rect("hd_rf_s", 3, 1, 2.0, BODY, axis="x")     # 舱顶南半 [3,5]x[1,2]
b.flat_rect("hd_rf_n", 3, 2, 2.0, BODY, axis="x")     # 舱顶北半 [3,5]x[2,3]

# =================================================================
# 6. 排气管: 等腰高塔尖立舱顶东沿短边 (重心正压铰链)
# =================================================================
b.spire_ew("exhaust", 5.0, 1, 2.0, WHEEL)

# =================================================================
# 7. 犁刀: 3 片直角三角斜插车尾, 直角边吸地坪格边与后轮竖短边
# =================================================================
b.brace("plow_s", (1.0, 1.0, 0.0), "-x", FURROW)      # 南犁刀 (贴南后轮)
b.brace("plow_m", (1.0, 2.0, 0.0), "-x", FURROW)      # 中犁刀
b.brace("plow_n", (1.0, 3.0, 0.0), "-x", FURROW)      # 北犁刀 (贴北后轮)

# =================================================================
# 8. 麦浪: 6 片金黄等边三角在田东成排
# =================================================================
b.crest_ew("wt_e0", 8.0, 0, 0.0, WHEAT)
b.crest_ew("wt_e1", 8.0, 1, 0.0, WHEAT)
b.crest_ew("wt_e2", 8.0, 2, 0.0, WHEAT)
b.crest_ew("wt_e3", 8.0, 3, 0.0, WHEAT)
b.crest_ns("wt_s", 7, 1.0, 0.0, WHEAT)                # 田角麦丛 (南)
b.crest_ns("wt_n", 7, 3.0, 0.0, WHEAT)                # 田角麦丛 (北)

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺耕地南沿: 6 片地坪排开, 橙色长板是翻好的垄沟。",
    ["f_0_0", "f_r0", "f_3_0", "f_4_0", "f_r1", "f_7_0"],
    tip="垄沟 [1,3] 的北长边就是大后轮的地基缝 —— 拼缝先行。",
)
b.step(
    "铺耕地中部: 2 行灰色车底土路加橙色垄沟, 拖拉机的车位留好了。",
    ["f_0_1", "f_a_1", "f_b_1", "f_c_1", "f_7_1",
     "f_0_2", "f_a_2", "f_b_2", "f_c_2", "f_7_2"],
    highlight=["f_r0", "f_4_0"],
    tip="y=1 与 y=3 两条拼缝之间, 就是车身的宽度。",
)
b.step(
    "铺耕地北沿: 6 片合拢, 8x4 耕地就绪。",
    ["f_0_3", "f_r3", "f_3_3", "f_4_3", "f_r4", "f_7_3"],
    highlight=["f_a_2", "f_c_2"],
    tip="土地平整完毕 —— 该请主角进场了。",
)
b.step(
    "装大后轮: 2 片车轮底座沿 y=1 与 y=3 拼缝立起, 底边整边吸合。",
    ["wh_rs", "wh_rn"],
    highlight=["f_r0", "f_r3"],
    tip="车轮底座一片顶两格 —— 拖拉机的大后轮就是它的招牌。",
)
b.step(
    "装小前轮: 2 片灰色方板立在 x [4,5] 格边上, 前轮比后轮小一号。",
    ["wh_fs", "wh_fn"],
    highlight=["wh_rs", "wh_rn"],
    tip="大后轮小前轮 —— 这才是拖拉机的经典侧影。",
)
b.step(
    "架底盘后段: 2 片红色长板长边整边压住两侧后轮顶边。",
    ["ch_rs", "ch_rn"],
    highlight=["wh_rs", "wh_rn"],
    tip="底盘压轮成桥 —— 车架从这里开始受力。",
)
b.step(
    "接底盘前段: 再接 2 片, 短边与后段短边接龙, 长边内侧"
    "稳稳吸住前轮顶边。",
    ["ch_fs", "ch_fn"],
    highlight=["ch_rs", "wh_fs"],
    tip="前轮顶边完整落在长板长边内 —— 长短边贴合同样牢固。",
)
b.step(
    "立驾驶室玻璃圈层: 4 片透明长楣在底盘后段围成一圈, "
    "四角竖边咬合。",
    ["cb_s_g", "cb_n_g", "cb_w_g", "cb_e_g"],
    highlight=["ch_rs", "ch_rn"],
    tip="透明圈层就是 360 度环景驾驶室 —— 农机手视野第一。",
)
b.step(
    "立引擎舱墙: 南北 2 片红色长楣加前格栅, 西墙借用驾驶室前风挡 "
    "—— 两舱共墙锁成双环。",
    ["hd_s", "hd_n", "hd_e"],
    highlight=["cb_e_g", "ch_fs"],
    tip="共墙是双环结构的关键: 一面墙同时属于两个圈层。",
)
b.step(
    "盖引擎舱顶: 2 片长板南北合拢, 南沿吸舱南墙顶、短边搭格栅与风挡顶。",
    ["hd_rf_s", "hd_rf_n"],
    highlight=["hd_s", "hd_e"],
    tip="舱顶盖上, 引擎舱成了一只结实的箱子。",
)
b.step(
    "叠驾驶室红色圈层: 4 片红色长楣再叠一圈, 驾驶楼高过引擎舱一头。",
    ["cb_s_t", "cb_n_t", "cb_w_t", "cb_e_t"],
    highlight=["cb_s_g", "hd_rf_s"],
    tip="高驾驶楼 + 低引擎舱 —— 拖拉机的阶梯轮廓出来了。",
)
b.step(
    "盖驾驶室顶: 2 片红色长板压顶, 驾驶楼封舱。",
    ["cb_rf_s", "cb_rf_n"],
    highlight=["cb_s_t", "cb_n_t"],
    tip="顶板长边整边吸墙顶 —— 圈层砌法的标准收顶。",
)
b.step(
    "竖排气管: 等腰高塔尖立在舱顶东沿短边上。",
    ["exhaust"],
    highlight=["hd_rf_s"],
    tip="重心正压铰链零力矩 —— 突突突, 黑烟从这里冒。",
)
b.step(
    "挂犁刀: 车尾 3 片直角三角斜插, 直角边分别吸地坪格边与"
    "后轮竖短边。",
    ["plow_s", "plow_m", "plow_n"],
    highlight=["wh_rs", "wh_rn"],
    tip="斜边就是犁尖 —— 一趟下去翻出三条垄。",
)
b.step(
    "种田东麦浪: 4 片金黄等边三角沿东沿立成一排。",
    ["wt_e0", "wt_e1", "wt_e2", "wt_e3"],
    highlight=["f_7_1"],
    tip="底边吸地坪格边 —— 风一吹, 麦浪翻滚。",
)
b.step(
    "补田角麦丛: 最后 2 片就位 —— 拖拉机开耕, 丰收在望!",
    ["wt_s", "wt_n"],
    highlight=["wt_e0", "wt_e3"],
    tip="从东头望去: 麦浪、格栅、排气管、驾驶楼一线排开 —— 出发!",
)

b.finalize(
    model_id="tractor_01",
    name="农用拖拉机",
    name_en="Farm Tractor 01",
    description=(
        "全库第一台农用拖拉机: 大后轮用车轮底座、小前轮用方板, 底盘长板"
        "压轮成桥; 驾驶室透明圈层与红色圈层叠出高驾驶楼, 引擎舱低一头"
        "在前, 两舱共墙锁成双环, 舱顶东沿竖起等腰排气管; 车尾三片直角"
        "犁刀斜插进土, 橙色垄沟与金黄麦浪铺满耕地 —— 突突突, 开耕啦!"
    ),
    difficulty=3,
    tags=["田园", "农场", "拖拉机", "车轮底座", "进阶"],
    min_pieces=50,
    min_steps=16,
)
