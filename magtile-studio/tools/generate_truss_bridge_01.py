#!/usr/bin/env python3
"""生成模型 data/models/truss_bridge_01.json (三角桁架红桥)。

内容批 G 模型 4/4: 桥梁工程第一座真桁架墙桥。库内已有多跨连续
木桥 (桥墩逐跨落水)/风雨廊桥 (墩台驮亭)/悬索桥 (斜拉索+菱形主缆)/
过街天桥 (梯塔抬桥面)/罗马水道桥 (连拱), 本作与它们全部错开:
结构签名是"华伦式桁架墙" —— 九片等边三角形尖朝上/尖朝下交替
连排, 相邻斜边两两整边互咬, 在桥面两沿各拼出一道刚性三角桁墙
(抗剪靠几何, 不靠磁力硬拽); 有了桁墙撑腰, 三格宽的主跨一座桥墩
都不落水, 全靠两岸桥台把桥面架过河 —— 河面留给小鸭子游过桥洞。
两端四条 30 度引桥顶边铰桥台墙顶, 坡尾落岸, 小车可以一路开过河!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 桥沿东西向跨河):
  - 两岸河谷地坪 (x [0,11], y [0,4]): 草岸 + 蓝色河面        28 片
  - 桥台 x2 (x [3,4] 与 [7,8], y [1,3], z 0..1): 箱形墙环    12 片
  - 桥面 (x [3,8], y [1,3], z=1): 五条长板短边入扣互吸        5 片
  - 华伦桁架墙 x2 (桥面南北沿): 尖上 5 + 尖下 4, 每侧 9 片   18 片
  - 引桥 x4: 两端各两条 30 度长板坡道                         4 片
  - 小鸭 x2 (桥洞下) + 岸边灌木 x2 + 野花 x2                  6 片
  合计 73 片, 12 个教程步骤, 3 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告 + jitter 50 全绿):
  - 尖朝上的桁片底边整边吸桥面板短边, 尖朝下的桁片两条斜边
    分别整边吸左右邻片 —— 桁墙每片至少两条整边吸合, 剪断任一
    铰链桁墙仍连成整体 (R8 冗余);
  - 桥面五条长板短边互吸连排, 两端整落桥台墙顶, 主跨零墩;
  - 桥台箱形墙环墙脚踩岸上方板拼缝, 四角竖边互咬;
  - 引桥顶边整边吸桥台墙顶, 坡尾压岸 —— 顶铰链 + 接地坡尾;
  - 小鸭 (高 0.87) 从净空 1.0 的桥洞下穿过, 不碰桥底。

用法: python3 tools/generate_truss_bridge_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

BANK = "green"      # 草岸
RIVER = "blue"      # 河面
PIER = "gray"       # 桥台
ROAD = "gray"       # 桥面与引桥
TRUSS = "red"       # 桁架墙
DUCK = "yellow"     # 小鸭
BUSH = "green"      # 灌木
FLOWER = "pink"     # 野花

TRI_H = 0.866025    # 等边三角形高
TOP = 1.0 + TRI_H   # 桁墙上弦高度


def inv_tri(tile_id, x0, y, color):
    """尖朝下的桁片: 上底从 (x0+1, y, TOP) 到 (x0, y, TOP), 尖触桥面。"""
    b.place_tri(tile_id, "equilateral_triangle",
                (x0 + 1.0, y, TOP), (x0, y, TOP), (x0 + 0.5, y, 1.0), color)


# =================================================================
# 1. 西岸 (x [0,4], y [0,4]): 草岸, 桥台脚下用单位方板
# =================================================================
b.flat_rect("wb_0_s", 0, 0, 0.0, BANK)
b.flat_rect("wb_2_s", 2, 0, 0.0, BANK)
b.flat_rect("wb_0_1", 0, 1, 0.0, BANK)
b.flat("wb_2_1", 2, 1, 0.0, BANK)
b.flat("wb_3_1", 3, 1, 0.0, BANK)
b.flat_rect("wb_0_2", 0, 2, 0.0, BANK)
b.flat("wb_2_2", 2, 2, 0.0, BANK)
b.flat("wb_3_2", 3, 2, 0.0, BANK)
b.flat_rect("wb_0_n", 0, 3, 0.0, BANK)
b.flat_rect("wb_2_n", 2, 3, 0.0, BANK)

# =================================================================
# 2. 河面 (x [4,7], y [0,4]): 三格宽的蓝色河道
# =================================================================
b.flat_rect("rv_s_w", 4, 0, 0.0, RIVER)
b.flat("rv_s_e", 6, 0, 0.0, RIVER)
b.flat_rect("rv_1_w", 4, 1, 0.0, RIVER)
b.flat("rv_1_e", 6, 1, 0.0, RIVER)
b.flat("rv_2_w", 4, 2, 0.0, RIVER)
b.flat_rect("rv_2_e", 5, 2, 0.0, RIVER)
b.flat("rv_n_w", 4, 3, 0.0, RIVER)
b.flat_rect("rv_n_e", 5, 3, 0.0, RIVER)

# =================================================================
# 3. 东岸 (x [7,11], y [0,4]): 与西岸镜像
# =================================================================
b.flat_rect("eb_7_s", 7, 0, 0.0, BANK)
b.flat_rect("eb_9_s", 9, 0, 0.0, BANK)
b.flat("eb_7_1", 7, 1, 0.0, BANK)
b.flat("eb_8_1", 8, 1, 0.0, BANK)
b.flat_rect("eb_9_1", 9, 1, 0.0, BANK)
b.flat("eb_7_2", 7, 2, 0.0, BANK)
b.flat("eb_8_2", 8, 2, 0.0, BANK)
b.flat_rect("eb_9_2", 9, 2, 0.0, BANK)
b.flat_rect("eb_7_n", 7, 3, 0.0, BANK)
b.flat_rect("eb_9_n", 9, 3, 0.0, BANK)

# =================================================================
# 4. 桥台 x2: 箱形墙环 (z 0..1), 墙脚踩岸上方板拼缝
# =================================================================
b.wall_ns("wp_s", 3, 1.0, 0, PIER)
b.wall_ns("wp_n", 3, 3.0, 0, PIER)
b.wall_ew("wp_w_s", 3.0, 1, 0, PIER)
b.wall_ew("wp_w_n", 3.0, 2, 0, PIER)
b.wall_ew("wp_e_s", 4.0, 1, 0, PIER)
b.wall_ew("wp_e_n", 4.0, 2, 0, PIER)
b.wall_ns("ep_s", 7, 1.0, 0, PIER)
b.wall_ns("ep_n", 7, 3.0, 0, PIER)
b.wall_ew("ep_w_s", 7.0, 1, 0, PIER)
b.wall_ew("ep_w_n", 7.0, 2, 0, PIER)
b.wall_ew("ep_e_s", 8.0, 1, 0, PIER)
b.wall_ew("ep_e_n", 8.0, 2, 0, PIER)

# =================================================================
# 5. 桥面 (z=1): 五条长板短边入扣互吸, 两端整落桥台墙顶
# =================================================================
for k, x in enumerate(range(3, 8)):
    b.flat_rect(f"deck_{k}", x, 1, 1.0, ROAD, axis="y")

# =================================================================
# 6. 华伦桁架墙 x2: 尖上/尖下交替, 斜边两两整边互咬
# =================================================================
for i, x in enumerate(range(3, 8)):
    b.crest_ns(f"ts_up_{i}", x, 1.0, 1.0, TRUSS)     # 南桁墙尖朝上
for i, x in enumerate(range(3, 7)):
    inv_tri(f"ts_dn_{i}", x + 0.5, 1.0, TRUSS)       # 南桁墙尖朝下
for i, x in enumerate(range(3, 8)):
    b.crest_ns(f"tn_up_{i}", x, 3.0, 1.0, TRUSS)     # 北桁墙尖朝上
for i, x in enumerate(range(3, 7)):
    inv_tri(f"tn_dn_{i}", x + 0.5, 3.0, TRUSS)       # 北桁墙尖朝下

# =================================================================
# 7. 引桥 x4: 30 度长板顶边铰桥台墙顶, 坡尾落岸
# =================================================================
b.ramp("ramp_w_s", "-x", 3.0, 1, 1.0, ROAD)
b.ramp("ramp_w_n", "-x", 3.0, 2, 1.0, ROAD)
b.ramp("ramp_e_s", "+x", 8.0, 1, 1.0, ROAD)
b.ramp("ramp_e_n", "+x", 8.0, 2, 1.0, ROAD)

# =================================================================
# 8. 小鸭 x2 (桥洞下的河面拼缝) + 灌木 x2 + 野花 x2
# =================================================================
b.crest_ew("duck_a", 6.0, 1, 0.0, DUCK)   # 正要游进桥洞
b.crest_ew("duck_b", 5.0, 2, 0.0, DUCK)   # 已经游到桥底下
b.crest_ew("bush_w", 2.0, 0, 0.0, BUSH)
b.crest_ew("bush_e", 9.0, 3, 0.0, BUSH)
b.crest_ew("flower_w", 2.0, 3, 0.0, FLOWER)
b.crest_ew("flower_e", 9.0, 0, 0.0, FLOWER)

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺西岸: 草岸长板收边, 桥台脚下的四格用单位方板。",
    ["wb_0_s", "wb_2_s", "wb_0_1", "wb_2_1", "wb_3_1",
     "wb_0_2", "wb_2_2", "wb_3_2", "wb_0_n", "wb_2_n"],
    tip="河谷春游日! 桥台的墙脚要踩在方板拼缝上, 先把西岸铺好。",
)
b.step(
    "铺河面: 三格宽的蓝色河道, 行行等边互吸。",
    ["rv_s_w", "rv_s_e", "rv_1_w", "rv_1_e",
     "rv_2_w", "rv_2_e", "rv_n_w", "rv_n_e"],
    highlight=["wb_2_s"],
    tip="河面上一座桥墩都不会有 —— 过河的本事全在桁架墙身上。",
)
b.step(
    "铺东岸: 与西岸镜像, 桥台脚下同样用单位方板。",
    ["eb_7_s", "eb_9_s", "eb_7_1", "eb_8_1", "eb_9_1",
     "eb_7_2", "eb_8_2", "eb_9_2", "eb_7_n", "eb_9_n"],
    highlight=["rv_s_e"],
    tip="两岸铺齐, 河谷就位 —— 就差一座桥了。",
)
b.step(
    "砌西桥台: 六片灰墙围成箱形墙环, 四角竖边互咬。",
    ["wp_s", "wp_n", "wp_w_s", "wp_w_n", "wp_e_s", "wp_e_n"],
    highlight=["wb_2_1", "wb_3_1"],
    tip="桥台是全桥的地基 —— 箱形闭环把桥面的重量稳稳传进岸里。",
)
b.step(
    "砌东桥台: 与西桥台镜像, 隔河相望。",
    ["ep_s", "ep_n", "ep_w_s", "ep_w_n", "ep_e_s", "ep_e_n"],
    highlight=["eb_7_1", "eb_8_1"],
    tip="两座桥台正好隔开三格河道 —— 这就是主跨的跨度。",
)
b.step(
    "架桥面: 五条灰色长板短边入扣互吸, 两端整落桥台墙顶。",
    ["deck_0", "deck_1", "deck_2", "deck_3", "deck_4"],
    highlight=["wp_s", "ep_s"],
    tip="长板一条接一条从西岸伸到东岸 —— 主跨中间一座墩都不落水!",
)
b.step(
    "立南桁墙尖朝上五片: 红色等边底边整边吸桥面南沿。",
    ["ts_up_0", "ts_up_1", "ts_up_2", "ts_up_3", "ts_up_4"],
    highlight=["deck_0"],
    tip="桁架墙开工 —— 先把尖朝上的五片沿桥沿排成一列。",
)
b.step(
    "补南桁墙尖朝下四片: 每片两条斜边整边咬住左右邻片。",
    ["ts_dn_0", "ts_dn_1", "ts_dn_2", "ts_dn_3"],
    highlight=["ts_up_0", "ts_up_1"],
    tip="尖上尖下交替互咬, 这就是华伦式桁架 —— 抗剪靠三角形的几何!",
)
b.step(
    "立北桁墙尖朝上五片: 与南桁墙隔桥面相望。",
    ["tn_up_0", "tn_up_1", "tn_up_2", "tn_up_3", "tn_up_4"],
    highlight=["deck_0"],
    tip="两道桁墙一南一北, 桥面被夹在中间才够硬气。",
)
b.step(
    "补北桁墙尖朝下四片: 华伦桁架合龙。",
    ["tn_dn_0", "tn_dn_1", "tn_dn_2", "tn_dn_3"],
    highlight=["tn_up_0", "tn_up_1"],
    tip="剪断任何一条铰链, 桁墙照样连成整体 —— 三角形最可靠。",
)
b.step(
    "搭四条引桥: 30 度长板顶边铰桥台墙顶, 坡尾稳稳落岸。",
    ["ramp_w_s", "ramp_w_n", "ramp_e_s", "ramp_e_n"],
    highlight=["wp_w_s", "ep_e_s"],
    tip="顶铰链 + 接地坡尾, 重量走两条路 —— 小车可以一路开过河啦。",
)
b.step(
    "请小鸭游进桥洞, 岸边种上灌木野花: 通桥仪式开始!",
    ["duck_a", "duck_b", "bush_w", "bush_e", "flower_w", "flower_e"],
    highlight=["rv_1_e", "rv_2_e"],
    tip="桥洞净空一格, 小鸭 (高 0.87) 正好从桥底下游过去 —— 嘎嘎!",
)

b.finalize(
    model_id="truss_bridge_01",
    name="三角桁架红桥",
    name_en="Warren Truss Bridge 01",
    description=(
        "只用核心九片型的桥梁工程新范式 —— 全库第一座真桁架墙桥: "
        "与逐跨落墩的木桥/驮亭的廊桥/挂缆的悬索桥全部错开, 招牌是"
        "华伦式桁架墙 —— 九片红色等边三角形尖朝上/尖朝下交替连排, "
        "相邻斜边两两整边互咬, 在桥面两沿各拼出一道刚性三角桁墙, "
        "抗剪靠三角形的几何而不是磁力硬拽; 有了桁墙撑腰, 三格宽的"
        "主跨一座桥墩都不落水, 五条长板桥面两端整落桥台墙顶, 桥洞"
        "净空留给小鸭子游过; 两端四条 30 度引桥顶边铰桥台墙顶坡尾"
        "落岸 —— 通桥仪式开始, 小车一路开过河!"
    ),
    difficulty=3,
    tags=["桥梁", "桁架", "工程", "河谷", "进阶"],
    min_pieces=73,
    min_steps=12,
)
