#!/usr/bin/env python3
"""生成模型 data/models/butterfly_garden_01.json (蝴蝶花园)。

动物园/野生动物主题批 4/4: 全库第一座"藤廊 + 立体蝴蝶"的花园
—— 与 butterfly_01 (平铺马赛克蝴蝶: 翅膀贴地+箱形身体) 与
greenhouse_01 / greenhouse_dome_01 (封闭玻璃房) 刻意区分, 本作
的蝴蝶是"立起来的": 每只由两片等边三角从同一条拼缝向两侧 45 度
张开 —— 底边共吸一条线互为镜像, 双翅夹角 90 度像正要起飞;
入园主轴是一条 4 格深的藤蔓廊架 (每格一榀门式框: 双柱托横板,
相邻横板长边拼缝互吸、相邻立柱竖边互咬 —— 四榀框连成筒状绿廊,
绿/透明棚板相间如藤蔓漏光); 廊外两座花圃 (四墙合环的种植槽,
红粉黄花朵骑槽沿), 东侧 1x1 观蝶亭四面窗格方 360 度透明, 戴
粉色等腰四坡花冠顶 (亭尖 2.94 全场最高); 三只蝴蝶分别停在
草坪拼缝、花圃槽沿与草地上 —— 悄悄走, 别惊飞它们。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 花园地坪 (x [0,7], y [0,5]): 方板 x27 + 长板 x4
    (廊下石径、草坪、花圃土、亭基)                             31 片
  - 藤蔓廊架 x4 榀 (y [0,4]): 双柱 8 + 棚板 4                  12 片
  - 花圃 A [3,5]x[1,2]: 四墙合环 6 + 花朵骑沿 x2                8 片
  - 花圃 B [5,7]x[0,1]: 四墙合环 6 + 花朵骑沿 x2                8 片
  - 观蝶亭 (5,3): 窗格方 x4 + 等腰四坡花冠顶 4                  8 片
  - 立体蝴蝶 x3: 每只两片等边三角 45 度对开                     6 片
  合计 73 片, 14 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 立体蝴蝶: 两片翅膀底边共吸同一条拼缝 (彼此再互吸), 各向外
    45 度张开 —— 单翅力矩 13g x 0.204 = 2.7 g·单位 << strict
    抗弯预算 17.5 g·单位, 双翅对称合力矩为零;
  - 藤蔓廊架: 每片棚板两短边同吸双柱顶 (双端受力零悬挑), 相邻
    棚板长边拼缝互吸、相邻立柱竖边互咬 —— 柱-板-柱-地坪门式
    刚架环连成筒;
  - 花圃/观蝶亭墙环四角竖边互吸自锁, 花冠四条斜棱两两互吸成环;
  - 花朵骑槽沿重心正压铰链线, 力矩为零。

用法: python3 tools/generate_butterfly_garden_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

COS45 = 0.7071068
TRI_H = 0.866025                       # 等边三角形高
WING = round(TRI_H * COS45, 6)         # 45 度张开翅膀的投影 0.612372

b = ModelBuilder()

LAWN = "green"       # 草坪
PATH = "gray"        # 廊下石径 / 亭基
SOIL = "orange"      # 花圃土
POST = "gray"        # 廊架立柱
VINE1 = "green"      # 藤蔓棚板
VINE2 = "clear"      # 漏光棚板
BED = "orange"       # 花圃墙
KIOSK = "clear"      # 观蝶亭窗
HAT = "pink"         # 亭顶花冠


def wings(prefix, b0, b1, out_axis, color_a, color_b):
    """一只立体蝴蝶: 两片等边三角从拼缝 b0->b1 向两侧 45 度张开。

    out_axis: 'x' 表示拼缝沿 y、翅膀向 ±x 张开; 'y' 反之。
    """
    mid = ((b0[0] + b1[0]) / 2, (b0[1] + b1[1]) / 2, (b0[2] + b1[2]) / 2)
    if out_axis == "x":
        apex_a = (round(mid[0] + WING, 6), mid[1], round(mid[2] + WING, 6))
        apex_b = (round(mid[0] - WING, 6), mid[1], round(mid[2] + WING, 6))
    else:
        apex_a = (mid[0], round(mid[1] + WING, 6), round(mid[2] + WING, 6))
        apex_b = (mid[0], round(mid[1] - WING, 6), round(mid[2] + WING, 6))
    b.place_tri(f"{prefix}_a", "equilateral_triangle", b0, b1, apex_a, color_a)
    b.place_tri(f"{prefix}_b", "equilateral_triangle", b1, b0, apex_b, color_b)


# =================================================================
# 1. 花园地坪 (x [0,7], y [0,5]): 31 片
#    廊架柱脚两列 (x [0,2]) 与花圃/亭基周边全用方板。
# =================================================================
# 廊下石径与柱脚 (x [0,2], y [0,4]): 两列方板
for y in range(4):
    b.flat(f"gd_0_{y}", 0, y, 0.0, LAWN)
    b.flat(f"gd_1_{y}", 1, y, 0.0, PATH)
# 中部草坪与花圃土
b.flat("gd_2_0", 2, 0, 0.0, LAWN)
b.flat("gd_3_0", 3, 0, 0.0, PATH)
b.flat("gd_4_0", 4, 0, 0.0, LAWN)
b.flat("bd_b_w", 5, 0, 0.0, SOIL)      # 花圃 B 土 (西格)
b.flat("bd_b_e", 6, 0, 0.0, SOIL)      # 花圃 B 土 (东格)
b.flat("gd_2_1", 2, 1, 0.0, LAWN)
b.flat("bd_a_w", 3, 1, 0.0, SOIL)      # 花圃 A 土 (西格)
b.flat("bd_a_e", 4, 1, 0.0, SOIL)      # 花圃 A 土 (东格)
b.flat("gd_5_1", 5, 1, 0.0, LAWN)
b.flat("gd_6_1", 6, 1, 0.0, LAWN)
# 行 y2: 长板 x2 + 方 x1
b.flat_rect("gd_2_2", 2, 2, 0.0, LAWN)
b.flat_rect("gd_4_2", 4, 2, 0.0, LAWN)
b.flat("gd_6_2", 6, 2, 0.0, LAWN)
# 行 y3: 长板 + 方 x3 (亭基)
b.flat_rect("gd_2_3", 2, 3, 0.0, LAWN)
b.flat("gd_4_3", 4, 3, 0.0, LAWN)
b.flat("gd_5_3", 5, 3, 0.0, PATH)      # 观蝶亭基
b.flat("gd_6_3", 6, 3, 0.0, LAWN)
# 行 y4: 方 x2 + 长板 + 方 x3
b.flat("gd_0_4", 0, 4, 0.0, LAWN)
b.flat("gd_1_4", 1, 4, 0.0, LAWN)
b.flat_rect("gd_2_4", 2, 4, 0.0, LAWN)
b.flat("gd_4_4", 4, 4, 0.0, LAWN)
b.flat("gd_5_4", 5, 4, 0.0, LAWN)
b.flat("gd_6_4", 6, 4, 0.0, LAWN)

# =================================================================
# 2. 藤蔓廊架 (x [0,2], y [0,4]): 4 榀门式框连成筒
# =================================================================
for y in range(4):
    b.wall_ew(f"pg_w_{y}", 0.0, y, 0, POST)
    b.wall_ew(f"pg_e_{y}", 2.0, y, 0, POST)
    b.flat_rect(f"pg_top_{y}", 0, y, 1.0, VINE1 if y % 2 == 0 else VINE2)

# =================================================================
# 3. 花圃 A [3,5]x[1,2]: 四墙合环 + 花朵骑沿
# =================================================================
b.wall_ns("ba_s_3", 3, 1.0, 0, BED)
b.wall_ns("ba_s_4", 4, 1.0, 0, BED)
b.wall_ns("ba_n_3", 3, 2.0, 0, BED)
b.wall_ns("ba_n_4", 4, 2.0, 0, BED)
b.wall_ew("ba_w", 3.0, 1, 0, BED)
b.wall_ew("ba_e", 5.0, 1, 0, BED)
b.crest_ns("ba_fl_s", 3, 1.0, 1.0, "red")      # 南沿红花
b.crest_ns("ba_fl_n", 4, 2.0, 1.0, "pink")     # 北沿粉花

# =================================================================
# 4. 花圃 B [5,7]x[0,1]: 四墙合环 + 花朵骑沿
# =================================================================
b.wall_ns("bb_s_5", 5, 0.0, 0, BED)
b.wall_ns("bb_s_6", 6, 0.0, 0, BED)
b.wall_ns("bb_n_5", 5, 1.0, 0, BED)
b.wall_ns("bb_n_6", 6, 1.0, 0, BED)
b.wall_ew("bb_w", 5.0, 0, 0, BED)
b.wall_ew("bb_e", 7.0, 0, 0, BED)
b.crest_ns("bb_fl_s", 5, 0.0, 1.0, "yellow")   # 南沿黄花
b.crest_ns("bb_fl_n", 6, 1.0, 1.0, "red")      # 北沿红花

# =================================================================
# 5. 观蝶亭 (5,3): 四面窗格方 + 等腰四坡花冠顶
# =================================================================
b.add("kk_s", "window_square", (5.5, 3.0, 0.5), (90, 0, 0), KIOSK)
b.add("kk_n", "window_square", (5.5, 4.0, 0.5), (90, 0, 0), KIOSK)
b.add("kk_w", "window_square", (5.0, 3.5, 0.5), (90, 0, 90), KIOSK)
b.add("kk_e", "window_square", (6.0, 3.5, 0.5), (90, 0, 90), KIOSK)
b.hat4("kk_hat", 5, 3, 1.0, HAT)

# =================================================================
# 6. 立体蝴蝶 x3: 双翅 45 度对开
# =================================================================
# 1 号: 停在北草坪拼缝 (x=5, y [4,5]), 紫/粉双翅向东西张开
wings("bf1", (5.0, 4.0, 0.0), (5.0, 5.0, 0.0), "x", "purple", "pink")
# 2 号: 停在东草坪拼缝 (y=2, x [6,7]), 青/蓝双翅向南北张开
wings("bf2", (6.0, 2.0, 0.0), (7.0, 2.0, 0.0), "y", "cyan", "blue")
# 3 号: 停在花圃 A 东槽沿 (x=5, y [1,2], z=1), 黄/红双翅向东西张开
wings("bf3", (5.0, 1.0, 1.0), (5.0, 2.0, 1.0), "x", "yellow", "red")

# =================================================================
# 教程步骤 (14 步)
# =================================================================
b.step(
    "铺廊下石径与柱脚 (x [0,2], y [0,5]): 两列方板, 石径居中。",
    [f"gd_0_{y}" for y in range(4)] + [f"gd_1_{y}" for y in range(4)]
    + ["gd_0_4", "gd_1_4"],
    tip="廊架的八只柱脚都要踩在方板整边上 —— 先铺对地面。",
)
b.step(
    "铺中部草坪与花圃土: 方板为主, 橙色是花圃的种植土。",
    ["gd_2_0", "gd_3_0", "gd_4_0", "bd_b_w", "bd_b_e",
     "gd_2_1", "bd_a_w", "bd_a_e", "gd_5_1", "gd_6_1"],
    highlight=["gd_1_0"],
    tip="两块橙色土各 2 格 —— 花圃墙就围着它们合环。",
)
b.step(
    "铺北半草坪与亭基: 长板收边, 灰色方板是观蝶亭的亭基。",
    ["gd_2_2", "gd_4_2", "gd_6_2", "gd_2_3", "gd_4_3", "gd_5_3", "gd_6_3",
     "gd_2_4", "gd_4_4", "gd_5_4", "gd_6_4"],
    highlight=["gd_2_1", "gd_6_1"],
    tip="花园 7x5 合拢 —— 蝴蝶就停在这些拼缝上。",
)
b.step(
    "立廊架南两榀立柱: 4 片灰墙分立石径两侧 (x=0 与 x=2)。",
    ["pg_w_0", "pg_e_0", "pg_w_1", "pg_e_1"],
    highlight=["gd_1_0", "gd_1_1"],
    tip="相邻立柱竖边互咬 —— 一整面柱列比单柱稳得多。",
)
b.step(
    "立廊架北两榀立柱: 再立 4 片, 柱列贯通 4 格。",
    ["pg_w_2", "pg_e_2", "pg_w_3", "pg_e_3"],
    highlight=["pg_w_1", "pg_e_1"],
    tip="八柱两列对齐 —— 棚板一搭就是一条绿廊。",
)
b.step(
    "搭藤蔓棚板: 4 片长板横跨双柱 (两短边同吸柱顶), 绿/透明相间。",
    ["pg_top_0", "pg_top_1", "pg_top_2", "pg_top_3"],
    highlight=["pg_w_0", "pg_e_3"],
    tip="相邻棚板长边拼缝互吸 —— 四榀门式刚架连成筒, 藤蔓漏下光斑。",
)
b.step(
    "围花圃 A ([3,5]x[1,2]): 6 片橙墙绕种植土合环。",
    ["ba_s_3", "ba_s_4", "ba_n_3", "ba_n_4", "ba_w", "ba_e"],
    highlight=["bd_a_w", "bd_a_e"],
    tip="墙脚踩着土格方板整边 —— 四角竖边互吸自锁。",
)
b.step(
    "围花圃 B ([5,7]x[0,1]): 再围 6 片, 两座花圃斜角相望。",
    ["bb_s_5", "bb_s_6", "bb_n_5", "bb_n_6", "bb_w", "bb_e"],
    highlight=["bd_b_w", "bd_b_e"],
    tip="花圃 B 的西北角正好咬住花圃 A 的东南角气场 —— 蝶道就从中间过。",
)
b.step(
    "花开满圃: 红粉黄 4 朵等边三角花骑上槽沿 (槽沿+墙顶一线双吸)。",
    ["ba_fl_s", "ba_fl_n", "bb_fl_s", "bb_fl_n"],
    highlight=["ba_s_3", "bb_n_6"],
    tip="花朵重心正压槽沿线 —— 蜜就藏在花心里, 等蝴蝶来。",
)
b.step(
    "立观蝶亭: 4 扇透明窗格方围 (5,3) 一圈, 360 度看蝶不惊蝶。",
    ["kk_s", "kk_n", "kk_w", "kk_e"],
    highlight=["gd_5_3"],
    tip="窗格方物理上按实心方片拼接 —— 亭里的孩子看得见每一只蝶。",
)
b.step(
    "戴亭顶花冠: 4 片粉色等腰三角四坡收尖 (亭尖 2.94, 全场最高)。",
    ["kk_hat_s", "kk_hat_e", "kk_hat_n", "kk_hat_w"],
    highlight=["kk_s"],
    tip="四条斜棱两两互吸自锁成环 —— 花冠顶就是亭子的招牌。",
)
b.step(
    "1 号蝴蝶落北草坪: 紫/粉双翅从拼缝向两侧 45 度张开。",
    ["bf1_a", "bf1_b"],
    highlight=["gd_4_4", "gd_5_4"],
    tip="两片翅膀底边共吸一条缝、彼此再互吸 —— 夹角 90 度像正要起飞。",
)
b.step(
    "2 号蝴蝶落东草坪: 青/蓝双翅向南北张开。",
    ["bf2_a", "bf2_b"],
    highlight=["gd_6_1", "gd_6_2"],
    tip="单翅力矩只有 2.7 g·单位 —— 蝴蝶站得比看起来稳。",
)
b.step(
    "3 号蝴蝶落花圃槽沿: 黄/红双翅落在花圃 A 东墙顶上 —— 别出声!",
    ["bf3_a", "bf3_b"],
    highlight=["ba_e", "ba_fl_n"],
    tip="它停在离花最近的地方 —— 观蝶亭里刚好看个正着。",
)

b.finalize(
    model_id="butterfly_garden_01",
    name="蝴蝶花园",
    name_en="Butterfly Garden 01",
    description=(
        "只用核心九片型的观蝶花园: 招牌是三只'立起来'的蝴蝶 ——"
        " 每只两片等边三角从同一条拼缝向两侧 45 度张开 (底边共吸"
        "一条线、彼此再互吸), 双翅夹角 90 度像正要起飞, 单翅力矩"
        " 2.7 远小于预算; 入园主轴是 4 格深的藤蔓廊架 —— 每榀双柱"
        "托横板双端受力, 相邻棚板长边拼缝互吸、立柱竖边互咬, 四榀"
        "门式刚架连成绿/透明相间的漏光绿廊; 廊外两座花圃四墙合环,"
        " 红粉黄花朵骑槽沿, 东侧 1x1 观蝶亭四面窗格方 360 度透明,"
        " 戴粉色等腰四坡花冠顶 —— 悄悄走进亭子, 别惊飞槽沿上那只。"
    ),
    difficulty=3,
    tags=["动物园", "野生动物", "蝴蝶", "花园", "进阶"],
    min_pieces=73,
    min_steps=14,
)
