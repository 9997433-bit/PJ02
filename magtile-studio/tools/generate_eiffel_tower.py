#!/usr/bin/env python3
"""生成模型 data/models/eiffel_tower_01.json (埃菲尔铁塔)。

第二批模型 ⑫: 世界地标主题 —— 埃菲尔铁塔: 5x5 林荫广场中央
四条拱脚桥墩托起第一观景台, 八根斜撑收出铁塔的"肩线", 1x1 塔身
截面直上第二观景台与塔顶, 最后以四坡尖顶收官 —— 从侧面看
就是那个经典的 A 字剪影。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 广场: 3x3 环形绿地 (中心留空当拱门庭院)                    8 片
  - 外环林荫道: 5x5 外圈 16 片 (石板走道正对四面拱门)          16 片
  - 四条塔脚 (z 0..2): 每脚两面外壳墙 x 2 层                  16 片
  - 塔脚护撑: 四角外侧 8 根直角三角斜撑                         8 片
  - 拱门楣板: 四面拱门上沿各 1 片 (z 1..2)                      4 片
  - 第一观景台 (z=2): 3x3 平台                                  9 片
  - 观景台护栏: 四沿 8 片红色等边三角                            8 片
  - 塔身下段 (z 2..4): 1x1 箱形筒 2 层 + 肩线斜撑 8            16 片
  - 第二观景台 (z=4): 平台 1 片                                  1 片
  - 塔身上段 (z 4..5): 1x1 箱形筒 1 层 + 顶板                   5 片
  - 塔尖: 四坡等腰尖顶 (锥尖高 5.87)                             4 片
  合计 95 片, 21 个教程步骤, 4 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 塔脚是 L 形双墙外壳, 与广场、拱楣、观景台锁成环;
  - 外环林荫道整边吸内圈绿地, 并接住 8 根拱脚护撑的水平直角边;
  - 肩线斜撑水平边吸观景台接缝、竖直边吸塔身竖边 (三角刚性节点);
  - 塔身全程 1x1 箱形筒 + 层层压板, 高塔冗余充足。

用法: python3 tools/generate_eiffel_tower.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

# =================================================================
# 1. 广场: 3x3 环形绿地 (中心 [1,2]x[1,2] 留空)
# =================================================================
for x in range(3):
    for y in range(3):
        if (x, y) == (1, 1):
            continue
        b.flat(f"pz_{x}_{y}", x, y, 0.0, "green")

# 外环林荫道: 5x5 外圈 16 片; 正对四面拱门的走道换灰色石板,
# 其余为绿地 —— 外圈还负责接住 8 根拱脚护撑的水平直角边
WALKWAYS = {(1, -1), (1, 3), (-1, 1), (3, 1)}
RING = [(x, y) for y in range(-1, 4) for x in range(-1, 4)
        if not (0 <= x <= 2 and 0 <= y <= 2)]
for x, y in RING:
    b.flat(f"rg_{x + 1}_{y + 1}", x, y, 0.0,
           "gray" if (x, y) in WALKWAYS else "green")

# =================================================================
# 2. 四条塔脚 (z 0..2): 每脚两面外壳墙 (L 形), 叠 2 层
#    脚位: 西南(0,0) 东南(2,0) 东北(2,2) 西北(0,2)
# =================================================================
LEGS = {
    "sw": ((0, 0.0), (0.0, 0)),      # (wall_ns 参数, wall_ew 参数)
    "se": ((2, 0.0), (3.0, 0)),
    "ne": ((2, 3.0), (3.0, 2)),
    "nw": ((0, 3.0), (0.0, 2)),
}
for name, ((nx, ny), (ex, ey)) in LEGS.items():
    for z in range(2):
        b.wall_ns(f"lg_{name}_a{z}", nx, ny, z, "gray")   # 南北向外壳
        b.wall_ew(f"lg_{name}_b{z}", ex, ey, z, "gray")   # 东西向外壳

# =================================================================
# 3. 塔脚护撑: 四角外侧 8 根直角三角斜撑 (斜脚的意象)
# =================================================================
b.brace("bt_sw_x", (0.0, 0.0, 0.0), "-x", "orange")
b.brace("bt_sw_y", (0.0, 0.0, 0.0), "-y", "orange")
b.brace("bt_se_x", (3.0, 0.0, 0.0), "+x", "orange")
b.brace("bt_se_y", (3.0, 0.0, 0.0), "-y", "orange")
b.brace("bt_ne_x", (3.0, 3.0, 0.0), "+x", "orange")
b.brace("bt_ne_y", (3.0, 3.0, 0.0), "+y", "orange")
b.brace("bt_nw_x", (0.0, 3.0, 0.0), "-x", "orange")
b.brace("bt_nw_y", (0.0, 3.0, 0.0), "+y", "orange")

# =================================================================
# 4. 拱门楣板 (z 1..2): 四面拱门上沿, 竖边吸两侧塔脚
# =================================================================
b.wall_ns("ar_s", 1, 0.0, 1, "yellow")
b.wall_ns("ar_n", 1, 3.0, 1, "yellow")
b.wall_ew("ar_w", 0.0, 1, 1, "yellow")
b.wall_ew("ar_e", 3.0, 1, 1, "yellow")

# =================================================================
# 5. 第一观景台 (z=2): 3x3 平台 + 四沿护栏
# =================================================================
for x in range(3):
    for y in range(3):
        b.flat(f"d1_{x}_{y}", x, y, 2.0, "gray")
for x in (0, 2):
    b.crest_ns(f"rl_s_{x}", x, 0.0, 2.0, "red")
    b.crest_ns(f"rl_n_{x}", x, 3.0, 2.0, "red")
for y in (0, 2):
    b.crest_ew(f"rl_w_{y}", 0.0, y, 2.0, "red")
    b.crest_ew(f"rl_e_{y}", 3.0, y, 2.0, "red")

# =================================================================
# 6. 塔身下段 (z 2..4): 1x1 箱形筒 2 层 + 肩线斜撑 8
# =================================================================
for z in (2, 3):
    b.wall_ns(f"sh_s_{z}", 1, 1.0, z, "gray" if z == 2 else "clear")
    b.wall_ns(f"sh_n_{z}", 1, 2.0, z, "gray" if z == 2 else "clear")
    b.wall_ew(f"sh_w_{z}", 1.0, 1, z, "gray" if z == 2 else "clear")
    b.wall_ew(f"sh_e_{z}", 2.0, 1, z, "gray" if z == 2 else "clear")
b.brace("sd_sw_x", (1.0, 1.0, 2.0), "-x", "orange")
b.brace("sd_sw_y", (1.0, 1.0, 2.0), "-y", "orange")
b.brace("sd_se_x", (2.0, 1.0, 2.0), "+x", "orange")
b.brace("sd_se_y", (2.0, 1.0, 2.0), "-y", "orange")
b.brace("sd_ne_x", (2.0, 2.0, 2.0), "+x", "orange")
b.brace("sd_ne_y", (2.0, 2.0, 2.0), "+y", "orange")
b.brace("sd_nw_x", (1.0, 2.0, 2.0), "-x", "orange")
b.brace("sd_nw_y", (1.0, 2.0, 2.0), "+y", "orange")

# =================================================================
# 7. 第二观景台 (z=4) + 塔身上段 (z 4..5) + 顶板 + 塔尖
# =================================================================
b.flat("d2", 1, 1, 4.0, "yellow")
b.wall_ns("tp_s", 1, 1.0, 4, "gray")
b.wall_ns("tp_n", 1, 2.0, 4, "gray")
b.wall_ew("tp_w", 1.0, 1, 4, "gray")
b.wall_ew("tp_e", 2.0, 1, 4, "gray")
b.flat("tp_cap", 1, 1, 5.0, "yellow")
HAT = b.hat4("spire", 1, 1, 5.0, "red")

# =================================================================
# 教程步骤 (21 步)
# =================================================================
b.step(
    "铺设广场: 8 片绿色方板围成 3x3 环形绿地, 中心留空当拱门庭院。",
    [f"pz_{x}_{y}" for x in range(3) for y in range(3) if (x, y) != (1, 1)],
    tip="中间那格故意不铺 —— 游客要从四面拱门穿过塔底。",
)
b.step(
    "铺设外环林荫道南半圈: 7 片方板贴着绿地外沿铺开 (南面正中的"
    "灰色石板走道正对将来的南拱门)。",
    [f"rg_{x + 1}_{y + 1}" for x, y in RING if y <= 0],
    highlight=["pz_1_0", "pz_0_0"],
    tip="外圈每片都与内圈绿地或相邻外圈板整边吸合, 广场才是一整块。",
)
b.step(
    "铺完外环林荫道北半圈: 再补 9 片, 5x5 林荫广场合拢, "
    "四条灰色走道正对四面拱门。",
    [f"rg_{x + 1}_{y + 1}" for x, y in RING if y > 0],
    highlight=["rg_0_0", "rg_4_0"],
    tip="从上往下看: 绿地环抱塔基, 四条石板道通向四方 —— 战神广场就绪。",
)
b.step(
    "竖立南侧两条塔脚下层: 西南、东南脚各 2 面灰色外壳墙, "
    "在拐角处竖边互吸成 L 形。",
    ["lg_sw_a0", "lg_sw_b0", "lg_se_a0", "lg_se_b0"],
    highlight=["pz_0_0", "pz_2_0"],
    tip="L 形双墙比单面墙稳得多 —— 每条塔脚都是一个直角外壳。",
)
b.step(
    "竖立北侧两条塔脚下层: 东北、西北脚与南侧镜像。",
    ["lg_ne_a0", "lg_ne_b0", "lg_nw_a0", "lg_nw_b0"],
    highlight=["lg_sw_a0"],
    tip="四条塔脚立好后, 从正上方看是 4 个指向中心的直角。",
)
b.step(
    "安装南侧塔脚护撑: 西南、东南脚外侧各 2 根橙色直角三角斜撑, "
    "竖直边吸塔脚竖边、水平边落地。",
    ["bt_sw_x", "bt_sw_y", "bt_se_x", "bt_se_y"],
    highlight=["lg_sw_a0"],
    tip="斜撑向外张开 —— 正是铁塔拱脚外扩的经典姿态。",
)
b.step(
    "安装北侧塔脚护撑: 其余 4 根, 八方位全部锁定。",
    ["bt_ne_x", "bt_ne_y", "bt_nw_x", "bt_nw_y"],
    highlight=["bt_sw_x"],
    tip="八根斜撑装完, 用手轻推任何一条塔脚都纹丝不动。",
)
b.step(
    "塔脚加高到 2 层: 南侧两脚各叠 2 面墙。",
    ["lg_sw_a1", "lg_sw_b1", "lg_se_a1", "lg_se_b1"],
    highlight=["lg_sw_a0"],
    tip="上下层墙横边对齐吸合, 塔脚升到拱门的高度。",
)
b.step(
    "北侧两脚同样加高: 四脚齐平 2 层。",
    ["lg_ne_a1", "lg_ne_b1", "lg_nw_a1", "lg_nw_b1"],
    highlight=["lg_sw_a1"],
    tip="检查四脚等高 —— 观景台要同时压住它们。",
)
b.step(
    "安装拱门楣板: 四面拱门上沿各 1 片黄色正方形 (z 1..2), "
    "两条竖边分别吸左右塔脚竖边。",
    ["ar_s", "ar_n", "ar_w", "ar_e"],
    highlight=["lg_sw_a1", "lg_se_a1"],
    tip="楣板一装, 四条塔脚就连成了著名的四面大拱门。",
)
b.step(
    "铺设第一观景台南两排: 6 片灰色方板压在塔脚与楣板顶上。",
    [f"d1_{x}_{y}" for y in (0, 1) for x in range(3)],
    highlight=["ar_s"],
    tip="平台边要与墙顶边整边吸合, 中央那片悬在庭院上空。",
)
b.step(
    "铺完第一观景台: 北排 3 片, 3x3 平台合拢。",
    [f"d1_{x}_{y}" for y in (2,) for x in range(3)],
    highlight=["d1_1_1"],
    tip="9 片平台缝缝相吸 —— 这是整座铁塔的腰部铁环。",
)
b.step(
    "安装南北护栏: 观景台南北沿各 2 片红色等边三角。",
    ["rl_s_0", "rl_s_2", "rl_n_0", "rl_n_2"],
    highlight=["d1_0_0", "d1_2_2"],
    tip="护栏立在平台边沿, 中间留出观景缺口。",
)
b.step(
    "安装东西护栏: 再立 4 片, 第一观景台完工。",
    ["rl_w_0", "rl_w_2", "rl_e_0", "rl_e_2"],
    highlight=["rl_s_0"],
    tip="8 片红色护栏就位, 游客可以凭栏看巴黎了。",
)
b.step(
    "竖立塔身第一层: 观景台正中围出 1x1 箱形筒 (z 2..3), "
    "四面墙在四角竖边互吸。",
    ["sh_s_2", "sh_n_2", "sh_w_2", "sh_e_2"],
    highlight=["d1_1_1"],
    tip="墙底边吸平台接缝 —— 塔身正好骑在观景台正中。",
)
b.step(
    "安装肩线斜撑: 塔身四角各 2 根橙色直角三角形, 水平边吸平台接缝、"
    "竖直边吸塔身竖边。",
    ["sd_sw_x", "sd_sw_y", "sd_se_x", "sd_se_y",
     "sd_ne_x", "sd_ne_y", "sd_nw_x", "sd_nw_y"],
    highlight=["sh_s_2"],
    tip="八根斜撑收出铁塔的\"肩线\" —— A 字剪影的关键一笔。",
)
b.step(
    "塔身升到第二层: 4 面透明墙叠上箱形筒 (z 3..4)。",
    ["sh_s_3", "sh_n_3", "sh_w_3", "sh_e_3"],
    highlight=["sh_s_2"],
    tip="透明层是电梯井 —— 想象小电梯正沿塔身爬升。",
)
b.step(
    "压上第二观景台: 1 片黄色方板盖住箱形筒 (z=4)。",
    ["d2"],
    highlight=["sh_s_3"],
    tip="四边同时吸住四面墙顶, 塔身又锁紧一环。",
)
b.step(
    "竖立塔顶层: 再围 1 层 1x1 箱形筒 (z 4..5)。",
    ["tp_s", "tp_n", "tp_w", "tp_e"],
    highlight=["d2"],
    tip="越往上越细的错觉来自肩线 —— 顶层依旧是稳稳的箱形筒。",
)
b.step(
    "封顶板: 1 片黄色方板盖住塔顶层 (z=5)。",
    ["tp_cap"],
    highlight=["tp_s"],
    tip="这是塔尖的底座, 四边都要吸牢。",
)
b.step(
    "安装塔尖: 4 片红色等腰三角形底边吸顶板四边, 斜棱两两互吸, "
    "锥尖在 5.87 格高处会合 —— 铁塔落成!",
    HAT,
    highlight=["tp_cap"],
    tip="最后一片卡进去, 整个塔尖咔哒自锁 —— 向巴黎致敬!",
)

b.finalize(
    model_id="eiffel_tower_01",
    name="埃菲尔铁塔",
    name_en="Eiffel Tower 01",
    description=(
        "世界地标系列: 5x5 林荫广场中央四条 L 形塔脚围出四面大拱门 (灰色石板"
        "走道正对拱门), 八根斜撑张开拱脚、八根斜撑收出肩线, 第一观景台红色"
        "护栏环绕, 1x1 箱形塔身经第二观景台直上塔顶, 四坡红色塔尖在 5.87 格"
        "高处自锁会合 —— 从侧面看就是那个经典的 A 字剪影。"
    ),
    difficulty=4,
    tags=["世界地标", "高塔", "工程", "进阶"],
    min_pieces=85,
    min_steps=20,
)
