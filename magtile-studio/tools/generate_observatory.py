#!/usr/bin/env python3
"""生成模型 data/models/observatory_01.json (山顶天文台)。

科学探索主题: 全库第一座"叠环鼓身"建筑 —— 塔身不用一片正方形墙,
而是三层长方形横砌成的自锁叠环 (每环 4 片长方形拐角竖边互吸,
上环底边整边吸下环顶边); 环顶直接生长出两级棱面穹顶:
下级 4 片梯形收口, 上级 4 片等边三角形锁尖, 其中一条经线整体
透明 —— 那是望远镜的观测缝。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 观星广场: 塔基外环 (方板 8 + 长板 2) + 六边形星图 + 日晷 + 灌木 13 片
  - 叠环鼓身 (x 1..3, y 1..3, z 0..3): 三层长方形自锁环,
    底层南面留 2 格宽拱门, 顶层东面透明采光                       11 片
  - 望远镜厅: 厅内地板长板 x2 + 赤道仪基墩 + 梯形接收架             4 片
  - 两级棱面穹顶: 4 片梯形 + 4 片等边三角形, 东经线透明观测缝       8 片
  - 控制室附楼 (x 4..6, y 1..3): 一层四壁 (朝塔留门) + 平顶 + 双天线 13 片
  - 广场旗饰: 四向 4 片等边三角旗                                   4 片
  合计 53 片, 16 个教程步骤。

物理规则要点 (通过 R1~R8 全部校验):
  - 叠环鼓身: 每片长方形的两端竖边与相邻环片互吸, 四片成环自锁;
    上环底边 (长 2) 与下环顶边等长整边贴合, 力纯竖向传递;
  - 底层拱门: 上环南片充当门楣, 两端竖边吸东西环片竖边 (三边受力);
  - 穹顶: 梯形下底 (长 2) 恰与环顶边等长互吸, 四腰两两互吸;
    等边三角形底边吸梯形上底 (长 1), 斜棱互吸锁尖 —— 两级都自锁;
  - 望远镜基墩接地且先于穹顶安装, 顶口敞开时从上方伸手可达 (R7b)。

用法: python3 tools/generate_observatory.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import EQ_APEX, ModelBuilder, _sub  # noqa: E402

b = ModelBuilder()

# =================================================================
# 1. 观星广场: 4x4 外环 (中央 2x2 留给鼓身)
#    西/北两侧用平铺长方形 —— 长边 (长 2) 恰与鼓身长方形底边
#    等长整边互吸, 把叠环鼓身焊在广场上
# =================================================================
for x0 in range(4):                              # 南排 4 片方板
    b.flat(f"pz_{x0}_0", x0, 0, 0.0, "gray" if x0 % 2 == 0 else "blue")
b.flat_rect("pw", 0, 1, 0.0, "blue", axis="y")   # 西侧长板 (x 0..1, y 1..3)
b.flat_rect("pn", 1, 3, 0.0, "blue", axis="x")   # 北侧长板 (x 1..3, y 3..4)
b.flat("pz_0_3", 0, 3, 0.0, "gray")              # 西北角
b.flat("pz_3_3", 3, 3, 0.0, "gray")              # 东北角
b.flat("pz_3_1", 3, 1, 0.0, "blue")              # 东侧两片方板
b.flat("pz_3_2", 3, 2, 0.0, "gray")              # (附楼西门要吸在这片边上)

# ---- 南侧六边形星图 + 日晷尖 (北边整边吸广场南沿) ----------------
b.add("starmap", "hexagon", (1.5, -0.866025, 0.0), (0, 0, 0), "purple")
b.spire_ns("sundial", 1, -1.732051, 0.0, "yellow")
b.crest_ns("shrub", 2, 0.0, 0.0, "green")        # 广场南沿灌木

# =================================================================
# 2. 叠环鼓身 (x 1..3, y 1..3): 三层长方形自锁环
#    底层南面留拱门 (3 片), 中层南片即门楣 (4 片), 顶层东面透明 (4 片)
# =================================================================
b.lintel_ew("dr0_w", 1.0, 1, 0, "gray")     # 底环西片
b.lintel_ns("dr0_n", 1, 3.0, 0, "gray")     # 底环北片
b.lintel_ew("dr0_e", 3.0, 1, 0, "gray")     # 底环东片 (南面 = 拱门)
b.lintel_ew("dr1_w", 1.0, 1, 1, "blue")     # 中环西片
b.lintel_ns("dr1_n", 1, 3.0, 1, "blue")     # 中环北片
b.lintel_ew("dr1_e", 3.0, 1, 1, "blue")     # 中环东片
b.lintel_ns("dr1_s", 1, 1.0, 1, "yellow")   # 中环南片 = 拱门门楣
b.lintel_ew("dr2_w", 1.0, 1, 2, "gray")     # 顶环西片
b.lintel_ns("dr2_n", 1, 3.0, 2, "gray")     # 顶环北片
b.lintel_ew("dr2_e", 3.0, 1, 2, "clear")    # 顶环东片 (透明采光带)
b.lintel_ns("dr2_s", 1, 1.0, 2, "gray")     # 顶环南片

# =================================================================
# 3. 望远镜厅: 鼓身内部地板 (2 片平铺长方形, 长边整边吸鼓身底边)
#    + 中缝立起赤道仪基墩 (竖立长方形) + 顶边接收架 (竖立梯形)
#    —— 全部先于穹顶安装 (R7b: 封口前从上方伸手可达)
# =================================================================
b.flat_rect("fl_w", 1, 1, 0.0, "gray", axis="y")   # 厅内地板西半 (x 1..2)
b.flat_rect("fl_e", 2, 1, 0.0, "gray", axis="y")   # 厅内地板东半 (x 2..3)
b.lintel_ew("pier", 2.0, 1, 0, "orange")           # 赤道仪基墩: 立在地板中缝上
b.place_edge("dish", "trapezoid", 0,
             (2.0, 1.0, 1.0), (2.0, 3.0, 1.0), (0, 0, 1), "red")  # 接收架

# =================================================================
# 4. 两级棱面穹顶: 4 片梯形 (z 3 -> 3.707) + 4 片等边三角形锁尖
#    东经线 (梯形 + 三角) 整体透明 = 观测缝
# =================================================================
ZT = 3.0 + EQ_APEX                          # 梯形上底高度 3.707107
TRAP_FACES = {
    "s": ((1.0, 1.0, 3.0), (3.0, 1.0, 3.0), (2.0, 1.5, ZT), "cyan"),
    "e": ((3.0, 1.0, 3.0), (3.0, 3.0, 3.0), (2.5, 2.0, ZT), "clear"),
    "n": ((3.0, 3.0, 3.0), (1.0, 3.0, 3.0), (2.0, 2.5, ZT), "cyan"),
    "w": ((1.0, 3.0, 3.0), (1.0, 1.0, 3.0), (1.5, 2.0, ZT), "cyan"),
}
for side, (b0, b1, top_mid, color) in TRAP_FACES.items():
    bottom_mid = tuple((b0[i] + b1[i]) / 2 for i in range(3))
    b.place_edge(f"dome_{side}", "trapezoid", 0, b0, b1,
                 _sub(top_mid, bottom_mid), color)

APEX = (2.0, 2.0, ZT + EQ_APEX)             # 锥尖 z = 4.414
CAP_BASES = {
    "s": ((1.5, 1.5, ZT), (2.5, 1.5, ZT), "cyan"),
    "e": ((2.5, 1.5, ZT), (2.5, 2.5, ZT), "clear"),
    "n": ((2.5, 2.5, ZT), (1.5, 2.5, ZT), "cyan"),
    "w": ((1.5, 2.5, ZT), (1.5, 1.5, ZT), "cyan"),
}
for side, (b0, b1, color) in CAP_BASES.items():
    b.place_tri(f"cap_{side}", "equilateral_triangle", b0, b1, APEX, color)

# =================================================================
# 5. 控制室附楼 (x 4..6, y 1..3): 一层四壁 (西面朝塔留门) + 平顶
# =================================================================
for x0 in (4, 5):
    b.wall_ns(f"ax_s_{x0}", x0, 1.0, 0, "orange")
    b.wall_ns(f"ax_n_{x0}", x0, 3.0, 0, "orange")
for y0 in (1, 2):
    b.wall_ew(f"ax_e_{y0}", 6.0, y0, 0, "orange")
b.wall_ew("ax_w", 4.0, 2, 0, "orange")      # 西面 y 1..2 留门通向塔
for x0 in (4, 5):
    for y0 in (1, 2):
        b.flat(f"ax_rf_{x0}_{y0}", x0, y0, 1.0, "gray")
b.crest_ns("antenna", 4, 3.0, 1.0, "red")   # 屋顶通讯天线
b.crest_ew("antenna2", 6.0, 1, 1.0, "red")  # 屋顶东沿第二根天线

# =================================================================
# 6. 广场旗饰: 四向 4 片等边三角旗
# =================================================================
b.crest_ns("flag_s", 0, 0.0, 0.0, "green")
b.crest_ns("flag_n", 3, 4.0, 0.0, "green")
b.crest_ew("flag_w", 0.0, 3, 0.0, "green")
b.crest_ew("flag_e", 4.0, 0, 0.0, "green")

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "观星广场南排: 4 片方板一字铺开 (x 0..4, y 0..1), 灰蓝相间。",
    ["pz_0_0", "pz_1_0", "pz_2_0", "pz_3_0"],
    tip="中央 2x2 空位是鼓身的地基 —— 广场只围不占。",
)
b.step(
    "广场合围: 西/北各平铺 1 片长板 (2 格长), 东侧 2 片方板, "
    "再补东北西北两角 —— 外环合拢。",
    ["pw", "pn", "pz_3_1", "pz_3_2", "pz_0_3", "pz_3_3"],
    highlight=["pz_0_0", "pz_3_0"],
    tip="西/北的长板长边留给鼓身底边整边吸合 —— 这是塔的地锚。",
)
b.step(
    "六边形星图: 紫色六边形北边整边吸广场南沿 (x 1..2), 上面立 1 片"
    "黄色日晷尖, 旁边再种 1 丛绿色灌木。",
    ["starmap", "sundial", "shrub"],
    highlight=["pz_1_0", "pz_2_0"],
    tip="六边形的边长与方板边长通用, 对准 x 1..2 那一段再放。",
)
b.step(
    "鼓身底环: 3 片灰色长方形横立成 U 形 (西/北/东), 拐角竖边两两"
    "互吸; 西/北两片底边整边吸住广场长板边, 南面整面留空作拱门。",
    ["dr0_w", "dr0_n", "dr0_e"],
    highlight=["pw", "pn"],
    tip="长方形横着立 —— 一片顶两格宽, 三片就围出大半个塔身。",
)
b.step(
    "望远镜厅: 塔内平铺 2 片地板长方形 (长边分别吸鼓身东西底边), "
    "中缝立起橙色赤道仪基墩, 基墩顶边再立 1 片红色梯形接收架 —— "
    "趁塔顶敞开先装好内部设备。",
    ["fl_w", "fl_e", "pier", "dish"],
    highlight=["dr0_w", "dr0_e"],
    tip="等穹顶封了口, 手就伸不进去了 —— 内部件永远先装。",
)
b.step(
    "鼓身中环 U 形: 西/北/东 3 片蓝色长方形整边叠上底环顶边。",
    ["dr1_w", "dr1_n", "dr1_e"],
    highlight=["dr0_w", "dr0_e"],
    tip="上环底边与下环顶边等长, 整边贴合才吸得实。",
)
b.step(
    "拱门门楣: 黄色长方形横跨拱门上方, 两端竖边分别吸中环西片与"
    "东片的竖边 —— 三边受力的过梁。",
    ["dr1_s"],
    highlight=["dr1_w", "dr1_e"],
    tip="门楣下方是 2 格宽的拱门 —— 观测员推着仪器车进出无碍。",
)
b.step(
    "鼓身顶环: 4 片长方形合成完整一环, 东面用透明片作采光带。",
    ["dr2_w", "dr2_n", "dr2_e", "dr2_s"],
    highlight=["dr1_s", "dr1_n"],
    tip="顶环四片拐角全部互吸, 是承接穹顶的刚性环梁。",
)
b.step(
    "穹顶下级·南北面: 2 片青色梯形下底整边吸顶环顶边, 向内倾斜。",
    ["dome_s", "dome_n"],
    highlight=["dr2_s", "dr2_n"],
    tip="梯形下底长 2, 恰与长方形顶边等长 —— 这就是叠环的深意。",
)
b.step(
    "穹顶下级·东西面: 再上 2 片, 四腰两两互吸收成 1x1 顶口; "
    "东面这片用透明 —— 观测缝的下半段。",
    ["dome_e", "dome_w"],
    highlight=["dome_s", "dome_n"],
    tip="腰边卡进相邻梯形的瞬间会咔哒一声 —— 那是自锁完成。",
)
b.step(
    "穹顶上级锁尖: 4 片等边三角形底边吸梯形上底, 斜棱两两互吸, "
    "锥尖在 z=4.41 合拢; 东面透明片接上观测缝。",
    ["cap_s", "cap_e", "cap_n", "cap_w"],
    highlight=["dome_e", "dome_w"],
    tip="从东侧看: 透明经线从环顶一直贯到锥尖 —— 星光的通道。",
)
b.step(
    "附楼起步: 西墙底边吸广场东板边, 再沿拐角一路吸出北墙 2 片、"
    "东墙 2 片 —— 控制室的 C 形外廓。",
    ["ax_w", "ax_n_4", "ax_n_5", "ax_e_2", "ax_e_1"],
    highlight=["pz_3_2"],
    tip="先装吸着广场板边的西墙, 其余墙沿它的拐角一路吸过去。",
)
b.step(
    "附楼南墙: 2 片补齐南面, 西南角留出通向塔身拱门的室内门洞。",
    ["ax_s_5", "ax_s_4"],
    highlight=["ax_e_1", "ax_w"],
    tip="观测员从控制室穿过这道门, 十步就到望远镜脚下。",
)
b.step(
    "附楼平顶: 4 片灰色方板压住四面墙顶, 控制室封顶。",
    [f"ax_rf_{x0}_{y0}" for x0 in (4, 5) for y0 in (1, 2)],
    highlight=["ax_w", "ax_e_1"],
    tip="每片顶板至少压住一段墙顶边, 四片再彼此互吸成整板。",
)
b.step(
    "屋顶双天线: 顶板北沿与东沿各立 1 根红色三角天线 —— 对接"
    "天文台网络。",
    ["antenna", "antenna2"],
    highlight=["ax_rf_4_2", "ax_rf_5_1"],
    tip="天线底边吸顶板边, 竖直立件不产生任何力矩。",
)
b.step(
    "四向旗饰: 广场东南西北各立 1 面绿旗, 山顶天文台落成!",
    ["flag_s", "flag_n", "flag_w", "flag_e"],
    highlight=["pz_0_0", "pz_3_3"],
    tip="夜幕降临, 观测缝对准东方 —— 今晚看木星。",
)

b.finalize(
    model_id="observatory_01",
    name="山顶天文台",
    name_en="Mountain Observatory 01",
    description=(
        "全库第一座叠环建筑: 鼓身由三层长方形横砌自锁环叠成 (拐角竖边"
        "互吸、上环整边压下环), 底层留 2 格拱门、门楣三边受力; 环顶直接"
        "生长两级棱面穹顶 —— 梯形收口、等边三角锁尖, 东经线整体透明就是"
        "望远镜的观测缝。塔内先装 L 形基墩与镜筒, 东侧控制室附楼与塔身"
        "由室内通道相连。"
    ),
    difficulty=3,
    tags=["科学探索", "建筑", "天文", "穹顶"],
    min_pieces=50,
    min_steps=16,
)
