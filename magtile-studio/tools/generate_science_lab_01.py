#!/usr/bin/env python3
"""生成模型 data/models/science_lab_01.json (科学实验室)。

校园/学校主题批 2/4: 全库第一间校园科学实验室 —— 与
robot_lab_01 (机器人检修实验室: 梳状充电坞 + 箱式机器人) 刻意
区分: 本作的结构签名是"剖面教室 + 玻璃天窗锥 + 排风塔" ——
三面墙的实验室南面整个敞开 (剖面视角), 屋顶只盖北半跨, 正中
留 1x1 洞口由透明等边四坡玻璃天窗锥封住 (三边吸沿 + 四棱互吸
自锁); 敞开的前半间摆着实验台矩阵: 双柱长台 + 方箱小台共墙
相连, 台面沿口骑着红/绿/橙三只烧瓶; 西山墙外一座两层排风塔
借实验室西墙合环, 塔顶灰色排风尖直上 4.0 全场制高。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 实验室朝南敞开):
  - 校园地坪 7x4: 门前空地 + 实验室内地坪 + 后侧绿化           21 片
  - 实验室三面墙 (x [1,6], y [1,3], 高 2): 一层素墙 x9 +
    二层窗格方 x5 / 素墙 x4                                     18 片
  - 北半跨屋顶 (y [2,3], z=2): 方板 x4 + 玻璃天窗锥 x4           8 片
  - 排风塔 (x [0,1], y [2,3], 高 2): 借西墙合环 x6 + 压顶 +
    排风尖 (顶 4.0)                                              8 片
  - 长实验台 (x [2,4]): 前后长楣 + 侧墙合环 + 台面               5 片
  - 方实验台 (x [4,5]): 借长台东墙合环 + 台面                    4 片
  - 烧瓶 x3: 等边三角骑台面沿口                                  3 片
  合计 67 片, 14 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 屋顶方板北边整边压北墙顶、侧边吸山墙顶/邻板, 南边仅挑出
    半格 (重心距铰链 0.5, 力矩远小于 strict 抗弯预算);
  - 玻璃天窗锥: 西/北/东三条底边分别吸邻板边与北墙顶, 南底边
    临空但四条斜棱两两互吸自锁成环;
  - 排风塔借实验室西墙合环 (共墙即共保险), 塔顶压顶方板东沿
    与屋顶西板共线互吸, 塔身与主体锁成一体; 排风尖底边
    "压顶北沿 + 塔北墙顶"一线双吸;
  - 长台台面: 南北长边各整边吸长楣顶 (2.0 对 2.0 等长), 东西
    短边吸侧墙顶 —— 四边全锁; 方台借长台东墙, 烧瓶骑沿口
    (台面沿 + 墙顶一线双吸) 力矩为零;
  - 地坪拼缝纪律: 墙脚与台脚线处全单位方板/等长长板拼缝。

用法: python3 tools/generate_science_lab_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

APRON = "gray"       # 门前空地
FLOOR = "cyan"       # 实验室内地坪
GREEN = "green"      # 后侧绿化
WALL = "clear"       # 实验室素墙 (白)
WIN = "clear"        # 高窗窗格方
ROOF = "blue"        # 屋顶
SKY = "clear"        # 玻璃天窗锥
TOWER = "purple"     # 排风塔
VENT = "gray"        # 排风尖
BENCH = "orange"     # 实验台 (木)
TOP = "gray"         # 台面
FLASK_R = "red"      # 烧瓶
FLASK_G = "green"
FLASK_O = "orange"


# =================================================================
# 1. 校园地坪 7x4 (x [0,7], y [0,4]): 拼缝纪律 —— 墙脚/台脚线处
#    必须有等长拼缝; 相邻行至少一对等长边互吸。
# =================================================================
# 门前空地 (y [0,1])
b.flat_rect("g_0_w", 0, 0, 0.0, APRON)
b.flat_rect("g_0_m", 2, 0, 0.0, APRON)
b.flat_rect("g_0_e", 4, 0, 0.0, APRON)
b.flat("g_0_6", 6, 0, 0.0, GREEN)
# 实验室前半间 (y [1,2]): 台脚线处单位方板 / 长台脚下等长长板
b.flat("g_1_0", 0, 1, 0.0, APRON)
b.flat("g_1_1", 1, 1, 0.0, FLOOR)
b.flat_rect("g_bench", 2, 1, 0.0, FLOOR)           # 长台脚下 (南北边等长 2.0)
b.flat("g_1_4", 4, 1, 0.0, FLOOR)                  # 方台脚下
b.flat("g_1_5", 5, 1, 0.0, FLOOR)
b.flat("g_1_6", 6, 1, 0.0, GREEN)
# 实验室后半间 (y [2,3]): 北墙脚线处全单位方板
b.flat("g_2_0", 0, 2, 0.0, APRON)                  # 排风塔脚下
for x in range(1, 6):
    b.flat(f"g_2_{x}", x, 2, 0.0, FLOOR)
b.flat("g_2_6", 6, 2, 0.0, GREEN)
# 后侧绿化 (y [3,4])
b.flat_rect("g_3_w", 0, 3, 0.0, GREEN)
b.flat_rect("g_3_m", 2, 3, 0.0, GREEN)
b.flat_rect("g_3_e", 4, 3, 0.0, GREEN)
b.flat("g_3_6", 6, 3, 0.0, GREEN)

# =================================================================
# 2. 实验室三面墙 (x [1,6], y [1,3], 高 2): 南面敞开 (剖面视角)
# =================================================================
for x in range(1, 6):
    b.wall_ns(f"wl_n1_{x}", x, 3.0, 0, WALL)       # 北墙一层
b.wall_ew("wl_w1_s", 1.0, 1, 0, WALL)              # 西山墙一层
b.wall_ew("wl_w1_n", 1.0, 2, 0, WALL)
b.wall_ew("wl_e1_s", 6.0, 1, 0, WALL)              # 东山墙一层
b.wall_ew("wl_e1_n", 6.0, 2, 0, WALL)
# 二层: 北墙窗格方与素墙相间 (高窗采光), 山墙南窗北素
for i, x in enumerate(range(1, 6)):
    if x % 2 == 1:
        b.add(f"wl_n2_{x}", "window_square", (x + 0.5, 3.0, 1.5), (90, 0, 0), WIN)
    else:
        b.wall_ns(f"wl_n2_{x}", x, 3.0, 1, WALL)
b.add("wl_w2_s", "window_square", (1.0, 1.5, 1.5), (90, 0, 90), WIN)
b.wall_ew("wl_w2_n", 1.0, 2, 1, WALL)
b.add("wl_e2_s", "window_square", (6.0, 1.5, 1.5), (90, 0, 90), WIN)
b.wall_ew("wl_e2_n", 6.0, 2, 1, WALL)

# =================================================================
# 3. 北半跨屋顶 (y [2,3], z=2): 方板 x4 + 中央玻璃天窗锥
# =================================================================
b.flat("rf_1", 1, 2, 2.0, ROOF)
b.flat("rf_2", 2, 2, 2.0, ROOF)
b.flat("rf_4", 4, 2, 2.0, ROOF)
b.flat("rf_5", 5, 2, 2.0, ROOF)
b.hat4("sky", 3, 2, 2.0, SKY, shape="equilateral_triangle")

# =================================================================
# 4. 排风塔 (x [0,1], y [2,3], 高 2): 借实验室西墙合环
# =================================================================
b.wall_ns("tw1_s", 0, 2.0, 0, TOWER)
b.wall_ns("tw1_n", 0, 3.0, 0, TOWER)
b.wall_ew("tw1_w", 0.0, 2, 0, TOWER)
b.wall_ns("tw2_s", 0, 2.0, 1, TOWER)
b.wall_ns("tw2_n", 0, 3.0, 1, TOWER)
b.wall_ew("tw2_w", 0.0, 2, 1, TOWER)
b.flat("tw_cap", 0, 2, 2.0, TOWER)
b.spire_ns("tw_vent", 0, 3.0, 2.0, VENT)           # 排风尖 (顶 4.0)

# =================================================================
# 5. 实验台矩阵 (前半间 y [1,2]): 长台 + 方台共墙相连
# =================================================================
b.lintel_ns("bA_s", 2, 1.0, 0, BENCH)              # 长台前后长楣
b.lintel_ns("bA_n", 2, 2.0, 0, BENCH)
b.wall_ew("bA_w", 2.0, 1, 0, BENCH)
b.wall_ew("bA_e", 4.0, 1, 0, BENCH)
b.flat_rect("bA_top", 2, 1, 1.0, TOP)              # 台面四边全锁
b.wall_ns("bB_s", 4, 1.0, 0, BENCH)                # 方台借长台东墙
b.wall_ns("bB_n", 4, 2.0, 0, BENCH)
b.wall_ew("bB_e", 5.0, 1, 0, BENCH)
b.flat("bB_top", 4, 1, 1.0, TOP)
b.crest_ew("flask_w", 2.0, 1, 1.0, FLASK_R)        # 烧瓶骑台面沿口
b.crest_ew("flask_m", 4.0, 1, 1.0, FLASK_G)
b.crest_ns("flask_e", 4, 2.0, 1.0, FLASK_O)

# =================================================================
# 教程步骤 (14 步)
# =================================================================
b.step(
    "铺门前空地: 三片灰色长板 + 东角绿茵。",
    ["g_0_w", "g_0_m", "g_0_e", "g_0_6"],
    tip="实验室朝南敞开 —— 从这片空地就能看进整间教室。",
)
b.step(
    "铺实验室前半间地坪: 长台脚下用整片长板 (南北边等长 2.0)。",
    ["g_1_0", "g_1_1", "g_bench", "g_1_4", "g_1_5", "g_1_6"],
    highlight=["g_0_m"],
    tip="长台的长楣墙脚要整边吸在这片长板的边上 —— 等长才吸得上。",
)
b.step(
    "铺后半间地坪: 北墙脚线处全部用单位方板。",
    ["g_2_0", "g_2_1", "g_2_2", "g_2_3", "g_2_4", "g_2_5", "g_2_6"],
    highlight=["g_1_1"],
    tip="西头那格是排风塔的地基 —— 塔和教室共用一道墙。",
)
b.step(
    "铺后侧绿化收口地坪。",
    ["g_3_w", "g_3_m", "g_3_e", "g_3_6"],
    highlight=["g_2_6"],
    tip="7x4 地坪合拢 —— 每条拼缝都是墙脚与台脚的地基。",
)
b.step(
    "立实验室一层墙: 北墙 5 片 + 东西山墙各 2 片, 南面敞开。",
    ["wl_n1_1", "wl_n1_2", "wl_n1_3", "wl_n1_4", "wl_n1_5",
     "wl_w1_s", "wl_w1_n", "wl_e1_s", "wl_e1_n"],
    highlight=["g_2_1", "g_2_5"],
    tip="三面墙 + 敞开的南面 —— 这是能看见里面上课的剖面教室。",
)
b.step(
    "立二层高窗: 北墙窗格方与素墙相间, 山墙南窗北素。",
    ["wl_n2_1", "wl_n2_2", "wl_n2_3", "wl_n2_4", "wl_n2_5",
     "wl_w2_s", "wl_w2_n", "wl_e2_s", "wl_e2_n"],
    highlight=["wl_n1_1"],
    tip="窗格方物理上按实心方片拼接 —— 高窗采光, 实验看得清。",
)
b.step(
    "盖北半跨屋顶: 4 片蓝板北边整边压北墙顶, 正中留 1x1 天窗洞。",
    ["rf_1", "rf_2", "rf_4", "rf_5"],
    highlight=["wl_n2_1", "wl_w2_n"],
    tip="屋顶只盖北半跨 —— 南半间露天, 阳光直照实验台。",
)
b.step(
    "封玻璃天窗锥: 先放北/东/西三片吸沿, 南片最后靠斜棱互吸合拢。",
    ["sky_n", "sky_e", "sky_w", "sky_s"],
    highlight=["rf_2", "rf_4"],
    tip="南底边虽然临空, 四条斜棱两两互吸照样锁成金字塔环。",
)
b.step(
    "砌排风塔一层: 三片紫墙借实验室西墙合环。",
    ["tw1_s", "tw1_n", "tw1_w"],
    highlight=["wl_w1_n", "g_2_0"],
    tip="塔和教室共用一道墙 —— 共墙就是共保险。",
)
b.step(
    "砌排风塔二层并压顶: 塔顶方板东沿与屋顶西板共线互吸。",
    ["tw2_s", "tw2_n", "tw2_w", "tw_cap"],
    highlight=["tw1_s", "rf_1"],
    tip="压顶一放, 塔身和主体屋顶锁成一个整体。",
)
b.step(
    "立排风尖: 灰色等腰高尖'压顶北沿+塔北墙顶'一线双吸, 顶 4.0 全场制高。",
    ["tw_vent"],
    highlight=["tw_cap"],
    tip="实验室的废气就从这里排走 —— 重心正压铰链线, 力矩为零。",
)
b.step(
    "搭长实验台: 前后长楣整边吸地板长边, 侧墙合环。",
    ["bA_s", "bA_n", "bA_w", "bA_e"],
    highlight=["g_bench"],
    tip="长楣墙脚 2.0 对 2.0 整边贴合 —— 这就是拼缝纪律。",
)
b.step(
    "盖长台台面 + 搭方实验台: 台面南北长边各整边吸长楣顶四边全锁; "
    "方台借长台东墙合环再压台面。",
    ["bA_top", "bB_s", "bB_n", "bB_e", "bB_top"],
    highlight=["bA_e"],
    tip="两座台共用一道墙 —— 实验台矩阵连成一体。",
)
b.step(
    "摆烧瓶: 红/绿/橙三只等边三角骑上台面沿口 —— 开始做实验!",
    ["flask_w", "flask_m", "flask_e"],
    highlight=["bA_top", "bB_top"],
    tip="每只烧瓶'台面沿+墙顶'一线双吸 —— 碰倒了也摔不下来。",
)

b.finalize(
    model_id="science_lab_01",
    name="科学实验室",
    name_en="School Science Lab 01",
    description=(
        "只用核心九片型的校园科学实验室, 结构签名是'剖面教室 + 玻璃"
        "天窗锥 + 排风塔': 三面墙的教室南面整个敞开, 二层高窗窗格方"
        "与素墙相间; 屋顶只盖北半跨, 正中 1x1 洞口由透明等边四坡玻璃"
        "天窗锥封住 —— 南底边临空, 三边吸沿加四棱互吸照样自锁成环; "
        "西山墙外两层排风塔借教室西墙合环 (共墙即共保险), 塔顶压顶"
        "东沿与屋顶共线互吸, 灰色排风尖一线双吸直上 4.0 全场制高; "
        "敞开的前半间里长台与方台共墙连成实验台矩阵, 台面四边全锁, "
        "红/绿/橙三只烧瓶骑沿口力矩为零 —— 上课铃响, 开始做实验!"
    ),
    difficulty=3,
    tags=["校园", "实验室", "科学课", "玻璃天窗", "进阶"],
    min_pieces=67,
    min_steps=14,
)
