#!/usr/bin/env python3
"""生成模型 data/models/drawbridge_01.json (升起的活动吊桥)。

中世纪/城堡主题: 全库第一座 "正在升起" 的活动吊桥 —— 与
castle_drawbridge_01 (平放桥板 + 围城门楼) 的结构逻辑刻意区分:
那座桥是铺在护城河上的静态通道, 本作的主角是吊桥机械本身 ——
两片长方形桥板绕南岸拼缝铰链抬起 65 度, 半悬在护城河上空
(每片力矩 60g x cos65 x 1.0 = 25.4 < 双吸铰链 strict 预算 35);
两座双层桥头塔夹住桥口, 塔间一根黄色门楣凌空锁定 (双端竖边
纯剪传力), 楣顶再架双板值房桥 —— 塔-楣-板围成门式刚架;
塔后两只配重石箱与塔共墙 (吊桥靠它们起落), 北岸门框方哨亭
把守对岸 —— 吊桥拉起, 全城安睡。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 护城河沿 x 向):
  - 地面 (x [0,8], y [0,4]): 南岸 2 行 + 护城河 1 行 + 北岸 1 行  21 片
  - 桥头塔 x2 (1x1 双层墙环, 二层南面窗格方射孔)                 16 片
  - 门楣 (z 1..2, x [3,5]): 长方形 x1, 双端竖边吸进塔身            1 片
  - 塔顶/值房板 (z=2): 方板 x4 (中段双板三边受力如桥)              4 片
  - 女儿墙城齿 x2 + 塔旗等腰尖 x2                                  4 片
  - 配重石箱 x2: 三面墙与塔共墙 + 压顶板 (每箱 4 片)               8 片
  - 吊桥板 x2: 长方形绕 y=2 拼缝铰链抬起 65 度 (顶缘 1.81)         2 片
  - 北岸哨亭: 墙环 x4 (门框方亭门) + 等边四坡亭顶 x4               8 片
  - 河面航标: 等边三角 x2 立在河沿拼缝                             2 片
  合计 66 片, 13 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, strict 档同样全绿):
  - 吊桥板短底边骑在南岸-河面拼缝上 (一线双吸): 每片抬起力矩
    25.4 <= 17.5 x 2 = 35 (strict 档), 两片长边互吸再加一道保险;
  - 门楣不落地也不悬空: 两端短竖边吸进塔身竖边, 重力纯剪传入
    塔身 (竖直铰链零弯矩); 值房双板南压楣顶、两端搭塔顶,
    塔-楣-板处处成环;
  - 配重箱北墙即塔身南墙 (共墙), 压顶板四边全吸;
  - 哨亭墙环 + 四坡锥顶自锁, 航标重心正压拼缝铰链。

用法: python3 tools/generate_drawbridge.py  (在 magtile-studio 目录下运行)
"""

import math

from magtile_gen import ModelBuilder

b = ModelBuilder()

BANK = "green"      # 两岸草地
ROAD = "gray"       # 进城道
MOAT = "cyan"       # 护城河
TOWER = "gray"      # 桥头塔
SLIT = "clear"      # 窗格方射孔
LINTEL = "yellow"   # 门楣
DECKC = "orange"    # 吊桥板 (木色)
CAP = "blue"        # 塔顶/值房板
CREST = "yellow"    # 女儿墙城齿
FLAG = "red"        # 塔旗
BALLAST = "purple"  # 配重石箱
BOOTH = "gray"      # 哨亭
ROOF = "red"        # 哨亭顶
BUOY = "red"        # 航标

TILT = 65.0  # 吊桥抬起角 (自水平面), cos65 = 0.4226
COS_T = round(math.cos(math.radians(TILT)), 6)
SIN_T = round(math.sin(math.radians(TILT)), 6)

# =================================================================
# 1. 地面 (x [0,8], y [0,4]): 塔基与哨亭处留出所需拼缝
# =================================================================
for r, ys in (("ga", 0), ("gb", 1)):
    b.flat_rect(f"{r}_0", 0, ys, 0.0, BANK)              # [0,2]
    b.flat(f"{r}_1", 2, ys, 0.0, BANK)                   # [2,3]
    b.flat_rect(f"{r}_2", 3, ys, 0.0, ROAD)              # [3,5] 进城道
    b.flat(f"{r}_3", 5, ys, 0.0, BANK)                   # [5,6]
    b.flat_rect(f"{r}_4", 6, ys, 0.0, BANK)              # [6,8]
b.flat_rect("gm_0", 0, 2, 0.0, MOAT)                     # 护城河一行
b.flat("gm_1", 2, 2, 0.0, MOAT)
b.flat_rect("gm_2", 3, 2, 0.0, MOAT)
b.flat("gm_3", 5, 2, 0.0, MOAT)
b.flat_rect("gm_4", 6, 2, 0.0, MOAT)
b.flat_rect("gn_0", 0, 3, 0.0, BANK)                     # 北岸一行
b.flat("gn_1", 2, 3, 0.0, BANK)
b.flat_rect("gn_2", 3, 3, 0.0, ROAD)
b.flat("gn_3", 5, 3, 0.0, BANK)
b.flat("gn_4", 6, 3, 0.0, BANK)
b.flat("gn_5", 7, 3, 0.0, BANK)

# =================================================================
# 2. 桥头塔 x2 (x [2,3] / [5,6], y [1,2], z 0..2)
# =================================================================
for p, x0 in (("tw", 2), ("te", 5)):
    b.wall_ns(f"{p}1_s", x0, 1.0, 0, TOWER)
    b.wall_ns(f"{p}1_n", x0, 2.0, 0, TOWER)
    b.wall_ew(f"{p}1_w", float(x0), 1, 0, TOWER)
    b.wall_ew(f"{p}1_e", float(x0 + 1), 1, 0, TOWER)
    b.add(f"{p}2_s", "window_square", (x0 + 0.5, 1.0, 1.5), (90, 0, 0), SLIT)
    b.wall_ns(f"{p}2_n", x0, 2.0, 1, TOWER)
    b.wall_ew(f"{p}2_w", float(x0), 1, 1, TOWER)
    b.wall_ew(f"{p}2_e", float(x0 + 1), 1, 1, TOWER)

# =================================================================
# 3. 门楣 + 塔顶/值房板 + 女儿墙 + 塔旗
# =================================================================
b.lintel_ns("lintel", 3, 1.0, 1, LINTEL)                 # y=1, x [3,5], z 1..2
b.flat("cap_w", 2, 1, 2.0, CAP)                          # 塔顶板
b.flat("cap_e", 5, 1, 2.0, CAP)
b.flat("br_w", 3, 1, 2.0, CAP)                           # 值房板 (三边受力)
b.flat("br_e", 4, 1, 2.0, CAP)
b.crest_ns("pcr_w", 3, 2.0, 2.0, CREST)
b.crest_ns("pcr_e", 4, 2.0, 2.0, CREST)
b.spire_ew("fl_w", 2.0, 1, 2.0, FLAG)
b.spire_ew("fl_e", 6.0, 1, 2.0, FLAG)

# =================================================================
# 4. 配重石箱 x2 (塔正南, 与塔共墙): 三面墙 + 压顶板
# =================================================================
for p, x0 in (("cw", 2), ("ce", 5)):
    b.wall_ns(f"{p}_s", x0, 0.0, 0, BALLAST)
    b.wall_ew(f"{p}_w", float(x0), 0, 0, BALLAST)
    b.wall_ew(f"{p}_e", float(x0 + 1), 0, 0, BALLAST)
    b.flat(f"{p}_cap", x0, 0, 1.0, BALLAST)

# =================================================================
# 5. 吊桥板 x2: 绕南岸 y=2 拼缝铰链抬起 65 度, 半悬河上
# =================================================================
b.place_edge("deck_w", "rectangle", 1,
             (3.0, 2.0, 0.0), (4.0, 2.0, 0.0), (0.0, COS_T, SIN_T), DECKC)
b.place_edge("deck_e", "rectangle", 1,
             (4.0, 2.0, 0.0), (5.0, 2.0, 0.0), (0.0, COS_T, SIN_T), DECKC)

# =================================================================
# 6. 北岸哨亭 (x [6,7], y [3,4]) + 河面航标
# =================================================================
b.add("bo_s", "door_frame", (6.5, 3.0, 0.5), (90, 0, 0), BOOTH)
b.wall_ns("bo_n", 6, 4.0, 0, BOOTH)
b.wall_ew("bo_w", 6.0, 3, 0, BOOTH)
b.wall_ew("bo_e", 7.0, 3, 0, BOOTH)
ROOF_IDS = b.hat4("bo_roof", 6, 3, 1.0, ROOF, shape="equilateral_triangle")
b.crest_ew("bu_w", 2.0, 2, 0.0, BUOY)
b.crest_ew("bu_e", 6.0, 2, 0.0, BUOY)

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺南岸第一行 (y [0,1]): 5 片, 配重石箱踩这行。",
    ["ga_0", "ga_1", "ga_2", "ga_3", "ga_4"],
    tip="灰色进城道居中 (x [3,5]) —— 吊桥就开在这条轴线上。",
)
b.step(
    "铺南岸第二行 (y [1,2]): 5 片, 桥头塔踩这行拼缝。",
    ["gb_0", "gb_1", "gb_2", "gb_3", "gb_4"],
    highlight=["ga_2"],
    tip="x=2/3 与 x=5/6 的拼缝是双塔的墙脚。",
)
b.step(
    "铺护城河 (y [2,3]): 5 片青色水面, 与南岸拼缝对齐。",
    ["gm_0", "gm_1", "gm_2", "gm_3", "gm_4"],
    highlight=["gb_2"],
    tip="y=2 这条水岸拼缝就是吊桥的铰链线 —— 记住它。",
)
b.step(
    "铺北岸 (y [3,4]): 6 片, 对岸大道通向哨亭。",
    ["gn_0", "gn_1", "gn_2", "gn_3", "gn_4", "gn_5"],
    highlight=["gm_2"],
    tip="吊桥升起时, 北岸的路在河边断头 —— 这正是吊桥的意义。",
)
b.step(
    "立双塔第 1 层: 每座 4 片墙环, 四角竖边互吸。",
    ["tw1_s", "tw1_n", "tw1_w", "tw1_e",
     "te1_s", "te1_n", "te1_w", "te1_e"],
    highlight=["gb_1", "gb_3"],
    tip="两座塔夹住进城道 —— 桥口只有 2 格宽。",
)
b.step(
    "叠双塔第 2 层: 南面各嵌 1 扇窗格方射孔。",
    ["tw2_s", "tw2_n", "tw2_w", "tw2_e",
     "te2_s", "te2_n", "te2_w", "te2_e"],
    highlight=["tw1_s", "te1_s"],
    tip="射孔盯住桥口 —— 想混进城? 先过这两只眼睛。",
)
b.step(
    "架门楣与塔顶/值房板: 黄色门楣双端竖边吸进塔身, 4 片板封顶。",
    ["lintel", "cap_w", "cap_e", "br_w", "br_e"],
    highlight=["tw2_e", "te2_w"],
    tip="门楣重力纯剪传入塔身; 值房板南压楣顶、两端搭塔顶 —— 处处成环。",
)
b.step(
    "砌配重石箱: 每箱三面墙借塔身当北墙 (共墙), 压顶板四边全吸。",
    ["cw_s", "cw_w", "cw_e", "cw_cap", "ce_s", "ce_w", "ce_e", "ce_cap"],
    highlight=["tw1_s", "te1_s"],
    tip="吊桥靠这两箱石头起落 —— 一墙两用是共墙技法。",
)
b.step(
    "装值房女儿墙 + 双塔旗: 2 片城齿 + 2 片等腰尖旗。",
    ["pcr_w", "pcr_e", "fl_w", "fl_e"],
    highlight=["br_w", "cap_e"],
    tip="城齿与尖旗重心都正压铰链线, 力矩为零。",
)
b.step(
    "升吊桥! 2 片长方形桥板骑上水岸拼缝, 绕铰链抬起 65 度。",
    ["deck_w", "deck_e"],
    highlight=["gb_2", "gm_2"],
    tip="短底边一线双吸 (岸 + 河), 力矩 25.4 < 预算 35 —— 两片长边再互吸一道。",
)
b.step(
    "立北岸哨亭墙环: 门框方亭门朝南望桥。",
    ["bo_s", "bo_n", "bo_w", "bo_e"],
    highlight=["gn_4"],
    tip="哨亭把守对岸 —— 吊桥落下前, 谁也别想过河。",
)
b.step(
    "盖哨亭四坡锥顶: 4 片等边三角互吸自锁。",
    ROOF_IDS,
    highlight=["bo_s"],
    tip="四条斜棱两两互吸 —— 小亭子也有讲究。",
)
b.step(
    "放河面航标: 2 片红色等边三角立在河沿拼缝 —— 吊桥拉起, 全城安睡!",
    ["bu_w", "bu_e"],
    highlight=["gm_1", "gm_3"],
    tip="航标重心正压拼缝铰链, 力矩为零。",
)

b.finalize(
    model_id="drawbridge_01",
    name="升起的活动吊桥",
    name_en="Raised Drawbridge 01",
    description=(
        "全库第一座正在升起的活动吊桥: 两片长方形桥板绕南岸水岸"
        "拼缝铰链抬起 65 度、半悬护城河上 (每片力矩 25.4 < 双吸"
        "铰链 strict 预算 35, 长边互吸再加保险); 双层桥头塔夹住"
        "桥口, 黄色门楣双端竖边纯剪锁进塔身、楣顶架值房双板 ——"
        " 塔-楣-板围成门式刚架; 塔后配重石箱与塔共墙, 北岸门框方"
        "哨亭把守断头路。铰链抬板、门式刚架、共墙配重 —— 吊桥"
        "机械三技法一课学会。"
    ),
    difficulty=3,
    tags=["中世纪", "城堡", "吊桥", "护城河", "进阶"],
    min_pieces=64,
    min_steps=13,
)
