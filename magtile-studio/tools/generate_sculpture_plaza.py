#!/usr/bin/env python3
"""生成模型 data/models/sculpture_plaza_01.json (雕塑艺术广场)。

博物馆/艺术主题 2/4: 全库第一座 "雕塑群落" 场景 —— 与
fountain_plaza_01 (中央水池 + 四方水舌) 的中心式广场刻意区分:
雕塑广场没有中心水景, 而是五件互不重样的户外雕塑散布在 7x5
石板广场上, 每件用一种不同的结构语言:
  1. 方尖碑: 1x1 箱式墙环两层竖叠 + 等腰四坡锥收尖 (尖顶 3.94),
     每层四角竖边互吸闭环, 层间四条平行拼缝互为冗余;
  2. pi 形拱门: 双立墙托一片天桥板 (双端受力零悬挑), 板上立等边
     三角冠 —— 墙-板-地闭合成环;
  3. 现代画屏: 大正方形 (2x2) 整片立起, 底边一线双吸地板拼缝,
     两端直角三角斜撑双边吸合抗侧力;
  4. 低卧金字塔: 4 片等边三角直接落地四棱互吸自锁 (不需要底座);
  5. 悬挑长椅 x2: 单墙托悬挑坐板 (力矩 15 < strict 预算 17.5)。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 广场地面 (x [0,7], y [0,5]): 石板 + 草格 + 雕塑基座 5 行  29 片
  - 方尖碑 (x [3,4], y [2,3]): 墙环 4x2 + 等腰四坡锥 x4       12 片
  - pi 形拱门 (x [1,2], y [1,2]): 立墙 x2 + 天桥板 + 三角冠     4 片
  - 现代画屏 (x [3,5], y=4): 大正方形 x1 + 直角三角斜撑 x2      3 片
  - 低卧金字塔 (x [5,6], y [1,2]): 等边三角 x4                  4 片
  - 悬挑长椅 x2: 靠背墙 + 悬挑坐板                              4 片
  合计 56 片, 12 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (R1~R8 全绿, strict 档零警告):
  - 方尖碑两层墙环各自四角闭环, 层间 4 条竖叠拼缝任断其一仍
    经其余绕行 (无单点失效); 锥顶四棱两两互吸自锁;
  - 拱门天桥板双端压墙顶 (纯压零力矩), 画屏底边 2.0 长边同时
    吸两片共线地板拼缝, 斜撑竖直边纯剪吸画屏侧棱;
  - 长椅悬挑坐板单边铰链: 力矩 30x0.5=15 g·单位 < 17.5 预算。

用法: python3 tools/generate_sculpture_plaza.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

STONE = "gray"      # 石板广场
PATH = "orange"     # 参观步道
GRASS = "green"     # 草格
OBELISK = "purple"  # 方尖碑墙身
OBK_TOP = "yellow"  # 方尖碑锥顶
GATE = "red"        # pi 形拱门
GATE_C = "blue"     # 拱门三角冠
SCREEN = "pink"     # 现代画屏
BRACE = "gray"      # 画屏斜撑
PYRA = "cyan"       # 低卧金字塔
BENCH = "gray"      # 长椅

# =================================================================
# 1. 广场地面 (x [0,7], y [0,5]): 拼缝对准每件雕塑的落点
# =================================================================
b.flat_rect("p0_a", 0, 0, 0.0, STONE)
b.flat_rect("p0_b", 2, 0, 0.0, STONE)
b.flat("p0_c", 4, 0, 0.0, STONE)
b.flat("p0_d", 5, 0, 0.0, STONE)          # 拼缝给金字塔南棱
b.flat("p0_e", 6, 0, 0.0, STONE)

b.flat("p1_a", 0, 1, 0.0, STONE)
b.flat("p1_b", 1, 1, 0.0, PATH)           # 拱门门洞地
b.flat("p1_c", 2, 1, 0.0, PATH)
b.flat("p1_d", 3, 1, 0.0, PATH)
b.flat("p1_e", 4, 1, 0.0, STONE)
b.flat("p1_f", 5, 1, 0.0, GRASS)          # 金字塔草座
b.flat("p1_g", 6, 1, 0.0, STONE)

b.flat("p2_a", 0, 2, 0.0, STONE)
b.flat("p2_b", 1, 2, 0.0, STONE)
b.flat("p2_c", 2, 2, 0.0, PATH)
b.flat("p2_d", 3, 2, 0.0, GRASS)          # 方尖碑基座
b.flat("p2_e", 4, 2, 0.0, PATH)
b.flat("p2_f", 5, 2, 0.0, STONE)          # 长椅东坐板下方
b.flat("p2_g", 6, 2, 0.0, STONE)

b.flat("p3_a", 0, 3, 0.0, STONE)
b.flat("p3_b", 1, 3, 0.0, STONE)          # 长椅西坐板下方
b.flat("p3_c", 2, 3, 0.0, STONE)
b.flat_rect("p3_d", 3, 3, 0.0, STONE)     # 拼缝给画屏底边
b.flat("p3_e", 5, 3, 0.0, STONE)
b.flat("p3_f", 6, 3, 0.0, STONE)

b.flat_rect("p4_a", 0, 4, 0.0, STONE)
b.flat_rect("p4_b", 2, 4, 0.0, GRASS)
b.flat_rect("p4_c", 4, 4, 0.0, GRASS)
b.flat("p4_d", 6, 4, 0.0, STONE)

# =================================================================
# 2. 方尖碑 (x [3,4], y [2,3]): 两层箱式墙环 + 等腰四坡锥 (尖 3.94)
# =================================================================
b.wall_ns("obk1_s", 3, 2.0, 0, OBELISK)
b.wall_ew("obk1_e", 4.0, 2, 0, OBELISK)
b.wall_ns("obk1_n", 3, 3.0, 0, OBELISK)
b.wall_ew("obk1_w", 3.0, 2, 0, OBELISK)
b.wall_ns("obk2_s", 3, 2.0, 1, OBELISK)
b.wall_ew("obk2_e", 4.0, 2, 1, OBELISK)
b.wall_ns("obk2_n", 3, 3.0, 1, OBELISK)
b.wall_ew("obk2_w", 3.0, 2, 1, OBELISK)
OBK_HAT = b.hat4("obk_hat", 3, 2, 2.0, OBK_TOP)   # 等腰四坡锥, 尖顶 3.94

# =================================================================
# 3. pi 形拱门 (x [1,2], y [1,2]): 双立墙托天桥板 + 三角冠
# =================================================================
b.wall_ew("gate_w", 1.0, 1, 0, GATE)
b.wall_ew("gate_e", 2.0, 1, 0, GATE)
b.flat("gate_top", 1, 1, 1.0, GATE)
b.crest_ns("gate_crest", 1, 2.0, 1.0, GATE_C)

# =================================================================
# 4. 现代画屏 (x [3,5], y=4): 大正方形立片 + 直角三角斜撑 x2
# =================================================================
b.add("screen", "large_square", (4.0, 4.0, 1.0), (90, 0, 0), SCREEN)
b.brace("scr_brc_w", (3.0, 4.0, 0.0), "-x", BRACE)
b.brace("scr_brc_e", (5.0, 4.0, 0.0), "+x", BRACE)

# =================================================================
# 5. 低卧金字塔 (x [5,6], y [1,2]): 等边四棱直接落地自锁
# =================================================================
PYR_IDS = b.hat4("pyr", 5, 1, 0.0, PYRA, shape="equilateral_triangle")

# =================================================================
# 6. 悬挑长椅 x2: 靠背墙 + 悬挑坐板 (力矩 15 < 17.5)
# =================================================================
b.wall_ns("bench_w_back", 1, 4.0, 0, BENCH)
b.flat("bench_w_seat", 1, 3, 1.0, GRASS)
b.wall_ns("bench_e_back", 5, 3.0, 0, BENCH)
b.flat("bench_e_seat", 5, 2, 1.0, GRASS)

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺广场南行 (y [0,1]): 5 片石板打底。",
    ["p0_a", "p0_b", "p0_c", "p0_d", "p0_e"],
    tip="x [5,6] 这条北缝稍后是金字塔雕塑的南棱基线。",
)
b.step(
    "铺步道行 (y [1,2]): 7 片, 橙色步道穿过拱门直通广场。",
    ["p1_a", "p1_b", "p1_c", "p1_d", "p1_e", "p1_f", "p1_g"],
    highlight=["p0_c"],
    tip="绿色草座是金字塔雕塑的落点, 四条边缝都要对齐。",
)
b.step(
    "铺中心行 (y [2,3]): 7 片, 正中绿色草格是方尖碑基座。",
    ["p2_a", "p2_b", "p2_c", "p2_d", "p2_e", "p2_f", "p2_g"],
    highlight=["p1_d"],
    tip="方尖碑的四面墙就立在这一格的四条边缝上。",
)
b.step(
    "铺北二行 (y [3,4]): 6 片, 长板拼缝留给画屏底边。",
    ["p3_a", "p3_b", "p3_c", "p3_d", "p3_e", "p3_f"],
    highlight=["p2_d"],
    tip="画屏底边长 2.0, 正好压住这块长板的北缝。",
)
b.step(
    "铺北行 (y [4,5]): 4 片, 广场合拢。",
    ["p4_a", "p4_b", "p4_c", "p4_d"],
    highlight=["p3_d"],
    tip="7x5 广场铺满 —— 五件雕塑即将登场。",
)
b.step(
    "砌方尖碑第 1 层墙环: 4 片紫色立墙四角竖边互吸闭环。",
    ["obk1_s", "obk1_e", "obk1_n", "obk1_w"],
    highlight=["p2_d"],
    tip="闭合墙环是方尖碑的根 —— 轻推应整体联动。",
)
b.step(
    "砌方尖碑第 2 层墙环: 4 片竖叠, 层间四条拼缝互为冗余。",
    ["obk2_s", "obk2_e", "obk2_n", "obk2_w"],
    highlight=["obk1_s"],
    tip="任断一条竖叠拼缝, 力仍经其余三条绕行。",
)
b.step(
    "收方尖碑锥顶: 4 片等腰三角四棱两两互吸 (尖顶 3.94)。",
    OBK_HAT,
    highlight=["obk2_s"],
    tip="瘦高的等腰锥是方尖碑的标志轮廓 —— 全场最高点。",
)
b.step(
    "立 pi 形拱门: 双立墙托天桥板, 板上立蓝色三角冠。",
    ["gate_w", "gate_e", "gate_top", "gate_crest"],
    highlight=["p1_b", "p1_c"],
    tip="天桥板双端压墙顶, 零悬挑 —— 从门洞下走进雕塑广场。",
)
b.step(
    "立现代画屏: 大正方形整片立起, 两端直角三角斜撑抵脚。",
    ["screen", "scr_brc_w", "scr_brc_e"],
    highlight=["p3_d"],
    tip="底边 2.0 一线双吸地板拼缝, 斜撑竖边纯剪锁住侧棱。",
)
b.step(
    "落低卧金字塔: 4 片等边三角直接落地, 四棱互吸自锁。",
    PYR_IDS,
    highlight=["p1_f"],
    tip="不需要底座 —— 四条斜棱两两互吸就是它的全部结构。",
)
b.step(
    "装两张悬挑长椅 —— 雕塑艺术广场落成!",
    ["bench_w_back", "bench_w_seat", "bench_e_back", "bench_e_seat"],
    highlight=["p3_b", "p2_f"],
    tip="坐板单边铰链悬挑 (力矩 15), 坐下正好面对方尖碑。",
)

b.finalize(
    model_id="sculpture_plaza_01",
    name="雕塑艺术广场",
    name_en="Sculpture Plaza 01",
    description=(
        "全库第一座雕塑群落场景: 7x5 石板广场上五件互不重样的户外"
        "雕塑各用一种结构语言 —— 方尖碑两层箱式墙环竖叠、等腰四坡锥"
        "收尖 (尖顶 3.94); pi 形拱门双墙托天桥板零悬挑; 现代画屏"
        "大正方形整片立起、直角三角斜撑抵脚; 低卧金字塔四棱落地自锁;"
        " 悬挑长椅单边铰链托坐板 —— 一场广场上的结构语言展。"
    ),
    difficulty=3,
    tags=["博物馆", "艺术", "雕塑", "广场", "进阶"],
    min_pieces=54,
    min_steps=12,
)
