#!/usr/bin/env python3
"""生成模型 data/models/fireworks_show_01.json (烟花表演)。

节日/庆典主题 4/4: 全库第一场夜空烟花秀 —— 与观测类高塔
(wizard_tower_01 观星室 / clock_tower_01) 刻意区分, 本作的结构
逻辑是 "绽放塔冠 + 地面旋轮 + 双发射管 + 看台坡道" 四景同场:
夜蓝广场正中发射塔两层墙环拔起 (二层透明控制窗), 塔顶四沿
绽放烟花 —— 南北两支瘦高等腰三角火柱直上 4.0, 东西两片等边
三角火花对开, 四片全部一线双吸 (盖板沿 + 墙顶); 塔脚是全库
第一圈平铺直角三角地面旋轮 (凯瑟琳轮): 发射台四周留出十字形
4 格空窗, 每片旋轮一条直角边吸发射台板边、另一条直角边吸邻格
广场板边, 斜边逐格外旋 —— 旋轮既是烟花图案又是把中央岛焊进
广场的连接件; 广场前排两座开顶发射管 (四壁墙环不封顶), 管沿
各骑一支蓄势待发的三角火箭; 北侧双跨观礼台长板双端受力,
东端 30 度坡道顶边一线双吸、坡尾扫地 —— 观众就位, 点火!

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 地面 (x [0,9], y [0,5]): 夜蓝广场, 旋轮处留 4 格空窗      33 片
  - 发射塔 (x [4,5], y [2,3]): 两层墙环 + 两层盖板 +
    塔冠火柱 x2 / 火花 x2                                     14 片
  - 地面旋轮 x4: 平铺直角三角双直角边同吸 (发射台 + 邻格)      4 片
  - 发射管 x2 (x [1,2] / x [7,8], y [1,2]): 四壁开顶 + 火箭   10 片
  - 观礼台 (x [2,6], y [4,5]): 三墙双跨长板 + 双旗 + 坡道      8 片
  - 火花桩 x4: 等边三角骑广场拼缝                              4 片
  合计 73 片, 13 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 发射塔两层墙环四角竖边互咬闭环, 盖板四边压四墙顶 (处处
    成环通过 R8 高层检查); 塔冠火柱/火花底边全部落在 "盖板沿
    + 墙顶" 同一条线上 (一线双吸), 重心正压铰链线力矩为零,
    最高点 4.0 (火柱尖);
  - 地面旋轮每片两条直角边分别整边吸发射台与邻格广场板 ——
    中央岛与广场磁力焊死, 发射台不再是孤岛 (R2 连通);
  - 发射管四壁互咬成环不封顶, 火箭重心正压管沿铰链;
  - 观礼台两跨长板短边分别压三墙顶 (双端受力零悬挑), 坡道
    顶边一线双吸 (平台短边 + 东墙顶), 坡尾自然扫地。

用法: python3 tools/generate_fireworks_show.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

NIGHT = "blue"      # 夜蓝广场
PAD = "gray"        # 发射台 / 管座 / 看台墙
TOWER1 = "purple"   # 塔身第 1 层
TOWER2 = "clear"    # 塔身第 2 层 (控制窗)
CAP = "gray"        # 塔盖板
FIRE_COL = "red"    # 塔冠火柱 (南北)
FIRE_SPK = "yellow" # 塔冠火花 (东西)
RAY_A = "red"       # 地面星芒
RAY_B = "yellow"
TUBE = "gray"       # 发射管
ROCKET_W = "red"    # 西火箭
ROCKET_E = "orange" # 东火箭
STAND = "purple"    # 观礼台长板
FLAG_A = "pink"     # 观礼台旗
FLAG_B = "red"
RAMP = "gray"       # 看台坡道
SPARK = "yellow"    # 火花桩

# =================================================================
# 1. 地面 (x [0,9], y [0,5]): 夜蓝广场, 星芒处留 4 格空窗
# =================================================================
b.flat("n0_0", 0, 0, 0.0, NIGHT)
b.flat_rect("n0_1", 1, 0, 0.0, NIGHT)
b.flat_rect("n0_2", 3, 0, 0.0, NIGHT)
b.flat_rect("n0_3", 5, 0, 0.0, NIGHT)
b.flat("n0_4", 7, 0, 0.0, NIGHT)
b.flat("n0_5", 8, 0, 0.0, NIGHT)

b.flat("n1_0", 0, 1, 0.0, NIGHT)
b.flat("n1_1", 1, 1, 0.0, PAD)      # 西发射管座
b.flat("n1_2", 2, 1, 0.0, NIGHT)
b.flat("n1_3", 3, 1, 0.0, NIGHT)
# [4,5] 空窗: 南星芒
b.flat("n1_4", 5, 1, 0.0, NIGHT)
b.flat("n1_5", 6, 1, 0.0, NIGHT)
b.flat("n1_6", 7, 1, 0.0, PAD)      # 东发射管座
b.flat("n1_7", 8, 1, 0.0, NIGHT)

b.flat_rect("n2_0", 0, 2, 0.0, NIGHT)
b.flat("n2_1", 2, 2, 0.0, NIGHT)
# [3,4] 空窗: 西星芒
b.flat("n2_2", 4, 2, 0.0, PAD)      # 发射台
# [5,6] 空窗: 东星芒
b.flat("n2_3", 6, 2, 0.0, NIGHT)
b.flat_rect("n2_4", 7, 2, 0.0, NIGHT)

b.flat_rect("n3_0", 0, 3, 0.0, NIGHT)
b.flat("n3_1", 2, 3, 0.0, NIGHT)
b.flat("n3_2", 3, 3, 0.0, NIGHT)
# [4,5] 空窗: 北星芒
b.flat("n3_3", 5, 3, 0.0, NIGHT)
b.flat("n3_4", 6, 3, 0.0, NIGHT)
b.flat_rect("n3_5", 7, 3, 0.0, NIGHT)

b.flat_rect("n4_0", 0, 4, 0.0, NIGHT)
for k, x0 in enumerate((2, 3, 4, 5, 6, 7, 8)):
    b.flat(f"n4_{k + 1}", x0, 4, 0.0, NIGHT)

# =================================================================
# 2. 发射塔 (x [4,5], y [2,3]): 两层墙环 + 盖板 + 塔冠
# =================================================================
b.wall_ns("tw1_s", 4, 2.0, 0, TOWER1)
b.wall_ew("tw1_w", 4.0, 2, 0, TOWER1)
b.wall_ew("tw1_e", 5.0, 2, 0, TOWER1)
b.wall_ns("tw1_n", 4, 3.0, 0, TOWER1)
b.flat("tw_cap1", 4, 2, 1.0, CAP)
b.add("tw2_s", "window_square", (4.5, 2.0, 1.5), (90, 0, 0), TOWER2)
b.add("tw2_w", "window_square", (4.0, 2.5, 1.5), (90, 0, 90), TOWER2)
b.add("tw2_e", "window_square", (5.0, 2.5, 1.5), (90, 0, 90), TOWER2)
b.add("tw2_n", "window_square", (4.5, 3.0, 1.5), (90, 0, 0), TOWER2)
b.flat("tw_cap2", 4, 2, 2.0, CAP)
b.spire_ns("fw_s", 4, 2.0, 2.0, FIRE_COL)
b.spire_ns("fw_n", 4, 3.0, 2.0, FIRE_COL)
b.crest_ew("fw_w", 4.0, 2, 2.0, FIRE_SPK)
b.crest_ew("fw_e", 5.0, 2, 2.0, FIRE_SPK)

# =================================================================
# 3. 地面旋轮 x4: 平铺直角三角, 直角边同吸发射台边 + 邻格板边,
#    斜边逐格外旋成凯瑟琳轮 (兼作中央岛与广场的连接件)
# =================================================================
b.place_tri("ray_w", "right_triangle",
            (4.0, 2.0, 0.0), (4.0, 3.0, 0.0), (3.0, 2.0, 0.0), RAY_B)
b.place_tri("ray_s", "right_triangle",
            (5.0, 2.0, 0.0), (4.0, 2.0, 0.0), (5.0, 1.0, 0.0), RAY_A)
b.place_tri("ray_e", "right_triangle",
            (5.0, 3.0, 0.0), (5.0, 2.0, 0.0), (6.0, 3.0, 0.0), RAY_B)
b.place_tri("ray_n", "right_triangle",
            (4.0, 3.0, 0.0), (5.0, 3.0, 0.0), (4.0, 4.0, 0.0), RAY_A)

# =================================================================
# 4. 发射管 x2 (x [1,2] / x [7,8], y [1,2]): 四壁开顶 + 骑沿火箭
# =================================================================
b.wall_ns("tb_w_s", 1, 1.0, 0, TUBE)
b.wall_ew("tb_w_w", 1.0, 1, 0, TUBE)
b.wall_ew("tb_w_e", 2.0, 1, 0, TUBE)
b.wall_ns("tb_w_n", 1, 2.0, 0, TUBE)
b.spire_ns("rk_w", 1, 1.0, 1.0, ROCKET_W)

b.wall_ns("tb_e_s", 7, 1.0, 0, TUBE)
b.wall_ew("tb_e_w", 7.0, 1, 0, TUBE)
b.wall_ew("tb_e_e", 8.0, 1, 0, TUBE)
b.wall_ns("tb_e_n", 7, 2.0, 0, TUBE)
b.spire_ns("rk_e", 7, 1.0, 1.0, ROCKET_E)

# =================================================================
# 5. 观礼台 (x [2,6], y [4,5]): 三墙双跨长板 + 双旗 + 东坡道
# =================================================================
b.wall_ew("st_w", 2.0, 4, 0, PAD)
b.wall_ew("st_m", 4.0, 4, 0, PAD)
b.wall_ew("st_e", 6.0, 4, 0, PAD)
b.flat_rect("st_deck_w", 2, 4, 1.0, STAND)
b.flat_rect("st_deck_e", 4, 4, 1.0, STAND)
b.crest_ew("st_flag_w", 2.0, 4, 1.0, FLAG_A)
b.crest_ew("st_flag_m", 4.0, 4, 1.0, FLAG_B)
b.ramp("st_ramp", "+x", 6.0, 4, 1.0, RAMP)

# =================================================================
# 6. 火花桩 x4: 等边三角骑广场拼缝
# =================================================================
b.crest_ns("sp_sw", 0, 1.0, 0.0, SPARK)
b.crest_ns("sp_se", 8, 1.0, 0.0, SPARK)
b.crest_ns("sp_nw", 2, 3.0, 0.0, SPARK)
b.crest_ns("sp_ne", 6, 3.0, 0.0, SPARK)

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺广场南行 (y [0,1]): 夜蓝方板与长板铺出前排。",
    ["n0_0", "n0_1", "n0_2", "n0_3", "n0_4", "n0_5"],
    tip="今晚广场是夜蓝色的 —— 烟花要在深色的天幕上才好看。",
)
b.step(
    "铺第二行 (y [1,2]): 两片灰色管座落位, x [4,5] 留一格空窗 —— "
    "那是南星芒的位置。",
    ["n1_0", "n1_1", "n1_2", "n1_3", "n1_4", "n1_5", "n1_6", "n1_7"],
    highlight=["n0_0"],
    tip="空窗不是漏铺 —— 星芒三角一会儿就从发射台边上射出来。",
)
b.step(
    "铺发射台行 (y [2,3]) 并旋出西/南两片旋轮: 每片直角三角一条"
    "直角边吸发射台板边、另一条吸邻格板边。",
    ["n2_0", "n2_1", "n2_2", "n2_3", "n2_4", "ray_w", "ray_s"],
    highlight=["n1_3", "n1_4"],
    tip="旋轮是发射台和广场之间的磁力焊点 —— 中央岛绝不孤立。",
)
b.step(
    "铺第四行 (y [3,4]) 并旋出东/北两片旋轮: 四片斜边逐格外旋, "
    "地面凯瑟琳轮成形。",
    ["n3_0", "n3_1", "n3_2", "n3_3", "n3_4", "n3_5", "ray_e", "ray_n"],
    highlight=["ray_w", "ray_s"],
    tip="红黄相间的旋轮转起来 —— 这是贴在地上的烟花。",
)
b.step(
    "铺观礼行 (y [4,5]): 西端长板 + 7 片方板, 看台墙脚整边就位。",
    ["n4_0", "n4_1", "n4_2", "n4_3", "n4_4", "n4_5", "n4_6", "n4_7"],
    highlight=["n3_1"],
    tip="方板四条边都是整边 —— 三面看台墙都要踩它们的拼缝。",
)
b.step(
    "立发射塔第 1 层: 4 片紫墙环踩住发射台四条边。",
    ["tw1_s", "tw1_w", "tw1_e", "tw1_n"],
    highlight=["n2_2"],
    tip="每片底边吸发射台板边、转角竖边互咬 —— 墙环闭合才稳。",
)
b.step(
    "盖第 1 层盖板, 再叠透明控制窗层: 四面窗格方 360 度看火。",
    ["tw_cap1", "tw2_s", "tw2_w", "tw2_e", "tw2_n"],
    highlight=["tw1_s"],
    tip="盖板四边压四墙顶; 第 2 层每片同时吸盖板沿与邻片竖边。",
)
b.step(
    "封塔顶并绽放塔冠: 南北两支瘦高火柱直上 4.0, 东西两片火花"
    "对开 —— 四片全部一线双吸。",
    ["tw_cap2", "fw_s", "fw_n", "fw_w", "fw_e"],
    highlight=["tw2_s"],
    tip="每片底边都落在盖板沿+墙顶同一条线上, 重心正压力臂为零。",
)
b.step(
    "拼西发射管: 4 片灰壁互咬成环不封顶, 管沿骑上红火箭。",
    ["tb_w_s", "tb_w_w", "tb_w_e", "tb_w_n", "rk_w"],
    highlight=["n1_1"],
    tip="发射管开着顶 —— 火箭重心正压管沿铰链, 蓄势待发。",
)
b.step(
    "拼东发射管: 橙火箭就位, 双管齐发。",
    ["tb_e_s", "tb_e_w", "tb_e_e", "tb_e_n", "rk_e"],
    highlight=["rk_w"],
    tip="两管一左一右夹着发射塔 —— 三连发的阵型。",
)
b.step(
    "立观礼台三墙 (x=2/4/6): 双跨看台的三个支点。",
    ["st_w", "st_m", "st_e"],
    highlight=["n4_1", "n4_5"],
    tip="三面墙都踩在方板整边上, 中墙同时服务东西两跨。",
)
b.step(
    "铺看台双跨长板、骑双旗、搭东坡道: 长板短边分别压墙顶 (双端"
    "受力), 坡道顶边一线双吸、坡尾扫地 —— 观众就位, 点火!",
    ["st_deck_w", "st_deck_e", "st_flag_w", "st_flag_m", "st_ramp"],
    highlight=["st_w", "st_m", "st_e"],
    tip="双跨零悬挑, 坡道剪断顶铰链也掉不下来 —— 安心看烟花。",
)
b.step(
    "插四支火花桩: 等边三角骑广场拼缝, 火光落满全场 —— 烟花秀"
    "开演!",
    ["sp_sw", "sp_se", "sp_nw", "sp_ne"],
    highlight=["fw_s", "fw_n"],
    tip="塔冠绽放、地面星芒、火箭待发 —— 3, 2, 1, 点火!",
)

b.finalize(
    model_id="fireworks_show_01",
    name="烟花表演",
    name_en="Fireworks Show 01",
    description=(
        "只用核心九片型的夜空烟花秀: 夜蓝广场正中发射塔两层墙环"
        "拔起 (二层透明控制窗), 塔冠绽放 —— 南北两支瘦高火柱直上"
        " 4.0, 东西两片火花对开, 四片全部一线双吸 (盖板沿+墙顶)"
        " 重心正压铰链; 塔脚是全库第一圈平铺直角三角地面旋轮"
        " (凯瑟琳轮): 每片一条直角边吸发射台板边、另一条吸邻格"
        "广场板边, 斜边逐格外旋 —— 旋轮既是贴地烟花又是把中央岛"
        "焊进广场的连接件; 前排两座开顶发射管四壁互咬, 管沿各骑"
        "一支蓄势火箭; 北侧双跨观礼台长板双端受力零悬挑, 东端"
        " 30 度坡道顶边一线双吸坡尾扫地 —— 观众就位, 3, 2, 1, 点火!"
    ),
    difficulty=3,
    tags=["节日", "烟花", "庆典", "夜景", "进阶"],
    min_pieces=73,
    min_steps=13,
)
