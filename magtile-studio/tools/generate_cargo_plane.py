#!/usr/bin/env python3
"""生成模型 data/models/cargo_plane_01.json (大型货运飞机)。

机场航空主题 3/4: 全库第一架完整的固定翼货机 —— 与
helicopter_01 (旋翼飞行器) 与 aircraft_carrier_01 的舰载机
(4 片装饰机) 刻意区分: 这是一架以真实静力学摆开的高翼货机 ——
1 格宽 6 格长的箱式机身两侧长板横楣成环, 高置主翼从货舱顶沿
两舷各展 2 格, 翼下发动机短舱墙直落地面 —— 机翼双端受力如桥,
零悬挑; 机尾开敞, 30 度尾门坡道直探停机坪, 等腰垂尾立在尾门
正上 (尖端 3.0), 平尾两片等边三角贴着尾段外展; 机头 747 式
驼峰驾驶舱三面透明风挡; 翼尖帆片、翼上进气锥、机侧集装货堆
与车轮底座拖板车摆满装卸区 —— 舱门已开, 装货!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 机头朝西):
  - 停机坪 8x7 (x [0,8], y [0,7]): 长板为主, 含拖板车
    车轮底座与货堆地格                                         29 片
  - 机身 (x [0,6], y [3,4], z 0..1): 两舷长板横楣 x6 +
    机头封板 + 机尾封板                                         8 片
  - 货舱顶 (z=1): 长板 x2 + 方板 x2 (尾段分格)                  4 片
  - 驾驶舱驼峰 (x [0,1], z 1..2): 透明风挡 x3 + 舱顶 x1         4 片
  - 主翼 (z=1): 每侧 2x2 方板 x4, 高翼双端受力                  8 片
  - 发动机短舱: 立墙 x4 (翼下直落地面)                          4 片
  - 翼上进气锥 x2 + 翼尖帆片 x2                                  4 片
  - 平尾: 等边三角平板 x2; 垂尾: 等腰三角 x1 (尖端 3.0)          3 片
  - 尾门坡道: 30 度长板 x1 (顶边一线双吸, 坡尾探地)              1 片
  - 集装货堆: 等边四坡锥 x4                                      4 片
  合计 69 片, 13 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, strict 档同样全绿):
  - 主翼不是悬挑: 翼根短边吸货舱顶沿与舷墙顶边 (一线双吸),
    翼尖短边落在发动机短舱墙顶 —— 每侧机翼双端受力如桥;
  - 尾门坡道顶边同时吸货舱顶东短边与机尾封板顶边, 坡尾自然
    落地; 垂尾底边同吸一线 (顶沿 + 封板顶), 重心正压力矩为零;
  - 驼峰风挡西片底边整边吸舱顶西短边与机头封板顶边, 三面
    风挡四角竖边互吸再被舱顶压圈;
  - 高层 R8 (垂尾 3.0): 全机处处成环, 单条连接剪断均可绕行。

用法: python3 tools/generate_cargo_plane.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

APRON = "gray"      # 停机坪
RUNWAY = "gray"     # 滑行道
MARK = "yellow"     # 装卸区标线
BODY = "green"      # 机身 (军绿涂装)
DECK = "green"      # 货舱顶
WIN = "clear"       # 驾驶舱风挡
HUMP = "green"      # 驼峰舱顶
WING = "green"      # 主翼
POD = "gray"        # 发动机短舱
ENGINE = "red"      # 进气锥
TIPFIN = "red"      # 翼尖帆片
TAIL = "red"        # 垂尾 / 平尾
RAMPC = "yellow"    # 尾门坡道
CARGO = "yellow"    # 集装货堆
CART = "cyan"       # 拖板车

# =================================================================
# 1. 停机坪 8x7 (x [0,8], y [0,7])
# =================================================================
b.flat_rect("p0_a", 0, 0, 0.0, APRON)
b.add("cart", "wheel_base", (3.0, 0.5, 0.0), (0, 0, 0), CART)  # 拖板车 x [2,4]
b.flat_rect("p0_c", 4, 0, 0.0, APRON)
b.flat("p0_d", 6, 0, 0.0, MARK)         # 货堆地格
b.flat("p0_e", 7, 0, 0.0, MARK)

b.flat_rect("p1_a", 0, 1, 0.0, APRON)
b.flat_rect("p1_b", 2, 1, 0.0, MARK)    # 南装卸区标线
b.flat_rect("p1_c", 4, 1, 0.0, APRON)
b.flat_rect("p1_d", 6, 1, 0.0, APRON)

b.flat_rect("p2_a", 0, 2, 0.0, APRON)
b.flat_rect("p2_b", 2, 2, 0.0, APRON)
b.flat_rect("p2_c", 4, 2, 0.0, APRON)
b.flat_rect("p2_d", 6, 2, 0.0, APRON)

b.flat_rect("p3_a", 0, 3, 0.0, RUNWAY)  # 机腹滑行道
b.flat_rect("p3_b", 2, 3, 0.0, RUNWAY)
b.flat_rect("p3_c", 4, 3, 0.0, RUNWAY)
b.flat_rect("p3_d", 6, 3, 0.0, RUNWAY)

b.flat_rect("p4_a", 0, 4, 0.0, APRON)
b.flat_rect("p4_b", 2, 4, 0.0, APRON)
b.flat_rect("p4_c", 4, 4, 0.0, APRON)
b.flat_rect("p4_d", 6, 4, 0.0, APRON)

b.flat_rect("p5_a", 0, 5, 0.0, APRON)
b.flat_rect("p5_b", 2, 5, 0.0, MARK)    # 北装卸区标线
b.flat_rect("p5_c", 4, 5, 0.0, APRON)
b.flat_rect("p5_d", 6, 5, 0.0, APRON)

b.flat_rect("p6_a", 0, 6, 0.0, APRON)
b.flat_rect("p6_b", 2, 6, 0.0, APRON)
b.flat_rect("p6_c", 4, 6, 0.0, APRON)
b.flat_rect("p6_d", 6, 6, 0.0, APRON)

# =================================================================
# 2. 集装货堆 (x [6,7], y [0,1]): 等边四坡锥
# =================================================================
CARGO_IDS = b.hat4("cargo", 6, 0, 0.0, CARGO, shape="equilateral_triangle")

# =================================================================
# 3. 机身 (x [0,6], y [3,4], z 0..1): 两舷横楣 + 首尾封板
# =================================================================
b.lintel_ns("fu_s1", 0, 3.0, 0, BODY)
b.lintel_ns("fu_s2", 2, 3.0, 0, BODY)
b.lintel_ns("fu_s3", 4, 3.0, 0, BODY)
b.wall_ew("fu_nose", 0.0, 3, 0, BODY)
b.lintel_ns("fu_n1", 0, 4.0, 0, BODY)
b.lintel_ns("fu_n2", 2, 4.0, 0, BODY)
b.lintel_ns("fu_n3", 4, 4.0, 0, BODY)
b.wall_ew("fu_tail", 6.0, 3, 0, BODY)

# =================================================================
# 4. 货舱顶 (z=1): 西两段长板 + 尾段两片方板 (给平尾/垂尾留整边)
# =================================================================
b.flat_rect("dk_1", 0, 3, 1.0, DECK)
b.flat_rect("dk_2", 2, 3, 1.0, DECK)
b.flat("dk_3", 4, 3, 1.0, DECK)
b.flat("dk_4", 5, 3, 1.0, DECK)

# =================================================================
# 5. 驾驶舱驼峰 (x [0,1], y [3,4], z 1..2): 三面透明风挡 + 舱顶
# =================================================================
b.add("cp_w", "window_square", (0.0, 3.5, 1.5), (90, 0, 90), WIN)
b.add("cp_s", "window_square", (0.5, 3.0, 1.5), (90, 0, 0), WIN)
b.add("cp_n", "window_square", (0.5, 4.0, 1.5), (90, 0, 0), WIN)
b.flat("cp_top", 0, 3, 2.0, HUMP)

# =================================================================
# 6. 发动机短舱 (z 0..1) + 主翼 (z=1, 每侧 2x2 方板)
# =================================================================
b.wall_ns("pod_s1", 2, 1.0, 0, POD)
b.wall_ns("pod_s2", 3, 1.0, 0, POD)
b.wall_ns("pod_n1", 2, 6.0, 0, POD)
b.wall_ns("pod_n2", 3, 6.0, 0, POD)

b.flat("wg_s1", 2, 1, 1.0, WING)        # 南翼尖排 (先落短舱墙顶)
b.flat("wg_s2", 3, 1, 1.0, WING)
b.flat("wg_s3", 2, 2, 1.0, WING)        # 南翼根排
b.flat("wg_s4", 3, 2, 1.0, WING)
b.flat("wg_n1", 2, 5, 1.0, WING)        # 北翼尖排
b.flat("wg_n2", 3, 5, 1.0, WING)
b.flat("wg_n3", 2, 4, 1.0, WING)        # 北翼根排
b.flat("wg_n4", 3, 4, 1.0, WING)

# =================================================================
# 7. 翼上进气锥 + 翼尖帆片
# =================================================================
b.crest_ew("eng_s", 3.0, 2, 1.0, ENGINE)
b.crest_ew("eng_n", 3.0, 4, 1.0, ENGINE)
b.crest_ns("tip_s", 2, 1.0, 1.0, TIPFIN)
b.crest_ns("tip_n", 2, 6.0, 1.0, TIPFIN)

# =================================================================
# 8. 尾翼 + 尾门坡道
# =================================================================
b.place_tri("st_s", "equilateral_triangle",
            (6.0, 3.0, 1.0), (5.0, 3.0, 1.0), (5.5, 2.133975, 1.0), TAIL)
b.place_tri("st_n", "equilateral_triangle",
            (5.0, 4.0, 1.0), (6.0, 4.0, 1.0), (5.5, 4.866025, 1.0), TAIL)
b.ramp("tail_ramp", "+x", 6.0, 3, 1.0, RAMPC)
b.spire_ew("vfin", 6.0, 3, 1.0, TAIL)

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺停机坪南带 (y [0,2]): 9 片, 拖板车嵌进装卸道, 东南角是货堆地格。",
    ["p0_a", "cart", "p0_c", "p0_d", "p0_e", "p1_a", "p1_b", "p1_c", "p1_d"],
    tip="车轮底座拖板车与黄色标线, 都是装卸区的一部分。",
)
b.step(
    "铺停机坪中带 (y [2,4]): 8 片, 灰色滑行道就是机腹。",
    ["p2_a", "p2_b", "p2_c", "p2_d", "p3_a", "p3_b", "p3_c", "p3_d"],
    highlight=["p1_b"],
    tip="y=3 与 y=4 两条拼缝将咬住两舷横楣的底边。",
)
b.step(
    "铺停机坪北带 (y [4,7]): 12 片, 8x7 场坪合拢。",
    ["p4_a", "p4_b", "p4_c", "p4_d", "p5_a", "p5_b", "p5_c", "p5_d",
     "p6_a", "p6_b", "p6_c", "p6_d"],
    highlight=["p3_b"],
    tip="翼下发动机短舱要踩 y=1 与 y=6 的拼缝 —— 场坪必须先铺满。",
)
b.step(
    "码集装货堆: 4 片等边三角四棱互吸自锁。",
    CARGO_IDS,
    highlight=["p0_d", "p0_e"],
    tip="货堆就位, 等着从尾门坡道推进货舱。",
)
b.step(
    "立机身南舷与机头: 3 片长板横楣骑滑行道拼缝 + 机头封板。",
    ["fu_s1", "fu_s2", "fu_s3", "fu_nose"],
    highlight=["p3_a", "p3_b"],
    tip="长板横楣一片顶两格, 6 格长的货舱一侧只有两条竖缝。",
)
b.step(
    "立机身北舷与机尾封板: 机尾上半留作尾门。",
    ["fu_n1", "fu_n2", "fu_n3", "fu_tail"],
    highlight=["fu_nose"],
    tip="首尾封板的竖边与两舷横楣互吸, 箱式机身四角闭环。",
)
b.step(
    "盖货舱顶 (z=1): 西两段长板 + 尾段两片方板。",
    ["dk_1", "dk_2", "dk_3", "dk_4"],
    highlight=["fu_s2", "fu_n2"],
    tip="尾段拆成方板 —— 平尾与垂尾都要咬它们的整边。",
)
b.step(
    "起驾驶舱驼峰: 三面透明风挡四角互吸, 舱顶压圈。",
    ["cp_w", "cp_s", "cp_n", "cp_top"],
    highlight=["dk_1", "fu_nose"],
    tip="风挡西片底边同时吸舱顶西短边与机头封板顶边 —— 一线双吸。",
)
b.step(
    "立发动机短舱: 4 片立墙骑装卸区拼缝, 翼下直落地面。",
    ["pod_s1", "pod_s2", "pod_n1", "pod_n2"],
    highlight=["p1_b", "p5_b"],
    tip="短舱墙就是机翼的外支座 —— 高翼货机的力直接走到地面。",
)
b.step(
    "展南翼: 先落翼尖排 (压短舱墙顶), 再拼翼根排 (吸货舱顶沿)。",
    ["wg_s1", "wg_s2", "wg_s3", "wg_s4"],
    highlight=["pod_s1", "dk_2"],
    tip="翼根一线双吸、翼尖压墙顶 —— 机翼是一座双端受力的桥。",
)
b.step(
    "展北翼: 4 片方板同法, 双翼对称合拢。",
    ["wg_n1", "wg_n2", "wg_n3", "wg_n4"],
    highlight=["pod_n1", "wg_s3"],
    tip="剪断翼根整条铰链, 力还能从短舱墙绕回地面。",
)
b.step(
    "装进气锥与翼尖帆片: 4 片三角立在机翼拼缝与翼尖沿口。",
    ["eng_s", "eng_n", "tip_s", "tip_n"],
    highlight=["wg_s4", "wg_n4"],
    tip="进气锥骑翼面拼缝, 帆片同吸翼尖短边与短舱墙顶。",
)
b.step(
    "装平尾、放尾门坡道、立垂尾 —— 大型货机整装待发!",
    ["st_s", "st_n", "tail_ramp", "vfin"],
    highlight=["dk_4", "fu_tail"],
    tip="坡道顶边与垂尾底边同吸尾段一线, 垂尾尖端 3.0 重心正压。",
)

b.finalize(
    model_id="cargo_plane_01",
    name="大型货运飞机",
    name_en="Cargo Plane 01",
    description=(
        "全库第一架完整固定翼货机: 1x6 箱式机身两舷长板横楣四角闭环,"
        " 高置主翼每侧 2x2 方板 —— 翼根短边一线双吸货舱顶沿与舷墙顶边,"
        " 翼尖落在发动机短舱墙顶, 双端受力如桥零悬挑; 机尾开敞, 30 度"
        "尾门坡道顶边一线双吸、坡尾探地, 等腰垂尾立尾门正上 (尖端 3.0"
        " 重心正压力矩为零), 平尾两片等边三角贴尾段外展; 机头 747 式"
        "驼峰三面透明风挡被舱顶压圈; 翼上进气锥、翼尖帆片、集装货堆与"
        "车轮底座拖板车摆满装卸区 —— 高层 R8 处处成环。"
    ),
    difficulty=3,
    tags=["机场", "航空", "货机", "载具", "进阶"],
    min_pieces=65,
    min_steps=13,
)
