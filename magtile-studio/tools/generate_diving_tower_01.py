#!/usr/bin/env python3
"""生成模型 data/models/diving_tower_01.json (跳水训练中心)。

内容批 E 补位模型 (顶替与批 C 撞车撤下的 canal_lock_01): 全库第一座
跳水场景 —— 与 swimming_pool_01 (泳池本体) / 各类瞭望塔 (看的塔)
刻意区分: 本作的结构签名是"一塔两跳台, 低桥高挑臂": 二层跳台塔
立在泳池东侧, 低跳台 (z=1) 像一座桥 —— 东边吸塔墙顶、西边吸池壁
顶, 双端受力零悬挑; 高跳板 (z=2) 才是真正的挑臂 —— 东边整边吸塔
二层墙顶向池心平挑, 板下两片直角三角斜撑双边受力 (水平直角边吸
跳板侧边、竖直直角边吸塔角竖棱), 板-撑-塔锁成门式框架, 剪断顶
铰链跳板照样有支撑路径 (R9 抖动巡检同款加固, 先天免疫)。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 泳池在西):
  - 场地地坪 5 行 (x [0,8], y [0,5]): 灰色防滑砖                24 片
  - 泳池 (x [1,4], y [1,4]): 蓝色池底 3x3 + 青色池壁环 x12      21 片
  - 跳台塔 (x [5,6], y [2,3], z 0..2): 两节墙环 (门框方入口
    + 窗格方瞭望窗)                                              8 片
  - 低跳台 (z=1, 桥式双端受力) + 登塔坡道                        2 片
  - 高跳板 (z=2, 平挑池心) + 双直角三角斜撑                      3 片
  - 泳道浮标线 x2 + 计分屏 + 塔顶红旗                            4 片
  合计 62 片, 13 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告 + jitter 全绿):
  - 低跳台东西两短边分别整边吸塔一层墙顶与池壁顶 (云梯桥同款
    双端受力), 高跳板东边吸塔二层墙顶、板下双斜撑锁成门式框架;
  - 斜撑竖直直角边吸塔墙角竖棱 (一棱双吸: 塔西墙南竖边与塔南墙
    西竖边共线), 水平直角边吸跳板侧边 —— T14 不是装饰;
  - 登塔坡道顶边吸塔东墙顶, 坡尾自然落地 (顶铰链 + 接地两路径);
  - 泳道浮标线骑池底拼缝, 计分屏立地缝, 红旗骑塔顶零力矩;
  - 地坪拼缝纪律: 池壁与塔墙脚处全单位方板。

用法: python3 tools/generate_diving_tower_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

DECK = "gray"        # 场地防滑砖
POOL_F = "blue"      # 池底
POOL_W = "cyan"      # 池壁
TOWER = "orange"     # 跳台塔
TWIN = "cyan"        # 塔二层瞭望窗
PLAT = "clear"       # 跳台 / 跳板
BRACE = "red"        # 斜撑
RAMP = "gray"        # 登塔坡道
LANE = "yellow"      # 泳道浮标线
BOARD = "cyan"       # 计分屏
FLAG = "red"         # 塔顶红旗

# =================================================================
# 1. 场地地坪 5 行 (x [0,8], y [0,5]): 池壁与塔墙脚处全单位方板
# =================================================================
# 南行 (y [0,1])
b.flat_rect("d0_w", 0, 0, 0.0, DECK)
b.flat_rect("d0_m", 2, 0, 0.0, DECK)
b.flat("d0_4", 4, 0, 0.0, DECK)
b.flat("d0_5", 5, 0, 0.0, DECK)
b.flat_rect("d0_e", 6, 0, 0.0, DECK)
# 池区行 (y [1,2] / y [2,3] / y [3,4]): 泳池外只铺东西两侧
b.flat("d1_0", 0, 1, 0.0, DECK)
b.flat("d1_4", 4, 1, 0.0, DECK)
b.flat("d1_5", 5, 1, 0.0, DECK)
b.flat("d1_6", 6, 1, 0.0, DECK)
b.flat("d1_7", 7, 1, 0.0, DECK)
b.flat("d2_0", 0, 2, 0.0, DECK)
b.flat("d2_4", 4, 2, 0.0, DECK)
b.flat("d2_6", 6, 2, 0.0, DECK)
b.flat("d2_7", 7, 2, 0.0, DECK)
b.flat("d3_0", 0, 3, 0.0, DECK)
b.flat("d3_4", 4, 3, 0.0, DECK)
b.flat("d3_5", 5, 3, 0.0, DECK)
b.flat("d3_6", 6, 3, 0.0, DECK)
b.flat("d3_7", 7, 3, 0.0, DECK)
# 北行 (y [4,5])
b.flat_rect("d4_w", 0, 4, 0.0, DECK)
b.flat_rect("d4_m", 2, 4, 0.0, DECK)
b.flat("d4_4", 4, 4, 0.0, DECK)
b.flat("d4_5", 5, 4, 0.0, DECK)
b.flat_rect("d4_e", 6, 4, 0.0, DECK)

# =================================================================
# 2. 泳池 (x [1,4], y [1,4]): 池底 3x3 + 池壁环
# =================================================================
for x in (1, 2, 3):
    for y in (1, 2, 3):
        b.flat(f"pf_{x}_{y}", x, y, 0.0, POOL_F)
for x in (1, 2, 3):
    b.wall_ns(f"pw_s_{x}", x, 1.0, 0, POOL_W)
    b.wall_ns(f"pw_n_{x}", x, 4.0, 0, POOL_W)
for y in (1, 2, 3):
    b.wall_ew(f"pw_w_{y}", 1.0, y, 0, POOL_W)
    b.wall_ew(f"pw_e_{y}", 4.0, y, 0, POOL_W)

# =================================================================
# 3. 跳台塔 (x [5,6], y [2,3], z 0..2): 两节墙环
# =================================================================
b.add("tw1_s", "door_frame", (5.5, 2.0, 0.5), (90, 0, 0), TOWER)  # 入口
b.wall_ns("tw1_n", 5, 3.0, 0, TOWER)
b.wall_ew("tw1_w", 5.0, 2, 0, TOWER)
b.wall_ew("tw1_e", 6.0, 2, 0, TOWER)
b.add("tw2_s", "window_square", (5.5, 2.0, 1.5), (90, 0, 0), TWIN)  # 瞭望窗
b.wall_ns("tw2_n", 5, 3.0, 1, TOWER)
b.wall_ew("tw2_w", 5.0, 2, 1, TOWER)
b.wall_ew("tw2_e", 6.0, 2, 1, TOWER)

# =================================================================
# 4. 低跳台 (桥式) + 登塔坡道 + 高跳板 (挑臂) + 双斜撑
# =================================================================
b.flat("plat_low", 4, 2, 1.0, PLAT)                # 东吸塔顶西吸池壁顶
b.ramp("ladder", "+x", 6, 2, 1.0, RAMP)            # 登塔坡道, 坡尾落地
b.flat("plat_high", 4, 2, 2.0, PLAT)               # 高跳板平挑池心
b.place_tri("brace_s", "right_triangle",
            (5.0, 2.0, 2.0), (4.0, 2.0, 2.0), (5.0, 2.0, 1.0), BRACE)
b.place_tri("brace_n", "right_triangle",
            (5.0, 3.0, 2.0), (4.0, 3.0, 2.0), (5.0, 3.0, 1.0), BRACE)

# =================================================================
# 5. 泳道浮标线 + 计分屏 + 塔顶红旗
# =================================================================
b.crest_ew("lane_a", 2.0, 2, 0.0, LANE)            # 骑池底 x=2 拼缝
b.crest_ew("lane_b", 3.0, 1, 0.0, LANE)            # 骑池底 x=3 拼缝
b.add("score", "window_square", (7.5, 4.0, 0.5), (90, 0, 0), BOARD)
b.crest_ns("flag", 5, 3.0, 2.0, FLAG)              # 骑塔顶北墙沿

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺场地南行: 防滑砖两长两短, 池壁脚下用单位方板。",
    ["d0_w", "d0_m", "d0_4", "d0_5", "d0_e"],
    tip="跳水中心从观众入口这一侧开始铺 —— 比赛马上开始。",
)
b.step(
    "铺池区两行的东西两侧: 泳池的坑位先空着。",
    ["d1_0", "d1_4", "d1_5", "d1_6", "d1_7",
     "d2_0", "d2_4", "d2_6", "d2_7"],
    highlight=["d0_4"],
    tip="塔脚四格都是单位方板 —— 墙底边要和方板边等长吸合。",
)
b.step(
    "铺第三行与北行收口: 场地围出泳池坑位。",
    ["d3_0", "d3_4", "d3_5", "d3_6", "d3_7",
     "d4_w", "d4_m", "d4_4", "d4_5", "d4_e"],
    highlight=["d2_4"],
    tip="相邻行等长边互吸 —— 整片场地连成一体。",
)
b.step(
    "铺泳池池底: 3x3 蓝色水板, 池壁的脚全踩在这些拼缝上。",
    ["pf_1_1", "pf_1_2", "pf_1_3", "pf_2_1", "pf_2_2", "pf_2_3",
     "pf_3_1", "pf_3_2", "pf_3_3"],
    highlight=["d1_0"],
    tip="蓝色一铺, 水就注进来了 —— 深水区就在跳台正下方。",
)
b.step(
    "砌池壁南墙与西墙: 六片青色瓷砖立墙, 转角竖边互咬。",
    ["pw_s_1", "pw_s_2", "pw_s_3", "pw_w_1", "pw_w_2", "pw_w_3"],
    highlight=["pf_1_1"],
    tip="池壁脚踩池底与场地双拼缝 —— 一圈墙把水兜住。",
)
b.step(
    "砌池壁北墙与东墙合环: 东壁顶一会儿要接住低跳台。",
    ["pw_n_1", "pw_n_2", "pw_n_3", "pw_e_1", "pw_e_2", "pw_e_3"],
    highlight=["pw_s_1"],
    tip="闭环池壁拆一片不倒 —— 它还是跳台桥的西岸。",
)
b.step(
    "立跳台塔第一节: 门框方入口朝南, 四角竖边互咬成环。",
    ["tw1_s", "tw1_n", "tw1_w", "tw1_e"],
    highlight=["d2_4"],
    tip="运动员从这扇门进塔 —— 塔环是全部跳台的靠山。",
)
b.step(
    "摞塔第二节: 瞭望窗朝南, 底边与下节墙顶整边共线吸合。",
    ["tw2_s", "tw2_n", "tw2_w", "tw2_e"],
    highlight=["tw1_s"],
    tip="两节都是闭环 —— 高跳板的根就扎在这节墙顶上。",
)
b.step(
    "架低跳台与登塔坡道: 跳台东吸塔墙顶西吸池壁顶如桥, 坡道"
    "顶边吸塔东墙顶、坡尾落地。",
    ["plat_low", "ladder"],
    highlight=["pw_e_2", "tw1_w"],
    tip="低跳台双端受力零悬挑 —— 新手先从一米台开始。",
)
b.step(
    "挑出高跳板并锁双斜撑: 跳板东边吸塔二层墙顶向池心平挑, "
    "两片红色斜撑竖边吸塔角竖棱、横边吸跳板侧边。",
    ["plat_high", "brace_s", "brace_n"],
    highlight=["tw2_w"],
    tip="板-撑-塔锁成门式框架 —— 剪断顶铰链跳板也不掉。",
)
b.step(
    "拉泳道浮标线: 两条黄色浮标骑池底拼缝, 分出深浅水区。",
    ["lane_a", "lane_b"],
    highlight=["pf_2_2"],
    tip="浮标线重心正压拼缝铰链 —— 水波推不歪。",
)
b.step(
    "立计分屏: 窗格方大屏立上东北角地缝, 面朝跳台。",
    ["score"],
    highlight=["d3_7"],
    tip="裁判打分全场都看得见 —— 满分动作预备!",
)
b.step(
    "升塔顶红旗: 红旗骑二层北墙顶, 跳水中心开赛!",
    ["flag"],
    highlight=["tw2_n"],
    tip="红旗重心正压墙顶铰链线 —— 三米板, 向前翻腾两周半!",
)

b.finalize(
    model_id="diving_tower_01",
    name="跳水训练中心",
    name_en="Diving Tower 01",
    description=(
        "只用核心九片型的跳水场景, 结构签名是'一塔两跳台, 低桥高挑臂'"
        ": 二层跳台塔 (门框方入口 + 窗格方瞭望窗) 立在泳池东侧, 低跳台"
        "像一座桥 —— 东边吸塔一层墙顶、西边吸池壁顶双端受力零悬挑; 高"
        "跳板才是真正的挑臂 —— 东边整边吸塔二层墙顶向池心平挑, 板下两"
        "片红色直角三角斜撑竖边吸塔角竖棱、横边吸跳板侧边, 板-撑-塔锁"
        "成门式框架, 剪断顶铰链跳板照样有支撑路径; 登塔坡道坡尾落地, "
        "3x3 蓝色泳池两条黄色浮标线分出深浅水区, 窗格方计分屏立在东北"
        "角 —— 三米板, 向前翻腾两周半, 入水!"
    ),
    difficulty=3,
    tags=["运动", "跳水", "泳池", "竞技", "挑战"],
    min_pieces=62,
    min_steps=13,
)
