#!/usr/bin/env python3
"""生成模型 data/models/pipe_organ_01.json (音乐厅管风琴)。

内容批 F 模型 1/4: 全库第一台管风琴 —— 音乐主题此前只有
drum_set (架子鼓) / piano_stage (钢琴舞台) / violin_shop (提琴铺) /
marching_band (行进乐队), 键盘乐器只有平放的钢琴, 还没有一件
"往天上长"的乐器。结构签名是"共墙音管楼按 1-2-3-2-1 阶梯升高":
五座 1x1 音管楼在一条直线上并肩而立, 相邻音管楼共用一面隔墙
(不是五座独立塔), 楼高从两端向中央 1-2-3-2-1 递增, 每座楼顶
盖板后沿立一支金色瘦高管口, 五支管口连成一道阶梯天际线;
演奏台前的键盘是一块 30 度透明斜板 (顶边整边吸台口, 坡尾压地),
与 tessellation_screen (平面屏风) / farm_silo (单筒仓) /
skyscraper (旋位退台) 的结构逻辑全部错开。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 音管墙朝南):
  - 音乐厅地板 4 行 (x [0,7], y [0,4]): 石板 + 红毯走道       21 片
  - 音管楼群 (x [1,6], y [3,4]): 五座共墙音管楼, 楼高
    1-2-3-2-1, 隔墙 12 + 前后墙 20 + 盖板 5 + 金管口 5        42 片
  - 演奏台 (x [3,4], y [2,3]): 三面围墙 (北墙与中央音管楼
    共用) + 台面 + 30 度键盘斜板                               5 片
  - 琴凳 (x [1,2], y [0,1]): 四墙小箱 + 软垫盖板              5 片
  - 演奏家 + 听众 x2: 骑缝三角                                 1 片
  合计 74 片, 13 个教程步骤, 4 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告 + jitter 全绿):
  - 相邻音管楼共用隔墙, 每层楼环四角竖边互咬, 荷载沿墙直下;
  - 隔墙高度取两侧楼高的较大值, 盖板四边全部有墙顶/墙底边可吸;
  - 键盘斜板顶边整边吸演奏台前墙顶 + 台面南沿, 坡尾稳稳压地
    (顶铰链 + 接地坡尾双路受力, 投石机长臂同款);
  - 地板拼缝纪律: 全部墙脚与骑缝三角脚下都是单位方板/短边对齐。

用法: python3 tools/generate_pipe_organ_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

FLOOR = "gray"      # 音乐厅石板
CARPET = "red"      # 红毯走道
PIPE_F = "clear"    # 音管楼前墙 (银管)
PIPE_S = "gray"     # 音管楼隔墙与后墙
CAP = "gray"        # 音管楼盖板
MOUTH = "yellow"    # 金色管口
DESK = "orange"     # 演奏台木墙
KEYS = "clear"      # 键盘斜板
BENCH = "orange"    # 琴凳
CUSHION = "red"     # 琴凳软垫
PLAYER = "blue"     # 演奏家
GUEST1 = "green"    # 听众
GUEST2 = "pink"     # 听众

# 音管楼高度型线 (西 -> 东): 1-2-3-2-1
HEIGHTS = [1, 2, 3, 2, 1]

# =================================================================
# 1. 音乐厅地板 4 行 (x [0,7], y [0,4])
# =================================================================
# 音管楼行 (y [3,4]): 七片单位方板, 全部隔墙脚都踩在拼缝上
for x in range(7):
    b.flat(f"g3_{x}", x, 3, 0.0, FLOOR)
# 演奏台行 (y [2,3]): 台脚三方板 + 两侧长板
b.flat_rect("g2_w", 0, 2, 0.0, FLOOR)
b.flat("g2_2", 2, 2, 0.0, FLOOR)
b.flat("g2_3", 3, 2, 0.0, FLOOR)
b.flat("g2_4", 4, 2, 0.0, FLOOR)
b.flat_rect("g2_e", 5, 2, 0.0, FLOOR)
# 走道行 (y [1,2]): 琴凳北脚方板 + 红毯 + 东侧长板
b.flat("g1_1", 1, 1, 0.0, FLOOR)
b.flat("g1_2", 2, 1, 0.0, FLOOR)
b.flat("g1_3", 3, 1, 0.0, CARPET)
b.flat_rect("g1_e", 4, 1, 0.0, FLOOR)
# 听众行 (y [0,1]): 琴凳脚方板 + 红毯 + 东侧长板
b.flat("g0_0", 0, 0, 0.0, FLOOR)
b.flat("g0_1", 1, 0, 0.0, FLOOR)
b.flat("g0_2", 2, 0, 0.0, FLOOR)
b.flat("g0_3", 3, 0, 0.0, CARPET)
b.flat_rect("g0_e", 4, 0, 0.0, FLOOR)

# =================================================================
# 2. 音管楼群一层 (z 0..1): 前后墙 + 六面隔墙
# =================================================================
for k in range(5):
    b.wall_ns(f"p{k}_f0", 1 + k, 3.0, 0, PIPE_F)   # 前墙 (南)
    b.wall_ns(f"p{k}_b0", 1 + k, 4.0, 0, PIPE_S)   # 后墙 (北)
for x in range(1, 7):
    b.wall_ew(f"d{x}_0", float(x), 3, 0, PIPE_S)   # 隔墙 z0

# =================================================================
# 3. 音管楼群二层 (z 1..2): 中间三座楼继续长高
# =================================================================
for k in (1, 2, 3):
    b.wall_ns(f"p{k}_f1", 1 + k, 3.0, 1, PIPE_F)
    b.wall_ns(f"p{k}_b1", 1 + k, 4.0, 1, PIPE_S)
for x in (2, 3, 4, 5):
    b.wall_ew(f"d{x}_1", float(x), 3, 1, PIPE_S)

# =================================================================
# 4. 中央音管楼三层 (z 2..3): 只有正中一座冲到最高
# =================================================================
b.wall_ns("p2_f2", 3, 3.0, 2, PIPE_F)
b.wall_ns("p2_b2", 3, 4.0, 2, PIPE_S)
b.wall_ew("d3_2", 3.0, 3, 2, PIPE_S)
b.wall_ew("d4_2", 4.0, 3, 2, PIPE_S)

# =================================================================
# 5. 楼顶盖板 + 金色管口 (瘦高三角骑盖板北沿)
# =================================================================
for k, h in enumerate(HEIGHTS):
    b.flat(f"cap_{k}", 1 + k, 3, float(h), CAP)
for k, h in enumerate(HEIGHTS):
    b.spire_ns(f"mouth_{k}", 1 + k, 4.0, float(h), MOUTH)

# =================================================================
# 6. 演奏台 (x [3,4], y [2,3]): 北墙与中央音管楼前墙共用
# =================================================================
b.wall_ns("con_s", 3, 2.0, 0, DESK)
b.wall_ew("con_w", 3.0, 2, 0, DESK)
b.wall_ew("con_e", 4.0, 2, 0, DESK)
b.flat("con_deck", 3, 2, 1.0, DESK)

# =================================================================
# 7. 键盘斜板: 30 度透明长板, 顶边吸台口, 坡尾压红毯
# =================================================================
b.ramp("keys", "-y", 2.0, 3, 1.0, KEYS)

# =================================================================
# 8. 琴凳 (x [1,2], y [0,1]) + 演奏家 + 听众
# =================================================================
b.wall_ns("bench_s", 1, 0.0, 0, BENCH)
b.wall_ns("bench_n", 1, 1.0, 0, BENCH)
b.wall_ew("bench_w", 1.0, 0, 0, BENCH)
b.wall_ew("bench_e", 2.0, 0, 0, BENCH)
b.flat("bench_cap", 1, 0, 1.0, CUSHION)
b.crest_ns("player", 1, 1.0, 1.0, PLAYER)        # 演奏家骑凳垫北沿
b.crest_ew("guest_w", 1.0, 1, 0.0, GUEST1)       # 听众骑走道拼缝
b.crest_ew("guest_e", 4.0, 0, 0.0, GUEST2)       # 听众骑听众席拼缝

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺音管楼行: 七片单位方板一字排开, 五座音管楼的墙脚全踩这行。",
    [f"g3_{x}" for x in range(7)],
    tip="音乐厅开工啦! 墙脚下必须是单位方板, 拼缝就是墙的地基线。",
)
b.step(
    "铺演奏台行: 三片方板托住台脚, 两端各接一块长板。",
    ["g2_w", "g2_2", "g2_3", "g2_4", "g2_e"],
    highlight=["g3_3"],
    tip="相邻行等长边互吸 —— 方板挨方板, 长板短边对方板。",
)
b.step(
    "铺红毯走道行: 红毯方板正对演奏台, 观众沿着红毯入场。",
    ["g1_1", "g1_2", "g1_3", "g1_e"],
    highlight=["g2_3"],
    tip="红毯铺在正中央, 一路通到键盘前。",
)
b.step(
    "铺听众行收口: 琴凳脚下三片方板 + 红毯 + 东侧长板。",
    ["g0_0", "g0_1", "g0_2", "g0_3", "g0_e"],
    highlight=["g1_1"],
    tip="地板连成一整片, 音乐厅的地基完工!",
)
b.step(
    "立音管楼一层前后墙: 五片银色前墙朝南, 五片灰墙在后排。",
    [f"p{k}_f0" for k in range(5)] + [f"p{k}_b0" for k in range(5)],
    highlight=["g3_1", "g3_5"],
    tip="前墙是亮闪闪的银管面 —— 一口气排出五座楼的地基墙。",
)
b.step(
    "插一层隔墙: 六面隔墙把五座音管楼隔开, 相邻楼共用一面墙。",
    [f"d{x}_0" for x in range(1, 7)],
    highlight=["p0_f0", "p4_b0"],
    tip="共墙是这台管风琴的小秘密 —— 五座楼其实手拉手连成一体。",
)
b.step(
    "音管楼长到二层: 中间三座继续升高, 前后墙加隔墙整层摞上去。",
    ["p1_f1", "p2_f1", "p3_f1", "p1_b1", "p2_b1", "p3_b1",
     "d2_1", "d3_1", "d4_1", "d5_1"],
    highlight=["d3_0"],
    tip="底边与一层墙顶整边共线吸合, 两端的矮楼就停在一层。",
)
b.step(
    "中央音管冲顶三层: 正中一座楼再长一层, 成为全场最高。",
    ["p2_f2", "p2_b2", "d3_2", "d4_2"],
    highlight=["p2_f1"],
    tip="1-2-3-2-1 的阶梯天际线, 中央这根管子唱最低的音!",
)
b.step(
    "盖五块楼顶盖板: 每座音管楼的楼顶四边都有墙边可吸。",
    [f"cap_{k}" for k in range(5)],
    highlight=["p2_f2"],
    tip="盖板一压, 每座音管楼都变成结实的闭口箱。",
)
b.step(
    "立金色管口: 五支瘦高三角骑在盖板北沿, 连成阶梯音阶。",
    [f"mouth_{k}" for k in range(5)],
    highlight=["cap_2"],
    tip="金管口从矮到高再到矮 —— 嘟~ 这就是管风琴的嗓子。",
)
b.step(
    "砌演奏台: 三面木墙围住台位, 北面借用中央音管楼的前墙, 盖上台面。",
    ["con_s", "con_w", "con_e", "con_deck"],
    highlight=["g2_3", "p2_f0"],
    tip="演奏台紧贴音管楼 —— 台面四边都吸在墙顶上。",
)
b.step(
    "搭琴凳: 四面矮墙围成小箱, 盖上红色软垫。",
    ["bench_s", "bench_n", "bench_w", "bench_e", "bench_cap"],
    highlight=["g0_1"],
    tip="凳箱四角竖边互咬, 演奏家坐上去稳稳当当。",
)
b.step(
    "挂键盘斜板并请大家就位: 透明长板顶边整边吸台口, 坡尾压在红毯上; "
    "演奏家骑凳垫, 两位听众骑地缝。",
    ["keys", "player", "guest_w", "guest_e"],
    highlight=["con_deck", "g1_3"],
    tip="十指落键 —— 音乐厅的第一首曲子, 开演!",
)

b.finalize(
    model_id="pipe_organ_01",
    name="音乐厅管风琴",
    name_en="Pipe Organ 01",
    description=(
        "只用核心九片型的音乐厅一景, 全库第一台管风琴, 给音乐主题"
        "补上一件'往天上长'的乐器: 结构签名是'共墙音管楼按 1-2-3-2-1 "
        "阶梯升高' —— 五座 1x1 音管楼在一条直线上并肩而立, 相邻楼"
        "共用一面隔墙 (五座楼其实手拉手连成一体), 楼高从两端向中央"
        "1-2-3-2-1 递增, 每座楼顶盖板后沿立一支金色瘦高管口, 五支"
        "管口连成阶梯天际线; 演奏台紧贴中央音管楼 (北墙共用), 30 度"
        "透明键盘斜板顶边整边吸台口、坡尾稳稳压在红毯上, 橙色琴凳"
        "四角互咬, 演奏家落座, 两位听众沿红毯入场 —— 嘟~ 第一首"
        "曲子开演!"
    ),
    difficulty=3,
    tags=["音乐", "管风琴", "音乐厅", "演出", "进阶"],
    min_pieces=74,
    min_steps=13,
)
