#!/usr/bin/env python3
"""生成模型 data/models/bike_rack_park_01.json (自行车亭公园)。

绿色出行主题: 全库第一座慢行交通街角公园 —— 7x5 绿地中央
一座开敞式自行车亭: 蓝色后墙加两根黄色前柱托起透明顶棚
(前后双铰链线互为保险), 亭檐三片橙色三角装饰; 亭前一排
灰色停车架, 四辆彩色单车斜靠架位 (直角三角双边吸合);
东侧绿色修车小站戴红色等腰尖顶, 东西步道穿园而过,
入口发光园牌, 双树成荫、清池映花 —— 骑车来, 走路走,
绿色出行最风景。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 车亭朝南):
  - 园区地坪 7x5: 草坪/车亭地/步道/清池混铺                    28 片
  - 自行车亭: 后墙 x3 + 前柱 x2 + 透明顶棚 x3 + 檐饰等边 x3   11 片
  - 停车架: 等边三角 x3 (y=2 格线一字排开)                      3 片
  - 单车: 直角三角 x4 (垂直插进架位, 双边吸合)                  4 片
  - 修车小站 1x1: 方墙 x4 + 等腰四坡尖顶 x4                     8 片
  - 大树: 方板树干 x2 + 等边树冠 x2                             4 片
  - 入口园牌: 方柱 x1 + 发光窗格牌 x1                           2 片
  - 花丛等边 x2                                                 2 片
  合计 62 片, 16 个教程步骤, 6 种磁力片形状 (CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验):
  - 车亭顶棚每片方板北边整边压后墙顶、南边落前柱顶/邻板互吸,
    前后两条铰链线互为保险 —— 剪断任一条, 顶棚仍有另一条传力;
  - 单车直角三角竖边吸格线、横边吸地坪, 双边吸合像真车支脚;
  - 修车小站四墙拐角互吸自锁, 等腰四坡尖顶斜棱两两互吸,
    锥尖 2.94 格是全场制高点;
  - 檐饰/停车架/花丛底边全部整边吸沿口或格线, 重心正压铰链。

用法: python3 tools/generate_bike_rack_park.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

LAWN = "green"      # 草坪
FLOOR = "gray"      # 车亭地坪
PATH = "cyan"       # 步道
POND = "clear"      # 清池
SHED_W = "blue"     # 车亭后墙
POST = "yellow"     # 前柱
CANOPY = "clear"    # 透明顶棚
FASCIA = "orange"   # 檐饰
RACK = "gray"       # 停车架
KIOSK = "green"     # 修车小站
KHAT = "red"        # 小站尖顶
TRUNK = "gray"      # 树干
LEAF = "green"      # 树冠
SIGN = "green"      # 园牌
FLOWER = "pink"     # 花丛

# =================================================================
# 1. 园区地坪 7x5
# =================================================================
b.flat_rect("g4_a", 0, 4, 0.0, LAWN)                # 后排 [0,2]
b.flat("g4_2", 2, 4, 0.0, LAWN)
b.flat_rect("g4_b", 3, 4, 0.0, LAWN)                # [3,5]
b.flat("g4_5", 5, 4, 0.0, LAWN)
b.flat("g4_6", 6, 4, 0.0, LAWN)
for x in range(7):
    color = FLOOR if 1 <= x <= 3 or x == 5 else LAWN
    b.flat(f"g3_{x}", x, 3, 0.0, color)             # 车亭行
for x in range(7):
    b.flat(f"g2_{x}", x, 2, 0.0, FLOOR if 1 <= x <= 4 else LAWN)  # 停车行
b.flat_rect("g1_a", 0, 1, 0.0, PATH)                # 步道 [0,2]
b.flat_rect("g1_b", 2, 1, 0.0, PATH)                # [2,4]
b.flat_rect("g1_c", 4, 1, 0.0, PATH)                # [4,6]
b.flat("g1_6", 6, 1, 0.0, PATH)
b.flat("g0_0", 0, 0, 0.0, LAWN)
b.flat_rect("g0_a", 1, 0, 0.0, LAWN)                # [1,3]
b.flat("g0_3", 3, 0, 0.0, LAWN)
b.flat_rect("g0_pond", 4, 0, 0.0, POND)             # 清池 [4,6]
b.flat("g0_6", 6, 0, 0.0, LAWN)

# =================================================================
# 2. 自行车亭 [1,4]x[3,4]: 后墙 + 前柱 + 透明顶棚 + 檐饰
# =================================================================
for x in (1, 2, 3):
    b.wall_ns(f"sh_b{x}", x, 4.0, 0, SHED_W)        # 后墙
b.wall_ns("sh_pw", 1, 3.0, 0, POST)                 # 西前柱
b.wall_ns("sh_pe", 3, 3.0, 0, POST)                 # 东前柱
for x in (1, 2, 3):
    b.flat(f"sh_r{x}", x, 3, 1.0, CANOPY)           # 透明顶棚
for x in (1, 2, 3):
    b.crest_ns(f"sh_f{x}", x, 3.0, 1.0, FASCIA)     # 檐饰

# =================================================================
# 3. 停车架 (y=2 格线) + 单车 (垂直插进架位)
# =================================================================
for x in (1, 2, 3):
    b.crest_ns(f"rack_{x}", x, 2.0, 0.0, RACK)
for x, c in ((1, "red"), (2, "blue"), (3, "purple"), (4, "orange")):
    b.brace(f"bike_{x}", (float(x), 2.0, 0.0), "+y", c)

# =================================================================
# 4. 修车小站 [5,6]x[3,4] + 大树 + 园牌 + 花丛
# =================================================================
b.wall_ns("kk_s", 5, 3.0, 0, KIOSK)
b.wall_ns("kk_n", 5, 4.0, 0, KIOSK)
b.wall_ew("kk_w", 5.0, 3, 0, KIOSK)
b.wall_ew("kk_e", 6.0, 3, 0, KIOSK)
KIOSK_HAT = b.hat4("kh", 5, 3, 1.0, KHAT)           # 等腰尖顶 (2.94 格)
b.wall_ns("tr1_t", 0, 4.0, 0, TRUNK)                # 西树
b.crest_ns("tr1_c", 0, 4.0, 1.0, LEAF)
b.wall_ns("tr2_t", 6, 4.0, 0, TRUNK)                # 东树
b.crest_ns("tr2_c", 6, 4.0, 1.0, LEAF)
b.wall_ew("sg_post", 6.0, 1, 0, SIGN)               # 园牌柱 (步道东口)
b.add("sg_sign", "window_square", (6.0, 1.5, 1.5), (90, 0, 90), SIGN)
b.crest_ns("fl_1", 0, 0.0, 0.0, FLOWER)             # 花丛
b.crest_ns("fl_2", 3, 0.0, 0.0, "red")

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺后排草坪: 沿 y=4 铺 5 片绿色, 长板与方板混拼。",
    ["g4_a", "g4_2", "g4_b", "g4_5", "g4_6"],
    tip="车亭后墙、小站和双树都会踩在这排格线上。",
)
b.step(
    "铺车亭行: 7 片方板, 灰色是车亭与小站的地基。",
    [f"g3_{x}" for x in range(7)],
    highlight=["g4_2"],
    tip="每片对齐格子 —— 前柱与小站南墙踩这排格线。",
)
b.step(
    "铺停车行: 再铺 7 片, 灰色四格是单车的停车位。",
    [f"g2_{x}" for x in range(7)],
    highlight=["g3_1"],
    tip="停车架立在 y=2 格线上, 单车垂直插进架位。",
)
b.step(
    "铺东西步道: 3 片青色长板加 1 片方板横贯全园。",
    ["g1_a", "g1_b", "g1_c", "g1_6"],
    highlight=["g2_0"],
    tip="步道东口就是园牌的位置 —— 行人从这里进园。",
)
b.step(
    "铺前排草坪与清池: 透明长板是一汪清池, 绿地收边。",
    ["g0_0", "g0_a", "g0_3", "g0_pond", "g0_6"],
    highlight=["g1_a"],
    tip="池水映着车亭 —— 公园的南沿完成。",
)
b.step(
    "立车亭后墙: 3 片蓝色方墙沿 y=4 一字排开, 竖边互吸。",
    ["sh_b1", "sh_b2", "sh_b3"],
    highlight=["g3_1", "g3_3"],
    tip="后墙是顶棚的主要依托 —— 底边整边吸格线。",
)
b.step(
    "立前柱: 2 根黄色方柱分立车亭前沿两端, 中间留出推车口。",
    ["sh_pw", "sh_pe"],
    highlight=["sh_b1", "sh_b3"],
    tip="前柱与后墙隔 1 格相望 —— 顶棚要同时压住它们。",
)
b.step(
    "盖透明顶棚: 3 片透明方板北边压后墙顶、南边落前柱顶。",
    ["sh_r1", "sh_r2", "sh_r3"],
    highlight=["sh_b1", "sh_pw"],
    tip="前后两条铰链线互为保险 —— 剪断一条, 另一条还在。",
)
b.step(
    "装亭檐装饰: 3 片橙色等边三角立上顶棚南沿。",
    ["sh_f1", "sh_f2", "sh_f3"],
    highlight=["sh_r1", "sh_r3"],
    tip="底边整边吸顶棚沿口, 重心正压铰链 —— 车亭有了眉眼。",
)
b.step(
    "立停车架: 3 片灰色等边三角沿 y=2 格线排开。",
    ["rack_1", "rack_2", "rack_3"],
    highlight=["g2_1", "g2_3"],
    tip="三角架就是车位卡槽 —— 每片底边整边吸格线。",
)
b.step(
    "停单车: 4 辆彩色单车垂直插进架位, 直角边双边吸合。",
    ["bike_1", "bike_2", "bike_3", "bike_4"],
    highlight=["rack_1", "rack_3"],
    tip="竖边吸格线、横边吸地坪 —— 像真车支脚一样稳。",
)
b.step(
    "起修车小站四墙: 东侧 1x1 绿色方墙拐角互吸。",
    ["kk_s", "kk_n", "kk_w", "kk_e"],
    highlight=["g3_5"],
    tip="补胎打气都在这里 —— 四墙自锁成筒。",
)
b.step(
    "戴小站尖顶: 4 片等腰三角四坡合拢, 锥尖 2.94 格。",
    KIOSK_HAT,
    highlight=["kk_s", "kk_n"],
    tip="斜棱两两互吸自锁成环 —— 全场制高点。",
)
b.step(
    "种双树: 东西两角树干顶起绿色树冠。",
    ["tr1_t", "tr1_c", "tr2_t", "tr2_c"],
    highlight=["g4_a", "g4_6"],
    tip="树冠重心正压树干顶铰链 —— 草坪有了树荫。",
)
b.step(
    "立入口园牌: 绿色方柱顶起发光窗格牌, 守着步道东口。",
    ["sg_post", "sg_sign"],
    highlight=["g1_6"],
    tip="牌上写着: 骑车来, 走路走 —— 绿色出行最风景。",
)
b.step(
    "栽花丛: 南沿开出粉红两丛花 —— 街角公园开园!",
    ["fl_1", "fl_2"],
    highlight=["g0_0", "g0_3"],
    tip="花丛底边整边吸草坪格线 —— 停好车, 逛公园去。",
)

b.finalize(
    model_id="bike_rack_park_01",
    name="自行车亭公园",
    name_en="Bike Rack Park 01",
    description=(
        "全库第一座慢行交通街角公园: 开敞式自行车亭由蓝色后墙与两根黄色"
        "前柱托起 3 片透明顶棚 —— 每片北边整边压后墙顶、南边落前柱顶或与"
        "邻板互吸, 前后双铰链线互为保险; 亭檐三片橙色三角点睛, 亭前一排"
        "灰色停车架, 四辆彩色单车垂直插进架位 (直角三角竖边吸格线、横边"
        "吸地坪, 双边吸合像真车支脚); 东侧绿色修车小站四墙自锁、等腰四坡"
        "尖顶 2.94 格制高, 东西步道穿园, 入口发光园牌, 双树成荫、清池映花 "
        "—— 骑车来, 走路走, 绿色出行最风景。"
    ),
    difficulty=3,
    tags=["城市", "公园", "自行车", "绿色出行", "进阶"],
    min_pieces=50,
    min_steps=16,
)
