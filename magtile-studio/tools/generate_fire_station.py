#!/usr/bin/env python3
"""生成模型 data/models/fire_station_01.json (消防站)。

第二批模型 ⑨: 城市生活主题 —— 一号消防站: 5 格宽双车库
(两个 2 格宽车库大门 + 中央立柱), 东侧 4 层瞭望塔戴四坡尖顶,
门前停车坪上还停着一辆红色消防车 (车顶警灯闪闪)。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 车库地坪: 5x2 方板                                        10 片
  - 车库墙体: 后墙 10 + 两侧山墙 8 + 中央立柱 2 + 门楣 2      22 片
  - 车库屋顶: 5x2 方板                                        10 片
  - 瞭望塔 (x 5..6): 底板 + 四面筒壁 4 层 + 顶板 + 四坡尖顶   20 片
  - 停车坪: 门前 5 片方板                                      5 片
  - 消防车: 底盘 2 + 车厢墙 6 + 车顶 2 + 警灯 1               11 片
  - 站牌垛口: 屋顶前沿 3 片红色等边三角                         3 片
  合计 81 片, 19 个教程步骤, 4 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 车库大门上方的门楣两端竖边分别吸山墙与立柱竖边 (三边受力过梁);
  - 瞭望塔西侧下两层直接借用车库东山墙 (共墙不重叠), 塔身是
    闭合箱形筒 + 顶板 + 四坡自锁尖顶;
  - 消防车通过停车坪与主楼相连, 全场一个连通整体。

用法: python3 tools/generate_fire_station.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

# =================================================================
# 1. 车库地坪 (z=0): 5x2 方板
# =================================================================
for x in range(5):
    for y in range(2):
        b.flat(f"fl_{x}_{y}", x, y, 0.0, "gray")

# =================================================================
# 2. 车库墙体 (z 0..2): 后墙 / 山墙 / 中央立柱 / 门楣
# =================================================================
for x in range(5):                          # 后墙 (y=2) 两层
    b.wall_ns(f"bk1_{x}", x, 2.0, 0, "red")
    b.wall_ns(f"bk2_{x}", x, 2.0, 1, "red")
for y in range(2):                          # 西山墙 (x=0) 两层
    b.wall_ew(f"ww1_{y}", 0.0, y, 0, "red")
    b.wall_ew(f"ww2_{y}", 0.0, y, 1, "red")
for y in range(2):                          # 东山墙 (x=5) 两层
    b.wall_ew(f"ew1_{y}", 5.0, y, 0, "red")
    b.wall_ew(f"ew2_{y}", 5.0, y, 1, "red")
b.wall_ns("pil1", 2, 0.0, 0, "yellow")      # 中央立柱下层 (两门之间)
b.wall_ns("pil2", 2, 0.0, 1, "yellow")      # 中央立柱上层
b.lintel_ns("lin_w", 0, 0.0, 1, "yellow")   # 西门楣 (跨 x 0..2)
b.lintel_ns("lin_e", 3, 0.0, 1, "yellow")   # 东门楣 (跨 x 3..5)

# =================================================================
# 3. 车库屋顶 (z=2): 5x2 方板
# =================================================================
for x in range(5):
    for y in range(2):
        b.flat(f"rf_{x}_{y}", x, y, 2.0, "gray")

# =================================================================
# 4. 瞭望塔 (x 5..6, y 0..1, z 0..4): 西侧下两层借用车库东山墙
# =================================================================
b.flat("tw_base", 5, 0, 0.0, "gray")                  # 塔底板
for z in range(4):
    b.wall_ns(f"tw_s_{z}", 5, 0.0, z, "red")          # 塔南壁
    b.wall_ns(f"tw_n_{z}", 5, 1.0, z, "red")          # 塔北壁
    b.wall_ew(f"tw_e_{z}", 6.0, 0, z, "clear")        # 塔东壁 (透明观察窗)
for z in (2, 3):
    b.wall_ew(f"tw_w_{z}", 5.0, 0, z, "red")          # 塔西壁上两层
b.flat("tw_top", 5, 0, 4.0, "gray")                   # 塔顶板
HAT = b.hat4("tw_hat", 5, 0, 4.0, "orange")           # 四坡尖顶

# =================================================================
# 5. 停车坪 (y -1..0): 门前 5 片方板
# =================================================================
for x in range(5):
    b.flat(f"ap_{x}", x, -1, 0.0, "gray")

# =================================================================
# 6. 消防车 (x 1..3, y -2..-1): 底盘 + 车厢 + 车顶 + 警灯
# =================================================================
for x in (1, 2):
    b.flat(f"tr_fl_{x}", x, -2, 0.0, "red")           # 底盘
for x in (1, 2):
    b.wall_ns(f"tr_s_{x}", x, -2.0, 0, "red")         # 车厢南壁
    b.wall_ns(f"tr_n_{x}", x, -1.0, 0, "red")         # 车厢北壁
b.wall_ew("tr_w", 1.0, -2, 0, "clear")                # 车头挡风玻璃
b.wall_ew("tr_e", 3.0, -2, 0, "red")                  # 车尾
for x in (1, 2):
    b.flat(f"tr_rf_{x}", x, -2, 1.0, "yellow")        # 车顶
b.crest_ns("tr_light", 1, -2.0, 1.0, "blue")          # 车顶警灯

# =================================================================
# 7. 站牌垛口: 屋顶前沿 3 片红色等边三角
# =================================================================
for x in (0, 2, 4):
    b.crest_ns(f"sign_{x}", x, 0.0, 2.0, "red")

# =================================================================
# 教程步骤 (19 步)
# =================================================================
b.step(
    "铺设车库地坪西半段: 沿前后两排平放 6 片灰色方板 (x 0..3)。",
    [f"fl_{x}_{y}" for x in range(3) for y in range(2)],
    tip="地坪是 5x2 的长方形 —— 要停两辆消防车, 车库得够深。",
)
b.step(
    "铺设车库地坪东半段: 再补 4 片方板, 地坪完工。",
    [f"fl_{x}_{y}" for x in (3, 4) for y in range(2)],
    highlight=["fl_2_0"],
    tip="10 片地坪缝缝相吸, 铺完应是严丝合缝的一整块。",
)
b.step(
    "竖立后墙下层: 5 片红色正方形沿地坪北沿一字排开, 底边吸地坪边。",
    [f"bk1_{x}" for x in range(5)],
    highlight=["fl_0_1", "fl_4_1"],
    tip="后墙是整座车库的脊梁, 5 片墙的竖边也要两两吸牢。",
)
b.step(
    "竖立两侧山墙下层: 东西两端各 2 片红色正方形, 与后墙拐角吸合。",
    ["ww1_0", "ww1_1", "ew1_0", "ew1_1"],
    highlight=["bk1_0", "bk1_4"],
    tip="山墙与后墙在拐角处竖边互吸, 房子立刻有了三面围合。",
)
b.step(
    "竖立中央立柱下层: 1 片黄色正方形立在地坪前沿正中 (x 2..3), "
    "把门脸分成两个车库大门。",
    ["pil1"],
    highlight=["fl_2_0"],
    tip="立柱两侧各留 2 格宽的大门 —— 消防车出警可不能堵门。",
)
b.step(
    "叠加后墙上层: 5 片红色正方形叠上后墙, 横边完全对齐。",
    [f"bk2_{x}" for x in range(5)],
    highlight=["bk1_2"],
    tip="上下错缝会让墙变弱 —— 磁力片楼房要对缝叠。",
)
b.step(
    "叠加山墙与立柱上层: 山墙各叠 2 片、立柱叠 1 片, 全楼到 2 层高。",
    ["ww2_0", "ww2_1", "ew2_0", "ew2_1", "pil2"],
    highlight=["pil1"],
    tip="立柱上层将来要同时吸住两条门楣, 位置务必摆正。",
)
b.step(
    "安装门楣: 2 片黄色长方形横跨两个大门上方, 两端竖边分别吸山墙"
    "竖边与立柱竖边。",
    ["lin_w", "lin_e"],
    highlight=["pil2", "ww2_0", "ew2_0"],
    tip="门楣是三边受力的过梁: 两端竖边吸牢, 顶上还要接屋顶。",
)
b.step(
    "铺设屋顶西半段: 6 片灰色方板压在墙顶与门楣上 (x 0..3)。",
    [f"rf_{x}_{y}" for x in range(3) for y in range(2)],
    highlight=["lin_w"],
    tip="每片屋顶板边都要吸住下方墙顶边, 压完轻按四角检查。",
)
b.step(
    "铺设屋顶东半段: 再补 4 片方板, 车库封顶。",
    [f"rf_{x}_{y}" for x in (3, 4) for y in range(2)],
    highlight=["rf_2_0"],
    tip="从大门望进去: 车库内部宽敞明亮, 随时可以出警。",
)
b.step(
    "瞭望塔起步: 东山墙外侧放塔底板, 塔南北壁各叠 2 层, "
    "西侧直接借用车库东山墙。",
    ["tw_base", "tw_s_0", "tw_s_1", "tw_n_0", "tw_n_1"],
    highlight=["ew1_0"],
    tip="共墙不重复 —— 塔的西面就是车库的东山墙, 一墙两用。",
)
b.step(
    "安装塔东壁下两层: 2 片透明正方形做观察窗。",
    ["tw_e_0", "tw_e_1"],
    highlight=["tw_s_0"],
    tip="透明窗让小消防员随时看到塔里的旋转楼梯 (想象一下)。",
)
b.step(
    "塔身加高到 4 层: 南北壁与东壁各叠 2 层, 西壁补上 2 层 "
    "(从车库屋顶高度往上)。",
    ["tw_s_2", "tw_s_3", "tw_n_2", "tw_n_3", "tw_e_2", "tw_e_3",
     "tw_w_2", "tw_w_3"],
    highlight=["tw_s_1"],
    tip="瞭望塔比车库高一倍 —— 站得高才看得见全城的烟。",
)
b.step(
    "塔顶封板: 1 片灰色方板盖住塔口, 四边同时吸住四面塔壁顶边。",
    ["tw_top"],
    highlight=["tw_s_3", "tw_e_3"],
    tip="盖上顶板, 塔身变成闭合的箱形筒 —— 抗风又抗晃。",
)
b.step(
    "安装四坡尖顶: 4 片橙色等腰三角形底边吸塔顶板四边, "
    "斜棱两两互吸、锥尖自锁。",
    HAT,
    highlight=["tw_top"],
    tip="最后一片卡进去的瞬间, 整个尖顶会咔哒一声锁成一体。",
)
b.step(
    "铺设停车坪: 大门前平铺 5 片灰色方板, 与地坪边缘吸合。",
    [f"ap_{x}" for x in range(5)],
    highlight=["fl_0_0", "pil1"],
    tip="停车坪连着车库大门 —— 消防车出警的第一段路。",
)
b.step(
    "拼装消防车车身: 停车坪前停好底盘 2 片, 围上车厢四壁 "
    "(车头是透明挡风玻璃)。",
    ["tr_fl_1", "tr_fl_2", "tr_s_1", "tr_s_2", "tr_n_1", "tr_n_2",
     "tr_w", "tr_e"],
    highlight=["ap_1", "ap_2"],
    tip="车厢北壁底边同时吸住底盘边与停车坪边 —— 车就停稳了。",
)
b.step(
    "封车顶装警灯: 2 片黄色车顶板盖住车厢, 车顶前端立 1 片蓝色"
    "三角警灯。",
    ["tr_rf_1", "tr_rf_2", "tr_light"],
    highlight=["tr_s_1"],
    tip="蓝色警灯朝前 —— 出警时它是全城最亮的星。",
)
b.step(
    "挂站牌垛口: 屋顶前沿立 3 片红色等边三角, 一号消防站落成!",
    ["sign_0", "sign_2", "sign_4"],
    highlight=["rf_0_0", "rf_4_0"],
    tip="三片红三角就是站徽: 时刻准备, 闻警即动。",
)

b.finalize(
    model_id="fire_station_01",
    name="一号消防站",
    name_en="Fire Station 01",
    description=(
        "城市守护者基地: 5 格宽双车库开着两个 2 格宽的出警大门, 黄色门楣三边"
        "受力横跨门洞; 东侧 4 层瞭望塔与车库共用山墙, 顶戴橙色四坡自锁尖顶; "
        "门前停车坪上一辆红色消防车整装待发, 车顶蓝色警灯朝前 —— 全场连成"
        "一个整体, 随时准备出警。"
    ),
    difficulty=4,
    tags=["城市", "职业体验", "建筑", "进阶"],
    min_pieces=75,
    min_steps=18,
)
