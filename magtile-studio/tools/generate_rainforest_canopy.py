#!/usr/bin/env python3
"""生成模型 data/models/rainforest_canopy_01.json (雨林树冠天桥)。

自然世界主题: 全库第一座雨林树冠天桥 —— 青色小河穿过绿色
林地, 两株三层箱式巨树隔空相望: 树腰 (z=2) 各探出三片树冠
平台 (每片配一根板根斜撑成环), 一条四板天桥横跨两树之间
(两端整边吸树身, 剪断任一端仍经另一株回到地面), 桥面黄色
护栏对角守望; 树身继续拔高一层, 双双戴上瘦高四坡绿冠 (树尖
4.94); 林地四朵花冠立拼缝、两株蕨苗外倾伸展 —— 走上天桥,
雨林在脚下沙沙作响!

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 小河: 青色长板 x4 (y [0,1])                               4 片
  - 林地: 绿色方板 x24 + 长板 x4 (y [1,5])                   28 片
  - 巨树 x2 (x [1,2] / [6,7], y [2,3]): 三层箱式树身 x12
    + 瘦高四坡树冠 x4                                     2x16 片
  - 树冠平台: 每树 3 片绿板平挑树腰 (z=2)
    + 3 片直角三角形板根斜撑                              2x6 片
  - 天桥: 桥板 x4 (z=2, 两端吸树身) + 护栏等边 x4             8 片
  - 花冠等边 x4 + 蕨苗外倾等边 x2                             6 片
  合计 90 片, 18 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, strict 档与 R9 抖动仿真
--profile strict --jitter 50 同样全绿):
  - 树身三层箱式闭环 (四角竖边互吸), 天桥两端整边吸两株
    树身 —— 树-桥-树连成大环, 剪断任一端桥仍不塌;
  - 树冠平台单片平挑树腰铰链, 每片配一根直角三角形板根
    斜撑 (竖直角边吸树身竖直磁力边, 水平直角边吸平台侧边):
    平台-斜撑-树身成环, 剪断树腰铰链后平台仍有支撑路径,
    悬臂力矩分析自然消失 —— 名义力矩 15 贴 strict 预算 17.5
    的零裕量外挑经此加固, ±1.5mm/±2° 抖动 50/50 轮全绿
    (docs/PHYSICS_RULES.md R9 节 strict 巡检记录的处置);
  - 第三层树身与平台/桥板共享树腰铰链线但互不重叠,
    四坡树冠四棱互吸自锁; 花冠/护栏重心正压铰链 (力矩 0);
  - 蕨苗底边吸林地拼缝外倾 30 度 (力矩 1.9)。

用法: python3 tools/generate_rainforest_canopy.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

RIVER = "cyan"      # 小河
FLOOR = "green"     # 林地
TRUNK = "orange"    # 树身
LEAF = "green"      # 树冠平台 / 树冠
PLANK = "orange"    # 天桥桥板
RAIL = "yellow"     # 天桥护栏
FLOWER = "pink"     # 花冠
FERN = "green"      # 蕨苗

TOWERS = (1, 6)     # 两株巨树的西南角 x 坐标 (y 均为 2)

# =================================================================
# 1. 小河与林地 (x [0,8], y [0,5])
# =================================================================
for k in range(4):
    b.flat_rect(f"rv_{k}", 2 * k, 0, 0.0, RIVER)
    b.flat_rect(f"fl_n_{k}", 2 * k, 4, 0.0, FLOOR)
for x in range(8):
    b.flat(f"fl_1_{x}", x, 1, 0.0, FLOOR)
    b.flat(f"fl_2_{x}", x, 2, 0.0, FLOOR)
    b.flat(f"fl_3_{x}", x, 3, 0.0, FLOOR)

# =================================================================
# 2. 巨树 x2: 三层箱式树身 (z 0~3) + 瘦高四坡树冠
# =================================================================
for t in TOWERS:
    for z in (0, 1, 2):
        b.wall_ns(f"tk{t}_s_{z}", t, 2.0, z, TRUNK)
        b.wall_ns(f"tk{t}_n_{z}", t, 3.0, z, TRUNK)
        b.wall_ew(f"tk{t}_w_{z}", float(t), 2, z, TRUNK)
        b.wall_ew(f"tk{t}_e_{z}", float(t + 1), 2, z, TRUNK)
CROWN_W = b.hat4("crown_w", TOWERS[0], 2, 3.0, LEAF)
CROWN_E = b.hat4("crown_e", TOWERS[1], 2, 3.0, LEAF)

# =================================================================
# 3. 树冠平台 (z=2): 西树 北/西/南 三片, 东树 北/东/南 三片;
#    每片平台配一根直角三角形板根斜撑 —— 竖直角边吸树身竖直
#    磁力边 (z [1,2]), 水平直角边吸平台侧边: 平台-斜撑-树身
#    成环, 树腰铰链剪断后平台仍有支撑路径, 单边平挑的悬臂
#    力矩分析自然消失 (R9 抖动零裕量加固, PHYSICS_RULES.md R9)
# =================================================================
b.flat("lf_w_n", 1, 3, 2.0, LEAF)
b.flat("lf_w_w", 0, 2, 2.0, LEAF)
b.flat("lf_w_s", 1, 1, 2.0, LEAF)
b.flat("lf_e_n", 6, 3, 2.0, LEAF)
b.flat("lf_e_e", 7, 2, 2.0, LEAF)
b.flat("lf_e_s", 6, 1, 2.0, LEAF)
b.place_tri("bc_w_n", "right_triangle",
            (1.0, 3.0, 2.0), (1.0, 4.0, 2.0), (1.0, 3.0, 1.0), TRUNK)
b.place_tri("bc_w_w", "right_triangle",
            (1.0, 2.0, 2.0), (0.0, 2.0, 2.0), (1.0, 2.0, 1.0), TRUNK)
b.place_tri("bc_w_s", "right_triangle",
            (1.0, 2.0, 2.0), (1.0, 1.0, 2.0), (1.0, 2.0, 1.0), TRUNK)
b.place_tri("bc_e_n", "right_triangle",
            (7.0, 3.0, 2.0), (7.0, 4.0, 2.0), (7.0, 3.0, 1.0), TRUNK)
b.place_tri("bc_e_e", "right_triangle",
            (7.0, 2.0, 2.0), (8.0, 2.0, 2.0), (7.0, 2.0, 1.0), TRUNK)
b.place_tri("bc_e_s", "right_triangle",
            (7.0, 2.0, 2.0), (7.0, 1.0, 2.0), (7.0, 2.0, 1.0), TRUNK)

# =================================================================
# 4. 天桥 (z=2, x [2,6]): 四板桥面 + 四片护栏
# =================================================================
for x in (2, 3, 4, 5):
    b.flat(f"br_{x}", x, 2, 2.0, PLANK)
b.crest_ns("rl_s_2", 2, 2.0, 2.0, RAIL)
b.crest_ns("rl_s_4", 4, 2.0, 2.0, RAIL)
b.crest_ns("rl_n_3", 3, 3.0, 2.0, RAIL)
b.crest_ns("rl_n_5", 5, 3.0, 2.0, RAIL)

# =================================================================
# 5. 花冠 + 蕨苗
# =================================================================
b.crest_ns("fw_a", 0, 1.0, 0.0, FLOWER)
b.crest_ns("fw_b", 4, 1.0, 0.0, FLOWER)
b.crest_ns("fw_c", 7, 1.0, 0.0, FLOWER)
b.crest_ns("fw_d", 0, 4.0, 0.0, "red")
b.place_tri("fern_a", "equilateral_triangle",
            (3.0, 4.0, 0.0), (4.0, 4.0, 0.0), (3.5, 4.433013, 0.75), FERN)
b.place_tri("fern_b", "equilateral_triangle",
            (4.0, 4.0, 0.0), (5.0, 4.0, 0.0), (4.5, 4.433013, 0.75), FERN)

# =================================================================
# 教程步骤 (18 步)
# =================================================================
b.step(
    "铺小河: 4 片青色长板连成河道。",
    [f"rv_{k}" for k in range(4)],
    tip="雨林里的小河 —— 花冠等会儿就开在河岸拼缝上。",
)
b.step(
    "铺林地第一行: 8 片绿色方板 (y [1,2])。",
    [f"fl_1_{x}" for x in range(8)],
    highlight=["rv_0"],
    tip="方板与河道整边贴合, 拼缝对齐网格。",
)
b.step(
    "铺林地第二行: 8 片 (y [2,3]), 两株巨树都扎根这行拼缝。",
    [f"fl_2_{x}" for x in range(8)],
    highlight=["fl_1_0"],
    tip="西树踩 x=1~2, 东树踩 x=6~7 —— 隔空相望。",
)
b.step(
    "铺林地第三行: 8 片 (y [3,4])。",
    [f"fl_3_{x}" for x in range(8)],
    highlight=["fl_2_0"],
    tip="三行方板铺平 —— 巨树的根基稳稳当当。",
)
b.step(
    "铺北林缘: 4 片绿色长板, 林地合拢。",
    [f"fl_n_{k}" for k in range(4)],
    highlight=["fl_3_0"],
    tip="蕨苗一会儿就从北缘前的拼缝里探出来。",
)
b.step(
    "立西树第一层: 4 片橙色树身踩林地拼缝, 四角互吸。",
    ["tk1_s_0", "tk1_n_0", "tk1_w_0", "tk1_e_0"],
    highlight=["fl_2_1", "fl_3_1"],
    tip="箱式树身是闭合环 —— 雨林巨树从不歪斜。",
)
b.step(
    "叠西树第二层: 底边整边吸下层顶边。",
    ["tk1_s_1", "tk1_n_1", "tk1_w_1", "tk1_e_1"],
    highlight=["tk1_s_0"],
    tip="层层箱环相扣 —— 树腰 (z=2) 就是平台与天桥的高度。",
)
b.step(
    "立东树第一层: 同样 4 片踩拼缝。",
    ["tk6_s_0", "tk6_n_0", "tk6_w_0", "tk6_e_0"],
    highlight=["fl_2_6", "fl_3_6"],
    tip="两株树相距 4 格 —— 天桥正好四块桥板。",
)
b.step(
    "叠东树第二层。",
    ["tk6_s_1", "tk6_n_1", "tk6_w_1", "tk6_e_1"],
    highlight=["tk6_s_0"],
    tip="东西两树同高, 树腰铰链线在同一平面。",
)
b.step(
    "探西树树冠平台: 北/西/南三片绿板平挑树腰, 各配一根板根斜撑。",
    ["lf_w_n", "lf_w_w", "lf_w_s", "bc_w_n", "bc_w_w", "bc_w_s"],
    highlight=["tk1_n_1", "tk1_w_1"],
    tip="斜撑两条直角边分别吸树身竖边与平台侧边 —— 平台-斜撑-树身成环, 平挑稳如板根。",
)
b.step(
    "探东树树冠平台: 北/东/南三片, 同样各配一根板根斜撑。",
    ["lf_e_n", "lf_e_e", "lf_e_s", "bc_e_n", "bc_e_e", "bc_e_s"],
    highlight=["tk6_n_1", "tk6_e_1"],
    tip="东面平台朝林外 —— 观鸟的最佳机位, 板根斜撑托得稳稳的。",
)
b.step(
    "架天桥: 4 片橙色桥板从西树接到东树。",
    ["br_2", "br_3", "br_4", "br_5"],
    highlight=["tk1_e_1", "tk6_w_1"],
    tip="先放西端: 桥板西边整边吸西树身 —— 逐板向东。",
)
b.step(
    "装天桥护栏: 4 片黄色等边对角守望。",
    ["rl_s_2", "rl_n_3", "rl_s_4", "rl_n_5"],
    highlight=["br_2", "br_5"],
    tip="护栏重心正压桥板沿口 —— 力矩为零。",
)
b.step(
    "西树再拔高一层 (z 2~3)。",
    ["tk1_s_2", "tk1_n_2", "tk1_w_2", "tk1_e_2"],
    highlight=["lf_w_n", "br_2"],
    tip="第三层与平台共享树腰铰链线, 但互不重叠。",
)
b.step(
    "东树再拔高一层。",
    ["tk6_s_2", "tk6_n_2", "tk6_w_2", "tk6_e_2"],
    highlight=["lf_e_n", "br_5"],
    tip="两株树再次同高 —— 就差树冠了。",
)
b.step(
    "戴西树四坡绿冠: 树尖 4.94 直插云霄。",
    CROWN_W,
    highlight=["tk1_s_2"],
    tip="四条斜棱两两互吸自锁成环。",
)
b.step(
    "戴东树四坡绿冠。",
    CROWN_E,
    highlight=["tk6_s_2"],
    tip="双冠对峙 —— 雨林的天际线完成。",
)
b.step(
    "开花冠、展蕨苗 —— 雨林在脚下沙沙作响!",
    ["fw_a", "fw_b", "fw_c", "fw_d", "fern_a", "fern_b"],
    highlight=["fl_1_0", "fl_3_4"],
    tip="花冠正压河岸拼缝, 蕨苗外倾 30 度 (力矩 1.9)。",
)

b.finalize(
    model_id="rainforest_canopy_01",
    name="雨林树冠天桥",
    name_en="Rainforest Canopy Walk 01",
    description=(
        "全库第一座雨林树冠天桥: 两株三层箱式巨树隔空相望, 树腰"
        " (z=2) 各探三片树冠平台, 每片配一根直角三角形板根斜撑"
        " —— 平台-斜撑-树身成环, 平挑经得起毫米级放置误差 (R9 抖"
        "动仿真全绿); 四板天桥两端整边吸树身 —— 树-桥-树连成大环,"
        " 剪断任一端桥仍不塌; 树身拔高至第三层双双戴瘦高四坡绿冠"
        " (树尖 4.94), 桥面黄色护栏对角守望; 青色小河畔四朵花冠立"
        "拼缝, 两株蕨苗外倾伸展 —— 走上天桥, 雨林在脚下沙沙作响!"
    ),
    difficulty=4,
    tags=["自然", "雨林", "树屋", "天桥", "进阶"],
    min_pieces=88,
    min_steps=18,
)
