#!/usr/bin/env python3
"""生成模型 data/models/plank_bridge_01.json (三墩小板桥)。

D1 补员批 4 模型 2/4 (难度配额解冻线 D1 >= 20, 路径 B1): 入门档
桥梁工程选题 —— 跨过小溪的三墩双跨小板桥。结构签名是"墩-梁-板
三件套": 三座 1x1 空心桥墩托起桥面, 每跨两根长方形边梁立在墩间
当侧梁, 桥面长板短边吸墩帽、长边整边压住边梁顶 —— 一块板同时被
四条边抓住, 这就是桥梁工程里"多传力路径"的入门课; 与凉亭 (围院
中心亭)、折墙 (开放折线) 和小黄鸭 (叠层动物) 的结构逻辑完全不同。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 桥沿 x 向东西走):
  - 三座桥墩 (格 [0,1]/[3,4]/[6,7] x [0,1]): 各 4 墙 + 1 墩帽  15 片
  - 边梁 4 根 (长方形立板, 跨 [1,3]/[4,6], 南北各一)           4 片
  - 桥面 2 块 (长方形平板, z=1, 短边吸墩帽, 长边压边梁顶)      2 片
  - 护栏小旗 6 面 (等边三角, 与墩帽/墙顶整边重合)              6 片
  合计 27 片, 5 个教程步骤, 3 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 桥墩四墙竖棱角缝互吸成环, 全部接地; 墩帽四边整边锁住墙顶;
  - 边梁接地立在墩间, 两条竖边分别吸住两侧墩墙竖棱 (R2 环环相扣);
  - 桥面短边吸墩帽边、长边完整压住边梁顶边 —— 每块板四边受抓,
    两端简支 + 两侧连续支撑, 零悬挑零吊挂;
  - 最高点 1.58 (护栏小旗) < 2.5, 不触发 R8 高层结构判定。

用法: python3 tools/generate_plank_bridge_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

PIER = "gray"       # 桥墩墙
CAP = "yellow"      # 墩帽
BEAM = "red"        # 边梁
DECK = "orange"     # 桥面
RAIL = "cyan"       # 护栏小旗

# =================================================================
# 1. 三座桥墩 (x [0,1] / [3,4] / [6,7], y [0,1]): 各四墙一圈
# =================================================================
PIERS = {"w": 0, "m": 3, "e": 6}
for tag, x0 in PIERS.items():
    b.wall_ns(f"pier_{tag}_s", x0, 0.0, 0, PIER)
    b.wall_ns(f"pier_{tag}_n", x0, 1.0, 0, PIER)
    b.wall_ew(f"pier_{tag}_w", float(x0), 0, 0, PIER)
    b.wall_ew(f"pier_{tag}_e", float(x0 + 1), 0, 0, PIER)

# =================================================================
# 2. 三顶墩帽 (z=1 平铺方板, 四边整边锁住墙顶)
# =================================================================
for tag, x0 in PIERS.items():
    b.flat(f"cap_{tag}", x0, 0, 1.0, CAP)

# =================================================================
# 3. 边梁 (长方形立板, 立在墩间, 竖边吸两侧墩墙竖棱)
# =================================================================
b.lintel_ns("beam_w_s", 1, 0.0, 0, BEAM)
b.lintel_ns("beam_w_n", 1, 1.0, 0, BEAM)
b.lintel_ns("beam_e_s", 4, 0.0, 0, BEAM)
b.lintel_ns("beam_e_n", 4, 1.0, 0, BEAM)

# =================================================================
# 4. 桥面 (z=1 长方形平板, 短边吸墩帽, 长边压边梁顶)
# =================================================================
b.flat_rect("deck_w", 1, 0, 1.0, DECK)
b.flat_rect("deck_e", 4, 0, 1.0, DECK)

# =================================================================
# 5. 护栏小旗 (等边三角, 与墩墙顶整边重合)
# =================================================================
for tag, x0 in PIERS.items():
    b.crest_ns(f"rail_{tag}_s", x0, 0.0, 1.0, RAIL)
    b.crest_ns(f"rail_{tag}_n", x0, 1.0, 1.0, RAIL)

# =================================================================
# 教程步骤 (5 步): 从西岸往东岸修, 每一步完成后全桥连成一体
# =================================================================
b.step(
    "立西墩: 四片灰色方墙竖棱角缝互吸围成空心墩, 黄色墩帽四边整边锁住墙顶。",
    ["pier_w_s", "pier_w_n", "pier_w_w", "pier_w_e", "cap_w"],
    tip="四片墙的竖棱像小手拉手 —— 拉成一圈桥墩就推不倒了。",
)
b.step(
    "架西跨边梁并立中墩: 两根红色边梁竖边先吸住西墩墙棱, 中墩四墙一圈再把边梁另一头咬住, 盖上墩帽。",
    ["beam_w_s", "beam_w_n",
     "pier_m_s", "pier_m_n", "pier_m_w", "pier_m_e", "cap_m"],
    highlight=["pier_w_s", "cap_w"],
    tip="边梁是桥面的第二条传力路径 —— 真正的桥都不止一条腿。",
)
b.step(
    "架东跨边梁并立东墩: 照西跨的样子再修一跨, 边梁两头都被墩墙竖棱咬住。",
    ["beam_e_s", "beam_e_n",
     "pier_e_s", "pier_e_n", "pier_e_w", "pier_e_e", "cap_e"],
    highlight=["pier_m_s", "cap_m"],
)
b.step(
    "铺桥面: 两块橙色长板短边吸墩帽、长边完整压住边梁顶, 一块板四边同时被抓住。",
    ["deck_w", "deck_e"],
    highlight=["beam_w_s", "beam_e_s"],
    tip="按一按桥面 —— 四边受力的板才配叫桥。",
)
b.step(
    "插护栏小旗: 六面青色小旗骑上三座墩顶, 小板桥通车!",
    ["rail_w_s", "rail_w_n", "rail_m_s", "rail_m_n", "rail_e_s", "rail_e_n"],
    highlight=["deck_w", "deck_e"],
)

b.finalize(
    model_id="plank_bridge_01",
    name="三墩小板桥",
    name_en="Plank Bridge 01",
    description=(
        "入门档桥梁工程: 跨过小溪的三墩双跨小板桥, 结构签名是'墩-梁-板"
        "三件套' —— 三座空心桥墩四墙竖棱角缝互吸成环, 黄色墩帽四边整边"
        "锁住墙顶; 每跨两根红色边梁接地立在墩间、竖边吸住两侧墩墙竖棱, "
        "橙色桥面短边吸墩帽、长边完整压住边梁顶 —— 一块板同时被四条边"
        "抓住, 两端简支加两侧连续支撑, 这就是桥梁'多传力路径'的入门课。"
        "27 片全程接地受压零悬挑, 搭完就能开小车过桥。"
    ),
    difficulty=1,
    tags=["桥梁工程", "板桥", "桥墩", "亲子入门"],
    min_pieces=27,
    min_steps=5,
    series="bridge_engineering",
)
print("已写入 series=bridge_engineering")
