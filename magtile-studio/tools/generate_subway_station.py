#!/usr/bin/env python3
"""生成模型 data/models/subway_station_01.json (地铁一号线车站)。

城市交通主题: 与中央火车站 (人字坡大厅) 刻意区分 —— 本模型是
"剖面式站台": 轨道层在地面, 一列蓝色地铁列车正靠站; 站台板
悬架在站台立墙上, 背后一面三层海报墙撑起单坡雨棚, 雨棚前沿
由三根柱廊接力; 站台上有灯箱、进站闸机与站名小塔, 东端一条
30 度出站扶梯斜下街面。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 轨道层 (y 0..1): 道床 5 片 + 东端缓冲挡                        6 片
  - 地铁列车 (x 0..3): 底架 3 + 南侧窗墙 3 + 车头车尾 2 +
    车顶 3 + 车头灯                                               12 片
  - 站台立墙 (y=1, z 0..1): 6 片                                   6 片
  - 站台板 (y 1..3, z=1): 前后两排共 12 片                         12 片
  - 海报墙 (y=3, z 0..3): 三层共 18 片 (中层夹彩色海报带)          18 片
  - 柱廊 + 站台家具: 3 根双层柱 + 2 座灯箱尖 + 2 片闸机            10 片
  - 单坡雨棚 (z=3, y 1..3): 12 片                                  12 片
  - 站名小塔 (雨棚上 1x1): 四壁 + 顶板 + 塔旗                       6 片
  - 出站扶梯 + 站名菱形灯箱 x2 + 雨棚顶旗 x2                        5 片
  合计 87 片, 18 个教程步骤。

物理规则要点 (通过 R1~R8 全部校验):
  - 站台板先铺前排 (悬挑吸站台立墙顶, 6 片合计力矩 90 < 预算 120),
    海报墙下层与后排板同步安装 —— 后排板一手吸前排板边、一手压
    墙顶边, 墙板互锁不留孤立件;
  - 雨棚后沿压海报墙顶、前沿落三根柱廊顶 —— 剪断任何一条铰链线,
    另一侧支撑路径仍然接地;
  - 列车车顶北边与站台板南边整边互吸 —— 列车正靠站, 全场连通。

用法: python3 tools/generate_subway_station.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

TRAIN = "blue"
PLAT = "yellow"
WALLC = "gray"
CANOPY = "blue"
COL = "green"

# =================================================================
# 1. 轨道层 (y 0..1): 道床 + 东端缓冲挡
# =================================================================
for x0 in range(3, 8):
    b.flat(f"tk_{x0}", x0, 0, 0.0, WALLC)
b.crest_ew("buffer", 8.0, 0, 0.0, "red")          # 缓冲挡立在道床东端

# =================================================================
# 2. 地铁列车 (x 0..3, y 0..1): 底架 + 南窗墙 + 车头车尾 + 车顶
# =================================================================
for x0 in range(3):
    b.flat(f"tr_fl_{x0}", x0, 0, 0.0, TRAIN)
b.wall_ns("tr_s_0", 0, 0.0, 0, TRAIN)
b.wall_ns("tr_s_1", 1, 0.0, 0, "clear")           # 中段大车窗
b.wall_ns("tr_s_2", 2, 0.0, 0, TRAIN)
b.wall_ew("tr_head", 0.0, 0, 0, "clear")          # 车头挡风玻璃
b.wall_ew("tr_tail", 3.0, 0, 0, TRAIN)
for x0 in range(3):
    b.flat(f"tr_rf_{x0}", x0, 0, 1.0, TRAIN)
b.crest_ew("tr_light", 0.0, 0, 1.0, PLAT)         # 车头灯

# =================================================================
# 3. 站台立墙 (y=1, z 0..1) + 站台板 (y 1..3, z=1)
# =================================================================
for x0 in range(6):
    b.wall_ns(f"pf_{x0}", x0, 1.0, 0, WALLC)
for x0 in range(6):
    b.flat(f"sl_f_{x0}", x0, 1, 1.0, PLAT)        # 前排板 (y 1..2)
for x0 in range(6):
    b.flat(f"sl_b_{x0}", x0, 2, 1.0, PLAT)        # 后排板 (y 2..3)

# =================================================================
# 4. 海报墙 (y=3, z 0..3): 三层, 中层夹彩色海报带
# =================================================================
POSTER = ["orange", "green", "clear", "pink", "clear", "orange"]
for x0 in range(6):
    b.wall_ns(f"bw0_{x0}", x0, 3.0, 0, WALLC)
    b.wall_ns(f"bw1_{x0}", x0, 3.0, 1, POSTER[x0])
    b.wall_ns(f"bw2_{x0}", x0, 3.0, 2, WALLC)

# =================================================================
# 5. 柱廊 (y=1, z 1..3) + 站台家具 (灯箱尖 + 进站闸机)
# =================================================================
for x0 in (0, 2, 4):
    b.wall_ns(f"col_{x0}_lo", x0, 1.0, 1, COL)
    b.wall_ns(f"col_{x0}_hi", x0, 1.0, 2, COL)
b.spire_ns("lamp_1", 1, 2.0, 1.0, "purple")       # 站台灯箱 (立在板中缝)
b.spire_ns("lamp_2", 4, 2.0, 1.0, "purple")
b.crest_ew("gate_1", 0.0, 1, 1.0, "clear")        # 进站闸机 (站台西端)
b.crest_ew("gate_2", 0.0, 2, 1.0, "clear")

# =================================================================
# 6. 单坡雨棚 (z=3, y 1..3): 后排压海报墙顶, 前排落柱廊顶
# =================================================================
for x0 in range(6):
    b.flat(f"cn_b_{x0}", x0, 2, 3.0, CANOPY)      # 后排 (y 2..3)
for x0 in (0, 2, 4, 1, 3, 5):
    b.flat(f"cn_f_{x0}", x0, 1, 3.0, CANOPY)      # 前排 (y 1..2), 先柱顶后悬跨

# =================================================================
# 7. 站名小塔 (雨棚上 x 2..3, y 1..2) + 屋面点缀
# =================================================================
b.wall_ns("st_s", 2, 1.0, 3, COL)
b.wall_ns("st_n", 2, 2.0, 3, COL)
b.wall_ew("st_w", 2.0, 1, 3, "clear")
b.wall_ew("st_e", 3.0, 1, 3, "clear")
b.flat("st_top", 2, 1, 4.0, WALLC)
b.crest_ns("st_flag", 2, 1.0, 4.0, "red")         # 塔旗 (立在塔顶南沿)

b.place_edge("sign_w", "rhombus", 0, (0.0, 1.0, 3.0), (1.0, 1.0, 3.0),
             (0, 0, 1), "red")                    # 站名菱形灯箱西
b.place_edge("sign_e", "rhombus", 0, (4.0, 1.0, 3.0), (5.0, 1.0, 3.0),
             (0, 0, 1), "red")                    # 站名菱形灯箱东
b.crest_ns("rf_flag_w", 0, 3.0, 3.0, "orange")    # 雨棚顶旗 (北沿)
b.crest_ns("rf_flag_e", 5, 3.0, 3.0, "orange")

# =================================================================
# 8. 出站扶梯: 顶边吸站台板东沿, 梯尾落街面
# =================================================================
b.ramp("escalator", "+x", 6.0, 1, 1.0, WALLC)

# =================================================================
# 教程步骤 (17 步)
# =================================================================
b.step(
    "轨道层: 铺 5 片道床 (x 3..8), 东端立 1 片红色缓冲挡。",
    ["tk_3", "tk_4", "tk_5", "tk_6", "tk_7", "buffer"],
    tip="道床西侧留出的 3 格空位, 正是即将进站的列车车位。",
)
b.step(
    "列车底架: 3 片蓝色底架接上道床西端, 东边与道床整边相吸。",
    ["tr_fl_2", "tr_fl_1", "tr_fl_0"],
    highlight=["tk_3"],
    tip="从道床一侧往西铺 —— 每片放下就有邻边可吸。",
)
b.step(
    "列车南窗墙: 南侧立 3 片车厢墙, 中段是透明大车窗。",
    ["tr_s_0", "tr_s_1", "tr_s_2"],
    highlight=["tr_fl_0", "tr_fl_2"],
    tip="车墙底边吸底架边 —— 透明中段留给乘客看站台。",
)
b.step(
    "车头车尾与车顶: 透明挡风玻璃 + 车尾板围合, 3 片车顶盖住"
    "车厢, 车头再立 1 盏黄色头灯。",
    ["tr_head", "tr_tail", "tr_rf_0", "tr_rf_1", "tr_rf_2", "tr_light"],
    highlight=["tr_s_0", "tr_s_2"],
    tip="车顶与车墙顶边整边互吸 —— 一列真正闭合的车厢。",
)
b.step(
    "站台立墙: 6 片灰色立墙沿 y=1 一字排开, 底边吸道床与列车"
    "底架的北沿边。",
    [f"pf_{x0}" for x0 in range(6)],
    highlight=["tr_fl_0", "tk_4"],
    tip="这面墙是站台的承重前缘 —— 立直吸牢, 上面要挑站台板。",
)
b.step(
    "站台板前排: 6 片黄色站台板压上立墙顶, 向北悬挑半格重心 —— "
    "6 片连排的悬挑力矩仍在预算内。",
    [f"sl_f_{x0}" for x0 in range(6)],
    highlight=["pf_0", "pf_5"],
    tip="板南边吸墙顶边, 与列车车顶北边也会咔哒一声相认。",
)
b.step(
    "海报墙下层与站台板后排: 先沿 y=3 立 6 片灰墙, 随即用后排"
    "6 片站台板把它们与前排板锁成整层。",
    [f"bw0_{x0}" for x0 in range(6)] + [f"sl_b_{x0}" for x0 in range(6)],
    highlight=["sl_f_0", "sl_f_5"],
    tip="后排板一手吸前排板边、一手压墙顶边 —— 墙板互锁。",
)
b.step(
    "海报墙中层: 6 片彩色海报带叠上下层 (透明片是灯箱广告位)。",
    [f"bw1_{x0}" for x0 in range(6)],
    highlight=["bw0_0", "bw0_5"],
    tip="上下对缝叠齐 —— 乘客候车时看的就是这排海报。",
)
b.step(
    "海报墙上层: 6 片灰墙封顶, 背墙到 3 格高。",
    [f"bw2_{x0}" for x0 in range(6)],
    highlight=["bw1_2"],
    tip="这层将来要压雨棚后沿, 顶边务必平齐。",
)
b.step(
    "站台柱廊: 3 根绿色双层柱立在站台板前缘 (x 0..1 / 2..3 / "
    "4..5), 柱底吸板边。",
    ["col_0_lo", "col_0_hi", "col_2_lo", "col_2_hi",
     "col_4_lo", "col_4_hi"],
    highlight=["sl_f_0", "sl_f_2", "sl_f_4"],
    tip="柱子踩在立墙正上方 —— 力一路顺着墙传到地面。",
)
b.step(
    "站台家具: 板中缝立 2 座紫色灯箱尖, 西端装 2 片透明进站闸机。",
    ["lamp_1", "lamp_2", "gate_1", "gate_2"],
    highlight=["sl_f_1", "sl_b_1"],
    tip="灯箱骑在前后排板的中缝上, 闸机吸在站台板西沿。",
)
b.step(
    "雨棚后排西段: 3 片蓝色棚板压上海报墙顶 (x 0..3)。",
    ["cn_b_0", "cn_b_1", "cn_b_2"],
    highlight=["bw2_0", "bw2_2"],
    tip="后沿整排压墙, 雨棚的一半重量交给海报墙。",
)
b.step(
    "雨棚后排东段: 再压 3 片, 后排合拢。",
    ["cn_b_3", "cn_b_4", "cn_b_5"],
    highlight=["cn_b_2"],
    tip="每片北边吸墙顶、西边吸邻板 —— 双保险。",
)
b.step(
    "雨棚前排: 先放 3 片柱顶板 (x 0/2/4), 再补 3 片悬跨板 —— "
    "前沿落在柱廊顶上, 雨棚合拢。",
    ["cn_f_0", "cn_f_2", "cn_f_4", "cn_f_1", "cn_f_3", "cn_f_5"],
    highlight=["col_0_hi", "cn_b_0"],
    tip="先有柱顶支点再悬跨 —— 和铺楼板一个道理。",
)
b.step(
    "站名小塔: 雨棚正中立 1x1 小塔 (南北绿墙 + 东西透明), 顶板"
    "盖住塔口。",
    ["st_s", "st_n", "st_w", "st_e", "st_top"],
    highlight=["cn_f_2", "cn_b_2"],
    tip="小塔骑在雨棚前后排的中缝上, 四壁底边都吸棚板边。",
)
b.step(
    "塔旗与雨棚顶旗: 塔顶南沿立红旗, 雨棚北沿再立 2 面橙旗。",
    ["st_flag", "rf_flag_w", "rf_flag_e"],
    highlight=["st_top"],
    tip="竖直立件不产生力矩 —— 屋面装饰随便立。",
)
b.step(
    "站名菱形灯箱: 2 片红色菱形立在雨棚前沿 (x 0..1 与 x 4..5), "
    "底边吸棚板南边 —— 倾斜的平行四边形自带霓虹感。",
    ["sign_w", "sign_e"],
    highlight=["cn_f_0", "cn_f_4"],
    tip="菱形立在竖直平面内却斜着长 —— 这就是它的时髦之处。",
)
b.step(
    "出站扶梯: 30 度扶梯顶边吸站台板东沿, 梯尾稳稳落在街面 —— "
    "地铁一号线车站开门迎客!",
    ["escalator"],
    highlight=["sl_f_5"],
    tip="出闸右转下扶梯 —— 街面见!",
)

b.finalize(
    model_id="subway_station_01",
    name="地铁一号线车站",
    name_en="Subway Station Line 1",
    description=(
        "剖面式地铁车站: 轨道层上一列透明大窗的蓝色列车正靠站, 车顶与"
        "悬挑站台板整边相吸; 站台板前排先悬挑后互锁, 背后三层海报墙与"
        "三根柱廊分挑单坡雨棚; 站台上灯箱、进站闸机一应俱全, 雨棚前沿"
        "两片菱形站名灯箱斜身发光, 东端 30 度出站扶梯直下街面。"
    ),
    difficulty=4,
    tags=["城市交通", "地铁", "剖面", "建筑"],
    min_pieces=80,
    min_steps=16,
)
