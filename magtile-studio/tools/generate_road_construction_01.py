#!/usr/bin/env python3
"""生成模型 data/models/road_construction_01.json (道路施工段)。

建筑/工地主题: 与塔吊 (吊装)/搅拌车 (浇筑)/脚手架 (翻新) 都不同
的市政场景 —— 本作的主角是 "一段正在翻修的路": 南半路基裸露、
北半沥青已铺; 路中开挖沟槽埋下双节涵管 (闭环管节 + 盖板桥面),
西端龙门情报板双柱简支横跨车道, 沥青面上一台双轮压路机来回
碾压; 路基侧围挡雪糕筒把守, 东端沥青料堆四坡自锁。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 路面 8x4 (x [0,8], y [0,4]): 南半路基 (黄) 北半沥青 (灰),
    x [5,6] x y [1,3] 留沟槽                                    21 片
  - 涵管 (x [5,6], y [1,3], z 0..1): 管壁 x7 (双节闭环共用中隔)
    + 盖板桥面 x2                                                9 片
  - 龙门情报板 (x [1,2]): 双柱两层墙环 x16 + 横板 x2 +
    情报板三角 x2 (板顶 2.87)                                   20 片
  - 压路机 (x [2,4], y [2,3]): 双轮底座 x2 + 底盘长板 x1 +
    驾驶室 x4 + 舱顶 x1 + 警灯 x1                                9 片
  - 场景: 围挡墙 x2 + 围挡齿 x2 + 雪糕筒 x3 + 沥青堆四坡 x4 +
    告示牌 x2                                                   13 片
  合计 72 片, 15 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点:
  - 涵管双节共用中隔墙, 每节四壁闭环, 盖板四边同时压四段管壁
    顶 —— 沟槽上重新通车的就是这两块盖板;
  - 龙门横板两块对缝互吸, 两端短边分别整边压南北柱顶 ——
    双端简支, 情报板三角骑在横板西沿;
  - 压路机底盘长板两条长边整边压双轮底座顶, 驾驶室墙环 +
    舱顶锁成箱形;
  - 沥青堆四坡斜棱两两互吸自锁, 底边吸路面格边。

用法: python3 tools/generate_road_construction_01.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

BASE = "yellow"     # 南半路基
ROAD = "gray"       # 北半沥青
PIPE = "cyan"       # 涵管管壁
CAP = "gray"        # 盖板桥面
POST = "blue"       # 龙门柱
BEAM = "blue"       # 龙门横板
BOARD = "green"     # 情报板三角
WHEEL = "gray"      # 压路机轮
BODY = "yellow"     # 压路机车身
GLASS = "clear"     # 驾驶室挡风
FENCE = "red"       # 围挡墙
FTOP = "yellow"     # 围挡齿
CONE = "red"        # 雪糕筒
PILE = "orange"     # 沥青料堆
SIGN = "yellow"     # 告示牌

# =================================================================
# 1. 路面 8x4: 南半路基 (黄) 北半沥青 (灰), x [5,6] x y [1,3] 留沟槽
# =================================================================
b.flat("r0_a", 0, 0, 0.0, BASE)
b.flat("r0_b", 1, 0, 0.0, BASE)
b.flat_rect("r0_c", 2, 0, 0.0, BASE)
b.flat_rect("r0_d", 4, 0, 0.0, BASE)
b.flat_rect("r0_e", 6, 0, 0.0, BASE)
b.flat_rect("r1_a", 0, 1, 0.0, BASE)
b.flat_rect("r1_b", 2, 1, 0.0, BASE)
b.flat("r1_c", 4, 1, 0.0, BASE)
b.flat("r1_d", 6, 1, 0.0, BASE)
b.flat("r1_e", 7, 1, 0.0, BASE)
b.flat_rect("r2_a", 0, 2, 0.0, ROAD)
b.flat_rect("r2_b", 2, 2, 0.0, ROAD)
b.flat("r2_c", 4, 2, 0.0, ROAD)
b.flat("r2_d", 6, 2, 0.0, ROAD)
b.flat("r2_e", 7, 2, 0.0, ROAD)
b.flat("r3_a", 0, 3, 0.0, ROAD)
b.flat("r3_b", 1, 3, 0.0, ROAD)
b.flat_rect("r3_c", 2, 3, 0.0, ROAD)
b.flat_rect("r3_d", 4, 3, 0.0, ROAD)
b.flat("r3_e", 6, 3, 0.0, ROAD)
b.flat("r3_f", 7, 3, 0.0, ROAD)

# =================================================================
# 2. 涵管 (x [5,6], y [1,3], z 0..1): 双节闭环共用中隔 + 盖板
# =================================================================
b.wall_ew("cv_w1", 5.0, 1, 0, PIPE)
b.wall_ew("cv_w2", 5.0, 2, 0, PIPE)
b.wall_ew("cv_e1", 6.0, 1, 0, PIPE)
b.wall_ew("cv_e2", 6.0, 2, 0, PIPE)
b.wall_ns("cv_s", 5, 1.0, 0, PIPE)
b.wall_ns("cv_n", 5, 3.0, 0, PIPE)
b.wall_ns("cv_m", 5, 2.0, 0, PIPE)
b.flat("cv_cap1", 5, 1, 1.0, CAP)
b.flat("cv_cap2", 5, 2, 1.0, CAP)

# =================================================================
# 3. 龙门情报板: 双柱 (x [1,2] x y [0,1] / [3,4]) 两层 + 横板 + 情报板
# =================================================================
for lv in range(2):
    b.wall_ew(f"gs{lv}_w", 1.0, 0, lv, POST)
    b.wall_ns(f"gs{lv}_s", 1, 0.0, lv, POST)
    b.wall_ns(f"gs{lv}_n", 1, 1.0, lv, POST)
    b.wall_ew(f"gs{lv}_e", 2.0, 0, lv, POST)
    b.wall_ew(f"gn{lv}_w", 1.0, 3, lv, POST)
    b.wall_ns(f"gn{lv}_s", 1, 3.0, lv, POST)
    b.wall_ns(f"gn{lv}_n", 1, 4.0, lv, POST)
    b.wall_ew(f"gn{lv}_e", 2.0, 3, lv, POST)
b.flat("bm_s", 1, 1, 2.0, BEAM)
b.flat("bm_n", 1, 2, 2.0, BEAM)
b.crest_ew("board_s", 1.0, 1, 2.0, BOARD)
b.crest_ew("board_n", 1.0, 2, 2.0, BOARD)

# =================================================================
# 4. 压路机 (x [2,4], y [2,3], z 0..2): 双轮 + 底盘 + 驾驶室
# =================================================================
b.add("rl_wf", "wheel_base", (3.0, 2.0, 0.5), (90, 0, 0), WHEEL)
b.add("rl_wr", "wheel_base", (3.0, 3.0, 0.5), (90, 0, 0), WHEEL)
b.flat_rect("rl_ch", 2, 2, 1.0, BODY)
b.wall_ew("rl_cw", 2.0, 2, 1, GLASS)
b.wall_ns("rl_cs", 2, 2.0, 1, BODY)
b.wall_ns("rl_cn", 2, 3.0, 1, BODY)
b.wall_ew("rl_ce", 3.0, 2, 1, GLASS)
b.flat("rl_roof", 2, 2, 2.0, BODY)
b.crest_ns("rl_bc", 2, 2.0, 2.0, "orange")

# =================================================================
# 5. 场景: 围挡 + 雪糕筒 + 沥青料堆 + 告示牌
# =================================================================
b.wall_ns("bar_w1", 3, 0.0, 0, FENCE)
b.wall_ns("bar_w2", 4, 0.0, 0, FENCE)
b.crest_ns("bar_c1", 3, 0.0, 1.0, FTOP)
b.crest_ns("bar_c2", 4, 0.0, 1.0, FTOP)
b.crest_ns("cn_a", 4, 1.0, 0.0, CONE)
b.crest_ns("cn_b", 6, 3.0, 0.0, CONE)
b.crest_ew("cn_c", 7.0, 1, 0.0, CONE)
b.hat4("pile", 7, 0, 0.0, PILE, shape="equilateral_triangle")
b.wall_ns("sign", 7, 4.0, 0, SIGN)
b.crest_ns("sign_top", 7, 4.0, 1.0, "red")

# =================================================================
# 教程步骤 (15 步)
# =================================================================
b.step(
    "铺南半路基 (y [0,2]): 10 片黄色路基, x [5,6] 沟槽先留着。",
    ["r0_a", "r0_b", "r0_c", "r0_d", "r0_e",
     "r1_a", "r1_b", "r1_c", "r1_d", "r1_e"],
    tip="翻修从开挖开始 —— 留空的沟槽一会儿要埋涵管。",
)
b.step(
    "铺北半沥青 (y [2,4]): 11 片灰色沥青面, 沟槽穿过路中。",
    ["r2_a", "r2_b", "r2_c", "r2_d", "r2_e",
     "r3_a", "r3_b", "r3_c", "r3_d", "r3_e", "r3_f"],
    highlight=["r1_c", "r1_d"],
    tip="黄灰分界就是施工分界 —— 北半已铺好, 南半还在养护。",
)
b.step(
    "沉涵管四壁与两端: 6 片青色管壁沿沟槽格边立起, 竖边逐片咬合。",
    ["cv_w1", "cv_w2", "cv_e1", "cv_e2", "cv_s", "cv_n"],
    highlight=["r1_c", "r2_d"],
    tip="管壁底边整边吸沟槽两侧的路面格边 —— 涵管走向与道路垂直。",
)
b.step(
    "装中隔并盖板通车: 中隔墙把涵管分成双节, 2 片盖板四边压管壁顶。",
    ["cv_m", "cv_cap1", "cv_cap2"],
    highlight=["cv_w1", "cv_e2"],
    tip="每块盖板同时吸四段管壁顶 —— 沟槽上重新通车的就是它们。",
)
b.step(
    "立龙门南柱第一层: 4 片蓝色墙围成 1x1 柱环。",
    ["gs0_w", "gs0_s", "gs0_n", "gs0_e"],
    highlight=["r0_b"],
    tip="柱环四角互吸 —— 龙门柱其实是根方管。",
)
b.step(
    "立龙门北柱第一层: 对岸再起一柱。",
    ["gn0_w", "gn0_s", "gn0_n", "gn0_e"],
    highlight=["r3_b"],
    tip="双柱夹着整幅路面 —— 情报板要跨过所有车道。",
)
b.step(
    "双柱齐上第二层: 8 片, 竖缝与下层对齐。",
    ["gs1_w", "gs1_s", "gs1_n", "gs1_e",
     "gn1_w", "gn1_s", "gn1_n", "gn1_e"],
    highlight=["gs0_s", "gn0_n"],
    tip="每层都是闭环 —— 两根方管天生抗扭。",
)
b.step(
    "架龙门横板 + 挂情报板: 2 片横板对缝互吸、两端整边压柱顶, "
    "2 片绿色情报板三角骑在横板西沿。",
    ["bm_s", "bm_n", "board_s", "board_n"],
    highlight=["gs1_n", "gn1_s"],
    tip="双端简支 —— 剪断任何一条铰链线, 力都能从另一根柱走回地面。",
)
b.step(
    "落压路机双轮与底盘: 2 条车轮底座咬住沥青缝, 底盘长板双边压轮顶。",
    ["rl_wf", "rl_wr", "rl_ch"],
    highlight=["r2_b", "r3_c"],
    tip="双轮同宽同轴 —— 压路机的碾轮就是它的车轮。",
)
b.step(
    "装驾驶室: 前后透明挡风 + 两侧黄色侧墙, 围成 1x1 舱环。",
    ["rl_cw", "rl_cs", "rl_cn", "rl_ce"],
    highlight=["rl_ch"],
    tip="司机要看两头 —— 压路机来回碾, 挡风也前后各一面。",
)
b.step(
    "封舱顶 + 装警灯: 舱顶方板四边压墙顶, 橙色警灯骑南沿。",
    ["rl_roof", "rl_bc"],
    highlight=["rl_cs", "rl_cn"],
    tip="箱形环锁死 —— 碾压振动也散不了架。",
)
b.step(
    "立围挡: 2 片红色围挡墙踩路基缝, 2 片黄色围挡齿骑墙顶。",
    ["bar_w1", "bar_w2", "bar_c1", "bar_c2"],
    highlight=["r0_c", "r0_d"],
    tip="围挡立在路基与便道之间 —— 行人止步。",
)
b.step(
    "摆雪糕筒: 3 只红色雪糕筒围住沟槽作业区。",
    ["cn_a", "cn_b", "cn_c"],
    highlight=["cv_cap1"],
    tip="雪糕筒立在拼缝上, 底边整边吸格边。",
)
b.step(
    "堆沥青料: 东南角 4 片等边三角四坡自锁成料堆。",
    ["pile_s", "pile_e", "pile_n", "pile_w"],
    highlight=["r0_e"],
    tip="四条斜棱两两互吸 —— 下一车沥青就从这里上料。",
)
b.step(
    "立告示牌: 东北角黄牌红顶 —— 前方施工, 减速慢行!",
    ["sign", "sign_top"],
    highlight=["r3_f"],
    tip="俯瞰全场: 涵管、龙门、压路机 —— 一段路的翻修全流程。",
)

b.finalize(
    model_id="road_construction_01",
    name="道路施工段",
    name_en="Road Construction 01",
    description=(
        "建筑/工地主题的市政场景: 一段正在翻修的路 —— 南半路基"
        "裸露、北半沥青已铺, 路中沟槽埋下双节青色涵管 (共用中隔的"
        "闭环管节 + 双盖板桥面, 盖板四边压四段管壁顶); 西端龙门"
        "情报板双柱两层墙环起架, 双横板对缝互吸、两端整边压柱顶"
        "双端简支, 绿色情报板三角骑板沿 (板顶 2.87); 沥青面上双轮"
        "压路机来回碾压 —— 双车轮底座 + 底盘长板 + 前后挡风箱形"
        "舱环; 围挡雪糕筒把守作业区, 东南角沥青料堆四坡自锁。"
        "开挖、埋管、盖板、碾压 —— 一段路的翻修全流程。"
    ),
    difficulty=3,
    tags=["工程", "道路施工", "涵管", "龙门架", "载具"],
    min_pieces=72,
    min_steps=15,
)
