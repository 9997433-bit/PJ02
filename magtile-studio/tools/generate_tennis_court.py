#!/usr/bin/env python3
"""生成模型 data/models/tennis_court_01.json (网球场)。

运动主题批 ③: 全库第一座网球场 —— 与足球场 (门形环球门 + 坡道看台)
和篮球场 (篮架塔 + 铁丝网) 的结构逻辑都不同: 8x4 草地球场正中一道
**窗格方球网**横贯南北 (网眼即网孔, 两端灰柱锁扣), 北侧一把**双斜撑
高架裁判椅** (双层墙柱 + 两片直角三角侧撑 + 悬挑座板), 西端一面
**双层练习墙** (背后三片直角三角斜撑顶住, 打壁球式回球训练), 东端
记分窗格牌; 底线上一颗压线网球, 南沿一排绿篱、北角双旗 —— 网前
截击、底线对拉, 这一分打了二十拍!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 球场 [0,8]x[0,4]):
  - 球场: 透明底线方板 x8 + 草地长方形 x8 + 草地方板 x8       24 片
  - 南北走道: 方板 x16                                        16 片
  - 球网: 窗格方 x4 + 灰色网柱 x2                              6 片
  - 西走道 + 后场: 方板 x8                                     8 片
  - 练习墙: 双层墙 x8 + 直角三角斜撑 x3                       11 片
  - 裁判椅: 双层柱 x2 + 直角三角侧撑 x2 + 悬挑座板 x1          5 片
  - 东走道 + 记分牌: 方板 x4 + 窗格方 x2                       6 片
  - 网球 (四坡等边自锁) x4 + 绿篱 x4 + 角旗 x2                10 片
  合计 86 片, 20 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, 常规+strict 双档零警告):
  - 球网窗格方底边整边吸球场中线格边, 相邻竖边连吸成排, 两端
    网柱竖边锁扣 —— 一道网就是一面小桁架;
  - 练习墙背后三片直角三角斜撑: 竖直角边吸墙体拼缝竖边, 水平
    直角边整边吸后场方板拼缝 —— 双边受力的真斜撑;
  - 裁判椅两片侧撑同样双边受力, 座板单片悬挑力矩 15 <= 17.5;
  - 全场最高点 2.0 (裁判椅座板/练习墙顶), 不触发 R8 高层检查;
  - 每一步放下的片都接地或整边吸附, 走道环 + 拼缝互吸全场成环。

用法: python3 tools/generate_tennis_court.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

GRASS = "green"     # 草地
LINE = "clear"      # 底线白带
WALK = "gray"       # 走道
NET = "clear"       # 球网 (窗格方)
POST = "gray"       # 网柱
PWALL = "green"     # 练习墙
BRACE = "gray"      # 斜撑
CHAIR = "blue"      # 裁判椅
SCORE = "blue"      # 记分牌
BALL = "yellow"     # 网球
HEDGE = "green"     # 绿篱
FLAG = "red"        # 角旗

# =================================================================
# 1. 球场 [0,8]x[0,4]: 底线透明带 + 草地长方形/方板
# =================================================================
for y0 in range(4):
    b.flat(f"c_w_{y0}", 0, y0, 0.0, LINE)                 # 西底线
    b.flat_rect(f"c_wr_{y0}", 1, y0, 0.0, GRASS, axis="x")
    b.flat(f"c_m0_{y0}", 3, y0, 0.0, GRASS)
    b.flat(f"c_m1_{y0}", 4, y0, 0.0, GRASS)
    b.flat_rect(f"c_er_{y0}", 5, y0, 0.0, GRASS, axis="x")
    b.flat(f"c_e_{y0}", 7, y0, 0.0, LINE)                 # 东底线

# =================================================================
# 2. 南北走道: 各 8 片方板
# =================================================================
for x0 in range(8):
    b.flat(f"st_s_{x0}", x0, -1, 0.0, WALK)
for x0 in range(8):
    b.flat(f"st_n_{x0}", x0, 4, 0.0, WALK)

# =================================================================
# 3. 球网 (x=4 中线): 窗格方 x4 + 两端网柱
# =================================================================
for y0 in range(4):
    b.add(f"net_{y0}", "window_square", (4.0, y0 + 0.5, 0.5), (90, 0, 90), NET)
b.wall_ew("post_s", 4.0, -1, 0, POST)
b.wall_ew("post_n", 4.0, 4, 0, POST)

# =================================================================
# 4. 西走道 + 后场, 练习墙 (x=-1) + 背后斜撑
# =================================================================
for y0 in range(4):
    b.flat(f"ap_w_{y0}", -1, y0, 0.0, WALK)               # 西走道
for y0 in range(4):
    b.flat(f"ap_b_{y0}", -2, y0, 0.0, WALK)               # 后场
for z0 in (0, 1):
    for y0 in range(4):
        b.wall_ew(f"rw_{z0}_{y0}", -1.0, y0, z0, PWALL)   # 练习墙双层
for i, yl in enumerate((1, 2, 3)):
    b.brace(f"rb_{i}", (-1.0, float(yl), 0.0), "-x", BRACE)  # 背后斜撑

# =================================================================
# 5. 裁判椅 (北走道 [5,6]x[4,5]): 双层柱 + 侧撑 + 悬挑座板
# =================================================================
for z0 in (0, 1):
    b.wall_ns(f"uc_w_{z0}", 5, 5.0, z0, CHAIR)
b.brace("uc_b_w", (5.0, 5.0, 0.0), "-y", BRACE)
b.brace("uc_b_e", (6.0, 5.0, 0.0), "-y", BRACE)
b.flat("uc_seat", 5, 4, 2.0, CHAIR)                       # 座板 (悬挑向场内)

# =================================================================
# 6. 东走道 + 记分牌
# =================================================================
for y0 in range(4):
    b.flat(f"ap_e_{y0}", 8, y0, 0.0, WALK)
b.add("sb_0", "window_square", (9.0, 1.5, 0.5), (90, 0, 90), SCORE)
b.add("sb_1", "window_square", (9.0, 2.5, 0.5), (90, 0, 90), SCORE)

# =================================================================
# 7. 网球 (东底线 [7,8]x[1,2]) + 绿篱 + 角旗
# =================================================================
BALL_IDS = b.hat4("ball", 7, 1, 0.0, BALL, shape="equilateral_triangle")
for i, x0 in enumerate((0, 2, 5, 7)):
    b.crest_ns(f"hd_{i}", x0, -1.0, 0.0, HEDGE)
b.spire_ns("fl_w", 0, 5.0, 0.0, FLAG)
b.spire_ns("fl_e", 7, 5.0, 0.0, FLAG)

# =================================================================
# 教程步骤 (20 步)
# =================================================================
for y0, label in ((0, "第一"), (1, "第二"), (2, "第三"), (3, "第四")):
    b.step(
        f"铺球场{label}排: 透明底线方板在两端, 草地长方形与方板居中 "
        f"(自西向东 6 片)。",
        [f"c_w_{y0}", f"c_wr_{y0}", f"c_m0_{y0}", f"c_m1_{y0}",
         f"c_er_{y0}", f"c_e_{y0}"],
        highlight=[] if y0 == 0 else [f"c_w_{y0 - 1}"],
        tip="长方形与方板整边互吸, 底线透明带就是发球的界线。"
        if y0 == 0 else "新一排南边整边吸上一排北边, 草地平整无缝。",
    )
b.step(
    "铺南走道: 8 片灰色方板沿球场南沿排开。",
    [f"st_s_{x0}" for x0 in range(8)],
    highlight=["c_w_0"],
    tip="走道是捡球员的跑道, 也是绿篱的地基。",
)
b.step(
    "铺北走道: 再 8 片, 与南走道对称。",
    [f"st_n_{x0}" for x0 in range(8)],
    highlight=["c_w_3"],
    tip="北走道稍后要立裁判椅和角旗。",
)
b.step(
    "立球网: 4 片透明窗格方沿中线一字排开, 底边吸场地格边、"
    "竖边连吸成排。",
    ["net_0", "net_1", "net_2", "net_3"],
    highlight=["c_m0_0", "c_m1_3"],
    tip="窗格就是网孔 —— 过网才算好球。",
)
b.step(
    "锁网柱: 两端各 1 片灰色柱墙, 竖边与球网锁扣。",
    ["post_s", "post_n"],
    highlight=["net_0", "net_3"],
    tip="网柱把整道网绷紧, 一道网就是一面小桁架。",
)
b.step(
    "铺西走道: 4 片方板贴住西底线。",
    [f"ap_w_{y0}" for y0 in range(4)],
    highlight=["c_w_1"],
    tip="西走道后面就是练习墙的位置。",
)
b.step(
    "铺练习墙后场: 再 4 片方板, 给斜撑留地基。",
    [f"ap_b_{y0}" for y0 in range(4)],
    highlight=["ap_w_1"],
    tip="斜撑的水平直角边要吸在这排拼缝上。",
)
b.step(
    "立练习墙一层: 4 片绿色墙板沿 x=-1 排开, 竖边连吸。",
    [f"rw_0_{y0}" for y0 in range(4)],
    highlight=["ap_w_0", "ap_b_0"],
    tip="底边吸走道与后场拼缝, 一层墙先站稳。",
)
b.step(
    "顶背后斜撑: 3 片直角三角, 竖直角边吸墙体拼缝竖边、"
    "水平直角边整边吸后场拼缝。",
    ["rb_0", "rb_1", "rb_2"],
    highlight=["rw_0_1", "rw_0_2"],
    tip="双边受力的真斜撑 —— 回球再重, 墙也纹丝不动。",
)
b.step(
    "叠练习墙二层: 再 4 片, 底边整边吸一层墙顶。",
    [f"rw_1_{y0}" for y0 in range(4)],
    highlight=["rw_0_0", "rb_1"],
    tip="两层墙高 2, 正好接住高压球的反弹。",
)
b.step(
    "立裁判椅一层柱与双侧撑: 柱墙立上北走道北沿, 两片直角三角"
    "侧撑左右夹住柱脚。",
    ["uc_w_0", "uc_b_w", "uc_b_e"],
    highlight=["st_n_5"],
    tip="侧撑竖边吸柱竖边、横边吸走道拼缝 —— 高椅的秘密全在脚下。",
)
b.step(
    "叠裁判椅二层柱并压座板: 柱升到 2 层, 座板压柱顶向场内悬挑。",
    ["uc_w_1", "uc_seat"],
    highlight=["uc_w_0"],
    tip="座板单片悬挑力矩 15 <= 预算 17.5 —— 裁判看得清每一个压线球。",
)
b.step(
    "铺东走道: 4 片方板贴住东底线。",
    [f"ap_e_{y0}" for y0 in range(4)],
    highlight=["c_e_1"],
    tip="东走道尽头立记分牌。",
)
b.step(
    "挂记分窗格牌: 2 片蓝色窗格方立上东走道外沿, 中缝互吸。",
    ["sb_0", "sb_1"],
    highlight=["ap_e_1", "ap_e_2"],
    tip="窗格里翻分片 —— 15, 30, 40, 局点!",
)
b.step(
    "拼压线网球: 4 片黄色等边三角四坡互吸自锁, 正好压在东底线上。",
    BALL_IDS,
    highlight=["c_e_1"],
    tip="鹰眼回放: 压线, 好球!",
)
b.step(
    "种南沿绿篱: 4 片绿色等边三角立上南走道外沿。",
    ["hd_0", "hd_1", "hd_2", "hd_3"],
    highlight=["st_s_0", "st_s_7"],
    tip="绿篱底边吸走道板边, 挡风又养眼。",
)
b.step(
    "升北角双旗: 2 面红色角旗立上北走道两角 —— 比赛开始!",
    ["fl_w", "fl_e"],
    highlight=["st_n_0", "st_n_7"],
    tip="角旗立在走道板边铰链线上, 重心正压。",
)

b.finalize(
    model_id="tennis_court_01",
    name="网球场",
    name_en="Tennis Court",
    description=(
        "草地网球场: 8x4 球场两端透明底线带, 正中一道窗格方球网横贯南北、"
        "两端灰柱锁扣; 北侧双斜撑高架裁判椅悬挑座板俯瞰全场, 西端双层练习墙"
        "背后三片直角三角斜撑顶住, 东端窗格记分牌翻着局分, 底线上一颗四坡"
        "自锁的黄色网球压线 —— 网前截击、底线对拉, 这一分打了二十拍!"
    ),
    difficulty=4,
    tags=["运动", "网球", "球场", "进阶"],
    min_pieces=86,
    min_steps=20,
)
