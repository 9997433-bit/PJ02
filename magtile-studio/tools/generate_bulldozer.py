#!/usr/bin/env python3
"""生成模型 data/models/bulldozer_01.json (履带推土机)。

工程机械主题: 全库第一台推土机 —— 橙色土场上, 四片车轮底座
(wheel_base) 组成双侧长履带, 底盘长板压顶锁成箱形车架;
车头满宽推土铲由推架方板与车架锁成受力环 (铲不是悬挂件!),
铲前一座四坡土丘正被推走; 车尾直角三角松土器入地, 两层
驾驶室上层全透明, 引擎罩前角竖着红色排气管 —— 工地开工!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 铲刀朝东):
  - 土场 8x4: 方板 x16 + 长板 x8 (拼缝落在履带线上)            24 片
  - 履带: 车轮底座 x4 (双侧各 2, 底边整边吸土场长板拼缝)        4 片
  - 底盘: 尾端墙 x2 + 底盘长板 x4 (z=1)                         6 片
  - 推土铲 x2 + 推架 x2 (铲与车架锁成受力环)                    4 片
  - 驾驶室两层 (x 1..3): 下层 x8 + 透明上层 x8 + 顶板 x2       18 片
  - 引擎罩 (x 3..5): 侧壁 x6 + 罩顶长板 x2                      8 片
  - 排气管 x1 + 松土器 x1 + 土丘 hat4 x4 + 碎石 x2              8 片
  合计 72 片, 16 个教程步骤, 6 种片形。

物理规则要点 (通过 R1~R8 全部校验):
  - 履带+尾端墙+底盘长板锁成箱形车架 (长板长边整边压履带顶);
  - 推土铲底边整边吸土场拼缝接地, 铲顶边再被推架方板压住,
    推架另一端咬住底盘长板短边 —— 铲-推架-车架三件受力环,
    推土的反力经推架直接传回车架;
  - 引擎罩顶长板双端简支: 西短边压驾驶室东墙顶, 东短边压
    罩前壁顶 —— 无悬挑;
  - 松土器直角三角: 竖边吸尾端墙竖边, 横边整边吸土场拼缝。

用法: python3 tools/generate_bulldozer.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

DIRT = "orange"     # 土场
TRACK = "gray"      # 履带
FRAME = "gray"      # 车架
BODY = "yellow"     # 车身
GLASS = "clear"     # 驾驶室上层
ROOF = "gray"       # 驾驶室顶
BLADE = "yellow"    # 推土铲
PIPE = "red"        # 排气管
MOUND = "orange"    # 土丘
ROCK = "gray"       # 碎石

# =================================================================
# 1. 土场 8x4: 长板拼缝落在履带线 (x 1..3 与 3..5)
# =================================================================
for y0 in range(4):
    b.flat(f"d0_{y0}", 0, y0, 0.0, DIRT)
    b.flat_rect(f"da_{y0}", 1, y0, 0.0, DIRT)       # [1..3]
    b.flat_rect(f"db_{y0}", 3, y0, 0.0, DIRT)       # [3..5]
    b.flat(f"d5_{y0}", 5, y0, 0.0, DIRT)
    b.flat(f"d6_{y0}", 6, y0, 0.0, DIRT)
    b.flat(f"d7_{y0}", 7, y0, 0.0, DIRT)

# =================================================================
# 2. 履带: 4 片车轮底座, 双侧各 2, 底边整边吸长板拼缝
# =================================================================
for x0 in (1, 3):
    b.add(f"tk_s_{x0}", "wheel_base", (x0 + 1.0, 1.0, 0.5),
          (90, 0, 0), TRACK)
    b.add(f"tk_n_{x0}", "wheel_base", (x0 + 1.0, 3.0, 0.5),
          (90, 0, 0), TRACK)

# =================================================================
# 3. 底盘: 尾端墙 (x=1) + 底盘长板 (z=1)
# =================================================================
for y0 in (1, 2):
    b.wall_ew(f"rw_{y0}", 1.0, y0, 0, FRAME)        # 尾端墙
for y0 in (1, 2):
    b.flat_rect(f"ch_w_{y0}", 1, y0, 1.0, FRAME)    # 底盘长板 [1..3]
    b.flat_rect(f"ch_e_{y0}", 3, y0, 1.0, FRAME)    # 底盘长板 [3..5]

# =================================================================
# 4. 推土铲 (x=6, z 0..1) + 推架 (z=1): 铲-推架-车架受力环
# =================================================================
for y0 in (1, 2):
    b.wall_ew(f"blade_{y0}", 6.0, y0, 0, BLADE)     # 推土铲
for y0 in (1, 2):
    b.flat(f"push_{y0}", 5, y0, 1.0, FRAME)         # 推架方板

# =================================================================
# 5. 驾驶室两层 (x 1..3, z 1..3) + 顶板
# =================================================================
for x0 in (1, 2):
    b.wall_ns(f"c0_s_{x0}", x0, 1.0, 1, BODY)       # 下层
    b.wall_ns(f"c0_n_{x0}", x0, 3.0, 1, BODY)
for y0 in (1, 2):
    b.wall_ew(f"c0_w_{y0}", 1.0, y0, 1, BODY)
    b.wall_ew(f"c0_e_{y0}", 3.0, y0, 1, BODY)
for x0 in (1, 2):
    b.wall_ns(f"c1_s_{x0}", x0, 1.0, 2, GLASS)      # 透明上层
    b.wall_ns(f"c1_n_{x0}", x0, 3.0, 2, GLASS)
for y0 in (1, 2):
    b.wall_ew(f"c1_w_{y0}", 1.0, y0, 2, GLASS)
    b.wall_ew(f"c1_e_{y0}", 3.0, y0, 2, GLASS)
b.flat_rect("cr_s", 1, 1, 3.0, ROOF)                # 驾驶室顶
b.flat_rect("cr_n", 1, 2, 3.0, ROOF)

# =================================================================
# 6. 引擎罩 (x 3..5, z 1..2): 侧壁 + 罩顶长板双端简支
# =================================================================
for x0 in (3, 4):
    b.wall_ns(f"h_s_{x0}", x0, 1.0, 1, BODY)        # 罩侧壁
    b.wall_ns(f"h_n_{x0}", x0, 3.0, 1, BODY)
for y0 in (1, 2):
    b.wall_ew(f"h_e_{y0}", 5.0, y0, 1, BODY)        # 罩前壁
b.flat_rect("h_top_s", 3, 1, 2.0, BODY)             # 罩顶长板
b.flat_rect("h_top_n", 3, 2, 2.0, BODY)

# =================================================================
# 7. 排气管 + 松土器 + 土丘 + 碎石
# =================================================================
b.crest_ew("pipe", 5.0, 1, 2.0, PIPE)               # 排气管 (罩前沿)
b.brace("ripper", (1.0, 2.0, 0.0), "-x", FRAME)     # 松土器 (车尾)
MOUND_IDS = b.hat4("mound", 6, 1, 0.0, MOUND,
                   shape="equilateral_triangle")    # 铲前土丘
b.crest_ns("rock_a", 7, 2.0, 0.0, ROCK)             # 碎石
b.crest_ns("rock_b", 6, 3.0, 0.0, ROCK)

# =================================================================
# 教程步骤 (16 步)
# =================================================================
ROW_IDS = lambda y0: [f"d0_{y0}", f"da_{y0}", f"db_{y0}",
                      f"d5_{y0}", f"d6_{y0}", f"d7_{y0}"]
b.step(
    "铺土场·第 1 行: 方板+长板混铺 (y 0..1), 长板落在 x 1..5。",
    ROW_IDS(0),
    tip="长板拼缝就是履带线 —— 推土机的履带将吸在这两条缝上。",
)
b.step(
    "铺土场·第 2 行: 同样混铺一行 (y 1..2)。",
    ROW_IDS(1),
    highlight=["da_0", "db_0"],
    tip="两行长板缝上下对齐 —— 履带底边要同时咬住两条长边。",
)
b.step(
    "铺土场·第 3 行: 再铺一行 (y 2..3)。",
    ROW_IDS(2),
    highlight=["da_1"],
    tip="北侧履带线也备好了 —— 工地一天比一天平整。",
)
b.step(
    "铺土场·第 4 行: 8x4 土场合拢 (y 3..4)。",
    ROW_IDS(3),
    highlight=["da_2"],
    tip="橙色的土, 灰色的石 —— 这就是推土机的战场。",
)
b.step(
    "装南侧履带: 2 片车轮底座沿 y=1 拼缝立起, 底边整边吸合。",
    ["tk_s_1", "tk_s_3"],
    highlight=["da_0", "db_0"],
    tip="一片顶两格, 两片连成长履带 —— 竖边还彼此互吸。",
)
b.step(
    "装北侧履带: y=3 拼缝再立 2 片, 双侧履带就位。",
    ["tk_n_1", "tk_n_3"],
    highlight=["tk_s_1", "tk_s_3"],
    tip="两侧履带严格对位 —— 底盘长板要同时压住它们。",
)
b.step(
    "立尾端墙: x=1 线上 2 片灰色方墙, 底边整边吸土场格边。",
    ["rw_1", "rw_2"],
    highlight=["d0_1", "d0_2"],
    tip="尾端墙与履带同高 —— 它们共同托起底盘。",
)
b.step(
    "盖底盘长板: 4 片长板长边整边压履带顶、短边压尾端墙顶, "
    "箱形车架合龙。",
    ["ch_w_1", "ch_w_2", "ch_e_1", "ch_e_2"],
    highlight=["tk_s_1", "rw_1"],
    tip="履带+端墙+底盘锁成箱形环 —— 这就是推土机的脊梁。",
)
b.step(
    "立推土铲: x=6 线上 2 片黄色满宽铲刀, 底边整边吸土场拼缝。",
    ["blade_1", "blade_2"],
    highlight=["d5_1", "d5_2"],
    tip="铲刀接地承重 —— 推土的力从来不靠磁铁硬扛。",
)
b.step(
    "锁推架: 2 片方板西咬底盘长板短边、东压铲刀顶边 —— "
    "铲-推架-车架锁成受力环。",
    ["push_1", "push_2"],
    highlight=["ch_e_1", "blade_1"],
    tip="推土的反力经推架直接传回车架 —— 这是推土机的力学核心。",
)
b.step(
    "驾驶室下层: 8 片黄色围壁立在底盘拼缝上 (x 1..3), 先立东西"
    "端墙再合南北侧壁。",
    ["c0_w_1", "c0_w_2", "c0_e_1", "c0_e_2",
     "c0_s_1", "c0_s_2", "c0_n_1", "c0_n_2"],
    highlight=["ch_w_1", "ch_w_2"],
    tip="围壁四角竖边互吸成环 —— 驾驶室从底盘上长出来。",
)
b.step(
    "驾驶室透明上层: 再叠 8 片透明围壁 —— 司机要看清铲刀每一寸。",
    ["c1_s_1", "c1_s_2", "c1_n_1", "c1_n_2",
     "c1_w_1", "c1_w_2", "c1_e_1", "c1_e_2"],
    highlight=["c0_s_1", "c0_e_1"],
    tip="全透明驾驶舱 360 度视野, 上下层严格对缝。",
)
b.step(
    "盖驾驶室顶: 2 片长板短边双端压住围壁顶, 驾驶室合龙。",
    ["cr_s", "cr_n"],
    highlight=["c1_w_1", "c1_e_2"],
    tip="双端简支 —— 顶板还兼作防落物棚。",
)
b.step(
    "装引擎罩: 侧壁 4 片 + 前壁 2 片, 罩顶 2 片长板西压驾驶室"
    "东墙顶、东压前壁顶。",
    ["h_s_3", "h_s_4", "h_n_3", "h_n_4", "h_e_1", "h_e_2",
     "h_top_s", "h_top_n"],
    highlight=["c0_e_1", "ch_e_1"],
    tip="罩顶长板双端简支, 引擎的轰鸣就闷在这个箱子里。",
)
b.step(
    "竖排气管与松土器: 罩前沿立 1 片红色排气管, 车尾直角三角"
    "松土器竖边吸端墙、横边吸地缝。",
    ["pipe", "ripper"],
    highlight=["h_top_s", "rw_2"],
    tip="排气管重心正压铰链; 松土器入地 —— 倒车也能干活。",
)
b.step(
    "堆铲前土丘与碎石: 4 片土丘四棱互吸, 再放 2 片碎石 —— "
    "工地开工!",
    MOUND_IDS + ["rock_a", "rock_b"],
    highlight=["blade_1", "d6_1"],
    tip="土丘就堆在铲刀正前方 —— 一脚油门, 推平它!",
)

b.finalize(
    model_id="bulldozer_01",
    name="履带推土机",
    name_en="Bulldozer 01",
    description=(
        "全库第一台推土机: 四片车轮底座组成双侧长履带, 底盘长板压顶锁成"
        "箱形车架; 车头满宽推土铲接地承重, 推架方板把铲刀与车架锁成"
        "受力环 (推土反力直达车架); 两层驾驶室上层全透明, 引擎罩顶长板"
        "双端简支, 罩前红色排气管、车尾直角三角松土器一应俱全, 铲前"
        "四坡土丘正等着被推平 —— 工地开工!"
    ),
    difficulty=3,
    tags=["工程", "推土机", "工程机械", "车轮底座", "载具"],
    min_pieces=65,
    min_steps=16,
)
