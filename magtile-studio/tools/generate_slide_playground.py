#!/usr/bin/env python3
"""生成模型 data/models/slide_playground_01.json (滑梯乐园)。

游乐园主题: 与 water_slide_park_01 (泳池入水单滑道) 刻意区分 ——
本模型的主角是**双道竞速大滑梯**: 两层高的攀爬主塔向东甩出两条
并排的两段式滑道 (中继桥墩接力落地), 滑道尽头冲过双柱冲线门;
主塔西侧是直角三角攀岩壁, 北侧连着幼儿塔 (一层高) 与向西的
缓滑道 —— 大孩子比速度, 小朋友玩缓坡, 各得其乐。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 地面: 主塔地台 4 + 攀岩围裙 2 + 连接步道 2 + 幼儿塔地台 2
          + 落地沙坑 8                                        18 片
  - 攀爬主塔 [0,2]x[0,2]: 四面立墙 x2 层 + 甲板 4             20 片
  - 甲板护栏: 西沿等边护栏 2 + 南北沿等腰旗杆 2                4 片
  - 竞速双滑道: 每道上段坡 + 中继桥墩 + 下段坡, 共 2 道        6 片
  - 攀岩壁: 直角三角攀爬斜撑 2                                 2 片
  - 幼儿塔 [0,2]x[3,4]: 四面立墙 6 + 甲板 2 + 顶旗 1           9 片
  - 幼儿缓滑道: 向西单段坡道 1                                  1 片
  - 冲线门 (x=6): 门垛地板 2 + 双柱 x2 层 + 长方形横梁          7 片
  合计 67 片, 16 个教程步骤, 5 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 两段式滑道: 上段坡顶边吸甲板沿口, 坡尾由中继桥墩顶边接住,
    下段坡顶边吸同一条铰链线、坡尾自然落地 (滚珠塔同款三角刚性);
  - 两道滑道的桥墩同面并肩, 竖边互吸成整面墩墙;
  - 攀岩斜撑竖直角边吸塔墙竖边、水平直角边吸围裙板缝 (刚性节点);
  - 冲线门横梁两端竖边吸双柱上层竖边, 横跨两条滑道出口上方。

用法: python3 tools/generate_slide_playground.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import SQ3, ModelBuilder  # noqa: E402

b = ModelBuilder()

PAD = "gray"        # 地台与步道
SAND = "yellow"     # 落地沙坑
TOWER = "blue"      # 攀爬主塔
KID = "green"       # 幼儿塔
SLIDE = "orange"    # 滑道
PIER = "gray"       # 中继桥墩
RAIL = "cyan"       # 甲板护栏
FLAG = "red"        # 旗杆与冲线门
ROCK = "purple"     # 攀岩斜撑

# =================================================================
# 1. 地面: 主塔地台 / 攀岩围裙 / 连接步道 / 幼儿塔地台 / 沙坑
# =================================================================
for x in range(2):
    for y in range(2):
        b.flat(f"pd_{x}_{y}", x, y, 0.0, PAD)        # 主塔地台 [0,2]x[0,2]
b.flat("ap_0", -1, 0, 0.0, PAD)                      # 攀岩围裙 (塔西)
b.flat("ap_1", -1, 1, 0.0, PAD)
b.flat("pw_0", 0, 2, 0.0, PAD)                       # 连接步道
b.flat("pw_1", 1, 2, 0.0, PAD)
b.flat("kp_0", 0, 3, 0.0, PAD)                       # 幼儿塔地台
b.flat("kp_1", 1, 3, 0.0, PAD)
for x in range(2, 6):
    for y in range(2):
        b.flat(f"sd_{x}_{y}", x, y, 0.0, SAND)       # 落地沙坑 [2,6]x[0,2]

# =================================================================
# 2. 攀爬主塔 [0,2]x[0,2]: 四面立墙 x2 层 + 甲板 (z=2)
# =================================================================
for lv in range(2):
    for x in range(2):
        b.wall_ns(f"tw_s{lv}_{x}", x, 0.0, lv, TOWER)   # 南壁
        b.wall_ns(f"tw_n{lv}_{x}", x, 2.0, lv, TOWER)   # 北壁
    for y in range(2):
        b.wall_ew(f"tw_w{lv}_{y}", 0.0, y, lv, TOWER)   # 西壁
        b.wall_ew(f"tw_e{lv}_{y}", 2.0, y, lv, TOWER)   # 东壁
for x in range(2):
    for y in range(2):
        b.flat(f"dk_{x}_{y}", x, y, 2.0, TOWER)         # 甲板

# 甲板护栏: 西沿等边护栏 2 + 南北沿等腰旗杆 2
b.crest_ew("rl_w0", 0.0, 0, 2.0, RAIL)
b.crest_ew("rl_w1", 0.0, 1, 2.0, RAIL)
b.spire_ns("fg_s", 0, 0.0, 2.0, FLAG)
b.spire_ns("fg_n", 1, 2.0, 2.0, FLAG)

# =================================================================
# 3. 竞速双滑道 (向东): 上段坡 + 中继桥墩 + 下段坡, 两道并排
# =================================================================
X_PIER = 2.0 + SQ3          # 中继铰链线 x = 3.732051
for lane in range(2):
    b.wall_ew(f"sp_{lane}", X_PIER, lane, 0, PIER)          # 中继桥墩
    b.ramp(f"su_{lane}", "+x", 2.0, lane, 2.0, SLIDE)       # 上段坡 (z 2->1)
    b.ramp(f"sl_{lane}", "+x", X_PIER, lane, 1.0, SLIDE)    # 下段坡 (z 1->0)

# =================================================================
# 4. 攀岩壁 (塔西): 直角三角攀爬斜撑 x2
# =================================================================
b.brace("rk_0", (0.0, 0.0, 0.0), "-x", ROCK)
b.brace("rk_1", (0.0, 1.0, 0.0), "-x", ROCK)

# =================================================================
# 5. 幼儿塔 [0,2]x[3,4]: 一层立墙 + 甲板 (z=1) + 顶旗 + 缓滑道
# =================================================================
for x in range(2):
    b.wall_ns(f"kt_s_{x}", x, 3.0, 0, KID)
    b.wall_ns(f"kt_n_{x}", x, 4.0, 0, KID)
b.wall_ew("kt_w", 0.0, 3, 0, KID)
b.wall_ew("kt_e", 2.0, 3, 0, KID)
b.flat("kd_0", 0, 3, 1.0, KID)
b.flat("kd_1", 1, 3, 1.0, KID)
b.crest_ns("kt_flag", 1, 4.0, 1.0, RAIL)
b.ramp("ks", "-x", 0.0, 3, 1.0, SLIDE)               # 幼儿缓滑道 (坡尾落地)

# =================================================================
# 6. 冲线门 (x=6 立面): 门垛地板 2 + 双柱 x2 层 + 长方形横梁
#    双柱分立滑道出口两侧 (y0=-1 与 y0=2), 横梁跨 y 0..2 合龙
# =================================================================
b.flat("gf_s", 5, -1, 0.0, PAD)
b.flat("gf_n", 5, 2, 0.0, PAD)
b.wall_ew("gp_s1", 6.0, -1, 0, FLAG)
b.wall_ew("gp_s2", 6.0, -1, 1, FLAG)
b.wall_ew("gp_n1", 6.0, 2, 0, FLAG)
b.wall_ew("gp_n2", 6.0, 2, 1, FLAG)
b.lintel_ew("gp_ban", 6.0, 0, 1, FLAG)

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺设主塔地台与攀岩围裙: 4 片灰色方板做塔基, 塔西再铺 2 片围裙板。",
    ["pd_0_0", "pd_1_0", "pd_0_1", "pd_1_1", "ap_0", "ap_1"],
    tip="地台是整座乐园的锚点, 6 片板缝缝相吸铺成一整块。",
)
b.step(
    "铺设落地沙坑: 塔东 8 片黄色方板, 竞速滑道将从这里冲线。",
    [f"sd_{x}_{y}" for x in range(2, 6) for y in range(2)],
    highlight=["pd_1_0"],
    tip="沙坑板与塔基板整边吸合 —— 落地区要足够长才安全。",
)
b.step(
    "竖立主塔下层墙: 8 片蓝色正方形沿塔基四边围合成筒。",
    [f"tw_s0_{x}" for x in range(2)] + [f"tw_n0_{x}" for x in range(2)]
    + [f"tw_w0_{y}" for y in range(2)] + [f"tw_e0_{y}" for y in range(2)],
    highlight=["pd_0_0", "pd_1_1"],
    tip="墙底边吸地台边, 四角竖边互吸 —— 方筒是最稳的塔身。",
)
b.step(
    "主塔加高到两层: 上层 8 片墙对缝叠上, 攀爬塔到顶。",
    [f"tw_s1_{x}" for x in range(2)] + [f"tw_n1_{x}" for x in range(2)]
    + [f"tw_w1_{y}" for y in range(2)] + [f"tw_e1_{y}" for y in range(2)],
    highlight=["tw_s0_0", "tw_e0_1"],
    tip="上下两层墙横边完全对齐, 错缝会让塔身变弱。",
)
b.step(
    "铺设主塔甲板: 4 片蓝色方板压住墙顶边, 四边逐片吸实。",
    ["dk_0_0", "dk_1_0", "dk_0_1", "dk_1_1"],
    highlight=["tw_s1_0", "tw_n1_1"],
    tip="甲板即是滑梯的出发平台 —— 每条外沿边都要吸牢墙顶。",
)
b.step(
    "安装甲板护栏与旗杆: 西沿立 2 片青色等边护栏, 南北沿各立 1 根"
    "红色等腰旗杆。",
    ["rl_w0", "rl_w1", "fg_s", "fg_n"],
    highlight=["dk_0_0"],
    tip="护栏立在甲板沿口铰链线上, 重心正压、力臂为零。",
)
b.step(
    "安装南道竞速滑梯: 先立中继桥墩 (x=2+√3 处), 上段坡顶边吸甲板"
    "沿口、坡尾搭桥墩顶边, 下段坡接力冲向沙坑落地。",
    ["sp_0", "su_0", "sl_0"],
    highlight=["sd_3_0", "dk_1_0"],
    tip="坡道-桥墩-塔身三件互吸成三角刚性节点, 零悬挑零悬挂。",
)
b.step(
    "安装北道竞速滑梯: 桥墩与南道墩竖边互吸并肩, 两段坡道与南道"
    "严格平行, 双道就绪等待发令。",
    ["sp_1", "su_1", "sl_1"],
    highlight=["sp_0", "su_0"],
    tip="两条坡道严格平行, 谁先落沙坑谁赢!",
)
b.step(
    "安装攀岩壁: 2 片紫色直角三角斜撑, 竖直角边吸塔西墙竖边、"
    "水平直角边吸围裙板缝。",
    ["rk_0", "rk_1"],
    highlight=["tw_w0_0", "ap_0"],
    tip="斜撑把塔墙和地面锁成刚性三角 —— 这也是攀岩的扶手棱。",
)
b.step(
    "铺设连接步道与幼儿塔地台: 塔北 2 片步道板 + 2 片地台板。",
    ["pw_0", "pw_1", "kp_0", "kp_1"],
    highlight=["pd_0_1"],
    tip="步道把大塔与幼儿塔连成一个连通整体。",
)
b.step(
    "竖立幼儿塔墙: 6 片绿色正方形围合一层小塔。",
    ["kt_s_0", "kt_s_1", "kt_n_0", "kt_n_1", "kt_w", "kt_e"],
    highlight=["kp_0", "kp_1"],
    tip="幼儿塔只有一层高 —— 高度刚好适合小小朋友。",
)
b.step(
    "铺设幼儿塔甲板并升顶旗: 2 片甲板压墙顶, 北沿立 1 面青色小旗。",
    ["kd_0", "kd_1", "kt_flag"],
    highlight=["kt_s_0"],
    tip="甲板四沿吸实墙顶边, 顶旗立在北沿铰链线上。",
)
b.step(
    "安装幼儿缓滑道: 橙色坡道顶边吸幼儿塔西沿, 坡尾自然落地。",
    ["ks"],
    highlight=["kd_0"],
    tip="一层高的缓坡, 坡尾直接贴地 —— 小朋友的专属跑道。",
)
b.step(
    "铺设门垛地板并竖立冲线门双柱下层: 沙坑东端两侧各铺 1 片门垛板, "
    "2 片红色正方形柱分立滑道出口两旁。",
    ["gf_s", "gf_n", "gp_s1", "gp_n1"],
    highlight=["sd_5_0", "sd_5_1"],
    tip="柱底边吸门垛板东沿 —— 冲线门要正对两条滑道的出口。",
)
b.step(
    "双柱加高: 各叠 1 片, 柱顶升到 2 层高。",
    ["gp_s2", "gp_n2"],
    highlight=["gp_s1", "gp_n1"],
    tip="上下对缝叠放, 双柱像两名站姿笔挺的裁判。",
)
b.step(
    "架设冲线横梁: 红色长方形两端竖边吸双柱竖边, 横跨双道出口上方, "
    "滑梯乐园开园!",
    ["gp_ban"],
    highlight=["gp_s2", "gp_n2"],
    tip="横梁合龙的一刻 —— 预备, 比赛开始!",
)

b.finalize(
    model_id="slide_playground_01",
    name="滑梯乐园",
    name_en="Slide Playground",
    description=(
        "双道竞速滑梯乐园: 两层攀爬主塔向东甩出两条并排的两段式竞速滑道 "
        "(中继桥墩接力落地), 冲过红色双柱冲线门; 塔西紫色直角三角攀岩壁, "
        "塔北幼儿塔配向西缓滑道, 甲板护栏与等腰旗杆一应俱全 —— 大孩子"
        "比速度, 小朋友玩缓坡, 全场连成一个连通整体。"
    ),
    difficulty=3,
    tags=["游乐园", "运动", "进阶"],
    min_pieces=65,
    min_steps=16,
)
