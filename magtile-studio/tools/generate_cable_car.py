#!/usr/bin/env python3
"""生成模型 data/models/cable_car_01.json (缆车站)。

第三批模型 ③: 高山交通主题 —— 山顶缆车站: 4x4 山地上
立起 2x2 两层山顶站塔, 塔顶平台挂着六边形驱动轮, 一条
30 度索道经中途支架塔分两段滑向山脚, 山脚站台上停着
一台戴四坡尖顶的红色缆车吊舱, 站前围栏一路相迎。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 山顶: 4x4 山地 16 + 2x2 站塔两层 16 + 塔顶平台 4        36 片
  - 驱动轮 + 站旗: 六边形立轮 1 + 旗 2                        3 片
  - 索道: 30 度坡道 x2 + 中途支架塔 x1                        3 片
  - 山脚: 联络步道 2 + 站台 3x3 地坪 9                       11 片
  - 缆车吊舱: 1x1 舱体 4 + 等边四坡尖顶 4                     8 片
  - 站台围栏: 等边三角 x3                                     3 片
  合计 64 片, 17 个教程步骤, 6 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 索道第一段顶边整边吸塔顶平台东沿, 坡尾由中途支架塔顶边接住
    (螺旋滚珠塔"坡尾桥墩"同款);
  - 第二段从支架塔顶继续下滑, 坡尾自然落地滑入山脚站台;
  - 驱动轮六边形立于竖直平面 (力矩为零), 底边整边吸平台沿口;
  - 联络步道把山地与山脚站台连成一个磁力连通整体。

用法: python3 tools/generate_cable_car.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import COS30, HEX_APOTHEM, ModelBuilder  # noqa: E402

b = ModelBuilder()

PIER_X = round(3.0 + 2 * COS30, 6)      # 中途支架塔 x = 4.73205

# =================================================================
# 1. 山顶山地 4x4: 绿色草甸点缀灰色岩块
# =================================================================
ROCKS = {(0, 3), (3, 0), (2, 3)}
for j in range(4):
    for i in range(4):
        b.flat(f"mt_{i}_{j}", i, j, 0.0, "gray" if (i, j) in ROCKS else "green")

# =================================================================
# 2. 山顶站塔: 2x2 (x 1..3, y 1..3) 两层, 塔顶平台 z=2
# =================================================================
for z0 in (0, 1):
    layer = "gray" if z0 == 0 else "green"
    for i in range(2):
        b.wall_ns(f"tw_s{z0}_{i}", 1 + i, 1.0, z0, layer)   # 南墙
        b.wall_ns(f"tw_n{z0}_{i}", 1 + i, 3.0, z0, layer)   # 北墙
    for j in range(2):
        b.wall_ew(f"tw_w{z0}_{j}", 1.0, 1 + j, z0, layer)   # 西墙
        b.wall_ew(f"tw_e{z0}_{j}", 3.0, 1 + j, z0, layer)   # 东墙
for j in range(2):
    for i in range(2):
        b.flat(f"tw_d_{i}_{j}", 1 + i, 1 + j, 2.0, "gray")  # 塔顶平台

# 驱动轮: 六边形立在平台东沿北半 (y 2..3), 正对索道
b.add("wheel", "hexagon", (3.0, 2.5, 2 + HEX_APOTHEM), (90, 0, 90), "red")
b.crest_ew("flag_w", 1.0, 1, 2.0, "yellow")                 # 平台西沿站旗
b.spire_ns("flag_n", 1, 3.0, 2.0, "purple")                 # 平台北沿尖旗

# =================================================================
# 3. 索道: 两段 30 度坡道 + 中途支架塔 (索道走 y 1..2 车道)
# =================================================================
b.ramp("rope_1", "+x", 3.0, 1, 2.0, "red")                  # 第一段: z 2 -> 1
b.wall_ew("pier", PIER_X, 1, 0, "gray")                     # 中途支架塔
b.ramp("rope_2", "+x", PIER_X, 1, 1.0, "red")               # 第二段: z 1 -> 0

# =================================================================
# 4. 山脚: 联络步道 + 3x3 站台地坪 (x 6..9, y 0..3)
# =================================================================
b.flat("path_0", 4, 1, 0.0, "gray")
b.flat("path_1", 5, 1, 0.0, "gray")
for j in range(3):
    for i in range(3):
        color = "orange" if (i + j) % 2 == 0 else "gray"
        b.flat(f"st_{i}_{j}", 6 + i, j, 0.0, color)

# =================================================================
# 5. 缆车吊舱: 1x1 舱体 (x 7..8, y 1..2) + 等边四坡尖顶
# =================================================================
b.wall_ns("car_s", 7, 1.0, 0, "red")
b.wall_ew("car_w", 7.0, 1, 0, "clear")                      # 观景舷窗
b.wall_ns("car_n", 7, 2.0, 0, "red")
b.wall_ew("car_e", 8.0, 1, 0, "yellow")
CAR_ROOF = b.hat4("car_top", 7, 1, 1.0, "red", shape="equilateral_triangle")

# =================================================================
# 6. 站台围栏: 南沿 2 片 + 东沿 1 片
# =================================================================
b.crest_ns("fn_s0", 6, 0.0, 0.0, "orange")
b.crest_ns("fn_s1", 8, 0.0, 0.0, "orange")
b.crest_ew("fn_e", 9.0, 1, 0.0, "orange")

# =================================================================
# 教程步骤 (17 步): 山顶 -> 站塔 -> 索道 -> 山脚 -> 吊舱
# =================================================================
b.step(
    "铺山顶南半: 4x4 山地的前 2 排共 8 片, 绿草甸点缀灰岩块。",
    [f"mt_{i}_{j}" for j in range(2) for i in range(4)],
    tip="山顶铺在桌面西侧 —— 索道还要向东滑下一大截。",
)
b.step(
    "铺山顶北半: 再铺 2 排共 8 片, 4x4 山地就绪。",
    [f"mt_{i}_{j}" for j in range(2, 4) for i in range(4)],
    highlight=["mt_0_1", "mt_3_1"],
    tip="每片先对准一条边再松手, 山地中间不能留缝。",
)
b.step(
    "站塔起层: 沿山地中央 2x2 区域立起第一层南墙与西墙各 2 片灰色正方形。",
    ["tw_s0_0", "tw_s0_1", "tw_w0_0", "tw_w0_1"],
    highlight=["mt_1_1", "mt_1_2"],
    tip="底边吸山地格线, 转角竖边互吸 —— 山顶站的地基。",
)
b.step(
    "第一层合围: 补北墙与东墙各 2 片, 塔身四面锁成筒。",
    ["tw_n0_0", "tw_n0_1", "tw_e0_0", "tw_e0_1"],
    highlight=["tw_s0_1", "tw_w0_1"],
    tip="四角竖边两两互吸后, 轻捏塔口应感觉整体联动。",
)
b.step(
    "站塔升到第二层: 绿色正方形沿第一层顶边再围一圈 8 片。",
    [f"tw_s1_{i}" for i in range(2)] + [f"tw_n1_{i}" for i in range(2)]
    + [f"tw_w1_{j}" for j in range(2)] + [f"tw_e1_{j}" for j in range(2)],
    highlight=["tw_s0_0", "tw_e0_0"],
    tip="上下两层竖缝对齐, 塔身升到 2 格高 —— 山顶站有了海拔。",
)
b.step(
    "铺塔顶平台: 4 片灰色方板压在第二层墙顶上 (z=2)。",
    [f"tw_d_{i}_{j}" for j in range(2) for i in range(2)],
    highlight=["tw_s1_0", "tw_n1_1"],
    tip="平台四边都坐在墙顶上, 箱形受力 —— 它要挂住整条索道。",
)
b.step(
    "挂驱动轮: 红色六边形立在平台东沿北半, 正对索道方向。",
    ["wheel"],
    highlight=["tw_d_1_1"],
    tip="底边整边吸平台沿口 —— 这就是带动缆绳的大轮盘。",
)
b.step(
    "插站旗: 平台西沿立黄色等边旗, 北沿立紫色尖旗。",
    ["flag_w", "flag_n"],
    highlight=["tw_d_0_0", "tw_d_0_1"],
    tip="山顶站落成 —— 旗子一挂, 游客就知道在哪上车。",
)
b.step(
    "架索道第一段: 先在山地东侧空地立 1 片灰色支架塔 (x=4.73 处), "
    "再把红色 30 度坡道顶边整边吸上平台东沿 (y 1..2 车道), "
    "坡尾恰好落在支架塔顶边上。",
    ["pier", "rope_1"],
    highlight=["wheel", "tw_d_1_0"],
    tip="顶边贴平台沿口、坡尾吸支架顶边 —— 两端受力才是合格的索道。",
)
b.step(
    "架索道第二段: 从支架塔顶继续向东下滑, 坡尾自然落地。",
    ["rope_2"],
    highlight=["pier", "rope_1"],
    tip="两段坡道在支架顶上排成一条直线, 这就是下山的缆绳。",
)
b.step(
    "铺联络步道: 2 片灰色方板把山地东沿与山脚站台连起来。",
    ["path_0", "path_1"],
    highlight=["mt_3_1"],
    tip="步道从山地一直铺到站台门口, 全场连成一个整体。",
)
b.step(
    "铺山脚站台西列与中列: 6 片橙灰相间的方板 (x 6..8)。",
    [f"st_{i}_{j}" for i in range(2) for j in range(3)],
    highlight=["path_1"],
    tip="站台紧贴步道东端, 橙灰棋盘就是候车区地坪。",
)
b.step(
    "补齐站台东列 3 片 —— 3x3 山脚站台就绪。",
    [f"st_2_{j}" for j in range(3)],
    highlight=["st_1_1"],
    tip="索道坡尾正好滑进站台西北角 —— 到站下车!",
)
b.step(
    "拼缆车吊舱: 站台中央立 1x1 舱体四壁, 西面用透明片当观景舷窗。",
    ["car_s", "car_w", "car_n", "car_e"],
    highlight=["st_1_1"],
    tip="四角竖边两两互吸, 红色舱体立稳在站台上。",
)
b.step(
    "盖吊舱尖顶: 4 片红色等边三角形底边吸舱顶四边, 斜棱互吸合拢成锥。",
    CAR_ROOF,
    highlight=["car_s", "car_n"],
    tip="先立两片相对的, 再补另外两片 —— 四条斜棱自锁成环。",
)
b.step(
    "装站台围栏: 南沿与东沿共 3 片橙色等边三角形, 缆车站正式运营!",
    ["fn_s0", "fn_s1", "fn_e"],
    highlight=["st_0_0", "st_2_2"],
    tip="围栏中间留出检票通道 —— 排好队, 上山看云海喽。",
)

b.finalize(
    model_id="cable_car_01",
    name="缆车站",
    name_en="Cable Car Station 01",
    description=(
        "高山交通主题: 4x4 山地上立起 2x2 两层山顶站塔, 塔顶平台东沿挂着"
        "红色六边形驱动轮, 一条 30 度索道分两段滑向山脚 —— 第一段坡尾由"
        "中途支架塔整边接住, 第二段自然落地滑进 3x3 山脚站台; 站台上停着"
        "戴等边四坡尖顶的红色缆车吊舱 (透明观景舷窗), 联络步道把全场连成"
        "一个磁力整体 —— 检票上车, 上山看云海。"
    ),
    difficulty=3,
    tags=["高山", "缆车", "交通", "索道", "进阶"],
    min_pieces=50,
    min_steps=16,
)
