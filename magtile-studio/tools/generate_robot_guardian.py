#!/usr/bin/env python3
"""生成模型 data/models/robot_01.json (机器人卫士)。

第四批模型 ③: 机器人主题 —— 全库第一台人形机器人:
两条 1x1 箱式塔腿踩在充电底座上, 髋板横跨双腿合体, 3 格宽的
箱式躯干立在髋板上; 双臂不是悬挑 —— 臂柱立在髋板外端、臂顶
托住肩板外端, 髋-臂-肩-躯干围成闭合的力学环路, 剪断任何一条
铰链线力都能绕行; 玻璃面罩的方头戴双天线, 摊开的手掌单片
平挑, 力矩正好在预算内。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 充电底座: 3 排 x 5 片平铺正方形                              15 片
  - 塔腿: 2 条 x 2 层 x 4 片墙环                                 16 片
  - 脚趾: 4 片直角三角形斜撑                                      4 片
  - 髋板: 5 片平铺正方形 (含双腿之间的桥接片)                     5 片
  - 躯干: 2 层 x 8 片墙环 (胸口能量核心 1 片黄色)                16 片
  - 臂柱: 2 条 x 2 片立墙                                         4 片
  - 肩板: 5 片 (外端 2 片由臂柱托住)                              5 片
  - 手掌: 2 片单片平挑                                            2 片
  - 方头: 墙环 4 + 顶板 1 + 天线 2                                7 片
  合计 74 片, 16 个教程步骤, 3 种磁力片形状。

几何要点:
  - 髋板外端 -> 臂柱 -> 肩板外端 -> 肩板内段 -> 躯干 -> 髋板
    构成闭合环路: 肩板外端不是悬挑, 是双端受力的短桥;
  - 手掌是全库标定过的"单片平挑"极限案例 (力矩 15 < 预算 20);
  - 臂柱平面 (x=-1 / x=4) 与躯干侧壁平面 (x=0 / x=3) 相距 1,
    互不共面, 天生零重叠。

用法: python3 tools/generate_robot_guardian.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

# =================================================================
# 1. 充电底座: 3 排 x 5 片 (x -1..4, y 0..3)
# =================================================================
for row in range(3):
    for i, x in enumerate(range(-1, 4)):
        b.flat(f"base_{row}_{i}", x, row, 0.0, "gray")

# =================================================================
# 2. 塔腿: 左腿 [0,1]x[1,2] / 右腿 [2,3]x[1,2], 各 2 层 4 片墙环
# =================================================================
for tag, lx in (("l", 0), ("r", 2)):
    for lv in (0, 1):
        b.wall_ns(f"leg_{tag}_s_{lv}", lx, 1.0, lv, "blue")
        b.wall_ns(f"leg_{tag}_n_{lv}", lx, 2.0, lv, "blue")
        b.wall_ew(f"leg_{tag}_w_{lv}", float(lx), 1, lv, "blue")
        b.wall_ew(f"leg_{tag}_e_{lv}", float(lx) + 1.0, 1, lv, "blue")

# =================================================================
# 3. 脚趾: 4 片直角三角形斜撑, 竖边吸腿脚竖边、平边吸底座拼缝
# =================================================================
b.brace("toe_lw", (0.0, 1.0, 0.0), "-y", "yellow")
b.brace("toe_le", (1.0, 1.0, 0.0), "-y", "yellow")
b.brace("toe_rw", (2.0, 1.0, 0.0), "-y", "yellow")
b.brace("toe_re", (3.0, 1.0, 0.0), "-y", "yellow")

# =================================================================
# 4. 髋板 (z=2): 5 片, 先踩双腿顶环, 再桥接裆部, 最后伸出外端
# =================================================================
b.flat("hip_l", 0, 1, 2.0, "gray")                   # 左腿顶
b.flat("hip_r", 2, 1, 2.0, "gray")                   # 右腿顶
b.flat("hip_mid", 1, 1, 2.0, "gray")                 # 裆部桥接
b.flat("hip_tip_w", -1, 1, 2.0, "gray")              # 西外端 (接臂柱)
b.flat("hip_tip_e", 3, 1, 2.0, "gray")               # 东外端

# =================================================================
# 5. 躯干 (x 0..3, y 1..2, z 2..4): 2 层 8 片墙环
# =================================================================
for lv, zlv in ((0, 2), (1, 3)):
    for i, x in enumerate(range(3)):
        color = "yellow" if (lv == 0 and x == 1) else "blue"   # 胸口能量核心
        b.wall_ns(f"to_s_{lv}_{i}", x, 1.0, zlv, color)
    for i, x in enumerate(range(3)):
        b.wall_ns(f"to_n_{lv}_{i}", x, 2.0, zlv, "blue")
    b.wall_ew(f"to_w_{lv}", 0.0, 1, zlv, "blue")
    b.wall_ew(f"to_e_{lv}", 3.0, 1, zlv, "blue")

# =================================================================
# 6. 臂柱: 立在髋板外端上 (平面 x=-1 / x=4), 各 2 片
# =================================================================
for lv in (2, 3):
    b.wall_ew(f"arm_w_{lv}", -1.0, 1, lv, "red")
for lv in (2, 3):
    b.wall_ew(f"arm_e_{lv}", 4.0, 1, lv, "red")

# =================================================================
# 7. 肩板 (z=4): 内段 3 片踩躯干墙顶, 外端 2 片由臂柱托住
# =================================================================
b.flat("sh_l", 0, 1, 4.0, "gray")
b.flat("sh_m", 1, 1, 4.0, "gray")
b.flat("sh_r", 2, 1, 4.0, "gray")
b.flat("sh_tip_w", -1, 1, 4.0, "gray")               # 西肩端 (臂柱托底)
b.flat("sh_tip_e", 3, 1, 4.0, "gray")                # 东肩端

# =================================================================
# 8. 手掌: 2 片黄色正方形单片平挑在髋板外端旁
# =================================================================
b.flat("palm_w", -2, 1, 2.0, "yellow")
b.flat("palm_e", 4, 1, 2.0, "yellow")

# =================================================================
# 9. 方头 (z 4..5): 墙环 + 顶板 + 双天线
# =================================================================
b.wall_ns("hd_s", 1, 1.0, 4, "clear")                # 玻璃面罩
b.wall_ns("hd_n", 1, 2.0, 4, "blue")
b.wall_ew("hd_w", 1.0, 1, 4, "blue")
b.wall_ew("hd_e", 2.0, 1, 4, "blue")
b.flat("hd_top", 1, 1, 5.0, "gray")
b.crest_ew("ant_w", 1.0, 1, 5.0, "red")
b.crest_ew("ant_e", 2.0, 1, 5.0, "red")

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺充电底座前排: 5 片灰色正方形沿东西向排开。",
    [f"base_0_{i}" for i in range(5)],
    tip="从西向东接龙, 机器人将踩在这块底座的中排上。",
)
b.step(
    "铺充电底座中排: 再 5 片贴着前排合拢。",
    [f"base_1_{i}" for i in range(5)],
    highlight=["base_0_0", "base_0_4"],
    tip="中排就是双腿的立足线, 长边整条互吸。",
)
b.step(
    "铺充电底座后排: 最后 5 片, 3x5 底座完工。",
    [f"base_2_{i}" for i in range(5)],
    highlight=["base_1_2"],
    tip="底座越宽, 高个子机器人越站得稳。",
)
b.step(
    "立左腿第 1 层: 4 片蓝色正方形围成 1x1 墙环, 踩在底座拼缝上。",
    ["leg_l_s_0", "leg_l_n_0", "leg_l_w_0", "leg_l_e_0"],
    highlight=["base_1_1"],
    tip="墙底整边吸底座, 转角竖边互吸 —— 箱式塔腿自锁。",
)
b.step(
    "立右腿第 1 层: 镜像再围一环, 双腿间留 1 格裆部。",
    ["leg_r_s_0", "leg_r_n_0", "leg_r_w_0", "leg_r_e_0"],
    highlight=["leg_l_s_0"],
    tip="两腿内壁相距 1 格, 髋板将从这里横跨合体。",
)
b.step(
    "装脚趾: 4 片黄色直角三角形斜撑抵住双腿前脚, 竖边吸腿角"
    "竖边、平边吸底座拼缝。",
    ["toe_lw", "toe_le", "toe_rw", "toe_re"],
    highlight=["leg_l_s_0", "leg_r_s_0"],
    tip="脚趾是最小的三角桁架, 卫士从此推不倒。",
)
b.step(
    "左腿加第 2 层: 4 片墙环整层叠上。",
    ["leg_l_s_1", "leg_l_n_1", "leg_l_w_1", "leg_l_e_1"],
    highlight=["leg_l_s_0"],
    tip="每层都是独立自锁环, 叠环成腿。",
)
b.step(
    "右腿加第 2 层: 再 4 片, 双腿齐平。",
    ["leg_r_s_1", "leg_r_n_1", "leg_r_w_1", "leg_r_e_1"],
    highlight=["leg_r_s_0", "leg_l_s_1"],
    tip="两腿同高, 髋板才放得平。",
)
b.step(
    "架髋板: 左右 2 片踩腿顶环, 中间 1 片桥接裆部, 两外端各"
    "再伸 1 片。",
    ["hip_l", "hip_r", "hip_mid", "hip_tip_w", "hip_tip_e"],
    highlight=["leg_l_s_1", "leg_r_s_1"],
    tip="髋板把双腿合成一体; 外端两片是臂柱的地基。",
)
b.step(
    "立躯干第 1 层: 8 片墙环立在髋板上, 胸口正中是黄色能量核心。",
    ["to_s_0_0", "to_s_0_1", "to_s_0_2",
     "to_n_0_0", "to_n_0_1", "to_n_0_2", "to_w_0", "to_e_0"],
    highlight=["hip_l", "hip_r"],
    tip="3 格宽的箱式躯干, 前后墙各 3 片, 东西侧壁封口。",
)
b.step(
    "立躯干第 2 层: 再 8 片墙环, 躯干到达肩高。",
    ["to_s_1_0", "to_s_1_1", "to_s_1_2",
     "to_n_1_0", "to_n_1_1", "to_n_1_2", "to_w_1", "to_e_1"],
    highlight=["to_s_0_1"],
    tip="墙底整边吸下层墙顶, 箱体逐层长高。",
)
b.step(
    "装双臂并合肩: 每侧 2 片红色臂柱踩髋板外端, 随即用 5 片"
    "肩板把臂顶与躯干墙顶锁成一体。",
    ["arm_w_2", "arm_w_3", "arm_e_2", "arm_e_3",
     "sh_l", "sh_m", "sh_r", "sh_tip_w", "sh_tip_e"],
    highlight=["hip_tip_w", "to_s_1_1"],
    tip="臂柱与肩板必须同步合拢: 髋-臂-肩-躯干闭合成环, "
        "剪断任何一条缝力都能绕行。",
)
b.step(
    "摊开手掌: 2 片黄色正方形平挑在髋板外端旁。",
    ["palm_w", "palm_e"],
    highlight=["hip_tip_w", "hip_tip_e"],
    tip="单片平挑是磁力片的力矩极限案例 —— 再多一片就会塌。",
)
b.step(
    "围方头墙环: 玻璃面罩朝南, 4 片立在肩板正中。",
    ["hd_s", "hd_n", "hd_w", "hd_e"],
    highlight=["sh_m"],
    tip="面罩用透明片 —— 卫士的眼睛要看得见前方。",
)
b.step(
    "盖头顶板: 1 片灰色正方形压住头部墙环。",
    ["hd_top"],
    highlight=["hd_s"],
    tip="顶板四边都吸墙顶, 方头自成一个刚性小箱。",
)
b.step(
    "插双天线: 2 片红色三角形立在头顶东西沿边 —— 机器人卫士"
    "上线执勤!",
    ["ant_w", "ant_e"],
    highlight=["hd_top"],
    tip="天线立在头顶板的侧边上, 信号满格。",
)

b.finalize(
    model_id="robot_01",
    name="机器人卫士",
    name_en="Robot Guardian 01",
    description=(
        "机器人主题: 全库第一台人形机器人 —— 两条箱式塔腿踩充电底座, "
        "髋板横跨双腿合体, 3 格宽箱式躯干藏着黄色能量核心; 双臂不是"
        "悬挑: 臂柱立在髋板外端、臂顶托住肩板外端, 髋-臂-肩-躯干围成"
        "闭合力学环路, 剪断任何一条铰链线力都能绕行; 摊开的手掌是单片"
        "平挑的力矩极限案例, 玻璃面罩方头戴双天线, 直角三角脚趾抵住"
        "双腿 —— 卫士上线, 全天执勤。"
    ),
    difficulty=3,
    tags=["机器人", "科技", "人形", "环路结构"],
    min_pieces=70,
    min_steps=16,
)
