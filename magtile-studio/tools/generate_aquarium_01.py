#!/usr/bin/env python3
"""生成模型 data/models/aquarium_01.json (海底隧道水族馆)。

内容批 E 模型 4/5: 全库第一座可以"走进去"的水族馆 —— 与
coral_reef (海底珊瑚礁盘) / deep_sea_lab_01 (舱体+廊道+气闸水下
基地) / car_wash_01 (两墙夹道封闭隧道) 刻意区分: 本作的结构签名
是"玻璃观景隧道从两座水缸中间穿过": 两座满墙窗格方的玻璃水缸
南北对峙, 三片透明隧道顶两短边各吸两缸内墙顶 —— 双端受力零悬挑
(云梯桥同款), 游客从西门框拱门进馆, 头顶就是水缸的水面。缸里
粉色珊瑚四坡锥静静盛开, 三条小鱼跃出水面骑在缸沿上, 东北角
一柄蓝色鲸尾高高扬起 —— 这是散场前最后一场鲸鱼表演。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 入口朝西):
  - 地坪 5x5: 广场砖 x10 + 缸底水板 x12 + 隧道地板 x3          25 片
  - 南北玻璃水缸 (x [1,4], 各 3x2): 窗格方墙环 x10 每缸         20 片
  - 玻璃隧道顶 (y [2,3], z=1): 透明方板 x3 双端受力              3 片
  - 西入口门厅: 门框方门柱 x2 + 透明门厅顶 + 馆牌红三角          4 片
  - 缸内造景: 粉色珊瑚四坡锥 x1 (4 片) + 跃水小鱼 x3 + 鲸尾 x1   8 片
  合计 60 片, 13 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 隧道顶每片南北两边分别整边吸南缸北墙顶与北缸南墙顶, 双端
    受力零悬挑 (云梯桥/过街天桥同款), 彼此再共面互吸成排;
  - 门厅顶南北吸双门柱顶, 东边与隧道顶西片共面互吸 —— 三边
    受力, 馆牌骑门厅顶西沿重心正压铰链线;
  - 水缸墙环四角竖边互咬, 墙脚全部踩在地坪拼缝上; 窗格方外框
    与正方形完全一致, 物理与拼接按实心正方形处理;
  - 珊瑚锥四棱互吸自锁且整体没进缸里 (锥尖 0.71 < 缸墙顶 1.0),
    小鱼与鲸尾骑缸沿, 迎风力矩为零。

用法: python3 tools/generate_aquarium_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

PLAZA = "gray"       # 馆外广场砖
WATER = "blue"       # 缸底水板
WALK = "gray"        # 隧道地板
GLASS = "cyan"       # 玻璃缸墙 (窗格方)
TUNNEL = "clear"     # 隧道顶 / 门厅顶
DOORP = "orange"     # 门柱 (门框方)
SIGN = "red"         # 馆牌
CORAL = "pink"       # 珊瑚
FISH_A = "orange"    # 小鱼
FISH_B = "yellow"    # 小鱼
FISH_C = "pink"      # 小鱼
WHALE = "blue"       # 鲸尾

# =================================================================
# 1. 地坪 5x5 (x [0,5], y [0,5]): 广场砖 + 缸底水板 + 隧道地板
# =================================================================
# 西列广场 (x [0,1], 含入口门厅地板)
for y in range(5):
    b.flat(f"pz_w_{y}", 0, y, 0.0, PLAZA)
# 南缸缸底 (x [1,4], y [0,2])
for x in (1, 2, 3):
    for y in (0, 1):
        b.flat(f"tf_s_{x}_{y}", x, y, 0.0, WATER)
# 隧道地板 (y [2,3])
for x in (1, 2, 3):
    b.flat(f"walk_{x}", x, 2, 0.0, WALK)
# 北缸缸底 (x [1,4], y [3,5])
for x in (1, 2, 3):
    for y in (3, 4):
        b.flat(f"tf_n_{x}_{y}", x, y, 0.0, WATER)
# 东列广场 (x [4,5])
for y in range(5):
    b.flat(f"pz_e_{y}", 4, y, 0.0, PLAZA)

# =================================================================
# 2. 南玻璃水缸 (x [1,4], y [0,2]): 窗格方墙环
# =================================================================
for x in (1, 2, 3):
    b.add(f"ts_s_{x}", "window_square", (x + 0.5, 0.0, 0.5), (90, 0, 0), GLASS)
    b.add(f"ts_n_{x}", "window_square", (x + 0.5, 2.0, 0.5), (90, 0, 0), GLASS)
for y in (0, 1):
    b.add(f"ts_w_{y}", "window_square", (1.0, y + 0.5, 0.5), (90, 0, 90), GLASS)
    b.add(f"ts_e_{y}", "window_square", (4.0, y + 0.5, 0.5), (90, 0, 90), GLASS)

# =================================================================
# 3. 北玻璃水缸 (x [1,4], y [3,5]): 窗格方墙环
# =================================================================
for x in (1, 2, 3):
    b.add(f"tn_s_{x}", "window_square", (x + 0.5, 3.0, 0.5), (90, 0, 0), GLASS)
    b.add(f"tn_n_{x}", "window_square", (x + 0.5, 5.0, 0.5), (90, 0, 0), GLASS)
for y in (3, 4):
    b.add(f"tn_w_{y}", "window_square", (1.0, y + 0.5, 0.5), (90, 0, 90), GLASS)
    b.add(f"tn_e_{y}", "window_square", (4.0, y + 0.5, 0.5), (90, 0, 90), GLASS)

# =================================================================
# 4. 玻璃隧道顶 (y [2,3], z=1): 双端受力零悬挑
# =================================================================
for x in (1, 2, 3):
    b.flat(f"roof_{x}", x, 2, 1.0, TUNNEL)

# =================================================================
# 5. 西入口门厅: 门框方门柱 + 门厅顶 + 馆牌
# =================================================================
b.add("po_s", "door_frame", (0.5, 2.0, 0.5), (90, 0, 0), DOORP)
b.add("po_n", "door_frame", (0.5, 3.0, 0.5), (90, 0, 0), DOORP)
b.flat("po_roof", 0, 2, 1.0, TUNNEL)
b.crest_ew("po_sign", 0.0, 2, 1.0, SIGN)           # 馆牌骑门厅顶西沿

# =================================================================
# 6. 缸内造景: 珊瑚锥 + 跃水小鱼 + 鲸尾
# =================================================================
b.hat4("coral", 2, 0, 0.0, CORAL, shape="equilateral_triangle")
b.crest_ns("fish_a", 1, 0.0, 1.0, FISH_A)          # 骑南缸南沿
b.crest_ns("fish_b", 3, 0.0, 1.0, FISH_B)          # 骑南缸南沿
b.crest_ns("fish_c", 2, 5.0, 1.0, FISH_C)          # 骑北缸北沿
b.spire_ew("whale_tail", 4.0, 3, 1.0, WHALE)       # 鲸尾扬到 3.0

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺西列广场砖: 五片灰色方板一字排开, 正中那格是门厅地板。",
    ["pz_w_0", "pz_w_1", "pz_w_2", "pz_w_3", "pz_w_4"],
    tip="开馆第一件事是铺好入口 —— 检票口就设在正中那格。",
)
b.step(
    "铺南缸缸底: 六片蓝色水板, 缸墙的脚全踩在这些拼缝上。",
    ["tf_s_1_0", "tf_s_1_1", "tf_s_2_0", "tf_s_2_1", "tf_s_3_0", "tf_s_3_1"],
    highlight=["pz_w_0"],
    tip="蓝色一铺, 水就'注'进来了 —— 南缸住的是热带鱼。",
)
b.step(
    "铺隧道地板与北缸缸底: 灰色步道居中, 六片水板铺北缸。",
    ["walk_1", "walk_2", "walk_3",
     "tf_n_1_3", "tf_n_1_4", "tf_n_2_3", "tf_n_2_4", "tf_n_3_3", "tf_n_3_4"],
    highlight=["tf_s_1_1"],
    tip="灰色步道两侧都是水 —— 一会儿游客就从这里穿缸而过。",
)
b.step(
    "铺东列广场砖收口: 地坪 5x5 围合完成。",
    ["pz_e_0", "pz_e_1", "pz_e_2", "pz_e_3", "pz_e_4"],
    highlight=["walk_3"],
    tip="相邻格等长边互吸 —— 整片地坪连成一体, 场馆放线完毕。",
)
b.step(
    "砌南缸南墙与西墙: 五片窗格方玻璃, 四角竖边互咬。",
    ["ts_s_1", "ts_s_2", "ts_s_3", "ts_w_0", "ts_w_1"],
    highlight=["tf_s_1_0"],
    tip="窗格方就是玻璃幕墙 —— 镂空外框照样整边吸合。",
)
b.step(
    "砌南缸北墙与东墙合环: 北墙就是隧道的南壁。",
    ["ts_n_1", "ts_n_2", "ts_n_3", "ts_e_0", "ts_e_1"],
    highlight=["walk_1"],
    tip="闭环玻璃缸比单面墙稳得多 —— 它还要托半边隧道顶。",
)
b.step(
    "砌北缸南墙与西墙: 南墙就是隧道的北壁。",
    ["tn_s_1", "tn_s_2", "tn_s_3", "tn_w_3", "tn_w_4"],
    highlight=["walk_2"],
    tip="两道缸墙隔出一条 1 格宽的走廊 —— 隧道的雏形出来了。",
)
b.step(
    "砌北缸北墙与东墙合环: 双缸对峙, 就差一片天。",
    ["tn_n_1", "tn_n_2", "tn_n_3", "tn_e_3", "tn_e_4"],
    highlight=["tn_s_1"],
    tip="第二座玻璃缸合环 —— 南北双缸的内墙顶等高等距。",
)
b.step(
    "盖玻璃隧道顶: 三片透明方板, 南北两边各吸一缸内墙顶。",
    ["roof_1", "roof_2", "roof_3"],
    highlight=["ts_n_2", "tn_s_2"],
    tip="双端受力零悬挑 —— 从今天起, 头顶就是水面。",
)
b.step(
    "立入口门厅: 双门框方门柱 + 透明门厅顶 + 馆牌骑顶西沿。",
    ["po_s", "po_n", "po_roof", "po_sign"],
    highlight=["pz_w_2", "roof_1"],
    tip="门厅顶东边与隧道顶共面互吸 —— 检票进门直通海底。",
)
b.step(
    "种缸内珊瑚: 粉色四坡锥四棱互吸, 整棵没进南缸水里。",
    ["coral_s", "coral_e", "coral_n", "coral_w"],
    highlight=["tf_s_2_0"],
    tip="锥尖 0.71 比缸墙顶还低 —— 从隧道里仰头看正好。",
)
b.step(
    "放三条跃水小鱼: 橙黄粉各一条, 骑在缸沿上跃出水面。",
    ["fish_a", "fish_b", "fish_c"],
    highlight=["ts_s_1"],
    tip="小鱼重心正压缸沿铰链线 —— 定格在跃出水面的一瞬间。",
)
b.step(
    "扬起鲸尾: 蓝色等腰大尾鳍骑上北缸东墙顶, 直上 3.0 全场制高!",
    ["whale_tail"],
    highlight=["tn_e_3"],
    tip="散场前最后一场鲸鱼表演 —— 大尾巴拍下来水花四溅!",
)

b.finalize(
    model_id="aquarium_01",
    name="海底隧道水族馆",
    name_en="Aquarium Tunnel 01",
    description=(
        "只用核心九片型的水族馆, 结构签名是'玻璃观景隧道从两座水缸"
        "中间穿过': 两座满墙窗格方的玻璃水缸南北对峙 (墙环四角竖边"
        "互咬, 缸底蓝色水板), 三片透明隧道顶南北两边分别整边吸住两缸"
        "内墙顶 —— 双端受力零悬挑, 游客从西端门框方拱门进馆, 头顶"
        "就是水缸的水面; 缸里粉色珊瑚四坡锥静静盛开 (锥尖没进水线), "
        "三条小鱼骑缸沿跃出水面, 东北角蓝色鲸尾直上 3.0 高高扬起 —— "
        "这是散场前最后一场鲸鱼表演!"
    ),
    difficulty=3,
    tags=["海洋", "水族馆", "观景隧道", "亲子", "挑战"],
    min_pieces=60,
    min_steps=13,
)
