#!/usr/bin/env python3
"""生成模型 data/models/rice_terrace_01.json (梯田稻香)。

农场/农业主题批 1/4: 全库第一座"山坡即建筑"的梯田景观 —— 与
farm_barn_01 (谷仓房屋) / farm_silo_01 (双塔) / greenhouse_01
(玻璃房) 刻意区分, 本作没有"主体建筑", 整个模型就是一面被田坎
雕出来的山坡: 三级水田沿 y 轴逐级抬升 (z=0 / z=1 / z=2), 每一级
都是"土坎墙合环 + 田面压顶"的箱形梯级 —— 上一级的田面就是
下一级的屋顶; 青色水面上三排绿秧苗骑缝而立, 30 度田埂坡道从
村口爬上二级田, 登田石阶盒再上三级 (与三级田坎共墙), 田头一间
红墙黄顶的农舍守着全场最高点 (顶尖 3.71) —— 春耕水满, 山坡
一层层绿上去。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 山坡朝南):
  - 一级水田 (y [0,2], z=0): 长板 x2 + 方板 x6                  8 片
  - 一级秧苗: 绿色等边三角 x4 骑 y=1 水面拼缝                   4 片
  - 二级田坎 (z 0..1): 土坎墙合环 x16                          16 片
  - 二级田面 (z=1): 方板 x8 + 长板 x3 压顶                     11 片
  - 二级秧苗 x3 + 田埂坡道 x1 (30 度, 坡尾落回一级)             4 片
  - 登田石阶盒 (z 1..2): 墙 x3 (北墙借三级田坎) + 阶顶 x1       4 片
  - 三级田坎 (z 1..2): 土坎墙合环 x12                          12 片
  - 三级田面 (z=2): 方板 x5 压顶 + 秧苗 x2                      7 片
  - 农舍 (z 2..3.71): 门框方 + 窗格方 x2 + 方墙 + 四坡顶 x4     8 片
  合计 74 片, 15 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 梯级箱形: 每级田坎四面合环 (四角竖边互吸), 田面方板压顶
    多铰链互为保险 —— 剪断任意一条拼缝线仍有旁路传力;
  - 田埂坡道: 顶边整边吸二级田坎南墙顶 (铰链), 坡尾落地生根
    (z=0 接地斜撑, 光伏板同款受力) —— 中层绝不悬空搭板;
  - 登田石阶盒: 与三级田坎南墙共墙成环, 阶顶南北两边"自家墙顶
    + 三级坎顶"双吸;
  - 秧苗骑缝: 底边落在两片田面的公共拼缝上 (一缝双吸), 重心
    正压铰链线力矩为零。

用法: python3 tools/generate_rice_terrace_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

WATER = "cyan"       # 灌满水的田面
BUND = "orange"      # 夯土田坎
PATH = "gray"        # 田埂路 / 石阶 / 石基
SPROUT = "green"     # 秧苗
HUT = "red"          # 农舍墙
ROOF = "yellow"      # 农舍稻草顶

# =================================================================
# 1. 一级水田 (x [0,5], y [0,2], z=0): 南半长板铺水, 北半方板咬缝
#    (北行必须是方板: 二级田坎南墙与秧苗都要吸它的单位边)。
# =================================================================
b.flat_rect("p1_s_a", 0, 0, 0.0, WATER)            # 南行 [0,2]
b.flat_rect("p1_s_b", 2, 0, 0.0, WATER)            # 南行 [2,4]
b.flat("p1_s_c", 4, 0, 0.0, PATH)                  # 南行村口 (坡道落脚)
b.flat("p1_n_0", 0, 1, 0.0, WATER)
b.flat("p1_n_1", 1, 1, 0.0, WATER)
b.flat("p1_n_2", 2, 1, 0.0, WATER)
b.flat("p1_n_3", 3, 1, 0.0, WATER)
b.flat("p1_n_4", 4, 1, 0.0, PATH)                  # 田埂路 (坡道躺这条道上)

# 一级秧苗: 4 株骑 y=1 水面拼缝 (底边整边吸北行方板南边)
for x in range(4):
    b.crest_ns(f"rice1_{x}", x, 1.0, 0.0, SPROUT)

# =================================================================
# 2. 二级田坎 (y [2,5], z 0..1): 土坎墙四面合环 x16
# =================================================================
for x in range(5):
    b.wall_ns(f"t2_s_{x}", x, 2.0, 0, BUND)        # 南坎 (临一级水田)
    b.wall_ns(f"t2_n_{x}", x, 5.0, 0, BUND)        # 北坎
for y in range(2, 5):
    b.wall_ew(f"t2_w_{y}", 0.0, y, 0, BUND)        # 西坎
    b.wall_ew(f"t2_e_{y}", 5.0, y, 0, BUND)        # 东坎

# =================================================================
# 3. 二级田面 (z=1): 压顶封箱 —— 中行方板咬缝 (秧苗/石阶要用),
#    南北两行长板省料。
# =================================================================
b.flat_rect("f2_s_a", 0, 2, 1.0, WATER)            # 南行 [0,2]
b.flat_rect("f2_s_b", 2, 2, 1.0, WATER)            # 南行 [2,4]
b.flat("f2_s_c", 4, 2, 1.0, PATH)                  # 坡道上来的落脚位
for x in range(4):
    b.flat(f"f2_m_{x}", x, 3, 1.0, WATER)          # 中行方板
b.flat("f2_m_4", 4, 3, 1.0, PATH)                  # 石阶盒的基座
b.flat_rect("f2_n_a", 0, 4, 1.0, PATH)             # 北行 [0,2] (三级石基)
b.flat_rect("f2_n_b", 2, 4, 1.0, PATH)             # 北行 [2,4]
b.flat("f2_n_c", 4, 4, 1.0, PATH)

# 二级秧苗: 3 株骑 y=3 拼缝 (底边吸中行方板南边)
for x in range(3):
    b.crest_ns(f"rice2_{x}", x, 3.0, 1.0, SPROUT)

# 田埂坡道: 顶边整边吸二级南坎墙顶 (x [4,5]), 坡尾落地 y=0.27
b.ramp("ramp1", "-y", 2.0, 4, 1.0, PATH)

# =================================================================
# 4. 登田石阶盒 (x [4,5], y [3,4], z 1..2): 南/西/东三面墙 +
#    阶顶, 北墙借三级田坎南墙共墙成环。
# =================================================================
b.wall_ns("st_s", 4, 3.0, 1, PATH)
b.wall_ew("st_w", 4.0, 3, 1, PATH)
b.wall_ew("st_e", 5.0, 3, 1, PATH)
b.flat("st_top", 4, 3, 2.0, PATH)                  # 阶顶 (南吸自家墙, 北吸三级坎)

# =================================================================
# 5. 三级田坎 (y [4,5], z 1..2): 南墙立二级田面上, 北墙叠二级
#    北坎顶, 西东单墙合环。
# =================================================================
for x in range(5):
    b.wall_ns(f"t3_s_{x}", x, 4.0, 1, BUND)
    b.wall_ns(f"t3_n_{x}", x, 5.0, 1, BUND)
b.wall_ew("t3_w", 0.0, 4, 1, BUND)
b.wall_ew("t3_e", 5.0, 4, 1, BUND)

# =================================================================
# 6. 三级田面 (z=2) + 秧苗 x2
# =================================================================
b.flat("f3_0", 0, 4, 2.0, WATER)
b.flat("f3_1", 1, 4, 2.0, WATER)
b.flat("f3_2", 2, 4, 2.0, PATH)                    # 农舍地基
b.flat("f3_3", 3, 4, 2.0, WATER)
b.flat("f3_4", 4, 4, 2.0, PATH)                    # 石阶上来的场院
b.crest_ew("rice3_a", 1.0, 4, 2.0, SPROUT)         # 骑 x=1 拼缝
b.crest_ew("rice3_b", 4.0, 4, 2.0, SPROUT)         # 骑 x=4 拼缝

# =================================================================
# 7. 农舍 (x [2,3], y [4,5], z 2..3): 门朝南 + 双侧窗 + 四坡顶
# =================================================================
b.add("hut_s", "door_frame", (2.5, 4.0, 2.5), (90, 0, 0), HUT)
b.add("hut_w", "window_square", (2.0, 4.5, 2.5), (90, 0, 90), HUT)
b.add("hut_e", "window_square", (3.0, 4.5, 2.5), (90, 0, 90), HUT)
b.wall_ns("hut_n", 2, 5.0, 2, HUT)
b.hat4("hut_hat", 2, 4, 3.0, ROOF, shape="equilateral_triangle")

# =================================================================
# 教程步骤 (15 步)
# =================================================================
b.step(
    "铺一级水田南半: 2 片青色长板灌满水, 村口留一格灰色石板。",
    ["p1_s_a", "p1_s_b", "p1_s_c"],
    tip="梯田从山脚往上搭 —— 最低的一级水田先蓄水。",
)
b.step(
    "铺一级水田北半: 5 片方板咬缝合拢, 东端灰色是田埂路。",
    ["p1_n_0", "p1_n_1", "p1_n_2", "p1_n_3", "p1_n_4"],
    highlight=["p1_s_a", "p1_s_c"],
    tip="北行必须用方板: 二级田坎与秧苗都要吸它的单位边。",
)
b.step(
    "插一级秧苗: 4 株绿色等边三角骑上 y=1 水面拼缝。",
    ["rice1_0", "rice1_1", "rice1_2", "rice1_3"],
    highlight=["p1_n_0", "p1_n_3"],
    tip="底边一缝双吸、重心正压铰链线 —— 秧苗比看起来站得稳。",
)
b.step(
    "砌二级南坎: 5 片橙色土坎墙沿 y=2 立起, 墙脚吸一级田北边。",
    [f"t2_s_{x}" for x in range(5)],
    highlight=["p1_n_0", "p1_n_4"],
    tip="相邻坎墙竖边互咬 —— 整面坎比单片墙稳得多。",
)
b.step(
    "砌二级侧坎: 西东各 3 片, 与南坎四角竖边互吸。",
    ["t2_w_2", "t2_w_3", "t2_w_4", "t2_e_2", "t2_e_3", "t2_e_4"],
    highlight=["t2_s_0", "t2_s_4"],
    tip="拐角一咬, 田坎就从'一面墙'变成了'一圈箱'。",
)
b.step(
    "砌二级北坎: 5 片合环, 第二级梯级的土箱围好了。",
    [f"t2_n_{x}" for x in range(5)],
    highlight=["t2_w_4", "t2_e_4"],
    tip="四面合环处处成圈 —— 剪断任何一条缝都塌不了。",
)
b.step(
    "铺二级田面南半: 长板 + 方板压顶, 东端灰格是坡道的落脚位。",
    ["f2_s_a", "f2_s_b", "f2_s_c", "f2_m_0", "f2_m_1", "f2_m_2", "f2_m_3", "f2_m_4"],
    highlight=["t2_s_0", "t2_s_4"],
    tip="田面就是土箱的盖子 —— 南边吸坎顶, 相邻板互咬。",
)
b.step(
    "铺二级田面北半: 3 片灰色石基压顶封箱 (三级田坎要踩它)。",
    ["f2_n_a", "f2_n_b", "f2_n_c"],
    highlight=["f2_m_0", "f2_m_4"],
    tip="第二级台面合拢 —— 上一级的田面就是下一级的屋顶。",
)
b.step(
    "插二级秧苗 + 架田埂坡道: 3 株骑 y=3 拼缝, 30 度坡道顶边"
    "吸南坎墙顶、坡尾落回一级田埂。",
    ["rice2_0", "rice2_1", "rice2_2", "ramp1"],
    highlight=["t2_s_4", "p1_n_4"],
    tip="顶铰链 + 接地斜撑 —— 人越踩, 坡道贴得越紧。",
)
b.step(
    "砌登田石阶盒: 南/西/东三面灰墙立二级田面上, 阶顶压住。",
    ["st_s", "st_w", "st_e", "st_top"],
    highlight=["f2_m_4"],
    tip="石阶盒的北墙先空着 —— 一会儿三级田坎来补, 共墙成环。",
)
b.step(
    "砌三级南坎: 5 片土坎墙沿 y=4 立在二级石基上 (x=4 那片就是"
    "石阶盒的北墙)。",
    [f"t3_s_{x}" for x in range(5)],
    highlight=["st_top", "f2_n_a"],
    tip="一墙两用: 既是三级的坎, 又是石阶盒的第四面。",
)
b.step(
    "砌三级北坎与侧坎: 北排 5 片叠上二级北坎顶, 西东单墙合环。",
    [f"t3_n_{x}" for x in range(5)] + ["t3_w", "t3_e"],
    highlight=["t3_s_0", "t2_n_0"],
    tip="上下两圈坎在山背面叠成 2 格高的整面崖 —— 这就是梯田的断面。",
)
b.step(
    "铺三级田面: 5 片方板压顶, 灰色两格是农舍地基与场院。",
    ["f3_0", "f3_1", "f3_2", "f3_3", "f3_4"],
    highlight=["t3_s_0", "t3_n_4"],
    tip="最高一级封顶 —— 从石阶上来, 全村的水田都在脚下。",
)
b.step(
    "插三级秧苗 + 立农舍墙: 秧苗骑田面拼缝; 门框方朝南、双侧"
    "窗格方、北面方墙围出 1x1 农舍。",
    ["rice3_a", "rice3_b", "hut_s", "hut_w", "hut_e", "hut_n"],
    highlight=["f3_2"],
    tip="农舍四角竖边互吸自锁 —— 开门就能望见整面山坡。",
)
b.step(
    "盖农舍稻草顶: 4 片黄色等边三角四坡收尖 (顶尖 3.71 全场最高)。",
    ["hut_hat_s", "hut_hat_e", "hut_hat_n", "hut_hat_w"],
    highlight=["hut_s"],
    tip="四条斜棱两两互吸自锁成环 —— 春耕水满, 山坡一层层绿上去!",
)

b.finalize(
    model_id="rice_terrace_01",
    name="梯田稻香",
    name_en="Rice Terrace 01",
    description=(
        "只用核心九片型的梯田景观: 整个模型就是一面被田坎雕出来的"
        "山坡 —— 三级水田沿山坡逐级抬升, 每一级都是'土坎墙四面合环"
        " + 田面压顶'的箱形梯级, 上一级的田面就是下一级的屋顶, 上下"
        "两圈坎在山背面叠成 2 格高的整面崖; 30 度田埂坡道顶边吸坎顶、"
        "坡尾落地生根 (顶铰链 + 接地斜撑), 登田石阶盒与三级田坎共墙"
        "成环, 阶顶两边双吸; 青色水面上三排绿秧苗骑缝而立 (一缝双吸"
        "零力矩), 田头红墙黄顶农舍守着全场最高点 (顶尖 3.71) —— 春耕"
        "水满, 山坡一层层绿上去。"
    ),
    difficulty=3,
    tags=["田园", "农场", "农业", "梯田", "进阶"],
    min_pieces=74,
    min_steps=15,
)
