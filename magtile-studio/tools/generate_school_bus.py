#!/usr/bin/env python3
"""生成模型 data/models/school_bus_01.json (校车).

城市街景载具主题: 全库最长的公路车辆 —— 三轴六轮的大鼻子校车:
前轴一对、后双轴四只车轮底座 (wheel_base) 托起 8 格长的橙色底盘,
一层黄色车身嵌门框方乘客门, 二层整圈 16 扇窗格方车窗一字排开,
车头两片透明挡风、车尾两扇后窗, 16 片方板拼出大平顶。人行道上
立着红顶站牌 —— 叮叮, 校车进站, 请排队上车!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 车头朝东):
  - 街道三排 + 人行道                                     26 片
  - 车轮底座 x6 (前轴一对 + 后双轴两对)                    6 片
  - 底盘长板 x8 (4x2, 长边整边压轮组顶)                    8 片
  - 一层车身: 黄方墙 x15 + 门框方 x1 + 首尾墙 x4          20 片
  - 二层车窗: 窗格方 x18 + 挡风玻璃 x2                    20 片
  - 车顶方板 x16                                          16 片
  - 站牌 (方板 + 红三角)                                   2 片
  合计 98 片, 18 个教程步骤, 6 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验, 常规+strict 双档):
  - 底盘长板长边整边吸轮组顶 (力臂零), 六轮任断其一,
    其余五轮仍托得住 —— 无单点失效;
  - 一层墙身经首尾角墙竖边受力链落底盘短边, 墙链逐片
    竖边互吸; 二层窗格方底边整边吸一层墙顶 (单位边对单位边);
  - 车顶用 16 片方板而不是长板 —— 每片南北边都能整边吸住
    窗顶, 顶盖与两侧窗墙锁成连续箱形环。

用法: python3 tools/generate_school_bus.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

ROAD = "gray"
WALK = "pink"
WHEEL = "gray"
CHASSIS = "orange"   # 底盘裙边
BODY = "yellow"      # 校车黄
WIN = "clear"        # 车窗
GLASS = "clear"      # 挡风

# =================================================================
# 1. 街道 [0,10]x[0,3] + 人行道 [0,10]x[3,4]
#    车道行序 方板+长板x4+方板: 拼缝给六只车轮当吸附线
# =================================================================
for row, y in (("r0", 0), ("r1", 1), ("r2", 2)):
    b.flat(f"{row}_a", 0, y, 0.0, ROAD)
    b.flat_rect(f"{row}_b", 1, y, 0.0, ROAD)
    b.flat_rect(f"{row}_c", 3, y, 0.0, ROAD)
    b.flat_rect(f"{row}_d", 5, y, 0.0, ROAD)
    b.flat_rect(f"{row}_e", 7, y, 0.0, ROAD)
    b.flat(f"{row}_f", 9, y, 0.0, ROAD)
b.flat_rect("wk_a", 0, 3, 0.0, WALK)
for i in range(6):
    b.flat(f"wk_{i}", 2 + i, 3, 0.0, WALK)
b.flat_rect("wk_b", 8, 3, 0.0, WALK)

# =================================================================
# 2. 车轮底座 x6: 前轴 x[7,9], 后双轴 x[1,3] 与 [3,5]
# =================================================================
b.add("wh_f_s", "wheel_base", (8.0, 1.0, 0.5), (90, 0, 0), WHEEL)
b.add("wh_f_n", "wheel_base", (8.0, 3.0, 0.5), (90, 0, 0), WHEEL)
b.add("wh_r1_s", "wheel_base", (2.0, 1.0, 0.5), (90, 0, 0), WHEEL)
b.add("wh_r1_n", "wheel_base", (2.0, 3.0, 0.5), (90, 0, 0), WHEEL)
b.add("wh_r2_s", "wheel_base", (4.0, 1.0, 0.5), (90, 0, 0), WHEEL)
b.add("wh_r2_n", "wheel_base", (4.0, 3.0, 0.5), (90, 0, 0), WHEEL)

# =================================================================
# 3. 底盘 z=1: 4x2 长板, 长边整边压轮组顶
# =================================================================
for x0 in (1, 3, 5, 7):
    b.flat_rect(f"ch_s_{x0}", x0, 1, 1.0, CHASSIS)
    b.flat_rect(f"ch_n_{x0}", x0, 2, 1.0, CHASSIS)

# =================================================================
# 4. 一层车身 z1..2: 首尾角墙先立, 墙链竖边互吸;
#    南墙 x=7 格嵌门框方乘客门
# =================================================================
b.wall_ew("w1_w0", 1.0, 1, 1, BODY)                # 车尾墙
b.wall_ew("w1_w1", 1.0, 2, 1, BODY)
for x in range(1, 7):
    b.wall_ns(f"w1_s{x}", x, 1.0, 1, BODY)         # 南墙 x=1..7
b.wall_ns("w1_s7", 7, 1.0, 1, BODY)
b.add("w1_door", "door_frame", (8.5, 1.0, 1.5), (90, 0, 0), BODY)
b.wall_ew("w1_e0", 9.0, 1, 1, BODY)                # 车头墙
b.wall_ew("w1_e1", 9.0, 2, 1, BODY)
for x in range(1, 9):
    b.wall_ns(f"w1_n{x}", x, 3.0, 1, BODY)         # 北墙 x=1..9

# =================================================================
# 5. 二层车窗 z2..3: 窗格方整圈 + 车头挡风玻璃
# =================================================================
b.add("w2_w0", "window_square", (1.0, 1.5, 2.5), (90, 0, 90), WIN)
b.add("w2_w1", "window_square", (1.0, 2.5, 2.5), (90, 0, 90), WIN)
b.add("w2_e0", "square", (9.0, 1.5, 2.5), (90, 0, 90), GLASS)
b.add("w2_e1", "square", (9.0, 2.5, 2.5), (90, 0, 90), GLASS)
for x in range(1, 9):
    b.add(f"w2_s{x}", "window_square", (x + 0.5, 1.0, 2.5), (90, 0, 0), WIN)
for x in range(1, 9):
    b.add(f"w2_n{x}", "window_square", (x + 0.5, 3.0, 2.5), (90, 0, 0), WIN)

# =================================================================
# 6. 车顶 z=3: 16 片方板, 南北边整边吸窗顶
# =================================================================
for x in range(1, 9):
    b.flat(f"rf_s{x}", x, 1, 3.0, BODY)
    b.flat(f"rf_n{x}", x, 2, 3.0, BODY)

# =================================================================
# 7. 站牌: 人行道上方板立柱 + 红色站牌三角
# =================================================================
b.wall_ns("stop_pole", 6, 4.0, 0, "clear")
b.crest_ns("stop_sign", 6, 4.0, 1.0, "red")

# =================================================================
# 教程步骤 (18 步)
# =================================================================
b.step(
    "南车道: 方板+长板 x4+方板 铺出第一排, 四条长板拼缝就是"
    "六只车轮的吸附线。",
    ["r0_a", "r0_b", "r0_c", "r0_d", "r0_e", "r0_f"],
    tip="校车有 10 格长 —— 这是全库最长的公路车辆。",
)
b.step(
    "公交车道: 同样板序再铺一排, 校车就停这排。",
    ["r1_a", "r1_b", "r1_c", "r1_d", "r1_e", "r1_f"],
    highlight=["r0_b", "r0_e"],
)
b.step(
    "北车道: 第三排合拢, 路面完工。",
    ["r2_a", "r2_b", "r2_c", "r2_d", "r2_e", "r2_f"],
    highlight=["r1_a", "r1_f"],
)
b.step(
    "人行道: 两端长砖、中段 x=2~8 六块粉色方砖 —— 站牌要立在"
    "方砖格边上。",
    ["wk_a", "wk_0", "wk_1", "wk_2", "wk_3", "wk_4", "wk_5", "wk_b"],
    highlight=["r2_b", "r2_e"],
)
b.step(
    "前轴车轮: 一对车轮底座立在 x=7~9 拼缝上 (y=1 与 y=3 线)。",
    ["wh_f_s", "wh_f_n"],
    highlight=["r0_e", "r1_e"],
    tip="车轮底座一片顶两格, 底边整边咬住路缝。",
)
b.step(
    "后双轴: 两对车轮吸 x=1~3 与 x=3~5 拼缝 —— 校车屁股沉, "
    "后面要四只轮子扛。",
    ["wh_r1_s", "wh_r1_n", "wh_r2_s", "wh_r2_n"],
    highlight=["wh_f_s", "wh_f_n"],
)
b.step(
    "底盘西半: 4 片橙色长板长边整边压后双轴轮顶。",
    ["ch_s_1", "ch_n_1", "ch_s_3", "ch_n_3"],
    highlight=["wh_r1_s", "wh_r2_n"],
    tip="长边对轮顶, 力臂为零 —— 底盘稳稳架空。",
)
b.step(
    "底盘东半: 再铺 4 片, 4x2 底盘合拢, 东端压前轴轮顶。",
    ["ch_s_5", "ch_s_7", "ch_n_5", "ch_n_7"],
    highlight=["ch_s_3", "wh_f_n"],
)
b.step(
    "车尾与南墙西段: 车尾两片角墙竖边吸底盘短边, 南墙从西向东"
    "逐片竖边互吸链到 x=5。",
    ["w1_w0", "w1_w1", "w1_s1", "w1_s2", "w1_s3", "w1_s4"],
    highlight=["ch_s_1", "ch_n_1"],
    tip="先立角墙再链墙 —— 每片新墙都吸得住前一片。",
)
b.step(
    "南墙东段与乘客门: 墙链续到 x=8, 嵌入门框方乘客门, 车头"
    "两片角墙合拢。",
    ["w1_s5", "w1_s6", "w1_s7", "w1_door", "w1_e0", "w1_e1"],
    highlight=["w1_s4", "ch_s_7"],
    tip="门框方就是上下车的门 —— 叮叮, 前门上车。",
)
b.step(
    "北墙西段: 从车尾角墙向东链 4 片。",
    ["w1_n1", "w1_n2", "w1_n3", "w1_n4"],
    highlight=["w1_w1"],
)
b.step(
    "北墙东段: 再链 4 片到车头, 一层车身围合。",
    ["w1_n5", "w1_n6", "w1_n7", "w1_n8"],
    highlight=["w1_n4", "w1_e1"],
)
b.step(
    "车尾后窗与车头挡风: 尾部 2 扇窗格方、头部 2 片透明方板"
    "竖立第二层, 底边整边吸一层墙顶。",
    ["w2_w0", "w2_w1", "w2_e0", "w2_e1"],
    highlight=["w1_w0", "w1_e0"],
)
b.step(
    "南侧车窗: 8 扇窗格方一字排开, 底边逐扇吸南墙顶。",
    ["w2_s1", "w2_s2", "w2_s3", "w2_s4", "w2_s5", "w2_s6", "w2_s7", "w2_s8"],
    highlight=["w1_s1", "w1_door"],
    tip="每扇窗一个座位 —— 靠窗的位子最抢手。",
)
b.step(
    "北侧车窗: 再排 8 扇, 二层整圈车窗合拢。",
    ["w2_n1", "w2_n2", "w2_n3", "w2_n4", "w2_n5", "w2_n6", "w2_n7", "w2_n8"],
    highlight=["w2_s1", "w2_s8"],
)
b.step(
    "车顶南列: 8 片黄色方板盖上 z=3, 南边整边压南窗顶。",
    ["rf_s1", "rf_s2", "rf_s3", "rf_s4", "rf_s5", "rf_s6", "rf_s7", "rf_s8"],
    highlight=["w2_s1", "w2_s8"],
)
b.step(
    "车顶北列: 再盖 8 片, 大平顶合拢 —— 顶盖与两侧窗墙锁成"
    "连续箱形环。",
    ["rf_n1", "rf_n2", "rf_n3", "rf_n4", "rf_n5", "rf_n6", "rf_n7", "rf_n8"],
    highlight=["rf_s1", "w2_n8"],
)
b.step(
    "校车站牌: 人行道上立透明方板立柱, 顶上戴红色站牌三角 —— "
    "校车进站, 请排队上车!",
    ["stop_pole", "stop_sign"],
    highlight=["wk_4"],
)

b.finalize(
    model_id="school_bus_01",
    name="校车",
    name_en="School Bus 01",
    description=(
        "全库最长的公路车辆: 三轴六轮大鼻子校车 —— 前轴一对、后双轴"
        "四只车轮底座托起 8 格长的橙色底盘 (长边整边压轮顶, 六轮断一"
        "仍稳), 一层黄色车身嵌门框方乘客门, 二层 16 扇窗格方车窗整圈"
        "一字排开, 车头透明挡风、车尾两扇后窗, 16 片方板大平顶与两侧"
        "窗墙锁成连续箱形环; 人行道红顶站牌立在格边上 —— 叮叮, 校车"
        "进站, 请排队上车!"
    ),
    difficulty=4,
    tags=["校车", "城市", "载具", "交通", "车轮底座"],
    min_pieces=95,
    min_steps=18,
)
