#!/usr/bin/env python3
"""生成模型 data/models/peacock_01.json (开屏孔雀)。

内容批 F 模型 2/4: 全库第一只孔雀 —— 动物家族里 owl (箱体猫头鹰) /
penguin (企鹅) / panda_bamboo (坐姿熊猫) 都是"胖箱体"造型, 还没有
一只动物把"一面墙"当作身体的主角。结构签名是"独立阶梯扇墙开屏":
尾屏是一面 5 格宽的独立立墙, 墙高从两端向中央 1-2-3-2-1 递增,
五片彩色眼斑三角分别骑在五级阶梯的顶沿, 展开成对称的大扇子;
扇墙靠两条路站稳 —— 身箱与扇墙中央共用一面墙 (身体顶住尾屏),
再加四条直角三角斜撑在墙后双边吸合 (T14, 摩天大楼同款), 与
tessellation_screen (密铺屏风, 无身体无斜撑) / great_wall (城墙
带敌楼) 的结构逻辑全部错开。头顶瘦高冠羽 + 窗格方孔雀脸。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 尾屏朝北, 头朝南):
  - 草坪与水塘 4 行 (x [0,5], y [0,4])                        18 片
  - 尾屏扇墙 (y=3 立面): 阶梯墙 1-2-3-2-1 共 9 片
    + 五片眼斑三角骑阶梯顶沿                                  14 片
  - 扇墙斜撑 x4: 直角三角在墙后双边吸合                        4 片
  - 身箱 (x [2,3], y [1,3]): 五面墙 (北墙与扇墙共用) + 双盖板  7 片
  - 头颈 (x [2,3], y [1,2], z 1..2): 窗格方孔雀脸 + 三墙
    + 顶板 + 橙喙 + 金色瘦高冠羽                               7 片
  合计 50 片, 12 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告 + jitter 全绿):
  - 扇墙每片与左右邻居竖边互吸、与下层墙顶整边共线吸合;
  - 身箱北墙就是扇墙中央底格 —— 身体与尾屏互为支撑;
  - 四条斜撑水平直角边吸地板拼缝、竖直直角边吸扇墙竖缝, 双边受力;
  - 眼斑三角/冠羽/橙喙全部骑整边沿口, 地板拼缝纪律同前批。

用法: python3 tools/generate_peacock_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

LAWN = "green"      # 草坪
POND = "cyan"       # 水塘
FAN_LOW = "green"   # 扇墙一层
FAN_MID = "cyan"    # 扇墙二层
FAN_TOP = "blue"    # 扇墙三层
EYE_A = "purple"    # 眼斑三角 (外侧)
EYE_B = "pink"      # 眼斑三角 (内侧)
EYE_C = "yellow"    # 眼斑三角 (中央)
BRACE = "green"     # 斜撑
BODY = "blue"       # 身箱
HEAD = "blue"       # 头颈
FACE = "cyan"       # 窗格方孔雀脸
BEAK = "orange"     # 橙喙
CROWN = "yellow"    # 冠羽

# 扇墙高度型线 (西 -> 东): 1-2-3-2-1
HEIGHTS = [1, 2, 3, 2, 1]

# =================================================================
# 1. 草坪与水塘 4 行 (x [0,5], y [0,4])
# =================================================================
# 扇墙后行 (y [3,4]): 五片单位方板, 斜撑的水平脚踩这行拼缝
for x in range(5):
    b.flat(f"g3_{x}", x, 3, 0.0, LAWN)
# 扇墙前行 (y [2,3]): 五片单位方板, 扇墙底边落在 y=3 拼缝
for x in range(5):
    b.flat(f"g2_{x}", x, 2, 0.0, LAWN)
# 身箱行 (y [1,2]): 身箱脚方板 + 东侧水塘
b.flat("g1_0", 0, 1, 0.0, LAWN)
b.flat("g1_1", 1, 1, 0.0, LAWN)
b.flat("g1_2", 2, 1, 0.0, LAWN)
b.flat("g1_3", 3, 1, 0.0, LAWN)
b.flat("g1_4", 4, 1, 0.0, POND)
# 前行 (y [0,1]): 草坪长板 + 头前方板 + 水塘长板
b.flat_rect("g0_w", 0, 0, 0.0, LAWN)
b.flat("g0_2", 2, 0, 0.0, LAWN)
b.flat_rect("g0_e", 3, 0, 0.0, POND)

# =================================================================
# 2. 尾屏扇墙一层 (y=3 立面, z 0..1): 五格一字排开
# =================================================================
for k in range(5):
    b.wall_ns(f"fan{k}_0", k, 3.0, 0, FAN_LOW)

# =================================================================
# 3. 扇墙斜撑 x4: 墙后双边吸合 (水平边吸地缝, 竖直边吸墙竖缝)
# =================================================================
b.brace("brace_w", (0.0, 3.0, 0.0), "+y", BRACE)
b.brace("brace_cw", (2.0, 3.0, 0.0), "+y", BRACE)
b.brace("brace_ce", (3.0, 3.0, 0.0), "+y", BRACE)
b.brace("brace_e", (5.0, 3.0, 0.0), "+y", BRACE)

# =================================================================
# 4. 扇墙二层与三层: 中间三格长到 2, 正中一格冲到 3
# =================================================================
for k in (1, 2, 3):
    b.wall_ns(f"fan{k}_1", k, 3.0, 1, FAN_MID)
b.wall_ns("fan2_2", 2, 3.0, 2, FAN_TOP)

# =================================================================
# 5. 眼斑三角: 五片骑在五级阶梯的顶沿
# =================================================================
b.crest_ns("eye_0", 0, 3.0, 1.0, EYE_A)
b.crest_ns("eye_1", 1, 3.0, 2.0, EYE_B)
b.crest_ns("eye_2", 2, 3.0, 3.0, EYE_C)
b.crest_ns("eye_3", 3, 3.0, 2.0, EYE_B)
b.crest_ns("eye_4", 4, 3.0, 1.0, EYE_A)

# =================================================================
# 6. 身箱 (x [2,3], y [1,3], z 0..1): 北墙与扇墙中央底格共用
# =================================================================
b.wall_ns("body_s", 2, 1.0, 0, BODY)
b.wall_ew("body_w1", 2.0, 1, 0, BODY)
b.wall_ew("body_w2", 2.0, 2, 0, BODY)
b.wall_ew("body_e1", 3.0, 1, 0, BODY)
b.wall_ew("body_e2", 3.0, 2, 0, BODY)
b.flat("body_cap_s", 2, 1, 1.0, BODY)
b.flat("body_cap_n", 2, 2, 1.0, BODY)

# =================================================================
# 7. 头颈 (x [2,3], y [1,2], z 1..2): 孔雀脸 + 冠羽 + 橙喙
# =================================================================
b.add("face", "window_square", (2.5, 1.0, 1.5), (90, 0, 0), FACE)
b.wall_ew("head_w", 2.0, 1, 1, HEAD)
b.wall_ew("head_e", 3.0, 1, 1, HEAD)
b.wall_ns("head_n", 2, 2.0, 1, HEAD)
b.flat("head_cap", 2, 1, 2.0, HEAD)
b.crest_ns("beak", 2, 1.0, 2.0, BEAK)       # 橙喙骑头顶南沿
b.spire_ns("crown", 2, 2.0, 2.0, CROWN)     # 冠羽骑头顶北沿

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺扇墙后行草坪: 五片绿方板, 斜撑的脚都会踩在这行拼缝上。",
    [f"g3_{x}" for x in range(5)],
    tip="孔雀要来花园开屏啦! 先把尾屏后面的草坪铺好。",
)
b.step(
    "铺扇墙前行草坪: 再来五片绿方板, 尾屏就立在两行的接缝上。",
    [f"g2_{x}" for x in range(5)],
    highlight=["g3_0"],
    tip="方板对方板, 拼缝对整齐 —— 这条缝就是尾屏的地基线。",
)
b.step(
    "铺身箱行: 四片草坪方板 + 一片水塘方板。",
    ["g1_0", "g1_1", "g1_2", "g1_3", "g1_4"],
    highlight=["g2_2"],
    tip="青色方板是孔雀喝水的小水塘。",
)
b.step(
    "铺前行收口: 草坪长板 + 方板 + 水塘长板, 花园围合完成。",
    ["g0_w", "g0_2", "g0_e"],
    highlight=["g1_4"],
    tip="长板短边对方板整边吸合, 草坪连成一整片。",
)
b.step(
    "立尾屏一层: 五片绿墙在 y=3 拼缝上一字排开, 竖边互吸。",
    [f"fan{k}_0" for k in range(5)],
    highlight=["g2_0", "g3_0"],
    tip="扇墙的第一层 —— 每片墙都和邻居手拉手。",
)
b.step(
    "装四条斜撑: 直角三角躲在墙后, 水平边吸地缝、竖直边吸墙缝。",
    ["brace_w", "brace_cw", "brace_ce", "brace_e"],
    highlight=["fan0_0", "fan4_0"],
    tip="斜撑两条直角边都要吸牢 —— 尾屏再高也不怕晃。",
)
b.step(
    "尾屏长到二层: 中间三格摞上青色墙, 底边与一层墙顶整边吸合。",
    ["fan1_1", "fan2_1", "fan3_1"],
    highlight=["fan1_0"],
    tip="阶梯开始收分 —— 两端停在一层, 中间继续长高。",
)
b.step(
    "正中冲顶三层: 一片蓝墙登顶, 阶梯型线 1-2-3-2-1 完成。",
    ["fan2_2"],
    highlight=["fan2_1"],
    tip="正中这格最高 —— 孔雀尾屏的骨架搭好了!",
)
b.step(
    "贴五片眼斑: 彩色三角分别骑在五级阶梯的顶沿。",
    ["eye_0", "eye_1", "eye_2", "eye_3", "eye_4"],
    highlight=["fan2_2"],
    tip="紫粉金三色眼斑一亮 —— 大扇子哗地展开!",
)
b.step(
    "砌身箱: 南墙加东西各两片蓝墙, 北面借用扇墙中央底格围合。",
    ["body_s", "body_w1", "body_w2", "body_e1", "body_e2"],
    highlight=["fan2_0", "g1_2"],
    tip="身体顶住尾屏 —— 孔雀的身箱和尾屏互相帮忙站稳。",
)
b.step(
    "盖身箱双盖板: 两片蓝板四边吸墙顶, 背部圆润收口。",
    ["body_cap_s", "body_cap_n"],
    highlight=["body_s"],
    tip="盖板一压, 身箱变成结实的闭口箱。",
)
b.step(
    "搭头颈点睛: 窗格方孔雀脸朝南, 三片蓝墙围颈, 盖顶板, "
    "橙喙骑南沿, 金色冠羽骑北沿。",
    ["face", "head_w", "head_e", "head_n", "head_cap", "beak", "crown"],
    highlight=["body_cap_s"],
    tip="冠羽一竖, 小孔雀昂首挺胸 —— 开屏成功, 快请朋友来看!",
)

b.finalize(
    model_id="peacock_01",
    name="开屏孔雀",
    name_en="Peacock 01",
    description=(
        "只用核心九片型的花园一景, 全库第一只孔雀, 也是动物家族里"
        "第一只把'一面墙'当身体主角的动物: 结构签名是'独立阶梯扇墙"
        "开屏' —— 尾屏是一面五格宽的立墙, 墙高从两端向中央 1-2-3-2-1 "
        "递增, 紫粉金三色眼斑三角分别骑在五级阶梯顶沿, 展开成对称"
        "的大扇子; 扇墙靠两条路站稳: 蓝色身箱与扇墙中央底格共用一面"
        "墙 (身体顶住尾屏), 四条直角三角斜撑在墙后水平边吸地缝、竖直"
        "边吸墙缝双边受力; 头颈立在身箱前顶, 窗格方孔雀脸朝南, 橙喙"
        "骑南沿, 金色瘦高冠羽骑北沿, 旁边还有一汪青色小水塘 —— "
        "哗! 大扇子展开, 快请朋友来看开屏!"
    ),
    difficulty=3,
    tags=["自然", "动物世界", "孔雀", "开屏", "进阶"],
    min_pieces=50,
    min_steps=12,
)
