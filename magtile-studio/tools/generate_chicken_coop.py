#!/usr/bin/env python3
"""生成模型 data/models/chicken_coop_01.json (农场鸡舍)。

田园农场主题: 7x5 后院里, 一座架高的红色鸡舍立在橙色台座上 ——
台座是 2x2 长方形圈层, 黄色平台压顶; 平台前半起一间人字坡
小红屋, 东端门框方就是鸡的小门, 屋后半留作捡蛋露台, 等边
护栏守住台沿; 一条 30 度黄色跳板从小门斜下到院子里, 三只
金黄小鸡在围栏里踱步, 东北角干草窝四坡自锁, 蓝色方板是
它们的水盆 —— 咯咯哒, 下蛋啦!

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 后院 7x5: 方板 + 长板混铺 (含蓝色水盆方板)              30 片
  - 台座: 长方形圈层 x4 + 平台长板 x2                        6 片
  - 鸡舍小屋: 长楣 x2 + 端墙 + 门框方 + 60 度坡面 x2 +
    等边山花 x2                                              8 片
  - 露台护栏: 等边三角 x2                                    2 片
  - 跳板: 30 度长方形 x1                                     1 片
  - 围栏等边三角 x8 + 小鸡等边三角 x3 + 干草窝四坡锥 x4     15 片
  合计 62 片, 16 个教程步骤, 6 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 台座长方形圈层四角竖边咬合, 平台长板长边整边压圈层墙顶,
    台座 + 平台锁成箱形环;
  - 小屋北墙立在平台两长板的 y=2 拼缝上 (两条 2 格长边同时
    整边吸合), 60 度人字坡脊线互吸、等边山花两腰封坡;
  - 跳板顶端短边整边吸平台东短边 (小门正下方), 坡尾落地 ——
    双端受力, 鸡上鸡下两不误;
  - 门框方外框按实心正方形拼接, 顶边吸山花底边、底边吸台沿。

用法: python3 tools/generate_chicken_coop.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

RIDGE_H = 0.866025

GRASS = "green"
DIRT = "orange"     # 鸡群刨过的土地
PATH = "gray"
BASE = "orange"     # 台座
DECK = "yellow"     # 平台
HOUSE = "red"       # 小屋
ROOF = "gray"
RAMP = "yellow"
FENCE = "orange"
CHICK = "yellow"
WATER = "blue"

# =================================================================
# 1. 后院 7x5 (x 0..7, y 0..5): 西侧台座地基用长板, 东侧鸡群
#    活动区用方板 (围栏/小鸡都要吸方板格边)
# =================================================================
b.flat("g_0_0", 0, 0, 0.0, GRASS)
b.flat_rect("g_r_0", 1, 0, 0.0, PATH, axis="x")       # 台座南地基 [1,3]
b.flat("g_3_0", 3, 0, 0.0, DIRT)                      # 围栏门口
b.flat("g_4_0", 4, 0, 0.0, DIRT)
b.flat("g_5_0", 5, 0, 0.0, DIRT)
b.flat("g_6_0", 6, 0, 0.0, DIRT)
for y in (1, 2, 3):
    b.flat(f"g_0_{y}", 0, y, 0.0, GRASS)
    b.flat_rect(f"g_r_{y}", 1, y, 0.0, PATH, axis="x")    # 台座地坪 [1,3]
    for x in (3, 4, 5, 6):
        color = WATER if (x, y) == (4, 2) else DIRT
        b.flat(f"g_{x}_{y}", x, y, 0.0, color)
b.flat_rect("g_t_0", 0, 4, 0.0, GRASS, axis="x")      # 北排 [0,2]
b.flat("g_2_4", 2, 4, 0.0, GRASS)
b.flat("g_3_4", 3, 4, 0.0, DIRT)
b.flat("g_4_4", 4, 4, 0.0, DIRT)
b.flat("g_5_4", 5, 4, 0.0, DIRT)
b.flat("g_6_4", 6, 4, 0.0, DIRT)

# =================================================================
# 2. 台座 (x 1..3, y 1..3, z 0..1): 长方形圈层 + 平台压顶
# =================================================================
b.lintel_ns("bs_s", 1, 1.0, 0, BASE)                  # 台座南墙
b.lintel_ns("bs_n", 1, 3.0, 0, BASE)                  # 台座北墙
b.lintel_ew("bs_w", 1.0, 1, 0, BASE)                  # 台座西墙
b.lintel_ew("bs_e", 3.0, 1, 0, BASE)                  # 台座东墙
b.flat_rect("dk_s", 1, 1, 1.0, DECK, axis="x")        # 平台南半 [1,3]x[1,2]
b.flat_rect("dk_n", 1, 2, 1.0, DECK, axis="x")        # 平台北半 [1,3]x[2,3]

# =================================================================
# 3. 鸡舍小屋 (x 1..3, y 1..2, z 1..2): 人字坡小红屋, 东端小门
# =================================================================
b.lintel_ns("hs_s", 1, 1.0, 1, HOUSE)                 # 小屋南墙
b.lintel_ns("hs_n", 1, 2.0, 1, HOUSE)                 # 小屋北墙 (平台拼缝上)
b.wall_ew("hs_w", 1.0, 1, 1, HOUSE)                   # 西端墙
b.wall_ew("hs_door", 3.0, 1, 1, "clear")              # 东端小门 (门框方)
b.tiles[-1]["type"] = "door_frame"
b.place_edge("hs_rf_s", "rectangle", 0, (1.0, 1.0, 2.0), (3.0, 1.0, 2.0),
             (0.0, 0.5, RIDGE_H), ROOF)               # 南坡面
b.place_edge("hs_rf_n", "rectangle", 0, (3.0, 2.0, 2.0), (1.0, 2.0, 2.0),
             (0.0, -0.5, RIDGE_H), ROOF)              # 北坡面
b.crest_ew("hs_gb_w", 1.0, 1, 2.0, HOUSE)             # 西山花
b.crest_ew("hs_gb_e", 3.0, 1, 2.0, HOUSE)             # 东山花

# =================================================================
# 4. 捡蛋露台护栏 + 跳板
# =================================================================
b.crest_ew("pr_w", 1.0, 2, 1.0, DECK)                 # 露台西护栏
b.crest_ew("pr_e", 3.0, 2, 1.0, DECK)                 # 露台东护栏
b.ramp("ramp", "+x", 3.0, 1, 1.0, RAMP)               # 小门跳板 (顶边吸台沿)

# =================================================================
# 5. 围栏 (留南门口) + 小鸡 + 干草窝
# =================================================================
b.crest_ns("fn_s0", 4, 0.0, 0.0, FENCE)               # 南围栏
b.crest_ns("fn_s1", 5, 0.0, 0.0, FENCE)
b.crest_ns("fn_s2", 6, 0.0, 0.0, FENCE)
b.crest_ew("fn_e0", 7.0, 0, 0.0, FENCE)               # 东围栏
b.crest_ew("fn_e1", 7.0, 2, 0.0, FENCE)
b.crest_ew("fn_e2", 7.0, 4, 0.0, FENCE)
b.crest_ns("fn_n0", 3, 5.0, 0.0, FENCE)               # 北围栏
b.crest_ns("fn_n1", 5, 5.0, 0.0, FENCE)
b.crest_ns("chick_a", 4, 2.0, 0.0, CHICK)             # 小鸡 (水盆边)
b.crest_ns("chick_b", 5, 3.0, 0.0, CHICK)
b.crest_ns("chick_c", 5, 1.0, 0.0, CHICK)
NEST = b.hat4("nest", 6, 4, 0.0, CHICK,
              shape="equilateral_triangle")           # 干草窝

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺后院南排: 6 片地坪排开, 橙色是鸡群刨松的土地。",
    ["g_0_0", "g_r_0", "g_3_0", "g_4_0", "g_5_0", "g_6_0"],
    tip="灰色长板 [1,3] 的北长边是台座南墙的地基线。",
)
b.step(
    "铺后院中部第一行: 台座地坪长板加 4 片方板。",
    ["g_0_1", "g_r_1", "g_3_1", "g_4_1", "g_5_1", "g_6_1"],
    highlight=["g_r_0"],
    tip="东侧活动区必须用方板 —— 围栏和小鸡都要吸方板格边。",
)
b.step(
    "铺后院中部第二三行: 12 片合拢, 蓝色方板是鸡群的水盆。",
    ["g_0_2", "g_r_2", "g_3_2", "g_4_2", "g_5_2", "g_6_2",
     "g_0_3", "g_r_3", "g_3_3", "g_4_3", "g_5_3", "g_6_3"],
    highlight=["g_r_1"],
    tip="水盆放在活动区正中 —— 咕咚咕咚, 喝水不打架。",
)
b.step(
    "铺后院北排: 6 片合拢, 7x5 后院就绪。",
    ["g_t_0", "g_2_4", "g_3_4", "g_4_4", "g_5_4", "g_6_4"],
    highlight=["g_r_3"],
    tip="院子铺好了, 该给母鸡们盖新家了。",
)
b.step(
    "立台座圈层: 4 片橙色长楣围成 2x2 一圈, 四角竖边咬合, "
    "底边整边吸地坪拼缝。",
    ["bs_s", "bs_n", "bs_w", "bs_e"],
    highlight=["g_r_0", "g_r_3"],
    tip="鸡舍要架高 —— 防潮防黄鼠狼, 老农的智慧。",
)
b.step(
    "盖平台: 2 片黄色长板长边整边压圈层墙顶, 台座锁成箱形环。",
    ["dk_s", "dk_n"],
    highlight=["bs_s", "bs_n"],
    tip="平台拼缝落在 y=2 线上 —— 小屋北墙马上立在这条缝上。",
)
b.step(
    "立小屋南北墙: 2 片红色长楣, 北墙正立在平台拼缝上。",
    ["hs_s", "hs_n"],
    highlight=["dk_s", "dk_n"],
    tip="拼缝两侧的长板各伸出一条 2 格长边, 同时咬住北墙底边。",
)
b.step(
    "封小屋两端: 西端红墙 + 东端门框方小门, 竖边咬住南北墙短边。",
    ["hs_w", "hs_door"],
    highlight=["hs_s", "hs_n"],
    tip="门框方就是鸡的小门 —— 正对跳板, 进出方便。",
)
b.step(
    "架人字坡南面: 灰色长方形 60 度斜置, 下长边整边吸南墙顶边。",
    ["hs_rf_s"],
    highlight=["hs_s"],
    tip="扶稳别松手 —— 等北坡上来合脊。",
)
b.step(
    "北坡合脊: 第二片坡面脊线处两长边互吸, 人字顶合拢。",
    ["hs_rf_n"],
    highlight=["hs_rf_s"],
    tip="咔哒一声, 小红屋有了雨天不漏的顶。",
)
b.step(
    "封山花: 东西各 1 片红色等边三角, 底边吸端墙顶边、两腰吸坡面短边。",
    ["hs_gb_w", "hs_gb_e"],
    highlight=["hs_rf_s", "hs_rf_n"],
    tip="山花一封, 小屋密不透风 —— 冬天也暖和。",
)
b.step(
    "立露台护栏: 平台北半是捡蛋露台, 东西台沿各立 1 片等边护栏。",
    ["pr_w", "pr_e"],
    highlight=["dk_n"],
    tip="清晨来露台捡蛋, 护栏挡着鸡蛋不滚落。",
)
b.step(
    "架跳板: 30 度黄色长方形, 顶端短边整边吸台沿短边 "
    "(小门正下方), 坡尾落地。",
    ["ramp"],
    highlight=["hs_door", "dk_s"],
    tip="双端受力 —— 母鸡们排着队, 咯咯哒地走上新家。",
)
b.step(
    "插围栏: 南沿 3 片 (西头留门口)、东沿 3 片、北沿 2 片, "
    "活动区围合。",
    ["fn_s0", "fn_s1", "fn_s2", "fn_e0", "fn_e1", "fn_e2",
     "fn_n0", "fn_n1"],
    highlight=["g_3_0"],
    tip="等边三角底边吸方板格边 —— 黄鼠狼, 请回吧。",
)
b.step(
    "放小鸡: 3 片金黄等边三角在水盆边踱步。",
    ["chick_a", "chick_b", "chick_c"],
    highlight=["g_4_2"],
    tip="叽叽叽 —— 三姐妹排队喝水。",
)
b.step(
    "堆干草窝: 东北角 4 片金黄等边三角合拢成四坡草窝 —— "
    "鸡舍交付, 咯咯哒!",
    NEST,
    highlight=["g_6_4"],
    tip="从南门望去: 跳板、小门、人字顶一线排开 —— 母鸡的豪宅落成。",
)

b.finalize(
    model_id="chicken_coop_01",
    name="农场鸡舍",
    name_en="Chicken Coop 01",
    description=(
        "架高的母鸡豪宅: 橙色长方形圈层台座上黄色平台压顶锁成箱形环, "
        "前半起一间 60 度人字坡小红屋 —— 北墙立在平台双长板拼缝上, "
        "东端门框方小门正对 30 度跳板 (顶边吸台沿、坡尾落地, 双端受力); "
        "屋后捡蛋露台等边护栏守边, 围栏圈出活动区, 三只小鸡围着蓝色"
        "水盆踱步, 东北角干草窝四坡自锁 —— 防潮防黄鼠狼, 老农的智慧。"
    ),
    difficulty=3,
    tags=["田园", "农场", "鸡舍", "动物世界", "进阶"],
    min_pieces=50,
    min_steps=16,
)
