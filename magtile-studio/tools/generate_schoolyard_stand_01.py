#!/usr/bin/env python3
"""生成模型 data/models/schoolyard_stand_01.json (操场看台)。

校园/学校主题批 1/4: 全库第一座校园运动会看台 —— 与
amphitheater_01 (放射状环带看台, 梯形+菱形扩展片) 和
stadium_gate_01 (体育场大门门楼) 刻意区分: 本作是"直线两级退台 +
侧向斜撑"的校园看台, 只用核心九片型; 与 rice_terrace_01 的山坡
梯田 (箱形梯级层层抬升) 的区别在于结构词汇 —— 看台不用坡道与
石阶盒, 而是用直角三角斜撑锁住二排高层, 台前还有运动会才有的
1-2-3 三连领奖台 (中间冠军台高两格) 与白色终点线跑道。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 看台朝南望向跑道):
  - 操场地坪 6x5: 红色跑道 (白色终点线) + 绿茵 + 看台脚下方板   24 片
  - 前排看台 A (x [1,5], y [3,4], z 0..1): 墙环 x10 + 座板 x2    12 片
  - 后排看台 B (y [4,5], z 0..2): 两层墙环 x16 + 座板 x2         18 片
  - 侧向斜撑 x2: 直角三角竖边吸二排墙棱、横边吸前排座板沿        2 片
  - 彩旗 x2: 等边三角骑后排顶沿                                   2 片
  - 领奖台 (x [2,5], y [1,2]): 墙 x10 + 亚季军台 x2 + 冠军台 x5  17 片
  合计 75 片, 15 个教程步骤, 4 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 两级看台均为"墙环合环 + 座板压顶"的闭环箱体, 后排二层墙环
    直接骑在一层墙顶上 (整边共线吸合), R8 高层检查由闭环拓扑通过;
  - 侧向斜撑: 直角三角竖直角边吸后排二层墙前棱、水平直角边吸
    前排座板侧沿 (双边受力零悬挑, 摩天大楼同款);
  - 彩旗骑后排墙顶沿口, 重心正压铰链线力矩为零;
  - 领奖台三连箱共墙成环: 四道隔墙把三座台分开又互相锁住,
    冠军台二层墙环的竖直边再吸亚/季军台面沿 (一线双吸);
  - 地坪拼缝纪律: 所有墙脚线处均为等长单位方板拼缝, 相邻行
    至少一对等长边互吸保证逐步装配全程连通。

用法: python3 tools/generate_schoolyard_stand_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

TRACK = "red"        # 跑道
FINISH = "clear"     # 终点线 (白)
GRASS = "green"      # 绿茵
BASE = "gray"        # 看台脚下地坪 / 台基
STAND = "blue"       # 看台墙体
SEAT_A = "cyan"      # 前排座板
SEAT_B = "blue"      # 后排座板
BRACE = "red"        # 侧向斜撑
FLAG_W = "red"       # 西彩旗
FLAG_E = "yellow"    # 东彩旗
GOLD = "yellow"      # 冠军台
SILVER = "clear"     # 亚军台
BRONZE = "orange"    # 季军台

# =================================================================
# 1. 操场地坪 6x5 (x [0,6], y [0,5]): 拼缝纪律 —— 看台/领奖台墙脚
#    线处必须有等长的单位方板边; 相邻行至少一对等长边互吸。
# =================================================================
# 跑道 (y [0,1]): 红色直道 + 白色终点线
b.flat_rect("g_track_w", 0, 0, 0.0, TRACK)
b.flat_rect("g_track_m", 2, 0, 0.0, TRACK)
b.flat("g_finish", 4, 0, 0.0, FINISH)              # 终点线
b.flat("g_track_e", 5, 0, 0.0, TRACK)
# 领奖台行 (y [1,2]): 全单位方板 (台基三格 + 两端绿茵)
b.flat("g_1_0", 0, 1, 0.0, GRASS)
b.flat("g_1_1", 1, 1, 0.0, GRASS)
b.flat("g_pod_w", 2, 1, 0.0, BASE)                 # 季军台脚下
b.flat("g_pod_m", 3, 1, 0.0, BASE)                 # 冠军台脚下
b.flat("g_pod_e", 4, 1, 0.0, BASE)                 # 亚军台脚下
b.flat("g_1_5", 5, 1, 0.0, GRASS)
# 缓冲绿茵 (y [2,3])
b.flat("g_2_0", 0, 2, 0.0, GRASS)
b.flat_rect("g_2_m1", 1, 2, 0.0, GRASS)
b.flat_rect("g_2_m2", 3, 2, 0.0, GRASS)
b.flat("g_2_5", 5, 2, 0.0, GRASS)
# 前排看台脚下 (y [3,4]): 6 格单位方板
for x in range(6):
    b.flat(f"g_3_{x}", x, 3, 0.0, BASE if 1 <= x <= 4 else GRASS)
# 后排看台脚下 (y [4,5]): 看台 x [1,5] 之下 4 格
for x in range(1, 5):
    b.flat(f"g_4_{x}", x, 4, 0.0, BASE)

# =================================================================
# 2. 前排看台 A (x [1,5], y [3,4], z 0..1): 墙环 + 座板
# =================================================================
for x in range(1, 5):
    b.wall_ns(f"stA_s_{x}", x, 3.0, 0, STAND)
for x in range(1, 5):
    b.wall_ns(f"stA_n_{x}", x, 4.0, 0, STAND)
b.wall_ew("stA_w", 1.0, 3, 0, STAND)
b.wall_ew("stA_e", 5.0, 3, 0, STAND)
b.flat_rect("stA_seat_w", 1, 3, 1.0, SEAT_A)
b.flat_rect("stA_seat_e", 3, 3, 1.0, SEAT_A)

# =================================================================
# 3. 后排看台 B (x [1,5], y [4,5], z 0..2): 一层借前排北墙,
#    二层墙环整体骑上一层墙顶
# =================================================================
for x in range(1, 5):
    b.wall_ns(f"stB1_n_{x}", x, 5.0, 0, STAND)
b.wall_ew("stB1_w", 1.0, 4, 0, STAND)
b.wall_ew("stB1_e", 5.0, 4, 0, STAND)
for x in range(1, 5):
    b.wall_ns(f"stB2_s_{x}", x, 4.0, 1, STAND)
for x in range(1, 5):
    b.wall_ns(f"stB2_n_{x}", x, 5.0, 1, STAND)
b.wall_ew("stB2_w", 1.0, 4, 1, STAND)
b.wall_ew("stB2_e", 5.0, 4, 1, STAND)
b.flat_rect("stB_seat_w", 1, 4, 2.0, SEAT_B)
b.flat_rect("stB_seat_e", 3, 4, 2.0, SEAT_B)

# =================================================================
# 4. 侧向斜撑 x2 + 彩旗 x2
# =================================================================
b.brace("brace_w", (1.0, 4.0, 1.0), "-y", BRACE)   # 竖边吸 B 二层西墙前棱
b.brace("brace_e", (5.0, 4.0, 1.0), "-y", BRACE)   # 横边吸 A 座板侧沿
b.crest_ns("flag_w", 1, 5.0, 2.0, FLAG_W)          # 骑后排顶沿
b.crest_ns("flag_e", 4, 5.0, 2.0, FLAG_E)

# =================================================================
# 5. 领奖台 (x [2,5], y [1,2]): 三连箱共墙成环, 冠军台高两格
# =================================================================
for x in (2, 3, 4):
    b.wall_ns(f"pod_s_{x}", x, 1.0, 0, BASE)
for x in (2, 3, 4):
    b.wall_ns(f"pod_n_{x}", x, 2.0, 0, BASE)
for x in (2, 3, 4, 5):
    b.wall_ew(f"pod_d_{x}", float(x), 1, 0, BASE)  # 四道隔墙
b.flat("pod_cap_w", 2, 1, 1.0, BRONZE)             # 季军台面 (z=1)
b.flat("pod_cap_e", 4, 1, 1.0, SILVER)             # 亚军台面 (z=1)
b.wall_ns("pod2_s", 3, 1.0, 1, GOLD)               # 冠军台二层墙环
b.wall_ns("pod2_n", 3, 2.0, 1, GOLD)
b.wall_ew("pod2_w", 3.0, 1, 1, GOLD)
b.wall_ew("pod2_e", 4.0, 1, 1, GOLD)
b.flat("pod_cap_m", 3, 1, 2.0, GOLD)               # 冠军台面 (z=2)

# =================================================================
# 教程步骤 (15 步)
# =================================================================
b.step(
    "铺跑道: 红色直道两长板冲向白色终点线, 东头再补一格。",
    ["g_track_w", "g_track_m", "g_finish", "g_track_e"],
    tip="运动会从这条终点线开始 —— 冠军马上就要冲线了!",
)
b.step(
    "铺领奖台行: 中间三格灰色台基, 两端绿茵, 全部用单位方板。",
    ["g_1_0", "g_1_1", "g_pod_w", "g_pod_m", "g_pod_e", "g_1_5"],
    highlight=["g_finish"],
    tip="领奖台的六道墙脚全踩在这排方板的拼缝上 —— 一格都不能换长板。",
)
b.step(
    "铺缓冲绿茵 (y [2,3]): 两端方板与上一行等边互吸。",
    ["g_2_0", "g_2_m1", "g_2_m2", "g_2_5"],
    highlight=["g_1_0"],
    tip="两端方板与领奖台行等长咬合 —— 地坪逐行连成一张网。",
)
b.step(
    "铺看台脚下地坪 (y [3,5]): 前排 6 格, 后排 4 格, 全单位方板。",
    ["g_3_0", "g_3_1", "g_3_2", "g_3_3", "g_3_4", "g_3_5",
     "g_4_1", "g_4_2", "g_4_3", "g_4_4"],
    highlight=["g_2_0"],
    tip="看台一层墙的每一段墙脚都要有等长的方板拼缝可吸。",
)
b.step(
    "立前排看台南墙与侧墙: 4 片蓝墙 + 东西侧墙, 四角竖边互咬。",
    ["stA_s_1", "stA_s_2", "stA_s_3", "stA_s_4", "stA_w", "stA_e"],
    highlight=["g_3_1", "g_3_4"],
    tip="拐角一咬, 排墙就从'一排片'变成了'半圈环'。",
)
b.step(
    "立前排北墙合环: 4 片补齐, 前排箱体处处成环。",
    ["stA_n_1", "stA_n_2", "stA_n_3", "stA_n_4"],
    highlight=["stA_w", "stA_e"],
    tip="这道墙同时也是后排看台的一层南墙 —— 一墙两用。",
)
b.step(
    "盖前排座板: 两片青色长板压顶, 短边互吸、两端吸侧墙顶。",
    ["stA_seat_w", "stA_seat_e"],
    highlight=["stA_s_2"],
    tip="第一排坐好 —— 离跑道最近, 加油声最响!",
)
b.step(
    "立后排一层: 北墙 4 片 + 东西侧墙, 与前排北墙合成一层环。",
    ["stB1_n_1", "stB1_n_2", "stB1_n_3", "stB1_n_4", "stB1_w", "stB1_e"],
    highlight=["stA_n_1", "g_4_1"],
    tip="后排借前排的北墙当自己的南墙 —— 两级看台背靠背。",
)
b.step(
    "立后排二层南北墙: 8 片墙整边骑上一层墙顶。",
    ["stB2_s_1", "stB2_s_2", "stB2_s_3", "stB2_s_4",
     "stB2_n_1", "stB2_n_2", "stB2_n_3", "stB2_n_4"],
    highlight=["stB1_n_1"],
    tip="上下两层墙整边共线吸合 —— 退台第二级就这样长高。",
)
b.step(
    "二层侧墙合环并盖后排座板: 蓝色长板压顶, 后排比前排高一格。",
    ["stB2_w", "stB2_e", "stB_seat_w", "stB_seat_e"],
    highlight=["stB2_s_1"],
    tip="二层墙环 + 座板锁成箱体 —— R8 高层检查由闭环天然通过。",
)
b.step(
    "装侧向斜撑与彩旗: 红色直角三角竖边吸二层墙棱、横边吸前排"
    "座板沿; 红黄彩旗骑上后排顶沿。",
    ["brace_w", "brace_e", "flag_w", "flag_e"],
    highlight=["stB2_w", "stA_seat_w"],
    tip="斜撑双边受力零悬挑 —— 摩天大楼同款的抗侧力保险。",
)
b.step(
    "砌领奖台南北墙: 各 3 片灰墙, 正对终点线。",
    ["pod_s_2", "pod_s_3", "pod_s_4", "pod_n_2", "pod_n_3", "pod_n_4"],
    highlight=["g_pod_m"],
    tip="领奖台面向跑道 —— 冲线之后就到这里领奖。",
)
b.step(
    "插四道隔墙: 三连箱共墙成环, 每道隔墙两端竖边互咬。",
    ["pod_d_2", "pod_d_3", "pod_d_4", "pod_d_5"],
    highlight=["pod_s_2", "pod_n_4"],
    tip="四道隔墙把三座台分开又互相锁住 —— 共墙就是共保险。",
)
b.step(
    "盖亚军季军台面: 银色台面在东, 铜色台面在西 (z=1)。",
    ["pod_cap_w", "pod_cap_e"],
    highlight=["pod_d_2"],
    tip="台面四边全吸墙顶 —— 第二名第三名, 请上台!",
)
b.step(
    "冠军台升第二层: 金色墙环骑中箱顶再压金色台面 —— 冠军最高!",
    ["pod2_s", "pod2_n", "pod2_w", "pod2_e", "pod_cap_m"],
    highlight=["pod_cap_w", "pod_cap_e"],
    tip="二层墙的竖边再吸亚/季军台面沿 —— 一线双吸两条保险。",
)

b.finalize(
    model_id="schoolyard_stand_01",
    name="操场看台",
    name_en="Schoolyard Grandstand 01",
    description=(
        "只用核心九片型的校园运动会看台: 与放射环带的圆形剧场和门楼式"
        "体育场大门都不同, 这是'直线两级退台'的校园看台 —— 前后两级"
        "墙环合环 + 座板压顶的闭环箱体背靠背, 后排二层墙环整边骑上"
        "一层墙顶, 两片红色直角三角斜撑竖边吸二层墙棱、横边吸前排"
        "座板沿 (双边受力零悬挑), 红黄彩旗骑顶沿力矩为零; 台前红色"
        "跑道冲向白色终点线, 1-2-3 三连领奖台四道隔墙共墙成环, 金色"
        "冠军台二层墙环再压金色台面全场最高 —— 三、二、一, 冲线!"
    ),
    difficulty=3,
    tags=["校园", "操场", "看台", "运动会", "领奖台", "进阶"],
    min_pieces=75,
    min_steps=15,
)
