#!/usr/bin/env python3
"""生成模型 data/models/magic_pinwheel_mill_01.json (魔法风车坊)。

D1 收官批 4 模型 4/4 (难度配额解冻线 D1 >= 20, 路径 B1): 入门档
幻想与机械选题 —— 研磨星尘的魔法风车坊, 也是幻想与机械主题的
第一个 D1。结构签名是"塔楼十字翼 + 借墙工坊": 1x1 磨坊塔楼
封顶后, 四面等边三角风车翼骑上塔帽四条沿边, 从天上看正好是
一朵十字风车 —— 每片翼底边同时吸住塔帽沿与墙顶, 一处沿口两处
受抓; 东侧工坊借塔楼东墙当自己的第四面墙 (省一片料的老木匠
智慧), 工坊帽东沿立一枚魔法水晶; 门前三片星尘晒场, 西端一段
矮篱笆骑住塔角, 篱笆顶开一朵星光花, 晒场南沿平贴两片水晶碎料。
与库内 D3 大风车 (55 片菱形梯形翼) 及本批探测器 (十字斜撑)、
巨石门环 (三石塔)、滚珠坡 (塔-坡-槽) 的结构逻辑完全不同 ——
全批唯一"塔帽四沿立翼"的旋转对称顶部结构。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 坊门朝南 -y):
  - 星尘晒场 3 片方板 (x [-1,2], y [-1,0], 全部接地)      3 片
  - 磨坊塔楼一圈 (z 0..1): 南门框方 + 三面方墙            4 片
  - 塔帽 1 片方板 (z=1, 四边整边锁墙顶)                   1 片
  - 十字风车翼 4 面 (等边三角, 骑塔帽四条沿边)            4 片
  - 借墙工坊 (格 [1,2]x[0,1]): 3 墙 (东面窗格方) + 1 帽   4 片
  - 魔法水晶 1 枚 (等边三角, 骑工坊帽东沿)                1 片
  - 矮篱笆 1 片方墙 + 星光花 1 面 (骑篱笆顶)              2 片
  - 水晶碎料 2 片 (等边三角平贴晒场南沿)                  2 片
  合计 21 片, 6 个教程步骤, 4 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 塔楼墙脚整边吸晒场板边, 竖棱角缝互吸成环, 塔帽四边锁墙顶
    (先合围后封顶, R7b 无包围放置);
  - 每片风车翼底边同时吸塔帽沿边与墙顶 (两处受抓), 翼与翼
    互不相碰 —— 从顶视图看是四叶十字;
  - 工坊西侧直接借塔楼东墙, 工坊帽西边整边吸塔帽东边;
  - 最高点 1.87 (翼尖) < 2.5, 不触发 R8 高层结构判定。

用法: python3 tools/generate_magic_pinwheel_mill_01.py  (在 magtile-studio 目录下运行)
"""

import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

YARD = "yellow"     # 星尘晒场
TOWER = "purple"    # 磨坊塔楼
DOOR = "orange"     # 坊门
HUB = "gray"        # 塔帽 (翼毂)
SAIL = "cyan"       # 风车翼
SHED = "purple"     # 工坊
GLASS = "clear"     # 工坊天窗
CRYSTAL = "pink"    # 魔法水晶
FENCE = "green"     # 矮篱笆
FLOWER = "pink"     # 星光花

TRI_H = round(math.sqrt(3) / 2, 6)   # 等边三角形高 0.866025

# =================================================================
# 1. 星尘晒场 (x [-1,2], y [-1,0], 全部接地)
# =================================================================
b.flat("yard_w", -1, -1, 0.0, YARD)
b.flat("yard_c", 0, -1, 0.0, YARD)
b.flat("yard_e", 1, -1, 0.0, YARD)

# =================================================================
# 2. 磨坊塔楼 (格 [0,1]x[0,1], z 0..1): 南门框方 + 三面方墙
# =================================================================
b.add("mill_s", "door_frame", (0.5, 0.0, 0.5), (90, 0, 0), DOOR)
b.wall_ew("mill_w", 0.0, 0, 0, TOWER)
b.wall_ns("mill_n", 0, 1.0, 0, TOWER)
b.wall_ew("mill_e", 1.0, 0, 0, TOWER)

# =================================================================
# 3. 借墙工坊 (格 [1,2]x[0,1], 西面直接借塔楼东墙)
# =================================================================
b.wall_ns("shed_s", 1, 0.0, 0, SHED)
b.wall_ns("shed_n", 1, 1.0, 0, SHED)
b.add("shed_e", "window_square", (2.0, 0.5, 0.5), (90, 0, 90), GLASS)
b.flat("shed_cap", 1, 0, 1.0, SHED)

# =================================================================
# 4. 塔帽与十字风车翼 (四面等边三角骑塔帽四条沿边)
# =================================================================
b.flat("hub", 0, 0, 1.0, HUB)
b.crest_ns("sail_s", 0, 0.0, 1.0, SAIL)
b.crest_ns("sail_n", 0, 1.0, 1.0, SAIL)
b.crest_ew("sail_w", 0.0, 0, 1.0, SAIL)
b.crest_ew("sail_e", 1.0, 0, 1.0, SAIL)

# =================================================================
# 5. 魔法水晶 + 矮篱笆 + 星光花 + 水晶碎料
# =================================================================
b.crest_ew("crystal_e", 2.0, 0, 1.0, CRYSTAL)   # 骑工坊帽东沿与天窗顶
b.wall_ns("fence_w", -1, 0.0, 0, FENCE)          # 墙脚吸晒场板边, 竖棱吸塔角
b.crest_ns("flower", -1, 0.0, 1.0, FLOWER)       # 骑篱笆顶
b.place_tri("shard_w", "equilateral_triangle",
            (0.0, -1.0, 0.0), (-1.0, -1.0, 0.0), (-0.5, -1.0 - TRI_H, 0.0), CRYSTAL)
b.place_tri("shard_e", "equilateral_triangle",
            (2.0, -1.0, 0.0), (1.0, -1.0, 0.0), (1.5, -1.0 - TRI_H, 0.0), CRYSTAL)

# =================================================================
# 教程步骤 (6 步)
# =================================================================
b.step(
    "铺星尘晒场: 三片黄色方板整边相吸一字排开 —— 磨好的星尘粉就晾在这里。",
    ["yard_w", "yard_c", "yard_e"],
)
b.step(
    "立磨坊塔楼: 橙色门框方是坊门, 墙脚整边吸住晒场板边, 三面紫墙竖棱角缝互吸围成一圈。",
    ["mill_s", "mill_w", "mill_n", "mill_e"],
    highlight=["yard_c"],
    tip="四片墙的竖棱像小手拉手 —— 拉成一圈塔楼就推不倒了。",
)
b.step(
    "搭借墙工坊: 工坊西面直接借塔楼东墙, 南北两片紫墙加透明天窗围好, 盖上工坊帽。",
    ["shed_s", "shed_n", "shed_e", "shed_cap"],
    highlight=["mill_e"],
    tip="借一面墙省一片料 —— 这是老木匠的智慧。",
)
b.step(
    "盖塔帽装风车翼: 灰色塔帽四边整边锁住墙顶, 四面青色三角翼骑上塔帽四条沿边 —— 从天上看正好是一朵十字风车。",
    ["hub", "sail_s", "sail_n", "sail_w", "sail_e"],
    highlight=["mill_n"],
    tip="每片翼的底边同时吸住塔帽沿和墙顶 —— 一条沿口两处受抓。",
)
b.step(
    "点水晶围篱笆: 粉色魔法水晶骑上工坊帽东沿, 绿色矮篱笆墙脚吸晒场板边、竖棱咬住塔角, 篱笆顶开一朵星光花。",
    ["crystal_e", "fence_w", "flower"],
    highlight=["shed_cap", "yard_w"],
)
b.step(
    "晾水晶碎料: 两片粉色小三角平贴晒场南沿, 魔法风车坊开工啦!",
    ["shard_w", "shard_e"],
    highlight=["yard_w", "yard_e"],
)

b.finalize(
    model_id="magic_pinwheel_mill_01",
    name="魔法风车坊",
    name_en="Magic Pinwheel Mill 01",
    description=(
        "入门档幻想与机械: 研磨星尘的魔法风车坊, 结构签名是'塔楼"
        "十字翼 + 借墙工坊' —— 紫色磨坊塔楼墙脚整边吸晒场板边、"
        "竖棱角缝互吸成环, 灰色塔帽四边锁墙顶后, 四面青色等边三角"
        "风车翼骑上塔帽四条沿边, 每片翼底边同时吸住塔帽沿与墙顶, "
        "顶视正是一朵十字风车; 东侧工坊借塔楼东墙当第四面墙, 透明"
        "天窗上方立一枚粉色魔法水晶; 门前三片星尘晒场、西端矮篱笆"
        "与星光花、南沿两片水晶碎料。21 片全程接地受压零悬挑, "
        "翼尖 1.87 不触发高层判定, 搭完就能给魔法师磨第一袋星尘粉。"
    ),
    difficulty=1,
    tags=["幻想与机械", "风车", "魔法", "亲子入门"],
    min_pieces=21,
    min_steps=6,
    series="fantasy_machinery",
)
print("已写入 series=fantasy_machinery")
