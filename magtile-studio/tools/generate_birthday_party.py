#!/usr/bin/env python3
"""生成模型 data/models/birthday_party_01.json (生日派对)。

节日/庆典主题 3/4: 全库第一场生日派对 —— 主角是全库第一只
"阶梯双层大蛋糕": 与灯塔/圣诞树的 1x1 直筒墙环刻意区分, 蛋糕
底层是 2x2 大墙环 (每边 2 片, 八片转角互咬), 奶油平台 4 片方板
每片同时压两段墙顶与邻板拼缝; 第 2 层 1x1 墙环退台踩在平台
西南角 (阶梯蛋糕的经典造型), 顶面奶油盖四沿骑满生日蜡烛 ——
6 支等边三角蜡烛全部一线双吸 (盖板沿 + 墙顶); 场外彩旗门双柱
托横板骑双旗, 两顶派对帽四棱自锁落地, 四只气球瘦高三角直上
2.0 —— 许愿吹蜡烛之前, 先把派对现场搭出来。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 地面 (x [0,9], y [0,4]): 派对彩格地板                    27 片
  - 蛋糕 (x [3,5], y [2,4]): 底层 2x2 墙环 x8 + 奶油平台 x4 +
    第 2 层 1x1 墙环 x4 + 奶油盖 x1 + 蜡烛 x6                23 片
  - 彩旗门 (x [0,1], 跨 y [0,2]): 双柱各 2 节 + 顶横板 + 双旗  7 片
  - 派对帽 x2: 等边四坡三角锥落地自锁                          8 片
  - 气球 x4: 瘦高等腰三角骑地板拼缝                            4 片
  合计 69 片, 14 个教程步骤, 4 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 蛋糕底层 2x2 墙环八片转角竖边互咬闭环, 奶油平台每片同时
    吸两段墙顶 + 邻板拼缝 (处处成环, 通过 R8 高层检查);
  - 第 2 层墙环底边分别吸平台外沿与平台拼缝 (一线双吸),
    奶油盖四边压四墙顶;
  - 6 支蜡烛底边全部落在 "盖板沿 + 墙顶" 的同一条线上 (一线
    双吸), 重心正压铰链线, 力矩为零;
  - 彩旗门顶横板两短边分别压双柱顶 (双端受力零悬挑), 柱-板-
    柱-地面锁成门式刚架; 派对帽四棱互吸、基线踩地板整边;
  - 气球重心正压拼缝铰链线, 两片地板各贡献一条吸边。

用法: python3 tools/generate_birthday_party.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

FLOOR_A = "cyan"    # 彩格地板长板
FLOOR_B = "yellow"  # 彩格地板方板
TRAY = "gray"       # 蛋糕托盘
CAKE1 = "pink"      # 蛋糕底层
CREAM = "clear"     # 奶油平台 / 奶油盖
CAKE2 = "purple"    # 蛋糕第 2 层
CANDLE = ["red", "yellow", "blue", "orange", "green", "red"]  # 蜡烛
GATE = "cyan"       # 彩旗门柱
BEAM = "yellow"     # 彩旗门横板
FLAG_A = "pink"     # 门旗
FLAG_B = "red"
HAT_W = "red"       # 西派对帽
HAT_E = "blue"      # 东派对帽
BALLOON = ["red", "yellow", "blue", "purple"]  # 气球

# =================================================================
# 1. 地面 (x [0,9], y [0,4]): 彩格地板, 方板留给墙脚/帽底/气球缝
# =================================================================
b.flat("f0_0", 0, 0, 0.0, FLOOR_B)
b.flat("f0_1", 1, 0, 0.0, FLOOR_B)
b.flat_rect("f0_2", 2, 0, 0.0, FLOOR_A)
b.flat_rect("f0_3", 4, 0, 0.0, FLOOR_A)
b.flat_rect("f0_4", 6, 0, 0.0, FLOOR_A)
b.flat("f0_5", 8, 0, 0.0, FLOOR_B)

b.flat("f1_0", 0, 1, 0.0, FLOOR_B)
b.flat_rect("f1_1", 1, 1, 0.0, FLOOR_A)
b.flat_rect("f1_2", 3, 1, 0.0, FLOOR_A)
b.flat_rect("f1_3", 5, 1, 0.0, FLOOR_A)
b.flat("f1_4", 7, 1, 0.0, FLOOR_B)
b.flat("f1_5", 8, 1, 0.0, FLOOR_B)

b.flat_rect("f2_0", 0, 2, 0.0, FLOOR_A)
b.flat("f2_1", 2, 2, 0.0, FLOOR_B)
b.flat("f2_2", 3, 2, 0.0, TRAY)
b.flat("f2_3", 4, 2, 0.0, TRAY)
b.flat("f2_4", 5, 2, 0.0, FLOOR_B)
b.flat_rect("f2_5", 6, 2, 0.0, FLOOR_A)
b.flat("f2_6", 8, 2, 0.0, FLOOR_B)

b.flat_rect("f3_0", 0, 3, 0.0, FLOOR_A)
b.flat("f3_1", 2, 3, 0.0, FLOOR_B)
b.flat("f3_2", 3, 3, 0.0, TRAY)
b.flat("f3_3", 4, 3, 0.0, TRAY)
b.flat("f3_4", 5, 3, 0.0, FLOOR_B)
b.flat("f3_5", 6, 3, 0.0, FLOOR_B)
b.flat("f3_6", 7, 3, 0.0, FLOOR_B)
b.flat("f3_7", 8, 3, 0.0, FLOOR_B)

# =================================================================
# 2. 蛋糕底层 (x [3,5], y [2,4], z 0..1): 2x2 大墙环, 八片转角互咬
# =================================================================
b.wall_ns("ck1_s_w", 3, 2.0, 0, CAKE1)
b.wall_ns("ck1_s_e", 4, 2.0, 0, CAKE1)
b.wall_ew("ck1_w_s", 3.0, 2, 0, CAKE1)
b.wall_ew("ck1_w_n", 3.0, 3, 0, CAKE1)
b.wall_ew("ck1_e_s", 5.0, 2, 0, CAKE1)
b.wall_ew("ck1_e_n", 5.0, 3, 0, CAKE1)
b.wall_ns("ck1_n_w", 3, 4.0, 0, CAKE1)
b.wall_ns("ck1_n_e", 4, 4.0, 0, CAKE1)

# =================================================================
# 3. 奶油平台 (z=1): 4 片方板, 每片压两段墙顶 + 邻板拼缝
# =================================================================
b.flat("cr_sw", 3, 2, 1.0, CREAM)
b.flat("cr_se", 4, 2, 1.0, CREAM)
b.flat("cr_nw", 3, 3, 1.0, CREAM)
b.flat("cr_ne", 4, 3, 1.0, CREAM)

# =================================================================
# 4. 蛋糕第 2 层 (x [3,4], y [2,3], z 1..2): 1x1 墙环退台在西南角
# =================================================================
b.wall_ns("ck2_s", 3, 2.0, 1, CAKE2)
b.wall_ew("ck2_w", 3.0, 2, 1, CAKE2)
b.wall_ew("ck2_e", 4.0, 2, 1, CAKE2)
b.wall_ns("ck2_n", 3, 3.0, 1, CAKE2)
b.flat("ck2_cap", 3, 2, 2.0, CREAM)

# =================================================================
# 5. 生日蜡烛 x6: 顶盖四沿 x4 + 底层平台外沿 x2, 全部一线双吸
# =================================================================
b.crest_ns("cd_top_s", 3, 2.0, 2.0, CANDLE[0])
b.crest_ew("cd_top_w", 3.0, 2, 2.0, CANDLE[1])
b.crest_ew("cd_top_e", 4.0, 2, 2.0, CANDLE[2])
b.crest_ns("cd_top_n", 3, 3.0, 2.0, CANDLE[3])
b.crest_ew("cd_low_e", 5.0, 2, 1.0, CANDLE[4])
b.crest_ns("cd_low_n", 4, 4.0, 1.0, CANDLE[5])

# =================================================================
# 6. 彩旗门 (x [0,1], 跨 y [0,2]): 双柱 2 节 + 顶横板 + 双旗
# =================================================================
b.wall_ns("gt_s0", 0, 0.0, 0, GATE)
b.wall_ns("gt_s1", 0, 0.0, 1, GATE)
b.wall_ns("gt_n0", 0, 2.0, 0, GATE)
b.wall_ns("gt_n1", 0, 2.0, 1, GATE)
b.flat_rect("gt_beam", 0, 0, 2.0, BEAM, axis="y")
b.crest_ns("gt_flag_s", 0, 0.0, 2.0, FLAG_A)
b.crest_ns("gt_flag_n", 0, 2.0, 2.0, FLAG_B)

# =================================================================
# 7. 派对帽 x2: 等边四坡三角锥落地自锁
# =================================================================
PH_W = b.hat4("ph_w", 7, 1, 0.0, HAT_W, shape="equilateral_triangle")
PH_E = b.hat4("ph_e", 7, 3, 0.0, HAT_E, shape="equilateral_triangle")

# =================================================================
# 8. 气球 x4: 瘦高等腰三角骑地板拼缝
# =================================================================
b.spire_ns("bl_0", 1, 1.0, 0.0, BALLOON[0])
b.spire_ns("bl_1", 8, 1.0, 0.0, BALLOON[1])
b.spire_ns("bl_2", 2, 3.0, 0.0, BALLOON[2])
b.spire_ns("bl_3", 5, 3.0, 0.0, BALLOON[3])

# =================================================================
# 教程步骤 (14 步)
# =================================================================
b.step(
    "铺地板南行 (y [0,1]): 黄方板与青长板拼出彩格。",
    ["f0_0", "f0_1", "f0_2", "f0_3", "f0_4", "f0_5"],
    tip="西端两片黄方板是彩旗门的柱础 —— 南沿整边留给门柱。",
)
b.step(
    "铺地板第二行 (y [1,2]): 方板落在门柱与派对帽脚下。",
    ["f1_0", "f1_1", "f1_2", "f1_3", "f1_4", "f1_5"],
    highlight=["f0_0"],
    tip="方板四条边都是整边 —— 墙脚、帽底、气球缝全靠它们。",
)
b.step(
    "铺地板第三行 (y [2,3]): 两片灰托盘 (x [3,5]) 垫在蛋糕脚下。",
    ["f2_0", "f2_1", "f2_2", "f2_3", "f2_4", "f2_5", "f2_6"],
    highlight=["f1_2"],
    tip="托盘的外沿就是蛋糕底层大墙环的落脚线。",
)
b.step(
    "铺地板北行 (y [3,4]): 再垫两片托盘, 2x2 蛋糕托盘就位。",
    ["f3_0", "f3_1", "f3_2", "f3_3", "f3_4", "f3_5", "f3_6", "f3_7"],
    highlight=["f2_2", "f2_3"],
    tip="派对场地铺好了 —— 接下来是全场主角: 大蛋糕。",
)
b.step(
    "立蛋糕底层 2x2 大墙环: 每边 2 片粉墙, 八片转角竖边互咬。",
    ["ck1_s_w", "ck1_s_e", "ck1_e_s", "ck1_e_n",
     "ck1_n_e", "ck1_n_w", "ck1_w_n", "ck1_w_s"],
    highlight=["f2_2", "f3_3"],
    tip="沿托盘外沿顺时针立一圈 —— 大墙环闭合的瞬间就稳了。",
)
b.step(
    "铺奶油平台: 4 片透明方板, 每片同时压两段墙顶与邻板拼缝。",
    ["cr_sw", "cr_se", "cr_nw", "cr_ne"],
    highlight=["ck1_s_w", "ck1_n_e"],
    tip="每片平台都是双向受力 —— 墙顶与拼缝一起吸, 处处成环。",
)
b.step(
    "叠蛋糕第 2 层: 1x1 紫墙环退台踩在平台西南角。",
    ["ck2_s", "ck2_w", "ck2_e", "ck2_n"],
    highlight=["cr_sw"],
    tip="东墙与北墙踩的是平台拼缝 (一线双吸) —— 阶梯蛋糕的秘密。",
)
b.step(
    "盖奶油顶并插顶层蜡烛: 奶油盖四边压四墙顶, 4 支蜡烛骑满四沿。",
    ["ck2_cap", "cd_top_s", "cd_top_w", "cd_top_e", "cd_top_n"],
    highlight=["ck2_s"],
    tip="每支蜡烛底边都落在盖板沿+墙顶的同一条线上 —— 一线双吸。",
)
b.step(
    "插底层蜡烛: 平台东沿与北沿再骑 2 支。",
    ["cd_low_e", "cd_low_n"],
    highlight=["cr_se", "cr_ne"],
    tip="6 支蜡烛 —— 今天过 6 岁生日的就是你!",
)
b.step(
    "立彩旗门双柱 (x [0,1]): 南北柱各叠 2 节, 柱脚吸地板南沿与拼缝。",
    ["gt_s0", "gt_s1", "gt_n0", "gt_n1"],
    highlight=["f0_0", "f1_0"],
    tip="双柱相距 2 格 —— 顶横板正好横跨过去。",
)
b.step(
    "架门顶横板并骑双旗: 横板两短边分别压双柱顶, 粉红双旗骑上板沿。",
    ["gt_beam", "gt_flag_s", "gt_flag_n"],
    highlight=["gt_s1", "gt_n1"],
    tip="横板双端受力零悬挑 —— 柱-板-柱-地面锁成门式刚架。",
)
b.step(
    "拼西派对帽 (x [7,8], y [1,2]): 4 片红色等边三角斜棱两两互吸。",
    PH_W,
    highlight=["f1_4"],
    tip="帽子基线踩满地板整边, 四棱自锁 —— 越推越紧。",
)
b.step(
    "拼东派对帽 (x [7,8], y [3,4]): 蓝帽与红帽并排。",
    PH_E,
    highlight=["ph_w_s"],
    tip="一人一顶 —— 寿星戴红帽, 客人戴蓝帽。",
)
b.step(
    "插四只气球: 瘦高三角骑地板拼缝, 红黄蓝紫直上 2.0 —— 派对开始!",
    ["bl_0", "bl_1", "bl_2", "bl_3"],
    highlight=["gt_beam", "ck2_cap"],
    tip="气球重心正压拼缝铰链线 —— 唱完生日歌再吹蜡烛。",
)

b.finalize(
    model_id="birthday_party_01",
    name="生日派对",
    name_en="Birthday Party 01",
    description=(
        "只用核心九片型的生日派对现场: 主角是全库第一只阶梯双层"
        "大蛋糕 —— 底层 2x2 大墙环八片转角竖边互咬, 奶油平台每片"
        "同时压两段墙顶与邻板拼缝 (处处成环), 第 2 层 1x1 墙环退台"
        "踩在平台西南角, 6 支等边三角蜡烛全部一线双吸 (盖板沿+"
        "墙顶) 重心正压铰链; 场外彩旗门双柱托横板 (双端受力零悬挑)"
        " 骑粉红双旗, 两顶派对帽四棱自锁落地, 四只气球瘦高三角骑"
        "地板拼缝直上 2.0 —— 许愿吹蜡烛之前, 先把派对现场搭出来。"
    ),
    difficulty=3,
    tags=["节日", "生日", "派对", "蛋糕", "进阶"],
    min_pieces=69,
    min_steps=14,
)
