#!/usr/bin/env python3
"""生成模型 data/models/duckling_pond_01.json (池塘小黄鸭)。

D1 补员批 4 模型 4/4 (难度配额解冻线 D1 >= 20, 路径 B1): 入门档
动物世界选题 —— 浮在池塘上的小黄鸭。结构签名是"叠层动物": 身体
是 2x1 封顶箱体, 头部是骑在身顶前格上的 1x1 二层小塔 (墙脚整边
吸身顶方板与拼缝), 橙色面墙当嘴、窗格方当眼睛; 两片蓝色长板铺
在身体两侧当池塘水面, 东角一片绿色荷叶, 尾巴和翅膀是三面立起的
橙色小旗。与凉亭 (围院中心亭)、板桥 (墩-梁-板) 和折墙 (开放
折线) 的结构逻辑完全不同 —— 本批唯一的双层叠塔结构。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 鸭头朝西 -x):
  - 池塘水面 2 长板 + 荷叶 1 方板 + 身体底板 1 长板           4 片
  - 身体一圈 6 片方墙 (z 0..1, 竖棱角缝互吸)                  6 片
  - 身顶 2 片方板 (z=1, 四边整边锁住墙顶)                     2 片
  - 头部小塔 4 墙 + 1 顶 (z 1..2, 骑在身顶前格上)             5 片
  - 尾巴 + 双翅 3 面小旗 (等边三角, 与墙顶整边重合)           3 片
  合计 20 片, 5 个教程步骤, 4 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 池塘长板长边与身体底板长边完整贴合, 荷叶整边吸池塘短边 ——
    水面与鸭身锁成一体, 全部接地;
  - 身体墙脚接地, 竖棱角缝互吸成环; 身顶方板四边锁墙顶,
    头部墙脚整边骑住身顶方板边与拼缝 (R2 环环相扣);
  - 先合围后封顶, 箱腔封闭前内部无待放片 (R7b 无包围放置);
  - 最高点 2.0 (头顶) < 2.5, 不触发 R8 高层结构判定。

用法: python3 tools/generate_duckling_pond_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

POND = "blue"       # 池塘水面
LILY = "green"      # 荷叶
BODY = "yellow"     # 鸭身
BEAK = "orange"     # 嘴 (头部面墙)
EYE = "clear"       # 眼睛 (窗格方)
WING = "orange"     # 尾巴与翅膀

# =================================================================
# 1. 池塘、荷叶与身体底板 (全部接地, 长边/整边互吸)
# =================================================================
b.flat_rect("pond_s", 0, -1, 0.0, POND)     # [0,2] x [-1,0]
b.flat_rect("pond_n", 0, 1, 0.0, POND)      # [0,2] x [1,2]
b.flat("lily", 2, -1, 0.0, LILY)            # [2,3] x [-1,0]
b.flat_rect("belly", 0, 0, 0.0, BODY)       # [0,2] x [0,1]

# =================================================================
# 2. 身体一圈 (z 0..1): 南 2 + 北 2 + 西 1 + 东 1
# =================================================================
b.wall_ns("body_s0", 0, 0.0, 0, BODY)
b.wall_ns("body_s1", 1, 0.0, 0, BODY)
b.wall_ns("body_n0", 0, 1.0, 0, BODY)
b.wall_ns("body_n1", 1, 1.0, 0, BODY)
b.wall_ew("body_w", 0.0, 0, 0, BODY)
b.wall_ew("body_e", 2.0, 0, 0, BODY)

# =================================================================
# 3. 身顶 (z=1): 两片方板, 四边整边锁住墙顶
# =================================================================
b.flat("back_w", 0, 0, 1.0, BODY)
b.flat("back_e", 1, 0, 1.0, BODY)

# =================================================================
# 4. 头部小塔 (z 1..2, 骑在身顶前格 [0,1]x[0,1] 上)
# =================================================================
b.add("head_s", "window_square", (0.5, 0.0, 1.5), (90, 0, 0), EYE)
b.wall_ns("head_n", 0, 1.0, 1, BODY)
b.wall_ew("head_w", 0.0, 0, 1, BEAK)
b.wall_ew("head_e", 1.0, 0, 1, BODY)
b.flat("head_top", 0, 0, 2.0, BODY)

# =================================================================
# 5. 尾巴与双翅 (等边三角, 与墙顶整边重合)
# =================================================================
b.crest_ns("wing_s", 1, 0.0, 1.0, WING)
b.crest_ns("wing_n", 1, 1.0, 1.0, WING)
b.crest_ew("tail", 2.0, 0, 1.0, WING)

# =================================================================
# 教程步骤 (5 步)
# =================================================================
b.step(
    "铺池塘和鸭肚: 两片蓝色长板当水面, 黄色长板夹在中间当鸭肚, 东角吸上绿色荷叶。",
    ["pond_s", "pond_n", "belly", "lily"],
    tip="长板长边完整贴合 —— 小黄鸭要浮在水面正中央。",
)
b.step(
    "围鸭身: 六片黄色方墙墙脚骑住鸭肚板边, 竖棱角缝互吸围成一圈。",
    ["body_s0", "body_s1", "body_n0", "body_n1", "body_w", "body_e"],
    highlight=["belly"],
)
b.step(
    "盖鸭背: 两片黄色方板四边整边锁住墙顶, 圆滚滚的身体封好了。",
    ["back_w", "back_e"],
    highlight=["body_s0", "body_e"],
    tip="先合围再封顶 —— 装配顺序也是设计的一部分。",
)
b.step(
    "搭鸭头: 四片小墙骑上身顶前格, 橙色面墙是嘴、窗格方是眼睛, 最后盖上头顶。",
    ["head_s", "head_n", "head_w", "head_e", "head_top"],
    highlight=["back_w"],
    tip="头部墙脚正好压住身顶方板的边和拼缝 —— 二层小塔稳稳当当。",
)
b.step(
    "翘尾巴张翅膀: 三面橙色小旗骑上身后墙顶, 小黄鸭下水啦!",
    ["wing_s", "wing_n", "tail"],
    highlight=["back_e"],
)

b.finalize(
    model_id="duckling_pond_01",
    name="池塘小黄鸭",
    name_en="Duckling Pond 01",
    description=(
        "入门档动物世界: 浮在池塘上的小黄鸭, 结构签名是'叠层动物' "
        "—— 身体是 2x1 封顶箱体, 六片方墙竖棱角缝互吸、身顶方板四边"
        "锁墙顶; 头部是骑在身顶前格上的 1x1 二层小塔, 墙脚整边压住"
        "身顶方板边与拼缝, 橙色面墙当嘴、透明窗格方当眼睛; 两片蓝色"
        "长板长边完整贴住鸭肚当池塘水面, 东角一片绿色荷叶, 尾巴和"
        "双翅是三面立起的橙色小旗。20 片全程受压零悬挑, 头顶 2.0 "
        "不触发高层判定, 搭完就能让小黄鸭在桌面池塘里巡游。"
    ),
    difficulty=1,
    tags=["动物世界", "小鸭", "池塘", "亲子入门"],
    min_pieces=20,
    min_steps=5,
    series="animal_world",
)
print("已写入 series=animal_world")
