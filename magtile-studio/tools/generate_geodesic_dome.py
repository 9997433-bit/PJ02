#!/usr/bin/env python3
"""生成模型 data/models/geodesic_dome_01.json (测地穹顶)。

第二批模型 ⑧: 未来建筑主题 —— 模型库第一座非直角网格建筑:
以正六边形为平面的观景穹顶, 中段是 12 片等边三角形组成的
"反棱柱三角带" (上下六边形错开 30 度, 真正的测地线网格),
顶部六边形压盖再冠以 6 片等腰三角形的浅锥王冠。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 地面: 正六边形地板 + 六瓣广场 (方板 x6 + 楔形三角 x6)      13 片
  - 鼓身 (z 0..2): 六边形筒壁两层, 下层留 1 格门洞             11 片
  - 三角带 (z 2..2.856): 6 片正立 + 6 片倒立等边三角形,
    上下六边形错开 30 度 —— 反棱柱测地网格                     12 片
  - 压盖: 顶部六边形盖板 (转 30 度正好吸住三角带上沿)           1 片
  - 王冠: 6 片等腰三角形浅锥, 斜棱两两互吸自锁成环               6 片
  - 围栏: 广场外沿 6 片等边三角旗饰                              6 片
  合计 49 片, 15 个教程步骤, 4 种磁力片形状。

几何要点 (全部整边精确吸合):
  - 六边形磁力片边长恰为 1, 与正方形/三角形边长通用;
  - 反棱柱带高 sqrt(1 - 4*sin^2(15°)) ≈ 0.8556, 12 片三角形
    的所有斜边两两共线等长;
  - 王冠等腰三角形腰长 sqrt(1.25) 与相邻腰完全重合, 锥尖高 +0.5。

用法: python3 tools/generate_geodesic_dome.py  (在 magtile-studio 目录下运行)
"""

import math

from magtile_gen import ModelBuilder

b = ModelBuilder()

R = 1.0                                   # 六边形外接圆半径 (边长 1)
V = [(R * math.cos(math.radians(60 * k)),
      R * math.sin(math.radians(60 * k))) for k in range(6)]        # 底六边形顶点
BAND_H = math.sqrt(1.0 - (2.0 * math.sin(math.radians(15))) ** 2)   # 0.855623
Z_RING = 2.0 + BAND_H                     # 顶六边形高度
T = [(R * math.cos(math.radians(60 * k + 30)),
      R * math.sin(math.radians(60 * k + 30))) for k in range(6)]   # 顶六边形顶点
DOOR = 0                                  # 门洞所在的鼓身侧面编号


def n_out(k):
    """第 k 条边 (V[k] -> V[k+1]) 的水平外法向 (单位向量)。"""
    ang = math.radians(60 * k + 30)
    return (math.cos(ang), math.sin(ang), 0.0)


# =================================================================
# 1. 地面: 六边形地板 + 六瓣广场 (方板向外、楔形三角补角)
# =================================================================
b.add("floor", "hexagon", (0, 0, 0), (0, 0, 0), "gray")
for k in range(6):
    v0, v1 = V[k], V[(k + 1) % 6]
    b.place_edge(f"pl_sq_{k}", "square", 0,
                 (v0[0], v0[1], 0.0), (v1[0], v1[1], 0.0), n_out(k), "green")
for k in range(6):
    # 顶点 V[k] 处的 60 度楔形空隙, 由等边三角形正好补满
    vk = (V[k][0], V[k][1], 0.0)
    p_prev = (V[k][0] + n_out(k - 1)[0], V[k][1] + n_out(k - 1)[1], 0.0)
    p_next = (V[k][0] + n_out(k)[0], V[k][1] + n_out(k)[1], 0.0)
    b.place_tri(f"pl_tri_{k}", "equilateral_triangle", p_prev, p_next, vk, "yellow")

# =================================================================
# 2. 鼓身: 六边形筒壁两层 (下层第 DOOR 面留门洞)
# =================================================================
for k in range(6):
    if k == DOOR:
        continue
    v0, v1 = V[k], V[(k + 1) % 6]
    b.place_edge(f"dr1_{k}", "square", 0,
                 (v0[0], v0[1], 0.0), (v1[0], v1[1], 0.0), (0, 0, 1), "cyan")
for k in range(6):
    v0, v1 = V[k], V[(k + 1) % 6]
    b.place_edge(f"dr2_{k}", "square", 0,
                 (v0[0], v0[1], 1.0), (v1[0], v1[1], 1.0), (0, 0, 1), "clear")

# =================================================================
# 3. 三角带: 反棱柱测地网格 (正立三角底边吸鼓身顶沿,
#    倒立三角两腰吸正立三角斜边, 上沿围成转 30 度的顶六边形)
# =================================================================
for k in range(6):
    v0, v1 = V[k], V[(k + 1) % 6]
    apex = (T[k][0], T[k][1], Z_RING)
    b.place_tri(f"up_{k}", "equilateral_triangle",
                (v0[0], v0[1], 2.0), (v1[0], v1[1], 2.0), apex, "clear")
for k in range(6):
    t0 = (T[k - 1][0], T[k - 1][1], Z_RING)
    t1 = (T[k][0], T[k][1], Z_RING)
    vk = (V[k][0], V[k][1], 2.0)
    b.place_tri(f"dn_{k}", "equilateral_triangle", t1, t0, vk, "cyan")

# =================================================================
# 4. 压盖 + 王冠: 顶六边形盖板 (转 30 度), 上面 6 片等腰浅锥
# =================================================================
b.add("cap", "hexagon", (0, 0, Z_RING), (0, 0, 30), "blue")
APEX = (0.0, 0.0, Z_RING + 0.5)
for k in range(6):
    t0 = (T[k][0], T[k][1], Z_RING)
    t1 = (T[(k + 1) % 6][0], T[(k + 1) % 6][1], Z_RING)
    b.place_tri(f"cr_{k}", "isosceles_triangle", t0, t1, APEX, "purple")

# =================================================================
# 5. 围栏旗饰: 广场方板外沿立 6 片等边三角
# =================================================================
for k in range(6):
    e0 = (V[k][0] + n_out(k)[0], V[k][1] + n_out(k)[1], 0.0)
    e1 = (V[(k + 1) % 6][0] + n_out(k)[0], V[(k + 1) % 6][1] + n_out(k)[1], 0.0)
    b.place_edge(f"fl_{k}", "equilateral_triangle", 0, e0, e1, (0, 0, 1), "red")

# =================================================================
# 教程步骤 (15 步)
# =================================================================
b.step(
    "放好六边形地板: 1 片灰色六边形平放桌面正中, 它是整座穹顶的地基。",
    ["floor"],
    tip="六边形的每条边都和正方形边一样长 1 格 —— 这是本模型的钥匙。",
)
b.step(
    "铺设广场方板: 6 片绿色正方形沿六边形的 6 条边向外平铺。",
    [f"pl_sq_{k}" for k in range(6)],
    highlight=["floor"],
    tip="每片方板一条边与地板整边吸合, 铺完像一朵六瓣花。",
)
b.step(
    "补齐广场楔角: 相邻方板之间的 60 度缺口正好塞进 1 片黄色等边三角形, "
    "共 6 片。",
    [f"pl_tri_{k}" for k in range(6)],
    highlight=["pl_sq_0", "pl_sq_1"],
    tip="三角形两条边分别吸住两侧方板 —— 广场从此连成一个整圆盘。",
)
b.step(
    "竖立鼓身下层: 5 片青色正方形沿地板边缘立起 (朝东北的一面留作门洞), "
    "相邻墙的竖边在拐角处互相吸合。",
    [f"dr1_{k}" for k in range(6) if k != DOOR],
    highlight=["floor"],
    tip="每面墙底边吸地板边、侧边吸邻墙 —— 六边形筒壁自己就能锁紧。",
)
b.step(
    "叠加鼓身上层前半: 3 片透明正方形叠在下层墙顶 (从门洞左侧数起)。",
    ["dr2_1", "dr2_2", "dr2_3"],
    highlight=["dr1_1"],
    tip="上下两层墙的横边要完全对齐, 透明墙让阳光洒进穹顶。",
)
b.step(
    "叠加鼓身上层后半并封门楣: 再叠 2 片透明墙, 最后 1 片横跨门洞上方, "
    "两条竖边分别吸住左右邻墙。",
    ["dr2_4", "dr2_5", f"dr2_{DOOR}"],
    highlight=["dr2_1", "dr2_5"],
    tip="门楣那片没有下层墙托底, 全靠两侧竖边吸牢 —— 这就是过梁。",
)
b.step(
    "安装三角带正立片 (前半): 3 片透明等边三角形底边吸鼓身顶沿, "
    "向内倾斜, 尖端指向穹顶轴线上空。",
    ["up_0", "up_1", "up_2"],
    highlight=["dr2_0"],
    tip="尖端悬空不用怕 —— 等一圈装完它们会互相锁住。",
)
b.step(
    "安装三角带正立片 (后半): 其余 3 片, 6 个尖端围成一个转了 30 度的"
    "小六边形。",
    ["up_3", "up_4", "up_5"],
    highlight=["up_0"],
    tip="从正上方看: 6 个尖端正好落在下方 6 个墙拐角的正中间上空。",
)
b.step(
    "嵌入三角带倒立片 (前半): 3 片青色等边三角形尖端朝下, "
    "两条腰分别吸住左右正立片的斜边。",
    ["dn_0", "dn_1", "dn_2"],
    highlight=["up_0", "up_5"],
    tip="倒立片一嵌进去, 三角带立刻变硬 —— 这就是测地穹顶的奥秘。",
)
b.step(
    "嵌入三角带倒立片 (后半): 其余 3 片, 正倒三角交替围成完整一圈。",
    ["dn_3", "dn_4", "dn_5"],
    highlight=["dn_0"],
    tip="装完轻按整圈三角带: 12 片应像一个整体一样纹丝不动。",
)
b.step(
    "盖上顶板: 1 片蓝色六边形转 30 度放上三角带顶沿, 6 条边同时吸合。",
    ["cap"],
    highlight=["dn_0", "up_0"],
    tip="注意方向: 顶板的角要对准倒立三角的上沿接缝才吸得上。",
)
b.step(
    "安装王冠 (前半): 3 片紫色等腰三角形底边吸顶板边, 向内浅浅倾斜。",
    ["cr_0", "cr_1", "cr_2"],
    highlight=["cap"],
    tip="等腰三角形又高又尖, 6 片的尖端将在顶板上方 0.5 格处会合。",
)
b.step(
    "安装王冠 (后半): 其余 3 片, 6 条斜棱两两互吸, 锥尖自锁成环。",
    ["cr_3", "cr_4", "cr_5"],
    highlight=["cr_0"],
    tip="最后一片轻轻卡进去, 王冠合拢 —— 穹顶封顶!",
)
b.step(
    "竖立围栏旗饰 (前半): 3 片红色等边三角形立在广场方板外沿。",
    ["fl_0", "fl_1", "fl_2"],
    highlight=["pl_sq_0"],
    tip="底边与方板外沿整边吸合, 像围着穹顶的一圈小旗。",
)
b.step(
    "竖立围栏旗饰 (后半): 其余 3 片, 测地穹顶落成!",
    ["fl_3", "fl_4", "fl_5"],
    highlight=["fl_0"],
    tip="从门洞望进去: 阳光穿过透明鼓身与三角带, 洒满整个穹顶。",
)

b.finalize(
    model_id="geodesic_dome_01",
    name="测地穹顶",
    name_en="Geodesic Dome 01",
    description=(
        "模型库第一座非直角网格建筑: 正六边形地基上立起两层筒壁 (留门洞与"
        "透明门楣), 中段 12 片等边三角形组成上下错开 30 度的反棱柱测地三角带, "
        "顶部六边形压盖再冠以 6 片等腰浅锥王冠 —— 所有斜棱两两精确互吸, "
        "一圈装完自锁成环, 越按越紧。"
    ),
    difficulty=3,
    tags=["未来建筑", "穹顶", "测地网格", "进阶"],
    min_pieces=48,
    min_steps=15,
)
