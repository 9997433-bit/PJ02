#!/usr/bin/env python3
"""生成模型 data/models/bullet_train_01.json (高速动车组)。

铁路/火车站主题: 全库第一列流线型高铁 —— 与单轨列车段 (高架墩柱
托梁、跨座箱车) 和蒸汽机车 (六边形外露动轮) 刻意区分, 本作的
结构逻辑是 "贴地板式道床 + 双坡流线车头 + 门式接触网":
无砟板式道床贴地铺 13 格 (长板横铺, y [0,2]), 北侧绿化带镶边;
车身 2 格宽横跨整幅道床, 两侧整排窗格方观景窗 (南墙嵌乘客门),
车顶长板横跨双墙 (双端受力); 招牌是车头车尾各一对 30 度长方形
斜坡拼成的流线鼻锥 —— 两坡沿斜脊长边互吸、顶短边吸车顶前沿、
坡尾贴地, 高铁的"子弹头"就是两片坡的几何; 车顶中央受电弓骑
拼缝, 车尾信号鳍骑坡顶; 线路两端各一座门式接触网架 (双柱顶
横板, 双端受力零悬挑), 绿化带上红绿里程标对望。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 板式道床 (x [0,13], y [0,2]): 长板横铺 x13                  13 片
  - 绿化带 (x [1,13], y [2,3]): 方板 x2 + 长板 x5                 7 片
  - 车身侧墙 (x [3,10], z 0..1): 南墙 门框方 x1 + 窗格方 x6,
    北墙 窗格方 x7                                               14 片
  - 车顶 (z=1): 横跨长板 x6 + 方板 x2 (受电弓骑其拼缝)            8 片
  - 流线鼻锥: 车头/车尾各 2 片 30 度斜坡                          4 片
  - 车顶装备: 受电弓 x1 + 车尾信号鳍 x1                           2 片
  - 门式接触网架 x2: 双柱 (各 2 节) + 顶横板 (每座 5 片)         10 片
  - 里程标: 绿化带红绿等边三角 x2                                 2 片
  合计 60 片, 12 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 鼻锥双坡: 顶短边整边吸车顶前沿, 相邻两坡沿斜脊长边互吸,
    坡尾自然贴地 —— 每片坡自身接地, 剪断顶铰链也掉不下来;
  - 车顶横跨长板两短边分别整边压南北墙顶 (双端受力零悬挑),
    墙-顶-墙-道床锁成连续箱形闭环;
  - 接触网架横板两短边同吸双柱顶 (双端受力), 柱-板-柱-道床
    成门式刚架; 全场最高点 2.0, 不触发 R8 高层检查;
  - 受电弓/信号鳍/里程标重心正压铰链线, 力矩为零。

用法: python3 tools/generate_bullet_train.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

SLAB = "gray"       # 板式道床
VERGE = "green"     # 绿化带
BODY = "clear"      # 观景窗带
DOOR = "orange"     # 乘客门
NOSE = "red"        # 流线鼻锥
ROOF = "red"        # 车顶
PANTO = "gray"      # 受电弓
FIN = "yellow"      # 车尾信号鳍
MAST = "gray"       # 接触网立柱
BEAM = "yellow"     # 接触网横板
MK_W = "red"        # 西里程标
MK_E = "green"      # 东里程标

# =================================================================
# 1. 板式道床 (x [0,13], y [0,2]): 13 片长板横铺
# =================================================================
for x in range(13):
    b.flat_rect(f"slab_{x}", x, 0, 0.0, SLAB, axis="y")

# =================================================================
# 2. 绿化带 (x [1,13], y [2,3]): 两端方板 + 中段长板
# =================================================================
b.flat("vg_w", 1, 2, 0.0, VERGE)
for k, x0 in enumerate((2, 4, 6, 8, 10)):
    b.flat_rect(f"vg_{k}", x0, 2, 0.0, VERGE)
b.flat("vg_e", 12, 2, 0.0, VERGE)

# =================================================================
# 3. 车身侧墙 (x [3,10], z 0..1): 南门北窗, 整排观景窗带
# =================================================================
b.add("bd_s_3", "door_frame", (3.5, 0.0, 0.5), (90, 0, 0), DOOR)
for x in range(4, 10):
    b.add(f"bd_s_{x}", "window_square", (x + 0.5, 0.0, 0.5), (90, 0, 0), BODY)
for x in range(3, 10):
    b.add(f"bd_n_{x}", "window_square", (x + 0.5, 2.0, 0.5), (90, 0, 0), BODY)

# =================================================================
# 4. 车顶 (z=1): 横跨长板 + 中央方板 (受电弓骑拼缝)
# =================================================================
for x in (3, 4, 5, 7, 8, 9):
    b.flat_rect(f"rf_{x}", x, 0, 1.0, ROOF, axis="y")
b.flat("rf_6s", 6, 0, 1.0, ROOF)
b.flat("rf_6n", 6, 1, 1.0, ROOF)

# =================================================================
# 5. 流线鼻锥: 车头 (西) / 车尾 (东) 各 2 片 30 度斜坡
# =================================================================
b.ramp("nose_s", "-x", 3.0, 0, 1.0, NOSE)
b.ramp("nose_n", "-x", 3.0, 1, 1.0, NOSE)
b.ramp("tail_s", "+x", 10.0, 0, 1.0, NOSE)
b.ramp("tail_n", "+x", 10.0, 1, 1.0, NOSE)

# =================================================================
# 6. 车顶装备: 受电弓 (骑方板拼缝) + 车尾信号鳍 (骑坡顶)
# =================================================================
b.crest_ew("panto", 6.0, 0, 1.0, PANTO)
b.crest_ew("fin", 10.0, 1, 1.0, FIN)

# =================================================================
# 7. 门式接触网架: 西 (x [0,1]) / 东 (x [12,13])
# =================================================================
for tag, x0 in (("w", 0), ("e", 12)):
    b.wall_ns(f"ct_{tag}_s0", x0, 0.0, 0, MAST)
    b.wall_ns(f"ct_{tag}_s1", x0, 0.0, 1, MAST)
    b.wall_ns(f"ct_{tag}_n0", x0, 2.0, 0, MAST)
    b.wall_ns(f"ct_{tag}_n1", x0, 2.0, 1, MAST)
    b.flat_rect(f"ct_{tag}_beam", x0, 0, 2.0, BEAM, axis="y")

# =================================================================
# 8. 里程标: 绿化带两端红绿等边三角
# =================================================================
b.crest_ns("mk_w", 1, 3.0, 0.0, MK_W)
b.crest_ns("mk_e", 12, 3.0, 0.0, MK_E)

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺道床西半段: 7 片灰色长板横铺 (x [0,7], 每片跨 y [0,2])。",
    [f"slab_{x}" for x in range(7)],
    tip="板式道床没有道砟 —— 高铁贴着这条平板飞驰。",
)
b.step(
    "铺道床东半段: 再横铺 6 片, 道床贯通 13 格。",
    [f"slab_{x}" for x in range(7, 13)],
    highlight=["slab_6"],
    tip="长板之间的长边拼缝对齐网格线 —— 道床铺直了车才稳。",
)
b.step(
    "镶绿化带: 北沿 2 片方板 + 5 片长板 (x [1,13], y [2,3])。",
    ["vg_w", "vg_0", "vg_1", "vg_2", "vg_3", "vg_4", "vg_e"],
    highlight=["slab_1", "slab_12"],
    tip="绿化带贴着道床北沿 —— 里程标就立在它的边上。",
)
b.step(
    "立车身南墙: 橙色乘客门在车头, 6 扇透明观景窗一字排开 (x [3,10])。",
    ["bd_s_3"] + [f"bd_s_{x}" for x in range(4, 10)],
    highlight=["slab_3", "slab_9"],
    tip="墙脚整边吸道床板边 —— 高铁是贴地跑的, 不用站台架高。",
)
b.step(
    "立车身北墙: 7 扇观景窗与南墙隔道对望。",
    [f"bd_n_{x}" for x in range(3, 10)],
    highlight=["bd_s_3"],
    tip="两墙相距 2 格 —— 车顶长板正好横跨过去。",
)
b.step(
    "盖车顶: 6 片红色长板横跨双墙 (两短边分别压南北墙顶), 中央"
    "x [6,7] 改用 2 片方板 —— 拼缝留给受电弓。",
    ["rf_3", "rf_4", "rf_5", "rf_6s", "rf_6n", "rf_7", "rf_8", "rf_9"],
    highlight=["bd_s_4", "bd_n_4"],
    tip="每片车顶双端受力零悬挑 —— 墙-顶-墙-道床锁成箱形闭环。",
)
b.step(
    "拼车头鼻锥: 2 片红色 30 度斜坡, 顶短边整边吸车顶前沿, "
    "斜脊长边互吸, 坡尾贴地。",
    ["nose_s", "nose_n"],
    highlight=["rf_3"],
    tip="高铁的'子弹头'就是两片坡的几何 —— 风从坡面上滑走。",
)
b.step(
    "拼车尾鼻锥: 车尾再拼 2 片, 头尾对称的流线型完成。",
    ["tail_s", "tail_n"],
    highlight=["rf_9"],
    tip="动车组两头都是驾驶室 —— 到站不用调头, 反向就开。",
)
b.step(
    "装受电弓与信号鳍: 灰色受电弓骑上车顶方板拼缝, 黄色信号鳍"
    "骑上车尾坡顶短边。",
    ["panto", "fin"],
    highlight=["rf_6s", "tail_n"],
    tip="两片三角重心都正压铰链线, 力臂为零 —— 350 也吹不倒。",
)
b.step(
    "立西端接触网架: 双柱各叠 2 节, 黄色横板两短边同吸柱顶 —— "
    "门式刚架跨过整条线路。",
    ["ct_w_s0", "ct_w_s1", "ct_w_n0", "ct_w_n1", "ct_w_beam"],
    highlight=["slab_0"],
    tip="横板双端受力零悬挑 —— 剪断任一端, 另一端立柱仍接地。",
)
b.step(
    "立东端接触网架: 与西端对称, 电力走廊合龙。",
    ["ct_e_s0", "ct_e_s1", "ct_e_n0", "ct_e_n1", "ct_e_beam"],
    highlight=["slab_12"],
    tip="受电弓就从两座网架下穿过 —— 电从头顶来。",
)
b.step(
    "插里程标: 绿化带两端红绿等边三角对望 —— 高铁, 发车!",
    ["mk_w", "mk_e"],
    highlight=["vg_w", "vg_e"],
    tip="红标进站、绿标出站 —— 下一站, 未来城。",
)

b.finalize(
    model_id="bullet_train_01",
    name="高速动车组",
    name_en="Bullet Train 01",
    description=(
        "只用核心九片型的流线型高铁: 13 格无砟板式道床贴地横铺,"
        " 2 格宽车身横跨整幅道床 —— 两侧整排窗格方观景窗 (南墙嵌"
        "橙色乘客门), 车顶长板两短边分别压南北墙顶双端受力; 招牌是"
        "车头车尾各一对 30 度斜坡拼成的流线鼻锥 —— 顶短边吸车顶"
        "前沿、斜脊长边互吸、坡尾贴地, '子弹头'就是两片坡的几何;"
        " 车顶中央受电弓骑拼缝、车尾信号鳍骑坡顶, 线路两端门式"
        "接触网架 (双柱顶横板, 双端受力零悬挑) 跨线对望, 绿化带上"
        "红绿里程标相迎 —— 高铁发车, 下一站未来城。"
    ),
    difficulty=3,
    tags=["交通", "火车", "高铁", "城市", "进阶"],
    min_pieces=60,
    min_steps=12,
)
