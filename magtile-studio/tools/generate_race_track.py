#!/usr/bin/env python3
"""生成模型 data/models/race_track_01.json (环形赛道)。

竞速运动主题: 全库第一条"闭合环道"—— 20 片赛道板围成 7x5 的
矩形环形赛道 (中央大内场), 发车直道上一座双柱龙门横跨赛道,
南看台两级阶梯坐席由斜撑锁边, 西侧维修站三连车库开着中门,
东北角两层赛控塔戴四坡顶, 内场发车区停着红蓝双雄。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 环形赛道: 外框 7x5 的周圈 20 片                               20 片
  - 发车龙门: 内场通道板 + 双柱 (各 2 层) + 门桥板 + 冠军旗        7 片
  - 赛车 x2: 底盘 + 车头鼻翼 + 尾翼 (红蓝双雄)                     6 片
  - 南看台: 观众通道 2 + 一级台 (前后墙 + 坐板) 6 +
    二级台 (前墙/后墙柱/坐板) 8 + 两翼斜撑 2                      18 片
  - 维修站 (西侧): 通道 3 + 前墙 2 (中门) + 后墙 3 + 山墙 2 +
    车库顶 3                                                      13 片
  - 赛控塔 (东北角): 通道板 + 两层塔身 + 顶板 + 四坡顶            14 片
  - 弯角路肩: 四角 4 片红色路肩三角                                 4 片
  合计 82 片, 18 个教程步骤。

物理规则要点 (通过 R1~R8 全部校验):
  - 环形赛道是全接地闭环, 每片与前后邻板整边互吸;
  - 龙门双柱分立赛道两侧 (内柱踩内场通道板), 门桥板两短边
    同时吸双柱顶边 —— 剪断任一柱顶铰链, 另一柱仍撑住门桥;
  - 二级看台的后排墙柱直接落地、前排墙立在一级坐板上, 坐板
    前后两沿都有铰链线, 互为冗余; 两翼直角斜撑抗侧推;
  - 全部建筑通过通道板吸在赛道环上, 全场一个连通整体。

用法: python3 tools/generate_race_track.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

ASPHALT = "gray"
STAND = "blue"
SEAT = "green"
PIT = "orange"

# =================================================================
# 1. 环形赛道: 7x5 外框周圈 20 片
# =================================================================
RING = ([(x, 0) for x in range(7)] + [(x, 4) for x in range(7)]
        + [(0, y) for y in (1, 2, 3)] + [(6, y) for y in (1, 2, 3)])
for x0, y0 in RING:
    b.flat(f"tk_{x0}_{y0}", x0, y0, 0.0, ASPHALT)

# =================================================================
# 2. 发车龙门 (跨南直道 x 3..4): 内场通道板 + 双柱 + 门桥板 + 冠军旗
# =================================================================
b.flat("gt_pad", 3, 1, 0.0, SEAT)                 # 内场通道板 (y 1..2)
b.wall_ns("gt_s_lo", 3, 0.0, 0, "yellow")         # 外柱 (平面 y=0)
b.wall_ns("gt_s_hi", 3, 0.0, 1, "yellow")
b.wall_ns("gt_n_lo", 3, 2.0, 0, "yellow")         # 内柱 (平面 y=2)
b.wall_ns("gt_n_hi", 3, 2.0, 1, "yellow")
b.flat_rect("gt_beam", 3, 0, 2.0, STAND, axis="y")  # 门桥板 (y 0..2, z=2)
b.crest_ns("gt_flag", 3, 0.0, 2.0, "red")         # 冠军旗

# =================================================================
# 3. 赛车 x2 (内场发车区): 底盘 + 车头鼻翼 + 尾翼
# =================================================================
b.flat("car1", 4, 1, 0.0, "red")                  # 红车 (x 4..5)
b.crest_ew("car1_nose", 4.0, 1, 0.0, "yellow")
b.crest_ew("car1_wing", 5.0, 1, 0.0, "red")
b.flat("car2", 2, 1, 0.0, STAND)                  # 蓝车 (x 2..3)
b.crest_ew("car2_wing", 2.0, 1, 0.0, STAND)
b.crest_ew("car2_nose", 3.0, 1, 0.0, "yellow")

# =================================================================
# 4. 南看台 (y < 0, x 2..4): 两级阶梯坐席 + 两翼斜撑
# =================================================================
for x0 in (2, 3):
    b.flat(f"gs_ap_{x0}", x0, -1, 0.0, ASPHALT)   # 观众通道 (y -1..0)
    b.wall_ns(f"gs_f1_{x0}", x0, -1.0, 0, STAND)  # 一级前墙 (平面 y=-1)
    b.wall_ns(f"gs_r1_{x0}", x0, -2.0, 0, STAND)  # 一级后墙 (平面 y=-2)
    b.flat(f"gs_d1_{x0}", x0, -2, 1.0, SEAT)      # 一级坐板 (z=1)
for x0 in (2, 3):
    b.wall_ns(f"gs_f2_{x0}", x0, -2.0, 1, STAND)  # 二级前墙 (立在一级坐板上)
    b.wall_ns(f"gs_r2lo_{x0}", x0, -3.0, 0, STAND)  # 二级后墙柱下节 (落地)
    b.wall_ns(f"gs_r2hi_{x0}", x0, -3.0, 1, STAND)  # 二级后墙柱上节
    b.flat(f"gs_d2_{x0}", x0, -3, 2.0, SEAT)      # 二级坐板 (z=2)
b.brace("gs_br_w", (2.0, -3.0, 0.0), "-x", "purple")  # 西翼斜撑
b.brace("gs_br_e", (4.0, -3.0, 0.0), "+x", "purple")  # 东翼斜撑

# =================================================================
# 5. 维修站 (西侧 x < 0, y 1..4): 三连车库, 中门开敞
# =================================================================
for y0 in (1, 2, 3):
    b.flat(f"pt_ap_{y0}", -1, y0, 0.0, ASPHALT)   # 维修通道 (x -1..0)
b.wall_ew("pt_f1", -1.0, 1, 0, PIT)               # 前墙南段 (中段 y 2..3 是门)
b.wall_ew("pt_f3", -1.0, 3, 0, PIT)               # 前墙北段
for y0 in (1, 2, 3):
    b.wall_ew(f"pt_r{y0}", -2.0, y0, 0, PIT)      # 后墙 3 片
b.wall_ns("pt_gs", -2, 1.0, 0, PIT)               # 南山墙 (x -2..-1)
b.wall_ns("pt_gn", -2, 4.0, 0, PIT)               # 北山墙
for y0 in (1, 2, 3):
    b.flat(f"pt_rf_{y0}", -2, y0, 1.0, ASPHALT)   # 车库顶 3 片

# =================================================================
# 6. 赛控塔 (东北角外侧 x 7..8, y 4..5): 两层 + 顶板 + 四坡顶
# =================================================================
b.flat("ct_pad", 7, 4, 0.0, ASPHALT)              # 塔前通道板
b.wall_ns("ct_s0", 7, 4.0, 0, SEAT)
b.wall_ns("ct_n0", 7, 5.0, 0, SEAT)
b.wall_ew("ct_w0", 7.0, 4, 0, SEAT)
b.wall_ew("ct_e0", 8.0, 4, 0, SEAT)
b.wall_ns("ct_s1", 7, 4.0, 1, "clear")            # 上层四面观察窗
b.wall_ns("ct_n1", 7, 5.0, 1, "clear")
b.wall_ew("ct_w1", 7.0, 4, 1, "clear")
b.wall_ew("ct_e1", 8.0, 4, 1, "clear")
b.flat("ct_top", 7, 4, 2.0, ASPHALT)
TOWER_HAT = b.hat4("ct_hat", 7, 4, 2.0, "red", shape="equilateral_triangle")

# =================================================================
# 7. 弯角路肩: 四角 4 片红色路肩三角
# =================================================================
b.crest_ns("kb_sw", 0, 0.0, 0.0, "red")
b.crest_ns("kb_se", 6, 0.0, 0.0, "red")
b.crest_ns("kb_nw", 0, 5.0, 0.0, "red")
b.crest_ns("kb_ne", 6, 5.0, 0.0, "red")

# =================================================================
# 教程步骤 (18 步)
# =================================================================
b.step(
    "发车直道: 沿南边一字铺 7 片赛道板 (y 0..1), 相邻边互吸。",
    [f"tk_{x}_0" for x in range(7)],
    tip="这是发车直道 —— 铺得笔直, 赛车才跑得痛快。",
)
b.step(
    "东西弯道: 西边、东边各接 3 片, 环道立起两条侧边。",
    ["tk_0_1", "tk_0_2", "tk_0_3", "tk_6_1", "tk_6_2", "tk_6_3"],
    highlight=["tk_0_0", "tk_6_0"],
    tip="从直道两端向北爬 —— 每片都吸着前一片生长。",
)
b.step(
    "北直道合龙: 7 片补齐北边, 20 片闭合环道成形 —— 中央就是"
    "大内场。",
    [f"tk_{x}_4" for x in range(7)],
    highlight=["tk_0_3", "tk_6_3"],
    tip="最后一片落位时东西两头同时咔哒 —— 环道闭合的仪式感。",
)
b.step(
    "发车龙门立柱: 先在内场铺 1 片通道板, 再立双柱各 2 层 —— "
    "外柱吸赛道南沿, 内柱吸通道板北沿。",
    ["gt_pad", "gt_s_lo", "gt_s_hi", "gt_n_lo", "gt_n_hi"],
    highlight=["tk_3_0"],
    tip="双柱分立赛道两侧, 中间正好放行一辆赛车。",
)
b.step(
    "龙门合龙: 门桥板两短边同时吸双柱顶边, 桥上再立冠军旗。",
    ["gt_beam", "gt_flag"],
    highlight=["gt_s_hi", "gt_n_hi"],
    tip="门桥一搭, 双柱互相扶持 —— 这就是门式刚架。",
)
b.step(
    "红蓝双雄: 内场发车区停 2 辆赛车 —— 底盘吸通道板与赛道内沿, "
    "车头鼻翼朝前、尾翼朝后。",
    ["car1", "car1_nose", "car1_wing", "car2", "car2_wing", "car2_nose"],
    highlight=["gt_pad", "tk_4_0"],
    tip="红车杆位、蓝车二位 —— 尾翼是立在底盘边上的小三角。",
)
b.step(
    "看台观众通道: 赛道南侧接 2 片通道板。",
    ["gs_ap_2", "gs_ap_3"],
    highlight=["tk_2_0", "tk_3_0"],
    tip="通道板北边吸赛道南沿 —— 观众从这里入座。",
)
b.step(
    "一级看台: 前后墙各 2 片立在通道板两侧, 2 片绿色坐板压顶 —— "
    "第一排座位成形。",
    ["gs_f1_2", "gs_f1_3", "gs_r1_2", "gs_r1_3", "gs_d1_2", "gs_d1_3"],
    highlight=["gs_ap_2", "gs_ap_3"],
    tip="坐板前后两沿都压着墙顶 —— 双铰链互为保险。",
)
b.step(
    "二级看台: 前墙立在一级坐板上, 后墙柱两节落地叠高, 2 片"
    "坐板在 z=2 压顶 —— 第二排比第一排高一头。",
    ["gs_f2_2", "gs_f2_3", "gs_r2lo_2", "gs_r2lo_3",
     "gs_r2hi_2", "gs_r2hi_3", "gs_d2_2", "gs_d2_3"],
    highlight=["gs_d1_2", "gs_d1_3"],
    tip="先立墙后压板 —— 二级坐板同样前后双铰链。",
)
b.step(
    "看台斜撑: 2 片紫色直角三角形撑住二级后墙两翼 —— 竖边吸"
    "墙柱竖边, 横边贴地。",
    ["gs_br_w", "gs_br_e"],
    highlight=["gs_r2lo_2", "gs_r2lo_3"],
    tip="斜撑双边受力, 看台从此不怕观众齐声跺脚。",
)
b.step(
    "维修通道: 赛道西侧接 3 片通道板 —— 这是进站车道。",
    ["pt_ap_1", "pt_ap_2", "pt_ap_3"],
    highlight=["tk_0_1", "tk_0_3"],
    tip="通道板东边吸赛道西沿, 赛车从这里进站换胎。",
)
b.step(
    "维修站前后墙: 前墙 2 片 (中间 y 2..3 留车库大门), 后墙 3 片"
    "一字排开。",
    ["pt_f1", "pt_f3", "pt_r1", "pt_r2", "pt_r3"],
    highlight=["pt_ap_1", "pt_ap_3"],
    tip="前墙底边吸通道板边 —— 大门正对进站车道。",
)
b.step(
    "维修站山墙与车库顶: 南北山墙合拢, 3 片车库顶压住前后墙 —— "
    "中门上方的顶板由两侧邻板与后墙一起托住。",
    ["pt_gs", "pt_gn", "pt_rf_1", "pt_rf_2", "pt_rf_3"],
    highlight=["pt_f1", "pt_r2"],
    tip="先盖两端有前墙的顶板, 中间那片靠邻板与后墙接力。",
)
b.step(
    "赛控塔塔基: 东北角外侧铺 1 片通道板, 4 片绿色塔墙围成塔基。",
    ["ct_pad", "ct_s0", "ct_w0", "ct_e0", "ct_n0"],
    highlight=["tk_6_4"],
    tip="通道板西边吸赛道东北角, 塔墙底边吸板边。",
)
b.step(
    "赛控塔观察层: 4 片透明片叠上一层 —— 赛会干事 360 度环视"
    "全场。",
    ["ct_s1", "ct_w1", "ct_e1", "ct_n1"],
    highlight=["ct_s0"],
    tip="透明层对缝叠齐 —— 别挡了裁判看发车的视线。",
)
b.step(
    "赛控塔顶板: 1 片顶板封口, 四边吸满观察层顶边。",
    ["ct_top"],
    highlight=["ct_s1", "ct_e1"],
    tip="盖上顶板, 塔身成为闭合箱形筒。",
)
b.step(
    "赛控塔尖顶: 4 片红色等边三角形锁成四坡顶 —— 全场最高的"
    "红色信号点。",
    TOWER_HAT,
    highlight=["ct_top"],
    tip="斜棱两两互吸自锁 —— 红顶就是赛道的灯塔。",
)
b.step(
    "弯角路肩: 四个弯心外沿各立 1 片红色路肩三角 —— 环形赛道"
    "升起绿旗!",
    ["kb_sw", "kb_se", "kb_nw", "kb_ne"],
    highlight=["tk_0_0", "tk_6_4"],
    tip="红白路肩是弯道的界碑 —— 压上去会咯噔一下 (想象中)。",
)

b.finalize(
    model_id="race_track_01",
    name="环形赛道",
    name_en="Circuit Race Track 01",
    description=(
        "全库第一条闭合环道: 20 片赛道板围成 7x5 矩形环形赛道, 发车"
        "直道上双柱龙门合龙、冠军旗高悬; 南看台两级阶梯坐席前后双铰链"
        "互为保险、两翼直角斜撑锁边; 西侧三连维修车库中门开敞, 东北角"
        "两层透明赛控塔戴红色四坡顶 —— 内场红蓝双雄已在杆位就绪。"
    ),
    difficulty=4,
    tags=["竞速运动", "赛道", "载具", "场馆"],
    min_pieces=78,
    min_steps=18,
)
