#!/usr/bin/env python3
"""生成模型 data/models/festival_gate_01.json (新春彩门, D1 入门)。

D1 补员批 3 模型 4/4 (节日限定): 新春庙会入口的迷你彩门。
结构签名是"双塔驮桥楼": 两座 1x1 空心方塔踩在红毯上, 塔顶
压顶后由一片长板横跨门洞当过梁, 过梁南沿再立一面通长横匾 ——
匾在梁上、梁在塔上、塔在毯上, 三层受压一线到底; 与库内中世纪
城门/凯旋门 (60~90 片方板砌拱) 的结构逻辑完全不同: 这是
20 片量级的"板桥式"彩门。

结构总览 (世界单位 1.0 = 正方形磁力片边长, 观众站在南侧):
  - 红毯 (x [-1,5], y [0,1]): 方板 6 片一字铺           6 片
  - 双塔 (footprint [0,1] / [3,4]): 各 4 面墙, 南面窗格  8 片
  - 塔顶压顶: 方板 2 片                                  2 片
  - 过梁: 长板 1 片横跨门洞, 两短边坐塔墙顶              1 片
  - 横匾: 长楣 1 片立在过梁南沿, 底边等长贴合            1 片
  - 塔旗: 等边三角 2 片立在压顶外沿                      2 片
  - 迎宾彩旗: 等边三角 2 片立在红毯两端南沿              2 片
  合计 22 片, 5 个教程步骤, 4 种片形 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 塔墙墙脚整边骑红毯方板边, 四角竖边互咬成筒;
  - 过梁两条短边分别坐在两塔相向的墙顶上 (双端支承,
    无悬臂), 长边与压顶共面互吸再加保险;
  - 横匾底边 (长 2) 与过梁南长边等长贴合, 重心正压支承线;
  - 最高点 2.0 (匾顶), 低于 2.5 高层阈值, 无 R8 拓扑告警。

用法: python3 tools/generate_festival_gate_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

CARPET = "red"      # 红毯
TOWER = "red"       # 塔身
LATTICE = "clear"   # 南面灯窗
CAP = "yellow"      # 压顶
BEAM = "yellow"     # 过梁
BANNER = "red"      # 横匾
FLAG = "yellow"     # 塔旗
BUNTING = "pink"    # 迎宾彩旗


def wall_ns_t(tid, tile_type, x0, y, z0, color):
    b.add(tid, tile_type, (x0 + 0.5, y, z0 + 0.5), (90, 0, 0), color)


# =================================================================
# 1. 红毯 (x [-1,5], y [0,1]): 六片方板一字铺到门洞两头
# =================================================================
for i, x0 in enumerate(range(-1, 5)):
    b.flat(f"carpet_{i}", x0, 0, 0.0, CARPET)

# =================================================================
# 2. 双塔: 各四面墙合成空心方筒, 南面窗格方当灯窗
# =================================================================
for x0, side in ((0, "w"), (3, "e")):
    wall_ns_t(f"tower_{side}_s", "window_square", x0, 0.0, 0, LATTICE)
    b.wall_ns(f"tower_{side}_n", x0, 1.0, 0, TOWER)
    b.wall_ew(f"tower_{side}_in", float(x0) if side == "e" else float(x0 + 1),
              0, 0, TOWER)
    b.wall_ew(f"tower_{side}_out", float(x0 + 1) if side == "e" else float(x0),
              0, 0, TOWER)

# =================================================================
# 3. 塔顶压顶 + 过梁: 压顶封筒, 长板短边坐两塔墙顶横跨门洞
# =================================================================
b.flat("cap_w", 0, 0, 1.0, CAP)
b.flat("cap_e", 3, 0, 1.0, CAP)
b.flat_rect("beam", 1, 0, 1.0, BEAM)

# =================================================================
# 4. 横匾: 长楣立在过梁南沿, 面朝来客
# =================================================================
b.lintel_ns("banner", 1, 0.0, 1, BANNER)

# =================================================================
# 5. 塔旗与迎宾彩旗
# =================================================================
b.crest_ew("flag_w", 0.0, 0, 1.0, FLAG)
b.crest_ew("flag_e", 4.0, 0, 1.0, FLAG)
b.crest_ns("bunting_w", -1, 0.0, 0.0, BUNTING)
b.crest_ns("bunting_e", 4, 0.0, 0.0, BUNTING)

# =================================================================
# 教程步骤 (5 步)
# =================================================================
b.step(
    "铺红毯: 六片红色方板一字排开, 庙会入口的地界画好了。",
    [f"carpet_{i}" for i in range(6)],
    tip="每片与上一片整边贴合, 红毯笔直, 彩门才立得正。",
)
b.step(
    "立西塔: 四面墙踩住红毯方板边合成方筒, 透明窗格朝南当灯窗。",
    ["tower_w_s", "tower_w_n", "tower_w_in", "tower_w_out"],
    highlight=["carpet_1"],
    tip="相邻两面墙的竖边互相一咬, 塔就自己站住了。",
)
b.step(
    "立东塔: 与西塔一模一样, 中间空出两格宽的门洞。",
    ["tower_e_s", "tower_e_n", "tower_e_in", "tower_e_out"],
    highlight=["carpet_4", "tower_w_in"],
)
b.step(
    "压顶架梁: 两片黄色压顶封住塔筒, 长板两头坐上塔墙顶, 横跨门洞。",
    ["cap_w", "cap_e", "beam"],
    highlight=["tower_w_in", "tower_e_in"],
    tip="过梁两条短边各坐一座塔 —— 桥就是这样架起来的。",
)
b.step(
    "挂匾插旗: 横匾立上过梁南沿, 塔旗与迎宾彩旗就位 —— 庙会开门!",
    ["banner", "flag_w", "flag_e", "bunting_w", "bunting_e"],
    highlight=["beam", "carpet_0"],
    tip="横匾底边整条压住过梁边, 写上'新春大吉'正合适。",
)

b.finalize(
    model_id="festival_gate_01",
    name="新春彩门",
    name_en="Festival Gate 01",
    description=(
        "D1 入门节日限定: 新春庙会入口的迷你彩门 —— 六片红毯铺底, 两座"
        "带灯窗的空心方塔踩毯而立, 黄色压顶封筒后一片长板横跨门洞当"
        "过梁 (两短边双端坐塔, 无悬臂), 红色横匾再立上梁沿面朝来客; "
        "塔顶黄旗、毯端粉色迎宾彩旗一插, 庙会正式开门。匾在梁上、梁在"
        "塔上、塔在毯上 —— 三层受压一线到底, 是孩子第一课'架桥'启蒙。"
    ),
    difficulty=1,
    tags=["节日", "新春", "彩门", "亲子入门"],
    min_pieces=22,
    min_steps=5,
    series="holiday_seasonal",
)
