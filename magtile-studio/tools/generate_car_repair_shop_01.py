#!/usr/bin/env python3
"""生成模型 data/models/car_repair_shop_01.json (汽车修理站)。

内容批 B 5/5: 全库第一座把车举到二楼的修理站 —— 与加油站 (门架
雨棚 + 加油机)、洗车馆 (贯通隧道) 刻意错开: 主角是举升机 ——
双片灰墙门柱托起黄色举升台 (双端受力零悬挑), 红色小车整车骑在
台上: 双轮立台面两条长边 (一缝双吸), 车顶板压双轮顶, 台-轮-顶
锁成二楼上的滚动门式框架; 台下正好钻得进检修工。东侧敞面工坊
南面整个不砌墙 (剖面视角), 北墙窗格方就是挂满扳手的工具墙,
墙脚两片红色直角三角斜撑双边受力; 待修的青色小车排在场外,
橙色零件箱开顶待取 —— 全库唯一的"车在头顶上修"。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 场地 (x [0,5], y [0,4]): 方板 x16 + 轮胎堆平放 x1 +
    待修车位长板 x1                                             18 片
  - 举升机 (x [1,2], y [1,3]): 双门柱 + 举升台长板              3 片
  - 举升车 (z 1..2): 双轮 + 车顶板 + 挡风玻璃                   4 片
  - 敞面工坊 (x [3,5], y [2,4]): 三面墙 x6 (北墙含工具墙) +
    后半跨屋顶 x2 + 斜撑 x2 + 招牌杆 x1                        11 片
  - 待修车 (x [2,4], y [0,1]): 双轮 + 车顶板 + 挡风玻璃         4 片
  - 零件箱 (x [0,1], y [3,4]): 开顶墙环 x4                      4 片
  - 警示锥 x1: 橙色等边三角骑地缝                                1 片
  合计 45 片, 10 个教程步骤, 7 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 举升台两短边各压一根门柱顶, 柱-台-柱-地面锁成门式刚架;
    车轮底边整边吸台面长边, 车顶板双长边压双轮顶 —— 整车在
    二楼上再锁一个门式框架, 支撑路径经双柱直落地面;
  - 工坊南面敞开 (剖面视角), 屋顶只盖北半跨, 每片北边整边压
    北墙顶、东西边压侧墙顶; 两片直角三角斜撑竖边吸侧墙南竖棱、
    横边吸场地拼缝 (双边受力, 摩天大楼同款);
  - 招牌杆底边"北墙顶 + 屋顶板北沿"一线双吸直上 3.0;
  - 轮胎堆是平放的车轮底座 (语义复用), 与场地方板拼缝互吸;
    零件箱开顶墙环四角竖边互咬。

用法: python3 tools/generate_car_repair_shop_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

FLOOR = "gray"      # 场地
LANE = "clear"      # 检修通道格
TIRES = "gray"      # 轮胎堆 (平放车轮底座)
BAY = "clear"       # 待修车位长板
PIER = "gray"       # 举升机门柱
LIFT = "yellow"     # 举升台
WHEEL = "gray"      # 车轮底座
CAR_UP = "red"      # 举升车
CAR_WAIT = "cyan"   # 待修车
GLASS = "clear"     # 挡风玻璃
SHOP = "gray"       # 工坊墙
TOOLWALL = "cyan"   # 工具墙 (窗格方)
ROOF = "blue"       # 工坊屋顶
BRACE = "red"       # 斜撑
SIGN = "red"        # 招牌杆
BIN = "orange"      # 零件箱
CONE = "orange"     # 警示锥


def wall_ns_t(tid, tile_type, x0, y, z0, color):
    b.add(tid, tile_type, (x0 + 0.5, y, z0 + 0.5), (90, 0, 0), color)


# =================================================================
# 1. 场地 (x [0,5], y [0,4]): 轮胎堆与待修车位嵌进南两行
# =================================================================
b.add("tire_stack", "wheel_base", (0.5, 1.0, 0.0), (0, 0, 90), TIRES)
b.flat_rect("wait_bay", 2, 0, 0.0, BAY)        # 待修车位横放南沿
b.flat("fl_1_0", 1, 0, 0.0, FLOOR)
b.flat("fl_4_0", 4, 0, 0.0, FLOOR)
for x0 in (1, 2, 3, 4):
    color = LANE if x0 == 1 else FLOOR
    b.flat(f"fl_{x0}_1", x0, 1, 0.0, color)
for y0 in range(2, 4):
    for x0 in range(5):
        color = LANE if x0 == 1 else FLOOR
        b.flat(f"fl_{x0}_{y0}", x0, y0, 0.0, color)

# =================================================================
# 2. 举升机 (x [1,2], y [1,3]): 双门柱 + 举升台
# =================================================================
b.wall_ns("lift_pier_s", 1, 1.0, 0, PIER)
b.wall_ns("lift_pier_n", 1, 3.0, 0, PIER)
b.flat_rect("lift_deck", 1, 1, 1.0, LIFT, axis="y")

# =================================================================
# 3. 举升车 (z 1..2): 双轮立台面长边, 车顶板压双轮顶
# =================================================================
b.add("up_wh_w", "wheel_base", (1.0, 2.0, 1.5), (90, 0, 90), WHEEL)
b.add("up_wh_e", "wheel_base", (2.0, 2.0, 1.5), (90, 0, 90), WHEEL)
b.flat_rect("up_top", 1, 1, 2.0, CAR_UP, axis="y")
b.crest_ns("up_glass", 1, 3.0, 2.0, GLASS)

# =================================================================
# 4. 敞面工坊 (x [3,5], y [2,4]): 南面敞开, 北墙是工具墙
# =================================================================
wall_ns_t("shop_n_3", "window_square", 3, 4.0, 0, TOOLWALL)   # 工具墙
wall_ns_t("shop_n_4", "window_square", 4, 4.0, 0, TOOLWALL)
b.wall_ew("shop_w_2", 3.0, 2, 0, SHOP)
b.wall_ew("shop_w_3", 3.0, 3, 0, SHOP)
b.wall_ew("shop_e_2", 5.0, 2, 0, SHOP)
b.wall_ew("shop_e_3", 5.0, 3, 0, SHOP)
b.flat("roof_3", 3, 3, 1.0, ROOF)              # 屋顶只盖北半跨
b.flat("roof_4", 4, 3, 1.0, ROOF)
b.brace("brace_w", (3.0, 2.0, 0.0), "-y", BRACE)
b.brace("brace_e", (5.0, 2.0, 0.0), "-y", BRACE)
b.spire_ns("sign_pole", 3, 4.0, 1.0, SIGN)     # 招牌杆一线双吸, 尖 3.0

# =================================================================
# 5. 待修车 (x [2,4], y [0,1], 车头朝西对着检修通道) + 零件箱 + 警示锥
# =================================================================
b.add("wt_wh_s", "wheel_base", (3.0, 0.0, 0.5), (90, 0, 0), WHEEL)
b.add("wt_wh_n", "wheel_base", (3.0, 1.0, 0.5), (90, 0, 0), WHEEL)
b.flat_rect("wt_top", 2, 0, 1.0, CAR_WAIT)
b.crest_ew("wt_glass", 2.0, 0, 1.0, GLASS)     # 车头朝检修通道
b.wall_ns("bin_s", 0, 3.0, 0, BIN)
b.wall_ns("bin_n", 0, 4.0, 0, BIN)
b.wall_ew("bin_w", 0.0, 3, 0, BIN)
b.wall_ew("bin_e", 1.0, 3, 0, BIN)
b.crest_ns("cone", 2, 2.0, 0.0, CONE)          # 警示锥骑地缝

# =================================================================
# 教程步骤 (10 步)
# =================================================================
b.step(
    "铺场地南行: 轮胎堆平放在西角, 清色待修车位长板横在南沿。",
    ["tire_stack", "fl_1_0", "wait_bay", "fl_4_0"],
    tip="轮胎堆就是平放的车轮底座 —— 修理站的备件都码在地上。",
)
b.step(
    "补第二行四片方板, 南半场铺齐。",
    ["fl_1_1", "fl_2_1", "fl_3_1", "fl_4_1"],
    highlight=["tire_stack"],
    tip="轮胎堆一块顶两格; 车位长板的两条长边就是待修车的轮缝。",
)
b.step(
    "铺第三行: 五片方板横贯, 清色检修通道格对准举升机。",
    [f"fl_{x0}_2" for x0 in range(5)],
    highlight=["fl_1_1"],
    tip="检修通道从南门一直通到举升机底下。",
)
b.step(
    "铺第四行: 场地铺满, 工坊地基就位。",
    [f"fl_{x0}_3" for x0 in range(5)],
    highlight=["fl_0_2"],
    tip="行行等边互吸, 每道拼缝都是一条磁力吸边。",
)
b.step(
    "立举升机: 南北双门柱踩住地缝, 黄色举升台短边压双柱顶。",
    ["lift_pier_s", "lift_pier_n", "lift_deck"],
    highlight=["fl_1_2"],
    tip="柱-台-柱-地面锁成门式刚架, 双端受力零悬挑 —— 台下正好"
        "钻得进检修工。",
)
b.step(
    "红色小车开上举升台: 双轮立台面长边, 车顶板压双轮顶。",
    ["up_wh_w", "up_wh_e", "up_top", "up_glass"],
    highlight=["lift_deck"],
    tip="车轮底边整边吸住台面长边 (一缝双吸), 整车在二楼上再锁"
        "一个门式框架。",
)
b.step(
    "起敞面工坊: 南面不砌墙, 北墙两片窗格方就是工具墙。",
    ["shop_n_3", "shop_n_4", "shop_w_2", "shop_w_3",
     "shop_e_2", "shop_e_3"],
    highlight=["fl_3_3"],
    tip="窗格方的格子挂满扳手螺丝刀 —— 工具墙一眼看得清。",
)
b.step(
    "盖北半跨屋顶, 侧墙南棱装斜撑, 招牌杆骑北墙顶。",
    ["roof_3", "roof_4", "brace_w", "brace_e", "sign_pole"],
    highlight=["shop_n_3"],
    tip="斜撑竖边吸侧墙竖棱、横边吸地缝, 双边受力; 招牌杆一线"
        "双吸直上 3.0。",
)
b.step(
    "青色待修车停进南沿车位, 车头朝着检修通道排队。",
    ["wt_wh_s", "wt_wh_n", "wt_top", "wt_glass", "cone"],
    highlight=["wait_bay"],
    tip="同款双轮 + 车顶板 + 挡风玻璃; 警示锥骑在通道缝上 —— "
        "排队检修, 请勿越线。",
)
b.step(
    "围零件箱收尾: 四片橙色墙开顶合环。",
    ["bin_s", "bin_n", "bin_w", "bin_e"],
    highlight=["cone"],
    tip="开顶不盖, 伸手就能拿零件 —— 修理站开工!",
)

b.finalize(
    model_id="car_repair_shop_01",
    name="汽车修理站",
    name_en="Car Repair Shop 01",
    description=(
        "只用核心九片型的修理站: 主角是举升机 —— 双片门柱托起"
        "黄色举升台 (双端受力零悬挑), 红色小车整车骑在台上, 双轮"
        "立台面两条长边、车顶板压双轮顶, 在二楼上锁成滚动门式"
        "框架, 台下正好钻得进检修工; 东侧工坊南面整个敞开 (剖面"
        "视角), 北墙窗格方就是挂满扳手的工具墙, 墙脚红色直角三角"
        "斜撑双边受力, 红色招牌杆一线双吸直上 3.0; 青色待修车在"
        "场外排队, 轮胎堆平放在角落, 橙色零件箱开顶待取 —— 你的"
        "车, 举到头顶上修!"
    ),
    difficulty=2,
    tags=["城市", "修理站", "职业体验", "汽车", "工程"],
    min_pieces=45,
    min_steps=10,
)
