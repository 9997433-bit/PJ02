#!/usr/bin/env python3
"""生成模型 data/models/museum_01.json (艺术博物馆)。

建筑地标主题: 全库第一座博物馆 —— 前庭正中一座透明玻璃金字塔
(卢浮宫式样, 梯形四坡+方板压顶自锁), 身后是古典三段式主馆:
两翼展廊戴栏板与翼端旗, 中央大厅由上下两环长方形横楣箱形
叠合、顶戴梯形四坡金顶; 玻璃门厅整面通透, 门前双柱门廊托着
檐饰三角, 步道两侧立着馆藏雕塑 —— 今天常设展免费开放!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 大门朝南):
  - 前庭地坪 x4 + 步道 x4 + 玻璃金字塔 (梯形 x4 + 压顶 x1)     13 片
  - 两翼展廊 (z 0..1): 正面墙 x6 + 背墙 x6 + 端墙 x4           16 片
  - 大厅一层横楣环 (z 0..1): 长方形 x4 (玻璃门厅整面通透)       4 片
  - 两翼屋面 x12 + 翼顶栏板 x4 + 翼端旗 x2                     18 片
  - 大厅二层横楣环 (z 1..2) x4 + 梯形四坡金顶 x5                9 片
  - 门廊双柱 x2 + 门廊顶 x2 + 檐饰 x2 + 前庭雕塑 x2             8 片
  合计 68 片, 16 个教程步骤, 4 种片形。

物理规则要点 (通过 R1~R8 全部校验):
  - 大厅是"横楣环"技法的塔楼化用: 每层 4 片长方形横楣在四角
    以竖边互吸围成箱形环, 上环底边 (长 2) 整边吸下环顶边,
    环环相扣; 金顶梯形下底恰与横楣顶边等长贴合 —— 这正是
    hip_roof2 要求"洞口沿边必须是长方形长边"的原因;
  - 玻璃金字塔四片梯形腰腰互吸+方板压顶, 下底整边吸前庭
    地坪长板长边, 五片自锁成环;
  - 门廊双柱底边吸步道拼缝, 门廊顶南压柱顶、北整排吸不上
    (长短不齐) 改由柱顶+拼缝双路受力, 与大厅玻璃横楣合成环;
  - 两翼墙体接地起步, 屋面四边吸满墙顶 —— 全馆无悬挑无吊挂。

用法: python3 tools/generate_museum.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

COURT = "gray"      # 前庭地坪
WALK = "gray"       # 步道
PYR = "clear"       # 玻璃金字塔
WING = "yellow"     # 两翼墙体 (砂岩)
WIN = "clear"       # 翼墙玻璃窗
ROOF = "gray"       # 翼屋面
HALL = "yellow"     # 大厅横楣
GOLD = "orange"     # 金顶
PORCH = "gray"      # 门廊
ART = "red"         # 雕塑 / 翼端旗

# =================================================================
# 1. 前庭 (z=0): 金字塔地坪长板 x4 + 步道方板 x4
# =================================================================
b.flat_rect("ct_s", 3, 0, 0.0, COURT)               # [3..5]x[0..1]
b.flat_rect("ct_n", 3, 1, 0.0, COURT)               # [3..5]x[1..2]
b.flat_rect("ct_w", 2, 0, 0.0, COURT, axis="y")     # [2..3]x[0..2]
b.flat_rect("ct_e", 5, 0, 0.0, COURT, axis="y")     # [5..6]x[0..2]
for x0 in (2, 3, 4, 5):
    b.flat(f"wk_{x0}", x0, 2, 0.0, WALK)            # 步道 y[2..3]

# =================================================================
# 2. 玻璃金字塔: 梯形四坡 + 方板压顶 (卢浮宫式样)
# =================================================================
PYR_IDS, PYR_CAP = b.hip_roof2("pyr", 3, 0, 0.0, PYR)

# =================================================================
# 3. 两翼展廊墙体 (z 0..1): 正面/背墙/端墙
# =================================================================
for x0 in (0, 1, 2, 5, 6, 7):
    c = WIN if x0 in (1, 6) else WING
    b.wall_ns(f"wf_{x0}", x0, 3.0, 0, c)            # 正面墙 (y=3)
for x0 in (0, 1, 2, 5, 6, 7):
    b.wall_ns(f"wb_{x0}", x0, 5.0, 0, WING)         # 背墙 (y=5)
for y0 in (3, 4):
    b.wall_ew(f"we_w_{y0}", 0.0, y0, 0, WING)       # 西端墙
    b.wall_ew(f"we_e_{y0}", 8.0, y0, 0, WING)       # 东端墙

# =================================================================
# 4. 大厅一层横楣环 (x 3..5, z 0..1): 玻璃门厅整面通透
# =================================================================
b.add("h1_w", "rectangle", (3.0, 4.0, 0.5), (90, 0, 90), HALL)
b.add("h1_e", "rectangle", (5.0, 4.0, 0.5), (90, 0, 90), HALL)
b.add("h1_s", "rectangle", (4.0, 3.0, 0.5), (90, 0, 0), WIN)   # 玻璃门厅
b.add("h1_n", "rectangle", (4.0, 5.0, 0.5), (90, 0, 0), HALL)

# =================================================================
# 5. 两翼屋面 (z=1) + 栏板 + 翼端旗
# =================================================================
for x0 in (0, 1, 2, 5, 6, 7):
    for y0 in (3, 4):
        b.flat(f"rf_{x0}_{y0}", x0, y0, 1.0, ROOF)
b.crest_ns("bal_w0", 0, 3.0, 1.0, WING)             # 翼顶栏板
b.crest_ns("bal_w1", 1, 3.0, 1.0, WING)
b.crest_ns("bal_e0", 6, 3.0, 1.0, WING)
b.crest_ns("bal_e1", 7, 3.0, 1.0, WING)
b.crest_ew("flag_w", 0.0, 3, 1.0, ART)              # 翼端旗
b.crest_ew("flag_e", 8.0, 4, 1.0, ART)

# =================================================================
# 6. 大厅二层横楣环 (z 1..2) + 梯形四坡金顶
# =================================================================
b.add("h2_w", "rectangle", (3.0, 4.0, 1.5), (90, 0, 90), HALL)
b.add("h2_e", "rectangle", (5.0, 4.0, 1.5), (90, 0, 90), HALL)
b.add("h2_s", "rectangle", (4.0, 3.0, 1.5), (90, 0, 0), HALL)
b.add("h2_n", "rectangle", (4.0, 5.0, 1.5), (90, 0, 0), HALL)
GOLD_IDS, GOLD_CAP = b.hip_roof2("gold", 3, 3, 2.0, GOLD)

# =================================================================
# 7. 门廊 + 檐饰 + 前庭雕塑
# =================================================================
b.wall_ns("col_w", 3, 2.0, 0, PORCH)                # 门廊双柱
b.wall_ns("col_e", 4, 2.0, 0, PORCH)
b.flat("porch_w", 3, 2, 1.0, PORCH)                 # 门廊顶
b.flat("porch_e", 4, 2, 1.0, PORCH)
b.crest_ns("ped_w", 3, 2.0, 1.0, GOLD)              # 檐饰三角
b.crest_ns("ped_e", 4, 2.0, 1.0, GOLD)
b.crest_ns("statue_w", 2, 2.0, 0.0, ART)            # 前庭雕塑
b.crest_ns("statue_e", 5, 2.0, 0.0, ART)

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺前庭地坪: 4 片灰色长板围出 2x2 金字塔基座 (拼缝即塔缘)。",
    ["ct_s", "ct_n", "ct_w", "ct_e"],
    tip="长板长边就是金字塔的下底吸合线 —— 铺正再往下走。",
)
b.step(
    "铺步道: 4 片方板一字排开 (y 2..3), 连接前庭与大门。",
    [f"wk_{x0}" for x0 in (2, 3, 4, 5)],
    highlight=["ct_w", "ct_e"],
    tip="步道短边整边吸地坪长板端边 —— 观众从这里排队入馆。",
)
b.step(
    "起玻璃金字塔: 4 片透明梯形下底整边吸地坪长边, 腰腰互吸, "
    "方板压顶合龙。",
    PYR_IDS + [PYR_CAP],
    highlight=["ct_s", "ct_n"],
    tip="卢浮宫同款 —— 五片自锁成环, 阳光直落前庭。",
)
b.step(
    "立两翼正面墙: 6 片方墙沿 y=3 线立起, x=1 与 x=6 两格用透明"
    "玻璃窗。",
    [f"wf_{x0}" for x0 in (0, 1, 2, 5, 6, 7)],
    highlight=["wk_2", "wk_5"],
    tip="靠步道两格墙脚踩步道北边 —— 展廊的落地展窗朝南。",
)
b.step(
    "封两翼端墙: 东西端各立 2 片方墙, 竖边与正面墙拐角互吸。",
    ["we_w_3", "we_w_4", "we_e_3", "we_e_4"],
    highlight=["wf_0", "wf_7"],
    tip="端墙先上, 背墙才有拐角可靠 —— 搭建顺序也是结构智慧。",
)
b.step(
    "立两翼背墙: 背面再立 6 片方墙 (y=5 线), 竖边与端墙拐角互吸。",
    [f"wb_{x0}" for x0 in (0, 1, 2, 5, 6, 7)],
    highlight=["we_w_4", "we_e_4"],
    tip="从端墙向中间合龙 —— 两翼箱形闭环, 屋面有了四边支座。",
)
b.step(
    "围大厅一层横楣环: 4 片长方形横楣在四角竖边互吸围成环, "
    "南面用透明片 —— 玻璃门厅整面通透。",
    ["h1_w", "h1_e", "h1_s", "h1_n"],
    highlight=["wf_2", "wf_5"],
    tip="横楣环是大厅的骨架 —— 竖边与两翼墙角互吸, 环环相扣。",
)
b.step(
    "盖西翼屋面: 6 片灰色方板四边吸满墙顶 (x 0..3)。",
    [f"rf_{x0}_{y0}" for x0 in (0, 1, 2) for y0 in (3, 4)],
    highlight=["wf_0", "wb_2"],
    tip="每片听到与墙顶的咔哒声再松手 —— 展厅从此有了天光顶。",
)
b.step(
    "盖东翼屋面: 再盖 6 片 (x 5..8), 两翼合龙。",
    [f"rf_{x0}_{y0}" for x0 in (5, 6, 7) for y0 in (3, 4)],
    highlight=["wf_5", "wb_7"],
    tip="两翼屋面同高 —— 古典三段式的水平基准线。",
)
b.step(
    "立翼顶栏板: 4 片黄色三角立在屋面南沿 —— 古典檐口的齿饰。",
    ["bal_w0", "bal_w1", "bal_e0", "bal_e1"],
    highlight=["rf_0_3", "rf_7_3"],
    tip="栏板底边整边吸屋面沿边, 立面一下子有了节奏。",
)
b.step(
    "叠大厅二层横楣环: 4 片长方形底边整边吸一层环顶边, 再合一环。",
    ["h2_w", "h2_e", "h2_s", "h2_n"],
    highlight=["h1_w", "h1_s"],
    tip="上下环严格对缝 —— 大厅从两翼屋面之上探出头来。",
)
b.step(
    "戴梯形四坡金顶: 4 片橙色梯形下底恰与横楣顶边等长贴合, "
    "腰腰互吸, 方板压顶。",
    GOLD_IDS + [GOLD_CAP],
    highlight=["h2_s", "h2_n"],
    tip="金顶自锁成环 —— 全城都认得这顶博物馆的皇冠。",
)
b.step(
    "立门廊双柱: 2 片方墙踩步道拼缝立在大门前。",
    ["col_w", "col_e"],
    highlight=["wk_3", "wk_4"],
    tip="双柱与玻璃门厅隔步道相望 —— 门廊的骨架。",
)
b.step(
    "盖门廊顶: 2 片方板南压柱顶、北吸大厅玻璃横楣顶边。",
    ["porch_w", "porch_e"],
    highlight=["col_w", "col_e"],
    tip="柱顶+横楣双路受力, 门廊与大厅锁成一环。",
)
b.step(
    "装檐饰三角: 门廊顶南沿立 2 片橙色三角 —— 微缩的山花。",
    ["ped_w", "ped_e"],
    highlight=["porch_w", "porch_e"],
    tip="山花是古典建筑的眉眼 —— 底边整边吸门廊顶沿。",
)
b.step(
    "立前庭雕塑与翼端旗: 步道两端各立 1 座红色雕塑, 两翼屋面"
    "端沿再各插 1 面红旗 —— 博物馆开馆!",
    ["statue_w", "statue_e", "flag_w", "flag_e"],
    highlight=["wk_2", "wk_5"],
    tip="雕塑底边吸步道格边, 旗底边吸屋面端边 —— 常设展免费开放!",
)

b.finalize(
    model_id="museum_01",
    name="艺术博物馆",
    name_en="Art Museum 01",
    description=(
        "全库第一座博物馆: 前庭正中透明玻璃金字塔 (梯形四坡+方板压顶"
        "自锁, 卢浮宫式样), 身后古典三段式主馆 —— 两翼展廊戴栏板与"
        "翼端旗, 中央大厅由上下两环长方形横楣箱形叠合、顶戴梯形四坡"
        "金顶; 玻璃门厅整面通透, 门前双柱门廊托檐饰三角, 步道两侧立"
        "馆藏雕塑 —— 今天常设展免费开放!"
    ),
    difficulty=3,
    tags=["建筑地标", "博物馆", "玻璃金字塔", "古典建筑", "进阶"],
    min_pieces=60,
    min_steps=16,
)
