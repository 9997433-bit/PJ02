#!/usr/bin/env python3
"""生成模型 data/models/ski_lodge_01.json (滑雪小屋)。

冰雪运动主题: 全库第一栋 A 字形滑雪小屋 —— 雪原上一栋红墙
尖顶木屋: 两面透明雪顶长板以 60 度对倾, 顶边在屋脊整边互吸,
山墙等边三角刚好塞满 A 形断面 (三边同时吸墙顶与两面雪顶),
西山墙嵌透明观景窗、东山墙嵌橙色小门; 屋旁一座练习雪坡
(双长板矮台 + 30 度滑道), 雪坡道口正对雪原; 林线四棵瘦高
等腰雪杉, 雪场路牌与一堆四坡雪丘点缀 —— 冲呀, 新手道!

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 雪原 (x [0,10], y [0,4]): 长板 x10 + 方板 x20            30 片
  - A 字小屋 (x [0,4], y [1,2]): 一层长板墙 x4 + 山墙
    窗格方/门框方 x2 + 60 度雪顶长板 x4 + 山墙等边 x2        12 片
  - 练习雪坡 (x [7,9], y [1,2]): 长板矮墙 x2 + 台面长板 x1
    + 30 度滑道长板 x1                                        4 片
  - 雪杉: 瘦高等腰三角 x4 (林线立雪原拼缝)                    4 片
  - 雪场路牌 (等边) x1 + 四坡雪丘 (等边锥) x4                 5 片
  合计 55 片, 12 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, strict 档同样全绿):
  - 雪顶长板底边 (长 2) 与一层长板墙顶边整边等长互吸,
    两面雪顶顶边在屋脊线两两互吸 —— 墙-顶-墙锁成门式闭环;
  - 山墙等边三角底边吸墙顶、两腰分别吸两面雪顶短边 ——
    三边受力, A 形断面自锁;
  - 滑道顶边整边吸台面短边、坡尾自然落雪原 (顶铰链+接地);
  - 雪杉/路牌重心正压拼缝铰链 (力矩 0), 雪丘四棱互吸自锁;
  - 滑道走廊 (x>4.2) 与小屋 (x<=4) 完全错开, 互不侵入。

用法: python3 tools/generate_ski_lodge.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

SNOW = "clear"      # 雪原 / 雪顶 / 雪丘 / 滑道
WALL = "red"        # 小屋一层墙
DOOR = "orange"     # 东山墙小门
GLASS = "clear"     # 西山墙观景窗
GABLE = "orange"    # 山墙三角
TREE = "green"      # 雪杉
SIGN = "red"        # 雪场路牌
PLAT = "gray"       # 雪坡矮墙
TOP = "clear"       # 雪坡台面

# =================================================================
# 1. 雪原 (x [0,10], y [0,4]): 南北长板行夹两行方板
# =================================================================
for k in range(5):
    b.flat_rect(f"sn_s_{k}", 2 * k, 0, 0.0, SNOW)
    b.flat_rect(f"sn_n_{k}", 2 * k, 3, 0.0, SNOW)
for x in range(10):
    b.flat(f"sn_a_{x}", x, 1, 0.0, SNOW)
    b.flat(f"sn_b_{x}", x, 2, 0.0, SNOW)

# =================================================================
# 2. A 字小屋 (x [0,4], y [1,2]): 长板墙 + 山墙 + 60 度雪顶
# =================================================================
for k in (0, 2):
    b.lintel_ns(f"lg_s_{k}", k, 1.0, 0, WALL)        # 南墙 (长板)
    b.lintel_ns(f"lg_n_{k}", k, 2.0, 0, WALL)        # 北墙 (长板)
b.add("lg_win", "window_square", (0.0, 1.5, 0.5), (90, 0, 90), GLASS)
b.add("lg_door", "door_frame", (4.0, 1.5, 0.5), (90, 0, 90), DOOR)
# 60 度雪顶: 底边吸墙顶 (z=1), 顶边在屋脊 (y=1.5, z=1.866) 互吸
for k in (0, 2):
    b.place_edge(f"roof_s_{k}", "rectangle", 0,
                 (float(k), 1.0, 1.0), (float(k + 2), 1.0, 1.0),
                 (0.0, 0.5, 0.866025), SNOW)
    b.place_edge(f"roof_n_{k}", "rectangle", 0,
                 (float(k + 2), 2.0, 1.0), (float(k), 2.0, 1.0),
                 (0.0, -0.5, 0.866025), SNOW)
b.crest_ew("gable_w", 0.0, 1, 1.0, GABLE)            # 西山墙三角
b.crest_ew("gable_e", 4.0, 1, 1.0, GABLE)            # 东山墙三角

# =================================================================
# 3. 练习雪坡 (x [7,9], y [1,2]): 矮台 + 30 度滑道 (坡尾向西)
# =================================================================
b.lintel_ns("pf_s", 7, 1.0, 0, PLAT)
b.lintel_ns("pf_n", 7, 2.0, 0, PLAT)
b.flat_rect("pf_top", 7, 1, 1.0, TOP)
b.ramp("slope", "-x", 7.0, 1, 1.0, SNOW)             # 坡尾落在 x=5.27

# =================================================================
# 4. 雪杉林线 + 路牌 + 雪丘
# =================================================================
for x0 in (0, 2, 4, 6):
    b.spire_ns(f"fir_{x0}", x0, 3.0, 0.0, TREE)      # 雪杉 (立 y=3 拼缝)
b.crest_ns("sign", 9, 3.0, 0.0, SIGN)                # 雪场路牌
DRIFT = b.hat4("drift", 5, 2, 0.0, SNOW,
               shape="equilateral_triangle")         # 四坡雪丘 [5,6]x[2,3]

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺雪原南沿: 5 片透明长板连成雪场边线。",
    [f"sn_s_{k}" for k in range(5)],
    tip="长板短边互吸连成直线 —— 这是雪场的南边界。",
)
b.step(
    "铺雪原第一行方板 (y [1,2]): 10 片。",
    [f"sn_a_{x}" for x in range(10)],
    highlight=["sn_s_0"],
    tip="方板行的两条拼缝就是小屋墙脚与雪坡矮墙的落点。",
)
b.step(
    "铺雪原第二行方板 (y [2,3]): 再来 10 片。",
    [f"sn_b_{x}" for x in range(10)],
    highlight=["sn_a_0"],
    tip="两行方板拼缝对齐 —— 雪原中央平平整整。",
)
b.step(
    "铺雪原北沿: 5 片透明长板, 雪场合拢。",
    [f"sn_n_{k}" for k in range(5)],
    highlight=["sn_b_0"],
    tip="北沿外就是雪杉林线 —— 树马上种上。",
)
b.step(
    "砌小屋一层: 南北各 2 片红色长板墙踩方板拼缝。",
    ["lg_s_0", "lg_s_2", "lg_n_0", "lg_n_2"],
    highlight=["sn_a_1", "sn_b_1"],
    tip="长板墙顶边长 2 —— 等会儿雪顶底边要整边吸住它。",
)
b.step(
    "封山墙一层: 西端透明观景窗 + 东端橙色小门。",
    ["lg_win", "lg_door"],
    highlight=["lg_s_0", "lg_n_2"],
    tip="两条竖边同时吸住南北墙 —— 一层锁成闭环。",
)
b.step(
    "架南面雪顶: 2 片透明长板 60 度上倾, 底边整边吸南墙顶。",
    ["roof_s_0", "roof_s_2"],
    highlight=["lg_s_0", "lg_s_2"],
    tip="A 字屋顶越陡越滑雪 —— 60 度让积雪自己溜走。",
)
b.step(
    "架北面雪顶: 顶边在屋脊与南面雪顶两两互吸。",
    ["roof_n_0", "roof_n_2"],
    highlight=["roof_s_0", "roof_s_2"],
    tip="屋脊磁条对磁条 —— 墙-顶-墙锁成门式闭环。",
)
b.step(
    "塞山墙三角: 两片橙色等边刚好填满 A 形断面。",
    ["gable_w", "gable_e"],
    highlight=["roof_s_0", "roof_n_2"],
    tip="底边吸墙顶、两腰吸雪顶短边 —— 三边同时受力。",
)
b.step(
    "搭练习雪坡矮台: 2 片灰色长板矮墙 + 1 片台面。",
    ["pf_s", "pf_n", "pf_top"],
    highlight=["sn_a_7", "sn_b_7"],
    tip="台面两条长边整边压住矮墙顶 —— 双边受力。",
)
b.step(
    "架 30 度滑道: 顶边整边吸台面短边, 坡尾落回雪原。",
    ["slope"],
    highlight=["pf_top"],
    tip="顶铰链 + 接地坡尾 —— 越滑越稳, 冲呀新手道!",
)
b.step(
    "种雪杉林线 + 立路牌 + 堆雪丘 —— 滑雪小屋开门营业!",
    [f"fir_{x0}" for x0 in (0, 2, 4, 6)] + ["sign"] + DRIFT,
    highlight=["sn_b_0", "sn_b_9"],
    tip="雪杉与路牌重心正压拼缝铰链, 雪丘四棱互吸自锁。",
)

b.finalize(
    model_id="ski_lodge_01",
    name="滑雪小屋",
    name_en="Ski Lodge 01",
    description=(
        "全库第一栋 A 字形滑雪小屋: 红色长板墙上两面透明雪顶以 60 度"
        "对倾, 顶边在屋脊整边互吸锁成门式闭环, 山墙等边三角三边同时"
        "吸墙顶与两面雪顶 —— A 形断面自锁; 西山墙透明观景窗、东山墙"
        "橙色小门; 屋旁练习雪坡 30 度滑道顶铰链+接地坡尾, 林线四棵"
        "瘦高等腰雪杉, 雪场路牌与四坡雪丘点缀 —— 冲呀, 新手道!"
    ),
    difficulty=3,
    tags=["运动", "滑雪", "小屋", "雪原", "进阶"],
    min_pieces=54,
    min_steps=12,
)
