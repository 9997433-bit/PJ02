#!/usr/bin/env python3
"""生成模型 data/models/moon_lander_01.json (月宫着陆舱)。

太空主题: 与月面着陆器 lunar_lander_01 (3x3 箱体 + 甲板对接 +
风车状起落架) 结构逻辑完全不同的十字五舱着陆器 —— 下降级不是
方箱, 而是十字形五舱布局: 中央核心舱四面各接一间翼舱, 12 片
金色舱墙沿十字周界锁成一整条闭环; 十字屋面五片方板全靠板缝
互吸 (核心顶板四边都骑在翼舱顶板拼缝上, 多路受力); 核心舱上
再起一节透明舷窗上升舱, 戴等边四坡穹顶 (顶 2.71); 四个十字
舱尖各配一对直角三角八字抱脚 —— 双直角边分别咬住月面拼缝与
舱墙竖棱, 16 个方向都掰不倒; 舱东天线塔尖 3.0 直指地球,
橙色喷射灼痕、环形山、月岩与红旗铺满着陆场 —— 广寒宫到了。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 月面 6x5: 方板 x18 + 长板 x6 (透明环形山 + 橙色灼痕)     24 片
  - 十字舱墙 (z 0~1): 金墙 x11 + 门框方舱门 x1 (闭环)        12 片
  - 十字屋面 (z=1): 翼舱顶 x4 + 核心顶 x1 (板缝互吸)          5 片
  - 上升舱 (x [2,3], y [2,3], z 1~2): 灰墙 x2 + 舷窗 x2       4 片
  - 等边四坡穹顶 (顶 2.71): x4                                4 片
  - 八字抱脚: 直角三角 x8 (每个舱尖一对)                      8 片
  - 天线塔尖 (等腰, 尖 3.0) + 红旗 (方墙+等边旗) + 月岩 x3    6 片
  合计 63 片, 15 个教程步骤, 7 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, strict 档同样全绿):
  - 十字周界 12 片墙在 8 个凸角 + 4 个凹角全部竖边互吸,
    是一条真正的闭环 (剪断任意一条连接都有旁路);
  - 抱脚与舱尖墙共面: 竖直角边吸墙竖棱 (每条竖棱同时被两面
    墙共享, 一脚三吸), 水平直角边吸月面拼缝 —— 零悬挑;
  - 核心顶板无墙可踩, 四边全部骑翼舱顶板拼缝 (四路受力);
    上升舱墙再踩这些拼缝, 每片底边双连接;
  - 穹顶四棱互吸自锁; 天线塔尖底边同时吸翼舱顶沿与舱墙顶边
    (双连接), 重心正压铰链线力矩 0; 全模型最高 3.0 触发 R8
    高层检查, 闭环 + 双连接处处冗余, 零警告。

用法: python3 tools/generate_moon_lander.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

MOON = "gray"       # 月面
CRATER = "clear"    # 环形山
SCORCH = "orange"   # 喷射灼痕
HULL = "yellow"     # 下降级舱墙 (金箔)
HATCH = "orange"    # 舱门
DECK = "gray"       # 十字屋面
ASCENT = "gray"     # 上升舱
GLASS = "clear"     # 舷窗
DOME = "clear"      # 穹顶
LEG = "orange"      # 抱脚
ANT = "clear"       # 天线塔尖
POLE = "gray"       # 旗杆
FLAG = "red"        # 红旗
ROCK = "gray"       # 月岩

# =================================================================
# 1. 月面 6x5 (x [0,6], y [0,5]): 南北长板收边 + 中三行方板
# =================================================================
CRATER_CELLS = {(0, 1), (5, 3), (4, 3)}
SCORCH_CELLS = {(2, 2)}
for k in range(3):
    b.flat_rect(f"mn_s_{k}", 2 * k, 0, 0.0, MOON)
for y in range(1, 4):
    for x in range(6):
        color = MOON
        if (x, y) in CRATER_CELLS:
            color = CRATER
        elif (x, y) in SCORCH_CELLS:
            color = SCORCH
        b.flat(f"mn_{x}_{y}", x, y, 0.0, color)
for k in range(3):
    b.flat_rect(f"mn_n_{k}", 2 * k, 4, 0.0, MOON)

# =================================================================
# 2. 十字舱墙 (z 0~1): 核心 (2,2) 四面接翼舱, 周界 12 片闭环
# =================================================================
b.add("hatch", "door_frame", (2.5, 1.0, 0.5), (90, 0, 0), HATCH)  # 南舱门
b.wall_ew("wS_w", 2.0, 1, 0, HULL)
b.wall_ew("wS_e", 3.0, 1, 0, HULL)
b.wall_ns("wN_n", 2, 4.0, 0, HULL)
b.wall_ew("wN_w", 2.0, 3, 0, HULL)
b.wall_ew("wN_e", 3.0, 3, 0, HULL)
b.wall_ew("wW_w", 1.0, 2, 0, HULL)
b.wall_ns("wW_s", 1, 2.0, 0, HULL)
b.wall_ns("wW_n", 1, 3.0, 0, HULL)
b.wall_ew("wE_e", 4.0, 2, 0, HULL)
b.wall_ns("wE_s", 3, 2.0, 0, HULL)
b.wall_ns("wE_n", 3, 3.0, 0, HULL)

# =================================================================
# 3. 八字抱脚: 每个十字舱尖一对直角三角, 与舱尖墙共面
# =================================================================
b.brace("lg_s_w", (2.0, 1.0, 0.0), "-x", LEG)
b.brace("lg_s_e", (3.0, 1.0, 0.0), "+x", LEG)
b.brace("lg_n_w", (2.0, 4.0, 0.0), "-x", LEG)
b.brace("lg_n_e", (3.0, 4.0, 0.0), "+x", LEG)
b.brace("lg_w_s", (1.0, 2.0, 0.0), "-y", LEG)
b.brace("lg_w_n", (1.0, 3.0, 0.0), "+y", LEG)
b.brace("lg_e_s", (4.0, 2.0, 0.0), "-y", LEG)
b.brace("lg_e_n", (4.0, 3.0, 0.0), "+y", LEG)

# =================================================================
# 4. 十字屋面 (z=1): 翼舱顶 x4 + 核心顶 (板缝互吸)
# =================================================================
b.flat("dk_s", 2, 1, 1.0, DECK)
b.flat("dk_n", 2, 3, 1.0, DECK)
b.flat("dk_w", 1, 2, 1.0, DECK)
b.flat("dk_e", 3, 2, 1.0, DECK)
b.flat("dk_c", 2, 2, 1.0, DECK)

# =================================================================
# 5. 上升舱 (z 1~2) + 等边四坡穹顶 + 天线塔尖
# =================================================================
b.wall_ns("asc_s", 2, 2.0, 1, ASCENT)
b.wall_ns("asc_n", 2, 3.0, 1, ASCENT)
b.add("asc_w", "window_square", (2.0, 2.5, 1.5), (90, 0, 90), GLASS)
b.add("asc_e", "window_square", (3.0, 2.5, 1.5), (90, 0, 90), GLASS)
DOME_IDS = b.hat4("dome", 2, 2, 2.0, DOME, shape="equilateral_triangle")
b.spire_ew("antenna", 4.0, 2, 1.0, ANT)

# =================================================================
# 6. 红旗 + 月岩
# =================================================================
b.wall_ns("flag_pole", 4, 1.0, 0, POLE)
b.crest_ns("flag_top", 4, 1.0, 1.0, FLAG)
b.crest_ew("rock_a", 5.0, 1, 0.0, ROCK)
b.crest_ns("rock_b", 0, 3.0, 0.0, ROCK)
b.crest_ew("rock_c", 6.0, 2, 0.0, ROCK)

# =================================================================
# 教程步骤 (15 步)
# =================================================================
b.step(
    "铺月面南沿: 3 片灰长板 (y [0,1])。",
    ["mn_s_0", "mn_s_1", "mn_s_2"],
    tip="着陆场从南沿铺起 —— 舱门朝这边开。",
)
b.step(
    "铺第二行 (y [1,2]): 6 片, 西端透明环形山。",
    [f"mn_{x}_1" for x in range(6)],
    highlight=["mn_s_0"],
    tip="南抱脚与旗杆都踩这行拼缝。",
)
b.step(
    "铺第三行 (y [2,3]): 6 片, 中央橙斑是发动机喷射灼痕。",
    [f"mn_{x}_2" for x in range(6)],
    highlight=["mn_0_1"],
    tip="灼痕正下方就是核心舱 —— 着陆点分毫不差。",
)
b.step(
    "铺第四行 (y [3,4]): 6 片, 东侧两个环形山。",
    [f"mn_{x}_3" for x in range(6)],
    highlight=["mn_2_2"],
    tip="环形山是陨石砸出来的 —— 着陆器绕着它们落。",
)
b.step(
    "铺北沿: 3 片长板, 月面合拢。",
    ["mn_n_0", "mn_n_1", "mn_n_2"],
    highlight=["mn_0_3"],
    tip="六五月面铺满 —— 十字着陆器马上落月。",
)
b.step(
    "立南翼与西翼舱墙: 门框方舱门朝南, 6 片墙竖边互吸。",
    ["hatch", "wS_w", "wS_e", "wW_w", "wW_s", "wW_n"],
    highlight=["mn_2_1", "mn_1_2"],
    tip="十字周界开始合围 —— 凹角竖边也要咬紧。",
)
b.step(
    "立北翼与东翼舱墙: 再来 6 片, 十字闭环锁死。",
    ["wN_n", "wN_w", "wN_e", "wE_e", "wE_s", "wE_n"],
    highlight=["hatch", "wW_w"],
    tip="12 片墙 8 凸角 4 凹角全互吸 —— 剪断哪条都有旁路。",
)
b.step(
    "装南北舱尖抱脚: 4 片直角三角, 双直角边咬墙棱与拼缝。",
    ["lg_s_w", "lg_s_e", "lg_n_w", "lg_n_e"],
    highlight=["hatch", "wN_n"],
    tip="八字张开 —— 落月冲击全被抱脚分走。",
)
b.step(
    "装东西舱尖抱脚: 再来 4 片, 十六个方向都掰不倒。",
    ["lg_w_s", "lg_w_n", "lg_e_s", "lg_e_n"],
    highlight=["wW_w", "wE_e"],
    tip="一条竖棱两面墙共享 —— 抱脚一咬就是三吸。",
)
b.step(
    "盖四间翼舱顶板: 每片压三面墙顶。",
    ["dk_s", "dk_n", "dk_w", "dk_e"],
    highlight=["wS_w", "wE_n"],
    tip="翼舱顶板三边都有墙可踩 —— 稳稳当当。",
)
b.step(
    "盖核心顶板 + 竖天线塔尖: 顶板四边全骑翼舱板缝。",
    ["dk_c", "antenna"],
    highlight=["dk_s", "dk_e"],
    tip="核心顶板下面没有墙 —— 全靠四条板缝多路受力。",
)
b.step(
    "起上升舱: 2 片灰墙 + 2 片舷窗踩核心顶板缝。",
    ["asc_s", "asc_n", "asc_w", "asc_e"],
    highlight=["dk_c"],
    tip="每片底边同时吸核心顶与翼舱顶 —— 双连接。",
)
b.step(
    "戴等边四坡穹顶: 顶 2.71, 四棱互吸自锁。",
    DOME_IDS,
    highlight=["asc_s", "asc_e"],
    tip="穹顶合拢 —— 上升舱随时可以点火回家。",
)
b.step(
    "插红旗: 方墙旗杆踩拼缝, 等边红旗压杆顶。",
    ["flag_pole", "flag_top"],
    highlight=["mn_4_1"],
    tip="旗面重心正压铰链 —— 月面无风, 旗永远展开。",
)
b.step(
    "摆三块月岩 —— 广寒宫到了!",
    ["rock_a", "rock_b", "rock_c"],
    highlight=["mn_5_1", "mn_0_3"],
    tip="月岩重心正压拼缝铰链, 力矩为零。",
)

b.finalize(
    model_id="moon_lander_01",
    name="月宫着陆舱",
    name_en="Moon Lander 01",
    description=(
        "十字五舱月面着陆器 (结构逻辑不同于月面着陆器的方箱"
        "对接): 中央核心舱四面各接一间翼舱, 12 片金色舱墙沿"
        "十字周界 8 凸角 4 凹角全部竖边互吸闭环; 核心顶板无墙"
        "可踩, 四边全骑翼舱顶板拼缝多路受力; 其上再起透明舷窗"
        "上升舱, 戴等边四坡穹顶 (2.71); 四个舱尖各配一对直角"
        "三角八字抱脚 —— 竖直角边吸墙竖棱、水平直角边吸月面"
        "拼缝, 一脚三吸零悬挑; 天线塔尖 3.0 直指地球, 灼痕"
        "环形山月岩红旗铺满着陆场 —— 广寒宫到了。"
    ),
    difficulty=3,
    tags=["航天", "着陆器", "月球", "航天器", "进阶"],
    min_pieces=60,
    min_steps=15,
)
