#!/usr/bin/env python3
"""生成模型 data/models/hanging_garden_01.json (空中花园)。

奇观园林主题: 两座 2 层砖塔 (屋顶花园) 之间架起 6 格长的空中绿廊,
绿廊下方悬挂 3 幅绿色藤幕 (真正"吊挂"在桥板长边下), 廊面北沿立
3 面粉色花篱 (立式梯形), 塔顶绿茵上有灌木与棕榈; 西塔半腰一道
青色瀑布顺 30 度坡道泻入塔脚水池, 塔间地面是石板中庭, 塔前石径
上再植灌木棕榈 —— 悬空的花园、垂落的藤蔓、跌落的流水层层呼应。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 西塔 [0,2]x[0,2] (z 0..2): 两层箱形墙 16 + 绿茵顶板 4        20 片
  - 东塔 [8,10]x[0,2]: 同构                                      20 片
  - 塔间中庭石板 [2,8]x[0,1]: 方片 6                              6 片
  - 塔前石径 y[-1,0]: 方片 4                                      4 片
  - 水池 [-2,0]x[0,2]: 青色方片 4                                 4 片
  - 瀑布: 30 度坡道 1 片 (顶边吸西塔半腰, 坡尾落地)               1 片
  - 拱廊墩 x=4 / x=6: 各 2x2 立墙                                 8 片
  - 空中绿廊 [2,8]x[0,2] (z=2): 长板 6                            6 片
  - 悬挂藤幕: 3 片长板吊挂在绿廊南长边下 (z 1..2)                 3 片
  - 花篱: 3 片立式梯形立在绿廊北长边                              3 片
  - 塔顶花园: 灌木 4 + 棕榈 2                                     6 片
  - 石径花木: 灌木 2 + 棕榈 2                                     4 片
  合计 85 片, 18 个教程步骤, 5 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 藤幕顶边整边吸绿廊长板南长边 (R5 悬挂), 两侧竖边又分别吸
    塔壁/拱廊墩竖边, 吊挂之余再加侧向锁定;
  - 绿廊两端短边吸塔顶板, 中间两道短边缝正落在拱廊墩顶边上,
    四线支承, 无悬臂;
  - 瀑布坡道顶边吸西塔半腰墙缝 (三片共线), 坡尾触地自承;
  - 中庭石板把两塔与拱廊墩在地面连成一体, 全程无孤立分组。

用法: python3 tools/generate_hanging_garden.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

BRICK = "orange"    # 塔身与拱廊墩
TURF = "green"      # 绿茵 / 藤蔓 / 花木
WATER = "cyan"      # 水池与瀑布
STONE = "gray"      # 中庭与石径
FLOWER = "pink"     # 花篱

# =================================================================
# 1. 东西双塔 [0,2]x[0,2] 与 [8,10]x[0,2]: 两层箱形墙 + 绿茵顶板
# =================================================================
for pfx, bx in (("wt", 0), ("et", 8)):
    for z in range(2):
        for dx in range(2):
            b.wall_ns(f"{pfx}_s_{dx}_{z}", bx + dx, 0.0, z, BRICK)
            b.wall_ns(f"{pfx}_n_{dx}_{z}", bx + dx, 2.0, z, BRICK)
        for dy in range(2):
            b.wall_ew(f"{pfx}_w_{dy}_{z}", bx + 0.0, dy, z, BRICK)
            b.wall_ew(f"{pfx}_e_{dy}_{z}", bx + 2.0, dy, z, BRICK)
    for dx in range(2):
        for dy in range(2):
            b.flat(f"{pfx}_fl_{dx}_{dy}", bx + dx, dy, 2.0, TURF)

# =================================================================
# 2. 地面: 塔间中庭石板 / 塔前石径 / 西塔脚水池
# =================================================================
for x in range(2, 8):                               # 中庭石板 [2,8]x[0,1]
    b.flat(f"ct_{x}", x, 0, 0.0, STONE)
for x in (0, 1, 8, 9):                              # 塔前石径 y [-1,0]
    b.flat(f"fc_{x}", x, -1, 0.0, STONE)
for x0 in (-1, -2):                                 # 水池 [-2,0]x[0,2]
    for y0 in (0, 1):
        b.flat(f"pool_{x0}_{y0}", x0, y0, 0.0, WATER)

# 瀑布: 顶边吸西塔西壁半腰 (z=1 墙缝), 向西泻下, 坡尾落地入池
b.ramp("cascade", "-x", 0, 0, 1.0, WATER)

# =================================================================
# 3. 拱廊墩 x=4 / x=6: 各一面 2x2 立墙, 底边吸中庭石板边
# =================================================================
for px in (4, 6):
    for dy in range(2):
        for z in range(2):
            b.wall_ew(f"pr{px}_{dy}_{z}", float(px), dy, z, BRICK)

# =================================================================
# 4. 空中绿廊 [2,8]x[0,2] (z=2) + 悬挂藤幕 + 花篱
# =================================================================
for x0 in (2, 4, 6):
    b.flat_rect(f"dk_{x0}_0", x0, 0, 2.0, TURF)     # 绿廊长板
    b.flat_rect(f"dk_{x0}_1", x0, 1, 2.0, TURF)
for x0 in (2, 4, 6):                                # 藤幕吊挂在南长边下
    b.lintel_ns(f"vine_{x0}", x0, 0.0, 1, TURF)
for x0 in (2, 4, 6):                                # 花篱立在北长边上
    b.place_edge(f"hedge_{x0}", "trapezoid", 0,
                 (float(x0), 2.0, 2.0), (float(x0 + 2), 2.0, 2.0),
                 (0.0, 0.0, 1.0), FLOWER)

# =================================================================
# 5. 塔顶花园 + 石径花木
# =================================================================
b.crest_ns("wt_bush_0", 0, 0.0, 2.0, TURF)          # 西塔南沿灌木
b.crest_ns("wt_bush_1", 1, 0.0, 2.0, TURF)
b.spire_ns("wt_palm", 0, 2.0, 2.0, TURF)            # 西塔北沿棕榈
b.crest_ns("et_bush_8", 8, 2.0, 2.0, TURF)          # 东塔北沿灌木
b.crest_ns("et_bush_9", 9, 2.0, 2.0, TURF)
b.spire_ns("et_palm", 9, 0.0, 2.0, TURF)            # 东塔南沿棕榈
b.crest_ns("shrub_1", 1, -1.0, 0.0, TURF)           # 石径灌木
b.crest_ns("shrub_8", 8, -1.0, 0.0, TURF)
b.spire_ns("palm_0", 0, -1.0, 0.0, TURF)            # 石径棕榈
b.spire_ns("palm_9", 9, -1.0, 0.0, TURF)

# =================================================================
# 教程步骤 (18 步)
# =================================================================
b.step(
    "起西塔首层: 8 片橙色方片围成 2x2 箱形墙, 相邻竖边两两互吸。",
    [f"wt_{s}_{i}_0" for s in ("s", "n") for i in (0, 1)]
    + [f"wt_{s}_{i}_0" for s in ("w", "e") for i in (0, 1)],
    tip="箱形墙四角自锁 —— 空中花园的西塔从这圈砖墙长起。",
)
b.step(
    "铺塔间中庭: 6 片灰色石板从西塔东墙脚一路铺到 x=8。",
    [f"ct_{x}" for x in range(2, 8)],
    highlight=["wt_e_0_0"],
    tip="第一片石板西边吸西塔墙脚 —— 中庭负责把全场连成一体。",
)
b.step(
    "起东塔首层: 中庭东端再围一圈 2x2 箱形墙, 西墙脚吸石板东边。",
    [f"et_{s}_{i}_0" for s in ("s", "n") for i in (0, 1)]
    + [f"et_{s}_{i}_0" for s in ("w", "e") for i in (0, 1)],
    highlight=["ct_7"],
    tip="两塔隔中庭相望 —— 之后空中绿廊就架在它们之间。",
)
b.step(
    "铺塔前石径: 两塔南墙脚各铺 2 片灰色石板。",
    ["fc_0", "fc_1", "fc_8", "fc_9"],
    highlight=["wt_s_0_0", "et_s_1_0"],
    tip="石径北边整边吸塔墙脚, 是游客仰望空中花园的地方。",
)
b.step(
    "挖西塔脚水池: 4 片青色方片铺在西塔西墙脚外。",
    ["pool_-1_0", "pool_-1_1", "pool_-2_0", "pool_-2_1"],
    highlight=["wt_w_0_0", "wt_w_1_0"],
    tip="池板东边吸塔墙脚 —— 等着接住半腰泻下的瀑布。",
)
b.step(
    "西塔加高到二层: 再叠 8 片橙色方片, 上下墙缝整边贴合。",
    [f"wt_{s}_{i}_1" for s in ("s", "n") for i in (0, 1)]
    + [f"wt_{s}_{i}_1" for s in ("w", "e") for i in (0, 1)],
    highlight=["wt_s_0_0"],
    tip="第二层墙缝就是瀑布出水口的高度。",
)
b.step(
    "东塔加高到二层: 同样再叠 8 片。",
    [f"et_{s}_{i}_1" for s in ("s", "n") for i in (0, 1)]
    + [f"et_{s}_{i}_1" for s in ("w", "e") for i in (0, 1)],
    highlight=["et_s_0_0"],
    tip="两塔同高, 塔顶将来都是绿茵花园。",
)
b.step(
    "挂瀑布: 1 片青色长板顶边吸西塔西壁半腰墙缝, 30 度泻向水池, "
    "坡尾触地。",
    ["cascade"],
    highlight=["wt_w_0_0", "wt_w_0_1"],
    tip="顶边与上下两层墙缝三线共吸, 坡尾自己踩地 —— 流水稳稳落池。",
)
b.step(
    "铺西塔绿茵顶板: 4 片绿色方片盖住塔口, 四边吸墙顶边。",
    ["wt_fl_0_0", "wt_fl_1_0", "wt_fl_0_1", "wt_fl_1_1"],
    highlight=["wt_s_0_1", "wt_n_1_1"],
    tip="盖上顶板, 砖塔变花台 —— 空中花园的西端平台就绪。",
)
b.step(
    "铺东塔绿茵顶板: 同样 4 片绿色方片封顶。",
    ["et_fl_0_0", "et_fl_1_0", "et_fl_0_1", "et_fl_1_1"],
    highlight=["et_s_0_1", "et_n_1_1"],
    tip="东端平台就绪, 就差中间 6 格的绿廊了。",
)
b.step(
    "立第一道拱廊墩: x=4 处 4 片橙色方片砌成 2x2 立墙, "
    "底边吸中庭石板缝。",
    ["pr4_0_0", "pr4_1_0", "pr4_0_1", "pr4_1_1"],
    highlight=["ct_3", "ct_4"],
    tip="墩墙底边正落在两片石板的拼缝上, 左右各吸一边。",
)
b.step(
    "立第二道拱廊墩: x=6 处再砌一面 2x2 立墙。",
    ["pr6_0_0", "pr6_1_0", "pr6_0_1", "pr6_1_1"],
    highlight=["ct_5", "ct_6"],
    tip="两道墩把塔间分成三孔拱廊 —— 藤幕就挂在这三孔上方。",
)
b.step(
    "架空中绿廊: 6 片绿色长板从西塔顶铺到东塔顶, 两端短边吸塔顶板, "
    "中间两道拼缝正压拱廊墩顶边。",
    [f"dk_{x0}_{y}" for x0 in (2, 4, 6) for y in (0, 1)],
    highlight=["wt_fl_1_0", "et_fl_0_0", "pr4_0_1", "pr6_0_1"],
    tip="四线支承的空中平台 —— 名副其实的悬空花园。",
)
b.step(
    "挂藤幕: 3 片绿色长板顶边整边吸绿廊南长边, 垂挂在三孔拱廊前, "
    "两侧竖边又吸住塔壁与墩边。",
    ["vine_2", "vine_4", "vine_6"],
    highlight=["dk_2_0", "dk_4_0", "dk_6_0"],
    tip="藤蔓从空中平台垂落 —— 这就是'空中花园'的招牌一幕。",
)
b.step(
    "立花篱: 3 片粉色梯形下底整边吸绿廊北长边, 立成一排花墙。",
    ["hedge_2", "hedge_4", "hedge_6"],
    highlight=["dk_2_1", "dk_6_1"],
    tip="梯形下底长 2 恰与长板等长 —— 南垂藤、北开花。",
)
b.step(
    "布置西塔顶花园: 南沿立 2 丛灌木, 北沿立 1 棵棕榈。",
    ["wt_bush_0", "wt_bush_1", "wt_palm"],
    highlight=["wt_fl_0_0"],
    tip="灌木底边吸顶板南边, 棕榈高过花篱 —— 层层叠叠都是绿。",
)
b.step(
    "布置东塔顶花园: 北沿立 2 丛灌木, 南沿立 1 棵棕榈。",
    ["et_bush_8", "et_bush_9", "et_palm"],
    highlight=["et_fl_1_1"],
    tip="与西塔对角呼应, 从哪个方向看都有绿意压顶。",
)
b.step(
    "种石径花木: 石径南沿立 2 丛灌木、2 棵棕榈 —— 空中花园落成!",
    ["shrub_1", "shrub_8", "palm_0", "palm_9"],
    highlight=["fc_1", "fc_8"],
    tip="地面有石径流水, 半空有藤幕花篱, 塔顶有绿茵棕榈 —— 三层花园。",
)

b.finalize(
    model_id="hanging_garden_01",
    name="空中花园",
    name_en="Hanging Garden 01",
    description=(
        "两座 2 层橙砖塔顶着绿茵花园, 塔间 6 格长的空中绿廊由塔顶板与两道"
        "拱廊墩四线支承; 3 幅绿藤幕真正吊挂在绿廊南长边下 (R5 悬挂 + 侧边"
        "锁定), 北沿立起 3 面粉色梯形花篱; 西塔半腰一道青色瀑布顺 30 度"
        "坡道泻入塔脚水池, 塔间石板中庭、塔前石径花木把全场连成一体 —— "
        "悬空的花园、垂落的藤蔓、跌落的流水, 三层绿意层层呼应。"
    ),
    difficulty=4,
    tags=["奇观", "花园", "自然", "建筑", "进阶"],
    min_pieces=75,
    min_steps=18,
)
