#!/usr/bin/env python3
"""生成模型 data/models/planetarium_02.json (十字星厅天文馆)。

博物馆/艺术主题 4/4: 全库第一座十字形平面建筑 —— 与
planetarium_01 (六棱鼓身 + 浅锥星空穹) 和 observatory_01 (长方形
叠环鼓身 + 棱面穹顶) 的圆厅逻辑完全不同: 星厅是方的, 平面是
十字 —— 3x3 中央大厅向东西各伸一条长板墙侧翼 (整面墙就是一块
长板, 底边 2.0 一线双吸地板长缝), 向南伸出入口门廊; 大厅屋面
是 3x3 回字环 (中心留 1x1 采光井), 井口四沿立透明窗格方采光鼓,
鼓顶等腰四坡锥收出 3.94 高的星塔金尖; 馆内星象仪先立后封顶
(R7b), 天窗竖井正对星象仪 —— 星光落在仪器上; 前庭一座四棱
太阳雕塑直接落地自锁, 月相步道从门廊一路排开。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 入口朝南):
  - 地面 (x [0,7], y [0,6]): 前庭 + 大厅 + 侧翼地板 6 行      29 片
  - 中央大厅墙环 (z 0..1): 南 3 (含门) + 北 3 + 东西各 2,
    东西留 1 格负空间通道接侧翼                               10 片
  - 馆内星象仪 x1 (先立后封顶) + 入口门廊 x4                   5 片
  - 东西侧翼 x2: 长板墙 x2 + 端墙 + 翼顶 + 端头三角 各 5 片   10 片
  - 大厅回字环屋面 (z=1, 中心留 1x1 采光井)                    8 片
  - 采光鼓窗格方 x4 + 等腰四坡锥星塔 x4 (金尖 3.94)            8 片
  - 前庭太阳雕塑: 等边四棱落地自锁 x4                          4 片
  合计 74 片, 12 个教程步骤, 7 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (R1~R8 全绿, strict 档零警告):
  - 大厅墙环四角竖边闭环 (东西通道两侧的墙段经地板与屋面绕行);
    回字环屋面每片同时压墙顶与邻板拼缝;
  - 采光鼓四片窗格方吸井口四沿、四角竖边闭环, 星塔四棱互吸自锁;
  - 侧翼长板墙底边 2.0 同侧一线双吸, 翼顶三边受力 (南北墙顶 +
    端墙顶) 零悬挑; 门廊顶三边受力 (双墙顶 + 大厅门楣顶);
  - 星象仪与采光井同轴, 先立后封顶满足 R7b 装配可达。

用法: python3 tools/generate_planetarium_02.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

PLAZA = "gray"      # 前庭石板
PATH = "orange"     # 入馆步道
HALL_F = "cyan"     # 大厅地板
DIAL = "yellow"     # 星象仪座
WALL = "gray"       # 馆墙
STARW = "blue"      # 星窗
GLASS = "clear"     # 采光鼓 / 月相步道
ROOF = "blue"       # 屋面
SPIRE = "purple"    # 星塔锥
GOLD = "yellow"     # 星象仪 / 端头三角 / 太阳

# =================================================================
# 1. 地面 (x [0,7], y [0,6]): 前庭 + 大厅 + 侧翼, 拼缝对准全部墙线
# =================================================================
b.flat_rect("f0_a", 0, 0, 0.0, PLAZA)
b.flat_rect("f0_b", 2, 0, 0.0, PLAZA)
b.flat("f0_c", 4, 0, 0.0, GLASS)          # 月相步道
b.flat("f0_d", 6, 0, 0.0, GLASS)          # (5,0) 留给太阳雕塑落地

b.flat_rect("f1_a", 0, 1, 0.0, PLAZA)
b.flat("f1_b", 2, 1, 0.0, PLAZA)
b.flat("f1_c", 3, 1, 0.0, PATH)           # 门廊地
b.flat("f1_d", 4, 1, 0.0, PLAZA)
b.flat("f1_e", 5, 1, 0.0, PLAZA)
b.flat("f1_f", 6, 1, 0.0, PLAZA)

b.flat_rect("f2_a", 0, 2, 0.0, PLAZA)
b.flat("f2_b", 2, 2, 0.0, HALL_F)
b.flat("f2_c", 3, 2, 0.0, HALL_F)
b.flat("f2_d", 4, 2, 0.0, HALL_F)
b.flat_rect("f2_e", 5, 2, 0.0, PLAZA)

b.flat_rect("f3_a", 0, 3, 0.0, PLAZA)     # 西翼地板 (长缝给长板墙)
b.flat("f3_b", 2, 3, 0.0, HALL_F)
b.flat("f3_c", 3, 3, 0.0, DIAL)           # 星象仪座 (与采光井同轴)
b.flat("f3_d", 4, 3, 0.0, HALL_F)
b.flat_rect("f3_e", 5, 3, 0.0, PLAZA)     # 东翼地板

b.flat_rect("f4_a", 0, 4, 0.0, PLAZA)
b.flat("f4_b", 2, 4, 0.0, HALL_F)
b.flat("f4_c", 3, 4, 0.0, HALL_F)
b.flat("f4_d", 4, 4, 0.0, HALL_F)
b.flat_rect("f4_e", 5, 4, 0.0, PLAZA)

b.flat_rect("f5_a", 0, 5, 0.0, PLAZA)
b.flat_rect("f5_b", 2, 5, 0.0, PLAZA)
b.flat_rect("f5_c", 4, 5, 0.0, PLAZA)
b.flat("f5_d", 6, 5, 0.0, PLAZA)

# =================================================================
# 2. 中央大厅墙环 (x [2,5], y [2,5], z 0..1): 东西留通道
# =================================================================
b.add("hS_w", "window_square", (2.5, 2.0, 0.5), (90, 0, 0), STARW)
b.add("hS_d", "door_frame", (3.5, 2.0, 0.5), (90, 0, 0), GLASS)
b.add("hS_e", "window_square", (4.5, 2.0, 0.5), (90, 0, 0), STARW)
b.wall_ew("hE_s", 5.0, 2, 0, WALL)        # 东墙 y [3,4] 留通道
b.wall_ns("hN_w", 2, 5.0, 0, WALL)
b.add("hN_m", "window_square", (3.5, 5.0, 0.5), (90, 0, 0), STARW)
b.wall_ns("hN_e", 4, 5.0, 0, WALL)
b.wall_ew("hE_n", 5.0, 4, 0, WALL)
b.wall_ew("hW_s", 2.0, 2, 0, WALL)        # 西墙 y [3,4] 留通道
b.wall_ew("hW_n", 2.0, 4, 0, WALL)

# =================================================================
# 3. 馆内星象仪 (先立后封顶) + 入口门廊 (x [3,4], y [1,2])
# =================================================================
b.crest_ns("orrery", 3, 4.0, 0.0, GOLD)   # 星象仪金色指针, 正对采光井
b.wall_ew("po_w", 3.0, 1, 0, WALL)
b.wall_ew("po_e", 4.0, 1, 0, WALL)
b.flat("po_roof", 3, 1, 1.0, ROOF)        # 三边受力: 双墙顶 + 门楣顶
b.crest_ns("po_crest", 3, 1.0, 1.0, GOLD)

# =================================================================
# 4. 东西侧翼 (y [3,4], z 0..1): 长板墙 + 端墙 + 翼顶 + 端头三角
# =================================================================
b.lintel_ns("wingW_s", 0, 3.0, 0, WALL)   # 底边 2.0 一线双吸
b.lintel_ns("wingW_n", 0, 4.0, 0, WALL)
b.wall_ew("wingW_cap", 0.0, 3, 0, WALL)
b.flat_rect("wingW_roof", 0, 3, 1.0, ROOF)
b.crest_ew("wingW_tri", 0.0, 3, 1.0, GOLD)
b.lintel_ns("wingE_s", 5, 3.0, 0, WALL)
b.lintel_ns("wingE_n", 5, 4.0, 0, WALL)
b.wall_ew("wingE_cap", 7.0, 3, 0, WALL)
b.flat_rect("wingE_roof", 5, 3, 1.0, ROOF)
b.crest_ew("wingE_tri", 7.0, 3, 1.0, GOLD)

# =================================================================
# 5. 大厅回字环屋面 (z=1): 中心留 1x1 采光井 (x [3,4], y [3,4])
# =================================================================
b.flat("r_s1", 2, 2, 1.0, ROOF)
b.flat("r_s2", 3, 2, 1.0, ROOF)
b.flat("r_s3", 4, 2, 1.0, ROOF)
b.flat("r_w", 2, 3, 1.0, ROOF)
b.flat("r_e", 4, 3, 1.0, ROOF)
b.flat("r_n1", 2, 4, 1.0, ROOF)
b.flat("r_n2", 3, 4, 1.0, ROOF)
b.flat("r_n3", 4, 4, 1.0, ROOF)

# =================================================================
# 6. 采光鼓 (z 1..2) + 星塔等腰四坡锥 (金尖 3.94)
# =================================================================
b.add("drum_s", "window_square", (3.5, 3.0, 1.5), (90, 0, 0), GLASS)
b.add("drum_e", "window_square", (4.0, 3.5, 1.5), (90, 0, 90), GLASS)
b.add("drum_n", "window_square", (3.5, 4.0, 1.5), (90, 0, 0), GLASS)
b.add("drum_w", "window_square", (3.0, 3.5, 1.5), (90, 0, 90), GLASS)
SPIRE_IDS = b.hat4("spire", 3, 3, 2.0, SPIRE)

# =================================================================
# 7. 前庭太阳雕塑 (x [5,6], y [0,1]): 等边四棱落地自锁
# =================================================================
SUN_IDS = b.hat4("sun", 5, 0, 0.0, GOLD, shape="equilateral_triangle")

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺前庭两行 (y [0,2]): 10 片, 透明月相步道排上南缘。",
    ["f0_a", "f0_b", "f0_c", "f0_d",
     "f1_a", "f1_b", "f1_c", "f1_d", "f1_e", "f1_f"],
    tip="(5,0) 一格故意留空 —— 太阳雕塑最后直接落地自锁。",
)
b.step(
    "铺大厅与侧翼两行 (y [2,4]): 10 片, 黄色一格是星象仪座。",
    ["f2_a", "f2_b", "f2_c", "f2_d", "f2_e",
     "f3_a", "f3_b", "f3_c", "f3_d", "f3_e"],
    highlight=["f1_c"],
    tip="星象仪座正对未来的采光井 —— 星光会落在这一格。",
)
b.step(
    "铺北侧两行 (y [4,6]): 9 片, 场地合拢。",
    ["f4_a", "f4_b", "f4_c", "f4_d", "f4_e",
     "f5_a", "f5_b", "f5_c", "f5_d"],
    highlight=["f3_c"],
    tip="大厅墙环与侧翼长板墙都压在这些拼缝上。",
)
b.step(
    "立大厅南墙与东南角: 星窗-馆门-星窗 + 东墙南段。",
    ["hS_w", "hS_d", "hS_e", "hE_s"],
    highlight=["f1_c"],
    tip="东墙 y [3,4] 留一格负空间 —— 那是通往东翼的室内通道。",
)
b.step(
    "立大厅北墙与另三个墙角: 6 片, 墙环闭合。",
    ["hN_w", "hN_m", "hN_e", "hE_n", "hW_s", "hW_n"],
    highlight=["hS_w"],
    tip="西墙同样留通道 —— 十字平面的四条臂从这里伸出去。",
)
b.step(
    "立星象仪、围门廊: 金色指针正对井位, 门廊顶三边受力。",
    ["orrery", "po_w", "po_e", "po_roof", "po_crest"],
    highlight=["f3_c", "hS_d"],
    tip="先立仪器后封顶 (R7b) —— 装配顺序就是布展顺序。",
)
b.step(
    "搭西翼: 两块长板墙一线双吸 + 端墙 + 翼顶 + 端头金三角。",
    ["wingW_s", "wingW_n", "wingW_cap", "wingW_roof", "wingW_tri"],
    highlight=["hW_s", "hW_n"],
    tip="整面墙就是一块长板, 底边 2.0 同时吸两段地板长缝。",
)
b.step(
    "搭东翼: 与西翼镜像, 十字平面的东西臂完成。",
    ["wingE_s", "wingE_n", "wingE_cap", "wingE_roof", "wingE_tri"],
    highlight=["hE_s", "hE_n"],
    tip="翼顶南北压长板墙顶、西端压大厅墙侧 —— 零悬挑。",
)
b.step(
    "盖大厅回字环屋面: 8 片, 中心留 1x1 采光井。",
    ["r_s1", "r_s2", "r_s3", "r_w", "r_e", "r_n1", "r_n2", "r_n3"],
    highlight=["orrery"],
    tip="每片同时压墙顶与邻板拼缝; 井口正上方就是星塔的位置。",
)
b.step(
    "立采光鼓: 4 片透明窗格方吸井口四沿, 四角竖边闭环。",
    ["drum_s", "drum_e", "drum_n", "drum_w"],
    highlight=["r_s2", "r_e"],
    tip="鼓身是井口上的一圈玻璃 —— 白天采光, 夜里透星。",
)
b.step(
    "收星塔: 4 片等腰三角四棱互吸, 金尖 3.94 全馆最高。",
    SPIRE_IDS,
    highlight=["drum_s"],
    tip="瘦高的等腰锥收出星塔尖 —— 从很远就能认出天文馆。",
)
b.step(
    "落前庭太阳雕塑 —— 十字星厅天文馆开馆!",
    SUN_IDS,
    highlight=["f0_c"],
    tip="四片等边三角直接落地四棱自锁, 月相步道尽头升起太阳。",
)

b.finalize(
    model_id="planetarium_02",
    name="十字星厅天文馆",
    name_en="Planetarium 02",
    description=(
        "全库第一座十字形平面建筑: 3x3 中央星厅向东西各伸一条"
        "长板墙侧翼 (整面墙一块长板, 底边 2.0 一线双吸), 向南伸出"
        "门廊; 屋面是回字环、中心留 1x1 采光井, 井口立透明窗格方"
        "采光鼓、鼓顶等腰四坡锥收出 3.94 星塔金尖; 馆内星象仪与"
        "采光井同轴、先立后封顶 —— 星光正落在仪器上; 前庭太阳雕塑"
        "四棱落地自锁, 与六棱鼓身的天象厅走完全不同的方厅路线。"
    ),
    difficulty=3,
    tags=["博物馆", "星空", "天象厅", "十字厅", "进阶"],
    min_pieces=72,
    min_steps=12,
)
