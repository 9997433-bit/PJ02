#!/usr/bin/env python3
"""生成模型 data/models/trilithon_ring_01.json (巨石门环)。

D1 收官批 4 模型 2/4 (难度配额解冻线 D1 >= 20, 路径 B1): 入门档
建筑地标选题 —— 环绕青草祭坛的四座巨石门, 也是建筑地标主题的
第一个 D1。结构签名是"三石塔环列 (trilithon)": 每座石门由两块
竖立的长方形石板 + 一块平放的门楣板组成 —— 门楣两条长边分别
整边压住内外石板顶, 两端简支互为备份, 这是史前巨匠"三石塔"
的入门课; 四座石门围着中央 2x2 大方祭坛列成一圈, 内圈石板脚
整边吸住祭坛四边、相邻石板竖棱角缝互吸锁成环, 一条两节参道
从南门直通场外, 参道两侧四面祭旗、南北门楣上各立两枚日晷石。
与库内 D4 巨石阵 (91 片方板堆叠) 及本批探测器 (十字斜撑)、
滚珠坡 (塔-坡-槽)、风车坊 (塔楼十字翼) 的结构逻辑完全不同 ——
全批唯一以竖立长板为骨的门式框架环。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 参道朝南 -y):
  - 中央祭坛: 大正方形 1 片 (格 [1,3]x[1,3])              1 片
  - 四座三石塔: 内外竖石板各 1 + 门楣板 1, 共 4 座       12 片
  - 参道: 长方板 2 节 (南门外一字铺)                       2 片
  - 祭旗: 等边三角 4 面 (骑参道两侧短边)                   4 片
  - 日晷石: 等边三角 4 枚 (骑南北门楣两端短边)             4 片
  合计 23 片, 5 个教程步骤, 3 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 八块竖石板全部接地; 内圈石板脚整边吸祭坛四边, 相邻内圈
    石板竖棱 90 度角缝互吸 —— 门环锁成一体 (R2 环环相扣);
  - 门楣板两条长边分别整边压内外石板顶: 两端简支, 剪断任一侧
    仍有另一侧支撑 (R5/R6 假想切割分析天然通过);
  - 南门外石板脚整边压住参道板边, 参道与门环锁成一体;
  - 最高点 1.87 (日晷石尖) < 2.5, 不触发 R8 高层结构判定。

用法: python3 tools/generate_trilithon_ring_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

ALTAR = "green"     # 中央青草祭坛
STONE = "gray"      # 竖石板
LINTEL = "blue"     # 门楣板 (暮色石)
AVENUE = "yellow"   # 参道
FLAG = "red"        # 祭旗
SUN = "orange"      # 日晷石

# =================================================================
# 1. 中央祭坛 (2x2 大正方形, 格 [1,3]x[1,3]) 与南参道
# =================================================================
b.add("altar", "large_square", (2.0, 2.0, 0.0), (0, 0, 0), ALTAR)
b.flat_rect("ave_1", 1, -1, 0.0, AVENUE)   # [1,3] x [-1,0]
b.flat_rect("ave_2", 1, -2, 0.0, AVENUE)   # [1,3] x [-2,-1]

# =================================================================
# 2. 四座三石塔 (内外竖石板 + 门楣板)
#    内圈石板脚整边吸祭坛四边, 相邻内圈石板竖棱角缝互吸成环
# =================================================================
b.lintel_ns("s_in", 1, 1.0, 0, STONE)          # 南门内石板 (y=1)
b.lintel_ns("s_out", 1, 0.0, 0, STONE)         # 南门外石板 (y=0, 脚压参道板边)
b.flat_rect("s_cap", 1, 0, 1.0, LINTEL)        # 南门楣 [1,3]x[0,1]

b.lintel_ns("n_in", 1, 3.0, 0, STONE)          # 北门内石板 (y=3)
b.lintel_ns("n_out", 1, 4.0, 0, STONE)         # 北门外石板 (y=4)
b.flat_rect("n_cap", 1, 3, 1.0, LINTEL)        # 北门楣 [1,3]x[3,4]

b.lintel_ew("w_in", 1.0, 1, 0, STONE)          # 西门内石板 (x=1)
b.lintel_ew("w_out", 0.0, 1, 0, STONE)         # 西门外石板 (x=0)
b.flat_rect("w_cap", 0, 1, 1.0, LINTEL, axis="y")   # 西门楣 [0,1]x[1,3]

b.lintel_ew("e_in", 3.0, 1, 0, STONE)          # 东门内石板 (x=3)
b.lintel_ew("e_out", 4.0, 1, 0, STONE)         # 东门外石板 (x=4)
b.flat_rect("e_cap", 3, 1, 1.0, LINTEL, axis="y")   # 东门楣 [3,4]x[1,3]

# =================================================================
# 3. 日晷石 (等边三角, 骑南北门楣两端短边)
# =================================================================
b.crest_ew("sun_sw", 1.0, 0, 1.0, SUN)
b.crest_ew("sun_se", 3.0, 0, 1.0, SUN)
b.crest_ew("sun_nw", 1.0, 3, 1.0, SUN)
b.crest_ew("sun_ne", 3.0, 3, 1.0, SUN)

# =================================================================
# 4. 祭旗 (等边三角, 骑参道两侧短边)
# =================================================================
b.crest_ew("flag_w1", 1.0, -1, 0.0, FLAG)
b.crest_ew("flag_e1", 3.0, -1, 0.0, FLAG)
b.crest_ew("flag_w2", 1.0, -2, 0.0, FLAG)
b.crest_ew("flag_e2", 3.0, -2, 0.0, FLAG)

# =================================================================
# 教程步骤 (5 步)
# =================================================================
b.step(
    "铺祭坛: 绿色大方板放正中当青草祭坛 —— 大方板一片顶四片, 祭坛要又大又平。",
    ["altar"],
)
b.step(
    "立南门铺参道: 内石板脚整边吸祭坛南边, 门楣两条长边同时压住两块石板顶, 两节黄色参道从外石板脚下一字铺出去。",
    ["s_in", "s_out", "s_cap", "ave_1", "ave_2"],
    highlight=["altar"],
    tip="门楣两端都有石板托着 —— 剪掉一边还有另一边, 这就是三石塔站了五千年的秘密。",
)
b.step(
    "立西门和东门: 照南门的样子各立两块竖石板再盖门楣, 内圈石板竖棱和南门内石板角缝互吸。",
    ["w_in", "w_out", "w_cap", "e_in", "e_out", "e_cap"],
    highlight=["s_in"],
    tip="内圈四块石板竖棱手拉手 —— 门环锁成一圈就推不倒了。",
)
b.step(
    "立北门点日晷: 北门内外石板加门楣合拢门环, 四枚橙色日晷石骑上南北门楣两端。",
    ["n_in", "n_out", "n_cap", "sun_sw", "sun_se", "sun_nw", "sun_ne"],
    highlight=["w_in", "e_in"],
)
b.step(
    "插祭旗: 四面红色祭旗骑上参道两侧短边, 巨石门环迎来第一缕晨光!",
    ["flag_w1", "flag_e1", "flag_w2", "flag_e2"],
    highlight=["ave_1", "ave_2"],
)

b.finalize(
    model_id="trilithon_ring_01",
    name="巨石门环",
    name_en="Trilithon Ring 01",
    description=(
        "入门档建筑地标: 环绕青草祭坛的四座巨石门, 结构签名是"
        "'三石塔环列' —— 每座石门两块竖立长石板托一块平放门楣, "
        "门楣两条长边分别整边压住内外石板顶, 两端简支互为备份; "
        "内圈石板脚整边吸住 2x2 大方祭坛四边、相邻石板竖棱 90 度"
        "角缝互吸锁成门环, 一条两节黄色参道从南门直通场外, 参道"
        "两侧四面红色祭旗、南北门楣上四枚橙色日晷石。23 片全程"
        "接地受压零悬挑, 日晷尖 1.87 不触发高层判定, 搭完就是"
        "桌面上的史前天文台。"
    ),
    difficulty=1,
    tags=["建筑地标", "巨石阵", "三石塔", "亲子入门"],
    min_pieces=23,
    min_steps=5,
    series="landmark_architecture",
)
print("已写入 series=landmark_architecture")
