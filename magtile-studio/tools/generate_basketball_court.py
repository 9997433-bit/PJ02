#!/usr/bin/env python3
"""生成模型 data/models/basketball_court_01.json (街头篮球场)。

运动主题批 ①: 全库第一座街头篮球半场 —— 与篮球馆 basketball_arena_01
(全场双篮架 + 两层箱形梁看台) 结构逻辑完全不同: 半场以**大正方形油漆区**
为地面主角, 篮架不再是门式双柱, 而是一座 U 形箱筒塔 (三面墙两层围合、
东面敞开), 塔顶东侧嵌两片**窗格方篮板** (网眼即篮板格纹), 篮筐平台
两片方板压篮板顶边向场内悬挑; 场地南/西/北三面立起一圈**窗格方铁丝网
围栏** (南面门框方球场大门), 东侧一排悬挑坐板球员长凳, 场上一颗四坡
自锁的橙色篮球 —— 嘭、嘭、嘭, 运球声就是街头的心跳。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 半场 [0,5]x[0,4]):
  - 半场地面: 大正方形油漆区 + 长方形 x6 + 方板 x4 + 蓝边线   11 片
  - 篮架塔 [-1,0]x[1,3]: 底板 2 + U 形墙两层 8 + 窗格篮板 2
    + 悬挑篮筐平台 2                                           14 片
  - 铁丝网围栏: 窗格方 x11 + 门框方大门 x1                     12 片
  - 球员长凳 (东侧): 台面 3 + 背墙 3 + 悬挑坐板 3               9 片
  - 篮球 (四坡等边自锁) x4 + 围栏角旗 x2                        6 片
  合计 52 片, 15 个教程步骤, 7 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, 常规+strict 双档零警告):
  - 篮筐平台两片方板共线铰链合并受力: 力矩 30 <= strict 预算 35
    (25 x 2 x 0.7), 篮板窗格方顶边就是铰链线;
  - U 形塔三面墙拐角竖边互吸、两层错缝叠放, 窗格篮板竖边吸二层
    墙竖边 + 两片篮板中缝互吸 —— 塔身处处成环无单点失效;
  - 围栏窗格方竖边连吸成排, 三处拐角与塔身竖边锁扣;
  - 长凳一排坐板共线铰链合并受力: 力矩 45 <= strict 预算 52.5;
  - 全场最高点角旗尖 3.0, 触发 R8 高层检查 —— 塔/围栏/长凳的
    环状拓扑保证剪任何一条连接都不塌 (零 SPOF 警告)。

用法: python3 tools/generate_basketball_court.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

COURT = "gray"      # 水泥场地
PAINT = "orange"    # 油漆区 (大正方形)
LINE = "blue"       # 蓝色边线带
FENCE = "clear"     # 铁丝网围栏 (窗格方 = 网眼)
GATE = "green"      # 球场大门 (门框方)
TOWER = "gray"      # 篮架塔身
BOARD = "clear"     # 窗格篮板
HOOP = "red"        # 篮筐平台
BENCH = "blue"      # 球员长凳
BALL = "orange"     # 篮球
FLAG = "red"        # 围栏角旗

# =================================================================
# 1. 半场地面 [0,5]x[0,4]: 大正方形油漆区 + 长方形 + 方板
# =================================================================
b.flat_rect("ct_s_w", 0, 0, 0.0, LINE, axis="x")     # 南边线西段 [0,2]
b.flat_rect("ct_s_m", 2, 0, 0.0, COURT, axis="x")    # 南场地 [2,4]
b.flat("ct_s_e", 4, 0, 0.0, LINE)                    # 南边线东角 [4,5]
b.add("paint", "large_square", (1.0, 2.0, 0.0), (0, 0, 0), PAINT)  # 油漆区 [0,2]x[1,3]
b.flat_rect("ct_m0", 2, 1, 0.0, COURT, axis="x")     # 中场 [2,4]x[1,2]
b.flat("ct_m0_e", 4, 1, 0.0, COURT)
b.flat_rect("ct_m1", 2, 2, 0.0, COURT, axis="x")     # 中场 [2,4]x[2,3]
b.flat("ct_m1_e", 4, 2, 0.0, COURT)
b.flat_rect("ct_n_w", 0, 3, 0.0, LINE, axis="x")     # 北边线西段
b.flat_rect("ct_n_m", 2, 3, 0.0, COURT, axis="x")
b.flat("ct_n_e", 4, 3, 0.0, LINE)

# =================================================================
# 2. 篮架塔 [-1,0]x[1,3]: 底板 + U 形墙两层 + 窗格篮板 + 篮筐平台
# =================================================================
b.flat("tw_f0", -1, 1, 0.0, TOWER)                   # 塔底板
b.flat("tw_f1", -1, 2, 0.0, TOWER)
for z0 in (0, 1):
    b.wall_ns(f"tw_s_{z0}", -1, 1.0, z0, TOWER)      # 塔南墙
    b.wall_ns(f"tw_n_{z0}", -1, 3.0, z0, TOWER)      # 塔北墙
    b.wall_ew(f"tw_w0_{z0}", -1.0, 1, z0, TOWER)     # 塔西墙 (两片)
    b.wall_ew(f"tw_w1_{z0}", -1.0, 2, z0, TOWER)
b.add("bb_s", "window_square", (0.0, 1.5, 1.5), (90, 0, 90), BOARD)  # 窗格篮板南片
b.add("bb_n", "window_square", (0.0, 2.5, 1.5), (90, 0, 90), BOARD)  # 窗格篮板北片
b.flat("hoop_s", 0, 1, 2.0, HOOP)                    # 篮筐平台 (悬挑向场内)
b.flat("hoop_n", 0, 2, 2.0, HOOP)

# =================================================================
# 3. 铁丝网围栏: 南 (留门) / 西 / 北 三面, 窗格方 = 网眼
# =================================================================
for i, x0 in enumerate((0, 1, 3, 4)):
    b.add(f"fn_s_{i}", "window_square", (x0 + 0.5, 0.0, 0.5), (90, 0, 0), FENCE)
b.add("fn_gate", "door_frame", (2.5, 0.0, 0.5), (90, 0, 0), GATE)   # 南门
b.add("fn_w_s", "window_square", (0.0, 0.5, 0.5), (90, 0, 90), FENCE)
b.add("fn_w_n", "window_square", (0.0, 3.5, 0.5), (90, 0, 90), FENCE)
for x0 in range(5):
    b.add(f"fn_n_{x0}", "window_square", (x0 + 0.5, 4.0, 0.5), (90, 0, 0), FENCE)

# =================================================================
# 4. 球员长凳 (东侧 [5,6]x[0,3]): 台面 + 背墙 + 悬挑坐板
# =================================================================
for y0 in range(3):
    b.flat(f"bn_f_{y0}", 5, y0, 0.0, COURT)          # 台面
for y0 in range(3):
    b.wall_ew(f"bn_w_{y0}", 6.0, y0, 0, BENCH)       # 背墙
for y0 in range(3):
    b.flat(f"bn_s_{y0}", 5, y0, 1.0, BENCH)          # 悬挑坐板

# =================================================================
# 5. 篮球 (场上 [4,5]x[1,2]) + 围栏角旗
# =================================================================
BALL_IDS = b.hat4("ball", 4, 1, 0.0, BALL, shape="equilateral_triangle")
b.spire_ns("fl_w", 0, 4.0, 1.0, FLAG)                # 北围栏西角旗
b.spire_ns("fl_e", 4, 4.0, 1.0, FLAG)                # 北围栏东角旗

# =================================================================
# 教程步骤 (15 步)
# =================================================================
b.step(
    "铺半场南排: 蓝色边线长方形 + 灰色场地长方形 + 蓝色角方板。",
    ["ct_s_w", "ct_s_m", "ct_s_e"],
    tip="街头半场从南边线铺起, 长方形长边彼此等长互吸。",
)
b.step(
    "铺油漆区与中场南带: 橙色大正方形一片顶四片, 南边整边吸边线长方形长边 "
    "(2 = 2); 再补中场长方形与方板。",
    ["paint", "ct_m0", "ct_m0_e"],
    highlight=["ct_s_w"],
    tip="大正方形是油漆区 —— 罚球线内的必争之地。",
)
b.step(
    "合拢场地: 中场北带 + 北边线一排, 半场 5x4 铺完。",
    ["ct_m1", "ct_m1_e", "ct_n_w", "ct_n_m", "ct_n_e"],
    highlight=["paint"],
    tip="北边线长方形与大正方形北边等长互吸, 场地连成刚性整板。",
)
b.step(
    "铺篮架塔底板: 2 片灰色方板贴在油漆区西侧场外。",
    ["tw_f0", "tw_f1"],
    highlight=["paint"],
    tip="塔底板中缝互吸, 也是塔身三面墙的地基。",
)
b.step(
    "立篮架塔一层: 南/北/西三面墙 U 形围合 (东面敞开做通道), "
    "拐角竖边互吸锁定。",
    ["tw_s_0", "tw_n_0", "tw_w0_0", "tw_w1_0"],
    highlight=["tw_f0", "tw_f1"],
    tip="U 形墙三面锁角, 比两根孤柱结实得多 —— 这是街球篮架的底气。",
)
b.step(
    "叠篮架塔二层: 再 4 片墙, 底边整边吸一层墙顶边。",
    ["tw_s_1", "tw_n_1", "tw_w0_1", "tw_w1_1"],
    highlight=["tw_s_0", "tw_w0_0"],
    tip="上下两层墙缝对缝, 拐角继续互吸成环。",
)
b.step(
    "嵌窗格篮板: 2 片透明窗格方立在塔东口, 竖边吸二层墙竖边、"
    "两片中缝互吸。",
    ["bb_s", "bb_n"],
    highlight=["tw_s_1", "tw_n_1"],
    tip="窗格就是篮板格纹 —— 打板进筐就靠它。",
)
b.step(
    "压篮筐平台: 2 片红色方板压住篮板顶边、向场内悬挑。",
    ["hoop_s", "hoop_n"],
    highlight=["bb_s", "bb_n"],
    tip="两片平台共线铰链合并受力 (力矩 30 <= 预算 35)。",
)
b.step(
    "立南围栏与大门: 4 片窗格网眼 + 1 扇绿色门框方大门, "
    "底边吸场地南沿。",
    ["fn_s_0", "fn_s_1", "fn_gate", "fn_s_2", "fn_s_3"],
    highlight=["ct_s_w", "ct_s_m"],
    tip="窗格方就是铁丝网 —— 街球场的味道一下就来了。",
)
b.step(
    "立西围栏: 2 片窗格方补上西侧两角, 竖边与南围栏、篮架塔锁扣。",
    ["fn_w_s", "fn_w_n"],
    highlight=["fn_s_0", "tw_s_0"],
    tip="拐角竖边互吸, 围栏和塔身连成一体。",
)
b.step(
    "立北围栏: 5 片窗格方一字排开, 三面铁丝网合拢。",
    ["fn_n_0", "fn_n_1", "fn_n_2", "fn_n_3", "fn_n_4"],
    highlight=["fn_w_n"],
    tip="球飞不出场, 行人也看得见 —— 铁丝网围栏两全其美。",
)
b.step(
    "搭球员长凳台: 东侧 3 片台面方板 + 3 片蓝色背墙。",
    ["bn_f_0", "bn_f_1", "bn_f_2", "bn_w_0", "bn_w_1", "bn_w_2"],
    highlight=["ct_s_e"],
    tip="背墙底边吸台面板边, 竖边互吸连成整面。",
)
b.step(
    "压长凳坐板: 3 片坐板压背墙顶边、面朝球场悬挑。",
    ["bn_s_0", "bn_s_1", "bn_s_2"],
    highlight=["bn_w_0", "bn_w_2"],
    tip="一排坐板共线铰链合并受力 (力矩 45 <= 预算 52.5)。",
)
b.step(
    "拼场上篮球: 4 片橙色等边三角四坡互吸自锁, 停在中场格上。",
    BALL_IDS,
    highlight=["ct_m0_e"],
    tip="四条斜棱两两互吸 —— 篮球在等下一次运球。",
)
b.step(
    "升围栏角旗: 2 面红色瘦高角旗立上北围栏顶边 —— 开球!",
    ["fl_w", "fl_e"],
    highlight=["fn_n_0", "fn_n_4"],
    tip="角旗立在围栏顶铰链线上, 重心正压不外倾。",
)

b.finalize(
    model_id="basketball_court_01",
    name="街头篮球场",
    name_en="Street Basketball Court",
    description=(
        "街头篮球半场: 橙色大正方形油漆区领衔 5x4 水泥场地, U 形箱筒篮架塔"
        "两层围合、塔口嵌两片窗格方篮板, 红色篮筐平台压顶悬挑; 三面窗格方"
        "铁丝网围栏 (南开门框方大门) 与塔身竖边锁扣, 东侧球员长凳悬挑坐板"
        "面朝场地, 中场一颗四坡自锁的橙色篮球 —— 嘭、嘭、嘭, 运球声就是"
        "街头的心跳。"
    ),
    difficulty=3,
    tags=["运动", "篮球", "街头", "场景"],
    min_pieces=52,
    min_steps=15,
)
