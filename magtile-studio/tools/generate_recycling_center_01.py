#!/usr/bin/env python3
"""生成模型 data/models/recycling_center_01.json (环保回收站)。

内容批 I 模型 3/4: 全库第一座垃圾分类回收站 —— 与救援总部 (单条
出动坡道) / 滚珠塔 (轨道分段对接) 刻意区分, 本作的招牌是"三色
分类滑道": 分拣大厅的屋顶就是分拣台, 三条 30 度滑道并排从台沿
甩向地面, 蓝 / 绿 / 红三色滑道对准三格连体分类箱 —— 可回收物、
厨余、有害垃圾各回各家; 分拣台西角立着站长小亭, 回收小车在
南门口等着装货。垃圾分类, 从小做起!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 滑道朝东):
  - 站区地坪 5 行 (x [0,7], y [0,5])                    24 片
  - 分拣大厅 (x [1,3], y [1,4], z 0..1): 墙环 10
    (西面嵌门框方正门) + 分拣台方板 6                   16 片
  - 站长小亭 (x [1,2], y [2,3], z 1..2): 墙 4 + 顶板
    + 站旗                                              6 片
  - 三色分类滑道 x3 (30 度长板, 顶边吸台沿, 坡尾压地)    3 片
  - 三格连体分类箱 (x [5,6], y [1,4]): 隔墙共用          10 片
  - 回收小车 (车轮底座 x2 + 底盘 + 驾驶窗 + 尾墙 + 顶)   6 片
  合计 65 片, 13 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告 + jitter 全绿):
  - 三条滑道顶边分别整边吸分拣台东沿 (与大厅东墙顶共线),
    坡尾压地 —— 顶铰链 + 接地坡尾, 悬臂力矩为零;
  - 大厅墙环四角竖边互咬闭环, 分拣台方板四边入扣墙顶;
  - 小亭墙脚压分拣台拼缝, 荷载沿大厅西墙直下;
  - 分类箱三格共用隔墙, 格格闭环, 箱口敞开等着投卡片;
  - 小车底盘长板两条长边分别整边压两只车轮底座顶 (校车同款),
    驾驶窗与尾墙吸底盘短边, 车顶长板锁住两墙;
  - 地坪拼缝纪律: 大厅墙脚 / 分类箱底下全单位方板。

用法: python3 tools/generate_recycling_center_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

PAVE = "gray"       # 站区地坪
LAWN = "green"      # 站区草坪
HALL = "yellow"     # 分拣大厅
DOOR = "orange"     # 正门门框方
DECK = "gray"       # 分拣台
KIOSK = "cyan"      # 站长小亭
FLAG = "green"      # 站旗
CHUTE_R = "blue"    # 可回收滑道
CHUTE_K = "green"   # 厨余滑道
CHUTE_H = "red"     # 有害滑道
BIN_R = "blue"      # 可回收箱
BIN_K = "green"     # 厨余箱
BIN_H = "red"       # 有害箱
WHEEL = "gray"      # 车轮底座
TRUCK = "purple"    # 回收小车
CAB = "clear"       # 驾驶窗

# =================================================================
# 1. 站区地坪 5 行 (x [0,7], y [0,5])
# =================================================================
# 南行 (y [0,1]): 东端长板给回收小车当车位
b.flat_rect("g0_a", 0, 0, 0.0, PAVE)
b.flat("g0_2", 2, 0, 0.0, LAWN)
b.flat_rect("g0_b", 3, 0, 0.0, PAVE)
b.flat_rect("g0_c", 5, 0, 0.0, PAVE)
# 大厅南行 (y [1,2]): 大厅与分类箱脚下全单位方板
b.flat_rect("g_w", 0, 1, 0.0, LAWN, axis="y")
b.flat("g1_1", 1, 1, 0.0, PAVE)
b.flat("g1_2", 2, 1, 0.0, PAVE)
b.flat_rect("g1_b", 3, 1, 0.0, PAVE)
b.flat("g1_5", 5, 1, 0.0, PAVE)
b.flat_rect("g_e", 6, 1, 0.0, LAWN, axis="y")
# 大厅中行 (y [2,3])
b.flat("g2_1", 1, 2, 0.0, PAVE)
b.flat("g2_2", 2, 2, 0.0, PAVE)
b.flat_rect("g2_b", 3, 2, 0.0, LAWN)
b.flat("g2_5", 5, 2, 0.0, PAVE)
# 大厅北行 (y [3,4])
b.flat("g3_0", 0, 3, 0.0, LAWN)
b.flat("g3_1", 1, 3, 0.0, PAVE)
b.flat("g3_2", 2, 3, 0.0, PAVE)
b.flat_rect("g3_b", 3, 3, 0.0, PAVE)
b.flat("g3_5", 5, 3, 0.0, PAVE)
b.flat("g3_6", 6, 3, 0.0, LAWN)
# 北行 (y [4,5])
b.flat_rect("g4_a", 0, 4, 0.0, LAWN)
b.flat_rect("g4_b", 2, 4, 0.0, PAVE)
b.flat_rect("g4_c", 4, 4, 0.0, LAWN)
b.flat("g4_6", 6, 4, 0.0, PAVE)

# =================================================================
# 2. 分拣大厅墙环 (x [1,3], y [1,4], z 0..1): 西面嵌门框方正门
# =================================================================
b.wall_ns("h_s_w", 1, 1.0, 0, HALL)
b.wall_ns("h_s_e", 2, 1.0, 0, HALL)
b.wall_ns("h_n_w", 1, 4.0, 0, HALL)
b.wall_ns("h_n_e", 2, 4.0, 0, HALL)
b.add("h_door", "door_frame", (1.0, 1.5, 0.5), (90, 0, 90), DOOR)
b.wall_ew("h_w_m", 1.0, 2, 0, HALL)
b.wall_ew("h_w_n", 1.0, 3, 0, HALL)
b.wall_ew("h_e_s", 3.0, 1, 0, HALL)
b.wall_ew("h_e_m", 3.0, 2, 0, HALL)
b.wall_ew("h_e_n", 3.0, 3, 0, HALL)

# 分拣台方板 (z=1): 六片方板四边入扣墙顶
b.flat("deck_sw", 1, 1, 1.0, DECK)
b.flat("deck_se", 2, 1, 1.0, DECK)
b.flat("deck_mw", 1, 2, 1.0, DECK)
b.flat("deck_me", 2, 2, 1.0, DECK)
b.flat("deck_nw", 1, 3, 1.0, DECK)
b.flat("deck_ne", 2, 3, 1.0, DECK)

# =================================================================
# 3. 站长小亭 (x [1,2], y [2,3], z 1..2): 墙脚压分拣台拼缝
# =================================================================
b.wall_ns("k_s", 1, 2.0, 1, KIOSK)
b.wall_ns("k_n", 1, 3.0, 1, KIOSK)
b.wall_ew("k_w", 1.0, 2, 1, KIOSK)
b.wall_ew("k_e", 2.0, 2, 1, KIOSK)
b.flat("k_cap", 1, 2, 2.0, KIOSK)
b.crest_ns("k_flag", 1, 3.0, 2.0, FLAG)

# =================================================================
# 4. 三色分类滑道: 顶边吸分拣台东沿, 坡尾压地
# =================================================================
b.ramp("chute_r", "+x", 3.0, 1, 1.0, CHUTE_R)
b.ramp("chute_k", "+x", 3.0, 2, 1.0, CHUTE_K)
b.ramp("chute_h", "+x", 3.0, 3, 1.0, CHUTE_H)

# =================================================================
# 5. 三格连体分类箱 (x [5,6], y [1,4]): 隔墙共用, 箱口敞开
# =================================================================
b.wall_ns("bin_d0", 5, 1.0, 0, BIN_R)
b.wall_ns("bin_d1", 5, 2.0, 0, BIN_K)
b.wall_ns("bin_d2", 5, 3.0, 0, BIN_H)
b.wall_ns("bin_d3", 5, 4.0, 0, BIN_H)
b.wall_ew("bin_w_r", 5.0, 1, 0, BIN_R)
b.wall_ew("bin_w_k", 5.0, 2, 0, BIN_K)
b.wall_ew("bin_w_h", 5.0, 3, 0, BIN_H)
b.wall_ew("bin_e_r", 6.0, 1, 0, BIN_R)
b.wall_ew("bin_e_k", 6.0, 2, 0, BIN_K)
b.wall_ew("bin_e_h", 6.0, 3, 0, BIN_H)

# =================================================================
# 6. 回收小车 (x [3,5], y [0,1]): 校车同款轮组受力
# =================================================================
b.add("t_wheel_s", "wheel_base", (4.0, 0.0, 0.5), (90, 0, 0), WHEEL)
b.add("t_wheel_n", "wheel_base", (4.0, 1.0, 0.5), (90, 0, 0), WHEEL)
b.flat_rect("t_bed", 3, 0, 1.0, TRUCK)
b.add("t_cab", "window_square", (3.0, 0.5, 1.5), (90, 0, 90), CAB)
b.wall_ew("t_back", 5.0, 0, 1, TRUCK)
b.flat_rect("t_roof", 3, 0, 2.0, TRUCK)

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺南行与大厅南行: 大厅墙脚和分类箱底下都要用单位方板。",
    ["g0_a", "g0_2", "g0_b", "g0_c",
     "g_w", "g1_1", "g1_2", "g1_b", "g1_5", "g_e"],
    tip="回收站开工啦 —— 墙底边要和方板边等长吸合才抓得牢。",
)
b.step(
    "铺大厅中行与北行: 行行等边互吸, 分类箱那格继续留单位方板。",
    ["g2_1", "g2_2", "g2_b", "g2_5",
     "g3_0", "g3_1", "g3_2", "g3_b", "g3_5", "g3_6"],
    highlight=["g1_1"],
)
b.step(
    "铺北行收口: 三条长板加一片方板, 站区地坪完工。",
    ["g4_a", "g4_b", "g4_c", "g4_6"],
    highlight=["g3_1"],
)
b.step(
    "立大厅南墙与西墙: 西面下格嵌橙色门框方, 这是回收站的正门。",
    ["h_s_w", "h_s_e", "h_door", "h_w_m", "h_w_n"],
    highlight=["g1_1", "g1_2"],
    tip="大厅是 2x3 的墙环 —— 墙脚踩住拼缝才站得稳。",
)
b.step(
    "合大厅北墙与东墙: 十片墙环四角竖边互咬闭环。",
    ["h_n_w", "h_n_e", "h_e_s", "h_e_m", "h_e_n"],
    highlight=["h_s_w"],
    tip="东墙顶就是滑道的起点 —— 砌整齐, 待会儿滑道要整边吸上去。",
)
b.step(
    "盖分拣台: 六片灰色方板四边入扣墙顶, 板板互吸。",
    ["deck_sw", "deck_se", "deck_mw", "deck_me", "deck_nw", "deck_ne"],
    highlight=["h_e_s"],
    tip="大厅的屋顶就是分拣台 —— 分好类的物品从这里出发。",
)
b.step(
    "起站长小亭: 四片青色墙骑上分拣台西列, 墙脚压住板缝。",
    ["k_s", "k_n", "k_w", "k_e"],
    highlight=["deck_mw"],
    tip="站长在亭子里盯着三条滑道 —— 别投错颜色哟。",
)
b.step(
    "封亭顶并升站旗: 顶板四边入扣, 绿旗骑亭顶北沿。",
    ["k_cap", "k_flag"],
    highlight=["k_n"],
)
b.step(
    "挂三色滑道: 蓝 / 绿 / 红三条 30 度长板并排, 顶边整边吸台沿, "
    "坡尾稳稳压地。",
    ["chute_r", "chute_k", "chute_h"],
    highlight=["deck_se", "h_e_s"],
    tip="顶铰链 + 接地坡尾, 重量走两条路 —— 三条滑道各管一种垃圾。",
)
b.step(
    "立分类箱隔墙: 四片隔墙一字排开, 三格箱位就分出来了。",
    ["bin_d0", "bin_d1", "bin_d2", "bin_d3"],
    highlight=["g1_5"],
    tip="中间的隔墙两格共用 —— 省片又结实。",
)
b.step(
    "合分类箱东西墙: 蓝格接可回收、绿格接厨余、红格接有害, "
    "箱口敞开等着收货。",
    ["bin_w_r", "bin_w_k", "bin_w_h", "bin_e_r", "bin_e_k", "bin_e_h"],
    highlight=["bin_d0", "chute_r"],
    tip="滑道什么颜色, 箱子就什么颜色 —— 对色入箱不迷路。",
)
b.step(
    "装回收小车轮组与底盘: 两只车轮底座咬住车位拼缝, "
    "紫色底盘长边整边压轮顶。",
    ["t_wheel_s", "t_wheel_n", "t_bed"],
    highlight=["g0_b"],
    tip="长边对轮顶, 力臂为零 —— 校车同款的稳当底盘。",
)
b.step(
    "装驾驶窗、尾墙与车顶: 小车整装待发, 满载再生宝贝出发!",
    ["t_cab", "t_back", "t_roof"],
    highlight=["t_bed"],
    tip="垃圾分类, 从小做起 —— 再生宝贝们要去新家啦。",
)

b.finalize(
    model_id="recycling_center_01",
    name="环保回收站",
    name_en="Recycling Center 01",
    description=(
        "只用核心九片型的全库第一座垃圾分类回收站: 与救援总部的单条"
        "出动坡道不同, 本作的招牌是'三色分类滑道' —— 分拣大厅的屋顶"
        "就是分拣台, 蓝 / 绿 / 红三条 30 度滑道并排从台沿甩向地面 "
        "(顶边整边吸台沿, 坡尾压地, 重量走两条路), 正对三格共用隔墙"
        "的连体分类箱, 可回收物、厨余、有害垃圾对色入箱各回各家; "
        "分拣台西角立着站长小亭, 紫色回收小车两只车轮底座托着底盘"
        "在南门口等着装货 —— 垃圾分类, 从小做起!"
    ),
    difficulty=3,
    tags=["城市", "环保", "回收站", "职业体验", "进阶"],
    min_pieces=65,
    min_steps=13,
)
