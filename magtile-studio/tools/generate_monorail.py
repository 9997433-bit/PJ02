#!/usr/bin/env python3
"""生成模型 data/models/monorail_01.json (单轨列车段)。

城市交通主题: 全库第一段跨座式单轨 —— 三座直角三角斜撑加固的
高架墩柱托起 10 格青色轨道梁, 一列红色单轨列车跨坐在梁上:
两侧整排透明观景车窗 (窗格方首次上列车), 南侧嵌乘客门 (门框方),
车顶受电弓与前后信号鳍立在沿口, 轨道尽头一片红色缓冲挡板 ——
叮! 下一站, 科技馆。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 街景绿化带: 绿色长板 x5 (y [0,1])                        5 片
  - 轨道基带: 灰色方板 x11 (y [1,2], 墩柱踩它的拼缝)        11 片
  - 高架墩柱: 三座, 每座两节立墙叠高 (x = 1 / 5 / 10)         6 片
  - 墩柱斜撑: 每座前后各一片直角三角形 (平面 y=1)             6 片
  - 轨道梁: 青色方板平铺 z=2, 首尾贴墩柱顶                   10 片
  - 缓冲挡板: 轨道尽头立墙 x1 (x=10, 正压端墩柱顶)            1 片
  - 列车车厢 (x [3,7]): 南墙 门框方x1+窗格方x3,
    北墙 窗格方x4, 前后端墙 方板x2, 车顶方板x4               14 片
  - 车顶装备: 前后信号鳍 (等边三角) x2 + 受电弓 x1            3 片
  合计 56 片, 12 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, strict 档同样全绿):
  - 墩柱立墙踩轨道基带方板拼缝 (整边吸合), 前后直角三角斜撑
    竖直角边吸墩柱竖边、水平直角边吸基带板边 —— 抗侧倾;
  - 轨道梁与墩柱顶整边吸合, 梁片之间拼缝互吸; 东端墩柱直接
    立在轨道尽头 (x=10), 缓冲挡板重心正压墩柱顶铰链 (力矩 0),
    西端悬出格单片力矩 15 <= strict 预算 17.5, 不再外延;
  - 车厢墙踩轨道梁长沿, 车顶双边压墙顶, 与前后端墙锁成
    连续箱形闭环 (结构冗余, 单点断连不塌);
  - 信号鳍/受电弓/缓冲挡板重心均正压铰链线, 力矩为零。

用法: python3 tools/generate_monorail.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

LAWN = "green"      # 街景绿化带
BASE = "gray"       # 轨道基带 / 墩柱 / 斜撑
BEAM = "cyan"       # 轨道梁
BODY = "red"        # 车体 / 车顶 / 缓冲挡板
GLASS = "clear"     # 观景车窗
DOOR = "orange"     # 乘客门
FIN = "yellow"      # 信号鳍
PANTO = "gray"      # 受电弓

PYLONS = (1, 5, 10)  # 墩柱所在的轨道基带拼缝 (x = 整数网格线)

# =================================================================
# 1. 地面: 绿化带长板 (y [0,1]) + 轨道基带方板 (y [1,2])
# =================================================================
for k in range(5):
    b.flat_rect(f"lawn_{k}", 2 * k, 0, 0.0, LAWN)
for x in range(11):
    b.flat(f"base_{x}", x, 1, 0.0, BASE)

# =================================================================
# 2. 高架墩柱: 三座两节立墙 (踩基带拼缝) + 前后直角三角斜撑
# =================================================================
for k in PYLONS:
    b.wall_ew(f"py_{k}_0", float(k), 1, 0, BASE)
    b.wall_ew(f"py_{k}_1", float(k), 1, 1, BASE)
    b.brace(f"br_{k}_e", (float(k), 1.0, 0.0), "+x", BASE)
    b.brace(f"br_{k}_w", (float(k), 1.0, 0.0), "-x", BASE)

# =================================================================
# 3. 轨道梁: 青色方板平铺 z=2, 梁缝与墩柱顶共线
# =================================================================
for x in range(10):
    b.flat(f"beam_{x}", x, 1, 2.0, BEAM)
b.wall_ew("bumper", 10.0, 1, 2, BODY)       # 轨道尽头缓冲挡板

# =================================================================
# 4. 列车车厢 (x [3,7], z [2,3]): 两侧车窗墙 + 前后端墙 + 车顶
# =================================================================
# 南墙: 乘客门 (门框方) + 3 扇窗格方; 北墙: 4 扇窗格方
b.add("car_s_3", "door_frame", (3.5, 1.0, 2.5), (90, 0, 0), DOOR)
for x in (4, 5, 6):
    b.add(f"car_s_{x}", "window_square", (x + 0.5, 1.0, 2.5), (90, 0, 0), GLASS)
for x in (3, 4, 5, 6):
    b.add(f"car_n_{x}", "window_square", (x + 0.5, 2.0, 2.5), (90, 0, 0), GLASS)
b.wall_ew("car_w", 3.0, 1, 2, BODY)         # 车头端墙
b.wall_ew("car_e", 7.0, 1, 2, BODY)         # 车尾端墙
for x in (3, 4, 5, 6):
    b.flat(f"roof_{x}", x, 1, 3.0, BODY)    # 车顶

# =================================================================
# 5. 车顶装备: 前后信号鳍 + 受电弓
# =================================================================
b.crest_ew("fin_w", 3.0, 1, 3.0, FIN)       # 车头信号鳍
b.crest_ew("fin_e", 7.0, 1, 3.0, FIN)       # 车尾信号鳍
b.crest_ew("panto", 5.0, 1, 3.0, PANTO)     # 受电弓 (立车顶拼缝)

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺街景绿化带: 5 片绿色长板沿线排开 (y [0,1])。",
    [f"lawn_{k}" for k in range(5)],
    tip="绿化带的北沿拼缝, 就是墩柱斜撑的落脚线。",
)
b.step(
    "铺轨道基带西半段: 5 片灰色方板 (x 0~5)。",
    [f"base_{x}" for x in range(5)],
    highlight=["lawn_0"],
    tip="方板之间的拼缝要对齐网格线 —— 墩柱就踩在拼缝上。",
)
b.step(
    "铺轨道基带东半段: 再铺 6 片, 基带贯通 11 格。",
    [f"base_{x}" for x in range(5, 11)],
    highlight=["base_4"],
    tip="基带铺直了, 高架才立得正。",
)
b.step(
    "立三座高架墩柱: 每座两节立墙叠高, 墙脚整边吸基带拼缝。",
    [tid for k in PYLONS for tid in (f"py_{k}_0", f"py_{k}_1")],
    highlight=["base_1", "base_5", "base_9"],
    tip="上节墙底边整边吸下节墙顶边 —— 磁条对磁条, 一条不落。",
)
b.step(
    "加墩柱斜撑: 每座前后各一片直角三角形, 竖边吸墙、底边吸板。",
    [tid for k in PYLONS for tid in (f"br_{k}_e", f"br_{k}_w")],
    highlight=["py_1_0", "py_5_0", "py_10_0"],
    tip="三角形是最稳的形状 —— 列车驶过, 墩柱纹丝不动。",
)
b.step(
    "架轨道梁西半段: 5 片青色方板从西端铺到中央墩柱。",
    [f"beam_{x}" for x in range(5)],
    highlight=["py_1_1", "py_5_1"],
    tip="先放 x=0 这片: 它的东边正好吸住西墩柱顶。",
)
b.step(
    "架轨道梁东半段 + 缓冲挡板: 梁铺满 10 格, 尽头立起红色挡板。",
    [f"beam_{x}" for x in range(5, 10)] + ["bumper"],
    highlight=["beam_4", "py_10_1"],
    tip="挡板正压端墩柱顶 —— 列车永远不会冲出轨道。",
)
b.step(
    "立列车南墙: 橙色乘客门在前, 3 扇透明观景窗随后。",
    ["car_s_3", "car_s_4", "car_s_5", "car_s_6"],
    highlight=["beam_3", "beam_6"],
    tip="墙脚踩轨道梁的南沿 —— 单轨列车是跨坐在梁上的。",
)
b.step(
    "立列车北墙: 4 扇透明观景窗一字排开。",
    ["car_n_3", "car_n_4", "car_n_5", "car_n_6"],
    highlight=["car_s_3"],
    tip="两侧墙隔梁相望, 车顶一盖就是牢固的箱形结构。",
)
b.step(
    "封前后端墙: 车头车尾各一片红色方板, 竖边与侧墙互吸。",
    ["car_w", "car_e"],
    highlight=["car_s_3", "car_n_6"],
    tip="端墙底边吸梁缝、两条竖边吸侧墙 —— 三边受力。",
)
b.step(
    "盖车顶: 4 片红色方板双边压住南北墙顶。",
    ["roof_3", "roof_4", "roof_5", "roof_6"],
    highlight=["car_w", "car_e"],
    tip="车顶把整节车厢锁成闭环 —— 这就是结构冗余。",
)
b.step(
    "装车顶装备: 前后黄色信号鳍 + 中央受电弓 —— 发车!",
    ["fin_w", "fin_e", "panto"],
    highlight=["roof_3", "roof_5"],
    tip="三片三角重心都正压车顶铰链, 力臂为零, 稳如泰山。",
)

b.finalize(
    model_id="monorail_01",
    name="单轨列车段",
    name_en="Monorail Segment 01",
    description=(
        "全库第一段跨座式单轨: 三座直角三角斜撑加固的高架墩柱托起"
        " 10 格青色轨道梁, 红色单轨列车跨坐梁上 —— 两侧整排透明观景"
        "车窗 (窗格方首次上列车), 南墙嵌橙色乘客门, 车顶受电弓与前后"
        "信号鳍立在沿口, 轨道尽头一片红色缓冲挡板。车厢墙踩梁沿、"
        "车顶双边压墙顶锁成箱形闭环 —— 叮! 下一站, 科技馆。"
    ),
    difficulty=3,
    tags=["交通", "单轨", "列车", "城市", "进阶"],
    min_pieces=54,
    min_steps=12,
)
