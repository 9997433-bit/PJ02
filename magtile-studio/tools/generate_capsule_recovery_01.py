#!/usr/bin/env python3
"""生成模型 data/models/capsule_recovery_01.json (返回舱回收站)。

太空探索主题批 4/4: 全库第一张"平铺伞面" —— 与月球/月面着陆器的
多舱对接结构完全不同, 本作讲的是任务的最后一幕: 返回舱稳稳落在
草原着陆场, 红白棋盘格主伞平铺嵌进草地 (伞衣与草坪同层拼缝互吸,
既是地面也是图案), 两片灰色伞绳板一路牵到舱边; 返回舱四墙合环
落在烧灼的着陆点上, 橙色舱门朝东迎着赶来的回收车, 等边四坡
防热锥尖 1.71; 蓝色回收车驾驶窗朝西、红色警灯闪烁, 两面红色
信标旗标出着陆场边界 —— 欢迎回家, 航天员!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 伞面在西, 回收车在东):
  - 草原基底: 南行长板 x4 + 零散长板/方板 x10                   14 片
  - 主伞伞面 (x [0,3], y [1,4]): 红白棋盘格方板 3x3               9 片
  - 伞绳板 x2 + 烧灼着陆点 x1 (灰色, 嵌进草地同层)              (计入上行)
  - 返回舱 (x [5,6], y [2,3], z 0..1): 素墙 x2 + 舷窗窗格方
    朝西 + 橙色舱门框朝东 + 等边四坡防热锥 (尖 1.71)             8 片
  - 回收车 (x [6,8], y [1,2]): 车轮底座 x2 + 甲板长板 + 箱体
    横楣 x2 + 驾驶窗 + 尾门 + 舱顶长板 + 红色警灯 (2.87)         9 片
  - 信标旗 x2: 红色等边三角骑场界拼缝                             2 片
  合计 42 片, 10 个教程步骤, 7 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 伞面/伞绳/着陆点全部平铺在 z=0 与草坪同层, 靠配色画图案,
    没有任何共面重叠; 全场地一张拼缝网, 处处整边互吸;
  - 返回舱四墙踩着陆点方板四条边线 (整边精确贴合), 四角竖边
    互咬合环, 防热锥四棱互吸自锁 —— 环上加锥, 连接图环路充足;
  - 回收车与救护车同款门式底盘: 车轮底座底边与草坪长板北/南长边
    完全等长贴合, 甲板长边整边压双轮顶, 箱体横楣 + 端墙 + 舱顶
    锁成完整箱环; 红色警灯底边一线双吸驾驶窗顶与舱顶短边;
  - 最高点 2.87 (警灯尖) 触发 R8 高层检查: 箱环 + 舱环环路充足,
    剪断任何单条连接最多失联 1 片 (< 3), 单点失效通过。

用法: python3 tools/generate_capsule_recovery_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

GRASS = "green"     # 草原
CHUTE_A = "red"     # 伞面 (红白棋盘)
CHUTE_B = "clear"
LINE = "gray"       # 伞绳板
PAD = "gray"        # 烧灼着陆点
HULL = "gray"       # 返回舱墙
PORT = "clear"      # 舷窗
HATCH = "orange"    # 舱门
SHIELD = "orange"   # 防热锥
TRUCK = "blue"      # 回收车箱体
GLASS = "clear"     # 驾驶窗 / 舱顶
BEACON = "red"      # 警灯 / 信标旗


def wall_ns_t(tid, tile_type, x0, y, z0, color):
    b.add(tid, tile_type, (x0 + 0.5, y, z0 + 0.5), (90, 0, 0), color)


def wall_ew_t(tid, tile_type, x, y0, z0, color):
    b.add(tid, tile_type, (x, y0 + 0.5, z0 + 0.5), (90, 0, 90), color)


# =================================================================
# 1. 草原基底 + 平铺伞面: 全部 z=0 同层, 配色画图案
# =================================================================
for i, x0 in enumerate((0, 2, 4, 6)):
    b.flat_rect(f"g_s{i}", x0, 0, 0.0, GRASS)             # 南行草坪
for y0 in (1, 2, 3):
    for x0 in (0, 1, 2):
        color = CHUTE_A if (x0 + y0) % 2 == 0 else CHUTE_B
        b.flat(f"chute_{x0}_{y0}", x0, y0, 0.0, color)    # 红白棋盘伞面
b.flat("g_12", 3, 1, 0.0, GRASS)                          # 中带草坪
b.flat_rect("g_13", 4, 1, 0.0, GRASS)
b.flat_rect("g_14", 6, 1, 0.0, GRASS)
b.flat("line_a", 3, 2, 0.0, LINE)                         # 伞绳板牵向舱边
b.flat("line_b", 4, 2, 0.0, LINE)
b.flat("pad", 5, 2, 0.0, PAD)                             # 烧灼着陆点
b.flat_rect("g_23", 6, 2, 0.0, GRASS)
b.flat("g_31", 3, 3, 0.0, GRASS)                          # 北带草坪
b.flat_rect("g_32", 4, 3, 0.0, GRASS)
b.flat_rect("g_33", 6, 3, 0.0, GRASS)

# =================================================================
# 2. 返回舱 (x [5,6], y [2,3], z 0..1): 四墙合环 + 等边四坡防热锥
# =================================================================
b.wall_ns("cap_s", 5, 2.0, 0, HULL)
b.wall_ns("cap_n", 5, 3.0, 0, HULL)
wall_ew_t("cap_w", "window_square", 5.0, 2, 0, PORT)      # 舷窗朝伞面
wall_ew_t("cap_e", "door_frame", 6.0, 2, 0, HATCH)        # 舱门朝回收车
CONE_IDS = b.hat4("cap_cone", 5, 2, 1.0, SHIELD, shape="equilateral_triangle")

# =================================================================
# 3. 回收车 (x [6,8], y [1,2]): 门式底盘 + 完整箱环 + 警灯
# =================================================================
b.add("wh_s", "wheel_base", (7.0, 1.0, 0.5), (90, 0, 0), "gray")
b.add("wh_n", "wheel_base", (7.0, 2.0, 0.5), (90, 0, 0), "gray")
b.flat_rect("tk_deck", 6, 1, 1.0, "gray")                 # 甲板整边压双轮顶
b.lintel_ns("tk_s", 6, 1.0, 1, TRUCK)                     # 南横楣
b.lintel_ns("tk_n", 6, 2.0, 1, TRUCK)                     # 北横楣
wall_ew_t("tk_w", "window_square", 6.0, 1, 1, GLASS)      # 驾驶窗朝返回舱
b.wall_ew("tk_e", 8.0, 1, 1, TRUCK)                       # 尾门
b.flat_rect("tk_top", 6, 1, 2.0, GLASS)                   # 舱顶长板
b.crest_ew("tk_lamp", 6.0, 1, 2.0, BEACON)                # 红色警灯 (2.87)

# =================================================================
# 4. 信标旗 x2: 骑着陆场边界拼缝
# =================================================================
b.crest_ns("bcn_n", 3, 4.0, 0.0, BEACON)                  # 北界
b.crest_ew("bcn_s", 4.0, 0, 0.0, BEACON)                  # 南界

# =================================================================
# 教程步骤 (10 步)
# =================================================================
b.step(
    "铺南行草坪: 四条绿色长板短边互吸, 草原着陆场开工。",
    ["g_s0", "g_s1", "g_s2", "g_s3"],
    tip="返回舱预报落点就在这片草原 —— 回收队凌晨就出发了。",
)
b.step(
    "平铺主伞伞面: 九片红白棋盘方板嵌进草地, 与草坪同层拼缝互吸。",
    [f"chute_{x0}_{y0}" for y0 in (1, 2, 3) for x0 in (0, 1, 2)],
    highlight=["g_s0"],
    tip="主伞落地后摊成一大朵红白花 —— 直升机在天上一眼就能认出。",
)
b.step(
    "铺中带草坪: 方板加长板, 行行与南行对齐。",
    ["g_12", "g_13", "g_14"],
    highlight=["chute_2_1"],
    tip="伞面东边留出通道 —— 回收车要从这里开到舱边。",
)
b.step(
    "铺伞绳板与着陆点: 两片灰色伞绳板从伞面一路牵到烧灼的落点。",
    ["line_a", "line_b", "pad", "g_23"],
    highlight=["chute_2_2"],
    tip="灰色方板就是伞绳与烧痕 —— 防热大底真的会把草烤焦一圈。",
)
b.step(
    "铺北带草坪合拢场地: 着陆场占地 8x4。",
    ["g_31", "g_32", "g_33"],
    highlight=["pad"],
    tip="全场一张拼缝网 —— 返回舱和回收车都要踩它的边线。",
)
b.step(
    "立返回舱四墙: 素墙合上朝西舷窗与朝东橙色舱门, 踩住落点边线。",
    ["cap_s", "cap_n", "cap_w", "cap_e"],
    highlight=["pad", "line_b"],
    tip="四角竖边互咬合环 —— 舱门朝东, 正对回收车开来的方向。",
)
b.step(
    "戴防热锥: 橙色等边四坡锥四棱互咬自锁, 尖端 1.71。",
    CONE_IDS,
    highlight=["cap_s"],
    tip="再入大气层时全靠它顶住上千度烈焰 —— 现在功成身退。",
)
b.step(
    "装回收车底盘: 双轮底座吸住草坪长缝, 甲板长边整边压双轮顶。",
    ["wh_s", "wh_n", "tk_deck"],
    highlight=["g_14", "g_23"],
    tip="车轮底座长 2, 草坪长板也长 2 —— 门式底盘一格不差。",
)
b.step(
    "合回收车箱体: 横楣双面 + 驾驶窗 + 尾门 + 舱顶, 红色警灯点亮。",
    ["tk_s", "tk_n", "tk_w", "tk_e", "tk_top", "tk_lamp"],
    highlight=["cap_e"],
    tip="驾驶窗朝西正对舱门 —— 医监医生第一个跳下车。",
)
b.step(
    "插信标旗收尾: 南北场界各一面红旗 —— 欢迎回家, 航天员!",
    ["bcn_n", "bcn_s"],
    highlight=["tk_lamp", "cap_cone_s"],
    tip="旗子底边整边吸场界拼缝 —— 下一位乘客, 也许就是你。",
)

b.finalize(
    model_id="capsule_recovery_01",
    name="返回舱回收站",
    name_en="Capsule Recovery Site 01",
    description=(
        "只用核心九片型的任务最后一幕: 与月球着陆器的多舱对接不同, "
        "主角是落地的返回舱与全库第一张平铺伞面 —— 红白棋盘格主伞"
        "嵌进草地同层 (既是地面也是图案), 两片灰色伞绳板一路牵到"
        "烧灼的着陆点; 返回舱四墙踩落点边线合环, 舷窗朝伞、橙色舱门"
        "朝东迎着回收车, 等边四坡防热锥尖 1.71; 蓝色回收车门式底盘"
        "驮完整箱环, 驾驶窗正对舱门、红色警灯 2.87 闪烁, 两面信标旗"
        "标出场界 —— 欢迎回家, 航天员!"
    ),
    difficulty=2,
    tags=["航天", "返回舱", "降落伞", "回收", "草原"],
    min_pieces=42,
    min_steps=10,
)
