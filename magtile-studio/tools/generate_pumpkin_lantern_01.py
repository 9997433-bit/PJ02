#!/usr/bin/env python3
"""生成模型 data/models/pumpkin_lantern_01.json (南瓜灯小屋)。

内容批 I 模型 2/4: 全库第一盏南瓜灯 —— 节日主题此前有圣诞集市 /
元宵灯会 / 雪人广场, 万圣秋收夜还是空白; 与姜饼糖果屋 (坡顶小房) /
雪人 (三比一突变收分) 刻意区分: 本作是一座"会做鬼脸的灯箱楼" ——
2x2 双层墙环南瓜身, 二层两扇窗格方是眯眯眼, 一层两扇门框方并排
拼成咧到耳根的大嘴 (双门大嘴全库唯一), 楼顶绿色瘦高茎尖骑拼缝
直上 4.0, 两片藤叶伏在瓜顶; 瓜田里两颗四棱自锁的迷你南瓜,
稻草人与小黑猫在田边站岗 —— 点灯喽, 糖果夜快乐!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 瓜脸朝南):
  - 瓜田地面 5 行 (x [0,6], y [0,5]): 田垄与草地       19 片
  - 南瓜身一层 (x [2,4], y [1,3], z 0..1): 墙环 8
    (南面两扇门框方大嘴)                                8 片
  - 南瓜身二层 (z 1..2): 墙环 8 (南面两扇窗格方眯眯眼)   8 片
  - 瓜顶方板 x4 + 茎尖 (瘦高等腰骑拼缝) + 藤叶 x2        7 片
  - 迷你南瓜 x2 (等边四坡锥四棱自锁)                     8 片
  - 稻草人 (立柱 + 草帽) + 小黑猫                        3 片
  合计 53 片, 12 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告 + jitter 全绿):
  - 南瓜身两节墙环整边共线上叠, 四角竖边互咬一通到顶,
    闭环拓扑天然通过高层检查;
  - 窗格方 / 门框方物理上按实心正方形处理, 嵌进墙环不减刚度;
  - 瓜顶四片方板四边入扣墙顶并互吸, 茎尖与藤叶骑板缝,
    剪断任何一条装饰连接最多失联 1 片, R8 单点失效通过;
  - 迷你南瓜四片等边斜棱互吸自锁成锥, 底边整边吸单位方板;
  - 地坪拼缝纪律: 瓜身墙脚 / 迷你南瓜 / 稻草人脚下全单位方板。

用法: python3 tools/generate_pumpkin_lantern_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

FIELD = "orange"    # 田垄
GRASS = "green"     # 草地
BODY = "orange"     # 南瓜身
EYE = "yellow"      # 眯眯眼 (窗格方透出灯光)
MOUTH = "yellow"    # 大嘴 (门框方)
CAP = "orange"      # 瓜顶
STEM = "green"      # 茎尖
LEAF = "green"      # 藤叶
MINI = "orange"     # 迷你南瓜
POLE = "yellow"     # 稻草人立柱
HAT = "red"         # 稻草人草帽
CAT = "gray"        # 小黑猫 (灰代黑)

# =================================================================
# 1. 瓜田地面 5 行 (x [0,6], y [0,5])
# =================================================================
# 南行 (y [0,1]): 稻草人与小黑猫脚下留单位方板
b.flat("g0_0", 0, 0, 0.0, GRASS)
b.flat_rect("g0_b", 1, 0, 0.0, FIELD)
b.flat_rect("g0_c", 3, 0, 0.0, GRASS)
b.flat("g0_5", 5, 0, 0.0, FIELD)
# 瓜脸行 (y [1,2]): 瓜身南脚踩这行
b.flat_rect("g1_a", 0, 1, 0.0, FIELD)
b.flat("g1_2", 2, 1, 0.0, GRASS)
b.flat("g1_3", 3, 1, 0.0, GRASS)
b.flat_rect("g1_c", 4, 1, 0.0, GRASS)
# 瓜身行 (y [2,3])
b.flat_rect("g2_a", 0, 2, 0.0, GRASS)
b.flat("g2_2", 2, 2, 0.0, FIELD)
b.flat("g2_3", 3, 2, 0.0, FIELD)
b.flat_rect("g2_c", 4, 2, 0.0, FIELD)
# 瓜后行 (y [3,4]): 两颗迷你南瓜脚下留单位方板
b.flat("g3_0", 0, 3, 0.0, FIELD)
b.flat_rect("g3_b", 1, 3, 0.0, GRASS)
b.flat_rect("g3_c", 3, 3, 0.0, FIELD)
b.flat("g3_5", 5, 3, 0.0, GRASS)
# 北行 (y [4,5])
b.flat_rect("g4_a", 0, 4, 0.0, GRASS)
b.flat_rect("g4_b", 2, 4, 0.0, FIELD)
b.flat_rect("g4_c", 4, 4, 0.0, GRASS)

# =================================================================
# 2. 南瓜身一层墙环 (x [2,4], y [1,3], z 0..1): 南面双门大嘴
# =================================================================
b.add("mouth_w", "door_frame", (2.5, 1.0, 0.5), (90, 0, 0), MOUTH)
b.add("mouth_e", "door_frame", (3.5, 1.0, 0.5), (90, 0, 0), MOUTH)
b.wall_ns("p1_n_w", 2, 3.0, 0, BODY)
b.wall_ns("p1_n_e", 3, 3.0, 0, BODY)
b.wall_ew("p1_w_s", 2.0, 1, 0, BODY)
b.wall_ew("p1_w_n", 2.0, 2, 0, BODY)
b.wall_ew("p1_e_s", 4.0, 1, 0, BODY)
b.wall_ew("p1_e_n", 4.0, 2, 0, BODY)

# =================================================================
# 3. 南瓜身二层墙环 (z 1..2): 南面两扇窗格方眯眯眼
# =================================================================
b.add("eye_w", "window_square", (2.5, 1.0, 1.5), (90, 0, 0), EYE)
b.add("eye_e", "window_square", (3.5, 1.0, 1.5), (90, 0, 0), EYE)
b.wall_ns("p2_n_w", 2, 3.0, 1, BODY)
b.wall_ns("p2_n_e", 3, 3.0, 1, BODY)
b.wall_ew("p2_w_s", 2.0, 1, 1, BODY)
b.wall_ew("p2_w_n", 2.0, 2, 1, BODY)
b.wall_ew("p2_e_s", 4.0, 1, 1, BODY)
b.wall_ew("p2_e_n", 4.0, 2, 1, BODY)

# =================================================================
# 4. 瓜顶方板 x4 + 茎尖 + 藤叶 x2 (z=2)
# =================================================================
b.flat("cap_sw", 2, 1, 2.0, CAP)
b.flat("cap_se", 3, 1, 2.0, CAP)
b.flat("cap_nw", 2, 2, 2.0, CAP)
b.flat("cap_ne", 3, 2, 2.0, CAP)
b.spire_ew("stem", 3.0, 1, 2.0, STEM)     # 骑南列板缝, 尖 4.0 全场制高
b.crest_ns("leaf_w", 2, 2.0, 2.0, LEAF)   # 伏在北列板缝上
b.crest_ns("leaf_e", 3, 2.0, 2.0, LEAF)

# =================================================================
# 5. 迷你南瓜 x2 (等边四坡锥四棱自锁)
# =================================================================
b.hat4("mini_a", 0, 3, 0.0, MINI, shape="equilateral_triangle")
b.hat4("mini_b", 5, 3, 0.0, MINI, shape="equilateral_triangle")

# =================================================================
# 6. 稻草人 + 小黑猫
# =================================================================
b.wall_ns("scare_pole", 0, 1.0, 0, POLE)
b.crest_ns("scare_hat", 0, 1.0, 1.0, HAT)
b.crest_ew("cat", 5.0, 0, 0.0, CAT)

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺瓜田南行与瓜脸行: 瓜身墙脚下的四格都要用单位方板。",
    ["g0_0", "g0_b", "g0_c", "g0_5",
     "g1_a", "g1_2", "g1_3", "g1_c"],
    tip="秋收的瓜田到了 —— 墙底边要和方板边等长吸合才抓得牢。",
)
b.step(
    "铺瓜身行与瓜后行: 行行等边互吸, 东西两角给迷你南瓜留单位方板。",
    ["g2_a", "g2_2", "g2_3", "g2_c",
     "g3_0", "g3_b", "g3_c", "g3_5"],
    highlight=["g1_2"],
    tip="迷你南瓜的四条底边都要整边吸住脚下的方板。",
)
b.step(
    "铺北行收口: 三条长板合拢, 瓜田完工。",
    ["g4_a", "g4_b", "g4_c"],
    highlight=["g3_b"],
)
b.step(
    "立一层南墙与西墙: 两扇黄色门框方并排, 就是咧到耳根的大嘴!",
    ["mouth_w", "mouth_e", "p1_w_s", "p1_w_n"],
    highlight=["g1_2", "g1_3"],
    tip="双门大嘴全库只有这一张 —— 笑得越开, 灯光越亮。",
)
b.step(
    "合一层北墙与东墙: 八片墙环四角竖边互咬闭环。",
    ["p1_n_w", "p1_n_e", "p1_e_s", "p1_e_n"],
    highlight=["mouth_w"],
    tip="闭环墙才站得稳 —— 南瓜的圆肚子有了。",
)
b.step(
    "摞二层南墙: 两扇窗格方骑上大嘴正上方, 这是南瓜的眯眯眼。",
    ["eye_w", "eye_e", "p2_w_s", "p2_w_n"],
    highlight=["mouth_w", "mouth_e"],
    tip="底边与一层墙顶整边共线吸合 —— 灯一点, 眼睛就眨起来。",
)
b.step(
    "合二层北墙与东墙: 第二节墙环合拢, 四角互咬一通到顶。",
    ["p2_n_w", "p2_n_e", "p2_e_s", "p2_e_n"],
    highlight=["p1_n_w"],
)
b.step(
    "盖瓜顶: 四片方板四边入扣墙顶, 板板互吸封口。",
    ["cap_sw", "cap_se", "cap_nw", "cap_ne"],
    highlight=["p2_n_w", "eye_w"],
    tip="瓜顶封住, 灯箱就聚光了 —— 茎和藤叶都骑在板缝上。",
)
b.step(
    "竖茎尖并铺藤叶: 绿色瘦高茎尖直上 4.0, 两片藤叶伏在瓜顶。",
    ["stem", "leaf_w", "leaf_e"],
    highlight=["cap_se"],
    tip="茎尖是全场最高点 —— 老远就能认出这盏南瓜灯。",
)
b.step(
    "堆西侧迷你南瓜: 四片等边斜棱互吸自锁成锥。",
    ["mini_a_s", "mini_a_e", "mini_a_n", "mini_a_w"],
    highlight=["g3_0"],
    tip="四棱自锁 —— 小南瓜也要长得结结实实。",
)
b.step(
    "堆东侧迷你南瓜: 同样的四坡锥, 瓜田成双。",
    ["mini_b_s", "mini_b_e", "mini_b_n", "mini_b_w"],
    highlight=["g3_5"],
)
b.step(
    "请稻草人与小黑猫就位: 立柱戴红草帽守田, 小黑猫蹲东南角。",
    ["scare_pole", "scare_hat", "cat"],
    highlight=["g0_0", "g0_5"],
    tip="点灯喽 —— 提上小篮子, 糖果夜快乐!",
)

b.finalize(
    model_id="pumpkin_lantern_01",
    name="南瓜灯小屋",
    name_en="Pumpkin Lantern Cottage 01",
    description=(
        "只用核心九片型的全库第一盏南瓜灯, 给节日货架补上万圣秋收夜: "
        "与姜饼糖果屋 (坡顶小房) 和雪人 (三比一突变收分) 都不同, 本作"
        "是一座'会做鬼脸的灯箱楼' —— 2x2 双层墙环南瓜身四角互咬一通"
        "到顶, 二层两扇窗格方是眯眯眼, 一层两扇门框方并排拼成咧到耳根"
        "的大嘴 (双门大嘴全库唯一), 瓜顶绿色瘦高茎尖骑拼缝直上 4.0, "
        "两片藤叶伏在瓜顶; 田里两颗四棱自锁的迷你南瓜, 稻草人戴红帽"
        "守田, 小黑猫蹲在东南角 —— 点灯喽, 糖果夜快乐!"
    ),
    difficulty=3,
    tags=["节日", "万圣节", "南瓜灯", "秋收", "进阶"],
    min_pieces=53,
    min_steps=12,
)
