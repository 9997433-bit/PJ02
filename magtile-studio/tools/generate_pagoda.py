#!/usr/bin/env python3
"""生成模型 data/models/pagoda_01.json (五重塔 · 旋位挑檐)。

技法: T06 螺旋塔 (主) + T12 层叠退台 + T11 拱肩镜像; 范式 bottom_up。
招牌技法: 每层楼板向两个相邻方向挑出宽檐, 挑檐方位逐层绕塔心旋位
(南东 -> 南西 -> 北西 -> 北东), 檐角再立一片翘起的脊饰 —— 塔身
方正不动, 屋檐却绕着塔"旋"上去; 顶阁沿旋位落在西南角, 山形双坡
屋面对脊合拢收顶。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 塔身占地 [1,3]x[1,3]):
  - 庭院: 12 片回形地坪环绕塔基                                     12 片
  - 山门: 双柱二层 + 长方形门楣 + 双塔尖 —— 门楣底边整边吸住
    第一层南挑檐外缘, 山门与塔从结构上连为一体                       7 片
  - 塔身 1~4 层: 每层四面墙, 2~4 层为整片长方形墙 (竖放 2x1),
    第一层南面开门洞 (T17 负空间)                                   16 片
  - 楼板与挑檐 1~4 层: 每层 2 片长方形楼板压墙顶 + 1 片长方形
    宽檐 + 2 片方檐 + 1 片檐角 + 1 片檐角脊饰, 方位逐层旋位          28 片
  - 顶阁: 2x1 阁楼落在西南旋位 + 双坡长方形屋面对脊自锁 +
    山面双破风板                                                     8 片
  - 参道石灯笼 2 座                                                   2 片
  合计 73 片, 16 个教程步骤。

物理规则要点 (通过 R1~R8 全部校验):
  - 长方形墙顶边 (长 2) 只与长方形楼板长边整边贴合 —— 楼板必须
    沿东西向铺, 方檐 (1x1) 则吸楼板短边, 长短边分工明确;
  - 每层挑檐组悬挑力矩: 宽檐 30 + 檐角 15 + 脊饰 13 = 58 g·单位,
    跨铰链磁边总长 3 -> 预算 60, 恰好压线通过 (设计值, 非巧合);
  - 山门门楣底边吸住第一层南檐外缘, 为最重的首层挑檐提供第二条
    支撑路径; 檐角同时坐在山门柱顶上;
  - 双坡屋面两片长方形对脊互吸自锁 (脊线 z=5.866), 山面破风板
    只挂在阁楼山墙顶边上, 不参与屋面受力。

坐标约定与 C++ 端一致: 旋转为欧拉角 (度), R = Rz * Ry * Rx。
用法: python3 tools/generate_pagoda.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

mb = ModelBuilder()

WALL = "red"        # 塔身朱红
FLOOR = "yellow"    # 楼板
EAVE = "cyan"       # 挑檐 (琉璃瓦)
CREST = "yellow"    # 檐角脊饰

# =================================================================
# 1. 庭院回形地坪 (环绕塔基 [1,3]x[1,3])
# =================================================================
mb.flat("c_sw", 0, 0, 0.0, "gray")
mb.flat("a_s0", 1, 0, 0.0, "green")
mb.flat("a_s1", 2, 0, 0.0, "green")
mb.flat("c_se", 3, 0, 0.0, "gray")
mb.flat("a_w0", 0, 1, 0.0, "green")
mb.flat("a_w1", 0, 2, 0.0, "green")
mb.flat("c_nw", 0, 3, 0.0, "gray")
mb.flat("a_n0", 1, 3, 0.0, "green")
mb.flat("a_n1", 2, 3, 0.0, "green")
mb.flat("c_ne", 3, 3, 0.0, "gray")
mb.flat("a_e0", 3, 1, 0.0, "green")
mb.flat("a_e1", 3, 2, 0.0, "green")

# =================================================================
# 2. 山门 (平面 y=0): 双柱二层 + 门楣 + 塔尖; 参道石灯笼 (东沿)
# =================================================================
mb.wall_ns("gp_w_0", 0, 0.0, 0, WALL)
mb.wall_ns("gp_w_1", 0, 0.0, 1, WALL)
mb.wall_ns("gp_e_0", 3, 0.0, 0, WALL)
mb.wall_ns("gp_e_1", 3, 0.0, 1, WALL)
mb.lintel_ns("g_lintel", 1, 0.0, 1, "purple")      # 门楣 x 1..3, z 1..2
mb.spire_ns("g_spire_w", 0, 0.0, 2.0, CREST)
mb.spire_ns("g_spire_e", 3, 0.0, 2.0, CREST)
mb.spire_ew("lantern_a", 4.0, 1, 0.0, "orange")    # 石灯笼立在庭院东沿
mb.spire_ew("lantern_b", 4.0, 2, 0.0, "orange")

# =================================================================
# 3. 塔身 1~4 层 (占地 [1,3]x[1,3]) + 楼板与旋位挑檐
#    挑檐方位逐层旋转: L1 南+东(檐角SE) -> L2 南+西(SW) -> L3 北+西(NW)
#    -> L4 北+东(NE); 檐角脊饰立在檐角块朝外的短边上
# =================================================================
# ---- 第一层塔身: 南面开门洞 (方墙 + 负空间), 其余三面整片长方形墙 --
mb.wall_ns("s1_s", 2, 1.0, 0, WALL)                # 门洞东侧方墙
mb.lintel_ew("s1_w", 1.0, 1, 0, WALL)
mb.lintel_ew("s1_e", 3.0, 1, 0, WALL)
mb.lintel_ns("s1_n", 1, 3.0, 0, WALL)

# ---- 2~4 层塔身: 四面整片长方形墙 -------------------------------
for lv, z0 in (("2", 1), ("3", 2), ("4", 3)):
    mb.lintel_ns(f"s{lv}_s", 1, 1.0, z0, WALL)
    mb.lintel_ew(f"s{lv}_w", 1.0, 1, z0, WALL)
    mb.lintel_ew(f"s{lv}_e", 3.0, 1, z0, WALL)
    mb.lintel_ns(f"s{lv}_n", 1, 3.0, z0, WALL)

# ---- 楼板 + 旋位挑檐 (每层: 2 楼板rect + 1 宽檐rect + 2 方檐 +
#      1 檐角 + 1 脊饰) -------------------------------------------
# 脊饰立在檐角块朝外的一条短边上, 方位随层旋位 (南沿被山门占用,
# 故 L1/L2 的脊饰分别翘向东/西, L3/L4 翘向北)
EAVE_PLAN = {
    1: {"z": 1.0, "wide": "s", "side": "e", "corner": (3, 0), "crest": ("ew", 4.0, 0)},
    2: {"z": 2.0, "wide": "s", "side": "w", "corner": (0, 0), "crest": ("ew", 0.0, 0)},
    3: {"z": 3.0, "wide": "n", "side": "w", "corner": (0, 3), "crest": ("ns", 0, 4.0)},
    4: {"z": 4.0, "wide": "n", "side": "e", "corner": (3, 3), "crest": ("ns", 3, 4.0)},
}
for lv, plan in EAVE_PLAN.items():
    z = plan["z"]
    # 楼板: 两片长方形沿东西向, 长边吸南北墙顶
    mb.flat_rect(f"fl{lv}_a", 1, 1, z, FLOOR)      # [1,3]x[1,2]
    mb.flat_rect(f"fl{lv}_b", 1, 2, z, FLOOR)      # [1,3]x[2,3]
    # 宽檐: 长方形贴楼板长边向南/北挑出
    if plan["wide"] == "s":
        mb.flat_rect(f"ev{lv}_wide", 1, -1 + 1, z, EAVE)   # [1,3]x[0,1]
    else:
        mb.flat_rect(f"ev{lv}_wide", 1, 3, z, EAVE)        # [1,3]x[3,4]
    # 方檐: 两片 1x1 吸楼板短边向东/西挑出
    ex = 3 if plan["side"] == "e" else 0
    mb.flat(f"ev{lv}_side0", ex, 1, z, EAVE)
    mb.flat(f"ev{lv}_side1", ex, 2, z, EAVE)
    # 檐角块 + 檐角脊饰
    cx, cy = plan["corner"]
    mb.flat(f"ev{lv}_c", cx, cy, z, EAVE)
    kind, ca, cb = plan["crest"]
    if kind == "ew":
        mb.crest_ew(f"crest{lv}", ca, cb, z, CREST)
    else:
        mb.crest_ns(f"crest{lv}", ca, cb, z, CREST)

# =================================================================
# 4. 顶阁 (第 5 层): 2x1 阁楼 [1,3]x[1,2] + 双坡屋面 + 破风板
# =================================================================
mb.lintel_ns("s5_s", 1, 1.0, 4, WALL)              # 南墙 rect
mb.lintel_ns("s5_n", 1, 2.0, 4, WALL)              # 北墙 rect (吸楼板中缝)
mb.wall_ew("s5_w", 1.0, 1, 4, WALL)                # 西山墙 1x1
mb.wall_ew("s5_e", 3.0, 1, 4, WALL)                # 东山墙 1x1

# 双坡屋面: 两片长方形从南北墙顶斜向对脊 (脊线 y=1.5, z=5.866025)
mb.place_edge("roof_s", "rectangle", 0,
              (1.0, 1.0, 5.0), (3.0, 1.0, 5.0), (0.0, 0.5, 0.866025), "blue")
mb.place_edge("roof_n", "rectangle", 0,
              (3.0, 2.0, 5.0), (1.0, 2.0, 5.0), (0.0, -0.5, 0.866025), "blue")

# 破风板: 等边三角形立在东西山墙顶边, 收进屋面山尖之下
mb.crest_ew("gable_w", 1.0, 1, 5.0, CREST)
mb.crest_ew("gable_e", 3.0, 1, 5.0, CREST)

# =================================================================
# 教程步骤 (16 步): 一层塔身 + 一层檐成对推进, 挑檐方位逐层旋位
# =================================================================
mb.step(
    "庭院南半: 沿塔基南、西两侧铺 6 片地坪 (灰色角石 + 绿色步道), "
    "相邻边互吸围出回形庭院的前半圈。",
    ["c_sw", "a_s0", "a_s1", "c_se", "a_w0", "a_w1"],
    tip="塔基 [1,3]x[1,3] 空在回形中央 —— 塔身直接落地, 地坪只作庭院。",
)
mb.step(
    "庭院北半: 补齐北、东两侧 6 片, 回形庭院合围。",
    ["c_nw", "a_n0", "a_n1", "c_ne", "a_e0", "a_e1"],
    highlight=["c_sw", "c_se"],
    tip="四角灰色角石对齐, 之后山门与灯笼都立在地坪沿口上。",
)
mb.step(
    "山门双柱: 庭院南沿两端各立 2 层朱红门柱 (平面 y=0), 柱底吸角石边。",
    ["gp_w_0", "gp_w_1", "gp_e_0", "gp_e_1"],
    highlight=["c_sw", "c_se"],
    tip="两柱间空出的 2 格是门洞 —— 门楣下一步才架。",
)
mb.step(
    "山门门楣与塔尖: 紫色长方形门楣横跨双柱 (竖直短边与柱身互吸), "
    "柱顶各插 1 根黄色塔尖。",
    ["g_lintel", "g_spire_w", "g_spire_e"],
    highlight=["gp_w_1", "gp_e_1"],
    tip="门楣顶边与第一层挑檐同高 —— 它稍后还要托住塔檐, 别装歪。",
)
mb.step(
    "第一层塔身: 西、东、北三面整片长方形墙竖放落地, 南面只在东半立 "
    "1 片方墙 —— 西半留出门洞 (负空间), 从山门望进去正对塔门。",
    ["s1_w", "s1_e", "s1_n", "s1_s"],
    highlight=["g_lintel"],
    tip="长方形墙竖放时占 2 格宽 1 格高, 四角竖边两两互吸。",
)
mb.step(
    "第一层楼板与挑檐 (南+东): 2 片黄色楼板长边压北墙与南墙顶, 宽檐"
    "向南挑出 (底边恰好吸住山门门楣顶缘), 2 片方檐吸楼板短边向东挑出, "
    "东南檐角补齐 —— 檐口比塔身宽一圈。",
    ["fl1_b", "fl1_a", "ev1_wide", "ev1_side0", "ev1_side1", "ev1_c"],
    highlight=["s1_n", "g_lintel"],
    tip="先铺北侧楼板 (吸北墙顶), 再铺南侧, 挑檐最后向外接 —— 南檐同时"
        "被门楣托住, 是全塔最稳的一圈檐。",
)
mb.step(
    "东南脊饰 + 第二层塔身: 檐角朝东的短边立 1 片翘起的黄色脊饰; 第二层"
    "四面长方形墙压上一层墙顶与楼板边。",
    ["crest1", "s2_s", "s2_e", "s2_w", "s2_n"],
    highlight=["ev1_c", "fl1_a"],
    tip="脊饰是每层檐角的'指南针'—— 之后每层它都会绕塔心转一个方位。",
)
mb.step(
    "第二层楼板与挑檐 (南+西): 楼板照旧, 但这层宽檐仍向南、方檐改向西, "
    "檐角旋到西南 —— 挑檐开始绕塔旋位。",
    ["fl2_a", "fl2_b", "ev2_wide", "ev2_side0", "ev2_side1", "ev2_c"],
    highlight=["s2_s", "s2_w"],
    tip="对照下一层: 檐角 SE -> SW -> NW -> NE, 逆时针盘旋而上。",
)
mb.step(
    "西南脊饰 + 第三层塔身: 脊饰立在西南檐角朝西的短边上, 第三层四面墙"
    "继续收高。",
    ["crest2", "s3_s", "s3_e", "s3_w", "s3_n"],
    highlight=["ev2_c"],
    tip="塔身始终方正不动, 旋的是屋檐 —— 这就是本塔的螺旋逻辑。",
)
mb.step(
    "第三层楼板与挑檐 (北+西): 宽檐转向北面, 方檐仍在西面, 檐角旋至西北。",
    ["fl3_a", "fl3_b", "ev3_wide", "ev3_side0", "ev3_side1", "ev3_c"],
    highlight=["s3_n", "s3_w"],
    tip="从塔顶俯视, 三层檐已转过半圈 —— 剪影从每个角度都不同。",
)
mb.step(
    "西北脊饰 + 第四层塔身: 脊饰立在西北檐角北边, 第四层墙体到位。",
    ["crest3", "s4_s", "s4_e", "s4_w", "s4_n"],
    highlight=["ev3_c"],
    tip="塔已 4 层高, 放片前先扶稳下层墙顶。",
)
mb.step(
    "第四层楼板与挑檐 (北+东): 宽檐在北, 方檐转回东面, 檐角旋至东北 —— "
    "四层檐正好绕塔一整圈。",
    ["fl4_a", "fl4_b", "ev4_wide", "ev4_side0", "ev4_side1", "ev4_c"],
    highlight=["s4_n", "s4_e"],
    tip="至此四个檐角各据一方, 从正上方看是一幅旋转的风车图。",
)
mb.step(
    "东北脊饰 + 顶阁墙身: 最后一片脊饰落位; 顶阁沿旋位退到南半 —— "
    "南北两片长方形墙分别吸第四层楼板南缘与中缝, 东西山墙 1x1 补齐, "
    "围出 2x1 阁楼 (T12 退台收分)。",
    ["crest4", "s5_s", "s5_n", "s5_w", "s5_e"],
    highlight=["ev4_c", "fl4_a"],
    tip="顶阁只占楼板南半 —— 这是第五次旋位, 也是全塔唯一一次塔身退台。",
)
mb.step(
    "双坡屋面: 两片蓝色长方形从南北墙顶斜向中央, 顶边在脊线两两互吸 —— "
    "自锁的山形大屋顶。",
    ["roof_s", "roof_n"],
    highlight=["s5_s", "s5_n"],
    tip="先搭南坡吸住墙顶, 北坡随后对脊压合, 听到'嗒'即自锁到位。",
)
mb.step(
    "山面破风板: 东西山墙顶各立 1 片等边三角形, 恰好收进屋面山尖之下。",
    ["gable_w", "gable_e"],
    highlight=["roof_s", "roof_n"],
    tip="破风板不受屋面重量, 只是山面的装饰性封板。",
)
mb.step(
    "参道石灯笼: 庭院东沿立 2 座橙色石灯笼 —— 五重塔落成, 晨钟可闻。",
    ["lantern_a", "lantern_b"],
    highlight=["a_e0", "a_e1"],
    tip="从山门望进去: 门洞、塔门、逐层旋上的四角飞檐一线贯通。",
)

mb.finalize(
    model_id="pagoda_01",
    name="五重塔",
    name_en="Five-Story Pagoda 01",
    description=(
        "旋位挑檐的五重塔: 塔身方正逐层上叠, 每层楼板却向两个相邻方向"
        "挑出宽檐, 檐角连同翘起的脊饰绕塔心逐层旋位 (东南->西南->西北->"
        "东北), 屋檐像风车一样绕塔盘旋而上; 第一层南檐落在山门门楣上, "
        "门洞-塔门负空间一线贯通; 顶阁沿旋位退台成 2x1 阁楼, 双坡屋面"
        "对脊自锁收顶。塔身收、屋檐放 —— 东亚木塔的轮廓由此而来。"
    ),
    difficulty=3,
    tags=["五重塔", "建筑地标", "宝塔", "旋位", "挑檐"],
    min_pieces=65,
    min_steps=16,
)
