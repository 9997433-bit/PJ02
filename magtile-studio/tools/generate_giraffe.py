#!/usr/bin/env python3
"""生成模型 data/models/giraffe_01.json (长颈鹿 · 草原立姿)。

动物世界主题: 与霸王龙骨架 (水平箱形梁悬挑) 刻意区分 —— 长颈鹿是
全库第一只"纵向动物": 四条腿柱撑起箱形躯干, 躯干前端拔起一座
四层"梯架脖颈" (左右颈壁夹周期横档), 顶端戴 1x1 头颅小箱,
鹿角/耳朵/吻/尾巴全部用三角件点睛。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 体轴沿 x, 头朝西):
  - 草原基座: 6 片平铺草地 + 3 片围栏旗饰                       9 片
  - 四腿: 前后腿各一对 (平面 y=0 / y=1), 每腿 2 层立片,
    前腿脚前各 1 片直角三角蹄撑                                 10 片
  - 躯干箱 (x 1..5, z 2..3): 左右壁各 4 + 4 片背板压顶          12 片
  - 梯架脖颈 (x 1..2, z 3..7): 左右颈壁各 4 层 + 中部横档        9 片
  - 头颅小箱 (z 7..8): 头底板 + 四壁 + 颅顶                      6 片
  - 头饰: 吻部水平收尖 + 双耳 + 双鹿角 (骨突)                    5 片
  - 尾巴: 等边三角形挂在躯干东端竖边上                           1 片
  合计 52 片, 16 个教程步骤。

物理规则要点 (通过 R1~R8 全部校验):
  - 脖颈是纯竖向堆叠 (压力传递), 横档把左右颈壁锁成梯架,
    剪断任何一条铰链后另一侧颈壁仍然接地 (R6 力矩天然为零);
  - 头颅小箱直接压在颈顶横档上, 吻部是 13g 级水平小悬挑
    (力矩 3.8 << 20 预算), 耳/角是零力矩竖直立件;
  - 脖颈位于 x 1..2, 全程重心水平投影落在 x 0..6 草地凸包内。

用法: python3 tools/generate_giraffe.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

HIDE = "yellow"      # 鹿皮主色
SPOT = "orange"      # 斑纹色
MANE = "red"         # 鬃毛/头饰点缀

# =================================================================
# 1. 草原基座 (x 0..6, y 0..1): 6 片草地
# =================================================================
for x0 in range(6):
    b.flat(f"gr_{x0}", x0, 0, 0.0, "green" if x0 % 2 == 0 else "cyan")

# =================================================================
# 2. 四腿 (前腿 x 1..2, 后腿 x 4..5; 左腿平面 y=0, 右腿平面 y=1)
#    + 前蹄直角三角撑 (竖边吸腿骨, 横边贴地前伸)
# =================================================================
for lv in range(2):
    c = HIDE if lv == 0 else SPOT
    b.wall_ns(f"fleg_l_{lv}", 1, 0.0, lv, c)
    b.wall_ns(f"fleg_r_{lv}", 1, 1.0, lv, c)
    b.wall_ns(f"hleg_l_{lv}", 4, 0.0, lv, c)
    b.wall_ns(f"hleg_r_{lv}", 4, 1.0, lv, c)
b.brace("hoof_l", (1.0, 0.0, 0.0), "-x", HIDE)
b.brace("hoof_r", (1.0, 1.0, 0.0), "-x", HIDE)

# =================================================================
# 3. 躯干箱 (x 1..5, z 2..3): 左右壁 + 背板压顶
# =================================================================
for x0 in range(1, 5):
    c = HIDE if x0 % 2 == 0 else SPOT
    b.wall_ns(f"bd_l_{x0}", x0, 0.0, 2, c)
    b.wall_ns(f"bd_r_{x0}", x0, 1.0, 2, c)
    b.flat(f"bk_{x0}", x0, 0, 3.0, SPOT if x0 % 2 == 0 else HIDE)

# =================================================================
# 4. 梯架脖颈 (x 1..2, z 3..7): 左右颈壁 4 层 + 中部横档 (z=5)
# =================================================================
for lv in range(4):
    c = HIDE if lv % 2 == 0 else SPOT
    b.wall_ns(f"nk_l_{lv}", 1, 0.0, 3 + lv, c)
    b.wall_ns(f"nk_r_{lv}", 1, 1.0, 3 + lv, c)
b.flat("rung", 1, 0, 5.0, MANE)          # 中部横档: 把左右颈壁锁成梯架

# =================================================================
# 5. 头颅小箱 (x 1..2, z 7..8): 头底板 + 四壁 + 颅顶
# =================================================================
b.flat("hd_base", 1, 0, 7.0, HIDE)
b.wall_ns("hd_s", 1, 0.0, 7, HIDE)
b.wall_ns("hd_n", 1, 1.0, 7, HIDE)
b.wall_ew("hd_w", 1.0, 0, 7, SPOT)       # 面颊 (朝西的脸)
b.wall_ew("hd_e", 2.0, 0, 7, SPOT)       # 后脑
b.flat("hd_top", 1, 0, 8.0, HIDE)

# ---- 头饰: 吻部 (水平收尖, 等边短吻) + 双耳 + 双鹿角 ---------------
b.place_tri("muzzle", "equilateral_triangle",
            (1.0, 1.0, 7.0), (1.0, 0.0, 7.0), (0.133975, 0.5, 7.0), SPOT)
b.crest_ew("ear_w", 1.0, 0, 8.0, HIDE)   # 西耳 (立在颅顶西沿)
b.crest_ew("ear_e", 2.0, 0, 8.0, HIDE)   # 东耳 (立在颅顶东沿)
b.spire_ns("horn_s", 1, 0.0, 8.0, MANE)  # 南侧鹿角骨突
b.spire_ns("horn_n", 1, 1.0, 8.0, MANE)  # 北侧鹿角骨突

# =================================================================
# 6. 尾巴: 等边三角形底边吸躯干左壁东端竖边, 水平向东收尖
# =================================================================
b.place_tri("tail", "equilateral_triangle",
            (5.0, 0.0, 3.0), (5.0, 0.0, 2.0), (5.866025, 0.0, 2.5), MANE)

# =================================================================
# 7. 草原围栏: 基座南沿 3 片等边三角旗饰
# =================================================================
for x0 in (2, 3, 5):
    b.crest_ns(f"fence_{x0}", x0, 0.0, 0.0, "purple")

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺草原基座: 6 片草地方板沿 x 一字铺开 (x 0..6), 相邻边互吸。",
    [f"gr_{x0}" for x0 in range(6)],
    tip="长颈鹿要站上来的地基 —— 绿色青色交替就是斑驳的草地。",
)
b.step(
    "立前腿下节: 左右前腿各 1 片黄色方片立在草地上 (x 1..2), "
    "底边分别吸草地南北沿边。",
    ["fleg_l_0", "fleg_r_0"],
    highlight=["gr_1"],
    tip="左腿在 y=0 沿, 右腿在 y=1 沿 —— 两片平行相对, 中间留空。",
)
b.step(
    "立后腿下节: 同样手法在 x 4..5 立起左右后腿。",
    ["hleg_l_0", "hleg_r_0"],
    highlight=["gr_4", "fleg_l_0"],
    tip="前后腿间距 2 格, 正好是躯干的跨度。",
)
b.step(
    "前蹄斜撑: 2 片直角三角形竖边吸前腿骨, 横边贴地向西前伸 —— "
    "这是长颈鹿俯身喝水的前蹄, 也是全身的抗侧地锚。",
    ["hoof_l", "hoof_r"],
    highlight=["fleg_l_0", "fleg_r_0"],
    tip="直角三角形两条直角边同时吸腿与贴地, 双边受力最稳。",
)
b.step(
    "腿加高一节: 4 片橙色方片分别叠上四条腿, 竖边横边全部对齐。",
    ["fleg_l_1", "fleg_r_1", "hleg_l_1", "hleg_r_1"],
    highlight=["hoof_l"],
    tip="四条腿都到 2 格高 —— 长颈鹿的腿比很多动物的全身还高。",
)
b.step(
    "躯干左壁: 4 片方片横跨前后腿顶 (x 1..5), 黄橙相间。",
    [f"bd_l_{x0}" for x0 in range(1, 5)],
    highlight=["fleg_l_1", "hleg_l_1"],
    tip="左壁两端分别压在前后腿顶边上, 中段靠竖边互吸悬跨。",
)
b.step(
    "躯干右壁: 同样 4 片补齐右侧, 躯干成双壁通道。",
    [f"bd_r_{x0}" for x0 in range(1, 5)],
    highlight=["fleg_r_1", "hleg_r_1"],
    tip="左右壁平行相对, 腹部留空 —— 从侧面看就是修长的肚线。",
)
b.step(
    "背板压顶: 4 片背板盖住躯干 (z=3), 每片同时吸左右壁顶边, "
    "躯干锁成箱形梁。",
    [f"bk_{x0}" for x0 in range(1, 5)],
    highlight=["bd_l_2", "bd_r_2"],
    tip="背板是躯干的力学锁扣 —— 盖完轻推躯干应纹丝不动。",
)
b.step(
    "脖颈起步: 左右颈壁各 2 层叠在躯干前端背板上 (x 1..2, z 3..5)。",
    ["nk_l_0", "nk_r_0", "nk_l_1", "nk_r_1"],
    highlight=["bk_1"],
    tip="颈壁踩着背板与躯干壁顶边起跳, 每层都要对缝竖直向上。",
)
b.step(
    "中部横档: 1 片红色横档在 z=5 锁住左右颈壁 —— 脖颈从双壁变成"
    "梯架。",
    ["rung"],
    highlight=["nk_l_1", "nk_r_1"],
    tip="横档同时吸住两侧颈壁顶边, 是长脖子抗晃的关键一档。",
)
b.step(
    "脖颈到顶: 左右颈壁再各叠 2 层 (z 5..7), 长脖子拔到 7 格高。",
    ["nk_l_2", "nk_r_2", "nk_l_3", "nk_r_3"],
    highlight=["rung"],
    tip="上两层踩在横档与下层颈壁上 —— 全库最高的动物脖颈。",
)
b.step(
    "头底板: 1 片方板盖住颈顶 (z=7), 同时吸左右颈壁顶边。",
    ["hd_base"],
    highlight=["nk_l_3", "nk_r_3"],
    tip="这块板既是颈顶横档又是头颅的地板, 一片两用。",
)
b.step(
    "头颅四壁: 南北面颊 + 西脸 + 后脑围出 1x1 头颅小箱 (z 7..8)。",
    ["hd_s", "hd_n", "hd_w", "hd_e"],
    highlight=["hd_base"],
    tip="四壁底边吸头底板四边, 拐角竖边两两互吸围成闭箱。",
)
b.step(
    "颅顶与吻部: 颅顶板封箱, 1 片等边三角形底边吸头底板西沿竖边, "
    "水平向西收出低头觅食的吻部。",
    ["hd_top", "muzzle"],
    highlight=["hd_w"],
    tip="吻部挂在竖直磁边上水平前伸, 小小一片不产生超预算力矩。",
)
b.step(
    "耳朵与鹿角: 颅顶东西沿立 2 片耳朵, 南北沿立 2 片红色等腰骨突 "
    "—— 长颈鹿标志性的一对小角。",
    ["ear_w", "ear_e", "horn_s", "horn_n"],
    highlight=["hd_top"],
    tip="四件头饰都是竖直立件, 底边吸颅顶四沿, 零力矩零负担。",
)
b.step(
    "尾巴与围栏: 等边尾巴底边吸躯干左壁东端竖边、水平向东收尖, "
    "草地南沿立 3 面紫色围栏旗 —— 草原上的长颈鹿落成!",
    ["tail", "fence_2", "fence_3", "fence_5"],
    highlight=["bd_l_4", "bd_r_4"],
    tip="退后一步看: 四腿一躯一长颈, 昂首站在草原上。",
)

b.finalize(
    model_id="giraffe_01",
    name="长颈鹿",
    name_en="Giraffe 01",
    description=(
        "草原立姿长颈鹿: 四条双层腿柱撑起箱形躯干, 躯干前端拔起四层"
        "'左右颈壁 + 中部横档'的梯架脖颈, 顶端戴 1x1 头颅小箱 —— 吻部"
        "水平收尖、双耳双角点睛, 尾巴挂在躯干末端竖边上。全库第一只"
        "纵向生长的动物: 脖颈纯竖向传力, 横档锁架抗晃, 站得又高又稳。"
    ),
    difficulty=3,
    tags=["动物世界", "草原", "生物", "高塔"],
    min_pieces=50,
    min_steps=16,
)
