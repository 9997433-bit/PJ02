#!/usr/bin/env python3
"""生成模型 data/models/cactus_desert_01.json (沙漠仙人掌)。

自然世界主题: 全库第一片沙漠造景 —— 金沙铺地, 一株两层箱式
巨型萨瓜罗仙人掌戴着瘦高四坡尖冠 (顶尖 3.94 全场最高), 腰间
两片外倾等边花苞探出躯干; 东侧一座红岩平顶台地 (2x2 箱体 +
岩顶板), 西角一丛桶形仙人球顶开粉色花冠; 沙面上两株外倾
幼苗与一堆四坡砾石 —— 烈日当空, 沙漠也生机勃勃!

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 沙漠地坪 (x [0,8], y [0,5]): 长板 x8 + 方板 x24          32 片
  - 巨型萨瓜罗 (x [2,3], y [2,3]): 箱式躯干两层 x8
    + 瘦高四坡尖冠 x4 + 外倾花苞等边 x2                      14 片
  - 红岩台地 (x [5,7], y [1,3]): 箱壁方墙 x8 + 岩顶方板 x4   12 片
  - 桶形仙人球 (x [0,1], y [1,2]): 方墙 x4 + 四坡花冠 x4      8 片
  - 沙漠幼苗: 外倾等边 x2 (斜插沙面拼缝)                      2 片
  - 砾石堆 (x [7,8], y [3,4]): 四坡等边锥 x4                  4 片
  合计 72 片, 15 个教程步骤, 4 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, strict 档同样全绿):
  - 萨瓜罗躯干两层箱式闭环 (四角竖边互吸), 剪断任一连接
    不塌; 四坡尖冠四条斜棱两两互吸自锁成环;
  - 花苞底边整边吸躯干层间拼缝, 外倾 30 度力矩仅 1.9,
    远在 strict 预算 17.5 之内; 幼苗同理斜插沙面拼缝;
  - 台地箱壁闭环, 岩顶四板压壁顶多路受力锁成箱体;
  - 仙人球方墙闭环 + 花冠四棱自锁 —— 全模型无一处悬挑链。

用法: python3 tools/generate_cactus_desert.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

DUNE = "orange"     # 沙丘沿 (南北长板)
SAND = "yellow"     # 沙漠地坪
CACT = "green"      # 萨瓜罗 / 仙人球 / 幼苗
CROWN = "green"     # 萨瓜罗尖冠
ROCK = "red"        # 红岩台地
ROCKTOP = "orange"  # 岩顶
BLOOM = "pink"      # 仙人球花冠
STONE = "gray"      # 砾石堆

# =================================================================
# 1. 沙漠地坪 (x [0,8], y [0,5])
# =================================================================
for k in range(4):
    b.flat_rect(f"dn_s_{k}", 2 * k, 0, 0.0, DUNE)
    b.flat_rect(f"dn_n_{k}", 2 * k, 4, 0.0, DUNE)
for x in range(8):
    b.flat(f"sa_1_{x}", x, 1, 0.0, SAND)
    b.flat(f"sa_2_{x}", x, 2, 0.0, SAND)
    b.flat(f"sa_3_{x}", x, 3, 0.0, SAND)

# =================================================================
# 2. 巨型萨瓜罗 (x [2,3], y [2,3]): 两层箱式躯干 + 尖冠 + 花苞
# =================================================================
for z in (0, 1):
    b.wall_ns(f"sg_s_{z}", 2, 2.0, z, CACT)
    b.wall_ns(f"sg_n_{z}", 2, 3.0, z, CACT)
    b.wall_ew(f"sg_w_{z}", 2.0, 2, z, CACT)
    b.wall_ew(f"sg_e_{z}", 3.0, 2, z, CACT)
SG_CROWN = b.hat4("sg_crown", 2, 2, 2.0, CROWN)     # 瘦高尖冠 (顶尖 3.94)
# 花苞: 底边吸层间拼缝 (z=1), 外倾 30 度
b.place_tri("bud_s", "equilateral_triangle",
            (2.0, 2.0, 1.0), (3.0, 2.0, 1.0), (2.5, 1.566987, 1.75), CACT)
b.place_tri("bud_e", "equilateral_triangle",
            (3.0, 2.0, 1.0), (3.0, 3.0, 1.0), (3.433013, 2.5, 1.75), CACT)

# =================================================================
# 3. 红岩台地 (x [5,7], y [1,3]): 2x2 箱壁 + 岩顶
# =================================================================
for x in (5, 6):
    b.wall_ns(f"rk_s_{x}", x, 1.0, 0, ROCK)
    b.wall_ns(f"rk_n_{x}", x, 3.0, 0, ROCK)
for y in (1, 2):
    b.wall_ew(f"rk_w_{y}", 5.0, y, 0, ROCK)
    b.wall_ew(f"rk_e_{y}", 7.0, y, 0, ROCK)
for x in (5, 6):
    for y in (1, 2):
        b.flat(f"rk_top_{x}_{y}", x, y, 1.0, ROCKTOP)

# =================================================================
# 4. 桶形仙人球 (x [0,1], y [1,2]): 方墙箱 + 粉色花冠
# =================================================================
b.wall_ns("br_s", 0, 1.0, 0, CACT)
b.wall_ns("br_n", 0, 2.0, 0, CACT)
b.wall_ew("br_w", 0.0, 1, 0, CACT)
b.wall_ew("br_e", 1.0, 1, 0, CACT)
BR_BLOOM = b.hat4("br_bloom", 0, 1, 1.0, BLOOM,
                  shape="equilateral_triangle")

# =================================================================
# 5. 沙漠幼苗 (外倾等边) + 砾石堆 (四坡锥)
# =================================================================
b.place_tri("seedling_a", "equilateral_triangle",
            (3.0, 4.0, 0.0), (4.0, 4.0, 0.0), (3.5, 4.433013, 0.75), CACT)
b.place_tri("seedling_b", "equilateral_triangle",
            (5.0, 4.0, 0.0), (6.0, 4.0, 0.0), (5.5, 4.433013, 0.75), CACT)
STONES = b.hat4("stone", 7, 3, 0.0, STONE,
                shape="equilateral_triangle")

# =================================================================
# 教程步骤 (15 步)
# =================================================================
b.step(
    "铺南沙丘沿: 4 片橙色长板。",
    [f"dn_s_{k}" for k in range(4)],
    tip="沙丘沿是整片沙漠的南边界。",
)
b.step(
    "铺沙漠第一行: 8 片金沙方板 (y [1,2])。",
    [f"sa_1_{x}" for x in range(8)],
    highlight=["dn_s_0"],
    tip="这行拼缝是仙人球与台地南壁的落点。",
)
b.step(
    "铺沙漠第二行: 8 片 (y [2,3])。",
    [f"sa_2_{x}" for x in range(8)],
    highlight=["sa_1_0"],
    tip="巨型萨瓜罗就扎根在这行的拼缝上。",
)
b.step(
    "铺沙漠第三行: 8 片 (y [3,4])。",
    [f"sa_3_{x}" for x in range(8)],
    highlight=["sa_2_0"],
    tip="三行方板拼缝对齐 —— 沙漠平整如镜。",
)
b.step(
    "铺北沙丘沿: 4 片橙色长板, 沙漠合拢。",
    [f"dn_n_{k}" for k in range(4)],
    highlight=["sa_3_0"],
    tip="幼苗一会儿就斜插在北沿前的拼缝上。",
)
b.step(
    "立萨瓜罗第一层: 4 片绿墙踩沙面拼缝, 四角竖边互吸。",
    ["sg_s_0", "sg_n_0", "sg_w_0", "sg_e_0"],
    highlight=["sa_2_2", "sa_3_2"],
    tip="箱式躯干是闭合环 —— 剪断任一连接都不塌。",
)
b.step(
    "叠萨瓜罗第二层: 再来 4 片, 底边整边吸下层顶边。",
    ["sg_s_1", "sg_n_1", "sg_w_1", "sg_e_1"],
    highlight=["sg_s_0", "sg_e_0"],
    tip="两层箱体环环相扣 —— 沙漠巨人挺直腰杆。",
)
b.step(
    "戴四坡尖冠: 4 片瘦高等腰合拢, 顶尖 3.94 全场最高。",
    SG_CROWN,
    highlight=["sg_s_1", "sg_n_1"],
    tip="四条斜棱两两互吸自锁成环 —— 尖冠稳稳扣住躯干。",
)
b.step(
    "探出花苞: 两片等边从层间拼缝外倾 30 度。",
    ["bud_s", "bud_e"],
    highlight=["sg_s_0", "sg_e_1"],
    tip="花苞力矩只有 1.9 —— 远在预算之内, 放心外倾。",
)
b.step(
    "砌红岩台地箱壁: 8 片红墙围合 2x2, 四角互吸。",
    ["rk_s_5", "rk_s_6", "rk_n_5", "rk_n_6",
     "rk_w_1", "rk_w_2", "rk_e_1", "rk_e_2"],
    highlight=["sa_1_5", "sa_2_6"],
    tip="红岩台地是沙漠的地标 —— 箱壁闭环最结实。",
)
b.step(
    "盖岩顶: 4 片橙色方板压壁顶, 拼缝互吸锁成箱体。",
    ["rk_top_5_1", "rk_top_6_1", "rk_top_5_2", "rk_top_6_2"],
    highlight=["rk_s_5", "rk_e_2"],
    tip="每片岩顶都有两条壁顶 + 两条拼缝多路受力。",
)
b.step(
    "立桶形仙人球: 4 片绿墙围成小方箱。",
    ["br_s", "br_n", "br_w", "br_e"],
    highlight=["sa_1_0", "sa_2_0"],
    tip="矮胖的仙人球 —— 沙漠里的储水罐。",
)
b.step(
    "开粉色花冠: 4 片等边四坡合拢, 仙人球开花啦。",
    BR_BLOOM,
    highlight=["br_s", "br_e"],
    tip="花冠四棱互吸自锁, 正压球顶。",
)
b.step(
    "斜插两株幼苗: 底边吸沙面拼缝, 外倾 30 度。",
    ["seedling_a", "seedling_b"],
    highlight=["sa_3_3", "sa_3_5"],
    tip="幼苗歪着头晒太阳 —— 底边磁条一条不落。",
)
b.step(
    "堆砾石: 4 片灰色等边四坡锥 —— 沙漠生机勃勃!",
    STONES,
    highlight=["sa_3_7"],
    tip="砾石四棱互吸自锁 —— 给蜥蜴留个阴凉。",
)

b.finalize(
    model_id="cactus_desert_01",
    name="沙漠仙人掌",
    name_en="Cactus Desert 01",
    description=(
        "全库第一片沙漠造景: 两层箱式巨型萨瓜罗仙人掌戴瘦高四坡"
        "尖冠 (顶尖 3.94 全场最高), 腰间两片等边花苞从层间拼缝外倾"
        " 30 度探出 (力矩 1.9 远在预算内); 东侧红岩平顶台地箱壁闭环"
        "岩顶锁箱, 西角桶形仙人球顶开粉色四坡花冠, 沙面两株外倾"
        "幼苗与一堆四坡砾石 —— 烈日当空, 沙漠也生机勃勃!"
    ),
    difficulty=3,
    tags=["自然", "沙漠", "仙人掌", "造景", "进阶"],
    min_pieces=70,
    min_steps=15,
)
