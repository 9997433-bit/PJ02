#!/usr/bin/env python3
"""生成模型 data/models/elephant_pavilion_01.json (大象馆)。

动物园/野生动物主题批 3/4: 全库第一座"象舍 + 小象 + 淋浴场"的
展馆场景 —— 与 elephant_01 (95 片大象本体: 四腿方柱+头盘桥式受力)
刻意区分, 本作的主角是"象住的房子和洗澡的地方"这组场馆关系:
4x2 象舍南面开 2 格宽象门洞 (横楣双端竖边纯剪锁进二层墙竖棱,
门洞无门框 —— 大象出入不用开门), 北墙二层整排窗格方高窗采光,
4 片红色屋顶长板横跨双墙, 南檐两支橙色等腰馆旗骑墙顶; 场院里
一头小象整装卧姿 —— 2x1 箱式身躯 (墙环+背板处处成环), 立颈
方头昂起, 30 度长鼻坡道从背沿扫地 (鼻尖自己接地, 剪断顶铰链
也掉不下来), 两片粉色大耳 45 度外展, 尾巴骑背板东沿; 东侧
蓝色淋浴池上一座门式淋浴架 (双柱托横板), 两只青色喷头骑板沿
对喷; 象舍边一格绿色草料槽四墙合环, 黄色干草骑槽沿。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 场院地坪 (x [0,7], y [0,4]): 方板 x22 + 长板 x3
    (含 4 片蓝色淋浴池 [5,7]x[2,4]、馆内灰砖)                  25 片
  - 象舍 [0,4]x[2,4] 两层: 一层南墙 2 (中留 2 格门洞) + 北墙 4
    + 山墙 4; 二层南墙 2 + 横楣 1 + 北窗 4 + 山墙 4            21 片
  - 象舍屋顶 (z=2): 4 片红色长板横跨双墙                        4 片
  - 馆旗: 2 支橙色等腰塔尖骑南檐墙顶 (旗尖 4.0 全场最高)        2 片
  - 小象 [2,4]x[0,1]: 身躯墙环 6 + 背板 2 + 立颈方头 1 +
    30 度长鼻坡道 1 + 粉色大耳 x2 + 尾巴 1                     13 片
  - 淋浴架: 双柱 2 + 横板 1 + 青色喷头 x2                       5 片
  - 草料槽 (6,1): 四墙合环 4 + 黄色干草 1                       5 片
  合计 75 片, 15 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 象门横楣: 长方形竖立跨 2 格门洞, 两端竖边分别与二层南墙的
    竖棱纯剪互锁 (重力对竖直铰链轴力矩恒为零), 楣顶与屋顶同高;
  - 屋顶长板: 两短边分别整边压南北墙顶 (双端受力零悬挑), 长边
    拼缝相邻互吸 —— 墙-顶-墙-地坪锁成箱形闭环;
  - 小象长鼻: 30 度坡道顶短边整边吸背板西沿 (与方头底边同线
    互吸), 鼻尖自然扫地 —— 每片自身接地, 剪断顶铰链也掉不下来;
  - 大耳 45 度外展: 力矩 13g x 0.204 = 2.7 g·单位 << strict
    抗弯预算 17.5 g·单位;
  - 淋浴架横板两短边同吸双柱顶, 柱-板-柱-地坪门式刚架环;
  - 馆旗/喷头/干草/尾巴重心正压铰链线, 力矩为零。

用法: python3 tools/generate_elephant_pavilion_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

COS45 = 0.7071068
TRI_H = 0.866025                       # 等边三角形高
EAR_OFF = round(TRI_H * COS45, 6)      # 45 度外展耳的投影 0.612372

b = ModelBuilder()

SAND = "yellow"      # 场院沙地
FLOOR = "gray"       # 馆内地坪
POOL = "blue"        # 淋浴池
WALL = "orange"      # 象舍夯土墙
LINTEL = "orange"    # 象门横楣
WIN = "clear"        # 北墙高窗
ROOF = "red"         # 屋顶
FLAG = "orange"      # 馆旗
ELEP = "gray"        # 小象
EAR = "pink"         # 大耳
MAST = "gray"        # 淋浴架柱
BEAM = "yellow"      # 淋浴架横板
SPRAY = "cyan"       # 喷头
TROUGH = "green"     # 草料槽
HAY = "yellow"       # 干草

# =================================================================
# 1. 场院地坪 (x [0,7], y [0,4]): 25 片
#    馆内 [0,4]x[2,4] 8 片灰砖 (墙脚整边全有吸); 小象场 (2,0)/(3,0)
#    与草料槽坑 (6,1) 用方板; 淋浴池 [5,7]x[2,4] 4 片蓝色方板。
# =================================================================
# 行 y0: 方 x5 + 长板 x1
b.flat("gd_0_0", 0, 0, 0.0, SAND)
b.flat("gd_1_0", 1, 0, 0.0, SAND)
b.flat("el_gd_2", 2, 0, 0.0, SAND)     # 小象西格
b.flat("el_gd_3", 3, 0, 0.0, SAND)     # 小象东格
b.flat("gd_4_0", 4, 0, 0.0, SAND)
b.flat_rect("gd_5_0", 5, 0, 0.0, SAND)
# 行 y1: 长板 + 方 + 方 + 长板 + 槽坑方
b.flat_rect("gd_0_1", 0, 1, 0.0, SAND)
b.flat("gd_2_1", 2, 1, 0.0, SAND)
b.flat("gd_3_1", 3, 1, 0.0, SAND)
b.flat_rect("gd_4_1", 4, 1, 0.0, SAND)
b.flat("gd_6_1", 6, 1, 0.0, SAND)      # 草料槽坑
# 行 y2: 馆内灰砖 x4 + 方 + 淋浴池 x2
b.flat("fl_0_2", 0, 2, 0.0, FLOOR)
b.flat("fl_1_2", 1, 2, 0.0, FLOOR)
b.flat("fl_2_2", 2, 2, 0.0, FLOOR)
b.flat("fl_3_2", 3, 2, 0.0, FLOOR)
b.flat("gd_4_2", 4, 2, 0.0, SAND)
b.flat("pl_5_2", 5, 2, 0.0, POOL)
b.flat("pl_6_2", 6, 2, 0.0, POOL)
# 行 y3: 馆内灰砖 x4 + 方 + 淋浴池 x2
b.flat("fl_0_3", 0, 3, 0.0, FLOOR)
b.flat("fl_1_3", 1, 3, 0.0, FLOOR)
b.flat("fl_2_3", 2, 3, 0.0, FLOOR)
b.flat("fl_3_3", 3, 3, 0.0, FLOOR)
b.flat("gd_4_3", 4, 3, 0.0, SAND)
b.flat("pl_5_3", 5, 3, 0.0, POOL)
b.flat("pl_6_3", 6, 3, 0.0, POOL)

# =================================================================
# 2. 象舍一层 (z 0..1): 南墙中留 2 格象门洞
# =================================================================
b.wall_ns("hs_s0_w", 0, 2.0, 0, WALL)      # 南墙西段 (门洞 x [1,3])
b.wall_ns("hs_s0_e", 3, 2.0, 0, WALL)      # 南墙东段
for x in range(4):
    b.wall_ns(f"hs_n0_{x}", x, 4.0, 0, WALL)
b.wall_ew("hs_w0_2", 0.0, 2, 0, WALL)
b.wall_ew("hs_w0_3", 0.0, 3, 0, WALL)
b.wall_ew("hs_e0_2", 4.0, 2, 0, WALL)
b.wall_ew("hs_e0_3", 4.0, 3, 0, WALL)

# =================================================================
# 3. 象舍二层 (z 1..2): 南墙 + 象门横楣 + 北墙整排高窗
# =================================================================
b.wall_ns("hs_s1_w", 0, 2.0, 1, WALL)
b.wall_ns("hs_s1_e", 3, 2.0, 1, WALL)
b.lintel_ns("hs_lintel", 1, 2.0, 1, LINTEL)    # 象门横楣 x [1,3]
for x in range(4):
    b.add(f"hs_n1_{x}", "window_square", (x + 0.5, 4.0, 1.5), (90, 0, 0), WIN)
b.wall_ew("hs_w1_2", 0.0, 2, 1, WALL)
b.wall_ew("hs_w1_3", 0.0, 3, 1, WALL)
b.wall_ew("hs_e1_2", 4.0, 2, 1, WALL)
b.wall_ew("hs_e1_3", 4.0, 3, 1, WALL)

# =================================================================
# 4. 象舍屋顶 (z=2): 4 片红色长板横跨双墙
# =================================================================
for x in range(4):
    b.flat_rect(f"rf_{x}", x, 2, 2.0, ROOF, axis="y")

# =================================================================
# 5. 馆旗: 2 支橙色等腰塔尖骑南檐墙顶 (x [0,1] 与 [3,4])
# =================================================================
b.spire_ns("flag_w", 0, 2.0, 2.0, FLAG)
b.spire_ns("flag_e", 3, 2.0, 2.0, FLAG)

# =================================================================
# 6. 小象 [2,4]x[0,1]: 箱式身躯 + 立颈方头 + 长鼻坡道 + 大耳 + 尾巴
# =================================================================
b.wall_ns("el_s_2", 2, 0.0, 0, ELEP)
b.wall_ns("el_s_3", 3, 0.0, 0, ELEP)
b.wall_ns("el_n_2", 2, 1.0, 0, ELEP)
b.wall_ns("el_n_3", 3, 1.0, 0, ELEP)
b.wall_ew("el_w", 2.0, 0, 0, ELEP)
b.wall_ew("el_e", 4.0, 0, 0, ELEP)
b.flat("el_bk_2", 2, 0, 1.0, ELEP)         # 背板西
b.flat("el_bk_3", 3, 0, 1.0, ELEP)         # 背板东
b.wall_ew("el_head", 2.0, 0, 1, ELEP)      # 立颈方头 (z 1..2)
b.ramp("el_trunk", "-x", 2.0, 0, 1.0, ELEP)  # 30 度长鼻, 鼻尖扫地
# 粉色大耳: 从背板西格南北沿 45 度外展
b.place_tri("el_ear_n", "equilateral_triangle",
            (2.0, 1.0, 1.0), (3.0, 1.0, 1.0),
            (2.5, round(1.0 + EAR_OFF, 6), round(1.0 + EAR_OFF, 6)), EAR)
b.place_tri("el_ear_s", "equilateral_triangle",
            (3.0, 0.0, 1.0), (2.0, 0.0, 1.0),
            (2.5, round(0.0 - EAR_OFF, 6), round(1.0 + EAR_OFF, 6)), EAR)
b.crest_ew("el_tail", 4.0, 0, 1.0, ELEP)   # 尾巴骑背板东沿

# =================================================================
# 7. 淋浴架 (淋浴池南半 [5,7]x[2,3]): 双柱 + 横板 + 双喷头
# =================================================================
b.wall_ew("sh_w", 5.0, 2, 0, MAST)
b.wall_ew("sh_e", 7.0, 2, 0, MAST)
b.flat_rect("sh_beam", 5, 2, 1.0, BEAM)
b.crest_ew("sh_spray_w", 5.0, 2, 1.0, SPRAY)
b.crest_ew("sh_spray_e", 7.0, 2, 1.0, SPRAY)

# =================================================================
# 8. 草料槽 (6,1): 四墙合环 + 干草骑槽沿
# =================================================================
b.wall_ns("tr_s", 6, 1.0, 0, TROUGH)
b.wall_ns("tr_n", 6, 2.0, 0, TROUGH)
b.wall_ew("tr_w", 6.0, 1, 0, TROUGH)
b.wall_ew("tr_e", 7.0, 1, 0, TROUGH)
b.crest_ns("tr_hay", 6, 1.0, 1.0, HAY)

# =================================================================
# 教程步骤 (15 步)
# =================================================================
b.step(
    "铺场院南半 (y [0,2]): 沙地方板与长板, 小象场与草料槽坑全用方板。",
    ["gd_0_0", "gd_1_0", "el_gd_2", "el_gd_3", "gd_4_0", "gd_5_0",
     "gd_0_1", "gd_2_1", "gd_3_1", "gd_4_1", "gd_6_1"],
    tip="小象和草料槽的墙脚要踩方板整边 —— 先把'地基'铺对。",
)
b.step(
    "铺馆内前排与淋浴池南半 (y [2,3]): 4 片灰砖 + 沙地方板 + 2 片蓝色方板。",
    ["fl_0_2", "fl_1_2", "fl_2_2", "fl_3_2", "gd_4_2", "pl_5_2", "pl_6_2"],
    highlight=["gd_0_1", "gd_6_1"],
    tip="馆内地坪全用方板 —— 象舍的每条墙脚都有整边可吸。",
)
b.step(
    "铺馆内后排与淋浴池北半 (y [3,4]): 场院 7x4 合拢。",
    ["fl_0_3", "fl_1_3", "fl_2_3", "fl_3_3", "gd_4_3", "pl_5_3", "pl_6_3"],
    highlight=["fl_0_2", "pl_6_2"],
    tip="淋浴池 2x2 贴着场院东北角 —— 洗澡水不会溅到干草。",
)
b.step(
    "立象舍一层: 南墙留 2 格象门洞 (x [1,3]), 北墙 4 片、山墙 4 片合环。",
    ["hs_s0_w", "hs_s0_e", "hs_n0_0", "hs_n0_1", "hs_n0_2", "hs_n0_3",
     "hs_w0_2", "hs_w0_3", "hs_e0_2", "hs_e0_3"],
    highlight=["fl_0_2", "fl_3_3"],
    tip="象门洞宽 2 格不装门 —— 大象出入自己说了算。",
)
b.step(
    "立象舍二层南墙与山墙: 南墙两端各 1 片, 东西山墙各 2 片。",
    ["hs_s1_w", "hs_s1_e", "hs_w1_2", "hs_w1_3", "hs_e1_2", "hs_e1_3"],
    highlight=["hs_s0_w", "hs_s0_e"],
    tip="先立两端 —— 横楣的竖边等着跟它们互锁。",
)
b.step(
    "架象门横楣: 长方形竖立跨过门洞, 两端竖边与二层南墙竖棱纯剪互锁。",
    ["hs_lintel"],
    highlight=["hs_s1_w", "hs_s1_e"],
    tip="重力对竖直铰链轴的力矩恒为零 —— 竖边剪切互锁最结实。",
)
b.step(
    "装北墙高窗: 4 扇透明窗格方压上一层北墙顶, 整排采光。",
    ["hs_n1_0", "hs_n1_1", "hs_n1_2", "hs_n1_3"],
    highlight=["hs_n0_0", "hs_n0_3"],
    tip="高窗让阳光照进象舍 —— 大象也要晒太阳补钙。",
)
b.step(
    "盖屋顶: 4 片红色长板横跨南北墙 (两短边压墙顶), 长边拼缝互吸。",
    ["rf_0", "rf_1", "rf_2", "rf_3"],
    highlight=["hs_lintel", "hs_n1_0"],
    tip="每片双端受力零悬挑 —— 墙-顶-墙-地坪锁成箱形闭环。",
)
b.step(
    "升馆旗: 2 支橙色等腰塔尖骑南檐墙顶 (旗尖 4.0, 全场最高)。",
    ["flag_w", "flag_e"],
    highlight=["rf_0", "rf_3"],
    tip="双旗夹着象门 —— 重心正压墙顶线, 力臂为零。",
)
b.step(
    "拼小象身躯: 6 片灰墙围出 2x1 箱身, 2 片背板压顶 (处处成环)。",
    ["el_s_2", "el_s_3", "el_n_2", "el_n_3", "el_w", "el_e",
     "el_bk_2", "el_bk_3"],
    highlight=["el_gd_2", "el_gd_3"],
    tip="背板每片同时吸三段墙顶加一条拼缝 —— 小象的背最结实。",
)
b.step(
    "立颈昂头 + 长鼻扫地: 方头立在背板西沿, 30 度长鼻坡道从同一条沿"
    "滑到地面。",
    ["el_head", "el_trunk"],
    highlight=["el_bk_2"],
    tip="头与长鼻共吸一条沿口 —— 鼻尖自己接地, 剪断顶铰链也掉不下来。",
)
b.step(
    "展大耳 + 翘尾巴: 2 片粉色等边三角从背沿 45 度外展, 尾巴骑背板东沿。",
    ["el_ear_n", "el_ear_s", "el_tail"],
    highlight=["el_head"],
    tip="外展力矩只有 2.7 g·单位 —— 大耳扇起来也不会掉。",
)
b.step(
    "立淋浴架: 双柱踩池沿, 黄色横板两短边同吸柱顶 —— 门式刚架跨过淋浴池。",
    ["sh_w", "sh_e", "sh_beam"],
    highlight=["pl_5_2", "pl_6_2"],
    tip="柱-板-柱-地坪锁成环 —— 剪断任一端, 另一端立柱仍接地。",
)
b.step(
    "装喷头: 2 只青色等边三角骑横板两端 (板沿+柱顶一线双吸), 对喷冲澡。",
    ["sh_spray_w", "sh_spray_e"],
    highlight=["sh_beam"],
    tip="洗澡是大象每天最快乐的事 —— 水花从两边一起来。",
)
b.step(
    "装草料槽: 4 片绿墙合环, 黄色干草骑槽沿 —— 开饭啦!",
    ["tr_s", "tr_n", "tr_w", "tr_e", "tr_hay"],
    highlight=["el_trunk"],
    tip="槽紧挨着小象场 —— 长鼻子一伸就够到干草。",
)

b.finalize(
    model_id="elephant_pavilion_01",
    name="大象馆",
    name_en="Elephant Pavilion 01",
    description=(
        "只用核心九片型的大象展馆场景: 4x2 象舍南面开 2 格宽象门洞"
        " —— 横楣两端竖边与二层南墙竖棱纯剪互锁 (竖直铰链轴力矩恒"
        "为零), 北墙二层整排窗格方高窗, 4 片红色屋顶长板横跨双墙"
        "双端受力, 南檐双馆旗骑墙顶直上 4.0; 场院里一头小象整装:"
        " 2x1 箱式身躯处处成环, 立颈方头昂起, 30 度长鼻坡道从背沿"
        "扫地 (鼻尖自己接地), 粉色大耳 45 度外展 (力矩 2.7 远小于"
        "预算), 尾巴骑背板东沿; 东侧蓝色淋浴池上门式淋浴架双喷头"
        "对喷, 象舍边草料槽四墙合环干草骑沿 —— 冲完澡, 开饭啦!"
    ),
    difficulty=3,
    tags=["动物园", "野生动物", "大象", "场馆", "进阶"],
    min_pieces=75,
    min_steps=15,
)
