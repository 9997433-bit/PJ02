#!/usr/bin/env python3
"""生成模型 data/models/whale_watching_01.json (观鲸瞭望站)。

水下/海洋主题: 与 whale_01 (纯鲸鱼造型) 刻意区分 —— 本作的主角是
"岸上的人看海里的鲸" 这组场景关系: 海陆各半的 5x4 地面上, 东侧
崖顶起 2x2 观景台 (环墙 + 满铺台面 + 女儿墙护齿), 台上再拔一座
1x1 双层瞭望塔 (窗格方观察窗 + 平顶护齿瞭望位), 一条 30 度木栈道
从台面直下海滩 (坡尾落在预留的空水格); 西侧海湾里一头 2x1 蓝鲸
弓背出水 —— 壳体环墙 + 背板 + 等腰高尾鳍 (鳍尖 3.0) + 喷水柱,
海面拼缝上再立两朵浪花。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 地面 (x [0,5], y [0,4]): 海面 (青) + 沙滩草地 (黄/绿) 满铺,
    x [1,2] x y [1,2] 留空给栈道坡尾                             19 片
  - 观景台 (x [3,5], y [1,3], z 0..1): 环墙 x8 + 台面 x4 +
    女儿墙护齿 x4                                                16 片
  - 瞭望塔 (x [4,5], y [1,2], z 1..3): 两层墙环 x8 (含窗格方 x3)
    + 塔顶盖板 x1 + 顶沿护齿 x4 (顶齿 3.58)                      13 片
  - 木栈道: 30 度长方形 x1 (顶边吸台面西沿, 坡尾落空水格)          1 片
  - 蓝鲸 (x [0,2], y [2,3], z 0..1): 壳体环墙 x6 + 背板 x2 +
    尾鳍等腰塔尖 x1 (鳍尖 3.0) + 喷水柱等边三角 x1               10 片
  - 浪花: 直角三角 x2 (海面拼缝)                                  2 片
  合计 61 片, 14 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点:
  - 观景台环墙四角互吸闭环, 台面每片同时压墙顶与邻板拼缝;
  - 瞭望塔两层墙环踩台面拼缝层层互吸, 盖板四边全吸, 顶齿骑沿;
  - 栈道顶边一线双吸 (台面西沿 + 环墙顶), 坡尾落在预留空水格
    的实地上, 不与鲸和水面板相交;
  - 蓝鲸壳体踩海面拼缝, 背板压壳顶, 尾鳍/喷水柱骑沿口共面零力矩。

用法: python3 tools/generate_whale_watching_01.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

SEA = "cyan"        # 海面
BEACH = "yellow"    # 沙滩
GRASSLAND = "green" # 崖顶草地
CLIFF = "gray"      # 观景台环墙 (石崖)
DECKT = "green"     # 台面草地
CREST = "yellow"    # 女儿墙护齿
TOWER = "blue"      # 瞭望塔
WIN = "clear"       # 窗格方观察窗
CAP = "gray"        # 塔顶盖板
RAMP = "gray"       # 木栈道
WHALE = "blue"      # 蓝鲸
SPOUT = "clear"     # 喷水柱
WAVE = "cyan"       # 浪花

# =================================================================
# 1. 地面 (x [0,5], y [0,4]): 西海东岸; x [1,2] x y [1,2] 留空
#    (栈道坡尾落地格), 海陆分界在 x=2
# =================================================================
def ground_color(x, y):
    if x < 2:
        return SEA
    return BEACH if y < 2 else GRASSLAND

for x in range(5):
    b.flat(f"gd_{x}_0", x, 0, 0.0, ground_color(x, 0))
for x in (0, 2, 3, 4):
    b.flat(f"gd_{x}_1", x, 1, 0.0, ground_color(x, 1))
for x in range(5):
    b.flat(f"gd_{x}_2", x, 2, 0.0, ground_color(x, 2))
for x in range(5):
    b.flat(f"gd_{x}_3", x, 3, 0.0, ground_color(x, 3))

# =================================================================
# 2. 观景台 (x [3,5], y [1,3], z 0..1): 石崖环墙 + 草地台面 + 护齿
# =================================================================
b.wall_ns("vt_s_3", 3, 1.0, 0, CLIFF)
b.wall_ns("vt_s_4", 4, 1.0, 0, CLIFF)
b.wall_ew("vt_w_1", 3.0, 1, 0, CLIFF)
b.wall_ew("vt_w_2", 3.0, 2, 0, CLIFF)
b.wall_ns("vt_n_3", 3, 3.0, 0, CLIFF)
b.wall_ns("vt_n_4", 4, 3.0, 0, CLIFF)
b.wall_ew("vt_e_1", 5.0, 1, 0, CLIFF)
b.wall_ew("vt_e_2", 5.0, 2, 0, CLIFF)
for x in (3, 4):
    for y in (1, 2):
        b.flat(f"vt_d_{x}_{y}", x, y, 1.0, DECKT)
b.crest_ns("vt_c_n1", 3, 3.0, 1.0, CREST)
b.crest_ns("vt_c_n2", 4, 3.0, 1.0, CREST)
b.crest_ew("vt_c_e", 5.0, 2, 1.0, CREST)
b.crest_ns("vt_c_s", 3, 1.0, 1.0, CREST)

# =================================================================
# 3. 瞭望塔 (x [4,5], y [1,2], z 1..3): 两层墙环 + 盖板 + 顶齿
#    第 1 层西面窗看栈道, 第 2 层西/北双窗看海
# =================================================================
b.wall_ns("tw1_s", 4, 1.0, 1, TOWER)
b.wall_ns("tw1_n", 4, 2.0, 1, TOWER)
b.add("tw1_w", "window_square", (4.0, 1.5, 1.5), (90, 0, 90), WIN)
b.wall_ew("tw1_e", 5.0, 1, 1, TOWER)
b.wall_ns("tw2_s", 4, 1.0, 2, TOWER)
b.add("tw2_n", "window_square", (4.5, 2.0, 2.5), (90, 0, 0), WIN)
b.add("tw2_w", "window_square", (4.0, 1.5, 2.5), (90, 0, 90), WIN)
b.wall_ew("tw2_e", 5.0, 1, 2, TOWER)
b.flat("tw_cap", 4, 1, 3.0, CAP)
b.crest_ns("tw_c_s", 4, 1.0, 3.0, CREST)
b.crest_ns("tw_c_n", 4, 2.0, 3.0, CREST)
b.crest_ew("tw_c_w", 4.0, 1, 3.0, CREST)
b.crest_ew("tw_c_e", 5.0, 1, 3.0, CREST)

# =================================================================
# 4. 木栈道: 顶边吸台面西沿, 坡尾落在预留空水格 (x [1,2] x y [1,2])
# =================================================================
b.ramp("ramp", "-x", 3.0, 1, 1.0, RAMP)

# =================================================================
# 5. 蓝鲸 (x [0,2], y [2,3], z 0..1): 壳体 + 背板 + 尾鳍 + 喷水柱
# =================================================================
b.wall_ns("wh_s_0", 0, 2.0, 0, WHALE)
b.wall_ns("wh_s_1", 1, 2.0, 0, WHALE)
b.wall_ns("wh_n_0", 0, 3.0, 0, WHALE)
b.wall_ns("wh_n_1", 1, 3.0, 0, WHALE)
b.wall_ew("wh_w", 0.0, 2, 0, WHALE)
b.wall_ew("wh_e", 2.0, 2, 0, WHALE)
b.flat("wh_b_0", 0, 2, 1.0, WHALE)
b.flat("wh_b_1", 1, 2, 1.0, WHALE)
b.spire_ew("wh_tail", 0.0, 2, 1.0, WHALE)
b.crest_ew("wh_spout", 2.0, 2, 1.0, SPOUT)

# =================================================================
# 6. 浪花: 直角三角立在海面拼缝
# =================================================================
b.place_tri("wave_s", "right_triangle", (0, 1, 0), (1, 1, 0), (0, 1, 1), WAVE)
b.place_tri("wave_n", "right_triangle", (2, 3, 0), (3, 3, 0), (2, 3, 1), WAVE)

# =================================================================
# 教程步骤 (14 步)
# =================================================================
b.step(
    "铺地面南行 (y [0,1]): 5 片 —— 西边是海, 东边是沙滩。",
    [f"gd_{x}_0" for x in range(5)],
    tip="海陆分界在 x=2: 青色向西, 黄色向东。",
)
b.step(
    "铺地面第二行 (y [1,2]): 4 片, x [1,2] 留一格空水面。",
    ["gd_0_1", "gd_2_1", "gd_3_1", "gd_4_1"],
    highlight=["gd_0_0"],
    tip="留空的水格是木栈道的落脚点 —— 先留位, 后搭桥。",
)
b.step(
    "铺地面第三行 (y [2,3]): 5 片 —— 崖顶草地从这里向东铺开。",
    [f"gd_{x}_2" for x in range(5)],
    highlight=["gd_2_1"],
    tip="蓝鲸一会儿就停在这一行的西侧海湾。",
)
b.step(
    "铺地面北行 (y [3,4]): 5 片, 地面合拢。",
    [f"gd_{x}_3" for x in range(5)],
    highlight=["gd_0_2"],
    tip="5x4 海陆各半 —— 观鲸的舞台就绪。",
)
b.step(
    "砌观景台南墙与西墙: 4 片石崖立墙踩拼缝。",
    ["vt_s_3", "vt_s_4", "vt_w_1", "vt_w_2"],
    highlight=["gd_3_1", "gd_3_2"],
    tip="观景台是垫高的崖顶 —— 每片底边吸缝、侧边咬邻片。",
)
b.step(
    "砌观景台北墙与东墙: 4 片, 环墙闭合。",
    ["vt_n_3", "vt_n_4", "vt_e_1", "vt_e_2"],
    highlight=["vt_s_3", "vt_w_2"],
    tip="闭合环墙是崖体的骨架 —— 轻推应整体联动。",
)
b.step(
    "铺台面: 4 片草地方板压墙顶。",
    ["vt_d_3_1", "vt_d_3_2", "vt_d_4_1", "vt_d_4_2"],
    highlight=["vt_s_4", "vt_n_3"],
    tip="每片同时吸两段墙顶与邻板拼缝 —— 台面就是新地面。",
)
b.step(
    "搭木栈道 + 立台沿护齿: 30 度栈道顶边吸台面西沿, 4 片护齿骑沿口。",
    ["ramp", "vt_c_n1", "vt_c_n2", "vt_c_e", "vt_c_s"],
    highlight=["vt_d_3_1", "vt_d_3_2"],
    tip="栈道一线双吸 (台面沿 + 环墙顶), 坡尾正落预留空水格。",
)
b.step(
    "起瞭望塔第 1 层: 4 片蓝色墙环踩台面拼缝, 西面嵌观察窗。",
    ["tw1_s", "tw1_n", "tw1_w", "tw1_e"],
    highlight=["vt_d_4_1"],
    tip="瞭望塔踞守东南角, 观察窗正对栈道与海湾。",
)
b.step(
    "叠瞭望塔第 2 层: 4 片, 西/北双窗看海。",
    ["tw2_s", "tw2_n", "tw2_w", "tw2_e"],
    highlight=["tw1_w"],
    tip="站得高看得远 —— 鲸群从西北方向来。",
)
b.step(
    "封塔顶 + 立顶沿护齿: 盖板四边全吸, 4 片护齿围出瞭望位 (顶齿 3.58)。",
    ["tw_cap", "tw_c_s", "tw_c_n", "tw_c_w", "tw_c_e"],
    highlight=["tw2_s", "tw2_n"],
    tip="护齿就是瞭望位的栏杆 —— 望远镜架在这里。",
)
b.step(
    "拼蓝鲸壳体: 6 片蓝色立墙踩海面拼缝, 弓背环闭合。",
    ["wh_s_0", "wh_s_1", "wh_n_0", "wh_n_1", "wh_w", "wh_e"],
    highlight=["gd_0_2", "gd_1_2"],
    tip="2x1 壳体是鲸的身躯 —— 四角互吸, 稳稳浮在海湾。",
)
b.step(
    "盖鲸背 + 装喷水柱: 2 片背板压壳顶, 透明三角骑头沿。",
    ["wh_b_0", "wh_b_1", "wh_spout"],
    highlight=["wh_s_0", "wh_n_1"],
    tip="透明喷水柱 —— 鲸鱼换气的瞬间!",
)
b.step(
    "竖尾鳍 + 立浪花: 等腰尾鳍直上 3.0, 2 片浪花点在拼缝 —— 观鲸站落成!",
    ["wh_tail", "wave_s", "wave_n"],
    highlight=["wh_b_0", "gd_2_2"],
    tip="尾鳍拍浪、浪花四溅 —— 瞭望塔上的孩子们欢呼起来。",
)

b.finalize(
    model_id="whale_watching_01",
    name="观鲸瞭望站",
    name_en="Whale Watching Station 01",
    description=(
        "只用核心九片型的观鲸场景: 5x4 海陆各半的地面上, 东侧崖顶"
        "起 2x2 观景台 (石崖环墙 + 草地台面 + 女儿墙护齿), 台上再"
        "拔 1x1 双层瞭望塔 (三扇窗格方观察窗 + 平顶护齿瞭望位,"
        " 顶齿 3.58), 30 度木栈道从台面直下海滩预留空水格; 西侧"
        "海湾一头 2x1 蓝鲸弓背出水 —— 壳体环墙 + 背板 + 等腰高"
        "尾鳍 (鳍尖 3.0) + 透明喷水柱, 海面拼缝再立两朵浪花。"
        "岸上瞭望、海里鲸跃 —— 一组会讲故事的场景模型。"
    ),
    difficulty=3,
    tags=["海洋", "观鲸", "瞭望塔", "海岸", "进阶"],
    min_pieces=58,
    min_steps=14,
)
