#!/usr/bin/env python3
"""生成模型 data/models/airport_terminal_02.json (登机廊桥航站楼)。

机场航空主题 2/4: 全库第一条 "高架玻璃登机廊桥" —— 与
airport_terminal_01 (玻璃前脸大厅 + 贴建控制塔 + 观景四坡顶) 与
ferry_terminal_01 (桩柱托栈桥 + 渡轮) 的结构逻辑刻意区分: 这一座
的主角不是大厅而是廊桥 —— 两层候机厅的二层东墙开出 1 格廊桥口,
玻璃管廊桥 (长板地板 + 长板玻璃护壁 + 长板顶盖) 由两根桥墩接力
托举, 每段地板双端受力如桥, 末端 30 度登机坡道直下停机位;
大厅门前透明雨棚成对共铰平挑, 楼下一列行李牵引车 (车轮底座
拖头 + 拖斗) 正沿廊桥下方驶向机坪 —— 旅客在玻璃管里走向蓝天!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 大门朝南):
  - 站坪 9x5 (x [0,9], y [0,5]): 方板 + 长板混铺, 含行李
    牵引车拖头/拖斗两片车轮底座                                29 片
  - 候机厅一层 (x [1,4], y [1,4], z 0..1): 南面门框方大门 +
    西北长楣 + 东墙 3 片单元墙 (预留廊桥承口)                  10 片
  - 候机厅二层 (z 1..2): 南面窗格方带 x3 + 西北透明长楣 +
    窗格方 x2 + 东面窗格方 x2 (正中留廊桥口)                    9 片
  - 大厅屋面 (z=2): 长板 + 方板 3 行                            6 片
  - 大门雨棚 (z=1): 透明方板 x2 (成对共铰, 力矩 30 <= 35)       2 片
  - 登机廊桥 (z 1..2): 桥墩 x2 + 长板地板 x2 + 玻璃长板
    护壁 x4 + 长板顶盖 x2                                      10 片
  - 登机坡道: 30 度长板 x1 (顶边一线双吸, 坡尾落停机位)          1 片
  - 行李车队装饰: 车头 + 行李堆等边三角 x3                       3 片
  - 停机位引导标: 等边三角 x2                                    2 片
  合计 72 片, 14 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, strict 档同样全绿):
  - 廊桥每段地板西端吸大厅东墙顶边/前段桥墩顶边、东端吸下一根
    桥墩顶边 —— 双端受力零悬挑; 玻璃护壁底边整边吸地板长边,
    顶盖再压护壁顶边, 管状截面处处成环;
  - 雨棚两片成对共铰 (铰链线长 2) 且互咬拼缝: 力矩 60 x 0.5 =
    30 <= 严格档预算 35, 与楼顶挑板同款技法;
  - 登机坡道顶边同时吸廊桥地板东短边与末端桥墩顶边, 坡尾接地;
  - 全场最高点 2.0, 每个中间步骤单一连通体、重心始终在站坪内。

用法: python3 tools/generate_airport_terminal_02.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

APRON = "gray"      # 站坪
ROAD = "gray"       # 行车道
MARK = "yellow"     # 机位标线
HALL = "blue"       # 候机厅墙体
DOOR = "yellow"     # 出发大门
WIN = "clear"       # 窗格方
GLASS = "clear"     # 透明长楣 / 玻璃护壁 / 雨棚
ROOF = "blue"       # 大厅屋面
PIER = "gray"       # 廊桥桥墩
FLOOR = "yellow"    # 廊桥地板
BRIDGE_ROOF = "blue"  # 廊桥顶盖
RAMP = "yellow"     # 登机坡道
TUG = "red"         # 牵引车头
BAG1 = "yellow"     # 行李堆
BAG2 = "cyan"       # 行李堆
GUIDE = "yellow"    # 引导标

# =================================================================
# 1. 站坪 9x5 (x [0,9], y [0,5]): 行李车队嵌进南行车道
# =================================================================
b.flat_rect("m0_a", 0, 0, 0.0, ROAD)
b.flat_rect("m0_b", 2, 0, 0.0, ROAD)
b.flat("m0_c", 4, 0, 0.0, ROAD)
b.add("tug_head", "wheel_base", (6.0, 0.5, 0.0), (0, 0, 0), TUG)   # 拖头 x [5,7]
b.add("tug_cart", "wheel_base", (8.0, 0.5, 0.0), (0, 0, 0), "cyan")  # 拖斗 x [7,9]

b.flat("m1_a", 0, 1, 0.0, APRON)
b.flat_rect("m1_b", 1, 1, 0.0, APRON)
b.flat_rect("m1_c", 3, 1, 0.0, APRON)
b.flat("m1_d", 5, 1, 0.0, APRON)      # 单元方板: 给车队装饰留整边
b.flat("m1_d2", 6, 1, 0.0, APRON)
b.flat("m1_e", 7, 1, 0.0, APRON)
b.flat("m1_e2", 8, 1, 0.0, APRON)

b.flat("m2_a", 0, 2, 0.0, APRON)
b.flat_rect("m2_b", 1, 2, 0.0, APRON)
b.flat_rect("m2_c", 3, 2, 0.0, APRON)
b.flat("m2_d", 5, 2, 0.0, APRON)
b.flat_rect("m2_e", 6, 2, 0.0, MARK)    # 廊桥下机位标线
b.flat("m2_f", 8, 2, 0.0, MARK)

b.flat("m3_a", 0, 3, 0.0, APRON)
b.flat_rect("m3_b", 1, 3, 0.0, APRON)
b.flat_rect("m3_c", 3, 3, 0.0, APRON)
b.flat_rect("m3_d", 5, 3, 0.0, APRON)
b.flat_rect("m3_e", 7, 3, 0.0, APRON)

b.flat("m4_a", 0, 4, 0.0, APRON)
b.flat_rect("m4_b", 1, 4, 0.0, APRON)
b.flat_rect("m4_c", 3, 4, 0.0, APRON)
b.flat_rect("m4_d", 5, 4, 0.0, APRON)
b.flat("m4_e", 7, 4, 0.0, APRON)      # 单元方板: 给引导标留整边
b.flat("m4_e2", 8, 4, 0.0, APRON)

# =================================================================
# 2. 候机厅一层 (x [1,4], y [1,4], z 0..1)
# =================================================================
b.wall_ns("h1_s1", 1, 1.0, 0, HALL)
b.add("h1_door", "door_frame", (2.5, 1.0, 0.5), (90, 0, 0), DOOR)
b.wall_ns("h1_s2", 3, 1.0, 0, HALL)
b.lintel_ew("h1_w", 1.0, 1, 0, HALL)
b.wall_ew("h1_w2", 1.0, 3, 0, HALL)
b.lintel_ns("h1_n", 1, 4.0, 0, HALL)
b.wall_ns("h1_n2", 3, 4.0, 0, HALL)
b.wall_ew("h1_e1", 4.0, 1, 0, HALL)
b.wall_ew("h1_e2", 4.0, 2, 0, HALL)    # 廊桥承口墙
b.wall_ew("h1_e3", 4.0, 3, 0, HALL)

# =================================================================
# 3. 候机厅二层 (z 1..2): 东面正中留 1 格廊桥口
# =================================================================
b.add("h2_s1", "window_square", (1.5, 1.0, 1.5), (90, 0, 0), WIN)
b.add("h2_s2", "window_square", (2.5, 1.0, 1.5), (90, 0, 0), WIN)
b.add("h2_s3", "window_square", (3.5, 1.0, 1.5), (90, 0, 0), WIN)
b.lintel_ew("h2_w", 1.0, 1, 1, GLASS)
b.add("h2_w2", "window_square", (1.0, 3.5, 1.5), (90, 0, 90), WIN)
b.lintel_ns("h2_n", 1, 4.0, 1, GLASS)
b.add("h2_n2", "window_square", (3.5, 4.0, 1.5), (90, 0, 0), WIN)
b.add("h2_e1", "window_square", (4.0, 1.5, 1.5), (90, 0, 90), WIN)
b.add("h2_e2", "window_square", (4.0, 3.5, 1.5), (90, 0, 90), WIN)

# =================================================================
# 4. 大厅屋面 (z=2) + 大门雨棚 (z=1)
# =================================================================
b.flat_rect("r_s", 1, 1, 2.0, ROOF)
b.flat("r_s2", 3, 1, 2.0, ROOF)
b.flat_rect("r_m", 1, 2, 2.0, ROOF)
b.flat("r_m2", 3, 2, 2.0, ROOF)
b.flat_rect("r_n", 1, 3, 2.0, ROOF)
b.flat("r_n2", 3, 3, 2.0, ROOF)

b.flat("cano_w", 1, 0, 1.0, GLASS)
b.flat("cano_e", 2, 0, 1.0, GLASS)

# =================================================================
# 5. 登机廊桥 (y [2,3], x 4..8, z 1..2) + 登机坡道
# =================================================================
b.wall_ew("pier_1", 6.0, 2, 0, PIER)
b.wall_ew("pier_2", 8.0, 2, 0, PIER)
b.flat_rect("bf_w", 4, 2, 1.0, FLOOR)
b.flat_rect("bf_e", 6, 2, 1.0, FLOOR)
b.lintel_ns("bg_s1", 4, 2.0, 1, GLASS)
b.lintel_ns("bg_s2", 6, 2.0, 1, GLASS)
b.lintel_ns("bg_n1", 4, 3.0, 1, GLASS)
b.lintel_ns("bg_n2", 6, 3.0, 1, GLASS)
b.flat_rect("br_w", 4, 2, 2.0, BRIDGE_ROOF)
b.flat_rect("br_e", 6, 2, 2.0, BRIDGE_ROOF)
b.ramp("board_ramp", "+x", 8.0, 2, 1.0, RAMP)

# =================================================================
# 6. 行李车队装饰 + 停机位引导标
# =================================================================
b.crest_ns("tug_cab", 5, 1.0, 0.0, TUG)      # 车头驾驶棚
b.crest_ns("bag_1", 7, 1.0, 0.0, BAG1)       # 行李堆
b.crest_ns("bag_2", 8, 1.0, 0.0, BAG2)
b.crest_ns("guide_1", 7, 4.0, 0.0, GUIDE)    # 引导标
b.crest_ns("guide_2", 8, 4.0, 0.0, GUIDE)

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺南行车道 (y [0,1]): 5 片, 东段两片车轮底座是行李拖头与拖斗。",
    ["m0_a", "m0_b", "m0_c", "tug_head", "tug_cart"],
    tip="车轮底座嵌进车道: 行李车队与站坪天生连成一体。",
)
b.step(
    "铺车队北侧一行 (y [1,2]): 7 片, 东段改用单元方板咬住车队。",
    ["m1_a", "m1_b", "m1_c", "m1_d", "m1_d2", "m1_e", "m1_e2"],
    highlight=["m0_b"],
    tip="单元方板的整边正好吸住行李堆与车头驾驶棚的底边。",
)
b.step(
    "铺廊桥地带 (y [2,3]): 6 片, 黄色标线正指登机位。",
    ["m2_a", "m2_b", "m2_c", "m2_d", "m2_e", "m2_f"],
    highlight=["m1_d"],
    tip="x=6 与 x=8 的拼缝要留给廊桥桥墩。",
)
b.step(
    "铺站坪北带 (y [3,5]): 11 片, 候机厅地基合拢。",
    ["m3_a", "m3_b", "m3_c", "m3_d", "m3_e",
     "m4_a", "m4_b", "m4_c", "m4_d", "m4_e", "m4_e2"],
    highlight=["m2_e"],
    tip="9x5 站坪铺满, 大厅与廊桥都踩在整片地基上。",
)
b.step(
    "砌候机厅一层南墙与西墙: 5 片, 正中门框方是出发大门。",
    ["h1_s1", "h1_door", "h1_s2", "h1_w", "h1_w2"],
    highlight=["m1_b"],
    tip="大门骑南沿拼缝, 西墙用整片长楣 —— 竖缝越少墙越整。",
)
b.step(
    "砌候机厅一层北墙与东墙: 5 片, 东墙三片单元墙留好廊桥承口。",
    ["h1_n", "h1_n2", "h1_e1", "h1_e2", "h1_e3"],
    highlight=["h1_s1"],
    tip="东墙正中那片的顶边就是廊桥地板的西支座。",
)
b.step(
    "立二层南面窗带与东面窗格: 5 片, 东面正中留出廊桥口。",
    ["h2_s1", "h2_s2", "h2_s3", "h2_e1", "h2_e2"],
    highlight=["h1_door", "h1_e2"],
    tip="旅客从二层直接走进玻璃廊桥 —— 洞口是负空间, 不用补片。",
)
b.step(
    "立二层西面与北面: 透明长楣 x2 + 窗格方 x2。",
    ["h2_w", "h2_w2", "h2_n", "h2_n2"],
    highlight=["h2_s1"],
    tip="透明长楣一片顶两格, 二层环墙四角竖边互吸闭合。",
)
b.step(
    "盖大厅屋面 (z=2): 3 行 6 片, 先落东南角方板再接长板。",
    ["r_s2", "r_s", "r_m", "r_m2", "r_n", "r_n2"],
    highlight=["h2_w", "h2_n"],
    tip="屋面东沿与廊桥顶盖同高 —— 天际线一步到位。",
)
b.step(
    "平挑大门雨棚: 2 片透明方板成对共铰、互咬拼缝。",
    ["cano_w", "cano_e"],
    highlight=["h1_door", "h2_s2"],
    tip="力矩 30 <= 严格档预算 35, 与楼顶挑板同款技法。",
)
b.step(
    "立桥墩并架廊桥地板: 每段地板双端受力如桥。",
    ["pier_1", "pier_2", "bf_w", "bf_e"],
    highlight=["h1_e2", "m2_e"],
    tip="西段搭在大厅东墙顶与 1 号墩上, 东段接力到 2 号墩 —— 零悬挑。",
)
b.step(
    "装玻璃护壁: 4 片透明长板底边整边吸地板长边。",
    ["bg_s1", "bg_n1", "bg_s2", "bg_n2"],
    highlight=["bf_w", "bf_e"],
    tip="护壁与大厅二层窗格的竖边在廊桥口互吸 —— 楼桥锁成一体。",
)
b.step(
    "盖廊桥顶盖并放登机坡道: 玻璃管合拢, 坡尾落在停机位。",
    ["br_w", "br_e", "board_ramp"],
    highlight=["bg_s1", "bg_s2"],
    tip="坡道顶边同时吸地板东短边与 2 号墩顶边, 一线双吸。",
)
b.step(
    "摆行李车队与引导标: 车头驾驶棚 + 行李堆 + 停机位引导标。",
    ["tug_cab", "bag_1", "bag_2", "guide_1", "guide_2"],
    highlight=["tug_head", "tug_cart"],
    tip="行李车沿廊桥下驶向机坪 —— 登机廊桥航站楼投入运营!",
)

b.finalize(
    model_id="airport_terminal_02",
    name="登机廊桥航站楼",
    name_en="Boarding Bridge Terminal 02",
    description=(
        "全库第一条高架玻璃登机廊桥: 两层候机厅 (门框方大门 + 整圈窗格"
        "方候机窗带) 的二层东墙开出廊桥口, 玻璃管廊桥由两根桥墩接力托举"
        " —— 每段长板地板双端受力如桥, 玻璃护壁底边整边吸地板长边、顶盖"
        "再压护壁顶边, 管状截面处处成环; 末端 30 度登机坡道一线双吸直下"
        "停机位; 大门透明雨棚成对共铰平挑 (力矩 30 <= 35), 廊桥下行李"
        "牵引车队 (车轮底座拖头 + 拖斗) 正驶向机坪。"
    ),
    difficulty=3,
    tags=["机场", "航空", "廊桥", "交通", "进阶"],
    min_pieces=70,
    min_steps=14,
)
