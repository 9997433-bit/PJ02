#!/usr/bin/env python3
"""生成模型 data/models/lego_style_house_01.json (别墅小屋)。

第三批模型 ⑦: 经典盒式建筑主题 —— 花园别墅小屋: 6x5 草坪上,
一座 2x2 两层主楼 (长方形圈层砌法) 戴梯形四坡屋顶与烟囱,
东侧接一间 1 格进深的门厅侧翼 —— 檐口横楣跨过大门成楣,
顶上 60 度人字坡屋面与等边山花合脊; 院子里狗窝、绿篱、
小树与花丛一应俱全, 是磁力片盒式搭建的标准教科书。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 草坪 6x5: 方板 18 + 环屋步道/室内地坪长板 6             24 片
  - 主楼: 长方形圈层 x2 层 8 + 梯形四坡顶 5 + 烟囱 1        14 片
  - 门厅侧翼: 墙体 4 (南面留门) + 山墙 1 + 檐口横楣 2        7 片
  - 人字坡屋面: 60 度长方形 x2 + 等边山花 x2                 4 片
  - 狗窝 (等腰四坡小屋) 4 + 绿篱 4 + 小树 2 + 花丛 2        12 片
  合计 61 片, 17 个教程步骤, 6 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 主楼长方形圈层四角竖边咬合 (吊桥城堡主楼同款), 梯形四坡
    屋顶下底长 2 恰与长方形墙顶边等长贴合;
  - 侧翼檐口横楣西端竖边吸主楼二层竖边、东端竖边吸山墙竖边,
    南面大门由南檐口横楣自然成楣 (负空间门洞);
  - 人字坡屋面 60 度斜置, 底长边吸檐口顶边, 脊线两长边互吸,
    等边山花两腰与坡面短边严丝合缝 (中央火车站同款技法)。

用法: python3 tools/generate_lego_style_house.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

RIDGE_H = 0.866025          # 等边山花高 = 60 度坡面竖直投影

# =================================================================
# 1. 草坪 6x5: 绿色草地 + 入户步道; 主楼地基一圈用灰色长板铺成
#    环屋步道 —— 长板长边与主楼长方形墙底边等长, 圈层墙体从
#    第一片起就与地面磁力连通
# =================================================================
PATH = {(3, 0)}
SQUARES = [(0, 0), (3, 0), (4, 0), (5, 0),
           (4, 1), (5, 1), (4, 2), (5, 2),
           (0, 3), (3, 3), (4, 3), (5, 3),
           (0, 4), (1, 4), (2, 4), (3, 4), (4, 4), (5, 4)]
for i, j in SQUARES:
    b.flat(f"lw_{i}_{j}", i, j, 0.0, "gray" if (i, j) in PATH else "green")
b.flat_rect("lr_s", 1, 0, 0.0, "gray", axis="x")     # 环屋步道南段 (1..3, 0..1)
b.flat_rect("lr_n", 1, 3, 0.0, "gray", axis="x")     # 环屋步道北段 (1..3, 3..4)
b.flat_rect("lr_w", 0, 1, 0.0, "gray", axis="y")     # 环屋步道西段 (0..1, 1..3)
b.flat_rect("lr_e", 3, 1, 0.0, "gray", axis="y")     # 环屋步道东段 (3..4, 1..3)
b.flat_rect("lr_f0", 1, 1, 0.0, "green", axis="x")   # 主楼室内地坪 (1..3, 1..2)
b.flat_rect("lr_f1", 1, 2, 0.0, "green", axis="x")   # 主楼室内地坪 (1..3, 2..3)

# =================================================================
# 2. 主楼 2x2 (x 1..3, y 1..3): 长方形圈层砌法 x2 层
# =================================================================
for z0, color in ((0, "orange"), (1, "pink")):
    b.lintel_ns(f"mb_s_{z0}", 1, 1.0, z0, color)     # 南墙
    b.lintel_ew(f"mb_e_{z0}", 3.0, 1, z0, color)     # 东墙
    b.lintel_ns(f"mb_n_{z0}", 1, 3.0, z0, color)     # 北墙
    b.lintel_ew(f"mb_w_{z0}", 1.0, 1, z0, color)     # 西墙

# 梯形四坡屋顶 + 压顶 + 烟囱
MB_ROOF, MB_CAP = b.hip_roof2("mb_roof", 1, 1, 2.0, "red", cap_color="gray")
b.spire_ns("chimney", 1.5, 1.5, 2.707107, "gray")    # 烟囱立在压顶南沿

# =================================================================
# 3. 门厅侧翼 (x 3..5, y 1..2): 1 格进深, 南面留门, 檐口横楣跨门
# =================================================================
b.wall_ns("wg_s", 4, 1.0, 0, "yellow")               # 南墙东段 (x 3..4 为大门)
b.wall_ns("wg_n_0", 3, 2.0, 0, "yellow")             # 北墙西段
b.wall_ns("wg_n_1", 4, 2.0, 0, "yellow")             # 北墙东段
b.wall_ew("wg_e", 5.0, 1, 0, "clear")                # 东墙下层 (观景窗)
b.wall_ew("wg_gab", 5.0, 1, 1, "yellow")             # 东山墙上层
b.lintel_ns("wg_ev_s", 3, 1.0, 1, "orange")          # 南檐口 (跨大门成楣)
b.lintel_ns("wg_ev_n", 3, 2.0, 1, "orange")          # 北檐口

# 人字坡屋面: 60 度长方形 x2 + 等边山花 x2
b.place_edge("wg_rf_s", "rectangle", 0, (3.0, 1.0, 2.0), (5.0, 1.0, 2.0),
             (0.0, 0.5, RIDGE_H), "red")             # 南坡面
b.place_edge("wg_rf_n", "rectangle", 0, (5.0, 2.0, 2.0), (3.0, 2.0, 2.0),
             (0.0, -0.5, RIDGE_H), "red")            # 北坡面
b.crest_ew("wg_gab_e", 5.0, 1, 2.0, "yellow")        # 东山花
b.crest_ew("wg_gab_w", 3.0, 1, 2.0, "yellow")        # 西山花 (贴主楼)

# =================================================================
# 4. 院子: 狗窝 + 绿篱 + 小树 + 花丛
# =================================================================
DOG = b.hat4("dog", 4, 3, 0.0, "red", shape="isosceles_triangle")
b.crest_ns("hd_0", 0, 0.0, 0.0, "green")             # 西南角绿篱 (南面)
b.crest_ew("hd_1", 0.0, 0, 0.0, "green")             # 西南角绿篱 (西面)
b.crest_ns("hd_2", 4, 0.0, 0.0, "green")             # 南绿篱东段 (留出步道口)
b.crest_ns("hd_3", 5, 0.0, 0.0, "green")
b.spire_ew("tree_0", 6.0, 2, 0.0, "green")           # 东侧小树
b.spire_ew("tree_1", 6.0, 4, 0.0, "green")
b.crest_ns("fl_0", 1, 5.0, 0.0, "pink")              # 北侧花丛
b.crest_ns("fl_1", 4, 5.0, 0.0, "pink")

# =================================================================
# 教程步骤 (17 步): 草坪 -> 主楼 -> 侧翼 -> 屋面 -> 院子
# =================================================================
b.step(
    "铺草坪南排: 4 片绿色方板加 1 片灰色长板 (环屋步道南段), "
    "入户步道口开在南沿正中偏东。",
    ["lw_0_0", "lr_s", "lw_3_0", "lw_4_0", "lw_5_0"],
    tip="草坪铺在桌面中央, 灰色长板的长边就是主楼南墙的地基线。",
)
b.step(
    "铺草坪中部: 西东两片灰色长板竖铺、室内两片绿色长板横铺, "
    "再补东侧 4 片绿色方板 —— 环屋步道围出主楼地基。",
    ["lr_w", "lr_f0", "lr_f1", "lr_e", "lw_4_1", "lw_5_1", "lw_4_2", "lw_5_2"],
    highlight=["lr_s", "lw_3_0"],
    tip="长板环环相扣, 主楼的每条墙底线都落在长板长边上。",
)
b.step(
    "铺草坪北部: 环屋步道北段长板加 4 片方板, 再补齐最北一排 6 片 —— "
    "6x5 院子就绪。",
    ["lr_n", "lw_0_3", "lw_3_3", "lw_4_3", "lw_5_3"]
    + [f"lw_{i}_4" for i in range(6)],
    highlight=["lr_w", "lr_e"],
    tip="院子铺好了, 别墅马上开工。",
)
b.step(
    "主楼首层圈层: 4 片橙色长方形立成 2x2 围圈, 四角竖边咬合, "
    "每片底长边整边吸住环屋步道长板的长边。",
    ["mb_s_0", "mb_e_0", "mb_n_0", "mb_w_0"],
    highlight=["lr_s", "lr_n"],
    tip="长方形圈层砌法 —— 每个转角两片竖边互吸, 一圈锁定。",
)
b.step(
    "主楼二层圈层: 再叠 4 片粉色长方形, 主楼升到 2 格高。",
    ["mb_s_1", "mb_e_1", "mb_n_1", "mb_w_1"],
    highlight=["mb_s_0", "mb_w_0"],
    tip="上下圈层的竖缝对齐, 墙顶留出 2 格长的整边给屋顶。",
)
b.step(
    "架主楼四坡屋顶前半: 南北 2 片梯形下底整边吸墙顶边。",
    ["mb_roof_s", "mb_roof_n"],
    highlight=["mb_s_1", "mb_n_1"],
    tip="梯形下底长 2, 恰与长方形墙顶边等长 —— 先立相对的两片。",
)
b.step(
    "屋顶合拢并压顶: 补东西 2 片梯形 (腰两两互吸), 顶口盖上灰色压顶方板。",
    ["mb_roof_e", "mb_roof_w", "mb_roof_cap"],
    highlight=["mb_roof_s", "mb_roof_n"],
    tip="四片腰线互吸自锁成环, 压顶一放, 整个屋顶就纹丝不动。",
)
b.step(
    "竖烟囱: 灰色等腰三角立在压顶南沿。",
    ["chimney"],
    highlight=["mb_roof_cap"],
    tip="烟囱尖是主楼最高点 (3.7 格) —— 冬天炉火就从这里冒烟。",
)
b.step(
    "起门厅侧翼: 主楼东侧立南墙东段、北墙 2 片与透明观景窗东墙 "
    "(南面 x 3..4 留 1 格大门)。",
    ["wg_s", "wg_n_0", "wg_n_1", "wg_e"],
    highlight=["mb_e_0"],
    tip="底边吸草坪格线 —— 大门正对步道, 负空间就是入口。",
)
b.step(
    "叠东山墙上层: 1 片黄色正方形叠在观景窗顶上。",
    ["wg_gab"],
    highlight=["wg_e"],
    tip="它是人字坡屋面的东端支点。",
)
b.step(
    "架檐口横楣: 南北各 1 片橙色长方形 (z 1..2), 西端竖边吸主楼二层"
    "竖边、东端竖边吸山墙竖边 —— 南檐口恰好跨过大门成楣。",
    ["wg_ev_s", "wg_ev_n"],
    highlight=["mb_e_1", "wg_gab"],
    tip="门楣底边悬空不用怕, 两端竖边传力 —— 吊桥城堡同款。",
)
b.step(
    "架人字坡南坡面: 红色长方形 60 度斜置, 底长边整边吸南檐口顶边。",
    ["wg_rf_s"],
    highlight=["wg_ev_s"],
    tip="坡面先别松手 —— 等北坡架上, 脊线两长边一吸就稳了。",
)
b.step(
    "北坡面合脊: 第二片长方形从北侧斜置, 脊线处两长边互吸, 人字顶合拢。",
    ["wg_rf_n"],
    highlight=["wg_rf_s"],
    tip="咔哒一声, 两片坡面在屋脊锁成一体。",
)
b.step(
    "封山花: 东西各立 1 片黄色等边三角形, 两腰恰好吸住坡面端边。",
    ["wg_gab_e", "wg_gab_w"],
    highlight=["wg_rf_s", "wg_rf_n"],
    tip="等边三角底 1 高 0.866, 与 60 度坡面严丝合缝 —— 几何的魔法。",
)
b.step(
    "搭狗窝: 院子东北角 4 片红色等腰三角形直接在草坪上合拢成小尖屋。",
    DOG,
    highlight=["lw_4_3"],
    tip="先立两片相对的再补另外两片 —— 旺财的家也要自锁成环。",
)
b.step(
    "种绿篱: 西南角绿篱包角 2 片, 大门东侧再立 2 片, 中间留出步道口。",
    ["hd_0", "hd_1", "hd_2", "hd_3"],
    highlight=["lw_3_0"],
    tip="绿篱底边吸草坪外沿格线, 整整齐齐。",
)
b.step(
    "栽小树与花丛: 东沿 2 株等腰小树, 北沿 2 片粉色花丛 —— 别墅交房!",
    ["tree_0", "tree_1", "fl_0", "fl_1"],
    highlight=["dog_s"],
    tip="从南面步道望去: 大门、门楣、人字顶、烟囱一线排开 —— 欢迎回家。",
)

b.finalize(
    model_id="lego_style_house_01",
    name="别墅小屋",
    name_en="Villa Cottage 01",
    description=(
        "经典盒式建筑教科书: 6x5 草坪上, 2x2 主楼用长方形圈层砌法叠起两层, "
        "梯形四坡屋顶下底恰与墙顶整边等长贴合, 压顶上再立烟囱; 东侧 1 格"
        "进深的门厅侧翼以檐口横楣跨过大门成楣 (两端竖边传力), 顶上 60 度"
        "人字坡屋面脊线互吸、等边山花严丝合缝; 院里狗窝自锁成环, 绿篱、"
        "小树、花丛围出温馨小院 —— 盒式搭建三大技法, 一栋别墅全学会。"
    ),
    difficulty=3,
    tags=["田园", "别墅", "盒式建筑", "人字坡", "进阶"],
    min_pieces=50,
    min_steps=16,
)
