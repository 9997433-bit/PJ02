#!/usr/bin/env python3
"""生成模型 data/models/aquarium_tunnel_01.json (海底隧道水族馆)。

内容批 B 4/5: 全库第一条"人从鱼底下走过去"的海底隧道 —— 与企鹅
戏水池 (架高水池 + 跳水岩) 和洗车馆 (车从楼里穿过去) 刻意错开:
大水箱正中留出一条 2 格宽的贯通隧道, 游客从南门走进去, 头顶
就是水箱底 —— 隧道顶板两短边压双排清色隧道墙 (双端受力如桥),
顶板之上是第二层玻璃观景环, 三条小鱼骑在水底拼缝上, 隔着玻璃
从四面都看得见; 馆旗红色瘦高杆骑东壁顶直上 4.0 —— 全库唯一的
"下层走人、上层养鱼"双层断面。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 隧道沿 y 贯通):
  - 馆前广场 (x [0,4], y [0,4]): 单位方板 x16                  16 片
  - 水箱一层 (x [0,4], y [1,3], z 0..1): 周边墙 x8 (南北面各
    留 2 格宽隧道口) + 隧道墙 x4 (清色)                        12 片
  - 水箱底 (z=1): 两侧方板 x4 + 隧道顶长板 x2 (双端受力)        6 片
  - 玻璃观景环 (z 1..2): 清色墙环 x12                          12 片
  - 小鱼 x3: 橙/红/黄等边三角骑水底拼缝                          3 片
  - 珊瑚 x2 + 馆旗 x1                                            3 片
  合计 52 片, 12 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 隧道两侧是两个箱形闭环 (周边墙 + 隧道墙 + 底板围合), 隧道
    顶板两短边整边压双排隧道墙顶, 双端受力零悬挑如桥;
  - 第二层玻璃环 12 片墙整圈闭合, 竖边互咬 + 底边吸水箱底沿,
    R8 高层检查由闭环拓扑天然通过; 馆旗骑墙顶重心正压铰链;
  - 小鱼底边整边吸水底拼缝 (一缝双吸), 在玻璃环合拢之前从
    开顶处放入, 装配可达;
  - 隧道口上方的玻璃墙底边踩长板顶沿, 与相邻玻璃墙竖边互咬,
    双路径受力。

用法: python3 tools/generate_aquarium_tunnel_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

PLAZA = "gray"      # 馆前广场
PATH = "yellow"     # 隧道步道
SEABED = "blue"     # 水箱底 (封在箱内)
WALL = "blue"       # 水箱外壁
TUNNEL = "clear"    # 隧道墙 (玻璃)
DECK = "blue"       # 水底板
GLASS = "clear"     # 二层玻璃观景环
FISH_A = "orange"
FISH_B = "red"
FISH_C = "yellow"
CORAL_A = "pink"
CORAL_B = "green"
FLAG = "red"        # 馆旗

# =================================================================
# 1. 馆前广场 (x [0,4], y [0,4]): 隧道步道纵贯正中
# =================================================================
for y0 in range(4):
    for x0 in range(4):
        color = PATH if x0 in (1, 2) and y0 in (1, 2) else PLAZA
        b.flat(f"plz_{x0}_{y0}", x0, y0, 0.0, color)

# =================================================================
# 2. 水箱一层 (x [0,4], y [1,3], z 0..1): 南北面各留隧道口
# =================================================================
b.wall_ns("t0_s_0", 0, 1.0, 0, WALL)           # 南面: 隧道口在 x [1,3]
b.wall_ns("t0_s_3", 3, 1.0, 0, WALL)
b.wall_ns("t0_n_0", 0, 3.0, 0, WALL)
b.wall_ns("t0_n_3", 3, 3.0, 0, WALL)
b.wall_ew("t0_w_1", 0.0, 1, 0, WALL)
b.wall_ew("t0_w_2", 0.0, 2, 0, WALL)
b.wall_ew("t0_e_1", 4.0, 1, 0, WALL)
b.wall_ew("t0_e_2", 4.0, 2, 0, WALL)
b.wall_ew("tn_w_1", 1.0, 1, 0, TUNNEL)         # 隧道墙 (玻璃)
b.wall_ew("tn_w_2", 1.0, 2, 0, TUNNEL)
b.wall_ew("tn_e_1", 3.0, 1, 0, TUNNEL)
b.wall_ew("tn_e_2", 3.0, 2, 0, TUNNEL)

# =================================================================
# 3. 水箱底 (z=1): 两侧方板 + 隧道顶长板 (双端受力)
# =================================================================
b.flat("dk_w_1", 0, 1, 1.0, DECK)
b.flat("dk_w_2", 0, 2, 1.0, DECK)
b.flat("dk_e_1", 3, 1, 1.0, DECK)
b.flat("dk_e_2", 3, 2, 1.0, DECK)
b.flat_rect("dk_t_1", 1, 1, 1.0, DECK)         # 隧道顶: 短边压双墙顶
b.flat_rect("dk_t_2", 1, 2, 1.0, DECK)

# =================================================================
# 4. 小鱼 x3: 骑水底拼缝 (玻璃环合拢前放入)
# =================================================================
b.crest_ew("fish_a", 1.0, 1, 1.0, FISH_A)      # 骑侧板-长板缝
b.crest_ew("fish_b", 3.0, 2, 1.0, FISH_B)
b.crest_ns("fish_c", 0, 2.0, 1.0, FISH_C)      # 骑两侧板中缝

# =================================================================
# 5. 玻璃观景环 (z 1..2): 整圈 12 片清色墙
# =================================================================
for x0 in range(4):
    b.wall_ns(f"g_s_{x0}", x0, 1.0, 1, GLASS)
for x0 in range(4):
    b.wall_ns(f"g_n_{x0}", x0, 3.0, 1, GLASS)
b.wall_ew("g_w_1", 0.0, 1, 1, GLASS)
b.wall_ew("g_w_2", 0.0, 2, 1, GLASS)
b.wall_ew("g_e_1", 4.0, 1, 1, GLASS)
b.wall_ew("g_e_2", 4.0, 2, 1, GLASS)

# =================================================================
# 6. 珊瑚 x2 (馆前) + 馆旗
# =================================================================
b.crest_ns("coral_w", 0, 0.0, 0.0, CORAL_A)    # 骑广场南沿
b.crest_ns("coral_e", 3, 0.0, 0.0, CORAL_B)
b.spire_ew("flag", 4.0, 1, 2.0, FLAG)          # 馆旗骑东壁顶, 尖 4.0

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺广场南行: 四片方板一字排开, 这是水族馆的门脸。",
    [f"plz_{x0}_0" for x0 in range(4)],
    tip="中间两列待会是隧道步道, 黄色的路一直通到馆里。",
)
b.step(
    "铺第二行: 黄色步道格居中, 灰色广场格在两边。",
    [f"plz_{x0}_1" for x0 in range(4)],
    highlight=["plz_0_0"],
    tip="行行等边互吸, 步道从这里钻进水箱底下。",
)
b.step(
    "铺第三行: 步道继续向北。",
    [f"plz_{x0}_2" for x0 in range(4)],
    highlight=["plz_1_1"],
    tip="这两行黄格就是隧道的地面 —— 头顶马上就要有鱼了。",
)
b.step(
    "铺第四行: 广场铺满, 北出口亮相。",
    [f"plz_{x0}_3" for x0 in range(4)],
    highlight=["plz_1_2"],
    tip="隧道南进北出, 两头都不封 —— 这是一条走得通的路。",
)
b.step(
    "立水箱外壁: 蓝色墙踩住广场拼缝, 南北面各留 2 格隧道口。",
    ["t0_s_0", "t0_s_3", "t0_n_0", "t0_n_3",
     "t0_w_1", "t0_w_2", "t0_e_1", "t0_e_2"],
    highlight=["plz_0_1"],
    tip="四角竖边互咬; 正中空出来的洞口就是隧道大门。",
)
b.step(
    "立隧道玻璃墙: 两排清色墙夹住黄色步道。",
    ["tn_w_1", "tn_w_2", "tn_e_1", "tn_e_2"],
    highlight=["t0_s_0"],
    tip="玻璃墙与外壁围成左右两个闭环箱体 —— 那是鱼住的地方。",
)
b.step(
    "铺水箱底两侧: 四片蓝色方板压上外壁与隧道墙顶。",
    ["dk_w_1", "dk_w_2", "dk_e_1", "dk_e_2"],
    highlight=["tn_w_1"],
    tip="每片底板两条外边压墙顶, 箱体就此封成整环。",
)
b.step(
    "盖隧道顶: 两块蓝色长板短边各压一排玻璃墙顶。",
    ["dk_t_1", "dk_t_2"],
    highlight=["dk_w_1"],
    tip="双端受力零悬挑, 像桥一样跨过隧道 —— 桥上就是水底。",
)
b.step(
    "放小鱼: 三条小鱼骑上水底拼缝, 趁玻璃环没合拢先入住。",
    ["fish_a", "fish_b", "fish_c"],
    highlight=["dk_t_1"],
    tip="底边整边吸住拼缝; 橙色小丑鱼最喜欢待在隧道顶上。",
)
b.step(
    "起玻璃观景环南面与西面: 清色墙踩住水底沿口。",
    ["g_s_0", "g_s_1", "g_s_2", "g_s_3", "g_w_1", "g_w_2"],
    highlight=["fish_a"],
    tip="隧道口上方的玻璃墙踩在长板顶沿上, 竖边再与邻片互咬。",
)
b.step(
    "补北面与东面, 玻璃环整圈闭合。",
    ["g_n_0", "g_n_1", "g_n_2", "g_n_3", "g_e_1", "g_e_2"],
    highlight=["g_s_0"],
    tip="十二片玻璃合成一圈, 从哪个方向都能看到鱼游过头顶。",
)
b.step(
    "馆前珊瑚与馆旗收尾: 红旗骑东壁顶直上 4.0。",
    ["coral_w", "coral_e", "flag"],
    highlight=["g_e_1"],
    tip="粉珊瑚绿珊瑚分立大门两侧 —— 走, 从鱼肚子底下穿过去!",
)

b.finalize(
    model_id="aquarium_tunnel_01",
    name="海底隧道水族馆",
    name_en="Aquarium Tunnel 01",
    description=(
        "只用核心九片型的海底隧道: 大水箱正中留出一条 2 格宽的"
        "贯通隧道, 黄色步道南进北出, 头顶就是水箱底 —— 隧道顶板"
        "两短边压双排玻璃墙顶, 双端受力如桥; 顶板之上第二层玻璃"
        "观景环整圈闭合, 三条小鱼骑在水底拼缝上, 隔着玻璃从四面"
        "都看得见; 红色馆旗骑东壁顶直上 4.0, 馆前粉绿珊瑚分立"
        "两侧 —— 从鱼肚子底下穿过去是什么感觉?"
    ),
    difficulty=3,
    tags=["海洋", "水族馆", "隧道", "探险", "小鱼"],
    min_pieces=52,
    min_steps=12,
)
