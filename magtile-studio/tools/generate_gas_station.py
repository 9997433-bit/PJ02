#!/usr/bin/env python3
"""生成模型 data/models/gas_station_01.json (加油站)。

城市生活主题: 星光加油站 —— 全库首座"门式大雨棚"建筑: 西/中/东
三榀双层门架 (各 2 片宽 x2 层) 托起 4x2 大雨棚, 棚檐前沿升起整排
招牌墙 + 双星徽记; 棚下两台黄色加油机立在车道分缝上, 橙色油枪
朝天; 东侧便利店借门架当西墙 (门框方店门 + 窗格方橱窗), 屋顶
插双旗; 南侧车道上一辆车轮底座敞篷小车正在加油, 西口还立着
一杆窗格方价目牌 —— 加满一箱, 出发!

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 雨棚场坪 [0,4]x[0,2]: 4x2 方板                             8 片
  - 南侧车道: 路板 2 + 车轮底座小车 (底盘/厢壁/首尾/半篷)      8 片
  - 门架: 西/中/东三榀, 各 2 片宽 x2 层                       12 片
  - 大雨棚 (z=2): 4x2 方板                                     8 片
  - 招牌墙 (前檐 z 2..3): 4 片 + 双星徽记 2 片                 6 片
  - 加油机: 立墙 x2 + 等边油枪 x2                              4 片
  - 便利店 [4,6]x[0,2]: 地板 4 + 立墙 6 (门框方 + 窗格方)
    + 平顶 4 + 顶旗 2                                         16 片
  - 价目牌 (西口): 杆 1 + 窗格方牌面 1                          2 片
  合计 64 片, 16 个教程步骤, 7 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 大雨棚每半跨都两端整边压在相邻两榀门架顶边上 (零悬挑),
    棚板拼缝互吸成网 —— 剪断任意一榀铰链, 棚面仍有支撑;
  - 招牌墙底边吸棚板前沿, 相邻竖边互吸成整排;
  - 加油机立在场坪拼缝上 (缝两侧双吸), 先装机后盖棚, 伸手可达;
  - 敞篷小车: 厢壁长方形整边吸底座长边, 车首尾底边同时吸底座
    短边与路板边 (双路径), 半篷单片悬挑力矩 15 <= 严格档 17.5。

用法: python3 tools/generate_gas_station.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

APRON = "gray"      # 场坪
ROAD = "gray"       # 车道路板
FRAME = "red"       # 门架
CANOPY = "red"      # 大雨棚
FASCIA = "clear"    # 招牌墙
STAR = "red"        # 星徽
PUMP = "yellow"     # 加油机
NOZZLE = "orange"   # 油枪
SHOP = "green"      # 便利店
SHOPROOF = "gray"   # 便利店平顶
FLAG = "cyan"       # 顶旗
CAR = "blue"        # 小车
GLASS = "clear"     # 挡风玻璃
SIGN = "yellow"     # 价目牌

# =================================================================
# 1. 雨棚场坪 [0,4]x[0,2] 与南侧车道
# =================================================================
for x in range(4):
    for y in range(2):
        b.flat(f"ap_{x}_{y}", x, y, 0.0, APRON)
b.flat("rd_w", 0, -1, 0.0, ROAD)
b.flat("rd_e", 3, -1, 0.0, ROAD)

# =================================================================
# 2. 门架: 西榀 (x=0) / 中榀 (x=2) / 东榀 (x=4), 各 2 片宽 x2 层
#    中榀立在雨棚拼缝正下方 —— 逐半安装棚板时两端都有依托
# =================================================================
for lv in range(2):
    for y in range(2):
        b.wall_ew(f"fr_w{lv}_{y}", 0.0, y, lv, FRAME)
        b.wall_ew(f"fr_m{lv}_{y}", 2.0, y, lv, FRAME)
        b.wall_ew(f"fr_e{lv}_{y}", 4.0, y, lv, FRAME)

# =================================================================
# 3. 加油机: 场坪分缝 (y=1) 上 2 台 + 等边油枪 (避开中榀门架)
# =================================================================
b.wall_ns("pm_0", 0, 1.0, 0, PUMP)
b.wall_ns("pm_1", 3, 1.0, 0, PUMP)
b.crest_ns("nz_0", 0, 1.0, 1.0, NOZZLE)
b.crest_ns("nz_1", 3, 1.0, 1.0, NOZZLE)

# =================================================================
# 4. 大雨棚 (z=2): 4x2 方板, 两端压门架顶
# =================================================================
for x in range(4):
    for y in range(2):
        b.flat(f"cn_{x}_{y}", x, y, 2.0, CANOPY)

# 招牌墙 (前檐 y=0, z 2..3) + 双星徽记
for x in range(4):
    b.wall_ns(f"fa_{x}", x, 0.0, 2, FASCIA)
b.crest_ns("st_0", 1, 0.0, 3.0, STAR)
b.crest_ns("st_1", 2, 0.0, 3.0, STAR)

# =================================================================
# 5. 便利店 [4,6]x[0,2]: 西借东榀门架下层
# =================================================================
for x in range(4, 6):
    for y in range(2):
        b.flat(f"sh_f_{x}_{y}", x, y, 0.0, APRON)
b.add("sh_door", "door_frame", (4.5, 0.0, 0.5), (90, 0, 0), SHOP)
b.add("sh_win", "window_square", (5.5, 0.0, 0.5), (90, 0, 0), GLASS)
b.wall_ns("sh_n_4", 4, 2.0, 0, SHOP)
b.wall_ns("sh_n_5", 5, 2.0, 0, SHOP)
b.wall_ew("sh_e_0", 6.0, 0, 0, SHOP)
b.wall_ew("sh_e_1", 6.0, 1, 0, SHOP)
for x in range(4, 6):
    for y in range(2):
        b.flat(f"sh_r_{x}_{y}", x, y, 1.0, SHOPROOF)
b.spire_ew("sh_fl0", 6.0, 0, 1.0, FLAG)
b.spire_ew("sh_fl1", 6.0, 1, 1.0, FLAG)

# =================================================================
# 6. 敞篷小车 (南侧车道 [1,3]x[-1,0]) + 价目牌 (西口)
# =================================================================
b.add("car_ch", "wheel_base", (2.0, -0.5, 0.0), (0, 0, 0), CAR)
b.lintel_ns("car_s", 1, -1.0, 0, CAR)          # 南厢壁
b.lintel_ns("car_n", 1, 0.0, 0, CAR)           # 北厢壁
b.wall_ew("car_t", 1.0, -1, 0, CAR)            # 车尾
b.wall_ew("car_w", 3.0, -1, 0, GLASS)          # 挡风玻璃
b.flat("car_r", 1, -1, 1.0, CAR)               # 半篷 (车尾半段)
b.wall_ew("sg_pole", 0.0, -1, 0, SIGN)
b.add("sg_board", "window_square", (0.0, -0.5, 1.5), (90, 0, 90), GLASS)

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺设雨棚场坪: 4x2 共 8 片灰色方板。",
    [f"ap_{x}_{y}" for x in range(4) for y in range(2)],
    tip="场坪的中缝 (y=1) 是两条车道的分界 —— 加油机就立在缝上。",
)
b.step(
    "铺设南侧车道并立价目牌: 路板 2 片, 黄色牌杆立西口、"
    "窗格方牌面叠上。",
    ["rd_w", "rd_e", "sg_pole", "sg_board"],
    highlight=["ap_0_0", "ap_3_0"],
    tip="价目牌立在路板西沿 —— 今日油价一目了然。",
)
b.step(
    "竖立三榀门架下层: 西/中/东各 2 片红色方墙, 底边吸场坪板缝。",
    ["fr_w0_0", "fr_w0_1", "fr_m0_0", "fr_m0_1", "fr_e0_0", "fr_e0_1"],
    highlight=["ap_0_0", "ap_3_1"],
    tip="三榀门架是大雨棚的顶梁柱, 中榀正好立在棚板拼缝下方。",
)
b.step(
    "门架加高到两层: 上层 6 片对缝叠齐。",
    ["fr_w1_0", "fr_w1_1", "fr_m1_0", "fr_m1_1", "fr_e1_0", "fr_e1_1"],
    highlight=["fr_w0_0", "fr_m0_0", "fr_e0_0"],
    tip="上下对缝叠放 —— 雨棚要架在 2 层高的门架顶上。",
)
b.step(
    "安装加油机: 2 台黄色机身立在车道分缝上, 橙色油枪朝天。",
    ["pm_0", "pm_1", "nz_0", "nz_1"],
    highlight=["ap_0_0", "ap_3_1"],
    tip="趁雨棚还没盖, 先把加油机装好 —— 伸手可达。",
)
b.step(
    "铺设大雨棚西半: 4 片红色棚板, 西沿压西榀门架顶、东沿压中榀"
    "门架顶 —— 两端都有依托。",
    [f"cn_{x}_{y}" for x in range(2) for y in range(2)],
    highlight=["fr_w1_0", "fr_m1_0"],
    tip="棚板两头受力零悬挑, 拼缝互吸成网。",
)
b.step(
    "铺设大雨棚东半: 再 4 片跨中榀与东榀门架, 雨棚合拢。",
    [f"cn_{x}_{y}" for x in range(2, 4) for y in range(2)],
    highlight=["cn_1_0", "fr_e1_0"],
    tip="剪断任意一榀铰链, 棚面仍由另外两榀托住 —— 三保险。",
)
b.step(
    "升起招牌墙: 前檐 4 片透明方墙, 底边吸棚板前沿、竖边互吸成排。",
    [f"fa_{x}" for x in range(4)],
    highlight=["cn_0_0", "cn_3_0"],
    tip="整排招牌墙是加油站的天际线。",
)
b.step(
    "点亮双星徽记: 2 片红色等边三角立上招牌墙顶边正中。",
    ["st_0", "st_1"],
    highlight=["fa_1", "fa_2"],
    tip="星徽立在招牌墙顶的铰链线上, 重心正压。",
)
b.step(
    "铺设便利店地板: 4 片方板接在东榀门架东侧。",
    [f"sh_f_{x}_{y}" for x in range(4, 6) for y in range(2)],
    highlight=["ap_3_0"],
    tip="便利店的西墙直接借用东榀门架下层 —— 一墙两用。",
)
b.step(
    "竖立便利店店面与东墙: 门框方店门 + 窗格方橱窗 + 东墙 2 片。",
    ["sh_door", "sh_win", "sh_e_0", "sh_e_1"],
    highlight=["sh_f_4_0"],
    tip="橱窗里摆着地图、饮料和小饼干。",
)
b.step(
    "竖立便利店北墙: 2 片, 店堂围合。",
    ["sh_n_4", "sh_n_5"],
    highlight=["sh_e_1"],
    tip="拐角竖边互吸, 小店也是闭合箱形筒。",
)
b.step(
    "盖便利店平顶: 4 片灰色顶板, 西沿吸门架下层顶边。",
    [f"sh_r_{x}_{y}" for x in range(4, 6) for y in range(2)],
    highlight=["sh_n_4", "fr_e0_0"],
    tip="顶板一边搭门架、一边搭店墙 —— 两头受力最稳。",
)
b.step(
    "便利店顶插双旗: 2 面青色等腰旗立上平顶东沿。",
    ["sh_fl0", "sh_fl1"],
    highlight=["sh_r_5_0"],
    tip="小旗立在顶板沿口铰链线上, 迎风招展。",
)
b.step(
    "拼装敞篷小车: 车轮底座落在车道正中, 长方形厢壁整边吸底座"
    "长边, 车尾与挡风玻璃合拢。",
    ["car_ch", "car_s", "car_n", "car_t", "car_w"],
    highlight=["rd_w", "rd_e"],
    tip="车首尾底边同时吸底座短边与路板边 —— 双路径受力。",
)
b.step(
    "装上半篷: 1 片蓝色篷板压车尾顶边向前悬挑, 加满一箱, 出发!",
    ["car_r"],
    highlight=["car_t"],
    tip="单片半篷悬挑力矩 15, 严格档预算之内 —— 兜风去喽!",
)

b.finalize(
    model_id="gas_station_01",
    name="加油站",
    name_en="Gas Station",
    description=(
        "星光加油站: 西/中/东三榀双层门架托起 4x2 红色大雨棚 (每半跨"
        "两端受力零悬挑), 前檐整排透明招牌墙点亮双星徽记; 棚下两台黄色"
        "加油机油枪朝天, 东侧便利店借门架一墙两用 (门框方店门 + 窗格方"
        "橱窗), 屋顶双旗迎风; 南侧车道上车轮底座敞篷小车正在加油, 西口"
        "窗格方价目牌一目了然 —— 加满一箱, 出发!"
    ),
    difficulty=3,
    tags=["城市", "交通", "车辆", "进阶"],
    min_pieces=64,
    min_steps=16,
)
