#!/usr/bin/env python3
"""生成模型 data/models/trex_skeleton_01.json (博物馆霸王龙)。

第二批模型 ②: 全库第一件"生物雕塑" —— 博物馆展台上的霸王龙:
双腿立柱撑起箱形躯干, 30 度坡道甩出一条拖地长尾, 高高的头骨
张开下颚露出两颗獠牙, 背脊立着一排三角骨板。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 博物馆展台: 中轴 6 片 + 两侧各 6 片, 共 18 片地台            18 片
  - 后腿 x2: 立墙腿柱 + 4 根直角三角形腿部肌腱斜撑                6 片
  - 躯干: 底板 3 + 四周立墙 8 + 背板 3                           14 片
  - 背脊骨板: 3 片等边三角形立在背脊沿上                          3 片
  - 尾巴: 30 度坡道拖地 + 尾尖三角                                2 片
  - 颈部与头骨: 双立墙颈柱, 1x1 头骨盒 + 头冠                     8 片
  - 下颚与獠牙: 外挑下颚板 + 2 颗三角獠牙                         3 片
  合计 54 片, 15 个教程步骤, 5 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 腿柱由 4 根斜撑锁在展台上 (三角刚性节点), 躯干楼板压顶成环;
  - 尾巴坡道顶边整边吸躯干底板沿口, 坡尾自身接地;
  - 下颚单边外挑力矩 15+13 g·单位, 在双磁边 40 g·单位预算之内;
    獠牙立在下颚两侧沿上, 不与颈柱共面。

用法: python3 tools/generate_trex_skeleton.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

# =================================================================
# 1. 博物馆展台: 中轴 (y 0..1) 6 片 + 南北两排各 6 片
# =================================================================
for x in range(6):
    b.flat(f"base_c_{x}", x, 0, 0.0, "gray" if x % 2 == 0 else "cyan")
for x in range(6):
    b.flat(f"base_s_{x}", x, -1, 0.0, "green")
for x in range(6):
    b.flat(f"base_n_{x}", x, 1, 0.0, "green")

# =================================================================
# 2. 后腿: 两根立墙腿柱 (x=2 与 x=3 平面) + 腿部肌腱斜撑
# =================================================================
b.wall_ew("leg_w", 2.0, 0, 0, "yellow")
b.wall_ew("leg_e", 3.0, 0, 0, "yellow")
b.brace("ten_sw", (2.0, 0.0, 0.0), "-x", "orange")   # 西腿南侧肌腱
b.brace("ten_nw", (2.0, 1.0, 0.0), "-x", "orange")   # 西腿北侧肌腱
b.brace("ten_se", (3.0, 0.0, 0.0), "+x", "orange")   # 东腿南侧肌腱
b.brace("ten_ne", (3.0, 1.0, 0.0), "+x", "orange")   # 东腿北侧肌腱

# =================================================================
# 3. 躯干: 底板 (z=1) + 四周肋壁 (z 1..2) + 背板 (z=2)
# =================================================================
for x in (1, 2, 3):
    b.flat(f"belly_{x}", x, 0, 1.0, "yellow")
for x in (1, 2, 3):
    b.wall_ns(f"rib_s_{x}", x, 0.0, 1, "yellow" if x % 2 else "orange")
for x in (1, 2, 3):
    b.wall_ns(f"rib_n_{x}", x, 1.0, 1, "yellow" if x % 2 else "orange")
b.wall_ew("hip_w", 1.0, 0, 1, "orange")    # 臀端封板
b.wall_ew("chest_e", 4.0, 0, 1, "orange")  # 胸端封板
for x in (1, 2, 3):
    b.flat(f"back_{x}", x, 0, 2.0, "yellow")

# 背脊骨板: 等边三角形立在背板北沿
for x in (1, 2, 3):
    b.crest_ns(f"plate_{x}", x, 1.0, 2.0, "red")

# =================================================================
# 4. 尾巴: 30 度坡道从臀部拖到地面, 尾尖立三角
# =================================================================
b.ramp("tail", "-x", 1.0, 0, 1.0, "yellow")            # 顶边吸躯干底板西沿
b.crest_ew("tail_tip", 1.0 - 1.732051, 0, 0.0, "red")  # 尾尖立在坡尾沿上

# =================================================================
# 5. 颈部与头骨: 双立墙颈柱 (z 2..3) 托起 1x1 头骨盒 (z 3..4)
# =================================================================
b.wall_ew("neck_w", 3.0, 0, 2, "yellow")
b.wall_ew("neck_e", 4.0, 0, 2, "yellow")
b.flat("skull_base", 3, 0, 3.0, "yellow")     # 头骨底板
b.wall_ns("skull_s", 3, 0.0, 3, "yellow")
b.wall_ew("skull_e", 4.0, 0, 3, "orange")     # 吻端
b.wall_ns("skull_n", 3, 1.0, 3, "yellow")
b.wall_ew("skull_w", 3.0, 0, 3, "orange")
b.flat("skull_top", 3, 0, 4.0, "yellow")      # 头骨顶板
b.spire_ew("skull_crest", 3.0, 0, 4.0, "red")  # 头冠 (等腰三角)

# =================================================================
# 6. 下颚与獠牙: 下颚板从头骨底板向前外挑, 两颗獠牙立其两侧沿上
# =================================================================
b.flat("jaw", 4, 0, 3.0, "orange")            # 下颚外挑板 (x 4..5)
b.crest_ns("fang_s", 4, 0.0, 3.0, "clear")    # 南獠牙
b.crest_ns("fang_n", 4, 1.0, 3.0, "clear")    # 北獠牙

# =================================================================
# 教程步骤 (15 步)
# =================================================================
b.step(
    "铺设展台中轴: 沿直线平放 6 片正方形 (灰青相间), 相邻边互相吸合。",
    [f"base_c_{x}" for x in range(6)],
    tip="这条中轴线就是霸王龙的身体轴线: 尾巴朝西, 头朝东。",
)
b.step(
    "铺设展台南排: 中轴南侧接 6 片绿色地台。",
    [f"base_s_{x}" for x in range(6)],
    highlight=["base_c_0", "base_c_5"],
    tip="每片先吸住中轴地台的边, 再与左右邻片吸合。",
)
b.step(
    "铺设展台北排: 中轴北侧再接 6 片, 3x6 展台完工。",
    [f"base_n_{x}" for x in range(6)],
    highlight=["base_s_0"],
    tip="展台要留出西端两格空地 —— 那是尾巴落地的位置。",
)
b.step(
    "竖立两条后腿并装肌腱: 黄色腿柱立在中轴 x=2 与 x=3 的接缝上, "
    "再用 4 根橙色直角三角形斜撑锁住腿柱两侧。",
    ["leg_w", "leg_e", "ten_sw", "ten_nw", "ten_se", "ten_ne"],
    highlight=["base_c_2", "base_c_3"],
    tip="斜撑的竖直边吸腿柱竖边、水平边吸展台接缝 —— 这就是霸王龙的腿部肌腱。",
)
b.step(
    "铺设躯干底板: 3 片黄色正方形压在两条腿柱顶边上 (先铺正中一片)。",
    ["belly_2", "belly_1", "belly_3"],
    highlight=["leg_w", "leg_e"],
    tip="正中一片要同时吸住两条腿柱的顶边, 躯干的重量全靠它们传下去。",
)
b.step(
    "竖立躯干南肋壁与臀端封板: 南侧 3 片立墙 + 臀端 (西) 1 片封板。",
    ["rib_s_1", "rib_s_2", "rib_s_3", "hip_w"],
    highlight=["belly_1", "belly_3"],
    tip="立墙底边吸底板沿口; 转角处臀端封板与南肋壁竖边互吸。",
)
b.step(
    "竖立躯干北肋壁与胸端封板, 躯干合围。",
    ["rib_n_1", "rib_n_2", "rib_n_3", "chest_e"],
    highlight=["hip_w", "rib_s_1"],
    tip="合围后轻推躯干应整体联动 —— 四角竖边都要互相吸住。",
)
b.step(
    "盖上背板: 3 片黄色正方形压住四周肋壁顶边, 躯干成为刚性箱体。",
    ["back_1", "back_2", "back_3"],
    highlight=["rib_s_2", "rib_n_2"],
    tip="背板四边都压在肋壁顶上, 剪断任何一条边都还有别的支撑 —— 这就是箱形结构。",
)
b.step(
    "安装背脊骨板: 3 片红色等边三角形立在背板北沿, 尖角朝天。",
    ["plate_1", "plate_2", "plate_3"],
    highlight=["back_1", "back_3"],
    tip="骨板底边吸背板沿口即可站稳, 一排三角就是霸王龙的背脊轮廓。",
)
b.step(
    "安装尾巴: 30 度长方形坡道顶边整边吸在躯干底板西沿, 坡尾拖到展台上; "
    "再在坡尾沿上立 1 片红色尾尖三角。",
    ["tail", "tail_tip"],
    highlight=["belly_1", "hip_w"],
    tip="坡道顶边与底板沿口完全贴合后, 坡尾自然落地, 不需要任何支撑。",
)
b.step(
    "竖立颈柱: 2 片黄色立墙立在背板东端 x=3 与 x=4 的沿口上。",
    ["neck_w", "neck_e"],
    highlight=["back_3", "chest_e"],
    tip="两根颈柱平行朝前, 与腿柱一样是一对承重立墙。",
)
b.step(
    "铺头骨底板并竖立头骨四壁: 底板压住两根颈柱顶边, 四壁围成 1x1 头骨盒。",
    ["skull_base", "skull_s", "skull_e", "skull_n", "skull_w"],
    highlight=["neck_w", "neck_e"],
    tip="底板要同时吸住两根颈柱; 四壁按 南-东-北-西 顺序合围, 竖边互吸。",
)
b.step(
    "盖头骨顶板并装头冠: 顶板压住头骨四壁, 西沿立 1 片红色等腰三角头冠。",
    ["skull_top", "skull_crest"],
    highlight=["skull_s", "skull_n"],
    tip="高高的头冠让霸王龙的剪影一眼可辨。",
)
b.step(
    "安装下颚: 1 片橙色正方形从头骨底板前沿向东外挑 —— 霸王龙张开了嘴。",
    ["jaw"],
    highlight=["skull_base", "skull_e"],
    tip="下颚同时吸住头骨底板沿与吻端墙根两条磁边, 单边外挑也纹丝不动。",
)
b.step(
    "装上獠牙: 2 片透明三角形立在下颚南北两沿, 霸王龙威风完工!",
    ["fang_s", "fang_n"],
    highlight=["jaw"],
    tip="獠牙底边吸下颚沿口; 从正面看, 张开的大嘴里两颗牙闪闪发亮。",
)

b.finalize(
    model_id="trex_skeleton_01",
    name="博物馆霸王龙",
    name_en="T-Rex Skeleton 01",
    description=(
        "全库第一件生物雕塑: 博物馆展台上的霸王龙 —— 双腿立柱由 4 根直角三角形"
        "肌腱斜撑锁定, 箱形躯干背脊立着一排三角骨板, 30 度坡道甩出拖地长尾, "
        "1x1 头骨盒张开外挑下颚, 两颗透明獠牙立在颚沿上。从尾尖到头冠高低起伏"
        "的剪影, 摆在展示柜里就是一件标本级作品。"
    ),
    difficulty=3,
    tags=["恐龙", "雕塑", "博物馆", "进阶"],
    min_pieces=50,
    min_steps=15,
)
