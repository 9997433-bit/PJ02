#!/usr/bin/env python3
"""生成模型 data/models/mars_habitat_01.json (火星互联栖息基地)。

科幻/实验室主题 3/4: 全库第一座多舱互联基地 —— 与 mars_rover_01
(六轮行星车) 和 asteroid_mining_01 (龙门钻机 + 独立居住舱) 的
结构逻辑刻意区分: 五个舱室以中央枢纽为心拼成十字 —— 枢纽四面
全部是门框方舱门 (北通穹顶居住舱 / 东通玻璃温室 / 南通气闸 /
西通能源舱), 枢纽顶板四边同时压四樘门顶, 把整个基地锁成一体;
居住舱三面窗格方舷窗, 舱顶透明等边四坡穹顶自锁; 温室两道透明
长板横楣夹出 2x1 玻璃房, 屋顶通长透明长板双楣受力, 封顶前先
在地缝上种下绿色作物; 气闸红外门橙内门双门串联朝南开向荒原;
能源舱黄色三墙, 屋顶北沿骑等腰通讯桅杆 (杆尖 3.0 全场最高);
舱外红色荒原上: 双轮底座巡逻车驮着蓝色甲板、两道透明太阳能板墙
沿基地南线展开、东侧四坡岩丘与信标旗把守 —— 火星安家!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 气闸朝南):
  - 火星荒原 8x5: 方板 + 长板混铺 (舱室地垫各有颜色)         27 片
  - 气闸舱: 外门 + 侧墙 x2 + 内门 + 顶板                      5 片
  - 中央枢纽: 舱门 x3 (含气闸内门共 4 樘) + 顶板              4 片
  - 穹顶居住舱: 舷窗墙 x3 + 透明等边四坡穹顶 x4               7 片
  - 能源舱: 黄墙 x3 + 顶板 + 通讯桅杆 (杆尖 3.0)              5 片
  - 玻璃温室: 透明横楣 x2 + 东墙 + 作物 + 通长玻璃顶          5 片
  - 太阳能板墙 x2 + 信标旗 x1                                 3 片
  - 巡逻车: 车轮底座 x2 + 甲板长板 + 天线三角                 4 片
  - 岩丘: 等边四坡锥 x4                                       4 片
  合计 64 片, 12 个教程步骤, 7 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (R1~R8 全绿, strict 档零警告):
  - 十字互联: 每个舱室与枢纽共享一樘门框方 —— 门竖边同时被
    两舱墙咬住, 枢纽顶板四边压四门顶, 处处成环;
  - 温室横楣底边吸地板长边 (2 对 2 整边), 西端竖边吸温室门,
    玻璃顶两长边双楣受力; 作物先种后封顶 (R7b 装配可达);
  - 桅杆底边同时吸能源舱顶板北沿与北墙顶 (一缝双吸);
    杆尖 3.0 触发 R8 高层检查 —— 全基地箱式闭环冗余通过;
  - 巡逻车甲板两长边分别压双轮顶 (双端受力), 无悬挑无吊挂。

用法: python3 tools/generate_mars_habitat.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

MARS = "red"        # 火星荒原
DUST = "orange"     # 风化带 / 岩丘
HAB = "cyan"        # 居住区地垫
GH_F = "green"      # 温室地垫
PWR_F = "yellow"    # 能源舱地垫
AIR_F = "gray"      # 气闸地垫
WALL = "gray"       # 舱壁
DOOR_IN = "orange"  # 舱内互联门
DOOR_OUT = "red"    # 气闸外门
GLASS = "clear"     # 穹顶 / 温室 / 太阳能板
PWR = "yellow"      # 能源舱墙
CROP = "green"      # 温室作物
MAST = "red"        # 通讯桅杆
ROVER = "gray"      # 巡逻车轮
DECK = "blue"       # 巡逻车甲板

# =================================================================
# 1. 荒原 (x [0,8], y [0,5]): 拼缝对准全部舱墙线
# =================================================================
b.flat_rect("m0_a", 0, 0, 0.0, MARS)
b.flat_rect("m0_b", 2, 0, 0.0, DUST)
b.flat_rect("m0_c", 4, 0, 0.0, MARS)
b.flat_rect("m0_d", 6, 0, 0.0, MARS)

b.flat_rect("m1_a", 0, 1, 0.0, MARS)
b.flat("m1_b", 2, 1, 0.0, DUST)
b.flat("m1_c", 3, 1, 0.0, AIR_F)          # 气闸地垫
b.flat("m1_d", 4, 1, 0.0, MARS)
b.flat("m1_e", 5, 1, 0.0, DUST)
b.flat_rect("m1_f", 6, 1, 0.0, MARS)      # 巡逻车车位

b.flat_rect("m2_a", 0, 2, 0.0, DUST)
b.flat("m2_b", 2, 2, 0.0, PWR_F)          # 能源舱地垫
b.flat("m2_c", 3, 2, 0.0, HAB)            # 枢纽地垫
b.flat("m2_d", 4, 2, 0.0, GH_F)           # 温室地垫
b.flat("m2_e", 5, 2, 0.0, GH_F)
b.flat_rect("m2_f", 6, 2, 0.0, MARS)

b.flat_rect("m3_a", 0, 3, 0.0, MARS)
b.flat("m3_b", 2, 3, 0.0, DUST)
b.flat("m3_c", 3, 3, 0.0, HAB)            # 居住舱地垫
b.flat("m3_d", 4, 3, 0.0, MARS)
b.flat("m3_e", 5, 3, 0.0, MARS)
b.flat("m3_f", 6, 3, 0.0, DUST)           # 岩丘地基
b.flat("m3_g", 7, 3, 0.0, MARS)

b.flat_rect("m4_a", 0, 4, 0.0, MARS)
b.flat_rect("m4_b", 2, 4, 0.0, MARS)
b.flat_rect("m4_c", 4, 4, 0.0, DUST)
b.flat_rect("m4_d", 6, 4, 0.0, MARS)

# =================================================================
# 2. 气闸舱 (x [3,4], y [1,2]): 红外门 + 双侧墙 + 橙内门 + 顶板
# =================================================================
b.add("al_door_s", "door_frame", (3.5, 1.0, 0.5), (90, 0, 0), DOOR_OUT)
b.wall_ew("al_w", 3.0, 1, 0, WALL)
b.wall_ew("al_e", 4.0, 1, 0, WALL)
b.add("al_door_n", "door_frame", (3.5, 2.0, 0.5), (90, 0, 0), DOOR_IN)
b.flat("al_roof", 3, 1, 1.0, WALL)

# =================================================================
# 3. 中央枢纽 (x [3,4], y [2,3]): 三樘互联门 + 顶板锁四门
# =================================================================
b.add("hab_door", "door_frame", (3.5, 3.0, 0.5), (90, 0, 0), DOOR_IN)
b.add("gh_door", "door_frame", (4.0, 2.5, 0.5), (90, 0, 90), DOOR_IN)
b.add("pw_door", "door_frame", (3.0, 2.5, 0.5), (90, 0, 90), DOOR_IN)
b.flat("hub_roof", 3, 2, 1.0, HAB)

# =================================================================
# 4. 穹顶居住舱 (x [3,4], y [3,4]): 三面舷窗 + 透明四坡穹顶
# =================================================================
b.add("hab_w", "window_square", (3.0, 3.5, 0.5), (90, 0, 90), WALL)
b.add("hab_e", "window_square", (4.0, 3.5, 0.5), (90, 0, 90), WALL)
b.add("hab_n", "window_square", (3.5, 4.0, 0.5), (90, 0, 0), WALL)
HAB_DOME = b.hat4("hab_dome", 3, 3, 1.0, GLASS, shape="equilateral_triangle")

# =================================================================
# 5. 能源舱 (x [2,3], y [2,3]): 黄墙三面 + 顶板 + 通讯桅杆
# =================================================================
b.wall_ew("pw_w", 2.0, 2, 0, PWR)
b.wall_ns("pw_s", 2, 2.0, 0, PWR)
b.wall_ns("pw_n", 2, 3.0, 0, PWR)
b.flat("pw_roof", 2, 2, 1.0, WALL)
b.spire_ns("pw_mast", 2, 3.0, 1.0, MAST)   # 杆尖 3.0, 全场最高

# =================================================================
# 6. 玻璃温室 (x [4,6], y [2,3]): 双楣夹房 + 先种作物后封顶
# =================================================================
b.lintel_ns("gh_s", 4, 2.0, 0, GLASS)
b.lintel_ns("gh_n", 4, 3.0, 0, GLASS)
b.wall_ew("gh_e", 6.0, 2, 0, GH_F)
b.crest_ew("gh_crop", 5.0, 2, 0.0, CROP)   # 地缝上的作物
b.flat_rect("gh_roof", 4, 2, 1.0, GLASS)

# =================================================================
# 7. 舱外: 太阳能板墙 + 信标旗 + 巡逻车 + 岩丘
# =================================================================
b.lintel_ns("sol1", 0, 1.0, 0, GLASS)      # 太阳能板墙 (基地南线)
b.lintel_ns("sol2", 4, 1.0, 0, GLASS)
b.crest_ns("beacon", 2, 1.0, 0.0, DOOR_OUT)  # 信标旗

b.add("rov_w1", "wheel_base", (7.0, 1.0, 0.5), (90, 0, 0), ROVER)
b.add("rov_w2", "wheel_base", (7.0, 2.0, 0.5), (90, 0, 0), ROVER)
b.flat_rect("rov_deck", 6, 1, 1.0, DECK)   # 甲板双轮受力
b.crest_ew("rov_ant", 6.0, 1, 1.0, DECK)   # 车头天线

ROCK = b.hat4("rock", 6, 3, 0.0, DUST, shape="equilateral_triangle")

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺荒原南缘 (y [0,1]): 4 片长板, 红色火星地表铺起。",
    ["m0_a", "m0_b", "m0_c", "m0_d"],
    tip="橙色条带是风化带 —— 基地会建在它们北侧。",
)
b.step(
    "铺基地南排 (y [1,2]): 6 片, 灰色气闸地垫就位。",
    ["m1_a", "m1_b", "m1_c", "m1_d", "m1_e", "m1_f"],
    highlight=["m0_b"],
    tip="灰色方板是气闸落点, 东端长板是巡逻车车位。",
)
b.step(
    "铺舱室排 (y [2,3]): 6 片, 五色地垫一字排开。",
    ["m2_a", "m2_b", "m2_c", "m2_d", "m2_e", "m2_f"],
    highlight=["m1_c"],
    tip="黄=能源舱, 青=枢纽, 绿=温室 —— 地垫颜色就是舱位图。",
)
b.step(
    "铺北侧荒原 (y [3,5]): 11 片, 场地合拢。",
    ["m3_a", "m3_b", "m3_c", "m3_d", "m3_e", "m3_f", "m3_g",
     "m4_a", "m4_b", "m4_c", "m4_d"],
    highlight=["m2_c"],
    tip="8x5 荒原铺满, 所有舱墙都压在地板拼缝上。",
)
b.step(
    "立气闸舱: 红色外门朝南, 双侧墙 + 橙色内门 + 顶板。",
    ["al_door_s", "al_w", "al_e", "al_door_n", "al_roof"],
    highlight=["m1_c"],
    tip="出舱必经之路: 外门-侧墙-内门围成 1x1 过渡舱。",
)
b.step(
    "拼中央枢纽: 三樘橙门合围, 顶板四边锁住四门顶。",
    ["hab_door", "gh_door", "pw_door", "hub_roof"],
    highlight=["al_door_n"],
    tip="枢纽四面全是门 —— 每樘门都同时属于两个舱室。",
)
b.step(
    "起穹顶居住舱: 三面舷窗墙 + 4 片透明等边锥穹顶。",
    ["hab_w", "hab_e", "hab_n"] + HAB_DOME,
    highlight=["hab_door"],
    tip="穹顶四棱两两自锁 —— 躺在舱里就能仰望火星星空。",
)
b.step(
    "立能源舱: 黄墙三面 + 顶板, 北沿骑起通讯桅杆。",
    ["pw_w", "pw_s", "pw_n", "pw_roof", "pw_mast"],
    highlight=["pw_door"],
    tip="桅杆底边同时吸顶板北沿与北墙顶, 杆尖 3.0 全场最高。",
)
b.step(
    "建玻璃温室: 双透明横楣夹房, 先种作物再封玻璃顶。",
    ["gh_s", "gh_n", "gh_e", "gh_crop", "gh_roof"],
    highlight=["gh_door"],
    tip="绿色作物先立在地缝上, 玻璃顶最后合拢 —— 顺序别反。",
)
b.step(
    "展开太阳能板墙、插信标旗: 基地南线 3 片。",
    ["sol1", "sol2", "beacon"],
    highlight=["al_door_s"],
    tip="两道透明长板墙底边整边吸地板长边 —— 2 对 2 严丝合缝。",
)
b.step(
    "组装巡逻车: 双轮底座 + 蓝色甲板 + 车头天线。",
    ["rov_w1", "rov_w2", "rov_deck", "rov_ant"],
    highlight=["m1_f"],
    tip="甲板两长边分别压双轮顶边 —— 双端受力像一座小桥。",
)
b.step(
    "堆东侧岩丘 —— 火星互联栖息基地落成!",
    ROCK,
    highlight=["rov_deck"],
    tip="四片等边锥两两自锁成岩丘, 给基地挡住东来的沙暴。",
)

b.finalize(
    model_id="mars_habitat_01",
    name="火星互联栖息基地",
    name_en="Mars Habitat 01",
    description=(
        "全库第一座多舱互联基地: 五个舱室以中央枢纽为心拼成十字, "
        "枢纽四面全是门框方舱门 (北穹顶居住舱 / 东玻璃温室 / 南气闸 / "
        "西能源舱), 枢纽顶板四边压四门顶把基地锁成一体; 居住舱三面"
        "舷窗戴透明四坡穹顶, 温室双透明横楣夹房、先种作物后封玻璃顶, "
        "气闸红外门橙内门双门串联, 能源舱顶骑通讯桅杆 (杆尖 3.0); "
        "舱外双轮巡逻车甲板双端受力、太阳能板墙沿南线展开、四坡岩丘"
        "把守东侧 —— 在红色荒原上安下第一个家。"
    ),
    difficulty=3,
    tags=["航天", "火星", "基地", "科学探索", "进阶"],
    min_pieces=64,
    min_steps=12,
)
