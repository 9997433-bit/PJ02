#!/usr/bin/env python3
"""生成模型 data/models/castle_tower_01.json (土丘要塞主塔)。

中世纪/城堡主题: 全库第一座 "土丘-城塞" (motte-and-bailey) 主塔 ——
与 castle_foundation_01 (平地四面围墙) / great_wall_01 (线性墙体
连敌楼) 的结构逻辑刻意区分: 本作先夯一座 3x3 石砌土丘 (环墙 +
满铺台面), 主塔再从丘顶拔起 —— 塔基比地面高一层, 这就是诺曼
城堡的 "居高临下"; 2x2 主塔偏踞丘顶西南, 空出的 L 形台面成为
环塔哨道; 一条 30 度马道从丘顶直下南坡, 塔顶再起 1x1 瞭望
角楼、戴等腰四坡尖顶 (塔尖 5.94 全场最高)。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 地面 (x [0,6], y [0,5]): 草甸 + 丘前石板路 5 行             18 片
  - 土丘环墙 (x [1,4], y [1,4], z 0..1): 石砌立墙 x12           12 片
  - 丘顶台面 (z=1): 九宫格满铺 x9                                9 片
  - 马道: 30 度长方形坡道 x1 (南坡直下, 坡尾自然落地)             1 片
  - 主塔 (x [1,3], y [1,3], z 1..3): 两层墙环 x16 (含门框方
    塔门 x1 + 窗格方了望窗 x2)                                  16 片
  - 塔顶平台 (z=3): 方板 x4 + 女儿墙城齿 x4                      8 片
  - 瞭望角楼 (x [1,2], y [1,2], z 3..4): 墙环 x4 (含窗格方 x1)
    + 等腰四坡尖顶 x4 (塔尖 5.94)                                8 片
  - 哨道城齿 (z=1 台面沿口): 等边三角 x3                          3 片
  合计 75 片, 13 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, strict 档同样全绿):
  - 土丘环墙四角竖边互吸闭环, 台面每片同时压墙顶与邻板拼缝;
  - 主塔每层 8 片墙环四角互吸, 底层同时吸台面拼缝 (南/西沿还
    与土丘墙顶共线三重吸合), 层层成环无单点失效;
  - 马道顶边整边吸台面南沿 + 土丘墙顶 (一线双吸), 坡尾落地;
  - 角楼踩塔顶板缝再起一环, 尖顶四棱两两互吸自锁;
  - 全部城齿与墙共面, 重心正压铰链线, 力矩为零。

用法: python3 tools/generate_castle_tower.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

GRASS = "green"     # 草甸
PATH = "gray"       # 丘前石板路
MOUND = "gray"      # 土丘石砌
DECK = "gray"       # 丘顶台面
KEEP1 = "blue"      # 主塔第 1 层
KEEP2 = "blue"      # 主塔第 2 层
DOOR = "orange"     # 门框方塔门
WIN = "clear"       # 窗格方了望窗
TOP = "purple"      # 塔顶平台 / 角楼
CREST = "yellow"    # 城齿
SPIRE = "red"       # 角楼尖顶
RAMP = "gray"       # 马道

# =================================================================
# 1. 地面 (x [0,6], y [0,5]): 5 行; 中间三行留 x=1 / x=4 拼缝
# =================================================================
for r, ys in (("gr0", 0), ("gr4", 4)):
    b.flat_rect(f"{r}_a", 0, ys, 0.0, GRASS)
    b.flat_rect(f"{r}_b", 2, ys, 0.0, PATH if ys == 0 else GRASS)
    b.flat_rect(f"{r}_c", 4, ys, 0.0, GRASS)
for r, ys in (("gr1", 1), ("gr2", 2), ("gr3", 3)):
    b.flat(f"{r}_a", 0, ys, 0.0, GRASS)
    b.flat_rect(f"{r}_b", 1, ys, 0.0, GRASS)
    b.flat(f"{r}_c", 3, ys, 0.0, GRASS)
    b.flat_rect(f"{r}_d", 4, ys, 0.0, GRASS)

# =================================================================
# 2. 土丘环墙 (x [1,4], y [1,4], z 0..1) + 丘顶台面 + 马道
# =================================================================
for x in (1, 2, 3):
    b.wall_ns(f"mo_s_{x}", x, 1.0, 0, MOUND)
    b.wall_ns(f"mo_n_{x}", x, 4.0, 0, MOUND)
for y in (1, 2, 3):
    b.wall_ew(f"mo_w_{y}", 1.0, y, 0, MOUND)
    b.wall_ew(f"mo_e_{y}", 4.0, y, 0, MOUND)
for x in (1, 2, 3):
    for y in (1, 2, 3):
        b.flat(f"pf_{x}_{y}", x, y, 1.0, DECK)
b.ramp("ramp", "-y", 1.0, 2, 1.0, RAMP)

# =================================================================
# 3. 主塔 (x [1,3], y [1,3], z 1..3): 两层墙环
#    第 1 层东面开门框方塔门 (通向东侧哨道)
# =================================================================
b.wall_ns("kp1_s_1", 1, 1.0, 1, KEEP1)
b.wall_ns("kp1_s_2", 2, 1.0, 1, KEEP1)
b.wall_ns("kp1_n_1", 1, 3.0, 1, KEEP1)
b.wall_ns("kp1_n_2", 2, 3.0, 1, KEEP1)
b.wall_ew("kp1_w_1", 1.0, 1, 1, KEEP1)
b.wall_ew("kp1_w_2", 1.0, 2, 1, KEEP1)
b.add("kp1_gate", "door_frame", (3.0, 1.5, 1.5), (90, 0, 90), DOOR)
b.wall_ew("kp1_e_2", 3.0, 2, 1, KEEP1)

b.add("kp2_s_1", "window_square", (1.5, 1.0, 2.5), (90, 0, 0), WIN)
b.wall_ns("kp2_s_2", 2, 1.0, 2, KEEP2)
b.wall_ns("kp2_n_1", 1, 3.0, 2, KEEP2)
b.wall_ns("kp2_n_2", 2, 3.0, 2, KEEP2)
b.wall_ew("kp2_w_1", 1.0, 1, 2, KEEP2)
b.wall_ew("kp2_w_2", 1.0, 2, 2, KEEP2)
b.add("kp2_e_1", "window_square", (3.0, 1.5, 2.5), (90, 0, 90), WIN)
b.wall_ew("kp2_e_2", 3.0, 2, 2, KEEP2)

# =================================================================
# 4. 塔顶平台 (z=3) + 女儿墙城齿 + 瞭望角楼 + 尖顶
# =================================================================
for x in (1, 2):
    for y in (1, 2):
        b.flat(f"tp_{x}_{y}", x, y, 3.0, TOP)
b.crest_ns("pc_s", 2, 1.0, 3.0, CREST)
b.crest_ew("pc_e", 3.0, 2, 3.0, CREST)
b.crest_ns("pc_n", 2, 3.0, 3.0, CREST)
b.crest_ew("pc_w", 1.0, 2, 3.0, CREST)

b.wall_ns("tr_s", 1, 1.0, 3, TOP)
b.wall_ns("tr_n", 1, 2.0, 3, TOP)
b.wall_ew("tr_w", 1.0, 1, 3, TOP)
b.add("tr_e", "window_square", (2.0, 1.5, 3.5), (90, 0, 90), WIN)
SPIRE_IDS = b.hat4("spire", 1, 1, 4.0, SPIRE)

# =================================================================
# 5. 哨道城齿 (z=1, 台面东沿与北沿)
# =================================================================
b.crest_ew("wc_e1", 4.0, 1, 1.0, CREST)
b.crest_ew("wc_e2", 4.0, 3, 1.0, CREST)
b.crest_ns("wc_n", 3, 4.0, 1.0, CREST)

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺草甸南行 (y [0,1]): 3 片长板, 灰色石板路对准马道。",
    ["gr0_a", "gr0_b", "gr0_c"],
    tip="石板路 (x [2,4]) 是上丘马道的起点。",
)
b.step(
    "铺草甸中段两行 (y [1,3]): 8 片, 土丘环墙踩这里的拼缝。",
    ["gr1_a", "gr1_b", "gr1_c", "gr1_d",
     "gr2_a", "gr2_b", "gr2_c", "gr2_d"],
    highlight=["gr0_b"],
    tip="x=1 与 x=4 的拼缝就是土丘墙脚 —— 布局从地面开始。",
)
b.step(
    "铺草甸北段两行 (y [3,5]): 7 片, 地面合拢。",
    ["gr3_a", "gr3_b", "gr3_c", "gr3_d", "gr4_a", "gr4_b", "gr4_c"],
    highlight=["gr2_a"],
    tip="6x5 草甸铺满 —— 诺曼人先选地, 再夯丘。",
)
b.step(
    "砌土丘南墙与西墙: 6 片石砌立墙踩拼缝, 转角竖边互吸。",
    ["mo_s_1", "mo_s_2", "mo_s_3", "mo_w_1", "mo_w_2", "mo_w_3"],
    highlight=["gr1_b", "gr2_b"],
    tip="土丘是整座要塞的地基 —— 每片底边吸缝、侧边咬邻片。",
)
b.step(
    "砌土丘北墙与东墙: 再 6 片, 环墙四角闭合。",
    ["mo_n_1", "mo_n_2", "mo_n_3", "mo_e_1", "mo_e_2", "mo_e_3"],
    highlight=["mo_s_1", "mo_w_3"],
    tip="闭合环墙是丘体的骨架 —— 轻推应整体联动。",
)
b.step(
    "满铺丘顶台面: 9 片方板先围一圈再补正中。",
    ["pf_1_1", "pf_2_1", "pf_3_1", "pf_1_2", "pf_3_2",
     "pf_1_3", "pf_2_3", "pf_3_3", "pf_2_2"],
    highlight=["mo_s_2", "mo_n_2"],
    tip="每片同时压墙顶与邻板拼缝 —— 台面就是主塔的新地面。",
)
b.step(
    "搭马道 + 立哨道城齿: 30 度坡道顶边吸台面南沿, 坡尾落地。",
    ["ramp", "wc_e1", "wc_e2", "wc_n"],
    highlight=["pf_2_1", "pf_3_1"],
    tip="马道一线双吸 (台面沿 + 墙顶); 东、北沿口的城齿守住哨道。",
)
b.step(
    "起主塔第 1 层: 8 片墙环踞丘顶西南, 东面开门框方塔门。",
    ["kp1_s_1", "kp1_s_2", "kp1_w_1", "kp1_w_2",
     "kp1_n_1", "kp1_n_2", "kp1_gate", "kp1_e_2"],
    highlight=["pf_1_1", "pf_2_2"],
    tip="塔门朝东正对哨道 —— 上丘、过哨道、进塔一条动线。",
)
b.step(
    "叠主塔第 2 层: 8 片墙环, 南面与东面嵌窗格方了望窗。",
    ["kp2_s_1", "kp2_s_2", "kp2_w_1", "kp2_w_2",
     "kp2_n_1", "kp2_n_2", "kp2_e_1", "kp2_e_2"],
    highlight=["kp1_gate"],
    tip="两扇了望窗盯住南坡与东哨道 —— 居高临下。",
)
b.step(
    "盖塔顶平台: 4 片方板压第 2 层墙顶。",
    ["tp_1_1", "tp_2_1", "tp_1_2", "tp_2_2"],
    highlight=["kp2_s_1", "kp2_n_2"],
    tip="每片同时吸两段墙顶与邻板拼缝 —— 多路受力。",
)
b.step(
    "装女儿墙城齿: 4 片黄色等边三角骑上平台四沿。",
    ["pc_s", "pc_e", "pc_n", "pc_w"],
    highlight=["tp_2_1", "tp_1_2"],
    tip="城齿沿口避开西南角 —— 那里要起瞭望角楼。",
)
b.step(
    "起瞭望角楼: 4 片墙环踩塔顶板缝, 东面嵌窗格方。",
    ["tr_s", "tr_n", "tr_w", "tr_e"],
    highlight=["tp_1_1"],
    tip="角楼又比塔顶高一层 —— 要塞的眼睛。",
)
b.step(
    "戴等腰四坡尖顶: 塔尖 5.94, 全场最高 —— 主塔落成!",
    SPIRE_IDS,
    highlight=["tr_s", "tr_e"],
    tip="四条斜棱两两互吸自锁; 红色塔尖十里可见。",
)

b.finalize(
    model_id="castle_tower_01",
    name="土丘要塞主塔",
    name_en="Motte Castle Tower 01",
    description=(
        "全库第一座土丘-城塞主塔: 先夯 3x3 石砌土丘 (环墙互吸 +"
        " 九宫格台面满铺), 2x2 主塔再从丘顶拔起两层墙环 —— 塔基"
        "比地面高一层, 居高临下; 主塔偏踞西南, 空出 L 形哨道由"
        "城齿护沿, 30 度马道从丘顶直下南坡; 塔顶女儿墙围平台,"
        " 西南角再起 1x1 瞭望角楼戴等腰四坡尖顶 (塔尖 5.94 全场"
        "最高)。垫高地基、偏置塔身、环环相扣 —— 诺曼要塞一课学会。"
    ),
    difficulty=3,
    tags=["中世纪", "城堡", "塔楼", "土丘要塞", "进阶"],
    min_pieces=72,
    min_steps=13,
)
