#!/usr/bin/env python3
"""生成模型 data/models/fountain_plaza_01.json (音乐喷泉广场)。

城市生活主题: 全库第一座水景广场 —— 7x7 石板广场正中央, 3x3
喷泉水池由 12 片青色池壁围成闭合环 (四角竖边互吸), 池心立起
两节透明水柱、顶端绽开水花; 四条透明 30 度水舌从池壁顶沿口
向四方划出抛物线落回广场 (顶边整边吸池壁顶, 坡尾接地斜撑);
南池沿竖起六边形音乐水幕屏, 广场对角摆着两只直角三角音响,
四角路灯挑亮暖黄灯冠, 两畦粉色花丘四坡自锁 —— 音乐响起,
水随声舞!

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 广场地坪 7x7: 走道长板 x16 + 走道方板 x10 + 水面方板 x9   35 片
  - 喷泉池壁: 四面各 3 片青色立墙, 四角竖边互吸闭环 (z0..1)   12 片
  - 中央水柱: 透明立板 x2 节 + 顶端水花三角 x1                 3 片
  - 水舌: 透明 30 度斜板 x4 (四方各一条)                       4 片
  - 音乐水幕屏: 六边形 x1 (立在南池沿口)                       1 片
  - 音响: 直角三角斜面 x2 (对角摆放, 整边吸地坪拼缝)           2 片
  - 路灯: 方板灯柱 x4 + 等边三角灯冠 x4 (四角)                 8 片
  - 花丘: 等边四坡锥 x2 (对角两畦, 每畦 4 片)                  8 片
  合计 73 片, 17 个教程步骤, 5 种磁力片形状 (迁移期不使用等腰片)。

物理规则要点 (通过 R1~R8 全部校验):
  - 全模型遵循 整边吸合 纪律: 池壁踩水面方板与走道的拼缝,
    四角竖边互吸锁成闭合环 (结构冗余);
  - 水舌顶边整边吸池壁顶 (长 1 整边), 坡尾自然落地 —— 顶铰
    链 + 接地斜撑, 水舌越冲越稳;
  - 中央水柱两节叠立 (上节底边整边吸下节顶边), 水花三角与
    六边形水幕屏重心都正压铰链线、力臂为零;
  - 音响直角边整边吸走道拼缝, 花丘四坡三角四棱互吸自锁。

用法: python3 tools/generate_fountain_plaza.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

PAVE = "gray"       # 石板走道
WATER = "blue"      # 池中水面
BASIN = "cyan"      # 池壁
JET = "clear"       # 水柱 / 水舌
LAMP = "yellow"     # 灯冠
POST = "gray"       # 灯柱
FLOWER = "pink"     # 花丘
SCREEN = "purple"   # 音乐水幕屏
SPK = "orange"      # 音响

# =================================================================
# 1. 广场地坪 7x7: 边行 方板+长板, 中五行 长板+方板x3+长板
#    (水池 [2,5]x[2,5], 池心 9 格为蓝色水面)
# =================================================================
for y in (0, 6):
    b.flat(f"pv_c0_{y}", 0, y, 0.0, PAVE)           # [0,1] 角格
    b.flat_rect(f"pv_a_{y}", 1, y, 0.0, PAVE)       # [1,3]
    b.flat(f"pv_m_{y}", 3, y, 0.0, PAVE)            # [3,4]
    b.flat_rect(f"pv_b_{y}", 4, y, 0.0, PAVE)       # [4,6]
    b.flat(f"pv_c6_{y}", 6, y, 0.0, PAVE)           # [6,7] 角格
for y in range(1, 6):
    b.flat_rect(f"pv_w_{y}", 0, y, 0.0, PAVE)       # [0,2]
    color = WATER if 2 <= y <= 4 else PAVE
    for x in (2, 3, 4):
        b.flat(f"ct_{x}_{y}", x, y, 0.0, color)     # 中三格
    b.flat_rect(f"pv_e_{y}", 5, y, 0.0, PAVE)       # [5,7]

# =================================================================
# 2. 喷泉池壁 (z0..1): 围合 [2,5]x[2,5], 四角竖边互吸闭环
# =================================================================
for x in (2, 3, 4):
    b.wall_ns(f"bs_s_{x}", x, 2.0, 0, BASIN)        # 南池壁
    b.wall_ns(f"bs_n_{x}", x, 5.0, 0, BASIN)        # 北池壁
for y in (2, 3, 4):
    b.wall_ew(f"bs_w_{y}", 2.0, y, 0, BASIN)        # 西池壁
    b.wall_ew(f"bs_e_{y}", 5.0, y, 0, BASIN)        # 东池壁

# =================================================================
# 3. 中央水柱: 两节透明立板叠立 + 顶端水花三角
# =================================================================
b.wall_ns("wc_0", 3, 3.0, 0, JET)                   # 水柱下节
b.wall_ns("wc_1", 3, 3.0, 1, JET)                   # 水柱上节
b.crest_ns("wc_top", 3, 3.0, 2.0, JET)              # 顶端水花

# =================================================================
# 4. 水舌: 四条透明 30 度斜板, 顶边整边吸池壁顶, 坡尾落地
# =================================================================
b.ramp("jet_s", "-y", 2.0, 3, 1.0, JET)             # 南舌 (尾 y=0.27)
b.ramp("jet_n", "+y", 5.0, 3, 1.0, JET)             # 北舌 (尾 y=6.73)
b.ramp("jet_w", "-x", 2.0, 3, 1.0, JET)             # 西舌 (尾 x=0.27)
b.ramp("jet_e", "+x", 5.0, 3, 1.0, JET)             # 东舌 (尾 x=6.73)

# =================================================================
# 5. 音乐水幕屏 + 音响
# =================================================================
b.place_edge("screen", "hexagon", 4,
             (4.0, 2.0, 1.0), (5.0, 2.0, 1.0), (0.0, 0.0, 1.0), SCREEN)
b.brace("spk_w", (2.0, 1.0, 0.0), "+y", SPK)        # 西南音响 (x=2 缝)
b.brace("spk_e", (5.0, 5.0, 0.0), "+y", SPK)        # 东北音响 (x=5 缝)

# =================================================================
# 6. 路灯: 四角灯柱 + 灯冠
# =================================================================
b.wall_ns("lp_sw", 0, 0.0, 0, POST)                 # 西南灯柱
b.crest_ns("lc_sw", 0, 0.0, 1.0, LAMP)
b.wall_ns("lp_se", 6, 0.0, 0, POST)                 # 东南灯柱
b.crest_ns("lc_se", 6, 0.0, 1.0, LAMP)
b.wall_ns("lp_nw", 0, 7.0, 0, POST)                 # 西北灯柱
b.crest_ns("lc_nw", 0, 7.0, 1.0, LAMP)
b.wall_ns("lp_ne", 6, 7.0, 0, POST)                 # 东北灯柱
b.crest_ns("lc_ne", 6, 7.0, 1.0, LAMP)

# =================================================================
# 7. 花丘: 对角两畦等边四坡锥
# =================================================================
FL_SW = b.hat4("fl_sw", 2, 1, 0.0, FLOWER,
               shape="equilateral_triangle")        # [2,3]x[1,2]
FL_NE = b.hat4("fl_ne", 4, 5, 0.0, FLOWER,
               shape="equilateral_triangle")        # [4,5]x[5,6]

# =================================================================
# 教程步骤 (17 步)
# =================================================================
b.step(
    "铺广场南段: 南沿行 5 片 + 第二行 5 片 (长板走道, 中三格方板)。",
    ["pv_c0_0", "pv_a_0", "pv_m_0", "pv_b_0", "pv_c6_0",
     "pv_w_1", "ct_2_1", "ct_3_1", "ct_4_1", "pv_e_1"],
    tip="角格必须用方板 —— 灯柱脚要踩一条整板边。",
)
b.step(
    "铺广场中段: 2 行 长板+方板x3+长板, 中央 6 格换蓝色水面板。",
    [tid for y in (2, 3)
     for tid in (f"pv_w_{y}", f"ct_2_{y}", f"ct_3_{y}", f"ct_4_{y}",
                 f"pv_e_{y}")],
    highlight=["ct_3_1", "pv_w_1"],
    tip="蓝色方板就是未来的池底 —— 拼缝正是池壁的落脚线。",
)
b.step(
    "铺广场次北段: 水面第三行 + 北走道行, 共 10 片。",
    ["pv_w_4", "ct_2_4", "ct_3_4", "ct_4_4", "pv_e_4",
     "pv_w_5", "ct_2_5", "ct_3_5", "ct_4_5", "pv_e_5"],
    highlight=["ct_2_3", "ct_4_3"],
    tip="9 格蓝色水面到此铺齐 —— 池壁马上沿着它的边缘升起。",
)
b.step(
    "铺广场北沿: 最后 5 片, 广场合拢成 7x7。",
    ["pv_c0_6", "pv_a_6", "pv_m_6", "pv_b_6", "pv_c6_6"],
    highlight=["pv_w_5", "pv_e_5"],
    tip="七七四十九格 —— 音乐喷泉的舞台就绪。",
)
b.step(
    "砌南北池壁: 沿水面板拼缝各立 3 片青色立墙。",
    ["bs_s_2", "bs_s_3", "bs_s_4", "bs_n_2", "bs_n_3", "bs_n_4"],
    highlight=["ct_2_2", "ct_4_4"],
    tip="墙脚整边吸水面板边 —— 池壁围的就是这 9 格水。",
)
b.step(
    "砌东西池壁: 各立 3 片, 四角竖边互吸 —— 水池闭环。",
    ["bs_w_2", "bs_w_3", "bs_w_4", "bs_e_2", "bs_e_3", "bs_e_4"],
    highlight=["bs_s_2", "bs_n_4"],
    tip="转角两片墙的竖边磁力相扣 —— 闭合环是最强的结构。",
)
b.step(
    "立中央水柱下节: 池心拼缝上立 1 片透明立板。",
    ["wc_0"],
    highlight=["ct_3_3"],
    tip="水柱踩在池心 9 格的正中拼缝上 —— 喷泉的心脏。",
)
b.step(
    "接水柱上节: 再叠 1 片, 底边整边吸下节顶边。",
    ["wc_1"],
    highlight=["wc_0"],
    tip="两节叠立冲出池口 —— 主喷已经高过池壁一整格。",
)
b.step(
    "绽水花: 水柱顶端立 1 片透明三角。",
    ["wc_top"],
    highlight=["wc_1"],
    tip="重心正压柱顶铰链, 力臂为零 —— 水花在最高点绽开。",
)
b.step(
    "放南北水舌: 2 片透明斜板顶边整边吸池壁顶, 坡尾落回广场。",
    ["jet_s", "jet_n"],
    highlight=["bs_s_3", "bs_n_3"],
    tip="顶铰链 + 接地斜撑 —— 水舌划出的正是抛物线。",
)
b.step(
    "放东西水舌: 再挂 2 片, 四方水舌同时起舞。",
    ["jet_w", "jet_e"],
    highlight=["bs_w_3", "bs_e_3"],
    tip="四条水舌对称受力 —— 池壁环被拉得更稳。",
)
b.step(
    "竖音乐水幕屏: 南池沿口立起紫色六边形。",
    ["screen"],
    highlight=["bs_s_4"],
    tip="六边形重心正压池壁顶铰链 —— 灯光音乐都投在这面水幕上。",
)
b.step(
    "摆音响: 对角 2 只橙色直角三角斜面, 直角边整边吸走道拼缝。",
    ["spk_w", "spk_e"],
    highlight=["pv_w_1", "pv_e_5"],
    tip="斜面朝外 —— 声浪盖过水声, 这才叫音乐喷泉。",
)
b.step(
    "立南侧路灯: 两角各竖灯柱、点亮灯冠。",
    ["lp_sw", "lc_sw", "lp_se", "lc_se"],
    highlight=["pv_c0_0", "pv_c6_0"],
    tip="灯柱整边吸角格板边, 灯冠正压柱顶 —— 广场亮起来了。",
)
b.step(
    "立北侧路灯: 再点亮两盏, 四角灯火合围。",
    ["lp_nw", "lc_nw", "lp_ne", "lc_ne"],
    highlight=["pv_c0_6", "pv_c6_6"],
    tip="四盏路灯对角呼应 —— 夜场喷泉秀开演。",
)
b.step(
    "堆西南花丘: 4 片粉色等边三角四棱互吸, 合拢成一畦花丘。",
    FL_SW,
    highlight=["pv_a_0"],
    tip="四坡自锁 —— 花丘就堆在南水舌旁边, 溅点水花更娇艳。",
)
b.step(
    "堆东北花丘: 对角再堆一畦 —— 音乐响起, 水随声舞!",
    FL_NE,
    highlight=[FL_SW[0]],
    tip="两畦花丘对角呼应 —— 广场的最后一抹颜色。",
)

b.finalize(
    model_id="fountain_plaza_01",
    name="音乐喷泉广场",
    name_en="Musical Fountain Plaza 01",
    description=(
        "全库第一座水景广场: 7x7 石板广场中央, 12 片青色池壁四角竖边互吸"
        "围成闭合水池, 池心两节透明水柱顶端绽开水花, 四条透明 30 度水舌"
        "从池壁顶沿口向四方划出抛物线落回广场 (顶铰链 + 接地斜撑); 南池沿"
        "竖起六边形音乐水幕屏, 对角两只直角三角音响, 四角路灯挑亮暖黄"
        "灯冠, 两畦粉色花丘四坡自锁 —— 音乐响起, 水随声舞!"
    ),
    difficulty=3,
    tags=["城市生活", "喷泉", "广场", "水景", "进阶"],
    min_pieces=70,
    min_steps=16,
)
