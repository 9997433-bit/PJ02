#!/usr/bin/env python3
"""生成模型 data/models/conveyor_factory_01.json (传送带车间).

工程结构主题: 全库第一条工厂流水线 —— 蓝色厂房两面锯齿天窗墙
之间, 一条绿色传送带横贯车间: 西端 30 度上料坡道贴地起跑,
四座灰色托架墙把带面逐段顶到 1 格高, 带面上橙红两枚三角包裹
正在行进, 东端落进红色卸料仓 (托架兼作仓壁的闭合环); 带尾
方台上四坡礼盒即将封箱, 厂区东南角控制室亮着警示灯, 烟囱
塔尖直指 3 格高空 —— 开机, 整条流水线跑起来!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 带头朝东):
  - 车间地坪 9x4: 长板收边 + 方板铺作业区                     30 片
  - 厂房墙: 南北各 5 片蓝色立墙 (x2..7)                       10 片
  - 锯齿天窗: 透明等边三角 x6 (南北错位各 3 片)                6 片
  - 传送带托架: 灰色立墙 x4 (x=2/4/6/7, 底边整边吸拼缝)        4 片
  - 带面: 长板 x2 + 方板 x1 (逐段双端搭托架顶)                 3 片
  - 上料坡道: 30 度长板 x1 (顶边整边吸托架顶, 坡尾接地)        1 片
  - 包裹: 等边三角 x2 (立带面拼缝) + 四坡礼盒 x4               6 片
  - 卸料仓: 立墙 x3 (与东托架合围成闭合环)                     3 片
  - 控制室: 立墙 x4 + 方板顶 x1 + 警示灯三角 x1                6 片
  - 烟囱: 方墙 x1 + 等腰塔尖 x1 (尖端 3.0)                     2 片
  合计 71 片, 15 个教程步骤, 5 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验, default + strict 双档):
  - 带面逐段双端受力: 每段长板两条短边分别搭在相邻托架顶上,
    任何中间状态都不存在悬臂 (先立托架、后搭带面);
  - 上料坡道顶边整边吸托架顶、坡尾接地 (音乐喷泉水舌同款
    顶铰链 + 接地斜撑), 包裹三角立在带面拼缝上重心正压铰链;
  - 卸料仓复用东端托架作西壁, 四面竖边互吸闭合环;
  - 烟囱尖端 3.0 触发 R8 高层检查: 全模型环冗余充足, 零警告。

用法: python3 tools/generate_conveyor_factory.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

FLOOR = "gray"      # 车间地坪
LANE = "cyan"       # 流水线作业带地坪
HALL = "blue"       # 厂房墙
SKY = "clear"       # 锯齿天窗
TRESTLE = "gray"    # 传送带托架
BELT = "green"      # 带面 / 坡道
PKG_A = "orange"    # 包裹
PKG_B = "red"       # 包裹 / 卸料仓
GIFT = "yellow"     # 四坡礼盒
CTRL = "purple"     # 控制室
STACK = "gray"      # 烟囱

# =================================================================
# 1. 车间地坪 9x4: 南北收边行 7 片, 中间两行方板通铺
#    (拼缝 x=2..8 是托架/仓壁/控制室的落点)
# =================================================================
for y in (0, 3):
    b.flat_rect(f"fl_w_{y}", 0, y, 0.0, FLOOR)      # [0,2]
    for x in range(2, 7):
        b.flat(f"fl_{x}_{y}", x, y, 0.0, FLOOR)     # [2,7] 方板
    b.flat_rect(f"fl_e_{y}", 7, y, 0.0, FLOOR)      # [7,9]
for y in (1, 2):
    color = LANE if y == 1 else FLOOR
    b.flat_rect(f"fl_w_{y}", 0, y, 0.0, color)      # [0,2]
    for x in range(2, 9):
        b.flat(f"fl_{x}_{y}", x, y, 0.0, color)     # [2,9] 方板

# =================================================================
# 2. 厂房墙: 南北各 5 片蓝色立墙 (x2..7, 底边整边吸地坪格边)
# =================================================================
for x in range(2, 7):
    b.wall_ns(f"hw_s_{x}", x, 0.0, 0, HALL)         # 南墙 (y=0)
    b.wall_ns(f"hw_n_{x}", x, 4.0, 0, HALL)         # 北墙 (y=4)

# =================================================================
# 3. 锯齿天窗: 南北墙顶错位各立 3 片透明等边三角
# =================================================================
for x in (2, 4, 6):
    b.crest_ns(f"saw_s_{x}", x, 0.0, 1.0, SKY)      # 南锯齿
for x in (3, 5):
    b.crest_ns(f"saw_n_{x}", x, 4.0, 1.0, SKY)      # 北锯齿
b.crest_ns("saw_n_7", 6, 4.0, 1.0, SKY)             # 北锯齿收尾

# =================================================================
# 4. 传送带托架: x=2/4/6/7 拼缝各立 1 片灰色立墙 (y1..2)
# =================================================================
for x in (2, 4, 6, 7):
    b.wall_ew(f"tr_{x}", float(x), 1, 0, TRESTLE)

# =================================================================
# 5. 带面 (z=1): 2 片长板 + 1 片方板, 逐段双端搭托架顶
# =================================================================
b.flat_rect("belt_a", 2, 1, 1.0, BELT)              # [2,4]x[1,2]
b.flat_rect("belt_b", 4, 1, 1.0, BELT)              # [4,6]x[1,2]
b.flat("belt_c", 6, 1, 1.0, BELT)                   # [6,7]x[1,2]

# =================================================================
# 6. 上料坡道: 顶边整边吸西托架顶, 坡尾落地 (x=0.27)
# =================================================================
b.ramp("feed", "-x", 2.0, 1, 1.0, BELT)

# =================================================================
# 7. 包裹: 带面拼缝立 2 片三角 + 带尾方台四坡礼盒
# =================================================================
b.crest_ew("pkg_a", 4.0, 1, 1.0, PKG_A)             # x=4 拼缝
b.crest_ew("pkg_b", 6.0, 1, 1.0, PKG_B)             # x=6 拼缝
GIFT_IDS = b.hat4("gift", 6, 1, 1.0, GIFT,
                  shape="equilateral_triangle")     # 带尾礼盒

# =================================================================
# 8. 卸料仓: [7,8]x[1,2] 三面立墙, 与东托架 (x=7) 合围闭环
# =================================================================
b.wall_ns("bin_s", 7, 1.0, 0, PKG_B)
b.wall_ns("bin_n", 7, 2.0, 0, PKG_B)
b.wall_ew("bin_e", 8.0, 1, 0, PKG_B)

# =================================================================
# 9. 控制室: [8,9]x[2,3] 闭合环 + 方板顶 + 警示灯
# =================================================================
b.wall_ns("ct_s", 8, 2.0, 0, CTRL)
b.wall_ns("ct_n", 8, 3.0, 0, CTRL)
b.wall_ew("ct_w", 8.0, 2, 0, CTRL)
b.wall_ew("ct_e", 9.0, 2, 0, CTRL)
b.flat("ct_roof", 8, 2, 1.0, CTRL)
b.crest_ew("ct_lamp", 8.0, 2, 1.0, PKG_B)           # 警示灯 (西沿)

# =================================================================
# 10. 烟囱: 方墙 + 等腰塔尖 (y=1 拼缝, 尖端 3.0)
# =================================================================
b.wall_ns("stk_0", 8, 1.0, 0, STACK)
b.spire_ns("stk_tip", 8, 1.0, 1.0, STACK)

# =================================================================
# 教程步骤 (15 步)
# =================================================================
b.step(
    "铺地坪南沿行: 长板 + 方板x5 + 长板, 共 7 片。",
    ["fl_w_0"] + [f"fl_{x}_0" for x in range(2, 7)] + ["fl_e_0"],
    tip="方板区 x2..7 的格边就是厂房南墙的落脚线。",
)
b.step(
    "铺流水线行: 青色作业带一行 8 片 (长板 + 方板x7)。",
    ["fl_w_1"] + [f"fl_{x}_1" for x in range(2, 9)],
    highlight=["fl_2_0", "fl_6_0"],
    tip="青色地带正上方 1 格高处, 就是未来的传送带面。",
)
b.step(
    "铺第三行: 再铺 8 片, 拼缝与流水线行严格对齐。",
    ["fl_w_2"] + [f"fl_{x}_2" for x in range(2, 9)],
    highlight=["fl_2_1", "fl_8_1"],
    tip="托架墙要同时咬住这两行的拼缝 —— 一格都不能错位。",
)
b.step(
    "铺地坪北沿行: 7 片收边, 车间地坪合拢成 9x4。",
    ["fl_w_3"] + [f"fl_{x}_3" for x in range(2, 7)] + ["fl_e_3"],
    highlight=["fl_2_2", "fl_6_2"],
    tip="地坪就是流水线的图纸 —— 每条拼缝都有用。",
)
b.step(
    "立南厂房墙: 5 片蓝色立墙, 底边整边吸南沿格边。",
    [f"hw_s_{x}" for x in range(2, 7)],
    highlight=["fl_2_0", "fl_6_0"],
    tip="相邻立墙竖边互吸 —— 整面墙连成一体。",
)
b.step(
    "立北厂房墙: 对面再立 5 片, 车间两面围合。",
    [f"hw_n_{x}" for x in range(2, 7)],
    highlight=["hw_s_2", "hw_s_6"],
    tip="南北墙相距 4 格 —— 中间留给流水线与叉车通道。",
)
b.step(
    "装锯齿天窗: 南墙顶 3 片、北墙顶 3 片透明三角错位而立。",
    ["saw_s_2", "saw_s_4", "saw_s_6", "saw_n_3", "saw_n_5", "saw_n_7"],
    highlight=["hw_s_2", "hw_n_6"],
    tip="锯齿形天窗是老厂房的招牌 —— 北向采光不刺眼。",
)
b.step(
    "立传送带托架: x=2/4/6/7 拼缝各立 1 片灰墙, 共 4 片。",
    ["tr_2", "tr_4", "tr_6", "tr_7"],
    highlight=["fl_2_1", "fl_7_1"],
    tip="托架底边整边咬住两行拼缝 —— 先立支点, 再搭带面。",
)
b.step(
    "搭带面: 2 片长板 + 1 片方板, 每段两端稳稳压在托架顶上。",
    ["belt_a", "belt_b", "belt_c"],
    highlight=["tr_2", "tr_7"],
    tip="逐段双端受力, 零悬挑 —— 这是流水线的钢骨脊梁。",
)
b.step(
    "接上料坡道: 30 度绿色长板顶边整边吸西托架顶, 坡尾贴地。",
    ["feed"],
    highlight=["tr_2", "belt_a"],
    tip="顶铰链 + 接地斜撑 —— 原料从地面一路爬上带面。",
)
b.step(
    "放行进包裹: 带面两条拼缝上各立 1 枚三角包裹。",
    ["pkg_a", "pkg_b"],
    highlight=["belt_a", "belt_c"],
    tip="包裹重心正压拼缝铰链线 —— 带面开动也不倒。",
)
b.step(
    "封四坡礼盒: 带尾方台上 4 片黄色三角四棱互吸合拢。",
    GIFT_IDS,
    highlight=["belt_c"],
    tip="四坡自锁 —— 最后一道工序: 封箱!",
)
b.step(
    "砌卸料仓: 3 片红色立墙与东托架合围成闭合环。",
    ["bin_s", "bin_n", "bin_e"],
    highlight=["tr_7"],
    tip="托架兼作仓壁 —— 一片顶两用, 四角竖边互吸锁死。",
)
b.step(
    "盖控制室: 4 片紫色立墙闭环, 方板压顶, 西沿点亮警示灯。",
    ["ct_s", "ct_n", "ct_w", "ct_e", "ct_roof", "ct_lamp"],
    highlight=["fl_8_2"],
    tip="控制室看得见整条流水线 —— 红灯亮起, 随时急停。",
)
b.step(
    "竖烟囱: 方墙上立等腰塔尖, 尖端直指 3 格高空 —— 开机!",
    ["stk_0", "stk_tip"],
    highlight=["ct_w"],
    tip="塔尖重心正压墙顶铰链, 力臂为零 —— 全线贯通, 出货!",
)

b.finalize(
    model_id="conveyor_factory_01",
    name="传送带车间",
    name_en="Conveyor Factory 01",
    description=(
        "全库第一条工厂流水线: 蓝色厂房两面锯齿天窗墙之间, 四座托架墙把"
        "绿色带面逐段顶到 1 格高 (每段双端受力零悬挑), 西端 30 度上料坡道"
        "顶铰链接地起跑, 带面上两枚三角包裹行进、带尾四坡礼盒封箱, 东端"
        "落进与托架合围的红色卸料仓; 控制室警示灯与 3 格高烟囱塔尖收束"
        "全景 —— 开机, 整条流水线跑起来!"
    ),
    difficulty=3,
    tags=["工程", "工厂", "流水线", "传送带", "职业体验"],
    min_pieces=68,
    min_steps=15,
)
