#!/usr/bin/env python3
"""生成模型 data/models/marble_starter_slope_01.json (滚珠起步坡)。

D1 收官批 4 模型 3/4 (难度配额解冻线 D1 >= 20, 路径 B1): 入门档
滚珠乐园选题 —— 孩子的第一条滚珠道, 也是滚珠乐园主题的第一个
D1。结构签名是"塔-坡-槽三段式": 一座 1x1 空心发射塔托起 30 度
长板滑坡 (坡顶短边整边吸塔帽沿与塔墙顶, 坡尾自然落在跑道板上),
两侧各两片方墙立在跑道板边当护轨, 道尾三面围墙合成接球槽 ——
滚珠从塔顶出发、顺坡加速、贴轨直行、入槽停稳, 这是"斜面让
小球跑起来"的第一课。与库内滚珠塔 (90+ 片多层折返) 及本批
探测器 (十字斜撑)、巨石门环 (三石塔)、风车坊 (塔楼十字翼)
的结构逻辑完全不同 —— 全批唯一带坡道的动态玩法结构。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 滚珠朝东 +x 跑):
  - 跑道板 3 片方板 (x [1,4], y [0,1], 全部接地)          3 片
  - 发射塔一圈 4 片方墙 (格 [0,1]x[0,1], z 0..1)          4 片
  - 塔帽 1 片方板 (z=1, 四边整边锁墙顶)                   1 片
  - 30 度滑坡 1 片长板 (坡顶吸塔帽东沿, 坡尾落跑道)       1 片
  - 出发旗 1 面 (等边三角, 骑塔帽西沿)                    1 片
  - 上球台 1 片方板 (塔西侧, 整边吸塔墙脚)                1 片
  - 护轨 4 片方墙 (跑道两侧, 竖棱吸塔角与彼此)            4 片
  - 接球槽 3 片方墙 (道尾合围, 开顶)                      3 片
  - 终点旗 1 面 + 槽沿小旗 2 面 (等边三角)                3 片
  合计 21 片, 6 个教程步骤, 3 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 塔墙竖棱角缝互吸成环, 塔帽四边整边锁墙顶 (先合围后封顶);
  - 坡顶短边同时吸塔帽东沿与东墙顶 (三方互吸成环), 坡尾
    降到 z=0 恰好贴在跑道板面上 —— 接地受压, 不悬挑;
  - 护轨墙脚整边压跑道板边, 竖棱依次角缝互吸直到接球槽;
  - 最高点 1.87 (出发旗尖) < 2.5, 不触发 R8 高层结构判定。

用法: python3 tools/generate_marble_starter_slope_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

TRACK = "cyan"      # 跑道板
TOWER = "purple"    # 发射塔
CAP = "yellow"      # 塔帽
SLOPE = "orange"    # 滑坡
RAIL = "blue"       # 护轨
BASIN = "green"     # 接球槽
FLAG = "red"        # 出发/终点旗
PAD = "gray"        # 上球台

# =================================================================
# 1. 跑道板 (x [1,4], y [0,1], 全部接地, 板板整边互吸)
# =================================================================
b.flat("track_1", 1, 0, 0.0, TRACK)
b.flat("track_2", 2, 0, 0.0, TRACK)
b.flat("track_3", 3, 0, 0.0, TRACK)

# =================================================================
# 2. 发射塔 (格 [0,1]x[0,1], z 0..1): 四墙一圈 + 塔帽
# =================================================================
b.wall_ew("tw_e", 1.0, 0, 0, TOWER)     # 东墙先立, 墙脚吸跑道板西边
b.wall_ns("tw_s", 0, 0.0, 0, TOWER)
b.wall_ns("tw_n", 0, 1.0, 0, TOWER)
b.wall_ew("tw_w", 0.0, 0, 0, TOWER)
b.flat("t_cap", 0, 0, 1.0, CAP)

# =================================================================
# 3. 滑坡 + 出发旗 + 上球台
# =================================================================
b.ramp("slope", "+x", 1.0, 0, 1.0, SLOPE)   # 坡顶 x=1 z=1, 坡尾 x=2.73 落跑道
b.crest_ew("start_flag", 0.0, 0, 1.0, FLAG)
b.flat("pad_w", -1, 0, 0.0, PAD)            # 上球台, 东边整边吸塔西墙脚

# =================================================================
# 4. 护轨 (跑道两侧方墙, 墙脚压板边, 竖棱依次角缝互吸)
# =================================================================
b.wall_ns("rail_s1", 1, 0.0, 0, RAIL)
b.wall_ns("rail_s2", 2, 0.0, 0, RAIL)
b.wall_ns("rail_n1", 1, 1.0, 0, RAIL)
b.wall_ns("rail_n2", 2, 1.0, 0, RAIL)

# =================================================================
# 5. 接球槽 (道尾三面围墙, 开顶) + 旗帜
# =================================================================
b.wall_ns("basin_s", 3, 0.0, 0, BASIN)
b.wall_ns("basin_n", 3, 1.0, 0, BASIN)
b.wall_ew("basin_e", 4.0, 0, 0, BASIN)
b.crest_ew("goal_flag", 4.0, 0, 1.0, FLAG)
b.crest_ns("cheer_s", 3, 0.0, 1.0, FLAG)
b.crest_ns("cheer_n", 3, 1.0, 1.0, FLAG)

# =================================================================
# 教程步骤 (6 步)
# =================================================================
b.step(
    "铺跑道: 三片青色方板整边相吸一字排开 —— 这就是滚珠要跑的直道。",
    ["track_1", "track_2", "track_3"],
)
b.step(
    "立发射塔: 东墙墙脚先吸住跑道板西边, 其余三面墙竖棱角缝互吸围成一圈。",
    ["tw_e", "tw_s", "tw_n", "tw_w"],
    highlight=["track_1"],
    tip="四片墙的竖棱像小手拉手 —— 拉成一圈塔就推不倒了。",
)
b.step(
    "盖塔帽搭滑坡: 黄色塔帽四边整边锁住墙顶, 橙色长板坡顶吸塔帽东沿、坡尾顺势落在跑道上, 出发旗骑上塔帽西沿, 灰色上球台贴住塔脚。",
    ["t_cap", "slope", "start_flag", "pad_w"],
    highlight=["tw_e"],
    tip="30 度斜面是滚珠的发动机 —— 越陡越快, 这个角度刚刚好。",
)
b.step(
    "装护轨: 四片蓝色方墙墙脚压住跑道板边, 竖棱先吸塔角再依次手拉手。",
    ["rail_s1", "rail_n1", "rail_s2", "rail_n2"],
    highlight=["track_1", "track_2"],
    tip="护轨夹住滑坡两侧 —— 滚珠再调皮也跑不出道。",
)
b.step(
    "围接球槽: 三片绿色方墙在道尾合围, 开口正对滑坡 —— 滚珠到站!",
    ["basin_s", "basin_n", "basin_e"],
    highlight=["track_3"],
)
b.step(
    "插旗开赛: 终点旗骑上槽尾墙顶, 两面加油旗立在槽沿, 3 2 1 放球!",
    ["goal_flag", "cheer_s", "cheer_n"],
    highlight=["basin_e"],
)

b.finalize(
    model_id="marble_starter_slope_01",
    name="滚珠起步坡",
    name_en="Marble Starter Slope 01",
    description=(
        "入门档滚珠乐园: 孩子的第一条滚珠道, 结构签名是'塔-坡-槽"
        "三段式' —— 紫色空心发射塔四墙竖棱角缝互吸、黄色塔帽四边"
        "整边锁墙顶, 橙色 30 度长板滑坡坡顶同时吸住塔帽东沿与塔墙顶、"
        "坡尾自然落在青色跑道板上; 四片蓝色护轨墙脚压住跑道板边夹出"
        "直道, 道尾三片绿色方墙合成开顶接球槽, 出发旗、终点旗和两面"
        "加油旗各就各位。21 片全程接地受压零悬挑, 旗尖 1.87 不触发"
        "高层判定, 搭完放上一颗玻璃珠就能开赛。"
    ),
    difficulty=1,
    tags=["滚珠乐园", "滑坡", "轨道", "亲子入门"],
    min_pieces=21,
    min_steps=6,
    series="marble_run",
)
print("已写入 series=marble_run")
