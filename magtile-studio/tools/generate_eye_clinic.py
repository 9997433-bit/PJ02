#!/usr/bin/env python3
"""生成模型 data/models/eye_clinic_01.json (眼科诊所)。

医院健康主题: 全库第一座"把视力表搭成楼"的模型 —— 双面视力表
箱塔: 3x1 底 3 层高的箱形闭环塔, 南北两面各用 8 片蓝方板拼出
一个巨型 E 字 (留白格分居两面的中层两侧 —— 南面 E 开口朝东、
北面开口朝西, 正是视力表上会转方向的 E); 塔前一条测距道笔直
铺向南: 透明格与黄格相间标出距离, 尽头一片红色站位格 —— 站上
红格、伸手指方向, 两侧橙色长凳坐着排队的小朋友。西侧验光室
是 2x2 一层小白盒, 屋顶骑缝立着一副巨型眼镜 —— 两扇青色窗格
方镜片肩并肩竖边互吸, 镜框正对测距道; 塔顶红色检查灯压檐,
东北角院旗高扬 —— E 朝哪边? 眼睛越练越亮!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 视力表朝南):
  - 院子地坪 7x5: 测距道 (红站位格/黄距离格) + 草坪/步道      27 片
  - 视力表箱塔 [3,6]x[4,5] 三层: 每层 8 片箱形闭环 x3         24 片
  -   塔顶: 长板+方板压顶 + 红色检查灯等边                      3 片
  - 验光室 [0,2]x[2,4] 一层: 门框方+窗格方+白墙 x6             8 片
  -   平顶方板 x4 + 巨型眼镜 (窗格方镜片 x2 骑缝而立)           6 片
  - 候诊长凳等边 x2 + 东北角院旗等腰 x1                         3 片
  合计 71 片, 13 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, 常规+strict 双档零警告):
  - 箱塔三层全部箱形闭环: 每层四面墙竖边互吸成环, 上层墙底边
    整边吸下层墙顶边, 高 3.0 的墙体靠闭环拓扑通过 R8 高层检查,
    无单点失效; 塔顶板短边整边压东西壁顶;
  - E 字是结构的一部分而非贴纸: 蓝方板与留白方板同为承重墙,
    换任何一格塔都照样站得住;
  - 巨型眼镜两镜片底边各整边吸一片屋顶方板的骑缝边, 镜片间
    竖边互吸冗余, 重心正压铰链零力矩;
  - 检查灯/长凳/院旗底边全部整边吸檐口或地坪格线。

用法: python3 tools/generate_eye_clinic.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

LAWN = "green"      # 草坪
PAVE = "gray"       # 硬化地坪
PATH = "orange"     # 验光室门前步道
SPOT = "red"        # 站位格
MARK = "yellow"     # 距离格
LANE = "clear"      # 测距道
FLOOR = "clear"     # 室内地板
E_STROKE = "blue"   # E 字笔画
E_BLANK = "clear"   # 视力表留白
SIDE = "clear"      # 塔侧壁
ROOF = "gray"       # 屋面
LAMP = "red"        # 检查灯
WALL = "clear"      # 验光室墙
DOOR = "blue"       # 验光室门
WIN = "cyan"        # 验光室窗
LENS = "cyan"       # 眼镜镜片
BENCH = "orange"    # 候诊长凳
FLAG = "red"        # 院旗

# =================================================================
# 1. 院子地坪 7x5 (测距道沿 x[4,5] 纵贯)
# =================================================================
# 行 y[0,1]: 站位格居中, 两侧长凳落脚方板
b.flat_rect("g0_w", 0, 0, 0.0, LAWN)
b.flat("g0_a", 2, 0, 0.0, PAVE)
b.flat("g0_b", 3, 0, 0.0, PAVE)
b.flat("g0_spot", 4, 0, 0.0, SPOT)              # 站上红格读 E
b.flat("g0_c", 5, 0, 0.0, PAVE)
b.flat("g0_e", 6, 0, 0.0, LAWN)
# 行 y[1,2]: 验光室门前步道 + 测距道
b.flat("g1_w", 0, 1, 0.0, LAWN)
b.flat("g1_path", 1, 1, 0.0, PATH)
b.flat_rect("g1_a", 2, 1, 0.0, LAWN)
b.flat("g1_lane", 4, 1, 0.0, LANE)
b.flat_rect("g1_e", 5, 1, 0.0, LAWN)
# 行 y[2,3]: 验光室地板行
b.flat("g2_fw", 0, 2, 0.0, FLOOR)
b.flat("g2_fe", 1, 2, 0.0, FLOOR)
b.flat_rect("g2_a", 2, 2, 0.0, LAWN)
b.flat("g2_lane", 4, 2, 0.0, MARK)              # 黄距离格
b.flat_rect("g2_e", 5, 2, 0.0, LAWN)
# 行 y[3,4]
b.flat("g3_fw", 0, 3, 0.0, FLOOR)
b.flat("g3_fe", 1, 3, 0.0, FLOOR)
b.flat_rect("g3_a", 2, 3, 0.0, LAWN)
b.flat("g3_lane", 4, 3, 0.0, LANE)
b.flat_rect("g3_e", 5, 3, 0.0, LAWN)
# 行 y[4,5]: 箱塔落脚行
b.flat_rect("g4_w", 0, 4, 0.0, LAWN)
b.flat("g4_a", 2, 4, 0.0, LAWN)
b.flat("g4_t0", 3, 4, 0.0, FLOOR)
b.flat("g4_t1", 4, 4, 0.0, FLOOR)
b.flat("g4_t2", 5, 4, 0.0, FLOOR)
b.flat("g4_e", 6, 4, 0.0, LAWN)

# =================================================================
# 2. 视力表箱塔 [3,6]x[4,5] 三层 (南面 E 开口朝东, 北面开口朝西)
# =================================================================
# 南面 E (viewer 在南): 留白 = 中层东格; 北面: 留白 = 中层西格
for z in range(3):
    for i, x in enumerate((3, 4, 5)):
        s_color = E_BLANK if (z == 1 and x == 5) else E_STROKE
        n_color = E_BLANK if (z == 1 and x == 3) else E_STROKE
        b.wall_ns(f"t{z}_s{i}", x, 4.0, z, s_color)
        b.wall_ns(f"t{z}_n{i}", x, 5.0, z, n_color)
    b.wall_ew(f"t{z}_w", 3.0, 4, z, SIDE)
    b.wall_ew(f"t{z}_e", 6.0, 4, z, SIDE)

# 塔顶 z=3: 长板 + 方板压顶, 南檐红色检查灯
b.flat_rect("tcap_w", 3, 4, 3.0, ROOF)
b.flat("tcap_e", 5, 4, 3.0, ROOF)
b.crest_ns("t_lamp", 4, 4.0, 3.0, LAMP)

# =================================================================
# 3. 验光室 [0,2]x[2,4] 一层 + 屋顶巨型眼镜
# =================================================================
b.add("c_win", "window_square", (0.5, 2.0, 0.5), (90, 0, 0), WIN)
b.add("c_door", "door_frame", (1.5, 2.0, 0.5), (90, 0, 0), DOOR)
b.wall_ns("c_n0", 0, 4.0, 0, WALL)
b.wall_ns("c_n1", 1, 4.0, 0, WALL)
b.wall_ew("c_w2", 0.0, 2, 0, WALL)
b.wall_ew("c_w3", 0.0, 3, 0, WALL)
b.wall_ew("c_e2", 2.0, 2, 0, WALL)
b.wall_ew("c_e3", 2.0, 3, 0, WALL)
for x0, y0 in ((0, 2), (1, 2), (0, 3), (1, 3)):
    b.flat(f"c_rf_{x0}_{y0}", x0, y0, 1.0, ROOF)
b.add("lens_w", "window_square", (0.5, 3.0, 1.5), (90, 0, 0), LENS)
b.add("lens_e", "window_square", (1.5, 3.0, 1.5), (90, 0, 0), LENS)

# =================================================================
# 4. 候诊长凳 + 院旗
# =================================================================
b.crest_ns("bench_w", 3, 0.0, 0.0, BENCH)
b.crest_ns("bench_e", 5, 0.0, 0.0, BENCH)
b.spire_ns("flag", 6, 5.0, 0.0, FLAG)

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺院子南排: 红色站位格居中 —— 测视力就站这里, 两侧方板"
    "给候诊长凳留落脚边。",
    ["g0_w", "g0_a", "g0_b", "g0_spot", "g0_c", "g0_e"],
    tip="站位格到视力表正好隔四格 —— 距离画在地上。",
)
b.step(
    "铺步道行: 橙色步道正对验光室门位, 测距道第一格接上站位格。",
    ["g1_w", "g1_path", "g1_a", "g1_lane", "g1_e"],
    highlight=["g0_spot"],
)
b.step(
    "铺验光室地板两行: 白色地板居西, 黄色距离格嵌进测距道正中。",
    ["g2_fw", "g2_fe", "g2_a", "g2_lane", "g2_e",
     "g3_fw", "g3_fe", "g3_a", "g3_lane", "g3_e"],
    highlight=["g1_lane"],
    tip="黄格是测距道的中点记号 —— 透明黄透明相间。",
)
b.step(
    "铺箱塔落脚行: 三片白地板并排 —— 视力表箱塔的地基。",
    ["g4_w", "g4_a", "g4_t0", "g4_t1", "g4_t2", "g4_e"],
    highlight=["g3_lane"],
)
b.step(
    "起箱塔第一层: 南北各 3 片蓝方板 + 东西侧壁, 四面竖边互吸"
    "闭环 —— E 字的底横杠。",
    ["t0_s0", "t0_s1", "t0_s2", "t0_n0", "t0_n1", "t0_n2",
     "t0_w", "t0_e"],
    highlight=["g4_t0", "g4_t2"],
    tip="E 字是承重墙不是贴纸 —— 每片都在干活。",
)
b.step(
    "起箱塔第二层: 中层要留白! 南面东格、北面西格换透明方板 "
    "—— 南 E 开口朝东、北 E 开口朝西。",
    ["t1_s0", "t1_s1", "t1_s2", "t1_n0", "t1_n1", "t1_n2",
     "t1_w", "t1_e"],
    highlight=["t0_s0"],
    tip="视力表上的 E 会转方向 —— 两面开口不一样才好玩。",
)
b.step(
    "起箱塔第三层: 再上一整圈蓝环 —— E 字的顶横杠, 塔高 3.0 "
    "全靠层层闭环站稳。",
    ["t2_s0", "t2_s1", "t2_s2", "t2_n0", "t2_n1", "t2_n2",
     "t2_w", "t2_e"],
    highlight=["t1_s2"],
)
b.step(
    "箱塔压顶 + 检查灯: 长板与方板短边整边压东西壁顶, 红色"
    "等边检查灯立上南檐正中。",
    ["tcap_w", "tcap_e", "t_lamp"],
    highlight=["t2_w", "t2_e"],
    tip="检查灯正对测距道 —— 亮灯就开测!",
)
b.step(
    "立验光室南立面与西墙: 窗格方+蓝色门框方朝南, 西墙 2 片。",
    ["c_win", "c_door", "c_w2", "c_w3"],
    highlight=["g1_path"],
)
b.step(
    "合验光室北墙与东墙: 各 2 片, 一层白盒箱形围合。",
    ["c_n0", "c_n1", "c_e2", "c_e3"],
    highlight=["c_w3"],
)
b.step(
    "盖验光室平顶: 4 片方板四边压墙顶 —— 顶上要骑眼镜, 必须"
    "用方板留出骑缝边。",
    ["c_rf_0_2", "c_rf_1_2", "c_rf_0_3", "c_rf_1_3"],
    highlight=["c_n0", "c_e2"],
)
b.step(
    "架巨型眼镜: 两扇青色窗格方镜片肩并肩骑上屋顶中缝, "
    "镜片间竖边互吸 —— 镜框正对测距道。",
    ["lens_w", "lens_e"],
    highlight=["c_rf_0_2", "c_rf_1_3"],
    tip="窗格方的镂空格正好当镜片 —— 全城最大的一副眼镜。",
)
b.step(
    "摆候诊长凳、升院旗: 两片橙等边面朝站位格, 红色等腰院旗"
    "立上东北角 —— 眼科诊所开诊, E 朝哪边?",
    ["bench_w", "bench_e", "flag"],
    highlight=["g0_spot"],
    tip="站上红格、伸手指方向 —— 眼睛越练越亮!",
)

b.finalize(
    model_id="eye_clinic_01",
    name="眼科诊所",
    name_en="Eye Clinic 01",
    description=(
        "全库第一座'把视力表搭成楼'的模型: 3x1 底 3 层高的双面视力表"
        "箱塔, 南北两面各用 8 片蓝方板拼出巨型 E 字 (留白格分居中层"
        "两侧 —— 南 E 开口朝东、北 E 开口朝西, 正是视力表上会转方向"
        "的 E), E 字本身就是承重墙, 塔高 3.0 靠层层箱形闭环通过高层"
        "检查; 塔前测距道透明格黄格相间笔直铺向南, 尽头红色站位格, "
        "两侧橙色候诊长凳; 西侧 2x2 验光室平顶骑缝立一副巨型眼镜 —— "
        "两扇青色窗格方镜片肩并肩竖边互吸, 镜框正对测距道; 塔顶红色"
        "检查灯压檐, 东北角院旗高扬 —— 站上红格伸手指方向, 眼睛越练"
        "越亮!"
    ),
    difficulty=3,
    tags=["医院", "城市", "职业体验", "视力表", "进阶"],
    min_pieces=71,
    min_steps=13,
)
