#!/usr/bin/env python3
"""生成模型 data/models/warehouse_01.json (仓库).

城市生活主题: 全库第一座物流仓库 —— 三排橙色墙列托起两跨
蓝色金属屋面 (每片屋面板两端整边压墙顶, 双端受力零悬挑),
屋脊线上三只透明排风器错落而立; 两跨库房里绿黄货垛四坡自锁,
东侧月台升起 1 格高, 30 度装卸坡道贴地放平、黄色防撞栏压沿;
东北角红色调度室升旗 3 格高 —— 卡车进港, 开始收货!

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 库区地坪 8x6: 方板为主 + 长板收边                         44 片
  - 墙列: y=1/3/5 三排各 5 片橙色立墙 (x1..6)                 15 片
  - 屋面: 两跨各 5 片长板 (跨深 2, 两端整边压墙顶)             10 片
  - 排风器: 透明等边三角 x3 (立屋脊线)                          3 片
  - 货垛: 等边四坡垛 x3 (A 跨 2 垛 + B 跨 1 垛)                12 片
  - 装卸月台: 立墙闭环 x4 + 方板台面 + 防撞栏 + 30 度坡道       7 片
  - 调度室: 立墙闭环 x4 + 方板顶 + 等腰旗杆 (尖端 3.0)          6 片
  合计 97 片, 18 个教程步骤, 5 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验, default + strict 双档):
  - 屋面板短边与墙顶等长整边贴合, 每片两端受力 (力矩为零),
    相邻屋面板长边互吸成整跨 —— 墙列+屋面锁成门式框架环;
  - 货垛先入库、屋面后合拢 (R7b 装配可达: 封顶前留手位);
  - 月台坡道顶边整边吸台沿、坡尾接地 (顶铰链 + 接地斜撑);
  - 旗杆尖端 3.0 触发 R8 高层检查: 全模型闭环冗余充足,
    零警告; 排风器/防撞栏重心均正压铰链线。

用法: python3 tools/generate_warehouse.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

FLOOR = "gray"      # 库区地坪
APRON = "yellow"    # 月台作业区地坪
WALL = "orange"     # 仓库墙列
ROOF = "blue"       # 金属屋面
VENT = "clear"      # 屋脊排风器
CARGO_A = "green"   # 货垛
CARGO_B = "yellow"  # 货垛
DOCK = "gray"       # 月台
RAIL = "yellow"     # 防撞栏
OFFICE = "red"      # 调度室
FLAG = "clear"      # 旗杆

# =================================================================
# 1. 库区地坪 8x6: 库内 x1..6 全方板 (墙列与货垛的落点),
#    东侧月台区行内加铺方板
# =================================================================
for y in range(6):
    b.flat(f"fl_w_{y}", 0, y, 0.0, FLOOR)           # [0,1] 西沿
    for x in range(1, 6):
        b.flat(f"fl_{x}_{y}", x, y, 0.0, FLOOR)     # [1,6] 库内方板
    if y in (2, 4):
        b.flat(f"fl_e6_{y}", 6, y, 0.0, APRON)      # [6,7] 月台格
        b.flat(f"fl_e7_{y}", 7, y, 0.0, APRON)      # [7,8]
    else:
        b.flat_rect(f"fl_e_{y}", 6, y, 0.0, FLOOR)  # [6,8] 长板收边

# =================================================================
# 2. 墙列: y=1/3/5 三排各 5 片橙色立墙 (x1..6, 相邻竖边互吸)
# =================================================================
for tag, wy in (("a", 1.0), ("m", 3.0), ("n", 5.0)):
    for x in range(1, 6):
        b.wall_ns(f"wl_{tag}_{x}", x, wy, 0, WALL)

# =================================================================
# 3. 货垛: 屋面合拢前先入库 (R7b 装配可达)
# =================================================================
STACK_A1 = b.hat4("ca1", 1, 1, 0.0, CARGO_A,
                  shape="equilateral_triangle")     # A 跨 [1,2]x[1,2]
STACK_A2 = b.hat4("ca2", 4, 1, 0.0, CARGO_B,
                  shape="equilateral_triangle")     # A 跨 [4,5]x[1,2]
STACK_B = b.hat4("cb", 2, 4, 0.0, CARGO_A,
                 shape="equilateral_triangle")      # B 跨 [2,3]x[4,5]

# =================================================================
# 4. 屋面: 两跨各 5 片长板 (跨深 2), 短边整边压墙顶
# =================================================================
for x in range(1, 6):
    b.flat_rect(f"rf_a_{x}", x, 1, 1.0, ROOF, axis="y")  # A 跨 y[1,3]
for x in range(1, 6):
    b.flat_rect(f"rf_b_{x}", x, 3, 1.0, ROOF, axis="y")  # B 跨 y[3,5]

# =================================================================
# 5. 排风器: 屋脊线 (y=3, z=1) 上 3 只透明三角
# =================================================================
for x in (1, 3, 5):
    b.crest_ns(f"vent_{x}", x, 3.0, 1.0, VENT)

# =================================================================
# 6. 装卸月台: [6,7]x[2,3] 闭环 + 台面 + 防撞栏 + 南向坡道
# =================================================================
b.wall_ew("dk_w", 6.0, 2, 0, DOCK)
b.wall_ew("dk_e", 7.0, 2, 0, DOCK)
b.wall_ns("dk_s", 6, 2.0, 0, DOCK)
b.wall_ns("dk_n", 6, 3.0, 0, DOCK)
b.flat("dk_top", 6, 2, 1.0, DOCK)                   # 台面 z=1
b.crest_ns("dk_rail", 6, 3.0, 1.0, RAIL)            # 北沿防撞栏
b.ramp("dk_ramp", "-y", 2.0, 6, 1.0, DOCK)          # 南向坡道 (尾 y=0.27)

# =================================================================
# 7. 调度室: [6,7]x[4,5] 闭环 + 方板顶 + 等腰旗杆
# =================================================================
b.wall_ew("of_w", 6.0, 4, 0, OFFICE)
b.wall_ew("of_e", 7.0, 4, 0, OFFICE)
b.wall_ns("of_s", 6, 4.0, 0, OFFICE)
b.wall_ns("of_n", 6, 5.0, 0, OFFICE)
b.flat("of_top", 6, 4, 1.0, OFFICE)                 # 顶 z=1
b.spire_ns("of_flag", 6, 4.0, 1.0, FLAG)            # 旗杆尖端 3.0

# =================================================================
# 教程步骤 (18 步)
# =================================================================
b.step(
    "铺地坪第 1 行 (南沿): 方板 x6 + 长板收边, 共 7 片。",
    ["fl_w_0"] + [f"fl_{x}_0" for x in range(1, 6)] + ["fl_e_0"],
    tip="库内 x1..6 全用方板 —— 墙列脚要逐格咬缝。",
)
b.step(
    "铺第 2 行: 7 片, A 跨库房的地面。",
    ["fl_w_1"] + [f"fl_{x}_1" for x in range(1, 6)] + ["fl_e_1"],
    highlight=["fl_1_0", "fl_5_0"],
    tip="y=1 拼缝就是第一排墙列的落脚线。",
)
b.step(
    "铺第 3 行: 库内 6 片 + 黄色月台格 2 片。",
    ["fl_w_2"] + [f"fl_{x}_2" for x in range(1, 6)]
    + ["fl_e6_2", "fl_e7_2"],
    highlight=["fl_5_1"],
    tip="黄色作业区留给东侧月台 —— 卡车从这里倒车进港。",
)
b.step(
    "铺第 4 行: 7 片, 中排墙列的基准行。",
    ["fl_w_3"] + [f"fl_{x}_3" for x in range(1, 6)] + ["fl_e_3"],
    highlight=["fl_1_2", "fl_5_2"],
    tip="y=3 是两跨屋面共用的屋脊线。",
)
b.step(
    "铺第 5 行: 库内 6 片 + 黄色月台格 2 片。",
    ["fl_w_4"] + [f"fl_{x}_4" for x in range(1, 6)]
    + ["fl_e6_4", "fl_e7_4"],
    highlight=["fl_5_3"],
    tip="东北角这块黄色区是调度室的地基。",
)
b.step(
    "铺第 6 行 (北沿): 7 片, 地坪合拢成 8x6。",
    ["fl_w_5"] + [f"fl_{x}_5" for x in range(1, 6)] + ["fl_e_5"],
    highlight=["fl_1_4", "fl_5_4"],
    tip="四十四片地坪铺齐 —— 仓库的图纸画好了。",
)
b.step(
    "立南排墙列: y=1 线 5 片橙色立墙, 相邻竖边互吸。",
    [f"wl_a_{x}" for x in range(1, 6)],
    highlight=["fl_1_0", "fl_5_0"],
    tip="整排墙连成一体 —— 这是 A 跨屋面的南支座。",
)
b.step(
    "立中排墙列: y=3 线再立 5 片, 两跨共用这排墙。",
    [f"wl_m_{x}" for x in range(1, 6)],
    highlight=["wl_a_1", "wl_a_5"],
    tip="一排墙托两跨屋面 —— 这就是联跨厂房的省料秘诀。",
)
b.step(
    "立北排墙列: y=5 线 5 片, 三排墙列全部就位。",
    [f"wl_n_{x}" for x in range(1, 6)],
    highlight=["wl_m_1", "wl_m_5"],
    tip="三排墙互相平行 —— 屋面板一搭就是门式框架。",
)
b.step(
    "A 跨入库: 两座四坡货垛在屋面合拢前先码好, 共 8 片。",
    STACK_A1 + STACK_A2,
    highlight=["fl_1_1", "fl_4_1"],
    tip="先入库后封顶 —— 封顶之后手可就伸不进去了。",
)
b.step(
    "B 跨入库: 再码一座绿色货垛, 4 片四棱互吸。",
    STACK_B,
    highlight=["fl_2_4"],
    tip="四坡自锁的货垛, 叉车撞一下也不散。",
)
b.step(
    "盖 A 跨屋面: 5 片蓝色长板, 两条短边整边压南/中排墙顶。",
    [f"rf_a_{x}" for x in range(1, 6)],
    highlight=["wl_a_1", "wl_m_1"],
    tip="每片双端受力零悬挑, 相邻长边互吸 —— 整跨锁成一体。",
)
b.step(
    "盖 B 跨屋面: 再搭 5 片, 两跨金属屋面合拢。",
    [f"rf_b_{x}" for x in range(1, 6)],
    highlight=["wl_m_1", "wl_n_1"],
    tip="墙列+屋面是门式框架环 —— 仓库有了遮风挡雨的顶。",
)
b.step(
    "装排风器: 屋脊线上 3 只透明三角错落而立。",
    ["vent_1", "vent_3", "vent_5"],
    highlight=["rf_a_1", "rf_b_5"],
    tip="重心正压屋脊铰链线 —— 热气从这里排出去。",
)
b.step(
    "砌月台: 黄色作业区上 4 片灰墙四角竖边互吸闭环。",
    ["dk_w", "dk_e", "dk_s", "dk_n"],
    highlight=["fl_e6_2"],
    tip="月台高 1 格 —— 正好与卡车货厢齐平。",
)
b.step(
    "铺台面、压防撞栏、放坡道: 台面四边压墙顶, 北沿立黄栏, "
    "30 度坡道顶边吸台沿、坡尾贴地。",
    ["dk_top", "dk_rail", "dk_ramp"],
    highlight=["dk_s", "dk_n"],
    tip="顶铰链 + 接地斜撑 —— 叉车顺着坡道直上月台。",
)
b.step(
    "砌调度室: 东北角 4 片红色立墙闭环。",
    ["of_w", "of_e", "of_s", "of_n"],
    highlight=["fl_e6_4"],
    tip="调度室看得见月台与两跨库门 —— 指挥全场。",
)
b.step(
    "封顶升旗: 方板压顶, 等腰旗杆直上 3 格 —— 开始收货!",
    ["of_top", "of_flag"],
    highlight=["of_s"],
    tip="旗杆重心正压屋顶铰链, 力臂为零 —— 仓库正式开张!",
)

b.finalize(
    model_id="warehouse_01",
    name="物流仓库",
    name_en="Warehouse 01",
    description=(
        "全库第一座物流仓库: 三排橙色墙列托起两跨蓝色金属屋面 (每片屋面板"
        "短边与墙顶等长整边贴合、双端受力零悬挑), 屋脊线上三只透明排风器"
        "错落而立; 三座四坡货垛在封顶前先入库 (R7b 装配可达), 东侧月台"
        "闭环升起 1 格、30 度装卸坡道贴地放平, 东北角红色调度室旗杆直上 "
        "3 格 —— 卡车进港, 开始收货!"
    ),
    difficulty=4,
    tags=["城市", "仓库", "物流", "门式框架", "职业体验"],
    min_pieces=90,
    min_steps=18,
)
