#!/usr/bin/env python3
"""生成模型 data/models/fishing_boat_01.json (渔船靠泊)。

海洋航行主题: 全库第一艘带泊位场景的作业渔船 —— 蓝色拖网渔船
稳稳靠在浮码头边: 前部驾驶室透明前窗迎着航道, 艉部门架 (网架)
由直角三角斜撑锁定, 甲板中段扣着盖好篷布的渔获罩; 船舷插着
浮标旗, 码头上系缆桩与灯柱一字排开 —— 今天渔获满舱!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 船艏朝东):
  - 船底 (x 0..5, y 0..2): 长板 x4 + 方板 x2                     6 片
  - 舷墙 (z 0..1): 南舷横楣 x2 + 方墙 x8 + 艏艉封板 x4          13 片
  - 主甲板 (z=1): 方板 x10 (逐格压住靠泊舷)                     10 片
  - 驾驶室 (x 3..4, z 1..2): 围壁 x6 + 长板顶 x1 + 桅/烟囱 x2    9 片
  - 艉部网架门架: 方墙 x2 + 直角三角斜撑 x2                      4 片
  - 渔获罩 hat4 + 浮标旗 x2 + 船艏旗                              7 片
  - 浮码头 (y 2..3): 底板 x4 + 岸墙 x4 + 面板 x4 + 桩/灯 x3     15 片
  合计 63 片, 16 个教程步骤, 4 种片形 (全 core-5)。

物理规则要点 (通过 R1~R8 全部校验):
  - 靠泊舷 (北舷) 全用方墙: 码头面板南边逐格整边吸舷墙顶边,
    船体与浮码头锁成一体 (跳板都省了);
  - 网架门架双保险: 方墙底边吸甲板拼缝, 两片直角三角斜撑
    直角边分别吸甲板格边与门架竖边 —— 刚性节点抗住拖网拉力;
  - 渔获罩四坡自锁成环, 底边整边吸甲板拼缝;
  - 全船无悬挑无吊挂, 曲面一律不用 —— 作业船要的是皮实。

用法: python3 tools/generate_fishing_boat.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

HULL = "blue"       # 船壳
DECK = "gray"       # 甲板
CABIN = "yellow"    # 驾驶室
GLASS = "clear"     # 前窗
GANTRY = "orange"   # 网架门架
CATCH = "cyan"      # 渔获罩 (篷布)
PIER = "gray"       # 浮码头
POST = "red"        # 系缆桩 / 桅杆

# =================================================================
# 1. 船底 (z=0): 长板 x4 + 艏部方板 x2
# =================================================================
for y0 in (0, 1):
    b.flat_rect(f"kb_0_{y0}", 0, y0, 0.0, HULL)
    b.flat_rect(f"kb_2_{y0}", 2, y0, 0.0, HULL)
    b.flat(f"kb_4_{y0}", 4, y0, 0.0, HULL)

# =================================================================
# 2. 舷墙 (z 0..1): 南舷横楣 + 靠泊舷方墙 + 艏艉封板
# =================================================================
b.wall_ew("stern_0", 0.0, 0, 0, HULL)               # 艉封板
b.wall_ew("stern_1", 0.0, 1, 0, HULL)
b.wall_ew("bow_0", 5.0, 0, 0, HULL)                 # 艏封板
b.wall_ew("bow_1", 5.0, 1, 0, HULL)
b.lintel_ns("bw_s_0", 0, 0.0, 0, HULL)              # 南舷横楣
b.lintel_ns("bw_s_2", 2, 0.0, 0, HULL)
b.wall_ns("bw_s_4", 4, 0.0, 0, HULL)                # 南舷艏段方墙
for x0 in range(5):
    b.wall_ns(f"bw_n_{x0}", x0, 2.0, 0, HULL)       # 靠泊舷 (北) 全方墙

# =================================================================
# 3. 主甲板 (z=1): 方板逐格, 每片都咬住靠泊舷顶边
# =================================================================
for x0 in range(5):
    for y0 in (0, 1):
        b.flat(f"dk_{x0}_{y0}", x0, y0, 1.0, DECK)

# =================================================================
# 4. 驾驶室 (x 3..4, z 1..2): 透明前窗朝艏, 长板顶双端简支
# =================================================================
b.wall_ew("ch_w_0", 3.0, 0, 1, CABIN)
b.wall_ew("ch_w_1", 3.0, 1, 1, CABIN)
b.wall_ew("ch_e_0", 4.0, 0, 1, GLASS)               # 前窗
b.wall_ew("ch_e_1", 4.0, 1, 1, GLASS)
b.wall_ns("ch_s", 3, 0.0, 1, CABIN)
b.wall_ns("ch_n", 3, 2.0, 1, CABIN)
b.add("ch_top", "rectangle", (3.5, 1.0, 2.0), (0, 0, 90), CABIN)
b.crest_ns("mast", 3, 0.0, 2.0, POST)               # 桅杆 (顶南沿)
b.crest_ns("funnel", 3, 2.0, 2.0, POST)             # 烟囱 (顶北沿)

# =================================================================
# 5. 艉部网架门架 (x=1, z 1..2): 方墙 + 直角三角斜撑
# =================================================================
b.wall_ew("gt_0", 1.0, 0, 1, GANTRY)
b.wall_ew("gt_1", 1.0, 1, 1, GANTRY)
b.brace("gt_br_s", (1.0, 0.0, 1.0), "-x", GANTRY)
b.brace("gt_br_n", (1.0, 2.0, 1.0), "-x", GANTRY)

# =================================================================
# 6. 渔获罩 + 浮标旗 + 船艏旗
# =================================================================
CATCH_IDS = b.hat4("catch", 2, 0, 1.0, CATCH, shape="equilateral_triangle")
b.crest_ns("buoy_w", 1, 0.0, 1.0, "orange")         # 浮标旗 (南舷)
b.crest_ns("buoy_e", 4, 0.0, 1.0, "green")
b.crest_ew("bow_flag", 5.0, 1, 1.0, POST)           # 船艏旗

# =================================================================
# 7. 浮码头 (y 2..3, x 0..4): 底板 + 岸墙 + 面板 + 桩/灯
# =================================================================
for x0 in range(4):
    b.flat(f"pf_{x0}", x0, 2, 0.0, PIER)            # 码头底板
for x0 in range(4):
    b.wall_ns(f"pw_{x0}", x0, 3.0, 0, PIER)         # 岸墙
for x0 in range(4):
    b.flat(f"pd_{x0}", x0, 2, 1.0, PIER)            # 码头面板
b.crest_ns("bollard_w", 0, 3.0, 1.0, POST)          # 系缆桩
b.crest_ns("bollard_e", 2, 3.0, 1.0, POST)
b.crest_ew("lamp", 4.0, 2, 1.0, "yellow")           # 灯柱 (码头东端)

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺船底·主段: 4 片蓝色长板双列并进 (x 0..4), 拼缝落在 x=2 线。",
    ["kb_0_0", "kb_0_1", "kb_2_0", "kb_2_1"],
    tip="渔船船底要铺得平 —— 出海作业全靠这块底子。",
)
b.step(
    "船底收艏并立艏封板: 2 片方板补齐船艏, 艏部 2 片方墙封板立起。",
    ["kb_4_0", "kb_4_1", "bow_0", "bow_1"],
    highlight=["kb_2_0", "kb_2_1"],
    tip="艏封板底边整边吸方板东边 —— 船头先站直。",
)
b.step(
    "立艉封板与南舷: 艉部 2 片封板, 南舷 2 片横楣长板 + 1 片方墙。",
    ["stern_0", "stern_1", "bw_s_0", "bw_s_2", "bw_s_4"],
    highlight=["kb_0_0"],
    tip="横楣底边 (长 2) 整边吸船底长板长边, 拐角竖边互吸。",
)
b.step(
    "立靠泊舷: 北舷 5 片方墙逐格立起 —— 这一舷要跟码头咬在一起。",
    [f"bw_n_{x0}" for x0 in range(5)],
    highlight=["stern_1", "bow_1"],
    tip="靠泊舷全用方墙, 码头面板将来逐格压住它的顶边。",
)
b.step(
    "盖主甲板·艉段: 6 片灰色方板从艉向艏铺 (x 0..3)。",
    [f"dk_{x0}_{y0}" for x0 in (0, 1, 2) for y0 in (0, 1)],
    highlight=["stern_0", "bw_n_0"],
    tip="第一片先咬住艉封板顶边, 后面逐格拼缝互吸。",
)
b.step(
    "盖主甲板·艏段: 再铺 4 片, 全通甲板合龙。",
    [f"dk_{x0}_{y0}" for x0 in (3, 4) for y0 in (0, 1)],
    highlight=["dk_2_0", "dk_2_1"],
    tip="船底+舷墙+甲板锁成箱形环 —— 风浪里也扛得住。",
)
b.step(
    "立驾驶室围壁: 后壁与侧壁 4 片黄色方墙 (x 3..4)。",
    ["ch_w_0", "ch_w_1", "ch_s", "ch_n"],
    highlight=["dk_3_0", "dk_3_1"],
    tip="墙脚踩甲板拼缝, 荷载顺舷墙直落船底。",
)
b.step(
    "装透明前窗: 2 片透明方墙朝艏立起 —— 船长要看清整条航道。",
    ["ch_e_0", "ch_e_1"],
    highlight=["ch_s", "ch_n"],
    tip="前窗竖边与侧壁竖边互吸, 驾驶室四面合龙。",
)
b.step(
    "盖驾驶室顶并竖桅杆烟囱: 长板顶双端简支压住前后壁, 南北沿"
    "各立 1 片红色三角。",
    ["ch_top", "mast", "funnel"],
    highlight=["ch_w_0", "ch_e_0"],
    tip="长板短边双端压墙顶 —— 桅杆天线与烟囱各就各位。",
)
b.step(
    "立艉部网架门架: 2 片橙色方墙横跨甲板 (x=1 线)。",
    ["gt_0", "gt_1"],
    highlight=["dk_1_0", "dk_1_1"],
    tip="门架是拖网的起吊架 —— 底边整边吸甲板拼缝。",
)
b.step(
    "锁门架斜撑: 2 片直角三角形直角边分别吸甲板格边与门架竖边。",
    ["gt_br_s", "gt_br_n"],
    highlight=["gt_0", "gt_1"],
    tip="三角斜撑把铰链变成刚性节点 —— 拖网的拉力全靠它扛。",
)
b.step(
    "扣渔获罩: 4 片青色等边三角四棱互吸, 盖住今天的渔获。",
    CATCH_IDS,
    highlight=["dk_2_0"],
    tip="四坡自锁成环 —— 篷布罩得严严实实, 海鸟别想偷嘴。",
)
b.step(
    "插浮标旗与船艏旗: 南舷 2 面浮标旗, 船艏 1 面红旗。",
    ["buoy_w", "buoy_e", "bow_flag"],
    highlight=["dk_1_0", "dk_4_0"],
    tip="橙绿浮标旗标记网位 —— 底边整边吸甲板沿边。",
)
b.step(
    "铺浮码头底板: 4 片灰色方板沿靠泊舷一字排开 (y 2..3)。",
    [f"pf_{x0}" for x0 in range(4)],
    highlight=["bw_n_0", "bw_n_3"],
    tip="码头底板逐格互吸 —— 这是渔港的泊位。",
)
b.step(
    "立码头岸墙: 4 片方墙沿 y=3 线立起, 底边整边吸底板北边。",
    [f"pw_{x0}" for x0 in range(4)],
    highlight=["pf_0", "pf_3"],
    tip="岸墙与靠泊舷同高 —— 码头面板马上把两边一起压住。",
)
b.step(
    "盖码头面板并装桩灯: 4 片面板南边吸舷墙顶、北边压岸墙顶, "
    "再立 2 根系缆桩与 1 盏灯柱 —— 渔船靠泊完成!",
    [f"pd_{x0}" for x0 in range(4)] + ["bollard_w", "bollard_e", "lamp"],
    highlight=["bw_n_1", "pw_1"],
    tip="面板一头咬船一头咬岸, 船与码头锁成一体 —— 收工卸鱼!",
)

b.finalize(
    model_id="fishing_boat_01",
    name="渔船靠泊",
    name_en="Fishing Boat 01",
    description=(
        "全库第一艘带泊位场景的作业渔船: 蓝色拖网渔船靠在浮码头边, 码头"
        "面板一头整边吸靠泊舷顶边、一头压岸墙顶, 船与码头锁成一体; 前部"
        "驾驶室透明前窗迎着航道, 艉部网架门架由直角三角斜撑锁成刚性节点, "
        "甲板中段四坡渔获罩自锁扣紧, 浮标旗与系缆桩点出渔港烟火气 —— "
        "今天渔获满舱!"
    ),
    difficulty=3,
    tags=["海洋航行", "舰船", "载具", "渔港", "码头"],
    min_pieces=55,
    min_steps=16,
)
