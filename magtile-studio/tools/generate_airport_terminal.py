#!/usr/bin/env python3
"""生成模型 data/models/airport_terminal_01.json (国际机场航站楼)。

城市交通主题旗舰场景: 6 格长的玻璃前脸候机大厅 (中央 2 格出发大门 +
黄色雨棚平挑门前), 大厅屋面西端起一座玻璃环廊观景台收梯形四坡顶,
东端贴建 4 层控制塔 (顶层四面透明塔台 + 四坡尖顶), 塔身下两层直接
借用大厅东山墙 (共墙不重叠); 楼前停机坪上一架红翼小客机正对
出发大门, 机坪南沿立着进近引导灯标。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 候机大厅 [0,6]x[0,2]: 地板长板 6 + 玻璃前脸 4 + 前脸门楣层 3 +
    后墙长板 6 + 山墙 8 + 屋面长板 6                             33 片
  - 出发门雨棚: 门楣底沿向南平挑 1 片长板 (力矩 30 <= 预算 40)    1 片
  - 观景台 [0,2]x[0,2] (z 2..3.7): 玻璃环梁圈 4 + 梯形四坡顶 4 +
    攒尖压顶 1                                                    9 片
  - 控制塔 [6,7]x[0,1] (z 0..4.87): 底板 + 三面塔身 12 + 高层西壁 2
    + 顶层透明塔台 (计入塔身) + 顶板 + 四坡尖顶 4                20 片
  - 停机坪: 6 片方板 + 2 片引导灯标                               8 片
  - 小客机: 机身 2 + 机翼 2 + 机鼻 1 + 垂尾 1                     6 片
  合计 77 片, 18 个教程步骤, 6 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 前脸门楣/后墙/屋面全部用长板: 长边 (长 2) 逐段等长整边贴合,
    观景台环梁圈底边才有同长的屋面长边可吸;
  - 雨棚北长边整边吸门楣底沿, 单片平挑力矩 30 <= 铰链预算 40;
  - 控制塔与大厅共用东山墙下两层 (一墙两用不重叠), 塔身闭合
    箱形筒 + 顶板 + 四坡自锁尖顶;
  - 小客机经停机坪与航站楼连成一个整体。

用法: python3 tools/generate_airport_terminal.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

WALL = "blue"       # 大厅墙身
GLASS = "clear"     # 玻璃幕墙
ROOF = "gray"
TOWER = "orange"    # 控制塔
APRON = "gray"      # 停机坪

# =================================================================
# 1. 候机大厅 [0,6]x[0,2]: 地板 / 玻璃前脸 (出发大门) / 后墙 / 山墙
# =================================================================
for x0 in (0, 2, 4):
    b.flat_rect(f"fl_{x0}_0", x0, 0, 0.0, "cyan")   # 地板长板
    b.flat_rect(f"fl_{x0}_1", x0, 1, 0.0, "cyan")
for x in (0, 1, 4, 5):                              # 玻璃前脸下层
    b.wall_ns(f"ft0_{x}", x, 0.0, 0, GLASS)         #   (中间 [2,4] 出发大门)
for x0 in (0, 2, 4):                                # 前脸门楣层 (长板)
    b.lintel_ns(f"ft1_{x0}", x0, 0.0, 1, WALL)
for x0 in (0, 2, 4):                                # 后墙两层 (整片长板)
    b.lintel_ns(f"bk0_{x0}", x0, 2.0, 0, WALL)
    b.lintel_ns(f"bk1_{x0}", x0, 2.0, 1, WALL)
for y in range(2):                                  # 东西山墙两层
    b.wall_ew(f"gw_{y}_0", 0.0, y, 0, WALL)
    b.wall_ew(f"gw_{y}_1", 0.0, y, 1, WALL)
    b.wall_ew(f"ge_{y}_0", 6.0, y, 0, WALL)         # 东山墙 = 塔身下两层西壁
    b.wall_ew(f"ge_{y}_1", 6.0, y, 1, WALL)
for x0 in (0, 2, 4):                                # 屋面长板
    b.flat_rect(f"rf_{x0}_0", x0, 0, 2.0, ROOF)
    b.flat_rect(f"rf_{x0}_1", x0, 1, 2.0, ROOF)

# 出发门雨棚: 北长边整边吸中央门楣底沿, 向南平挑
b.flat_rect("canopy", 2, -1, 1.0, "yellow")

# =================================================================
# 2. 观景台 [0,2]x[0,2] (屋面西端): 玻璃环梁圈 + 梯形四坡顶 + 压顶
# =================================================================
b.lintel_ns("dk_s", 0, 0.0, 2, GLASS)
b.lintel_ns("dk_n", 0, 2.0, 2, GLASS)
b.lintel_ew("dk_w", 0.0, 0, 2, GLASS)
b.lintel_ew("dk_e", 2.0, 0, 2, GLASS)
DK_ROOF, DK_CAP = b.hip_roof2("dk_rf", 0, 0, 3.0, "cyan", cap_color="yellow")

# =================================================================
# 3. 控制塔 [6,7]x[0,1] (z 0..4.87): 下两层西壁借用大厅东山墙
# =================================================================
b.flat("tw_base", 6, 0, 0.0, ROOF)
for z in range(4):
    c = GLASS if z == 3 else TOWER                  # 顶层四面透明塔台
    b.wall_ns(f"tw_s_{z}", 6, 0.0, z, c)
    b.wall_ns(f"tw_n_{z}", 6, 1.0, z, c)
    b.wall_ew(f"tw_e_{z}", 7.0, 0, z, c)
b.wall_ew("tw_w_2", 6.0, 0, 2, TOWER)               # 高层西壁 (借墙之上)
b.wall_ew("tw_w_3", 6.0, 0, 3, GLASS)
b.flat("tw_top", 6, 0, 4.0, ROOF)
TW_HAT = b.hat4("tw_hat", 6, 0, 4.0, "red")

# =================================================================
# 4. 停机坪 (y -1..0) + 进近引导灯标
# =================================================================
for x in range(6):
    b.flat(f"ap_{x}", x, -1, 0.0, APRON)
b.crest_ns("bcn_4", 4, -1.0, 0.0, "orange")         # 引导灯标
b.crest_ns("bcn_5", 5, -1.0, 0.0, "orange")

# =================================================================
# 5. 小客机 (机头朝南, 正对出发大门西侧机位)
# =================================================================
b.flat("pl_fus_a", 1, -2, 0.0, "gray")              # 机身 [1,2]x[-2,-1]
b.flat("pl_fus_b", 1, -3, 0.0, "gray")              # 机身 [1,2]x[-3,-2]
b.flat("pl_wing_w", 0, -3, 0.0, "red")              # 左翼
b.flat("pl_wing_e", 2, -3, 0.0, "red")              # 右翼
b.place_tri("pl_nose", "equilateral_triangle",      # 机鼻
            (1.0, -3.0, 0.0), (2.0, -3.0, 0.0), (1.5, -3.866025, 0.0), "red")
b.spire_ns("pl_tail", 1, -1.0, 0.0, "red")          # 垂尾

# =================================================================
# 教程步骤 (18 步)
# =================================================================
b.step(
    "铺大厅地板: 6 片青色长板两排纵横铺满 [0,6]x[0,2], 长短边逐段互吸。",
    [f"fl_{x0}_{y}" for x0 in (0, 2, 4) for y in (0, 1)],
    tip="航站楼地基一次铺足 6 格长 —— 之后所有墙都吸在这些板边上。",
)
b.step(
    "铺停机坪: 大厅南面平铺 6 片灰色方板。",
    [f"ap_{x}" for x in range(6)],
    highlight=["fl_0_0", "fl_4_0"],
    tip="停机坪贴着大厅前脸底线, 是小客机的驻机位。",
)
b.step(
    "立山墙下层与玻璃前脸: 东西山墙各立 2 片蓝墙, 前脸立 4 片玻璃 "
    "(中间留 2 格出发大门)。",
    ["gw_0_0", "gw_1_0", "ge_0_0", "ge_1_0",
     "ft0_0", "ft0_1", "ft0_4", "ft0_5"],
    highlight=["fl_0_0", "fl_4_1"],
    tip="山墙底边吸地板短边, 玻璃片竖边与山墙拐角互吸。",
)
b.step(
    "立后墙下层: 3 片蓝色长板整片立起, 底边整边吸地板北长边。",
    ["bk0_0", "bk0_2", "bk0_4"],
    highlight=["fl_0_1", "fl_4_1"],
    tip="长板墙一片顶两片方片 —— 大跨度厅堂的标准砌法。",
)
b.step(
    "叠山墙上层与前脸门楣层: 山墙各叠 2 片, 前脸横架 3 片长板门楣 "
    "(中央一片正跨出发大门)。",
    ["gw_0_1", "gw_1_1", "ge_0_1", "ge_1_1",
     "ft1_0", "ft1_4", "ft1_2"],
    highlight=["ft0_0", "ft0_5"],
    tip="中央门楣两端竖边吸住左右门楣端边 —— 三片连成一道过梁。",
)
b.step(
    "叠后墙上层: 再立 3 片长板, 大厅四壁到 2 层高。",
    ["bk1_0", "bk1_2", "bk1_4"],
    highlight=["bk0_2"],
    tip="上下长板对缝整边贴合, 墙身最结实。",
)
b.step(
    "挑出发门雨棚: 1 片黄色长板北长边整边吸中央门楣底沿, 向南平挑。",
    ["canopy"],
    highlight=["ft1_2"],
    tip="单片长板平挑力矩 30, 铰链预算 40 —— 雨棚上别再放东西。",
)
b.step(
    "铺大厅屋面: 6 片灰色长板压住门楣、后墙与山墙顶边, 大厅封顶。",
    [f"rf_{x0}_{y}" for x0 in (0, 2, 4) for y in (0, 1)],
    highlight=["ft1_0", "bk1_4"],
    tip="屋面长边吸墙顶长边、短边吸山墙顶边 —— 逐段等长整边贴合。",
)
b.step(
    "起观景台环梁圈: 屋面西端立 4 片玻璃长板围成 2x2 环圈, "
    "南北两片底边吸屋面长边, 东西两片竖边锁拐角。",
    ["dk_s", "dk_n", "dk_w", "dk_e"],
    highlight=["rf_0_0", "rf_0_1"],
    tip="玻璃环廊 360 度看飞机起降 —— 先南北后东西, 四角自锁。",
)
b.step(
    "收观景台四坡顶: 4 片青色梯形下底整边吸环梁顶边, 四腰两两互吸。",
    DK_ROOF,
    highlight=["dk_s", "dk_e"],
    tip="梯形下底长 2 恰与环梁等长 —— 一片压一面。",
)
b.step(
    "盖攒尖压顶: 1 片黄色方片封住四坡顶天窗口, 观景台完工。",
    [DK_CAP],
    highlight=DK_ROOF[:2],
    tip="压顶落下的瞬间, 整顶梯形坡咔哒锁成一体。",
)
b.step(
    "控制塔起步: 东山墙外放塔底板, 立塔身南北壁与东壁下两层 "
    "(西面借用大厅东山墙)。",
    ["tw_base", "tw_s_0", "tw_s_1", "tw_n_0", "tw_n_1", "tw_e_0", "tw_e_1"],
    highlight=["ge_0_0", "ge_0_1"],
    tip="共墙不重复 —— 塔的西面就是大厅的东山墙, 一墙两用。",
)
b.step(
    "塔身升到第 3 层: 南北壁、东壁各叠 1 片, 西壁从大厅屋面高度补起。",
    ["tw_s_2", "tw_n_2", "tw_e_2", "tw_w_2"],
    highlight=["tw_s_1"],
    tip="从这层起塔身四面都是自己的墙了。",
)
b.step(
    "装顶层透明塔台: 4 片玻璃围出 360 度管制视野。",
    ["tw_s_3", "tw_n_3", "tw_e_3", "tw_w_3"],
    highlight=["tw_s_2"],
    tip="塔台管制员要同时看住跑道和停机坪 —— 四面都得透明。",
)
b.step(
    "塔顶封板: 1 片灰色方板盖住塔口, 塔身成为闭合箱形筒。",
    ["tw_top"],
    highlight=["tw_s_3", "tw_e_3"],
    tip="盖上顶板, 高塔抗风又抗晃。",
)
b.step(
    "装塔尖: 4 片红色等腰三角四坡自锁, 控制塔封顶。",
    TW_HAT,
    highlight=["tw_top"],
    tip="红色塔尖是全机场最高点 —— 也是它的地标。",
)
b.step(
    "停靠小客机: 机身 2 片接停机坪南沿, 左右机翼各 1 片, 机鼻三角收尖, "
    "机位正对出发大门。",
    ["pl_fus_a", "pl_fus_b", "pl_wing_w", "pl_wing_e", "pl_nose"],
    highlight=["ap_1", "ap_2"],
    tip="机身北端吸停机坪边 —— 飞机与航站楼连成一个整体。",
)
b.step(
    "立垂尾与引导灯标: 机尾立 1 片红色垂尾, 机坪南沿再立 2 片橙色"
    "灯标 —— 国际机场航站楼落成!",
    ["pl_tail", "bcn_4", "bcn_5"],
    highlight=["pl_fus_a", "ap_4"],
    tip="垂尾立在机身与机坪的拼缝上; 灯标指向跑道进近方向。",
)

b.finalize(
    model_id="airport_terminal_01",
    name="国际机场航站楼",
    name_en="Airport Terminal 01",
    description=(
        "6 格长的玻璃前脸候机大厅开着 2 格宽的出发大门, 黄色雨棚单片平挑 "
        "(力矩 30 <= 预算 40); 屋面西端玻璃环梁圈收梯形四坡顶做 360 度观景台, "
        "东端 4 层控制塔与大厅共用山墙, 顶层四面透明塔台戴红色四坡尖顶; "
        "楼前停机坪一架红翼小客机正对出发大门, 引导灯标指向跑道 —— 旅客"
        "登机、塔台放行, 一楼一塔一机连成整体。"
    ),
    difficulty=4,
    tags=["城市", "交通", "机场", "建筑", "进阶"],
    min_pieces=75,
    min_steps=18,
)
