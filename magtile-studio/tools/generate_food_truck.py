#!/usr/bin/env python3
"""生成模型 data/models/food_truck_01.json (街角美食餐车)。

城市生活主题: 消防站里的消防车是配角, 这里的餐车是绝对主角 ——
一辆 3 格长的厨房餐车停在街边, 侧面开着出餐窗口 (负空间),
窗口下一条吧台横跨车内车外 (台面同时吸住吧台墙顶与车身窗台底),
车顶向街面挑出三片条纹遮阳篷 (铰链线总力矩 45 <= 预算 60),
人行道上还有梧桐树、菜单招牌和两面斜插的开业彩旗。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 三条街面: 车道 [0,5]x[0,1] + 人行道 [0,5]x[1,2] +
    餐位广场 [0,5]x[-1,0]                                       15 片
  - 餐车 [1,4]x[0,1] (z 0..2): 后壁 6 + 前脸 5 (出餐窗口) +
    车头/车尾 4 + 车顶 3                                         18 片
  - 遮阳篷: 车顶前沿向南挑出 3 片 (红-黄-红条纹)                  3 片
  - 吧台: 3 片吧台墙 + 3 片台面 (台面北沿吸车身窗台底边)           6 片
  - 菜单招牌: 广场西端 1 片立牌 + 1 片尖顶                         2 片
  - 街景: 车顶彩旗 3 + 梧桐树 2 + 开业彩旗 (菱形斜插) 2            7 片
  合计 51 片, 16 个教程步骤, 4 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 出餐窗口是负空间: 前脸下层只砌两端, 上层窗楣方片靠两侧竖边
    互吸悬跨窗口 (一格宽窗洞的标准砌法);
  - 遮阳篷铰链线 (y=0, z=2) 总长 3, 力矩 3 x 15 = 45 <= 预算 60,
    篷上不再立任何装饰 —— 预算纪律;
  - 吧台台面同时吸吧台墙顶边与车身窗台底边, 一条吧台把餐车
    与广场焊成整体;
  - 开业彩旗是斜插的菱形 (平行四边形斜靠), 底边整边吸人行道
    北沿, 倾斜方向朝外避开梧桐树。

用法: python3 tools/generate_food_truck.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

BODY = "pink"       # 车身
ROOF = "gray"       # 车顶
BAR = "orange"      # 吧台
WALK = "gray"       # 人行道
ROAD = "blue"       # 车道
PLAZA = "green"     # 餐位广场

# =================================================================
# 1. 三条街面 (z=0): 车道 / 人行道 / 餐位广场, 各 5 片方板
# =================================================================
for x in range(5):
    b.flat(f"rd_{x}", x, 0, 0.0, ROAD)              # 车道 (餐车停在上面)
    b.flat(f"wk_{x}", x, 1, 0.0, WALK)              # 人行道
    b.flat(f"pz_{x}", x, -1, 0.0, PLAZA)            # 餐位广场

# =================================================================
# 2. 餐车 [1,4]x[0,1] (z 0..2): 后壁 / 前脸 (出餐窗口) / 车头车尾 / 车顶
# =================================================================
for x in range(1, 4):                               # 后壁 (y=1) 两层
    b.wall_ns(f"bk0_{x}", x, 1.0, 0, BODY)
    b.wall_ns(f"bk1_{x}", x, 1.0, 1, BODY)
b.wall_ns("ft0_1", 1, 0.0, 0, BODY)                 # 前脸下层两端
b.wall_ns("ft0_3", 3, 0.0, 0, BODY)                 #   (中间 [2,3] 是出餐窗口)
for x in range(1, 4):                               # 前脸上层 (中片是窗楣)
    b.wall_ns(f"ft1_{x}", x, 0.0, 1, BODY)
b.wall_ew("cab0", 1.0, 0, 0, BODY)                  # 车头下层
b.wall_ew("cab1", 1.0, 0, 1, "clear")               # 车头挡风玻璃
b.wall_ew("tail0", 4.0, 0, 0, BODY)                 # 车尾两层
b.wall_ew("tail1", 4.0, 0, 1, BODY)
for x in range(1, 4):                               # 车顶
    b.flat(f"rf_{x}", x, 0, 2.0, ROOF)

# =================================================================
# 3. 遮阳篷 (z=2): 车顶前沿向南挑出 3 片条纹方板, 覆盖 [1,4]x[-1,0] 上空
# =================================================================
b.flat("awn_1", 1, -1, 2.0, "red")
b.flat("awn_2", 2, -1, 2.0, "yellow")
b.flat("awn_3", 3, -1, 2.0, "red")

# =================================================================
# 4. 吧台 (y=-1 沿线): 3 片吧台墙 + 3 片台面 (北沿吸车身窗台底边)
# =================================================================
for x in range(1, 4):
    b.wall_ns(f"bar_w_{x}", x, -1.0, 0, BAR)        # 吧台墙
for x in range(1, 4):
    b.flat(f"bar_t_{x}", x, -1, 1.0, BAR)           # 台面 (z=1)

# =================================================================
# 5. 菜单招牌 (广场西端) + 街景 (彩旗 / 梧桐树 / 开业斜旗)
# =================================================================
b.wall_ns("menu", 0, -1.0, 0, "purple")             # 菜单立牌
b.spire_ns("menu_top", 0, -1.0, 1.0, "yellow")      # 招牌尖顶
for x in range(1, 4):                               # 车顶后沿彩旗
    b.crest_ns(f"flag_{x}", x, 1.0, 2.0, "cyan" if x % 2 else "yellow")
b.spire_ns("tree_1", 1, 2.0, 0.0, "green")          # 梧桐树
b.spire_ns("tree_3", 3, 2.0, 0.0, "green")
# 开业彩旗: 菱形斜插在人行道北沿, 左旗向西倒、右旗向东倒 (避开梧桐树)
b.place_edge("banner_w", "rhombus", 0,
             (1.0, 2.0, 0.0), (0.0, 2.0, 0.0), (0.0, 0.0, 1.0), "red")
b.place_edge("banner_e", "rhombus", 0,
             (4.0, 2.0, 0.0), (5.0, 2.0, 0.0), (0.0, 0.0, 1.0), "red")

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺车道: 5 片蓝色方板一字排开 ([0,5]x[0,1]), 相邻边互吸。",
    [f"rd_{x}" for x in range(5)],
    tip="餐车马上要停在这条车道上 —— 地面缝缝吸牢。",
)
b.step(
    "铺人行道: 车道北侧再铺 5 片灰色方板。",
    [f"wk_{x}" for x in range(5)],
    highlight=["rd_0", "rd_4"],
    tip="人行道贴着车道北沿, 一会儿梧桐树就种在这里。",
)
b.step(
    "铺餐位广场: 车道南侧铺 5 片绿色方板, 三条街面完工。",
    [f"pz_{x}" for x in range(5)],
    highlight=["rd_0", "rd_4"],
    tip="广场是食客排队的地方, 也是吧台的地基。",
)
b.step(
    "竖餐车后壁下层: 3 片粉色正方形沿车道北线立起。",
    ["bk0_1", "bk0_2", "bk0_3"],
    highlight=["rd_1", "rd_3"],
    tip="后壁底边同时吸住车道边与人行道边, 一举两得。",
)
b.step(
    "竖前脸下层两端: 前脸只立东西两端各 1 片, 中间留出一格宽的出餐窗口。",
    ["ft0_1", "ft0_3"],
    highlight=["rd_1", "rd_3"],
    tip="这个负空间就是餐车的灵魂 —— 出餐窗口。",
)
b.step(
    "封车头车尾下层: 车头车尾各立 1 片, 竖边与前后壁拐角互吸。",
    ["cab0", "tail0"],
    highlight=["ft0_1", "bk0_3"],
    tip="车头朝西 —— 下一步就给它装挡风玻璃。",
)
b.step(
    "叠上层车身: 后壁 3 片、车尾 1 片、车头换透明挡风玻璃。",
    ["bk1_1", "bk1_2", "bk1_3", "tail1", "cab1"],
    highlight=["bk0_1", "cab0"],
    tip="透明片就是驾驶室的挡风玻璃, 别装反位置。",
)
b.step(
    "装窗楣合前脸上层: 两端 2 片先叠上, 中间窗楣片靠两侧竖边互吸悬跨窗口。",
    ["ft1_1", "ft1_3", "ft1_2"],
    highlight=["ft0_1", "ft0_3"],
    tip="窗楣两条竖边同时吸住左右邻片 —— 一格宽窗洞的标准砌法。",
)
b.step(
    "盖车顶: 3 片灰色方板压住四面墙顶, 餐车封顶。",
    ["rf_1", "rf_2", "rf_3"],
    highlight=["ft1_2", "bk1_2"],
    tip="从出餐窗口望进去, 厨房宽敞明亮。",
)
b.step(
    "挑遮阳篷: 车顶前沿向南平挑 3 片红黄条纹方板, 篷片之间也要互吸。",
    ["awn_1", "awn_2", "awn_3"],
    highlight=["rf_1", "rf_3"],
    tip="每片篷力矩 15, 三片共用一条铰链线 (预算 60) —— 刚刚好, 篷上别再放东西。",
)
b.step(
    "砌吧台墙: 广场北沿立 3 片橙色矮墙, 正对出餐窗口。",
    ["bar_w_1", "bar_w_2", "bar_w_3"],
    highlight=["pz_1", "pz_3"],
    tip="吧台墙底边吸广场北沿, 就立在餐车正前方。",
)
b.step(
    "铺吧台台面: 3 片橙色方板同时吸住吧台墙顶边与车身窗台底边。",
    ["bar_t_1", "bar_t_2", "bar_t_3"],
    highlight=["bar_w_2", "ft1_2"],
    tip="一条吧台把餐车和广场焊成整体 —— 出餐、用餐一条线。",
)
b.step(
    "立菜单招牌: 广场西端立 1 片紫色立牌, 牌顶戴黄色尖顶。",
    ["menu", "menu_top"],
    highlight=["pz_0"],
    tip="招牌立在排队动线的入口, 老远就能看见。",
)
b.step(
    "插车顶彩旗: 车顶后沿立 3 片青黄相间的三角彩旗。",
    ["flag_1", "flag_2", "flag_3"],
    highlight=["rf_1", "rf_3"],
    tip="彩旗立在车顶后沿正上方, 力臂为零纯压不弯。",
)
b.step(
    "种梧桐树: 人行道北沿立 2 棵绿色等腰三角梧桐。",
    ["tree_1", "tree_3"],
    highlight=["wk_1", "wk_3"],
    tip="树影正好落在餐车上 —— 夏天排队也不晒。",
)
b.step(
    "斜插开业彩旗: 2 面红色菱形旗沿人行道北沿向外斜插, 街角美食餐车开业!",
    ["banner_w", "banner_e"],
    highlight=["wk_0", "wk_4"],
    tip="菱形旗底边整边吸人行道边, 倾斜方向朝外避开梧桐树。",
)

b.finalize(
    model_id="food_truck_01",
    name="街角美食餐车",
    name_en="Food Truck 01",
    description=(
        "把餐车从配角提拔成主角: 3 格长的厨房餐车侧开一格宽出餐窗口 (负空间"
        "窗楣砌法), 窗下一条橙色吧台同时吸住吧台墙顶与车身窗台底、把车和广场"
        "焊成整体; 车顶向街面平挑三片红黄条纹遮阳篷 (力矩 45 <= 铰链预算 60), "
        "人行道上梧桐成荫、菱形开业彩旗斜插 —— 出餐窗口一开, 整条街都香了。"
    ),
    difficulty=3,
    tags=["城市", "美食", "餐车", "职业体验", "负空间"],
    min_pieces=50,
    min_steps=16,
)
