#!/usr/bin/env python3
"""生成模型 data/models/rehab_park_01.json (康复操场)。

医院健康主题: 全库第一座康复训练操场 —— 主角是一条"上-平-下"
无障碍训练环线: 中央康复山丘 (箱形围筒 + 长板台面) 西边一条
30 度上坡、东边一条 30 度下坡, 两坡顶边都同时吸台面短边与壁顶
(共线双连接), 坡尾自然落地零悬臂 —— 从西边慢慢走上去、站上
台顶、再从东边稳稳走下来, 台顶南北沿各立两片黄色安全护栏,
扶着走不怕摔。山丘南边一条平行双杠步道: 四片青色扶杆分立
步道两侧地缝上, 小朋友扶着双杆练走路; 步道东头接一串橙黄
相间的平衡步石, 踩着格子回到坡道起点。北草坪两片橙色休息凳
面朝山丘, 西北角红色加油旗高扬 —— 一步一步来, 每天都进步!

与 skate_park_01 (街式道具场) / slide_playground_01 (竞速滑
梯塔) 的区分: 那里的坡道是"冲下来"的玩具, 这里的坡道是
"走上去再走下来"的环线 —— 双坡对称上下、台顶带护栏、地面
配扶杆步道, 结构为康复训练的慢动线服务。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 场地 6x4):
  - 操场地坪 6x4: 步道/步石/草坪混铺                          21 片
  - 康复山丘 [2,4]x[2,3]: 箱形围筒 x6 + 长板台面 x1            7 片
  - 无障碍坡道: 30 度长板 x2 (西上东下, 坡尾落地)              2 片
  - 台顶安全护栏: 黄等边 x4 (南北沿各 2)                       4 片
  - 平行双杠: 青色扶杆方板 x4 (步道两侧地缝而立)               4 片
  - 休息凳等边 x2 + 加油旗等腰 x1                              3 片
  合计 41 片, 9 个教程步骤, 4 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, 常规+strict 双档零警告):
  - 两条坡道均双端受力: 顶边整边同吸台面短边与山丘壁顶
    (共线双连接), 坡尾自然落地 —— 剪断顶边铰链坡道仍自行接地;
  - 山丘四壁竖边互吸成环, 台面长板短边整边压东西壁顶,
    长边再压南北壁顶 —— 筒 + 盖锁成箱形框架;
  - 护栏底边整边吸壁顶边 (与台面长边共线双吸), 重心正压
    铰链零力矩; 扶杆/休息凳/旗杆底边全部整边吸地坪格线。

用法: python3 tools/generate_rehab_park.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

LAWN = "green"      # 草坪
WALK = "clear"      # 双杠步道
STONE_A = "orange"  # 平衡步石 A
STONE_B = "yellow"  # 平衡步石 B
PAVE = "gray"       # 坡道起止区
MOUND = "green"     # 康复山丘
DECK = "clear"      # 台面
RAMP = "blue"       # 无障碍坡道
RAIL = "yellow"     # 台顶安全护栏
BAR = "cyan"        # 平行双杠扶杆
BENCH = "orange"    # 休息凳
FLAG = "red"        # 加油旗

# =================================================================
# 1. 操场地坪 6x4
# =================================================================
# 行 y[0,1]: 双杠步道 (x[1,3]) + 平衡步石 (x[4,6])
b.flat("g0_0", 0, 0, 0.0, LAWN)
b.flat("g0_1", 1, 0, 0.0, WALK)
b.flat("g0_2", 2, 0, 0.0, WALK)
b.flat("g0_3", 3, 0, 0.0, STONE_A)
b.flat("g0_4", 4, 0, 0.0, STONE_B)
b.flat("g0_5", 5, 0, 0.0, STONE_A)
# 行 y[1,2]: 扶杆北排落脚 + 步石折返
b.flat("g1_0", 0, 1, 0.0, LAWN)
b.flat("g1_1", 1, 1, 0.0, LAWN)
b.flat("g1_2", 2, 1, 0.0, LAWN)
b.flat("g1_3", 3, 1, 0.0, LAWN)
b.flat_rect("g1_4", 4, 1, 0.0, LAWN)
# 行 y[2,3]: 坡道起止区 + 山丘地基
b.flat_rect("g2_w", 0, 2, 0.0, PAVE)
b.flat("g2_m0", 2, 2, 0.0, DECK)
b.flat("g2_m1", 3, 2, 0.0, DECK)
b.flat_rect("g2_e", 4, 2, 0.0, PAVE)
# 行 y[3,4]: 北草坪 (方板留边给旗与凳)
b.flat("g3_0", 0, 3, 0.0, LAWN)
b.flat("g3_1", 1, 3, 0.0, LAWN)
b.flat("g3_2", 2, 3, 0.0, LAWN)
b.flat("g3_3", 3, 3, 0.0, LAWN)
b.flat("g3_4", 4, 3, 0.0, LAWN)
b.flat("g3_5", 5, 3, 0.0, LAWN)

# =================================================================
# 2. 康复山丘 [2,4]x[2,3]: 箱形围筒 + 长板台面
# =================================================================
b.wall_ns("m_s0", 2, 2.0, 0, MOUND)
b.wall_ns("m_s1", 3, 2.0, 0, MOUND)
b.wall_ns("m_n0", 2, 3.0, 0, MOUND)
b.wall_ns("m_n1", 3, 3.0, 0, MOUND)
b.wall_ew("m_w", 2.0, 2, 0, MOUND)
b.wall_ew("m_e", 4.0, 2, 0, MOUND)
b.flat_rect("m_deck", 2, 2, 1.0, DECK)

# 无障碍坡道: 西上东下, 顶边同吸台面短边与壁顶
b.ramp("ramp_up", "-x", 2, 2, 1.0, RAMP)
b.ramp("ramp_down", "+x", 4, 2, 1.0, RAMP)

# 台顶安全护栏: 南北沿各 2 片黄等边
b.crest_ns("rail_s0", 2, 2.0, 1.0, RAIL)
b.crest_ns("rail_s1", 3, 2.0, 1.0, RAIL)
b.crest_ns("rail_n0", 2, 3.0, 1.0, RAIL)
b.crest_ns("rail_n1", 3, 3.0, 1.0, RAIL)

# =================================================================
# 3. 平行双杠 (步道 [1,3]x[0,1] 两侧扶杆)
# =================================================================
b.wall_ns("bar_s0", 1, 0.0, 0, BAR)
b.wall_ns("bar_s1", 2, 0.0, 0, BAR)
b.wall_ns("bar_n0", 1, 1.0, 0, BAR)
b.wall_ns("bar_n1", 2, 1.0, 0, BAR)

# =================================================================
# 4. 休息凳 + 加油旗 (北草坪)
# =================================================================
b.crest_ns("bench_0", 3, 4.0, 0.0, BENCH)
b.crest_ns("bench_1", 4, 4.0, 0.0, BENCH)
b.spire_ns("flag", 0, 4.0, 0.0, FLAG)

# =================================================================
# 教程步骤 (9 步)
# =================================================================
b.step(
    "铺操场南排: 白色双杠步道两格居西, 橙黄相间的平衡步石"
    "三格接到东头。",
    ["g0_0", "g0_1", "g0_2", "g0_3", "g0_4", "g0_5"],
    tip="步石颜色一格一换 —— 踩着格子练平衡。",
)
b.step(
    "铺第二排草坪: 全部方板 —— 北排扶杆要吸这条格线。",
    ["g1_0", "g1_1", "g1_2", "g1_3", "g1_4"],
    highlight=["g0_1", "g0_2"],
)
b.step(
    "铺山丘行: 两片白色台基居中, 东西各一条灰色长板 —— "
    "坡道就落在长板上。",
    ["g2_w", "g2_m0", "g2_m1", "g2_e"],
    highlight=["g1_2"],
)
b.step(
    "铺北草坪: 6 片方板合拢场地, 西端留旗位、东段留凳位。",
    ["g3_0", "g3_1", "g3_2", "g3_3", "g3_4", "g3_5"],
    highlight=["g2_m0"],
)
b.step(
    "立平行双杠: 4 片青色扶杆分立步道两侧地缝, 竖边成对互吸。",
    ["bar_s0", "bar_s1", "bar_n0", "bar_n1"],
    highlight=["g0_1", "g0_2"],
    tip="两侧扶杆间距一格 —— 双手扶杆, 一步一步来。",
)
b.step(
    "起康复山丘围筒: 四面六片绿墙竖边互吸成环。",
    ["m_s0", "m_s1", "m_n0", "m_n1", "m_w", "m_e"],
    highlight=["g2_m0", "g2_m1"],
    tip="山丘是训练环线的制高点 —— 箱形闭环无单点失效。",
)
b.step(
    "盖台面、搭双坡: 长板台面短边压东西壁顶, 西坡上行、"
    "东坡下行, 坡顶边同吸台面边与壁顶, 坡尾自然落地。",
    ["m_deck", "ramp_up", "ramp_down"],
    highlight=["m_w", "m_e"],
    tip="从西边走上去、东边走下来 —— 上-平-下一条环线。",
)
b.step(
    "立台顶安全护栏: 南北沿各 2 片黄等边, 底边吸壁顶边。",
    ["rail_s0", "rail_s1", "rail_n0", "rail_n1"],
    highlight=["m_deck"],
    tip="护栏与台面长边共线双吸 —— 扶着走, 不怕摔。",
)
b.step(
    "摆休息凳、升加油旗: 两片橙等边面朝山丘, 红色等腰旗"
    "立上西北角 —— 康复操场开练, 每天都进步!",
    ["bench_0", "bench_1", "flag"],
    highlight=["g3_3", "g3_4"],
)

b.finalize(
    model_id="rehab_park_01",
    name="康复操场",
    name_en="Rehab Park 01",
    description=(
        "全库第一座康复训练操场, 主角是'上-平-下'无障碍训练环线: "
        "中央康复山丘箱形围筒 + 长板台面, 西边 30 度上坡、东边 30 度"
        "下坡, 两坡顶边都同吸台面短边与壁顶 (共线双连接) 坡尾自然"
        "落地零悬臂, 台顶南北沿四片黄色安全护栏扶着走不怕摔 —— 与 "
        "skate_park_01/slide_playground_01 '冲下来'的坡道不同, 这里"
        "的双坡是'走上去再走下来'的对称慢动线; 山丘南边平行双杠步道 "
        "四片青色扶杆分立地缝, 东头接橙黄相间的平衡步石踩格折返; "
        "北草坪休息凳面朝山丘, 加油旗高扬 —— 一步一步来, 每天都进步!"
    ),
    difficulty=2,
    tags=["医院", "城市", "运动", "康复", "无障碍"],
    min_pieces=41,
    min_steps=9,
)
