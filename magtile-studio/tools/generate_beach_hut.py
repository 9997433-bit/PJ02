#!/usr/bin/env python3
"""生成模型 data/models/beach_hut_01.json (海滩小屋)。

海岸度假主题: 全库第一栋高脚海滩小屋 —— 金色沙滩上四根桩柱
托起木甲板, 粉墙小屋盖着平顶露台 (两端小三角女儿墙), 西窗
东门; 甲板东侧一条 30 度栈道斜下沙滩; 屋旁一把大遮阳伞
(黄色伞座 + 红色四坡伞盖), 两块冲浪板插在浪花线上 ——
潮起潮落, 假期开始!

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 浪花线: 青色长板 x3 (y [0,1])                             3 片
  - 沙滩: 黄色方板 x12 + 长板 x3 (y [1,4])                   15 片
  - 高脚甲板 (x [1,3], y [2,4]): 桩柱立墙 x4 + 甲板方板 x4    8 片
  - 小屋 (x [1,3], y [3,4], z 1~2): 山墙 窗格方+门框方 x2
    + 长板墙 x2 + 平顶长板 x1 + 女儿墙小三角 x2               7 片
  - 登台栈道: 30 度长板 x1 (甲板东沿下沙滩)                   1 片
  - 遮阳伞 (x [4,5], y [1,2]): 伞座方墙 x4 + 四坡伞盖 x4      8 片
  - 冲浪板: 瘦高等腰三角 x2 (插在浪花线拼缝)                  2 片
  合计 44 片, 12 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, strict 档同样全绿):
  - 四根桩柱踩沙滩拼缝, 甲板四片方板双排互吸多路受力 ——
    剪断任一桩顶铰链, 甲板仍经其余桩柱回到地面;
  - 小屋山墙先立 (底边吸甲板板边), 长板墙竖边吸山墙竖边,
    平顶长板两条长边整边压墙顶 —— 墙-顶锁成箱形闭环;
  - 女儿墙小三角重心正压山墙顶铰链 (力矩 0);
  - 栈道顶边整边吸甲板东沿、坡尾自然落沙 (顶铰链+接地);
  - 伞座四墙闭环, 伞盖四棱互吸自锁成环正压座顶。

用法: python3 tools/generate_beach_hut.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

SURF = "cyan"       # 浪花线
SAND = "yellow"     # 沙滩
PILE = "gray"       # 桩柱
DECKC = "orange"    # 甲板 / 栈道
HUT = "pink"        # 小屋墙
GLASS = "clear"     # 观景窗
DOOR = "orange"     # 小门
ROOF = "gray"       # 平顶露台
PARA = "pink"       # 女儿墙小三角
POLE = "yellow"     # 伞座
CANOPY = "red"      # 伞盖
BOARD1 = "blue"     # 冲浪板 1
BOARD2 = "green"    # 冲浪板 2

# =================================================================
# 1. 浪花线与沙滩 (x [0,6], y [0,4])
# =================================================================
for k in range(3):
    b.flat_rect(f"surf_{k}", 2 * k, 0, 0.0, SURF)
for x in range(6):
    b.flat(f"sd_a_{x}", x, 1, 0.0, SAND)
    b.flat(f"sd_b_{x}", x, 2, 0.0, SAND)
for k in range(3):
    b.flat_rect(f"sd_c_{k}", 2 * k, 3, 0.0, SAND)

# =================================================================
# 2. 高脚甲板 (x [1,3], y [2,4], z=1): 四桩柱 + 四方板
# =================================================================
b.wall_ns("pile_s1", 1, 2.0, 0, PILE)
b.wall_ns("pile_s2", 2, 2.0, 0, PILE)
b.wall_ns("pile_n1", 1, 4.0, 0, PILE)
b.wall_ns("pile_n2", 2, 4.0, 0, PILE)
for x in (1, 2):
    for y in (2, 3):
        b.flat(f"deck_{x}_{y}", x, y, 1.0, DECKC)

# =================================================================
# 3. 小屋 (x [1,3], y [3,4], z 1~2): 山墙 + 长板墙 + 平顶露台
# =================================================================
b.add("hut_win", "window_square", (1.0, 3.5, 1.5), (90, 0, 90), GLASS)
b.add("hut_door", "door_frame", (3.0, 3.5, 1.5), (90, 0, 90), DOOR)
b.lintel_ns("hut_s", 1, 3.0, 1, HUT)
b.lintel_ns("hut_n", 1, 4.0, 1, HUT)
b.flat_rect("hut_roof", 1, 3, 2.0, ROOF)
b.crest_ew("para_w", 1.0, 3, 2.0, PARA)
b.crest_ew("para_e", 3.0, 3, 2.0, PARA)

# =================================================================
# 4. 登台栈道: 30 度长板, 顶边吸甲板东沿, 坡尾落沙
# =================================================================
b.ramp("boardwalk", "+x", 3.0, 2, 1.0, DECKC)

# =================================================================
# 5. 遮阳伞 (x [4,5], y [1,2]): 伞座小方箱 + 四坡伞盖
# =================================================================
b.wall_ns("um_s", 4, 1.0, 0, POLE)
b.wall_ns("um_n", 4, 2.0, 0, POLE)
b.wall_ew("um_w", 4.0, 1, 0, POLE)
b.wall_ew("um_e", 5.0, 1, 0, POLE)
UMBRELLA = b.hat4("um_top", 4, 1, 1.0, CANOPY,
                  shape="equilateral_triangle")

# =================================================================
# 6. 冲浪板: 两片瘦高等腰插在浪花线拼缝
# =================================================================
b.spire_ns("board_w", 0, 1.0, 0.0, BOARD1)
b.spire_ns("board_e", 5, 1.0, 0.0, BOARD2)

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺浪花线: 3 片青色长板连成海岸。",
    ["surf_0", "surf_1", "surf_2"],
    tip="长板短边互吸 —— 浪花线笔直, 冲浪板等会儿就插在这。",
)
b.step(
    "铺沙滩第一行: 6 片黄色方板 (y [1,2])。",
    [f"sd_a_{x}" for x in range(6)],
    highlight=["surf_0"],
    tip="沙滩方板与浪花线整边贴合 —— 涨潮也冲不走。",
)
b.step(
    "铺沙滩第二行: 再来 6 片 (y [2,3])。",
    [f"sd_b_{x}" for x in range(6)],
    highlight=["sd_a_0"],
    tip="这行的拼缝就是高脚桩柱的落点。",
)
b.step(
    "铺沙滩背排: 3 片黄色长板 (y [3,4]), 沙滩合拢。",
    ["sd_c_0", "sd_c_1", "sd_c_2"],
    highlight=["sd_b_0"],
    tip="高脚屋的后排桩柱就立在这排长板前沿。",
)
b.step(
    "立四根桩柱: 前排踩 y=2 拼缝, 后排踩 y=4 沙沿。",
    ["pile_s1", "pile_s2", "pile_n1", "pile_n2"],
    highlight=["sd_b_1", "sd_c_0"],
    tip="高脚屋防潮防沙 —— 四根桩柱双排受力。",
)
b.step(
    "铺高脚甲板: 4 片橙色方板压桩柱顶, 拼缝互吸。",
    ["deck_1_2", "deck_2_2", "deck_1_3", "deck_2_3"],
    highlight=["pile_s1", "pile_n2"],
    tip="剪断任何一根桩顶铰链, 甲板仍有三条路回地面。",
)
b.step(
    "立小屋山墙: 西端透明观景窗 + 东端橙色小门。",
    ["hut_win", "hut_door"],
    highlight=["deck_1_3", "deck_2_3"],
    tip="山墙底边整边吸甲板板边 —— 先立两端, 再挂长墙。",
)
b.step(
    "挂小屋长板墙: 南北各一片, 竖边吸山墙竖边。",
    ["hut_s", "hut_n"],
    highlight=["hut_win", "hut_door"],
    tip="长板墙顶边长 2 —— 平顶要整边压住它。",
)
b.step(
    "盖平顶露台 + 两端女儿墙小三角。",
    ["hut_roof", "para_w", "para_e"],
    highlight=["hut_s", "hut_n"],
    tip="平顶两条长边压墙顶锁成箱形, 小三角正压山墙顶。",
)
b.step(
    "架登台栈道: 顶边整边吸甲板东沿, 坡尾落回沙滩。",
    ["boardwalk"],
    highlight=["deck_2_2"],
    tip="顶铰链 + 接地坡尾 —— 抱着冲浪板跑上跑下都稳。",
)
b.step(
    "搭遮阳伞座: 4 片黄色方墙围成小方箱。",
    ["um_s", "um_n", "um_w", "um_e"],
    highlight=["sd_a_4", "sd_b_4"],
    tip="四墙竖边互吸闭环 —— 伞座比伞面更要紧。",
)
b.step(
    "撑开伞盖 + 插好冲浪板 —— 假期开始!",
    UMBRELLA + ["board_w", "board_e"],
    highlight=["um_s", "surf_0"],
    tip="伞盖四棱互吸自锁, 冲浪板重心正压浪花线拼缝。",
)

b.finalize(
    model_id="beach_hut_01",
    name="海滩小屋",
    name_en="Beach Hut 01",
    description=(
        "全库第一栋高脚海滩小屋: 四根桩柱踩沙滩拼缝托起木甲板,"
        " 粉墙小屋西窗东门, 平顶长板双长边压墙顶锁成箱形露台,"
        " 两端女儿墙小三角正压山墙顶; 甲板东沿一条 30 度栈道斜下"
        "沙滩 (顶铰链+接地坡尾); 屋旁黄色伞座撑起红色四坡伞盖,"
        " 两块冲浪板插在浪花线拼缝上 —— 潮起潮落, 假期开始!"
    ),
    difficulty=2,
    tags=["海岸", "沙滩", "小屋", "度假"],
    min_pieces=42,
    min_steps=12,
)
