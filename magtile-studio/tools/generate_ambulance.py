#!/usr/bin/env python3
"""生成模型 data/models/ambulance_01.json (120 急救车)。

城市守护者主题: 与火星车 (低矮宽甲板) 完全不同的高箱厢式车 ——
2 片车轮底座托起 2x1 底盘甲板, 甲板上立起两层高的白色方舱
(红色急救条纹绕舱一周, 舱顶红色警灯朝前); 车头驾驶室退低一级,
透明挡风正对前方, 蓝色示宽灯立在驾驶室顶前沿 —— 高低错落的
阶梯剪影就是厢式救护车的标志。车后是医院急诊楼门脸: 蓝色
急诊门、透明大窗、二层红十字, 门口透明雨棚平挑遮雨, 楼顶
红色急救旗高扬; 路口安全锥围出急救通道, 路灯下一路畅通 ——
呜哇呜哇, 请让出生命通道!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 车头朝东):
  - 街道 7x4: 马路三排 x15 + 人行道 x7                        22 片
  - 医院门脸 (y=4 立面): 门/窗/红十字两层 x8                    8 片
  - 急诊雨棚: 透明方板 x2 平挑 + 楼顶红旗等腰 x1                3 片
  - 救护车: 车轮底座 x2 + 底盘甲板 x1 + 方舱壁 x6 + 舱顶 x1
    + 红警灯 x1 + 驾驶室墙 x3 + 驾驶室顶 x1 + 蓝示宽灯 x1     16 片
  - 路灯: 方柱 x1 + 黄灯等边 x1                                 2 片
  - 安全锥: 橙色等边 x2                                         2 片
  合计 53 片, 16 个教程步骤, 7 种磁力片形状 (CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验):
  - 车轮底座底边 (长 2) 整边吸马路长板拼缝, 甲板长边整边压
    双轮顶 —— 轮组+甲板锁成门式框架;
  - 方舱前后壁踩甲板短边, 侧壁竖边吸进前后壁拐角 (圈层砌法),
    舱顶长板四边全吸 —— 方舱是完整的箱形环;
  - 驾驶室三墙直接落地, 车顶方板四边压墙顶, 西边整条贴住
    方舱前壁底线 —— 高低车身共享受力;
  - 医院立面重心正压地缝铰链零力矩, 雨棚单片力矩 15 <= 20
    且两片互吸共担。

用法: python3 tools/generate_ambulance.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

ROAD = "gray"       # 马路
WALK = "cyan"       # 人行道
BODY = "clear"      # 方舱 (白车身用透明白)
STRIPE = "red"      # 急救条纹
DECK = "gray"       # 底盘
WHEEL = "gray"      # 车轮
CAB = "gray"        # 驾驶室
GLASS = "clear"     # 挡风玻璃
HOSP = "gray"       # 医院墙
DOOR = "blue"       # 急诊门
WIN = "clear"       # 医院大窗
CROSS = "red"       # 红十字
CANOPY = "clear"    # 急诊雨棚
FLAG = "red"        # 急救旗
CONE = "orange"     # 安全锥
LAMP = "yellow"     # 路灯

# =================================================================
# 1. 街道 7x4: 马路三排 (救护车道在中排) + 人行道
# =================================================================
b.flat("r0_0", 0, 0, 0.0, ROAD)
b.flat_rect("r0_a", 1, 0, 0.0, ROAD)                # [1,3] 轮缝板
b.flat_rect("r0_b", 3, 0, 0.0, ROAD)
b.flat("r0_5", 5, 0, 0.0, ROAD)
b.flat("r0_6", 6, 0, 0.0, ROAD)
b.flat("r1_0", 0, 1, 0.0, ROAD)
b.flat_rect("r1_a", 1, 1, 0.0, ROAD)                # [1,3] 车底板
b.flat("r1_3", 3, 1, 0.0, ROAD)                     # 驾驶室地
b.flat_rect("r1_b", 4, 1, 0.0, ROAD)
b.flat("r1_6", 6, 1, 0.0, ROAD)
b.flat("r2_0", 0, 2, 0.0, ROAD)
b.flat_rect("r2_a", 1, 2, 0.0, ROAD)                # [1,3] 轮缝板
b.flat("r2_3", 3, 2, 0.0, ROAD)
b.flat_rect("r2_b", 4, 2, 0.0, ROAD)
b.flat("r2_6", 6, 2, 0.0, ROAD)
for x in range(7):
    b.flat(f"wk_{x}", x, 3, 0.0, WALK)              # 人行道

# =================================================================
# 2. 医院急诊楼门脸 (y=4 立面, x2..6)
# =================================================================
b.add("h1_win_w", "window_square", (2.5, 4.0, 0.5), (90, 0, 0), WIN)
b.add("h1_door", "door_frame", (3.5, 4.0, 0.5), (90, 0, 0), DOOR)
b.add("h1_win_e", "window_square", (4.5, 4.0, 0.5), (90, 0, 0), WIN)
b.wall_ns("h1_sq", 5, 4.0, 0, HOSP)
b.add("h2_win_w", "window_square", (2.5, 4.0, 1.5), (90, 0, 0), WIN)
b.wall_ns("h2_cross", 3, 4.0, 1, CROSS)             # 红十字
b.add("h2_win_e", "window_square", (4.5, 4.0, 1.5), (90, 0, 0), WIN)
b.wall_ns("h2_sq", 5, 4.0, 1, HOSP)

# =================================================================
# 3. 急诊雨棚 (z=2 平挑) + 楼顶急救旗
# =================================================================
b.flat("cp_w", 2, 3, 2.0, CANOPY)                   # 雨棚西
b.flat("cp_e", 3, 3, 2.0, CANOPY)                   # 雨棚东
b.spire_ns("er_flag", 5, 4.0, 2.0, FLAG)            # 急救旗

# =================================================================
# 4. 救护车: 轮组 + 底盘 + 高方舱 + 低驾驶室 (车头朝东)
# =================================================================
b.add("wh_s", "wheel_base", (2.0, 1.0, 0.5), (90, 0, 0), WHEEL)   # 南轮
b.add("wh_n", "wheel_base", (2.0, 2.0, 0.5), (90, 0, 0), WHEEL)   # 北轮
b.flat_rect("amb_deck", 1, 1, 1.0, DECK)            # 底盘甲板 [1,3]x[1,2]
b.wall_ew("bx_rear", 1.0, 1, 1, BODY)               # 方舱后壁
b.wall_ew("bx_front", 3.0, 1, 1, BODY)              # 方舱前壁
b.wall_ns("bx_s1", 1, 1.0, 1, STRIPE)               # 南侧急救条纹
b.wall_ns("bx_s2", 2, 1.0, 1, BODY)
b.wall_ns("bx_n1", 1, 2.0, 1, BODY)
b.wall_ns("bx_n2", 2, 2.0, 1, STRIPE)               # 北侧急救条纹
b.flat_rect("bx_roof", 1, 1, 2.0, DECK)             # 舱顶 [1,3]x[1,2]
b.crest_ew("beacon_r", 3.0, 1, 2.0, "red")          # 舱顶红警灯 (朝前)
b.wall_ns("cab_s", 3, 1.0, 0, CAB)                  # 驾驶室南墙
b.wall_ns("cab_n", 3, 2.0, 0, CAB)                  # 驾驶室北墙
b.wall_ew("cab_wind", 4.0, 1, 0, GLASS)             # 透明挡风 (车头)
b.flat("cab_roof", 3, 1, 1.0, CAB)                  # 驾驶室顶
b.crest_ew("beacon_b", 4.0, 1, 1.0, "blue")         # 蓝示宽灯

# =================================================================
# 5. 路灯 + 安全锥
# =================================================================
b.wall_ns("lamp_post", 6, 3.0, 0, LAMP)             # 路灯柱
b.crest_ns("lamp_top", 6, 3.0, 1.0, LAMP)           # 黄灯
b.crest_ns("cone_1", 5, 0.0, 0.0, CONE)             # 安全锥
b.crest_ns("cone_2", 6, 0.0, 0.0, CONE)

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺马路南排: 长板拼缝落在 y=1 线上 —— 那是南轮的落脚缝。",
    ["r0_0", "r0_a", "r0_b", "r0_5", "r0_6"],
    tip="车轮底座即将整边吸在这条拼缝上, 长板务必对齐。",
)
b.step(
    "铺急救车道: 中排再铺 5 片, 救护车就停在这条车道上。",
    ["r1_0", "r1_a", "r1_3", "r1_b", "r1_6"],
    highlight=["r0_a"],
    tip="车底长板两条长边就是南北轮的双保险吸合线。",
)
b.step(
    "铺马路北排: 5 片合拢马路, 轮缝板对齐 y=2 线。",
    ["r2_0", "r2_a", "r2_3", "r2_b", "r2_6"],
    highlight=["r1_a"],
    tip="三排马路铺完, 急救通道全线贯通。",
)
b.step(
    "铺人行道: 7 片青色方板沿医院门前排开。",
    [f"wk_{x}" for x in range(7)],
    highlight=["r2_0", "r2_6"],
    tip="医院门脸就立在人行道背后的格线上。",
)
b.step(
    "立医院一层门脸: 蓝色急诊门居中, 两侧透明大窗。",
    ["h1_win_w", "h1_door", "h1_win_e", "h1_sq"],
    highlight=["wk_2", "wk_3"],
    tip="底边整边吸人行道格线, 竖边逐片互吸成排。",
)
b.step(
    "立医院二层与红十字: 红十字方板挂在急诊门正上方。",
    ["h2_win_w", "h2_cross", "h2_win_e", "h2_sq"],
    highlight=["h1_door"],
    tip="上环整边压下环 —— 红十字是全城最醒目的坐标。",
)
b.step(
    "挑急诊雨棚并升旗: 2 片透明方板从二层墙顶平挑, 楼顶红旗升起。",
    ["cp_w", "cp_e", "er_flag"],
    highlight=["h2_win_w", "h2_cross"],
    tip="单片力矩 15 <= 预算 20, 两片再整边互吸共担。",
)
b.step(
    "装车轮: 2 片车轮底座沿 y=1 与 y=2 拼缝立起, 底边整边吸合。",
    ["wh_s", "wh_n"],
    highlight=["r0_a", "r2_a"],
    tip="一片车轮底座顶两格 —— 厢式车的四轮一步到位。",
)
b.step(
    "架底盘甲板: 长板两条长边同时整边压住南北轮顶。",
    ["amb_deck"],
    highlight=["wh_s", "wh_n"],
    tip="轮组+甲板锁成门式框架 —— 底盘从此不晃。",
)
b.step(
    "立方舱前后壁: 甲板短边上立起 2 片白色端壁。",
    ["bx_rear", "bx_front"],
    highlight=["amb_deck"],
    tip="端壁底边整边吸甲板短边 —— 方舱的骨架先立两端。",
)
b.step(
    "合方舱侧壁: 4 片侧壁竖边吸进前后壁拐角, 红色条纹绕舱一周。",
    ["bx_s1", "bx_s2", "bx_n1", "bx_n2"],
    highlight=["bx_rear", "bx_front"],
    tip="圈层砌法合龙 —— 急救舱要经得起一路飞驰。",
)
b.step(
    "盖舱顶并装警灯: 长板四边全吸封舱, 红色警灯立在舱顶前沿。",
    ["bx_roof", "beacon_r"],
    highlight=["bx_s1", "bx_n2"],
    tip="舱顶长板短边压端壁、长边压侧壁 —— 箱形环完整闭合。",
)
b.step(
    "立驾驶室: 南北矮墙加透明挡风, 车头正对前方。",
    ["cab_s", "cab_n", "cab_wind"],
    highlight=["bx_front", "r1_3"],
    tip="驾驶室退低一级 —— 高低错落是厢式救护车的剪影。",
)
b.step(
    "盖驾驶室顶并装示宽灯: 方板四边压墙顶, 蓝灯立车头。",
    ["cab_roof", "beacon_b"],
    highlight=["cab_s", "cab_wind"],
    tip="车顶西边整条贴住方舱前壁底线 —— 高低车身共享受力。",
)
b.step(
    "立路灯: 黄色灯柱站上人行道东端, 黄灯压顶。",
    ["lamp_post", "lamp_top"],
    highlight=["wk_6"],
    tip="灯下就是急救通道 —— 夜里也一路通明。",
)
b.step(
    "摆安全锥: 2 只橙色安全锥围出路口 —— 请让出生命通道!",
    ["cone_1", "cone_2"],
    highlight=["r0_5", "r0_6"],
    tip="底边整边吸马路南沿 —— 呜哇呜哇, 出发!",
)

b.finalize(
    model_id="ambulance_01",
    name="120 急救车",
    name_en="Ambulance 01",
    description=(
        "城市守护者的高箱厢式车: 2 片车轮底座整边吸马路拼缝, 底盘甲板"
        "双长边压轮顶锁成门式框架; 甲板上圈层砌法立起两层高的白色方舱 "
        "(红色急救条纹绕舱一周), 舱顶长板四边全吸闭合箱形环、红警灯朝前; "
        "驾驶室退低一级直接落地, 透明挡风正对车头, 车顶整条贴住方舱前壁"
        "共享受力 —— 高低错落的阶梯剪影就是救护车的标志。车后医院急诊楼"
        "门脸: 蓝色急诊门/透明大窗/二层红十字, 透明雨棚平挑 (力矩 15<=20 "
        "双片共担), 楼顶红旗高扬; 安全锥围出急救通道, 路灯长明 —— 呜哇"
        "呜哇, 请让出生命通道!"
    ),
    difficulty=3,
    tags=["城市", "职业体验", "救护车", "载具", "车轮底座", "进阶"],
    min_pieces=50,
    min_steps=16,
)
