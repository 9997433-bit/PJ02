#!/usr/bin/env python3
"""生成模型 data/models/penguin_pool_01.json (企鹅戏水池)。

动物园/野生动物主题批 2/4: 全库第一座"玻璃池壁展馆"—— 与
penguin_01 (直立企鹅塔式身躯+冰滑梯)、swimming_pool_01、
ice_rink_01 刻意区分, 本作的主角是"隔着玻璃看企鹅游泳"这组
展馆关系: 4x2 架高水池的南池壁整排窗格方 (游客隔玻璃看水下),
其余池壁灰色岩壁; 水面 4 片青色长板横跨双壁架在池壁顶上
(双端受力零悬挑, 长边拼缝互吸), 水线上两朵透明浮冰骑池沿;
西北角 1x1 双层跳水岩 (墙环两层 + 白色压顶), 岩顶一只企鹅
正要跳水; 池畔再站两只排队的企鹅 (竖立方身 + 橙喙等边头),
跳水岩北侧靠着一座四坡透明冰山; 西侧入口门架双柱托横板,
门旗等腰塔尖骑柱顶 —— 开馆了, 企鹅们排队下水!

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 园区地坪 (x [0,8], y [0,4]): 长板 x10 + 方板 x12
    (含 8 片蓝色池底 [1,5]x[1,3])                              22 片
  - 玻璃池壁 (z 0..1): 南壁窗格方 x4 + 灰岩壁 x8               12 片
  - 水面 (z=1): 4 片青色长板横跨南北池壁                        4 片
  - 浮冰: 2 片透明等边三角骑池沿 (壁顶+水面板沿一线双吸)        2 片
  - 跳水岩 [7,8]x[1,2]: 墙环 x2 层 8 + 白色压顶 1               9 片
  - 岩顶企鹅: 竖立灰方身 1 + 橙喙等边头 1                       2 片
  - 池畔企鹅 x2: 各 2 片                                        4 片
  - 冰山: 4 片透明等边四坡锥 (跳水岩北侧)                       4 片
  - 入口门架: 双柱 2 + 横板 1 + 门旗等腰塔尖 1                  4 片
  合计 63 片, 13 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 水面长板: 两短边分别整边压南北池壁顶 (双端受力零悬挑),
    长边拼缝相邻互吸 —— 壁-水面-壁-池底锁成箱形闭环;
  - 跳水岩: 两层墙环四角竖边互吸, 白色压顶四边全吸墙顶;
    岩顶企鹅方身底边一线双吸 (压顶板沿+北墙顶), 重心正压
    铰链线力矩为零, 橙喙头骑方身顶边;
  - 入口门架: 横板两短边同吸双柱顶 (双端受力), 柱-板-柱-地坪
    锁成门式刚架环, 门旗骑柱顶与板沿一线双吸;
  - 浮冰/企鹅/冰山重心均正压铰链线或四棱自锁, 力矩为零。

用法: python3 tools/generate_penguin_pool_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

DECK = "gray"        # 游客步道地坪
LAWN = "green"       # 绿化带
POOL = "blue"        # 池底
GLASS = "clear"      # 玻璃池壁 / 浮冰 / 冰山
ROCK = "gray"        # 岩壁 / 跳水岩
CAPCOL = "clear"     # 跳水岩压顶 (积雪白)
WATER = "cyan"       # 水面
PENG = "gray"        # 企鹅身
BEAK = "orange"      # 企鹅头喙
GATECOL = "gray"     # 门架柱
BEAM = "yellow"      # 门架横板
FLAG = "red"         # 门旗

# =================================================================
# 1. 园区地坪 (x [0,8], y [0,4]): 22 片
#    池底 [1,5]x[1,3] 8 片蓝色方板 (池壁墙脚整边全部有吸);
#    跳水岩坑 (7,1)、企鹅站位 (0,1)/(0,2)、冰山坑 (7,2) 用方板。
# =================================================================
# 行 y0: 4 片灰色长板 (游客南步道)
for k, x0 in enumerate((0, 2, 4, 6)):
    b.flat_rect(f"gd_s_{k}", x0, 0, 0.0, DECK)
# 行 y1: 方 + 池底 + 长板 + 方
b.flat("gd_0_1", 0, 1, 0.0, DECK)
b.flat("pl_1_1", 1, 1, 0.0, POOL)
b.flat("pl_2_1", 2, 1, 0.0, POOL)
b.flat("pl_3_1", 3, 1, 0.0, POOL)
b.flat("pl_4_1", 4, 1, 0.0, POOL)
b.flat_rect("gd_5_1", 5, 1, 0.0, LAWN)
b.flat("gd_7_1", 7, 1, 0.0, DECK)      # 跳水岩坑
# 行 y2: 同构
b.flat("gd_0_2", 0, 2, 0.0, DECK)
b.flat("pl_1_2", 1, 2, 0.0, POOL)
b.flat("pl_2_2", 2, 2, 0.0, POOL)
b.flat("pl_3_2", 3, 2, 0.0, POOL)
b.flat("pl_4_2", 4, 2, 0.0, POOL)
b.flat_rect("gd_5_2", 5, 2, 0.0, LAWN)
b.flat("gd_7_2", 7, 2, 0.0, DECK)      # 冰山坑
# 行 y3: 4 片灰色长板 (北巡游道, 西端两片留给入口门架)
for k, x0 in enumerate((0, 2, 4, 6)):
    b.flat_rect(f"gd_n_{k}", x0, 3, 0.0, DECK)

# =================================================================
# 2. 玻璃池壁 [1,5]x[1,3] (z 0..1): 南壁 4 扇窗格方 + 8 片灰岩壁
# =================================================================
for x in range(1, 5):
    b.add(f"pw_s_{x}", "window_square", (x + 0.5, 1.0, 0.5), (90, 0, 0), GLASS)
for x in range(1, 5):
    b.wall_ns(f"pw_n_{x}", x, 3.0, 0, ROCK)
b.wall_ew("pw_w_1", 1.0, 1, 0, ROCK)
b.wall_ew("pw_w_2", 1.0, 2, 0, ROCK)
b.wall_ew("pw_e_1", 5.0, 1, 0, ROCK)
b.wall_ew("pw_e_2", 5.0, 2, 0, ROCK)

# =================================================================
# 3. 水面 (z=1): 4 片青色长板横跨南北池壁
# =================================================================
for x in range(1, 5):
    b.flat_rect(f"wt_{x}", x, 1, 1.0, WATER, axis="y")

# =================================================================
# 4. 浮冰: 2 片透明等边三角骑池沿
# =================================================================
b.crest_ns("ice_s", 1, 1.0, 1.0, GLASS)    # 南池沿西端
b.crest_ns("ice_n", 4, 3.0, 1.0, GLASS)    # 北池沿东端

# =================================================================
# 5. 跳水岩 [7,8]x[1,2]: 两层墙环 + 白色压顶
# =================================================================
for lv in (0, 1):
    b.wall_ns(f"rk{lv}_s", 7, 1.0, lv, ROCK)
    b.wall_ns(f"rk{lv}_n", 7, 2.0, lv, ROCK)
    b.wall_ew(f"rk{lv}_w", 7.0, 1, lv, ROCK)
    b.wall_ew(f"rk{lv}_e", 8.0, 1, lv, ROCK)
b.flat("rk_cap", 7, 1, 2.0, CAPCOL)

# =================================================================
# 6. 企鹅 x3: 竖立灰方身 + 橙喙等边头
# =================================================================
# 岩顶企鹅 (站在压顶北沿, 正要跳水)
b.wall_ns("pg1_body", 7, 2.0, 2, PENG)
b.crest_ns("pg1_head", 7, 2.0, 3.0, BEAK)
# 池畔企鹅 A (南步道边)
b.wall_ns("pg2_body", 0, 1.0, 0, PENG)
b.crest_ns("pg2_head", 0, 1.0, 1.0, BEAK)
# 池畔企鹅 B (西沿排队)
b.wall_ew("pg3_body", 0.0, 2, 0, PENG)
b.crest_ew("pg3_head", 0.0, 2, 1.0, BEAK)

# =================================================================
# 7. 冰山: 透明等边四坡锥 (跳水岩北侧, 四棱自锁)
# =================================================================
b.hat4("berg", 7, 2, 0.0, GLASS, shape="equilateral_triangle")

# =================================================================
# 8. 入口门架 (北巡游道西端 [0,2]x[3,4]): 双柱 + 横板 + 门旗
# =================================================================
b.wall_ew("gate_w", 0.0, 3, 0, GATECOL)
b.wall_ew("gate_e", 2.0, 3, 0, GATECOL)
b.flat_rect("gate_beam", 0, 3, 1.0, BEAM)
b.spire_ew("gate_flag", 0.0, 3, 1.0, FLAG)

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺南步道: 4 片灰色长板 (y [0,1]) + 西侧 2 片站位方板。",
    [f"gd_s_{k}" for k in range(4)] + ["gd_0_1", "gd_0_2"],
    tip="长板长边压齐网格线 —— 游客就从南面隔着玻璃看企鹅。",
)
b.step(
    "铺池底: 8 片蓝色方板拼出 [1,5]x[1,3] 的水池底。",
    ["pl_1_1", "pl_2_1", "pl_3_1", "pl_4_1",
     "pl_1_2", "pl_2_2", "pl_3_2", "pl_4_2"],
    highlight=["gd_s_0", "gd_0_1"],
    tip="池底全用方板 —— 池壁每条墙脚都能整边吸上。",
)
b.step(
    "铺北巡游道与东侧地坪: 4 片长板贴着池底北沿, 绿化带长板与岩坑"
    "方板补齐东侧。",
    [f"gd_n_{k}" for k in range(4)] + ["gd_5_1", "gd_5_2", "gd_7_1", "gd_7_2"],
    highlight=["pl_1_2", "pl_4_2"],
    tip="东侧留出两格 —— 跳水岩和冰山就落在这里。",
)
b.step(
    "立玻璃池壁: 南壁 4 扇透明窗格方 —— 游客隔着玻璃看企鹅游泳。",
    ["pw_s_1", "pw_s_2", "pw_s_3", "pw_s_4"],
    highlight=["pl_1_1", "pl_4_1"],
    tip="窗格方物理上按实心方片拼接, 窗格只是玻璃的语义标记。",
)
b.step(
    "围灰岩壁: 北壁 4 片 + 东西壁各 2 片, 池壁合环。",
    ["pw_n_1", "pw_n_2", "pw_n_3", "pw_n_4",
     "pw_w_1", "pw_w_2", "pw_e_1", "pw_e_2"],
    highlight=["pw_s_1"],
    tip="十二片池壁拐角竖边互吸自锁 —— 水池是一圈闭合的环。",
)
b.step(
    "架水面: 4 片青色长板横跨南北池壁, 两短边分别压壁顶。",
    ["wt_1", "wt_2", "wt_3", "wt_4"],
    highlight=["pw_s_1", "pw_n_1"],
    tip="每片双端受力零悬挑, 长边拼缝再互吸 —— 壁-水面-壁-池底锁成箱形闭环。",
)
b.step(
    "放浮冰: 2 片透明等边三角骑池沿 (壁顶+水面板沿一线双吸)。",
    ["ice_s", "ice_n"],
    highlight=["wt_1", "wt_4"],
    tip="浮冰重心正压池沿线, 力臂为零 —— 企鹅的中途歇脚点。",
)
b.step(
    "垒跳水岩第一层: 4 片灰墙围 [7,8]x[1,2] 成环。",
    ["rk0_s", "rk0_n", "rk0_w", "rk0_e"],
    highlight=["gd_7_1"],
    tip="墙脚踩着岩坑方板整边 —— 四角竖边互吸自锁。",
)
b.step(
    "垒第二层并压顶: 再叠 4 片灰墙, 白色方板四边全吸墙顶。",
    ["rk1_s", "rk1_n", "rk1_w", "rk1_e", "rk_cap"],
    highlight=["rk0_s"],
    tip="上环整边压下环 —— 两层岩塔怎么敲都不散。",
)
b.step(
    "岩顶企鹅就位: 竖立灰方身底边一线双吸 (压顶板沿+北墙顶), "
    "橙喙头骑身顶。",
    ["pg1_body", "pg1_head"],
    highlight=["rk_cap"],
    tip="重心正压铰链线 —— 它在 2 米跳台上一点都不晃。",
)
b.step(
    "池畔企鹅排队: 南步道边与西沿各站一只 (方身+橙喙头)。",
    ["pg2_body", "pg2_head", "pg3_body", "pg3_head"],
    highlight=["pg1_body"],
    tip="企鹅身底边吸着地坪拼缝 —— 排好队, 一只一只跳。",
)
b.step(
    "堆冰山: 4 片透明等边三角四坡锥 (跳水岩北侧), 四条斜棱两两互吸。",
    ["berg_s", "berg_e", "berg_n", "berg_w"],
    highlight=["rk0_n"],
    tip="四棱自锁成环 —— 冰山看着尖, 其实是最稳的锥。",
)
b.step(
    "立入口门架: 双柱托黄色横板 (两短边同吸柱顶), 红门旗骑柱顶 —— "
    "企鹅馆开馆!",
    ["gate_w", "gate_e", "gate_beam", "gate_flag"],
    highlight=["gd_n_0"],
    tip="柱-板-柱-地坪锁成门式刚架环 —— 剪断任一端也塌不了。",
)

b.finalize(
    model_id="penguin_pool_01",
    name="企鹅戏水池",
    name_en="Penguin Pool 01",
    description=(
        "只用核心九片型的玻璃池壁展馆: 4x2 架高水池的南池壁整排"
        "窗格方 —— 游客隔玻璃看企鹅水下游泳, 其余池壁灰色岩壁合环;"
        " 4 片青色水面长板横跨双壁 (两短边压壁顶双端受力, 长边拼缝"
        "互吸), 壁-水面-壁-池底锁成箱形闭环, 水线上两朵透明浮冰骑"
        "池沿; 西北角 1x1 双层跳水岩 (墙环两层+白色压顶), 岩顶企鹅"
        "方身一线双吸正要跳水, 池畔两只企鹅排队, 北侧四坡透明冰山"
        "四棱自锁; 入口门架双柱托横板, 红门旗骑柱顶 —— 开馆了,"
        " 企鹅们排队下水!"
    ),
    difficulty=3,
    tags=["动物园", "野生动物", "企鹅", "戏水池", "进阶"],
    min_pieces=63,
    min_steps=13,
)
