#!/usr/bin/env python3
"""生成模型 data/models/tessellation_screen_01.json (三角密铺光影屏风)。

几何艺术主题开篇之作 (CONTENT_STRATEGY.md 主题矩阵中该主题此前为空):
T18 密铺变奏的入库示范 —— 按 2.4 节 J4 规则, 密铺不许平铺在桌面上
凑数, 必须"立起来"。本作把正/倒等边三角形的经典密铺带竖着砌进
三块屏板, 屏板走 Z 字折线互咬站立: 密铺是墙body, 折线是骨架。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - Z 字步道地台: 屏前/屏侧/屏后三段清灰步道方板            8 片
  - 屏板 A (南段, y=1 立面, x [0,3]): 灰色底排 x3 +
    密铺带 (红色正三角 x3 与橙色倒三角 x2 上下互咬) +
    清色悬排方板 x2 骑在倒三角上底 + 紫色尖冠 x2            12 片
  - 屏板 B (中段, x=3 立面, y [1,3]): 底排 x2 + 密铺带
    (黄正三角 x2 + 绿倒三角 x1) + 悬排 x1 + 尖冠 x1          7 片
  - 屏板 C (北段, y=3 立面, x [3,6]): 与 A 同构,
    密铺带换 青正三角 x3 + 蓝倒三角 x2 —— 彩虹渐变          12 片
  - 屏脚斜撑 x3 (T14): 两端头 + 中段拐点, 直角三角
    竖边吸屏板竖缝、横边吸步道拼缝, 锁成门式框架环            3 片
  合计 42 片, 9 个教程步骤, 3 种磁力片形状 (全部 CORE-9 之内)。

招牌技法: 正倒等边三角密铺带竖砌成墙, 悬排方板骑在倒三角上底,
三块屏板 Z 字转折互咬站立 —— 密铺立起来才是屏风, 铺地上只是地砖。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 倒三角两条斜边分别整边吸住左右两片正三角的斜边, 剪断任何
    一条斜边铰链仍有另一条支撑路径, 悬臂分析自然消失;
  - 悬排方板底边整边吸倒三角上底, 相邻悬排方板竖边互吸成环;
  - 三块屏板在拐点处竖边互咬, 底排踩步道拼缝整边吸合;
  - 屏脚斜撑双边吸合 (竖边吸屏板端缝, 横边吸步道缝),
    屏板-斜撑-步道锁成门式框架, 抗出平面方向的碰撞;
  - 最高点 (尖冠顶) 3.73, 低于 R8 无桁架高墙红线 4.0。

用法: python3 tools/generate_tessellation_screen.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

BT = 1.866025          # 密铺带上沿高度 (1 + 等边三角形高 0.866025)
FLOOR_A = "clear"      # 步道 (清/灰相间)
FLOOR_B = "gray"
BASE = "gray"          # 屏板底排
TOP = "clear"          # 悬排方板
CROWN = "purple"       # 尖冠
BRACE = "gray"         # 屏脚斜撑
# 彩虹渐变密铺带: (正三角色, 倒三角色)
PANEL_TRI = {"a": ("red", "orange"), "b": ("yellow", "green"), "c": ("cyan", "blue")}


def down_tri_ns(tid, xc, y, color):
    """倒等边三角形 (南北立面): 上底 [xc-0.5, xc+0.5] 在高度 BT, 顶点朝下。"""
    b.place_tri(tid, "equilateral_triangle",
                (xc + 0.5, y, BT), (xc - 0.5, y, BT), (xc, y, 1.0), color)


def down_tri_ew(tid, x, yc, color):
    """倒等边三角形 (东西立面): 上底 [yc-0.5, yc+0.5] 在高度 BT, 顶点朝下。"""
    b.place_tri(tid, "equilateral_triangle",
                (x, yc - 0.5, BT), (x, yc + 0.5, BT), (x, yc, 1.0), color)


# =================================================================
# 1. Z 字步道地台: 屏板 A 前 (y [0,1]) / B 侧 (x [3,4]) / C 后 (y [3,4])
# =================================================================
for i in range(3):
    b.flat(f"fa_{i}", i, 0, 0.0, FLOOR_A if i % 2 == 0 else FLOOR_B)
b.flat("fb_0", 3, 1, 0.0, FLOOR_B)
b.flat("fb_1", 3, 2, 0.0, FLOOR_A)
for i in range(3, 6):
    b.flat(f"fc_{i}", i, 3, 0.0, FLOOR_A if i % 2 == 1 else FLOOR_B)

# =================================================================
# 2. 屏板 A (y=1 立面, x [0,3]): 底排 + 密铺带 + 悬排 + 尖冠
# =================================================================
UP_A, DN_A = PANEL_TRI["a"]
for i in range(3):
    b.wall_ns(f"a_base_{i}", i, 1.0, 0, BASE)
for i in range(3):
    b.crest_ns(f"a_up_{i}", i, 1.0, 1.0, UP_A)
down_tri_ns("a_dn_0", 1.0, 1.0, DN_A)
down_tri_ns("a_dn_1", 2.0, 1.0, DN_A)
b.wall_ns("a_top_0", 0.5, 1.0, BT, TOP)
b.wall_ns("a_top_1", 1.5, 1.0, BT, TOP)
b.crest_ns("a_crown_0", 0.5, 1.0, BT + 1.0, CROWN)
b.crest_ns("a_crown_1", 1.5, 1.0, BT + 1.0, CROWN)

# =================================================================
# 3. 屏板 B (x=3 立面, y [1,3]): 拐点段, 与 A 竖缝互咬
# =================================================================
UP_B, DN_B = PANEL_TRI["b"]
for j in (1, 2):
    b.wall_ew(f"b_base_{j}", 3.0, j, 0, BASE)
for j in (1, 2):
    b.crest_ew(f"b_up_{j}", 3.0, j, 1.0, UP_B)
down_tri_ew("b_dn_0", 3.0, 2.0, DN_B)
b.wall_ew("b_top_0", 3.0, 1.5, BT, TOP)
b.crest_ew("b_crown_0", 3.0, 1.5, BT + 1.0, CROWN)

# =================================================================
# 4. 屏板 C (y=3 立面, x [3,6]): 与 A 同构, 青蓝收尾
# =================================================================
UP_C, DN_C = PANEL_TRI["c"]
for i in range(3, 6):
    b.wall_ns(f"c_base_{i}", i, 3.0, 0, BASE)
for i in range(3, 6):
    b.crest_ns(f"c_up_{i}", i, 3.0, 1.0, UP_C)
down_tri_ns("c_dn_0", 4.0, 3.0, DN_C)
down_tri_ns("c_dn_1", 5.0, 3.0, DN_C)
b.wall_ns("c_top_0", 3.5, 3.0, BT, TOP)
b.wall_ns("c_top_1", 4.5, 3.0, BT, TOP)
b.crest_ns("c_crown_0", 3.5, 3.0, BT + 1.0, CROWN)
b.crest_ns("c_crown_1", 4.5, 3.0, BT + 1.0, CROWN)

# =================================================================
# 5. 屏脚斜撑 x3 (T14): 西端头 / 拐点 / 东端头
# =================================================================
b.brace("brace_w", (0.0, 1.0, 0.0), "-y", BRACE)   # 竖边吸 A 西端缝, 横边吸步道西缘
b.brace("brace_m", (3.0, 2.0, 0.0), "+x", BRACE)   # 竖边吸 B 中缝, 横边吸步道拼缝
b.brace("brace_e", (6.0, 3.0, 0.0), "+y", BRACE)   # 竖边吸 C 东端缝, 横边吸步道东缘

# =================================================================
# 教程步骤 (9 步)
# =================================================================
b.step(
    "铺南段步道: 三片清灰相间的方板一字排开, 再沿步道北缝立起屏板 A 的灰色底排。",
    ["fa_0", "fa_1", "fa_2", "a_base_0", "a_base_1", "a_base_2"],
    tip="底排墙脚要正好踩在步道拼缝上, 整条底边吸住才站得稳。",
)
b.step(
    "砌屏板 A 的密铺带: 三片红色正三角先立在底排顶沿, 两片橙色倒三角再倒插进缺口。",
    ["a_up_0", "a_up_1", "a_up_2", "a_dn_0", "a_dn_1"],
    highlight=["a_base_0", "a_base_1", "a_base_2"],
    tip="倒三角两条斜边同时贴住左右正三角 —— 咔哒一声互咬, 这就是密铺!",
)
b.step(
    "架屏板 A 的悬排: 两片清色方板骑在倒三角上底, 竖边互吸; 顶沿再立两片紫色尖冠。",
    ["a_top_0", "a_top_1", "a_crown_0", "a_crown_1"],
    highlight=["a_dn_0", "a_dn_1"],
    tip="悬排方板错开半格, 像悬在花纹上 —— 底边整边吸住倒三角就很牢。",
)
b.step(
    "铺中段步道并立屏板 B 底排: 两片方板沿屏板 A 东端向北拐, 两片灰色底排"
    "踩上步道西缝, 竖缝与屏板 A 的东端互咬。",
    ["fb_0", "fb_1", "b_base_1", "b_base_2"],
    highlight=["a_base_2", "fa_2"],
    tip="Z 字形的拐点到了 —— 两块屏板的竖边在拐角贴紧吸合, 转折处比平墙更结实。",
)
b.step(
    "砌屏板 B 的密铺带并封顶: 黄色正三角与绿色倒三角互咬, 悬排方板与尖冠骑上花纹。",
    ["b_up_1", "b_up_2", "b_dn_0", "b_top_0", "b_crown_0"],
    highlight=["b_base_1", "b_base_2"],
    tip="中段窄一格, 花纹却和 A 段一模一样 —— 同一套密铺规则处处适用。",
)
b.step(
    "铺北段步道: 三片方板沿 y=3 向东排开, 步道完成 Z 字的最后一横。",
    ["fc_3", "fc_4", "fc_5"],
    highlight=["fb_1"],
    tip="从空中看, 步道和屏风一起画出一个大大的 Z。",
)
b.step(
    "立屏板 C 底排: 三片灰色方板踩上北段步道拼缝, 竖缝与屏板 B 北端互咬。",
    ["c_base_3", "c_base_4", "c_base_5"],
    highlight=["b_base_2", "fc_3"],
    tip="第三块屏板与第一块朝向相同 —— Z 字的两横互相平行。",
)
b.step(
    "砌屏板 C 的密铺带: 青色正三角与蓝色倒三角收尾, 彩虹渐变到此完成。",
    ["c_up_3", "c_up_4", "c_up_5", "c_dn_0", "c_dn_1"],
    highlight=["c_base_3", "c_base_4", "c_base_5"],
    tip="红橙、黄绿、青蓝 —— 三段花纹连起来正好是一道彩虹。",
)
b.step(
    "架屏板 C 悬排与尖冠, 最后装三片屏脚斜撑: 西端、拐点、东端各一片, 竖边吸屏缝、横边吸步道缝。",
    ["c_top_0", "c_top_1", "c_crown_0", "c_crown_1",
     "brace_w", "brace_m", "brace_e"],
    highlight=["c_dn_0", "c_dn_1"],
    tip="斜撑把屏板和步道锁成三角框 —— 迎着光摆好, 看花纹把影子投在桌上!",
)

b.finalize(
    model_id="tessellation_screen_01",
    name="三角密铺光影屏风",
    name_en="Tessellation Light Screen 01",
    description=(
        "几何艺术开篇: 正倒等边三角形的经典密铺带不铺地面, 竖着砌进三块屏板 —— "
        "红橙、黄绿、青蓝三段彩虹花纹上下互咬, 清色悬排方板骑在倒三角上底, 紫色"
        "尖冠点在最高处; 三块屏板沿 Z 字折线竖缝互咬站立, 屏脚三片直角斜撑把屏板"
        "与步道锁成门式框架。迎着台灯摆好, 密铺花纹会把一整条彩虹影子投在桌面上。"
    ),
    difficulty=2,
    tags=["几何艺术", "密铺", "屏风", "光影", "彩虹"],
    min_pieces=42,
    min_steps=9,
)
