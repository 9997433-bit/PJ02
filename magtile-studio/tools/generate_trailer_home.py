#!/usr/bin/env python3
"""生成模型 data/models/trailer_home_01.json (营地房车)。

田园主题: 全库第一辆宿营拖挂房车 —— 绿草地营地上, 一辆单轴
房车支好了家: 两片车轮底座 (wheel_base) 组成居中单轴, 底盘
端墙与车底板锁成箱形底架, 黄色车厢开着透明门窗, 门口挑出
一片橙色遮阳棚; 车尾牵引架斜搭在地上等着下一次出发, 营地
西头篝火正旺, 两棵绿树把黄昏拉得很长 —— 今晚就住这儿!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 车头朝东):
  - 营地草地 8x4: 方板 x24 + 长板 x4 (拼缝落在轮轴线上)        28 片
  - 单轴轮组: 车轮底座 x2 (南北各 1, 底边整边吸草地长板拼缝)    2 片
  - 底盘: 端墙 x4 (z 0..1) + 车底板 x6 (z=1)                   10 片
  - 车厢 (z 1..2): 南墙+门 x4 + 北墙 x4 + 端墙 x4              12 片
  - 车顶 x6 + 遮阳棚 x1 + 天线 x1                               8 片
  - 牵引架 x1 + 营火 hat4 x4 + 绿树 x2                          7 片
  合计 67 片, 16 个教程步骤, 5 种片形。

物理规则要点 (通过 R1~R8 全部校验):
  - 轮组+端墙+车底板锁成箱形底架: 车底板长板长边整边压轮组
    顶边、方板端边压端墙顶 —— 与火星车同源的底盘力学, 但
    单轴居中 + 上层整间车厢是房车独有的体量;
  - 遮阳棚单片平挑: 力矩 15 <= 严格档预算 17.5 (单片纪律,
    绝不连挑第二片);
  - 牵引架直角三角: 竖直角边吸底盘端墙竖边, 水平直角边整边
    吸草地拼缝 —— 既是拖车钩又是驻车斜撑;
  - 营火/绿树全部整边吸草地拼缝, 场景与主体连成一张连接图。

用法: python3 tools/generate_trailer_home.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

GRASS = "green"     # 草地
WHEEL = "gray"      # 轮组
CHASSIS = "gray"    # 底盘
BODY = "yellow"     # 车厢
DOOR = "clear"      # 门窗
ROOF = "gray"       # 车顶
AWNING = "orange"   # 遮阳棚
FIRE = "orange"     # 营火
TREE = "green"      # 绿树
ANT = "red"         # 天线

# =================================================================
# 1. 营地草地 8x4: 方板为主, 长板拼缝落在轮轴线 (x 3..5)
# =================================================================
for y0 in range(4):
    b.flat(f"g0_{y0}", 0, y0, 0.0, GRASS)
    b.flat(f"g1_{y0}", 1, y0, 0.0, GRASS)
    b.flat(f"g2_{y0}", 2, y0, 0.0, GRASS)
    b.flat_rect(f"gr_{y0}", 3, y0, 0.0, GRASS)      # 长板 [3..5]
    b.flat(f"g5_{y0}", 5, y0, 0.0, GRASS)
    b.flat(f"g6_{y0}", 6, y0, 0.0, GRASS)
    b.flat(f"g7_{y0}", 7, y0, 0.0, GRASS)

# =================================================================
# 2. 单轴轮组: 2 片车轮底座, 底边整边吸草地长板拼缝
# =================================================================
b.add("wh_s", "wheel_base", (4.0, 1.0, 0.5), (90, 0, 0), WHEEL)
b.add("wh_n", "wheel_base", (4.0, 3.0, 0.5), (90, 0, 0), WHEEL)

# =================================================================
# 3. 底盘 (z 0..1 端墙 + z=1 车底板)
# =================================================================
for y0 in (1, 2):
    b.wall_ew(f"cw_w_{y0}", 2.0, y0, 0, CHASSIS)    # 底盘西端墙
    b.wall_ew(f"cw_e_{y0}", 6.0, y0, 0, CHASSIS)    # 底盘东端墙
for y0 in (1, 2):
    b.flat(f"fl_w_{y0}", 2, y0, 1.0, CHASSIS)       # 底板西方板
    b.flat_rect(f"fl_c_{y0}", 3, y0, 1.0, CHASSIS)  # 底板中长板 (压轮组)
    b.flat(f"fl_e_{y0}", 5, y0, 1.0, CHASSIS)       # 底板东方板

# =================================================================
# 4. 车厢 (z 1..2): 南墙带门 + 北墙带窗 + 端墙
# =================================================================
for x0 in (2, 3, 4, 5):
    c = DOOR if x0 == 2 else BODY                   # 西南角是门
    b.wall_ns(f"bs_{x0}", x0, 1.0, 1, c)            # 南墙
for x0 in (2, 3, 4, 5):
    c = DOOR if x0 == 4 else BODY                   # 北墙开窗
    b.wall_ns(f"bn_{x0}", x0, 3.0, 1, c)
for y0 in (1, 2):
    b.wall_ew(f"be_w_{y0}", 2.0, y0, 1, BODY)       # 车厢西端墙
    b.wall_ew(f"be_e_{y0}", 6.0, y0, 1, BODY)       # 车厢东端墙

# =================================================================
# 5. 车顶 (z=2) + 遮阳棚 + 天线
# =================================================================
for y0 in (1, 2):
    b.flat(f"rf_w_{y0}", 2, y0, 2.0, ROOF)
    b.flat_rect(f"rf_c_{y0}", 3, y0, 2.0, ROOF)
    b.flat(f"rf_e_{y0}", 5, y0, 2.0, ROOF)
b.flat("awning", 2, 0, 2.0, AWNING)                 # 遮阳棚 (门口平挑)
b.crest_ew("antenna", 6.0, 2, 2.0, ANT)             # 天线 (车头顶)

# =================================================================
# 6. 牵引架 + 营火 + 绿树
# =================================================================
b.brace("hitch", (6.0, 2.0, 0.0), "+x", CHASSIS)    # 牵引架
FIRE_IDS = b.hat4("fire", 0, 1, 0.0, FIRE,
                  shape="equilateral_triangle")     # 营火
b.crest_ns("tree_w", 0, 3.0, 0.0, TREE)             # 绿树
b.crest_ns("tree_e", 7, 2.0, 0.0, TREE)

# =================================================================
# 教程步骤 (16 步)
# =================================================================
ROW_IDS = lambda y0: [f"g0_{y0}", f"g1_{y0}", f"g2_{y0}",
                      f"gr_{y0}", f"g5_{y0}", f"g6_{y0}", f"g7_{y0}"]
b.step(
    "铺草地·第 1 行: 方板+长板混铺 (y 0..1), 长板落在 x 3..5。",
    ROW_IDS(0),
    tip="长板拼缝就是轮轴线 —— 单轴房车的轮子将吸在这条缝上。",
)
b.step(
    "铺草地·第 2 行: 同样混铺一行 (y 1..2)。",
    ROW_IDS(1),
    highlight=["gr_0"],
    tip="两行长板缝上下对齐 —— 轮组底边要同时咬住两条长边。",
)
b.step(
    "铺草地·第 3 行: 再铺一行 (y 2..3)。",
    ROW_IDS(2),
    highlight=["gr_1"],
    tip="营地慢慢铺开 —— 北侧轮组的缝也备好了。",
)
b.step(
    "铺草地·第 4 行: 8x4 草地合拢 (y 3..4)。",
    ROW_IDS(3),
    highlight=["gr_2"],
    tip="草地就位 —— 房车、篝火与绿树都在这张图上。",
)
b.step(
    "装单轴轮组: 2 片车轮底座沿 y=1 与 y=3 拼缝立起, 底边整边"
    "吸合。",
    ["wh_s", "wh_n"],
    highlight=["gr_0", "gr_1"],
    tip="单轴居中是拖挂房车的标志 —— 一片顶两格, 稳稳咬住地缝。",
)
b.step(
    "立底盘端墙: 车头车尾各 2 片灰色方墙 (x=2 与 x=6 线)。",
    ["cw_w_1", "cw_w_2", "cw_e_1", "cw_e_2"],
    highlight=["g2_1", "g5_1"],
    tip="端墙与轮组同高 —— 它们共同托起车底板。",
)
b.step(
    "盖车底板: 中路长板长边压轮组顶, 两端方板压端墙顶, 箱形"
    "底架合龙。",
    ["fl_w_1", "fl_c_1", "fl_e_1", "fl_w_2", "fl_c_2", "fl_e_2"],
    highlight=["wh_s", "cw_w_1"],
    tip="轮组+端墙+底板锁成箱形环 —— 房车的家底就是这块底架。",
)
b.step(
    "立车厢南墙: 4 片墙立在底板拼缝上, 西南角留透明门。",
    ["bs_2", "bs_3", "bs_4", "bs_5"],
    highlight=["fl_w_1", "fl_e_1"],
    tip="先立带门这面 —— 从门缝里已经能想象床铺的位置了。",
)
b.step(
    "立车厢北墙: 再立 4 片, 中间开一扇透明观景窗。",
    ["bn_2", "bn_3", "bn_4", "bn_5"],
    highlight=["bs_2", "bs_5"],
    tip="观景窗朝北 —— 早上醒来先看山。",
)
b.step(
    "封车厢端墙: 车头车尾各 2 片, 车厢四面合龙。",
    ["be_w_1", "be_w_2", "be_e_1", "be_e_2"],
    highlight=["bs_2", "bn_2"],
    tip="端墙竖边与南北墙拐角互吸 —— 车厢箱形闭环。",
)
b.step(
    "盖车顶·南排: 方板+长板+方板压住南墙顶与端墙顶。",
    ["rf_w_1", "rf_c_1", "rf_e_1"],
    highlight=["bs_2", "be_w_1"],
    tip="车顶与车底板同款三段式 —— 上下呼应的箱形环。",
)
b.step(
    "盖车顶·北排: 再盖 3 片, 车厢封顶。",
    ["rf_w_2", "rf_c_2", "rf_e_2"],
    highlight=["rf_c_1"],
    tip="拼缝互吸成整块 —— 雨点打在车顶上就是营地白噪音。",
)
b.step(
    "挑遮阳棚与竖天线: 门口向南平挑 1 片橙色遮阳棚, 车头顶立"
    "天线。",
    ["awning", "antenna"],
    highlight=["bs_2", "rf_e_2"],
    tip="单片力矩 15 <= 严格档 17.5 —— 绝不贪心连挑第二片。",
)
b.step(
    "搭牵引架: 直角三角竖边吸底盘端墙竖边, 横边整边吸草地拼缝。",
    ["hitch"],
    highlight=["cw_e_2"],
    tip="既是拖车钩又是驻车斜撑 —— 随时挂上车头出发。",
)
b.step(
    "堆营火: 4 片橙色等边三角在草地上四棱互吸, 篝火升起。",
    FIRE_IDS,
    highlight=["g0_1"],
    tip="四坡自锁成环 —— 营地的晚饭有着落了。",
)
b.step(
    "栽两棵绿树: 营地西北与东头各立 1 棵 —— 今晚就住这儿!",
    ["tree_w", "tree_e"],
    highlight=["g0_3", "g7_2"],
    tip="树底边整边吸草地拼缝 —— 晚安, 房车与星空。",
)

b.finalize(
    model_id="trailer_home_01",
    name="营地房车",
    name_en="Trailer Home 01",
    description=(
        "全库第一辆宿营拖挂房车: 两片车轮底座组成居中单轴, 底盘端墙与"
        "车底板锁成箱形底架 (长板长边整边压轮组顶), 黄色车厢开透明门窗, "
        "门口平挑一片橙色遮阳棚 (力矩 15 <= 严格档 17.5); 车尾直角三角"
        "牵引架既是拖车钩又是驻车斜撑, 营地里篝火四坡自锁、绿树成荫 "
        "—— 今晚就住这儿!"
    ),
    difficulty=3,
    tags=["田园", "房车", "露营", "车轮底座", "载具"],
    min_pieces=60,
    min_steps=16,
)
