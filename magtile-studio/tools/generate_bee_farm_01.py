#!/usr/bin/env python3
"""生成模型 data/models/bee_farm_01.json (快乐养蜂场)。

内容批 E 模型 2/5: 全库第一座养蜂场 —— 与 chicken_coop_01 (禽舍
围栏) / farm_barn_01 (大谷仓) 等农场模型刻意区分: 本作的结构签名是
"一高一矮双蜂箱塔": 蜂箱就是逐层摞起的箱环 (真实养蜂人加继箱的
方式), 女王蜂箱两节箱环整边共线上叠 + 四坡锥顶, 工蜂箱单节箱环
+ 四坡锥顶; 每座蜂箱南面开门框方巢门, 女王蜂箱二层再嵌窗格方
观察窗 —— 掀开锥顶就能看蜂群酿蜜。花田粉色四坡锥盛开在南侧,
一只黄色小蜜蜂骑着地缝正从花丛飞回巢门。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 巢门朝南):
  - 草地 4 行 (x [0,6], y [0,4]): 绿茵 + 蜂箱脚下单位方板       20 片
  - 女王蜂箱 (x [1,2], y [2,3]): 两节箱环 + 两层压顶 + 锥顶     14 片
  - 工蜂箱 (x [4,5], y [2,3]): 单节箱环 + 压顶 + 锥顶            9 片
  - 花田: 粉色四坡锥 x1 (四棱自锁)                               4 片
  - 小蜜蜂: 黄色等边三角骑地缝                                   1 片
  合计 48 片, 10 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 蜂箱箱环四角竖边互吸自锁, 上节箱环底边与下节墙顶整边共线
    吸合, 全塔受压无悬挂链 (旗杆塔同款);
  - 压顶四边吸墙顶; 四坡锥顶底边吸压顶边与墙顶边共线双吸,
    四条斜棱两两互吸自锁成环;
  - 巢门门框方 / 观察窗窗格方外框与正方形完全一致, 物理与拼接
    按实心正方形处理 (TILE_SET.md);
  - 草地拼缝纪律: 蜂箱墙脚处全单位方板, 相邻行等长边互吸。

用法: python3 tools/generate_bee_farm_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

GRASS = "green"      # 草地
HIVE = "yellow"      # 蜂箱箱体
ROOF = "orange"      # 蜂箱锥顶
CAP = "gray"         # 蜂箱压顶
DOOR = "orange"      # 巢门
WIN = "cyan"         # 观察窗
FLOWER = "pink"      # 花田
BEE = "yellow"       # 小蜜蜂

# =================================================================
# 1. 草地 4 行 (x [0,6], y [0,4]): 蜂箱墙脚处全单位方板
# =================================================================
# 花田行 (y [0,1])
b.flat_rect("g0_w", 0, 0, 0.0, GRASS)
b.flat("g0_2", 2, 0, 0.0, GRASS)                   # 花田锥脚下
b.flat("g0_3", 3, 0, 0.0, GRASS)
b.flat_rect("g0_e", 4, 0, 0.0, GRASS)
# 飞行走廊行 (y [1,2])
for x in range(6):
    b.flat(f"g1_{x}", x, 1, 0.0, GRASS)
# 蜂箱行 (y [2,3])
for x in range(6):
    b.flat(f"g2_{x}", x, 2, 0.0, GRASS)
# 北缘行 (y [3,4])
b.flat_rect("g3_w", 0, 3, 0.0, GRASS)
b.flat("g3_2", 2, 3, 0.0, GRASS)
b.flat("g3_3", 3, 3, 0.0, GRASS)
b.flat_rect("g3_e", 4, 3, 0.0, GRASS)

# =================================================================
# 2. 女王蜂箱 (x [1,2], y [2,3]): 两节箱环 + 压顶 + 锥顶
# =================================================================
b.add("qa1_s", "door_frame", (1.5, 2.0, 0.5), (90, 0, 0), DOOR)   # 巢门
b.wall_ns("qa1_n", 1, 3.0, 0, HIVE)
b.wall_ew("qa1_w", 1.0, 2, 0, HIVE)
b.wall_ew("qa1_e", 2.0, 2, 0, HIVE)
b.flat("qa_cap1", 1, 2, 1.0, CAP)
b.add("qa2_s", "window_square", (1.5, 2.0, 1.5), (90, 0, 0), WIN)  # 观察窗
b.wall_ns("qa2_n", 1, 3.0, 1, HIVE)
b.wall_ew("qa2_w", 1.0, 2, 1, HIVE)
b.wall_ew("qa2_e", 2.0, 2, 1, HIVE)
b.flat("qa_cap2", 1, 2, 2.0, CAP)
b.hat4("qa_roof", 1, 2, 2.0, ROOF, shape="equilateral_triangle")

# =================================================================
# 3. 工蜂箱 (x [4,5], y [2,3]): 单节箱环 + 压顶 + 锥顶
# =================================================================
b.add("wb1_s", "door_frame", (4.5, 2.0, 0.5), (90, 0, 0), DOOR)   # 巢门
b.wall_ns("wb1_n", 4, 3.0, 0, HIVE)
b.wall_ew("wb1_w", 4.0, 2, 0, HIVE)
b.wall_ew("wb1_e", 5.0, 2, 0, HIVE)
b.flat("wb_cap", 4, 2, 1.0, CAP)
b.hat4("wb_roof", 4, 2, 1.0, ROOF, shape="equilateral_triangle")

# =================================================================
# 4. 花田 + 小蜜蜂
# =================================================================
b.hat4("flower", 2, 0, 0.0, FLOWER, shape="equilateral_triangle")
b.crest_ns("bee", 3, 1.0, 0.0, BEE)                # 骑 y=1 地缝

# =================================================================
# 教程步骤 (10 步)
# =================================================================
b.step(
    "铺花田行: 两片绿茵长板收东西两端, 花田锥脚下用单位方板。",
    ["g0_w", "g0_2", "g0_3", "g0_e"],
    tip="清晨的养蜂场从花田开始 —— 蜜蜂的早餐就种在这一行。",
)
b.step(
    "铺飞行走廊行: 六片单位方板一字排开, 与花田行对缝。",
    ["g1_0", "g1_1", "g1_2", "g1_3", "g1_4", "g1_5"],
    highlight=["g0_2"],
    tip="这条走廊是蜜蜂的航线 —— 从花田直飞巢门, 一格都不绕。",
)
b.step(
    "铺蜂箱行: 六片单位方板, 两座蜂箱的墙脚全踩在这行拼缝上。",
    ["g2_0", "g2_1", "g2_2", "g2_3", "g2_4", "g2_5"],
    highlight=["g1_1"],
    tip="蜂箱脚下必须是单位方板 —— 墙底边要和方板边等长吸合。",
)
b.step(
    "铺北缘行收口: 两片长板 + 两片方板, 草地围合完成。",
    ["g3_w", "g3_2", "g3_3", "g3_e"],
    highlight=["g2_2"],
    tip="相邻行至少一对等长边互吸 —— 整片草地连成一体。",
)
b.step(
    "砌女王蜂箱第一节: 巢门门框方朝南, 四角竖边互咬成环。",
    ["qa1_s", "qa1_n", "qa1_w", "qa1_e"],
    highlight=["g2_1"],
    tip="巢门是蜂群的大门 —— 门框方外框与正方形一样能整边吸合。",
)
b.step(
    "盖第一层压顶并摞第二节箱环: 观察窗窗格方朝南, 底边与下节"
    "墙顶整边共线吸合。",
    ["qa_cap1", "qa2_s", "qa2_n", "qa2_w", "qa2_e"],
    highlight=["qa1_s"],
    tip="加继箱喽! 真实的养蜂人就是这样一层层往上摞蜂箱的。",
)
b.step(
    "盖第二层压顶并合女王蜂箱锥顶: 四片等边三角四棱互吸自锁。",
    ["qa_cap2", "qa_roof_s", "qa_roof_e", "qa_roof_n", "qa_roof_w"],
    highlight=["qa2_s"],
    tip="锥顶底边吸'压顶边+墙顶边'两条共线铰链 —— 掀开就能看蜂群。",
)
b.step(
    "砌工蜂箱并盖压顶: 单节箱环巢门朝南, 压顶四边吸墙顶。",
    ["wb1_s", "wb1_n", "wb1_w", "wb1_e", "wb_cap"],
    highlight=["g2_4"],
    tip="矮的这座住工蜂 —— 一高一矮, 蜂场的天际线就有了节奏。",
)
b.step(
    "合工蜂箱锥顶: 四片橙色等边三角逐片就位, 斜棱两两互吸。",
    ["wb_roof_s", "wb_roof_e", "wb_roof_n", "wb_roof_w"],
    highlight=["wb_cap"],
    tip="第四片最难放 —— 它要同时吸住两条斜棱, 对准再松手。",
)
b.step(
    "种花田并放小蜜蜂: 粉色四坡锥四棱自锁, 黄色小蜜蜂骑地缝起飞!",
    ["flower_s", "flower_e", "flower_n", "flower_w", "bee"],
    highlight=["g0_2"],
    tip="小蜜蜂正沿着飞行走廊回家 —— 嗡嗡嗡, 今天也是采蜜的好日子!",
)

b.finalize(
    model_id="bee_farm_01",
    name="快乐养蜂场",
    name_en="Bee Farm 01",
    description=(
        "只用核心九片型的养蜂场, 结构签名是'一高一矮双蜂箱塔': 蜂箱"
        "就是逐层摞起的箱环 —— 女王蜂箱两节箱环整边共线上叠 (真实"
        "养蜂人加继箱的方式), 南面一层开门框方巢门、二层嵌窗格方"
        "观察窗, 顶上四坡锥顶四棱互吸自锁; 工蜂箱单节箱环 + 锥顶, "
        "一高一矮排出蜂场天际线。花田粉色四坡锥盛开在南侧, 黄色小"
        "蜜蜂骑着地缝沿飞行走廊从花丛直飞巢门 —— 嗡嗡嗡, 掀开锥顶"
        "就能看蜂群酿蜜!"
    ),
    difficulty=2,
    tags=["田园", "农场", "蜜蜂", "花田", "进阶"],
    min_pieces=48,
    min_steps=10,
)
