#!/usr/bin/env python3
"""生成模型 data/models/triumphal_arch_01.json (凯旋门)。

第四批模型 ②: 建筑地标主题 —— 全库第一座用扇形拼出圆拱的建筑:
两座 1x2 石墩各叠 3 层墙环, 2 格宽的门洞顶上由 4 片桥板双端受力
合龙; 4 片扇形贴在门洞四个内角, 竖半径边吸墩身竖边、水平半径边
吸桥板沿边, 双边受力拼出真正的圆弧拱腹线; 阁楼层墙环绕顶而立,
长方形檐板压顶, 中央双驾马车雕像与四角旌旗收笔。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 广场: 前后条带 12 片 + 门洞甬道 4 片                         16 片
  - 石墩: 2 座 x 3 层 x 6 片墙环                                 36 片
  - 墩顶压板: 2 片平铺长方形                                      2 片
  - 扶壁斜撑: 4 片直角三角形                                      4 片
  - 门洞桥板: 4 片正方形双端搁在墩顶                              4 片
  - 圆拱: 4 片扇形贴四个内角 (竖边吸墩, 平边吸桥板)               4 片
  - 阁楼层: 12 片墙环 + 4 片长方形檐板                           16 片
  - 雕像 2 + 旌旗 4                                               6 片
  合计 88 片, 18 个教程步骤, 6 种磁力片形状。

几何要点:
  - 扇形只有两条半径边是磁力边 (弧边不吸): 竖半径边整边吸石墩
    第 3 层墙的门洞竖边, 水平半径边整边吸桥板沿边 —— 双边受力,
    剪断任一条力都能绕行;
  - 桥板短边吸墩身墙顶单位边, 两端受力零悬挑;
  - 檐板只在东西山口吸墙顶, 长边互吸成整板, 雕像与旌旗骑在
    檐板短边缝上, 力矩为零。

用法: python3 tools/generate_triumphal_arch.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

# =================================================================
# 1. 广场: 前后条带 (x -1..5) + 门洞甬道
# =================================================================
for i, x in enumerate(range(-1, 5)):
    b.flat(f"pz_f_{i}", x, -1, 0.0, "gray")          # 前条带 y[-1,0]
for i, x in enumerate(range(-1, 5)):
    b.flat(f"pz_b_{i}", x, 2, 0.0, "gray")           # 后条带 y[2,3]
for row in (0, 1):
    for x in (1, 2):
        b.flat(f"pv_{row}_{x}", x, row, 0.0, "gray")  # 门洞甬道

# =================================================================
# 2. 石墩: 西墩 x[0,1] / 东墩 x[3,4], 各 3 层 6 片墙环 (y 0..2)
# =================================================================
for tag, px in (("w", 0), ("e", 3)):
    for lv in range(3):
        b.wall_ns(f"p{tag}_s_{lv}", px, 0.0, lv, "yellow")       # 南脸
        b.wall_ns(f"p{tag}_n_{lv}", px, 2.0, lv, "yellow")       # 北脸
        for lane in (0, 1):
            b.wall_ew(f"p{tag}_w_{lv}_{lane}", float(px), lane, lv, "yellow")
            b.wall_ew(f"p{tag}_e_{lv}_{lane}", float(px) + 1.0, lane, lv, "yellow")

# =================================================================
# 3. 扶壁斜撑: 4 片直角三角形抵住墩脚外竖边
# =================================================================
b.brace("bt_fw", (0.0, 0.0, 0.0), "-x", "gray")      # 前西
b.brace("bt_fe", (4.0, 0.0, 0.0), "+x", "gray")      # 前东
b.brace("bt_rw", (0.0, 2.0, 0.0), "-x", "gray")      # 后西
b.brace("bt_re", (4.0, 2.0, 0.0), "+x", "gray")      # 后东

# =================================================================
# 4. 墩顶压板 + 门洞桥板 (z=3)
# =================================================================
b.flat_rect("cap_w", 0, 0, 3.0, "gray", axis="y")    # 西墩压板 1x2
b.flat_rect("cap_e", 3, 0, 3.0, "gray", axis="y")    # 东墩压板 1x2
for row in (0, 1):
    for x in (1, 2):
        b.flat(f"br_{row}_{x}", x, row, 3.0, "yellow")  # 门洞桥板

# =================================================================
# 5. 圆拱: 4 片扇形贴门洞四个内角
# =================================================================
b.place_edge("arch_fw", "sector", 0, (1.0, 0.0, 3.0), (1.0, 0.0, 2.0),
             (1.0, 0.0, 0.0), "gray")
b.place_edge("arch_fe", "sector", 0, (3.0, 0.0, 3.0), (3.0, 0.0, 2.0),
             (-1.0, 0.0, 0.0), "gray")
b.place_edge("arch_rw", "sector", 0, (1.0, 2.0, 3.0), (1.0, 2.0, 2.0),
             (1.0, 0.0, 0.0), "gray")
b.place_edge("arch_re", "sector", 0, (3.0, 2.0, 3.0), (3.0, 2.0, 2.0),
             (-1.0, 0.0, 0.0), "gray")

# =================================================================
# 6. 阁楼层 (z 3..4): 12 片墙环 + 4 片长方形檐板 (z=4)
# =================================================================
for x in range(4):
    b.wall_ns(f"at_s_{x}", x, 0.0, 3, "yellow")      # 阁楼南墙
for x in range(4):
    b.wall_ns(f"at_n_{x}", x, 2.0, 3, "yellow")      # 阁楼北墙
for lane in (0, 1):
    b.wall_ew(f"at_w_{lane}", 0.0, lane, 3, "yellow")  # 阁楼西山
    b.wall_ew(f"at_e_{lane}", 4.0, lane, 3, "yellow")  # 阁楼东山
for tid, x0, row in (("cor_sw", 0, 0), ("cor_se", 2, 0),
                     ("cor_nw", 0, 1), ("cor_ne", 2, 1)):
    b.flat_rect(tid, x0, row, 4.0, "gray", axis="x")   # 檐板压顶

# =================================================================
# 7. 中央双驾马车雕像 + 四角旌旗 (骑在檐板短边缝上)
# =================================================================
b.crest_ew("st_s", 2.0, 0, 4.0, "yellow")            # 雕像南半
b.crest_ew("st_n", 2.0, 1, 4.0, "yellow")            # 雕像北半
b.crest_ew("fg_ws", 0.0, 0, 4.0, "red")              # 西南旗
b.crest_ew("fg_wn", 0.0, 1, 4.0, "red")              # 西北旗
b.crest_ew("fg_es", 4.0, 0, 4.0, "red")              # 东南旗
b.crest_ew("fg_en", 4.0, 1, 4.0, "red")              # 东北旗

# =================================================================
# 教程步骤 (18 步)
# =================================================================
b.step(
    "铺前广场条带: 6 片灰色正方形沿东西向排开, 凯旋大道由此起步。",
    [f"pz_f_{i}" for i in range(6)],
    tip="从西向东一片片接龙, 这条线就是阅兵队伍走来的方向。",
)
b.step(
    "铺门洞甬道: 4 片灰色正方形从前条带向北接龙, 填出通道地面。",
    ["pv_0_1", "pv_0_2", "pv_1_1", "pv_1_2"],
    highlight=["pz_f_2", "pz_f_3"],
    tip="甬道南沿整边吸住前条带, 从门洞里望出去是笔直的路。",
)
b.step(
    "铺后广场条带: 再 6 片对称排在北侧, 中段吸住甬道北沿。",
    [f"pz_b_{i}" for i in range(6)],
    highlight=["pv_1_1", "pv_1_2"],
    tip="前后条带相距 2 格, 中间正好是石墩与门洞的地界。",
)
b.step(
    "起西墩第 1 层: 6 片黄色正方形围成 1x2 墙环, 转角竖边互吸。",
    ["pw_s_0", "pw_n_0", "pw_w_0_0", "pw_w_0_1", "pw_e_0_0", "pw_e_0_1"],
    highlight=["pz_f_1", "pz_b_1"],
    tip="南脸先立, 东西山各 2 片跟上 —— 环一旦闭合就自锁。",
)
b.step(
    "起东墩第 1 层: 镜像再围一环。",
    ["pe_s_0", "pe_n_0", "pe_w_0_0", "pe_w_0_1", "pe_e_0_0", "pe_e_0_1"],
    highlight=["pw_s_0"],
    tip="两墩内脸相距 2 格 —— 这就是将来门洞的跨度。",
)
b.step(
    "装扶壁斜撑: 4 片直角三角形抵住两墩外脚, 竖边吸墙竖边、"
    "平边吸广场条带。",
    ["bt_fw", "bt_fe", "bt_rw", "bt_re"],
    highlight=["pw_s_0", "pe_s_0"],
    tip="斜撑是三角桁架的最小形态, 石墩从此推不倒。",
)
b.step(
    "西墩加第 2 层: 6 片墙环整层叠上, 墙底整边吸下层墙顶。",
    ["pw_s_1", "pw_n_1", "pw_w_1_0", "pw_w_1_1", "pw_e_1_0", "pw_e_1_1"],
    highlight=["pw_s_0"],
    tip="每一层都是独立的自锁环, 叠环成塔。",
)
b.step(
    "西墩加第 3 层: 再叠一环, 西墩到达门洞顶高度。",
    ["pw_s_2", "pw_n_2", "pw_w_2_0", "pw_w_2_1", "pw_e_2_0", "pw_e_2_1"],
    highlight=["pw_s_1"],
    tip="3 层 = 3 个单位高, 圆拱的圆心就定在这层的内角上。",
)
b.step(
    "东墩加第 2 层: 与西墩同法。",
    ["pe_s_1", "pe_n_1", "pe_w_1_0", "pe_w_1_1", "pe_e_1_0", "pe_e_1_1"],
    highlight=["pe_s_0"],
    tip="左右开工, 两墩始终同高才好合龙。",
)
b.step(
    "东墩加第 3 层: 两墩齐平, 就差顶上一跨。",
    ["pe_s_2", "pe_n_2", "pe_w_2_0", "pe_w_2_1", "pe_e_2_0", "pe_e_2_1"],
    highlight=["pe_s_1", "pw_s_2"],
    tip="门洞两壁已经立好, 圆拱的四个内角各就各位。",
)
b.step(
    "盖墩顶压板: 2 片灰色长方形分别盖住两墩顶口, 短边吸南北墙顶。",
    ["cap_w", "cap_e"],
    highlight=["pw_s_2", "pe_s_2"],
    tip="压板把 6 片墙环锁成一个整体, 也是阁楼层的地基。",
)
b.step(
    "架门洞桥板: 4 片黄色正方形横跨门洞, 两端整边搁在两墩墙顶。",
    ["br_0_1", "br_0_2", "br_1_1", "br_1_2"],
    highlight=["cap_w", "cap_e"],
    tip="每片桥板都两端受力零悬挑 —— 先合龙, 再砌拱。",
)
b.step(
    "贴前脸圆拱: 2 片扇形贴进门洞前脸两个内角, 竖半径边吸墩身"
    "竖边、水平半径边吸桥板沿边。",
    ["arch_fw", "arch_fe"],
    highlight=["pw_s_2", "br_0_1"],
    tip="扇形的弧线在门洞里拼出真正的拱腹 —— 两条半径边双边受力。",
)
b.step(
    "贴后脸圆拱: 另 2 片扇形镜像贴进北侧内角。",
    ["arch_rw", "arch_re"],
    highlight=["arch_fw"],
    tip="前后四片扇形合起来, 从门洞里看是一条完整的圆拱。",
)
b.step(
    "起阁楼层南墙与西山: 南墙 4 片吸压板与桥板沿边, 西山 2 片"
    "骑住转角。",
    ["at_s_0", "at_s_1", "at_s_2", "at_s_3", "at_w_0", "at_w_1"],
    highlight=["cap_w", "br_0_1"],
    tip="阁楼层横跨两墩与门洞, 把整座门锁成一体。",
)
b.step(
    "合拢阁楼层北墙与东山: 再 6 片, 阁楼墙环闭合。",
    ["at_n_0", "at_n_1", "at_n_2", "at_n_3", "at_e_0", "at_e_1"],
    highlight=["at_s_0", "at_w_0"],
    tip="墙环四角竖边互吸, 高处的环更要锁紧。",
)
b.step(
    "压檐板: 4 片灰色长方形盖住阁楼顶口, 短边吸东西山墙顶, "
    "长边互吸成整板。",
    ["cor_sw", "cor_se", "cor_nw", "cor_ne"],
    highlight=["at_w_0", "at_e_0"],
    tip="檐板一压, 凯旋门的轮廓就完整了。",
)
b.step(
    "立中央雕像与四角旌旗: 2 片金色三角雕像骑在檐板中缝, "
    "4 片红旗立在四角短边缝上 —— 凯旋门落成!",
    ["st_s", "st_n", "fg_ws", "fg_wn", "fg_es", "fg_en"],
    highlight=["cor_sw", "cor_ne"],
    tip="雕像正对门洞中轴 —— 从大道尽头望来, 旗与像都在正中。",
)

b.finalize(
    model_id="triumphal_arch_01",
    name="凯旋门",
    name_en="Triumphal Arch 01",
    description=(
        "建筑地标主题: 全库第一座用扇形拼出圆拱的建筑 —— 两座 1x2 石墩"
        "各叠 3 层自锁墙环, 直角三角扶壁抵住外脚; 2 格门洞由 4 片桥板"
        "双端受力合龙, 4 片扇形贴进门洞内角, 竖半径边吸墩身竖边、水平"
        "半径边吸桥板沿边, 双边受力拼出真正的圆弧拱腹线; 阁楼层墙环"
        "横跨两墩把整座门锁成一体, 长方形檐板压顶, 中央双驾马车雕像"
        "骑在檐板中缝上力矩为零, 四角红旗迎风 —— 凯旋大道由此穿门而过。"
    ),
    difficulty=4,
    tags=["建筑地标", "世界地标", "圆拱", "扇形", "挑战"],
    min_pieces=85,
    min_steps=17,
)
