#!/usr/bin/env python3
"""生成模型 data/models/lantern_festival_01.json (元宵灯会)。

节日/庆典主题 1/4: 全库第一条节日灯会长街 —— 与既有门式结构
(bullet_train_01 的接触网架 / fairy_castle_01 的塔间拱楣) 刻意区分,
本作的结构逻辑是 "跨街灯架 + 悬垂花灯 + 玻璃灯塔" 三件套:
一条 12 格红毯灯会街横贯全场, 街上跨着两座门式灯架 —— 双侧立柱
各叠 2 节, 拱心方板两侧竖边纯剪锁进柱顶 (吊桥门楣同款), 拱底
整边倒挂一盏受拉大宫灯 (灯尖垂到离地 0.13, 走马灯就该垂在街心);
街北矗立 2 层玻璃大花灯塔 —— 两层窗格方灯壁透出暖光, 戴等边
四坡灯冠 (灯尖 2.71); 街边石灯柱与灯架脚下的红灯笼列夹道相迎。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 灯会街沿 x 轴):
  - 地面 (x [0,12], y [0,3]): 南草带 + 红毯街 + 北灯带      23 片
  - 门式灯架 x2 (x=3 / x=9): 双柱各 2 节 + 拱心方 + 宫灯    12 片
  - 大花灯塔 (x [6,7], y [2,3]): 两层灯壁 (门框方 x1 +
    窗格方 x7) + 两层盖板 + 等边四坡灯冠                    14 片
  - 石灯柱 x2: 立方壁 + 骑顶黄灯                             4 片
  - 红灯笼列 x4: 灯架脚下等边三角对望                        4 片
  合计 57 片, 12 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 灯架拱心方两侧竖边吸进双柱第 2 节竖棱 (纯剪, 重力对竖直
    铰链轴力矩为零), 柱-拱-柱-地面锁成门式闭环;
  - 大宫灯底边整边吸拱心方底沿, 重心正下受拉 (13g << strict
    悬挂预算 84g/边长) —— 磁力最擅长的受力方向;
  - 灯塔两层灯壁四角竖边互咬成环, 盖板四边压四墙顶, 灯冠四棱
    两两互吸自锁 (灯尖 2.71, 环环相扣通过 R8 高层检查);
  - 石灯柱黄灯 / 红灯笼列重心正压铰链线, 力矩为零。

用法: python3 tools/generate_lantern_festival.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

LAWN = "green"      # 南北草带
STREET = "red"      # 红毯灯会街
PAD = "gray"        # 灯架柱础 / 石灯柱
GOLD = "yellow"     # 灯塔金座
GLOW = "yellow"     # 窗格方灯壁 (暖光)
DOOR = "orange"     # 灯塔门
CAP = "red"         # 灯塔盖板 / 灯冠
MAST = "gray"       # 灯架立柱
ARCH = "red"        # 灯架拱心方
LAMP = "yellow"     # 悬垂大宫灯
POST_LAMP = "yellow"  # 石灯柱顶灯
LANTERN = "red"     # 红灯笼列

# =================================================================
# 1. 地面南行 (y [0,1]): 草带 + 灯架柱础方板
# =================================================================
b.flat_rect("gs_0", 0, 0, 0.0, LAWN)
b.flat("gs_p1", 2, 0, 0.0, PAD)
b.flat("gs_p2", 3, 0, 0.0, PAD)
b.flat_rect("gs_1", 4, 0, 0.0, LAWN)
b.flat_rect("gs_2", 6, 0, 0.0, LAWN)
b.flat("gs_p3", 8, 0, 0.0, PAD)
b.flat("gs_p4", 9, 0, 0.0, PAD)
b.flat_rect("gs_3", 10, 0, 0.0, LAWN)

# =================================================================
# 2. 红毯灯会街 (y [1,2]): 6 片红长板横铺
# =================================================================
for k, x0 in enumerate((0, 2, 4, 6, 8, 10)):
    b.flat_rect(f"st_{k}", x0, 1, 0.0, STREET)

# =================================================================
# 3. 地面北行 (y [2,3]): 草带 + 柱础 + 灯塔金座
# =================================================================
b.flat_rect("gn_0", 0, 2, 0.0, LAWN)
b.flat("gn_p1", 2, 2, 0.0, PAD)
b.flat("gn_p2", 3, 2, 0.0, PAD)
b.flat_rect("gn_1", 4, 2, 0.0, LAWN)
b.flat("gn_gold", 6, 2, 0.0, GOLD)
b.flat("gn_2", 7, 2, 0.0, LAWN)
b.flat("gn_p3", 8, 2, 0.0, PAD)
b.flat("gn_p4", 9, 2, 0.0, PAD)
b.flat_rect("gn_3", 10, 2, 0.0, LAWN)

# =================================================================
# 4. 大花灯塔 (x [6,7], y [2,3]): 两层灯壁 + 盖板 + 灯冠
# =================================================================
b.add("tw1_s", "door_frame", (6.5, 2.0, 0.5), (90, 0, 0), DOOR)
b.wall_ew("tw1_w", 6.0, 2, 0, GLOW)
b.wall_ew("tw1_e", 7.0, 2, 0, GLOW)
b.add("tw1_n", "window_square", (6.5, 3.0, 0.5), (90, 0, 0), GLOW)
b.flat("tw_cap1", 6, 2, 1.0, CAP)
b.add("tw2_s", "window_square", (6.5, 2.0, 1.5), (90, 0, 0), GLOW)
b.add("tw2_w", "window_square", (6.0, 2.5, 1.5), (90, 0, 90), GLOW)
b.add("tw2_e", "window_square", (7.0, 2.5, 1.5), (90, 0, 90), GLOW)
b.add("tw2_n", "window_square", (6.5, 3.0, 1.5), (90, 0, 0), GLOW)
b.flat("tw_cap2", 6, 2, 2.0, CAP)
TW_CROWN = b.hat4("tw_crown", 6, 2, 2.0, CAP, shape="equilateral_triangle")

# =================================================================
# 5. 门式灯架 x2 (x=3 / x=9): 双柱 2 节 + 拱心方 + 悬垂大宫灯
# =================================================================
for tag, xm in (("w", 3.0), ("e", 9.0)):
    b.wall_ew(f"ar_{tag}_s0", xm, 0, 0, MAST)
    b.wall_ew(f"ar_{tag}_s1", xm, 0, 1, MAST)
    b.wall_ew(f"ar_{tag}_n0", xm, 2, 0, MAST)
    b.wall_ew(f"ar_{tag}_n1", xm, 2, 1, MAST)
    b.wall_ew(f"ar_{tag}_key", xm, 1, 1, ARCH)
    b.place_tri(f"ar_{tag}_lamp", "equilateral_triangle",
                (xm, 2.0, 1.0), (xm, 1.0, 1.0), (xm, 1.5, 0.133975), LAMP)

# =================================================================
# 6. 石灯柱 x2 (北界 y=3): 立方壁 + 骑顶黄灯
# =================================================================
b.wall_ns("po_w", 2, 3.0, 0, PAD)
b.crest_ns("po_w_lamp", 2, 3.0, 1.0, POST_LAMP)
b.wall_ns("po_e", 9, 3.0, 0, PAD)
b.crest_ns("po_e_lamp", 9, 3.0, 1.0, POST_LAMP)

# =================================================================
# 7. 红灯笼列 x4: 灯架脚下, 骑北行柱础南沿 (y=2)
# =================================================================
for tag, x0 in (("a", 2), ("b", 3), ("c", 8), ("d", 9)):
    b.crest_ns(f"lt_{tag}", x0, 2.0, 0.0, LANTERN)

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺地面南行 (y [0,1]): 4 片绿长板草带, 两座灯架脚下各垫 2 片"
    "灰色柱础方板 (x [2,4] 与 x [8,10])。",
    ["gs_0", "gs_p1", "gs_p2", "gs_1", "gs_2", "gs_p3", "gs_p4", "gs_3"],
    tip="柱础方板的拼缝 (x=3 与 x=9) 就是灯架立柱的落脚线。",
)
b.step(
    "铺红毯灯会街 (y [1,2]): 6 片红长板横贯 12 格。",
    ["st_0", "st_1", "st_2", "st_3", "st_4", "st_5"],
    highlight=["gs_p1", "gs_p4"],
    tip="元宵灯会最热闹的一条街 —— 灯架就跨在这条红毯上。",
)
b.step(
    "铺地面北行 (y [2,3]): 柱础与南行对齐, 黄色金座 (x [6,7]) "
    "留给大花灯塔。",
    ["gn_0", "gn_p1", "gn_p2", "gn_1", "gn_gold", "gn_2", "gn_p3",
     "gn_p4", "gn_3"],
    highlight=["st_2", "st_3"],
    tip="金座四条边一会儿要被灯塔的四面灯壁踩住 —— 先对准网格。",
)
b.step(
    "立灯塔第 1 层: 南面橙色门框方灯门, 其余三面窗格方灯壁围合。",
    ["tw1_s", "tw1_w", "tw1_e", "tw1_n"],
    highlight=["gn_gold"],
    tip="每片底边吸金座板边、转角竖边互咬 —— 灯壁成环才立得住。",
)
b.step(
    "盖第 1 层盖板, 再叠第 2 层灯壁: 四面全用窗格方, 灯光更透。",
    ["tw_cap1", "tw2_s", "tw2_w", "tw2_e", "tw2_n"],
    highlight=["tw1_s"],
    tip="盖板四边压四墙顶; 第 2 层每片同时吸盖板沿与邻片竖边。",
)
b.step(
    "封灯塔顶并戴灯冠: 盖板压顶, 4 片等边三角斜棱两两互吸自锁。",
    ["tw_cap2"] + TW_CROWN,
    highlight=["tw2_s"],
    tip="灯冠四棱互吸成环, 越推越紧 —— 灯尖亮到 2.71 高。",
)
b.step(
    "立西灯架双柱 (x=3): 南北柱各叠 2 节, 柱脚吸柱础拼缝。",
    ["ar_w_s0", "ar_w_s1", "ar_w_n0", "ar_w_n1"],
    highlight=["gs_p1", "gn_p1"],
    tip="柱脚整边吸进两片柱础方板的拼缝 —— 一条边吃两片的磁力。",
)
b.step(
    "锁西拱心方并挂大宫灯: 拱心方两侧竖边纯剪锁进柱顶, 宫灯底边"
    "整边倒挂在拱底。",
    ["ar_w_key", "ar_w_lamp"],
    highlight=["ar_w_s1", "ar_w_n1"],
    tip="宫灯重心正下受拉 (13g << 84g 预算), 灯尖垂到离地 0.13。",
)
b.step(
    "立东灯架双柱 (x=9): 与西灯架对称。",
    ["ar_e_s0", "ar_e_s1", "ar_e_n0", "ar_e_n1"],
    highlight=["ar_w_key"],
    tip="柱-拱-柱-地面是一个门式闭环 —— 剪断一处也塌不了。",
)
b.step(
    "锁东拱心方并挂大宫灯: 灯会街两端双灯对望。",
    ["ar_e_key", "ar_e_lamp"],
    highlight=["ar_e_s1", "ar_e_n1"],
    tip="两盏宫灯正对街心 —— 走马灯就该垂在人来人往的地方。",
)
b.step(
    "立石灯柱 x2 (北界 y=3): 立方壁骑方板北沿, 柱顶各骑一盏黄灯。",
    ["po_w", "po_w_lamp", "po_e", "po_e_lamp"],
    highlight=["gn_p1", "gn_p4"],
    tip="黄灯重心正压柱顶铰链线, 力臂为零 —— 夜风吹不倒。",
)
b.step(
    "挂红灯笼列: 4 只红灯笼骑上北行柱础南沿, 元宵灯会开街!",
    ["lt_a", "lt_b", "lt_c", "lt_d"],
    highlight=["po_w", "po_e"],
    tip="灯架脚下红灯成列 —— 正月十五, 灯照长街。",
)

b.finalize(
    model_id="lantern_festival_01",
    name="元宵灯会",
    name_en="Lantern Festival 01",
    description=(
        "只用核心九片型的节日灯会长街: 12 格红毯灯会街横贯全场,"
        " 两座门式灯架跨街而立 —— 双柱各叠 2 节, 拱心方两侧竖边"
        "纯剪锁进柱顶, 拱底整边倒挂受拉大宫灯 (13g << strict 悬挂"
        "预算 84g), 灯尖垂到离地 0.13 的街心; 街北 2 层玻璃大花灯塔"
        "两层窗格方灯壁透出暖光, 四角竖边互咬成环, 戴等边四坡灯冠"
        " (灯尖 2.71); 街边石灯柱骑顶黄灯与灯架脚下红灯笼列夹道"
        "相迎 —— 正月十五, 灯照长街。"
    ),
    difficulty=3,
    tags=["节日", "元宵", "灯会", "花灯", "进阶"],
    min_pieces=57,
    min_steps=12,
)
