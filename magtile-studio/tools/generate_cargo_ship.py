#!/usr/bin/env python3
"""生成模型 data/models/cargo_ship_01.json (集装箱货轮)。

海洋航行主题: 全库第一艘集装箱货轮 —— 9 格长的箱形船体以长方形
片为主骨 (船底/舷墙/主甲板三层长板互锁), 艉部两层船楼 (一层
船员舱 + 透明驾驶楼) 顶着雷达罩与信号桅, 甲板中段摞起三个
集装箱堆 (1 号舱位双层橙+蓝, 2 号舱位单层绿), 艏部四坡锚机罩
与透明栏杆收尾 —— 满载出港, 鸣笛三声!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 船艏朝东):
  - 船底 (x 0..9, y 0..2): 长板 x8 + 方板 x2                    10 片
  - 舷墙 (z 0..1): 双舷长板 x8 + 艏艉封板/舷角方墙 x6           14 片
  - 主甲板 (z=1): 长板 x8 + 方板 x2                             10 片
  - 艉楼一层 (x 0..2, z 1..2): 横楣 x2 + 方墙 x4 + 顶板 x4      10 片
  - 驾驶楼 (x 0..1, z 2..3): 透明围壁 x6 + 顶板 x2               8 片
  - 雷达罩 hat4 + 信号桅 + 烟囱罩 hat4                           9 片
  - 1 号货舱双层集装箱 (x 2..4): 一层 6 + 二层 8                14 片
  - 2 号货舱单层集装箱 (x 4..6)                                  6 片
  - 艏部锚机罩 hat4 + 艏艉栏杆 x2                                6 片
  合计 87 片, 18 个教程步骤, 核心三片型 (方/长方/等边, 全 core-5)。

物理规则要点 (通过 R1~R8 全部校验):
  - 长板纪律: 舷墙长板底边 (长 2) 整边吸船底长板长边, 主甲板
    长板长边整边压舷墙顶 —— 船底+舷墙+甲板锁成三层箱形环;
  - 集装箱逐层箱形合龙: 每层 横楣+方墙 围壁先立、顶板后盖,
    顶板四边吸满围壁顶边, 层层互为冗余; 1 号舱西壁与艉楼东壁
    共用同一列方墙 (共享承重, 消除同面重复);
  - 全部 hat4 四坡罩斜棱两两互吸自锁成环 (雷达/烟囱/锚机);
  - 无任何悬挑与吊挂 —— 货轮全船受压, 静力预算轻松全绿。

用法: python3 tools/generate_cargo_ship.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

HULL = "red"        # 船壳
DECK = "gray"       # 甲板
HOUSE = "yellow"    # 艉楼
GLASS = "clear"     # 驾驶楼 / 栏杆
BOX_A = "orange"    # 1 号货舱一层
BOX_B = "blue"      # 1 号货舱二层
BOX_C = "green"     # 2 号货舱
STACK = "red"       # 烟囱罩 / 信号桅

# =================================================================
# 1. 船底 (z=0): 长板为主骨, 拼缝落在 x=2/4/6/8 舱壁线上
# =================================================================
for y0 in (0, 1):
    for x0 in (0, 2, 4, 6):
        b.flat_rect(f"kb_{x0}_{y0}", x0, y0, 0.0, HULL)
    b.flat(f"kb_8_{y0}", 8, y0, 0.0, HULL)

# =================================================================
# 2. 舷墙 (z 0..1): 双舷横楣长板 + 艏艉封板 + 舷角方墙
# =================================================================
for x0 in (0, 2, 4, 6):
    b.lintel_ns(f"bw_s_{x0}", x0, 0.0, 0, HULL)     # 南舷
    b.lintel_ns(f"bw_n_{x0}", x0, 2.0, 0, HULL)     # 北舷
b.wall_ns("bw_s_8", 8, 0.0, 0, HULL)                # 舷角方墙
b.wall_ns("bw_n_8", 8, 2.0, 0, HULL)
b.wall_ew("stern_0", 0.0, 0, 0, HULL)               # 艉封板
b.wall_ew("stern_1", 0.0, 1, 0, HULL)
b.wall_ew("bow_0", 9.0, 0, 0, HULL)                 # 艏封板
b.wall_ew("bow_1", 9.0, 1, 0, HULL)

# =================================================================
# 3. 主甲板 (z=1): 长边整边压舷墙顶, 短边压艏艉封板顶
# =================================================================
for y0 in (0, 1):
    for x0 in (0, 2, 4, 6):
        b.flat_rect(f"dk_{x0}_{y0}", x0, y0, 1.0, DECK)
    b.flat(f"dk_8_{y0}", 8, y0, 1.0, DECK)

# =================================================================
# 4. 艉楼一层 (x 0..2, z 1..2): 船员舱, 东壁与 1 号货舱共用
# =================================================================
b.lintel_ns("h1_s", 0, 0.0, 1, HOUSE)               # 南横楣
b.lintel_ns("h1_n", 0, 2.0, 1, HOUSE)               # 北横楣
for y0 in (0, 1):
    b.wall_ew(f"h1_w_{y0}", 0.0, y0, 1, HOUSE)      # 艉壁
    b.wall_ew(f"h1_e_{y0}", 2.0, y0, 1, HOUSE)      # 东壁 (= 1 号舱西壁)
for x0 in (0, 1):
    for y0 in (0, 1):
        b.flat(f"h1_top_{x0}_{y0}", x0, y0, 2.0, DECK)

# =================================================================
# 5. 驾驶楼 (x 0..1, z 2..3): 透明围壁 360 度视野
# =================================================================
for y0 in (0, 1):
    b.wall_ew(f"wh_w_{y0}", 0.0, y0, 2, GLASS)
    b.wall_ew(f"wh_e_{y0}", 1.0, y0, 2, GLASS)
b.wall_ns("wh_s", 0, 0.0, 2, GLASS)
b.wall_ns("wh_n", 0, 2.0, 2, GLASS)
b.flat("wh_top_0", 0, 0, 3.0, DECK)
b.flat("wh_top_1", 0, 1, 3.0, DECK)

# =================================================================
# 6. 桅顶设备: 雷达罩 hat4 + 信号桅 + 烟囱罩 hat4
# =================================================================
RADAR = b.hat4("radar", 0, 0, 3.0, GLASS, shape="equilateral_triangle")
b.crest_ew("mast", 0.0, 1, 3.0, STACK)              # 信号桅 (艉沿)
FUNNEL = b.hat4("funnel", 1, 1, 2.0, STACK, shape="equilateral_triangle")

# =================================================================
# 7. 货舱集装箱: 1 号舱双层 (x 2..4), 2 号舱单层 (x 4..6)
# =================================================================
# 1 号舱一层 (橙): 西壁共用艉楼东壁, 自带东壁 x=4
b.lintel_ns("c1_s", 2, 0.0, 1, BOX_A)
b.lintel_ns("c1_n", 2, 2.0, 1, BOX_A)
for y0 in (0, 1):
    b.wall_ew(f"c1_e_{y0}", 4.0, y0, 1, BOX_A)
b.flat_rect("c1_top_0", 2, 0, 2.0, BOX_A)
b.flat_rect("c1_top_1", 2, 1, 2.0, BOX_A)

# 1 号舱二层 (蓝): 完整箱形, 骑在一层顶板上
b.lintel_ns("c2_s", 2, 0.0, 2, BOX_B)
b.lintel_ns("c2_n", 2, 2.0, 2, BOX_B)
for y0 in (0, 1):
    b.wall_ew(f"c2_w_{y0}", 2.0, y0, 2, BOX_B)
    b.wall_ew(f"c2_e_{y0}", 4.0, y0, 2, BOX_B)
b.flat_rect("c2_top_0", 2, 0, 3.0, BOX_B)
b.flat_rect("c2_top_1", 2, 1, 3.0, BOX_B)

# 2 号舱单层 (绿): 西壁共用 1 号舱东壁, 自带东壁 x=6
b.lintel_ns("c3_s", 4, 0.0, 1, BOX_C)
b.lintel_ns("c3_n", 4, 2.0, 1, BOX_C)
for y0 in (0, 1):
    b.wall_ew(f"c3_e_{y0}", 6.0, y0, 1, BOX_C)
b.flat_rect("c3_top_0", 4, 0, 2.0, BOX_C)
b.flat_rect("c3_top_1", 4, 1, 2.0, BOX_C)

# =================================================================
# 8. 艏部: 锚机罩 hat4 + 艏栏杆 + 舷侧栏杆
# =================================================================
ANCHOR = b.hat4("windlass", 8, 0, 1.0, DECK, shape="equilateral_triangle")
b.crest_ew("rail_bow", 9.0, 1, 1.0, GLASS)          # 艏栏杆
b.crest_ns("rail_n", 8, 2.0, 1.0, GLASS)            # 北舷栏杆

# =================================================================
# 教程步骤 (18 步)
# =================================================================
b.step(
    "铺船底·艉半: 4 片红色长板双列并进 (x 0..4), 拼缝落在 x=2 舱壁线。",
    [f"kb_{x0}_{y0}" for x0 in (0, 2) for y0 in (0, 1)],
    tip="货轮是全库最长的商船 —— 船底铺直, 全船以它找正。",
)
b.step(
    "铺船底·艏半: 再铺 4 片长板与 2 片方板, 9x2 船底贯通 (x 4..9)。",
    [f"kb_{x0}_{y0}" for x0 in (4, 6) for y0 in (0, 1)]
    + ["kb_8_0", "kb_8_1"],
    highlight=["kb_2_0", "kb_2_1"],
    tip="方板收在船艏 —— 那里将立起锚机罩。",
)
b.step(
    "立艉封板与艉段舷墙: 艉部 2 片方墙封板, 双舷各立 2 片横楣长板 "
    "(x 0..4), 拐角竖边互吸。",
    ["stern_0", "stern_1", "bw_s_0", "bw_s_2", "bw_n_0", "bw_n_2"],
    highlight=["kb_0_0", "kb_0_1"],
    tip="舷墙长板底边 (长 2) 整边吸船底长板长边 —— 一片顶两格。",
)
b.step(
    "舷墙艏段合龙: 双舷再各立 2 片长板, 舷角 2 片方墙, 艏部 2 片"
    "封板 —— 船壳一圈闭合。",
    ["bw_s_4", "bw_s_6", "bw_n_4", "bw_n_6",
     "bw_s_8", "bw_n_8", "bow_0", "bow_1"],
    highlight=["bw_s_2", "bw_n_2"],
    tip="艏封板与舷角方墙竖边互吸 —— 船头先合龙再盖甲板。",
)
b.step(
    "盖主甲板·艉半: 4 片灰色长板长边整边压舷墙顶 (x 0..4)。",
    [f"dk_{x0}_{y0}" for x0 in (0, 2) for y0 in (0, 1)],
    highlight=["bw_s_0", "stern_0"],
    tip="船底+舷墙+甲板锁成箱形环 —— 这就是货轮的船体刚度。",
)
b.step(
    "盖主甲板·艏半: 再盖 4 片长板与 2 片方板, 全通甲板贯通艏艉。",
    [f"dk_{x0}_{y0}" for x0 in (4, 6) for y0 in (0, 1)]
    + ["dk_8_0", "dk_8_1"],
    highlight=["dk_2_0"],
    tip="每片都要听到与舷墙顶边的咔哒声再松手。",
)
b.step(
    "起艉楼一层围壁: 黄色船员舱 2 片横楣 + 4 片方墙 (x 0..2), "
    "东壁将来与 1 号货舱共用。",
    ["h1_s", "h1_n", "h1_w_0", "h1_w_1", "h1_e_0", "h1_e_1"],
    highlight=["dk_0_0", "dk_0_1"],
    tip="艉壁正压艉封板延长线 —— 荷载顺墙身直落船底。",
)
b.step(
    "盖艉楼顶板: 4 片方板压满围壁顶边, 船员舱合龙。",
    [f"h1_top_{x0}_{y0}" for x0 in (0, 1) for y0 in (0, 1)],
    highlight=["h1_s", "h1_e_0"],
    tip="顶板拼缝互吸成整块 —— 这是驾驶楼的地基。",
)
b.step(
    "立驾驶楼围壁: 6 片透明方墙 (x 0..1) —— 船长要看清全部航道。",
    ["wh_w_0", "wh_w_1", "wh_e_0", "wh_e_1", "wh_s", "wh_n"],
    highlight=["h1_top_0_0", "h1_top_0_1"],
    tip="透明围壁 360 度视野, 墙脚踩艉楼顶板拼缝。",
)
b.step(
    "盖驾驶楼顶并竖信号桅: 2 片顶板 + 艉沿 1 片红色信号桅。",
    ["wh_top_0", "wh_top_1", "mast"],
    highlight=["wh_s", "wh_n"],
    tip="信号桅立在船尾最高处 —— 进出港的旗语都从这里升起。",
)
b.step(
    "扣雷达罩: 4 片透明等边三角在驾驶楼顶南格四棱互吸自锁。",
    RADAR,
    highlight=["wh_top_0"],
    tip="四坡自锁成环 —— 雷达罩咔哒一声扣上驾驶楼。",
)
b.step(
    "扣烟囱罩: 艉楼顶东北格再扣 4 片红色四坡罩 —— 鸣笛三声, 准备"
    "装货!",
    FUNNEL,
    highlight=["h1_top_1_1"],
    tip="烟囱罩底边吸艉楼顶板边 —— 货轮的红色烟囱是海上名片。",
)
b.step(
    "1 号货舱一层 (橙): 2 片横楣 + 2 片东壁围出箱壁, 西壁借用"
    "艉楼东壁。",
    ["c1_s", "c1_n", "c1_e_0", "c1_e_1"],
    highlight=["h1_e_0", "h1_e_1"],
    tip="共用舱壁是货轮的省料智慧 —— 一列方墙同时服务两舱。",
)
b.step(
    "盖 1 号舱一层顶: 2 片橙色长板四边吸满箱壁顶边。",
    ["c1_top_0", "c1_top_1"],
    highlight=["c1_s", "c1_n"],
    tip="第一层集装箱落位 —— 顶板就是第二层的甲板。",
)
b.step(
    "1 号货舱二层 (蓝): 2 片横楣 + 4 片方墙骑上一层顶板。",
    ["c2_s", "c2_n", "c2_w_0", "c2_w_1", "c2_e_0", "c2_e_1"],
    highlight=["c1_top_0", "c1_top_1"],
    tip="上层箱壁与下层严格对缝 —— 堆场吊车就是这么码的。",
)
b.step(
    "盖 1 号舱二层顶: 2 片蓝色长板合龙, 双层箱堆锁定。",
    ["c2_top_0", "c2_top_1"],
    highlight=["c2_w_0", "c2_e_0"],
    tip="逐层箱形合龙, 层层互为冗余 —— 风浪里也纹丝不动。",
)
b.step(
    "2 号货舱单层 (绿): 2 片横楣 + 2 片东壁 + 2 片顶板, 西壁借用"
    "1 号舱东壁。",
    ["c3_s", "c3_n", "c3_e_0", "c3_e_1", "c3_top_0", "c3_top_1"],
    highlight=["c1_e_0", "c1_e_1"],
    tip="绿色冷藏箱单独一层 —— 里面装的是要保鲜的热带水果。",
)
b.step(
    "艏部收尾: 4 片灰色锚机罩四坡自锁, 艏沿与北舷各立 1 片透明"
    "栏杆 —— 集装箱货轮满载出港!",
    ANCHOR + ["rail_bow", "rail_n"],
    highlight=["dk_8_0", "dk_8_1"],
    tip="锚机罩底边吸艏甲板拼缝 —— 起锚! 下一站, 环球航线。",
)

b.finalize(
    model_id="cargo_ship_01",
    name="集装箱货轮",
    name_en="Cargo Ship 01",
    description=(
        "全库第一艘集装箱货轮: 9 格长箱形船体以长方形片为主骨, 船底+舷墙+"
        "主甲板锁成三层箱形环; 艉部两层船楼 (船员舱+透明驾驶楼) 顶着雷达罩"
        "与信号桅, 甲板中段双层橙蓝箱堆与单层绿色冷藏箱逐层箱形合龙 (共用"
        "舱壁省料承重), 艏部四坡锚机罩与透明栏杆收尾 —— 满载出港, 鸣笛三声!"
    ),
    difficulty=4,
    tags=["海洋航行", "舰船", "载具", "集装箱", "港口"],
    min_pieces=80,
    min_steps=18,
)
