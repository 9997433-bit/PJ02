#!/usr/bin/env python3
"""生成模型 data/models/yurt_01.json (草原蒙古包)。

内容批 G 补位模型 (顶替与批 H pumpkin_lantern_01 同题撤下的
halloween_pumpkin_house_01 席位): 全库第一顶蒙古包, 民俗主题
第一座民居 (库内民俗只有舞狮一件动态大戏, 还没有一座房子)。
与巫师观星塔 (2x2 正交方塔 + 等腰四坡帽)/蘑菇精灵谷 (四坡锥帽
戴柄上)/圆顶温室 (穹壳) 全部错开: 结构签名是"正八边形毡墙环" ——
全库第一个非正交墙环: 八片方墙竖边以 135 度钝角逐对互咬, 闭环
自锁成蒙古包的圆筒毡壁, 只有正南的红漆门框方踩在毡房门阶拼缝上
(全环唯一的接地拼缝锚点), 其余七片墙脚潇洒落地; 筒顶八片瘦高
等腰三角沿八条斜棱互吸收拢成伞状毡顶, 青黄相间正是节日的顶饰。
门前羊圈三面矮墙围栏留西口, 两只小羊一只在圈一只出门吃草 ——
草原的早晨, 奶茶香从毡房里飘出来!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 大门朝南):
  - 草原地坪 2 行 (x [0,7], y [0,2]): 草地 + 土路门阶        12 片
  - 八边形毡墙环 (z 0..1): 7 片白毡墙 + 1 片红漆门框方        8 片
  - 伞状毡顶 (z 1..2.59): 8 片瘦高等腰青黄相间收拢成锥        8 片
  - 羊圈 (x [5,7], y [0,1]): 三面矮墙围栏留西口               5 片
  - 干草垛 (四棱自锁等边锥) + 小羊 x2 + 牧羊犬 + 野花         8 片
  合计 41 片, 9 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告 + jitter 50 全绿):
  - 八边形墙环每片墙与左右邻墙共享整条竖边 (135 度互咬), 闭环
    即刚; 正南门框墙脚整边吸住门阶方板北沿, 全环与草原锁成一体;
  - 其余七片墙脚直接落地 (接地支撑), 不需要脚下拼缝;
  - 毡顶片底边与墙顶整边共线吸合, 八条斜棱两两互吸自锁
    (摩天大楼金顶同款技法的八棱版);
  - 羊圈矮墙墙脚踩草地方板拼缝, 转角竖边互咬;
  - 干草垛四棱自锁, 底边整边吸脚下单位方板;
  - 小羊/牧羊犬/野花全部骑拼缝, 剪任一装饰最多失联 1 片。

用法: python3 tools/generate_yurt_01.py  (在 magtile-studio 目录下运行)
"""

import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder, ISO_H  # noqa: E402

b = ModelBuilder()

GRASS = "green"     # 草原
PATH = "yellow"     # 土路门阶
FELT = "clear"      # 白毡墙
DOOR = "red"        # 红漆门
ROOF_A = "cyan"     # 毡顶主色
ROOF_B = "yellow"   # 毡顶节日饰带
PEN = "gray"        # 羊圈围栏
HAY = "yellow"      # 干草垛
SHEEP = "clear"     # 小羊
DOG = "gray"        # 牧羊犬
FLOWER = "pink"     # 野花

# ---- 正八边形几何: 边长 1, 正南边恰好压在格线段 [3,4] x {2} 上 ----
S = 1.0
R = S / (2 * math.sin(math.pi / 8))     # 外接圆半径 1.306563
A = S / (2 * math.tan(math.pi / 8))     # 边心距 1.207107
CX, CY = 3.5, 2.0 + A                   # 圆心 (正南边中点在 (3.5, 2))


def overt(k):
    """第 k 个顶点 (逆时针, k=0 是正南边西端 (3,2))。"""
    th = math.radians(-112.5 + 45.0 * k)
    return (CX + R * math.cos(th), CY + R * math.sin(th))


# =================================================================
# 1. 草原地坪 2 行 (x [0,7], y [0,2]): 草地中间一条土路门阶
# =================================================================
b.flat_rect("g1_w", 0, 1, 0.0, GRASS)
b.flat("g1_2", 2, 1, 0.0, GRASS)
b.flat("g1_3", 3, 1, 0.0, PATH)      # 门阶: 北沿就是门框墙脚拼缝
b.flat("g1_4", 4, 1, 0.0, GRASS)
b.flat_rect("g1_e", 5, 1, 0.0, GRASS)
b.flat("g0_0", 0, 0, 0.0, GRASS)
b.flat("g0_1", 1, 0, 0.0, GRASS)     # 干草垛脚下的单位方板
b.flat("g0_2", 2, 0, 0.0, GRASS)
b.flat("g0_3", 3, 0, 0.0, PATH)
b.flat("g0_4", 4, 0, 0.0, GRASS)
b.flat("g0_5", 5, 0, 0.0, GRASS)     # 羊圈地坪
b.flat("g0_6", 6, 0, 0.0, GRASS)

# =================================================================
# 2. 八边形毡墙环 (z 0..1): 正南红漆门框方踩门阶拼缝
# =================================================================
x0, y0 = overt(0)
x1, y1 = overt(1)
b.place_edge("w_0", "door_frame", 0, (x0, y0, 0.0), (x1, y1, 0.0),
             (0, 0, 1), DOOR)
for k in range(1, 8):
    xa, ya = overt(k)
    xb, yb = overt((k + 1) % 8)
    b.place_edge(f"w_{k}", "square", 0, (xa, ya, 0.0), (xb, yb, 0.0),
                 (0, 0, 1), FELT)

# =================================================================
# 3. 伞状毡顶 (z 1..2.59): 八片瘦高等腰青黄相间沿斜棱收拢
# =================================================================
ROOF_H = math.sqrt(ISO_H * ISO_H - A * A)      # 1.594633
apex = (CX, CY, 1.0 + ROOF_H)
for k in range(8):
    xa, ya = overt(k)
    xb, yb = overt((k + 1) % 8)
    b.place_tri(f"roof_{k}", "isosceles_triangle",
                (xa, ya, 1.0), (xb, yb, 1.0), apex,
                ROOF_A if k % 2 == 0 else ROOF_B)

# =================================================================
# 4. 羊圈 (x [5,7], y [0,1], z 0..1): 三面矮墙围栏留西口
# =================================================================
b.wall_ns("pen_s_w", 5, 0.0, 0, PEN)
b.wall_ns("pen_s_e", 6, 0.0, 0, PEN)
b.wall_ns("pen_n_w", 5, 1.0, 0, PEN)
b.wall_ns("pen_n_e", 6, 1.0, 0, PEN)
b.wall_ew("pen_e", 7.0, 0, 0, PEN)

# =================================================================
# 5. 干草垛 + 小羊 x2 + 牧羊犬 + 野花
# =================================================================
b.hat4("hay", 1, 0, 0.0, HAY, shape="equilateral_triangle")
b.crest_ew("sheep_in", 6.0, 0, 0.0, SHEEP)     # 圈里的小羊骑圈内拼缝
b.crest_ew("sheep_out", 5.0, 1, 0.0, SHEEP)    # 出门吃草的小羊
b.crest_ew("dog", 2.0, 0, 0.0, DOG)            # 牧羊犬守着门前路口
b.crest_ew("flower", 2.0, 1, 0.0, FLOWER)      # 门阶西侧野花

# =================================================================
# 教程步骤 (9 步)
# =================================================================
b.step(
    "铺门前行: 两条草地长板夹三片方板, 中间黄色的是土路门阶。",
    ["g1_w", "g1_2", "g1_3", "g1_4", "g1_e"],
    tip="草原的早晨! 门阶北沿待会儿要咬住蒙古包的大门墙脚。",
)
b.step(
    "铺南行草原: 七片方板等边互吸, 黄色方板续上土路。",
    ["g0_0", "g0_1", "g0_2", "g0_3", "g0_4", "g0_5", "g0_6"],
    highlight=["g1_w"],
    tip="干草垛要堆在单位方板上 —— 四条底边都得有整边可吸。",
)
b.step(
    "起毡墙环南半: 红漆门框方踩上门阶北沿, 左右各接一片白毡墙。",
    ["w_0", "w_1", "w_7"],
    highlight=["g1_3"],
    tip="相邻墙片的竖边以 135 度互咬 —— 蒙古包的圆肚皮就是这么鼓起来的。",
)
b.step(
    "合毡墙环北半: 余下五片白毡墙逐片咬进环里, 首尾合拢。",
    ["w_2", "w_3", "w_4", "w_5", "w_6"],
    highlight=["w_1"],
    tip="八片墙合成闭环就自己站稳了 —— 除了大门, 其他墙脚直接踩草地。",
)
b.step(
    "搭毡顶南半: 四片瘦高等腰底边吸住墙顶, 斜棱互吸, 青黄相间。",
    ["roof_0", "roof_1", "roof_7", "roof_6"],
    highlight=["w_0"],
    tip="毡顶片一片挨一片, 斜棱两两咬住 —— 顶尖会在正中央碰头。",
)
b.step(
    "合毡顶北半: 余下四片收拢, 八条棱在顶尖自锁成环。",
    ["roof_2", "roof_3", "roof_4", "roof_5"],
    highlight=["roof_1"],
    tip="最后一片同时咬住两条斜棱 —— 伞状毡顶一锁, 草原大风也不怕。",
)
b.step(
    "围羊圈: 五片灰色矮墙转角互咬, 西边留出进出口。",
    ["pen_s_w", "pen_s_e", "pen_n_w", "pen_n_e", "pen_e"],
    highlight=["g0_5"],
    tip="围栏墙脚踩住草地拼缝 —— 小羊晚上就睡在这里。",
)
b.step(
    "堆干草垛: 四片黄色等边斜棱互吸自锁成锥。",
    ["hay_s", "hay_e", "hay_n", "hay_w"],
    highlight=["g0_1"],
    tip="过冬的草料堆成小金字塔 —— 四条底边都整边吸住脚下方板。",
)
b.step(
    "请小羊、牧羊犬和野花就位: 草原的一天开始啦!",
    ["sheep_in", "sheep_out", "dog", "flower"],
    highlight=["pen_s_e", "g1_3"],
    tip="一只小羊在圈里, 一只出门吃草, 牧羊犬守着路口 —— 奶茶香飘出毡房!",
)

b.finalize(
    model_id="yurt_01",
    name="草原蒙古包",
    name_en="Grassland Yurt 01",
    description=(
        "只用核心九片型的民俗主题第一座民居, 全库第一顶蒙古包, 也是"
        "全库第一个非正交墙环: 八片毡墙竖边以 135 度钝角逐对互咬, "
        "闭环自锁成蒙古包鼓鼓的圆筒毡壁, 只有正南的红漆门框方踩着"
        "土路门阶拼缝, 其余七片墙脚潇洒落地; 筒顶八片瘦高等腰三角"
        "沿八条斜棱互吸收拢成伞状毡顶, 青黄相间正是节日的顶饰; "
        "门前羊圈三面矮墙留西口, 一只小羊在圈里一只出门吃草, 干草垛"
        "四棱自锁堆成小金字塔, 牧羊犬守着路口 —— 草原的早晨, 奶茶香"
        "从毡房里飘出来!"
    ),
    difficulty=2,
    tags=["民俗", "草原", "蒙古包", "毡房", "田园"],
    min_pieces=41,
    min_steps=9,
)
