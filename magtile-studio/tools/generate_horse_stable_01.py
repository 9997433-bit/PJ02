#!/usr/bin/env python3
"""生成模型 data/models/horse_stable_01.json (马术俱乐部)。

内容批 B 5/5 (补位): 全库第一座马术场景 —— 与剪毛牧场 (羊圈 +
剪毛台) 和大象馆 (象舍 + 淋浴场) 刻意错开: 主角是"跳栏训练"
这件事本身 —— 沙地训练场里两道结构不同的跳栏: 低栏是"双柱夹
横杆"的纯剪互锁 (横杆两竖边咬进立柱竖棱, 竖直铰链轴力矩恒为
零), 高栏是"立柱托横板"再借围栏当另一根柱 (共构技法); 橙色小马
刚越过高栏, 扬起的等腰长脖子是全场焦点; 北侧马厩三开间格格
成环, 屋檐下两匹马从敞开的栏门探出头 —— 全库唯一的"跳栏 +
探头马厩"。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 马厩在北, 沙场在东):
  - 场地 (x [0,6], y [0,4]): 草地 x12 + 沙地 x12               24 片
  - 马厩 (x [0,3], y [3,4]): 北墙 x3 (含窗格方) + 隔墙/山墙 x4
    + 屋面 x3 + 探头马 x2 + 屋脊旗                             13 片
  - 训练场围栏 (东 x3 + 北 x2): 清色栏板                        5 片
  - 低栏 (y=1, x [1,3]): 双柱 + 红白横杆纯剪互锁                3 片
  - 高栏 (x [4,6], y [1,2], z=1): 立柱 + 横板 (东端借围栏)      2 片
  - 小马 (x [4,5], y [2,3]): 双侧板 + 背板 + 长脖子 + 尾巴      5 片
  - 草料垛 (x [0,3] 前坪): 等边四坡三角锥落地自锁                4 片
  合计 56 片, 13 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 低栏横杆两条竖直短边分别咬进两根立柱的竖棱 (纯剪互锁,
    重力平行竖直铰链轴, 力矩恒为零), 立柱墙脚踩沙地拼缝;
  - 高栏横板西短边压立柱顶、东短边压围栏顶 —— 围栏就是另一根
    柱 (共构即共保险), 双端受力零悬挑;
  - 小马双侧板立沙缝, 背板两边各压一块侧板顶, 板-背-板锁成
    门式框架; 长脖子底边整边吸背板北沿 (重心正压铰链线),
    尾巴骑背板南沿正好扬在高栏横板上方;
  - 马厩三开间: 北墙 + 四道隔墙/山墙全部落地, 每片屋面北边压
    北墙顶、东西两边压隔墙顶 (三边受力), 南面敞开是栏门 ——
    探头马底边整边吸屋面南沿, 零力矩;
  - 草料垛四条斜棱两两互吸自锁, 四条基线踩满地板整边。

用法: python3 tools/generate_horse_stable_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

GRASS = "green"     # 西半场草地
SAND = "yellow"     # 沙地训练场
BARN = "orange"     # 马厩木墙
BARN_WIN = "cyan"   # 马厩后窗 (窗格方)
ROOF = "red"        # 马厩屋面
HORSE = "orange"    # 马
FLAG = "red"        # 屋脊旗
FENCE = "clear"     # 围栏
POST = "gray"       # 跳栏立柱
RAIL = "red"        # 低栏横杆
BEAM = "clear"      # 高栏横板
HAY = "yellow"      # 草料垛


def wall_ns_t(tid, tile_type, x0, y, z0, color):
    b.add(tid, tile_type, (x0 + 0.5, y, z0 + 0.5), (90, 0, 0), color)


# =================================================================
# 1. 场地 (x [0,6], y [0,4]): 西半场草地, 东半场沙地训练场
# =================================================================
for y0 in range(4):
    for x0 in range(6):
        color = SAND if x0 >= 3 else GRASS
        b.flat(f"fld_{x0}_{y0}", x0, y0, 0.0, color)

# =================================================================
# 2. 马厩 (x [0,3], y [3,4]): 三开间, 南面敞开是栏门
# =================================================================
wall_ns_t("barn_n_0", "window_square", 0, 4.0, 0, BARN_WIN)   # 后窗
b.wall_ns("barn_n_1", 1, 4.0, 0, BARN)
b.wall_ns("barn_n_2", 2, 4.0, 0, BARN)
b.wall_ew("barn_w_0", 0.0, 3, 0, BARN)         # 西山墙
b.wall_ew("barn_p_1", 1.0, 3, 0, BARN)         # 隔墙
b.wall_ew("barn_p_2", 2.0, 3, 0, BARN)
b.wall_ew("barn_e_3", 3.0, 3, 0, BARN)         # 东山墙
b.flat("barn_r_0", 0, 3, 1.0, ROOF)            # 屋面: 三边受力
b.flat("barn_r_1", 1, 3, 1.0, ROOF)
b.flat("barn_r_2", 2, 3, 1.0, ROOF)
b.crest_ns("head_a", 0, 3.0, 1.0, HORSE)       # 探头马骑屋面南沿
b.crest_ns("head_b", 2, 3.0, 1.0, HORSE)
b.spire_ns("barn_flag", 1, 4.0, 1.0, FLAG)     # 屋脊旗一线双吸, 尖 3.0

# =================================================================
# 3. 训练场围栏 (东边 x=6 三片 + 北边 y=4 两片)
# =================================================================
b.wall_ew("fn_e_1", 6.0, 1, 0, FENCE)
b.wall_ew("fn_e_2", 6.0, 2, 0, FENCE)
b.wall_ew("fn_e_3", 6.0, 3, 0, FENCE)
b.wall_ns("fn_n_4", 4, 4.0, 0, FENCE)
b.wall_ns("fn_n_5", 5, 4.0, 0, FENCE)

# =================================================================
# 4. 低栏 (y=1, x [1,3]): 双柱夹横杆, 纯剪互锁
# =================================================================
b.wall_ew("lj_post_w", 1.0, 1, 0, POST)
b.wall_ew("lj_post_e", 3.0, 1, 0, POST)
b.lintel_ns("lj_rail", 1, 1.0, 0, RAIL)        # 横杆两竖边咬柱棱

# =================================================================
# 5. 高栏 (x [4,6], y [1,2], z=1): 立柱托横板, 东端借围栏当柱
# =================================================================
b.wall_ew("hj_post", 4.0, 1, 0, POST)
b.flat_rect("hj_beam", 4, 1, 1.0, BEAM)        # 短边压柱顶与围栏顶

# =================================================================
# 6. 小马 (x [4,5], y [2,3]): 刚越过高栏, 长脖子扬起
# =================================================================
b.wall_ew("hs_side_w", 4.0, 2, 0, HORSE)
b.wall_ew("hs_side_e", 5.0, 2, 0, HORSE)
b.flat("hs_back", 4, 2, 1.0, HORSE)            # 背板压双侧板顶
b.spire_ns("hs_neck", 4, 3.0, 1.0, HORSE)      # 长脖子吸背板北沿
b.crest_ns("hs_tail", 4, 2.0, 1.0, HORSE)      # 尾巴扬在高栏上方

# =================================================================
# 7. 草料垛 (x [0,1], y [1,2]): 等边四坡三角锥落地自锁
# =================================================================
HAY_IDS = b.hat4("hay", 0, 1, 0.0, HAY, shape="equilateral_triangle")

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺场地南行: 西边三片草地, 东边三片沙地。",
    [f"fld_{x0}_0" for x0 in range(6)],
    tip="草绿和沙黄的分界线就是训练场的入口线。",
)
b.step(
    "铺第二行: 行行等边互吸, 跳栏都要踩这行的拼缝。",
    [f"fld_{x0}_1" for x0 in range(6)],
    highlight=["fld_0_0"],
    tip="沙地松软, 小马落地不伤蹄 —— 真正的马场也铺沙。",
)
b.step(
    "铺第三行: 训练场越来越大。",
    [f"fld_{x0}_2" for x0 in range(6)],
    highlight=["fld_0_1"],
    tip="西边草地待会放草料垛, 东边沙地是小马的舞台。",
)
b.step(
    "铺第四行: 马厩地基与围栏墙脚线就位。",
    [f"fld_{x0}_3" for x0 in range(6)],
    highlight=["fld_0_2"],
    tip="整片场地连成一张网, 每道拼缝都是一条磁力吸边。",
)
b.step(
    "立马厩北墙: 窗格方后窗居西, 两片橙色木板墙接排。",
    ["barn_n_0", "barn_n_1", "barn_n_2"],
    highlight=["fld_0_3"],
    tip="北墙踩住场地北沿, 三片竖边互咬连成整面。",
)
b.step(
    "插四道隔墙: 山墙加隔墙隔出三个单间马房。",
    ["barn_w_0", "barn_p_1", "barn_p_2", "barn_e_3"],
    highlight=["barn_n_0"],
    tip="每道隔墙都与北墙竖边互咬 —— 格格成环, 拆一片不倒。",
)
b.step(
    "盖马厩屋面, 屋脊旗骑上北墙顶。",
    ["barn_r_0", "barn_r_1", "barn_r_2", "barn_flag"],
    highlight=["barn_p_1"],
    tip="每片屋面北边压北墙顶、东西两边压隔墙顶, 三边受力; "
        "旗杆底边一线双吸直上 3.0。",
)
b.step(
    "两匹马从栏门探出头: 底边整边吸住屋面南沿。",
    ["head_a", "head_b"],
    highlight=["barn_r_0"],
    tip="南面敞开就是栏门 —— 中间那间的小马已经出去训练啦。",
)
b.step(
    "装训练场围栏: 东边三片、北边两片清色栏板。",
    ["fn_e_1", "fn_e_2", "fn_e_3", "fn_n_4", "fn_n_5"],
    highlight=["fld_5_3"],
    tip="围栏底边整边吸场地边沿, 竖边逐片成链。",
)
b.step(
    "架低栏: 双柱踩沙缝, 红白横杆两竖边咬进柱棱。",
    ["lj_post_w", "lj_post_e", "lj_rail"],
    highlight=["fld_2_1"],
    tip="横杆挂在两柱之间, 竖直接缝纯剪互锁 —— 新手先跳这道。",
)
b.step(
    "架高栏: 立柱托横板, 东端直接压在围栏顶上。",
    ["hj_post", "hj_beam"],
    highlight=["fn_e_1"],
    tip="围栏就是另一根柱 (共构技法), 横板双端受力零悬挑。",
)
b.step(
    "小马登场: 双侧板立沙缝, 背板两边各压一块侧板顶。",
    ["hs_side_w", "hs_side_e", "hs_back"],
    highlight=["hj_beam"],
    tip="板-背-板锁成门式框架 —— 小马就站在高栏后面。",
)
b.step(
    "扬起长脖子, 尾巴翘上高栏 —— 这一跳真漂亮!",
    ["hs_neck", "hs_tail"] + HAY_IDS,
    highlight=["hs_back"],
    tip="脖子底边整边吸背板北沿, 重心正压铰链线; 最后把草料垛"
        "四片斜棱互咬锁在草地上 —— 训练结束好好吃一顿!",
)

b.finalize(
    model_id="horse_stable_01",
    name="马术俱乐部",
    name_en="Horse Stable 01",
    description=(
        "只用核心九片型的马术场景: 主角是跳栏训练 —— 沙地训练场里"
        "两道结构不同的跳栏: 低栏双柱夹横杆纯剪互锁 (竖直铰链轴"
        "力矩恒为零), 高栏立柱托横板、东端直接借围栏当柱 (共构"
        "技法, 双端受力零悬挑); 橙色小马刚越过高栏, 双侧板立沙缝"
        "背板压顶锁成门式框架, 扬起的等腰长脖子是全场焦点, 尾巴"
        "正翘在横板上方; 北侧马厩三开间格格成环、屋面三边受力, "
        "两匹马从敞开的栏门探出头, 草料垛四坡自锁堆在草地上 —— "
        "下一跳, 轮到你了!"
    ),
    difficulty=3,
    tags=["田园", "马术", "动物", "俱乐部", "运动"],
    min_pieces=56,
    min_steps=13,
)
