#!/usr/bin/env python3
"""生成模型 data/models/drum_set_01.json (摇滚架子鼓)。

音乐/乐器主题: 全库第一套架子鼓 —— 结构主角是 "竖立大鼓面 +
四向斜撑": 120g 大方片底鼓鼓面垂直立在地毯拼缝上 (底边与长板
北边 2=2 整边互吸, 一线双吸), 四只直角三角斜撑一前一后各两只
分别咬地缝与鼓面竖边 (前后对撑, 造型即鼓腿); 左右两只落地嗵鼓
与后排军鼓/中嗵是四座箱形墙环 (军鼓与中嗵共墙, 鼓手座再借军鼓
北墙 —— 一墙三用连环); 两支镲片立柱戴等边金镲, 两支等腰麦克风
杆直接立在台缝上重心正压铰链。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 鼓面朝南):
  - 舞台地毯 (x [0,6], y [0,4]): 前排 5 片 + 后三行 18 片      23 片
  - 底鼓: 大方片鼓面 x1 + 直角三角斜撑 x4 (前后对撑)             5 片
  - 落地嗵鼓 x2: 箱形墙环各 4 墙 + 鼓皮顶面                     10 片
  - 军鼓 + 中嗵: 双箱共墙 (5 墙 + 4 墙共 1) + 鼓皮 x2            9 片
  - 鼓手座: 借军鼓北墙 (北腿 x1 + 座面 x1)                       2 片
  - 镲片立柱 x2: 双层立柱 + 等边金镲                             6 片
  - 麦克风杆 x2: 等腰三角直立台缝                                2 片
  合计 57 片, 12 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, strict 档同样全绿):
  - 底鼓鼓面 (120g): 底边骑地毯拼缝 (长板北边 2=2 整边 +
    两片方砖南边, 一线三吸), 重心正压铰链线力矩为零;
    四只斜撑两条直角边分别吸地缝与鼓面竖边, 剪任一条铰链
    力都能绕行 —— 无单点失效;
  - 军鼓-中嗵共墙、鼓手座借军鼓北墙: 一墙多用, 箱环相扣;
  - 金镲/麦克风杆重心正压支承边, 纯压零力矩;
  - 全部箱体四角竖边互吸成环, strict 档零警告。

用法: python3 tools/generate_drum_set.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

CARPET = "purple"   # 舞台地毯
LANE = "red"        # 红毯中线
KICK = "red"        # 底鼓鼓面
BRACE = "gray"      # 斜撑
TOM_W = "blue"      # 西落地嗵
TOM_E = "blue"      # 东落地嗵
SNARE = "green"     # 军鼓
TOM_M = "cyan"      # 中嗵
SKIN = "clear"      # 鼓皮
THRONE = "orange"   # 鼓手座
STAND = "gray"      # 镲片立柱
CYMBAL = "yellow"   # 金镲
MIC = "gray"        # 麦克风杆

# =================================================================
# 1. 舞台地毯 (x [0,6], y [0,4]): 前排长板托底鼓, 后三行满铺
# =================================================================
b.flat("cp_0_0", 0, 0, 0.0, CARPET)
b.flat("cp_1_0", 1, 0, 0.0, CARPET)
b.flat_rect("cp_kick", 2, 0, 0.0, LANE)
b.flat("cp_4_0", 4, 0, 0.0, CARPET)
b.flat("cp_5_0", 5, 0, 0.0, CARPET)
for y in (1, 2, 3):
    for x in range(6):
        b.flat(f"cp_{x}_{y}", x, y, 0.0, LANE if x in (2, 3) and y == 1 else CARPET)

# =================================================================
# 2. 底鼓: 大方片鼓面立 y=1 拼缝 + 四向斜撑
# =================================================================
b.add("kick", "large_square", (3.0, 1.0, 1.0), (90, 0, 0), KICK)
b.brace("kb_w_s", (2.0, 1.0, 0.0), "-y", BRACE)
b.brace("kb_w_n", (2.0, 1.0, 0.0), "+y", BRACE)
b.brace("kb_e_s", (4.0, 1.0, 0.0), "-y", BRACE)
b.brace("kb_e_n", (4.0, 1.0, 0.0), "+y", BRACE)

# =================================================================
# 3. 落地嗵鼓 x2 (x [0,1] 与 x [5,6], y [1,2]): 箱形墙环 + 鼓皮
# =================================================================
b.wall_ns("tw_s", 0, 1.0, 0, TOM_W)
b.wall_ns("tw_n", 0, 2.0, 0, TOM_W)
b.wall_ew("tw_w", 0.0, 1, 0, TOM_W)
b.wall_ew("tw_e", 1.0, 1, 0, TOM_W)
b.flat("tw_skin", 0, 1, 1.0, SKIN)
b.wall_ns("te_s", 5, 1.0, 0, TOM_E)
b.wall_ns("te_n", 5, 2.0, 0, TOM_E)
b.wall_ew("te_w", 5.0, 1, 0, TOM_E)
b.wall_ew("te_e", 6.0, 1, 0, TOM_E)
b.flat("te_skin", 5, 1, 1.0, SKIN)

# =================================================================
# 4. 军鼓 + 中嗵 (x [2,4], y [2,3]): 双箱共墙
# =================================================================
b.wall_ns("sn_s", 2, 2.0, 0, SNARE)
b.wall_ns("sn_n", 2, 3.0, 0, SNARE)
b.wall_ew("sn_w", 2.0, 2, 0, SNARE)
b.wall_ew("sn_e", 3.0, 2, 0, SNARE)   # 共墙: 军鼓东墙 = 中嗵西墙
b.flat("sn_skin", 2, 2, 1.0, SKIN)
b.wall_ns("tm_s", 3, 2.0, 0, TOM_M)
b.wall_ns("tm_n", 3, 3.0, 0, TOM_M)
b.wall_ew("tm_e", 4.0, 2, 0, TOM_M)
b.flat("tm_skin", 3, 2, 1.0, SKIN)

# =================================================================
# 5. 鼓手座 (x [2,3], y [3,4]): 南腿借军鼓北墙
# =================================================================
b.wall_ns("th_n", 2, 4.0, 0, THRONE)
b.flat("th_seat", 2, 3, 1.0, THRONE)

# =================================================================
# 6. 镲片立柱 x2 + 麦克风杆 x2
# =================================================================
b.wall_ns("cw_lo", 0, 3.0, 0, STAND)
b.wall_ns("cw_hi", 0, 3.0, 1, STAND)
b.crest_ns("cw_cym", 0, 3.0, 2.0, CYMBAL)
b.wall_ns("ce_lo", 5, 3.0, 0, STAND)
b.wall_ns("ce_hi", 5, 3.0, 1, STAND)
b.crest_ns("ce_cym", 5, 3.0, 2.0, CYMBAL)
b.spire_ns("mic_w", 1, 0.0, 0.0, MIC)
b.spire_ns("mic_e", 4, 0.0, 0.0, MIC)

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺地毯前排 (y [0,1]): 4 片方砖 + 1 条长板居中。",
    ["cp_0_0", "cp_1_0", "cp_kick", "cp_4_0", "cp_5_0"],
    tip="长板的北边整整 2 格长 —— 那就是底鼓鼓面的落脚缝。",
)
b.step(
    "铺地毯第二行 (y [1,2]): 6 片, 拼缝对齐前排。",
    [f"cp_{x}_1" for x in range(6)],
    highlight=["cp_kick"],
    tip="y=1 的整条拼缝一线贯通 —— 鼓面与斜撑都靠它吸稳。",
)
b.step(
    "铺满地毯 (y [2,4]): 12 片, 舞台就位。",
    [f"cp_{x}_2" for x in range(6)] + [f"cp_{x}_3" for x in range(6)],
    highlight=["cp_0_1"],
    tip="后排留给军鼓、鼓手座和镲片立柱 —— 位置从地毯定下。",
)
b.step(
    "立底鼓鼓面: 120g 大方片垂直骑上 y=1 拼缝。",
    ["kick"],
    highlight=["cp_kick", "cp_2_1"],
    tip="底边与长板北边 2=2 整边互吸, 重心正压铰链 —— 力矩为零。",
)
b.step(
    "装四向斜撑: 直角三角一前一后各两只, 咬地缝又咬鼓面竖边。",
    ["kb_w_s", "kb_w_n", "kb_e_s", "kb_e_n"],
    highlight=["kick"],
    tip="前后对撑, 剪断任何一条铰链力都能绕行 —— 造型即鼓腿。",
)
b.step(
    "砌西落地嗵: 4 片墙环踩拼缝, 鼓皮压顶。",
    ["tw_s", "tw_w", "tw_n", "tw_e", "tw_skin"],
    highlight=["cp_0_1"],
    tip="箱形墙环四角竖边互吸, 鼓皮每边都压一段墙顶。",
)
b.step(
    "砌东落地嗵: 与西嗵对称, 5 片。",
    ["te_s", "te_w", "te_n", "te_e", "te_skin"],
    highlight=["tw_skin"],
    tip="左右两只落地嗵夹住底鼓 —— 架子鼓的经典布局。",
)
b.step(
    "砌军鼓 (x [2,3], y [2,3]): 4 片墙环 + 鼓皮。",
    ["sn_s", "sn_w", "sn_n", "sn_e", "sn_skin"],
    highlight=["cp_2_1"],
    tip="军鼓的东墙先砌好 —— 下一步中嗵要借这面墙。",
)
b.step(
    "拼中嗵: 只砌 3 面墙, 西面借军鼓东墙一墙两用。",
    ["tm_s", "tm_n", "tm_e", "tm_skin"],
    highlight=["sn_e"],
    tip="共墙省一片, 两只鼓还被锁成一个连环箱。",
)
b.step(
    "装鼓手座: 南腿借军鼓北墙, 北腿新立, 座面双端压顶。",
    ["th_n", "th_seat"],
    highlight=["sn_n"],
    tip="一墙三用: 军鼓北墙同时是鼓手座的南腿 —— 环环相扣。",
)
b.step(
    "立镲片: 两支双层立柱, 顶上各戴一面等边金镲。",
    ["cw_lo", "cw_hi", "cw_cym", "ce_lo", "ce_hi", "ce_cym"],
    highlight=["tw_n", "te_n"],
    tip="金镲重心正压柱顶铰链, 力矩为零 —— 一敲就响 (假装)。",
)
b.step(
    "插麦克风杆 x2 —— 摇滚架子鼓开场!",
    ["mic_w", "mic_e"],
    highlight=["kick"],
    tip="等腰长杆直接立在台缝上, 重心正压底边 —— 稳稳收工。",
)

b.finalize(
    model_id="drum_set_01",
    name="摇滚架子鼓",
    name_en="Drum Set 01",
    description=(
        "全库第一套架子鼓: 120g 大方片底鼓鼓面垂直骑上地毯拼缝"
        " (与长板北边 2=2 整边互吸, 重心正压铰链力矩为零), 四只"
        "直角三角斜撑一前一后对撑、同时咬地缝与鼓面竖边 (造型即"
        "鼓腿, 剪任一条铰链力都能绕行); 左右落地嗵与后排军鼓/"
        "中嗵是四座箱形墙环 —— 军鼓与中嗵共墙、鼓手座再借军鼓"
        "北墙, 一墙三用连环相扣; 双层立柱戴等边金镲, 两支等腰"
        "麦克风杆直立台缝。竖立大片、四向斜撑、共墙连环 —— "
        "一套鼓三种结构玩法。"
    ),
    difficulty=3,
    tags=["音乐", "乐器", "架子鼓", "乐队", "进阶"],
    min_pieces=55,
    min_steps=12,
)
