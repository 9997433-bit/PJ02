#!/usr/bin/env python3
"""生成模型 data/models/dinosaur_hall_01.json (恐龙化石挖掘展厅)。

博物馆/艺术主题 3/4: 全库第一座 "考古挖掘现场" 场景 —— 与
trex_skeleton_01 (立姿悬挑骨架) 和 dinosaur_stego_01 (活体腿柱箱体)
的恐龙搭法完全不同: 化石不站起来, 而是平卧在挖掘坑里 —— 骨架
是一幅嵌进地面的平面镶嵌画: 方形颅骨与脊柱、直角三角肋骨成对
共享竖直角边拼成 V 形胸腔、等边三角尾椎条带靠斜边两两互吸甩出
坑外, 坑内故意留白的半格就是挖掘沟槽的负空间; 北侧一条架空
观展廊桥 (门框方拱廊 + 长板桥面双端受力) 让参观者俯瞰全坑;
南侧双塔大门两层墙环竖叠、门楣双端竖边纯剪、等边四坡锥收顶。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 大门朝南):
  - 场地南行 + 坑缘 (x [0,8]): 石板 + 沙地                    16 片
  - 化石镶嵌画 (坑内 z=0): 颅骨 + 脊柱 x3 + 骨盆 + 前后肢 +
    肋骨直角三角 x4 (V 形成对) + 尾椎等边条带 x3              14 片
  - 坑北沙地 + 观展区地面: 沙 x3 + 长板 x8                    11 片
  - 观展廊桥: 门框方拱廊 x5 + 北墙长板 x4 + 桥面长板 x4 +
    了望三角旗 x5                                             18 片
  - 双塔大门: 墙环 4x2 x2 + 等边四坡锥 x2 + 门楣 x1           25 片
  合计 84 片, 18 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (R1~R8 全绿, strict 档零警告):
  - 化石全部平卧接地, 肋骨成对共享竖直角边、尾椎条带斜边互吸,
    每片至少一条整边落在网格拼缝上;
  - 廊桥桥面双端受力: 南缘压拱廊顶、北缘压北墙顶, 零悬挑;
    北墙用长板横砌 (底边 2.0 一线双吸地板长缝);
  - 双塔各两层墙环四角竖边闭环, 层间四缝互为冗余; 门楣跨
    2 格门洞、双端竖边纯剪锁进塔身, 剪断任一端仍经另一端绕行;
  - 挖掘坑东侧留一格负空间 (尾椎甩出坑外的挖掘沟槽)。

用法: python3 tools/generate_dinosaur_hall.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

STONE = "gray"      # 场地石板
SAND = "orange"     # 挖掘坑沙地
BONE = "clear"      # 化石骨骼
TOWER = "red"       # 大门塔身
TOWER2 = "purple"   # 大门塔身第 2 层
HAT = "yellow"      # 塔顶锥
LINTEL = "red"      # 门楣
ARCADE = "gray"     # 拱廊
GLASS = "clear"     # 观景窗
DECK = "green"      # 桥面
FLAG = "yellow"     # 了望三角旗

# =================================================================
# 1. 场地南行 (y [0,1]): 8 片单方, 拼缝对准双塔与坑缘
# =================================================================
for x in range(8):
    color = SAND if x in (2, 3) else STONE
    b.flat(f"s0_{x}", x, 0, 0.0, color)

# =================================================================
# 2. 坑缘与坑南沙地 (y [1,4] 两翼 + y [1,2] 坑内)
# =================================================================
b.flat("w_1", 0, 1, 0.0, STONE)
b.flat("w_2", 0, 2, 0.0, STONE)
b.flat("w_3", 0, 3, 0.0, STONE)
b.flat("e_1", 7, 1, 0.0, STONE)
b.flat("e_3", 7, 3, 0.0, STONE)           # (7,2) 留空: 尾椎甩出坑外的沟槽
b.flat("sd1_a", 4, 1, 0.0, SAND)
b.flat("sd1_b", 5, 1, 0.0, SAND)
b.flat("sd1_c", 6, 1, 0.0, SAND)

# =================================================================
# 3. 化石镶嵌画 (坑内 z=0, 头朝西尾朝东)
# =================================================================
b.flat("skull", 1, 2, 0.0, BONE)          # 颅骨
b.flat("leg_f", 1, 1, 0.0, BONE)          # 前肢
b.flat("spine_1", 2, 2, 0.0, BONE)        # 脊柱
b.flat("spine_2", 3, 2, 0.0, BONE)
b.flat("spine_3", 4, 2, 0.0, BONE)
b.flat("pelvis", 5, 2, 0.0, BONE)         # 骨盆
b.flat("leg_h", 5, 3, 0.0, BONE)          # 后肢
# 肋骨: 直角三角成对共享竖直角边, 拼成 V 形胸腔
b.place_tri("rib_s1", "right_triangle",
            (3.0, 2.0, 0.0), (2.0, 2.0, 0.0), (3.0, 1.0, 0.0), BONE)
b.place_tri("rib_s2", "right_triangle",
            (3.0, 2.0, 0.0), (4.0, 2.0, 0.0), (3.0, 1.0, 0.0), BONE)
b.place_tri("rib_n1", "right_triangle",
            (3.0, 3.0, 0.0), (2.0, 3.0, 0.0), (3.0, 4.0, 0.0), BONE)
b.place_tri("rib_n2", "right_triangle",
            (3.0, 3.0, 0.0), (4.0, 3.0, 0.0), (3.0, 4.0, 0.0), BONE)
# 尾椎: 等边三角条带, 斜边两两互吸甩出坑外
b.place_tri("tail_1", "equilateral_triangle",
            (6.0, 2.0, 0.0), (7.0, 2.0, 0.0), (6.5, 2.866025, 0.0), BONE)
b.place_tri("tail_2", "equilateral_triangle",
            (7.5, 2.866025, 0.0), (6.5, 2.866025, 0.0), (7.0, 2.0, 0.0), BONE)
b.place_tri("tail_3", "equilateral_triangle",
            (7.0, 2.0, 0.0), (8.0, 2.0, 0.0), (7.5, 2.866025, 0.0), BONE)

# =================================================================
# 4. 坑北沙地 (y [3,4]) + 观展区地面 (y [4,6])
# =================================================================
b.flat("sd3_a", 1, 3, 0.0, SAND)
b.flat("sd3_b", 4, 3, 0.0, SAND)
b.flat("sd3_c", 6, 3, 0.0, SAND)
for i, x0 in enumerate((0, 2, 4, 6)):
    b.flat_rect(f"g4_{i}", x0, 4, 0.0, STONE)
for i, x0 in enumerate((0, 2, 4, 6)):
    b.flat_rect(f"g5_{i}", x0, 5, 0.0, STONE)

# =================================================================
# 5. 观展廊桥: 拱廊 (y=5) + 北墙 (y=6) + 桥面 (z=1) + 三角旗
# =================================================================
b.add("arc_w", "window_square", (0.5, 5.0, 0.5), (90, 0, 0), GLASS)
b.add("arc_d1", "door_frame", (1.5, 5.0, 0.5), (90, 0, 0), ARCADE)
b.add("arc_d2", "door_frame", (3.5, 5.0, 0.5), (90, 0, 0), ARCADE)
b.add("arc_d3", "door_frame", (5.5, 5.0, 0.5), (90, 0, 0), ARCADE)
b.add("arc_e", "window_square", (7.5, 5.0, 0.5), (90, 0, 0), GLASS)
for i, x0 in enumerate((0, 2, 4, 6)):
    b.lintel_ns(f"nw_{i}", x0, 6.0, 0, STONE)
for i, x0 in enumerate((0, 2, 4, 6)):
    b.flat_rect(f"deck_{i}", x0, 5, 1.0, DECK)
b.crest_ns("flag_w", 0, 5.0, 1.0, FLAG)
b.crest_ns("flag_1", 1, 5.0, 1.0, FLAG)
b.crest_ns("flag_2", 3, 5.0, 1.0, FLAG)
b.crest_ns("flag_3", 5, 5.0, 1.0, FLAG)
b.crest_ns("flag_e", 7, 5.0, 1.0, FLAG)

# =================================================================
# 6. 双塔大门 (y [0,1] 两侧): 两层墙环 + 等边四坡锥 + 门楣
# =================================================================
def tower(prefix, x0, wall1, wall2):
    b.wall_ns(f"{prefix}1_s", x0, 0.0, 0, wall1)
    b.wall_ew(f"{prefix}1_e", x0 + 1.0, 0, 0, wall1)
    b.wall_ns(f"{prefix}1_n", x0, 1.0, 0, wall1)
    b.wall_ew(f"{prefix}1_w", x0 + 0.0, 0, 0, wall1)
    b.wall_ns(f"{prefix}2_s", x0, 0.0, 1, wall2)
    b.wall_ew(f"{prefix}2_e", x0 + 1.0, 0, 1, wall2)
    b.wall_ns(f"{prefix}2_n", x0, 1.0, 1, wall2)
    b.wall_ew(f"{prefix}2_w", x0 + 0.0, 0, 1, wall2)

tower("tw", 1, TOWER, TOWER2)             # 西塔 (x [1,2])
tower("te", 4, TOWER, TOWER2)             # 东塔 (x [4,5])
b.lintel_ns("gate_lintel", 2, 0.0, 1, LINTEL)   # 门楣跨 x [2,4], 双端纯剪
TW_HAT = b.hat4("tw_hat", 1, 0, 2.0, HAT, shape="equilateral_triangle")
TE_HAT = b.hat4("te_hat", 4, 0, 2.0, HAT, shape="equilateral_triangle")

# =================================================================
# 教程步骤 (18 步)
# =================================================================
b.step(
    "铺场地南行 (y [0,1]): 8 片, 沙色两格是大门门洞地。",
    [f"s0_{x}" for x in range(8)],
    tip="x [1,2] 与 [4,5] 的两格石板就是双塔的落点。",
)
b.step(
    "铺坑缘与坑南沙地: 7 片, 东缘 (7,2) 故意留空。",
    ["w_1", "w_2", "w_3", "e_1", "sd1_a", "sd1_b", "sd1_c"],
    highlight=["s0_0"],
    tip="留空的一格是挖掘沟槽 —— 恐龙尾巴会甩出坑外。",
)
b.step(
    "摆颅骨、前肢与脊柱: 5 片透明骨片嵌进坑底。",
    ["skull", "leg_f", "spine_1", "spine_2", "spine_3"],
    highlight=["w_2"],
    tip="化石是一幅平面镶嵌画 —— 头朝西, 脊柱沿坑中线向东。",
)
b.step(
    "摆骨盆、后肢与 4 根肋骨: 直角三角成对共享竖直角边。",
    ["pelvis", "leg_h", "rib_s1", "rib_s2", "rib_n1", "rib_n2"],
    highlight=["spine_2"],
    tip="每对肋骨拼成一个 V, 胸腔两侧的空半格就是挖掘负空间。",
)
b.step(
    "拼尾椎条带: 3 片等边三角斜边两两互吸, 甩出坑外。",
    ["tail_1", "tail_2", "tail_3"],
    highlight=["pelvis"],
    tip="条带只靠斜边互吸 + 底边压沙缝 —— 尾尖正好落在沟槽边。",
)
b.step(
    "铺坑北沙地与东北角石板: 4 片, 化石四周的地面合拢。",
    ["sd3_a", "sd3_b", "sd3_c", "e_3"],
    highlight=["leg_h"],
    tip="挖掘坑完成 —— 接下来在北侧给参观者搭一条空中廊桥。",
)
b.step(
    "铺观展区地面第一行 (y [4,5]): 4 片长板。",
    ["g4_0", "g4_1", "g4_2", "g4_3"],
    highlight=["sd3_a"],
    tip="长板长缝沿 y=5 一字排开, 拱廊就立在这条缝上。",
)
b.step(
    "铺观展区地面第二行 (y [5,6]): 4 片长板。",
    ["g5_0", "g5_1", "g5_2", "g5_3"],
    highlight=["g4_0"],
    tip="y=6 的北缝留给北墙长板横砌。",
)
b.step(
    "立拱廊 (y=5): 3 樘门框方 + 两端观景窗, 拱洞看向挖掘坑。",
    ["arc_w", "arc_d1", "arc_d2", "arc_d3", "arc_e"],
    highlight=["g4_1"],
    tip="门框方之间隔一格留空 —— 负空间拱洞就是画框。",
)
b.step(
    "砌北墙 (y=6): 4 片长板横砌, 底边一线双吸地板长缝。",
    ["nw_0", "nw_1", "nw_2", "nw_3"],
    highlight=["g5_0"],
    tip="相邻长板竖边互吸, 一整面墙是一个刚体。",
)
b.step(
    "架桥面 (z=1): 4 片长板双端受力 —— 南压拱廊顶北压墙顶。",
    ["deck_0", "deck_1", "deck_2", "deck_3"],
    highlight=["arc_d2", "nw_1"],
    tip="桥面零悬挑, 站上去俯瞰全坑 —— 这就是观展廊桥。",
)
b.step(
    "插了望三角旗: 5 片等边三角立上拱廊顶缝。",
    ["flag_w", "flag_1", "flag_2", "flag_3", "flag_e"],
    highlight=["deck_0"],
    tip="旗子底边正好吸住拱廊顶边 + 桥面南缘的直角缝。",
)
b.step(
    "砌西塔第 1 层墙环: 4 片红色立墙四角竖边闭环。",
    ["tw1_s", "tw1_e", "tw1_n", "tw1_w"],
    highlight=["s0_1"],
    tip="塔就骑在南行石板的四条边缝上。",
)
b.step(
    "砌西塔第 2 层墙环: 4 片紫色竖叠, 层间四缝互为冗余。",
    ["tw2_s", "tw2_e", "tw2_n", "tw2_w"],
    highlight=["tw1_s"],
    tip="任断一条竖叠缝, 力仍经其余三条绕行。",
)
b.step(
    "砌东塔第 1 层墙环: 4 片, 与西塔隔出 2 格门洞。",
    ["te1_s", "te1_e", "te1_n", "te1_w"],
    highlight=["tw1_e"],
    tip="门洞 x [2,4] 是负空间 —— 门楣下一步凌空锁定。",
)
b.step(
    "砌东塔第 2 层墙环: 4 片, 双塔等高。",
    ["te2_s", "te2_e", "te2_n", "te2_w"],
    highlight=["te1_s"],
    tip="两座塔的第 2 层墙角就是门楣的锚点。",
)
b.step(
    "架门楣 + 收西塔锥顶: 门楣双端竖边纯剪锁进塔身。",
    ["gate_lintel"] + TW_HAT,
    highlight=["tw2_e", "te2_w"],
    tip="门楣跨过 2 格门洞, 剪断任一端仍经另一端绕行。",
)
b.step(
    "收东塔锥顶 —— 恐龙化石挖掘展厅开放!",
    TE_HAT,
    highlight=["gate_lintel"],
    tip="双塔金锥等高对望, 大门正对挖掘坑与化石全貌。",
)

b.finalize(
    model_id="dinosaur_hall_01",
    name="恐龙化石挖掘展厅",
    name_en="Dinosaur Fossil Hall 01",
    description=(
        "全库第一座考古挖掘现场: 恐龙化石不站起来, 而是一幅平卧坑底"
        "的平面镶嵌画 —— 方形颅骨脊柱、直角三角肋骨成对拼 V 形胸腔、"
        "等边尾椎条带斜边互吸甩出坑外, 坑内留白半格是挖掘沟槽的负"
        "空间; 北侧门框方拱廊托起架空观展廊桥 (桥面双端受力零悬挑)"
        "俯瞰全坑; 南侧双塔大门两层墙环竖叠、门楣双端纯剪、等边四"
        "坡锥收顶 —— 与立姿霸王龙骨架完全不同的恐龙叙事。"
    ),
    difficulty=4,
    tags=["博物馆", "恐龙化石", "挖掘现场", "考古", "进阶"],
    min_pieces=82,
    min_steps=18,
)
