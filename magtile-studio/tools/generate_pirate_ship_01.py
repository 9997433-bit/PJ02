#!/usr/bin/env python3
"""生成模型 data/models/pirate_ship_01.json (海盗船与藏宝码头)。

内容批 G 模型 3/4: 全库第一艘海盗船。海空交通已有双体帆船 (甲板
桥连双浮筒)/集装箱货轮 (三层箱形环+箱堆)/阳光游轮 (逐级退台)/
龙舟 (六边形龙头)/拖网渔船 (浮码头靠泊), 本作与它们全部错开:
结构签名是"艉楼两层 + 舷侧炮窗 + 30 度登船跳板" —— 船尾在主甲板
上再起一层船长舱 (艉楼), 船长室两扇窗格方朝着船尾海面; 两舷各嵌
两扇灰色窗格方当炮窗 (窗格方语义开洞、物理实心, 正是打炮的好窗);
船艏一条 30 度长板跳板顶边整边铰甲板东沿、坡尾压在浮码头板上,
海盗们扛着宝箱沿跳板上船 —— 码头上还留着最后一只紫色大宝箱!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 船艏朝东):
  - 海面与船底: 南北浪带 10 + 西侧海面 2 + 船底舱板 10        22 片
  - 浮码头 (x [6,8], y [1,3]): 4 片黄色码头板                  4 片
  - 船体墙环 (x [1,6], y [1,3], z 0..1): 10 舷墙 + 4 炮窗     14 片
  - 主甲板 (z=1): 10 片方板                                  10 片
  - 艉楼 (x [1,2], z 1..2): 墙环 6 (含 2 舷窗) + 顶板 2       8 片
  - 艉楼甲板装饰: 船尾栏杆 + 海盗队旗 (瘦高尖)                 2 片
  - 主桅: L 形互咬双层墙 4 + 大帆 (瘦高) + 小帆 (等边)         6 片
  - 登船跳板 + 船艏破浪尖 + 鹦鹉                               3 片
  - 大宝箱 (码头上, 四墙 + 盖板)                               5 片
  合计 74 片, 13 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告 + jitter 50 全绿):
  - 船体墙环墙脚全部踩船底舱板拼缝, 四角竖边互咬闭环;
  - 主甲板方板边边入扣墙顶并互吸, 艉楼与主桅墙脚全踩甲板拼缝;
  - 跳板顶边整边吸甲板东沿, 坡尾压在码头板上 —— 顶铰链 +
    接地坡尾双路受力 (城堡投石机长臂同款);
  - 主桅两片墙竖边直角互咬 (L 形), 双层同位叠放, 互咬棱一通
    到顶, 帆片底边整边吸桅顶沿;
  - 炮窗/舷窗按实心正方形受力, 开洞只是语义标记;
  - 栏杆/队旗/破浪尖/鹦鹉全部骑拼缝, 剪任一装饰最多失联 1 片。

用法: python3 tools/generate_pirate_ship_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

SEA = "blue"        # 海面
WAVE = "cyan"       # 浪花
BILGE = "orange"    # 船底舱板
HULL = "orange"     # 船体舷墙
PORT = "gray"       # 炮窗
DECK = "yellow"     # 木甲板
CABIN = "orange"    # 艉楼
CWIN = "yellow"     # 船长室舷窗
RAIL = "red"        # 船尾栏杆
FLAG = "gray"       # 海盗队旗
MAST = "orange"     # 主桅
SAIL = "clear"      # 船帆
PLANK = "yellow"    # 登船跳板
PROW = "red"        # 船艏破浪尖
PARROT = "green"    # 鹦鹉
PIER = "yellow"     # 浮码头
CHEST = "purple"    # 大宝箱
LID = "yellow"      # 宝箱盖

# =================================================================
# 1. 海面: 南北浪带 (方板锚点 + 长板连排) 与西侧海面
# =================================================================
b.flat("sea_s_0", 0, 0, 0.0, SEA)
b.flat_rect("sea_s_1", 1, 0, 0.0, SEA)
b.flat_rect("sea_s_3", 3, 0, 0.0, SEA)
b.flat_rect("sea_s_5", 5, 0, 0.0, SEA)
b.flat("sea_s_7", 7, 0, 0.0, SEA)
b.flat("sea_n_0", 0, 3, 0.0, SEA)
b.flat_rect("sea_n_1", 1, 3, 0.0, SEA)
b.flat_rect("sea_n_3", 3, 3, 0.0, SEA)
b.flat_rect("sea_n_5", 5, 3, 0.0, SEA)
b.flat("sea_n_7", 7, 3, 0.0, SEA)
b.flat("sea_w_1", 0, 1, 0.0, SEA)
b.flat("sea_w_2", 0, 2, 0.0, SEA)

# 船底舱板 (x [1,6], y [1,3]): 舷墙墙脚的拼缝锚点
for x in range(1, 6):
    b.flat(f"bilge_{x}_1", x, 1, 0.0, BILGE)
    b.flat(f"bilge_{x}_2", x, 2, 0.0, BILGE)

# 浮码头 (x [6,8], y [1,3])
b.flat("pier_sw", 6, 1, 0.0, PIER)
b.flat("pier_se", 7, 1, 0.0, PIER)
b.flat("pier_nw", 6, 2, 0.0, PIER)
b.flat("pier_ne", 7, 2, 0.0, PIER)

# =================================================================
# 2. 船体墙环 (x [1,6], y [1,3], z 0..1): 两舷各嵌两扇灰炮窗
# =================================================================
b.wall_ns("hull_s_1", 1, 1.0, 0, HULL)
b.add("hull_s_2", "window_square", (2.5, 1.0, 0.5), (90, 0, 0), PORT)
b.wall_ns("hull_s_3", 3, 1.0, 0, HULL)
b.add("hull_s_4", "window_square", (4.5, 1.0, 0.5), (90, 0, 0), PORT)
b.wall_ns("hull_s_5", 5, 1.0, 0, HULL)
b.wall_ns("hull_n_1", 1, 3.0, 0, HULL)
b.add("hull_n_2", "window_square", (2.5, 3.0, 0.5), (90, 0, 0), PORT)
b.wall_ns("hull_n_3", 3, 3.0, 0, HULL)
b.add("hull_n_4", "window_square", (4.5, 3.0, 0.5), (90, 0, 0), PORT)
b.wall_ns("hull_n_5", 5, 3.0, 0, HULL)
b.wall_ew("hull_w_s", 1.0, 1, 0, HULL)
b.wall_ew("hull_w_n", 1.0, 2, 0, HULL)
b.wall_ew("hull_e_s", 6.0, 1, 0, HULL)
b.wall_ew("hull_e_n", 6.0, 2, 0, HULL)

# =================================================================
# 3. 主甲板 (z=1): 十片黄色方板边边入扣墙顶
# =================================================================
for x in range(1, 6):
    b.flat(f"deck_{x}_1", x, 1, 1.0, DECK)
    b.flat(f"deck_{x}_2", x, 2, 1.0, DECK)

# =================================================================
# 4. 艉楼 (x [1,2], y [1,3], z 1..2): 船长室两扇舷窗朝船尾
# =================================================================
b.wall_ns("cab_s", 1, 1.0, 1, CABIN)
b.wall_ns("cab_n", 1, 3.0, 1, CABIN)
b.add("cab_w_s", "window_square", (1.0, 1.5, 1.5), (90, 0, 90), CWIN)
b.add("cab_w_n", "window_square", (1.0, 2.5, 1.5), (90, 0, 90), CWIN)
b.wall_ew("cab_e_s", 2.0, 1, 1, CABIN)
b.wall_ew("cab_e_n", 2.0, 2, 1, CABIN)
b.flat("cab_top_s", 1, 1, 2.0, DECK)
b.flat("cab_top_n", 1, 2, 2.0, DECK)
b.crest_ns("rail", 1, 1.0, 2.0, RAIL)          # 船尾栏杆骑南沿
b.spire_ns("flag", 1, 3.0, 2.0, FLAG)          # 海盗队旗骑北沿, 尖 3.94

# =================================================================
# 5. 主桅: L 形互咬双层墙, 大帆小帆挂桅顶 (帆尖 5.0 全场最高)
# =================================================================
b.wall_ns("mast_a1", 3, 2.0, 1, MAST)
b.wall_ew("mast_b1", 4.0, 2, 1, MAST)
b.wall_ns("mast_a2", 3, 2.0, 2, MAST)
b.wall_ew("mast_b2", 4.0, 2, 2, MAST)
b.spire_ns("sail_main", 3, 2.0, 3.0, SAIL)     # 大帆 (瘦高), 尖 5.0
b.crest_ew("sail_top", 4.0, 2, 3.0, SAIL)      # 小帆 (等边)

# =================================================================
# 6. 登船跳板 + 船艏破浪尖 + 鹦鹉
# =================================================================
b.ramp("plank", "+x", 6.0, 1, 1.0, PLANK)      # 顶边铰甲板东沿, 坡尾压码头
b.crest_ew("prow", 6.0, 2, 1.0, PROW)          # 破浪尖骑船艏沿口
b.crest_ns("parrot", 5, 2.0, 1.0, PARROT)      # 鹦鹉骑甲板拼缝

# =================================================================
# 7. 大宝箱 (码头东北角, 四墙 + 盖板)
# =================================================================
b.wall_ns("chest_s", 7, 2.0, 0, CHEST)
b.wall_ns("chest_n", 7, 3.0, 0, CHEST)
b.wall_ew("chest_w", 7.0, 2, 0, CHEST)
b.wall_ew("chest_e", 8.0, 2, 0, CHEST)
b.flat("chest_lid", 7, 2, 1.0, LID)

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺船底舱板: 十片橙色方板两行互吸, 这是海盗船的龙骨地盘。",
    ["bilge_1_1", "bilge_2_1", "bilge_3_1", "bilge_4_1", "bilge_5_1",
     "bilge_1_2", "bilge_2_2", "bilge_3_2", "bilge_4_2", "bilge_5_2"],
    tip="出海寻宝喽! 舷墙的墙脚全要踩在这些舱板拼缝上。",
)
b.step(
    "接浮码头: 四片黄色码头板贴住船底东沿。",
    ["pier_sw", "pier_se", "pier_nw", "pier_ne"],
    highlight=["bilge_5_1"],
    tip="板板等边互吸 —— 跳板的坡尾待会儿要压在码头上。",
)
b.step(
    "铺南侧浪带与西侧海面: 方板当锚点, 长板连排。",
    ["sea_s_0", "sea_s_1", "sea_s_3", "sea_s_5", "sea_s_7",
     "sea_w_1", "sea_w_2"],
    highlight=["bilge_1_1"],
    tip="长板的短边正好和方板整边等长 —— 海面一格格连成片。",
)
b.step(
    "铺北侧浪带: 海面围合, 船坞就位。",
    ["sea_n_0", "sea_n_1", "sea_n_3", "sea_n_5", "sea_n_7"],
    highlight=["sea_w_2"],
    tip="蓝色的海面把船底围在中间 —— 就等船身立起来了。",
)
b.step(
    "立两舷舷墙: 南北各五片, 灰色窗格方就是炮窗。",
    ["hull_s_1", "hull_s_2", "hull_s_3", "hull_s_4", "hull_s_5",
     "hull_n_1", "hull_n_2", "hull_n_3", "hull_n_4", "hull_n_5"],
    highlight=["bilge_2_1"],
    tip="炮窗物理上按实心方片受力 —— 开洞只是给大炮留的观察口。",
)
b.step(
    "合艏艉端墙: 四片墙把船体锁成闭环。",
    ["hull_w_s", "hull_w_n", "hull_e_s", "hull_e_n"],
    highlight=["hull_s_1"],
    tip="四角竖边互咬 —— 箱形船体是全船的承重主环。",
)
b.step(
    "铺主甲板: 十片黄色方板边边入扣墙顶, 板板互吸。",
    ["deck_1_1", "deck_2_1", "deck_3_1", "deck_4_1", "deck_5_1",
     "deck_1_2", "deck_2_2", "deck_3_2", "deck_4_2", "deck_5_2"],
    highlight=["hull_s_1"],
    tip="甲板拼缝就是艉楼和主桅的墙脚锚点。",
)
b.step(
    "起艉楼墙环: 六片墙骑在船尾甲板上, 两扇黄窗格方朝着船尾。",
    ["cab_s", "cab_n", "cab_w_s", "cab_w_n", "cab_e_s", "cab_e_n"],
    highlight=["deck_1_1"],
    tip="这是船长室 —— 船长透过尾窗盯着海平线上的追兵。",
)
b.step(
    "盖艉楼甲板, 立栏杆与队旗: 红栏杆骑南沿, 灰队旗骑北沿。",
    ["cab_top_s", "cab_top_n", "rail", "flag"],
    highlight=["cab_s"],
    tip="队旗一升, 全海都认得这艘船 —— 艉楼比主甲板还高一层!",
)
b.step(
    "竖主桅: 两片墙竖边直角互咬成 L 形, 再同位叠高一层。",
    ["mast_a1", "mast_b1", "mast_a2", "mast_b2"],
    highlight=["deck_3_1"],
    tip="L 形折边就是桅杆的靠山 —— 直角互咬, 天生抗侧。",
)
b.step(
    "挂帆: 大帆骑主桅南沿一通到顶, 小帆挂在东侧桅顶。",
    ["sail_main", "sail_top"],
    highlight=["mast_a2"],
    tip="白帆鼓风, 帆尖 5.0 全场最高 —— 起航!",
)
b.step(
    "搭登船跳板, 装破浪尖, 请鹦鹉就位。",
    ["plank", "prow", "parrot"],
    highlight=["deck_5_1", "pier_se"],
    tip="跳板顶边铰甲板、坡尾压码头, 重量走两条路 —— 稳稳当当扛宝箱。",
)
b.step(
    "码头上摆大宝箱: 四片紫墙围成箱环, 黄盖板扣顶。",
    ["chest_s", "chest_n", "chest_w", "chest_e", "chest_lid"],
    highlight=["pier_ne"],
    tip="最后一只宝箱还没搬上船 —— 里面装的是金币还是彩虹糖?",
)

b.finalize(
    model_id="pirate_ship_01",
    name="海盗船与藏宝码头",
    name_en="Pirate Ship 01",
    description=(
        "只用核心九片型的全库第一艘海盗船: 与双体帆船 (甲板桥连双"
        "浮筒)/集装箱货轮 (三层箱形环)/阳光游轮 (逐级退台) 全部错开, "
        "结构签名是'艉楼两层 + 舷侧炮窗 + 30 度登船跳板' —— 船尾在"
        "主甲板上再起一层船长室, 两扇黄窗格方尾窗盯着海平线; 两舷各嵌"
        "两扇灰色窗格方当炮窗; 船艏跳板顶边整边铰甲板东沿、坡尾压在"
        "浮码头板上, 重量走两条路; 主桅 L 形互咬双层墙挂起大小白帆, "
        "帆尖 5.0 全场最高; 码头上还留着最后一只紫色大宝箱 —— 鹦鹉"
        "喊: 起航寻宝喽!"
    ),
    difficulty=3,
    tags=["海洋", "海盗船", "帆船", "宝箱", "码头", "进阶"],
    min_pieces=74,
    min_steps=13,
)
