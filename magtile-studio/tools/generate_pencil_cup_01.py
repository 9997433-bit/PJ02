#!/usr/bin/env python3
"""生成模型 data/models/pencil_cup_01.json (高低双筒笔筒)。

D1 补员批 2 模型 3/4 (难度配额解冻线 D1 >= 20, 路径 B1): 入门档
实用功能选题 —— 书桌上的高低双筒笔筒。结构签名是"高低开顶
双筒": 两层高的铅笔主筒 (上层窗格方透出笔身) + 一层高的便签
矮筒, 中间夹一对便签夹立三角, 北沿三面草绿灌木一排; 与杯垫台
(闭合箱体) 恰好相反 —— 本作全部筒腔开顶, 孩子搭完就能把真铅笔
插进去。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 桌垫 6 片方板棋盘 (x [0,3], y [0,2])                 6 片
  - 铅笔主筒第一层 4 片方板 (格 [0,1]x[0,1], z 0..1)     4 片
  - 铅笔主筒第二层 4 片窗格方 (z 1..2, 上下整边贴合)     4 片
  - 便签矮筒 4 片方板 (格 [2,3]x[0,1], z 0..1)           4 片
  - 便签夹立三角 x2 (骑 x=1 / x=2 拼缝, y [1,2] 段)      2 片
  - 北沿灌木 x3 (等边三角骑板端整边)                     3 片
  - 铅笔 (透明等腰三角, 立便签矮筒北沿)                  1 片
  合计 24 片, 7 个教程步骤, 4 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 筒身四片墙两两竖棱角缝互吸成环 (R8 意义上的闭合圈层),
    第二层与第一层上下整边贴合, 全程受压;
  - 窗格方外框与正方形完全一致, 物理按实心方板校验
    (docs/TILE_SET.md), 窗格只是能看到笔身的造型语义;
  - 立三角/灌木/铅笔重心正压铰链线, 力矩为零;
  - 最高点 3.0 (铅笔尖) 触发 R8 高层判定, 但双筒环环相扣
    (闭合圈层), 单点失效与无环拓扑均不成立, 零警告;
  - 便签夹避开筒墙所在的 y [0,1] 段, 与筒墙同平面不同区段,
    共面 SAT 重叠深度为零 (R3)。

用法: python3 tools/generate_pencil_cup_01.py  (在 magtile-studio 目录下运行)
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

MAT_A = "gray"      # 桌垫方板 (深)
MAT_B = "yellow"    # 桌垫方板 (浅)
CUP_LO = "blue"     # 主筒第一层
CUP_HI = "cyan"     # 主筒第二层 (窗格方)
TRAY = "orange"     # 便签矮筒
CLIP = "red"        # 便签夹立三角
BUSH = "green"      # 北沿灌木
PEN = "clear"       # 铅笔


def wall_ns_t(tile_id, tile_type, x0, y, z0, color):
    """南北朝向立墙 (自定义片型: 窗格方等外框同正方形的变体)。"""
    b.add(tile_id, tile_type, (x0 + 0.5, y, z0 + 0.5), (90, 0, 0), color)


def wall_ew_t(tile_id, tile_type, x, y0, z0, color):
    """东西朝向立墙 (自定义片型)。"""
    b.add(tile_id, tile_type, (x, y0 + 0.5, z0 + 0.5), (90, 0, 90), color)


# =================================================================
# 1. 桌垫: 六片方板棋盘 (x [0,3], y [0,2])
# =================================================================
for gx in range(3):
    for gy in range(2):
        color = MAT_A if (gx + gy) % 2 == 0 else MAT_B
        b.flat(f"mat_{gx}_{gy}", gx, gy, 0.0, color)

# =================================================================
# 2. 铅笔主筒第一层 (格 [0,1]x[0,1], z 0..1)
# =================================================================
b.wall_ns("cup_s0", 0, 0.0, 0, CUP_LO)
b.wall_ns("cup_n0", 0, 1.0, 0, CUP_LO)
b.wall_ew("cup_w0", 0.0, 0, 0, CUP_LO)
b.wall_ew("cup_e0", 1.0, 0, 0, CUP_LO)

# =================================================================
# 3. 铅笔主筒第二层 (窗格方, z 1..2, 上下整边贴合)
# =================================================================
wall_ns_t("cup_s1", "window_square", 0, 0.0, 1, CUP_HI)
wall_ns_t("cup_n1", "window_square", 0, 1.0, 1, CUP_HI)
wall_ew_t("cup_w1", "window_square", 0.0, 0, 1, CUP_HI)
wall_ew_t("cup_e1", "window_square", 1.0, 0, 1, CUP_HI)

# =================================================================
# 4. 便签矮筒 (格 [2,3]x[0,1], z 0..1)
# =================================================================
b.wall_ns("tray_s", 2, 0.0, 0, TRAY)
b.wall_ns("tray_n", 2, 1.0, 0, TRAY)
b.wall_ew("tray_w", 2.0, 0, 0, TRAY)
b.wall_ew("tray_e", 3.0, 0, 0, TRAY)

# =================================================================
# 5. 便签夹立三角 (骑 x=1 / x=2 拼缝的 y [1,2] 段, 避开筒墙)
# =================================================================
b.crest_ew("clip_w", 1.0, 1, 0.0, CLIP)
b.crest_ew("clip_e", 2.0, 1, 0.0, CLIP)

# =================================================================
# 6. 北沿灌木 x3 (骑长板北端整边)
# =================================================================
b.crest_ns("bush_0", 0, 2.0, 0.0, BUSH)
b.crest_ns("bush_1", 1, 2.0, 0.0, BUSH)
b.crest_ns("bush_2", 2, 2.0, 0.0, BUSH)

# =================================================================
# 7. 铅笔 (透明等腰三角, 立便签矮筒北墙顶沿)
# =================================================================
b.spire_ns("pencil", 2, 1.0, 1.0, PEN)

# =================================================================
# 教程步骤 (7 步)
# =================================================================
b.step(
    "铺桌垫: 六片灰黄棋盘方板逐片整边互吸, 铺成 3x2 的地基。",
    ["mat_0_0", "mat_0_1", "mat_1_0", "mat_1_1", "mat_2_0", "mat_2_1"],
    tip="棋盘颜色错开铺, 拼缝正好留给筒墙和便签夹踩。",
)
b.step(
    "起铅笔主筒第一层: 四片蓝色方板合围左前格, 竖棱角缝两两互吸。",
    ["cup_s0", "cup_e0", "cup_n0", "cup_w0"],
    highlight=["mat_0_0"],
    tip="四片墙围成环, 推一下整筒一起动才算吸对。",
)
b.step(
    "主筒加高第二层: 四片青色窗格方上下整边贴合, 窗格里能看到笔身。",
    ["cup_s1", "cup_e1", "cup_n1", "cup_w1"],
    highlight=["cup_s0"],
    tip="窗格方外框和方板一模一样, 吸法完全相同。",
)
b.step(
    "围便签矮筒: 四片橙色方板合围右前格, 一层高刚好露出便签头。",
    ["tray_s", "tray_e", "tray_n", "tray_w"],
    highlight=["mat_2_0"],
)
b.step(
    "夹便签夹: 两片红色立三角骑住中间两条拼缝的后半段。",
    ["clip_w", "clip_e"],
    highlight=["mat_1_1"],
    tip="立三角骑缝而立, 一格缝隙正好夹住课程表。",
)
b.step(
    "种北沿灌木: 三片草绿三角骑住桌垫北沿整边, 书桌也要有绿意。",
    ["bush_0", "bush_1", "bush_2"],
    highlight=["mat_0_1", "mat_2_1"],
)
b.step(
    "插铅笔收尾: 透明等腰三角立上矮筒北沿 —— 笔筒开张, 请真铅笔入住主筒!",
    ["pencil"],
    highlight=["tray_n"],
    tip="铅笔重心正压沿口, 站得笔直。",
)

model = b.finalize(
    model_id="pencil_cup_01",
    name="高低双筒笔筒",
    name_en="Pencil Cup 01",
    description=(
        "入门档实用功能: 书桌上的高低双筒笔筒, 结构签名是'高低开顶"
        "双筒' —— 两层高的铅笔主筒四片墙竖棱角缝互吸成环, 第二层"
        "换窗格方透出笔身, 旁边一层高的便签矮筒露出便签头, 中间"
        "两条拼缝各骑一片红色便签夹立三角, 北沿三片草绿灌木一排, "
        "透明'铅笔'立在矮筒沿上等真铅笔来换岗; 与封顶的杯垫台相反, "
        "本作全部筒腔开顶 —— 24 片搭完就能把整盒彩笔请进去。"
    ),
    difficulty=1,
    tags=["实用功能", "笔筒", "书桌", "文具", "入门"],
    min_pieces=24,
    min_steps=7,
)

# ---- series 归类落盘 (CONTENT_STRATEGY.md 4.3 节: 入库必填) --------
out = Path(__file__).resolve().parent.parent / "data" / "models" / "pencil_cup_01.json"
model["content_meta"] = {
    "series": "practical_utility",
    "structural_signature": model["content_meta"]["structural_signature"],
}
out.write_text(json.dumps(model, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
print("已写入 series=practical_utility")
