#!/usr/bin/env python3
"""生成模型 data/models/sailboat_01.json (双体帆船)。

第二批模型 ⑥: 海洋主题 —— 蓝色海面上的双体帆船 (катamaran):
两条 4 格长的浮筒船体由 2x2 中央甲板连成一体, 双层主桅两侧
各挂 3 面透明三角帆, 船艏立着高高的破浪尖, 艉部一面六边形
舵轮台。全库第一艘"下水"的船。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 海面: 6x5 蓝青波纹棋盘                                      30 片
  - 浮筒船体 x2: 四周立墙 10 + 筒面甲板 4 (每条 14 片)           28 片
  - 中央甲板: 2x2 桥接两条船体                                    4 片
  - 主桅: 双层立墙 + 桅顶信号旗                                   3 片
  - 船帆 x4: 每舷长方形主帆 (1 宽 2 高) + 直角三角前帆            4 片
  - 舵轮台: 六边形竖立在中央甲板艉沿                              1 片
  - 船艏破浪尖 x2 + 船艉信号旗 x2                                 4 片
  合计 24 + 28 + 4 + 3 + 4 + 1 + 4 = 68 片, 15 个教程步骤。

物理规则要点 (通过 R1~R8 全部校验):
  - 船体立墙底边吸海面接缝, 甲板四边压墙顶成环;
  - 中央甲板短边分别吸两条船体的内舷墙顶, 双船成刚性整体;
  - 前帆水平边吸甲板接缝、竖直边吸桅杆竖边 (三角刚性节点);
    主帆直接立在甲板接缝上, 不给桅杆上层接头增加负担 —— 桅顶
    只挂一面信号旗, 规避高层单点失效警告。

用法: python3 tools/generate_sailboat.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

# =================================================================
# 1. 海面: 6x4 蓝青波纹棋盘 (x 0..6, y 0..4)
# =================================================================
for j in range(4):
    for i in range(6):
        b.flat(f"sea_{i}_{j}", i, j, 0.0, "blue" if (i + j) % 2 == 0 else "cyan")

# =================================================================
# 2. 浮筒船体 x2: 南筒 (1..5, 0..1), 北筒 (1..5, 3..4)
#    每条: 外舷 4 + 内舷 4 + 艏艉端板 2 + 筒面甲板 4
# =================================================================
for name, y_out, y_in, y0 in (("s", 0.0, 1.0, 0), ("n", 4.0, 3.0, 3)):
    for i in range(1, 5):
        b.wall_ns(f"hull_{name}_o{i}", i, y_out, 0, "gray")
    for i in range(1, 5):
        b.wall_ns(f"hull_{name}_i{i}", i, y_in, 0, "gray")
    b.wall_ew(f"hull_{name}_stern", 1.0, y0, 0, "red")   # 船艉端板 (西)
    b.wall_ew(f"hull_{name}_bow", 5.0, y0, 0, "red")     # 船艏端板 (东)
    for i in range(1, 5):
        b.flat(f"deck_{name}_{i}", i, y0, 1.0, "orange" if i % 2 else "yellow")

# =================================================================
# 3. 中央甲板: 2x2 (2..4, 1..3) 桥接两条船体内舷墙顶
# =================================================================
for j in (1, 2):
    for i in (2, 3):
        b.flat(f"mid_{i}_{j}", i, j, 1.0, "yellow" if (i + j) % 2 else "orange")

# =================================================================
# 4. 主桅 (平面 x=3, y 1..2): 双层立墙 + 桅顶信号旗
# =================================================================
b.wall_ew("mast_1", 3.0, 1, 1, "gray")
b.wall_ew("mast_2", 3.0, 1, 2, "gray")
b.crest_ew("mast_flag", 3.0, 1, 3.0, "red")

# =================================================================
# 5. 船帆 x4: 每舷 1 面长方形主帆 + 1 面直角三角形前帆 (透明)
#    主帆: 1 宽 2 高竖立在甲板接缝上 (桅杆后方), 底短边整边吸合;
#    前帆: 水平边吸甲板接缝、竖直边吸桅杆竖边 (三角刚性节点)
# =================================================================
b.place_edge("sail_s_main", "rectangle", 1, (2.0, 1.0, 1.0), (3.0, 1.0, 1.0),
             (0, 0, 1), "clear")
b.place_edge("sail_n_main", "rectangle", 1, (2.0, 2.0, 1.0), (3.0, 2.0, 1.0),
             (0, 0, 1), "clear")
b.brace("sail_s_fore", (3.0, 1.0, 1.0), "+x", "clear")
b.brace("sail_n_fore", (3.0, 2.0, 1.0), "+x", "clear")

# =================================================================
# 6. 舵轮台 + 船艏破浪尖 + 船艉信号旗
# =================================================================
b.add("helm", "hexagon", (2.0, 1.5, 1.0 + 0.866025), (90, 0, 90), "purple")
b.spire_ew("bow_spike_s", 5.0, 0, 1.0, "red")    # 南筒破浪尖 (等腰三角)
b.spire_ew("bow_spike_n", 5.0, 3, 1.0, "red")
b.crest_ew("stern_fl_s", 1.0, 0, 1.0, "pink")    # 南筒艉旗
b.crest_ew("stern_fl_n", 1.0, 3, 1.0, "pink")

# =================================================================
# 教程步骤 (15 步)
# =================================================================
b.step(
    "铺设海面西半部: 3x4 共 12 片蓝青相间正方形。",
    [f"sea_{i}_{j}" for j in range(4) for i in range(3)],
    tip="海面棋盘就是船坞: 双体船的两条浮筒将立在它的接缝上。",
)
b.step(
    "铺设海面东半部 12 片, 6x4 海面完工。",
    [f"sea_{i}_{j}" for j in range(4) for i in range(3, 6)],
    highlight=[f"sea_2_{j}" for j in range(4)],
    tip="铺完检查一遍接缝: 波纹颜色应交替出现。",
)
b.step(
    "竖立南浮筒外舷与内舷: 沿 y=0 与 y=1 接缝各立 4 片灰色墙。",
    [f"hull_s_o{i}" for i in range(1, 5)] + [f"hull_s_i{i}" for i in range(1, 5)],
    highlight=["sea_1_0", "sea_4_0"],
    tip="外舷内舷平行相对, 相邻墙片竖边互吸 —— 这是一条 4 格长的浮筒。",
)
b.step(
    "封南浮筒艏艉端板: 东西两端各立 1 片红色端板, 转角竖边互吸。",
    ["hull_s_stern", "hull_s_bow"],
    highlight=["hull_s_o1", "hull_s_o4"],
    tip="端板一封, 浮筒就从两排墙变成一个刚性长盒。",
)
b.step(
    "盖南浮筒甲板: 4 片筒面板压住四周墙顶。",
    [f"deck_s_{i}" for i in range(1, 5)],
    highlight=["hull_s_o2", "hull_s_i2"],
    tip="每片甲板至少压住两条墙顶边; 铺完筒面应平整无缝。",
)
b.step(
    "竖立北浮筒外舷与内舷 (8 片), 与南浮筒镜像。",
    [f"hull_n_o{i}" for i in range(1, 5)] + [f"hull_n_i{i}" for i in range(1, 5)],
    highlight=["sea_1_3", "sea_4_3"],
    tip="对照南浮筒逐片检查位置 —— 双体船全靠两筒严格对称。",
)
b.step(
    "封北浮筒端板 2 片。",
    ["hull_n_stern", "hull_n_bow"],
    highlight=["hull_n_o1", "hull_n_o4"],
    tip="与南浮筒相同: 端板让浮筒成为刚性长盒。",
)
b.step(
    "盖北浮筒甲板 4 片。",
    [f"deck_n_{i}" for i in range(1, 5)],
    highlight=["hull_n_o2", "hull_n_i2"],
    tip="两条浮筒此刻还各自独立 —— 下一步就把它们连成一条船。",
)
b.step(
    "架设中央甲板: 2x2 共 4 片横跨两筒之间, 南北两边分别压住两条浮筒的"
    "内舷墙顶。",
    ["mid_2_1", "mid_3_1", "mid_2_2", "mid_3_2"],
    highlight=["hull_s_i2", "hull_n_i2"],
    tip="先铺贴南筒的两片再铺北侧; 桥面装完, 双体船成为一个刚性整体。",
)
b.step(
    "竖立主桅: 中央甲板正中接缝上叠 2 片灰色立墙, 桅顶立红色信号旗。",
    ["mast_1", "mast_2", "mast_flag"],
    highlight=["mid_2_1", "mid_3_1"],
    tip="桅杆立在甲板十字接缝上, 底边整边吸合; 它要挂起全部 6 面帆。",
)
b.step(
    "挂南舷两面透明帆: 长方形主帆竖立在桅杆后方的甲板接缝上 (1 宽 2 高, "
    "底边整边吸合); 三角前帆水平边吸甲板接缝、竖直边吸桅杆竖边。",
    ["sail_s_main", "sail_s_fore"],
    highlight=["mast_1", "mast_2"],
    tip="前帆是三角刚性节点 (双边吸合); 主帆高过桅顶一线, 斜阳下最好看。",
)
b.step(
    "挂北舷两面帆, 与南舷镜像。",
    ["sail_n_main", "sail_n_fore"],
    highlight=["mast_1", "mast_2"],
    tip="四面帆张开后, 从正前方看是一个对称的帆影。",
)
b.step(
    "安装舵轮台: 紫色六边形竖立在中央甲板艉沿, 底边整边吸合。",
    ["helm"],
    highlight=["mid_2_1", "mid_2_2"],
    tip="六边形立面就是船长的舵轮台 —— 它与桅杆同在船的中轴线上。",
)
b.step(
    "装船艏破浪尖: 两条浮筒艏端甲板沿各立 1 片红色等腰三角, 尖头朝天。",
    ["bow_spike_s", "bow_spike_n"],
    highlight=["deck_s_4", "deck_n_4"],
    tip="高高的破浪尖standing在船艏, 是双体帆船最精神的剪影。",
)
b.step(
    "挂船艉信号旗 2 片, 双体帆船离港起航!",
    ["stern_fl_s", "stern_fl_n"],
    highlight=["deck_s_1", "deck_n_1"],
    tip="轻推海面, 整条船应连同帆桅一起联动 —— 这就是刚性船体。",
)

b.finalize(
    model_id="sailboat_01",
    name="双体帆船",
    name_en="Catamaran Sailboat 01",
    description=(
        "海洋主题: 蓝青波纹海面上, 两条 4 格长的刚性浮筒由 2x2 中央甲板桥接成"
        "双体船, 双层主桅两侧挂 6 面透明三角帆 (下层帆双边吸合成三角刚性节点), "
        "艉部立紫色六边形舵轮台, 船艏一对破浪尖直指前方 —— 全库第一艘下水的船。"
    ),
    difficulty=3,
    tags=["帆船", "海洋", "交通工具", "进阶"],
    min_pieces=65,
    min_steps=15,
)
