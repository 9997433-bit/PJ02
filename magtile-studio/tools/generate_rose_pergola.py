#!/usr/bin/env python3
"""生成模型 data/models/rose_pergola_01.json (玫瑰花藤长廊)。

植物花园主题扩充: 与温室花房 (封闭玻璃盒) 和空中花园 (层叠平台)
的结构逻辑都不同 —— 本作是"门式框架长廊": 两排绿篱格栅墙夹出一条
能走通的花园走道, 三根横梁平板隔一空一地桥在两排墙顶上, 每个
梁-墙节点上都攀着一朵玫瑰; 阳光从梁间的空档漏下来, 在走道上
画出一条条光带 —— 全库唯一的"隔空横梁花架"。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 长廊沿东西向):
  - 长廊走道 (x [0,5], y [0,2]): 清灰棋盘方板两排              10 片
  - 绿篱格栅墙两排 (y=0 与 y=2, z 0..1): 绿色方板与清色
    窗格方相间, 墙脚踩走道沿口                                 10 片
  - 花架横梁 x3 (z=1, 隔一空一): 灰色长方形平板横跨走道,
    两端短边整边压在南北墙顶上                                  3 片
  - 玫瑰 x6: 粉/红三角立在梁端节点上, 底边同时吸住梁短边
    与墙顶边 —— 一片花锁两件                                    6 片
  - 花坛两排 (y [-1,0] 与 y [2,3]): 绿色苗床方板              10 片
  - 郁金香 x4: 红黄紫橙四色三角立在花坛外沿                     4 片
  合计 43 片, 9 个教程步骤, 4 种磁力片形状 (全部 CORE-9 之内)。

招牌技法: 横梁隔一空一桥在双排墙顶, 梁端玫瑰一片同时吸住梁短边
与墙顶边 —— 花不只是装饰, 是锁紧门式框架节点的那颗"销钉"。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 每根横梁两端短边分别整边压在南北墙顶, 墙-梁-墙锁成门式框架,
    剪断任何一端铰链, 另一端仍有支撑路径;
  - 走道与花坛方板行行整边互吸, 墙脚同时吸走道沿与花坛沿
    (一条缝两面吃), 全场连成一张网;
  - 玫瑰/郁金香底边整边吸节点/沿口, 竖立纯受压, 单点剪断
    最多失联 1 片;
  - 最高点 (玫瑰顶) 1.87, 矮胖构型, 重心检查裕量充足。

用法: python3 tools/generate_rose_pergola.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

PATH_A = "clear"    # 走道棋盘格
PATH_B = "gray"
HEDGE = "green"     # 绿篱墙
LATTICE = "clear"   # 窗格格栅
BEAM = "gray"       # 花架横梁
ROSE_S = "pink"     # 南侧玫瑰
ROSE_N = "red"      # 北侧玫瑰
BED = "green"       # 花坛苗床
TULIPS = ["red", "yellow", "purple", "orange"]


def wall_ns_t(tid, tile_type, x0, y, z0, color):
    b.add(tid, tile_type, (x0 + 0.5, y, z0 + 0.5), (90, 0, 0), color)


# =================================================================
# 1. 长廊走道 (x [0,5], y [0,2]): 清灰棋盘两排
# =================================================================
for j in range(2):
    for i in range(5):
        b.flat(f"path_{i}_{j}", i, j, 0.0, PATH_A if (i + j) % 2 == 0 else PATH_B)

# =================================================================
# 2. 绿篱格栅墙两排 (y=0 与 y=2): 方板与窗格方相间
# =================================================================
for i in range(5):
    if i % 2 == 0:
        b.wall_ns(f"hedge_s_{i}", i, 0.0, 0, HEDGE)
        b.wall_ns(f"hedge_n_{i}", i, 2.0, 0, HEDGE)
    else:
        wall_ns_t(f"hedge_s_{i}", "window_square", i, 0.0, 0, LATTICE)
        wall_ns_t(f"hedge_n_{i}", "window_square", i, 2.0, 0, LATTICE)

# =================================================================
# 3. 花架横梁 x3 (z=1, x [0,1]/[2,3]/[4,5]): 隔一空一桥在墙顶
# =================================================================
for k, x0 in enumerate((0, 2, 4)):
    b.flat_rect(f"beam_{k}", x0, 0, 1.0, BEAM, axis="y")

# =================================================================
# 4. 玫瑰 x6: 立在梁端节点, 底边同时吸梁短边与墙顶边
# =================================================================
for k, x0 in enumerate((0, 2, 4)):
    b.crest_ns(f"rose_s_{k}", x0, 0.0, 1.0, ROSE_S)
    b.crest_ns(f"rose_n_{k}", x0, 2.0, 1.0, ROSE_N)

# =================================================================
# 5. 花坛两排 (y [-1,0] 与 y [2,3]) + 郁金香 x4
# =================================================================
for i in range(5):
    b.flat(f"bed_s_{i}", i, -1, 0.0, BED)
for i in range(5):
    b.flat(f"bed_n_{i}", i, 2, 0.0, BED)
b.crest_ns("tulip_s_1", 1, -1.0, 0.0, TULIPS[0])
b.crest_ns("tulip_s_3", 3, -1.0, 0.0, TULIPS[1])
b.crest_ns("tulip_n_1", 1, 3.0, 0.0, TULIPS[2])
b.crest_ns("tulip_n_3", 3, 3.0, 0.0, TULIPS[3])

# =================================================================
# 教程步骤 (9 步)
# =================================================================
b.step(
    "铺走道南排: 五片清灰相间的方板从西到东一字排开。",
    [f"path_{i}_0" for i in range(5)],
    tip="这是能真正走通的花园长廊 —— 走道铺直, 墙和梁才不歪。",
)
b.step(
    "铺走道北排: 再来五片, 两排整边互吸, 棋盘格颜色错开。",
    [f"path_{i}_1" for i in range(5)],
    highlight=["path_0_0"],
    tip="两排走道拼成 5x2 的大地毯, 长廊的地基就位。",
)
b.step(
    "立南排绿篱墙: 绿色方板与清色窗格方相间, 墙脚踩住走道南沿。",
    [f"hedge_s_{i}" for i in range(5)],
    highlight=["path_0_0", "path_4_0"],
    tip="窗格方是格栅 —— 风和阳光穿得过, 玫瑰藤也顺着它往上爬。",
)
b.step(
    "立北排绿篱墙: 与南排一一相对, 相邻墙片竖边互吸。",
    [f"hedge_n_{i}" for i in range(5)],
    highlight=["path_0_1", "path_4_1"],
    tip="两排墙像仪仗队一样面对面站好 —— 它们马上要合力扛横梁。",
)
b.step(
    "架花架横梁: 三片灰色长板隔一空一横跨走道, 两端短边整边压在南北墙顶。",
    ["beam_0", "beam_1", "beam_2"],
    highlight=["hedge_s_0", "hedge_n_0"],
    tip="墙-梁-墙锁成门式框架 —— 隔出的空档就是阳光漏下来的地方。",
)
b.step(
    "南侧攀玫瑰: 三朵粉玫瑰立在梁端节点, 底边同时吸住梁短边与墙顶边。",
    ["rose_s_0", "rose_s_1", "rose_s_2"],
    highlight=["beam_0", "beam_1", "beam_2"],
    tip="一片花锁两件 —— 玫瑰不只是好看, 它把梁和墙钉在了一起。",
)
b.step(
    "北侧攀玫瑰: 三朵红玫瑰照样锁住北端节点, 花架完工。",
    ["rose_n_0", "rose_n_1", "rose_n_2"],
    highlight=["rose_s_0"],
    tip="南粉北红 —— 从长廊里抬头看, 花在梁上排成两条线。",
)
b.step(
    "铺南花坛并种郁金香: 五片绿色苗床贴住走道南墙脚, 红黄两株郁金香立在外沿。",
    [f"bed_s_{i}" for i in range(5)] + ["tulip_s_1", "tulip_s_3"],
    highlight=["hedge_s_1"],
    tip="苗床北沿与墙脚共用一条缝 —— 一条缝两面吃, 花园和长廊连成一体。",
)
b.step(
    "铺北花坛种上紫橙郁金香 —— 长廊落成, 从西门走到东门吧!",
    [f"bed_n_{i}" for i in range(5)] + ["tulip_n_1", "tulip_n_3"],
    highlight=["hedge_n_1"],
    tip="午后阳光穿过梁间空档, 在走道上画出一条条光带 —— 慢慢走, 别踩到花。",
)

b.finalize(
    model_id="rose_pergola_01",
    name="玫瑰花藤长廊",
    name_en="Rose Pergola Walk 01",
    description=(
        "植物花园新作: 两排绿篱格栅墙夹出一条真正能走通的花园走道, 三根灰色"
        "横梁隔一空一桥在墙顶, 锁成三个门式框架; 每个梁端节点上攀着一朵玫瑰"
        " —— 南粉北红, 一片花同时吸住梁短边与墙顶边, 花就是锁紧节点的销钉。"
        "走道两侧绿色花坛里还种着红黄紫橙四株郁金香; 午后阳光从梁间空档漏"
        "下来, 在棋盘走道上画出一条条光带。"
    ),
    difficulty=2,
    tags=["植物花园", "玫瑰", "长廊", "花架", "庭院"],
    min_pieces=43,
    min_steps=9,
)
