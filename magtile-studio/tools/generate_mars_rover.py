#!/usr/bin/env python3
"""生成模型 data/models/mars_rover_01.json (火星探测车)。

航天探索主题: 全库第一台六轮行星车 —— 红色火星荒原上, 一台
探测车正碾过岩钉与风蚀石阵: 四片车轮底座 (wheel_base) 组成
双侧轮组, 车首车尾方墙与甲板长板锁成箱形车身, 两翼各挑出
2 片透明太阳能板 (单边铰链平挑, 力矩在预算内); 车尾设备舱
退台升起, 舱顶竖起桅杆与六边形全景相机云台 —— 火星, 你好!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 车头朝东):
  - 火星荒原: 8x4 红色地坪 (方板 x16 + 长板 x8)              24 片
  - 地貌: 直角三角岩钉 x2 + 等边三角风蚀石 x2 + 四坡岩丘 x4    8 片
  - 轮组: 车轮底座 x4 (南北两侧各 2 片, 底边整边吸地坪拼缝)    4 片
  - 车身: 车首/车尾方墙 x4 + 甲板长板 x4 (箱形合龙)            8 片
  - 太阳能板: 透明方板 x4 (两翼各 2 片, 铰链在车墙顶)          4 片
  - 设备舱: 方墙 x4 + 舱顶长板 x2 (z1..2)                      6 片
  - 桅杆云台: 方板桅杆 x1 + 六边形全景相机 x1                  2 片
  合计 56 片, 16 个教程步骤, 6 种磁力片形状 (迁移期不使用等腰片)。

物理规则要点 (通过 R1~R8 全部校验):
  - 全模型遵循 整边吸合 纪律: 轮组底边 (长 2) 整边吸地坪长板
    拼缝, 甲板长板长边整边压轮组顶、短边整边压车墙顶 ——
    轮组+车墙+甲板锁成箱形环 (结构冗余);
  - 太阳能板单边铰链平挑: 方板质量 1 x 力臂 0.5, 力矩 15 <=
    单位铰链预算 20;
  - 设备舱墙脚踩甲板短边拼缝 (即车墙延长线), 舱顶长板双端
    简支; 桅杆立舱顶东缘, 六边形相机重心正压桅杆顶铰链;
  - 岩钉/风蚀石/岩丘全部整边吸地坪拼缝或格边, 接地稳定。

用法: python3 tools/generate_mars_rover.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

MARS = "red"        # 火星地表
ROCK = "orange"     # 岩石
BODY = "yellow"     # 车身
WHEEL = "gray"      # 轮组
PANEL = "clear"     # 太阳能板
CABIN = "gray"      # 设备舱
CAM = "blue"        # 相机云台

# =================================================================
# 1. 火星荒原 8x4: 方板+长板混铺, 拼缝落在轮组线与车墙线上
# =================================================================
for y in range(4):
    b.flat(f"ml_{y}", 0, y, 0.0, MARS)              # [0,1]
    b.flat_rect(f"ma_{y}", 1, y, 0.0, MARS)         # [1,3]
    b.flat_rect(f"mb_{y}", 3, y, 0.0, MARS)         # [3,5]
    b.flat(f"mc_{y}", 5, y, 0.0, MARS)              # [5,6]
    b.flat(f"md_{y}", 6, y, 0.0, MARS)              # [6,7]
    b.flat(f"me_{y}", 7, y, 0.0, MARS)              # [7,8]

# =================================================================
# 2. 地貌: 岩钉 (直角三角) + 风蚀石 (等边三角) + 岩丘 (四坡锥)
# =================================================================
b.brace("spike_s", (7.0, 0.0, 0.0), "+y", ROCK)     # 南岩钉 (x=7 缝)
b.brace("spike_n", (7.0, 3.0, 0.0), "+y", ROCK)     # 北岩钉
b.crest_ns("wind_w", 0, 0.0, 0.0, ROCK)             # 西南风蚀石
b.crest_ns("wind_n", 6, 4.0, 0.0, ROCK)             # 东北风蚀石
ROCK_IDS = b.hat4("mound", 6, 2, 0.0, ROCK,
                  shape="equilateral_triangle")     # 岩丘 [6,7]x[2,3]

# =================================================================
# 3. 轮组 (z0..1): 4 片车轮底座, 底边整边吸地坪长板拼缝
# =================================================================
for x0 in (1, 3):
    b.add(f"wh_s_{x0}", "wheel_base",
          (x0 + 1.0, 1.0, 0.5), (90, 0, 0), WHEEL)  # 南侧轮组 y=1
    b.add(f"wh_n_{x0}", "wheel_base",
          (x0 + 1.0, 3.0, 0.5), (90, 0, 0), WHEEL)  # 北侧轮组 y=3

# =================================================================
# 4. 车身: 车首 (x=5) / 车尾 (x=1) 方墙 + 甲板长板 (z=1)
# =================================================================
for y in (1, 2):
    b.wall_ew(f"bw_w_{y}", 1.0, y, 0, BODY)         # 车尾墙
    b.wall_ew(f"bw_e_{y}", 5.0, y, 0, BODY)         # 车首墙
for x0 in (1, 3):
    b.flat_rect(f"dk_s_{x0}", x0, 1, 1.0, BODY)     # 甲板南半 [x0,x0+2]x[1,2]
    b.flat_rect(f"dk_n_{x0}", x0, 2, 1.0, BODY)     # 甲板北半 [x0,x0+2]x[2,3]

# =================================================================
# 5. 太阳能板 (z=1): 两翼各 2 片透明方板, 铰链在车墙顶
# =================================================================
for y in (1, 2):
    b.flat(f"sp_w_{y}", 0, y, 1.0, PANEL)           # 西翼 [0,1]
    b.flat(f"sp_e_{y}", 5, y, 1.0, PANEL)           # 东翼 [5,6]

# =================================================================
# 6. 设备舱 (z1..2): 墙脚踩甲板短边拼缝 (x=1 与 x=3 线)
# =================================================================
for y in (1, 2):
    b.wall_ew(f"cb_w_{y}", 1.0, y, 1, CABIN)        # 舱西墙
    b.wall_ew(f"cb_e_{y}", 3.0, y, 1, CABIN)        # 舱东墙
b.flat_rect("cb_rf_s", 1, 1, 2.0, CABIN)            # 舱顶南半 [1,3]x[1,2]
b.flat_rect("cb_rf_n", 1, 2, 2.0, CABIN)            # 舱顶北半 [1,3]x[2,3]

# =================================================================
# 7. 桅杆云台: 方板桅杆立舱顶东缘 + 六边形全景相机
# =================================================================
b.wall_ew("mast", 3.0, 1, 2, BODY)                  # 桅杆 z2..3
b.place_edge("cam", "hexagon", 4,
             (3.0, 1.0, 3.0), (3.0, 2.0, 3.0), (0.0, 0.0, 1.0), CAM)

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "铺荒原南半: 2 行红色地坪, 每行 方板+长板+长板+方板 x3 (8x2)。",
    [f"m{k}_{y}" for y in (0, 1) for k in "labcde"],
    tip="长板拼缝落在 y=1 线上 —— 轮组马上要整边吸在这条缝上。",
)
b.step(
    "铺荒原北半: 再铺 2 行, 荒原合拢成 8x4 火星地表。",
    [f"m{k}_{y}" for y in (2, 3) for k in "labcde"],
    highlight=["ml_1", "me_1"],
    tip="红色大地一望无际 —— 这里是探测车的着陆区。",
)
b.step(
    "立地貌岩钉与风蚀石: 东端拼缝立 2 片直角三角岩钉, 对角再立 "
    "2 片橙色风蚀石。",
    ["spike_s", "spike_n", "wind_w", "wind_n"],
    highlight=["me_0", "me_3"],
    tip="直角边整边吸地坪拼缝 —— 火星的风把石头削成了刀片。",
)
b.step(
    "堆岩丘: 4 片橙色等边三角在东侧格子上四棱互吸, 合拢成一座岩丘。",
    ROCK_IDS,
    highlight=["md_2"],
    tip="四坡自锁 —— 亿万年的陨石堆积就是这个形状。",
)
b.step(
    "装南侧轮组: 2 片车轮底座沿 y=1 拼缝立起, 底边整边吸合。",
    ["wh_s_1", "wh_s_3"],
    highlight=["ma_0", "mb_0"],
    tip="车轮底座是探测车的脚 —— 一片顶两格, 稳稳咬住地缝。",
)
b.step(
    "装北侧轮组: y=3 拼缝再立 2 片, 六轮底盘左右就位。",
    ["wh_n_1", "wh_n_3"],
    highlight=["wh_s_1", "wh_s_3"],
    tip="两侧轮组严格对位 —— 甲板要同时压住它们。",
)
b.step(
    "立车尾墙: x=1 线上 2 片黄色方墙, 底边整边吸地坪格边。",
    ["bw_w_1", "bw_w_2"],
    highlight=["ml_1", "ml_2"],
    tip="车尾墙与轮组同高 —— 它们共同托起甲板。",
)
b.step(
    "立车首墙: x=5 线上再立 2 片, 车身四面有了骨架。",
    ["bw_e_1", "bw_e_2"],
    highlight=["mc_1", "mc_2"],
    tip="车首朝东 —— 全景相机将从这一侧眺望日出。",
)
b.step(
    "盖甲板南半: 2 片长板长边整边压南轮组顶、短边压车墙顶。",
    ["dk_s_1", "dk_s_3"],
    highlight=["wh_s_1", "bw_w_1"],
    tip="轮组+车墙+甲板锁成箱形环 —— 这就是车身的底盘刚度。",
)
b.step(
    "盖甲板北半: 再盖 2 片, 车身箱形合龙。",
    ["dk_n_1", "dk_n_3"],
    highlight=["wh_n_1", "dk_s_1"],
    tip="四片甲板互吸成整块 —— 探测车有了平整的背。",
)
b.step(
    "展西翼太阳能板: 车尾墙顶向外平挑 2 片透明方板。",
    ["sp_w_1", "sp_w_2"],
    highlight=["bw_w_1", "bw_w_2"],
    tip="方板质量 1 x 力臂 0.5, 力矩 15 <= 预算 20 —— 稳稳展开。",
)
b.step(
    "展东翼太阳能板: 车首墙顶同样平挑 2 片, 双翼展开迎着太阳。",
    ["sp_e_1", "sp_e_2"],
    highlight=["bw_e_1", "bw_e_2"],
    tip="火星阳光只有地球一半 —— 双翼一片都不能少。",
)
b.step(
    "起设备舱墙: 甲板短边拼缝上立 4 片灰色方墙 (x=1 与 x=3 线)。",
    ["cb_w_1", "cb_w_2", "cb_e_1", "cb_e_2"],
    highlight=["dk_s_1", "dk_n_1"],
    tip="墙脚踩的拼缝正是车墙延长线 —— 荷载顺墙身直落轮组。",
)
b.step(
    "盖舱顶: 2 片长板短边双端压住舱墙顶, 设备舱合龙。",
    ["cb_rf_s", "cb_rf_n"],
    highlight=["cb_w_1", "cb_e_2"],
    tip="双端简支 —— 舱里装着核电池与样本箱。",
)
b.step(
    "竖桅杆: 舱顶东缘立起 1 片黄色方板桅杆。",
    ["mast"],
    highlight=["cb_rf_s"],
    tip="桅杆底边整边吸舱顶短边 —— 站得直才看得远。",
)
b.step(
    "装全景相机: 桅杆顶竖起六边形云台 —— 火星, 你好!",
    ["cam"],
    highlight=["mast"],
    tip="六边形重心正压桅杆顶铰链, 力臂为零 —— 开始环拍 360 度。",
)

b.finalize(
    model_id="mars_rover_01",
    name="火星探测车",
    name_en="Mars Rover 01",
    description=(
        "全库第一台六轮行星车: 红色火星荒原上, 四片车轮底座组成双侧轮组, "
        "车首车尾方墙与甲板长板锁成箱形车身 (结构冗余环), 两翼平挑 4 片"
        "透明太阳能板 (力矩 15 <= 预算 20), 设备舱退台升起、舱顶竖起桅杆"
        "与六边形全景相机云台; 荒原上岩钉、风蚀石与四坡岩丘点出蛮荒地貌 "
        "—— 火星, 你好!"
    ),
    difficulty=3,
    tags=["航天探索", "火星", "探测车", "车轮底座", "进阶"],
    min_pieces=50,
    min_steps=16,
)
