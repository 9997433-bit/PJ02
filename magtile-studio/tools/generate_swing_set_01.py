#!/usr/bin/env python3
"""生成模型 data/models/swing_set_01.json (秋千乐园)。

内容批 I 模型 4/4: 全库第一架秋千 —— 游乐场货架有攀爬架/滑梯/
沙池, 荡秋千这个保留节目却一直缺席。与洗车房 (单片吊刷) 刻意
区分, 本作的招牌是"吊环秋千": 每架秋千由两片吊链方与一片坐板
围成闭环 —— 两条吊链顶边分别整边吸横板南北沿, 坐板两边整边
吸住两条吊链底边, 剪断任何一条吸边它都还有另一条路兜底 (环状
冗余), 这才是敢让小朋友坐上去的秋千; 门式框架两端红色墙柱
两层到顶, 柱脚直角三角斜撑抗侧, 顶面蓝色横板铺满, 南沿三面
彩旗迎风一排; 旁边黄沙方鑲四面橙色三角围边就是跳沙坑 ——
预备 —— 荡起来!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 框架沿 x 向):
  - 场地 4 行 (x [0,5], y [0,4]): 草坪/胶地长板 + 方板       12 片
  - 跳沙坑 (x [2,3], y [0,1]): 四面等边三角围边               4 片
  - 门式框架墙柱 x2 (x=0 / x=5, y [1,3], z 0..2)              8 片
  - 柱脚直角三角斜撑 x4 (竖边咬柱竖棱, 横边压地缝)            4 片
  - 框架顶板 (z=2, x [0,5], y [1,3]): 方板 x10               10 片
  - 吊环秋千 x2 (吊链方 x2 + 坐板, 闭环): x [1,2] / [3,4]     6 片
  - 南沿彩旗 x3 (骑顶板整边沿口)                              3 片
  合计 47 片, 10 个教程步骤, 4 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告 + jitter 全绿):
  - 秋千是闭环受拉结构: 吊链顶边吸顶板沿 (单链 30g 远低于
    strict 档 84g/单位边长悬挂预算), 坐板把两条链锁成环 ——
    剪断任何一条铰链, 坐板都还悬在另一条链上, 不存在单点失效;
  - 墙柱两层竖叠加直角三角斜撑: 竖直角边整边咬柱脚竖棱,
    水平直角边整边压地缝, 东西向抗侧一步到位;
  - 顶板两行方板: 两端整边压柱顶 (受压), 行内板板互吸,
    行间拼缝与吊链顶边三方共线互锁;
  - 彩旗/沙坑围边全部骑整边沿口, 重心正压铰链线力矩为零;
  - 场地拼缝纪律: 柱脚/斜撑/沙坑围边全部落在板边或拼缝上。

用法: python3 tools/generate_swing_set_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

LAWN = "green"      # 草坪
PAVE = "gray"       # 胶地
SAND = "yellow"     # 沙坑
RIM = "orange"      # 沙坑围边 / 斜撑
POST = "red"        # 框架墙柱
BEAM = "blue"       # 框架顶板
CHAIN = "gray"      # 吊链方
SEAT = "purple"     # 秋千坐板
FLAG = "pink"       # 彩旗

# =================================================================
# 1. 场地 4 行 (x [0,5], y [0,4])
# =================================================================
# 南行 (y [0,1]): 中间一格黄沙是跳沙坑
b.flat_rect("g0_w", 0, 0, 0.0, LAWN)
b.flat("g0_sand", 2, 0, 0.0, SAND)
b.flat_rect("g0_e", 3, 0, 0.0, LAWN)
# 框架南行 (y [1,2]): 两端方板给柱脚留整边
b.flat("g1_w", 0, 1, 0.0, PAVE)
b.flat_rect("g1_m", 1, 1, 0.0, PAVE)
b.flat_rect("g1_e", 3, 1, 0.0, PAVE)
# 框架北行 (y [2,3])
b.flat("g2_w", 0, 2, 0.0, PAVE)
b.flat_rect("g2_m", 1, 2, 0.0, PAVE)
b.flat_rect("g2_e", 3, 2, 0.0, PAVE)
# 北行 (y [3,4])
b.flat_rect("g3_w", 0, 3, 0.0, LAWN)
b.flat_rect("g3_e", 3, 3, 0.0, LAWN)
b.flat("g3_m", 2, 3, 0.0, LAWN)

# =================================================================
# 2. 跳沙坑围边 (x [2,3], y [0,1]): 四面等边三角骑黄沙整边
# =================================================================
b.crest_ns("sb_s", 2, 0.0, 0.0, RIM)
b.crest_ns("sb_n", 2, 1.0, 0.0, RIM)
b.crest_ew("sb_w", 2.0, 0, 0.0, RIM)
b.crest_ew("sb_e", 3.0, 0, 0.0, RIM)

# =================================================================
# 3. 门式框架墙柱 (x=0 / x=5, y [1,3], z 0..2) + 柱脚斜撑
# =================================================================
b.wall_ew("post_w_s0", 0.0, 1, 0, POST)
b.wall_ew("post_w_n0", 0.0, 2, 0, POST)
b.wall_ew("post_w_s1", 0.0, 1, 1, POST)
b.wall_ew("post_w_n1", 0.0, 2, 1, POST)
b.wall_ew("post_e_s0", 5.0, 1, 0, POST)
b.wall_ew("post_e_n0", 5.0, 2, 0, POST)
b.wall_ew("post_e_s1", 5.0, 1, 1, POST)
b.wall_ew("post_e_n1", 5.0, 2, 1, POST)
# 直角三角斜撑: 竖边咬柱脚竖棱, 横边压地缝 (东西向抗侧)
b.brace("br_w_s", (0.0, 1.0, 0.0), "+x", RIM)
b.brace("br_w_n", (0.0, 3.0, 0.0), "+x", RIM)
b.brace("br_e_s", (5.0, 1.0, 0.0), "-x", RIM)
b.brace("br_e_n", (5.0, 3.0, 0.0), "-x", RIM)

# =================================================================
# 4. 框架顶板 (z=2): 两行方板, 两端整边压柱顶
# =================================================================
for i in range(5):
    b.flat(f"roof_s_{i}", i, 1, 2.0, BEAM)
for i in range(5):
    b.flat(f"roof_n_{i}", i, 2, 2.0, BEAM)

# =================================================================
# 5. 吊环秋千 x2 (x [1,2] / x [3,4]): 吊链方 x2 + 坐板闭环
# =================================================================
b.wall_ns("chain_a_s", 1, 1.0, 1, CHAIN)
b.wall_ns("chain_a_n", 1, 2.0, 1, CHAIN)
b.wall_ns("chain_b_s", 3, 1.0, 1, CHAIN)
b.wall_ns("chain_b_n", 3, 2.0, 1, CHAIN)
b.flat("seat_a", 1, 1, 1.0, SEAT)
b.flat("seat_b", 3, 1, 1.0, SEAT)

# =================================================================
# 6. 南沿彩旗 x3 (骑顶板整边沿口)
# =================================================================
b.crest_ns("flag_w", 0, 1.0, 2.0, FLAG)
b.crest_ns("flag_m", 2, 1.0, 2.0, FLAG)
b.crest_ns("flag_e", 4, 1.0, 2.0, FLAG)

# =================================================================
# 教程步骤 (10 步)
# =================================================================
b.step(
    "铺场地南半场: 草坪夹着一格黄沙, 那是跳沙坑的位置。",
    ["g0_w", "g0_sand", "g0_e", "g1_w", "g1_m", "g1_e"],
    tip="游乐场开工啦 —— 板边等长吸合才抓得牢。",
)
b.step(
    "铺场地北半场: 胶地行行互吸, 两端方板给柱脚留整边。",
    ["g2_w", "g2_m", "g2_e", "g3_w", "g3_m", "g3_e"],
    highlight=["g1_w"],
)
b.step(
    "围跳沙坑: 四面橙色三角骑住黄沙整边, 落地不硌脚。",
    ["sb_s", "sb_n", "sb_w", "sb_e"],
    highlight=["g0_sand"],
    tip="三角围边重心正压板沿 —— 又稳又软和。",
)
b.step(
    "立西墙柱: 四片红墙两层竖叠, 柱脚两片斜撑咬棱压缝。",
    ["post_w_s0", "post_w_n0", "post_w_s1", "post_w_n1",
     "br_w_s", "br_w_n"],
    highlight=["g1_w"],
    tip="斜撑竖边咬柱竖棱、横边压地缝 —— 东西向推不倒。",
)
b.step(
    "立东墙柱: 与西柱对称, 门式框架的两条腿就位。",
    ["post_e_s0", "post_e_n0", "post_e_s1", "post_e_n1",
     "br_e_s", "br_e_n"],
    highlight=["post_w_s0"],
)
b.step(
    "铺框架顶板: 十片蓝色方板两行铺满, 两端整边压住柱顶。",
    ["roof_s_0", "roof_s_1", "roof_s_2", "roof_s_3", "roof_s_4",
     "roof_n_0", "roof_n_1", "roof_n_2", "roof_n_3", "roof_n_4"],
    highlight=["post_w_s1", "post_e_s1"],
    tip="板板互吸连成整面 —— 秋千的天梁就是它。",
)
b.step(
    "挂南侧吊链: 两片灰色吊链方顶边整边吸顶板南沿, 先稳稳垂下来。",
    ["chain_a_s", "chain_b_s"],
    highlight=["roof_s_1", "roof_s_3"],
    tip="单链 30g 远低于悬挂预算 —— 但好戏还在后头。",
)
b.step(
    "挂坐板: 紫色坐板南边整边吸住吊链底边, 像小手先拉住一条链。",
    ["seat_a", "seat_b"],
    highlight=["chain_a_s", "chain_b_s"],
    tip="从北边敞口伸手放板 —— 装配顺序也是设计的一部分。",
)
b.step(
    "合北侧吊链锁环: 顶边吸顶板北沿、底边吸坐板北边, 秋千闭环!",
    ["chain_a_n", "chain_b_n"],
    highlight=["seat_a", "seat_b"],
    tip="剪断任何一条吸边, 坐板都还悬在另一条链上 —— 环状冗余才敢坐。",
)
b.step(
    "升彩旗: 三面粉旗骑上顶板南沿, 游乐场正式开园!",
    ["flag_w", "flag_m", "flag_e"],
    highlight=["roof_s_0"],
    tip="预备 —— 荡起来! 荡得高, 笑得响。",
)

b.finalize(
    model_id="swing_set_01",
    name="秋千乐园",
    name_en="Swing Set 01",
    description=(
        "只用核心九片型的全库第一架秋千: 与洗车房的单片吊刷不同, "
        "本作的招牌是'吊环秋千' —— 每架秋千由两片吊链方与一片坐板"
        "围成闭环, 吊链顶边整边吸顶板南北沿, 坐板两边整边吸住两条"
        "吊链底边, 剪断任何一条吸边它都还有另一条路兜底, 环状冗余"
        "才是敢让小朋友坐上去的秋千; 门式框架红色墙柱两层到顶, "
        "柱脚直角三角斜撑咬棱压缝东西向抗侧, 顶面蓝色横板铺满, "
        "南沿三面彩旗迎风一排, 旁边黄沙方鑲四面橙色三角围边就是"
        "跳沙坑 —— 预备, 荡起来!"
    ),
    difficulty=2,
    tags=["游乐园", "秋千", "操场", "运动", "亲子"],
    min_pieces=47,
    min_steps=10,
)
