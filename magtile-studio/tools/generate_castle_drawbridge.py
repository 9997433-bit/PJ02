#!/usr/bin/env python3
"""生成模型 data/models/castle_drawbridge_01.json (吊桥城堡)。

城堡与要塞系列第二课 (主技法 T17 负空间造型 + T04 门楣横楣 +
T12 层叠): 与 castle_foundation_01 (实心地台 + 四面双层墙的
"围合基础课") 的结构逻辑刻意区分 —— 本作的主角是 "进出城的动线":
双塔门楼夹着 2 格宽的城门洞 (负空间), 两根长方形门楣横跨洞口
层层叠高; 吊桥跨过护城河缺口通向前方的桥头堡; 庭院深处再起一座
纯长方形圈层砌法的主楼, 顶上盖梯形四坡大屋顶。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 庭院地台 6x4 (主楼脚下用 2 片长方形通铺)                 20 + 2 片
  - 四面城墙两层: 南墙留 2 格宽城门洞, 门楣 + 女儿墙横楣叠高    35 片
  - 门楼: 双塔第 3 层 + 等腰尖塔 x2 + 四角城齿 x8              12 片
  - 主楼 (天守): 长方形圈层砌法 3 层 (每层 4 片风车状咬合),
    顶盖梯形四坡屋顶 + 金色压顶                               17 片
  - 吊桥: 2 片长方形跨过护城河缺口, 两端整边吸住城内外地台       2 片
  - 桥头堡: 2x2 地台 + 三面矮墙 + 双城齿                       12 片
  合计 99 片, 21 个教程步骤。

物理规则要点 (通过 R1~R8 全部校验):
  - 门楣长方形不坐在墙顶上 (2 长边无处贴合), 而是两端 1 长的短竖边
    分别吸住左右门楼墙的竖边 —— 拱式传力, 洞口才是真正的负空间;
  - 主楼每层 4 片长方形首尾风车状咬合 (短竖边互吸), 层与层长边
    整边叠合; 梯形屋顶下底 2 恰与长方形层顶边等长贴合;
  - 吊桥平铺接地, 北缘吸庭院地台、南缘吸桥头堡地台, 零悬挑。

用法: python3 tools/generate_castle_drawbridge.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

# =================================================================
# 1. 庭院地台 6x4: 主楼脚下 [2,4]x[2,4] 用 2 片长方形通铺
#    (长方形的 2 长边是主楼圈层砌法的地基吸合线)
# =================================================================
KEEP_FOOT = {(i, j) for i in (2, 3) for j in (2, 3)}
for j in range(4):
    for i in range(6):
        if (i, j) in KEEP_FOOT:
            continue
        b.flat(f"g_{i}_{j}", i, j, 0.0, "green" if (i + j) % 2 == 0 else "gray")
b.flat_rect("kf_s", 2, 2, 0.0, "purple", axis="x")   # [2,4]x[2,3]
b.flat_rect("kf_n", 2, 3, 0.0, "purple", axis="x")   # [2,4]x[3,4]

# =================================================================
# 2. 城墙第 1 层 (z 0..1): 南墙留 2 格宽城门洞 (x 2..4)
# =================================================================
for i in (0, 1, 4, 5):
    b.wall_ns(f"w1_s_{i}", i, 0.0, 0, "gray")
for j in range(4):
    b.wall_ew(f"w1_w_{j}", 0.0, j, 0, "gray")
for j in range(4):
    b.wall_ew(f"w1_e_{j}", 6.0, j, 0, "gray")
for i in (0, 1, 4, 5):
    b.wall_ns(f"w1_n_{i}", i, 4.0, 0, "gray")

# =================================================================
# 3. 城墙第 2 层 (z 1..2): 南面城门洞上架长方形门楣
#    (门楣两端短竖边吸住左右第 2 层墙的竖边, 洞口保持贯通)
# =================================================================
for i in (0, 1, 4, 5):
    b.wall_ns(f"w2_s_{i}", i, 0.0, 1, "blue")
for j in range(4):
    b.wall_ew(f"w2_w_{j}", 0.0, j, 1, "blue")
for j in range(4):
    b.wall_ew(f"w2_e_{j}", 6.0, j, 1, "blue")
for i in (0, 1, 4, 5):
    b.wall_ns(f"w2_n_{i}", i, 4.0, 1, "blue")
b.lintel_ns("gate_lintel", 2, 0.0, 1, "orange")      # 门楣 x 2..4, z 1..2

# =================================================================
# 4. 门楼 (z 2..3): 双塔 + 女儿墙横楣叠在门楣上 + 尖塔
# =================================================================
b.wall_ns("gt_w", 1, 0.0, 2, "blue")                 # 西门楼塔
b.wall_ns("gt_e", 4, 0.0, 2, "blue")                 # 东门楼塔
b.lintel_ns("gate_parapet", 2, 0.0, 2, "orange")     # 女儿墙横楣 z 2..3
b.spire_ns("gt_spire_w", 1, 0.0, 3.0, "red")
b.spire_ns("gt_spire_e", 4, 0.0, 3.0, "red")

# 城墙城齿: 四角各 2 片黄色等边三角形
CRESTS = [
    ("cr_s_w", "ns", 0, 0.0), ("cr_s_e", "ns", 5, 0.0),
    ("cr_n_w", "ns", 0, 4.0), ("cr_n_e", "ns", 5, 4.0),
    ("cr_w_s", "ew", 0.0, 1), ("cr_w_n", "ew", 0.0, 2),
    ("cr_e_s", "ew", 6.0, 1), ("cr_e_n", "ew", 6.0, 2),
]
for tid, orient, a, bb in CRESTS:
    if orient == "ns":
        b.crest_ns(tid, a, bb, 2.0, "yellow")
    else:
        b.crest_ew(tid, a, bb, 2.0, "yellow")

# =================================================================
# 5. 主楼 (天守, [2,4]x[2,4]): 长方形圈层砌法 3 层 + 梯形四坡屋顶
#    每层 4 片竖置长方形首尾风车状咬合: 南北片横跨 x 2..4,
#    东西片横跨 y 2..4, 四角短竖边两两互吸
# =================================================================
for lv in range(3):
    c = "purple" if lv % 2 == 0 else "pink"
    b.lintel_ns(f"keep{lv}_s", 2, 2.0, lv, c)
    b.lintel_ew(f"keep{lv}_e", 4.0, 2, lv, c)
    b.lintel_ns(f"keep{lv}_n", 2, 4.0, lv, c)
    b.lintel_ew(f"keep{lv}_w", 2.0, 2, lv, c)

ROOF_IDS, ROOF_CAP = b.hip_roof2("roof", 2, 2, 3.0, "red", cap_color="yellow")

# =================================================================
# 6. 吊桥 + 桥头堡: 护城河 (y -2..0) 上两片长方形桥板,
#    通向 2x2 桥头堡 (三面矮墙, 北面迎桥敞开)
# =================================================================
b.flat_rect("bridge_w", 2, -2, 0.0, "orange", axis="y")   # [2,3]x[-2,0]
b.flat_rect("bridge_e", 3, -2, 0.0, "orange", axis="y")   # [3,4]x[-2,0]

for j in (-4, -3):
    for i in (2, 3):
        b.flat(f"bk_{i}_{j}", i, j, 0.0, "cyan")
b.wall_ns("bkw_s_w", 2, -4.0, 0, "gray")
b.wall_ns("bkw_s_e", 3, -4.0, 0, "gray")
b.wall_ew("bkw_w_s", 2.0, -4, 0, "gray")
b.wall_ew("bkw_w_n", 2.0, -3, 0, "gray")
b.wall_ew("bkw_e_s", 4.0, -4, 0, "gray")
b.wall_ew("bkw_e_n", 4.0, -3, 0, "gray")
b.crest_ns("bk_cr_w", 2, -4.0, 1.0, "yellow")
b.crest_ns("bk_cr_e", 3, -4.0, 1.0, "yellow")

# =================================================================
# 教程步骤 (22 步)
# =================================================================
b.step(
    "铺设庭院地台南半部: 平放 2 排共 12 片正方形, 绿灰棋盘格。",
    [f"g_{i}_{j}" for j in range(2) for i in range(6)],
    tip="城门朝南: 地台南面要留出护城河与桥头堡的位置 (约四格深)。",
)
b.step(
    "铺设庭院地台北半部: 外圈 8 片正方形, 中央主楼地基改用 2 片紫色长方形通铺 —— "
    "长方形的长边就是主楼圈层砌法的地基吸合线。",
    [f"g_{i}_{j}" for j in (2, 3) for i in (0, 1, 4, 5)] + ["kf_s", "kf_n"],
    highlight=["g_1_1", "g_4_1"],
    tip="两片长方形东西向并排铺满 2x2 地基, 与四周正方形整边贴合。",
)
b.step(
    "城墙第 1 层南面: 城门两侧各立 2 片灰色正方形, 中间留出 2 格宽的城门洞。",
    ["w1_s_0", "w1_s_1", "w1_s_4", "w1_s_5"],
    highlight=["g_0_0", "g_5_0"],
    tip="城门洞是这座城堡最重要的负空间 —— 后面门楣要横跨在它上方。",
)
b.step(
    "城墙第 1 层西面与东面: 各立 4 片, 与南墙转角竖边互吸。",
    [f"w1_w_{j}" for j in range(4)] + [f"w1_e_{j}" for j in range(4)],
    highlight=["w1_s_0", "w1_s_5"],
    tip="先立转角那片再顺墙推进, 每片底边吸地台边、侧边吸邻片。",
)
b.step(
    "城墙第 1 层北面: 4 片合围 (中段 x 2..4 由主楼自己的墙体填补)。",
    [f"w1_n_{i}" for i in (0, 1, 4, 5)],
    highlight=["w1_w_3", "w1_e_3"],
    tip="北墙中段留空不要补 —— 主楼北立面会严丝合缝地嵌进来。",
)
b.step(
    "城墙第 2 层南面 + 城门门楣: 先叠 4 片蓝色正方形, 再把橙色长方形门楣横跨"
    "城门洞, 两端短竖边分别吸住左右墙片的竖边。",
    ["w2_s_0", "w2_s_1", "w2_s_4", "w2_s_5", "gate_lintel"],
    highlight=["w1_s_1", "w1_s_4"],
    tip="门楣下方完全悬空 —— 全部重量由两端竖边传给门楼, 这就是横楣传力。",
)
b.step(
    "城墙第 2 层西面与东面: 各叠 4 片蓝色正方形。",
    [f"w2_w_{j}" for j in range(4)] + [f"w2_e_{j}" for j in range(4)],
    highlight=[f"w1_w_{j}" for j in range(4)],
    tip="第二层与第一层完全对齐, 上下边整边贴合。",
)
b.step(
    "城墙第 2 层北面: 4 片叠上, 双层城墙合围完成。",
    [f"w2_n_{i}" for i in (0, 1, 4, 5)],
    highlight=[f"w1_n_{i}" for i in (0, 1, 4, 5)],
    tip="从远处平视: 南面城门洞应是整面墙上唯一的开口。",
)
b.step(
    "门楼升第 3 层: 门洞两侧塔身各叠 1 片, 中间再架一根橙色女儿墙横楣, "
    "两端竖边吸住双塔 —— 门楼从城墙中拔起。",
    ["gt_w", "gt_e", "gate_parapet"],
    highlight=["w2_s_1", "w2_s_4", "gate_lintel"],
    tip="女儿墙横楣长边还与下方门楣整边叠合, 双重吸合非常结实。",
)
b.step(
    "门楼封顶: 双塔顶各立 1 片红色等腰尖塔, 塔尖直指天空。",
    ["gt_spire_w", "gt_spire_e"],
    highlight=["gt_w", "gt_e"],
    tip="捏住尖角轻轻放下, 底边吸合即可站稳。",
)
b.step(
    "南北城齿: 城墙顶四角各装 1 片黄色等边三角形 (共 4 片)。",
    ["cr_s_w", "cr_s_e", "cr_n_w", "cr_n_e"],
    highlight=["w2_s_0", "w2_n_0"],
    tip="城齿底边吸墙顶边; 四角城齿让城堡轮廓一下子锋利起来。",
)
b.step(
    "东西城齿: 东西墙顶中段再各装 2 片 (共 4 片)。",
    ["cr_w_s", "cr_w_n", "cr_e_s", "cr_e_n"],
    highlight=["w2_w_1", "w2_e_1"],
    tip="全部城齿装完后从上往下看, 应呈对称的八点分布。",
)
b.step(
    "主楼第 1 层: 4 片紫色长方形竖立在地基长方形的长边上, 首尾风车状咬合 —— "
    "南北片横跨东西, 东西片横跨南北, 四角短竖边两两互吸。",
    ["keep0_s", "keep0_e", "keep0_n", "keep0_w"],
    highlight=["kf_s", "kf_n"],
    tip="按南-东-北-西顺序放: 每片长 2 格, 一片就是一整面墙。",
)
b.step(
    "主楼第 2 层: 再叠 4 片粉色长方形, 长边与下层整边贴合, 四角继续咬合。",
    ["keep1_s", "keep1_e", "keep1_n", "keep1_w"],
    highlight=["keep0_s", "keep0_e"],
    tip="圈层砌法上下层不留错缝, 但四角咬合让它比单片墙稳得多。",
)
b.step(
    "主楼第 3 层: 最后 4 片紫色长方形, 主楼升到三层 —— 比门楼还高。",
    ["keep2_s", "keep2_e", "keep2_n", "keep2_w"],
    highlight=["keep1_s", "keep1_e"],
    tip="越往上越要轻放, 一手扶住下层楼身。",
)
b.step(
    "主楼大屋顶: 4 片红色梯形下底分别吸住楼顶四条长边, 腰与腰两两互吸, "
    "向内收拢成四坡屋顶。",
    ROOF_IDS,
    highlight=["keep2_s", "keep2_n"],
    tip="梯形下底长 2, 恰好与长方形层顶边等长 —— 先放南北两片, 再补东西。",
)
b.step(
    "金色压顶: 屋顶正中的 1x1 洞口用金色正方形封住, 主楼落成!",
    [ROOF_CAP],
    highlight=ROOF_IDS,
    tip="压顶四边同时吸住四片梯形的上底, 把整个屋顶锁成一体。",
)
b.step(
    "放下吊桥: 2 片橙色长方形并排跨过护城河, 北端短边吸庭院地台南缘、"
    "南端短边悬向对岸, 两片长边互吸。",
    ["bridge_w", "bridge_e"],
    highlight=["g_2_0", "g_3_0"],
    tip="桥面正对城门洞: 从城外看, 门洞-吊桥-护城河连成一条进城动线。",
)
b.step(
    "铺设桥头堡地台: 吊桥南端接 2x2 共 4 片青色正方形。",
    ["bk_2_-3", "bk_3_-3", "bk_2_-4", "bk_3_-4"],
    highlight=["bridge_w", "bridge_e"],
    tip="第一排先吸住吊桥南缘短边, 第二排向南延伸。",
)
b.step(
    "桥头堡围墙: 南、西、东三面各立 2 片灰色矮墙, 北面迎桥敞开。",
    ["bkw_s_w", "bkw_s_e", "bkw_w_s", "bkw_w_n", "bkw_e_s", "bkw_e_n"],
    highlight=["bk_2_-4", "bk_3_-4"],
    tip="桥头堡是城外的第一道防线, 墙片底边吸地台边、转角竖边互吸。",
)
b.step(
    "桥头堡城齿: 南墙顶装 2 片黄色等边三角形 —— 与城墙城齿遥相呼应。",
    ["bk_cr_w", "bk_cr_e"],
    highlight=["bkw_s_w", "bkw_s_e"],
    tip="吊桥城堡完工: 手指当作来访的骑士, 走桥-穿门-进院-登主楼吧!",
)

b.finalize(
    model_id="castle_drawbridge_01",
    name="吊桥城堡",
    name_en="Drawbridge Castle 01",
    description=(
        "城堡系列第二课, 主角是进出城的动线: 双塔门楼夹着 2 格宽的城门洞, "
        "两根长方形门楣横跨洞口层层叠高 (两端竖边传力, 洞口全程贯通); 橙色"
        "吊桥跨过护城河通向三面围墙的桥头堡; 庭院深处的主楼用长方形圈层砌法"
        "四角咬合升起三层, 顶上梯形四坡大屋顶加金色压顶。负空间门洞、横楣"
        "传力、圈层砌法 —— 三个新技法一课学会。"
    ),
    difficulty=4,
    tags=["城堡", "吊桥", "门楼", "负空间", "挑战"],
    min_pieces=80,
    min_steps=18,
)
