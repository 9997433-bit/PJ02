#!/usr/bin/env python3
"""生成模型 data/models/basketball_arena_01.json (篮球馆)。

第三批模型 ①: 运动场馆主题首作 —— 全尺寸篮球馆: 6x4 球场
(橙色地板 + 黄色禁区 + 青色中圈), 东西两端各一座门式篮架
(双柱 + 透明篮板横楣 + 悬挑篮筐平台), 北侧一座两层阶梯看台
(前后挡墙 + 座席板层层升高), 看台顶上立着六边形大记分牌。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 球场 6x4 (橙地板/黄禁区/青中圈)                       24 片
  - 篮架 x2: 双柱 (各 2 层) + 透明篮板横楣 + 篮筐平台      12 片
  - 北看台: 一层看台 18 + 二层看台 24                      42 片
  - 记分牌: 六边形立在二层看台顶沿                          1 片
  - 场边旗与南侧围栏: 等腰旗 x2 + 等边围栏 x2               4 片
  合计 83 片, 18 个教程步骤, 5 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 篮板横楣两端竖边吸双柱第二层竖边 (吊桥城堡门楣同款传力);
  - 篮筐平台为 1x2 长方形, 整条长边吸篮板顶边, 悬挑力矩
    30 g·单位 < 抗弯预算 40 (R6 铰链切割静力分析放行);
  - 看台每层都是 前挡墙 + 后挡墙 + 座席板 锁成的箱形梁,
    二层前挡墙直接立在一层座席板后沿上, 逐层退台升高。

用法: python3 tools/generate_basketball_arena.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import HEX_APOTHEM, ModelBuilder  # noqa: E402

b = ModelBuilder()

# =================================================================
# 1. 球场 6x4: 橙色地板, 东西禁区黄色, 中圈青色
# =================================================================
KEY = {(0, 1), (0, 2), (5, 1), (5, 2)}          # 东西禁区 (油漆区)
CENTER = {(2, 1), (2, 2), (3, 1), (3, 2)}       # 中圈
for j in range(4):
    for i in range(6):
        color = "cyan" if (i, j) in CENTER else (
            "yellow" if (i, j) in KEY else "orange")
        b.flat(f"ct_{i}_{j}", i, j, 0.0, color)

# =================================================================
# 2. 篮架 x2: 双柱 + 透明篮板横楣 + 悬挑篮筐平台
#    双柱开在 y 0..1 / 3..4, 篮板横跨 y 1..3 (z 1..2),
#    篮筐平台 1x2 长方形平放在篮板顶边 (z=2), 悬入场内
# =================================================================
for z0 in (0, 1):
    b.wall_ew(f"hw_ps_{z0}", 0.0, 0, z0, "gray")     # 西篮架南柱
    b.wall_ew(f"hw_pn_{z0}", 0.0, 3, z0, "gray")     # 西篮架北柱
b.lintel_ew("hw_board", 0.0, 1, 1, "clear")          # 西篮板 (透明横楣)
b.flat_rect("hw_hoop", 0, 1, 2.0, "red", axis="y")   # 西篮筐平台 (悬挑)

for z0 in (0, 1):
    b.wall_ew(f"he_ps_{z0}", 6.0, 0, z0, "gray")     # 东篮架南柱
    b.wall_ew(f"he_pn_{z0}", 6.0, 3, z0, "gray")     # 东篮架北柱
b.lintel_ew("he_board", 6.0, 1, 1, "clear")          # 东篮板
b.flat_rect("he_hoop", 5, 1, 2.0, "red", axis="y")   # 东篮筐平台

# =================================================================
# 3. 北看台: 两层阶梯箱形梁 (前挡墙 + 后挡墙 + 座席板)
# =================================================================
for x in range(6):
    b.wall_ns(f"s1_f_{x}", x, 4.0, 0, "gray")        # 一层前挡墙 (y=4)
for x in range(6):
    b.wall_ns(f"s1_b_{x}", x, 5.0, 0, "gray")        # 一层后挡墙 (y=5)
for x in range(6):
    b.flat(f"s1_d_{x}", x, 4, 1.0, "blue" if x % 2 == 0 else "cyan")  # 一层座席
for x in range(6):
    b.wall_ns(f"s2_f_{x}", x, 5.0, 1, "gray")        # 二层前挡墙 (立在一层座席后沿)
for x in range(6):
    b.wall_ns(f"s2_b0_{x}", x, 6.0, 0, "gray")       # 二层后挡墙下段 (y=6)
for x in range(6):
    b.wall_ns(f"s2_b1_{x}", x, 6.0, 1, "gray")       # 二层后挡墙上段
for x in range(6):
    b.flat(f"s2_d_{x}", x, 5, 2.0, "cyan" if x % 2 == 0 else "blue")  # 二层座席

# =================================================================
# 4. 记分牌 + 场边旗 + 南侧围栏
# =================================================================
b.add("board", "hexagon", (2.5, 6.0, 2 + HEX_APOTHEM), (90, 0, 0), "purple")
b.spire_ns("flag_w", 0, 0.0, 0.0, "red")             # 西南角队旗
b.spire_ns("flag_e", 5, 0.0, 0.0, "blue")            # 东南角队旗
b.crest_ns("fence_w", 1, 0.0, 0.0, "green")          # 南侧围栏西段
b.crest_ns("fence_e", 4, 0.0, 0.0, "green")          # 南侧围栏东段

# =================================================================
# 教程步骤 (18 步): 球场 -> 篮架 -> 看台 -> 记分牌 -> 场边
# =================================================================
b.step(
    "铺设球场南边线一排: 6 片方板沿东西向平铺 (y=0), 两端黄色是禁区起点。",
    [f"ct_{i}_0" for i in range(6)],
    tip="球场要铺在桌面中央偏南 —— 北边还要盖两层看台。",
)
b.step(
    "铺球场第 2 排: 禁区黄、中圈青、其余橙, 每片与南排整边吸合。",
    [f"ct_{i}_1" for i in range(6)],
    highlight=["ct_0_0", "ct_5_0"],
    tip="青色两片是中圈的南半 —— 开球点就在球场正中。",
)
b.step(
    "铺球场第 3 排: 与第 2 排镜像, 中圈青色合成完整圆心区。",
    [f"ct_{i}_2" for i in range(6)],
    highlight=["ct_2_1", "ct_3_1"],
    tip="从上往下看, 4 片青色应拼成球场正中的方形中圈。",
)
b.step(
    "补齐球场北边线一排 —— 6x4 球场就绪, 可以进场热身了。",
    [f"ct_{i}_3" for i in range(6)],
    highlight=[f"ct_{i}_2" for i in range(6)],
    tip="整块球场中间不能留缝, 相邻边都要吸牢。",
)
b.step(
    "竖立西篮架双柱: 球场西端南北两角各立 2 层灰色立柱 (y 0..1 与 3..4), "
    "底边吸球场西边线。",
    ["hw_ps_0", "hw_pn_0", "hw_ps_1", "hw_pn_1"],
    highlight=["ct_0_0", "ct_0_3"],
    tip="先立下层再叠上层, 每层竖边与球场边整边吸合。",
)
b.step(
    "安装西篮板: 透明长方形横跨双柱之间, 两端竖边吸柱身第二层竖边。",
    ["hw_board"],
    highlight=["hw_ps_1", "hw_pn_1"],
    tip="篮板底边悬空不用怕 —— 两端竖边传力, 和城堡门楣同款。",
)
b.step(
    "装西篮筐: 红色 1x2 篮筐平台平放在篮板顶边上, 悬挑伸入场内。",
    ["hw_hoop"],
    highlight=["hw_board"],
    tip="篮筐整条长边都要吸住篮板顶边 —— 单边悬挑全靠这条磁力线。",
)
b.step(
    "竖立东篮架双柱: 与西侧完全镜像, 球场东端再立 4 片灰色立柱。",
    ["he_ps_0", "he_pn_0", "he_ps_1", "he_pn_1"],
    highlight=["ct_5_0", "ct_5_3"],
    tip="两端篮架对齐同一条中线, 才是标准球馆。",
)
b.step(
    "安装东篮板: 透明长方形横跨东侧双柱, 两端竖边吸柱身竖边。",
    ["he_board"],
    highlight=["he_ps_1", "he_pn_1"],
    tip="与西篮板同高同线 —— 篮板歪一点, 球感就差一截。",
)
b.step(
    "装东篮筐: 红色篮筐平台吸在东篮板顶边上, 与西侧镜像悬挑入场。",
    ["he_hoop"],
    highlight=["he_board"],
    tip="装完从场地正中看, 两个篮筐应正对着彼此。",
)
b.step(
    "看台开工: 沿球场北边线立 6 片一层前挡墙 (y=4)。",
    [f"s1_f_{x}" for x in range(6)],
    highlight=[f"ct_{i}_3" for i in range(6)],
    tip="挡墙底边吸球场北边, 竖边两两互吸 —— 看台的第一道边。",
)
b.step(
    "立一层后挡墙并铺座席: 6 片灰色正方形与前挡墙平行立起 (y=5), "
    "随即用 6 片蓝青座席板压在前后挡墙顶上 (z=1) 锁成箱形梁。",
    [f"s1_b_{x}" for x in range(6)] + [f"s1_d_{x}" for x in range(6)],
    highlight=["s1_f_0"],
    tip="座席板两长边分别吸前后挡墙顶边 —— 箱形梁一锁, 看台稳如磐石。",
)
b.step(
    "二层前挡墙: 6 片灰色正方形直接立在一层座席板后沿上 (y=5, z 1..2)。",
    [f"s2_f_{x}" for x in range(6)],
    highlight=[f"s1_d_{x}" for x in range(6)],
    tip="底边吸座席板后沿 —— 二层看台要比一层高整整一格。",
)
b.step(
    "二层后挡墙: 沿 y=6 先立 6 片接地下段, 再叠 6 片上段升到 2 格高。"
    "这排墙暂时自成一组, 下一步铺座席板就会与看台连成整体。",
    [f"s2_b0_{x}" for x in range(6)] + [f"s2_b1_{x}" for x in range(6)],
    highlight=["s2_f_0"],
    tip="上下两段竖边对齐 —— 它要扛住整个二层看台的后沿。",
)
b.step(
    "铺二层座席: 6 片青蓝相间的座席板压在二层前后挡墙顶上 (z=2)。",
    [f"s2_d_{x}" for x in range(6)],
    highlight=["s2_f_0", "s2_b1_5"],
    tip="两层看台阶梯升起 —— 后排观众也能看清每一个进球。",
)
b.step(
    "竖起记分牌: 紫色六边形立在二层座席北沿正中, 面向球场。",
    ["board"],
    highlight=["s2_d_2"],
    tip="底边整边吸座席板后沿, 六边形大屏全场都看得见。",
)
b.step(
    "插场边队旗: 球场南边线两角各立一面等腰三角旗 (红队 vs 蓝队)。",
    ["flag_w", "flag_e"],
    highlight=["ct_0_0", "ct_5_0"],
    tip="旗尖朝上, 底边吸球场南边线。",
)
b.step(
    "装南侧围栏: 2 片绿色等边三角形立在南边线中段, 篮球馆开馆!",
    ["fence_w", "fence_e"],
    highlight=["flag_w", "flag_e"],
    tip="围栏中间留出入场通道 —— 观众入场, 比赛开始!",
)

b.finalize(
    model_id="basketball_arena_01",
    name="篮球馆",
    name_en="Basketball Arena 01",
    description=(
        "运动场馆首作: 6x4 球场铺出橙地板、黄禁区与青色中圈, 东西两端各立一座"
        "门式篮架 —— 双柱夹透明篮板横楣 (两端竖边传力), 红色篮筐平台整条长边"
        "吸篮板顶边悬挑入场; 北侧两层阶梯看台逐层退台升高, 每层都是前挡墙 + "
        "后挡墙 + 座席板锁成的箱形梁, 看台顶上六边形大记分牌俯瞰全场 —— "
        "红队蓝队各执一旗, 开球!"
    ),
    difficulty=4,
    tags=["运动", "篮球", "场馆", "看台", "进阶"],
    min_pieces=50,
    min_steps=16,
)
