#!/usr/bin/env python3
"""生成模型 data/models/halloween_pumpkin_house_01.json (万圣节南瓜女巫屋)。

内容批 G 模型 1/4: 节日限定主题第一个万圣节模型 (库内已有春节舞狮 /
元宵灯会 / 中秋拜月台 / 圣诞集市, 万圣节档期一直空着)。
与巫师观星塔 (2x2 正交方塔 + 等腰四坡帽) 与姜饼糖果屋 (盒式坡顶
小屋) 刻意区分: 结构签名是"正八边形墙环" —— 全库第一个非正交
墙环: 八片方墙竖边以 135 度钝角逐对互咬, 闭环自锁成南瓜灯的圆筒
肚皮, 只有正南一片墙踩在整格地缝上 (全环唯一的接地拼缝锚点);
筒顶再用八片瘦高等腰三角沿八条棱互吸收拢成八棱女巫帽尖。
两扇黄色窗格方斜嵌在二层东南/西南棱面上, 就是南瓜灯的发光眼睛,
一层门框方是它咧开的大嘴 —— 不给糖就捣蛋!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 大门朝南):
  - 庭院地坪 2 行 (x [0,7], y [0,2]): 草地 + 青石门道          12 片
  - 八边形墙环一层 (z 0..1): 7 片橙墙 + 1 片门框方大嘴          8 片
  - 八边形墙环二层 (z 1..2): 6 片橙墙 + 2 片黄窗格方眼睛        8 片
  - 八棱女巫帽 (z 2..3.59): 8 片紫色瘦高等腰收拢成锥            8 片
  - 南瓜田: 两颗四棱自锁小南瓜 (等边四坡锥)                     8 片
  - 尖桩篱笆 x4 + 小黑猫 + 小幽灵                               6 片
  合计 50 片, 12 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告 + jitter 50 全绿):
  - 八边形墙环每片墙与左右邻墙共享整条竖边 (135 度互咬), 闭环
    即刚; 正南墙脚整边吸住门道方板北沿, 全环与庭院锁成一体;
  - 其余七片墙脚直接落地 (接地支撑), 不需要脚下拼缝;
  - 二层墙环底边与一层墙顶整边共线上叠, 帽片底边吸二层墙顶,
    八条斜棱两两互吸自锁 (摩天大楼金顶同款技法的八棱版);
  - 小南瓜四棱自锁 (等边四坡锥), 底边整边吸脚下单位方板;
  - 篱笆/黑猫/幽灵均骑拼缝, 剪任一装饰连接最多失联 1 片。

用法: python3 tools/generate_halloween_pumpkin_house_01.py  (在 magtile-studio 目录下运行)
"""

import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder, ISO_H  # noqa: E402

b = ModelBuilder()

LAWN = "green"      # 夜色草地
PATH = "gray"       # 青石门道
BODY = "orange"     # 南瓜筒身
DOOR = "yellow"     # 大嘴门框
EYE = "yellow"      # 发光眼睛
HAT = "purple"      # 女巫帽
PUMPKIN = "orange"  # 田里的小南瓜
FENCE = "gray"      # 尖桩篱笆
CAT = "gray"        # 小黑猫
GHOST = "clear"     # 小幽灵

# ---- 正八边形几何: 边长 1, 正南边恰好压在格线段 [3,4] x {2} 上 ----
S = 1.0
R = S / (2 * math.sin(math.pi / 8))     # 外接圆半径 1.306563
A = S / (2 * math.tan(math.pi / 8))     # 边心距 1.207107
CX, CY = 3.5, 2.0 + A                   # 圆心 (正南边中点在 (3.5, 2))


def overt(k):
    """第 k 个顶点 (逆时针, k=0 是正南边西端 (3,2))。"""
    th = math.radians(-112.5 + 45.0 * k)
    return (CX + R * math.cos(th), CY + R * math.sin(th))


def ring_wall(tile_id, k, z, tile_type, color):
    x0, y0 = overt(k)
    x1, y1 = overt((k + 1) % 8)
    b.place_edge(tile_id, tile_type, 0,
                 (x0, y0, float(z)), (x1, y1, float(z)), (0, 0, 1), color)


# =================================================================
# 1. 庭院地坪 2 行 (x [0,7], y [0,2]): 草地中间一条青石门道
# =================================================================
b.flat_rect("g1_w", 0, 1, 0.0, LAWN)
b.flat("g1_2", 2, 1, 0.0, LAWN)
b.flat("g1_3", 3, 1, 0.0, PATH)      # 门阶: 北沿就是南墙脚拼缝
b.flat("g1_4", 4, 1, 0.0, LAWN)
b.flat_rect("g1_e", 5, 1, 0.0, LAWN)
b.flat("g0_0", 0, 0, 0.0, LAWN)
b.flat("g0_1", 1, 0, 0.0, LAWN)      # 西南瓜脚下的单位方板
b.flat("g0_2", 2, 0, 0.0, LAWN)
b.flat("g0_3", 3, 0, 0.0, PATH)
b.flat("g0_4", 4, 0, 0.0, LAWN)      # 东南瓜脚下的单位方板
b.flat("g0_5", 5, 0, 0.0, LAWN)
b.flat("g0_6", 6, 0, 0.0, LAWN)

# =================================================================
# 2. 八边形墙环一层 (z 0..1): 正南门框方是南瓜灯咧开的大嘴
# =================================================================
ring_wall("w1_0", 0, 0, "door_frame", DOOR)
for k in range(1, 8):
    ring_wall(f"w1_{k}", k, 0, "square", BODY)

# =================================================================
# 3. 八边形墙环二层 (z 1..2): 东南/西南棱面斜嵌两只发光眼睛
# =================================================================
ring_wall("w2_0", 0, 1, "square", BODY)
ring_wall("w2_1", 1, 1, "window_square", EYE)   # 东南眼
for k in range(2, 7):
    ring_wall(f"w2_{k}", k, 1, "square", BODY)
ring_wall("w2_7", 7, 1, "window_square", EYE)   # 西南眼

# =================================================================
# 4. 八棱女巫帽 (z 2..3.59): 八片瘦高等腰沿八条棱互吸收拢
# =================================================================
HAT_H = math.sqrt(ISO_H * ISO_H - A * A)        # 1.594633
apex = (CX, CY, 2.0 + HAT_H)
for k in range(8):
    x0, y0 = overt(k)
    x1, y1 = overt((k + 1) % 8)
    b.place_tri(f"hat_{k}", "isosceles_triangle",
                (x0, y0, 2.0), (x1, y1, 2.0), apex, HAT)

# =================================================================
# 5. 南瓜田: 两颗四棱自锁小南瓜 (等边四坡锥)
# =================================================================
b.hat4("pk_w", 1, 0, 0.0, PUMPKIN, shape="equilateral_triangle")
b.hat4("pk_e", 4, 0, 0.0, PUMPKIN, shape="equilateral_triangle")

# =================================================================
# 6. 尖桩篱笆 + 小黑猫 + 小幽灵
# =================================================================
b.crest_ns("fence_0", 0, 0.0, 0.0, FENCE)
b.crest_ns("fence_1", 1, 0.0, 0.0, FENCE)
b.crest_ns("fence_5", 5, 0.0, 0.0, FENCE)
b.crest_ns("fence_6", 6, 0.0, 0.0, FENCE)
b.spire_ns("cat", 4, 1.0, 0.0, CAT)             # 骑草地拼缝, 守在门阶东侧
b.spire_ns("ghost", 1, 1.0, 0.0, GHOST)         # 南瓜田上空飘着小幽灵

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺门前行: 两条草地长板夹三片方板, 中间灰色的是青石门阶。",
    ["g1_w", "g1_2", "g1_3", "g1_4", "g1_e"],
    tip="万圣节的傍晚到啦! 门阶北沿待会儿要咬住南瓜屋的大门墙脚。",
)
b.step(
    "铺南瓜田行: 七片方板等边互吸, 灰色方板续上青石小路。",
    ["g0_0", "g0_1", "g0_2", "g0_3", "g0_4", "g0_5", "g0_6"],
    highlight=["g1_w"],
    tip="小南瓜要种在单位方板上 —— 四条底边都得有整边可吸。",
)
b.step(
    "起一层墙环南半: 门框方大嘴踩上门阶北沿, 左右各接一片橙墙。",
    ["w1_0", "w1_1", "w1_7"],
    highlight=["g1_3"],
    tip="相邻墙片的竖边以 135 度互咬 —— 南瓜的圆肚皮就是这么鼓起来的。",
)
b.step(
    "合一层墙环北半: 余下五片橙墙逐片咬进环里, 首尾合拢。",
    ["w1_2", "w1_3", "w1_4", "w1_5", "w1_6"],
    highlight=["w1_1"],
    tip="八片墙合成闭环就自己站稳了 —— 除了大门, 其他墙脚直接踩地。",
)
b.step(
    "摞二层墙环南半: 两扇黄窗格方斜嵌在东南和西南棱面上。",
    ["w2_0", "w2_1", "w2_7"],
    highlight=["w1_0"],
    tip="底边与一层墙顶整边共线吸合 —— 这两扇斜窗就是南瓜灯的眼睛!",
)
b.step(
    "合二层墙环北半: 五片橙墙上环, 南瓜灯的脑袋鼓圆了。",
    ["w2_2", "w2_3", "w2_4", "w2_5", "w2_6"],
    highlight=["w2_1"],
    tip="每片墙都要同时咬住脚下墙顶和旁边的邻墙。",
)
b.step(
    "戴女巫帽南半: 四片紫色瘦高等腰底边吸住二层墙顶, 斜棱互吸。",
    ["hat_0", "hat_1", "hat_7", "hat_6"],
    highlight=["w2_0"],
    tip="帽片一片挨一片, 斜棱两两咬住 —— 帽尖会在正中央碰头。",
)
b.step(
    "合女巫帽北半: 余下四片收拢, 八条棱在帽尖自锁成环。",
    ["hat_2", "hat_3", "hat_4", "hat_5"],
    highlight=["hat_1"],
    tip="最后一片同时咬住两条斜棱 —— 八棱帽尖一锁, 风都吹不歪。",
)
b.step(
    "种西边的小南瓜: 四片橙色等边斜棱互吸自锁成锥。",
    ["pk_w_s", "pk_w_e", "pk_w_n", "pk_w_w"],
    highlight=["g0_1"],
    tip="小南瓜的四条底边都要整边吸住脚下的草地方板。",
)
b.step(
    "种东边的小南瓜: 南瓜田凑成一对。",
    ["pk_e_s", "pk_e_e", "pk_e_n", "pk_e_w"],
    highlight=["g0_4"],
    tip="两颗小南瓜一西一东, 等着被做成明年的南瓜灯。",
)
b.step(
    "插尖桩篱笆: 四片灰色等边骑住庭院南沿, 中间留出小路豁口。",
    ["fence_0", "fence_1", "fence_5", "fence_6"],
    highlight=["g0_0"],
    tip="篱笆一片骑一沿 —— 讨糖的小客人从青石小路进来。",
)
b.step(
    "请出小黑猫和小幽灵: 一只守门阶, 一只飘在南瓜田上。",
    ["cat", "ghost"],
    highlight=["g1_4", "g0_1"],
    tip="不给糖就捣蛋! 南瓜灯的眼睛亮起来, 万圣节晚会开场啦。",
)

b.finalize(
    model_id="halloween_pumpkin_house_01",
    name="万圣节南瓜女巫屋",
    name_en="Halloween Pumpkin House 01",
    description=(
        "只用核心九片型的节日限定新档期 —— 全库第一个万圣节模型, 也是"
        "全库第一个非正交墙环: 八片方墙竖边以 135 度钝角逐对互咬, 闭环"
        "自锁成南瓜灯鼓鼓的圆筒肚皮, 只有正南的门框方大嘴踩着青石门阶"
        "拼缝, 其余七片墙脚潇洒落地; 筒顶八片紫色瘦高等腰沿八条斜棱"
        "互吸收拢成八棱女巫帽尖, 两扇黄窗格方斜嵌在东南西南棱面上, "
        "就是南瓜灯的发光眼睛; 田里两颗四棱自锁小南瓜, 篱笆边小黑猫"
        "守着门阶, 小幽灵飘过南瓜田 —— 不给糖就捣蛋!"
    ),
    difficulty=3,
    tags=["节日", "万圣节", "南瓜灯", "女巫屋", "进阶"],
    min_pieces=50,
    min_steps=12,
)
