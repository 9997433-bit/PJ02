#!/usr/bin/env python3
"""生成模型 data/models/sector_rotunda_01.json (扇形拱券半圆殿).

内容批 P 模型 9/10: 建筑地标主题 D3 —— 全库扇形片型深度示范:
七座石柱沿半圆殿南廊排开, 六片扇形拱券 (T04) 逐跨合龙成柱廊拱圈,
北墙窗格方留高窗负空间 (T17), 殿心贯通 —— 扇形拱券围成真正的
半圆殿轮廓, 不是点缀一两片的敷衍用法.

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 使用者站在南侧):
  - 柱廊地板 (y=0): 七片汉白玉石板                                 7 片
  - 柱廊 (y=0, z=0): 七根方柱                                     7 片
  - 扇形拱券 (y=0, z=1): 六跨扇形拱 (T04)                         6 片
  - 殿内地板 (y=1..2): 十四片                                     14 片
  - 侧墙 (x=0/6): 各两片                                          4 片
  - 北墙鼓身 (y=3): 五片实墙 + 两片窗格高窗 (T17)                  7 片
  - 鼓顶檐板 (y=3, z=1): 七片                                     7 片
  - 侧顶封板 (x=0/6, y=2): 各一片                                 2 片
  - 北檐三角饰 + 殿心雕像                                         4 片
  合计 59 片, 14 个教程步骤, 5 种磁力片形状 (含扩展扇形).

物理规则要点 (validate 常规 + strict 双档零警告):
  - 全模型单一连通组: 柱廊地板连柱脚、殿内地板、侧墙与北墙鼓身;
  - 扇形只有两条半径边可吸: 底边整边搁在相邻柱顶, 竖半径边吸柱身
    侧缝 —— 逐跨合龙 (T04), 剪断任一条力都能沿拱圈绕行;
  - 北墙窗格高窗 (T17) 留采光洞, 洞口两侧实墙闭环传力.

用法: python3 tools/generate_sector_rotunda_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

STONE = "gray"
COL = "clear"
ARCH = "yellow"
ROOF = "blue"
STATUE = "orange"
PED = "yellow"
WINDOW = "clear"


def wall_ns_t(tid, tile_type, x0, y, z0, color):
    b.add(tid, tile_type, (x0 + 0.5, y, z0 + 0.5), (90, 0, 0), color)


# =================================================================
# 1. 柱廊地板 (y=0) —— 全馆受力底盘, 与柱脚/殿内地板连成一体
# =================================================================
for x in range(7):
    b.flat(f"porch_{x}", x, 0, 0.0, STONE)

# =================================================================
# 2. 柱廊: 七根方柱 (y=0)
# =================================================================
for x in range(7):
    b.wall_ns(f"col_{x}", x, 0.0, 0, COL)

# =================================================================
# 3. 扇形拱券: 六跨 T04 逐跨合龙 (z=1, 底边搁柱顶)
# =================================================================
for i in range(6):
    b.place_edge(
        f"arch_{i}", "sector", 0,
        (float(i), 0.0, 1.0), (float(i + 1), 0.0, 1.0),
        (0.0, 0.0, 1.0), ARCH if i % 2 else STONE,
    )

# =================================================================
# 4. 殿内地板 (y=1..2) —— 连续铺地, 柱廊与殿心贯通
# =================================================================
for y in (1, 2):
    for x in range(7):
        b.flat(f"fl_{y}_{x}", x, y, 0.0, STONE)

# =================================================================
# 5. 侧墙 (x=0 西 / x=6 东, y=1..2)
# =================================================================
for y in (1, 2):
    b.wall_ew(f"side_w_{y}", 0.0, y, 0, STONE)
    b.wall_ew(f"side_e_{y}", 7.0, y, 0, STONE)

# =================================================================
# 6. 北墙鼓身 (y=3): 实墙 + 窗格高窗负空间 (T17)
# =================================================================
for x in (0, 1, 5, 6):
    b.wall_ns(f"back_{x}", x, 3.0, 0, STONE)
for x in (2, 3, 4):
    wall_ns_t(f"back_win_{x}", "window_square", x, 3.0, 0, WINDOW)

# =================================================================
# 7. 鼓顶檐板 (z=1) + 侧顶封板
# =================================================================
for x in range(7):
    b.flat(f"roof_{x}", x, 3, 1.0, ROOF)
b.flat("cap_w", 0, 2, 1.0, ROOF)
b.flat("cap_e", 6, 2, 1.0, ROOF)

# =================================================================
# 8. 北檐三角饰 + 殿心雕像
# =================================================================
b.crest_ns("ped_l", 1, 3.0, 1.0, PED)
b.crest_ns("ped_c", 3, 3.0, 1.0, PED)
b.crest_ns("ped_r", 5, 3.0, 1.0, PED)
b.wall_ns("statue", 3, 2.0, 0, STATUE)
b.crest_ns("statue_top", 3, 2.0, 1.0, PED)

# =================================================================
# 教程步骤 (14 步)
# =================================================================
b.step(
    "铺柱廊地板: 七片汉白玉石板沿东西向排开, 半圆殿由此向南敞开.",
    [f"porch_{x}" for x in range(7)],
    tip="这是全殿的受力底盘 —— 柱脚与殿内地板都从这里接龙.",
)
b.step(
    "立柱廊第一批: 西半四根方柱 (x=0..3), 柱脚整边踩地板北沿.",
    ["col_0", "col_1", "col_2", "col_3"],
    highlight=["porch_3"],
    tip="每根柱只有一片高 —— 柱顶高度就是扇形拱的落点.",
)
b.step(
    "立柱廊第二批: 东半三根方柱, 七座石柱排齐.",
    ["col_4", "col_5", "col_6"],
    highlight=["col_3"],
    tip="七柱等距 —— 六跨拱券即将逐跨合龙.",
)
b.step(
    "砌西三跨扇形拱: 三片扇形底边整边搁柱顶, 拱腹朝外 (T04 逐跨合龙).",
    ["arch_0", "arch_1", "arch_2"],
    highlight=["col_1"],
    tip="扇形只有两条半径边可吸 —— 底边搁柱顶, 竖边吸柱侧缝.",
)
b.step(
    "砌东三跨扇形拱: 另三片镜像合龙, 柱廊拱圈闭合.",
    ["arch_3", "arch_4", "arch_5"],
    highlight=["arch_2"],
    tip="六片扇形围成半圆殿南廊 —— 全库扇形片型的招牌用法.",
)
b.step(
    "铺殿内南排地板: 七片方板填满 y=1, 与柱廊地板缝缝相吸.",
    [f"fl_1_{x}" for x in range(7)],
    highlight=["porch_3"],
    tip="连续铺地 —— 从柱廊一步踏入殿心, 不再有断开的孤岛.",
)
b.step(
    "铺殿内北排地板: 再铺七片, 殿心地面完工.",
    [f"fl_2_{x}" for x in range(7)],
    highlight=["fl_1_3"],
    tip="北排与侧墙脚线对齐 —— 鼓身即将在此升起.",
)
b.step(
    "立西墙与东墙: 各两片立墙围出殿内侧界.",
    ["side_w_1", "side_w_2", "side_e_1", "side_e_2"],
    highlight=["fl_2_0"],
    tip="侧墙竖边吸地板拼缝, 与柱廊两端对齐.",
)
b.step(
    "砌北墙实墙段: 东西各两片实墙, 与侧墙转角互咬.",
    ["back_0", "back_1", "back_5", "back_6"],
    highlight=["side_w_2"],
    tip="实墙段先立好 —— 中间三格留给高窗负空间.",
)
b.step(
    "装北墙高窗: 三片窗格方留采光洞 (T17 负空间), 两侧实墙闭环传力.",
    ["back_win_2", "back_win_3", "back_win_4"],
    highlight=["back_1"],
    tip="少砌实墙、换上窗格 —— 殿内亮堂, 传力路径不断.",
)
b.step(
    "盖鼓顶檐板: 七片蓝色方板压在北墙顶口.",
    [f"roof_{x}" for x in range(7)],
    highlight=["back_win_3"],
    tip="檐板短边吸墙顶整边, 长边互吸成整带.",
)
b.step(
    "封侧顶: 两片檐板盖住东西侧墙顶, 与鼓顶齐平.",
    ["cap_w", "cap_e"],
    highlight=["roof_0"],
    tip="三面檐板合围, 殿顶轮廓完整.",
)
b.step(
    "装北檐三角饰: 三片金色三角点缀鼓顶北沿.",
    ["ped_l", "ped_c", "ped_r"],
    highlight=["roof_3"],
    tip="檐饰骑在檐板北沿 —— 古典半圆殿的收笔.",
)
b.step(
    "立殿心雕像与金冠 —— 扇形拱券半圆殿落成!",
    ["statue", "statue_top"],
    highlight=["fl_2_3"],
    tip="六扇拱券围成的半圆殿 —— 入库前须逐一实物复核.",
)

b.finalize(
    model_id="sector_rotunda_01",
    name="扇形拱券半圆殿",
    name_en="Sector Rotunda 01",
    description=(
        "建筑地标 D3 扇形示范: 七座石柱沿半圆殿南廊排开, 六片扇形拱券"
        " (T04) 逐跨合龙成真正的柱廊拱圈; 北墙三扇窗格高窗留采光负空间"
        " (T17), 殿内地板与柱廊贯通一体; 蓝色檐板与檐饰收顶, 殿心雕像"
        " 点缀中轴 —— 扇形片型不是点缀, 而是半圆殿的结构主角."
    ),
    difficulty=3,
    tags=["建筑地标", "半圆殿", "扇形", "柱廊", "拱券"],
    min_pieces=48,
    min_steps=12,
    series="landmark_architecture",
)
