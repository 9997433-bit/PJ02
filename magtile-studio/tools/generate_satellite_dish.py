#!/usr/bin/env python3
"""生成模型 data/models/satellite_dish_01.json (卫星地面站)。

太空主题: 全库第一口 "朝天锅" —— 与射电望远镜 (六边形天线盘
竖在塔顶, 竖直平面零力矩) 结构逻辑完全不同: 主天线是一只碗形
朝天碟 —— 1x1 两层蓝色基座塔上, 四片透明方板花瓣各自绕基座
顶边向外翻开 30 度, 围成一只仰望深空的碗; 碗底盖板 (馈源平台)
与花瓣共享同一圈顶边, 三吸一线; 西北角一口青色小碟 (等边花瓣
单层碗) 追踪低轨卫星, 黄色测控楼窗朝主碟, 屋脊天线与信标旗
把守场地 —— 深空的问候, 落进碗里。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 测控场 7x5: 方板 x21 + 长板 x6 (青色电缆沟 + 橙色戈壁斑) 27 片
  - 主碟基座塔 (x [2,3], y [2,3], z 0~2): 蓝色立墙两层           8 片
  - 馈源盖板 (z=2) + 碗形花瓣 x4 (外翻 30 度, 碗沿 2.87)         5 片
  - 测控楼 (x [4,6], y [1,3]): 墙 8 (含门框方门 + 双窗格方窗)
    + 平屋顶 4 + 屋脊天线 1                                     13 片
  - 小碟 (x [0,1], y [3,4]): 基座环 x4 + 等边花瓣 x4             8 片
  - 信标旗 (方墙+红旗) + 仪器箱等边三角 x2                       4 片
  合计 67 片, 14 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, strict 档同样全绿):
  - 碗形花瓣是全模型的招牌: 每片方板底边吸基座墙顶边 + 盖板
    沿边 (双连接), 向外翻开 30 度 —— 单片悬挑力矩 30g x 0.25
    = 7.5, 远低于 strict 抗弯预算 17.5; 四片互不依赖, 剪断
    任意一条铰链只失联一片;
  - 小碟等边花瓣同法外翻, 悬挑力矩仅 13g x 0.144 = 1.9;
  - 基座塔两层四角竖边互吸闭环, 盖板四边整边压墙顶 (碗沿
    2.87 触发 R8 高层检查, 环环相扣零警告);
  - 测控楼墙环 + 屋顶板缝互吸成箱, 屋脊天线骑双板拼缝 (双连
    接), 信标旗/仪器箱重心正压拼缝铰链 (力矩 0)。

用法: python3 tools/generate_satellite_dish.py  (在 magtile-studio 目录下运行)
"""

import math

from magtile_gen import ModelBuilder

b = ModelBuilder()

S30 = 0.5
C30 = round(math.cos(math.radians(30)), 6)   # 0.866025
TRI_H = 0.866025                             # 等边三角形高

GROUND = "gray"     # 测控场
GOBI = "orange"     # 戈壁斑
CABLE = "cyan"      # 电缆沟
PED = "blue"        # 主碟基座塔
LID = "gray"        # 馈源盖板
PETAL = "clear"     # 主碟花瓣
HOUSE = "yellow"    # 测控楼
ROOF = "blue"       # 测控楼屋顶
DOOR = "red"        # 门
GLASS = "clear"     # 窗
ANT = "red"         # 屋脊天线
MINI_PED = "gray"   # 小碟基座
MINI = "cyan"       # 小碟花瓣
POLE = "gray"       # 信标旗杆
FLAG = "red"        # 信标旗
BOX = "green"       # 仪器箱

# =================================================================
# 1. 测控场 7x5 (x [0,7], y [0,5]): 南北长板收边, 中三行方板
# =================================================================
GOBI_CELLS = {(0, 1), (6, 3)}
CABLE_CELLS = {(3, 1), (3, 2)}
for k in range(3):
    b.flat_rect(f"fd_s_{k}", 2 * k, 0, 0.0, GROUND)
b.flat("fd_s_3", 6, 0, 0.0, GROUND)
for y in range(1, 4):
    for x in range(7):
        color = GROUND
        if (x, y) in GOBI_CELLS:
            color = GOBI
        elif (x, y) in CABLE_CELLS:
            color = CABLE
        b.flat(f"fd_{x}_{y}", x, y, 0.0, color)
for k in range(3):
    b.flat_rect(f"fd_n_{k}", 2 * k, 4, 0.0, GROUND)
b.flat("fd_n_3", 6, 4, 0.0, GROUND)

# =================================================================
# 2. 主碟基座塔 (x [2,3], y [2,3], z 0~2): 两层四角闭环
# =================================================================
for lv in (0, 1):
    b.wall_ns(f"ped_s{lv}", 2, 2.0, lv, PED)
    b.wall_ns(f"ped_n{lv}", 2, 3.0, lv, PED)
    b.wall_ew(f"ped_w{lv}", 2.0, 2, lv, PED)
    b.wall_ew(f"ped_e{lv}", 3.0, 2, lv, PED)

# =================================================================
# 3. 馈源盖板 + 碗形花瓣: 底边吸墙顶+盖板沿, 向外翻开 30 度
# =================================================================
b.flat("dish_lid", 2, 2, 2.0, LID)
b.place_edge("dish_s", "square", 0, (2.0, 2.0, 2.0), (3.0, 2.0, 2.0),
             (0.0, -S30, C30), PETAL)
b.place_edge("dish_e", "square", 0, (3.0, 2.0, 2.0), (3.0, 3.0, 2.0),
             (S30, 0.0, C30), PETAL)
b.place_edge("dish_n", "square", 0, (3.0, 3.0, 2.0), (2.0, 3.0, 2.0),
             (0.0, S30, C30), PETAL)
b.place_edge("dish_w", "square", 0, (2.0, 3.0, 2.0), (2.0, 2.0, 2.0),
             (-S30, 0.0, C30), PETAL)

# =================================================================
# 4. 测控楼 (x [4,6], y [1,3]): 墙环 (西门朝碟 + 南双窗) + 平顶
# =================================================================
b.add("ho_win_a", "window_square", (4.5, 1.0, 0.5), (90, 0, 0), GLASS)
b.add("ho_win_b", "window_square", (5.5, 1.0, 0.5), (90, 0, 0), GLASS)
b.wall_ns("ho_n_a", 4, 3.0, 0, HOUSE)
b.wall_ns("ho_n_b", 5, 3.0, 0, HOUSE)
b.add("ho_door", "door_frame", (4.0, 1.5, 0.5), (90, 0, 90), DOOR)
b.wall_ew("ho_w_b", 4.0, 2, 0, HOUSE)
b.wall_ew("ho_e_a", 6.0, 1, 0, HOUSE)
b.wall_ew("ho_e_b", 6.0, 2, 0, HOUSE)
for x in (4, 5):
    for y in (1, 2):
        b.flat(f"ho_rf_{x}_{y}", x, y, 1.0, ROOF)
b.crest_ew("ho_ant", 5.0, 1, 1.0, ANT)

# =================================================================
# 5. 小碟 (x [0,1], y [3,4]): 单层基座环 + 等边花瓣外翻 30 度
# =================================================================
b.wall_ns("md_s", 0, 3.0, 0, MINI_PED)
b.wall_ns("md_n", 0, 4.0, 0, MINI_PED)
b.wall_ew("md_w", 0.0, 3, 0, MINI_PED)
b.wall_ew("md_e", 1.0, 3, 0, MINI_PED)


def mini_petal(tid, b0, b1, out_dir):
    mid = ((b0[0] + b1[0]) / 2, (b0[1] + b1[1]) / 2, b0[2])
    apex = (mid[0] + out_dir[0] * TRI_H * S30,
            mid[1] + out_dir[1] * TRI_H * S30,
            b0[2] + TRI_H * C30)
    b.place_tri(tid, "equilateral_triangle", b0, b1, apex, MINI)


mini_petal("md_p_s", (0.0, 3.0, 1.0), (1.0, 3.0, 1.0), (0, -1))
mini_petal("md_p_e", (1.0, 3.0, 1.0), (1.0, 4.0, 1.0), (1, 0))
mini_petal("md_p_n", (1.0, 4.0, 1.0), (0.0, 4.0, 1.0), (0, 1))
mini_petal("md_p_w", (0.0, 4.0, 1.0), (0.0, 3.0, 1.0), (-1, 0))

# =================================================================
# 6. 信标旗 + 仪器箱
# =================================================================
b.wall_ns("bcn_pole", 6, 4.0, 0, POLE)
b.crest_ns("bcn_flag", 6, 4.0, 1.0, FLAG)
b.crest_ns("ins_a", 1, 1.0, 0.0, BOX)
b.crest_ew("ins_b", 7.0, 2, 0.0, BOX)

# =================================================================
# 教程步骤 (14 步)
# =================================================================
b.step(
    "铺测控场南沿: 3 片灰长板 + 1 片方板 (y [0,1])。",
    ["fd_s_0", "fd_s_1", "fd_s_2", "fd_s_3"],
    tip="长板收边省片数 —— 拼缝对齐网格线。",
)
b.step(
    "铺第二行 (y [1,2]): 7 片, 青色电缆沟从主碟通向测控楼。",
    [f"fd_{x}_1" for x in range(7)],
    highlight=["fd_s_0"],
    tip="橙色是戈壁沙斑 —— 地面站建在旷野上。",
)
b.step(
    "铺第三行 (y [2,3]): 7 片, 主碟基座就踩这行拼缝。",
    [f"fd_{x}_2" for x in range(7)],
    highlight=["fd_0_1"],
    tip="电缆沟继续向东 —— 信号要送进测控楼。",
)
b.step(
    "铺第四行 (y [3,4]): 7 片, 东端留出戈壁斑。",
    [f"fd_{x}_3" for x in range(7)],
    highlight=["fd_0_2"],
    tip="小碟基座落在西北角这行上。",
)
b.step(
    "铺北沿: 3 片长板 + 1 片方板, 测控场合拢。",
    ["fd_n_0", "fd_n_1", "fd_n_2", "fd_n_3"],
    highlight=["fd_0_3"],
    tip="七五场坪铺满 —— 天线塔马上开工。",
)
b.step(
    "立主碟基座塔第一层: 4 片蓝墙踩拼缝, 四角竖边互吸闭环。",
    ["ped_s0", "ped_n0", "ped_w0", "ped_e0"],
    highlight=["fd_2_1", "fd_2_2"],
    tip="闭环是塔的骨架 —— 剪断一角也不散。",
)
b.step(
    "叠第二层: 再来 4 片, 底边整边吸下层墙顶。",
    ["ped_s1", "ped_n1", "ped_w1", "ped_e1"],
    highlight=["ped_s0", "ped_e0"],
    tip="两层塔身把碗举到 2 格高 —— 视野越过测控楼。",
)
b.step(
    "盖馈源盖板, 再把 4 片透明花瓣向外翻开 30 度 —— 朝天碗成形!",
    ["dish_lid", "dish_s", "dish_e", "dish_n", "dish_w"],
    highlight=["ped_s1", "ped_n1"],
    tip="花瓣底边同时吸墙顶与盖板沿 —— 单片力矩仅 7.5。",
)
b.step(
    "砌测控楼南墙与西墙: 双窗格方窗朝南, 门框方大门朝主碟。",
    ["ho_win_a", "ho_win_b", "ho_door", "ho_w_b"],
    highlight=["fd_4_1", "fd_4_2"],
    tip="值班员推门就能看见大碗 —— 电缆沟到门口。",
)
b.step(
    "砌北墙与东墙: 4 片黄墙, 楼体闭环。",
    ["ho_n_a", "ho_n_b", "ho_e_a", "ho_e_b"],
    highlight=["ho_door", "ho_win_a"],
    tip="八片墙锁成箱 —— 测控楼稳如磐石。",
)
b.step(
    "盖测控楼平顶 4 片, 屋脊骑缝立起红色天线。",
    ["ho_rf_4_1", "ho_rf_5_1", "ho_rf_4_2", "ho_rf_5_2", "ho_ant"],
    highlight=["ho_n_a", "ho_e_a"],
    tip="每片顶板压两面墙顶 —— 天线骑双板拼缝, 双连接。",
)
b.step(
    "立小碟基座环: 西北角 4 片灰墙闭环。",
    ["md_s", "md_n", "md_w", "md_e"],
    highlight=["fd_0_3"],
    tip="小碟追低轨卫星 —— 大小碟一深一近搭配干活。",
)
b.step(
    "小碟花瓣: 4 片青色等边三角向外翻开 30 度。",
    ["md_p_s", "md_p_e", "md_p_n", "md_p_w"],
    highlight=["md_s", "md_e"],
    tip="等边花瓣悬挑力矩仅 1.9 —— 轻若无物。",
)
b.step(
    "立信标旗, 摆两只仪器箱 —— 地面站开机!",
    ["bcn_pole", "bcn_flag", "ins_a", "ins_b"],
    highlight=["fd_n_3", "fd_1_1"],
    tip="旗与箱重心正压拼缝铰链 —— 力矩为零。",
)

b.finalize(
    model_id="satellite_dish_01",
    name="卫星地面站",
    name_en="Satellite Ground Station 01",
    description=(
        "全库第一口朝天锅: 1x1 两层蓝色基座塔顶, 四片透明方板"
        "花瓣绕墙顶铰链向外翻开 30 度, 与馈源盖板围成仰望深空的"
        "碗 (碗沿 2.87, 单片悬挑力矩 7.5 << strict 预算 17.5);"
        " 西北角青色等边花瓣小碟追低轨卫星, 黄色测控楼门框方"
        "大门朝碟、双窗格方窗朝南, 屋脊天线骑缝双连接, 信标旗"
        "与仪器箱点景 —— 深空的问候, 落进碗里。"
    ),
    difficulty=3,
    tags=["航天", "卫星", "天线", "地面站", "进阶"],
    min_pieces=64,
    min_steps=14,
)
