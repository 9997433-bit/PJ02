#!/usr/bin/env python3
"""生成模型 data/models/aircraft_carrier_01.json (航母甲板段)。

军港巡礼主题: 全库第一艘"箱形船体"模型 —— 8 格长的机库箱体
(尾门开敞可望进机库), 整层飞行甲板压顶, 舰艏两条 30 度滑跃
坡道直探水线; 右舷舰岛两层带透明舰桥, 顶戴四坡雷达罩,
甲板上还停着两架三角尾翼的舰载机。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 舰艏朝西):
  - 机库底板 (x 0..8, y 0..2): 8x2 共 16 片                       16 片
  - 舷墙: 左右舷各 8 片 (z 0..1) + 舰艏封板 2 片, 舰尾开敞        18 片
  - 飞行甲板 (z=1): 8x2 共 16 片                                  16 片
  - 舰艏滑跃坡道: 双车道 30 度坡道, 坡尾直探水线                    2 片
  - 舰岛 (x 4..6, y 1..2, z 1..3): 两层 12 片 + 顶板 2 +
    雷达罩 4 + 信号桅 1                                           19 片
  - 舰载机 x2: 双侧机身 + 机翼顶板 + 三角尾翼                       8 片
  - 甲板护网 4 + 舰尾旗 1                                           5 片
  合计 84 片, 18 个教程步骤。

物理规则要点 (通过 R1~R8 全部校验):
  - 飞行甲板同时压住左右舷墙顶边与舰艏封板顶边 —— 剪断任何
    一条舷侧铰链线, 甲板仍由另一舷与舰艏三路支撑;
  - 滑跃坡道顶边与甲板艏沿、舰艏封板顶边三线合一互吸, 坡尾
    自然落地 (水线), 是滚珠塔坡道技法的舰船化用;
  - 舰岛与舰载机全部立在甲板板缝上, 力经舷墙直达地面;
  - 舰尾整面开敞 —— 机库内部不放任何后补件, 不触发 R7b。

用法: python3 tools/generate_aircraft_carrier.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

HULL = "red"
DECK = "gray"
ISLAND = "yellow"
JET = "cyan"

# =================================================================
# 1. 机库底板 (x 0..8, y 0..2)
# =================================================================
for x0 in range(8):
    for y0 in range(2):
        b.flat(f"hf_{x0}_{y0}", x0, y0, 0.0, DECK)

# =================================================================
# 2. 舷墙 (z 0..1): 左右舷各 8 片 + 舰艏封板 2 片 (舰尾开敞)
# =================================================================
for x0 in range(8):
    b.wall_ns(f"hs_{x0}", x0, 0.0, 0, HULL)       # 左舷 (南)
    b.wall_ns(f"hn_{x0}", x0, 2.0, 0, HULL)       # 右舷 (北)
b.wall_ew("bow_s", 0.0, 0, 0, HULL)               # 舰艏封板南段
b.wall_ew("bow_n", 0.0, 1, 0, HULL)               # 舰艏封板北段

# =================================================================
# 3. 飞行甲板 (z=1): 8x2
# =================================================================
for x0 in range(8):
    for y0 in range(2):
        b.flat(f"fd_{x0}_{y0}", x0, y0, 1.0, DECK)

# =================================================================
# 4. 舰艏滑跃坡道: 双车道 30 度, 顶边吸甲板艏沿, 坡尾探水线
# =================================================================
b.ramp("ski_s", "-x", 0.0, 0, 1.0, HULL)
b.ramp("ski_n", "-x", 0.0, 1, 1.0, HULL)

# =================================================================
# 5. 舰岛 (x 4..6, y 1..2, z 1..3): 两层 + 顶板 + 雷达罩 + 信号桅
# =================================================================
for lv in (1, 2):
    c = ISLAND if lv == 1 else "clear"            # 上层是透明舰桥
    b.wall_ns(f"is_s{lv}_4", 4, 1.0, lv, c)
    b.wall_ns(f"is_s{lv}_5", 5, 1.0, lv, c)
    b.wall_ns(f"is_n{lv}_4", 4, 2.0, lv, ISLAND)
    b.wall_ns(f"is_n{lv}_5", 5, 2.0, lv, ISLAND)
    b.wall_ew(f"is_w{lv}", 4.0, 1, lv, ISLAND)
    b.wall_ew(f"is_e{lv}", 6.0, 1, lv, ISLAND)
b.flat("is_top_4", 4, 1, 3.0, DECK)
b.flat("is_top_5", 5, 1, 3.0, DECK)
RADAR = b.hat4("radar", 4, 1, 3.0, "orange")      # 雷达罩 (西格)
b.crest_ns("mast", 5, 1.0, 3.0, HULL)             # 信号桅 (东格南沿)

# =================================================================
# 6. 舰载机 x2: 双侧机身 + 机翼顶板 + 三角尾翼
# =================================================================
b.wall_ns("j1_s", 1, 0.0, 1, JET)                 # 1 号机 (x 1..2, y 0..1)
b.wall_ns("j1_n", 1, 1.0, 1, JET)
b.flat("j1_wing", 1, 0, 2.0, ISLAND)
b.crest_ew("j1_fin", 2.0, 0, 2.0, HULL)           # 尾翼朝舰尾
b.wall_ns("j2_s", 2, 1.0, 1, JET)                 # 2 号机 (x 2..3, y 1..2)
b.wall_ns("j2_n", 2, 2.0, 1, JET)
b.flat("j2_wing", 2, 1, 2.0, ISLAND)
b.crest_ew("j2_fin", 3.0, 1, 2.0, HULL)

# =================================================================
# 7. 甲板护网 4 + 舰尾旗
# =================================================================
b.crest_ns("net_s6", 6, 0.0, 1.0, "clear")
b.crest_ns("net_s7", 7, 0.0, 1.0, "clear")
b.crest_ns("net_n0", 0, 2.0, 1.0, "clear")
b.crest_ns("net_n6", 6, 2.0, 1.0, "clear")
b.crest_ew("stern_flag", 8.0, 0, 1.0, "green")    # 舰尾旗 (立在甲板尾沿)

# =================================================================
# 教程步骤 (18 步)
# =================================================================
b.step(
    "机库底板·艏段: 平铺 6 片底板 (x 0..3), 双列并进。",
    [f"hf_{x0}_{y0}" for x0 in range(3) for y0 in range(2)],
    tip="航母是全库最长的船 —— 底板铺直, 后面全靠它找正。",
)
b.step(
    "机库底板·中段: 再铺 6 片 (x 3..6)。",
    [f"hf_{x0}_{y0}" for x0 in (3, 4, 5) for y0 in range(2)],
    highlight=["hf_2_0", "hf_2_1"],
    tip="缝缝相吸往东延伸 —— 舰岛将来就坐在这段上方。",
)
b.step(
    "机库底板·艉段: 4 片收尾, 8x2 底板贯通。",
    [f"hf_{x0}_{y0}" for x0 in (6, 7) for y0 in range(2)],
    highlight=["hf_5_0"],
    tip="16 片底板就是航母的龙骨面。",
)
b.step(
    "舰艏封板与舷墙起步: 舰艏立 2 片封板, 左右舷各起 2 片 "
    "(x 0..2), 拐角竖边互吸。",
    ["bow_s", "bow_n", "hs_0", "hs_1", "hn_0", "hn_1"],
    highlight=["hf_0_0", "hf_0_1"],
    tip="封板与舷墙在舰艏拐角互吸 —— 船头先合龙。",
)
b.step(
    "舷墙中段: 左右舷各续 3 片 (x 2..5)。",
    ["hs_2", "hs_3", "hs_4", "hn_2", "hn_3", "hn_4"],
    highlight=["hs_1", "hn_1"],
    tip="舷墙底边吸底板边、竖边吸邻墙 —— 双保险一路向东。",
)
b.step(
    "舷墙艉段: 各续 3 片到 x=8, 舰尾整面开敞 —— 那是机库大门。",
    ["hs_5", "hs_6", "hs_7", "hn_5", "hn_6", "hn_7"],
    highlight=["hs_4", "hn_4"],
    tip="从舰尾望进去: 8 格深的机库一览无余。",
)
b.step(
    "飞行甲板·艏段: 6 片甲板压上舷墙与封板顶边 (x 0..3)。",
    [f"fd_{x0}_{y0}" for x0 in range(3) for y0 in range(2)],
    highlight=["bow_s", "hs_0"],
    tip="甲板同时吸住舷墙顶边与相邻板边 —— 机库从此有了天花板。",
)
b.step(
    "飞行甲板·中段: 再压 6 片 (x 3..6)。",
    [f"fd_{x0}_{y0}" for x0 in (3, 4, 5) for y0 in range(2)],
    highlight=["fd_2_0"],
    tip="每片都要听到与舷墙顶边的咔哒声再松手。",
)
b.step(
    "飞行甲板·艉段: 4 片合拢, 全通甲板贯通艏艉。",
    [f"fd_{x0}_{y0}" for x0 in (6, 7) for y0 in range(2)],
    highlight=["fd_5_0"],
    tip="全通式飞行甲板 —— 航母最威风的一条直线。",
)
b.step(
    "舰艏滑跃坡道: 双车道 30 度坡道顶边吸甲板艏沿, 坡尾直探"
    "水线 —— 舰载机从这里跃出海平面。",
    ["ski_s", "ski_n"],
    highlight=["fd_0_0", "fd_0_1"],
    tip="坡道顶边与甲板艏沿、封板顶边三线合一, 一吸三牢。",
)
b.step(
    "舰岛下层: 6 片黄色舱壁立在右舷甲板上 (x 4..6, y 1..2)。",
    ["is_s1_4", "is_s1_5", "is_n1_4", "is_n1_5", "is_w1", "is_e1"],
    highlight=["fd_4_1", "fd_5_1"],
    tip="舱壁底边吸甲板板缝 —— 舰岛永远在右舷, 这是航母的规矩。",
)
b.step(
    "舰岛上层舰桥: 再叠 6 片, 朝甲板一面用透明片 —— 舰长要"
    "看清每一次起降。",
    ["is_s2_4", "is_s2_5", "is_n2_4", "is_n2_5", "is_w2", "is_e2"],
    highlight=["is_s1_4", "is_e1"],
    tip="透明舰桥朝南 (飞行甲板一侧), 上下层对缝叠齐。",
)
b.step(
    "舰岛顶板与信号桅: 2 片顶板封舱, 东格南沿立 1 片红色信号桅。",
    ["is_top_4", "is_top_5", "mast"],
    highlight=["is_s2_5", "is_e2"],
    tip="顶板四边吸满舱壁顶边, 信号桅是全舰最高的红色标记。",
)
b.step(
    "雷达罩: 4 片橙色等腰三角形在舰岛西格锁成四坡尖罩。",
    RADAR,
    highlight=["is_top_4"],
    tip="斜棱两两互吸自锁 —— 雷达罩咔哒一声扣上舰岛。",
)
b.step(
    "1 号舰载机: 双侧机身立在艏部甲板上, 机翼顶板压顶, 尾翼"
    "朝舰尾 —— 随时准备滑跃起飞。",
    ["j1_s", "j1_n", "j1_wing", "j1_fin"],
    highlight=["fd_1_0", "fd_1_1"],
    tip="机身底边吸甲板板缝, 机翼板同时锁住两片机身。",
)
b.step(
    "2 号舰载机: 同法再停一架在左前方, 双机梯队。",
    ["j2_s", "j2_n", "j2_wing", "j2_fin"],
    highlight=["j1_wing"],
    tip="两架飞机错开半个身位 —— 甲板调度员的标准摆位。",
)
b.step(
    "甲板护网: 4 片透明护网立在甲板边沿 —— 拦住每一个滚向"
    "舷边的轮挡。",
    ["net_s6", "net_s7", "net_n0", "net_n6"],
    highlight=["fd_6_0", "fd_0_1"],
    tip="护网底边吸甲板沿边, 透明片不挡舰长视线。",
)
b.step(
    "舰尾旗: 舰尾甲板沿立 1 面绿旗 —— 航母甲板段列装服役!",
    ["stern_flag"],
    highlight=["fd_7_0"],
    tip="从舰尾机库大门再望一眼: 箱形船体 + 全通甲板, 这就是航母。",
)

b.finalize(
    model_id="aircraft_carrier_01",
    name="航母甲板段",
    name_en="Aircraft Carrier Deck 01",
    description=(
        "全库第一艘箱形船体: 8 格长机库箱体舰尾开敞、全通飞行甲板同时"
        "压住双舷墙与舰艏封板 (三路支撑互为冗余), 舰艏双车道 30 度滑跃"
        "坡道直探水线; 右舷两层舰岛带透明舰桥、四坡雷达罩与信号桅, "
        "甲板上双机梯队整装待发 —— 从舰尾望进机库, 8 格纵深一览无余。"
    ),
    difficulty=4,
    tags=["军港巡礼", "舰船", "载具", "机库"],
    min_pieces=80,
    min_steps=18,
)
