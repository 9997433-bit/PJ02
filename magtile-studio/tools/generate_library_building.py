#!/usr/bin/env python3
"""生成模型 data/models/library_building_01.json (城市图书馆)。

城市生活主题: 全库第一座图书馆 —— 两层通高的阅览大厅整面
南向玻璃幕墙, 馆内三列彩色书架隔着玻璃看得清清楚楚 (先上架
后封顶, 装配顺序过 R7b 可达性校验); 东端书塔三层拔起戴四坡
橙顶, 屋面栏板与馆旗收边; 门前广场上一座"巨书亭" —— 红色
讲台墙顶摊开两页 30 度斜板, 像一本永远翻开的书 —— 嘘,
阅览区请保持安静!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 幕墙朝南):
  - 馆底板 (x 0..6, y 2..4) x12 + 塔底 x1 + 广场 (y 1..2) x7   20 片
  - 大厅墙体两层: 玻璃幕墙 x12 + 背墙 x12 + 端墙 x8            32 片
  - 馆内书架 x3 (先上架后封顶)                                   3 片
  - 屋面 x12 + 屋顶栏板 x3 + 馆旗 x1                            16 片
  - 书塔 (x 6..7, y 2..3): 三层围壁 x10 + 四坡塔尖 x4           14 片
  - 巨书亭: 讲台墙 x1 + 30 度书页 x2; 广场绿树 x2                5 片
  合计 90 片, 18 个教程步骤, 4 种片形。

物理规则要点 (通过 R1~R8 全部校验):
  - 大厅两层箱形环: 上层墙底边整边吸下层墙顶边, 屋面四边吸满
    墙顶 —— 层环+顶环双重冗余;
  - 书架是"先内后外"装配顺序的教科书案例: 在封顶之前上架,
    每片底边整边吸底板拼缝, 顶上天窗方向伸手可达 (R7b 全绿);
  - 巨书亭 = 滚珠塔 30 度坡道技法的 A 字化用: 两页顶边同时
    整边吸讲台墙顶边并互吸, 坡尾自然落地 —— 三路受力;
  - 书塔借用大厅东墙作西壁 (共享承重), 每层四角竖边互吸成环。

用法: python3 tools/generate_library_building.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

FLOOR = "yellow"    # 馆内木地板
PLAZA = "gray"      # 门前广场
GLASS = "clear"     # 玻璃幕墙
BRICK = "red"       # 砖墙
ROOF = "gray"       # 屋面
TOWER = "red"       # 书塔
SPIRE = "orange"    # 塔尖
BOOK = "red"        # 巨书亭讲台
PAGE = "clear"      # 书页
TREE = "green"      # 绿树

# =================================================================
# 1. 馆底板 (z=0): 6x2 木地板 + 书塔底板 + 门前广场
# =================================================================
for x0 in range(6):
    for y0 in (2, 3):
        b.flat(f"fl_{x0}_{y0}", x0, y0, 0.0, FLOOR)
b.flat("fl_tower", 6, 2, 0.0, FLOOR)                # 塔底 [6..7]x[2..3]
for x0 in range(7):
    b.flat(f"pz_{x0}", x0, 1, 0.0, PLAZA)           # 广场 y[1..2]

# =================================================================
# 2. 大厅墙体两层 (z 0..2): 南玻璃幕墙 / 北背墙 / 东西端墙
# =================================================================
for lv in (0, 1):
    for x0 in range(6):
        b.wall_ns(f"gw{lv}_{x0}", x0, 2.0, lv, GLASS)   # 玻璃幕墙 y=2
        b.wall_ns(f"bw{lv}_{x0}", x0, 4.0, lv, BRICK)   # 背墙 y=4
    for y0 in (2, 3):
        b.wall_ew(f"ww{lv}_{y0}", 0.0, y0, lv, BRICK)   # 西端墙
        b.wall_ew(f"ew{lv}_{y0}", 6.0, y0, lv, BRICK)   # 东端墙

# =================================================================
# 3. 馆内书架 (z 0..1): 三列彩色书架, 先上架后封顶
# =================================================================
b.wall_ew("shelf_a", 1.0, 2, 0, "purple")
b.wall_ew("shelf_b", 3.0, 2, 0, "green")
b.wall_ew("shelf_c", 5.0, 2, 0, "blue")

# =================================================================
# 4. 屋面 (z=2) + 屋顶栏板 + 馆旗
# =================================================================
for x0 in range(6):
    for y0 in (2, 3):
        b.flat(f"rf_{x0}_{y0}", x0, y0, 2.0, ROOF)
b.crest_ns("bal_0", 0, 2.0, 2.0, BRICK)             # 屋顶栏板 (南沿)
b.crest_ns("bal_2", 2, 2.0, 2.0, BRICK)
b.crest_ns("bal_4", 4, 2.0, 2.0, BRICK)
b.crest_ew("flag", 0.0, 3, 2.0, SPIRE)              # 馆旗 (西北角)

# =================================================================
# 5. 书塔 (x 6..7, y 2..3, z 0..3): 西壁借用大厅东墙
# =================================================================
for lv in (0, 1):
    b.wall_ns(f"tw_s{lv}", 6, 2.0, lv, TOWER)
    b.wall_ns(f"tw_n{lv}", 6, 3.0, lv, TOWER)
    b.wall_ew(f"tw_e{lv}", 7.0, 2, lv, TOWER)
b.wall_ns("tw_s2", 6, 2.0, 2, TOWER)                # 第三层完整四壁
b.wall_ns("tw_n2", 6, 3.0, 2, TOWER)
b.wall_ew("tw_e2", 7.0, 2, 2, TOWER)
b.wall_ew("tw_w2", 6.0, 2, 2, TOWER)
SPIRE_IDS = b.hat4("spire", 6, 2, 3.0, SPIRE,
                   shape="equilateral_triangle")

# =================================================================
# 6. 巨书亭 (广场 x 2.3..5.7, y 1..2) + 绿树
# =================================================================
b.wall_ew("lectern", 4.0, 1, 0, BOOK)               # 讲台墙
b.ramp("page_e", "+x", 4.0, 1, 1.0, PAGE)           # 东页
b.ramp("page_w", "-x", 4.0, 1, 1.0, PAGE)           # 西页
b.crest_ns("tree_w", 0, 1.0, 0.0, TREE)             # 绿树
b.crest_ns("tree_e", 6, 1.0, 0.0, TREE)

# =================================================================
# 教程步骤 (18 步)
# =================================================================
b.step(
    "铺馆底板·西半: 6 片黄色木地板双列并进 (x 0..3)。",
    [f"fl_{x0}_{y0}" for x0 in (0, 1, 2) for y0 in (2, 3)],
    tip="木地板逐格拼缝互吸 —— 书架与墙脚全踩在这些缝上。",
)
b.step(
    "铺馆底板·东半与塔底: 再铺 6 片, 塔底 1 片收在东端。",
    [f"fl_{x0}_{y0}" for x0 in (3, 4, 5) for y0 in (2, 3)]
    + ["fl_tower"],
    highlight=["fl_2_2", "fl_2_3"],
    tip="塔底方板单独一格 —— 书塔将从这里拔地而起。",
)
b.step(
    "铺门前广场: 7 片灰色方板沿南面一字排开 (y 1..2)。",
    [f"pz_{x0}" for x0 in range(7)],
    highlight=["fl_0_2", "fl_5_2"],
    tip="广场北边整边吸馆底板南边 —— 巨书亭一会儿就立在这里。",
)
b.step(
    "立一层玻璃幕墙: 6 片透明方墙沿 y=2 线立起。",
    [f"gw0_{x0}" for x0 in range(6)],
    highlight=["pz_0", "pz_5"],
    tip="墙脚同时咬住底板缝与广场缝 —— 双铰链保险。",
)
b.step(
    "立一层背墙: 6 片红砖方墙 (y=4 线), 接地起步竖边互吸。",
    [f"bw0_{x0}" for x0 in range(6)],
    highlight=["gw0_0"],
    tip="背墙一侧是安静的书库 —— 不开窗, 保护古籍防晒。",
)
b.step(
    "封一层端墙: 东西端各 2 片, 拐角竖边互吸, 一层箱形合龙。",
    ["ww0_2", "ww0_3", "ew0_2", "ew0_3"],
    highlight=["gw0_0", "bw0_5"],
    tip="端墙一合, 大厅一层闭环 —— 这是二层的地基。",
)
b.step(
    "馆内上书架: 三列彩色书架踩底板拼缝立进大厅 —— 趁封顶之前, "
    "从天窗方向伸手正好。",
    ["shelf_a", "shelf_b", "shelf_c"],
    highlight=["fl_1_2", "fl_3_2", "fl_5_2"],
    tip="先内后外是装配铁律 —— 封顶之后手可就伸不进去了。",
)
b.step(
    "立二层玻璃幕墙: 6 片透明方墙底边整边吸一层墙顶。",
    [f"gw1_{x0}" for x0 in range(6)],
    highlight=["gw0_2", "gw0_3"],
    tip="两层通高幕墙 —— 阳光洒满整个阅览区。",
)
b.step(
    "立二层背墙: 再叠 6 片红砖方墙, 上下层严格对缝。",
    [f"bw1_{x0}" for x0 in range(6)],
    highlight=["bw0_0", "bw0_5"],
    tip="荷载顺墙身直落底板 —— 书比砖沉, 墙要站得直。",
)
b.step(
    "封二层端墙: 东西端再各 2 片, 二层箱形合龙。",
    ["ww1_2", "ww1_3", "ew1_2", "ew1_3"],
    highlight=["ww0_2", "ew0_2"],
    tip="层环叠层环 —— 大厅的骨架完成了。",
)
b.step(
    "盖屋面·西半: 6 片灰色方板四边吸满墙顶 (x 0..3)。",
    [f"rf_{x0}_{y0}" for x0 in (0, 1, 2) for y0 in (2, 3)],
    highlight=["gw1_0", "bw1_2"],
    tip="每片听到与墙顶的咔哒声再松手 —— 阅览区从此风雨无忧。",
)
b.step(
    "盖屋面·东半: 再盖 6 片, 大厅封顶。",
    [f"rf_{x0}_{y0}" for x0 in (3, 4, 5) for y0 in (2, 3)],
    highlight=["rf_2_2"],
    tip="屋面与墙顶锁成顶环 —— 层环+顶环双重冗余。",
)
b.step(
    "立屋顶栏板与馆旗: 南沿 3 片红砖三角, 西北角 1 面橙旗。",
    ["bal_0", "bal_2", "bal_4", "flag"],
    highlight=["rf_0_2", "rf_4_2"],
    tip="栏板底边整边吸屋面沿边 —— 屋顶花园改天见。",
)
b.step(
    "书塔一层: 3 片红色方墙围上塔底, 西壁借用大厅东墙。",
    ["tw_s0", "tw_n0", "tw_e0"],
    highlight=["ew0_2", "fl_tower"],
    tip="共享墙体省料又承重 —— 塔与馆从一开始就长在一起。",
)
b.step(
    "书塔二层: 再叠 3 片, 与大厅二层同步升高。",
    ["tw_s1", "tw_n1", "tw_e1"],
    highlight=["tw_s0", "ew1_2"],
    tip="上下层对缝, 四角竖边互吸成环。",
)
b.step(
    "书塔三层: 4 片完整围壁高出屋面 —— 塔里挂着借阅钟。",
    ["tw_s2", "tw_n2", "tw_e2", "tw_w2"],
    highlight=["tw_s1"],
    tip="第三层已高过大厅屋面, 从这里俯瞰整条街。",
)
b.step(
    "扣四坡塔尖: 4 片橙色等边三角四棱互吸自锁。",
    SPIRE_IDS,
    highlight=["tw_s2", "tw_e2"],
    tip="塔尖一扣, 全城都认得图书馆的方向。",
)
b.step(
    "巨书亭与绿树: 讲台墙立上广场拼缝, 两页 30 度斜板顶边同时"
    "吸墙顶并互吸、坡尾落地, 东西再各栽 1 棵绿树 —— 开馆!",
    ["lectern", "page_e", "page_w", "tree_w", "tree_e"],
    highlight=["pz_3", "pz_4"],
    tip="一本永远翻开的书 —— 嘘, 阅览区请保持安静!",
)

b.finalize(
    model_id="library_building_01",
    name="城市图书馆",
    name_en="City Library 01",
    description=(
        "全库第一座图书馆: 两层通高阅览大厅整面南向玻璃幕墙, 馆内三列"
        "彩色书架先上架后封顶 (R7b 装配顺序教科书案例), 隔着玻璃一目了然; "
        "东端书塔借大厅东墙作西壁, 三层拔起戴四坡橙顶; 门前广场立着"
        "巨书亭 —— 讲台墙顶摊开两页 30 度斜板, 像一本永远翻开的书, "
        "顶边互吸坡尾落地三路受力 —— 嘘, 阅览区请保持安静!"
    ),
    difficulty=4,
    tags=["城市生活", "图书馆", "玻璃幕墙", "文化建筑", "进阶"],
    min_pieces=85,
    min_steps=18,
)
