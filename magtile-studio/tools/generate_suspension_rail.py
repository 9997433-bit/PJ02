#!/usr/bin/env python3
"""生成模型 data/models/suspension_rail_01.json (空中悬挂轨道车)。

城市交通主题: 全库第一条"车厢挂在轨道下面"的悬挂式单轨 ——
四座 T 形立柱 (单片薄墙 + 直角三角柱脚斜撑) 托起 z=3 的高架轨道梁;
中跨两端的承台朝跨内伸出, 让 [5,7] 吊舱湾完全避开柱身; 一节玻璃
头尾的吊舱用两片长板吊架挂在跨下 (吊架顶边整边吸梁底沿, 吊架-舱底-
端窗围成闭合吊箱, 剪断任一条铰链线都掉不下来); 吊舱北侧是同高的
车站月台, 乘客跨半格登车, 月台东端两段 30 度坡道折返下到地面;
轨道两端站台由柱身膝撑 (直角三角) 托住, 端头立挡板。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 轨道沿 +x, 柱线 x=1/4/8/11):
  - 地面: 轨道警示带 [0,12]x[0,1] + 车站前庭 2                   14 片
  - T 形立柱 x4: 三层薄墙 + 双侧柱脚斜撑                         20 片
  - 高架轨道: 柱顶承台 4 + 跨间长板 3 + 两端站台 2 + 膝撑 4      13 片
  - 轨道护栏: 承台/端台沿口 12 片三角 + 两端挡板 2               14 片
  - 吊舱 (挂于 [5,7] 跨下): 吊架长板 2 + 舱底长板 1 + 玻璃端窗 2  5 片
  - 车站: 月台柱 4 + 月台长板 1 + 下行坡道 2 + 转折平台 + 桥墩    9 片
  合计 75 片, 17 个教程步骤, 5 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 跨间长板两端同时吸承台边/柱顶边 (双端受力零悬挑), 整条轨道
    是横跨四柱的连续梁;
  - 吊舱是"挂"而非"摆": 两片吊架顶边分别整边吸轨道梁南北底沿,
    舱底长边吸吊架底边, 端窗竖边再锁吊架端边 —— 闭合吊箱;
  - 两端站台外挑一格, 由柱身膝撑 (竖直角边吸柱顶层竖边、水平
    直角边吸站台底沿) 提供第二条支撑路径, 挡板才立得起;
  - 柱脚斜撑让单片薄墙立柱抗侧倾; 下行坡道末段坡尾自然落地。

用法: python3 tools/generate_suspension_rail.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder, SQ3

b = ModelBuilder()

PYLON = "red"       # 立柱
TRACK = "gray"      # 轨道梁
CABIN = "yellow"    # 吊舱
RAIL = "orange"     # 护栏
LANE = "cyan"       # 地面警示带

COLS = (1, 4, 8, 11)                                # 立柱所在 x 线
CAPS = (1, 4, 7, 10)                                # 承台西沿 (中跨两台朝跨内)

# =================================================================
# 1. 地面: 轨道正下方警示带 [0,12]x[0,1] + 车站前庭 [5,7]x[1,2]
# =================================================================
for x in range(12):
    b.flat(f"ln_{x}", x, 0, 0.0, LANE if x % 2 == 0 else "blue")
b.flat("fc_5", 5, 1, 0.0, "gray")                   # 车站前庭
b.flat("fc_6", 6, 1, 0.0, "gray")

# =================================================================
# 2. T 形立柱 x4: 三层薄墙 (东西朝向) + 双侧柱脚斜撑
# =================================================================
for c in COLS:
    for z in range(3):
        b.wall_ew(f"col_{c}_{z}", float(c), 0, z, PYLON)
for c in COLS:
    b.brace(f"ft_{c}_w", (float(c), 0.0, 0.0), "-x", PYLON)
    b.brace(f"ft_{c}_e", (float(c), 0.0, 0.0), "+x", PYLON)

# =================================================================
# 3. 高架轨道 (z=3): 承台 + 跨间长板 + 两端站台 (带膝撑) + 挡板
# =================================================================
for x0 in CAPS:                                     # 承台: 一边吸柱顶边
    b.flat(f"cap_{x0}", x0, 0, 3.0, TRACK)
for x0 in (2, 5, 8):                                # 跨间长板 (双端受力)
    b.flat_rect(f"span_{x0}", x0, 0, 3.0, TRACK)
b.flat("end_w", 0, 0, 3.0, TRACK)                   # 西端站台 (外挑一格)
b.flat("end_e", 11, 0, 3.0, TRACK)                  # 东端站台
# 端台膝撑: 竖直角边吸柱顶层竖边, 水平直角边吸站台底沿
b.place_tri("kb_w_s", "right_triangle",
            (1.0, 0.0, 3.0), (0.0, 0.0, 3.0), (1.0, 0.0, 2.0), PYLON)
b.place_tri("kb_w_n", "right_triangle",
            (1.0, 1.0, 3.0), (0.0, 1.0, 3.0), (1.0, 1.0, 2.0), PYLON)
b.place_tri("kb_e_s", "right_triangle",
            (11.0, 0.0, 3.0), (12.0, 0.0, 3.0), (11.0, 0.0, 2.0), PYLON)
b.place_tri("kb_e_n", "right_triangle",
            (11.0, 1.0, 3.0), (12.0, 1.0, 3.0), (11.0, 1.0, 2.0), PYLON)
b.crest_ew("stop_w", 0.0, 0, 3.0, RAIL)             # 端头挡板
b.crest_ew("stop_e", 12.0, 0, 3.0, RAIL)

# 轨道护栏: 承台与端台的南北沿口 (跨间沿口留空 = 吊架滑槽)
GUARD_X = (0, 1, 4, 7, 10, 11)
for x0 in GUARD_X:
    b.crest_ns(f"gd_s_{x0}", x0, 0.0, 3.0, RAIL)
    b.crest_ns(f"gd_n_{x0}", x0, 1.0, 3.0, RAIL)

# =================================================================
# 4. 吊舱 (挂于 [5,7] 跨下): 吊架 + 舱底 + 玻璃端窗, 闭合吊箱
# =================================================================
b.lintel_ns("hg_s", 5, 0.0, 2, CABIN)               # 南吊架, 顶边吸梁南底沿
b.lintel_ns("hg_n", 5, 1.0, 2, CABIN)               # 北吊架
b.flat_rect("cab_fl", 5, 0, 2.0, CABIN)             # 舱底, 长边吸吊架底边
b.wall_ew("cab_w", 5.0, 0, 2, "clear")              # 玻璃端窗 (车头)
b.wall_ew("cab_e", 7.0, 0, 2, "clear")              # 玻璃端窗 (车尾)

# =================================================================
# 5. 车站 (吊舱北侧): 月台柱 + 月台长板 (z=2) + 折返下行坡道
# =================================================================
for z in range(2):
    b.wall_ew(f"st_w_{z}", 5.0, 1, z, "purple")     # 月台西柱
    b.wall_ew(f"st_e_{z}", 7.0, 1, z, "purple")     # 月台东柱
b.flat_rect("plat", 5, 1, 2.0, "purple")            # 月台, 两端压柱顶
b.ramp("st_r1", "+x", 7.0, 1, 2.0, "gray")          # 上段坡道 z2->z1
MX = 7.0 + SQ3                                      # 转折平台西沿 8.732051
b.wall_ew("st_p", MX, 1, 0, "purple")               # 坡尾桥墩
b.flat("st_mid", MX, 1, 1.0, "gray")                # 转折平台
b.ramp("st_r2", "+x", MX + 1.0, 1, 1.0, "gray")     # 下段坡道, 坡尾落地

# =================================================================
# 教程步骤 (17 步)
# =================================================================
b.step(
    "铺警示带西半段: 轨道正下方铺 6 片青蓝相间方板 ([0,6]x[0,1])。",
    [f"ln_{x}" for x in range(6)],
    tip="悬挂轨道的正下方永远画警示带 —— 这也是全线的地面基准。",
)
b.step(
    "铺警示带东半段: 再铺 6 片, 警示带贯通 12 格。",
    [f"ln_{x}" for x in range(6, 12)],
    highlight=["ln_5"],
    tip="四座立柱将立在 x = 1/4/8/11 四条格线上。",
)
b.step(
    "铺车站前庭: 警示带北侧 [5,7] 段接 2 片灰色前庭方板。",
    ["fc_5", "fc_6"],
    highlight=["ln_5", "ln_6"],
    tip="前庭是月台柱的地基, 也是乘客进站的地面入口。",
)
b.step(
    "立四座立柱第 1 层: 4 片红色薄墙分别立上四条格线, 底边吸警示带边。",
    [f"col_{c}_0" for c in COLS],
    highlight=["ln_0", "ln_11"],
    tip="T 形柱是单片薄墙 —— 省料通透, 下一步马上加斜撑。",
)
b.step(
    "装柱脚斜撑: 每柱东西两侧各 1 片直角三角, 竖直角边吸柱身竖边、"
    "水平直角边吸警示带边。",
    [f"ft_{c}_{side}" for c in COLS for side in ("w", "e")],
    highlight=[f"col_{c}_0" for c in COLS],
    tip="斜撑装完, 薄墙立柱立刻抗侧倾 —— 轻推柱顶试试。",
)
b.step(
    "立柱加高到第 2 层: 每柱再叠 1 片, 上下边完整贴合。",
    [f"col_{c}_1" for c in COLS],
    highlight=["ft_1_w", "col_1_0"],
    tip="对缝直叠, 别错位 —— 柱身是全线唯一的竖向传力路径。",
)
b.step(
    "立柱加高到第 3 层: 四柱齐平三层高, 高架轨道的标高就位。",
    [f"col_{c}_2" for c in COLS],
    highlight=["col_1_1"],
    tip="越高越要轻放, 一手扶柱一手放片。",
)
b.step(
    "盖柱顶承台: 4 片灰色方板一边吸柱顶边 —— 注意中间两台朝跨内伸, "
    "给吊舱湾让出柱位。",
    [f"cap_{x0}" for x0 in CAPS],
    highlight=[f"col_{c}_2" for c in COLS],
    tip="承台悬挑半格 (力矩 15 <= 预算 20), 马上就有跨板来帮忙。",
)
b.step(
    "架跨间长板: 3 片灰色长板依次落下, 每片两端同时吸左右承台边/柱顶边。",
    ["span_2", "span_5", "span_8"],
    highlight=["cap_1", "cap_10"],
    tip="双端受力零悬挑 —— 高架轨道梁一次成型, 是横跨四柱的连续梁。",
)
b.step(
    "接两端站台并装膝撑: 轨道两端各外挑 1 片站台, 每片下方装 2 片"
    "直角三角膝撑 (竖边吸柱顶层竖边, 横边吸站台底沿)。",
    ["end_w", "kb_w_s", "kb_w_n", "end_e", "kb_e_s", "kb_e_n"],
    highlight=["cap_1", "cap_10"],
    tip="膝撑给外挑站台第二条支撑路径 —— 端头才敢再立挡板。",
)
b.step(
    "装端头挡板与南侧护栏: 两端立三角挡板, 承台/端台南沿立 6 片护栏 "
    "(跨间沿口留空 = 吊架滑槽)。",
    ["stop_w", "stop_e"] + [f"gd_s_{x0}" for x0 in GUARD_X],
    highlight=["end_w", "end_e"],
    tip="护栏只立在承台上 —— 跨间要留给吊舱的吊架通过。",
)
b.step(
    "装北侧护栏: 再立 6 片, 高架轨道全线合栏。",
    [f"gd_n_{x0}" for x0 in GUARD_X],
    highlight=["gd_s_0"],
    tip="从侧面看: 一条镂空的高架轨道梁已经悬在半空。",
)
b.step(
    "挂吊架封舱底: 南吊架顶边整边吸梁南底沿, 舱底长板长边先吸南吊架"
    "底边, 北吊架再压住舱底北长边并吸梁北底沿。",
    ["hg_s", "cab_fl", "hg_n"],
    highlight=["span_5"],
    tip="吊舱是'挂'上去的 —— 顶边贴合越严, 吊舱越稳。",
)
b.step(
    "锁玻璃端窗: 头尾 2 片透明端窗, 竖边吸吊架端边、底边吸舱底短边。",
    ["cab_w", "cab_e"],
    highlight=["hg_s", "hg_n"],
    tip="吊架-舱底-端窗围成闭合吊箱: 剪断任何一条缝都掉不下来。",
)
b.step(
    "立月台柱: 吊舱北侧前庭上立 2x2 片紫色月台柱。",
    ["st_w_0", "st_w_1", "st_e_0", "st_e_1"],
    highlight=["fc_5", "fc_6"],
    tip="柱底边吸前庭方板边, 柱高两层 = 吊舱舱底标高。",
)
b.step(
    "铺月台: 1 片紫色长板两端压柱顶, 南沿恰与舱底北沿同高相吸。",
    ["plat"],
    highlight=["st_w_1", "cab_fl"],
    tip="月台与舱底零高差 —— 乘客跨半步就登车。",
)
b.step(
    "修下行坡道: 上段坡道从月台东沿下探, 桥墩接坡尾并铺转折平台, "
    "下段坡道再落到地面 —— 空中悬挂轨道车通车!",
    ["st_r1", "st_p", "st_mid", "st_r2"],
    highlight=["plat"],
    tip="坡道-桥墩-平台三件互吸 (滚珠塔同款), 末段坡尾自然落地。",
)

b.finalize(
    model_id="suspension_rail_01",
    name="空中悬挂轨道车",
    name_en="Suspension Monorail 01",
    description=(
        "全库第一条车厢挂在轨道下面的悬挂式单轨: 四座 T 形薄墙立柱带直角"
        "三角柱脚斜撑, 托起三层高的连续轨道梁 (跨间长板双端受力零悬挑, "
        "两端站台由柱身膝撑托住); 玻璃头尾的吊舱用两片吊架挂在中跨下方, "
        "吊架-舱底-端窗围成闭合吊箱, 剪断任一条铰链线都兜得住; 北侧月台与"
        "舱底零高差, 东端两段 30 度坡道折返下地 —— 头顶列车驶过, 地面警示"
        "带亮起。"
    ),
    difficulty=3,
    tags=["交通", "轨道", "悬挂列车", "城市", "工程"],
    min_pieces=70,
    min_steps=16,
)
