#!/usr/bin/env python3
"""生成模型 data/models/parking_garage_01.json (立体停车场)。

城市交通主题: 全库第一座敞开式立体车库 —— 没有一面完整的外墙,
两层车板全部架在黄色立柱上: 一层车板 6 片长板纵铺, 南北立柱
上下对齐、柱脚四角直角三角斜撑锁地; 前街入口匝道 30 度爬上
一层, 后院出口匝道俯冲落地; 顶层车板四周青色护栏围边,
下行坡道从顶层北沿经中继桥墩两段接力降回地面 (坡道链);
西侧红色电梯塔三层直上, 透明观景层戴等腰四坡尖顶, 4.94 格
高俯瞰全场 —— 车位已满, 请上二层!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 入口朝南):
  - 街区地坪 8x5 + 后院车道: 街道/人行道/库区/后院            30 片
  - 一层立柱 x5 (南北交错) + 柱脚直角三角斜撑 x4               9 片
  - 一层车板: 长板 x6 (1x2 纵铺, 柱顶整边受力)                 6 片
  - 出入口匝道: 30 度长板 x2 (顶边吸车板沿, 坡尾自然落地)      2 片
  - 二层立柱 x5 + 二层车板长板 x6                              11 片
  - 顶层护栏: 等边三角 x5                                       5 片
  - 下行坡道链: 30 度长板 x2 + 中继桥墩方板 x1                  3 片
  - 电梯塔 1x1 三层 (方墙 x12) + 等腰四坡尖顶 x4               16 片
  合计 82 片, 18 个教程步骤, 5 种磁力片形状 (CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验):
  - 车板长板 1x2 纵铺: 南北两端整边压立柱顶, 相邻车板长边
    互吸 —— 柱-板-柱锁成多环框架, 剪断任一条铰链线力都绕行;
  - 柱脚直角三角斜撑双边吸合 (竖边吸柱竖边, 横边吸地坪格线),
    抵抗车板层的侧向晃动;
  - 下行坡道链: 上段顶边吸顶层车板北沿, 坡尾由中继桥墩顶边
    接住 (三角刚性节点), 下段再从墩顶俯冲自然落地 —— 每段
    两端受力, 零悬臂;
  - 电梯塔圈层砌法三层自锁, 东壁贴住车板西沿共享受力。

用法: python3 tools/generate_parking_garage.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder, SQ3

b = ModelBuilder()

STREET = "gray"     # 街道
WALK = "cyan"       # 人行道
FLOOR = "gray"      # 库区地坪
LAWN = "green"      # 后院绿化
LANE = "gray"       # 后院车道
COL = "yellow"      # 立柱
BRACE = "orange"    # 柱脚斜撑
DECK = "gray"       # 车板
RAIL = "cyan"       # 顶层护栏
RAMP = "blue"       # 匝道
TOWER = "red"       # 电梯塔
VIEW = "clear"      # 观景层

# =================================================================
# 1. 街区地坪: 街道 y0..1 / 人行道 y1..2 / 库区 y2..4 / 后院 y4..5
# =================================================================
for i, x0 in enumerate((0, 2, 4, 6)):
    b.flat_rect(f"st_{i}", x0, 0, 0.0, STREET)      # 街道
for i, x0 in enumerate((0, 2, 4, 6)):
    b.flat_rect(f"wk_{i}", x0, 1, 0.0, WALK)        # 人行道
b.flat("f2_0", 0, 2, 0.0, FLOOR)
b.flat("f2_1", 1, 2, 0.0, FLOOR)
b.flat_rect("f2_r1", 2, 2, 0.0, FLOOR)              # [2,4]
b.flat("f2_4", 4, 2, 0.0, FLOOR)
b.flat_rect("f2_r2", 5, 2, 0.0, FLOOR)              # [5,7]
b.flat("f2_7", 7, 2, 0.0, FLOOR)
b.flat("f3_0", 0, 3, 0.0, FLOOR)
b.flat("f3_1", 1, 3, 0.0, FLOOR)
b.flat("f3_2", 2, 3, 0.0, FLOOR)
b.flat_rect("f3_r1", 3, 3, 0.0, FLOOR)              # [3,5]
b.flat("f3_5", 5, 3, 0.0, FLOOR)
b.flat("f3_6", 6, 3, 0.0, FLOOR)
b.flat("f3_7", 7, 3, 0.0, FLOOR)
b.flat_rect("y4_a", 0, 4, 0.0, LAWN)                # 后院 [0,2]
b.flat("y4_lane1", 2, 4, 0.0, LANE)                 # 出口车道
b.flat_rect("y4_b", 3, 4, 0.0, LAWN)                # [3,5]
b.flat("y4_lane2", 5, 4, 0.0, LANE)                 # 下行车道
b.flat_rect("y4_c", 6, 4, 0.0, LAWN)                # [6,8]
b.flat("ln_exit", 2, 5, 0.0, LANE)                  # 出口坡道落点
b.flat("ln_d1", 5, 5, 0.0, LANE)                    # 下行车道延伸
b.flat("ln_d2", 5, 6, 0.0, LANE)
b.flat("ln_d3", 5, 7, 0.0, LANE)                    # 接地坡道落点

# =================================================================
# 2. 一层立柱 (z0..1) 南北交错 + 柱脚斜撑
# =================================================================
b.wall_ns("c1_s1", 1, 2.0, 0, COL)                  # 南柱 [1,2]
b.wall_ns("c1_s4", 4, 2.0, 0, COL)                  # 南柱 [4,5]
b.wall_ns("c1_s6", 6, 2.0, 0, COL)                  # 南柱 [6,7]
b.wall_ns("c1_n2", 2, 4.0, 0, COL)                  # 北柱 [2,3]
b.wall_ns("c1_n5", 5, 4.0, 0, COL)                  # 北柱 [5,6]
b.brace("br_sw", (1.0, 2.0, 0.0), "-x", BRACE)      # 西南斜撑
b.brace("br_se", (7.0, 2.0, 0.0), "+x", BRACE)      # 东南斜撑
b.brace("br_nw", (2.0, 4.0, 0.0), "-x", BRACE)      # 西北斜撑
b.brace("br_ne", (6.0, 4.0, 0.0), "+x", BRACE)      # 东北斜撑

# =================================================================
# 3. 一层车板 (z=1): 6 片长板纵铺 [x,x+1]x[2,4]
# =================================================================
for x in range(1, 7):
    b.flat_rect(f"d1_{x}", x, 2, 1.0, DECK, axis="y")

# =================================================================
# 4. 出入口匝道 (30 度, 坡尾自然落地)
# =================================================================
b.ramp("ramp_in", "-y", 2.0, 6, 1.0, RAMP)          # 入口: 前街爬上一层
b.ramp("ramp_out", "+y", 4.0, 2, 1.0, RAMP)         # 出口: 后院俯冲落地

# =================================================================
# 5. 二层立柱 (z1..2) + 二层车板 (z=2)
# =================================================================
b.wall_ns("c2_s1", 1, 2.0, 1, COL)
b.wall_ns("c2_s4", 4, 2.0, 1, COL)
b.wall_ns("c2_s6", 6, 2.0, 1, COL)
b.wall_ns("c2_n2", 2, 4.0, 1, COL)
b.wall_ns("c2_n5", 5, 4.0, 1, COL)
for x in range(1, 7):
    b.flat_rect(f"d2_{x}", x, 2, 2.0, DECK, axis="y")

# =================================================================
# 6. 顶层护栏 (等边三角) + 下行坡道链
# =================================================================
for x in (1, 3, 5):
    b.crest_ns(f"rl_s{x}", x, 2.0, 2.0, RAIL)       # 南沿护栏
for x in (1, 3):
    b.crest_ns(f"rl_n{x}", x, 4.0, 2.0, RAIL)       # 北沿护栏
b.ramp("ramp_dn", "+y", 4.0, 5, 2.0, RAMP)          # 顶层下行段
b.add("pier", "square", (5.5, 4.0 + SQ3, 0.5), (90, 0, 0), COL)  # 中继桥墩
b.ramp("ramp_gd", "+y", 4.0 + SQ3, 5, 1.0, RAMP)    # 接地段

# =================================================================
# 7. 电梯塔 1x1 [0,1]x[3,4]: 三层圈层 + 等腰四坡尖顶
# =================================================================
for z, c in ((0, TOWER), (1, TOWER), (2, VIEW)):
    b.wall_ns(f"tw_s{z}", 0, 3.0, z, c)
    b.wall_ns(f"tw_n{z}", 0, 4.0, z, c)
    b.wall_ew(f"tw_w{z}", 0.0, 3, z, c)
    b.wall_ew(f"tw_e{z}", 1.0, 3, z, c)
TOWER_HAT = b.hat4("th", 0, 3, 3.0, TOWER)

# =================================================================
# 教程步骤 (18 步)
# =================================================================
b.step(
    "铺街道与人行道: 4 片灰色长板是前街, 4 片青色长板是人行道。",
    [f"st_{i}" for i in range(4)] + [f"wk_{i}" for i in range(4)],
    tip="车流从前街驶入 —— 入口匝道马上要架在人行道上空。",
)
b.step(
    "铺库区南半: 方板落在立柱线上, 长板补中段。",
    ["f2_0", "f2_1", "f2_r1", "f2_4", "f2_r2", "f2_7"],
    highlight=["wk_0"],
    tip="南柱要踩在 y=2 格线上 —— 方板边线就是柱脚的落点。",
)
b.step(
    "铺库区北半: 再铺 7 片, 车库地基完成。",
    ["f3_0", "f3_1", "f3_2", "f3_r1", "f3_5", "f3_6", "f3_7"],
    highlight=["f2_0"],
    tip="北柱与电梯塔都踩这一排 —— 方板留足格线。",
)
b.step(
    "铺后院与车道: 绿化带夹着两条灰色车道, 车道一直伸到坡道落点。",
    ["y4_a", "y4_lane1", "y4_b", "y4_lane2", "y4_c",
     "ln_exit", "ln_d1", "ln_d2", "ln_d3"],
    highlight=["f3_2", "f3_5"],
    tip="西车道接出口匝道, 东车道接顶层下行坡道链。",
)
b.step(
    "立一层立柱: 南 3 北 2 交错排布, 底边整边吸地坪格线。",
    ["c1_s1", "c1_s4", "c1_s6", "c1_n2", "c1_n5"],
    highlight=["f2_1", "f3_2"],
    tip="敞开式车库没有外墙 —— 五根立柱就是全部支点。",
)
b.step(
    "锁柱脚斜撑: 四角直角三角双边吸合, 竖边吸柱、横边吸地。",
    ["br_sw", "br_se", "br_nw", "br_ne"],
    highlight=["c1_s1", "c1_n5"],
    tip="斜撑锁死侧向晃动 —— 车板上去之前先把脚站稳。",
)
b.step(
    "架一层车板: 6 片长板纵铺, 南北两端整边压柱顶, 相邻长边互吸。",
    [f"d1_{x}" for x in range(1, 7)],
    highlight=["c1_s1", "c1_n2"],
    tip="从西向东逐片推进 —— 柱-板-柱锁成框架环。",
)
b.step(
    "装出入口匝道: 入口从前街 30 度爬上南沿, 出口从北沿俯冲后院。",
    ["ramp_in", "ramp_out"],
    highlight=["d1_6", "d1_2"],
    tip="顶边整边吸车板沿口, 坡尾自己踩地 —— 零悬臂。",
)
b.step(
    "起电梯塔一层: 西侧 1x1 四面红墙拐角互吸。",
    ["tw_s0", "tw_n0", "tw_w0", "tw_e0"],
    highlight=["f3_0"],
    tip="塔东壁贴住一层车板西沿 —— 塔与车库共享受力。",
)
b.step(
    "立二层立柱: 与一层柱上下对齐, 底边整边吸车板边线。",
    ["c2_s1", "c2_s4", "c2_s6", "c2_n2", "c2_n5"],
    highlight=["d1_1", "d1_5"],
    tip="荷载顺柱身直落地面 —— 上下对齐是框架的纪律。",
)
b.step(
    "架二层车板: 再纵铺 6 片长板, 顶层停车面完成。",
    [f"d2_{x}" for x in range(1, 7)],
    highlight=["c2_s1", "c2_n2"],
    tip="与一层同样的铺法 —— 先柱顶板后邻板, 放下即吸。",
)
b.step(
    "起电梯塔二层: 沿一层塔顶再起一圈。",
    ["tw_s1", "tw_n1", "tw_w1", "tw_e1"],
    highlight=["tw_s0"],
    tip="上环整边压下环 —— 圈层砌法直上三层。",
)
b.step(
    "装顶层南护栏: 3 片青色等边三角沿南沿排开。",
    ["rl_s1", "rl_s3", "rl_s5"],
    highlight=["d2_1", "d2_5"],
    tip="底边整边吸车板沿口 —— 顶层停车先装护栏。",
)
b.step(
    "装顶层北护栏: 北沿再立 2 片, 东端留出下行坡道口。",
    ["rl_n1", "rl_n3"],
    highlight=["rl_s1"],
    tip="x5..6 的缺口不是漏装 —— 那是下行坡道的入口。",
)
b.step(
    "装顶层下行段与中继桥墩: 坡道从北沿俯冲, 坡尾由桥墩顶边接住。",
    ["ramp_dn", "pier"],
    highlight=["d2_5", "y4_lane2"],
    tip="墩顶与坡尾整边互吸成三角刚性节点 —— 两端受力零悬臂。",
)
b.step(
    "装接地段: 第二段坡道从墩顶继续俯冲, 坡尾落进车道尽头。",
    ["ramp_gd"],
    highlight=["pier"],
    tip="坡道链每段都两端受力 —— 顶层的车稳稳降回地面。",
)
b.step(
    "起电梯塔观景层: 第三层换透明墙, 360 度看车流。",
    ["tw_s2", "tw_n2", "tw_w2", "tw_e2"],
    highlight=["tw_s1"],
    tip="透明层是电梯厅也是观景台 —— 全场动线尽收眼底。",
)
b.step(
    "戴塔尖: 4 片等腰三角四坡合拢, 斜棱两两互吸自锁。",
    TOWER_HAT,
    highlight=["tw_s2"],
    tip="锥尖高 4.94 格俯瞰全场 —— 车位已满, 请上二层!",
)

b.finalize(
    model_id="parking_garage_01",
    name="立体停车场",
    name_en="Parking Garage 01",
    description=(
        "全库第一座敞开式立体车库: 没有一面完整外墙, 两层车板 (各 6 片"
        "长板纵铺) 全部架在南北交错的黄色立柱上 —— 板端整边压柱顶、邻板"
        "长边互吸, 柱-板-柱锁成多环框架, 柱脚四角直角三角斜撑锁地; 入口"
        "匝道从前街 30 度爬上一层, 出口匝道俯冲后院, 顶层青色护栏围边、"
        "下行坡道经中继桥墩两段接力降回地面 (坡道链每段两端受力零悬臂); "
        "西侧红色电梯塔三层圈层自锁, 透明观景层戴等腰四坡尖顶, 4.94 格高"
        "俯瞰全场 —— 车位已满, 请上二层!"
    ),
    difficulty=4,
    tags=["城市", "交通", "停车场", "框架结构", "坡道链", "挑战"],
    min_pieces=75,
    min_steps=18,
)
