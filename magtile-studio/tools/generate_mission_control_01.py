#!/usr/bin/env python3
"""生成模型 data/models/mission_control_01.json (任务控制中心)。

太空探索主题批 1/4: 全库第一座"巨幕指挥大厅" —— 与机场管制塔台
(独立高塔) 和各类看台 (退台阶梯) 都不同, 本作的主角是一面点亮的
巨幕墙: 六片青色窗格方拼成整排大屏, 上层正中两格红色窗格方是
任务计时屏; 大厅南面整个敞开 (剖面式), 双排控制台面朝巨幕 —— 台面
清色方板悬挑在台身墙顶上 (单边力矩 15 <= strict 预算 17.5);
屋顶只盖北跨, 两支红白测控天线骑着巨幕墙顶插上 4.0 高空 ——
"各号注意, 一分钟准备!"

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 巨幕墙在北):
  - 大厅后场地台 (y [2,4]): 大正方形 x3                          3 片
  - 大厅前场地台 (y [0,2]): 单位方板 x12 (前厅蓝毯一行)         12 片
  - 巨幕墙 (y=4, z 0..2): 下层青色窗格方大屏 x6 +
    上层素墙 x4 + 红色任务计时屏窗格方 x2                       12 片
  - 侧墙 x2 (x=0 / x=6, y [2,4], z 0..2): 下素上透 x8
    (东侧下层嵌蓝色门框方值班门) + 直角三角斜撑 x2              10 片
  - 屋顶北跨 (y [3,4], z=2): 长板 x3                             3 片
  - 测控天线 x2: 等腰三角骑巨幕墙顶, 尖端 4.0                    2 片
  - 控制台双排: 前排 3 座 + 后排 2 座 (台身墙 + 清色悬挑台面)   10 片
  合计 52 片, 13 个教程步骤, 7 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 巨幕墙是 6x2 墙格网: 相邻竖边互吸 + 上下横边互吸, 环路密布,
    R8 结构冗余天然通过;
  - 屋顶三条长板: 北长边压巨幕墙顶 (长短边贴合), 两端短边各吸
    一侧侧墙顶, 中板短边吸两端板 —— 剪断巨幕墙顶整条铰链线后
    屋顶仍经侧墙接地, 零悬挂零力矩;
  - 天线骑巨幕墙顶拼缝, 底边同线双吸墙顶与屋顶北长边 (一线双吸),
    正上方零力矩; 剪任何单条连接最多失联 1 片 (< 3), 单点失效通过;
  - 控制台台面清色方板单边悬挑: 30g x 0.5 = 力矩 15 <= strict
    预算 25 x 1 x 70% = 17.5, 全部台面同一预算逐一过账;
  - 侧墙前端直角三角斜撑双边吸合 (竖边吸墙角竖边 + 横边吸地台缝)。

用法: python3 tools/generate_mission_control_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

FLOOR = "gray"      # 大厅地台
CARPET = "blue"     # 前厅蓝毯
SCREEN = "cyan"     # 巨幕 (点亮的大屏)
WALL = "gray"       # 素墙
CLOCK = "red"       # 任务计时屏
GLASS = "clear"     # 侧墙高窗
DOOR = "blue"       # 值班门
BRACE = "cyan"      # 斜撑
ROOF = "clear"      # 屋顶北跨
ANT_A = "red"       # 测控天线
ANT_B = "clear"
DESK_A = "blue"     # 前排控制台
DESK_B = "orange"   # 后排控制台
TOP = "clear"       # 台面


def wall_ns_t(tid, tile_type, x0, y, z0, color):
    b.add(tid, tile_type, (x0 + 0.5, y, z0 + 0.5), (90, 0, 0), color)


def wall_ew_t(tid, tile_type, x, y0, z0, color):
    b.add(tid, tile_type, (x, y0 + 0.5, z0 + 0.5), (90, 0, 90), color)


# =================================================================
# 1. 大厅地台: 后场大正方形 x3 (y [2,4]) + 前场单位方板 x12 (y [0,2])
# =================================================================
for i, x0 in enumerate((0, 2, 4)):
    b.add(f"lg_{i}", "large_square", (x0 + 1.0, 3.0, 0.0), (0, 0, 0), FLOOR)
for x0 in range(6):
    b.flat(f"f_{x0}_1", x0, 1, 0.0, FLOOR)     # 控制台排行
for x0 in range(6):
    b.flat(f"f_{x0}_0", x0, 0, 0.0, CARPET)    # 前厅蓝毯行

# =================================================================
# 2. 巨幕墙 (y=4): 下层 6 片青色窗格方大屏 + 上层素墙夹红色任务计时屏
# =================================================================
for x0 in range(6):
    wall_ns_t(f"scr_{x0}", "window_square", x0, 4.0, 0, SCREEN)
for x0 in (0, 1, 4, 5):
    b.wall_ns(f"top_{x0}", x0, 4.0, 1, WALL)
wall_ns_t("clk_a", "window_square", 2, 4.0, 1, CLOCK)
wall_ns_t("clk_b", "window_square", 3, 4.0, 1, CLOCK)

# =================================================================
# 3. 侧墙 (x=0 / x=6, y [2,4]): 下素上透, 东侧嵌值班门, 前端斜撑
# =================================================================
b.wall_ew("sw_2_0", 0.0, 2, 0, WALL)
b.wall_ew("sw_3_0", 0.0, 3, 0, WALL)
b.wall_ew("sw_2_1", 0.0, 2, 1, GLASS)
b.wall_ew("sw_3_1", 0.0, 3, 1, GLASS)
wall_ew_t("se_door", "door_frame", 6.0, 2, 0, DOOR)   # 值班门朝东
b.wall_ew("se_3_0", 6.0, 3, 0, WALL)
b.wall_ew("se_2_1", 6.0, 2, 1, GLASS)
b.wall_ew("se_3_1", 6.0, 3, 1, GLASS)
b.brace("brace_w", (0.0, 2.0, 0.0), "-y", BRACE)
b.brace("brace_e", (6.0, 2.0, 0.0), "-y", BRACE)

# =================================================================
# 4. 屋顶北跨 (y [3,4], z=2) + 测控天线 x2 (骑巨幕墙顶, 尖端 4.0)
# =================================================================
b.flat_rect("roof_w", 0, 3, 2.0, ROOF)
b.flat_rect("roof_e", 4, 3, 2.0, ROOF)
b.flat_rect("roof_c", 2, 3, 2.0, ROOF)
b.spire_ns("ant_a", 1, 4.0, 2.0, ANT_A)
b.spire_ns("ant_b", 4, 4.0, 2.0, ANT_B)

# =================================================================
# 5. 控制台双排: 前排 3 座 (y=2 台身) + 后排 2 座错位 (y=1 台身),
#    台面清色方板悬挑 (力矩 15 <= 17.5)
# =================================================================
for i, x0 in enumerate((0, 2, 4), start=1):
    b.wall_ns(f"ca{i}_wall", x0, 2.0, 0, DESK_A)
    b.flat(f"ca{i}_top", x0, 1, 1.0, TOP)
for i, x0 in enumerate((1, 3), start=1):
    b.wall_ns(f"cb{i}_wall", x0, 1.0, 0, DESK_B)
    b.flat(f"cb{i}_top", x0, 0, 1.0, TOP)

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺大厅后场: 三片灰色大正方形整边互吸, 一片顶四片省时省力。",
    ["lg_0", "lg_1", "lg_2"],
    tip="大方片是地台主力 —— 巨幕墙和侧墙都要踩它的边线。",
)
b.step(
    "铺控制台排行: 六片灰色方板贴着大方片南边排开。",
    [f"f_{x0}_1" for x0 in range(6)],
    highlight=["lg_0"],
    tip="小方片北边整边吸进大方片南边 —— 长短边贴合一样牢。",
)
b.step(
    "铺前厅蓝毯行: 再来六片蓝色方板, 大厅地台完工。",
    [f"f_{x0}_0" for x0 in range(6)],
    highlight=["f_0_1"],
    tip="蓝毯是给参观的小朋友站的 —— 发射直播马上开始!",
)
b.step(
    "立巨幕下层: 六片青色窗格方沿北边线并肩竖起, 竖边互咬成排。",
    [f"scr_{x0}" for x0 in range(6)],
    highlight=["lg_0", "lg_2"],
    tip="这排窗格方就是任务大屏 —— 火箭的一举一动都在上面。",
)
b.step(
    "叠巨幕上层: 素墙四片夹住正中两格红色任务计时屏。",
    ["top_0", "top_1", "clk_a", "clk_b", "top_4", "top_5"],
    highlight=["scr_0", "scr_5"],
    tip="上下横边加左右竖边互吸, 墙格网环路密布, 撞一下也不怕。",
)
b.step(
    "起西侧墙: 下素上透两层, 前端直角三角斜撑双边吸合抵住墙角。",
    ["sw_2_0", "sw_3_0", "sw_2_1", "sw_3_1", "brace_w"],
    highlight=["scr_0"],
    tip="斜撑竖边吸墙角竖边、横边吸地台缝 —— 大厅开口处最需要它。",
)
b.step(
    "起东侧墙: 下层嵌蓝色值班门, 同样配透明高窗与斜撑。",
    ["se_door", "se_3_0", "se_2_1", "se_3_1", "brace_e"],
    highlight=["scr_5"],
    tip="控制中心昼夜值班, 值班门开在东侧不挡巨幕。",
)
b.step(
    "盖屋顶北跨: 两端长板先各吸一侧墙顶, 中板最后短边合拢。",
    ["roof_w", "roof_e", "roof_c"],
    highlight=["sw_3_1", "se_3_1"],
    tip="北长边压巨幕墙顶、短边互吸 —— 剪掉任何一条边它都不掉。",
)
b.step(
    "插测控天线: 两支等腰三角骑上巨幕墙顶拼缝, 尖端直插 4.0。",
    ["ant_a", "ant_b"],
    highlight=["roof_w", "roof_e"],
    tip="天线底边一线双吸墙顶与屋顶边, 正上方零力矩稳稳站住。",
)
b.step(
    "立前排控制台台身: 三片蓝色方墙面朝巨幕踩住地缝。",
    ["ca1_wall", "ca2_wall", "ca3_wall"],
    highlight=["scr_1"],
    tip="台身墙脚同时吸住前后两块地板的拼缝, 双保险。",
)
b.step(
    "搭前排台面: 清色方板北边吸台身墙顶, 朝南悬挑当桌面。",
    ["ca1_top", "ca2_top", "ca3_top"],
    highlight=["ca1_wall"],
    tip="单边悬挑力矩 15, 低于弱磁严格档预算 17.5 —— 安心办公。",
)
b.step(
    "立后排控制台台身: 两片橙色方墙与前排错位站好。",
    ["cb1_wall", "cb2_wall"],
    highlight=["ca1_top"],
    tip="错位排布让每个座位都能看见完整的巨幕。",
)
b.step(
    "搭后排台面收尾: 全体就位 —— 十, 九, 八…… 点火!",
    ["cb1_top", "cb2_top"],
    highlight=["clk_a", "clk_b"],
    tip="倒计时钟跳红, 巨幕上火箭尾焰腾起 —— 任务控制中心开工!",
)

b.finalize(
    model_id="mission_control_01",
    name="任务控制中心",
    name_en="Mission Control 01",
    description=(
        "只用核心九片型的太空探索指挥现场: 与机场塔台的独立高塔不同, "
        "主角是一面点亮的巨幕墙 —— 六片青色窗格方拼成整排任务大屏, "
        "上层素墙正中嵌两格红色任务计时屏; 大厅南面整个敞开, 双排控制台"
        "面朝巨幕, 清色台面悬挑在台身墙顶 (单边力矩 15 <= strict 预算 "
        "17.5); 屋顶北跨两端搭侧墙顶、北长边压巨幕墙顶, 两支红白测控"
        "天线骑墙顶拼缝直插 4.0 高空 —— 各号注意, 一分钟准备!"
    ),
    difficulty=3,
    tags=["航天", "指挥中心", "巨幕", "倒计时", "进阶"],
    min_pieces=52,
    min_steps=13,
)
