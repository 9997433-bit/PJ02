#!/usr/bin/env python3
"""生成模型 data/models/bamboo_house_01.json (竹楼民居 · 吊脚楼)。

民居风情主题: 全库第一座"架空层"建筑 —— 整栋房子不落地, 12 片
楼板悬架在 6 根竹柱墩上 (吊脚楼), 楼板前沿是带栏杆的挑廊,
一道 30 度竹梯从廊口斜下到院坝; 主屋戴梯形四坡攒尖茅顶,
院坝东侧还有一座同样架空的 1x1 粮仓小竹楼。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 架空层: 6 根竹柱墩 (南北各 2 + 东西各 1, z 0..1)              6 片
  - 吊脚楼板: 4x3 楼板悬架在柱墩顶上 (z=1)                       12 片
  - 主屋 (x 1..3, y 1..3, z 1..3): 两层竹墙, 南留门、上层透明窗   15 片
  - 顶棚 + 攒尖茅顶: 2 片长方形顶棚 (长边接梯形下底) +
    4 片梯形四坡 + 压顶                                            7 片
  - 挑廊: 楼板前沿 3 片栏杆 + 30 度竹梯斜下院坝                    4 片
  - 院坝 (x 4..6, y 0..2): 4 片地坪                                4 片
  - 粮仓小竹楼: 2 柱墩 + 仓板 + 四壁 + 四坡尖顶                   11 片
  - 院坝围篱: 3 片三角篱笆                                          3 片
  合计 62 片, 17 个教程步骤。

物理规则要点 (通过 R1~R8 全部校验):
  - 楼板铺设顺序先"柱顶板"后"悬跨板": 每片放下瞬间都吸得到
    柱墩顶边或已铺楼板边 (R7a); 楼板成网后任意剪断一条铰链,
    其余柱墩仍然托住整层 (R6);
  - 顶棚用 2 片平铺长方形: 长边 (长 2) 与梯形下底等长整边互吸,
    这是"方墙洞口接梯形四坡"的标准转换层;
  - 竹梯与粮仓通过院坝地坪与主楼连成一个整体 (东柱墩底边吸院坝)。

用法: python3 tools/generate_bamboo_house.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

BAMBOO = "green"     # 竹墙
DECK = "yellow"      # 竹席楼板
THATCH = "orange"    # 茅草顶
STONE = "gray"       # 柱础石墩

# =================================================================
# 1. 架空层: 6 根竹柱墩 (z 0..1)
# =================================================================
b.wall_ns("st_s0", 0, 0.0, 0, STONE)     # 南柱墩西 (x 0..1)
b.wall_ns("st_s3", 3, 0.0, 0, STONE)     # 南柱墩东 (x 3..4)
b.wall_ns("st_n0", 0, 3.0, 0, STONE)     # 北柱墩西
b.wall_ns("st_n3", 3, 3.0, 0, STONE)     # 北柱墩东
b.wall_ew("st_w", 0.0, 1, 0, STONE)      # 西柱墩 (y 1..2)
b.wall_ew("st_e", 4.0, 1, 0, STONE)      # 东柱墩 (y 1..2)

# =================================================================
# 2. 吊脚楼板: 4x3 悬架于 z=1
# =================================================================
for x0 in range(4):
    for y0 in range(3):
        b.flat(f"dk_{x0}_{y0}", x0, y0, 1.0, DECK)

# =================================================================
# 3. 主屋 (x 1..3, y 1..3): 两层竹墙, 南面留门, 上层透明窗
# =================================================================
b.wall_ns("w1_s2", 2, 1.0, 1, BAMBOO)    # 下层南墙东段 (西段 x1..2 是门)
b.wall_ew("w1_w1", 1.0, 1, 1, BAMBOO)
b.wall_ew("w1_w2", 1.0, 2, 1, BAMBOO)
b.wall_ew("w1_e1", 3.0, 1, 1, BAMBOO)
b.wall_ew("w1_e2", 3.0, 2, 1, BAMBOO)
b.wall_ns("w1_n1", 1, 3.0, 1, BAMBOO)
b.wall_ns("w1_n2", 2, 3.0, 1, BAMBOO)
b.wall_ns("w2_s1", 1, 1.0, 2, BAMBOO)    # 上层南墙 (门楣段)
b.wall_ns("w2_s2", 2, 1.0, 2, "clear")   # 上层南窗
b.wall_ew("w2_w1", 1.0, 1, 2, BAMBOO)
b.wall_ew("w2_w2", 1.0, 2, 2, BAMBOO)
b.wall_ew("w2_e1", 3.0, 1, 2, "clear")   # 上层东窗
b.wall_ew("w2_e2", 3.0, 2, 2, BAMBOO)
b.wall_ns("w2_n1", 1, 3.0, 2, BAMBOO)
b.wall_ns("w2_n2", 2, 3.0, 2, BAMBOO)

# =================================================================
# 4. 顶棚 (z=3, 2 片平铺长方形) + 攒尖茅顶 (梯形四坡 + 压顶)
# =================================================================
b.flat_rect("cl_s", 1, 1, 3.0, DECK, axis="x")   # 顶棚南半 (x 1..3, y 1..2)
b.flat_rect("cl_n", 1, 2, 3.0, DECK, axis="x")   # 顶棚北半 (x 1..3, y 2..3)
ROOF, ROOF_CAP = b.hip_roof2("rf", 1, 1, 3.0, THATCH, cap_color=DECK)

# =================================================================
# 5. 挑廊栏杆 + 30 度竹梯 (从廊口 x 2..3 斜下院坝)
# =================================================================
b.crest_ns("rail_0", 0, 0.0, 1.0, BAMBOO)
b.crest_ns("rail_1", 1, 0.0, 1.0, BAMBOO)
b.crest_ns("rail_3", 3, 0.0, 1.0, BAMBOO)
b.ramp("stair", "-y", 0.0, 2, 1.0, STONE)        # 顶边吸楼板南沿 x 2..3

# =================================================================
# 6. 院坝 (x 4..6, y 0..2) + 粮仓小竹楼 (x 5..6, y 1..2)
# =================================================================
for x0 in (4, 5):
    for y0 in (0, 1):
        b.flat(f"yd_{x0}_{y0}", x0, y0, 0.0, "cyan" if (x0 + y0) % 2 else "green")
b.wall_ns("gr_st_s", 5, 1.0, 0, STONE)           # 粮仓南柱墩
b.wall_ns("gr_st_n", 5, 2.0, 0, STONE)           # 粮仓北柱墩
b.flat("gr_deck", 5, 1, 1.0, DECK)               # 仓板
b.wall_ns("gr_s", 5, 1.0, 1, BAMBOO)
b.wall_ns("gr_n", 5, 2.0, 1, BAMBOO)
b.wall_ew("gr_w", 5.0, 1, 1, BAMBOO)
b.wall_ew("gr_e", 6.0, 1, 1, BAMBOO)
GRAIN_HAT = b.hat4("gr_hat", 5, 1, 2.0, THATCH)

# =================================================================
# 7. 院坝围篱: 3 片三角篱笆
# =================================================================
b.crest_ns("fn_4", 4, 0.0, 0.0, BAMBOO)
b.crest_ns("fn_5", 5, 0.0, 0.0, BAMBOO)
b.crest_ew("fn_e", 6.0, 1, 0.0, BAMBOO)

# =================================================================
# 教程步骤 (17 步)
# =================================================================
b.step(
    "西侧柱墩与楼板: 立 3 根灰色柱墩 (南/西/北), 随手把西列 3 片"
    "楼板压上柱顶 —— 每片底边吸柱墩顶边, 柱墩立刻连成一体。",
    ["st_s0", "st_w", "st_n0", "dk_0_0", "dk_0_1", "dk_0_2"],
    tip="柱墩单独立着会孤单 —— 立一根就马上用楼板把它吸进队伍。",
)
b.step(
    "东侧柱墩与南沿桥板: 同法立起东侧 3 根柱墩并压上东列 3 片"
    "楼板, 再沿南沿铺 2 片桥板把东西两半连通。",
    ["st_s3", "st_e", "st_n3", "dk_3_0", "dk_3_1", "dk_3_2",
     "dk_1_0", "dk_2_0"],
    highlight=["dk_0_0"],
    tip="南沿桥板两端都吸着有柱墩的楼板 —— 悬跨但不悬心。",
)
b.step(
    "楼板合拢: 补上中部 4 片悬跨板, 4x3 楼板成形 —— 竹楼从此"
    "不沾地。",
    ["dk_1_1", "dk_2_1", "dk_1_2", "dk_2_2"],
    highlight=["dk_1_0", "dk_2_0"],
    tip="悬跨板靠四邻边互吸传力, 铺完整层轻压中心检查是否结实。",
)
b.step(
    "主屋下层·西墙与门口: 西墙 2 片 + 南墙东段 1 片立上楼板 "
    "(x 1..2 的南面留作大门)。",
    ["w1_w1", "w1_w2", "w1_s2"],
    highlight=["dk_1_1", "dk_2_0"],
    tip="墙底边吸楼板边 —— 吊脚楼的墙立在楼板上, 不落地。",
)
b.step(
    "主屋下层·东墙与北墙: 东墙 2 片、北墙 2 片合拢, 下层围出"
    "带门洞的堂屋。",
    ["w1_e1", "w1_e2", "w1_n1", "w1_n2"],
    highlight=["w1_w2", "w1_s2"],
    tip="拐角竖边两两互吸, 从门洞望进去就是通风的堂屋。",
)
b.step(
    "主屋上层·西面与南面: 西墙 2 片先叠上下层, 再装横跨门洞的"
    "门楣段与透明南窗。",
    ["w2_w1", "w2_w2", "w2_s1", "w2_s2"],
    highlight=["w1_s2", "w1_w1"],
    tip="门楣段下方是空门洞, 全靠两端竖边吸邻墙 —— 先立邻墙再装它。",
)
b.step(
    "主屋上层·东面与北面: 透明东窗 + 3 片竹墙补齐, 两层墙体到顶。",
    ["w2_e1", "w2_e2", "w2_n1", "w2_n2"],
    highlight=["w2_s1", "w2_w2"],
    tip="上层两面开窗 —— 竹楼讲究穿堂风, 越通透越凉快。",
)
b.step(
    "顶棚转换层: 2 片长方形平铺在墙顶 (z=3), 短边吸东西墙顶边, "
    "两片中缝互吸 —— 长边留给四坡屋顶的梯形下底。",
    ["cl_s", "cl_n"],
    highlight=["w2_w1", "w2_e1"],
    tip="正方形墙顶接不住 2 格长的梯形底 —— 长方形顶棚就是转换层。",
)
b.step(
    "攒尖茅顶·南北坡: 2 片橙色梯形下底整边吸顶棚长边, 向内倾斜。",
    ["rf_s", "rf_n"],
    highlight=["cl_s", "cl_n"],
    tip="梯形下底与顶棚长边等长, 一格不差才吸得牢。",
)
b.step(
    "攒尖茅顶·东西坡与压顶: 东西 2 片梯形腰边卡进南北坡, 顶口"
    "盖上黄色压顶 —— 茅顶合拢。",
    ["rf_e", "rf_w", ROOF_CAP],
    highlight=["rf_s", "rf_n"],
    tip="四片腰两两互吸自锁, 压顶四边同时吸住四片梯形上底。",
)
b.step(
    "挑廊栏杆: 楼板南沿立 3 片竹栏杆, x 2..3 留作梯口。",
    ["rail_0", "rail_1", "rail_3"],
    highlight=["dk_0_0", "dk_3_0"],
    tip="挑廊是竹楼的客厅 —— 傍晚全家坐在栏杆边乘凉。",
)
b.step(
    "竹梯: 30 度长梯顶边吸楼板梯口边, 梯尾稳稳落地。",
    ["stair"],
    highlight=["rail_1", "rail_3"],
    tip="梯口正对堂屋大门 —— 上楼第一步就进家门。",
)
b.step(
    "院坝: 楼东铺 4 片地坪, 西沿吸住东柱墩底边 —— 院坝把竹楼"
    "和粮仓连成一家。",
    ["yd_4_0", "yd_4_1", "yd_5_0", "yd_5_1"],
    highlight=["st_e"],
    tip="院坝地坪与柱墩底边整边互吸, 全场从此是一个整体。",
)
b.step(
    "粮仓架空层: 院坝上立 2 根小柱墩, 顶上架 1 片仓板 —— 粮仓"
    "也要防潮防鼠, 一样不落地。",
    ["gr_st_s", "gr_st_n", "gr_deck"],
    highlight=["yd_5_0", "yd_5_1"],
    tip="仓板南北边分别吸两根柱墩顶边, 悬空的小平台就位。",
)
b.step(
    "粮仓四壁: 4 片竹墙围出 1x1 仓房。",
    ["gr_s", "gr_n", "gr_w", "gr_e"],
    highlight=["gr_deck"],
    tip="四壁底边吸仓板四边, 拐角竖边两两互吸。",
)
b.step(
    "粮仓尖顶: 4 片橙色等腰三角形四坡锁尖, 小茅顶咔哒合拢。",
    GRAIN_HAT,
    highlight=["gr_s", "gr_e"],
    tip="斜棱两两互吸、锥尖自锁 —— 和主屋茅顶遥相呼应。",
)
b.step(
    "院坝围篱: 南沿 2 片、东沿 1 片三角篱笆 —— 竹楼民居落成!",
    ["fn_4", "fn_5", "fn_e"],
    highlight=["yd_4_0", "yd_5_0"],
    tip="从竹梯上楼看看: 整栋楼悬在 6 根柱墩上, 底下能钻小狗。",
)

b.finalize(
    model_id="bamboo_house_01",
    name="竹楼民居",
    name_en="Bamboo Stilt House 01",
    description=(
        "全库第一座架空建筑: 12 片楼板悬架在 6 根石柱墩上 (吊脚楼), "
        "先柱顶板后悬跨板的铺法让每片放下即吸; 两层竹墙戴梯形攒尖茅顶 "
        "(长方形顶棚作转换层), 前沿挑廊配 30 度竹梯斜下院坝; 东侧粮仓"
        "小竹楼同样架空防潮, 院坝地坪把全场连成一个整体。"
    ),
    difficulty=3,
    tags=["民居风情", "建筑", "架空", "田园"],
    min_pieces=55,
    min_steps=16,
)
