#!/usr/bin/env python3
"""生成模型 data/models/excavator_01.json (履带挖掘机)。

工程机械主题: 与塔吊 (独柱高塔) 和港口门吊 (四腿门架) 完全不同的
履带式作业车 —— 两条 3 格长的箱形履带 (双壁 + 顶板锁成箱形梁)
分踞两侧, 3 片回转平台板横跨履带间隙把双履带桥接成整车底盘;
底盘上机舱箱体与玻璃驾驶室并肩, 尾部配重板压舱; 一条 30 度大臂
从平台东沿放下, 坡尾自然落地 (接地斜撑、零悬臂), 臂端立起铲斗
刃板正对橙色土堆 —— 挖掘机作业姿态定格。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 大臂朝 +x):
  - 场地: 整机地坪 [1,4]x[0,3] 9 + 作业带 [4,7]x[1,2] 3         12 片
  - 履带 x2 (x[1,4]): 外壁 3 + 内壁 3 + 顶板 3, 各 9 片          18 片
  - 回转平台: 3 片方板横跨履带间隙 (双端受力)                     3 片
  - 机舱 [1,2]x[0,2] (z1..2): 立墙 6 + 舱顶长板 1                 7 片
  - 驾驶室 [1,2]x[2,3]: 立墙 3 (东面透明) + 舱顶 1                4 片
  - 尾部配重: 红色方板向西悬挑 (力矩 15 <= 预算 20)               1 片
  - 大臂: 30 度长方形坡道 1 + 铲斗刃板 1                          2 片
  - 土堆: 等边四坡锥 4                                            4 片
  - 场景: 安全三角牌 x2 + 菱形警示旗 x2                           4 片
  合计 55 片, 18 个教程步骤, 5 种磁力片形状 (迁移期不使用等腰片)。

物理规则要点 (通过 R1~R8 全部校验):
  - 履带是 双壁+顶板 的箱形梁, 每片顶板同时压内外两壁 (双铰链
    互为保险); 回转平台板两端同时吸南北履带顶板 (双端受力);
  - 大臂顶边整边吸平台东沿, 坡尾自然落地 —— 接地斜撑零悬臂,
    这正是剑龙脖颈与鳄鱼上颚的同款收尾技法;
  - 配重板单格悬挑, 力矩 15 <= 铰链预算 20, 预算纪律;
  - 土堆四条斜棱两两互吸自锁成环。

用法: python3 tools/generate_excavator.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder, COS30

b = ModelBuilder()

TRACK = "gray"      # 履带
BODY = "yellow"     # 车身
ARM = "orange"      # 大臂
DIRT = "orange"     # 土堆

# =================================================================
# 1. 场地: 整机地坪 [1,4]x[0,3] + 作业带 [4,7]x[1,2]
# =================================================================
for x in range(1, 4):
    for y in range(3):
        b.flat(f"gd_{x}_{y}", x, y, 0.0, "green" if (x + y) % 2 else "gray")
for x in range(4, 7):
    b.flat(f"wk_{x}", x, 1, 0.0, "clear")

# =================================================================
# 2. 履带 x2: 双壁 + 顶板锁成箱形梁 (南 y[0,1], 北 y[2,3])
# =================================================================
for x in range(1, 4):
    b.wall_ns(f"ts_o_{x}", x, 0.0, 0, TRACK)        # 南履带外壁
    b.wall_ns(f"ts_i_{x}", x, 1.0, 0, TRACK)        # 南履带内壁
    b.wall_ns(f"tn_i_{x}", x, 2.0, 0, TRACK)        # 北履带内壁
    b.wall_ns(f"tn_o_{x}", x, 3.0, 0, TRACK)        # 北履带外壁
for x in range(1, 4):
    b.flat(f"ts_t_{x}", x, 0, 1.0, "blue")          # 南履带顶板
    b.flat(f"tn_t_{x}", x, 2, 1.0, "blue")          # 北履带顶板

# =================================================================
# 3. 回转平台: 3 片方板横跨履带间隙 y[1,2] (双端受力)
# =================================================================
for x in range(1, 4):
    b.flat(f"dk_{x}", x, 1, 1.0, BODY)

# =================================================================
# 4. 机舱 [1,2]x[0,2] (z1..2) + 驾驶室 [1,2]x[2,3] + 尾部配重
# =================================================================
b.wall_ns("eh_s", 1, 0.0, 1, BODY)                  # 机舱南墙
b.wall_ew("eh_w0", 1.0, 0, 1, BODY)                 # 机舱西墙
b.wall_ew("eh_w1", 1.0, 1, 1, BODY)
b.wall_ns("eh_n", 1, 2.0, 1, BODY)                  # 机舱北墙 (兼驾驶室南墙)
b.wall_ew("eh_e0", 2.0, 0, 1, BODY)                 # 机舱东墙
b.wall_ew("eh_e1", 2.0, 1, 1, BODY)
b.flat_rect("eh_top", 1, 0, 2.0, ARM, axis="y")     # 机舱顶长板
b.wall_ew("cb_w", 1.0, 2, 1, BODY)                  # 驾驶室西墙
b.wall_ns("cb_n", 1, 3.0, 1, BODY)                  # 驾驶室北墙
b.wall_ew("cb_e", 2.0, 2, 1, "clear")               # 驾驶室东窗
b.flat("cb_top", 1, 2, 2.0, "red")                  # 驾驶室顶
b.flat("cw", 0, 1, 1.0, "red")                      # 尾部配重 (向西悬挑)

# =================================================================
# 5. 大臂: 30 度坡道从平台东沿放下, 坡尾落地立铲斗刃板
# =================================================================
b.ramp("boom", "+x", 4.0, 1, 1.0, ARM)              # 顶边吸平台东沿
BUCKET_X = 4.0 + 2 * COS30                          # 坡尾 x = 5.73205
b.crest_ew("bucket", BUCKET_X, 1, 0.0, TRACK)       # 铲斗刃板

# =================================================================
# 6. 土堆 + 安全锥 + 菱形警示旗
# =================================================================
DIRT_IDS = b.hat4("dirt", 6, 1, 0.0, DIRT,
                  shape="equilateral_triangle")  # 土堆 (等边四坡锥)
b.crest_ns("cone_4", 4, 1.0, 0.0, "red")            # 安全三角牌
b.crest_ns("cone_5", 5, 1.0, 0.0, "red")
b.place_edge("fg_w", "rhombus", 0,
             (6.0, 2.0, 0.0), (5.0, 2.0, 0.0), (0.0, 0.0, 1.0), "red")
b.place_edge("fg_e", "rhombus", 0,
             (6.0, 2.0, 0.0), (7.0, 2.0, 0.0), (0.0, 0.0, 1.0), "red")

# =================================================================
# 教程步骤 (18 步)
# =================================================================
b.step(
    "铺整机地坪南半: [1,4]x[0,2] 铺 6 片灰绿相间方板。",
    [f"gd_{x}_{y}" for x in range(1, 4) for y in range(2)],
    tip="挖掘机自重大, 先给它一块平整地坪。",
)
b.step(
    "铺地坪北半与作业带: 北排 3 片补齐, 再向东铺 3 片透明作业带 —— "
    "大臂将落在这条线上。",
    [f"gd_{x}_2" for x in range(1, 4)] + [f"wk_{x}" for x in range(4, 7)],
    highlight=["gd_3_1"],
    tip="作业带与地坪边边相吸, 全场连成一个磁力整体。",
)
b.step(
    "立南履带外壁: 沿地坪南沿立 3 片灰色立墙。",
    [f"ts_o_{x}" for x in range(1, 4)],
    highlight=["gd_1_0", "gd_3_0"],
    tip="履带的箱形梁从外壁开始。",
)
b.step(
    "立南履带内壁: y=1 线上再立 3 片, 与外壁夹出履带体。",
    [f"ts_i_{x}" for x in range(1, 4)],
    highlight=["ts_o_1"],
    tip="双壁平行, 下一步顶板一压就是箱形梁。",
)
b.step(
    "盖南履带顶板: 3 片蓝色方板逐格压住内外双壁。",
    [f"ts_t_{x}" for x in range(1, 4)],
    highlight=["ts_o_1", "ts_i_3"],
    tip="每片顶板双铰链互为保险 —— 剪断一条还有另一条。",
)
b.step(
    "立北履带内壁: y=2 线上立 3 片灰色立墙。",
    [f"tn_i_{x}" for x in range(1, 4)],
    highlight=["ts_i_1"],
    tip="两条履带之间留 1 格间隙, 回转平台会横跨它。",
)
b.step(
    "立北履带外壁: 地坪北沿再立 3 片。",
    [f"tn_o_{x}" for x in range(1, 4)],
    highlight=["tn_i_1"],
    tip="南北履带严格镜像, 整车才不偏载。",
)
b.step(
    "盖北履带顶板: 3 片蓝色方板压住北履带双壁。",
    [f"tn_t_{x}" for x in range(1, 4)],
    highlight=["tn_i_1", "tn_o_3"],
    tip="第二条箱形梁成型 —— 履带越野车的底气。",
)
b.step(
    "架回转平台: 3 片黄色方板横跨履带间隙, 每片两端同时吸南北履带"
    "顶板边。",
    [f"dk_{x}" for x in range(1, 4)],
    highlight=["ts_t_1", "tn_t_3"],
    tip="双端受力零悬挑 —— 双履带从此桥接成一台整车。",
)
b.step(
    "立机舱围壁: 平台西段 [1,2]x[0,2] 四面立起 6 片黄色立墙。",
    ["eh_s", "eh_w0", "eh_w1", "eh_n", "eh_e0", "eh_e1"],
    highlight=["dk_1", "ts_t_1"],
    tip="机舱底边全部吸在履带顶板与平台板的沿口上。",
)
b.step(
    "盖机舱顶并挂配重: 橙色长板封住机舱, 红色配重板从平台西沿向外"
    "悬挑一格。",
    ["eh_top", "cw"],
    highlight=["eh_s", "dk_1"],
    tip="配重力矩 15 <= 铰链预算 20 —— 大臂在东, 配重在西, 这是天平。",
)
b.step(
    "立驾驶室: 机舱北侧立 3 片围壁 (东面透明大窗), 司机视野正对大臂。",
    ["cb_w", "cb_n", "cb_e"],
    highlight=["eh_n", "tn_t_1"],
    tip="驾驶室与机舱共用一面墙 —— 省料又结实。",
)
b.step(
    "盖驾驶室顶: 红色顶板四边压住围壁。",
    ["cb_top"],
    highlight=["cb_w", "cb_e"],
    tip="顶板一盖, 驾驶室锁成刚性小箱。",
)
b.step(
    "放下大臂: 30 度橙色大臂顶边整边吸平台东沿, 坡尾自然落在作业带上。",
    ["boom"],
    highlight=["dk_3", "wk_4"],
    tip="坡尾落地 = 接地斜撑, 零悬臂 —— 挖掘姿态天生稳。",
)
b.step(
    "立铲斗刃板: 灰色三角刃板立在大臂坡尾线上, 刃口正对土堆。",
    ["bucket"],
    highlight=["boom"],
    tip="刃板底边与坡尾整边互吸 —— 准备开挖!",
)
b.step(
    "堆土堆: 4 片橙色等边三角在作业带东端四棱互吸, 合拢成土堆。",
    DIRT_IDS,
    highlight=["wk_6", "bucket"],
    tip="四条斜棱两两精确互吸自锁成环 —— 一铲下去就冒尖。",
)
b.step(
    "立安全三角牌: 大臂两侧作业带沿口立 2 面红色三角警示牌。",
    ["cone_4", "cone_5"],
    highlight=["wk_4", "wk_5"],
    tip="作业半径内禁止靠近 —— 安全第一。",
)
b.step(
    "斜插警示旗: 土堆北沿两面红色菱形警示旗向两侧倒插 —— 挖掘机, "
    "开工!",
    ["fg_w", "fg_e"],
    highlight=["wk_6"],
    tip="菱形 60 度的天然斜度让旗面像正被机器的轰鸣掀动。",
)

b.finalize(
    model_id="excavator_01",
    name="履带挖掘机",
    name_en="Crawler Excavator 01",
    description=(
        "与塔吊、港口门吊完全不同的履带式工程车: 两条 3 格长的箱形履带 "
        "(双壁+顶板, 每片顶板双铰链互为保险) 由 3 片回转平台板桥接成整车"
        "底盘; 底盘上机舱箱体与透明驾驶室并肩, 红色配重板向西悬挑压舱 "
        "(力矩 15 <= 预算 20); 一条 30 度大臂从平台东沿放下、坡尾自然落地 "
        "(接地斜撑零悬臂), 臂端铲斗刃板正对四棱自锁的橙色土堆 —— 安全锥"
        "就位, 警示旗斜插, 开挖!"
    ),
    difficulty=3,
    tags=["工程", "挖掘机", "履带", "载具", "进阶"],
    min_pieces=50,
    min_steps=16,
)
