#!/usr/bin/env python3
"""生成模型 data/models/ski_jump_01.json (跳台滑雪场)。

运动主题: 全库第一条"直线下山"的坡道动线 —— 出发塔 (z=3) 甩出
三段 30 度坡道: 助滑坡 -> 中继台 -> 加速坡 -> 起跳台 (z=1) ->
着陆坡直落雪面, 滑进两格长的减速区撞上终点挡墙; 着陆区南侧
立一座戴四坡尖顶的裁判塔, 出发塔背后还有一条运动员登塔坡道。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 动线沿 +x):
  - 出发塔 [0,1]x[0,1]: 底板 + 三层筒壁 + 出发台 + 3 片护栏      17 片
  - 登塔坡道: 塔西侧 1 片坡道, 顶边吸塔壁顶, 坡尾落地             1 片
  - 助滑段: 坡道 + 双层栈桥墩 + 中继台 + 2 片护栏                 6 片
  - 加速段: 坡道 + 单层栈桥墩 + 起跳台 + 2 片护栏                 5 片
  - 着陆坡: 1 片坡道从起跳台直落雪面 (坡尾自然落地)               1 片
  - 减速区: 2 片雪面方板 + 4 片护栏 + 终点挡墙 + 终点旗           8 片
  - 裁判塔: 看台广场 2 + 底板 + 两层塔壁 8 + 顶板 + 四坡尖顶 4   16 片
  合计 54 片, 16 个教程步骤, 4 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 每段坡道顶边整边吸台沿, 坡尾由栈桥墩顶边接住, 坡道-桥墩-
    平台三件互吸成三角刚性节点 (滚珠塔同款);
  - 着陆坡与登塔坡坡尾直接落地 (接地斜撑), 不需要任何支撑;
  - 减速区方板从着陆坡坡尾 (x = 6.464+sqrt(3)) 逐片向东铺开,
    网格自然偏移, 磁力片不挑格子。

用法: python3 tools/generate_ski_jump.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder, SQ3

b = ModelBuilder()

SNOW = "clear"      # 雪道
TOWER = "red"       # 出发塔
RAIL = "blue"       # 护栏
DECK = "gray"       # 平台

# =================================================================
# 1. 出发塔 [0,1]x[0,1] (z 0..3): 底板 + 三层筒壁 + 出发台 + 护栏
# =================================================================
b.flat("tw_base", 0, 0, 0.0, DECK)
for z in range(3):
    b.wall_ns(f"tw_s_{z}", 0, 0.0, z, TOWER)
    b.wall_ns(f"tw_n_{z}", 0, 1.0, z, TOWER)
    b.wall_ew(f"tw_w_{z}", 0.0, 0, z, TOWER)
    b.wall_ew(f"tw_e_{z}", 1.0, 0, z, TOWER)
b.flat("tw_top", 0, 0, 3.0, DECK)                   # 出发台
b.crest_ew("tw_rail_w", 0.0, 0, 3.0, RAIL)          # 护栏 (东面是出发口)
b.crest_ns("tw_rail_s", 0, 0.0, 3.0, RAIL)
b.crest_ns("tw_rail_n", 0, 1.0, 3.0, RAIL)

# 运动员登塔坡道: 顶边吸塔西壁顶边 (z=1), 坡尾落地
b.ramp("climb", "-x", 0.0, 0, 1.0, DECK)

# =================================================================
# 2. 助滑段: 坡道 z3->z2, 双层栈桥墩, 中继台 (z=2)
# =================================================================
X1 = 1.0 + SQ3                                      # 中继台西沿 2.732051
b.wall_ew("p1_a", X1, 0, 0, TOWER)                  # 栈桥墩下层
b.wall_ew("p1_b", X1, 0, 1, TOWER)                  # 栈桥墩上层
b.ramp("run1", "+x", 1.0, 0, 3.0, SNOW)             # 助滑坡
b.flat("mid", X1, 0, 2.0, SNOW)                     # 中继台
b.crest_ns("mid_rail_s", X1, 0.0, 2.0, RAIL)
b.crest_ns("mid_rail_n", X1, 1.0, 2.0, RAIL)

# =================================================================
# 3. 加速段: 坡道 z2->z1, 单层栈桥墩, 起跳台 (z=1)
# =================================================================
X2 = X1 + 1.0 + SQ3                                 # 起跳台西沿 5.464102
b.wall_ew("p2", X2, 0, 0, TOWER)
b.ramp("run2", "+x", X1 + 1.0, 0, 2.0, SNOW)        # 加速坡
b.flat("table", X2, 0, 1.0, SNOW)                   # 起跳台
b.crest_ns("tab_rail_s", X2, 0.0, 1.0, RAIL)
b.crest_ns("tab_rail_n", X2, 1.0, 1.0, RAIL)

# =================================================================
# 4. 着陆坡与减速区: 坡道直落雪面, 2 片雪面方板 + 护栏 + 终点挡墙
# =================================================================
b.ramp("land", "+x", X2 + 1.0, 0, 1.0, SNOW)        # 着陆坡, 坡尾落地
X3 = X2 + 1.0 + SQ3                                 # 减速区西沿 8.196152
b.flat("out_0", X3, 0, 0.0, SNOW)
b.flat("out_1", X3 + 1.0, 0, 0.0, SNOW)
b.crest_ns("out_rail_s0", X3, 0.0, 0.0, RAIL)
b.crest_ns("out_rail_n0", X3, 1.0, 0.0, RAIL)
b.crest_ns("out_rail_s1", X3 + 1.0, 0.0, 0.0, RAIL)
b.crest_ns("out_rail_n1", X3 + 1.0, 1.0, 0.0, RAIL)
b.wall_ew("stop", X3 + 2.0, 0, 0, "orange")         # 终点挡墙
b.crest_ew("stop_flag", X3 + 2.0, 0, 1.0, "yellow") # 终点旗

# =================================================================
# 5. 裁判塔 (减速区南侧): 看台广场 + 两层塔身 + 顶板 + 四坡尖顶
# =================================================================
b.flat("pz_0", X3, -1, 0.0, DECK)                   # 看台广场
b.flat("pz_1", X3 + 1.0, -1, 0.0, DECK)
b.flat("jt_base", X3, -2, 0.0, DECK)                # 裁判塔底板
for z in range(2):
    b.wall_ns(f"jt_s_{z}", X3, -2.0, z, "purple")
    b.wall_ew(f"jt_w_{z}", X3, -2, z, "purple")
    b.wall_ew(f"jt_e_{z}", X3 + 1.0, -2, z, "purple")
b.wall_ns("jt_n_0", X3, -1.0, 0, "purple")
b.wall_ns("jt_n_1", X3, -1.0, 1, "clear")           # 二层观察窗朝向着陆坡
b.flat("jt_top", X3, -2, 2.0, DECK)
JT_HAT = b.hat4("jt_hat", X3, -2.0, 2.0, "purple")

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "出发塔第 1 层: 平放 1 片灰色底板, 四周立 4 片红色塔壁, 拐角竖边互吸。",
    ["tw_base", "tw_s_0", "tw_n_0", "tw_w_0", "tw_e_0"],
    tip="出发塔要长到三层高, 第一层的四角一定要吸方正。",
)
b.step(
    "出发塔第 2 层: 再立 4 片红色塔壁, 上下边完整贴合。",
    ["tw_s_1", "tw_n_1", "tw_w_1", "tw_e_1"],
    highlight=["tw_s_0", "tw_e_0"],
    tip="对缝叠墙吸力最强 —— 塔身是整条雪道的靠山。",
)
b.step(
    "出发塔第 3 层: 塔身升到三层, 一手扶塔一手放片。",
    ["tw_s_2", "tw_n_2", "tw_w_2", "tw_e_2"],
    highlight=["tw_s_1", "tw_e_1"],
    tip="越高越要轻放, 别让下层塔壁被带歪。",
)
b.step(
    "盖出发台: 1 片灰色方板压住塔口, 四边同时吸四面塔壁顶边。",
    ["tw_top"],
    highlight=["tw_s_2", "tw_e_2"],
    tip="出发台就是运动员蓄势待发的地方。",
)
b.step(
    "装出发台护栏: 西、南、北三面各立 1 片蓝色三角护栏, 东面留作出发口。",
    ["tw_rail_w", "tw_rail_s", "tw_rail_n"],
    highlight=["tw_top"],
    tip="护栏立在台沿正上方, 出发口朝向雪道正东。",
)
b.step(
    "装登塔坡道: 1 片灰色坡道顶边吸塔西壁顶边 (一层高), 坡尾自然落地。",
    ["climb"],
    highlight=["tw_w_0"],
    tip="这是运动员背着雪板登塔的楼梯 —— 坡尾落地就是支撑。",
)
b.step(
    "助滑段整段成组安装: 塔东侧先叠双层红色栈桥墩, 助滑坡顶边整边吸"
    "出发台东沿、坡尾搭上墩顶, 再铺 1 片中继台压住墩顶与坡尾。",
    ["p1_a", "p1_b", "run1", "mid"],
    highlight=["tw_top", "tw_e_0"],
    tip="坡道-桥墩-平台三件互吸成三角刚性节点, 装完轻摇应纹丝不动。",
)
b.step(
    "装中继台护栏: 南北各立 1 片蓝色三角, 逼住雪板笔直向东。",
    ["mid_rail_s", "mid_rail_n"],
    highlight=["mid"],
    tip="跳台滑雪的助滑道是笔直的 —— 护栏就是它的边界线。",
)
b.step(
    "加速段: 立单层桥墩, 加速坡从中继台东沿下探, 铺起跳台压住墩顶与坡尾。",
    ["p2", "run2", "table"],
    highlight=["mid", "mid_rail_s"],
    tip="与助滑段同样的三角刚性节点, 只是矮了一层。",
)
b.step(
    "装起跳台护栏: 南北各 1 片蓝色三角 —— 这里就是腾空点!",
    ["tab_rail_s", "tab_rail_n"],
    highlight=["table"],
    tip="起跳台只有一格长, 运动员在这里全力起跳。",
)
b.step(
    "装着陆坡: 1 片坡道顶边吸起跳台东沿, 坡尾直落雪面。",
    ["land"],
    highlight=["table"],
    tip="着陆坡不需要桥墩 —— 坡尾落地自然就是支撑。",
)
b.step(
    "铺减速区: 着陆坡坡尾向东平铺 2 片雪面方板。",
    ["out_0", "out_1"],
    highlight=["land"],
    tip="第一片方板的西沿正好吸住坡尾边 —— 磁力片不挑格子。",
)
b.step(
    "装减速区护栏与终点: 南北各 2 片蓝色三角, 东端立橙色挡墙, "
    "墙顶插黄色终点旗。",
    ["out_rail_s0", "out_rail_n0", "out_rail_s1", "out_rail_n1",
     "stop", "stop_flag"],
    highlight=["out_0", "out_1"],
    tip="挡墙底边吸雪面东沿, 终点旗立在墙顶正上方。",
)
b.step(
    "铺看台广场与裁判塔第 1 层: 减速区南侧铺 2 片广场, 再放塔底板, "
    "立第一层塔壁。",
    ["pz_0", "pz_1", "jt_base", "jt_s_0", "jt_w_0", "jt_e_0", "jt_n_0"],
    highlight=["out_0"],
    tip="裁判塔紧挨减速区 —— 裁判要看清每一次着陆。",
)
b.step(
    "裁判塔第 2 层: 叠第二层塔壁 (北面是透明观察窗), 盖上灰色顶板。",
    ["jt_s_1", "jt_w_1", "jt_e_1", "jt_n_1", "jt_top"],
    highlight=["jt_n_0"],
    tip="透明观察窗正对着陆坡 —— 裁判的视线一格不挡。",
)
b.step(
    "装裁判塔尖顶: 4 片紫色等腰三角底边吸顶板四边, 斜棱两两互吸锁尖, "
    "跳台滑雪场完工!",
    JT_HAT,
    highlight=["jt_top"],
    tip="最后一片卡进去的瞬间, 尖顶会咔哒一声自锁成一体。",
)

b.finalize(
    model_id="ski_jump_01",
    name="跳台滑雪场",
    name_en="Ski Jump 01",
    description=(
        "全库第一条直线下山的雪道动线: 三层出发塔甩出 助滑坡-中继台-加速坡-"
        "起跳台 三段 30 度雪道, 每段坡道顶边吸台沿、坡尾由栈桥墩接住 (三角"
        "刚性节点); 着陆坡直落雪面滑进减速区, 撞上橙色终点挡墙; 南侧紫色"
        "裁判塔戴四坡尖顶, 透明观察窗正对着陆点 —— 3, 2, 1, 出发!"
    ),
    difficulty=3,
    tags=["运动", "滑雪", "跳台", "坡道", "进阶"],
    min_pieces=50,
    min_steps=16,
)
