#!/usr/bin/env python3
"""生成模型 data/models/lunar_lander_01.json (月面着陆器)。

航天器系列首作 (内容策略简报 ⑨, 主技法 T16 分体对接 + T14 斜撑 +
T13 中空薄壳): 教程复刻真实航天器的级间结构 —— 先在月面上组装
下降级 (着陆平台 + 四条风车状斜撑起落架), 再于其甲板上对接组装
上升级 (中空指令舱 + 四坡锥形返回舱盖), 最后挂载天线、舷梯、
散热板与任务旗。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 月面着陆场 5x5 (灰色环形山地貌)                          25 片
  - 下降级: 3x3 舱体一层墙 + 四条直角三角起落架 (风车状)      12 + 4 片
  - 级间甲板 3x3 (z=1, 对接面)                                9 片
  - 上升级: 1x1 中空指令舱 (z 1..2) + 等腰四坡返回舱盖         4 + 4 片
  - 外挂设备: 东西六边形散热板 x2, 舷梯坡道, 天线塔尖, 任务旗   5 片
  合计 63 片, 16 个教程步骤。

物理规则要点 (通过 R1~R8 全部校验):
  - 起落架斜撑两条直角边分别吸住月面地台边与舱体墙角竖边 (T14);
  - 级间甲板四周全部坐在下降级墙顶上, 中间片四邻互吸, 无悬挑;
  - 返回舱盖四片等腰三角形底边吸舱顶、斜棱两两互吸, 自锁成环 (T13);
  - 舷梯顶边整边吸甲板北缘, 坡尾越过着陆场自然落地。

用法: python3 tools/generate_lunar_lander.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import HEX_APOTHEM, ModelBuilder  # noqa: E402

b = ModelBuilder()

# =================================================================
# 1. 月面着陆场 5x5: 灰色为主, 点缀几个 "环形山" 青斑
# =================================================================
CRATERS = {(1, 3), (3, 1), (4, 4), (0, 0)}
for j in range(5):
    for i in range(5):
        b.flat(f"m_{i}_{j}", i, j, 0.0, "cyan" if (i, j) in CRATERS else "gray")

# =================================================================
# 2. 下降级舱体: 3x3 占地 (x 1..4, y 1..4) 一层墙, 金色隔热层
# =================================================================
for i in range(3):
    b.wall_ns(f"ds_s_{i}", 1 + i, 1.0, 0, "orange")
for j in range(3):
    b.wall_ew(f"ds_e_{j}", 4.0, 1 + j, 0, "yellow")
for i in range(3):
    b.wall_ns(f"ds_n_{i}", 1 + i, 4.0, 0, "orange")
for j in range(3):
    b.wall_ew(f"ds_w_{j}", 1.0, 1 + j, 0, "yellow")

# 四条起落架 (T14): 竖直角边吸舱体墙角竖边, 水平直角边吸月面地台边,
# 风车状分布 —— 从上往下看像着陆器伸出的四条缓冲腿
LEGS = [
    ("leg_sw", (1.0, 1.0, 0.0), "-x"),
    ("leg_se", (4.0, 1.0, 0.0), "-y"),
    ("leg_ne", (4.0, 4.0, 0.0), "+x"),
    ("leg_nw", (1.0, 4.0, 0.0), "+y"),
]
for tid, corner, hdir in LEGS:
    b.brace(tid, corner, hdir, "red")

# =================================================================
# 3. 级间甲板 (z=1, 3x3): 上升级与下降级的对接面
# =================================================================
for j in range(3):
    for i in range(3):
        color = "blue" if (i, j) == (1, 1) else "gray"
        b.flat(f"deck_{i}_{j}", 1 + i, 1 + j, 1.0, color)

# 舷梯: 长方形 30 度坡道, 顶边吸甲板北缘, 坡尾越过着陆场落地
b.ramp("ladder", "+y", 4.0, 2, 1.0, "cyan")

# =================================================================
# 4. 上升级: 1x1 中空指令舱 (z 1..2, 甲板正中) + 返回舱盖
# =================================================================
b.wall_ns("as_s", 2, 2.0, 1, "blue")
b.wall_ew("as_w", 2.0, 2, 1, "cyan")
b.wall_ns("as_n", 2, 3.0, 1, "blue")
b.wall_ew("as_e", 3.0, 2, 1, "cyan")

# 返回舱盖: 等腰四坡锥顶, 锥尖 z=2.866 (T13 薄壳自锁环)
ROOF_IDS = b.hat4("cap", 2, 2, 2.0, "red", shape="isosceles_triangle")

# =================================================================
# 5. 外挂设备: 散热板 / 天线 / 任务旗
# =================================================================
b.add("rad_w", "hexagon", (1.0, 2.5, 1 + HEX_APOTHEM), (90, 0, 90), "yellow")
b.add("rad_e", "hexagon", (4.0, 2.5, 1 + HEX_APOTHEM), (90, 0, 90), "yellow")
b.spire_ns("antenna", 3, 1.0, 1.0, "purple")
b.add("flag", "rectangle", (0.0, 0.5, 1.0), (0, -90, 0), "red")

# =================================================================
# 教程步骤 (16 步): 按 "月面 -> 下降级 -> 对接甲板 -> 上升级 ->
# 外挂设备" 的级间顺序推进 (T16 分体对接的教学叙事)
# =================================================================
b.step(
    "铺设月面着陆场南半部: 平放 2 排共 10 片正方形, 相邻边互相吸合; "
    "青色片是环形山。",
    [f"m_{i}_{j}" for j in range(2) for i in range(5)],
    tip="着陆场要铺在桌面中央: 舷梯还要从北缘伸出一大截。",
)
b.step(
    "着陆场中部再铺 2 排共 10 片, 与南半部整边贴合。",
    [f"m_{i}_{j}" for j in range(2, 4) for i in range(5)],
    highlight=[f"m_{i}_1" for i in range(5)],
    tip="每片先对准一条边再松手, 整块月面中间不能留缝。",
)
b.step(
    "补齐着陆场最北一排 5 片 —— 5x5 月面就绪, 着陆器可以进场了。",
    [f"m_{i}_4" for i in range(5)],
    highlight=[f"m_{i}_3" for i in range(5)],
    tip="从上往下看, 四个青色环形山应错落分布在灰色月面上。",
)
b.step(
    "下降级起舱: 沿着陆场中央 3x3 区域立起南墙 3 片橙色、西墙 3 片金色正方形, "
    "底边吸月面网格线, 转角竖边互吸。",
    [f"ds_s_{i}" for i in range(3)] + [f"ds_w_{j}" for j in range(3)],
    highlight=["m_1_1", "m_1_3"],
    tip="橙金相间就是真实着陆器的多层隔热毯配色。",
)
b.step(
    "补齐下降级北墙与东墙各 3 片, 舱体四面合围。",
    [f"ds_n_{i}" for i in range(3)] + [f"ds_e_{j}" for j in range(3)],
    highlight=["ds_w_2", "ds_s_2"],
    tip="最后一片放入前检查四角: 每个转角的两片都应互相吸牢。",
)
b.step(
    "安装四条起落架: 红色直角三角形竖直角边吸舱体墙角竖边, 水平直角边贴住"
    "月面网格线, 四条腿呈风车状伸向四方。",
    [tid for tid, _, _ in LEGS],
    highlight=["ds_s_0", "ds_e_0", "ds_n_2", "ds_w_2"],
    tip="起落架必须两条直角边同时吸合 —— 它们是着陆缓冲结构, 不是装饰。",
)
b.step(
    "铺设级间甲板第 1 排: 3 片正方形坐上下降级南墙顶, 这一层就是两级的对接面。",
    [f"deck_{i}_0" for i in range(3)],
    highlight=[f"ds_s_{i}" for i in range(3)],
    tip="甲板边缘要同时吸住墙顶边与相邻甲板片。",
)
b.step(
    "铺设甲板第 2 排: 中央那片换成蓝色 —— 它是上升级的对接标记。",
    [f"deck_{i}_1" for i in range(3)],
    highlight=[f"deck_{i}_0" for i in range(3)],
    tip="蓝色片四边都要吸住相邻片, 对接面才能整体受力。",
)
b.step(
    "补齐甲板第 3 排 3 片, 下降级封顶完成 —— 第一级组装完毕!",
    [f"deck_{i}_2" for i in range(3)],
    highlight=[f"deck_{i}_1" for i in range(3)],
    tip="轻压甲板四角检查: 应结实得能托住整个上升级。",
)
b.step(
    "安装舷梯: 青色长方形斜靠在甲板北缘, 顶边整边吸合, 坡尾越过月面自然落地 —— "
    "宇航员将从这里走下着陆器。",
    ["ladder"],
    highlight=["deck_1_2"],
    tip="先把顶边完整贴上甲板边缘再松手, 坡尾要平稳落在桌面上。",
)
b.step(
    "上升级进场: 在甲板正中的蓝色标记上立起指令舱南墙与西墙各 1 片。",
    ["as_s", "as_w"],
    highlight=["deck_1_1"],
    tip="从这一步开始组装第二级 —— 对接面就是甲板网格线。",
)
b.step(
    "补齐指令舱北墙与东墙, 1x1 中空舱体合围 —— 舱内不需要任何支撑, "
    "全靠四面薄壳磁吸自持。",
    ["as_n", "as_e"],
    highlight=["as_s", "as_w"],
    tip="四角竖边两两互吸后, 轻捏舱体上口应感觉整体联动。",
)
b.step(
    "盖上返回舱盖: 4 片红色等腰三角形底边分别吸住舱顶四边, 斜棱两两互吸, "
    "合拢成尖顶锥形 —— 这就是宇航员回家的座舱。",
    ROOF_IDS,
    highlight=["as_s", "as_n", "as_w", "as_e"],
    tip="先立两片相对的, 再补另外两片, 四条斜棱吸合成环后极其稳固。",
)
b.step(
    "挂载散热板: 两片黄色六边形分别立在甲板东西两缘, 底边同时吸住甲板边与墙顶边。",
    ["rad_w", "rad_e"],
    highlight=["deck_0_1", "deck_2_1"],
    tip="六边形立稳后像着陆器展开的太阳翼, 左右对称。",
)
b.step(
    "竖起天线: 紫色等腰三角塔尖立在甲板南缘, 尖端指向地球方向。",
    ["antenna"],
    highlight=["deck_2_0"],
    tip="捏住尖角轻轻放下, 底边吸合即可站稳。",
)
b.step(
    "插上任务旗: 红色长方形竖立在着陆场西南角 —— 月面着陆器全系统就位, "
    "任务成功!",
    ["flag"],
    highlight=["m_0_0"],
    tip="旗面竖直朝上, 底边吸住月面边缘; 完成后合影留念。",
)

b.finalize(
    model_id="lunar_lander_01",
    name="月面着陆器",
    name_en="Lunar Lander 01",
    description=(
        "复刻真实航天器级间结构的分体对接教程: 先在 5x5 月面上组装下降级 —— "
        "金橙隔热舱体加四条风车状直角三角起落架 (每条腿双边吸合), 再铺 3x3 级间"
        "甲板对接上升级 —— 中空指令舱与四坡锥形返回舱盖自锁成环; 最后挂载六边形"
        "散热板、舷梯、天线与任务旗。搭完从舷梯走下第一步, 就是你的一大步。"
    ),
    difficulty=3,
    tags=["航天", "着陆器", "分体对接", "航天器", "进阶"],
    min_pieces=50,
    min_steps=16,
)
