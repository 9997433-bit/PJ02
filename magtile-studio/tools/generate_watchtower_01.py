#!/usr/bin/env python3
"""生成模型 data/models/watchtower_01.json (城墙转角哨塔)。

内容批 K 模型 1/4: 城堡与要塞主题首个 D1 —— 与 castle_tower_01
(75 片土丘要塞) 体量与结构均拉开。招牌是单塔 + L 形转角城墙短段:
T01 盒式框架搭起两层哨塔, T17 负空间用窗格方箭窗与门框方门洞
表达"能瞭望、能射击"的防御语义, 不是四片围一圈的敷衍城堡。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 使用者站在南侧):
  - 草甸地台 (x [0,4], y [0,2]): 灰绿棋盘方板                    8 片
  - L 形城墙 (西腿 x=0 + 南腿 y=0): 立墙 x4 + 城齿 x2              6 片
  - 哨塔一层 (x [1,2], y [1,2], z 0..1): 四墙合围 + 门框南门洞    5 片
  - 哨塔二层 (z 1..2): 三墙 + 北窗格方箭窗 + 平顶 + 等腰瞭望尖     6 片
  - 转角垛口 (z=1 沿口): 等边三角 x1                               1 片
  合计 24 片, 7 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 城墙墙脚整边踩地台拼缝, 转角竖边互咬;
  - 哨塔每层墙环四角竖边互吸闭环, 底层同时吸地台拼缝;
  - 箭窗/门洞语义片物理按实心墙处理, 负空间仅作造型表达;
  - 瞭望尖骑墙顶沿口, 重心正压铰链线。

用法: python3 tools/generate_watchtower_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

GRASS = "green"
PATH = "gray"
STONE = "gray"
WALL = "blue"
GATE = "orange"     # 门框方门洞 (T17)
SLIT = "clear"      # 窗格方箭窗 (T17)
CREST = "yellow"
LOOKOUT = "red"


def wall_ns_t(tid, tile_type, x0, y, z0, color):
    b.add(tid, tile_type, (x0 + 0.5, y, z0 + 0.5), (90, 0, 0), color)


# =================================================================
# 1. 草甸地台 (x [0,4], y [0,2])
# =================================================================
for j in range(2):
    for i in range(4):
        b.flat(f"ground_{i}_{j}", i, j, 0.0, GRASS if (i + j) % 2 == 0 else PATH)

# =================================================================
# 2. L 形城墙短段 (西腿 + 南腿) + 城齿
# =================================================================
b.wall_ew("wall_w_0", 0.0, 0, 0, STONE)
b.wall_ew("wall_w_1", 0.0, 1, 0, STONE)
b.wall_ns("wall_s_1", 1, 0.0, 0, STONE)
b.wall_ns("wall_s_2", 2, 0.0, 0, STONE)
b.crest_ew("crenel_w", 0.0, 1, 1.0, CREST)
b.crest_ns("crenel_s", 2, 0.0, 1.0, CREST)

# =================================================================
# 3. 哨塔一层 (1x1 盒式, 南门洞)
# =================================================================
b.wall_ns("t1_n", 1, 2.0, 0, WALL)
b.wall_ew("t1_w", 1.0, 1, 0, WALL)
wall_ns_t("t1_gate", "door_frame", 1, 1.0, 0, GATE)
b.wall_ew("t1_e", 2.0, 1, 0, WALL)

# =================================================================
# 4. 哨塔二层 (北箭窗 + 平顶 + 瞭望尖)
# =================================================================
wall_ns_t("t2_slit", "window_square", 1, 2.0, 1, SLIT)
b.wall_ew("t2_w", 1.0, 1, 1, WALL)
b.wall_ew("t2_e", 2.0, 1, 1, WALL)
b.flat("t2_roof", 1, 1, 2.0, WALL)
b.spire_ns("lookout", 1, 1.0, 2.0, LOOKOUT)

# =================================================================
# 5. 转角垛口 (L 形城墙与塔体交会处)
# =================================================================
b.crest_ns("tower_crenel", 1, 2.0, 2.0, CREST)

# =================================================================
# 教程步骤 (7 步)
# =================================================================
b.step(
    "铺草甸地台: 八片灰绿相间的方板拼成 4x2 平台, 这是转角城墙的地基。",
    [f"ground_{i}_{j}" for j in range(2) for i in range(4)],
    tip="拼缝对齐了, 上面的城墙和哨塔才有整边可吸。",
)
b.step(
    "立 L 形城墙: 西墙两片、南墙两片合围转角, 墙脚整边踩地台拼缝。",
    ["wall_w_0", "wall_w_1", "wall_s_1", "wall_s_2"],
    highlight=["ground_0_0", "ground_1_0"],
    tip="L 形短段就是城墙转角 —— 敌人从这边来, 先看见的就是这截墙。",
)
b.step(
    "装城墙城齿: 西墙与南墙顶沿各立一片黄色等边三角垛口。",
    ["crenel_w", "crenel_s"],
    highlight=["wall_w_1", "wall_s_2"],
    tip="城齿与墙共面, 重心正压墙顶 —— 力矩为零。",
)
b.step(
    "起哨塔一层: 三片蓝墙合围, 南面嵌一片橙色门框方门洞。",
    ["t1_n", "t1_w", "t1_gate", "t1_e"],
    highlight=["ground_1_1"],
    tip="门洞朝南 —— 哨兵进出塔内, 敌人从墙外看不见里面。",
)
b.step(
    "加哨塔二层: 北墙换清色窗格方箭窗, 东西墙续高, 平顶封住塔顶。",
    ["t2_slit", "t2_w", "t2_e", "t2_roof"],
    highlight=["t1_n", "t1_gate"],
    tip="箭窗就是 T17 负空间 —— 少一片墙, 瞭望孔却更有城堡味道。",
)
b.step(
    "立瞭望尖与塔顶城齿: 红色瞭望尖 + 黄色垛口 —— 转角哨塔落成!",
    ["lookout", "tower_crenel"],
    highlight=["t2_roof"],
    tip="单塔加短墙, 体量不大却站得住 —— 城堡主题第一座 D1 入门作品。",
)

b.finalize(
    model_id="watchtower_01",
    name="城墙转角哨塔",
    name_en="Corner Watchtower 01",
    description=(
        "城堡与要塞 D1 入门: 单座两层哨塔嵌在 L 形转角城墙短段上 —— 盒式墙环"
        "合围, 南门洞与北箭窗用门框方/窗格方做负空间造型; 黄色城齿与红色"
        "瞭望尖让体量虽小却有要塞味道。与 75 片的土丘主塔刻意拉开, 这是"
        "孩子能独立完成的第一个城堡作品。"
    ),
    difficulty=1,
    tags=["城堡", "哨塔", "城墙", "入门", "要塞"],
    min_pieces=24,
    min_steps=6,
    series="castle_fortress",
)
