#!/usr/bin/env python3
"""生成模型 data/models/particle_accelerator_01.json (环形粒子加速器)。

科幻/实验室主题 2/4: 全库第一座环形封闭隧道建筑 —— 与 observatory_01
(叠环鼓身) 和 art_gallery_01 (L 形白盒) 的结构逻辑刻意区分:
主体是一圈 "回" 字形束流隧道 —— 外墙环 12 片与内墙环 4 片双圈
合围, 8 片屏蔽顶板跨在双圈墙顶上 (每片同时压外墙顶 + 内墙顶 +
邻板拼缝, 双端受力零悬挑); 外墙嵌红蓝窗格方 "偏转磁铁" 色块,
束流从东侧门框方注入口冲进环里; 环心 1x1 对撞厅四面蓝色窗格方
观察窗, 厅顶等边四坡探测器穹顶自锁收头; 东侧直线注入器隧道
两墙一顶接在注入口上, 隧道口骑黄色束流标志; 西南角控制室
长板横楣 + 窗格方 + 门框方围成值班间, 屋顶西沿骑红色雷达 ——
全环通电, 束流对撞!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 注入器朝东):
  - 场地 8x5: 方板 + 长板混铺 (青色束流走廊 + 黄色对撞点)   30 片
  - 外墙环 (周长 12): 灰方 x8 + 磁铁窗格方 x3 + 注入门 x1   12 片
  - 内墙环 (对撞厅): 蓝色窗格方观察窗 x4                     4 片
  - 屏蔽顶板 (z=1): "回" 字环形 8 片                          8 片
  - 探测器穹顶: 对撞厅顶等边四坡锥 x4 (锥尖 1.71)            4 片
  - 注入器隧道: 侧墙 x4 + 顶板 x2 + 束流标志 x1              7 片
  - 控制室: 横楣 + 侧墙 x2 + 窗 + 门 + 屋顶 + 雷达           7 片
  合计 72 片, 14 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (R1~R8 全绿, strict 档零警告):
  - 双圈墙在四角竖边互吸, 每片顶板同时吸外墙顶 / 内墙顶 /
    邻板拼缝 —— 全环处处成环, 无一片单点受力;
  - 注入器侧墙西端竖边吸注入门竖边, 顶板双墙受力;
  - 控制室东墙竖边与外墙环西南角竖边互吸 (贴建);
  - 全场最高点 1.87 (< 2.5), 不触发 R8 高层检查; 无悬挑无吊挂。

用法: python3 tools/generate_particle_accelerator.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

FIELD = "gray"      # 场地
BEAM = "cyan"       # 束流走廊地面 / 注入器
CORE = "yellow"     # 对撞点地标 / 束流标志
WALL = "gray"       # 隧道墙 / 屏蔽体
MAG_R = "red"       # 偏转磁铁色块
MAG_B = "blue"
PORT = "yellow"     # 注入口门
DET = "blue"        # 探测器观察窗
SHIELD = "purple"   # 屏蔽顶板
DOME = "yellow"     # 探测器穹顶
GLASS = "clear"     # 控制室窗
DOOR = "orange"     # 控制室门
RADAR = "red"       # 雷达

# =================================================================
# 1. 场地 (x [0,8], y [0,5]): 拼缝对准双圈墙线与注入器墙线
# =================================================================
b.flat_rect("f0_a", 0, 0, 0.0, FIELD)     # 控制室地板
b.flat("f0_b", 2, 0, 0.0, FIELD)
b.flat("f0_c", 3, 0, 0.0, FIELD)
b.flat("f0_d", 4, 0, 0.0, FIELD)
b.flat_rect("f0_e", 5, 0, 0.0, FIELD)
b.flat("f0_f", 7, 0, 0.0, FIELD)

b.flat_rect("f1_a", 0, 1, 0.0, FIELD)
b.flat("f1_b", 2, 1, 0.0, BEAM)           # 束流走廊南段
b.flat("f1_c", 3, 1, 0.0, BEAM)
b.flat("f1_d", 4, 1, 0.0, BEAM)
b.flat("f1_e", 5, 1, 0.0, FIELD)
b.flat("f1_f", 6, 1, 0.0, FIELD)
b.flat("f1_g", 7, 1, 0.0, FIELD)

b.flat_rect("f2_a", 0, 2, 0.0, FIELD)
b.flat("f2_b", 2, 2, 0.0, BEAM)           # 束流走廊西段
b.flat("f2_c", 3, 2, 0.0, CORE)           # 对撞点地标
b.flat("f2_d", 4, 2, 0.0, BEAM)           # 束流走廊东段
b.flat("f2_e", 5, 2, 0.0, BEAM)           # 注入器地面
b.flat("f2_f", 6, 2, 0.0, BEAM)
b.flat("f2_g", 7, 2, 0.0, FIELD)

b.flat_rect("f3_a", 0, 3, 0.0, FIELD)
b.flat("f3_b", 2, 3, 0.0, BEAM)           # 束流走廊北段
b.flat("f3_c", 3, 3, 0.0, BEAM)
b.flat("f3_d", 4, 3, 0.0, BEAM)
b.flat_rect("f3_e", 5, 3, 0.0, FIELD)
b.flat("f3_f", 7, 3, 0.0, FIELD)

b.flat_rect("f4_a", 0, 4, 0.0, FIELD)
b.flat_rect("f4_b", 2, 4, 0.0, FIELD)
b.flat_rect("f4_c", 4, 4, 0.0, FIELD)
b.flat_rect("f4_d", 6, 4, 0.0, FIELD)

# =================================================================
# 2. 外墙环 (周长 12, x [2,5] x y [1,4]): 磁铁色块 + 注入口
# =================================================================
b.wall_ns("rs1", 2, 1.0, 0, WALL)                              # 南
b.add("rs2", "window_square", (3.5, 1.0, 0.5), (90, 0, 0), MAG_R)
b.wall_ns("rs3", 4, 1.0, 0, WALL)
b.wall_ew("rw1", 2.0, 1, 0, WALL)                              # 西
b.add("rw2", "window_square", (2.0, 2.5, 0.5), (90, 0, 90), MAG_R)
b.wall_ew("rw3", 2.0, 3, 0, WALL)
b.wall_ns("rn1", 2, 4.0, 0, WALL)                              # 北
b.add("rn2", "window_square", (3.5, 4.0, 0.5), (90, 0, 0), MAG_B)
b.wall_ns("rn3", 4, 4.0, 0, WALL)
b.wall_ew("re1", 5.0, 1, 0, WALL)                              # 东
b.add("re2", "door_frame", (5.0, 2.5, 0.5), (90, 0, 90), PORT)  # 注入口
b.wall_ew("re3", 5.0, 3, 0, WALL)

# =================================================================
# 3. 对撞厅内墙环 (x [3,4] x y [2,3]): 四面观察窗
# =================================================================
b.add("di_s", "window_square", (3.5, 2.0, 0.5), (90, 0, 0), DET)
b.add("di_e", "window_square", (4.0, 2.5, 0.5), (90, 0, 90), DET)
b.add("di_n", "window_square", (3.5, 3.0, 0.5), (90, 0, 0), DET)
b.add("di_w", "window_square", (3.0, 2.5, 0.5), (90, 0, 90), DET)

# =================================================================
# 4. 屏蔽顶板 (z=1): "回" 字环形 8 片, 双圈墙顶受力
# =================================================================
b.flat("rf_sw", 2, 1, 1.0, SHIELD)
b.flat("rf_s", 3, 1, 1.0, SHIELD)
b.flat("rf_se", 4, 1, 1.0, SHIELD)
b.flat("rf_w", 2, 2, 1.0, SHIELD)
b.flat("rf_e", 4, 2, 1.0, SHIELD)
b.flat("rf_nw", 2, 3, 1.0, SHIELD)
b.flat("rf_n", 3, 3, 1.0, SHIELD)
b.flat("rf_ne", 4, 3, 1.0, SHIELD)

# 探测器穹顶: 对撞厅顶等边四坡锥自锁 (锥尖 1.71)
DOME_IDS = b.hat4("dome", 3, 2, 1.0, DOME, shape="equilateral_triangle")

# =================================================================
# 5. 注入器隧道 (x [5,7] x y [2,3]): 两墙一顶 + 束流标志
# =================================================================
b.wall_ns("inj_s1", 5, 2.0, 0, WALL)
b.wall_ns("inj_s2", 6, 2.0, 0, WALL)
b.wall_ns("inj_n1", 5, 3.0, 0, WALL)
b.wall_ns("inj_n2", 6, 3.0, 0, WALL)
b.flat("inj_r1", 5, 2, 1.0, BEAM)
b.flat("inj_r2", 6, 2, 1.0, BEAM)
b.crest_ew("inj_flag", 7.0, 2, 1.0, CORE)   # 隧道口束流标志

# =================================================================
# 6. 控制室 (x [0,2] x y [0,1]): 贴建在外墙环西南角
# =================================================================
b.lintel_ns("cr_s", 0, 0.0, 0, WALL)
b.wall_ew("cr_w", 0.0, 0, 0, WALL)
b.wall_ew("cr_e", 2.0, 0, 0, WALL)
b.add("cr_win", "window_square", (0.5, 1.0, 0.5), (90, 0, 0), GLASS)
b.add("cr_door", "door_frame", (1.5, 1.0, 0.5), (90, 0, 0), DOOR)
b.flat_rect("cr_roof", 0, 0, 1.0, WALL)
b.crest_ew("cr_radar", 0.0, 0, 1.0, RADAR)   # 屋顶西沿雷达

# =================================================================
# 教程步骤 (14 步)
# =================================================================
b.step(
    "铺南侧场地 (y [0,1]): 6 片, 西端两格是控制室地板。",
    ["f0_a", "f0_b", "f0_c", "f0_d", "f0_e", "f0_f"],
    tip="拼缝就是墙线 —— 控制室与加速器环都会立在这些缝上。",
)
b.step(
    "铺束流走廊南排 (y [1,2]): 7 片青色走廊开始成形。",
    ["f1_a", "f1_b", "f1_c", "f1_d", "f1_e", "f1_f", "f1_g"],
    highlight=["f0_c"],
    tip="青色地面是束流隧道的内部走廊, 一会儿会被墙环圈住。",
)
b.step(
    "铺对撞排 (y [2,3]): 7 片, 黄色对撞点居中。",
    ["f2_a", "f2_b", "f2_c", "f2_d", "f2_e", "f2_f", "f2_g"],
    highlight=["f1_c"],
    tip="黄色方板是对撞点 —— 环心对撞厅将罩在它头上。",
)
b.step(
    "铺北侧场地 (y [3,5]): 10 片, 场地合拢。",
    ["f3_a", "f3_b", "f3_c", "f3_d", "f3_e", "f3_f",
     "f4_a", "f4_b", "f4_c", "f4_d"],
    highlight=["f2_c"],
    tip="8x5 场地铺满, 束流走廊在场地中央绕成一圈。",
)
b.step(
    "立外墙环南墙与西墙: 灰墙间嵌红色偏转磁铁。",
    ["rs1", "rs2", "rs3", "rw1", "rw2", "rw3"],
    highlight=["f1_b", "f2_b"],
    tip="彩色窗格方就是加速器的偏转磁铁 —— 墙即设备。",
)
b.step(
    "立外墙环北墙与东墙: 蓝磁铁 + 黄色门框方注入口。",
    ["rn1", "rn2", "rn3", "re1", "re2", "re3"],
    highlight=["rs1", "rw1"],
    tip="四角竖边互吸闭环 —— 束流将从东侧门框冲进环里。",
)
b.step(
    "立对撞厅内墙环: 4 面蓝色观察窗围住对撞点。",
    ["di_s", "di_e", "di_n", "di_w"],
    highlight=["f2_c"],
    tip="内外双圈墙隔出 '回' 字形隧道 —— 这就是束流的跑道。",
)
b.step(
    "盖南段屏蔽顶板: 3 片, 跨在双圈墙顶上。",
    ["rf_sw", "rf_s", "rf_se"],
    highlight=["rs1", "di_s"],
    tip="每片顶板同时压外墙顶与内墙顶 —— 双端受力零悬挑。",
)
b.step(
    "盖其余屏蔽顶板: 5 片, '回' 字环形合龙。",
    ["rf_w", "rf_e", "rf_nw", "rf_n", "rf_ne"],
    highlight=["rf_sw", "rf_se"],
    tip="紫色屏蔽层锁住整圈隧道, 轻推全环应一起联动。",
)
b.step(
    "起探测器穹顶: 对撞厅顶 4 片黄色等边锥自锁。",
    DOME_IDS,
    highlight=["rf_s", "rf_n"],
    tip="四条斜棱两两互吸 —— 穹顶下就是束流对撞的地方。",
)
b.step(
    "立注入器隧道侧墙: 4 片, 西端竖边吸注入口门框。",
    ["inj_s1", "inj_s2", "inj_n1", "inj_n2"],
    highlight=["re2"],
    tip="直线注入器正对门框方 —— 束流由此加速入环。",
)
b.step(
    "盖注入器顶板、骑束流标志: 隧道口黄旗朝东。",
    ["inj_r1", "inj_r2", "inj_flag"],
    highlight=["inj_s1", "inj_n1"],
    tip="顶板双墙受力, 黄色三角骑在隧道口沿上。",
)
b.step(
    "立控制室四墙: 横楣朝南, 窗与门朝加速器。",
    ["cr_s", "cr_w", "cr_e", "cr_win", "cr_door"],
    highlight=["rw1"],
    tip="控制室东墙竖边贴吸外墙环西南角 —— 贴建不另起炉灶。",
)
b.step(
    "盖控制室屋顶、骑雷达 —— 全环通电, 束流对撞!",
    ["cr_roof", "cr_radar"],
    highlight=["cr_win", "cr_door"],
    tip="长板屋顶四边受力, 红色雷达骑在屋顶西沿监视全环。",
)

b.finalize(
    model_id="particle_accelerator_01",
    name="环形粒子加速器",
    name_en="Particle Accelerator 01",
    description=(
        "全库第一座环形封闭隧道建筑: 外墙环 12 片与对撞厅内墙环 4 片"
        "双圈合围出 '回' 字形束流隧道, 8 片紫色屏蔽顶板跨在双圈墙顶上"
        "双端受力; 外墙嵌红蓝窗格方偏转磁铁, 束流从东侧门框方注入口"
        "经直线注入器隧道冲进环里; 环心对撞厅四面蓝色观察窗, 厅顶"
        "黄色等边四坡探测器穹顶自锁收头; 西南角控制室贴建在外墙环上, "
        "屋顶西沿骑红色雷达 —— 一圈墙就是一台科学装置。"
    ),
    difficulty=3,
    tags=["科学探索", "粒子加速器", "实验室", "环形隧道", "进阶"],
    min_pieces=72,
    min_steps=14,
)
