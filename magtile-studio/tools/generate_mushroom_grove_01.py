#!/usr/bin/env python3
"""生成模型 data/models/mushroom_grove_01.json (蘑菇精灵谷)。

内容批 F 模型 4/4: 全库第一丛蘑菇 —— 植物花园主题此前只有
rose_pergola (玫瑰花架长廊) / greenhouse (温室) / cactus_desert
(沙漠仙人掌) 等"藤架/棚体/柱体"逻辑, 还没有一件"帽子当主角"的
植物造型。结构签名是"高矮错落的三顶锥帽菇群": 三朵蘑菇的菌盖
都是四坡三角锥自锁帽, 但戴法各不相同 —— 大蘑菇两层菌柄开精灵
门 (门框方), 中蘑菇一层菌柄嵌圆窗 (窗格方), 小蘑菇贴地矮墩;
三顶锥帽在三个高度错开, 剪影像一串从地里冒出来的音符; 旁边倒
一根双楣墙圆木长凳 (lintel 长墙 + 长板压顶), 与 wizard_tower
(单塔尖帽) / gingerbread_house (坡顶糖果屋) 的"一楼一帽"逻辑
刻意区分: 这里是一窝帽子的家族合影。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 场地 5x4):
  - 林地地坪 4 行 (x [0,5], y [0,4])                          14 片
  - 大蘑菇 (x [1,2], y [2,3]): 两层菌柄 (一层带精灵门)
    + 红色四坡锥帽                                            12 片
  - 中蘑菇 (x [3,4], y [2,3]): 一层菌柄 (带圆窗) + 金锥帽      8 片
  - 小蘑菇 (x [2,3], y [0,1]): 一层菌柄 + 粉锥帽               8 片
  - 圆木长凳 (x [3,5], y [0,1]): 双楣墙 + 端墙 + 长板压顶,
    西端与小蘑菇共墙                                           4 片
  - 花篱 x3 + 蜗牛 + 蝴蝶: 骑缝三角                            5 片
  合计 51 片, 12 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告 + jitter 全绿):
  - 菌柄是 1x1 闭环箱楼 (门框方/窗格方按实心正方形受力),
    四角竖边互咬; 锥帽四条斜棱两两互吸自锁, 底边整边吸墙顶;
  - 圆木两面楣墙长边整边吸地板长边 (脚下必须是长板), 端墙
    短边收口, 长板压顶四边全吸 —— 躺倒的箱楼同样是闭环;
  - 地坪拼缝纪律: 菌柄墙脚全单位方板, 圆木脚下整块长板。

用法: python3 tools/generate_mushroom_grove_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

MOSS = "green"      # 林地苔藓
PATH = "gray"       # 林间小径
STALK = "clear"     # 菌柄 (奶白)
DOOR = "orange"     # 精灵门
WINDOW = "cyan"     # 圆窗
CAP_BIG = "red"     # 大蘑菇锥帽
CAP_MID = "yellow"  # 中蘑菇锥帽
CAP_SML = "pink"    # 小蘑菇锥帽
LOG = "orange"      # 圆木长凳
HEDGE = "green"     # 花篱
SNAIL = "purple"    # 蜗牛
FLY = "blue"        # 蓝蝴蝶

# =================================================================
# 1. 林地地坪 4 行 (x [0,5], y [0,4])
# =================================================================
# 蘑菇行 (y [2,3]): 五片单位方板, 大中蘑菇的菌柄脚全踩拼缝
b.flat("g2_0", 0, 2, 0.0, MOSS)
b.flat("g2_1", 1, 2, 0.0, PATH)
b.flat("g2_2", 2, 2, 0.0, MOSS)
b.flat("g2_3", 3, 2, 0.0, PATH)
b.flat("g2_4", 4, 2, 0.0, MOSS)
# 后行 (y [3,4]): 两块长板 + 一片方板
b.flat_rect("g3_w", 0, 3, 0.0, MOSS)
b.flat_rect("g3_m", 2, 3, 0.0, MOSS)
b.flat("g3_4", 4, 3, 0.0, MOSS)
# 小径行 (y [1,2]): 长板 + 小蘑菇北脚方板 + 长板
b.flat_rect("g1_w", 0, 1, 0.0, MOSS)
b.flat("g1_2", 2, 1, 0.0, PATH)
b.flat_rect("g1_e", 3, 1, 0.0, MOSS)
# 前行 (y [0,1]): 长板 + 小蘑菇脚方板 + 圆木脚长板
b.flat_rect("g0_w", 0, 0, 0.0, MOSS)
b.flat("g0_2", 2, 0, 0.0, PATH)
b.flat_rect("g0_log", 3, 0, 0.0, MOSS)

# =================================================================
# 2. 大蘑菇 (x [1,2], y [2,3]): 两层菌柄 + 精灵门 + 红锥帽
# =================================================================
b.add("big_door", "door_frame", (1.5, 2.0, 0.5), (90, 0, 0), DOOR)
b.wall_ew("big_w0", 1.0, 2, 0, STALK)
b.wall_ew("big_e0", 2.0, 2, 0, STALK)
b.wall_ns("big_n0", 1, 3.0, 0, STALK)
b.wall_ns("big_s1", 1, 2.0, 1, STALK)
b.wall_ew("big_w1", 1.0, 2, 1, STALK)
b.wall_ew("big_e1", 2.0, 2, 1, STALK)
b.wall_ns("big_n1", 1, 3.0, 1, STALK)
BIG_CAP = b.hat4("big_cap", 1, 2, 2.0, CAP_BIG,
                 shape="equilateral_triangle")

# =================================================================
# 3. 中蘑菇 (x [3,4], y [2,3]): 一层菌柄 + 圆窗 + 金锥帽
# =================================================================
b.add("mid_win", "window_square", (3.5, 2.0, 0.5), (90, 0, 0), WINDOW)
b.wall_ew("mid_w", 3.0, 2, 0, STALK)
b.wall_ew("mid_e", 4.0, 2, 0, STALK)
b.wall_ns("mid_n", 3, 3.0, 0, STALK)
MID_CAP = b.hat4("mid_cap", 3, 2, 1.0, CAP_MID,
                 shape="equilateral_triangle")

# =================================================================
# 4. 小蘑菇 (x [2,3], y [0,1]): 贴地矮墩 + 粉锥帽
# =================================================================
b.wall_ns("sml_s", 2, 0.0, 0, STALK)
b.wall_ns("sml_n", 2, 1.0, 0, STALK)
b.wall_ew("sml_w", 2.0, 0, 0, STALK)
b.wall_ew("sml_e", 3.0, 0, 0, STALK)
SML_CAP = b.hat4("sml_cap", 2, 0, 1.0, CAP_SML,
                 shape="equilateral_triangle")

# =================================================================
# 5. 圆木长凳 (x [3,5], y [0,1]): 躺倒的箱楼
# =================================================================
b.lintel_ns("log_s", 3, 0.0, 0, LOG)
b.lintel_ns("log_n", 3, 1.0, 0, LOG)
b.wall_ew("log_e", 5.0, 0, 0, LOG)
b.flat_rect("log_cap", 3, 0, 1.0, LOG)

# =================================================================
# 6. 花篱 x3 (西缘) + 蜗牛 + 蝴蝶
# =================================================================
b.crest_ew("hedge_1", 0.0, 1, 0.0, HEDGE)
b.crest_ew("hedge_2", 0.0, 2, 0.0, HEDGE)
b.crest_ew("hedge_3", 0.0, 3, 0.0, HEDGE)
b.crest_ns("snail", 2, 2.0, 0.0, SNAIL)     # 蜗牛骑小径拼缝
b.crest_ns("fly", 4, 3.0, 0.0, FLY)         # 蝴蝶骑后行拼缝

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺蘑菇行: 五片方板一字排开, 苔藓和小径交替。",
    ["g2_0", "g2_1", "g2_2", "g2_3", "g2_4"],
    tip="精灵谷开垦啦! 菌柄脚下必须是单位方板。",
)
b.step(
    "铺后行与小径行: 长板与方板整边互吸, 谷地向两边展开。",
    ["g3_w", "g3_m", "g3_4", "g1_w", "g1_2", "g1_e"],
    highlight=["g2_0", "g2_2"],
    tip="长板短边对方板整边 —— 苔藓地毯越铺越大。",
)
b.step(
    "铺前行收口: 长板 + 方板 + 圆木脚下的整块长板。",
    ["g0_w", "g0_2", "g0_log"],
    highlight=["g1_2"],
    tip="右下角这块长板是给圆木长凳留的床位。",
)
b.step(
    "立大蘑菇一层菌柄: 橙色精灵门朝南, 三片奶白墙围合闭环。",
    ["big_door", "big_w0", "big_e0", "big_n0"],
    highlight=["g2_1"],
    tip="门框方和普通方片一样结实 —— 精灵从这里进出。",
)
b.step(
    "大蘑菇菌柄长到二层: 四片奶白墙整边共线摞上去。",
    ["big_s1", "big_w1", "big_e1", "big_n1"],
    highlight=["big_door"],
    tip="四角竖边互咬 —— 菌柄是结实的小圆筒。",
)
b.step(
    "给大蘑菇戴红锥帽: 四片等边三角斜棱两两互吸自锁。",
    BIG_CAP,
    highlight=["big_s1"],
    tip="帽子底边整边吸住墙顶, 四条斜棱自己锁自己!",
)
b.step(
    "立中蘑菇菌柄: 青色圆窗朝南, 三片奶白墙围合。",
    ["mid_win", "mid_w", "mid_e", "mid_n"],
    highlight=["g2_3"],
    tip="窗格方是中蘑菇的小圆窗 —— 里面住着谁呢?",
)
b.step(
    "给中蘑菇戴金锥帽。",
    MID_CAP,
    highlight=["mid_win"],
    tip="第二顶帽子在半山腰 —— 高矮错落才像一家人。",
)
b.step(
    "立小蘑菇矮墩: 四片奶白墙贴地围合。",
    ["sml_s", "sml_n", "sml_w", "sml_e"],
    highlight=["g0_2", "g1_2"],
    tip="小蘑菇刚从土里冒头, 个子最小胆子最大。",
)
b.step(
    "给小蘑菇戴粉锥帽: 三顶锥帽在三个高度排成一串音符。",
    SML_CAP,
    highlight=["sml_s"],
    tip="红金粉三顶帽子高矮错落 —— 菇群合影完成!",
)
b.step(
    "放圆木长凳: 两面橙色楣墙长边吸住脚下长板, 西端顶住小蘑菇, "
    "东端墙收口, 长板压顶。",
    ["log_s", "log_n", "log_e", "log_cap"],
    highlight=["g0_log", "sml_e"],
    tip="圆木一头靠着小蘑菇 —— 躺倒的箱楼同样围成闭环。",
)
b.step(
    "种花篱请小客人: 三片绿篱骑西缘, 紫蜗牛骑小径缝, 蓝蝴蝶落后排。",
    ["hedge_1", "hedge_2", "hedge_3", "snail", "fly"],
    highlight=["g2_0", "g3_4"],
    tip="蜗牛慢慢爬, 蝴蝶翩翩飞 —— 蘑菇精灵谷开村!",
)

b.finalize(
    model_id="mushroom_grove_01",
    name="蘑菇精灵谷",
    name_en="Mushroom Grove 01",
    description=(
        "只用核心九片型的林间一景, 全库第一丛蘑菇, 给植物花园"
        "补上'帽子当主角'的造型: 结构签名是'高矮错落的三顶锥帽"
        "菇群' —— 三朵蘑菇的菌盖都是四坡等边三角锥自锁帽, 但戴法"
        "各不相同: 大蘑菇两层奶白菌柄开橙色精灵门 (门框方), 红锥帽"
        "戴在两层高; 中蘑菇一层菌柄嵌青色圆窗 (窗格方), 金锥帽戴在"
        "一层高; 小蘑菇贴地矮墩顶粉锥帽 —— 三顶帽子在三个高度错开, "
        "剪影像一串从地里冒出来的音符; 旁边躺一根橙色圆木长凳 (双楣"
        "墙长边整边吸脚下长板 + 长板压顶的躺倒箱楼), 绿篱骑西缘, "
        "紫蜗牛慢慢爬, 蓝蝴蝶翩翩飞 —— 蘑菇精灵谷开村!"
    ),
    difficulty=3,
    tags=["植物花园", "蘑菇", "森林", "精灵", "进阶"],
    min_pieces=51,
    min_steps=12,
)
