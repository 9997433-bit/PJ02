#!/usr/bin/env python3
"""生成模型 data/models/er_entrance_01.json (急诊入口)。

医院健康主题: 全库第一条 "入院风雨连廊" —— 与 hospital_01 (楼板
南缘外挑双片小雨棚) / toll_station_01 (收费亭当桥墩托雨棚) /
car_wash_01 (两墙夹道的封闭隧道) 的遮盖逻辑都不同: 这里是一串
门式框架连成的开敞雨廊 —— 四根独立方柱两两相对, 两片透明廊顶
长板短边各压一对柱顶 (双端受力零悬臂), 廊顶末节北长边还骑在
急诊大厅的双红门顶上 —— 廊子一头接街边、一头接大门, 担架车
淋不着一滴雨。急诊大厅是 5x2 的一层白盒: 南立面双红门框方
并肩 (医院同款推拉大门) 加三扇青色观察窗, 屋顶双红灯箱压门
而立、白色等腰旗杆在北檐高扬; 廊口停着一辆双轮担架车 —— 两片
车轮底座平行立在地缝上, 白色床板双长边同时压住两排轮顶,
锁成一个滚动的小门式框架, 正要推进大厅。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 大门朝南):
  - 街面地坪 7x5: 前院/连廊道/救护车位标线/后草坪            25 片
  - 急诊大厅 [1,6]x[2,4] 一层: 南立面 窗x3+红门框方x2,
    北墙 x5, 东西山墙各 x2                                    14 片
  - 大厅平顶: 长板 x4 + 方板 x2                                6 片
  - 急诊灯箱: 红方板 x2 压双门顶而立 + 红等边 x2               4 片
  - 北檐旗杆: 白等腰 x1                                        1 片
  - 风雨连廊: 独立方柱 x4 + 透明廊顶长板 x2                    6 片
  - 担架车: 车轮底座 x2 + 床板长板 x1                          3 片
  - 门口大树 x2: 橙干 + 绿冠                                   4 片
  合计 63 片, 13 个教程步骤, 7 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, 常规+strict 双档零警告):
  - 连廊每节都是门式框架: 廊顶长板两条短边整边压相对柱顶,
    双端受力零悬臂; 末节北长边同时吸两扇门框方顶边 (三边受力);
  - 柱脚整边吸地坪格线, 柱北竖边与大厅南墙竖边 90 度互咬;
  - 担架车与 ambulance_01 底盘同款门式框架: 床板双长边压
    双轮顶, 剪断任一条铰链线力都绕行;
  - 灯箱底边整边吸门框方顶边 (与廊顶长边共线), 双箱竖边互吸
    冗余, 重心正压铰链零力矩。

用法: python3 tools/generate_er_entrance.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

PAVE = "gray"       # 前院地坪
LANE = "cyan"       # 连廊步道
BAY = "yellow"      # 救护车位标线
FLOOR = "clear"     # 大厅室内地面
LAWN = "green"      # 草坪
WALL = "clear"      # 大厅墙身
WIN = "cyan"        # 观察窗
DOOR = "red"        # 急诊推拉门
ROOF = "gray"       # 大厅平顶
SIGN = "red"        # 急诊灯箱
FLAG = "clear"      # 北檐旗杆
COL = "clear"       # 连廊方柱
CANOPY = "clear"    # 连廊廊顶
WHEEL = "gray"      # 担架车轮
BED = "clear"       # 担架床板
TRUNK = "orange"    # 树干
LEAF = "green"      # 树冠

# =================================================================
# 1. 地坪 7x5: 前院 / 连廊道 / 救护车位 / 大厅地面 / 后草坪
# =================================================================
# 行 y[0,1]: 担架车位 (长板北边留给车轮缝) + 连廊道 + 救护车位标线
b.flat("g0_w", 0, 0, 0.0, PAVE)
b.flat_rect("g0_gur", 1, 0, 0.0, PAVE)          # [1,3] 担架车底板
b.flat("g0_l0", 3, 0, 0.0, LANE)                # 连廊步道
b.flat("g0_l1", 4, 0, 0.0, LANE)
b.flat_rect("g0_bay", 5, 0, 0.0, BAY)           # 救护车位标线
# 行 y[1,2]
b.flat("g1_w", 0, 1, 0.0, PAVE)
b.flat_rect("g1_gur", 1, 1, 0.0, PAVE)          # 南边即车轮缝
b.flat("g1_l0", 3, 1, 0.0, LANE)
b.flat("g1_l1", 4, 1, 0.0, LANE)
b.flat_rect("g1_bay", 5, 1, 0.0, BAY)
# 行 y[2,3] / y[3,4]: 大厅室内地面 + 两侧草坪
for row, y in (("g2", 2), ("g3", 3)):
    b.flat(f"{row}_w", 0, y, 0.0, LAWN)
    b.flat_rect(f"{row}_fa", 1, y, 0.0, FLOOR)
    b.flat_rect(f"{row}_fb", 3, y, 0.0, FLOOR)
    b.flat(f"{row}_fc", 5, y, 0.0, FLOOR)
    b.flat(f"{row}_e", 6, y, 0.0, LAWN)
# 行 y[4,5]: 后草坪 (两端方板留 1 格边给大树)
b.flat("g4_w", 0, 4, 0.0, LAWN)
b.flat("g4_a", 1, 4, 0.0, LAWN)
b.flat_rect("g4_b", 2, 4, 0.0, LAWN)
b.flat_rect("g4_c", 4, 4, 0.0, LAWN)
b.flat("g4_e", 6, 4, 0.0, LAWN)

# =================================================================
# 2. 急诊大厅 [1,6]x[2,4] 一层 (南立面 窗窗门门窗, 大门正对连廊)
# =================================================================
b.add("h_win_0", "window_square", (1.5, 2.0, 0.5), (90, 0, 0), WIN)
b.add("h_win_1", "window_square", (2.5, 2.0, 0.5), (90, 0, 0), WIN)
b.add("h_door_w", "door_frame", (3.5, 2.0, 0.5), (90, 0, 0), DOOR)
b.add("h_door_e", "door_frame", (4.5, 2.0, 0.5), (90, 0, 0), DOOR)
b.add("h_win_2", "window_square", (5.5, 2.0, 0.5), (90, 0, 0), WIN)
for x in range(1, 6):
    b.wall_ns(f"h_n_{x}", x, 4.0, 0, WALL)
for y in (2, 3):
    b.wall_ew(f"h_w_{y}", 1.0, y, 0, WALL)
    b.wall_ew(f"h_e_{y}", 6.0, y, 0, WALL)

# 大厅平顶 z=1: [1,6]x[2,4]
for row, y in (("rf2", 2), ("rf3", 3)):
    b.flat_rect(f"{row}_a", 1, y, 1.0, ROOF)
    b.flat_rect(f"{row}_b", 3, y, 1.0, ROOF)
    b.flat(f"{row}_c", 5, y, 1.0, ROOF)

# 急诊灯箱: 双红方板压双门顶而立, 顶上各一片红等边
b.wall_ns("sign_w", 3, 2.0, 1, SIGN)
b.wall_ns("sign_e", 4, 2.0, 1, SIGN)
b.crest_ns("sign_tw", 3, 2.0, 2.0, SIGN)
b.crest_ns("sign_te", 4, 2.0, 2.0, SIGN)
# 北檐旗杆: 白等腰立在北墙顶
b.spire_ns("flag_n", 3, 4.0, 1.0, FLAG)

# =================================================================
# 3. 风雨连廊 [3,5]x[0,2]: 两节门式框架, 末节骑双门顶
# =================================================================
b.wall_ew("col_w0", 3.0, 0, 0, COL)
b.wall_ew("col_w1", 3.0, 1, 0, COL)
b.wall_ew("col_e0", 5.0, 0, 0, COL)
b.wall_ew("col_e1", 5.0, 1, 0, COL)
b.flat_rect("cnp_s", 3, 0, 1.0, CANOPY)         # 廊顶南节
b.flat_rect("cnp_n", 3, 1, 1.0, CANOPY)         # 廊顶北节 (骑双门顶)

# =================================================================
# 4. 担架车 (廊口西侧): 双轮 + 床板锁成滚动门式框架
# =================================================================
b.add("gur_wh_s", "wheel_base", (2.0, 0.0, 0.5), (90, 0, 0), WHEEL)
b.add("gur_wh_n", "wheel_base", (2.0, 1.0, 0.5), (90, 0, 0), WHEEL)
b.flat_rect("gur_bed", 1, 0, 1.0, BED)

# =================================================================
# 5. 门口大树 x2 (后草坪两端)
# =================================================================
b.wall_ns("tree_w_t", 0, 5.0, 0, TRUNK)
b.crest_ns("tree_w_c", 0, 5.0, 1.0, LEAF)
b.wall_ns("tree_e_t", 6, 5.0, 0, TRUNK)
b.crest_ns("tree_e_c", 6, 5.0, 1.0, LEAF)

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺街面南排: 担架车底板长板居西 (北长边就是车轮缝), 青色连廊"
    "步道两格居中, 黄色救护车位标线长板居东。",
    ["g0_w", "g0_gur", "g0_l0", "g0_l1", "g0_bay"],
    tip="长板 [1,3] 的两条长边将来要接住担架车的双轮, 务必对齐。",
)
b.step(
    "补齐街面北排: 与南排一一对缝, 车轮缝 y=1 全线贯通。",
    ["g1_w", "g1_gur", "g1_l0", "g1_l1", "g1_bay"],
    highlight=["g0_gur"],
    tip="救护车沿黄色标线停靠, 病人下车正对连廊口。",
)
b.step(
    "铺大厅地面两排: 白色室内地板居中, 两侧绿草坪包边。",
    ["g2_w", "g2_fa", "g2_fb", "g2_fc", "g2_e",
     "g3_w", "g3_fa", "g3_fb", "g3_fc", "g3_e"],
    highlight=["g1_l0", "g1_l1"],
    tip="大厅四面墙都立在这两排地板的格线上。",
)
b.step(
    "铺后草坪: 5 片绿板合拢场地, 两端方板留出大树的落脚边。",
    ["g4_w", "g4_a", "g4_b", "g4_c", "g4_e"],
    highlight=["g3_w", "g3_e"],
)
b.step(
    "立大厅南立面: 两扇红色门框方并肩居中 (急诊推拉大门), "
    "两侧三扇青色观察窗。",
    ["h_win_0", "h_win_1", "h_door_w", "h_door_e", "h_win_2"],
    highlight=["g1_l0", "g1_l1"],
    tip="双红门正对连廊道 —— 担架车不拐弯直接进大厅。",
)
b.step(
    "立大厅北墙: 5 片白色方板一字排开。",
    ["h_n_1", "h_n_2", "h_n_3", "h_n_4", "h_n_5"],
    highlight=["g3_fa"],
)
b.step(
    "立东西山墙: 各 2 片, 竖边与南北墙互吸, 大厅箱形围合。",
    ["h_w_2", "h_w_3", "h_e_2", "h_e_3"],
    highlight=["h_win_0", "h_n_5"],
    tip="四角竖边互咬成环 —— 一层白盒无单点失效。",
)
b.step(
    "盖大厅平顶: 4 片长板 + 2 片方板, 短边整边压东西山墙顶。",
    ["rf2_a", "rf2_b", "rf2_c", "rf3_a", "rf3_b", "rf3_c"],
    highlight=["h_w_2", "h_e_2"],
    tip="长板长边压在门顶与窗顶上 —— 荷载沿墙身直落地面。",
)
b.step(
    "立急诊灯箱与旗杆: 双红方板压双门顶而立、红等边压顶, "
    "白色等腰旗杆立上北檐。",
    ["sign_w", "sign_e", "sign_tw", "sign_te", "flag_n"],
    highlight=["h_door_w", "h_door_e"],
    tip="灯箱底边吸门框方顶边, 双箱竖边互吸 —— 全街都认得这里。",
)
b.step(
    "立连廊方柱: 4 根白柱两两相对, 柱脚整边吸青色步道格线。",
    ["col_w0", "col_w1", "col_e0", "col_e1"],
    highlight=["g0_l0", "g1_l1"],
    tip="北柱竖边与大厅南墙竖边 90 度互咬 —— 连廊靠上大厅。",
)
b.step(
    "架连廊廊顶: 两片透明长板短边各压一对柱顶, 北节长边"
    "同时骑上双红门顶。",
    ["cnp_s", "cnp_n"],
    highlight=["col_w0", "h_door_w"],
    tip="每节都是双端受力的门式框架 —— 零悬臂, 雨天不淋。",
)
b.step(
    "拼担架车: 两片车轮底座平行立上地缝, 白色床板双长边"
    "同时压住两排轮顶。",
    ["gur_wh_s", "gur_wh_n", "gur_bed"],
    highlight=["g0_gur", "g1_gur"],
    tip="与救护车底盘同款门式框架 —— 床板东边正好接住廊顶边。",
)
b.step(
    "种门口大树: 橙色树干立上后草坪北沿, 绿色树冠压顶 —— "
    "急诊入口全天候开放!",
    ["tree_w_t", "tree_w_c", "tree_e_t", "tree_e_c"],
    highlight=["g4_w", "g4_e"],
    tip="树干底边整边吸草坪格边, 重心正压铰链零力矩。",
)

b.finalize(
    model_id="er_entrance_01",
    name="急诊入口",
    name_en="ER Entrance 01",
    description=(
        "全库第一条'入院风雨连廊': 与 hospital_01 楼板外挑小雨棚、"
        "toll_station_01 亭子当桥墩、car_wash_01 两墙夹道的封闭隧道都"
        "不同 —— 四根独立方柱两两相对串成开敞门式框架雨廊, 两片透明"
        "廊顶长板短边各压一对柱顶 (双端受力零悬臂), 末节北长边还骑在"
        "急诊大厅的双红门框方顶上, 廊子一头接街边一头接大门; 5x2 一层"
        "白盒大厅南立面双红推拉门加三扇青色观察窗, 屋顶双红灯箱压门"
        "而立、白等腰旗杆北檐高扬; 廊口双轮担架车 (车轮底座 x2 + 床板"
        "双长边压双轮顶的滚动门式框架) 正要推进大厅, 黄色救护车位"
        "标线画在街边 —— 全天候开放, 担架车淋不着一滴雨。"
    ),
    difficulty=3,
    tags=["医院", "城市", "职业体验", "急诊", "街景", "进阶"],
    min_pieces=63,
    min_steps=13,
)
