#!/usr/bin/env python3
"""生成模型 data/models/flag_plaza_01.json (升旗广场)。

校园/学校主题批 4/4: 全库第一座校园升旗广场 —— 与
pyramid_giza_01 (逐层居中收分的实心阶梯) 和各类钟塔/灯塔
(粗塔身大底盘) 刻意区分: 本作的结构签名是"检阅台 + 细高旗杆
环塔" —— 3x1 检阅台箱体居中, 台面正中骑上一座 1x1 截面的
四层旗杆塔 (三节墙环逐层整边共线上叠 + 压顶, 塔顶 4.0), 杆顶
灰色等腰杆尖直上 6.0 全场制高, 红旗等边三角骑压顶东沿迎风;
检阅台东西两侧各一条 30 度无障碍坡道 (顶边'侧墙顶+台面沿'
一线双吸、坡尾落地), 台前广场两座绿篱四坡锥分列左右。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 检阅台朝南):
  - 广场地坪 7x5: 灰色广场砖 + 红毯通道 + 绿茵                24 片
  - 检阅台 (x [2,5], y [3,4], z 0..1): 墙环 x8 + 台面方板 x3  11 片
  - 旗杆塔 (x [3,4], 台面上三节墙环 z 1..4 + 压顶)            13 片
  - 杆尖 (等腰, 顶 6.0) + 红旗 (等边, 骑压顶东沿)              2 片
  - 无障碍坡道 x2 (30 度, 东西对称)                            2 片
  - 绿篱四坡锥 x2 (台前分列左右, 四棱自锁)                     8 片
  合计 60 片, 13 个教程步骤, 4 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 旗杆塔第一节墙环骑在台面上: 南北墙底边'台面方板沿 +
    检阅台墙顶'一线双吸, 东西墙底边吸台面拼缝 —— 结构摞上
    家具 (剪毛台同款), 塔顶 4.0 触发 R8 高层检查, 三节墙环
    + 检阅台箱体全程闭环拓扑天然通过;
  - 每节墙环四角竖边互吸自锁, 上下节整边共线吸合, 全塔受压
    无悬挂链; 杆尖与红旗都骑整边沿口 ('压顶沿 + 墙顶'双共线
    连接), 重心正压铰链线力矩为零;
  - 无障碍坡道顶边同吸台侧墙顶与台面板沿, 坡尾自己落地 ——
    顶铰链 + 接地斜撑两条路径 (过街天桥同款);
  - 绿篱四坡锥底边四边吸脚下方板边, 四条斜棱两两互吸自锁;
  - 地坪拼缝纪律: 墙脚与锥脚处全单位方板, 相邻行等长边互吸。

用法: python3 tools/generate_flag_plaza_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

PLAZA = "gray"       # 广场砖
CARPET = "red"       # 红毯通道
GRASS = "green"      # 绿茵
STAGE = "gray"       # 检阅台墙体
DECK = "red"         # 台面 (红毯)
POLE = "clear"       # 旗杆塔身 (银白)
POLE_CAP = "gray"    # 塔顶压顶
TIP = "gray"         # 杆尖
FLAG = "red"         # 红旗
RAMP = "orange"      # 无障碍坡道
HEDGE = "green"      # 绿篱

# =================================================================
# 1. 广场地坪 7x5 (x [0,7], y [0,5]): 拼缝纪律 —— 墙脚/锥脚处
#    全单位方板, 相邻行至少一对等长边互吸。
# =================================================================
# 南缘 (y [0,1])
b.flat_rect("g_0_w", 0, 0, 0.0, PLAZA)
b.flat_rect("g_0_m", 2, 0, 0.0, PLAZA)
b.flat_rect("g_0_e", 4, 0, 0.0, PLAZA)
b.flat("g_0_6", 6, 0, 0.0, GRASS)
# 绿篱行 (y [1,2]): 锥脚处单位方板
b.flat("g_1_0", 0, 1, 0.0, GRASS)
b.flat("g_1_1", 1, 1, 0.0, GRASS)                  # 西绿篱脚下
b.flat_rect("g_1_m", 2, 1, 0.0, CARPET)            # 红毯通道
b.flat("g_1_4", 4, 1, 0.0, PLAZA)
b.flat("g_1_5", 5, 1, 0.0, GRASS)                  # 东绿篱脚下
b.flat("g_1_6", 6, 1, 0.0, GRASS)
# 台前行 (y [2,3])
b.flat_rect("g_2_w", 0, 2, 0.0, PLAZA)
b.flat_rect("g_2_m", 2, 2, 0.0, CARPET)
b.flat("g_2_4", 4, 2, 0.0, PLAZA)
b.flat_rect("g_2_e", 5, 2, 0.0, PLAZA)
# 检阅台行 (y [3,4]): 台脚处全单位方板
b.flat("g_3_0", 0, 3, 0.0, PLAZA)
b.flat("g_3_1", 1, 3, 0.0, PLAZA)
b.flat("g_3_2", 2, 3, 0.0, STAGE)
b.flat("g_3_3", 3, 3, 0.0, STAGE)
b.flat("g_3_4", 4, 3, 0.0, STAGE)
b.flat_rect("g_3_e", 5, 3, 0.0, PLAZA)
# 北缘 (y [4,5])
b.flat("g_4_0", 0, 4, 0.0, GRASS)
b.flat_rect("g_4_w", 1, 4, 0.0, GRASS)
b.flat_rect("g_4_m", 3, 4, 0.0, GRASS)
b.flat_rect("g_4_e", 5, 4, 0.0, GRASS)

# =================================================================
# 2. 检阅台 (x [2,5], y [3,4], z 0..1): 墙环 + 台面
# =================================================================
for x in (2, 3, 4):
    b.wall_ns(f"st_s_{x}", x, 3.0, 0, STAGE)
for x in (2, 3, 4):
    b.wall_ns(f"st_n_{x}", x, 4.0, 0, STAGE)
b.wall_ew("st_w", 2.0, 3, 0, STAGE)
b.wall_ew("st_e", 5.0, 3, 0, STAGE)
b.flat("st_top_w", 2, 3, 1.0, DECK)
b.flat("st_top_m", 3, 3, 1.0, DECK)
b.flat("st_top_e", 4, 3, 1.0, DECK)

# =================================================================
# 3. 旗杆塔 (x [3,4], y [3,4]): 台面上三节墙环 z 1..4 + 压顶
# =================================================================
for lv, z in (("1", 1), ("2", 2), ("3", 3)):
    b.wall_ns(f"po{lv}_s", 3, 3.0, z, POLE)
    b.wall_ns(f"po{lv}_n", 3, 4.0, z, POLE)
    b.wall_ew(f"po{lv}_w", 3.0, 3, z, POLE)
    b.wall_ew(f"po{lv}_e", 4.0, 3, z, POLE)
b.flat("po_cap", 3, 3, 4.0, POLE_CAP)

# =================================================================
# 4. 杆尖 + 红旗
# =================================================================
b.spire_ns("po_tip", 3, 4.0, 4.0, TIP)             # 顶 6.0 全场制高
b.crest_ew("po_flag", 4.0, 3, 4.0, FLAG)           # 红旗骑压顶东沿

# =================================================================
# 5. 无障碍坡道 x2 + 绿篱四坡锥 x2
# =================================================================
b.ramp("ramp_w", "-x", 2, 3, 1.0, RAMP)            # 西坡道
b.ramp("ramp_e", "+x", 5, 3, 1.0, RAMP)            # 东坡道
b.hat4("hedge_w", 1, 1, 0.0, HEDGE, shape="equilateral_triangle")
b.hat4("hedge_e", 5, 1, 0.0, HEDGE, shape="equilateral_triangle")

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺南缘广场砖: 三片灰色长板 + 东角绿茵。",
    ["g_0_w", "g_0_m", "g_0_e", "g_0_6"],
    tip="周一早晨的广场从南门开始铺 —— 同学们马上列队进场。",
)
b.step(
    "铺绿篱行: 红毯通道居中, 两株绿篱的脚下用单位方板。",
    ["g_1_0", "g_1_1", "g_1_m", "g_1_4", "g_1_5", "g_1_6"],
    highlight=["g_0_m"],
    tip="红毯正对检阅台 —— 升旗手从这条道走向旗杆。",
)
b.step(
    "铺台前行: 红毯继续向北, 两侧广场砖。",
    ["g_2_w", "g_2_m", "g_2_4", "g_2_e"],
    highlight=["g_1_m"],
    tip="红毯 2.0 对 2.0 整边互吸 —— 一条道笔直到台前。",
)
b.step(
    "铺检阅台行与北缘: 台脚三格用单位方板, 北缘绿茵收口。",
    ["g_3_0", "g_3_1", "g_3_2", "g_3_3", "g_3_4", "g_3_e",
     "g_4_0", "g_4_w", "g_4_m", "g_4_e"],
    highlight=["g_2_4"],
    tip="检阅台的八段墙脚全踩在这三格方板的拼缝上。",
)
b.step(
    "砌检阅台墙环: 南北墙各 3 片 + 东西侧墙, 四角竖边互咬。",
    ["st_s_2", "st_s_3", "st_s_4", "st_n_2", "st_n_3", "st_n_4",
     "st_w", "st_e"],
    highlight=["g_3_2", "g_3_4"],
    tip="闭环墙比单面墙稳得多 —— 这座台要托起整根旗杆。",
)
b.step(
    "铺红毯台面: 三片方板压顶, 四边吸墙顶、彼此互吸。",
    ["st_top_w", "st_top_m", "st_top_e"],
    highlight=["st_s_3"],
    tip="台面中间那格就是旗杆塔的落脚点 —— 拼缝一格不能错。",
)
b.step(
    "立旗杆塔第一节: 墙环骑上台面, 南北墙'台面沿+台墙顶'一线双吸。",
    ["po1_s", "po1_n", "po1_w", "po1_e"],
    highlight=["st_top_m"],
    tip="塔摞上台 —— 每片墙都吸着两条共线的铰链保险。",
)
b.step(
    "立第二节墙环: 整边骑第一节墙顶, 四角互咬。",
    ["po2_s", "po2_n", "po2_w", "po2_e"],
    highlight=["po1_s"],
    tip="上下节整边共线吸合 —— 旗杆一节一节往上长。",
)
b.step(
    "立第三节墙环: 塔身到 4.0, R8 高层检查靠闭环天然通过。",
    ["po3_s", "po3_n", "po3_w", "po3_e"],
    highlight=["po2_s"],
    tip="每节都是闭环 —— 全塔受压, 没有一条悬挂链。",
)
b.step(
    "压顶并立杆尖: 灰色压顶四边吸墙顶, 等腰杆尖'压顶北沿+塔北"
    "墙顶'一线双吸直上 6.0 全场制高。",
    ["po_cap", "po_tip"],
    highlight=["po3_n"],
    tip="杆尖重心正压铰链线 —— 力矩为零, 站得笔直。",
)
b.step(
    "升红旗: 等边红旗骑压顶东沿迎风 —— 升旗仪式开始!",
    ["po_flag"],
    highlight=["po_cap"],
    tip="红旗'压顶东沿+塔东墙顶'一线双吸 —— 迎风也不倒。",
)
b.step(
    "架东西无障碍坡道: 30 度坡顶边同吸'侧墙顶+台面沿', 坡尾落地。",
    ["ramp_w", "ramp_e"],
    highlight=["st_w", "st_e"],
    tip="顶铰链 + 接地斜撑两条路径 —— 坐轮椅的同学也能上台。",
)
b.step(
    "种台前绿篱: 两座绿色四坡锥分列红毯左右, 四棱互吸自锁。",
    ["hedge_w_s", "hedge_w_e", "hedge_w_n", "hedge_w_w",
     "hedge_e_s", "hedge_e_e", "hedge_e_n", "hedge_e_w"],
    highlight=["g_1_1", "g_1_5"],
    tip="锥底四边吸脚下方板边 —— 全体肃立, 升旗仪式现在开始!",
)

b.finalize(
    model_id="flag_plaza_01",
    name="升旗广场",
    name_en="Flag Plaza 01",
    description=(
        "只用核心九片型的校园升旗广场, 结构签名是'检阅台 + 细高旗杆"
        "环塔': 3x1 检阅台墙环合环红毯压顶, 台面正中骑上 1x1 截面的"
        "旗杆塔 —— 第一节墙环'台面沿+台墙顶'一线双吸摞上家具, 三节"
        "墙环逐层整边共线上叠到 4.0 (R8 高层检查全程闭环天然通过, "
        "全塔受压无悬挂链), 灰色等腰杆尖直上 6.0 全场制高, 红旗骑"
        "压顶东沿迎风力矩为零; 东西两条 30 度无障碍坡道顶边同吸"
        "'侧墙顶+台面沿'、坡尾落地生根, 红毯通道 2.0 对 2.0 整边"
        "互吸直通台前, 两座绿篱四坡锥分列左右四棱自锁 —— 全体肃立, "
        "升旗仪式现在开始!"
    ),
    difficulty=3,
    tags=["校园", "升旗台", "广场", "仪式", "进阶"],
    min_pieces=60,
    min_steps=13,
)
