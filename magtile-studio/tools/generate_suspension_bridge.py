#!/usr/bin/env python3
"""生成模型 data/models/suspension_bridge_01.json (跨河悬索大桥)。

第二批模型 ①: 土木工程主题 —— 一条 8 格长的车行桥跨过河面,
两座红色主塔各以 4 根直角三角形斜拉撑锁住桥面, 桥两端 30 度
引桥坡道直落河岸, 是模型库第一座"能通车"的桥梁。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 河床与河岸: 河道下铺 8 片青色浅滩, 两侧蓝色河水 + 绿色河岸   24 片
  - 桥墩: 5 座灰色立墙桥墩, 底边吸河床, 顶边接桥面               5 片
  - 桥面: 8 片车道板, 逐格压在桥墩顶边上                          8 片
  - 主塔 x2: 双层红色塔身 + 等腰三角塔尖, 立在桥面正中            6 片
  - 斜拉撑 x8: 直角三角形两直角边分别吸桥面沿边与塔身竖边          8 片
  - 护栏: 桥面两侧红色三角护栏                                    8 片
  - 引桥: 两端 30 度长方形坡道, 坡尾自然落地                      2 片
  合计 61 片, 15 个教程步骤, 6 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 桥面-桥墩-斜拉撑构成多重三角闭环, 剪断任何单条铰链线不塌;
  - 斜拉撑与摩天大楼 (skyscraper_01) 的 T14 斜撑同款: 两条直角边
    都吸牢才是结构件;
  - 引桥坡道顶边整边吸桥面沿口, 坡尾自身接地, 零悬挑。

用法: python3 tools/generate_suspension_bridge.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

# =================================================================
# 1. 河床与河岸: 桥下 8 格浅滩, 两侧河水与河岸
# =================================================================
for x in range(8):                       # 河床浅滩 (桥正下方, y 0..1)
    b.flat(f"bed_{x}", x, 0, 0.0, "cyan")
for x in range(2, 6):                    # 河水南岸段 (y -1..0)
    b.flat(f"wat_s_{x}", x, -1, 0.0, "blue")
for x in range(2, 6):                    # 河水北岸段 (y 1..2)
    b.flat(f"wat_n_{x}", x, 1, 0.0, "blue")
for x in (0, 1, 6, 7):                   # 河岸草地 (南)
    b.flat(f"bank_s_{x}", x, -1, 0.0, "green")
for x in (0, 1, 6, 7):                   # 河岸草地 (北)
    b.flat(f"bank_n_{x}", x, 1, 0.0, "green")

# =================================================================
# 2. 桥墩与桥面
# =================================================================
PIERS = (0, 2, 4, 6, 8)
for x in PIERS:                          # 桥墩: 东西向立墙, 底边吸河床
    b.wall_ew(f"pier_{x}", float(x), 0, 0, "gray")
for x in range(8):                       # 桥面车道板 (z=1)
    b.flat(f"deck_{x}", x, 0, 1.0, "gray" if x % 2 == 0 else "yellow")

# =================================================================
# 3. 主塔 (x=2 与 x=6): 双层红色塔身 + 塔尖
# =================================================================
for tx in (2, 6):
    b.wall_ew(f"tw_{tx}_1", float(tx), 0, 1, "red")   # 塔身下层 z 1..2
    b.wall_ew(f"tw_{tx}_2", float(tx), 0, 2, "red")   # 塔身上层 z 2..3
    b.spire_ew(f"tw_{tx}_top", float(tx), 0, 3.0, "red")  # 等腰三角塔尖

# =================================================================
# 4. 斜拉撑: 每座主塔 4 根 (桥面南北沿 x 塔两侧), 直角三角形
#    竖直边吸塔身竖边, 水平边吸桥面沿边 —— 三角刚性节点
# =================================================================
for tx in (2, 6):
    b.brace(f"stay_{tx}_sw", (float(tx), 0.0, 1.0), "-x", "orange")
    b.brace(f"stay_{tx}_se", (float(tx), 0.0, 1.0), "+x", "orange")
    b.brace(f"stay_{tx}_nw", (float(tx), 1.0, 1.0), "-x", "orange")
    b.brace(f"stay_{tx}_ne", (float(tx), 1.0, 1.0), "+x", "orange")

# =================================================================
# 5. 护栏: 桥面两侧等边三角护栏 (跨中与两端)
# =================================================================
for x in (0, 3, 4, 7):
    b.crest_ns(f"rail_s_{x}", x, 0.0, 1.0, "red")
for x in (0, 3, 4, 7):
    b.crest_ns(f"rail_n_{x}", x, 1.0, 1.0, "red")

# =================================================================
# 6. 引桥坡道: 两端 30 度长方形坡道, 坡尾自然落地
# =================================================================
b.ramp("ramp_w", "-x", 0.0, 0, 1.0, "orange")
b.ramp("ramp_e", "+x", 8.0, 0, 1.0, "orange")

# =================================================================
# 教程步骤 (15 步)
# =================================================================
b.step(
    "铺设河床西半段: 沿直线平放 4 片青色浅滩正方形, 相邻边互相吸合。",
    [f"bed_{x}" for x in range(4)],
    tip="这条 8 格长的浅滩就是大桥的中轴线, 请沿桌面摆直。",
)
b.step(
    "铺设河床东半段: 再接 4 片青色浅滩, 连成完整河道。",
    [f"bed_{x}" for x in range(4, 8)],
    highlight=["bed_3"],
    tip="8 片浅滩必须严丝合缝 —— 桥墩全都要立在它们的接缝上。",
)
b.step(
    "铺设河水: 浅滩中段两侧各平放 4 片蓝色正方形, 河面在桥下展开。",
    [f"wat_s_{x}" for x in range(2, 6)] + [f"wat_n_{x}" for x in range(2, 6)],
    highlight=["bed_3", "bed_4"],
    tip="河水只铺中段 —— 两端留给河岸, 大桥正好跨过最宽的河面。",
)
b.step(
    "铺设河岸: 河道两端两侧共 8 片绿色草地, 场地完工。",
    [f"bank_s_{x}" for x in (0, 1, 6, 7)] + [f"bank_n_{x}" for x in (0, 1, 6, 7)],
    highlight=["wat_s_2", "wat_n_5"],
    tip="从上往下看: 绿岸-蓝河-绿岸, 大桥将从东岸跨到西岸。",
)
b.step(
    "竖立 5 座桥墩: 灰色正方形逐一立在河床接缝上 (x = 0/2/4/6/8), "
    "底边与河床边缘吸合。",
    [f"pier_{x}" for x in PIERS],
    highlight=["bed_0", "bed_7"],
    tip="桥墩间距均为 2 格; 立好后从侧面看应像 5 根等距的琴柱。",
)
b.step(
    "铺设桥面西半段: 4 片车道板从西端桥墩开始逐格向东, 每片都压住桥墩顶边"
    "或吸住相邻车道板。",
    [f"deck_{x}" for x in range(4)],
    highlight=["pier_0", "pier_2", "pier_4"],
    tip="第一片车道板的西边要与西端桥墩顶边完全对齐吸合。",
)
b.step(
    "铺设桥面东半段: 再接 4 片车道板, 桥面贯通两岸。",
    [f"deck_{x}" for x in range(4, 8)],
    highlight=["deck_3", "pier_6", "pier_8"],
    tip="铺完轻按整条桥面: 应稳稳压在 5 座桥墩上, 不翘不晃。",
)
b.step(
    "竖立西主塔: 在 x=2 桥墩正上方叠 2 层红色塔身, 塔顶装等腰三角塔尖。",
    ["tw_2_1", "tw_2_2", "tw_2_top"],
    highlight=["deck_1", "deck_2"],
    tip="塔身底边吸桥面接缝, 与水下桥墩正好上下对齐成一根通柱。",
)
b.step(
    "安装西塔斜拉撑: 4 根橙色直角三角形分别立在塔身东西两侧的桥面南北沿上, "
    "竖直边吸塔身竖边、水平边吸桥面沿边。",
    ["stay_2_sw", "stay_2_se", "stay_2_nw", "stay_2_ne"],
    highlight=["tw_2_1"],
    tip="两条直角边都要吸牢 —— 这是把主塔锁在桥面上的三角刚性节点。",
)
b.step(
    "竖立东主塔: 在 x=6 桥墩正上方同样叠 2 层塔身并装塔尖, 与西塔对称。",
    ["tw_6_1", "tw_6_2", "tw_6_top"],
    highlight=["deck_5", "deck_6"],
    tip="对照西塔检查高度与位置, 两塔应完全镜像。",
)
b.step(
    "安装东塔斜拉撑: 4 根直角三角形, 做法与西塔完全相同。",
    ["stay_6_sw", "stay_6_se", "stay_6_nw", "stay_6_ne"],
    highlight=["tw_6_1"],
    tip="八根斜拉撑装完, 轻摇任何一座主塔都应带动整桥联动。",
)
b.step(
    "安装南侧护栏: 4 片红色三角护栏立在桥面南沿 (两端与跨中)。",
    [f"rail_s_{x}" for x in (0, 3, 4, 7)],
    highlight=["deck_3", "deck_4"],
    tip="护栏底边吸桥面沿口即可站稳, 跨中两片正好在两塔之间。",
)
b.step(
    "安装北侧护栏: 4 片三角护栏与南侧镜像。",
    [f"rail_n_{x}" for x in (0, 3, 4, 7)],
    highlight=["rail_s_3"],
    tip="从桥头望去, 两排护栏应整齐对称。",
)
b.step(
    "安装西引桥: 30 度长方形坡道顶边整边吸在桥面西端沿口, 坡尾自然落在西岸。",
    ["ramp_w"],
    highlight=["deck_0", "pier_0"],
    tip="坡道顶边要与桥面边完全贴合; 坡尾落地后不需要任何支撑。",
)
b.step(
    "安装东引桥: 与西引桥镜像, 悬索大桥全线通车!",
    ["ramp_e"],
    highlight=["deck_7", "pier_8"],
    tip="用一颗弹珠从引桥顶轻轻放下, 它会沿桥面滚过整条大桥。",
)

b.finalize(
    model_id="suspension_bridge_01",
    name="跨河悬索大桥",
    name_en="Suspension Bridge 01",
    description=(
        "土木工程第一课: 8 格长的车行桥跨过蓝色河面, 5 座桥墩托起桥面, 两座红色"
        "主塔各以 4 根直角三角形斜拉撑与桥面锁成三角刚性节点, 两端 30 度引桥坡道"
        "直落河岸 —— 搭完从引桥放一颗弹珠, 它会滚过整条大桥。"
    ),
    difficulty=3,
    tags=["桥梁", "工程", "河流", "进阶"],
    min_pieces=55,
    min_steps=15,
)
