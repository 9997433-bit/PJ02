#!/usr/bin/env python3
"""生成模型 data/models/fire_truck_01.json (消防车).

城市街景载具主题: 全库第一辆带升降云梯的救援车 —— 平头消防车
冲到火场: 两对车轮底座托起 4x2 底盘, 后段器材舱 (窗格方卷帘
器材柜) 与前段平头驾驶舱错列, 舱顶红色警灯; 器材舱顶一条黄色
云梯长板沿屋脊铰链升起 60 度, 直指东侧起火的小屋 —— 屋顶
三簇橙红火苗窜动, 街角消防栓待命。呜哇呜哇, 让一让!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 车头朝东):
  - 街道三排 + 人行道                                     24 片
  - 车轮底座 x4 + 底盘长板 x4                              8 片
  - 器材舱: 首尾方墙 x4 + 窗格方器材柜 x4                  8 片
  - 器材舱顶纵向长板 x2                                    2 片
  - 驾驶舱: 方墙 x4 + 挡风玻璃 x2 + 舱顶长板 x2 + 警灯     9 片
  - 云梯长板 (60 度升起, 铰在舱顶 x=3 整条长边上)          1 片
  - 起火小屋: 门框方+窗格方+方墙 x6 + 屋面 x4             10 片
  - 火苗三角 x3 + 消防栓 + 路灯                            5 片
  合计 69 片, 16 个教程步骤, 8 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验, 常规+strict 双档):
  - 云梯绕舱顶 x=3 长边铰链升起 60 度 (与水平面夹角):
    质量 60g x 水平力臂 0.5 = 弯矩 30 < 双倍长度铰链预算
    35 (strict 档) —— 再抬高一点就会超, 60 度正是实物
    云梯的稳定仰角;
  - 器材舱首尾方墙底边整边吸底盘长板短边, 舱顶纵向长板
    短边整边压器材柜顶 —— 轮组+墙身+舱顶锁成箱形环;
  - 火苗三角立在小屋屋面拼缝上, 重心正压铰链线。

用法: python3 tools/generate_fire_truck.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

ROAD = "gray"
WALK = "orange"
WHEEL = "gray"
CHASSIS = "gray"
BODY = "red"        # 消防红
LOCKER = "clear"    # 器材柜卷帘
GLASS = "clear"
LADDER = "yellow"
HOUSE = "clear"
FIRE_A = "orange"
FIRE_B = "red"

# =================================================================
# 1. 街道 [0,8]x[0,3] + 人行道 [0,8]x[3,4]
# =================================================================
for row, y in (("r0", 0), ("r1", 1), ("r2", 2), ("wk", 3)):
    color = WALK if row == "wk" else ROAD
    b.flat(f"{row}_a", 0, y, 0.0, color)
    b.flat_rect(f"{row}_b", 1, y, 0.0, color)
    b.flat_rect(f"{row}_c", 3, y, 0.0, color)
    b.flat(f"{row}_d", 5, y, 0.0, color)
    b.flat(f"{row}_e", 6, y, 0.0, color)
    b.flat(f"{row}_f", 7, y, 0.0, color)

# =================================================================
# 2. 车轮底座 x4 + 底盘 z=1 (4x2 长板)
# =================================================================
b.add("wb_ws", "wheel_base", (2.0, 1.0, 0.5), (90, 0, 0), WHEEL)
b.add("wb_wn", "wheel_base", (2.0, 3.0, 0.5), (90, 0, 0), WHEEL)
b.add("wb_es", "wheel_base", (4.0, 1.0, 0.5), (90, 0, 0), WHEEL)
b.add("wb_en", "wheel_base", (4.0, 3.0, 0.5), (90, 0, 0), WHEEL)
b.flat_rect("ch_ws", 1, 1, 1.0, CHASSIS)
b.flat_rect("ch_wn", 1, 2, 1.0, CHASSIS)
b.flat_rect("ch_es", 3, 1, 1.0, CHASSIS)
b.flat_rect("ch_en", 3, 2, 1.0, CHASSIS)

# =================================================================
# 3. 器材舱 [1,3]x[1,3] (z1..2): 首尾方墙 + 窗格方器材柜
# =================================================================
b.wall_ew("bd_w0", 1.0, 1, 1, BODY)                # 车尾墙
b.wall_ew("bd_w1", 1.0, 2, 1, BODY)
b.wall_ew("bd_p0", 3.0, 1, 1, BODY)                # 舱/驾驶舱隔墙
b.wall_ew("bd_p1", 3.0, 2, 1, BODY)
b.add("bd_s1", "window_square", (1.5, 1.0, 1.5), (90, 0, 0), LOCKER)
b.add("bd_s2", "window_square", (2.5, 1.0, 1.5), (90, 0, 0), LOCKER)
b.add("bd_n1", "window_square", (1.5, 3.0, 1.5), (90, 0, 0), LOCKER)
b.add("bd_n2", "window_square", (2.5, 3.0, 1.5), (90, 0, 0), LOCKER)
b.flat_rect("bd_r1", 1, 1, 2.0, BODY, axis="y")    # 舱顶纵向长板
b.flat_rect("bd_r2", 2, 1, 2.0, BODY, axis="y")

# =================================================================
# 4. 驾驶舱 [3,5]x[1,3] (z1..2): 平头 + 挡风 + 舱顶 + 警灯
# =================================================================
b.wall_ns("cb_s3", 3, 1.0, 1, BODY)
b.wall_ns("cb_s4", 4, 1.0, 1, BODY)
b.wall_ns("cb_n3", 3, 3.0, 1, BODY)
b.wall_ns("cb_n4", 4, 3.0, 1, BODY)
b.wall_ew("cb_gs", 5.0, 1, 1, GLASS)               # 平头挡风
b.wall_ew("cb_gn", 5.0, 2, 1, GLASS)
b.flat_rect("cb_r1", 3, 1, 2.0, "clear", axis="y")
b.flat_rect("cb_r2", 4, 1, 2.0, "clear", axis="y")
b.crest_ns("beacon", 3, 1.0, 2.0, BODY)            # 舱顶警灯

# =================================================================
# 5. 云梯: 铰在舱顶 x=3 整条长边, 升起 60 度直指火场
# =================================================================
b.place_edge("ladder", "rectangle", 0,
             (3.0, 1.0, 2.0), (3.0, 3.0, 2.0), (0.5, 0.0, 0.866025),
             LADDER)

# =================================================================
# 6. 起火小屋 [6,8]x[1,3] (z0..1) + 火苗
# =================================================================
b.add("hs_door", "door_frame", (6.5, 1.0, 0.5), (90, 0, 0), HOUSE)
b.add("hs_win", "window_square", (7.5, 1.0, 0.5), (90, 0, 0), HOUSE)
b.wall_ns("hs_n6", 6, 3.0, 0, HOUSE)
b.wall_ns("hs_n7", 7, 3.0, 0, HOUSE)
b.wall_ew("hs_w0", 6.0, 1, 0, HOUSE)
b.wall_ew("hs_w1", 6.0, 2, 0, HOUSE)
b.wall_ew("hs_e0", 8.0, 1, 0, HOUSE)
b.wall_ew("hs_e1", 8.0, 2, 0, HOUSE)
for x0, y0 in ((6, 1), (7, 1), (6, 2), (7, 2)):
    b.flat(f"hs_r{x0}{y0}", x0, y0, 1.0, "gray")
b.crest_ns("fire_a", 6, 2.0, 1.0, FIRE_A)          # 屋面拼缝上的火苗
b.crest_ew("fire_b", 7.0, 1, 1.0, FIRE_B)
b.crest_ns("fire_c", 7, 3.0, 1.0, FIRE_A)

# =================================================================
# 7. 街角消防栓 + 路灯
# =================================================================
b.crest_ns("hydrant", 0, 3.0, 0.0, "red")
b.spire_ns("lamp", 5, 4.0, 0.0, "yellow")

# =================================================================
# 教程步骤 (16 步)
# =================================================================
b.step(
    "南车道: 方板+长板+长板+方板 x3 铺出第一排, 长板拼缝就是"
    "车轮的吸附线。",
    ["r0_a", "r0_b", "r0_c", "r0_d", "r0_e", "r0_f"],
)
b.step(
    "消防通道: 同板序再铺一排 —— 消防车正压着这排冲向火场。",
    ["r1_a", "r1_b", "r1_c", "r1_d", "r1_e", "r1_f"],
    highlight=["r0_b", "r0_c"],
)
b.step(
    "北车道: 第三排合拢。",
    ["r2_a", "r2_b", "r2_c", "r2_d", "r2_e", "r2_f"],
    highlight=["r1_a", "r1_f"],
)
b.step(
    "人行道: 橙色步道砖沿路北铺一排。",
    ["wk_a", "wk_b", "wk_c", "wk_d", "wk_e", "wk_f"],
    highlight=["r2_a", "r2_f"],
)
b.step(
    "四只车轮: 两对车轮底座立在 x=1~3 与 3~5 拼缝上。",
    ["wb_ws", "wb_wn", "wb_es", "wb_en"],
    highlight=["r0_b", "r1_c"],
    tip="底边整边咬住路缝, 轮顶马上托起底盘。",
)
b.step(
    "底盘: 4 片灰色长板长边整边压轮组顶, 4x2 底盘架空。",
    ["ch_ws", "ch_wn", "ch_es", "ch_en"],
    highlight=["wb_ws", "wb_en"],
)
b.step(
    "器材舱骨架: 车尾与隔墙各 2 片红色方墙竖立, 底边整边吸"
    "底盘长板短边。",
    ["bd_w0", "bd_w1", "bd_p0", "bd_p1"],
    highlight=["ch_ws", "ch_es"],
)
b.step(
    "器材柜: 南北各嵌 2 扇窗格方卷帘门 —— 水带、破拆钳都收"
    "在里面, 竖边逐扇与端墙互吸成链。",
    ["bd_s1", "bd_s2", "bd_n1", "bd_n2"],
    highlight=["bd_w0", "bd_p0"],
)
b.step(
    "器材舱顶: 2 条纵向长板盖上 z=2, 短边整边压器材柜顶 —— "
    "轮组+墙身+舱顶锁成箱形环。",
    ["bd_r1", "bd_r2"],
    highlight=["bd_s1", "bd_n2"],
)
b.step(
    "驾驶舱墙身: 南北各 2 片红色方墙立在底盘格缝上。",
    ["cb_s3", "cb_s4", "cb_n3", "cb_n4"],
    highlight=["bd_p0", "ch_es"],
)
b.step(
    "平头挡风: 车头 x=5 两片透明方板竖立 —— 消防车是平头车, "
    "驾驶员视野要贴着火场。",
    ["cb_gs", "cb_gn"],
    highlight=["cb_s4", "cb_n4"],
)
b.step(
    "舱顶与警灯: 2 条白色纵向长板封舱顶, 南沿立红色警灯三角。",
    ["cb_r1", "cb_r2", "beacon"],
    highlight=["cb_s3", "cb_gs"],
)
b.step(
    "升云梯: 黄色云梯长板铰在舱顶 x=3 整条长边上, 升起 60 度"
    "直指火场 —— 弯矩 30 < 预算 35, 这是云梯的极限仰角。",
    ["ladder"],
    highlight=["bd_r2", "cb_r1"],
    tip="云梯长边整边吸住屋脊缝, 再抬高一点就会翻。",
)
b.step(
    "起火小屋: 门框方house门+窗格方窗朝街, 北墙 2 片、东西"
    "山墙各 2 片围合。",
    ["hs_door", "hs_win", "hs_w0", "hs_w1", "hs_e0", "hs_e1",
     "hs_n6", "hs_n7"],
    highlight=["r1_e", "wk_e"],
)
b.step(
    "小屋屋面: 4 片灰色方板盖上 z=1。",
    ["hs_r61", "hs_r71", "hs_r62", "hs_r72"],
    highlight=["hs_door", "hs_n7"],
)
b.step(
    "火情与街角: 屋面拼缝上立 3 簇橙红火苗, 街角红色消防栓"
    "与黄色路灯就位 —— 呜哇呜哇, 出水!",
    ["fire_a", "fire_b", "fire_c", "hydrant", "lamp"],
    highlight=["hs_r61", "wk_a"],
    tip="火苗三角重心正压屋面拼缝 —— 云梯正对着它们。",
)

b.finalize(
    model_id="fire_truck_01",
    name="消防车",
    name_en="Fire Truck 01",
    description=(
        "全库第一辆带升降云梯的救援车: 平头消防车两对车轮底座托起 "
        "4x2 底盘, 器材舱首尾方墙与舱顶纵向长板锁成箱形环, 南北"
        "四扇窗格方器材柜卷帘; 黄色云梯长板绕舱顶整条长边铰链升起 "
        "60 度 (弯矩 30 < 35, 实打实的极限仰角), 直指东侧起火小屋 "
        "—— 屋面拼缝上三簇橙红火苗窜动, 门框方房门待救, 街角消防栓"
        "待命。呜哇呜哇, 让一让!"
    ),
    difficulty=3,
    tags=["消防车", "城市", "载具", "救援", "车轮底座"],
    min_pieces=60,
    min_steps=16,
)
