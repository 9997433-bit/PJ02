#!/usr/bin/env python3
"""生成模型 data/models/sydney_opera_01.json (悉尼歌剧院造型)。

第三批模型: 世界地标主题 —— 全库第一个"帆壳建筑": 海湾畔的
高台上, 三组白帆逐级降低: 两组大帆由梯形对倾合脊自锁 (下底吸
高台长边, 上底在脊线互吸), 两组小帆由等腰/等边三角对尖收拢;
前庭再斜倚两对遮阳帆, 大台阶用 30 度坡道铺成 —— 从海面望去,
一串风帆正待起航。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 前庭花岗岩广场 [0,8]x[0,1] + 大台阶坡道 2                    10 片
  - 高台墙身 (南北方墙各 6 + 东西方墙各 2)                       16 片
  - 高台台面: 前排 6 方 + 后排 2 长方形 + 2 方                   10 片
  - 大帆 x2 (梯形对倾合脊自锁, 每组 2 片)                         4 片
  - 小帆 x2 (等腰对尖 + 等边对尖, 每组 2 片)                      4 片
  - 前庭遮阳帆 x2 组 (等腰对尖)                                   4 片
  - 海湾水面 6 + 旗杆 1 + 广场灯柱 2                              9 片
  合计 57 片, 16 个教程步骤, 5 种磁力片形状。

物理要点 (通过 R1~R8 全部校验):
  - 梯形大帆: 下底 (长 2) 整边吸台面长方形长边, 两片对倾 60 度,
    上底 (长 1) 在脊线 z=1.707 处互吸自锁 —— 与五重塔屋面同款;
  - 三角小帆对尖不互吸, 各自只靠下底吸台面, 但重心水平偏距仅
    0.17, 弯矩 2.5 g·单位, 远低于 20 的预算;
  - 台面前排方板吸南墙顶, 后排长方形短边吸东西墙顶 —— 剪断任一
    条铰链线, 台面仍经由另一侧墙体传力。

坐标约定与 C++ 端一致: 旋转为欧拉角 (度), R = Rz * Ry * Rx。
用法: python3 tools/generate_sydney_opera.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

mb = ModelBuilder()

PLAZA = "pink"      # 前庭花岗岩
WALL = "orange"     # 高台墙身 (砂岩)
DECK = "yellow"     # 高台台面
SAIL = "clear"      # 白帆 (透明白)
SEA = "blue"

# =================================================================
# 1. 前庭广场 [0,8]x[0,1] + 大台阶坡道 (通往高台南沿)
# =================================================================
for i in range(8):
    mb.flat(f"pl_{i}", i, 0, 0.0, PLAZA)
mb.ramp("stair_w", "-y", 1.0, 3, 1.0, PLAZA)       # 大台阶西半
mb.ramp("stair_e", "-y", 1.0, 4, 1.0, PLAZA)       # 大台阶东半

# =================================================================
# 2. 高台墙身: 南北各 6 方墙, 东西各 2 方墙 (围合 [1,7]x[1,3])
# =================================================================
for i in range(6):
    mb.wall_ns(f"pw_s{i}", 1 + i, 1.0, 0, WALL)
for i in range(6):
    mb.wall_ns(f"pw_n{i}", 1 + i, 3.0, 0, WALL)
mb.wall_ew("pw_w0", 1.0, 1, 0, WALL)
mb.wall_ew("pw_w1", 1.0, 2, 0, WALL)
mb.wall_ew("pw_e0", 7.0, 1, 0, WALL)
mb.wall_ew("pw_e1", 7.0, 2, 0, WALL)

# =================================================================
# 3. 高台台面 z=1: 前排 6 方 (吸南墙顶), 后排 2 长方形 + 2 方
# =================================================================
for i in range(6):
    mb.flat(f"dk_f{i}", 1 + i, 1, 1.0, DECK)
mb.flat_rect("dk_b0", 1, 2, 1.0, DECK)             # [1,3]x[2,3]
mb.flat_rect("dk_b1", 3, 2, 1.0, DECK)             # [3,5]x[2,3]
mb.flat("dk_b2", 5, 2, 1.0, DECK)                  # [5,6]x[2,3]
mb.flat("dk_b3", 6, 2, 1.0, DECK)                  # [6,7]x[2,3]

# =================================================================
# 4. 大帆: 梯形对倾合脊 (脊线 z=1.707), 落在后排长方形上
# =================================================================
for tag, x0 in (("a", 1), ("b", 3)):
    mb.place_edge(f"sail_{tag}_s", "trapezoid", 0,
                  (x0 + 0.0, 2.0, 1.0), (x0 + 2.0, 2.0, 1.0),
                  (0.0, 0.5, 0.707107), SAIL)
    mb.place_edge(f"sail_{tag}_n", "trapezoid", 0,
                  (x0 + 2.0, 3.0, 1.0), (x0 + 0.0, 3.0, 1.0),
                  (0.0, -0.5, 0.707107), SAIL)

# =================================================================
# 5. 小帆: 等腰对尖 ([5,6]) 与等边对尖 ([6,7]), 尖顶逐级降低
# =================================================================
mb.place_edge("sail_c_s", "isosceles_triangle", 0,
              (5.0, 2.0, 1.0), (6.0, 2.0, 1.0), (0.0, 0.5, 0.866025), SAIL)
mb.place_edge("sail_c_n", "isosceles_triangle", 0,
              (6.0, 3.0, 1.0), (5.0, 3.0, 1.0), (0.0, -0.5, 0.866025), SAIL)
mb.place_edge("sail_d_s", "equilateral_triangle", 0,
              (6.0, 2.0, 1.0), (7.0, 2.0, 1.0), (0.0, 0.5, 0.707107), SAIL)
mb.place_edge("sail_d_n", "equilateral_triangle", 0,
              (7.0, 3.0, 1.0), (6.0, 3.0, 1.0), (0.0, -0.5, 0.707107), SAIL)

# =================================================================
# 6. 前庭遮阳帆: 台面前排两端各一组等腰对尖
# =================================================================
for tag, x0 in (("w", 1), ("e", 5)):
    mb.place_edge(f"fore_{tag}_s", "isosceles_triangle", 0,
                  (x0 + 0.0, 1.0, 1.0), (x0 + 1.0, 1.0, 1.0),
                  (0.0, 0.5, 0.866025), "cyan")
    mb.place_edge(f"fore_{tag}_n", "isosceles_triangle", 0,
                  (x0 + 1.0, 2.0, 1.0), (x0 + 0.0, 2.0, 1.0),
                  (0.0, -0.5, 0.866025), "cyan")

# =================================================================
# 7. 海湾水面 [1,7]x[3,4] + 旗杆 + 广场灯柱
# =================================================================
for i in range(6):
    mb.flat(f"sea{i}", 1 + i, 3, 0.0, SEA)
mb.spire_ew("flag", 7.0, 2, 1.0, "red")            # 旗杆立台面东缘
mb.spire_ns("lamp_w", 0, 0.0, 0.0, "yellow")
mb.spire_ns("lamp_e", 7, 0.0, 0.0, "yellow")

# =================================================================
# 教程步骤 (16 步)
# =================================================================
mb.step(
    "前庭西半: 铺 4 片粉色花岗岩广场板, 相邻边互吸。",
    ["pl_0", "pl_1", "pl_2", "pl_3"],
    tip="高台立在广场北侧 —— 这排板是全场的基准线。",
)
mb.step(
    "前庭东半: 再铺 4 片, 8 格前庭广场贯通。",
    ["pl_4", "pl_5", "pl_6", "pl_7"],
    highlight=["pl_3"],
)
mb.step(
    "高台南墙: 沿广场北沿立 6 片橙色砂岩方墙, 墙底吸广场板边。",
    [f"pw_s{i}" for i in range(6)],
    highlight=["pl_1", "pl_6"],
)
mb.step(
    "东西侧墙: 从南墙两端拐角向北各立 2 片方墙, 拐角竖边互吸。",
    ["pw_w0", "pw_w1", "pw_e0", "pw_e1"],
    highlight=["pw_s0", "pw_s5"],
    tip="先立贴着南墙的那片再向北接 —— 每片放下时都有竖边可吸。",
)
mb.step(
    "高台北墙: 从西北角向东立 6 片方墙, 首尾吸住东西侧墙, "
    "四面围合。",
    [f"pw_n{i}" for i in range(6)],
    highlight=["pw_w1", "pw_e1"],
    tip="墙圈闭合后台面才有四面支点。",
)
mb.step(
    "大台阶: 2 片粉色长板以 30 度斜倚南墙, 顶边吸南墙顶 —— "
    "歌剧院标志性的纪念台阶。",
    ["stair_w", "stair_e"],
    highlight=["pw_s2", "pw_s3"],
    tip="坡尾自然落地, 顶边与台面同高。",
)
mb.step(
    "台面前排: 6 片黄色方板铺上高台 (z=1), 南边逐一吸住南墙顶。",
    [f"dk_f{i}" for i in range(6)],
    highlight=["pw_s0", "pw_s5"],
)
mb.step(
    "台面后排: 2 片长方形板短边吸东西墙顶与彼此, 东端再补 2 片"
    "方板吸北墙顶 —— 台面合拢。",
    ["dk_b0", "dk_b1", "dk_b2", "dk_b3"],
    highlight=["pw_w1", "pw_e1", "dk_f5"],
    tip="长方形长边留给大帆的下底 —— 长短边分工是本模型的关键。",
)
mb.step(
    "第一组大帆: 2 片透明梯形帆下底吸西侧长方形板的南北长边, "
    "对倾 60 度, 上底在脊线互吸自锁。",
    ["sail_a_s", "sail_a_n"],
    highlight=["dk_b0"],
    tip="先立南帆吸住板边, 北帆随后对脊压合, 听到'嗒'即自锁。",
)
mb.step(
    "第二组大帆: 同法在东侧长方形板上再合拢一组, 双帆并肩。",
    ["sail_b_s", "sail_b_n"],
    highlight=["sail_a_s", "dk_b1"],
)
mb.step(
    "第三组帆 (等腰): 2 片等腰三角帆对倾对尖, 尖顶在 z=1.866 "
    "轻轻相触 —— 各自只靠下底吸台面。",
    ["sail_c_s", "sail_c_n"],
    highlight=["dk_b2"],
    tip="重心几乎压在下底正上方, 单边吸合足够稳。",
)
mb.step(
    "第四组帆 (等边): 最东端 2 片等边三角帆对尖, 帆列逐级降低 "
    "—— 1.707, 1.866, 1.707 的天际线成形。",
    ["sail_d_s", "sail_d_n"],
    highlight=["sail_c_s", "dk_b3"],
)
mb.step(
    "前庭遮阳帆: 台面前排两端各斜倚 2 片青色等腰帆, 与主帆群"
    "呼应成小品。",
    ["fore_w_s", "fore_w_n", "fore_e_s", "fore_e_n"],
    highlight=["dk_f0", "dk_f4"],
)
mb.step(
    "海湾水面: 高台北侧铺 6 片蓝色水面, 南边吸北墙底。",
    [f"sea{i}" for i in range(6)],
    highlight=["pw_n0", "pw_n5"],
)
mb.step(
    "旗杆: 台面东缘立 1 根红色旗杆 (等腰塔尖)。",
    ["flag"],
    highlight=["dk_b3"],
)
mb.step(
    "广场灯柱: 前庭两端各立 1 根黄色灯柱 —— 帆影入海, 华灯初上。",
    ["lamp_w", "lamp_e"],
    highlight=["pl_0", "pl_7"],
)

mb.finalize(
    model_id="sydney_opera_01",
    name="悉尼歌剧院造型",
    name_en="Sydney Opera House 01",
    description=(
        "海湾畔的帆壳地标: 砂岩高台四面围合, 纪念大台阶以 30 度"
        "坡道斜倚南墙; 台面上三组白帆逐级降低 —— 两组梯形大帆对倾"
        "合脊自锁 (下底整边吸长方形台面板, 上底在脊线互吸), 等腰与"
        "等边小帆对尖收拢; 前庭再斜倚两组青色遮阳帆。长边给大帆、"
        "短边给墙顶的长短分工, 让整片帆群剪断任一条铰链线都不散架。"
    ),
    difficulty=3,
    tags=["歌剧院", "世界地标", "帆壳", "对倾合脊", "海湾"],
    min_pieces=55,
    min_steps=16,
)
