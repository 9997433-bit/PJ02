#!/usr/bin/env python3
"""生成模型 data/models/combine_harvester_01.json (联合收割机)。

农场/农业主题批 3/4: 全库第一台联合收割机, 也是全库第一个
"双车联动"场景 —— 与 tractor_01 (单车 + 车尾犁刀, 大轮在后)
刻意区分: 收割机大轮在前小轮在后, 车头不是犁而是一整幅比车身
还宽的割台 (4 格宽箱形割台自己落地生根, 三片直角割刀"地边 +
割台竖棱"双吸如锯齿入麦); 车身是敞口粮仓 (圈层 + 黄色粮面
压顶 + 粮尖骑沿), 透明驾驶室横跨前桥; 招牌是那条卸粮桥 ——
一片方板从粮仓北沿平伸到并行运粮车的南沿 (两短边各吸一箱,
双端受力零悬挑), 边收边卸, 两台车被一条桥锁成一个大环;
运粮车下环两片车轮底座当轮, 上环加高, 黄粮压顶冒尖 ——
东面麦浪未割, 西面麦茬满地, 丰收进行时!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 车头朝东):
  - 麦田 7x6 (x [1,8], y [0,6]): 茬地/车道/麦墙分色           25 片
  - 轮组: 车轮底座大前轮 x2 + 方板小后轮 x2                    4 片
  - 底盘 (z=1): 方板 x4 + 长板 x2 压轮成桥                     6 片
  - 粮仓圈层 (z 1..2): 长楣 x3 + 方墙 x2                       5 片
  - 粮面: 黄色长板 x2 压顶 + 粮尖等边 x1 骑沿                  3 片
  - 驾驶室: 窗格方 x2 + 透明长楣 + 车顶长板 + 排气等腰          5 片
  - 割台: 长楣 x4 + 侧墙 x2 + 顶板长板 x2 + 直角割刀 x3        11 片
  - 卸粮桥: 方板 x1 (粮仓北沿 -> 运粮车南沿, 双端受力)          1 片
  - 运粮车: 下环 (长楣 x2 + 车轮底座 x2) + 上环 x5 + 粮顶 x2   11 片
  - 麦浪: 等边三角 x3 骑麦墙前缘拼缝                           3 片
  合计 74 片, 14 个教程步骤, 7 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 卸粮桥双端受力: 南短边吸粮仓北墙顶、北短边吸运粮车南墙顶,
    剪断任一端另一端仍托着它 (farm_silo 天桥同款, 但首次跨在
    两台车之间);
  - 割台是独立接地的箱形环 (墙 z 0..1 + 顶板双端压墙顶),
    不吃车身一克悬挑; 割刀直角边"田板格边 + 割台竖棱"双吸;
  - 底盘压轮成桥, 粮仓南楣底边"底盘长边 + 前轮顶边"一线双吸;
  - 排气管/粮尖/麦浪骑沿骑缝, 重心正压铰链线力矩为零。

用法: python3 tools/generate_combine_harvester_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

STUBBLE = "orange"   # 割过的麦茬
LANE = "gray"        # 车底作业道
WHEAT = "yellow"     # 未割的麦
BODY = "red"         # 收割机车身
WHEEL = "gray"       # 轮组
GLASS = "clear"      # 驾驶室玻璃
GRAIN = "yellow"     # 粮
CART = "green"       # 运粮车车厢
STEEL = "gray"       # 割台顶/割刀/卸粮桥

# =================================================================
# 1. 麦田 7x6 (x [1,8], y [0,6]): 东两列是未割的麦, 中部车道,
#    西部麦茬。拼缝纪律: 轮线/墙线处必须有等长田板边。
# =================================================================
# 西列 x [1,2]: 小后轮的地基缝在 y=1 与 y=3
b.flat("fd_1_0", 1, 0, 0.0, STUBBLE)
b.flat_rect("fd_1_12", 1, 1, 0.0, LANE, axis="y")      # [1,2]x[1,3]
b.flat("fd_1_3", 1, 3, 0.0, STUBBLE)
b.flat_rect("fd_1_45", 1, 4, 0.0, STUBBLE, axis="y")   # [1,2]x[4,6] 运粮车道
# 中列 x [2,4]: 大前轮 (y=1/y=3) 与运粮车 (y=4/y=6) 的地基缝
b.flat_rect("fd_2_0", 2, 0, 0.0, STUBBLE)
b.flat_rect("fd_2_1", 2, 1, 0.0, LANE)
b.flat_rect("fd_2_2", 2, 2, 0.0, LANE)
b.flat_rect("fd_2_3", 2, 3, 0.0, STUBBLE)
b.flat_rect("fd_2_4", 2, 4, 0.0, LANE)                 # 运粮车车底
b.flat_rect("fd_2_5", 2, 5, 0.0, LANE)
# 前桥列 x [4,5] 与割台列 x [5,6]: 长板竖铺, 长边就是墙线
b.flat_rect("fd_4_02", 4, 0, 0.0, LANE, axis="y")      # [4,5]x[0,2]
b.flat_rect("fd_4_24", 4, 2, 0.0, LANE, axis="y")
b.flat_rect("fd_4_46", 4, 4, 0.0, WHEAT, axis="y")     # 北侧未割
b.flat_rect("fd_5_02", 5, 0, 0.0, LANE, axis="y")      # 割台脚下
b.flat_rect("fd_5_24", 5, 2, 0.0, LANE, axis="y")
b.flat_rect("fd_5_46", 5, 4, 0.0, WHEAT, axis="y")
# 麦墙列 x [6,7]: 方板咬缝 (割刀与麦浪要吸它的单位边)
for y in range(6):
    b.flat(f"fd_6_{y}", 6, y, 0.0, WHEAT)
# 东缘 x [7,8]: 未割麦海
b.flat_rect("fd_7_02", 7, 0, 0.0, WHEAT, axis="y")
b.flat_rect("fd_7_24", 7, 2, 0.0, WHEAT, axis="y")
b.flat_rect("fd_7_46", 7, 4, 0.0, WHEAT, axis="y")

# =================================================================
# 2. 轮组: 大前轮 (车轮底座, x [2,4]) + 小后轮 (方板, x [1,2])
# =================================================================
b.add("wh_fs", "wheel_base", (3.0, 1.0, 0.5), (90, 0, 0), WHEEL)   # 南前轮
b.add("wh_fn", "wheel_base", (3.0, 3.0, 0.5), (90, 0, 0), WHEEL)   # 北前轮
b.wall_ns("wh_rs", 1, 1.0, 0, WHEEL)                   # 南后轮
b.wall_ns("wh_rn", 1, 3.0, 0, WHEEL)                   # 北后轮

# =================================================================
# 3. 底盘 (z=1): 长板压前轮成桥, 方板接后轮与前桥
# =================================================================
b.flat("ch_rs", 1, 1, 1.0, BODY)                       # 后段南
b.flat("ch_rn", 1, 2, 1.0, BODY)                       # 后段北
b.flat_rect("ch_ms", 2, 1, 1.0, BODY)                  # 中段南 (压南前轮)
b.flat_rect("ch_mn", 2, 2, 1.0, BODY)                  # 中段北 (压北前轮)
b.flat("ch_fs", 4, 1, 1.0, BODY)                       # 前桥南
b.flat("ch_fn", 4, 2, 1.0, BODY)                       # 前桥北

# =================================================================
# 4. 粮仓圈层 (x [2,4], z 1..2): 南楣一线双吸, 北面两片方墙
#    (卸粮桥与粮尖要吸它们的单位顶边)
# =================================================================
b.lintel_ns("tk_s", 2, 1.0, 1, BODY)
b.lintel_ew("tk_w", 2.0, 1, 1, BODY)
b.lintel_ew("tk_e", 4.0, 1, 1, BODY)
b.wall_ns("tk_n_w", 2, 3.0, 1, BODY)
b.wall_ns("tk_n_e", 3, 3.0, 1, BODY)

# 粮面压顶 + 粮尖骑北沿
b.flat_rect("gr_s", 2, 1, 2.0, GRAIN)
b.flat_rect("gr_n", 2, 2, 2.0, GRAIN)
b.crest_ns("gr_peak", 2, 3.0, 2.0, GRAIN)

# =================================================================
# 5. 驾驶室 (x [4,5], z 1..2): 窗格方 x2 + 前窗长楣 + 车顶 + 排气
# =================================================================
b.add("cab_s", "window_square", (4.5, 1.0, 1.5), (90, 0, 0), GLASS)
b.add("cab_n", "window_square", (4.5, 3.0, 1.5), (90, 0, 0), GLASS)
b.lintel_ew("cab_e", 5.0, 1, 1, GLASS)                 # 前风挡
b.flat_rect("cab_roof", 4, 1, 2.0, BODY, axis="y")     # 车顶 (西吸粮仓楣顶)
b.spire_ns("exhaust", 4, 1.0, 2.0, WHEEL)              # 排气管 (顶 4.0)

# =================================================================
# 6. 割台 (x [5,7], y [0,4], z 0..1): 比车身宽的箱形环,
#    自己落地生根 + 三片直角割刀
# =================================================================
b.lintel_ew("hd_b_s", 5.0, 0, 0, BODY)                 # 背墙南半
b.lintel_ew("hd_b_n", 5.0, 2, 0, BODY)                 # 背墙北半
b.lintel_ew("hd_f_s", 6.0, 0, 0, BODY)                 # 前墙南半
b.lintel_ew("hd_f_n", 6.0, 2, 0, BODY)                 # 前墙北半
b.wall_ns("hd_side_s", 5, 0.0, 0, BODY)                # 南侧板
b.wall_ns("hd_side_n", 5, 4.0, 0, BODY)                # 北侧板
b.flat_rect("hd_top_s", 5, 0, 1.0, STEEL, axis="y")    # 台面南半 (双端压墙)
b.flat_rect("hd_top_n", 5, 2, 1.0, STEEL, axis="y")    # 台面北半
b.brace("tooth_s", (6.0, 0.0, 0.0), "+x", STEEL)       # 割刀 x3
b.brace("tooth_m", (6.0, 2.0, 0.0), "+x", STEEL)
b.brace("tooth_n", (6.0, 4.0, 0.0), "+x", STEEL)

# =================================================================
# 7. 运粮车 (x [2,4], y [4,6]): 下环含车轮底座, 上环加高, 黄粮压顶
# =================================================================
b.lintel_ns("ct_s_lo", 2, 4.0, 0, CART)
b.lintel_ns("ct_n_lo", 2, 6.0, 0, CART)
b.add("ct_w_lo", "wheel_base", (2.0, 5.0, 0.5), (90, 0, 90), WHEEL)
b.add("ct_e_lo", "wheel_base", (4.0, 5.0, 0.5), (90, 0, 90), WHEEL)
b.lintel_ew("ct_w_hi", 2.0, 4, 1, CART)
b.lintel_ew("ct_e_hi", 4.0, 4, 1, CART)
b.lintel_ns("ct_n_hi", 2, 6.0, 1, CART)
b.wall_ns("ct_s_hi_w", 2, 4.0, 1, CART)                # 南上墙西半 (卸粮桥吸它)
b.wall_ns("ct_s_hi_e", 3, 4.0, 1, CART)
b.flat_rect("ct_grain_n", 2, 5, 2.0, GRAIN)            # 粮顶北半 (先吸北墙顶)
b.flat_rect("ct_grain_s", 2, 4, 2.0, GRAIN)

# 卸粮桥: 方板从粮仓北沿平伸到运粮车南沿 (双端受力)
b.flat("auger", 3, 3, 2.0, STEEL)

# =================================================================
# 8. 麦浪: 3 片等边三角骑麦墙前缘拼缝 (x=7)
# =================================================================
b.crest_ew("wheat_a", 7.0, 1, 0.0, WHEAT)
b.crest_ew("wheat_b", 7.0, 2, 0.0, WHEAT)
b.crest_ew("wheat_c", 7.0, 4, 0.0, WHEAT)

# =================================================================
# 教程步骤 (14 步)
# =================================================================
b.step(
    "铺西半麦茬地: 橙色是割过的茬, 灰色是收割机与运粮车的车道。",
    ["fd_1_0", "fd_1_12", "fd_1_3", "fd_1_45",
     "fd_2_0", "fd_2_1", "fd_2_2", "fd_2_3", "fd_2_4", "fd_2_5"],
    tip="y=1 与 y=3 两条拼缝就是四只车轮的地基缝 —— 拼缝先行。",
)
b.step(
    "铺中部作业道: 长板竖铺, 长边正好是割台墙的落脚线。",
    ["fd_4_02", "fd_4_24", "fd_4_46", "fd_5_02", "fd_5_24", "fd_5_46"],
    highlight=["fd_2_1", "fd_2_2"],
    tip="x=5 与 x=6 两条长缝一会儿要整边吸住割台的背墙与前墙。",
)
b.step(
    "铺东侧麦墙与麦海: 方板咬缝的一列是正要割的麦。",
    ["fd_6_0", "fd_6_1", "fd_6_2", "fd_6_3", "fd_6_4", "fd_6_5",
     "fd_7_02", "fd_7_24", "fd_7_46"],
    highlight=["fd_5_02", "fd_5_46"],
    tip="东边金黄未割, 西边麦茬满地 —— 收割机就停在分界线上。",
)
b.step(
    "装轮组: 2 片车轮底座当大前轮, 2 片灰色方板当小后轮。",
    ["wh_fs", "wh_fn", "wh_rs", "wh_rn"],
    highlight=["fd_2_1", "fd_1_12"],
    tip="收割机与拖拉机正相反 —— 大轮在前扛割台, 小轮在后管转向。",
)
b.step(
    "架底盘: 2 片长板压前轮成桥, 4 片方板接后轮与前桥。",
    ["ch_rs", "ch_rn", "ch_ms", "ch_mn", "ch_fs", "ch_fn"],
    highlight=["wh_fs", "wh_fn"],
    tip="长板长边整边压轮顶 —— 车架从这里开始受力。",
)
b.step(
    "立粮仓圈层: 南楣'底盘长边+前轮顶边'一线双吸, 北面用两片"
    "方墙 (卸粮桥要吸它的单位顶边)。",
    ["tk_s", "tk_w", "tk_e", "tk_n_w", "tk_n_e"],
    highlight=["ch_ms", "ch_mn"],
    tip="四角竖边互咬合环 —— 这是收割机的大肚子。",
)
b.step(
    "封粮面 + 堆粮尖: 2 片黄长板压顶, 粮尖骑北沿。",
    ["gr_s", "gr_n", "gr_peak"],
    highlight=["tk_s", "tk_n_w"],
    tip="粮面就是仓盖 —— 粮越收越满, 尖都冒出来了。",
)
b.step(
    "立驾驶室 + 竖排气管: 双窗格方跨前桥, 透明前风挡, 车顶西边"
    "吸粮仓楣顶东边吸风挡顶, 排气等腰骑车顶南沿直上 4.0。",
    ["cab_s", "cab_n", "cab_e", "cab_roof", "exhaust"],
    highlight=["ch_fs", "tk_e"],
    tip="车顶两长边双端受力 —— 排气管重心正压铰链零力矩。",
)
b.step(
    "立割台墙: 背墙/前墙各 2 片长楣 + 南北侧板, 4 格宽的箱形环"
    "自己落地生根。",
    ["hd_b_s", "hd_b_n", "hd_f_s", "hd_f_n", "hd_side_s", "hd_side_n"],
    highlight=["fd_5_02", "fd_5_24"],
    tip="割台比车身还宽 —— 但它一克重量都不挂在车上。",
)
b.step(
    "盖割台面 + 装割刀: 2 片顶板双端压墙, 3 片直角割刀"
    "'田板格边+割台竖棱'双吸如锯齿入麦。",
    ["hd_top_s", "hd_top_n", "tooth_s", "tooth_m", "tooth_n"],
    highlight=["hd_b_s", "hd_f_n"],
    tip="斜边就是刀刃 —— 一趟过去撂倒四格宽的麦。",
)
b.step(
    "搭运粮车下环: 2 片车轮底座当轮, 前后长楣合环。",
    ["ct_s_lo", "ct_n_lo", "ct_w_lo", "ct_e_lo"],
    highlight=["fd_2_4", "fd_1_45"],
    tip="运粮车与收割机并排同行 —— 车距一格, 正好架桥。",
)
b.step(
    "加运粮车上环: 西东北三面长楣加高, 南面用两片方墙 (等着"
    "接卸粮桥)。",
    ["ct_w_hi", "ct_e_hi", "ct_n_hi", "ct_s_hi_w", "ct_s_hi_e"],
    highlight=["ct_w_lo", "ct_e_lo"],
    tip="上环底边整边吸下环顶边 —— 圈层砌法的标准加高。",
)
b.step(
    "装粮 + 架卸粮桥: 黄粮压顶, 卸粮桥南短边吸粮仓北墙顶、"
    "北短边吸运粮车南墙顶 —— 双端受力, 边收边卸。",
    ["ct_grain_n", "ct_grain_s", "auger"],
    highlight=["tk_n_e", "ct_s_hi_e"],
    tip="一条桥把两台车锁成一个大环 —— 剪断任一端都塌不了。",
)
b.step(
    "种麦浪: 3 片金黄等边三角骑上麦墙前缘拼缝 —— 开割!",
    ["wheat_a", "wheat_b", "wheat_c"],
    highlight=["tooth_s", "tooth_n"],
    tip="从驾驶室望出去: 麦浪、割刀、粮尖一线排开 —— 丰收进行时!",
)

b.finalize(
    model_id="combine_harvester_01",
    name="联合收割机",
    name_en="Combine Harvester 01",
    description=(
        "只用核心九片型的双车联动收割场景: 收割机大轮在前小轮在后"
        " (与拖拉机正相反), 车头是比车身还宽的 4 格箱形割台 ——"
        " 自己落地生根不吃车身一克悬挑, 三片直角割刀'田板格边+割台"
        "竖棱'双吸如锯齿入麦; 车身是敞口粮仓 (圈层合环 + 黄粮压顶"
        " + 粮尖骑沿), 透明驾驶室横跨前桥, 排气等腰直上 4.0; 招牌"
        "是那条卸粮桥 —— 方板从粮仓北沿平伸到并行运粮车南沿, 两短"
        "边各吸一箱双端受力, 一条桥把两台车锁成一个大环; 运粮车下环"
        "两片车轮底座当轮、上环加高黄粮冒尖 —— 东面麦浪未割, 西面"
        "麦茬满地, 边收边卸, 丰收进行时!"
    ),
    difficulty=3,
    tags=["田园", "农场", "农业", "收割机", "车轮底座", "进阶"],
    min_pieces=74,
    min_steps=14,
)
