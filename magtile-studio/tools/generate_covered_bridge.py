#!/usr/bin/env python3
"""生成模型 data/models/covered_bridge_01.json (风雨廊桥)。

第四批模型 ⑥: 中式木构主题 —— 全库第一座三亭连廊的风雨桥
(程阳桥式样): 两岸桥台与河心桥墩各驮一座梯形四坡亭, 三亭
之间由透明花窗廊道相连; 跨间桥板一整条长方形双端受力搭在
墩台顶上 (零中缝铰链), 花窗墙不靠底边 —— 竖边逐片吸进两端
亭身横楣; 廊顶长板短边压花窗墙顶, 长边整条吸进亭身上环,
行人从亭门穿桥而过, 风雨不侵。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 河面: 6x2 蓝色平铺                                     12 片
  - 桥台墙环 x2 + 桥墩墙环 (z 0..1)                        24 片
  - 亭位楼板: 3 座 x 2 条长方形 (短边接墙顶)                 6 片
  - 跨间桥板: 2 跨 x 2 条长方形 (双端受力)                   4 片
  - 亭身下环: 3 座 x 南北横楣                                6 片
  - 花窗廊墙: 2 跨 x 4 片透明 (竖边受力链)                   8 片
  - 亭身上环: 3 座 x 4 根横楣                               12 片
  - 廊顶长板: 2 跨 x 2 条 (短边压墙顶, 长边吸亭身)           4 片
  - 亭顶: 3 座梯形四坡 + 压顶                               15 片
  - 塔尖红旗: 3 片                                           3 片
  合计 94 片, 18 个教程步骤, 4 种磁力片形状。

几何要点:
  - 跨间桥板一整条长方形横跨 2 格河面, 两条短边分别吸桥台墙顶
    与桥墩墙顶 —— 双端受力, 跨中没有铰链缝;
  - 花窗墙底边不落桥板 (单位边接长边不吸), 全靠竖边逐片吸进
    两端亭身横楣, 形成水平受力链;
  - 亭身上环东西横楣先靠转角竖边挂住南北横楣, 廊顶长板到位后
    长边整条补吸, 三亭与双廊锁成一体。

用法: python3 tools/generate_covered_bridge.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

# =================================================================
# 1. 河面 (z=0): 6x2 蓝色平铺 (x 2..8)
# =================================================================
for x in range(2, 8):
    for y in (0, 1):
        b.flat(f"rv_{x}_{y}", x, y, 0.0, "blue")

# =================================================================
# 2. 桥台/桥墩墙环 (z 0..1): 三座 2x2 空心石墩
# =================================================================
def ring(prefix, x0, color):
    b.wall_ns(f"{prefix}_s0", x0, 0.0, 0, color)
    b.wall_ns(f"{prefix}_s1", x0 + 1, 0.0, 0, color)
    b.wall_ns(f"{prefix}_n0", x0, 2.0, 0, color)
    b.wall_ns(f"{prefix}_n1", x0 + 1, 2.0, 0, color)
    b.wall_ew(f"{prefix}_w0", float(x0), 0, 0, color)
    b.wall_ew(f"{prefix}_w1", float(x0), 1, 0, color)
    b.wall_ew(f"{prefix}_e0", float(x0 + 2), 0, 0, color)
    b.wall_ew(f"{prefix}_e1", float(x0 + 2), 1, 0, color)

ring("abw", 0, "gray")      # 西桥台 x 0..2
ring("pier", 4, "gray")     # 河心桥墩 x 4..6
ring("abe", 8, "gray")      # 东桥台 x 8..10

# =================================================================
# 3. 楼板 (z=1): 亭位长方形 (短边接墙顶) + 跨间桥板 (双端受力)
# =================================================================
for key, x0 in (("w", 0), ("c", 4), ("e", 8)):
    b.flat_rect(f"twf_{key}_0", x0, 0, 1.0, "yellow", axis="x")
    b.flat_rect(f"twf_{key}_1", x0, 1, 1.0, "yellow", axis="x")
for key, x0 in (("w", 2), ("e", 6)):
    b.flat_rect(f"spf_{key}_0", x0, 0, 1.0, "yellow", axis="x")
    b.flat_rect(f"spf_{key}_1", x0, 1, 1.0, "yellow", axis="x")

# =================================================================
# 4. 亭身下环 (z 1..2): 南北红色横楣 (东西留门洞通行)
# =================================================================
for key, x0 in (("w", 0), ("c", 4), ("e", 8)):
    b.lintel_ns(f"tlo_{key}_s", x0, 0.0, 1, "red")
    b.lintel_ns(f"tlo_{key}_n", x0, 2.0, 1, "red")

# =================================================================
# 5. 花窗廊墙 (z 1..2): 透明, 竖边逐片吸进两端亭身横楣
# =================================================================
for key, x0 in (("w", 2), ("e", 6)):
    for i in (0, 1):
        b.wall_ns(f"lat_{key}s_{i}", x0 + i, 0.0, 1, "clear")
    for i in (0, 1):
        b.wall_ns(f"lat_{key}n_{i}", x0 + i, 2.0, 1, "clear")

# =================================================================
# 6. 亭身上环 (z 2..3): 每亭 4 根横楣围成方筒
# =================================================================
for key, x0 in (("w", 0), ("c", 4), ("e", 8)):
    b.lintel_ns(f"tup_{key}_s", x0, 0.0, 2, "red")
    b.lintel_ns(f"tup_{key}_n", x0, 2.0, 2, "red")
    b.lintel_ew(f"tup_{key}_w", float(x0), 0, 2, "red")
    b.lintel_ew(f"tup_{key}_e", float(x0 + 2), 0, 2, "red")

# =================================================================
# 7. 廊顶长板 (z=2): 短边压花窗墙顶, 长边整条吸亭身上环
# =================================================================
for key, x0 in (("w", 2), ("e", 6)):
    b.flat_rect(f"gal_{key}_0", x0, 0, 2.0, "gray", axis="y")
    b.flat_rect(f"gal_{key}_1", x0 + 1, 0, 2.0, "gray", axis="y")

# =================================================================
# 8. 亭顶 (z=3): 梯形四坡 + 黄色压顶 + 塔尖红旗
# =================================================================
hip_w, cap_w = b.hip_roof2("hip_w", 0, 0, 3.0, "gray", cap_color="yellow")
hip_c, cap_c = b.hip_roof2("hip_c", 4, 0, 3.0, "gray", cap_color="yellow")
hip_e, cap_e = b.hip_roof2("hip_e", 8, 0, 3.0, "gray", cap_color="yellow")
b.crest_ns("flag_w", 0.5, 0.5, 3.707107, "red")
b.crest_ns("flag_c", 4.5, 0.5, 3.707107, "red")
b.crest_ns("flag_e", 8.5, 0.5, 3.707107, "red")

# =================================================================
# 教程步骤 (18 步)
# =================================================================
b.step(
    "铺西半河面: 6 片蓝色正方形从西向东铺出河水。",
    [f"rv_{x}_{y}" for x in (2, 3, 4) for y in (0, 1)],
    tip="河面是全桥的基准面, 桥墩就扎在河心。",
)
b.step(
    "铺东半河面: 再 6 片, 6x2 河面合拢。",
    [f"rv_{x}_{y}" for x in (5, 6, 7) for y in (0, 1)],
    highlight=["rv_4_0"],
    tip="两半河面长边互吸, 一整条河从桥下流过。",
)
b.step(
    "砌西桥台: 8 片灰色正方形在西岸围成 2x2 空心石墩。",
    [f"abw_{s}" for s in ("s0", "s1", "n0", "n1", "w0", "w1", "e0", "e1")],
    highlight=["rv_2_0", "rv_2_1"],
    tip="石墩东壁底边整边吸住河面西沿, 转角竖边互锁。",
)
b.step(
    "砌东桥台: 对岸再砌一座, 与西桥台隔河相望。",
    [f"abe_{s}" for s in ("s0", "s1", "n0", "n1", "w0", "w1", "e0", "e1")],
    highlight=["rv_7_0", "rv_7_1"],
    tip="东桥台西壁贴住河面东沿 —— 两岸就位, 只差河心。",
)
b.step(
    "砌河心桥墩: 8 片灰色正方形直接站上河面中段。",
    [f"pier_{s}" for s in ("s0", "s1", "n0", "n1", "w0", "w1", "e0", "e1")],
    highlight=["rv_4_0", "rv_5_1"],
    tip="墩壁底边吸河面拼缝, 河心墩把大跨劈成两小跨。",
)
b.step(
    "架亭位楼板: 3 座墩台各盖 2 条黄色长方形, 短边搭在墙顶。",
    ["twf_w_0", "twf_w_1", "twf_c_0", "twf_c_1", "twf_e_0", "twf_e_1"],
    highlight=["abw_w0", "pier_w0", "abe_e0"],
    tip="长板两端短边各吸一面墙顶 —— 双端受力, 亭子的地基。",
)
b.step(
    "合龙跨间桥板: 4 条长方形横跨河面, 两端短边分别吸墩台墙顶。",
    ["spf_w_0", "spf_w_1", "spf_e_0", "spf_e_1"],
    highlight=["abw_e0", "pier_w0", "pier_e0", "abe_w0"],
    tip="一整条桥板跨过一跨 —— 跨中没有铰链缝, 这是廊桥的脊梁。",
)
b.step(
    "立亭身下环南楣: 3 根红色横楣站上楼板南长边。",
    ["tlo_w_s", "tlo_c_s", "tlo_e_s"],
    highlight=["twf_w_0", "twf_c_0", "twf_e_0"],
    tip="横楣整条长边落座 —— 长方形接长边, 一寸不差。",
)
b.step(
    "立亭身下环北楣: 北侧再立 3 根, 东西留出亭门洞。",
    ["tlo_w_n", "tlo_c_n", "tlo_e_n"],
    highlight=["twf_w_1", "twf_c_1", "twf_e_1"],
    tip="亭身东西不封墙 —— 行人从亭门穿桥而过。",
)
b.step(
    "挂南廊花窗: 4 片透明片竖边逐片吸进两端亭楣, 拼成南廊墙。",
    ["lat_ws_0", "lat_ws_1", "lat_es_0", "lat_es_1"],
    highlight=["tlo_w_s", "tlo_c_s", "tlo_e_s"],
    tip="花窗底边不吸桥板, 全靠竖边受力链挂在亭身之间。",
)
b.step(
    "挂北廊花窗: 北侧再挂 4 片, 双廊透光。",
    ["lat_wn_0", "lat_wn_1", "lat_en_0", "lat_en_1"],
    highlight=["tlo_w_n", "tlo_c_n", "tlo_e_n"],
    tip="透明花窗挡风不挡景 —— 风雨桥的名字就从这里来。",
)
b.step(
    "叠亭身上环南北楣: 6 根红色横楣对缝叠上下环。",
    ["tup_w_s", "tup_w_n", "tup_c_s", "tup_c_n", "tup_e_s", "tup_e_n"],
    highlight=["tlo_w_s", "tlo_c_n"],
    tip="上下环长边整条互吸, 亭身一节比一节稳。",
)
b.step(
    "封亭身上环东西楣: 6 根横楣转角竖边挂进南北楣, 亭身成筒。",
    ["tup_w_w", "tup_w_e", "tup_c_w", "tup_c_e", "tup_e_w", "tup_e_e"],
    highlight=["tup_w_s", "tup_c_s", "tup_e_s"],
    tip="东西楣先靠四条转角竖边挂住 —— 廊顶一到就再补一道长边。",
)
b.step(
    "盖廊顶长板: 4 条灰色长板短边压花窗墙顶, 长边整条吸进亭身。",
    ["gal_w_0", "gal_w_1", "gal_e_0", "gal_e_1"],
    highlight=["lat_ws_0", "tup_w_e", "tup_c_w"],
    tip="廊顶把三亭与双廊锁成一体 —— 剪断任何一缝, 力都能绕行。",
)
b.step(
    "盖西亭顶: 4 片灰色梯形下底吸亭身顶边, 腰两两互锁, 黄色压顶。",
    hip_w + [cap_w],
    highlight=["tup_w_s"],
    tip="梯形四坡自锁成环, 这是风雨桥的第一顶亭帽。",
)
b.step(
    "盖中亭顶: 河心亭同样四坡合拢。",
    hip_c + [cap_c],
    highlight=["tup_c_s"],
    tip="中亭骑在河心墩正上方, 全桥重心稳稳落在河床。",
)
b.step(
    "盖东亭顶: 第三顶亭帽就位, 三亭连脊。",
    hip_e + [cap_e],
    highlight=["tup_e_s"],
    tip="三亭一线, 廊脊起伏 —— 程阳桥的轮廓出来了。",
)
b.step(
    "插塔尖红旗: 3 面红旗立上压顶南沿 —— 风雨廊桥落成通行!",
    ["flag_w", "flag_c", "flag_e"],
    highlight=["hip_w_cap", "hip_c_cap", "hip_e_cap"],
    tip="旗面迎风, 桥下流水 —— 风雨不侵, 行人如织。",
)

b.finalize(
    model_id="covered_bridge_01",
    name="风雨廊桥",
    name_en="Covered Bridge 01",
    description=(
        "中式木构主题: 全库第一座三亭连廊的风雨桥 (程阳桥式样) —— "
        "两岸桥台与河心桥墩各驮一座梯形四坡亭; 跨间桥板一整条长方形"
        "双端受力搭在墩台墙顶上, 跨中零铰链缝; 透明花窗廊墙底边不落"
        "桥板, 全靠竖边逐片吸进两端亭身横楣形成水平受力链; 亭身上环"
        "东西横楣先靠转角竖边挂住, 廊顶长板到位后长边整条补吸, 三亭"
        "与双廊锁成一体 —— 行人从亭门穿桥而过, 风雨不侵。"
    ),
    difficulty=4,
    tags=["中式建筑", "廊桥", "木构", "河流", "世界地标"],
    min_pieces=90,
    min_steps=18,
)
