#!/usr/bin/env python3
"""生成模型 data/models/tow_truck_01.json (道路救援拖车)。

内容批 E 模型 1/5: 全库第一辆平板道路救援拖车 —— 与 fire_truck_01 /
ambulance_01 / dump_truck_01 等箱式工程车刻意区分: 本作的结构签名是
"平板拖床 + 30 度登车坡道 + 待救小车", 讲完一个道路救援的完整故事:
驾驶室箱体与平板拖床同高共缝 (驾驶室压顶东边与拖床西短边整边互吸),
拖床双长边压住两排车轮底座轮顶 (担架车同款门式框架), 车尾 30 度
登车坡道顶边整边吸拖床东短边、坡尾自然落地零悬挑 —— 故障小车就停
在坡道尽头, 绞盘一收即可拉上平板。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 车头朝西):
  - 街面 3 行 (x [1,10], y [0,3]): 灰色路面 + 黄色分道砖        20 片
  - 驾驶室 (x [2,3], y [1,2], z 0..1): 挡风窗格方 + 双侧门框方
    + 尾隔墙 + 压顶 + 红色警灯                                   6 片
  - 底盘: 车轮底座 x2 (x [3,5], 立于 y=1 / y=2 地缝) + 拖床长板  3 片
  - 登车坡道 (30 度, 顶边吸拖床东短边, 坡尾 x~6.73 落地)          1 片
  - 故障小车 (x [7,9]): 车轮底座 x2 + 蓝色车板 + 尾翼三角         4 片
  - 作业警示: 橙色安全锥四坡锥 x2 + 黄色警示牌三角 x2            10 片
  合计 44 片, 10 个教程步骤, 7 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 车轮底座平行立在地缝上, 底边 (长 2) 与街面长板长边整边吸合;
    拖床双长边同时压两排轮顶, 剪断任一条铰链线力都绕行 (门式框架);
  - 驾驶室压顶与拖床同在 z=1 平面, 压顶东边与拖床西短边共面互吸,
    驾驶室箱体成为拖床的第二条支撑路径;
  - 登车坡道顶边 (短边) 整边吸拖床东短边, 坡尾自己落地 —— 顶铰链
    + 接地斜撑两条路径, 零悬挑 (无障碍坡道同款);
  - 安全锥四坡锥底边四边吸脚下方板边, 四条斜棱两两互吸自锁;
  - 街面拼缝纪律: 驾驶室墙脚与锥脚处全单位方板, 车轮线处用长板
    (轮底长 2 须与长板长边等长贴合)。

用法: python3 tools/generate_tow_truck_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

ROAD = "gray"        # 路面
LANE = "yellow"      # 分道砖
CAB = "orange"       # 驾驶室
GLASS = "cyan"       # 挡风窗
BED = "gray"         # 拖床与坡道
WHEEL = "gray"       # 车轮底座
BEACON = "red"       # 警灯
CAR = "blue"         # 故障小车
CONE = "orange"      # 安全锥
SIGN = "yellow"      # 警示牌

# =================================================================
# 1. 街面 3 行 (x [1,10], y [0,3]): 拼缝纪律 —— 驾驶室墙脚与锥脚处
#    全单位方板; 车轮线 (y=1 / y=2) 两侧用长板, 长边与轮底等长。
# =================================================================
# 南行 (y [0,1])
b.flat("g0_1", 1, 0, 0.0, ROAD)
b.flat("g0_2", 2, 0, 0.0, ROAD)                    # 驾驶室南墙脚
b.flat_rect("g0_t", 3, 0, 0.0, ROAD)               # 拖车轮位南板
b.flat("g0_5", 5, 0, 0.0, ROAD)
b.flat("g0_6", 6, 0, 0.0, ROAD)                    # 西安全锥脚下
b.flat_rect("g0_c", 7, 0, 0.0, ROAD)               # 小车轮位南板
b.flat("g0_9", 9, 0, 0.0, ROAD)
# 中行 (y [1,2]): 车道
b.flat("g1_1", 1, 1, 0.0, LANE)
b.flat("g1_2", 2, 1, 0.0, ROAD)                    # 驾驶室脚下
b.flat_rect("g1_t", 3, 1, 0.0, ROAD)               # 拖车双轮之间
b.flat_rect("g1_m", 5, 1, 0.0, ROAD)               # 坡道落地区
b.flat_rect("g1_c", 7, 1, 0.0, ROAD)               # 小车双轮之间
b.flat("g1_9", 9, 1, 0.0, LANE)
# 北行 (y [2,3])
b.flat("g2_1", 1, 2, 0.0, ROAD)
b.flat("g2_2", 2, 2, 0.0, ROAD)                    # 驾驶室北墙脚
b.flat_rect("g2_t", 3, 2, 0.0, ROAD)               # 拖车轮位北板
b.flat("g2_5", 5, 2, 0.0, ROAD)
b.flat("g2_6", 6, 2, 0.0, ROAD)                    # 北安全锥脚下
b.flat_rect("g2_c", 7, 2, 0.0, ROAD)               # 小车轮位北板
b.flat("g2_9", 9, 2, 0.0, ROAD)

# =================================================================
# 2. 驾驶室 (x [2,3], y [1,2], z 0..1): 箱体 + 压顶 + 警灯
# =================================================================
b.add("cab_front", "window_square", (2.0, 1.5, 0.5), (90, 0, 90), GLASS)
b.add("cab_door_s", "door_frame", (2.5, 1.0, 0.5), (90, 0, 0), CAB)
b.add("cab_door_n", "door_frame", (2.5, 2.0, 0.5), (90, 0, 0), CAB)
b.add("cab_rear", "square", (3.0, 1.5, 0.5), (90, 0, 90), CAB)
b.flat("cab_top", 2, 1, 1.0, CAB)
b.crest_ew("cab_beacon", 2.0, 1, 1.0, BEACON)      # 警灯骑压顶西沿

# =================================================================
# 3. 底盘与拖床: 车轮底座 x2 + 拖床长板 (担架车同款门式框架)
# =================================================================
b.add("tow_wh_s", "wheel_base", (4.0, 1.0, 0.5), (90, 0, 0), WHEEL)
b.add("tow_wh_n", "wheel_base", (4.0, 2.0, 0.5), (90, 0, 0), WHEEL)
b.flat_rect("tow_bed", 3, 1, 1.0, BED)             # 双长边压双轮顶

# =================================================================
# 4. 登车坡道: 顶边吸拖床东短边, 坡尾落地零悬挑
# =================================================================
b.ramp("tow_ramp", "+x", 5, 1, 1.0, BED)

# =================================================================
# 5. 故障小车 (x [7,9]): 双轮 + 车板 + 尾翼
# =================================================================
b.add("car_wh_s", "wheel_base", (8.0, 1.0, 0.5), (90, 0, 0), WHEEL)
b.add("car_wh_n", "wheel_base", (8.0, 2.0, 0.5), (90, 0, 0), WHEEL)
b.flat_rect("car_bed", 7, 1, 1.0, CAR)
b.crest_ew("car_fin", 9.0, 1, 1.0, CAR)            # 尾翼骑车板东短边

# =================================================================
# 6. 作业警示: 安全锥四坡锥 x2 + 警示牌 x2
# =================================================================
b.hat4("cone_s", 6, 0, 0.0, CONE, shape="equilateral_triangle")
b.hat4("cone_n", 6, 2, 0.0, CONE, shape="equilateral_triangle")
b.crest_ns("sign_w", 1, 1.0, 0.0, SIGN)            # 骑 y=1 地缝
b.crest_ns("sign_e", 9, 2.0, 0.0, SIGN)            # 骑 y=2 地缝

# =================================================================
# 教程步骤 (10 步)
# =================================================================
b.step(
    "铺街面南行: 驾驶室墙脚与安全锥脚下用单位方板, 车轮位用长板。",
    ["g0_1", "g0_2", "g0_t", "g0_5", "g0_6", "g0_c", "g0_9"],
    tip="车轮底座底边长 2 —— 轮位两侧必须是长板长边, 等长才吸得住。",
)
b.step(
    "铺车道中行: 两块黄色分道砖收在东西两端, 中段全灰色路面。",
    ["g1_1", "g1_2", "g1_t", "g1_m", "g1_c", "g1_9"],
    highlight=["g0_t"],
    tip="中行与南行的长板一一对缝 —— y=1 车轮缝要全线贯通。",
)
b.step(
    "铺街面北行: 与南行镜像对缝, y=2 车轮缝同样贯通。",
    ["g2_1", "g2_2", "g2_t", "g2_5", "g2_6", "g2_c", "g2_9"],
    highlight=["g1_t"],
    tip="三行铺完, 救援作业区就位 —— 拖车马上进场。",
)
b.step(
    "立驾驶室箱体: 挡风窗格方朝西, 两扇门框方作侧门, 尾隔墙收东。",
    ["cab_front", "cab_door_s", "cab_door_n", "cab_rear"],
    highlight=["g1_2"],
    tip="四面墙四角竖边互咬成环 —— 驾驶室是拖床的第二条支撑路径。",
)
b.step(
    "盖驾驶室压顶并装警灯: 压顶四边吸墙顶, 红色警灯骑压顶西沿。",
    ["cab_top", "cab_beacon"],
    highlight=["cab_front"],
    tip="警灯'压顶西沿+挡风窗顶'一线双吸 —— 出勤路上一闪一闪。",
)
b.step(
    "立双轮并铺拖床: 车轮底座平行立上地缝, 拖床双长边压双轮顶、"
    "西短边吸驾驶室压顶东边。",
    ["tow_wh_s", "tow_wh_n", "tow_bed"],
    highlight=["cab_top"],
    tip="床板压双轮 + 共缝驾驶室 —— 剪断任一条铰链线力都绕行。",
)
b.step(
    "架登车坡道: 30 度坡顶边整边吸拖床东短边, 坡尾自然落地。",
    ["tow_ramp"],
    highlight=["tow_bed"],
    tip="顶铰链 + 接地斜撑两条路径, 零悬挑 —— 绞盘就位!",
)
b.step(
    "拼故障小车: 双轮立上地缝, 蓝色车板双长边压轮顶。",
    ["car_wh_s", "car_wh_n", "car_bed"],
    highlight=["tow_ramp"],
    tip="小车车头正对坡道尽头 —— 就差把它拉上平板了。",
)
b.step(
    "装小车尾翼并摆西侧安全锥: 尾翼骑车板东短边, 锥底四边吸方板边。",
    ["car_fin", "cone_s_s", "cone_s_e", "cone_s_n", "cone_s_w"],
    highlight=["car_bed"],
    tip="四条斜棱两两互吸自锁 —— 安全锥摆好, 后方来车请绕行。",
)
b.step(
    "摆北侧安全锥与两块警示牌: 三角牌骑地缝立稳, 救援作业开始!",
    ["cone_n_s", "cone_n_e", "cone_n_n", "cone_n_w", "sign_w", "sign_e"],
    highlight=["cone_s_s"],
    tip="警示牌底边骑住地缝 —— 重心正压铰链线, 风吹不倒。",
)

b.finalize(
    model_id="tow_truck_01",
    name="道路救援拖车",
    name_en="Tow Truck 01",
    description=(
        "只用核心九片型的平板道路救援拖车, 结构签名是'平板拖床 + 30 度"
        "登车坡道 + 待救小车': 驾驶室箱体 (挡风窗格方 + 双侧门框方) 压顶"
        "与拖床同在一个平面, 压顶东边与拖床西短边整边互吸; 拖床双长边压"
        "住两排车轮底座轮顶锁成门式框架, 车尾 30 度登车坡道顶边整边吸"
        "拖床东短边、坡尾自然落地零悬挑; 故障小车停在坡道尽头, 两座橙色"
        "安全锥四坡锥与黄色警示牌围出作业区 —— 绞盘一收, 小车就上平板!"
    ),
    difficulty=2,
    tags=["城市", "交通", "救援车", "职业体验", "进阶"],
    min_pieces=44,
    min_steps=10,
)
