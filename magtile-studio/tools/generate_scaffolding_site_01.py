#!/usr/bin/env python3
"""生成模型 data/models/scaffolding_site_01.json (脚手架翻新工地)。

建筑/工地主题: 与塔吊/搅拌车 (吊装/浇筑) 刻意区分 —— 本作的主角
是 "楼与架" 这组翻新关系: 2x2 双层小楼 (门框方大门 + 窗格方窗洞
+ 两层满铺楼板 + 屋顶楼梯间塔与女儿墙), 南立面外贴一排双层脚手
架 —— 每层由立杆墙 + 端墙 + 双方板作业台组成, 作业台北沿直接
吸在楼体墙顶上, 楼与架层层锁成刚性环; 顶层作业台南沿立护栏齿,
东端 30 度爬梯直下地坪预留空位。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 工地地坪 7x4 (x [0,7], y [0,4]): x [5,7] x y [0,1] 留爬梯落位  18 片
  - 小楼 (x [3,5], y [1,3], z 0..2): 两层墙环 x16 (门框方 + 窗格方)
    + 两层满铺楼板 x8                                              24 片
  - 屋顶: 楼梯间等腰四坡塔 x4 (塔尖 3.94) + 女儿墙护齿 x4           8 片
  - 脚手架 (x [3,5], y [0,1], z 0..2): 两层 (立杆墙 x2 + 端墙 x2
    + 作业台方板 x2) x2                                            12 片
  - 护栏齿 x2 + 30 度爬梯 x1                                        3 片
  - 场景: 沙堆等边四坡 x4 + 雪糕筒 x2 + 告示牌 x2                   8 片
  合计 73 片, 14 个教程步骤, 7 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点:
  - 作业台方板南沿压脚手架立杆墙顶、北沿整边吸楼体墙顶 ——
    楼与架在每层高度都互锁成环, 剪断任何一条铰链线力都能绕行;
  - 爬梯顶边一线双吸 (作业台东沿 + 端墙顶), 坡尾落在预留空位
    的实地上;
  - 楼梯间四坡塔四条斜棱两两互吸自锁, 女儿墙护齿骑楼板沿口;
  - 沙堆四坡斜棱互锁, 底边吸地坪格边。

用法: python3 tools/generate_scaffolding_site_01.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

YARD = "gray"       # 工地地坪
LAWN = "green"      # 北缘绿化带
BUILDING = "cyan"   # 小楼墙体
DOOR = "blue"       # 门框方大门
WIN = "clear"       # 窗格方窗洞
DECK = "gray"       # 楼板
TURRET = "orange"   # 楼梯间四坡塔
PARAPET = "yellow"  # 女儿墙护齿
SCAF = "orange"     # 脚手架立杆墙
LATTICE = "clear"   # 脚手架格构面 (窗格方)
PLANK = "yellow"    # 作业台
RAIL = "red"        # 护栏齿
LADDER = "gray"     # 爬梯
SAND = "yellow"     # 沙堆
CONE = "red"        # 雪糕筒
SIGN = "yellow"     # 告示牌

# =================================================================
# 1. 工地地坪 7x4: x [5,7] x y [0,1] 留爬梯落位
# =================================================================
b.flat_rect("g0_a", 0, 0, 0.0, YARD)
b.flat("g0_b", 2, 0, 0.0, YARD)
b.flat("g0_c", 3, 0, 0.0, YARD)
b.flat("g0_d", 4, 0, 0.0, YARD)
b.flat_rect("g1_a", 0, 1, 0.0, YARD)
b.flat("g1_b", 2, 1, 0.0, YARD)
b.flat("g1_c", 3, 1, 0.0, YARD)
b.flat("g1_d", 4, 1, 0.0, YARD)
b.flat_rect("g1_e", 5, 1, 0.0, YARD)
b.flat_rect("g2_a", 0, 2, 0.0, YARD)
b.flat("g2_b", 2, 2, 0.0, YARD)
b.flat("g2_c", 3, 2, 0.0, YARD)
b.flat("g2_d", 4, 2, 0.0, YARD)
b.flat_rect("g2_e", 5, 2, 0.0, YARD)
b.flat_rect("g3_a", 0, 3, 0.0, LAWN)
b.flat_rect("g3_b", 2, 3, 0.0, LAWN)
b.flat_rect("g3_c", 4, 3, 0.0, LAWN)
b.flat("g3_d", 6, 3, 0.0, LAWN)

# =================================================================
# 2. 小楼第一层 (x [3,5], y [1,3], z 0..1): 门框方大门朝南
# =================================================================
b.add("b1_door", "door_frame", (3.5, 1.0, 0.5), (90, 0, 0), DOOR)
b.wall_ns("b1_s", 4, 1.0, 0, BUILDING)
b.wall_ew("b1_w1", 3.0, 1, 0, BUILDING)
b.wall_ew("b1_w2", 3.0, 2, 0, BUILDING)
b.wall_ns("b1_n1", 3, 3.0, 0, BUILDING)
b.wall_ns("b1_n2", 4, 3.0, 0, BUILDING)
b.wall_ew("b1_e1", 5.0, 1, 0, BUILDING)
b.wall_ew("b1_e2", 5.0, 2, 0, BUILDING)
b.flat("d1_a", 3, 1, 1.0, DECK)
b.flat("d1_b", 4, 1, 1.0, DECK)
b.flat("d1_c", 3, 2, 1.0, DECK)
b.flat("d1_d", 4, 2, 1.0, DECK)

# =================================================================
# 3. 小楼第二层 (z 1..2): 南/西/东开窗格方窗洞
# =================================================================
b.add("w2_s1", "window_square", (3.5, 1.0, 1.5), (90, 0, 0), WIN)
b.add("w2_s2", "window_square", (4.5, 1.0, 1.5), (90, 0, 0), WIN)
b.wall_ew("b2_w1", 3.0, 1, 1, BUILDING)
b.add("b2_w2", "window_square", (3.0, 2.5, 1.5), (90, 0, 90), WIN)
b.wall_ns("b2_n1", 3, 3.0, 1, BUILDING)
b.wall_ns("b2_n2", 4, 3.0, 1, BUILDING)
b.add("b2_e1", "window_square", (5.0, 1.5, 1.5), (90, 0, 90), WIN)
b.wall_ew("b2_e2", 5.0, 2, 1, BUILDING)
b.flat("d2_a", 3, 1, 2.0, DECK)
b.flat("d2_b", 4, 1, 2.0, DECK)
b.flat("d2_c", 3, 2, 2.0, DECK)
b.flat("d2_d", 4, 2, 2.0, DECK)

# =================================================================
# 4. 屋顶: 楼梯间等腰四坡塔 (东北格) + 女儿墙护齿
# =================================================================
b.hat4("turret", 4, 2, 2.0, TURRET)
b.crest_ns("p_s1", 3, 1.0, 2.0, PARAPET)
b.crest_ns("p_s2", 4, 1.0, 2.0, PARAPET)
b.crest_ew("p_w1", 3.0, 1, 2.0, PARAPET)
b.crest_ew("p_w2", 3.0, 2, 2.0, PARAPET)

# =================================================================
# 5. 脚手架第一层 (x [3,5], y [0,1], z 0..1)
# =================================================================
b.wall_ns("sc1_s1", 3, 0.0, 0, SCAF)
b.wall_ns("sc1_s2", 4, 0.0, 0, SCAF)
b.wall_ew("sc1_w", 3.0, 0, 0, SCAF)
b.wall_ew("sc1_e", 5.0, 0, 0, SCAF)
b.flat("sc1_d1", 3, 0, 1.0, PLANK)
b.flat("sc1_d2", 4, 0, 1.0, PLANK)

# =================================================================
# 6. 脚手架第二层 (z 1..2): 立杆墙换窗格方格构面
# =================================================================
b.add("sc2_s1", "window_square", (3.5, 0.0, 1.5), (90, 0, 0), LATTICE)
b.add("sc2_s2", "window_square", (4.5, 0.0, 1.5), (90, 0, 0), LATTICE)
b.wall_ew("sc2_w", 3.0, 0, 1, SCAF)
b.wall_ew("sc2_e", 5.0, 0, 1, SCAF)
b.flat("sc2_d1", 3, 0, 2.0, PLANK)
b.flat("sc2_d2", 4, 0, 2.0, PLANK)

# =================================================================
# 7. 护栏齿 + 30 度爬梯 (坡尾落预留空位)
# =================================================================
b.crest_ns("gr_1", 3, 0.0, 2.0, RAIL)
b.crest_ns("gr_2", 4, 0.0, 2.0, RAIL)
b.ramp("ladder", "+x", 5.0, 0, 1.0, LADDER)

# =================================================================
# 8. 场景: 沙堆 + 雪糕筒 + 告示牌
# =================================================================
b.hat4("sand", 1, 0, 0.0, SAND, shape="equilateral_triangle")
b.crest_ns("cone_a", 2, 1.0, 0.0, CONE)
b.crest_ew("cone_b", 7.0, 3, 0.0, CONE)
b.wall_ns("sign", 6, 4.0, 0, SIGN)
b.crest_ns("sign_top", 6, 4.0, 1.0, "red")

# =================================================================
# 教程步骤 (14 步)
# =================================================================
b.step(
    "铺地坪南两行 (y [0,2]): 9 片, 东南角 x [5,7] 留出爬梯落位。",
    ["g0_a", "g0_b", "g0_c", "g0_d",
     "g1_a", "g1_b", "g1_c", "g1_d", "g1_e"],
    tip="脚手架行 (y [0,1]) 全用单格方板 —— 立杆墙都吸在这行的格边上。",
)
b.step(
    "铺地坪北两行 (y [2,4]): 9 片, 北排绿化带合拢成 7x4。",
    ["g2_a", "g2_b", "g2_c", "g2_d", "g2_e",
     "g3_a", "g3_b", "g3_c", "g3_d"],
    highlight=["g1_a"],
    tip="小楼地基就位 —— 每条拼缝都是墙的吸附线。",
)
b.step(
    "砌小楼第一层南墙与西墙: 门框方大门开在南面, 共 4 片。",
    ["b1_door", "b1_s", "b1_w1", "b1_w2"],
    highlight=["g0_c", "g1_b"],
    tip="门框方外框与正方形完全一致 —— 底边吸缝、竖边咬邻片。",
)
b.step(
    "砌小楼第一层北墙与东墙: 4 片, 首层墙环闭合。",
    ["b1_n1", "b1_n2", "b1_e1", "b1_e2"],
    highlight=["b1_door", "b1_w2"],
    tip="闭合环墙天生抗扭 —— 这是脚手架的靠山。",
)
b.step(
    "铺一层楼板: 4 片方板压墙顶。",
    ["d1_a", "d1_b", "d1_c", "d1_d"],
    highlight=["b1_s", "b1_n1"],
    tip="每片同时吸两段墙顶与邻板拼缝。",
)
b.step(
    "砌小楼第二层南墙与西墙: 三扇窗格方窗洞朝南朝西。",
    ["w2_s1", "w2_s2", "b2_w1", "b2_w2"],
    highlight=["d1_a"],
    tip="翻新的正是这面窗墙 —— 脚手架一会儿就贴着它长起来。",
)
b.step(
    "砌小楼第二层北墙与东墙: 东面再开一扇窗, 二层墙环闭合。",
    ["b2_n1", "b2_n2", "b2_e1", "b2_e2"],
    highlight=["w2_s1", "b2_w1"],
    tip="墙环层层对缝 —— 楼体是一根方管。",
)
b.step(
    "铺二层楼板: 4 片方板封顶。",
    ["d2_a", "d2_b", "d2_c", "d2_d"],
    highlight=["b2_n2", "b2_e1"],
    tip="楼板沿口就是女儿墙与脚手架顶台的吸附线。",
)
b.step(
    "起楼梯间四坡塔: 东北格 4 片等腰三角合拢自锁, 塔尖 3.94。",
    ["turret_s", "turret_e", "turret_n", "turret_w"],
    highlight=["d2_d"],
    tip="四条斜棱两两互吸 —— 屋顶最高点从此有了名字。",
)
b.step(
    "立女儿墙护齿: 4 片黄色三角骑在楼板南沿与西沿。",
    ["p_s1", "p_s2", "p_w1", "p_w2"],
    highlight=["d2_a", "d2_c"],
    tip="护齿底边整边吸楼板沿口 —— 屋顶作业的安全线。",
)
b.step(
    "搭脚手架第一层: 2 片立杆墙踩格边, 2 片端墙封两端, "
    "2 片作业台方板南压杆顶、北吸楼墙。",
    ["sc1_s1", "sc1_s2", "sc1_w", "sc1_e", "sc1_d1", "sc1_d2"],
    highlight=["g0_c", "b1_door"],
    tip="作业台北沿整边吸小楼墙顶 —— 楼与架锁成第一个环。",
)
b.step(
    "搭脚手架第二层: 立杆墙换窗格方格构面, 作业台再上一层。",
    ["sc2_s1", "sc2_s2", "sc2_w", "sc2_e", "sc2_d1", "sc2_d2"],
    highlight=["sc1_d1", "sc1_d2"],
    tip="窗格方就是脚手架的格构面 —— 透过它能看见刷墙的工人。",
)
b.step(
    "装护栏与爬梯: 2 片红色护栏齿立在顶台南沿, 30 度爬梯"
    "顶边吸作业台东沿、坡尾落预留空位。",
    ["gr_1", "gr_2", "ladder"],
    highlight=["sc2_d1", "sc1_d2"],
    tip="爬梯一线双吸 (台沿 + 端墙顶) —— 上架请走爬梯。",
)
b.step(
    "布工地场景: 沙堆四坡自锁, 雪糕筒立拼缝, 东北角立告示牌 "
    "—— 翻新开工!",
    ["sand_s", "sand_e", "sand_n", "sand_w",
     "cone_a", "cone_b", "sign", "sign_top"],
    highlight=["g0_a", "g3_d"],
    tip="沙堆就在脚手架旁边 —— 抹灰的料从这里上斗。",
)

b.finalize(
    model_id="scaffolding_site_01",
    name="脚手架翻新工地",
    name_en="Scaffolding Site 01",
    description=(
        "建筑/工地主题: 楼与架层层互锁的翻新现场 —— 2x2 双层小楼 "
        "(门框方大门 + 四扇窗格方窗洞 + 两层满铺楼板), 屋顶东北格"
        "起等腰四坡楼梯间塔 (塔尖 3.94), 南沿西沿立女儿墙护齿; "
        "南立面外贴双层脚手架: 立杆墙 + 端墙 + 双方板作业台, 台板"
        "北沿整边吸楼体墙顶, 每层都与小楼锁成刚性环, 二层立杆换"
        "窗格方格构面; 顶台南沿护栏齿把守, 东端 30 度爬梯一线双吸"
        "直下地坪预留空位。场边沙堆四坡自锁 —— 一处会讲安全课的"
        "翻新工地。"
    ),
    difficulty=3,
    tags=["工程", "脚手架", "翻新", "在建小楼", "进阶"],
    min_pieces=73,
    min_steps=14,
)
