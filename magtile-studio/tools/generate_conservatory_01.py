#!/usr/bin/env python3
"""生成模型 data/models/conservatory_01.json (天窗玻璃花房)。

内容批 P 模型 2/10 (P2): 植物花园主题 D2, 主打窗格方 (window_square)
—— 重写版。招牌是"屋顶采光天窗塔 (roof lantern)": 4x3 单层花房盖
玻璃平顶后, 顶面正中再升起一圈 2x1 窗格方天窗塔, 塔顶长方形压顶、
两端三角尖饰 —— 维多利亚花房最经典的屋顶轮廓。与 greenhouse_01
(A 字斜顶) / greenhouse_dome_01 (穹顶) / 旧版 (两层盒式墙 + 梯形雨檐)
的剖面逻辑全部不同: 本作只有一层墙, 高度全让给屋顶上的天窗塔。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 入户朝北):
  - 单层墙环 (z 0..1): 南立面窗格 x4 + 北墙 (门洞留 T17 负空间) x3
    + 西墙 x3 + 东墙窗格 x3                                     13 片
  - 玻璃平顶: 透明方板 x12 (4x3 @z=1)                          12 片
  - 天窗塔 (z 1..2): 窗格方 x6 围 2x1, 骑平顶拼缝               6 片
  - 塔顶: 长方形压顶 x1 + 三角尖饰 x2                           3 片
  - 室内 L 形花池: 泥土方板 x4 + 三角盆栽 x3                    7 片
  合计 41 片, 9 个教程步骤; 窗格方 x16, 全部片型在 CORE-9 之内
  (仅等边三角形/长方形/正方形/窗格方 4 种形状)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 墙环直接落地 (接地即支撑), 相邻墙片竖直边等长互咬, 四角闭环;
  - 花池贴南墙/东墙脚, 底边与墙底边共线整边互吸, 盆栽骑花池拼缝;
  - 平顶方板与墙顶边等长互吸且彼此拼缝成网 —— 剪断任一条铰链线,
    每片顶板都还有第二条经由墙环的接地路径;
  - 天窗塔墙脚骑平顶拼缝 (缝两侧各一条整边连接), 压顶短边与塔端
    墙顶等长互吸; 尖饰底边与塔端墙顶/压顶短边共线双连接;
  - 最高点尖饰 2.87 触发 R8: 墙环 + 顶网 + 塔环多环冗余, 无单点
    失效损失 >= 3 片。

用法: python3 tools/generate_conservatory_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

GLASS = "clear"      # 窗格方玻璃 / 玻璃平顶
FRAME = "green"      # 实心框架墙
CAP = "green"        # 塔顶压顶
FINIAL = "yellow"    # 塔顶尖饰
SOIL = "orange"      # 室内花池
PLANTS = ["red", "purple", "pink"]


def win_ns(tid, x0, y, z0):
    """南北朝向窗格方立墙 (平面 y=y), 覆盖 x [x0,x0+1], z [z0,z0+1]。"""
    b.add(tid, "window_square", (x0 + 0.5, y, z0 + 0.5), (90, 0, 0), GLASS)


def win_ew(tid, x, y0, z0):
    """东西朝向窗格方立墙 (平面 x=x), 覆盖 y [y0,y0+1], z [z0,z0+1]。"""
    b.add(tid, "window_square", (x, y0 + 0.5, z0 + 0.5), (90, 0, 90), GLASS)


# =================================================================
# 1. 单层墙环 (4x3 足迹, z 0..1): 南向整排窗格, 北墙中央留门洞
# =================================================================
for x in range(4):
    win_ns(f"ws_s{x}", x, 0.0, 0)                 # 南立面 4 片窗格
b.wall_ns("wall_n0", 0, 3.0, 0, FRAME)            # 北墙西段 (实心)
win_ns("ws_n2", 2, 3.0, 0)                        # 北墙东段窗格 x2
win_ns("ws_n3", 3, 3.0, 0)                        # (x [1,2] 留门洞, T17)
b.wall_ew("wall_w0", 0.0, 0, 0, FRAME)            # 西墙: 实心-窗-实心
win_ew("ws_w1", 0.0, 1, 0)
b.wall_ew("wall_w2", 0.0, 2, 0, FRAME)
win_ew("ws_e0", 4.0, 0, 0)                        # 东墙整排窗格 x3
win_ew("ws_e1", 4.0, 1, 0)
win_ew("ws_e2", 4.0, 2, 0)

# =================================================================
# 2. 室内 L 形花池: 沿南墙脚 + 东墙脚, 盆栽骑花池拼缝
# =================================================================
b.flat("bed_1", 1, 0, 0.0, SOIL)
b.flat("bed_2", 2, 0, 0.0, SOIL)
b.flat("bed_3", 3, 0, 0.0, SOIL)
b.flat("bed_4", 3, 1, 0.0, SOIL)
b.crest_ew("plant_a", 2.0, 0, 0.0, PLANTS[0])     # 骑 bed_1|bed_2 拼缝
b.crest_ew("plant_b", 3.0, 0, 0.0, PLANTS[1])     # 骑 bed_2|bed_3 拼缝
b.crest_ns("plant_c", 3, 1.0, 0.0, PLANTS[2])     # 骑 bed_3|bed_4 拼缝

# =================================================================
# 3. 玻璃平顶: 12 片透明方板 (4x3 @z=1), 拼缝成网
# =================================================================
for y in range(3):
    for x in range(4):
        b.flat(f"roof_{x}_{y}", x, y, 1.0, GLASS)

# =================================================================
# 4. 天窗塔 (roof lantern): 6 片窗格方围 2x1, 骑平顶拼缝 (z 1..2)
# =================================================================
win_ns("lt_s1", 1, 1.0, 1)
win_ns("lt_s2", 2, 1.0, 1)
win_ns("lt_n1", 1, 2.0, 1)
win_ns("lt_n2", 2, 2.0, 1)
win_ew("lt_w", 1.0, 1, 1)
win_ew("lt_e", 3.0, 1, 1)

# =================================================================
# 5. 塔顶: 长方形压顶 + 两端三角尖饰
# =================================================================
b.add("lt_cap", "rectangle", (2.0, 1.5, 2.0), (0, 0, 0), CAP)
b.crest_ew("finial_w", 1.0, 1, 2.0, FINIAL)
b.crest_ew("finial_e", 3.0, 1, 2.0, FINIAL)

# =================================================================
# 教程步骤 (9 步)
# =================================================================
b.step(
    "砌南立面: 四片透明窗格方整排朝南 —— 花房的玻璃招牌墙, 竖直边"
    "逐片互咬。",
    [f"ws_s{x}" for x in range(4)],
    tip="窗格方物理上和实心墙一样稳 —— 从南边看进去是一整面玻璃。",
)
b.step(
    "铺 L 形花池: 四片泥土方板沿南墙脚与东侧拐弯, 底边与墙脚共线互吸。",
    ["bed_1", "bed_2", "bed_3", "bed_4"],
    highlight=["ws_s1", "ws_s3"],
    tip="花池贴墙种 —— 阳光从南窗照进来, 正好晒在土格上。",
)
b.step(
    "种盆栽: 红/紫/粉三株三角花骑上花池拼缝。",
    ["plant_a", "plant_b", "plant_c"],
    highlight=["bed_2", "bed_4"],
    tip="先种花再合围 —— 墙环合拢前手还伸得进花房。",
)
b.step(
    "合围西墙与东墙: 西侧实心-窗-实心三片, 东侧整排三片窗格, 四角"
    "竖直边互咬。",
    ["wall_w0", "ws_w1", "wall_w2", "ws_e0", "ws_e1", "ws_e2"],
    highlight=["ws_s0", "ws_s3"],
    tip="东墙三片全是窗 —— 晨光先照进花房的东脸。",
)
b.step(
    "封北墙留门洞: 西段实心墙 + 东段两片窗格, x [1,2] 空出入户门洞"
    "(T17 负空间)。",
    ["wall_n0", "ws_n2", "ws_n3"],
    highlight=["wall_w2", "ws_e2"],
    tip="少砌一片墙就是门 —— 门洞上方一会儿由平顶补齐。",
)
b.step(
    "铺南半平顶: 六片透明方板盖住南两行, 边与墙顶等长互吸、彼此拼缝。",
    [f"roof_{x}_{y}" for y in (0, 1) for x in range(4)][:6],
    highlight=["ws_s1", "ws_e0"],
    tip="从南墙顶开始铺 —— 每片至少吸住一条墙顶边或邻板拼缝。",
)
b.step(
    "铺北半平顶: 再六片补齐 4x3 玻璃平顶, 门洞上方由顶板连桥。",
    [f"roof_{x}_{y}" for y in (0, 1) for x in range(4)][6:]
    + [f"roof_{x}_2" for x in range(4)],
    highlight=["wall_n0", "ws_n2"],
    tip="平顶拼缝连成网 —— 正中的十字缝就是天窗塔的地基线。",
)
b.step(
    "升天窗塔: 六片窗格方骑住平顶正中拼缝, 围出 2x1 采光天窗环。",
    ["lt_s1", "lt_s2", "lt_w", "lt_n1", "lt_n2", "lt_e"],
    highlight=["roof_1_1", "roof_2_1"],
    tip="塔墙脚两侧各吸一片顶板 —— 天窗塔是屋顶上的小玻璃房。",
)
b.step(
    "封塔顶: 绿色长方形压顶两端与塔墙顶等长互吸, 黄色尖饰立上两端"
    "—— 天窗玻璃花房落成!",
    ["lt_cap", "finial_w", "finial_e"],
    highlight=["lt_w", "lt_e"],
    tip="尖饰底边同时吸住塔端墙顶与压顶短边 —— 阳光顺着天窗洒满花房。",
)

b.finalize(
    model_id="conservatory_01",
    name="天窗玻璃花房",
    name_en="Conservatory 01",
    description=(
        "植物花园 D2 窗格方主打示范: 4x3 单层花房南立面与东墙整排"
        "窗格方玻璃, 北墙留 T17 门洞; 盖满 12 片透明玻璃平顶后, 顶面"
        "正中再升起一圈 2x1 窗格方天窗塔 (roof lantern), 塔顶长方形"
        "压顶、两端黄色尖饰 —— 维多利亚花房的经典屋顶轮廓; 室内 L 形"
        "泥土花池沿窗摆着红紫粉三株盆栽。窗格方 x16 全在 CORE-9 内,"
        "与 A 字斜顶 greenhouse_01、穹顶 greenhouse_dome_01 剖面完全不同。"
    ),
    difficulty=2,
    tags=["植物花园", "温室", "花房", "天窗", "窗格", "进阶"],
    min_pieces=41,
    min_steps=9,
    series="plant_garden",
)
