#!/usr/bin/env python3
"""生成模型 data/models/butterfly_01.json (大蝴蝶)。

第二批模型 ⑪: 自然生灵主题 —— 一只停在花园地面上的大蝴蝶:
四扇彩色马赛克翅膀平展开来 (前翅红粉相间、后翅蓝青相间),
中间是隆起的箱形身体, 头顶两根等腰三角触角, 前翅上沿还各
"长"着一枚六边形眼斑 —— 模型库第一个对称拼花生物。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 身体地板: 中轴 5 片方板 (y 0..5)                            5 片
  - 身体箱体: 两侧立壁 10 + 尾板/头板 2 + 背板 5              17 片
  - 触角与头饰: 等腰三角触角 2 + 等边三角头饰 1                 3 片
  - 东翅: 前翅 6 方 + 后翅 4 方 + 翅尖等边三角 4               14 片
  - 西翅: 与东翅完全镜像                                       14 片
  - 眼斑: 前翅上沿六边形 2                                      2 片
  合计 55 片, 15 个教程步骤, 4 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 翅膀马赛克平铺接地, 内沿与身体地板边及立壁底边同缝三吸;
  - 身体是地板 + 双立壁 + 背板的闭合箱形环, 触角立在背板侧沿
    (同时吸背板边与立壁顶边);
  - 全模型左右严格镜像 —— 对称检查就是最好的自查。

用法: python3 tools/generate_butterfly.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

# =================================================================
# 1. 身体地板: 中轴 5 片方板 (x 0..1, y 0..5)
# =================================================================
for y in range(5):
    b.flat(f"bd_fl_{y}", 0, y, 0.0, "gray")

# =================================================================
# 2. 翅膀马赛克 (东翅 x>=1, 西翅 x<=0 镜像)
#    前翅 y 3..5 (3 列), 后翅 y 1..3 (2 列), 翅尖等边三角收边
# =================================================================
FORE = {(0, 1): "red", (1, 1): "pink", (2, 1): "red",
        (0, 0): "pink", (1, 0): "red", (2, 0): "pink"}
for (c, r), color in FORE.items():                    # 前翅 6 方
    b.flat(f"e_fw_{c}_{r}", 1 + c, 3 + r, 0.0, color)
    b.flat(f"w_fw_{c}_{r}", -1 - c, 3 + r, 0.0, color)
HIND = {(0, 1): "blue", (1, 1): "cyan",
        (0, 0): "cyan", (1, 0): "blue"}
for (c, r), color in HIND.items():                    # 后翅 4 方
    b.flat(f"e_hw_{c}_{r}", 1 + c, 1 + r, 0.0, color)
    b.flat(f"w_hw_{c}_{r}", -1 - c, 1 + r, 0.0, color)
for r in range(2):                                    # 前翅翅尖 (x=±4)
    b.place_edge(f"e_ft_{r}", "equilateral_triangle", 0,
                 (4.0, 3.0 + r, 0.0), (4.0, 4.0 + r, 0.0), (1, 0, 0), "purple")
    b.place_edge(f"w_ft_{r}", "equilateral_triangle", 0,
                 (-3.0, 4.0 + r, 0.0), (-3.0, 3.0 + r, 0.0), (-1, 0, 0), "purple")
for r in range(2):                                    # 后翅翅尖 (x=±3)
    b.place_edge(f"e_ht_{r}", "equilateral_triangle", 0,
                 (3.0, 1.0 + r, 0.0), (3.0, 2.0 + r, 0.0), (1, 0, 0), "purple")
    b.place_edge(f"w_ht_{r}", "equilateral_triangle", 0,
                 (-2.0, 2.0 + r, 0.0), (-2.0, 1.0 + r, 0.0), (-1, 0, 0), "purple")

# =================================================================
# 3. 身体箱体 (z 0..1): 双立壁 + 尾板/头板 + 背板
# =================================================================
for y in range(5):
    b.wall_ew(f"bd_w_{y}", 0.0, y, 0, "orange")       # 西立壁
    b.wall_ew(f"bd_e_{y}", 1.0, y, 0, "orange")       # 东立壁
b.wall_ns("bd_tail", 0, 0.0, 0, "orange")             # 尾板 (y=0)
b.wall_ns("bd_head", 0, 5.0, 0, "orange")             # 头板 (y=5)
for y in range(5):
    b.flat(f"bd_bk_{y}", 0, y, 1.0, "yellow" if y % 2 else "orange")  # 背板

# =================================================================
# 4. 触角与头饰: 背板头段侧沿立 2 根等腰触角 + 前沿 1 片头饰
# =================================================================
b.spire_ew("ant_w", 0.0, 4, 1.0, "purple")            # 西触角
b.spire_ew("ant_e", 1.0, 4, 1.0, "purple")            # 东触角
b.crest_ns("head_crest", 0, 5.0, 1.0, "red")          # 头饰

# =================================================================
# 5. 眼斑: 前翅上沿各挂 1 枚六边形
# =================================================================
b.place_edge("spot_e", "hexagon", 0, (2.0, 5.0, 0.0), (3.0, 5.0, 0.0),
             (0, 1, 0), "yellow")
b.place_edge("spot_w", "hexagon", 0, (-3.0, 5.0, 0.0), (-2.0, 5.0, 0.0),
             (0, 1, 0), "yellow")

# =================================================================
# 教程步骤 (15 步)
# =================================================================
b.step(
    "铺设身体地板: 5 片灰色方板沿南北向连成中轴 (y 0..5)。",
    [f"bd_fl_{y}" for y in range(5)],
    tip="这条中轴就是蝴蝶的身体投影, 左右翅膀都从它长出来。",
)
b.step(
    "铺设东后翅: 4 片蓝青相间的方板贴着中轴右侧平铺 (y 1..3)。",
    ["e_hw_0_0", "e_hw_1_0", "e_hw_0_1", "e_hw_1_1"],
    highlight=["bd_fl_1", "bd_fl_2"],
    tip="蓝青棋盘格是后翅的花纹, 内沿与中轴板边整边吸合。",
)
b.step(
    "铺设东前翅内列: 2 片红粉方板接在后翅上方 (y 3..5 第一列)。",
    ["e_fw_0_0", "e_fw_0_1"],
    highlight=["e_hw_0_1"],
    tip="前翅比后翅大 —— 先铺紧贴身体的第一列。",
)
b.step(
    "铺完东前翅: 再向外接 4 片, 红粉棋盘格铺满 3 列。",
    ["e_fw_1_0", "e_fw_1_1", "e_fw_2_0", "e_fw_2_1"],
    highlight=["e_fw_0_0"],
    tip="每片新板至少与一片旧板整边相吸, 花纹要红粉交错。",
)
b.step(
    "铺设西后翅: 与东后翅镜像, 蓝青花纹左右对称。",
    ["w_hw_0_0", "w_hw_1_0", "w_hw_0_1", "w_hw_1_1"],
    highlight=["bd_fl_1", "e_hw_0_0"],
    tip="对照东翅摆放 —— 蝴蝶最美的就是完美对称。",
)
b.step(
    "铺设西前翅内列: 2 片红粉方板, 与东侧第一列镜像。",
    ["w_fw_0_0", "w_fw_0_1"],
    highlight=["w_hw_0_1"],
    tip="左右两边同步检查: 每一格颜色都应镜像相同。",
)
b.step(
    "铺完西前翅: 再向外接 4 片, 两扇前翅完全展开。",
    ["w_fw_1_0", "w_fw_1_1", "w_fw_2_0", "w_fw_2_1"],
    highlight=["w_fw_0_0"],
    tip="从头顶俯视: 红粉两大扇、蓝青两小扇, 翅膀已见雏形。",
)
b.step(
    "安装东侧翅尖: 4 片紫色等边三角形贴在东翅外沿, 尖端朝外。",
    ["e_ft_0", "e_ft_1", "e_ht_0", "e_ht_1"],
    highlight=["e_fw_2_0", "e_hw_1_0"],
    tip="三角尖让翅膀轮廓变得锋利飘逸, 底边整边吸翅外沿。",
)
b.step(
    "安装西侧翅尖: 与东侧镜像, 4 片紫色三角收边。",
    ["w_ft_0", "w_ft_1", "w_ht_0", "w_ht_1"],
    highlight=["w_fw_2_0"],
    tip="8 个翅尖装完, 蝴蝶的平面轮廓就完成了。",
)
b.step(
    "竖立身体西立壁: 5 片橙色正方形沿中轴左沿立起。",
    [f"bd_w_{y}" for y in range(5)],
    highlight=["bd_fl_0"],
    tip="立壁底边同时吸住身体地板边与西翅内沿 —— 一缝三吸。",
)
b.step(
    "竖立身体东立壁: 5 片橙色正方形与西立壁平行。",
    [f"bd_e_{y}" for y in range(5)],
    highlight=["bd_w_0"],
    tip="两道立壁夹出蝴蝶隆起的身体腔。",
)
b.step(
    "封尾板与头板: 身体两端各立 1 片橙色正方形。",
    ["bd_tail", "bd_head"],
    highlight=["bd_w_0", "bd_e_4"],
    tip="头尾一封, 身体四面围合 —— 只差背板了。",
)
b.step(
    "盖身体背板: 5 片橙黄相间的方板压在立壁顶上, 身体隆起完成。",
    [f"bd_bk_{y}" for y in range(5)],
    highlight=["bd_w_2", "bd_e_2"],
    tip="橙黄条纹就是蝴蝶的绒毛节环, 每片两长边都要吸牢。",
)
b.step(
    "立触角与头饰: 头段背板两侧沿立 2 根紫色等腰触角, "
    "前沿立 1 片红色三角头饰。",
    ["ant_w", "ant_e", "head_crest"],
    highlight=["bd_bk_4"],
    tip="触角底边同时吸背板侧边与立壁顶边, 又高又稳。",
)
b.step(
    "挂眼斑: 两扇前翅上沿各吸 1 枚黄色六边形眼斑, 大蝴蝶展翅!",
    ["spot_e", "spot_w"],
    highlight=["e_fw_1_1", "w_fw_1_1"],
    tip="六边形眼斑是蝴蝶吓退小鸟的\"大眼睛\" —— 也是你的收尾印章。",
)

b.finalize(
    model_id="butterfly_01",
    name="花园大蝴蝶",
    name_en="Butterfly 01",
    description=(
        "模型库第一个对称拼花生物: 四扇马赛克翅膀平展在花园地面 (前翅红粉"
        "棋盘、后翅蓝青棋盘、紫色三角翅尖收边), 中间隆起橙黄条纹的箱形身体, "
        "头顶两根紫色触角, 前翅上沿还各挂一枚六边形眼斑 —— 左右完全镜像, "
        "拼完从头顶俯视最美。"
    ),
    difficulty=3,
    tags=["自然", "昆虫", "对称拼花", "进阶"],
    min_pieces=48,
    min_steps=15,
)
