#!/usr/bin/env python3
"""生成模型 data/models/greenhouse_dome_01.json (穹顶温室)。

第三批模型 ④: 田园农业主题 —— 采光穹顶温室: 6x6 花园地块
(草甸 + 花圃 + 入口步道) 中央立起 3x3 玻璃温室 (透明墙板 +
绿色骨架转角, 南面留 1 格门洞), 屋面是一圈 8 片透明环形采光板
围出 1x1 天窗洞口, 洞口上再冠以 4 片等腰三角形合拢的采光穹顶;
园区四角花篱、东侧两株郁金香、西侧一只六边形雨水罐。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 花园地块 6x6 (草甸/花圃/步道)                            36 片
  - 温室墙体: 3x3 一圈 12 减门洞 1                           11 片
  - 环形采光屋面: 8 片透明方板围出 1x1 天窗                    8 片
  - 采光穹顶: 等腰四坡锥顶 4 片                                4 片
  - 花篱 x4 + 郁金香 x2 + 雨水罐 x1                            7 片
  合计 66 片, 16 个教程步骤, 5 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 环形屋面先放四角 (各坐两段墙顶), 再补四边中片; 门洞正上方
    的中片两侧整边吸住相邻角片 —— 负空间门洞由屋面自然成楣;
  - 穹顶 4 片等腰三角底边吸天窗四沿, 斜棱两两互吸自锁成环;
  - 全部装饰件底边整边吸花园格线, 竖直放置力矩为零。

用法: python3 tools/generate_greenhouse_dome.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import HEX_APOTHEM, ModelBuilder  # noqa: E402

b = ModelBuilder()

# =================================================================
# 1. 花园地块 6x6: 草甸绿, 花圃粉/红, 入口步道灰 (通向南门洞)
# =================================================================
FLOWER = {(0, 0), (5, 0), (0, 5), (5, 5), (1, 4), (4, 1)}
PATH = {(3, 0), (3, 1)}
for j in range(6):
    for i in range(6):
        if (i, j) in PATH:
            color = "gray"
        elif (i, j) in FLOWER:
            color = "pink"
        else:
            color = "green"
        b.flat(f"gd_{i}_{j}", i, j, 0.0, color)

# =================================================================
# 2. 温室墙体: 3x3 (x 2..5, y 2..5), 南面中段留门洞,
#    四角骨架绿色, 其余透明玻璃
# =================================================================
b.wall_ns("gw_s_w", 2, 2.0, 0, "green")              # 南墙西段
b.wall_ns("gw_s_e", 4, 2.0, 0, "green")              # 南墙东段 (中段 x 3..4 门洞)
for j in range(3):
    b.wall_ew(f"gw_e_{j}", 5.0, 2 + j, 0,
              "green" if j == 1 else "clear")        # 东墙
for i in range(3):
    b.wall_ns(f"gw_n_{i}", 2 + i, 5.0, 0,
              "clear" if i == 1 else "green")        # 北墙
for j in range(3):
    b.wall_ew(f"gw_w_{j}", 2.0, 2 + j, 0,
              "green" if j == 1 else "clear")        # 西墙

# =================================================================
# 3. 环形采光屋面 (z=1): 四角片 + 四边中片, 围出 1x1 天窗 (3..4, 3..4)
# =================================================================
RING_CORNERS = [("rf_sw", 2, 2), ("rf_se", 4, 2), ("rf_nw", 2, 4), ("rf_ne", 4, 4)]
RING_MIDS = [("rf_s", 3, 2), ("rf_w", 2, 3), ("rf_e", 4, 3), ("rf_n", 3, 4)]
for tid, i, j in RING_CORNERS + RING_MIDS:
    b.flat(tid, i, j, 1.0, "clear")

# =================================================================
# 4. 采光穹顶: 天窗洞口上的等腰四坡锥顶 (锥尖 z=1.866)
# =================================================================
DOME = b.hat4("dome", 3, 3, 1.0, "cyan", shape="isosceles_triangle")

# =================================================================
# 5. 花篱 + 郁金香 + 雨水罐
# =================================================================
b.crest_ns("hg_sw", 0, 0.0, 0.0, "pink")             # 南沿花篱西
b.crest_ns("hg_se", 5, 0.0, 0.0, "pink")             # 南沿花篱东
b.crest_ns("hg_nw", 0, 6.0, 0.0, "pink")             # 北沿花篱西
b.crest_ns("hg_ne", 5, 6.0, 0.0, "pink")             # 北沿花篱东
b.spire_ew("tulip_r", 6.0, 2, 0.0, "red")            # 东侧郁金香
b.spire_ew("tulip_y", 6.0, 3, 0.0, "yellow")
b.add("tank", "hexagon", (0.0, 2.5, HEX_APOTHEM), (90, 0, 90), "cyan")  # 雨水罐

# =================================================================
# 教程步骤 (16 步): 花园 -> 墙体 -> 环形屋面 -> 穹顶 -> 园艺
# =================================================================
b.step(
    "铺花园最南 1 排 6 片: 绿草甸、粉花圃, 灰色步道口开在正中。",
    [f"gd_{i}_0" for i in range(6)],
    tip="花园铺在桌面中央, 步道留在南面正中。",
)
b.step(
    "铺花园第 2 排 6 片: 灰色步道向北延伸, 直指未来的温室大门。",
    [f"gd_{i}_1" for i in range(6)],
    highlight=["gd_3_0"],
    tip="两片灰色步道连成入口小径。",
)
b.step(
    "铺花园第 3 排 6 片: 这一排就是温室南墙的地基。",
    [f"gd_{i}_2" for i in range(6)],
    highlight=["gd_3_1"],
    tip="步道尽头对准第 3 排正中 —— 门洞将开在那里。",
)
b.step(
    "铺花园第 4 排 6 片。",
    [f"gd_{i}_3" for i in range(6)],
    highlight=["gd_2_2"],
    tip="每片先对准一条边再松手, 地块中间不能留缝。",
)
b.step(
    "铺完花园最北 2 排 12 片 —— 6x6 园区就绪。",
    [f"gd_{i}_{j}" for j in range(4, 6) for i in range(6)],
    highlight=["gd_4_1"],
    tip="四角粉色花圃对称分布, 从上往下看像四朵大花。",
)
b.step(
    "立温室南墙: 门洞两侧各 1 片绿色骨架墙 (中段 x 3..4 留 1 格大门)。",
    ["gw_s_w", "gw_s_e"],
    highlight=["gd_3_1"],
    tip="底边吸花园格线 —— 门洞正对步道, 负空间就是入口。",
)
b.step(
    "立温室西墙 3 片: 上下透明玻璃, 中段绿色骨架。",
    ["gw_w_0", "gw_w_1", "gw_w_2"],
    highlight=["gw_s_w"],
    tip="转角竖边与南墙互吸, 玻璃面朝外。",
)
b.step(
    "立温室东墙 3 片, 与西墙镜像。",
    ["gw_e_0", "gw_e_1", "gw_e_2"],
    highlight=["gw_s_e"],
    tip="东西两面玻璃墙对称, 阳光可以整天照进温室。",
)
b.step(
    "立温室北墙 3 片, 墙体一圈合围 (只留南面门洞)。",
    ["gw_n_0", "gw_n_1", "gw_n_2"],
    highlight=["gw_w_2", "gw_e_2"],
    tip="四角竖边两两互吸后, 轻捏墙口应感觉整体联动。",
)
b.step(
    "屋面四角就位: 4 片透明方板压在墙顶四角, 每片同时坐住两段墙顶。",
    [tid for tid, _, _ in RING_CORNERS],
    highlight=["gw_s_w", "gw_n_0"],
    tip="角片是屋面的承重锚点, 四角先锁住。",
)
b.step(
    "补屋面四边中片: 4 片透明方板嵌进角片之间, 围出 1x1 天窗洞口。"
    "门洞正上方那片两侧整边吸住相邻角片 —— 屋面自然成楣。",
    [tid for tid, _, _ in RING_MIDS],
    highlight=[tid for tid, _, _ in RING_CORNERS],
    tip="中片放入时先对准两侧角片的边, 再轻轻按平。",
)
b.step(
    "起穹顶: 先立南北 2 片相对的等腰三角形, 底边吸天窗沿口。",
    ["dome_s", "dome_n"],
    highlight=["rf_s", "rf_n"],
    tip="两片先互相扶持着别松手 —— 马上就来另外两片。",
)
b.step(
    "穹顶合拢: 再补东西 2 片, 四条斜棱两两互吸, 锥尖在 1.87 高处自锁。",
    ["dome_e", "dome_w"],
    highlight=["dome_s", "dome_n"],
    tip="咔哒一声合拢成环 —— 越按越紧, 这就是穹顶的魔法。",
)
b.step(
    "种花篱: 园区南北两沿各立 2 片粉色等边三角形。",
    ["hg_sw", "hg_se", "hg_nw", "hg_ne"],
    highlight=["gd_0_0", "gd_5_5"],
    tip="花篱底边吸园区外沿格线, 四角对称。",
)
b.step(
    "栽郁金香: 东侧园沿立红黄两株等腰三角郁金香。",
    ["tulip_r", "tulip_y"],
    highlight=["gd_5_2", "gd_5_3"],
    tip="尖尖的花苞朝上, 底边吸格线即可站稳。",
)
b.step(
    "装雨水罐: 青色六边形立在西侧园沿, 收集屋面雨水浇花 —— 从南门望进去, "
    "天窗与穹顶把阳光洒满苗床, 穹顶温室开园!",
    ["tank"],
    highlight=["gd_0_2"],
    tip="底边整边吸住园沿格线, 大水罐稳稳立住。",
)

b.finalize(
    model_id="greenhouse_dome_01",
    name="穹顶温室",
    name_en="Dome Greenhouse 01",
    description=(
        "田园农业主题: 6x6 花园地块 (草甸、花圃与入口步道) 中央立起 3x3 玻璃"
        "温室 —— 透明墙板配绿色骨架转角, 南面留 1 格负空间门洞; 屋面用 8 片"
        "透明方板围出 1x1 天窗, 门洞上方的屋面片两侧整边吸角片自然成楣, "
        "天窗上再冠以 4 片等腰三角合拢的采光穹顶; 园区四角花篱、东侧红黄"
        "郁金香、西侧六边形雨水罐 —— 阳光洒满苗床, 开园!"
    ),
    difficulty=3,
    tags=["田园", "温室", "穹顶", "负空间", "进阶"],
    min_pieces=50,
    min_steps=16,
)
