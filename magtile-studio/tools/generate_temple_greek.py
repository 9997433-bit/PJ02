#!/usr/bin/env python3
"""生成模型 data/models/temple_greek_01.json (希腊神庙)。

建筑地标主题: 全库第一座周柱式古典神庙 —— 7x4 大理石台基上,
正背两面各 4 根金色方柱与两侧壁柱围出周柱回廊, 回廊顶板逐格
铺开 (柱位板压柱顶, 空档板铰内殿墙顶); 内殿 (Cella) 四面围合,
殿心立着金冠神像; 阁楼层沿内殿墙线退台升起, 四座直角三角扶壁
在回廊顶上锁定阁楼墙; 殿顶横板双端合龙盖住阁楼, 前后檐口点缀
金色檐饰三角, 正面檐口正中竖起一轮六边形太阳盘 —— 献给智慧
女神!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 正面朝南):
  - 台基: 前后沿方板 x14 + 中间两行 方板 x6 + 长板 x4          24 片
  - 外柱列: 正面方柱 4 + 背面方柱 4 + 两侧壁柱 4              12 片
  - 内殿墙: 前墙 5 + 后墙 5 + 两侧山墙 4 (z0..1)              14 片
  - 神像: 殿心立板 + 金色三角头冠                               2 片
  - 回廊顶板: 前带方板 7 + 后带方板 7 + 两侧方板 4 (z=1)       18 片
  - 阁楼层: 前墙 5 + 后墙 5 (z1..2)                           10 片
  - 扶壁: 直角三角斜撑 x4 (竖边吸阁楼墙缝, 横边吸顶板拼缝)      4 片
  - 殿顶: 横跨长板 x5 (每片短边双端压住前后阁楼墙顶)            5 片
  - 檐饰: 等边三角 x5 + 正面六边形太阳盘 x1                     6 片
  合计 95 片, 18 个教程步骤, 5 种磁力片形状 (迁移期不使用等腰片)。

物理规则要点 (通过 R1~R8 全部校验):
  - 全模型遵循 整边吸合 纪律: 柱底/墙脚一律踩在 1 格板边上,
    回廊顶用 1x1 方板逐格铺 (柱位板整边压柱顶, 空档板整边
    铰内殿墙顶, 相邻板间再整边互吸 —— 顶带锁成一环);
  - 阁楼墙脚正踩回廊顶板北缘拼缝 (即内殿墙延长线), 荷载顺墙
    身直落台基; 扶壁竖边吸阁楼墙侧缝、横边吸顶板拼缝;
  - 殿顶横板 (轴向 y) 南北短边分别整边压住前后阁楼墙顶 ——
    双端简支合龙成箱; 神像先于殿顶放入 (装配可达, 像顶 1.87
    < 殿顶 2.0);
  - 檐饰三角与太阳盘立在殿顶檐口整边上, 重心正压铰链线。

用法: python3 tools/generate_temple_greek.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

BASE = "gray"       # 台基
COL = "yellow"      # 柱列 (阳光大理石)
CELLA = "orange"    # 内殿墙
CEIL = "gray"       # 回廊顶板
ATTIC = "orange"    # 阁楼层
ROOF = "red"        # 殿顶 (陶瓦)
PED = "yellow"      # 檐饰
GOD = "purple"      # 神像

# =================================================================
# 1. 台基 7x4: 前后沿整行方板 (柱脚需要 1 格整边),
#    中间两行 方板+长板 混铺 (拼缝落在墙线上)
# =================================================================
for x in range(7):
    b.flat(f"base_s_{x}", x, 0, 0.0, BASE)          # 南沿行 y[0,1]
    b.flat(f"base_n_{x}", x, 3, 0.0, BASE)          # 北沿行 y[3,4]
for y in (1, 2):
    b.flat(f"base_w_{y}", 0, y, 0.0, BASE)          # [0,1]
    b.flat_rect(f"base_a_{y}", 1, y, 0.0, BASE)     # [1,3]
    b.flat(f"base_m_{y}", 3, y, 0.0, BASE)          # [3,4]
    b.flat_rect(f"base_b_{y}", 4, y, 0.0, BASE)     # [4,6]
    b.flat(f"base_e_{y}", 6, y, 0.0, BASE)          # [6,7]

# =================================================================
# 2. 外柱列 (z0..1): 正背面各 4 根, 两侧各 2 片壁柱
# =================================================================
for x in (0, 2, 4, 6):
    b.wall_ns(f"col_s_{x}", x, 0.0, 0, COL)         # 正面柱
    b.wall_ns(f"col_n_{x}", x, 4.0, 0, COL)         # 背面柱
for y in (1, 2):
    b.wall_ew(f"col_w_{y}", 0.0, y, 0, COL)         # 西壁柱
    b.wall_ew(f"col_e_{y}", 7.0, y, 0, COL)         # 东壁柱

# =================================================================
# 3. 内殿墙 (z0..1): 前后墙 + 两侧山墙, 围合 [1,6]x[1,3]
# =================================================================
for x in range(1, 6):
    b.wall_ns(f"cel_s_{x}", x, 1.0, 0, CELLA)       # 内殿前墙
    b.wall_ns(f"cel_n_{x}", x, 3.0, 0, CELLA)       # 内殿后墙
for y in (1, 2):
    b.wall_ew(f"cel_w_{y}", 1.0, y, 0, CELLA)       # 内殿西山墙
    b.wall_ew(f"cel_e_{y}", 6.0, y, 0, CELLA)       # 内殿东山墙

# =================================================================
# 4. 神像: 殿心立板 + 金色三角头冠 (先于殿顶放入)
# =================================================================
b.wall_ns("god_body", 3, 2.0, 0, GOD)               # 神像立板
b.crest_ns("god_head", 3, 2.0, 1.0, PED)            # 三角头冠

# =================================================================
# 5. 回廊顶板 (z=1): 1x1 方板逐格铺, 整边吸合锁成一环
# =================================================================
for x in range(7):
    b.flat(f"cl_s_{x}", x, 0, 1.0, CEIL)            # 前带 y[0,1]
    b.flat(f"cl_n_{x}", x, 3, 1.0, CEIL)            # 后带 y[3,4]
for y in (1, 2):
    b.flat(f"cl_w_{y}", 0, y, 1.0, CEIL)            # 西侧带 [0,1]
    b.flat(f"cl_e_{y}", 6, y, 1.0, CEIL)            # 东侧带 [6,7]

# =================================================================
# 6. 阁楼层 (z1..2): 沿内殿墙线退台升起
# =================================================================
for x in range(1, 6):
    b.wall_ns(f"at_s_{x}", x, 1.0, 1, ATTIC)        # 阁楼前墙
    b.wall_ns(f"at_n_{x}", x, 3.0, 1, ATTIC)        # 阁楼后墙

# =================================================================
# 7. 扶壁: 竖边吸阁楼墙侧缝, 横边吸回廊顶拼缝 (x=2, 4)
# =================================================================
for x in (2, 4):
    b.brace(f"bt_s_{x}", (float(x), 1.0, 1.0), "-y", COL)
    b.brace(f"bt_n_{x}", (float(x), 3.0, 1.0), "+y", COL)

# =================================================================
# 8. 殿顶 (z=2): 横板双端合龙, 盖住 [1,6]x[1,3]
# =================================================================
for x in range(1, 6):
    b.flat_rect(f"roof_{x}", x, 1, 2.0, ROOF, axis="y")

# =================================================================
# 9. 檐饰: 前檐 2 + 后檐 3 等边三角, 正面檐口正中六边形太阳盘
# =================================================================
for x in (1, 5):
    b.crest_ns(f"ant_s_{x}", x, 1.0, 2.0, PED)      # 前檐饰
for x in (1, 3, 5):
    b.crest_ns(f"ant_n_{x}", x, 3.0, 2.0, PED)      # 后檐饰
b.place_edge("sun_disc", "hexagon", 4,
             (3.0, 1.0, 2.0), (4.0, 1.0, 2.0), (0.0, 0.0, 1.0), COL)

# =================================================================
# 教程步骤 (18 步)
# =================================================================
b.step(
    "铺台基南沿: 7 片灰色方板一字排开 (y[0,1])。",
    [f"base_s_{x}" for x in range(7)],
    tip="前沿必须用 1 格方板 —— 每根柱脚都要踩到一条整板边。",
)
b.step(
    "铺台基中段: 两行 方板+长板 混铺, 拼缝正落在内殿墙线上。",
    [f"base_{k}_{y}" for y in (1, 2) for k in ("w", "a", "m", "b", "e")],
    highlight=["base_s_0", "base_s_6"],
    tip="拼缝就是墙线 —— 台基铺对了, 后面的墙才有得吸。",
)
b.step(
    "铺台基北沿: 再排 7 片方板, 台基合拢成 7x4 大平台。",
    [f"base_n_{x}" for x in range(7)],
    highlight=["base_w_2", "base_e_2"],
    tip="南北两沿对称 —— 神庙的台基必须一丝不苟。",
)
b.step(
    "立正面柱列: 台基南沿立 4 根金色方柱, 逢一格空一格。",
    [f"col_s_{x}" for x in (0, 2, 4, 6)],
    highlight=["base_s_0", "base_s_6"],
    tip="柱底整边吸方板南边 —— 柱间空档是古典柱廊的呼吸。",
)
b.step(
    "立背面柱列: 台基北沿同样立 4 根, 与正面一一相对。",
    [f"col_n_{x}" for x in (0, 2, 4, 6)],
    highlight=["base_n_0", "base_n_6"],
    tip="前后柱严格对位 —— 回廊顶板要同时压住它们。",
)
b.step(
    "立两侧壁柱: 东西沿各 2 片连立, 柱列围合一圈。",
    ["col_w_1", "col_w_2", "col_e_1", "col_e_2"],
    highlight=["col_s_0", "col_n_6"],
    tip="侧面用连续壁柱 —— 神庙侧影更厚重。",
)
b.step(
    "砌内殿前墙: 柱列之内一格, 5 片橙墙踩着台基拼缝连成内殿正立面。",
    [f"cel_s_{x}" for x in range(1, 6)],
    highlight=["base_s_2", "col_s_2"],
    tip="内殿与柱列之间留出 1 格回廊 —— 这就是周柱式。",
)
b.step(
    "砌内殿后墙: 北侧同样 5 片, 与前墙夹出殿身。",
    [f"cel_n_{x}" for x in range(1, 6)],
    highlight=["cel_s_1", "base_n_2"],
    tip="前后墙都踩在台基拼缝上 —— 荷载直入地坪。",
)
b.step(
    "砌内殿山墙: 东西两端各 2 片, 内殿四面围合。",
    ["cel_w_1", "cel_w_2", "cel_e_1", "cel_e_2"],
    highlight=["cel_s_1", "cel_n_5"],
    tip="山墙封边 —— 殿心从此只从正门进出。",
)
b.step(
    "请神像入殿: 殿心拼缝上立紫色神像板, 顶上加金色三角头冠。",
    ["god_body", "god_head"],
    highlight=["base_m_1", "base_m_2"],
    tip="趁殿顶未盖先请神像 —— 盖顶之后手就伸不进去了。",
)
b.step(
    "盖回廊顶前带: 7 片方板逐格铺过南回廊 —— 柱位板整边压柱顶, "
    "空档板整边铰内殿墙顶。",
    [f"cl_s_{x}" for x in range(7)],
    highlight=["col_s_0", "cel_s_3"],
    tip="柱与墙各担一半 —— 相邻板间再整边互吸, 前带锁成整条。",
)
b.step(
    "盖回廊顶后带: 北回廊同样 7 片合拢。",
    [f"cl_n_{x}" for x in range(7)],
    highlight=["col_n_0", "cel_n_3"],
    tip="前后带对称受力 —— 回廊顶是全庙的力学枢纽。",
)
b.step(
    "盖两侧顶带: 东西各 2 片方板, 整边压壁柱顶与山墙顶 —— 回廊顶"
    "锁成完整一环。",
    ["cl_w_1", "cl_w_2", "cl_e_1", "cl_e_2"],
    highlight=["col_w_1", "cel_e_1"],
    tip="一片板铰住两道墙 —— 环形顶带越锁越紧。",
)
b.step(
    "起阁楼前墙: 沿内殿墙线在顶板北缘拼缝上退台立 5 片橙墙。",
    [f"at_s_{x}" for x in range(1, 6)],
    highlight=["cl_s_2", "cel_s_1"],
    tip="墙脚踩的拼缝正是下层墙线 —— 荷载顺墙身直落台基。",
)
b.step(
    "起阁楼后墙: 北线同样 5 片, 阁楼层前后合抱。",
    [f"at_n_{x}" for x in range(1, 6)],
    highlight=["at_s_1", "cl_n_2"],
    tip="阁楼层收进一圈 —— 古典建筑的退台韵律。",
)
b.step(
    "锁扶壁: 4 片金色直角三角, 竖边吸阁楼墙侧缝、横边吸回廊顶拼缝。",
    ["bt_s_2", "bt_s_4", "bt_n_2", "bt_n_4"],
    highlight=["at_s_2", "at_n_4"],
    tip="三角刚性节点 —— 阁楼墙从此纹丝不动。",
)
b.step(
    "盖殿顶: 5 片红色横板依次合龙, 南北短边整边压住前后阁楼墙顶。",
    [f"roof_{x}" for x in range(1, 6)],
    highlight=["at_s_1", "at_n_5"],
    tip="横板双端简支 —— 殿顶把阁楼锁成箱形。",
)
b.step(
    "装檐饰升太阳盘: 前后檐口点上 5 片金色三角, 正面檐口正中竖起"
    "一轮六边形太阳盘 —— 献给智慧女神!",
    ["ant_s_1", "ant_s_5", "ant_n_1", "ant_n_3", "ant_n_5", "sun_disc"],
    highlight=["roof_1", "roof_5"],
    tip="三角与太阳盘重心正压檐口铰链 —— 朝阳每天第一个照亮它。",
)

b.finalize(
    model_id="temple_greek_01",
    name="希腊神庙",
    name_en="Greek Temple 01",
    description=(
        "全库第一座周柱式古典神庙: 7x4 大理石台基上, 前后柱列与两侧壁柱"
        "围出周柱回廊, 回廊顶板逐格整边吸合锁成一环 (柱位板压柱顶, 空档"
        "板铰内殿墙顶); 内殿四面围合、殿心立着金冠神像, 阁楼层沿内殿墙线"
        "退台升起、四座直角三角扶壁锁定, 殿顶横板双端合龙, 前后檐口点缀"
        "金色檐饰三角, 正面檐口正中竖起一轮六边形太阳盘 —— 献给智慧女神!"
    ),
    difficulty=4,
    tags=["建筑地标", "神庙", "古典建筑", "柱廊", "进阶"],
    min_pieces=90,
    min_steps=18,
)
