#!/usr/bin/env python3
"""生成模型 data/models/marching_band_01.json (军乐队巡游)。

音乐/乐器主题: 全库第一支军乐队 —— 结构主角是 "跨街门式拱 +
轮基大鼓花车 + 乐手方阵": 彩旗拱门两柱双层, 顶排三片方片以
竖边互吸连排跨过街口 (中片悬在洞口上方, 全靠两侧竖边铰链,
重力平行铰链轴力矩为零 —— 门式刚架一课); 大鼓花车用两片
车轮底座作侧板, 双长板甲板压顶, 120g 大方片鼓面骑甲板中缝
立起, 四只直角三角斜撑在甲板上前后对撑; 六名乐手三排两列
(双层墙身肩并肩竖边互吸成网格), 前中排戴等边号帽, 后排扛
等腰大旗 (旗尖 4.0 全场最高); 东端检阅台墙环平台, 乐队指挥
执等腰指挥杖居高临下; 街角两面巡游路标彩旗。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 巡游向西过拱门):
  - 巡游街面 (x [0,8], y [0,3], 花车让出 x [4,6] 车位): 19 片
  - 彩旗拱门 (x=1): 双柱两层 x4 + 顶排 x3 + 彩旗 x3          10 片
  - 乐手方阵 (x [2,4], y 0/1/2): 6 名 x (双层墙身 + 帽/旗)   18 片
  - 大鼓花车 (x [4,6]): 车轮底座侧板 x2 + 甲板长板 x2
    + 大方片鼓面 x1 + 斜撑 x4                                  9 片
  - 检阅台 (x [6,8], y [0,2]): 墙环 x8 + 台面 x4
    + 指挥墙身 x1 + 等腰指挥杖 x1                             14 片
  - 巡游路标彩旗 x2: 立墙 + 等边彩旗                           4 片
  合计 74 片, 14 个教程步骤, 7 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, strict 档同样全绿):
  - 拱门顶排中片悬在洞口上方: 两条竖边铰链分别与左右邻片
    整边互吸, 重力平行竖直铰链轴 -> 力矩为零、纯剪传力;
    柱-顶排-柱-地面闭合成大环, 剪任一条铰链力都能绕行;
  - 花车鼓面 (120g) 底边与甲板中缝 2=2 整边互吸 (一线双吸),
    重心正压铰链; 斜撑直角边分别咬甲板短边与鼓面竖边;
    甲板长边整边压车轮底座顶边 (2=2), 花车与街面、方阵、
    检阅台四处竖边互吸 —— 全场单一连通体;
  - 乐手肩并肩、层层竖边互吸成 2x2x3 网格, 处处成环;
  - 号帽/大旗/指挥杖重心正压支承边, 纯压零力矩。

用法: python3 tools/generate_marching_band.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

STREET = "gray"     # 街面
LANE = "red"        # 巡游红毯车道
ARCH = "red"        # 拱门柱
ARCH_TOP = "yellow" # 拱门顶排
FLAG = "red"        # 拱门彩旗
UNIFORM = "blue"    # 乐手制服
HAT = "yellow"      # 等边号帽
BANNER = "red"      # 等腰大旗
CART = "green"      # 车轮底座侧板
DECK = "orange"     # 花车甲板
DRUM = "red"        # 大鼓鼓面
BRACE = "gray"      # 斜撑
STAND = "purple"    # 检阅台
MAJOR = "blue"      # 指挥墙身
BATON = "yellow"    # 指挥杖
MARKER = "orange"   # 路标立柱
MFLAG = "yellow"    # 路标彩旗

# =================================================================
# 1. 巡游街面 (x [0,8], y [0,3]): 花车让出 x [4,6] 车位
# =================================================================
for y in (0, 1):
    for x in (0, 1, 2, 3, 6, 7):
        b.flat(f"st_{x}_{y}", x, y, 0.0, LANE if y == 1 and x < 4 else STREET)
for x in (0, 1, 2, 3):
    b.flat(f"st_{x}_2", x, 2, 0.0, STREET)
b.flat_rect("st_deckrow", 4, 2, 0.0, STREET)
b.flat("st_6_2", 6, 2, 0.0, STREET)
b.flat("st_7_2", 7, 2, 0.0, STREET)

# =================================================================
# 2. 彩旗拱门 (x=1 立面): 双柱两层 + 顶排三片 + 彩旗
# =================================================================
b.wall_ew("ar_s_lo", 1.0, 0, 0, ARCH)
b.wall_ew("ar_s_hi", 1.0, 0, 1, ARCH)
b.wall_ew("ar_n_lo", 1.0, 2, 0, ARCH)
b.wall_ew("ar_n_hi", 1.0, 2, 1, ARCH)
b.wall_ew("ar_top_s", 1.0, 0, 2, ARCH_TOP)
b.wall_ew("ar_top_n", 1.0, 2, 2, ARCH_TOP)
b.wall_ew("ar_top_m", 1.0, 1, 2, ARCH_TOP)
b.crest_ew("ar_fl_s", 1.0, 0, 3.0, FLAG)
b.crest_ew("ar_fl_m", 1.0, 1, 3.0, FLAG)
b.crest_ew("ar_fl_n", 1.0, 2, 3.0, FLAG)

# =================================================================
# 3. 乐手方阵 (x [2,4], 三排两列): 双层墙身 + 号帽/大旗
# =================================================================
for rank, y in (("f", 0), ("m", 1)):
    for x in (2, 3):
        b.wall_ns(f"mu_{rank}{x}_lo", x, float(y), 0, UNIFORM)
        b.wall_ns(f"mu_{rank}{x}_hi", x, float(y), 1, UNIFORM)
        b.crest_ns(f"mu_{rank}{x}_hat", x, float(y), 2.0, HAT)
for x in (2, 3):
    b.wall_ns(f"mu_r{x}_lo", x, 2.0, 0, UNIFORM)
    b.wall_ns(f"mu_r{x}_hi", x, 2.0, 1, UNIFORM)
    b.spire_ns(f"mu_r{x}_flag", x, 2.0, 2.0, BANNER)

# =================================================================
# 4. 大鼓花车 (x [4,6], y [0,2]): 车轮侧板 + 甲板 + 鼓面 + 斜撑
# =================================================================
b.add("cart_s", "wheel_base", (5.0, 0.0, 0.5), (90, 0, 0), CART)
b.add("cart_n", "wheel_base", (5.0, 2.0, 0.5), (90, 0, 0), CART)
b.flat_rect("deck_s", 4, 0, 1.0, DECK)
b.flat_rect("deck_n", 4, 1, 1.0, DECK)
b.add("drum", "large_square", (5.0, 1.0, 2.0), (90, 0, 0), DRUM)
b.brace("dbr_w_s", (4.0, 1.0, 1.0), "-y", BRACE)
b.brace("dbr_w_n", (4.0, 1.0, 1.0), "+y", BRACE)
b.brace("dbr_e_s", (6.0, 1.0, 1.0), "-y", BRACE)
b.brace("dbr_e_n", (6.0, 1.0, 1.0), "+y", BRACE)

# =================================================================
# 5. 检阅台 (x [6,8], y [0,2]): 墙环 + 台面 + 指挥
# =================================================================
b.wall_ns("rv_s_w", 6, 0.0, 0, STAND)
b.wall_ns("rv_s_e", 7, 0.0, 0, STAND)
b.wall_ns("rv_n_w", 6, 2.0, 0, STAND)
b.wall_ns("rv_n_e", 7, 2.0, 0, STAND)
b.wall_ew("rv_w_s", 6.0, 0, 0, STAND)
b.wall_ew("rv_w_n", 6.0, 1, 0, STAND)
b.wall_ew("rv_e_s", 8.0, 0, 0, STAND)
b.wall_ew("rv_e_n", 8.0, 1, 0, STAND)
for x in (6, 7):
    for y in (0, 1):
        b.flat(f"rv_top_{x}_{y}", x, y, 1.0, STAND)
b.wall_ew("major", 7.0, 0, 1, MAJOR)
b.spire_ew("baton", 7.0, 0, 2.0, BATON)

# =================================================================
# 6. 巡游路标彩旗 x2 (西街角)
# =================================================================
b.wall_ns("mk_s", 0, 0.0, 0, MARKER)
b.crest_ns("mk_s_fl", 0, 0.0, 1.0, MFLAG)
b.wall_ns("mk_n", 0, 3.0, 0, MARKER)
b.crest_ns("mk_n_fl", 0, 3.0, 1.0, MFLAG)

# =================================================================
# 教程步骤 (14 步)
# =================================================================
b.step(
    "铺街面北排 (y [2,3]): 7 片一线贯通, 中段用长板锁边。",
    ["st_0_2", "st_1_2", "st_2_2", "st_3_2", "st_deckrow", "st_6_2", "st_7_2"],
    tip="先铺这条贯通的北排 —— 后面每一排都从它往南接。",
)
b.step(
    "铺红毯车道 (y [1,2]): 6 片贴着北排往南接, 红毯直通拱门。",
    [f"st_{x}_1" for x in (0, 1, 2, 3, 6, 7)],
    highlight=["st_deckrow"],
    tip="车道中段 (x [4,6]) 空着 —— 那是大鼓花车的车位。",
)
b.step(
    "铺街面南排 (y [0,1]): 6 片, 花车车位继续空着。",
    [f"st_{x}_0" for x in (0, 1, 2, 3, 6, 7)],
    highlight=["st_2_1"],
    tip="东西两段都咬着车道南沿 —— 街面始终连成一整片。",
)
b.step(
    "立拱门双柱: 每柱两层, 骑街面拼缝踩稳。",
    ["ar_s_lo", "ar_s_hi", "ar_n_lo", "ar_n_hi"],
    highlight=["st_0_0", "st_0_1"],
    tip="柱底边与街面拼缝整边互吸, 上层竖边再吸下层。",
)
b.step(
    "架拱门顶排, 插三面彩旗: 中片全靠两侧竖边铰链悬跨洞口。",
    ["ar_top_s", "ar_top_n", "ar_top_m", "ar_fl_s", "ar_fl_m", "ar_fl_n"],
    highlight=["ar_s_hi", "ar_n_hi"],
    tip="重力平行竖直铰链轴 -> 力矩为零; 柱-顶排-柱锁成门式大环。",
)
b.step(
    "前排乐手就位 (y=0): 双层墙身肩并肩, 戴等边号帽。",
    ["mu_f2_lo", "mu_f3_lo", "mu_f2_hi", "mu_f3_hi", "mu_f2_hat", "mu_f3_hat"],
    highlight=["st_2_0"],
    tip="两名乐手竖边互吸 —— 方阵的第一排要站得最齐。",
)
b.step(
    "中排乐手就位 (y=1): 同样双层 + 号帽。",
    ["mu_m2_lo", "mu_m3_lo", "mu_m2_hi", "mu_m3_hi", "mu_m2_hat", "mu_m3_hat"],
    highlight=["mu_f2_lo"],
    tip="前后排踩相邻拼缝, 层层竖边互吸 —— 方阵成网格处处成环。",
)
b.step(
    "后排旗手就位 (y=2): 双层墙身扛等腰大旗, 旗尖 4.0 全场最高。",
    ["mu_r2_lo", "mu_r3_lo", "mu_r2_hi", "mu_r3_hi", "mu_r2_flag", "mu_r3_flag"],
    highlight=["mu_m2_lo"],
    tip="大旗底边整边骑墙顶, 重心正压铰链 —— 旗高而不晃。",
)
b.step(
    "花车进场: 两片车轮底座作侧板落进车位, 双长板甲板压顶。",
    ["cart_s", "cart_n", "deck_s", "deck_n"],
    highlight=["st_deckrow", "mu_f3_lo"],
    tip="甲板长边与侧板顶边 2=2 整边互吸; 侧板竖边咬住方阵与街面。",
)
b.step(
    "竖大鼓: 120g 大方片鼓面骑上甲板中缝。",
    ["drum"],
    highlight=["deck_s", "deck_n"],
    tip="底边与甲板中缝 2=2 一线双吸, 重心正压铰链 —— 力矩为零。",
)
b.step(
    "装鼓面斜撑: 直角三角在甲板上一前一后对撑。",
    ["dbr_w_s", "dbr_w_n", "dbr_e_s", "dbr_e_n"],
    highlight=["drum"],
    tip="斜撑咬甲板短边又咬鼓面竖边 —— 花车过坎鼓不倒。",
)
b.step(
    "砌检阅台墙环 (x [6,8], y [0,2]): 8 片踩拼缝闭环。",
    ["rv_s_w", "rv_s_e", "rv_w_s", "rv_w_n", "rv_n_w", "rv_n_e", "rv_e_s", "rv_e_n"],
    highlight=["st_6_0", "st_6_1"],
    tip="检阅台西墙竖边同时咬住花车侧板 —— 全场连成一体。",
)
b.step(
    "铺检阅台台面, 指挥登台执杖: 4 + 2 片。",
    ["rv_top_6_0", "rv_top_7_0", "rv_top_6_1", "rv_top_7_1", "major", "baton"],
    highlight=["rv_s_w"],
    tip="台面每片压两段墙顶; 指挥杖重心正压墙顶, 与后排大旗齐高。",
)
b.step(
    "插巡游路标彩旗 x2 —— 军乐队巡游出发!",
    ["mk_s", "mk_s_fl", "mk_n", "mk_n_fl"],
    highlight=["ar_fl_m"],
    tip="路标立在街角拼缝上 —— 乐队向西, 穿过拱门!",
)

b.finalize(
    model_id="marching_band_01",
    name="军乐队巡游",
    name_en="Marching Band 01",
    description=(
        "全库第一支军乐队: 彩旗拱门顶排三片方片竖边互吸连排"
        "跨街 (中片悬在洞口上方, 重力平行竖直铰链轴力矩为零,"
        " 柱-顶排-柱-地面闭合成门式大环); 大鼓花车以两片车轮"
        "底座作侧板、双长板甲板 2=2 整边压顶, 120g 大方片鼓面"
        "骑甲板中缝立起、四只直角三角斜撑前后对撑; 六名乐手"
        "三排两列双层墙身肩并肩竖边互吸成网格, 前中排戴等边"
        "号帽、后排扛等腰大旗 (旗尖 4.0 全场最高); 东端检阅台"
        "墙环平台上乐队指挥执等腰指挥杖。门式拱、轮基花车、"
        "网格方阵 —— 一场巡游三种结构队形。"
    ),
    difficulty=3,
    tags=["音乐", "乐队", "巡游", "花车", "进阶"],
    min_pieces=72,
    min_steps=14,
)
