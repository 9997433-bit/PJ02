#!/usr/bin/env python3
"""生成模型 data/models/post_office_01.json (邮局)。

城市生活主题: 中央邮局 —— 两层营业大厅 (双门框方大门 + 二层四扇
窗格方) 前出四柱门廊 (双柱托横楣、门廊平顶与主楼平顶同层合缝),
檐口一排等边齿饰; 东侧下沉式装卸场: 高台月台 + 30 度手推车坡道;
西侧一辆车轮底座邮车 (长方形厢壁 + 门框方后门 + 透明挡风玻璃)
正待发车; 路口还立着一座嵌窗格方投信口的绿色邮筒。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 主楼地坪 [0,4]x[0,3]: 4x3 方板                            12 片
  - 门前广场 (y=-1): 4 片 + 东侧路板 2 片                       6 片
  - 一层: 前墙 (双门框方 + 方墙 x2) + 西/东/北墙              14 片
  - 二层: 前墙窗格方 x4 + 西/东/北墙                          14 片
  - 主楼平顶: 4x3 方板                                         12 片
  - 檐口齿饰: 前檐等边三角 x4                                   4 片
  - 门廊: 双柱 x2 层 + 横楣 + 门廊平顶 4                        9 片
  - 装卸场: 场地 4 + 三面台墙 6 + 月台板 4 + 手推车坡道 1      15 片
  - 邮车: 车轮底座 1 + 长方形厢壁 x2 + 后门 + 挡风 + 车顶 2     7 片
  - 邮车泊位: 连接板 2                                          2 片
  - 邮筒: 筒身 + 窗格方投信口                                   2 片
  合计 97 片, 19 个教程步骤, 6 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验):
  - 门廊横楣两端竖边吸双柱上层竖边; 门廊平顶北沿吸主楼二层墙顶,
    两端压双柱顶, 与主楼平顶同层合缝连成大环;
  - 月台板西沿借主楼东墙顶边 (共墙受力), 坡道顶边吸月台沿口、
    坡尾自然落地;
  - 邮车厢壁用长方形整边吸车轮底座长边 (等长贴合), 挡风玻璃底边
    同时吸底座短边与泊位板边 (双路径, 无单点失效)。

用法: python3 tools/generate_post_office.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

SLAB = "gray"       # 地坪
WALL = "green"      # 主楼墙 (邮政绿)
DOOR = "blue"       # 门框方
WIN = "clear"       # 窗格方
ROOF = "gray"       # 平顶
TOOTH = "yellow"    # 檐口齿饰
PORCH = "clear"     # 门廊
DOCK = "orange"     # 装卸场
VAN = "blue"        # 邮车
GLASS = "clear"     # 挡风玻璃
BOX = "green"       # 邮筒

# =================================================================
# 1. 地坪 / 门前广场 / 东侧路板
# =================================================================
for x in range(4):
    for y in range(3):
        b.flat(f"sl_{x}_{y}", x, y, 0.0, SLAB)
for x in range(4):
    b.flat(f"fc_{x}", x, -1, 0.0, SLAB)
b.flat("rd_0", 4, -1, 0.0, SLAB)
b.flat("rd_1", 5, -1, 0.0, SLAB)

# =================================================================
# 2. 主楼一层: 前墙 (双门框方) + 西/东/北墙
# =================================================================
b.wall_ns("g_f_0", 0, 0.0, 0, WALL)
b.add("g_door0", "door_frame", (1.5, 0.0, 0.5), (90, 0, 0), DOOR)
b.add("g_door1", "door_frame", (2.5, 0.0, 0.5), (90, 0, 0), DOOR)
b.wall_ns("g_f_3", 3, 0.0, 0, WALL)
for y in range(3):
    b.wall_ew(f"g_w_{y}", 0.0, y, 0, WALL)
    b.wall_ew(f"g_e_{y}", 4.0, y, 0, WALL)
for x in range(4):
    b.wall_ns(f"g_n_{x}", x, 3.0, 0, WALL)

# =================================================================
# 3. 主楼二层: 前墙四扇窗格方 + 西/东/北墙
# =================================================================
for x in range(4):
    b.add(f"u_win_{x}", "window_square", (x + 0.5, 0.0, 1.5), (90, 0, 0), WIN)
for y in range(3):
    b.wall_ew(f"u_w_{y}", 0.0, y, 1, WALL)
    b.wall_ew(f"u_e_{y}", 4.0, y, 1, WALL)
for x in range(4):
    b.wall_ns(f"u_n_{x}", x, 3.0, 1, WALL)

# =================================================================
# 4. 主楼平顶 (z=2) + 檐口齿饰
# =================================================================
for x in range(4):
    for y in range(3):
        b.flat(f"rf_{x}_{y}", x, y, 2.0, ROOF)
for x in range(4):
    b.crest_ns(f"th_{x}", x, 0.0, 2.0, TOOTH)

# =================================================================
# 5. 门廊 (y=-1 立面): 双柱 x2 层 + 横楣 + 门廊平顶 (z=2)
# =================================================================
b.wall_ns("pc_w1", 0, -1.0, 0, PORCH)
b.wall_ns("pc_w2", 0, -1.0, 1, PORCH)
b.wall_ns("pc_e1", 3, -1.0, 0, PORCH)
b.wall_ns("pc_e2", 3, -1.0, 1, PORCH)
b.lintel_ns("pc_lin", 1, -1.0, 1, WALL)
for x in range(4):
    b.flat(f"pc_r_{x}", x, -1, 2.0, PORCH)

# =================================================================
# 6. 装卸场 (东侧 [4,6]x[1,3]): 场地 + 三面台墙 + 月台板 + 坡道
# =================================================================
for x in range(4, 6):
    for y in range(1, 3):
        b.flat(f"dk_f_{x}_{y}", x, y, 0.0, SLAB)
for x in range(4, 6):
    b.wall_ns(f"dk_s_{x}", x, 1.0, 0, DOCK)
    b.wall_ns(f"dk_n_{x}", x, 3.0, 0, DOCK)
for y in range(1, 3):
    b.wall_ew(f"dk_e_{y}", 6.0, y, 0, DOCK)
for x in range(4, 6):
    for y in range(1, 3):
        b.flat(f"dk_p_{x}_{y}", x, y, 1.0, DOCK)
b.ramp("dk_ramp", "+x", 6.0, 1, 1.0, DOCK)     # 手推车坡道, 坡尾落地

# =================================================================
# 7. 邮车 (西侧 [-3,-1]x[0,1]) + 泊位连接板
# =================================================================
b.flat("vp_0", -1, 0, 0.0, SLAB)
b.flat("vp_1", -1, 1, 0.0, SLAB)
b.add("van_ch", "wheel_base", (-2.0, 0.5, 0.0), (0, 0, 0), VAN)
b.lintel_ns("van_s", -3, 0.0, 0, VAN)          # 南厢壁 (长方形整边吸底座长边)
b.lintel_ns("van_n", -3, 1.0, 0, VAN)          # 北厢壁
b.add("van_rd", "door_frame", (-3.0, 0.5, 0.5), (90, 0, 90), VAN)   # 后门
b.wall_ew("van_ws", -1.0, 0, 0, GLASS)         # 挡风玻璃
b.flat("van_r0", -3, 0, 1.0, VAN)              # 车顶
b.flat("van_r1", -2, 0, 1.0, VAN)

# =================================================================
# 8. 邮筒 (东侧路口): 筒身 + 窗格方投信口
# =================================================================
b.wall_ew("bx_0", 6.0, -1, 0, BOX)
b.add("bx_slot", "window_square", (6.0, -0.5, 1.5), (90, 0, 90), WIN)

# =================================================================
# 教程步骤 (19 步)
# =================================================================
b.step(
    "铺设主楼地坪南两排: 8 片灰色方板 (y 0..2)。",
    [f"sl_{x}_{y}" for x in range(4) for y in (0, 1)],
    tip="中央邮局的地坪要方方正正 —— 先铺南边两排。",
)
b.step(
    "补齐地坪北排: 4 片, 4x3 地坪完工。",
    [f"sl_{x}_2" for x in range(4)],
    highlight=["sl_0_1"],
    tip="12 片地坪板缝缝相吸。",
)
b.step(
    "铺设门前广场与东侧路板: 广场 4 片 + 路板 2 片。",
    [f"fc_{x}" for x in range(4)] + ["rd_0", "rd_1"],
    highlight=["sl_0_0", "sl_3_0"],
    tip="广场向东延伸出路板 —— 那是邮筒的位置。",
)
b.step(
    "竖立一层前墙: 两扇蓝色门框方大门居中, 两侧各 1 片邮政绿方墙。",
    ["g_f_0", "g_door0", "g_door1", "g_f_3"],
    highlight=["sl_1_0", "sl_2_0"],
    tip="双开大门是邮局的排面 —— 门框方外框照常整边吸合。",
)
b.step(
    "竖立一层西墙与东墙: 各 3 片, 与前墙拐角互吸。",
    ["g_w_0", "g_w_1", "g_w_2", "g_e_0", "g_e_1", "g_e_2"],
    highlight=["g_f_0", "g_f_3"],
    tip="东墙将来还要借给装卸月台当靠山 —— 一墙两用。",
)
b.step(
    "竖立一层北墙: 4 片, 一层围合成筒。",
    [f"g_n_{x}" for x in range(4)],
    highlight=["g_w_2", "g_e_2"],
    tip="四角竖边互吸, 箱形筒抗风又抗晃。",
)
b.step(
    "二层前墙装窗: 4 扇窗格方对缝叠上前墙与大门。",
    [f"u_win_{x}" for x in range(4)],
    highlight=["g_door0", "g_door1"],
    tip="营业大厅的高窗 —— 阳光洒在长长的柜台上。",
)
b.step(
    "二层围合西东墙: 各 3 片对缝叠齐。",
    ["u_w_0", "u_w_1", "u_w_2", "u_e_0", "u_e_1", "u_e_2"],
    highlight=["u_win_0"],
    tip="上下两层墙横边完全对齐 —— 错缝会让楼变弱。",
)
b.step(
    "二层北墙到顶: 4 片, 主楼骨架完成。",
    [f"u_n_{x}" for x in range(4)],
    highlight=["u_w_2", "u_e_2"],
    tip="两层楼的方筒立稳了, 就等封顶。",
)
b.step(
    "铺设主楼平顶外圈: 10 片灰色顶板沿四沿压住墙顶边。",
    [f"rf_{x}_{y}" for x in range(4) for y in range(3)
     if x in (0, 3) or y in (0, 2)],
    highlight=["u_n_1", "u_win_1"],
    tip="每片顶板的外沿边都要吸牢正下方的墙顶边。",
)
b.step(
    "补平顶中间 2 片并立檐口齿饰: 前檐一排 4 片黄色等边三角。",
    ["rf_1_1", "rf_2_1"] + [f"th_{x}" for x in range(4)],
    highlight=["rf_0_0"],
    tip="齿饰立在前檐铰链线上, 重心正压 —— 邮局的皇冠。",
)
b.step(
    "竖立门廊双柱下层: 透明方柱 2 片分立大门两侧的广场南沿。",
    ["pc_w1", "pc_e1"],
    highlight=["fc_0", "fc_3"],
    tip="柱底边吸广场板南沿 —— 门廊要正对双开大门。",
)
b.step(
    "双柱加高并架横楣: 柱各叠 1 片, 绿色横楣两端竖边吸双柱竖边。",
    ["pc_w2", "pc_e2", "pc_lin"],
    highlight=["pc_w1", "pc_e1"],
    tip="横楣是三边受力的过梁 —— 先叠柱、再合龙。",
)
b.step(
    "铺门廊平顶: 4 片透明顶板, 北沿吸主楼二层墙顶、两端压双柱顶, "
    "与主楼平顶同层合缝。",
    [f"pc_r_{x}" for x in range(4)],
    highlight=["pc_lin", "rf_0_0"],
    tip="门廊顶与主楼顶在同一层拼成大环 —— 环越大越稳。",
)
b.step(
    "铺设装卸场场地并围台墙: 场地 4 片 + 南/北/东台墙 6 片, "
    "西面借主楼东墙。",
    [f"dk_f_{x}_{y}" for x in range(4, 6) for y in range(1, 3)]
    + ["dk_s_4", "dk_s_5", "dk_n_4", "dk_n_5", "dk_e_1", "dk_e_2"],
    highlight=["g_e_1"],
    tip="共墙不重复 —— 月台的西面就是主楼的东墙。",
)
b.step(
    "铺月台板并搭手推车坡道: 4 片月台板压台墙顶, 坡道顶边吸月台"
    "东沿、坡尾自然落地。",
    [f"dk_p_{x}_{y}" for x in range(4, 6) for y in range(1, 3)] + ["dk_ramp"],
    highlight=["dk_e_1", "g_e_1"],
    tip="月台板一边搭主楼、一边搭台墙 —— 包裹小车从坡道上下。",
)
b.step(
    "拼装邮车底盘与厢壁: 泊位板 2 片接通地坪, 车轮底座落位, "
    "长方形厢壁整边吸底座长边, 后门与挡风玻璃合拢。",
    ["vp_0", "vp_1", "van_ch", "van_s", "van_n", "van_rd", "van_ws"],
    highlight=["sl_0_0"],
    tip="挡风玻璃底边同时吸底座短边与泊位板边 —— 双路径受力。",
)
b.step(
    "盖邮车车顶: 2 片蓝色车顶板, 两端分别吸后门顶边与挡风顶边。",
    ["van_r0", "van_r1"],
    highlight=["van_rd", "van_ws"],
    tip="车顶合上, 邮车整装待发。",
)
b.step(
    "立起邮筒: 绿色筒身立路板东沿, 窗格方投信口叠上, 中央邮局开门!",
    ["bx_0", "bx_slot"],
    highlight=["rd_1"],
    tip="把写好的明信片投进投信口 —— 叮, 寄往全世界。",
)

b.finalize(
    model_id="post_office_01",
    name="邮局",
    name_en="Post Office",
    description=(
        "中央邮局: 两层营业大厅开双门框方大门、二层嵌四扇窗格方高窗, "
        "四柱门廊托横楣、门廊平顶与主楼平顶同层合缝成大环, 前檐一排黄色"
        "等边齿饰; 东侧装卸月台借主楼东墙受力, 30 度手推车坡道直落场地; "
        "西侧车轮底座邮车 (长方形厢壁 + 门框方后门 + 透明挡风) 整装待发, "
        "路口绿色邮筒嵌窗格方投信口 —— 叮, 寄往全世界。"
    ),
    difficulty=4,
    tags=["城市", "职业体验", "建筑", "车辆", "进阶"],
    min_pieces=97,
    min_steps=19,
)
