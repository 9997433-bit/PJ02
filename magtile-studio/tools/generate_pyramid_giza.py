#!/usr/bin/env python3
"""生成模型 data/models/pyramid_giza_01.json (吉萨金字塔)。

建筑地标系列 (主技法 T12 层叠退台 + T14 斜撑 + T04 锥顶合拢):
逐层居中收分的三级阶梯金字塔 —— 5x5 沙漠地台之上, 两圈退台
平台 (3x3 -> 1x1 洞口) 层层收分, 顶上四片等边三角形合拢成
金色锥形压顶石 (Benben); 四角直角三角护坡斜撑双边吸合,
四座方尖碑立在地台四角, 一条长方形神道从东侧直通塔底。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 沙漠地台 5x5 (黄橙沙丘棋盘)                              25 片
  - 第一级塔身: 3x3 周圈墙 (z 0..1) + 四角护坡斜撑 (T14)      12 + 4 片
  - 第一级退台平台 3x3 (z=1)                                  9 片
  - 第二级塔身: 1x1 周圈墙 (z 1..2)                            4 片
  - 金色压顶石: 等边四坡锥顶合拢 (锥尖 z=2.71)                  4 片
  - 四角方尖碑 (等腰三角) + 东侧神道 (长方形 x2)               4 + 2 片
  合计 64 片, 17 个教程步骤。

物理规则要点 (通过 R1~R8 全部校验):
  - 每级退台平台四周全部坐在下级墙顶边上, 中央片四邻互吸, 无悬挑
    (T12 的收分量恰好保证上级墙体全部落在下级平台的接地凸包内);
  - 护坡斜撑竖直角边吸塔身墙角竖边、水平直角边吸地台网格线, 双边吸合;
  - 压顶石四片等边三角形底边吸第二级墙顶, 斜棱两两互吸自锁成环。

用法: python3 tools/generate_pyramid_giza.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

# =================================================================
# 1. 沙漠地台 5x5: 黄橙沙丘棋盘
# =================================================================
for j in range(5):
    for i in range(5):
        b.flat(f"s_{i}_{j}", i, j, 0.0, "yellow" if (i + j) % 2 == 0 else "orange")

# =================================================================
# 2. 第一级塔身: 3x3 周圈墙 (x 1..4, y 1..4, z 0..1)
# =================================================================
for i in range(3):
    b.wall_ns(f"t1_s_{i}", 1 + i, 1.0, 0, "orange")
for j in range(3):
    b.wall_ew(f"t1_e_{j}", 4.0, 1 + j, 0, "orange")
for i in range(3):
    b.wall_ns(f"t1_n_{i}", 1 + i, 4.0, 0, "orange")
for j in range(3):
    b.wall_ew(f"t1_w_{j}", 1.0, 1 + j, 0, "orange")

# 四角护坡斜撑 (T14): 竖直角边吸塔身墙角竖边, 水平直角边吸地台网格线
BRACES = [
    ("bt_sw", (1.0, 1.0, 0.0), "-x"),
    ("bt_se", (4.0, 1.0, 0.0), "-y"),
    ("bt_ne", (4.0, 4.0, 0.0), "+x"),
    ("bt_nw", (1.0, 4.0, 0.0), "+y"),
]
for tid, corner, hdir in BRACES:
    b.brace(tid, corner, hdir, "red")

# =================================================================
# 3. 第一级退台平台 3x3 (z=1): 四周坐在第一级墙顶上
# =================================================================
for j in range(3):
    for i in range(3):
        b.flat(f"p1_{i}_{j}", 1 + i, 1 + j, 1.0, "yellow" if (i + j) % 2 == 0 else "orange")

# =================================================================
# 4. 第二级塔身: 1x1 周圈墙 (x 2..3, y 2..3, z 1..2)
# =================================================================
b.wall_ns("t2_s", 2, 2.0, 1, "orange")
b.wall_ew("t2_w", 2.0, 2, 1, "yellow")
b.wall_ns("t2_n", 2, 3.0, 1, "orange")
b.wall_ew("t2_e", 3.0, 2, 1, "yellow")

# 金色压顶石: 等边四坡锥顶 (锥尖 z = 2.707)
CAP_IDS = b.hat4("cap", 2, 2, 2.0, "yellow", shape="equilateral_triangle")

# =================================================================
# 5. 四角方尖碑 + 东侧神道
# =================================================================
b.spire_ns("ob_sw", 0, 0.0, 0.0, "purple")
b.spire_ns("ob_se", 4, 0.0, 0.0, "purple")
b.spire_ns("ob_nw", 0, 5.0, 0.0, "purple")
b.spire_ns("ob_ne", 4, 5.0, 0.0, "purple")

b.flat_rect("cw_in", 5, 2, 0.0, "gray", axis="x")    # 神道内段 [5,7]x[2,3]
b.flat_rect("cw_out", 7, 2, 0.0, "gray", axis="x")   # 神道外段 [7,9]x[2,3]

# =================================================================
# 教程步骤 (17 步)
# =================================================================
for j in range(5):
    b.step(
        f"铺设沙漠地台第 {j + 1} 排: 5 片正方形平放并排, 黄橙相间, "
        "相邻边对齐吸合。" if j else
        "在平整桌面上铺设沙漠地台第 1 排: 5 片正方形平放并排, 黄橙相间。",
        [f"s_{i}_{j}" for i in range(5)],
        highlight=[f"s_{i}_{j - 1}" for i in range(5)] if j else [],
        tip="第一排沿桌面边缘摆直, 东侧要留出神道的位置。" if j == 0
            else "新一排每片先吸住上一排的边再落位, 地台中间不能留缝。",
    )
b.step(
    "第一级塔身南墙: 沿地台中央 3x3 区域的南缘立 3 片橙色正方形, "
    "底边吸地台网格线, 相邻竖边互吸。",
    [f"t1_s_{i}" for i in range(3)],
    highlight=["s_1_0", "s_3_0"],
    tip="塔身立在地台正中央 —— 四周各留一圈沙地, 退台的影子会落在那里。",
)
b.step(
    "第一级塔身西墙: 3 片, 西南转角与南墙竖边互吸。",
    [f"t1_w_{j}" for j in range(3)],
    highlight=["t1_s_0"],
    tip="先立转角那片再顺墙向北推进。",
)
b.step(
    "第一级塔身北墙: 3 片, 西北转角吸住西墙。",
    [f"t1_n_{i}" for i in range(3)],
    highlight=["t1_w_2"],
    tip="每片底边吸地台网格线、侧边吸邻片, 双重吸合。",
)
b.step(
    "第一级塔身东墙: 3 片补齐, 第一级四面合围。",
    [f"t1_e_{j}" for j in range(3)],
    highlight=["t1_n_2", "t1_s_2"],
    tip="最后一片放入前检查四角: 每个转角的两片都应互相吸牢。",
)
b.step(
    "安装四角护坡斜撑: 红色直角三角形竖直角边吸塔身墙角竖边, "
    "水平直角边贴住地台网格线, 呈风车状分布。",
    [tid for tid, _, _ in BRACES],
    highlight=["t1_s_0", "t1_e_0", "t1_n_2", "t1_w_2"],
    tip="斜撑要两条直角边同时吸合 —— 它们模拟的是金字塔的护坡, 也真的在抗侧力。",
)
b.step(
    "第一级退台平台第 1 排: 3 片正方形坐上南墙顶, 边缘同时吸墙顶边与邻片。",
    [f"p1_{i}_0" for i in range(3)],
    highlight=[f"t1_s_{i}" for i in range(3)],
    tip="这就是层叠退台: 平台比地台整整缩进一圈。",
)
b.step(
    "退台平台第 2 排: 3 片, 中央那片是第二级塔身的地基。",
    [f"p1_{i}_1" for i in range(3)],
    highlight=[f"p1_{i}_0" for i in range(3)],
    tip="中央片四边都要与邻片吸合, 上面还要再起一级。",
)
b.step(
    "退台平台第 3 排: 3 片补齐, 第一级封顶完成。",
    [f"p1_{i}_2" for i in range(3)],
    highlight=[f"p1_{i}_1" for i in range(3)],
    tip="从侧面平视: 塔身应已呈现出清晰的第一级台阶。",
)
b.step(
    "第二级塔身: 平台正中立 1x1 周圈墙共 4 片, 橙黄相间, 四角竖边两两互吸。",
    ["t2_s", "t2_w", "t2_n", "t2_e"],
    highlight=["p1_1_1"],
    tip="第二级再收进一圈 —— 阶梯金字塔的轮廓出来了。",
)
b.step(
    "盖上金色压顶石: 4 片等边三角形底边分别吸住第二级墙顶四边, "
    "斜棱两两互吸, 合拢成锥形塔尖 (Benben 石)。",
    CAP_IDS,
    highlight=["t2_s", "t2_n", "t2_w", "t2_e"],
    tip="先立两片相对的, 再补另外两片; 四条斜棱吸合成环后极其稳固。",
)
b.step(
    "竖立四角方尖碑: 4 片紫色等腰三角形分别立在地台四角边缘, 塔尖朝天。",
    ["ob_sw", "ob_se", "ob_nw", "ob_ne"],
    highlight=["s_0_0", "s_4_0", "s_0_4", "s_4_4"],
    tip="方尖碑只需底边吸住地台边缘就能站稳, 捏住尖角轻放。",
)
b.step(
    "铺设东侧神道: 2 片灰色长方形从地台东缘一路向东铺出 —— 法老的葬礼队伍"
    "将沿它走向金字塔。吉萨金字塔落成!",
    ["cw_in", "cw_out"],
    highlight=["s_4_2"],
    tip="神道短边先吸住地台东缘, 第二片再向东延伸; 完成后从神道尽头平视全塔。",
)

b.finalize(
    model_id="pyramid_giza_01",
    name="吉萨金字塔",
    name_en="Pyramid of Giza 01",
    description=(
        "逐层居中收分的三级阶梯金字塔: 5x5 沙漠地台上, 3x3 塔身与退台平台、"
        "1x1 第二级层层收分, 顶上四片等边三角形合拢成金色压顶石; 四角红色"
        "护坡斜撑双边吸合抗侧力, 四座方尖碑守望四角, 一条神道从东侧直通"
        "塔底。层叠退台的收分节奏与锥顶合拢的自锁环, 一课双技法。"
    ),
    difficulty=3,
    tags=["金字塔", "建筑地标", "层叠退台", "进阶"],
    min_pieces=45,
    min_steps=16,
)
