#!/usr/bin/env python3
"""生成模型 data/models/sheep_farm_01.json (剪毛牧场)。

农场/农业主题批 4/4: 全库第一座畜牧牧场 (库里此前只有 chicken_coop
的禽舍), 也是全库第一次"讲完一个流程"的农活叙事 —— 剪羊毛前后:
石砌羊圈里一只没剪的大绵羊蓬松雪白 (透明片=羊毛), 剪毛台上一只
剪完的羊通体粉红 (少了一身毛, 竟然小了一圈还高了一台), 台边两座
剪下的羊毛堆成小山, 栏外小羊羔排队等着轮到自己。结构上与
elephant_pavilion_01 的小象 (立颈方头 + 长鼻坡道) 刻意区分:
绵羊没有脖子 —— 方头直接"骑"在羊背东沿上 (底边'背板短边 +
体墙顶边'一线双吸), 双耳从头顶拼缝向两侧 45 度张开, 尾巴骑西沿;
剪毛台是 1x1 木箱台, 粉羊的四面体墙再骑上台顶四沿 (每面墙
'台顶沿 + 台墙顶'一线双吸), 动物摞在家具上 —— 这也是第一次。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 圈门朝南):
  - 草场 7x5: 方板 + 长板混铺 (绿草/橙土路)                  26 片
  - 石羊圈 (x [1,5], y [1,4]): 方墙 x13 + 木门框方 x1         14 片
  - 大绵羊 (圈内): 体环 x4 + 背板 + 方头 + 双耳 + 尾巴          9 片
  - 小羊羔 (栏外): 体环 x4 + 背板 + 脸蛋等边 x1                 6 片
  - 剪毛台: 木箱环 x4 + 台顶 x1                                 5 片
  - 粉羊 (台上): 体环 x4 + 背板 + 脸蛋等边 x1                   6 片
  - 羊毛山 x2: 等边四坡锥 x4 各自锁成环                         8 片
  合计 74 片, 15 个教程步骤, 4 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 绵羊方头: 底边"背板短边 + 体墙顶边"一线双吸 (两条独立
    磁力连接, 剪断任一条另一条仍锁着它);
  - 双耳: 两片等边三角从头顶拼缝向两侧 45 度张开 (底边共吸
    一条线、彼此再互吸), 单耳力矩 2.7 << strict 抗弯预算 35;
  - 粉羊骑台: 四面体墙每片"台顶沿 + 台墙顶"一线双吸, 台上
    再合环 —— 头顶 2.87 触发 R8 高层检查, 闭环拓扑天然通过;
  - 羊圈墙/尾巴/脸蛋骑缝骑沿, 重心正压铰链线力矩为零;
  - 羊毛山四坡锥四条斜棱两两互吸自锁成环。

用法: python3 tools/generate_sheep_farm_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

COS45 = 0.7071068
TRI_H = 0.866025
EAR = round(TRI_H * COS45, 6)          # 45 度张开的耳朵投影 0.612372

b = ModelBuilder()

GRASS = "green"      # 草场
TRAIL = "orange"     # 土路
STONE = "gray"       # 石砌羊圈
GATE = "orange"      # 圈门 (木)
WOOL = "clear"       # 羊毛 (蓬松雪白)
SKIN = "pink"        # 剪完毛的羊
FACE = "gray"        # 羊脸
DECK = "orange"      # 剪毛台 (木)


def sheep_box(prefix, x0, y0, z0, color, base_z_ids=None):
    """1x2 羊身躯: 前后长楣 + 左右方墙合环 + 背板压顶 (朝向东西)。"""
    b.lintel_ns(f"{prefix}_s", x0, y0, z0, color)
    b.lintel_ns(f"{prefix}_n", x0, y0 + 1.0, z0, color)
    b.wall_ew(f"{prefix}_w", x0, y0, z0, color)
    b.wall_ew(f"{prefix}_e", x0 + 2.0, y0, z0, color)
    b.flat_rect(f"{prefix}_back", x0, y0, z0 + 1.0, color)


# =================================================================
# 1. 草场 7x5 (x [0,7], y [0,5]): 拼缝纪律 —— 羊圈墙线/羊脚线处
#    必须有等长的单位田板边。
# =================================================================
# 南场院 (y [0,1]): 剪毛台位 + 门前土路 + 羊毛堆场
b.flat("g_0_0", 0, 0, 0.0, GRASS)                  # 剪毛台位
b.flat("g_1_0", 1, 0, 0.0, TRAIL)                  # 门前土路
b.flat("g_2_0", 2, 0, 0.0, GRASS)                  # 羊毛山 A 位
b.flat("g_3_0", 3, 0, 0.0, GRASS)                  # 羊毛山 B 位
b.flat("g_4_0", 4, 0, 0.0, GRASS)
b.flat_rect("g_56_0", 5, 0, 0.0, GRASS)
# 圈西草地
b.flat("g_0_1", 0, 1, 0.0, GRASS)
b.flat("g_0_2", 0, 2, 0.0, GRASS)
b.flat("g_0_3", 0, 3, 0.0, GRASS)
# 圈内: 土路 + 羊床草地
b.flat_rect("g_gate_in", 1, 1, 0.0, TRAIL, axis="y")   # [1,2]x[1,3] 圈内路
b.flat("g_1_3", 1, 3, 0.0, TRAIL)
b.flat_rect("g_bed_s", 2, 1, 0.0, GRASS)               # [2,4]x[1,2]
b.flat_rect("g_bed_m", 2, 2, 0.0, GRASS)               # 大绵羊脚下
b.flat_rect("g_bed_n", 2, 3, 0.0, GRASS)
b.flat_rect("g_e_in", 4, 1, 0.0, GRASS, axis="y")      # [4,5]x[1,3]
b.flat("g_4_3", 4, 3, 0.0, GRASS)
# 北草场 (y [4,5])
b.flat_rect("g_01_4", 0, 4, 0.0, GRASS)
b.flat("g_2_4", 2, 4, 0.0, GRASS)
b.flat("g_3_4", 3, 4, 0.0, GRASS)
b.flat_rect("g_45_4", 4, 4, 0.0, GRASS)
b.flat("g_6_4", 6, 4, 0.0, GRASS)
# 东草场: 小羊羔的排队区
b.flat("g_5_1", 5, 1, 0.0, GRASS)
b.flat("g_5_2", 5, 2, 0.0, GRASS)
b.flat_rect("g_56_3", 5, 3, 0.0, GRASS)
b.flat("g_6_1", 6, 1, 0.0, TRAIL)                  # 羔羊排队的小路
b.flat("g_6_2", 6, 2, 0.0, GRASS)                  # 小羊羔脚下

# =================================================================
# 2. 石羊圈 (x [1,5], y [1,4], 高 1): 方墙合环, 南面木门
# =================================================================
b.wall_ns("pen_s_1", 1, 1.0, 0, STONE)
b.add("pen_gate", "door_frame", (2.5, 1.0, 0.5), (90, 0, 0), GATE)
b.wall_ns("pen_s_3", 3, 1.0, 0, STONE)
b.wall_ns("pen_s_4", 4, 1.0, 0, STONE)
for y in (1, 2, 3):
    b.wall_ew(f"pen_w_{y}", 1.0, y, 0, STONE)
    b.wall_ew(f"pen_e_{y}", 5.0, y, 0, STONE)
for x in (1, 2, 3, 4):
    b.wall_ns(f"pen_n_{x}", x, 4.0, 0, STONE)

# =================================================================
# 3. 大绵羊 (圈内 x [2,4], y [2,3]): 透明羊毛体环 + 背板 +
#    方头骑东沿 + 双耳 45 度 + 尾巴骑西沿
# =================================================================
sheep_box("shA", 2, 2.0, 0, WOOL)
b.wall_ew("shA_head", 4.0, 2, 1, FACE)             # 方头 (背板短边+体墙顶一线双吸)
b.place_tri("shA_ear_e", "equilateral_triangle",
            (4.0, 2.0, 2.0), (4.0, 3.0, 2.0),
            (round(4.0 + EAR, 6), 2.5, round(2.0 + EAR, 6)), SKIN)
b.place_tri("shA_ear_w", "equilateral_triangle",
            (4.0, 3.0, 2.0), (4.0, 2.0, 2.0),
            (round(4.0 - EAR, 6), 2.5, round(2.0 + EAR, 6)), SKIN)
b.crest_ew("shA_tail", 2.0, 2, 1.0, WOOL)          # 尾巴骑西沿

# =================================================================
# 4. 小羊羔 (栏外 x [6,7], y [2,3]): 1x1 迷你体环 + 背板 + 脸蛋
# =================================================================
b.wall_ns("lamb_s", 6, 2.0, 0, WOOL)
b.wall_ns("lamb_n", 6, 3.0, 0, WOOL)
b.wall_ew("lamb_w", 6.0, 2, 0, WOOL)
b.wall_ew("lamb_e", 7.0, 2, 0, WOOL)
b.flat("lamb_back", 6, 2, 1.0, WOOL)
b.crest_ew("lamb_face", 7.0, 2, 1.0, FACE)         # 脸蛋骑东沿 (望着大门)

# =================================================================
# 5. 剪毛台 (x [0,1], y [0,1]): 1x1 木箱台
# =================================================================
b.wall_ns("dk_s", 0, 0.0, 0, DECK)
b.wall_ns("dk_n", 0, 1.0, 0, DECK)
b.wall_ew("dk_w", 0.0, 0, 0, DECK)
b.wall_ew("dk_e", 1.0, 0, 0, DECK)
b.flat("dk_top", 0, 0, 1.0, DECK)

# =================================================================
# 6. 粉羊 (台上 z 1..2): 四面体墙骑台顶四沿, 台上合环 + 背板 + 脸蛋
# =================================================================
b.wall_ns("shB_s", 0, 0.0, 1, SKIN)
b.wall_ns("shB_n", 0, 1.0, 1, SKIN)
b.wall_ew("shB_w", 0.0, 0, 1, SKIN)
b.wall_ew("shB_e", 1.0, 0, 1, SKIN)
b.flat("shB_back", 0, 0, 2.0, SKIN)
b.crest_ns("shB_face", 0, 1.0, 2.0, SKIN)          # 脸蛋骑北沿 (望着羊圈)

# =================================================================
# 7. 羊毛山 x2: 剪下的羊毛堆成等边四坡小锥
# =================================================================
b.hat4("wool_a", 2, 0, 0.0, WOOL, shape="equilateral_triangle")
b.hat4("wool_b", 3, 0, 0.0, WOOL, shape="equilateral_triangle")

# =================================================================
# 教程步骤 (15 步)
# =================================================================
b.step(
    "铺南场院: 剪毛台位、门前土路与羊毛堆场一字排开。",
    ["g_0_0", "g_1_0", "g_2_0", "g_3_0", "g_4_0", "g_56_0"],
    tip="牧场的一天从南场院开始 —— 台位和堆场都在这条线上。",
)
b.step(
    "铺圈西草地与圈内地坪: 橙色是圈门进来的土路, 绿色是羊床。",
    ["g_0_1", "g_0_2", "g_0_3", "g_gate_in", "g_1_3",
     "g_bed_s", "g_bed_m", "g_bed_n", "g_e_in", "g_4_3"],
    highlight=["g_1_0"],
    tip="羊床三片长板咬缝 —— 大绵羊的四只脚全踩在这些缝上。",
)
b.step(
    "铺北草场与东草场: 小羊羔的排队小路在东边。",
    ["g_01_4", "g_2_4", "g_3_4", "g_45_4", "g_6_4",
     "g_5_1", "g_5_2", "g_56_3", "g_6_1", "g_6_2"],
    highlight=["g_e_in"],
    tip="7x5 草场合拢 —— 每条拼缝都是圈墙与羊脚的地基。",
)
b.step(
    "砌羊圈南墙 + 装木门: 3 片石墙加 1 扇门框方, 门正对土路。",
    ["pen_s_1", "pen_gate", "pen_s_3", "pen_s_4"],
    highlight=["g_1_0", "g_gate_in"],
    tip="门框方物理上按实心方片拼接 —— 剪完毛从这扇门出去。",
)
b.step(
    "砌羊圈西东墙: 各 3 片, 与南墙四角竖边互咬。",
    ["pen_w_1", "pen_w_2", "pen_w_3", "pen_e_1", "pen_e_2", "pen_e_3"],
    highlight=["pen_s_1", "pen_s_4"],
    tip="拐角一咬, 石墙就从'一排片'变成了'一圈栏'。",
)
b.step(
    "砌羊圈北墙: 4 片合环, 石羊圈关得上门了。",
    ["pen_n_1", "pen_n_2", "pen_n_3", "pen_n_4"],
    highlight=["pen_w_3", "pen_e_3"],
    tip="四面合环处处成圈 —— 顽皮的羊也拱不开。",
)
b.step(
    "拼大绵羊身躯: 透明羊毛片前后长楣 + 左右方墙合环 (透明 ="
    " 蓬松雪白的毛)。",
    ["shA_s", "shA_n", "shA_w", "shA_e"],
    highlight=["g_bed_m"],
    tip="羊脚踩着羊床拼缝, 四角竖边互吸 —— 身躯处处成环。",
)
b.step(
    "盖羊背 + 装方头: 背板压顶, 方头骑上羊背东沿 —— 绵羊没有"
    "脖子, 头直接从毛里探出来。",
    ["shA_back", "shA_head"],
    highlight=["shA_e"],
    tip="头的底边'背板短边+体墙顶边'一线双吸 —— 两条保险。",
)
b.step(
    "竖双耳 + 安尾巴: 两片粉色等边从头顶拼缝向两侧 45 度张开,"
    " 小尾巴骑羊背西沿。",
    ["shA_ear_e", "shA_ear_w", "shA_tail"],
    highlight=["shA_head"],
    tip="双耳底边共吸一条线、彼此再互吸 —— 单耳力矩只有 2.7。",
)
b.step(
    "拼小羊羔身躯: 栏外 1x1 迷你体环, 排在小路尽头。",
    ["lamb_s", "lamb_n", "lamb_w", "lamb_e"],
    highlight=["g_6_2", "g_6_1"],
    tip="小羊羔个头只有妈妈一半 —— 但结构一样处处成环。",
)
b.step(
    "盖羔背 + 装脸蛋: 背板压顶, 灰色小脸骑东沿望着圈门。",
    ["lamb_back", "lamb_face"],
    highlight=["lamb_e"],
    tip="别急, 排队 —— 下一个就轮到你。",
)
b.step(
    "搭剪毛台: 1x1 木箱环 + 台顶压顶, 剪毛师傅的工作台。",
    ["dk_s", "dk_n", "dk_w", "dk_e", "dk_top"],
    highlight=["g_0_0"],
    tip="台顶四边全吸墙顶 —— 抬羊上台也纹丝不动。",
)
b.step(
    "粉羊上台: 四面粉色体墙骑上台顶四沿, 台上合环。",
    ["shB_s", "shB_n", "shB_w", "shB_e"],
    highlight=["dk_top"],
    tip="每片墙'台顶沿+台墙顶'一线双吸 —— 动物第一次摞上家具。",
)
b.step(
    "盖粉羊背 + 装脸蛋: 剪完毛通体粉红, 脸蛋骑北沿望着羊圈。",
    ["shB_back", "shB_face"],
    highlight=["shB_n"],
    tip="少了一身毛小了一圈, 站上台反而最高 (头顶 2.87)。",
)
b.step(
    "堆羊毛山: 剪下的羊毛堆成两座四坡小锥 —— 收工!",
    ["wool_a_s", "wool_a_e", "wool_a_n", "wool_a_w",
     "wool_b_s", "wool_b_e", "wool_b_n", "wool_b_w"],
    highlight=["shB_back", "g_2_0"],
    tip="四条斜棱两两互吸自锁成环 —— 今年的毛真厚, 装车喽!",
)

b.finalize(
    model_id="sheep_farm_01",
    name="剪毛牧场",
    name_en="Sheep Farm 01",
    description=(
        "只用核心九片型的畜牧牧场, 讲完'剪羊毛'一整个流程: 石砌"
        "羊圈里一只没剪的大绵羊蓬松雪白 (透明片=羊毛, 身躯处处"
        "成环), 方头不借脖子直接骑羊背东沿 ('背板短边+体墙顶边'"
        "一线双吸), 双耳从头顶拼缝向两侧 45 度张开 (单耳力矩 2.7"
        " 远小于预算); 剪毛台上一只剪完的羊通体粉红 —— 四面体墙"
        "每片'台顶沿+台墙顶'一线双吸, 动物第一次摞上家具, 头顶"
        " 2.87 全场最高; 台边两座剪下的羊毛四坡自锁堆成小山, 栏外"
        "小羊羔 1x1 迷你体环排队等着轮到自己 —— 今年的毛真厚!"
    ),
    difficulty=3,
    tags=["田园", "农场", "农业", "牧场", "动物世界", "进阶"],
    min_pieces=74,
    min_steps=15,
)
