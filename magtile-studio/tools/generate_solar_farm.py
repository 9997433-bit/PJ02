#!/usr/bin/env python3
"""生成模型 data/models/solar_farm_01.json (光伏阵列).

工程结构主题: 全库第一座太阳能电站 —— 绿色田野上两排共 6 片
蓝色光伏板以 30 度仰角朝南列阵: 每片板顶边整边吸在自己的
灰色支架墙顶上、坡尾贴地生根 (顶铰链 + 接地斜撑), 排距 2 格
互不遮挡; 东侧橙色逆变器房亮着红色告警灯, 隔墙相邻的黄色
储能电池柜共用一面墙, 东北角监测杆挑起透明塔尖直指 3 格
高空, 西南两面黄色围栏把守 —— 并网发电, 绿电入城!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 板面朝南):
  - 田野地坪 7x5: 南北长板收边 + 中两行方板咬缝              26 片
  - 光伏支架: 灰色立墙 x6 (两排各 3, 底边整边吸方板格边)       6 片
  - 光伏板: 30 度长板 x6 (顶边整边吸支架顶, 坡尾接地)          6 片
  - 逆变器房: 立墙闭环 x4 + 方板顶 + 红色告警灯三角             6 片
  - 储能电池柜: 立墙 x3 (与逆变器房共用一面墙) + 方板顶         4 片
  - 监测杆: 方墙 x1 + 透明等腰塔尖 x1 (尖端 3.0)                2 片
  - 围栏: 黄色等边三角 x3 (西面 2 + 南面 1)                     3 片
  合计 53 片, 13 个教程步骤, 5 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验, default + strict 双档):
  - 每片光伏板独立受力: 顶边与支架墙顶等长整边贴合 (铰链),
    坡尾自然落地成斜撑 —— 越压越稳, 6 片互不依赖;
  - 排距 2 格: 后排坡尾落在 y=2.27, 与前排支架墙 (y=2) 不碰
    (真实光伏电站的防遮挡排距在这里变成防碰撞排距);
  - 电池柜与逆变器房共用隔墙 (一片顶两用), 两环相扣冗余充足;
  - 监测杆尖端 3.0 触发 R8 高层检查: 杆上仅塔尖 1 片
    (重心正压铰链), 全模型零警告。

用法: python3 tools/generate_solar_farm.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

FIELD = "green"     # 田野
ROAD = "gray"       # 检修道
RACK = "gray"       # 光伏支架
PANEL = "blue"      # 光伏板
HUT = "orange"      # 逆变器房
LAMP = "red"        # 告警灯
BATT = "yellow"     # 储能电池柜
MAST = "gray"       # 监测杆
TIP = "clear"       # 塔尖
FENCE = "yellow"    # 围栏

# =================================================================
# 1. 田野地坪 7x5: 南沿检修道 + 中两行方板 (支架咬缝行)
# =================================================================
for y, color in ((0, ROAD), (1, FIELD)):
    b.flat_rect(f"fd_a_{y}", 0, y, 0.0, color)      # [0,2]
    b.flat_rect(f"fd_b_{y}", 2, y, 0.0, color)      # [2,4]
    b.flat_rect(f"fd_c_{y}", 4, y, 0.0, color)      # [4,6]
    b.flat(f"fd_d_{y}", 6, y, 0.0, color)           # [6,7]
for y in (2, 3):
    for x in range(7):
        b.flat(f"fd_{x}_{y}", x, y, 0.0, FIELD)     # 方板行
b.flat_rect("fd_a_4", 0, 4, 0.0, FIELD)             # [0,2]
b.flat_rect("fd_b_4", 2, 4, 0.0, FIELD)             # [2,4]
b.flat_rect("fd_c_4", 4, 4, 0.0, FIELD)             # [4,6]
b.flat("fd_d_4", 6, 4, 0.0, FIELD)                  # [6,7]

# =================================================================
# 2. 前排光伏 (y=2 线): 支架墙 x3 + 30 度光伏板 x3 (尾 y=0.27)
# =================================================================
for x in (1, 3, 5):
    b.wall_ns(f"rk_a_{x}", x, 2.0, 0, RACK)
for x in (1, 3, 5):
    b.ramp(f"pv_a_{x}", "-y", 2.0, x, 1.0, PANEL)

# =================================================================
# 3. 后排光伏 (y=4 线): 再立 3 组, 坡尾落 y=2.27 不碰前排
# =================================================================
for x in (1, 3, 5):
    b.wall_ns(f"rk_b_{x}", x, 4.0, 0, RACK)
for x in (1, 3, 5):
    b.ramp(f"pv_b_{x}", "-y", 4.0, x, 1.0, PANEL)

# =================================================================
# 4. 逆变器房: [6,7]x[2,3] 闭合环 + 方板顶 + 告警灯
# =================================================================
b.wall_ns("iv_s", 6, 2.0, 0, HUT)
b.wall_ns("iv_n", 6, 3.0, 0, HUT)
b.wall_ew("iv_w", 6.0, 2, 0, HUT)
b.wall_ew("iv_e", 7.0, 2, 0, HUT)
b.flat("iv_top", 6, 2, 1.0, HUT)
b.crest_ew("iv_lamp", 6.0, 2, 1.0, LAMP)            # 告警灯 (西沿)

# =================================================================
# 5. 储能电池柜: [6,7]x[3,4], 与逆变器房共用 y=3 隔墙
# =================================================================
b.wall_ns("bt_n", 6, 4.0, 0, BATT)
b.wall_ew("bt_w", 6.0, 3, 0, BATT)
b.wall_ew("bt_e", 7.0, 3, 0, BATT)
b.flat("bt_top", 6, 3, 1.0, BATT)

# =================================================================
# 6. 监测杆: 东北角方墙 + 透明等腰塔尖 (尖端 3.0)
# =================================================================
b.wall_ns("ms_pole", 6, 5.0, 0, MAST)
b.spire_ns("ms_tip", 6, 5.0, 1.0, TIP)

# =================================================================
# 7. 围栏: 西面 2 片 + 南面 1 片黄色三角
# =================================================================
b.crest_ew("fc_w2", 0.0, 2, 0.0, FENCE)
b.crest_ew("fc_w3", 0.0, 3, 0.0, FENCE)
b.crest_ns("fc_s", 6, 0.0, 0.0, FENCE)

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺南半地坪: 灰色检修道一行 + 绿色田野一行, 共 8 片。",
    ["fd_a_0", "fd_b_0", "fd_c_0", "fd_d_0",
     "fd_a_1", "fd_b_1", "fd_c_1", "fd_d_1"],
    tip="检修道正对板面 —— 光伏板的坡尾会落到这附近。",
)
b.step(
    "铺前排咬缝行: 7 片方板逐格铺满。",
    [f"fd_{x}_2" for x in range(7)],
    highlight=["fd_a_1", "fd_c_1"],
    tip="方板格边 y=2 就是前排支架墙的落脚线。",
)
b.step(
    "铺后排咬缝行: 再铺 7 片方板。",
    [f"fd_{x}_3" for x in range(7)],
    highlight=["fd_1_2", "fd_5_2"],
    tip="格边 y=4 留给后排 —— 排距 2 格, 冬至日也不遮挡。",
)
b.step(
    "铺北沿收边: 4 片, 田野合拢成 7x5。",
    ["fd_a_4", "fd_b_4", "fd_c_4", "fd_d_4"],
    highlight=["fd_1_3", "fd_5_3"],
    tip="东北角方板是监测杆的地基。",
)
b.step(
    "立前排支架: y=2 线上 3 片灰墙, 底边整边吸方板格边。",
    ["rk_a_1", "rk_a_3", "rk_a_5"],
    highlight=["fd_1_2", "fd_5_2"],
    tip="支架墙间隔而立 —— 每片光伏板一个支点。",
)
b.step(
    "挂前排光伏板: 3 片蓝色长板 30 度朝南, 顶边整边吸支架顶。",
    ["pv_a_1", "pv_a_3", "pv_a_5"],
    highlight=["rk_a_1", "rk_a_5"],
    tip="顶铰链 + 接地斜撑 —— 板面迎着正午的太阳。",
)
b.step(
    "立后排支架: y=4 线上再立 3 片灰墙。",
    ["rk_b_1", "rk_b_3", "rk_b_5"],
    highlight=["fd_1_3", "fd_5_3"],
    tip="与前排严格同列 —— 阵列的秩序感来自对齐。",
)
b.step(
    "挂后排光伏板: 再挂 3 片, 坡尾落在 y=2.27, 不碰前排。",
    ["pv_b_1", "pv_b_3", "pv_b_5"],
    highlight=["rk_b_1", "pv_a_1"],
    tip="6 片板独立受力 —— 一片检修拆下, 其余照常发电。",
)
b.step(
    "砌逆变器房: 东侧 4 片橙色立墙四角竖边互吸闭环。",
    ["iv_s", "iv_n", "iv_w", "iv_e"],
    highlight=["fd_6_2"],
    tip="直流从这里变交流 —— 电站的心脏。",
)
b.step(
    "封顶点灯: 方板压顶, 西沿立红色告警灯。",
    ["iv_top", "iv_lamp"],
    highlight=["iv_s", "iv_w"],
    tip="告警灯重心正压铰链 —— 红灯不亮, 万事正常。",
)
b.step(
    "装储能电池柜: 3 片黄墙与逆变器房共用隔墙, 方板压顶。",
    ["bt_n", "bt_w", "bt_e", "bt_top"],
    highlight=["iv_n"],
    tip="隔墙一片顶两用 —— 白天存电, 夜里放电。",
)
b.step(
    "竖监测杆: 东北角方墙上立透明等腰塔尖, 直指 3 格高空。",
    ["ms_pole", "ms_tip"],
    highlight=["fd_d_4"],
    tip="辐照、风速、温度 —— 全站数据从杆顶发回。",
)
b.step(
    "围栏收尾: 西面 2 片、南面 1 片黄色三角 —— 并网发电!",
    ["fc_w2", "fc_w3", "fc_s"],
    highlight=["fd_0_2", "fd_d_0"],
    tip="围栏立好, 电站封场 —— 绿电正在入城。",
)

b.finalize(
    model_id="solar_farm_01",
    name="光伏阵列",
    name_en="Solar Farm 01",
    description=(
        "全库第一座太阳能电站: 两排共 6 片蓝色光伏板以 30 度仰角朝南列阵, "
        "每片顶边与支架墙顶等长整边贴合、坡尾贴地生根 (顶铰链 + 接地斜撑, "
        "6 片独立受力), 排距 2 格互不遮挡; 逆变器房与储能电池柜共用隔墙"
        "两环相扣, 红色告警灯与 3 格高监测塔尖点睛, 黄色围栏封场 —— "
        "并网发电, 绿电入城!"
    ),
    difficulty=3,
    tags=["工程", "光伏", "太阳能", "新能源", "电站"],
    min_pieces=50,
    min_steps=13,
)
