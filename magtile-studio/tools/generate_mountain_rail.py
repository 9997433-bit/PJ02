#!/usr/bin/env python3
"""生成模型 data/models/mountain_rail_01.json (登山齿轨小火车)。

铁路/火车站主题: 全库第一条登山齿轨铁路 —— 与缆车站 (空中索道
吊舱) 和空中悬挂轨道车 (吊挂式单轨) 刻意区分, 本作的结构逻辑是
"梯级山体 + 折返齿轨 + 山腰会让站":
两级箱形台地叠成梯级山体 (山脚南壁嵌门框方隧道洞门, 一条洞前
引道钻山而出), 山顶台地上停着一列红色齿轨小火车 (窗格方了望
车窗 + 三角烟囱); 招牌是两段 30 度齿轨坡道的折返下山线 ——
第一段从山顶台面滑下, 坡尾恰好被山腰会让站的台面西沿接住
(一线双吸), 第二段再从会让站台面东沿继续下滑、坡尾自然落地
滑进山脚谷底车站; 会让站是一座落在半格网外的箱形站房 (南墙
嵌站门), 台面北沿列护齿; 山顶挂站旗、坡边长青松, 谷底站前
广场立站旗与松树 —— 咔哒咔哒, 齿轮咬着齿条爬山去。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 隧道引道 (x [1,2], y [-2,0]): 2                               2 片
  - 山脚台地 (x [0,3], y [0,2], z 0..1): 墙环 10 (含隧道洞门) +
    草甸台面 6                                                   16 片
  - 山顶台地 (x [0,2], y [0,2], z 1..2): 墙环 8 + 台面 4         12 片
  - 齿轨小火车 (x [0,2], y [0,1], z 2..3): 了望车窗 + 墙环 5 +
    车顶 2 + 三角烟囱                                             9 片
  - 山顶站旗 + 山坡青松 + 台沿护齿                                 3 片
  - 折返齿轨: 30 度坡道 x2 (第一段山顶->山腰, 第二段山腰->谷底)    2 片
  - 山腰会让站 (x [3.73,5.73], y [0,1]): 墙环 6 (南墙嵌站门) +
    台面 2 + 北沿护齿 2                                          10 片
  - 谷底车站 (x [7.46,9.46], y [0,2]): 站坪 4 + 站旗 + 松树        6 片
  - 洞前站牌松                                                     1 片
  合计 61 片, 13 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 折返齿轨的关键在"坡尾有人接": 第一段顶短边同吸山顶台面沿与
    上层东墙顶, 坡尾整边吸山腰会让站台面西沿 (会让站特意落在
    半格网外 x = 2 + sqrt3, 正好接住 30 度坡的落点) —— 双端受力;
  - 第二段从会让站台面东沿下滑, 坡尾自然落地, 谷底站坪西边
    整边吸坡尾 —— 山体、会让站、谷底三个接地体由两段坡道连成
    一个磁力连通整体;
  - 山体两级箱形台地层层墙环, 小火车墙环 + 车顶锁成箱形闭环,
    烟囱顶 3.87 触发 R8 高层检查, 连接图处处成环无单点失效;
  - 会让站连同第一段坡道同步安装 (同一步内合龙), 任意步骤结束
    时全场都是单一连通体。

用法: python3 tools/generate_mountain_rail.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder, SQ3  # noqa: E402

b = ModelBuilder()

X0 = round(2 + SQ3, 6)          # 山腰会让站西沿 = 第一段坡尾落点 3.732051
X1 = round(X0 + 2 + SQ3, 6)     # 谷底站坪西沿 = 第二段坡尾落点 7.464102

ROCK = "gray"       # 山体墙
TUN = "gray"        # 隧道洞门
MEADOW = "green"    # 山脚草甸台面
SUMMIT = "gray"     # 山顶台面
TRAIN = "red"       # 齿轨小火车
WIN = "clear"       # 了望车窗
FUNNEL = "gray"     # 烟囱
FLAG = "yellow"     # 山顶站旗
TREE = "green"      # 青松
RACK = "orange"     # 齿轨坡道
HUT = "orange"      # 会让站墙体
HDOOR = "red"       # 会让站站门
HDECK = "yellow"    # 会让站台面
FENCE = "yellow"    # 护齿
PLAZA = "gray"      # 谷底站坪
VFLAG = "red"       # 谷底站旗

# =================================================================
# 1. 隧道引道 + 山脚台地墙环 (南壁嵌隧道洞门)
# =================================================================
b.flat("pt_0", 1, -1, 0.0, PLAZA)
b.flat("pt_1", 1, -2, 0.0, PLAZA)
b.wall_ns("bs_s_0", 0, 0.0, 0, ROCK)
b.add("bs_tun", "door_frame", (1.5, 0.0, 0.5), (90, 0, 0), TUN)   # 隧道洞门
b.wall_ns("bs_s_2", 2, 0.0, 0, ROCK)
b.wall_ew("bs_w_0", 0.0, 0, 0, ROCK)
b.wall_ew("bs_w_1", 0.0, 1, 0, ROCK)
b.wall_ns("bs_n_0", 0, 2.0, 0, ROCK)
b.wall_ns("bs_n_1", 1, 2.0, 0, ROCK)
b.wall_ns("bs_n_2", 2, 2.0, 0, ROCK)
b.wall_ew("bs_e_0", 3.0, 0, 0, ROCK)
b.wall_ew("bs_e_1", 3.0, 1, 0, ROCK)
for x in range(3):
    for y in range(2):
        b.flat(f"bs_d_{x}_{y}", x, y, 1.0, MEADOW)

# =================================================================
# 2. 山顶台地 (x [0,2], y [0,2], z 1..2)
# =================================================================
b.wall_ns("up_s_0", 0, 0.0, 1, ROCK)
b.wall_ns("up_s_1", 1, 0.0, 1, ROCK)
b.wall_ew("up_w_0", 0.0, 0, 1, ROCK)
b.wall_ew("up_w_1", 0.0, 1, 1, ROCK)
b.wall_ns("up_n_0", 0, 2.0, 1, ROCK)
b.wall_ns("up_n_1", 1, 2.0, 1, ROCK)
b.wall_ew("up_e_0", 2.0, 0, 1, ROCK)
b.wall_ew("up_e_1", 2.0, 1, 1, ROCK)
for x in range(2):
    for y in range(2):
        b.flat(f"up_d_{x}_{y}", x, y, 2.0, SUMMIT)

# =================================================================
# 3. 齿轨小火车 (x [0,2], y [0,1], z 2..3): 车头朝西
# =================================================================
b.add("tr_w", "window_square", (0.0, 0.5, 2.5), (90, 0, 90), WIN)  # 了望车窗
b.wall_ns("tr_s_0", 0, 0.0, 2, TRAIN)
b.wall_ns("tr_s_1", 1, 0.0, 2, TRAIN)
b.wall_ew("tr_e", 2.0, 0, 2, TRAIN)
b.wall_ns("tr_n_0", 0, 1.0, 2, TRAIN)
b.wall_ns("tr_n_1", 1, 1.0, 2, TRAIN)
b.flat("tr_rf_0", 0, 0, 3.0, TRAIN)
b.flat("tr_rf_1", 1, 0, 3.0, TRAIN)
b.crest_ns("tr_funnel", 0, 0.0, 3.0, FUNNEL)    # 烟囱 (顶 3.87 全场最高)

# =================================================================
# 4. 山顶站旗 + 山坡青松 + 台沿护齿
# =================================================================
b.crest_ns("mt_flag", 1, 2.0, 2.0, FLAG)        # 山顶站旗 (骑台面北沿)
b.spire_ns("mt_tree", 2, 2.0, 1.0, TREE)        # 山坡青松 (骑草甸北沿)
b.crest_ew("mt_fence", 3.0, 1, 1.0, FENCE)      # 台沿护齿 (骑草甸东沿)

# =================================================================
# 5. 山腰会让站 (x [X0, X0+2], y [0,1]) + 折返齿轨两段
# =================================================================
b.add("mp_door", "door_frame", (X0 + 0.5, 0.0, 0.5), (90, 0, 0), HDOOR)
b.wall_ns("mp_s_1", X0 + 1, 0.0, 0, HUT)
b.wall_ew("mp_w", X0, 0, 0, HUT)
b.wall_ew("mp_e", X0 + 2, 0, 0, HUT)
b.wall_ns("mp_n_0", X0, 1.0, 0, HUT)
b.wall_ns("mp_n_1", X0 + 1, 1.0, 0, HUT)
b.flat("mp_d_0", X0, 0, 1.0, HDECK)
b.flat("mp_d_1", X0 + 1, 0, 1.0, HDECK)
b.ramp("rk_up", "+x", 2.0, 0, 2.0, RACK)        # 第一段: 山顶 -> 山腰
b.ramp("rk_dn", "+x", X0 + 2, 0, 1.0, RACK)     # 第二段: 山腰 -> 谷底
b.crest_ns("mp_fence_0", X0, 1.0, 1.0, FENCE)   # 台面北沿护齿
b.crest_ns("mp_fence_1", X0 + 1, 1.0, 1.0, FENCE)

# =================================================================
# 6. 谷底车站 (x [X1, X1+2], y [0,2]) + 点景
# =================================================================
b.flat("vl_0", X1, 0, 0.0, PLAZA)
b.flat("vl_1", X1 + 1, 0, 0.0, PLAZA)
b.flat("vl_2", X1, 1, 0.0, MEADOW)
b.flat("vl_3", X1 + 1, 1, 0.0, MEADOW)
b.spire_ns("vl_flag", X1 + 1, 2.0, 0.0, VFLAG)  # 谷底站旗
b.crest_ns("vl_tree", X1, 2.0, 0.0, TREE)       # 站前松树
b.spire_ns("pt_tree", 1, -2.0, 0.0, TREE)       # 洞前站牌松

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺隧道引道并立山脚南壁: 引道 2 片钻山而出, 南壁 3 片 —— "
    "正中嵌门框方隧道洞门。",
    ["bs_s_0", "bs_tun", "bs_s_2", "pt_0", "pt_1"],
    tip="山还没堆起来, 先给火车留好山洞 —— 洞门正对引道。",
)
b.step(
    "合山脚台地墙环: 西墙 2 + 北墙 3 + 东墙 2, 10 片墙锁成 3x2 箱形。",
    ["bs_w_0", "bs_w_1", "bs_n_0", "bs_n_1", "bs_n_2", "bs_e_0", "bs_e_1"],
    highlight=["bs_s_0", "bs_tun"],
    tip="箱形墙环就是山体的第一级台地 —— 处处成环, 剪一条不塌。",
)
b.step(
    "铺山脚草甸台面: 6 片绿色方板压墙顶, 第一级台地封顶。",
    [f"bs_d_{x}_{y}" for x in range(3) for y in range(2)],
    highlight=["bs_s_0", "bs_n_2"],
    tip="每片台面同时吸墙顶与邻板拼缝 —— 山腰草甸长出来了。",
)
b.step(
    "起山顶台地南墙与西墙: 4 片踩草甸台面沿边 (x [0,2])。",
    ["up_s_0", "up_s_1", "up_w_0", "up_w_1"],
    highlight=["bs_d_0_0"],
    tip="第二级台地直接叠在第一级上 —— 梯级山体的搭法。",
)
b.step(
    "合山顶台地墙环: 北墙 2 + 东墙 2。",
    ["up_n_0", "up_n_1", "up_e_0", "up_e_1"],
    highlight=["up_s_0", "up_w_1"],
    tip="上层墙脚整边吸台面沿边与下层墙顶 —— 一条缝两道吸。",
)
b.step(
    "铺山顶台面: 4 片灰色方板压墙顶, 山顶站台就绪。",
    ["up_d_0_0", "up_d_1_0", "up_d_0_1", "up_d_1_1"],
    highlight=["up_s_0", "up_n_1"],
    tip="海拔 2.0 —— 齿轨小火车的终点站到了。",
)
b.step(
    "拼齿轨小火车: 西端窗格方了望车窗打头, 红色墙环合拢 (x [0,2], "
    "y [0,1])。",
    ["tr_w", "tr_s_0", "tr_s_1", "tr_e", "tr_n_0", "tr_n_1"],
    highlight=["up_d_0_0", "up_d_1_0"],
    tip="车窗朝西看谷底 —— 墙脚踩台面拼缝, 竖边两两互咬。",
)
b.step(
    "封车顶装烟囱: 2 片车顶双边压墙顶, 三角烟囱骑上车顶南沿。",
    ["tr_rf_0", "tr_rf_1", "tr_funnel"],
    highlight=["tr_w", "tr_e"],
    tip="烟囱顶 3.87 全场最高 —— 墙-顶锁成箱形闭环, 高也不怕。",
)
b.step(
    "山顶插站旗、山坡种青松、台沿列护齿。",
    ["mt_flag", "mt_tree", "mt_fence"],
    highlight=["up_d_1_1", "bs_d_2_1"],
    tip="三片三角都骑整边沿口, 重心正压铰链 —— 力矩为零。",
)
b.step(
    "落山腰会让站并架第一段齿轨: 站房墙环 6 片 (南墙嵌红色站门) 落在"
    "半格网外 (x = 2 + sqrt3), 台面 2 片压顶; 30 度齿轨坡道从山顶台面"
    "滑下 —— 顶短边吸山顶沿, 坡尾恰好整边吸会让站台面西沿。",
    ["mp_door", "mp_s_1", "mp_w", "mp_e", "mp_n_0", "mp_n_1",
     "mp_d_0", "mp_d_1", "rk_up"],
    highlight=["up_d_1_0", "up_e_0"],
    tip="会让站特意落在半格网外 —— 正好接住 30 度坡的落点, 双端受力。",
)
b.step(
    "架第二段齿轨并列护齿: 坡道从会让站台面东沿继续下滑, 坡尾自然"
    "落地; 台面北沿列 2 片护齿。",
    ["rk_dn", "mp_fence_0", "mp_fence_1"],
    highlight=["mp_d_1", "mp_e"],
    tip="折返下山线成形 —— 齿轮咬着齿条, 陡坡也稳稳当当。",
)
b.step(
    "铺谷底站坪: 4 片方板从第二段坡尾向东铺开, 西边整边吸坡尾。",
    ["vl_0", "vl_1", "vl_2", "vl_3"],
    highlight=["rk_dn"],
    tip="山体、会让站、谷底 —— 三个接地体被两段坡道连成一体。",
)
b.step(
    "谷底插站旗种松树, 洞前再种一棵站牌松 —— 齿轨铁路通车!",
    ["vl_flag", "vl_tree", "pt_tree"],
    highlight=["vl_2", "pt_1"],
    tip="咔哒咔哒 —— 小火车从山顶下来, 钻隧道、过会让站, 到站!",
)

b.finalize(
    model_id="mountain_rail_01",
    name="登山齿轨小火车",
    name_en="Mountain Rack Railway 01",
    description=(
        "只用核心九片型的登山齿轨铁路: 两级箱形台地叠成梯级山体,"
        " 山脚南壁嵌门框方隧道洞门接引道, 山顶台地停着红色齿轨小火车"
        " (窗格方了望车窗朝谷底, 烟囱顶 3.87 全场最高); 招牌是两段"
        " 30 度齿轨坡道的折返下山线 —— 第一段坡尾恰好被落在半格网外"
        " (x = 2 + sqrt3) 的山腰会让站台面西沿整边接住 (双端受力),"
        " 第二段再从台面东沿滑向谷底自然落地; 山体、会让站、谷底"
        "三个接地体由两段坡道连成一个磁力连通整体, 站旗青松护齿"
        "一路点景 —— 咔哒咔哒, 齿轮咬着齿条爬山去。"
    ),
    difficulty=3,
    tags=["交通", "火车", "登山铁路", "自然", "进阶"],
    min_pieces=61,
    min_steps=13,
)
