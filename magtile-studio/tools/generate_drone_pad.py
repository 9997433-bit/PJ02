#!/usr/bin/env python3
"""生成模型 data/models/drone_pad_01.json (无人机停机坪).

城市生活主题: 全库第一座低空物流起降场 —— 7x7 停机坪广场
中央, 12 片蓝色墩墙四角竖边互吸围成闭合环, 顶起 3x3 起降
平台: 绿色 H 降落标线正中停着一架红色四坡快递无人机;
南侧 30 度检修坡道贴地放平, 西北角两层塔台戴着透明雷达
锥顶俯瞰全场, 东北角风向杆挑起橙色风向旗 —— 航线已批,
准备起飞!

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 停机坪广场 7x7: 方板 + 长板混铺                           34 片
  - 起降台墩墙: 四面各 3 片蓝色立墙, 四角竖边互吸闭环          12 片
  - 起降平台: 方板 x9 (周圈 8 片整边压墩墙顶 + 中心 1 片)       9 片
  - 检修坡道: 30 度长板 x1 (顶边整边吸墩墙顶, 坡尾接地)         1 片
  - 快递无人机: 红色等边四坡机身 x4 (停在 H 标线正中)           4 片
  - 塔台: 1x1 闭合环 x2 层 + 方板顶 + 透明雷达锥顶 x4          13 片
  - 风向杆: 方墙 x1 + 直角三角风向旗 x1 (竖边吸旗杆棱)          2 片
  合计 75 片, 13 个教程步骤, 4 种磁力片形状。

物理规则要点 (通过 R1~R8 全部校验, default + strict 双档):
  - 起降平台周圈 8 片方板每片至少一条整边压墩墙顶, 中心板
    四边吸邻板 —— 墩墙环 + 平台锁成刚性台体;
  - 检修坡道顶铰链 + 接地斜撑 (音乐喷泉水舌同款), 无人机
    四坡机身四棱互吸自锁、重心正压平台;
  - 风向旗竖直角边整边吸旗杆竖棱: 铰链轴竖直, 重力力矩为零
    (旗子绕杆转是真实物理);
  - 塔台雷达锥顶 2.71 触发 R8 高层检查: 两层闭合环 + 四坡
    互锁冗余充足, 零警告。

用法: python3 tools/generate_drone_pad.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

APRON = "gray"      # 停机坪广场
PIER = "blue"       # 起降台墩墙
PAD = "gray"        # 平台面
HMARK = "green"     # H 降落标线
DRONE = "red"       # 无人机机身
TOWER = "orange"    # 塔台
RADAR = "clear"     # 雷达锥顶
POLE = "gray"       # 风向杆
FLAG = "orange"     # 风向旗

# =================================================================
# 1. 停机坪广场 7x7: 起降台周边行方板咬缝, 南北沿长板收边
# =================================================================
b.flat_rect("ap_s0", 0, 0, 0.0, APRON)              # [0,2]x[0,1]
b.flat_rect("ap_s1", 2, 0, 0.0, APRON)              # [2,4]
b.flat_rect("ap_s2", 4, 0, 0.0, APRON)              # [4,6]
b.flat("ap_s3", 6, 0, 0.0, APRON)                   # [6,7]
for y in range(1, 6):
    b.flat_rect(f"ap_w_{y}", 0, y, 0.0, APRON)      # [0,2]
    for x in (2, 3, 4):
        b.flat(f"ap_{x}_{y}", x, y, 0.0, APRON)     # 中三格方板
    b.flat_rect(f"ap_e_{y}", 5, y, 0.0, APRON)      # [5,7]
b.flat("ap_n0", 0, 6, 0.0, APRON)                   # [0,1]x[6,7]
b.flat_rect("ap_n1", 1, 6, 0.0, APRON)              # [1,3]
b.flat("ap_n2", 3, 6, 0.0, APRON)                   # [3,4]
b.flat_rect("ap_n3", 4, 6, 0.0, APRON)              # [4,6]
b.flat("ap_n4", 6, 6, 0.0, APRON)                   # [6,7]

# =================================================================
# 2. 起降台墩墙: 围合 [2,5]x[2,5], 四角竖边互吸闭环 (z0..1)
# =================================================================
for x in (2, 3, 4):
    b.wall_ns(f"pr_s_{x}", x, 2.0, 0, PIER)         # 南墩墙
    b.wall_ns(f"pr_n_{x}", x, 5.0, 0, PIER)         # 北墩墙
for y in (2, 3, 4):
    b.wall_ew(f"pr_w_{y}", 2.0, y, 0, PIER)         # 西墩墙
    b.wall_ew(f"pr_e_{y}", 5.0, y, 0, PIER)         # 东墩墙

# =================================================================
# 3. 起降平台 (z=1): 周圈 8 片压墩墙顶 + 中心 1 片, 绿色 H 标线
# =================================================================
PAD_COLORS = {
    (2, 2): HMARK, (2, 3): HMARK, (2, 4): HMARK,    # H 左竖
    (4, 2): HMARK, (4, 3): HMARK, (4, 4): HMARK,    # H 右竖
    (3, 3): HMARK,                                  # H 横杠 (中心)
    (3, 2): PAD, (3, 4): PAD,
}
for (x, y), color in PAD_COLORS.items():
    if (x, y) != (3, 3):
        b.flat(f"pd_{x}_{y}", x, y, 1.0, color)
b.flat("pd_3_3", 3, 3, 1.0, PAD_COLORS[(3, 3)])     # 中心板最后合拢

# =================================================================
# 4. 检修坡道: 顶边整边吸南墩墙顶, 坡尾贴地 (y=0.27)
# =================================================================
b.ramp("svc_ramp", "-y", 2.0, 3, 1.0, APRON)

# =================================================================
# 5. 快递无人机: 红色四坡机身停在 H 横杠正中 (z=1 起坡)
# =================================================================
DRONE_IDS = b.hat4("drone", 3, 3, 1.0, DRONE,
                   shape="equilateral_triangle")

# =================================================================
# 6. 塔台: [0,1]x[6,7] 两层闭合环 + 方板顶 + 透明雷达锥顶
# =================================================================
for lv in (0, 1):
    b.wall_ns(f"tw_s_{lv}", 0, 6.0, lv, TOWER)
    b.wall_ns(f"tw_n_{lv}", 0, 7.0, lv, TOWER)
    b.wall_ew(f"tw_w_{lv}", 0.0, 6, lv, TOWER)
    b.wall_ew(f"tw_e_{lv}", 1.0, 6, lv, TOWER)
b.flat("tw_top", 0, 6, 2.0, TOWER)                  # 塔顶 z=2
RADAR_IDS = b.hat4("radar", 0, 6, 2.0, RADAR,
                   shape="equilateral_triangle")    # 锥尖 2.71

# =================================================================
# 7. 风向杆: 东北角方墙旗杆 + 直角三角风向旗 (竖边吸杆棱)
# =================================================================
b.wall_ns("ws_pole", 6, 7.0, 0, POLE)
b.place_tri("ws_flag", "right_triangle",
            (7.0, 7.0, 1.0), (7.0, 7.0, 0.0), (8.0, 7.0, 1.0), FLAG)

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺广场南沿与第二行: 长板收边 + 中三格方板, 共 9 片。",
    ["ap_s0", "ap_s1", "ap_s2", "ap_s3",
     "ap_w_1", "ap_2_1", "ap_3_1", "ap_4_1", "ap_e_1"],
    tip="中三格方板的拼缝就是起降台墩墙的落脚线。",
)
b.step(
    "铺广场中段: 2 行 长板+方板x3+长板, 共 10 片。",
    [tid for y in (2, 3)
     for tid in (f"ap_w_{y}", f"ap_2_{y}", f"ap_3_{y}", f"ap_4_{y}",
                 f"ap_e_{y}")],
    highlight=["ap_2_1", "ap_4_1"],
    tip="起降台就坐在这 3x3 的方板区正上方。",
)
b.step(
    "铺广场次北段: 再铺 2 行 10 片。",
    [tid for y in (4, 5)
     for tid in (f"ap_w_{y}", f"ap_2_{y}", f"ap_3_{y}", f"ap_4_{y}",
                 f"ap_e_{y}")],
    highlight=["ap_2_3", "ap_4_3"],
    tip="西北角要留给塔台 —— 广场马上合拢。",
)
b.step(
    "铺广场北沿: 5 片收边, 广场合拢成 7x7。",
    ["ap_n0", "ap_n1", "ap_n2", "ap_n3", "ap_n4"],
    highlight=["ap_w_5", "ap_e_5"],
    tip="西北角方板与东北角方板都各有用处 —— 塔台与风向杆。",
)
b.step(
    "砌南北墩墙: 沿方板拼缝各立 3 片蓝色墩墙。",
    ["pr_s_2", "pr_s_3", "pr_s_4", "pr_n_2", "pr_n_3", "pr_n_4"],
    highlight=["ap_2_1", "ap_4_5"],
    tip="墩墙底边整边吸方板格边 —— 起降台的桩基。",
)
b.step(
    "砌东西墩墙: 各立 3 片, 四角竖边互吸 —— 台体闭环。",
    ["pr_w_2", "pr_w_3", "pr_w_4", "pr_e_2", "pr_e_3", "pr_e_4"],
    highlight=["pr_s_2", "pr_n_4"],
    tip="闭合环是最强的结构 —— 无人机降落的冲击全靠它。",
)
b.step(
    "铺平台周圈: 8 片方板绕圈压上墩墙顶, 绿色片摆出 H 的两竖。",
    ["pd_2_2", "pd_3_2", "pd_4_2", "pd_2_3", "pd_4_3",
     "pd_2_4", "pd_3_4", "pd_4_4"],
    highlight=["pr_s_3", "pr_w_3"],
    tip="每片至少一条整边压墙顶 —— 周圈先锁边。",
)
b.step(
    "合拢中心板、放检修坡道: 绿色中心板补上 H 横杠, 30 度"
    "坡道顶边吸南墩墙顶。",
    ["pd_3_3", "svc_ramp"],
    highlight=["pd_3_2", "pr_s_3"],
    tip="顶铰链 + 接地斜撑 —— 检修员顺坡直上平台。",
)
b.step(
    "停无人机: 4 片红色三角在 H 正中四棱互吸, 合拢成机身。",
    DRONE_IDS,
    highlight=["pd_3_3"],
    tip="四坡自锁 —— 快递舱就藏在机身里。",
)
b.step(
    "砌塔台下环: 西北角 4 片橙色立墙四角竖边互吸。",
    ["tw_s_0", "tw_n_0", "tw_w_0", "tw_e_0"],
    highlight=["ap_n0"],
    tip="塔台要看全场 —— 地基先落西北角方板。",
)
b.step(
    "砌塔台上环: 再叠 4 片, 底边整边吸下环顶边。",
    ["tw_s_1", "tw_n_1", "tw_w_1", "tw_e_1"],
    highlight=["tw_s_0", "tw_e_0"],
    tip="两层环精确对位 —— 塔台升到 2 格高。",
)
b.step(
    "封塔顶、装雷达: 方板四边压环顶, 4 片透明三角合拢成锥。",
    ["tw_top"] + RADAR_IDS,
    highlight=["tw_s_1"],
    tip="雷达锥尖 2.71 高 —— 全场航迹尽收眼底。",
)
b.step(
    "竖风向杆: 东北角立方墙旗杆, 橙色直角旗竖边吸杆棱。",
    ["ws_pole", "ws_flag"],
    highlight=["ap_n4"],
    tip="旗绕竖轴转是真实物理 —— 风向一目了然, 准备起飞!",
)

b.finalize(
    model_id="drone_pad_01",
    name="无人机停机坪",
    name_en="Drone Pad 01",
    description=(
        "全库第一座低空物流起降场: 12 片蓝色墩墙四角竖边互吸围成闭合环, "
        "顶起 3x3 起降平台 (周圈 8 片整边压墙顶, 中心板最后合拢), 绿色 H "
        "标线正中停着红色四坡快递无人机; 南侧 30 度检修坡道顶铰链接地, "
        "西北角两层塔台戴透明雷达锥顶 (2.71 高, R8 零警告), 东北角风向旗"
        "竖边吸杆棱绕竖轴零力矩 —— 航线已批, 准备起飞!"
    ),
    difficulty=3,
    tags=["城市", "无人机", "停机坪", "低空物流", "科技"],
    min_pieces=72,
    min_steps=13,
)
