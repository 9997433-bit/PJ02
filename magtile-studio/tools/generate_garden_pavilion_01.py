#!/usr/bin/env python3
"""生成模型 data/models/garden_pavilion_01.json (花园小凉亭)。

D1 补员批 4 模型 1/4 (难度配额解冻线 D1 >= 20, 路径 B1): 入门档
植物花园选题 —— 有篱笆院子的小凉亭。结构签名是"围院中心亭":
一圈 12 片篱笆围出 3x3 小院, 院中央一座四面开窗的凉亭, 顶上
四片等边三角互吸自锁成金字塔锥顶 (摩天大楼金顶同款 hat4),
一条石板路从紫色院门直通亭子 —— 全批唯一的"环 + 心"布局,
与板桥 (多墩桥跨)、折墙 (开放折线) 和小黄鸭 (叠层动物) 的
结构逻辑完全不同。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 亭基 + 石板路: 平铺方板 (格 [1,2]x[1,2] / [1,2]x[0,1])   2 片
  - 凉亭四面窗格墙 (z 0..1, 墙脚整边吸亭基)                  4 片
  - 金字塔锥顶 hat4 (等边三角 4 片, 斜棱互吸自锁, 顶 1.71)   4 片
  - 篱笆一圈 (3x3 周边 12 段, 南面中段换紫色门框方)         12 片
  - 篱笆顶四角花朵 (等边三角, 与篱笆顶整边重合)              4 片
  合计 26 片, 6 个教程步骤, 4 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 凉亭墙脚整边骑亭基四边 (R2), 锥顶四片底边整边吸墙顶,
    斜棱两两互吸自锁成环 —— 先立墙后封顶, 亭腔封闭前内部
    无待放片 (R7b 无包围放置);
  - 篱笆逐段竖棱手拉手 (相邻墙竖边完整贴合), 全部接地受压;
  - 石板路两端分别整边吸亭基与门框方墙脚, 把亭与院锁成一体;
  - 最高点 1.71 (锥尖) < 2.5, 不触发 R8 高层结构判定。

用法: python3 tools/generate_garden_pavilion_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

BASE = "gray"       # 亭基
PATH = "yellow"     # 石板路
WALL = "clear"      # 凉亭窗格墙
ROOF = "red"        # 金字塔锥顶
FENCE = "green"     # 篱笆
GATE = "purple"     # 院门 (门框方)
FLOWER = "pink"     # 篱笆花朵

# =================================================================
# 1. 亭基与石板路 (院子 3x3, 亭子居中格 [1,2]x[1,2])
# =================================================================
b.flat("base", 1, 1, 0.0, BASE)
b.flat("path", 1, 0, 0.0, PATH)

# =================================================================
# 2. 凉亭四面窗格墙 (z 0..1, 墙脚整边吸亭基四边)
# =================================================================
b.add("pav_s", "window_square", (1.5, 1.0, 0.5), (90, 0, 0), WALL)
b.add("pav_n", "window_square", (1.5, 2.0, 0.5), (90, 0, 0), WALL)
b.add("pav_w", "window_square", (1.0, 1.5, 0.5), (90, 0, 90), WALL)
b.add("pav_e", "window_square", (2.0, 1.5, 0.5), (90, 0, 90), WALL)

# =================================================================
# 3. 金字塔锥顶 (等边 hat4, 底边整边吸墙顶, 锥尖 1.71)
# =================================================================
roof_ids = b.hat4("roof", 1, 1, 1.0, ROOF, shape="equilateral_triangle")

# =================================================================
# 4. 篱笆一圈 (3x3 周边 12 段, 南面中段是紫色院门)
# =================================================================
b.wall_ns("fence_s_w", 0, 0.0, 0, FENCE)
b.add("gate", "door_frame", (1.5, 0.0, 0.5), (90, 0, 0), GATE)
b.wall_ns("fence_s_e", 2, 0.0, 0, FENCE)
for i in range(3):
    b.wall_ns(f"fence_n_{i}", i, 3.0, 0, FENCE)
for j in range(3):
    b.wall_ew(f"fence_w_{j}", 0.0, j, 0, FENCE)
for j in range(3):
    b.wall_ew(f"fence_e_{j}", 3.0, j, 0, FENCE)

# =================================================================
# 5. 篱笆顶四角花朵 (等边三角, 与篱笆顶整边重合)
# =================================================================
b.crest_ns("flower_sw", 0, 0.0, 1.0, FLOWER)
b.crest_ns("flower_se", 2, 0.0, 1.0, FLOWER)
b.crest_ns("flower_nw", 0, 3.0, 1.0, FLOWER)
b.crest_ns("flower_ne", 2, 3.0, 1.0, FLOWER)

# =================================================================
# 教程步骤 (6 步)
# =================================================================
b.step(
    "铺亭基和石板路: 灰色方板放院子正中当亭基, 黄色方板贴在南边当石板路。",
    ["base", "path"],
    tip="两片方板整边吸合 —— 石板路以后就是进亭子的必经之路。",
)
b.step(
    "立凉亭四面窗格墙: 墙脚整边骑住亭基四边, 相邻墙竖棱手拉手围成一圈。",
    ["pav_s", "pav_w", "pav_n", "pav_e"],
    highlight=["base"],
)
b.step(
    "盖金字塔锥顶: 四片红色等边三角底边吸墙顶, 斜棱两两互吸, 最后一片一放就自锁成塔尖。",
    roof_ids,
    highlight=["pav_s", "pav_e"],
    tip="四条斜棱互吸成环 —— 这是摩天大楼金顶同款的自锁结构。",
)
b.step(
    "围南墙篱笆与西墙篱笆: 紫色门框方站在南面正中当院门, 绿色篱笆逐段竖棱手拉手。",
    ["fence_s_w", "gate", "fence_s_e", "fence_w_0", "fence_w_1", "fence_w_2"],
    highlight=["path"],
    tip="院门墙脚正好压住石板路南边 —— 路与门锁成一体。",
)
b.step(
    "围北墙篱笆与东墙篱笆: 六段绿色篱笆合拢一圈, 小院就围好了。",
    ["fence_n_0", "fence_n_1", "fence_n_2", "fence_e_0", "fence_e_1", "fence_e_2"],
    highlight=["fence_s_w", "fence_w_0"],
)
b.step(
    "开花: 四朵粉色小花骑上篱笆四角, 花园凉亭开门迎客!",
    ["flower_sw", "flower_se", "flower_nw", "flower_ne"],
    highlight=["fence_s_w", "fence_n_2"],
)

b.finalize(
    model_id="garden_pavilion_01",
    name="花园小凉亭",
    name_en="Garden Pavilion 01",
    description=(
        "入门档植物花园: 有篱笆院子的小凉亭, 结构签名是'围院中心亭' "
        "—— 一圈 12 段绿篱竖棱手拉手围出 3x3 小院, 院中央四面窗格墙"
        "整边骑住亭基, 顶上四片红色等边三角底边吸墙顶、斜棱两两互吸"
        "自锁成金字塔锥顶; 一条黄色石板路从紫色院门直通亭子, 把亭与院"
        "锁成一体, 篱笆四角还开着粉色小花。26 片全程接地受压零悬挑, "
        "锥尖 1.71 不触发高层判定, 4 岁小手也能一次合围成功。"
    ),
    difficulty=1,
    tags=["植物花园", "凉亭", "篱笆", "小院", "入门"],
    min_pieces=26,
    min_steps=6,
    series="plant_garden",
)
print("已写入 series=plant_garden")
