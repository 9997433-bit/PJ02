#!/usr/bin/env python3
"""生成模型 data/models/snowman_01.json (冬日雪人广场)。

内容批 E 模型 5/5: 全库第一个雪人 —— 与 pyramid_giza_01 (逐层
居中收分的实心阶梯) / flag_plaza_01 (窄检阅台 + 细高旗杆塔) 刻意
区分: 本作的结构签名是"三比一突变收分": 雪人身子是 3x3 足印的
两节大墙环 (空心箱体, 不是实心堆叠), 到脖子处一步跳到 1x1 的
雪球头 —— 头环四片墙全部骑在身盖 9 宫格正中那片方板的四条边上
(旗杆塔骑台面的同款技法, 但 3:1 的突变比例全库唯一); 头顶再合
一顶红色等腰四坡尖帽, 帽尖 4.94 全场制高。窗格方是点睛之笔:
身环南面正中嵌一片作煤扣, 头环南面嵌一片作眼睛; 红围巾结骑在
脖线正下方, 两条橙色树枝手臂从身盖东西沿伸出, 雪地一角还插着
一把等腰大扫帚。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 雪人面朝南):
  - 雪地 5 行 (x [0,6], y [0,5]): 白雪方板 + 青色冰面长板       26 片
  - 身子两节 3x3 墙环 (x [1,4], y [1,4], z 0..2, 含煤扣窗格方)  24 片
  - 身盖 9 宫格 (z=2): 周圈吸墙顶, 中心与邻板共面互吸            9 片
  - 雪球头 (x [2,3], y [2,3], z 2..3): 墙环 (含眼睛窗格方)+头盖  5 片
  - 红色等腰四坡尖帽 (帽尖 4.94)                                 4 片
  - 红围巾结 + 双树枝手臂 + 雪地大扫帚                           4 片
  合计 72 片, 14 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 两节身环整边共线上叠, 每节四角竖边互咬自锁, 全塔受压无
    悬挂链 (R8 高层检查靠闭环拓扑天然通过);
  - 身盖 9 宫格周圈八片吸墙顶, 中心一片四边与邻板共面互吸 ——
    环撑板面; 头环四片墙的底边恰好是中心方板的四条边, 一片
    方板独扛一颗头 (荷载直下, 拼缝一格不能错);
  - 尖帽四条斜棱两两互吸自锁 (摩天大楼金顶同款), 帽底边吸
    '头盖边 + 头墙顶'两条共线铰链;
  - 围巾结/手臂骑'身盖沿 + 墙顶'一线双吸, 重心正压铰链线;
  - 雪地拼缝纪律: 身环墙脚三行全单位方板, 相邻行等长边互吸。

用法: python3 tools/generate_snowman_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

SNOW = "clear"       # 雪地 / 雪人身
ICE = "cyan"         # 冰面
COAL = "gray"        # 煤扣 / 眼睛 (窗格方)
HAT = "red"          # 尖帽
SCARF = "red"        # 围巾结
ARM = "orange"       # 树枝手臂
BROOM = "orange"     # 大扫帚

# =================================================================
# 1. 雪地 5 行 (x [0,6], y [0,5]): 身环墙脚三行全单位方板
# =================================================================
# 南缘 (y [0,1])
b.flat("sn0_0", 0, 0, 0.0, SNOW)
b.flat("sn0_1", 1, 0, 0.0, SNOW)
b.flat_rect("sn0_m", 2, 0, 0.0, ICE)
b.flat_rect("sn0_e", 4, 0, 0.0, ICE)
# 身环三行 (y [1,4]): 全单位方板
for y in (1, 2, 3):
    for x in range(6):
        b.flat(f"sn{y}_{x}", x, y, 0.0, SNOW)
# 北缘 (y [4,5])
b.flat("sn4_0", 0, 4, 0.0, SNOW)
b.flat("sn4_1", 1, 4, 0.0, SNOW)
b.flat_rect("sn4_m", 2, 4, 0.0, ICE)
b.flat_rect("sn4_e", 4, 4, 0.0, ICE)

# =================================================================
# 2. 身子两节 3x3 墙环 (x [1,4], y [1,4], z 0..2)
# =================================================================
for lv, z in (("1", 0), ("2", 1)):
    for x in (1, 2, 3):
        if lv == "2" and x == 2:
            # 南面正中的煤扣 (窗格方)
            b.add("bd2_s_2", "window_square", (2.5, 1.0, 1.5), (90, 0, 0), COAL)
        else:
            b.wall_ns(f"bd{lv}_s_{x}", x, 1.0, z, SNOW)
        b.wall_ns(f"bd{lv}_n_{x}", x, 4.0, z, SNOW)
    for y in (1, 2, 3):
        b.wall_ew(f"bd{lv}_w_{y}", 1.0, y, z, SNOW)
        b.wall_ew(f"bd{lv}_e_{y}", 4.0, y, z, SNOW)

# =================================================================
# 3. 身盖 9 宫格 (z=2): 周圈吸墙顶, 中心一片环撑
# =================================================================
for x in (1, 2, 3):
    for y in (1, 2, 3):
        b.flat(f"cap_{x}_{y}", x, y, 2.0, SNOW)

# =================================================================
# 4. 雪球头 (x [2,3], y [2,3], z 2..3): 眼睛窗格方朝南 + 头盖
# =================================================================
b.add("hd_s", "window_square", (2.5, 2.0, 2.5), (90, 0, 0), COAL)
b.wall_ns("hd_n", 2, 3.0, 2, SNOW)
b.wall_ew("hd_w", 2.0, 2, 2, SNOW)
b.wall_ew("hd_e", 3.0, 2, 2, SNOW)
b.flat("hd_cap", 2, 2, 3.0, SNOW)

# =================================================================
# 5. 红色等腰四坡尖帽 (帽尖 4.94 全场制高)
# =================================================================
b.hat4("hat", 2, 2, 3.0, HAT, shape="isosceles_triangle")

# =================================================================
# 6. 围巾结 + 手臂 + 扫帚
# =================================================================
b.crest_ns("scarf", 2, 1.0, 2.0, SCARF)            # 骑身盖南沿正中
b.crest_ew("arm_w", 1.0, 2, 2.0, ARM)              # 西臂
b.crest_ew("arm_e", 4.0, 2, 2.0, ARM)              # 东臂
b.spire_ns("broom", 0, 1.0, 0.0, BROOM)            # 插在西南角雪地缝

# =================================================================
# 教程步骤 (14 步)
# =================================================================
b.step(
    "铺雪地南缘: 两片白雪方板 + 两片青色冰面长板。",
    ["sn0_0", "sn0_1", "sn0_m", "sn0_e"],
    tip="昨夜下了整晚的雪 —— 今天全院子的雪都归我们捏雪人!",
)
b.step(
    "铺身环第一行 (y 1..2): 六片白雪单位方板一字对缝。",
    ["sn1_0", "sn1_1", "sn1_2", "sn1_3", "sn1_4", "sn1_5"],
    highlight=["sn0_0"],
    tip="雪人身环的南墙脚就踩这行拼缝 —— 全用单位方板才吸得住。",
)
b.step(
    "铺身环第二行 (y 2..3): 六片白雪方板与上一行对缝。",
    ["sn2_0", "sn2_1", "sn2_2", "sn2_3", "sn2_4", "sn2_5"],
    highlight=["sn1_1"],
    tip="相邻行等长边互吸 —— 雪地连成一体, 雪人才站得稳。",
)
b.step(
    "铺身环第三行 (y 3..4): 再来六片, 身环的地基三行齐了。",
    ["sn3_0", "sn3_1", "sn3_2", "sn3_3", "sn3_4", "sn3_5"],
    highlight=["sn2_2"],
    tip="3x3 的大脚印 —— 这个雪人可比你还高哟。",
)
b.step(
    "铺雪地北缘收口: 两片方板 + 两片冰面长板。",
    ["sn4_0", "sn4_1", "sn4_m", "sn4_e"],
    highlight=["sn3_3"],
    tip="雪地围合完成 —— 开始滚第一个大雪球!",
)
b.step(
    "砌身子第一节南墙与西墙: 六片白雪立墙, 转角竖边互咬。",
    ["bd1_s_1", "bd1_s_2", "bd1_s_3", "bd1_w_1", "bd1_w_2", "bd1_w_3"],
    highlight=["sn1_1"],
    tip="雪人身子是空心大墙环 —— 不是实心雪堆, 片片受压。",
)
b.step(
    "砌第一节北墙与东墙合环: 3x3 大雪球的第一圈闭合。",
    ["bd1_n_1", "bd1_n_2", "bd1_n_3", "bd1_e_1", "bd1_e_2", "bd1_e_3"],
    highlight=["bd1_s_1"],
    tip="闭环墙拆一片不倒 —— 大雪球的腰身要经得起拍打。",
)
b.step(
    "摞身子第二节南墙与西墙: 南面正中嵌窗格方煤扣。",
    ["bd2_s_1", "bd2_s_2", "bd2_s_3", "bd2_w_1", "bd2_w_2", "bd2_w_3"],
    highlight=["bd1_s_2"],
    tip="上节底边与下节墙顶整边共线吸合 —— 煤扣正对着正南。",
)
b.step(
    "摞第二节北墙与东墙合环: 身子长到 2.0 高。",
    ["bd2_n_1", "bd2_n_2", "bd2_n_3", "bd2_e_1", "bd2_e_2", "bd2_e_3"],
    highlight=["bd2_s_2"],
    tip="两节都是闭环 —— R8 高层检查全靠这口环环相扣的硬气。",
)
b.step(
    "盖身盖 9 宫格: 周圈八片吸墙顶, 中心一片四边靠邻板互吸。",
    ["cap_1_1", "cap_2_1", "cap_3_1", "cap_1_2", "cap_3_2",
     "cap_1_3", "cap_2_3", "cap_3_3", "cap_2_2"],
    highlight=["bd2_n_2"],
    tip="中心那片最后放 —— 它就是雪球头的落脚点, 拼缝一格不能错。",
)
b.step(
    "骑上雪球头并盖头盖: 头环四片墙全骑在身盖正中那片的四条边上, "
    "眼睛窗格方朝南。",
    ["hd_s", "hd_n", "hd_w", "hd_e", "hd_cap"],
    highlight=["cap_2_2"],
    tip="3x3 的身子一步跳到 1x1 的头 —— 一片方板独扛一颗头。",
)
b.step(
    "合红色尖帽: 四片等腰三角逐片就位, 斜棱两两互吸自锁, 帽尖 4.94。",
    ["hat_s", "hat_e", "hat_n", "hat_w"],
    highlight=["hd_cap"],
    tip="最后一片要同时吸住两条斜棱 —— 对准再松手, 帽子就正了。",
)
b.step(
    "系围巾结并装双臂: 红结骑脖线正下方, 橙色树枝手骑身盖东西沿。",
    ["scarf", "arm_w", "arm_e"],
    highlight=["hd_s"],
    tip="围巾结'身盖沿+墙顶'一线双吸 —— 寒风里也吹不掉。",
)
b.step(
    "插上大扫帚: 橙色等腰大扫帚骑进西南角雪地缝, 雪人完工!",
    ["broom"],
    highlight=["sn0_0"],
    tip="扫帚重心正压地缝铰链线 —— 明天早上第一件事: 拍张合影!",
)

b.finalize(
    model_id="snowman_01",
    name="冬日雪人广场",
    name_en="Snowman Plaza 01",
    description=(
        "只用核心九片型的大雪人, 结构签名是'三比一突变收分': 身子是"
        " 3x3 足印的两节空心大墙环 (整边共线上叠, 四角竖边互咬, R8 "
        "高层检查靠闭环拓扑天然通过), 身盖 9 宫格周圈吸墙顶、中心一片"
        "靠邻板共面互吸环撑成板; 脖子处一步从 3x3 跳到 1x1 —— 雪球头"
        "的四片墙全骑在身盖正中那片方板的四条边上, 一片方板独扛一颗"
        "头; 头顶红色等腰四坡尖帽四棱自锁、帽尖 4.94 全场制高。窗格方"
        "作煤扣与眼睛, 红围巾结骑脖线, 双树枝手臂从身盖沿伸出, 雪地"
        "一角还插着一把等腰大扫帚 —— 拍完合影再回屋喝热可可!"
    ),
    difficulty=3,
    tags=["节日", "冬季", "雪人", "亲子", "挑战"],
    min_pieces=72,
    min_steps=14,
)
