#!/usr/bin/env python3
"""生成模型 data/models/space_elevator_01.json (太空电梯锚地站)。

科幻/实验室主题 4/4: 全库第一座 "缆塔 + 廊桥 + 爬升舱" 三位一体
高塔 —— 与 control_tower_01 (长板筒塔 + 十字挑台)、crane_tower
(井架 + 吊臂) 和 rocket_launchpad_01 (勤务塔摆渡桥对接火箭) 的
结构逻辑刻意区分: 1x1 缆塔四层墙环拔地而起 (灰实墙与透明导轨层
相间), 塔脚四片直角三角锚碇斜撑呈风车状分踞四角 (竖边吸塔角
竖边 / 横边吸地坪拼缝, 双边受力); 塔东两层候乘楼一层门框方
检票口、二层整圈玻璃候乘厅, 楼顶与塔身之间一片青色登舱廊桥
两端整边双吸 —— 把塔与楼锁成大环; 廊桥上一间三面透明爬升舱
正扒着塔身导轨层待发, 舱顶盖板反手又咬住塔身第三层; 塔顶盖板
上等腰四坡配重锥四棱自锁, 锥尖 5.94 全场最高 —— 那是伸向
同步轨道的缆绳起点; 塔下控制亭骑黄雷达, 双红信标把守登塔道 ——
地面站就绪, 爬升舱出发!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 候乘楼在东):
  - 锚地地坪 6x6: 方板 + 长板混铺                            23 片
  - 缆塔: 1x1 墙环 x4 层 (z 0..4, 实墙/导轨相间)             16 片
  - 锚碇斜撑: 直角三角 x4 (风车状分踞塔脚四角)                4 片
  - 候乘楼: 一层门框方 + 三墙, 二层玻璃厅 x6, 楼顶板 x1      11 片
  - 登舱廊桥: 方板 x1 (西吸塔身顶 / 东吸楼墙顶, 双端受力)     1 片
  - 爬升舱: 透明舱壁 x3 + 舱顶板 x1 (反咬塔身第三层)          4 片
  - 塔顶: 盖板 x1 + 等腰四坡配重锥 x4 (锥尖 5.94)             5 片
  - 控制亭: 三墙 + 舷窗 + 顶板 + 黄雷达                       6 片
  - 登塔道信标: 红色等边三角 x2                                2 片
  合计 72 片, 12 个教程步骤, 7 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (R1~R8 全绿, strict 档零警告):
  - 缆塔每层 4 片墙四角竖边互吸成环, 层间整边竖叠 (纯压),
    塔高 4.0 但环环相扣非树状 —— 通过 R8 无桁架高墙检查;
  - 锚碇斜撑竖边吸塔角、横边吸地缝, 塔脚四向加固;
  - 廊桥西边吸塔身二层顶、东边吸候乘楼墙顶 (双端受力力矩零);
    爬升舱壁立在廊桥三沿, 舱顶板又整边咬回塔身第三层顶 ——
    剪断任何一条铰链线, 力都能绕塔-桥-楼大环走通 (R8 冗余);
  - 配重锥四棱两两自锁, 正压塔顶盖板 (纯压零弯矩);
  - 全程无悬挑无吊挂, strict 弱磁档零警告。

用法: python3 tools/generate_space_elevator.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

FIELD = "gray"      # 锚地地坪
PAD = "orange"      # 塔基锚碇圈
TOWER = "gray"      # 缆塔实墙层
RAIL = "clear"      # 缆塔导轨层 (透明窗格方)
ANCHOR = "orange"   # 锚碇斜撑
BLDG = "gray"       # 候乘楼
GATE = "yellow"     # 检票口
GLASS = "clear"     # 候乘厅 / 爬升舱
BRIDGE = "cyan"     # 登舱廊桥 / 舱顶
CAP = "gray"        # 塔顶盖板
WEIGHT = "red"      # 配重锥
RADAR = "yellow"    # 控制亭雷达
BEACON = "red"      # 信标

# =================================================================
# 1. 地坪 (x [0,6], y [0,6]): 拼缝对准塔脚 / 斜撑 / 楼墙线
# =================================================================
b.flat_rect("e0_a", 0, 0, 0.0, FIELD)
b.flat_rect("e0_b", 2, 0, 0.0, FIELD)
b.flat_rect("e0_c", 4, 0, 0.0, FIELD)

b.flat_rect("e1_a", 0, 1, 0.0, FIELD)
b.flat("e1_b", 2, 1, 0.0, PAD)            # 登塔道
b.flat("e1_c", 3, 1, 0.0, PAD)
b.flat_rect("e1_d", 4, 1, 0.0, FIELD)

b.flat("e2_a", 0, 2, 0.0, FIELD)
b.flat("e2_b", 1, 2, 0.0, PAD)
b.flat("e2_c", 2, 2, 0.0, PAD)            # 塔基
b.flat("e2_d", 3, 2, 0.0, PAD)
b.flat_rect("e2_e", 4, 2, 0.0, BLDG)      # 候乘楼地板

b.flat_rect("e3_a", 0, 3, 0.0, FIELD)
b.flat("e3_b", 2, 3, 0.0, PAD)
b.flat("e3_c", 3, 3, 0.0, PAD)
b.flat_rect("e3_d", 4, 3, 0.0, FIELD)

b.flat("e4_a", 0, 4, 0.0, FIELD)          # 控制亭地板
b.flat_rect("e4_b", 1, 4, 0.0, FIELD)
b.flat_rect("e4_c", 3, 4, 0.0, FIELD)
b.flat("e4_d", 5, 4, 0.0, FIELD)

b.flat_rect("e5_a", 0, 5, 0.0, FIELD)
b.flat_rect("e5_b", 2, 5, 0.0, FIELD)
b.flat_rect("e5_c", 4, 5, 0.0, FIELD)

# =================================================================
# 2. 缆塔 (x [2,3], y [2,3]): 四层墙环, 实墙 / 导轨相间
# =================================================================
def tower_level(level, z, shape, color):
    b.add(f"tw{level}_s", shape, (2.5, 2.0, z + 0.5), (90, 0, 0), color)
    b.add(f"tw{level}_n", shape, (2.5, 3.0, z + 0.5), (90, 0, 0), color)
    b.add(f"tw{level}_w", shape, (2.0, 2.5, z + 0.5), (90, 0, 90), color)
    b.add(f"tw{level}_e", shape, (3.0, 2.5, z + 0.5), (90, 0, 90), color)
    return [f"tw{level}_s", f"tw{level}_n", f"tw{level}_w", f"tw{level}_e"]

L1 = tower_level(1, 0.0, "square", TOWER)
L2 = tower_level(2, 1.0, "window_square", RAIL)
L3 = tower_level(3, 2.0, "square", TOWER)
L4 = tower_level(4, 3.0, "window_square", RAIL)

# 锚碇斜撑: 风车状分踞塔脚四角 (竖边吸塔角竖边 / 横边吸地缝)
b.brace("br_s", (2, 2, 0), "-x", ANCHOR)
b.brace("br_e", (3, 2, 0), "-y", ANCHOR)
b.brace("br_n", (3, 3, 0), "+x", ANCHOR)
b.brace("br_w", (2, 3, 0), "+y", ANCHOR)

# =================================================================
# 3. 候乘楼 (x [4,6], y [2,3], z 0..2): 检票口 + 玻璃候乘厅
# =================================================================
b.add("bd_w1", "door_frame", (4.0, 2.5, 0.5), (90, 0, 90), GATE)  # 检票口
b.lintel_ns("bd_s1", 4, 2.0, 0, BLDG)
b.lintel_ns("bd_n1", 4, 3.0, 0, BLDG)
b.wall_ew("bd_e1", 6.0, 2, 0, BLDG)
b.add("bd_w2", "window_square", (4.0, 2.5, 1.5), (90, 0, 90), GLASS)
b.add("ws_s2a", "window_square", (4.5, 2.0, 1.5), (90, 0, 0), GLASS)
b.add("ws_s2b", "window_square", (5.5, 2.0, 1.5), (90, 0, 0), GLASS)
b.add("ws_n2a", "window_square", (4.5, 3.0, 1.5), (90, 0, 0), GLASS)
b.add("ws_n2b", "window_square", (5.5, 3.0, 1.5), (90, 0, 0), GLASS)
b.wall_ew("bd_e2", 6.0, 2, 1, BLDG)
b.flat_rect("bd_roof", 4, 2, 2.0, BLDG)

# 登舱廊桥 (z=2): 西吸塔身二层顶 / 东吸候乘楼墙顶, 双端受力
b.flat("bridge", 3, 2, 2.0, BRIDGE)

# =================================================================
# 4. 爬升舱 (x [3,4], y [2,3], z 2..3): 三面透明扒着塔身导轨
# =================================================================
b.add("pod_s", "window_square", (3.5, 2.0, 2.5), (90, 0, 0), GLASS)
b.add("pod_n", "window_square", (3.5, 3.0, 2.5), (90, 0, 0), GLASS)
b.add("pod_e", "window_square", (4.0, 2.5, 2.5), (90, 0, 90), GLASS)
b.flat("pod_roof", 3, 2, 3.0, BRIDGE)     # 反手咬住塔身第三层顶

# =================================================================
# 5. 塔顶 (z=4): 盖板 + 等腰四坡配重锥 (锥尖 5.94)
# =================================================================
b.flat("tw_cap", 2, 2, 4.0, CAP)
CW = b.hat4("cw", 2, 2, 4.0, WEIGHT, shape="isosceles_triangle")

# =================================================================
# 6. 控制亭 (x [0,1], y [4,5]) + 登塔道信标
# =================================================================
b.wall_ns("kk_s", 0, 4.0, 0, BLDG)
b.wall_ns("kk_n", 0, 5.0, 0, BLDG)
b.wall_ew("kk_e", 1.0, 4, 0, BLDG)
b.add("kk_w", "window_square", (0.0, 4.5, 0.5), (90, 0, 90), GLASS)
b.flat("kk_roof", 0, 4, 1.0, BLDG)
b.crest_ew("kk_radar", 1.0, 4, 1.0, RADAR)

b.crest_ns("bc1", 2, 1.0, 0.0, BEACON)
b.crest_ns("bc2", 3, 1.0, 0.0, BEACON)

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺南侧地坪 (y [0,2]): 7 片, 橙色登塔道指向塔基。",
    ["e0_a", "e0_b", "e0_c", "e1_a", "e1_b", "e1_c", "e1_d"],
    tip="橙色方板是登塔道 —— 乘客从这里走向检票口。",
)
b.step(
    "铺塔基排 (y [2,3]): 5 片, 缆塔与候乘楼共用这排拼缝。",
    ["e2_a", "e2_b", "e2_c", "e2_d", "e2_e"],
    highlight=["e1_b"],
    tip="塔基四周留出整圈橙色锚碇圈, 东侧长板是候乘楼地板。",
)
b.step(
    "铺北侧地坪 (y [3,6]): 11 片, 锚地合拢。",
    ["e3_a", "e3_b", "e3_c", "e3_d",
     "e4_a", "e4_b", "e4_c", "e4_d", "e5_a", "e5_b", "e5_c"],
    highlight=["e2_c"],
    tip="6x6 锚地铺满 —— 这一整片地坪就是缆塔的地基。",
)
b.step(
    "立缆塔第一层、装锚碇斜撑: 墙环 4 片 + 直角三角 4 片。",
    L1 + ["br_s", "br_e", "br_n", "br_w"],
    highlight=["e2_c"],
    tip="斜撑风车状分踞四角: 竖边吸塔角, 横边吸地缝, 双边受力。",
)
b.step(
    "起候乘楼一层: 黄色门框方检票口朝塔, 双横楣夹住楼身。",
    ["bd_w1", "bd_s1", "bd_n1", "bd_e1"],
    highlight=["e2_e"],
    tip="横楣底边与地板长边 2 对 2 整边吸合, 严丝合缝。",
)
b.step(
    "缆塔升到第二层: 4 片透明导轨窗环环相扣。",
    L2,
    highlight=["tw1_s"],
    tip="透明层是爬升舱的导轨段 —— 舱体待会儿就扒在这里。",
)
b.step(
    "封候乘楼玻璃厅、盖楼顶、搭登舱廊桥: 8 片。",
    ["bd_w2", "ws_s2a", "ws_s2b", "ws_n2a", "ws_n2b", "bd_e2",
     "bd_roof", "bridge"],
    highlight=["tw2_e"],
    tip="青色廊桥西吸塔顶东吸楼顶 —— 塔与楼从此锁成一个大环。",
)
b.step(
    "缆塔升到第三层: 4 片实墙, 塔身超过候乘楼。",
    L3,
    highlight=["bridge"],
    tip="第三层顶边一会儿要被爬升舱顶板反手咬住 —— 位置对准。",
)
b.step(
    "廊桥上组装爬升舱: 三面透明舱壁 + 舱顶板反咬塔身。",
    ["pod_s", "pod_n", "pod_e", "pod_roof"],
    highlight=["bridge", "tw3_e"],
    tip="舱壁立在廊桥三沿, 舱顶又整边咬回塔身 —— 双保险。",
)
b.step(
    "缆塔升到第四层: 4 片透明导轨窗, 塔高 4.0。",
    L4,
    highlight=["pod_roof"],
    tip="四层墙环环环相扣, 这是全库最高的自锁缆塔之一。",
)
b.step(
    "封塔顶、锁配重锥: 盖板 + 4 片等腰锥四棱自锁, 锥尖 5.94。",
    ["tw_cap"] + CW,
    highlight=["tw4_s"],
    tip="红色配重锥是缆绳伸向同步轨道的起点 —— 全场最高点。",
)
b.step(
    "建控制亭、插信标 —— 地面站就绪, 爬升舱出发!",
    ["kk_s", "kk_n", "kk_e", "kk_w", "kk_roof", "kk_radar",
     "bc1", "bc2"],
    highlight=["bd_w1"],
    tip="黄雷达骑亭顶东沿盯着塔尖, 双红信标把守登塔道口。",
)

b.finalize(
    model_id="space_elevator_01",
    name="太空电梯锚地站",
    name_en="Space Elevator 01",
    description=(
        "全库第一座 '缆塔 + 廊桥 + 爬升舱' 三位一体高塔: 1x1 缆塔"
        "四层墙环拔地而起 (实墙与透明导轨层相间), 塔脚四片直角三角"
        "锚碇斜撑风车状分踞四角; 候乘楼一层检票口二层整圈玻璃厅, "
        "青色登舱廊桥两端整边双吸把塔与楼锁成大环; 廊桥上三面透明"
        "爬升舱扒着导轨层待发, 舱顶板反手咬回塔身; 塔顶等腰四坡"
        "配重锥四棱自锁, 锥尖 5.94 全场最高 —— 那是伸向同步轨道的"
        "缆绳起点; 塔下控制亭骑黄雷达、双红信标把守登塔道。"
    ),
    difficulty=3,
    tags=["航天", "太空电梯", "科幻", "高塔", "进阶"],
    min_pieces=72,
    min_steps=12,
)
