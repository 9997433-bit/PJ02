#!/usr/bin/env python3
"""生成模型 data/models/safari_lodge_01.json (草原观兽庐)。

动物园/野生动物主题批 1/4: 全库第一座戴"遮阳檐环"的观兽建筑 ——
与 pet_clinic_01 (平顶主楼+锥顶犬舍)、whale_watching_01 (崖顶观景台
+30 度栈道)、ski_lodge_01 (A 字对倾雪顶) 刻意区分, 本作的结构逻辑是
"双层全景塔 + 45 度外倾遮阳檐 + 平顶金合欢": 2x2 观兽庐一层夯土墙
(门框方庐门朝南), 二层八扇窗格方 360 度全景观察窗; 屋顶改用 4 片
方板 (四边各吸两段墙顶, 拼缝十字咬合), 檐口一圈 8 片等边三角以
45 度外倾垂下 —— 底边同时吸墙顶与屋顶板沿 (一线双吸), 一圈"草檐"
既遮阳又是本作的招牌几何; 屋脊红色等腰瞭望旗骑上屋顶十字拼缝。
草原上两棵平顶金合欢树 (1x1 树干墙环 + 方板平树冠 + 四片竖立
绿冠齿骑冠沿) 与东侧 2x2 蓝色水潭构成观兽场景, 步道红旗指路。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 草原地坪 (x [0,7], y [0,4]): 方板 x20 + 长板 x4
    (含 4 片蓝色水潭 [5,7]x[1,3]、灰色步道、庐基灰砖)          24 片
  - 观兽庐一层 [1,3]x[1,3] (z 0..1): 门框方庐门 + 7 片夯土墙     8 片
  - 观兽庐二层 (z 1..2): 8 扇窗格方全景观察窗                    8 片
  - 庐顶 (z=2): 4 片方板 (每片吸两段墙顶 + 两条拼缝)             4 片
  - 遮阳檐环: 8 片等边三角 45 度外倾垂檐 (一线双吸)              8 片
  - 瞭望旗: 红色等腰塔尖骑屋顶拼缝 (旗尖 4.0 全场最高)           1 片
  - 平顶金合欢 x2: 树干墙环 4 + 平树冠方板 1 + 绿冠齿 x4         18 片
  - 步道红旗: 等边三角骑步道东沿                                 1 片
  合计 72 片, 13 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 遮阳檐: 每片等边三角底边同时吸二层墙顶与屋顶板沿 (双连接),
    45 度外倾力矩 13g x 0.204 = 2.7 g·单位 << strict 抗弯预算
    17.5 g·单位, 悬垂质量 13g << 悬挂预算 84g/单位边长;
  - 庐顶 4 方板: 每片两条外沿各整边压一段墙顶、两条内沿与邻板
    拼缝互吸 —— 墙-顶-墙-地坪锁成箱形闭环, 无单点失效;
  - 二层墙环: 底边整边压一层墙顶, 四角竖边互吸自锁成环;
  - 金合欢: 树干四片墙环四角互吸, 平树冠四边全吸树干顶,
    绿冠齿骑冠沿 (冠沿+干顶一线双吸), 重心正压铰链线力矩为零;
  - 瞭望旗/步道红旗重心正压底边, 力矩为零。

用法: python3 tools/generate_safari_lodge_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

COS45 = 0.7071068
TRI_H = 0.866025         # 等边三角形高 (sqrt(3)/2)
BRIM_OFF = round(TRI_H * COS45, 6)   # 45 度外倾檐的水平/竖直投影 0.612372

b = ModelBuilder()

SAND = "yellow"      # 草原沙地
GRASS = "green"      # 草地
PATH = "gray"        # 步道 / 庐基
WATER = "blue"       # 水潭
WALL1 = "orange"     # 一层夯土墙
DOOR = "orange"      # 庐门 (门框方)
WIN = "clear"        # 二层全景观察窗
ROOF = "yellow"      # 草顶
BRIM = "yellow"      # 遮阳檐
FLAG = "red"         # 瞭望旗 / 步道红旗
TRUNK = "orange"     # 金合欢树干
CROWN = "green"      # 金合欢平树冠

# =================================================================
# 1. 草原地坪 (x [0,7], y [0,4]): 24 片
#    观兽庐 [1,3]x[1,3] 与树坑周边全用方板, 保证墙脚整边有吸;
#    水潭 [5,7]x[1,3] 4 片蓝色方板。
# =================================================================
# 行 y0: 方 x2 (含步道) + 长板 x2 + 方 x1
b.flat("gd_0_0", 0, 0, 0.0, SAND)
b.flat("gd_1_0", 1, 0, 0.0, PATH)          # 庐门前步道
b.flat_rect("gd_2_0", 2, 0, 0.0, SAND)
b.flat_rect("gd_4_0", 4, 0, 0.0, GRASS)
b.flat("gd_6_0", 6, 0, 0.0, SAND)          # 金合欢 2 号树坑
# 行 y1: 全方板 (庐基 + 水潭)
b.flat("gd_0_1", 0, 1, 0.0, SAND)
b.flat("gd_1_1", 1, 1, 0.0, PATH)
b.flat("gd_2_1", 2, 1, 0.0, PATH)
b.flat("gd_3_1", 3, 1, 0.0, GRASS)
b.flat("gd_4_1", 4, 1, 0.0, SAND)
b.flat("gd_5_1", 5, 1, 0.0, WATER)
b.flat("gd_6_1", 6, 1, 0.0, WATER)
# 行 y2: 全方板
b.flat("gd_0_2", 0, 2, 0.0, GRASS)
b.flat("gd_1_2", 1, 2, 0.0, PATH)
b.flat("gd_2_2", 2, 2, 0.0, PATH)
b.flat("gd_3_2", 3, 2, 0.0, SAND)
b.flat("gd_4_2", 4, 2, 0.0, GRASS)         # 金合欢 1 号树坑
b.flat("gd_5_2", 5, 2, 0.0, WATER)
b.flat("gd_6_2", 6, 2, 0.0, WATER)
# 行 y3: 长板 x2 + 方 x3
b.flat_rect("gd_0_3", 0, 3, 0.0, GRASS)
b.flat_rect("gd_2_3", 2, 3, 0.0, SAND)
b.flat("gd_4_3", 4, 3, 0.0, SAND)
b.flat("gd_5_3", 5, 3, 0.0, GRASS)
b.flat("gd_6_3", 6, 3, 0.0, SAND)

# =================================================================
# 2. 观兽庐一层 [1,3]x[1,3] (z 0..1): 门框方庐门朝南 + 7 片夯土墙
# =================================================================
b.add("w1_s_door", "door_frame", (1.5, 1.0, 0.5), (90, 0, 0), DOOR)
b.wall_ns("w1_s_2", 2, 1.0, 0, WALL1)
b.wall_ns("w1_n_1", 1, 3.0, 0, WALL1)
b.wall_ns("w1_n_2", 2, 3.0, 0, WALL1)
b.wall_ew("w1_w_1", 1.0, 1, 0, WALL1)
b.wall_ew("w1_w_2", 1.0, 2, 0, WALL1)
b.wall_ew("w1_e_1", 3.0, 1, 0, WALL1)
b.wall_ew("w1_e_2", 3.0, 2, 0, WALL1)

# =================================================================
# 3. 观兽庐二层 (z 1..2): 8 扇窗格方全景观察窗
# =================================================================
for k, (x, y, rz) in enumerate((
        (1.5, 1.0, 0), (2.5, 1.0, 0),      # 南
        (1.5, 3.0, 0), (2.5, 3.0, 0),      # 北
        (1.0, 1.5, 90), (1.0, 2.5, 90),    # 西
        (3.0, 1.5, 90), (3.0, 2.5, 90))):  # 东
    b.add(f"w2_{k}", "window_square", (x, y, 1.5), (90, 0, rz), WIN)

# =================================================================
# 4. 庐顶 (z=2): 4 片方板十字咬合
# =================================================================
b.flat("rf_sw", 1, 1, 2.0, ROOF)
b.flat("rf_se", 2, 1, 2.0, ROOF)
b.flat("rf_nw", 1, 2, 2.0, ROOF)
b.flat("rf_ne", 2, 2, 2.0, ROOF)

# =================================================================
# 5. 遮阳檐环: 8 片等边三角 45 度外倾 (底边一线双吸墙顶+板沿)
# =================================================================
BRIM_EDGES = [
    # (id, b0, b1, 外倾方向)
    ("br_s_1", (1, 1, 2), (2, 1, 2), (0, -1)),
    ("br_s_2", (2, 1, 2), (3, 1, 2), (0, -1)),
    ("br_n_1", (2, 3, 2), (1, 3, 2), (0, 1)),
    ("br_n_2", (3, 3, 2), (2, 3, 2), (0, 1)),
    ("br_w_1", (1, 2, 2), (1, 1, 2), (-1, 0)),
    ("br_w_2", (1, 3, 2), (1, 2, 2), (-1, 0)),
    ("br_e_1", (3, 1, 2), (3, 2, 2), (1, 0)),
    ("br_e_2", (3, 2, 2), (3, 3, 2), (1, 0)),
]
for tid, b0, b1, (ox, oy) in BRIM_EDGES:
    mid = ((b0[0] + b1[0]) / 2, (b0[1] + b1[1]) / 2, 2.0)
    apex = (round(mid[0] + ox * BRIM_OFF, 6),
            round(mid[1] + oy * BRIM_OFF, 6),
            round(2.0 - BRIM_OFF, 6))
    b.place_tri(tid, "equilateral_triangle", b0, b1, apex, BRIM)

# =================================================================
# 6. 瞭望旗: 红色等腰塔尖骑屋顶南北拼缝 (x=2, y [1,2])
# =================================================================
b.spire_ew("flag_top", 2.0, 1, 2.0, FLAG)

# =================================================================
# 7. 平顶金合欢 x2: 树干墙环 + 平树冠 + 4 片绿冠齿
# =================================================================
def acacia(prefix, x0, y0):
    b.wall_ns(f"{prefix}_s", x0, y0 + 0.0, 0, TRUNK)
    b.wall_ns(f"{prefix}_n", x0, y0 + 1.0, 0, TRUNK)
    b.wall_ew(f"{prefix}_w", x0 + 0.0, y0, 0, TRUNK)
    b.wall_ew(f"{prefix}_e", x0 + 1.0, y0, 0, TRUNK)
    b.flat(f"{prefix}_cap", x0, y0, 1.0, CROWN)
    b.crest_ns(f"{prefix}_c_s", x0, y0 + 0.0, 1.0, CROWN)
    b.crest_ns(f"{prefix}_c_n", x0, y0 + 1.0, 1.0, CROWN)
    b.crest_ew(f"{prefix}_c_w", x0 + 0.0, y0, 1.0, CROWN)
    b.crest_ew(f"{prefix}_c_e", x0 + 1.0, y0, 1.0, CROWN)

acacia("tr1", 4, 2)     # 1 号树: 水潭西岸
acacia("tr2", 6, 0)     # 2 号树: 东南角

# =================================================================
# 8. 步道红旗: 骑步道东沿 (x=2, y [0,1])
# =================================================================
b.crest_ew("flag_path", 2.0, 0, 0.0, FLAG)

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺草原西半段 (x [0,4], y [0,3]): 方板为主, 庐基与步道用灰色。",
    ["gd_0_0", "gd_1_0", "gd_2_0", "gd_0_1", "gd_1_1", "gd_2_1", "gd_3_1",
     "gd_0_2", "gd_1_2", "gd_2_2", "gd_3_2"],
    tip="观兽庐 [1,3]x[1,3] 周边全用方板 —— 墙脚每条整边都有得吸。",
)
b.step(
    "铺草原东半段: 4 片蓝色方板拼出水潭 [5,7]x[1,3], 旱季它是动物的客厅。",
    ["gd_4_0", "gd_6_0", "gd_4_1", "gd_5_1", "gd_6_1", "gd_4_2", "gd_5_2",
     "gd_6_2"],
    highlight=["gd_3_1", "gd_3_2"],
    tip="水潭边留出两格草地树坑 —— 金合欢就种在岸边。",
)
b.step(
    "铺北沿收边: 2 片长板 + 3 片方板, 草原 7x4 合拢。",
    ["gd_0_3", "gd_2_3", "gd_4_3", "gd_5_3", "gd_6_3"],
    highlight=["gd_0_2", "gd_6_2"],
    tip="长板长边压齐网格线 —— 地坪平整, 上面的建筑才正。",
)
b.step(
    "立观兽庐一层: 南面橙色门框方庐门朝步道, 其余 7 片夯土墙围成 2x2 环。",
    ["w1_s_door", "w1_s_2", "w1_n_1", "w1_n_2", "w1_w_1", "w1_w_2",
     "w1_e_1", "w1_e_2"],
    highlight=["gd_1_0", "gd_1_1"],
    tip="八片墙四角竖边互吸自锁成环 —— 夯土墙是热带草原的隔热层。",
)
b.step(
    "立二层全景观察窗: 8 扇透明窗格方压上一层墙顶, 360 度无死角。",
    [f"w2_{k}" for k in range(8)],
    highlight=["w1_s_door", "w1_n_1"],
    tip="底边整边压一层墙顶, 四角竖边再互吸 —— 上下两环越锁越紧。",
)
b.step(
    "盖庐顶: 4 片方板十字咬合, 每片同时吸两段墙顶与两条拼缝。",
    ["rf_sw", "rf_se", "rf_nw", "rf_ne"],
    highlight=["w2_0", "w2_2"],
    tip="墙-顶-墙-地坪锁成箱形闭环 —— 剪断任何一处也塌不了。",
)
b.step(
    "挂南北遮阳檐: 4 片黄色等边三角以 45 度外倾垂下, 底边一线双吸"
    "墙顶与屋顶板沿。",
    ["br_s_1", "br_s_2", "br_n_1", "br_n_2"],
    highlight=["rf_sw", "rf_ne"],
    tip="外倾力矩只有 2.7 g·单位, 远小于预算 —— 草檐遮阳不坠落。",
)
b.step(
    "挂东西遮阳檐: 再挂 4 片, 檐环合拢一圈。",
    ["br_w_1", "br_w_2", "br_e_1", "br_e_2"],
    highlight=["br_s_1", "br_n_1"],
    tip="同侧两片檐共面互贴 —— 一圈'草帽檐'是观兽庐的招牌。",
)
b.step(
    "升瞭望旗: 红色等腰塔尖骑上屋顶十字拼缝 (旗尖 4.0, 全场最高)。",
    ["flag_top"],
    highlight=["rf_sw", "rf_se"],
    tip="重心正压拼缝线, 力臂为零 —— 草原的风吹不倒它。",
)
b.step(
    "种 1 号金合欢 (水潭西岸): 4 片橙色树干墙环四角互吸, 平树冠方板"
    "四边全吸干顶。",
    ["tr1_s", "tr1_n", "tr1_w", "tr1_e", "tr1_cap"],
    highlight=["gd_4_2"],
    tip="金合欢的树冠是平的 —— 长颈鹿都够不到顶。",
)
b.step(
    "给 1 号树插绿冠齿: 4 片绿色等边三角骑树冠四沿 (冠沿+干顶一线双吸)。",
    ["tr1_c_s", "tr1_c_n", "tr1_c_w", "tr1_c_e"],
    highlight=["tr1_cap"],
    tip="每片冠齿重心正压铰链线 —— 树冠看着蓬松, 其实纹丝不动。",
)
b.step(
    "种 2 号金合欢 (东南角): 树干、树冠、冠齿一次到位。",
    ["tr2_s", "tr2_n", "tr2_w", "tr2_e", "tr2_cap",
     "tr2_c_s", "tr2_c_n", "tr2_c_w", "tr2_c_e"],
    highlight=["tr1_cap"],
    tip="两棵树隔着水潭对望 —— 象群来喝水时就躲在树荫里看。",
)
b.step(
    "插步道红旗: 骑上步道东沿 —— 嘘, 别出声, 角马群正走向水潭!",
    ["flag_path"],
    highlight=["gd_1_0"],
    tip="红旗指向庐门 —— 游客沿步道进庐, 上二层全景窗观兽。",
)

b.finalize(
    model_id="safari_lodge_01",
    name="草原观兽庐",
    name_en="Safari Lodge 01",
    description=(
        "只用核心九片型的草原观兽建筑: 2x2 观兽庐一层夯土墙 (门框方"
        "庐门朝南), 二层八扇窗格方 360 度全景观察窗, 庐顶 4 片方板"
        "十字咬合 (每片吸两段墙顶+两条拼缝); 招牌是檐口一圈 8 片等边"
        "三角 45 度外倾的遮阳檐环 —— 底边一线双吸墙顶与板沿, 力矩"
        "2.7 远小于预算; 屋脊红色瞭望旗骑十字拼缝直上 4.0。草原上"
        "两棵平顶金合欢 (树干墙环+平树冠+绿冠齿骑沿) 隔着 2x2 蓝色"
        "水潭对望, 步道红旗引路 —— 上二层, 等角马群来喝水。"
    ),
    difficulty=3,
    tags=["动物园", "野生动物", "草原", "观察哨", "进阶"],
    min_pieces=72,
    min_steps=13,
)
