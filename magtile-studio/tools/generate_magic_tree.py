#!/usr/bin/env python3
"""生成模型 data/models/magic_tree_01.json (魔法垂枝树)。

童话/奇幻主题 3/4: 全库第一棵 "垂枝" 大树 —— 与 treehouse_01
(2x2 空心树干 + 四柱平台小屋) / rainforest_canopy_01 的结构逻辑
刻意区分: 本作的主角是 "披挂式树冠", 1x1 空心树干三层拔起 (树洞
门框方 + 精灵窗格方), 两圈各 4 片绿色方形垂枝从墙顶铰链向外下垂
30 度 —— 每片底边同时吸下层墙顶与上层墙底 (一线双吸), 像蓑衣
一样披在树干上; 树顶盖板再戴等腰四坡粉色花冠 (树尖 4.94); 树下
一红一黄两朵四棱自锁的蘑菇圈, 小径两侧萤光花开。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 树洞门朝南):
  - 地面 (x [0,5], y [0,5]): 草地 + 石板小径 5 行               21 片
  - 树干 (x [2,3], y [2,3], z 0..3): 三层墙环 (门框方树洞 x1 +
    窗格方精灵窗 x1)                                            12 片
  - 垂枝: 下圈 x4 (z=2 铰链) + 上圈 x4 (z=3 铰链), 各外垂 30 度   8 片
  - 树顶盖板 x1 + 等腰四坡花冠 x4 (树尖 4.94)                    5 片
  - 蘑菇圈: 等边四坡锥 x2 组 (红/黄)                             8 片
  - 萤光花: 等边三角 x4                                          4 片
  合计 58 片, 12 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, strict 档同样全绿):
  - 树干每层 4 片墙环四角竖边互吸闭环, 层层成环无单点失效;
  - 每片垂枝的底边落在两层墙的水平缝上 —— 同时吸下层墙顶与
    上层墙底 (上圈吸墙顶 + 盖板沿), 铰链预算翻倍 (35 g·单位),
    30 度外垂力矩 13.0 g·单位, 富余充足; 垂枝间彼此不接触,
    剪断任一枝只掉一片, 不成链;
  - 花冠四棱两两互吸自锁, 底边与盖板沿/墙顶三线共吸;
  - 蘑菇/萤光花基线全部踩在正方形地砖的整边上。

用法: python3 tools/generate_magic_tree.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

GRASS = "green"     # 草地
PATH = "gray"       # 石板小径
BARK = "orange"     # 树干
DOOR = "orange"     # 门框方树洞
WIN = "clear"       # 窗格方精灵窗
LEAF = "green"      # 垂枝
CAP = "pink"        # 树顶盖板
BLOOM = "pink"      # 花冠
MUSH_A = "red"      # 红蘑菇
MUSH_B = "yellow"   # 黄蘑菇
GLOW_A = "pink"     # 萤光花
GLOW_B = "cyan"

COS30 = 0.866025

# =================================================================
# 1. 地面 (x [0,5], y [0,5]): 5 行, 石板小径通向树洞门
# =================================================================
b.flat("mg0_a", 0, 0, 0.0, GRASS)
b.flat("mg0_b", 1, 0, 0.0, GRASS)
b.flat("mg0_c", 2, 0, 0.0, PATH)
b.flat_rect("mg0_d", 3, 0, 0.0, GRASS)

b.flat_rect("mg1_a", 0, 1, 0.0, GRASS)
b.flat("mg1_b", 2, 1, 0.0, PATH)
b.flat("mg1_c", 3, 1, 0.0, GRASS)
b.flat("mg1_d", 4, 1, 0.0, GRASS)

b.flat("mg2_a", 0, 2, 0.0, GRASS)
b.flat("mg2_b", 1, 2, 0.0, GRASS)
b.flat("mg2_c", 2, 2, 0.0, PATH)
b.flat("mg2_d", 3, 2, 0.0, GRASS)
b.flat("mg2_e", 4, 2, 0.0, GRASS)

b.flat("mg3_a", 0, 3, 0.0, GRASS)
b.flat("mg3_b", 1, 3, 0.0, GRASS)
b.flat("mg3_c", 2, 3, 0.0, GRASS)
b.flat_rect("mg3_d", 3, 3, 0.0, GRASS)

b.flat_rect("mg4_a", 0, 4, 0.0, GRASS)
b.flat("mg4_b", 2, 4, 0.0, GRASS)
b.flat("mg4_c", 3, 4, 0.0, GRASS)
b.flat("mg4_d", 4, 4, 0.0, GRASS)

# =================================================================
# 2. 树干 (x [2,3], y [2,3], z 0..3): 三层墙环
# =================================================================
b.add("tk1_s", "door_frame", (2.5, 2.0, 0.5), (90, 0, 0), DOOR)
b.wall_ew("tk1_w", 2.0, 2, 0, BARK)
b.wall_ew("tk1_e", 3.0, 2, 0, BARK)
b.wall_ns("tk1_n", 2, 3.0, 0, BARK)

b.wall_ns("tk2_s", 2, 2.0, 1, BARK)
b.wall_ew("tk2_w", 2.0, 2, 1, BARK)
b.add("tk2_e", "window_square", (3.0, 2.5, 1.5), (90, 0, 90), WIN)
b.wall_ns("tk2_n", 2, 3.0, 1, BARK)

b.wall_ns("tk3_s", 2, 2.0, 2, BARK)
b.wall_ew("tk3_w", 2.0, 2, 2, BARK)
b.wall_ew("tk3_e", 3.0, 2, 2, BARK)
b.wall_ns("tk3_n", 2, 3.0, 2, BARK)

# =================================================================
# 3. 垂枝两圈: 底边铰在墙层水平缝上, 向外下垂 30 度
# =================================================================
for lv, z in (("1", 2.0), ("2", 3.0)):
    b.place_edge(f"fr{lv}_s", "square", 0, (2.0, 2.0, z), (3.0, 2.0, z),
                 (0.0, -COS30, -0.5), LEAF)
    b.place_edge(f"fr{lv}_n", "square", 0, (2.0, 3.0, z), (3.0, 3.0, z),
                 (0.0, COS30, -0.5), LEAF)
    b.place_edge(f"fr{lv}_w", "square", 0, (2.0, 2.0, z), (2.0, 3.0, z),
                 (-COS30, 0.0, -0.5), LEAF)
    b.place_edge(f"fr{lv}_e", "square", 0, (3.0, 2.0, z), (3.0, 3.0, z),
                 (COS30, 0.0, -0.5), LEAF)

# =================================================================
# 4. 树顶盖板 + 花冠 (树尖 4.94)
# =================================================================
b.flat("crown_cap", 2, 2, 3.0, CAP)
CROWN_IDS = b.hat4("crown", 2, 2, 3.0, BLOOM)

# =================================================================
# 5. 蘑菇圈 + 萤光花
# =================================================================
MUSH_R = b.hat4("mush_r", 4, 1, 0.0, MUSH_A, shape="equilateral_triangle")
MUSH_Y = b.hat4("mush_y", 0, 3, 0.0, MUSH_B, shape="equilateral_triangle")
b.crest_ns("glow_a", 0, 1.0, 0.0, GLOW_A)
b.crest_ns("glow_b", 3, 4.0, 0.0, GLOW_B)
b.crest_ew("glow_c", 2.0, 0, 0.0, GLOW_B)
b.crest_ew("glow_d", 3.0, 0, 0.0, GLOW_A)

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺林间空地南段两行 (y [0,2]): 8 片, 石板小径通向树心。",
    ["mg0_a", "mg0_b", "mg0_c", "mg0_d",
     "mg1_a", "mg1_b", "mg1_c", "mg1_d"],
    tip="小径 (x [2,3]) 的尽头就是树洞门。",
)
b.step(
    "铺树根一行 (y [2,3]): 5 片, 树干踩这一行的格线。",
    ["mg2_a", "mg2_b", "mg2_c", "mg2_d", "mg2_e"],
    highlight=["mg1_b"],
    tip="x=2 与 x=3 的拼缝是树干的四条根线。",
)
b.step(
    "铺空地北段两行 (y [3,5]): 8 片, 草地合拢。",
    ["mg3_a", "mg3_b", "mg3_c", "mg3_d",
     "mg4_a", "mg4_b", "mg4_c", "mg4_d"],
    highlight=["mg2_c"],
    tip="5x5 空地铺满 —— 魔法树独占林间一方天地。",
)
b.step(
    "立树干第 1 层: 4 片墙环, 南面是橙色门框方树洞。",
    ["tk1_s", "tk1_w", "tk1_e", "tk1_n"],
    highlight=["mg1_b", "mg2_c"],
    tip="树洞门正对小径 —— 每片底边吸缝、转角竖边互咬。",
)
b.step(
    "叠树干第 2 层: 东面嵌窗格方精灵窗。",
    ["tk2_s", "tk2_w", "tk2_e", "tk2_n"],
    highlight=["tk1_s"],
    tip="精灵住在树干里, 窗户朝着日出的方向。",
)
b.step(
    "叠树干第 3 层: 4 片墙环, 树干升到 3 格高。",
    ["tk3_s", "tk3_w", "tk3_e", "tk3_n"],
    highlight=["tk2_e"],
    tip="第 3 层墙顶是上圈垂枝与花冠的铰链线。",
)
b.step(
    "披下圈垂枝: 4 片绿色方板从 z=2 水平缝向外下垂 30 度。",
    ["fr1_s", "fr1_n", "fr1_w", "fr1_e"],
    highlight=["tk3_s"],
    tip="每片底边同时吸下层墙顶与上层墙底 —— 铰链预算翻倍。",
)
b.step(
    "盖树顶盖板、披上圈垂枝: 盖板压墙顶, 4 片垂枝再披一圈。",
    ["crown_cap", "fr2_s", "fr2_n", "fr2_w", "fr2_e"],
    highlight=["fr1_s"],
    tip="上圈垂枝同时吸墙顶与盖板沿 —— 像蓑衣一样层层披挂。",
)
b.step(
    "戴粉色花冠: 4 片等腰三角斜棱两两互吸自锁 (树尖 4.94)。",
    CROWN_IDS,
    highlight=["crown_cap"],
    tip="花冠、盖板、墙顶、垂枝共用四条铰链线 —— 越吸越紧。",
)
b.step(
    "种红蘑菇: 4 片等边三角四棱自锁, 踩满一格地砖的四条边。",
    MUSH_R,
    highlight=["mg1_d"],
    tip="蘑菇圈是精灵的板凳 —— 四条基线全在整边上。",
)
b.step(
    "种黄蘑菇: 树的另一侧再来一朵。",
    MUSH_Y,
    highlight=["mush_r_s"],
    tip="一红一黄, 分立树干两角 —— 布局讲究平衡。",
)
b.step(
    "开萤光花 —— 魔法垂枝树落成!",
    ["glow_a", "glow_b", "glow_c", "glow_d"],
    highlight=["mg0_c", "mg4_c"],
    tip="花与地砖共面, 重心正压整边 —— 夜里它们会发光哦!",
)

b.finalize(
    model_id="magic_tree_01",
    name="魔法垂枝树",
    name_en="Magic Weeping Tree 01",
    description=(
        "全库第一棵垂枝大树: 1x1 空心树干三层拔起 (门框方树洞 +"
        " 窗格方精灵窗), 两圈各 4 片绿色方形垂枝从墙层水平缝向外"
        "下垂 30 度 —— 每片底边一线双吸 (下层墙顶 + 上层墙底/盖板沿),"
        " 像蓑衣一样披在树干上; 树顶等腰四坡粉色花冠四棱自锁 (树尖"
        " 4.94); 树下红黄蘑菇圈四棱自锁, 小径两侧萤光花开。披挂式"
        "树冠、缝上铰链、层层成环 —— 一棵树读懂悬挑与自锁。"
    ),
    difficulty=3,
    tags=["童话", "奇幻", "魔法树", "森林", "进阶"],
    min_pieces=56,
    min_steps=12,
)
