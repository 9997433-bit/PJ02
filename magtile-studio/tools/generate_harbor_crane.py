#!/usr/bin/env python3
"""生成模型 data/models/harbor_crane_01.json (港口门吊)。

第三批模型: 工业港口主题 —— 全库第一个"门式起重机": 四条门腿
横跨码头铁轨列车通道, 12 片方板在门腿顶架出整层作业平台,
臂架长板从平台北缘挑向海面、远端落在航道系缆墩上 (双端受力,
一根臂架两条支撑路径); 平台上机房与司机室并肩, 机房顶立 A 字架,
南缘两片配重脊板压舱。码头东侧还叠着两层集装箱。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 码头石板 [0,6]x[0,3]: 南北石板 + 中间装卸警示带 (门腿跨道)   18 片
  - 海面 [0,6]x[3,4] + 航道 [1,4]x[4,5] + 浮标                    10 片
  - 门腿 4 条 x 3 层 + 直角三角护撑 4                             16 片
  - 作业平台 12 方 (中排先压腿顶, 南北排随后合拢)                 12 片
  - 机房 (4 墙 + 顶) + A 字架 2 + 司机室 (4 墙 + 顶)              12 片
  - 臂架长板 1 + 系缆墩 3 + 配重脊板 2                             6 片
  - 集装箱两层 (各 4 墙 + 顶) + 系船柱 2                          12 片
  合计 86 片, 19 个教程步骤, 6 种磁力片形状。

物理要点 (通过 R1~R8 全部校验):
  - 门腿立在 y=1 / y=2 两条轨道边线上, 平台中排两边同时压腿顶,
    南北排再挂中排 —— 剪断任一条腿顶铰链线, 平台仍有 6 条整边
    磁力吸合传力 (预算 120 g·单位, 实际力矩 86);
  - 臂架南端吸平台北缘、北端吸系缆墩顶 —— 两条独立支撑路径,
    剪断任意一端都不成悬臂;
  - 配重脊板竖立在平台南缘正上方, 力臂为零, 纯压不弯。

坐标约定与 C++ 端一致: 旋转为欧拉角 (度), R = Rz * Ry * Rx。
用法: python3 tools/generate_harbor_crane.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

mb = ModelBuilder()

QUAY = "gray"       # 码头石板
LANE = "yellow"     # 装卸警示带 (门腿跨道)
SEA = "blue"        # 海面
LEG = "red"         # 门腿 (港机红)
DECK = "gray"       # 作业平台
HOUSE = "cyan"      # 机房
CAB = "clear"       # 司机室玻璃
JIB = "red"         # 臂架

# =================================================================
# 1. 码头石板 [0,6]x[0,3]: 南排/警示带/北排
# =================================================================
for i in range(6):
    mb.flat(f"q_s{i}", i, 0, 0.0, QUAY)
for i in range(6):
    mb.flat(f"q_m{i}", i, 1, 0.0, LANE)
for i in range(6):
    mb.flat(f"q_n{i}", i, 2, 0.0, QUAY)

# =================================================================
# 2. 海面 [0,6]x[3,4] + 航道 [1,4]x[4,5] + 浮标
# =================================================================
for i in range(6):
    mb.flat(f"sea{i}", i, 3, 0.0, SEA)
for i in range(3):
    mb.flat(f"chan{i}", 1 + i, 4, 0.0, SEA)
mb.crest_ns("buoy", 0, 4.0, 0.0, "pink")           # 浮标立在海面北缘

# =================================================================
# 3. 门腿 4 条 (跨 y [1,2] 警示带) + 直角三角护撑
# =================================================================
for lv in range(3):
    mb.wall_ns(f"leg_sw{lv}", 1, 1.0, lv, LEG)
    mb.wall_ns(f"leg_se{lv}", 4, 1.0, lv, LEG)
for lv in range(3):
    mb.wall_ns(f"leg_nw{lv}", 1, 2.0, lv, LEG)
    mb.wall_ns(f"leg_ne{lv}", 4, 2.0, lv, LEG)
mb.brace("br_sw", (2.0, 1.0, 0.0), "-y", "orange")
mb.brace("br_se", (4.0, 1.0, 0.0), "-y", "orange")
mb.brace("br_nw", (2.0, 2.0, 0.0), "+y", "orange")
mb.brace("br_ne", (4.0, 2.0, 0.0), "+y", "orange")

# =================================================================
# 4. 作业平台 z=3, [1,5]x[0,3]: 中排先压四条腿顶, 南北排随后
# =================================================================
for i in range(4):
    mb.flat(f"dk_m{i}", 1 + i, 1, 3.0, "yellow")   # 中排 (压腿顶)
for i in range(4):
    mb.flat(f"dk_s{i}", 1 + i, 0, 3.0, DECK)       # 南排
for i in range(4):
    mb.flat(f"dk_n{i}", 1 + i, 2, 3.0, DECK)       # 北排

# =================================================================
# 5. 机房 [2,3]x[1,2] + A 字架; 司机室 [4,5]x[1,2]
# =================================================================
mb.wall_ns("mh_s", 2, 1.0, 3, HOUSE)
mb.wall_ns("mh_n", 2, 2.0, 3, HOUSE)
mb.wall_ew("mh_w", 2.0, 1, 3, HOUSE)
mb.wall_ew("mh_e", 3.0, 1, 3, HOUSE)
mb.flat("mh_roof", 2, 1, 4.0, HOUSE)
mb.crest_ew("aframe_w", 2.0, 1, 4.0, "yellow")
mb.crest_ew("aframe_e", 3.0, 1, 4.0, "yellow")

mb.wall_ns("cab_s", 4, 1.0, 3, CAB)
mb.wall_ns("cab_n", 4, 2.0, 3, CAB)
mb.wall_ew("cab_w", 4.0, 1, 3, CAB)
mb.wall_ew("cab_e", 5.0, 1, 3, CAB)
mb.flat("cab_roof", 4, 1, 4.0, "blue")

# =================================================================
# 6. 配重脊板 + 系缆墩 + 臂架
# =================================================================
mb.crest_ns("cw_a", 2, 0.0, 3.0, "purple")         # 配重立在平台南缘
mb.crest_ns("cw_b", 3, 0.0, 3.0, "purple")
for lv in range(3):
    mb.wall_ns(f"pier{lv}", 2, 5.0, lv, QUAY)      # 航道系缆墩
mb.flat_rect("jib", 2, 3, 3.0, JIB, axis="y")      # 臂架 [2,3]x[3,5]

# =================================================================
# 7. 集装箱两层 [5,6]x[0,1] + 系船柱
# =================================================================
for lv, col in ((0, "green"), (1, "orange")):
    mb.wall_ns(f"box{lv}_s", 5, 0.0, lv, col)
    mb.wall_ns(f"box{lv}_n", 5, 1.0, lv, col)
    mb.wall_ew(f"box{lv}_w", 5.0, 0, lv, col)
    mb.wall_ew(f"box{lv}_e", 6.0, 0, lv, col)
    mb.flat(f"box{lv}_roof", 5, 0, lv + 1.0, col)
mb.spire_ns("bollard_a", 0, 0.0, 0.0, "yellow")    # 系船柱
mb.spire_ew("bollard_b", 0.0, 2, 0.0, "yellow")

# =================================================================
# 教程步骤 (19 步)
# =================================================================
mb.step(
    "码头南排: 沿最南侧铺 6 片灰色石板, 相邻边互吸成一条岸线。",
    [f"q_s{i}" for i in range(6)],
    tip="全场以这排石板定位 —— 门吊、集装箱、系船柱都从它出发。",
)
mb.step(
    "装卸警示带: 第二排铺 6 片黄色地板 —— 这是穿过门腿的列车通道。",
    [f"q_m{i}" for i in range(6)],
    highlight=["q_s0", "q_s5"],
    tip="门吊的四条腿稍后就跨立在这条黄带的南北两沿。",
)
mb.step(
    "码头北排: 第三排再铺 6 片灰色石板, 码头面完工。",
    [f"q_n{i}" for i in range(6)],
    highlight=["q_m0", "q_m5"],
)
mb.step(
    "海面: 码头北侧铺 6 片蓝色海面, 南边整边吸住码头北沿。",
    [f"sea{i}" for i in range(6)],
    highlight=["q_n0", "q_n5"],
)
mb.step(
    "航道与浮标: 海面再向北接 3 片航道, 西端海面北缘立 1 片粉色浮标。",
    ["chan0", "chan1", "chan2", "buoy"],
    highlight=["sea1", "sea0"],
    tip="航道中段稍后要立系缆墩, 给臂架当第二条支撑路径。",
)
mb.step(
    "西侧门腿: 警示带西端南北两沿各立一条 3 层红色门腿 (自下而上"
    "逐层叠高, 底边吸石板边)。",
    ["leg_sw0", "leg_sw1", "leg_sw2", "leg_nw0", "leg_nw1", "leg_nw2"],
    highlight=["q_m0"],
    tip="两条腿分立 y=1 与 y=2 两条线上 —— 中间恰好留出列车通道。",
)
mb.step(
    "东侧门腿: 警示带东端再立两条 3 层门腿, 四腿成门。",
    ["leg_se0", "leg_se1", "leg_se2", "leg_ne0", "leg_ne1", "leg_ne2"],
    highlight=["leg_sw2", "leg_nw2"],
)
mb.step(
    "腿根护撑: 每条门腿内侧根部加 1 片橙色直角三角护撑 —— 竖直角边"
    "吸腿身竖边, 水平直角边吸地板边。",
    ["br_sw", "br_se", "br_nw", "br_ne"],
    highlight=["leg_sw0", "leg_ne0"],
    tip="护撑与腿、地板围成三角闭环, 是整机抗撞的第一道保险。",
)
mb.step(
    "平台中排: 4 片黄色方板铺在腿顶 (z=3), 南北两边同时吸住南北"
    "两排腿顶 —— 力臂为零, 最稳的一排先落位。",
    ["dk_m0", "dk_m1", "dk_m2", "dk_m3"],
    highlight=["leg_sw2", "leg_se2"],
    tip="从西端腿顶开始向东铺, 每片都先吸腿顶或邻板再松手。",
)
mb.step(
    "平台南排: 4 片灰色方板向南挂出, 北边吸中排、西东两端同时"
    "吸住南侧腿顶。",
    ["dk_s0", "dk_s1", "dk_s2", "dk_s3"],
    highlight=["dk_m0", "dk_m3"],
)
mb.step(
    "平台北排: 4 片灰色方板向北合拢, 作业平台连成 4x3 整层。",
    ["dk_n0", "dk_n1", "dk_n2", "dk_n3"],
    highlight=["dk_m0", "dk_m3"],
)
mb.step(
    "机房墙身: 平台中排西段立 4 面青色机房墙, 墙底吸平台板边。",
    ["mh_s", "mh_n", "mh_w", "mh_e"],
    highlight=["dk_m1"],
)
mb.step(
    "机房顶与 A 字架: 盖 1 片青色机房顶, 顶板东西短边各立 1 片"
    "黄色等边三角 —— 门吊标志性的 A 字架。",
    ["mh_roof", "aframe_w", "aframe_e"],
    highlight=["mh_s", "mh_n"],
)
mb.step(
    "司机室: 平台中排东段立 4 面透明玻璃墙, 盖蓝色顶板 —— 司机"
    "在这里俯瞰整条航道。",
    ["cab_s", "cab_n", "cab_w", "cab_e", "cab_roof"],
    highlight=["dk_m3"],
)
mb.step(
    "配重脊板: 平台南缘竖立 2 片紫色等边三角配重, 正压在南排板"
    "边线上。",
    ["cw_a", "cw_b"],
    highlight=["dk_s1", "dk_s2"],
    tip="配重立在支承线正上方 —— 力臂为零, 只压不弯。",
)
mb.step(
    "系缆墩: 航道中段自下而上叠 3 片灰色方墙, 底边吸航道板北缘。",
    ["pier0", "pier1", "pier2"],
    highlight=["chan1"],
    tip="墩顶与平台同高 (z=3), 专等臂架远端搭上来。",
)
mb.step(
    "臂架: 红色长板从平台北缘挑向海面, 南短边吸平台板、北短边"
    "正落系缆墩顶 —— 两端受力, 不是悬臂。",
    ["jib"],
    highlight=["dk_n1", "pier2"],
    tip="先对准墩顶再放手; 剪断任何一端, 另一端仍能独立传力。",
)
mb.step(
    "集装箱下层: 码头东端拼 1 只绿色集装箱 (4 墙 + 顶)。",
    ["box0_s", "box0_n", "box0_w", "box0_e", "box0_roof"],
    highlight=["q_s5"],
)
mb.step(
    "集装箱上层与系船柱: 橙色集装箱整只叠上去, 码头西端再立 2 根"
    "黄色系船柱 —— 港口开工。",
    ["box1_s", "box1_n", "box1_w", "box1_e", "box1_roof",
     "bollard_a", "bollard_b"],
    highlight=["box0_roof", "q_s0"],
)

mb.finalize(
    model_id="harbor_crane_01",
    name="港口门吊",
    name_en="Harbor Gantry Crane 01",
    description=(
        "跨轨道作业的门式起重机: 四条三层门腿分立装卸警示带两沿, "
        "腿根直角三角护撑锁成闭环; 12 片方板在腿顶架出整层作业平台 "
        "(中排先压腿顶、南北排再合拢), 平台上机房与玻璃司机室并肩, "
        "机房顶立 A 字架、南缘配重脊板压舱; 臂架长板从平台北缘挑向"
        "海面, 远端稳稳落在航道系缆墩上 —— 一根臂架两条支撑路径。"
        "码头东端还叠着两层集装箱等待装船。"
    ),
    difficulty=4,
    tags=["港口", "起重机", "工业", "门式结构", "跨线"],
    min_pieces=80,
    min_steps=19,
)
