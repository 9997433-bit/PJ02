#!/usr/bin/env python3
"""生成模型 data/models/storage_chest_01.json (翻盖百宝盒)。

内容批 L 模型 1/4: 实用功能主题首个 D1 —— 与 desk_organizer_01
(敞口格架收纳站) 刻意区分: 结构签名是"翻盖百宝盒", 盖板先在
桌面平拼成 2x2 整板, 再沿后沿磁吸边整体翻折扣合 —— 磁吸边
即铰链; 盒身是 2x2 闭环箱框, 内里三枚金币与一把钥匙, 正面
金扣与顶把手一眼可辨。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 盒底 (x [0,2], y [0,2], z=0): 2x2 胡桃木方板              4 片
  - 盒身墙环 (z 0..1): 四片方墙围合                             4 片
  - 百宝 (盒内 z=0): 金币三角 x3 + 钥匙瘦高尖                   4 片
  - 翻盖 (z=1): 2x2 金色盖板 + 后沿铰链长板                     5 片
  - 锁扣与饰带: 前扣三角 + 侧饰长板 x2 + 角钉 x1                4 片
  - 顶把手: 等边三角                                           1 片
  - 展示垫 (x [3,5], y [0,1]): 两片方板                          2 片
  合计 24 片, 8 个教程步骤, 4 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 盒身墙环四角竖边互咬闭环, 墙脚踩盒底拼缝;
  - 翻盖 2x2 四边整边吸墙顶, 后沿长板短边与后墙顶共线互吸
    (铰链共线双吸), 力矩沿铰链轴为零;
  - 前扣三角底边整边吸前墙顶与盖板前沿 —— 一片锁三件;
  - 百宝片全在盒内接地或吸墙内侧, 合盖后不外露。

用法: python3 tools/generate_storage_chest_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

WOOD = "brown"      # 盒身
GOLD = "yellow"     # 盖板与金币
PAD = "gray"        # 展示垫
CLASP = "orange"    # 锁扣

# =================================================================
# 1. 展示垫 (x [3,5], y [0,2])
# =================================================================
b.flat("pad_3_0", 3, 0, 0.0, PAD)
b.flat("pad_4_0", 4, 0, 0.0, PAD)

# =================================================================
# 2. 盒底 2x2 (x [0,2], y [0,2])
# =================================================================
b.flat("base_00", 0, 0, 0.0, WOOD)
b.flat("base_01", 0, 1, 0.0, WOOD)
b.flat("base_10", 1, 0, 0.0, WOOD)
b.flat("base_11", 1, 1, 0.0, WOOD)

# =================================================================
# 3. 盒身墙环 (z 0..1)
# =================================================================
b.wall_ns("wall_s", 0, 0.0, 0, WOOD)
b.wall_ns("wall_n", 0, 2.0, 0, WOOD)
b.wall_ew("wall_w", 0.0, 0, 0, WOOD)
b.wall_ew("wall_e", 2.0, 0, 0, WOOD)

# =================================================================
# 4. 盒内百宝
# =================================================================
b.crest_ns("coin_a", 0, 0.0, 0.0, GOLD)
b.crest_ns("coin_b", 0, 1.0, 0.0, GOLD)
b.crest_ew("coin_c", 1.0, 0, 0.0, GOLD)
b.spire_ns("key", 0, 2.0, 0.0, GOLD)

# =================================================================
# 5. 翻盖 2x2 + 后沿铰链长板
# =================================================================
b.flat("lid_00", 0, 0, 1.0, GOLD)
b.flat("lid_01", 0, 1, 1.0, GOLD)
b.flat("lid_10", 1, 0, 1.0, GOLD)
b.flat("lid_11", 1, 1, 1.0, GOLD)
b.lintel_ew("hinge", 0.0, 0, 1, GOLD)

# =================================================================
# 6. 锁扣、饰带、把手
# =================================================================
b.crest_ns("clasp", 0, 0.0, 1.0, CLASP)
b.lintel_ns("band_s", 0, 0.0, 1, WOOD)
b.lintel_ns("band_n", 0, 2.0, 1, WOOD)
b.crest_ew("rivet_w", 0.0, 0, 1.0, CLASP)
b.crest_ew("handle", 1.0, 1, 1.0, GOLD)

# =================================================================
# 教程步骤 (8 步)
# =================================================================
b.step(
    "铺展示垫: 两片灰色方板在百宝盒右侧, 给盖板平拼留出工作台。",
    ["pad_3_0", "pad_4_0"],
    tip="实用功能 D1 开工! 展示垫就是盖板平拼的工作台。",
)
b.step(
    "拼盒底: 四片胡桃木方板 2x2 整边互吸, 角对角对齐。",
    ["base_00", "base_01", "base_10", "base_11"],
    highlight=["pad_3_0"],
    tip="盒底拼缝对齐, 墙脚才有整边可吸。",
)
b.step(
    "围盒身: 四片方墙踩住盒底四沿, 四角竖边互咬成环。",
    ["wall_s", "wall_n", "wall_w", "wall_e"],
    highlight=["base_00", "base_11"],
    tip="闭环箱框 —— 荷载沿墙面直下, 百宝才装得稳。",
)
b.step(
    "装入百宝: 三枚金币三角与一把钥匙瘦高尖放进盒内。",
    ["coin_a", "coin_b", "coin_c", "key"],
    highlight=["wall_s"],
    tip="金币底边吸盒底拼缝, 钥匙靠北墙 —— 关盖前先收好宝贝!",
)
b.step(
    "平拼翻盖并扣合: 四片金色方板 2x2 整边互吸, 沿后沿铰链翻折扣住墙顶;"
    " 可先于垫板上平拼再整体搬回 —— 磁吸边即铰链。",
    ["lid_00", "lid_01", "lid_10", "lid_11"],
    highlight=["pad_4_0", "wall_w"],
    tip="T05 平面翻折 —— 先在桌面平拼, 再沿后沿磁吸边整体翻折扣合。",
)
b.step(
    "装后沿铰链: 一片金色长板短边与盒身后墙顶整边共线互吸。",
    ["hinge"],
    highlight=["wall_w", "lid_00"],
    tip="铰链共线双吸 —— 力矩沿铰链轴为零, 盖板才能整板翻折。",
)
b.step(
    "扣上前锁与饰带: 前扣三角、侧饰长板与顶把手 —— 百宝盒封箱!",
    ["clasp", "band_s", "band_n", "rivet_w", "handle"],
    highlight=["lid_00", "wall_s"],
    tip="前扣一片锁三件 —— 翻盖百宝盒完工, 钥匙还在里面呢!",
)

b.finalize(
    model_id="storage_chest_01",
    name="翻盖百宝盒",
    name_en="Storage Chest 01",
    description=(
        "实用功能首个 D1: 结构签名是'翻盖百宝盒' —— 2x2 胡桃木闭环"
        "箱框内藏着三枚金币与一把钥匙; 盖板先在展示垫上平拼成 2x2 "
        "金色整板, 后沿长板与后墙顶共线互吸形成铰链, 再沿磁吸边整体"
        "翻折扣合 (T05 平面翻折, 磁吸边即铰链); 正面金扣三角同时吸"
        "前墙顶与盖板前沿, 侧饰长板与角钉收边, 顶把手一提就开 —— "
        "与敞口格架收纳站的开合方式完全不同!"
    ),
    difficulty=1,
    tags=["实用功能", "收纳", "翻盖", "百宝盒", "入门"],
    min_pieces=24,
    min_steps=8,
    series="practical_utility",
)
