#!/usr/bin/env python3
"""生成模型 data/models/santa_sleigh_01.json (圣诞雪橇)。

内容批 I 模型 2/4: 全库第一架圣诞雪橇 —— 节日货架此前有圣诞集市
(货亭群) 却还没有雪橇本橇。与校车/回收小车 (车轮底座) 刻意区分,
本作的招牌是"双滑轨 + 前滑坡": 雪橇不用轮子 —— 两排立墙滑轨
托起整张橇板, 橇头两条 30 度长板从板沿直落雪面 (顶边整边吸橇板
西沿, 坡尾压雪), 就是雪橇破雪前行的那道弧线; 橇尾高背座椅顶着
两面金色三角椅冠, 橇板上大小两只礼物箱盖得严严实实, 雪地上还有
一只紫色大礼物等着装车 —— 圣诞老人马上出发!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 橇头朝西):
  - 雪地 4 行 (x [0,6], y [0,4]): 白雪长板 + 方板拼缝位       15 片
  - 双滑轨 (y=1 / y=3, x [2,5], z 0..1): 立墙方板 x6           6 片
  - 橇板 (x [2,5], y [1,3], z=1): 长板 x2 + 方板 x2            4 片
  - 橇头前滑坡 x2 (30 度长板, 顶边吸橇板西沿, 坡尾压雪)        2 片
  - 高背座椅 (x=5, z 1..2): 立墙 x2 + 金色三角椅冠 x2          4 片
  - 大礼物箱 (x [2,4], y [2,3], z 1..2): 横楣环 + 长板盖        5 片
  - 小礼物箱 (x [4,5], y [1,2], z 1..2): 与椅背共墙 + 方盖      4 片
  - 装车礼物 (x [5,6], y [2,3], z 0..1): 墙环 + 方盖            5 片
  - 雪杉两棵 (骑北沿口: 瘦高塔尖 + 等边树冠)                   2 片
  合计 47 片, 10 个教程步骤, 4 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (validate 常规 + strict 双档零警告 + jitter 全绿):
  - 两条前滑坡顶边分别整边吸橇板西沿 (与滑轨西竖边共点),
    坡尾压雪 —— 顶铰链 + 接地坡尾, 悬臂力矩为零;
  - 橇板南北长边整边压双滑轨顶, 载荷沿滑轨直下雪面拼缝;
  - 大礼物箱横楣脚压橇板拼缝, 四角竖边互咬闭环, 长板盖四边入扣;
  - 小礼物箱与高背座椅共用东墙 (省片又互锁), 方盖四边入扣;
  - 装车礼物墙环立在雪面拼缝上, 西墙顶边与座椅脚共线三方互吸;
  - 椅冠/雪杉全部骑整边沿口, 重心正压铰链线力矩为零;
  - 雪地拼缝纪律: 滑轨脚/礼物墙脚全部落在板边或拼缝上。

用法: python3 tools/generate_santa_sleigh_01.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

SNOW = "clear"      # 雪地
ICE = "cyan"        # 冰面点缀
RAIL = "gray"       # 滑轨 / 前滑坡
SLED = "red"        # 橇板 / 座椅
TRIM = "yellow"     # 椅冠 / 礼物盖
GIFT_L = "green"    # 大礼物箱
GIFT_S = "blue"     # 小礼物箱
GIFT_G = "purple"   # 装车礼物
TREE = "green"      # 雪杉

# =================================================================
# 1. 雪地 4 行 (x [0,6], y [0,4])
# =================================================================
# 南行 (y [0,1])
b.flat_rect("g0_w", 0, 0, 0.0, SNOW)
b.flat_rect("g0_m", 2, 0, 0.0, ICE)
b.flat_rect("g0_e", 4, 0, 0.0, SNOW)
# 橇位南行 (y [1,2]): 东端两片方板给装车位留拼缝
b.flat_rect("g1_w", 0, 1, 0.0, SNOW)
b.flat_rect("g1_m", 2, 1, 0.0, SNOW)
b.flat("g1_e0", 4, 1, 0.0, SNOW)
b.flat("g1_e1", 5, 1, 0.0, SNOW)
# 橇位北行 (y [2,3])
b.flat_rect("g2_w", 0, 2, 0.0, SNOW)
b.flat_rect("g2_m", 2, 2, 0.0, SNOW)
b.flat("g2_e0", 4, 2, 0.0, SNOW)
b.flat("g2_e1", 5, 2, 0.0, ICE)
# 北行 (y [3,4]): 西端两片方板给雪杉留整边沿口
b.flat("g3_w0", 0, 3, 0.0, SNOW)
b.flat("g3_w1", 1, 3, 0.0, SNOW)
b.flat_rect("g3_m", 2, 3, 0.0, ICE)
b.flat_rect("g3_e", 4, 3, 0.0, SNOW)

# =================================================================
# 2. 双滑轨 (y=1 / y=3, x [2,5], z 0..1)
# =================================================================
b.wall_ns("rail_s_0", 2, 1.0, 0, RAIL)
b.wall_ns("rail_s_1", 3, 1.0, 0, RAIL)
b.wall_ns("rail_s_2", 4, 1.0, 0, RAIL)
b.wall_ns("rail_n_0", 2, 3.0, 0, RAIL)
b.wall_ns("rail_n_1", 3, 3.0, 0, RAIL)
b.wall_ns("rail_n_2", 4, 3.0, 0, RAIL)

# =================================================================
# 3. 橇板 (x [2,5], y [1,3], z=1)
# =================================================================
b.flat_rect("deck_sw", 2, 1, 1.0, SLED)
b.flat_rect("deck_nw", 2, 2, 1.0, SLED)
b.flat("deck_se", 4, 1, 1.0, SLED)
b.flat("deck_ne", 4, 2, 1.0, SLED)

# =================================================================
# 4. 橇头前滑坡 x2 (顶边吸橇板西沿 x=2, 坡尾压雪 x~0.27)
# =================================================================
b.ramp("prow_s", "-x", 2.0, 1, 1.0, RAIL)
b.ramp("prow_n", "-x", 2.0, 2, 1.0, RAIL)

# =================================================================
# 5. 高背座椅 (x=5, y [1,3], z 1..2) + 金色椅冠
# =================================================================
b.wall_ew("back_s", 5.0, 1, 1, SLED)
b.wall_ew("back_n", 5.0, 2, 1, SLED)
b.crest_ew("crown_s", 5.0, 1, 2.0, TRIM)
b.crest_ew("crown_n", 5.0, 2, 2.0, TRIM)

# =================================================================
# 6. 大礼物箱 (x [2,4], y [2,3], z 1..2): 横楣环 + 长板盖
# =================================================================
b.lintel_ns("box1_s", 2, 2.0, 1, GIFT_L)
b.lintel_ns("box1_n", 2, 3.0, 1, GIFT_L)
b.wall_ew("box1_w", 2.0, 2, 1, GIFT_L)
b.wall_ew("box1_e", 4.0, 2, 1, GIFT_L)
b.flat_rect("box1_lid", 2, 2, 2.0, TRIM)

# =================================================================
# 7. 小礼物箱 (x [4,5], y [1,2], z 1..2): 东面与椅背共墙
# =================================================================
b.wall_ns("box2_s", 4, 1.0, 1, GIFT_S)
b.wall_ns("box2_n", 4, 2.0, 1, GIFT_S)
b.wall_ew("box2_w", 4.0, 1, 1, GIFT_S)
b.flat("box2_lid", 4, 1, 2.0, TRIM)

# =================================================================
# 8. 装车礼物 (x [5,6], y [2,3], z 0..1): 雪地上的第四只箱子
# =================================================================
b.wall_ns("box3_s", 5, 2.0, 0, GIFT_G)
b.wall_ns("box3_n", 5, 3.0, 0, GIFT_G)
b.wall_ew("box3_w", 5.0, 2, 0, GIFT_G)
b.wall_ew("box3_e", 6.0, 2, 0, GIFT_G)
b.flat("box3_lid", 5, 2, 1.0, TRIM)

# =================================================================
# 9. 雪杉两棵 (骑北沿口 y=4, 底边与方板北沿整边等长)
# =================================================================
b.spire_ns("tree_a", 0, 4.0, 0.0, TREE)
b.crest_ns("tree_b", 1, 4.0, 0.0, TREE)

# =================================================================
# 教程步骤 (10 步)
# =================================================================
b.step(
    "铺雪地南半场: 白雪长板行行等边互吸, 中间一条冰面亮晶晶。",
    ["g0_w", "g0_m", "g0_e", "g1_w", "g1_m", "g1_e0", "g1_e1"],
    tip="圣诞夜出发前先铺好雪原 —— 板边等长吸合才抓得牢。",
)
b.step(
    "铺雪地北半场: 东端两片方板是装车位, 拼缝留给礼物墙脚。",
    ["g2_w", "g2_m", "g2_e0", "g2_e1", "g3_w0", "g3_w1", "g3_m", "g3_e"],
    highlight=["g1_m"],
)
b.step(
    "立双滑轨: 六片灰色立墙排成南北两条轨, 墙脚咬住雪面拼缝。",
    ["rail_s_0", "rail_s_1", "rail_s_2", "rail_n_0", "rail_n_1", "rail_n_2"],
    highlight=["g1_m"],
    tip="雪橇不用轮子 —— 两条滑轨就是它的雪上飞毯。",
)
b.step(
    "盖橇板: 先落东端两片方板咬住轨顶, 再拼西侧两条长板。",
    ["deck_se", "deck_ne", "deck_sw", "deck_nw"],
    highlight=["rail_s_0", "rail_n_0"],
    tip="长边对轨顶, 力臂为零 —— 橇板稳得能开茶话会。",
)
b.step(
    "装橇头前滑坡: 两条 30 度长板顶边整边吸橇板西沿, 坡尾稳稳压雪。",
    ["prow_s", "prow_n"],
    highlight=["deck_sw"],
    tip="顶铰链 + 接地坡尾, 重量走两条路 —— 破雪的弧线就位。",
)
b.step(
    "立高背座椅: 两片红墙骑橇板东沿, 顶上再压两面金色椅冠。",
    ["back_s", "back_n", "crown_s", "crown_n"],
    highlight=["deck_se"],
    tip="椅冠骑整边沿口, 重心正压铰链线 —— 圣诞老人的专座。",
)
b.step(
    "装大礼物箱: 两条绿横楣加两片绿墙围环, 黄色长板盖四边入扣。",
    ["box1_s", "box1_n", "box1_w", "box1_e", "box1_lid"],
    highlight=["deck_nw"],
    tip="横楣脚压橇板拼缝, 四角竖边互咬 —— 大礼物跑不了。",
)
b.step(
    "装小礼物箱: 三片蓝墙借椅背当东墙, 黄色方盖扣紧。",
    ["box2_s", "box2_n", "box2_w", "box2_lid"],
    highlight=["back_s"],
    tip="和座椅共用一面墙 —— 省片又互锁, 聪明的装法。",
)
b.step(
    "摆装车礼物: 紫色墙环立在雪面拼缝上, 方盖一扣就等装车。",
    ["box3_s", "box3_n", "box3_w", "box3_e", "box3_lid"],
    highlight=["g2_e1"],
)
b.step(
    "种雪杉: 瘦高塔尖加一顶绿树冠骑上北沿口, 雪原就有了小森林。",
    ["tree_a", "tree_b"],
    highlight=["g3_m"],
    tip="叮叮当, 叮叮当 —— 铃儿响叮当, 雪橇出发啦!",
)

b.finalize(
    model_id="santa_sleigh_01",
    name="圣诞雪橇",
    name_en="Santa Sleigh 01",
    description=(
        "只用核心九片型的全库第一架圣诞雪橇: 与校车/回收小车的车轮"
        "底座不同, 本作的招牌是'双滑轨 + 前滑坡' —— 两排立墙滑轨托起"
        "整张红色橇板, 橇头两条 30 度长板从板沿直落雪面 (顶边整边吸"
        "橇板西沿, 坡尾压雪, 重量走两条路), 正是雪橇破雪前行的那道"
        "弧线; 橇尾高背座椅顶着两面金色椅冠, 橇板上大小两只礼物箱"
        "盖得严严实实, 雪地上还有一只紫色大礼物等着装车, 三棵雪杉"
        "在北边排队送行 —— 铃儿响叮当, 圣诞老人马上出发!"
    ),
    difficulty=2,
    tags=["节日", "圣诞", "雪橇", "礼物", "冬季"],
    min_pieces=47,
    min_steps=10,
)
