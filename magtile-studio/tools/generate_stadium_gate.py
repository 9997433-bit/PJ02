#!/usr/bin/env python3
"""生成模型 data/models/stadium_gate_01.json (体育场大门)。

城市生活主题: 全库第一座体育场入口 —— 两座双层票务塔夹着
六格宽的观众通道, 塔间一条长方形门楣横带凌空锁定 (双端竖边
吸进塔身, 中缝互吸), 横带顶上三片梯形檐冠像掀起的人浪;
通道里两座转闸分流人群, 大门身后两阶看台拔起, 台上三面
观众旗迎风招展 —— 检票入场, 比赛马上开始!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 大门朝南):
  - 场前大道 + 通道地坪 + 看台地基: 方板 x32                   32 片
  - 东西票务塔 (1x2 footprint, 双层): 围壁 x24 + 顶板 x4       28 片
  - 门楣横带 (z 1..2): 长方形 x3 + 梯形檐冠 x3                  6 片
  - 转闸 x2                                                      2 片
  - 两阶看台: 踢面/后墙 x20 + 座面 x8 (逐阶双端简支)           28 片
  - 塔旗 x2 + 场旗杆 x2 + 观众旗 x3                              7 片
  合计 103 片, 18 个教程步骤, 4 种片形。

物理规则要点 (通过 R1~R8 全部校验):
  - 门楣横带不落地却不悬空: 三片长方形首尾竖边互吸, 两端竖边
    吸进塔身二层墙角 —— 重力纯剪传入塔身, 无弯矩无吊挂;
  - 檐冠梯形下底 (长 2) 恰与横楣顶边等长贴合, 重心正压铰链;
  - 看台座面双端简支: 每阶座面南压前踢面顶、北压后墙顶,
    剪断任何一条铰链线都还有另一端支座 (无悬挑座板);
  - 票务塔每层 6 片围壁四角竖边互吸成环, 层层对缝。

用法: python3 tools/generate_stadium_gate.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

GROUND = "gray"     # 场前大道 / 通道
TRACK = "red"       # 观众通道 (红色跑道色)
TOWER = "blue"      # 票务塔
BAND = "yellow"     # 门楣横带
CROWN = "orange"    # 檐冠
GATE = "gray"       # 转闸
STAND = "gray"      # 看台
SEAT = "green"      # 座面
FLAG = "red"        # 旗帜

# =================================================================
# 1. 地坪 (z=0): 场前大道 + 通道 + 看台地基, 全方板
# =================================================================
for x0 in range(8):
    b.flat(f"fc_{x0}", x0, 0, 0.0, GROUND)          # 场前大道 y[0..1]
for x0 in range(8):
    b.flat(f"pa_{x0}", x0, 1, 0.0, TRACK)           # 通道南排 y[1..2]
for x0 in range(8):
    b.flat(f"pb_{x0}", x0, 2, 0.0, TRACK)           # 通道北排 y[2..3]
for x0 in (2, 3, 4, 5):
    b.flat(f"sa_{x0}", x0, 3, 0.0, GROUND)          # 看台地基 y[3..4]
    b.flat(f"sb_{x0}", x0, 4, 0.0, GROUND)          # 看台地基 y[4..5]

# =================================================================
# 2. 东西票务塔 (x 0..1 / x 7..8, y 1..3, z 0..2): 双层围壁 + 顶板
# =================================================================
for lv in (0, 1):
    # 西塔
    b.wall_ns(f"wt_s{lv}", 0, 1.0, lv, TOWER)
    b.wall_ns(f"wt_n{lv}", 0, 3.0, lv, TOWER)
    b.wall_ew(f"wt_w{lv}_1", 0.0, 1, lv, TOWER)
    b.wall_ew(f"wt_w{lv}_2", 0.0, 2, lv, TOWER)
    b.wall_ew(f"wt_e{lv}_1", 1.0, 1, lv, TOWER)
    b.wall_ew(f"wt_e{lv}_2", 1.0, 2, lv, TOWER)
    # 东塔
    b.wall_ns(f"et_s{lv}", 7, 1.0, lv, TOWER)
    b.wall_ns(f"et_n{lv}", 7, 3.0, lv, TOWER)
    b.wall_ew(f"et_w{lv}_1", 7.0, 1, lv, TOWER)
    b.wall_ew(f"et_w{lv}_2", 7.0, 2, lv, TOWER)
    b.wall_ew(f"et_e{lv}_1", 8.0, 1, lv, TOWER)
    b.wall_ew(f"et_e{lv}_2", 8.0, 2, lv, TOWER)
b.flat("wt_top_1", 0, 1, 2.0, GROUND)               # 西塔顶板
b.flat("wt_top_2", 0, 2, 2.0, GROUND)
b.flat("et_top_1", 7, 1, 2.0, GROUND)               # 东塔顶板
b.flat("et_top_2", 7, 2, 2.0, GROUND)

# =================================================================
# 3. 门楣横带 (y=2, z 1..2) + 梯形檐冠
# =================================================================
b.lintel_ns("band_1", 1, 2.0, 1, BAND)              # [1..3]
b.lintel_ns("band_3", 3, 2.0, 1, BAND)              # [3..5]
b.lintel_ns("band_5", 5, 2.0, 1, BAND)              # [5..7]
b.place_edge("crown_1", "trapezoid", 0,
             (1.0, 2.0, 2.0), (3.0, 2.0, 2.0), (0.0, 0.0, 1.0), CROWN)
b.place_edge("crown_3", "trapezoid", 0,
             (3.0, 2.0, 2.0), (5.0, 2.0, 2.0), (0.0, 0.0, 1.0), CROWN)
b.place_edge("crown_5", "trapezoid", 0,
             (5.0, 2.0, 2.0), (7.0, 2.0, 2.0), (0.0, 0.0, 1.0), CROWN)

# =================================================================
# 4. 转闸 (y=2 线, z 0..1): 分流人群
# =================================================================
b.wall_ns("stile_2", 2, 2.0, 0, GATE)
b.wall_ns("stile_5", 5, 2.0, 0, GATE)

# =================================================================
# 5. 两阶看台 (x 2..6, 大门身后)
# =================================================================
for x0 in (2, 3, 4, 5):
    b.wall_ns(f"t1_f_{x0}", x0, 3.0, 0, STAND)      # 一阶前踢面 y=3
    b.wall_ns(f"t1_w_{x0}", x0, 4.0, 0, STAND)      # 一阶后墙 y=4
for x0 in (2, 3, 4, 5):
    b.flat(f"t1_d_{x0}", x0, 3, 1.0, SEAT)          # 一阶座面 y[3..4]
for x0 in (2, 3, 4, 5):
    b.wall_ns(f"t2_f_{x0}", x0, 4.0, 1, STAND)      # 二阶前踢面 y=4 (z 1..2)
    b.wall_ns(f"t2_w0_{x0}", x0, 5.0, 0, STAND)     # 二阶后墙下层 y=5
for x0 in (2, 3, 4, 5):
    b.wall_ns(f"t2_w1_{x0}", x0, 5.0, 1, STAND)     # 二阶后墙上层 y=5
for x0 in (2, 3, 4, 5):
    b.flat(f"t2_d_{x0}", x0, 4, 2.0, SEAT)          # 二阶座面 y[4..5]

# =================================================================
# 6. 旗帜: 塔旗 + 场旗杆 + 观众旗
# =================================================================
b.crest_ew("flag_w", 0.0, 1, 2.0, FLAG)             # 西塔旗
b.crest_ew("flag_e", 8.0, 2, 2.0, FLAG)             # 东塔旗
b.crest_ew("pole_w", 2.0, 0, 0.0, CROWN)            # 场旗杆
b.crest_ew("pole_e", 6.0, 0, 0.0, CROWN)
b.crest_ns("fan_1", 3, 3.0, 1.0, "yellow")          # 观众旗 (一阶)
b.crest_ns("fan_2", 2, 4.0, 2.0, "cyan")            # 观众旗 (二阶)
b.crest_ns("fan_3", 4, 4.0, 2.0, "purple")

# =================================================================
# 教程步骤 (18 步)
# =================================================================
b.step(
    "铺场前大道: 8 片灰色方板一字排开 (y 0..1)。",
    [f"fc_{x0}" for x0 in range(8)],
    tip="比赛日的人流从这条大道涌来 —— 逐格拼缝互吸。",
)
b.step(
    "铺观众通道·南排: 8 片红色方板 (y 1..2), 北边吸大道南边。",
    [f"pa_{x0}" for x0 in range(8)],
    highlight=["fc_0", "fc_7"],
    tip="红色跑道色标出检票动线 —— 票务塔就踩在这排缝上。",
)
b.step(
    "铺观众通道·北排: 再铺 8 片, 通道贯通 (y 2..3)。",
    [f"pb_{x0}" for x0 in range(8)],
    highlight=["pa_0", "pa_7"],
    tip="转闸线落在南北排的拼缝上 —— 提前记住 y=2 这条线。",
)
b.step(
    "铺看台地基: 大门身后 8 片方板 (x 2..6, y 3..5)。",
    [f"sa_{x0}" for x0 in (2, 3, 4, 5)]
    + [f"sb_{x0}" for x0 in (2, 3, 4, 5)],
    highlight=["pb_2", "pb_5"],
    tip="看台是全场最重的结构 —— 地基南边整边吸通道北边。",
)
b.step(
    "西塔一层: 6 片蓝色围壁四角竖边互吸成环 (x 0..1)。",
    ["wt_s0", "wt_n0", "wt_w0_1", "wt_w0_2", "wt_e0_1", "wt_e0_2"],
    highlight=["pa_0", "pb_0"],
    tip="墙脚踩地坪拼缝 —— 票务塔是门楣横带的支座。",
)
b.step(
    "东塔一层: 同法再围 6 片 (x 7..8), 两塔隔通道相望。",
    ["et_s0", "et_n0", "et_w0_1", "et_w0_2", "et_e0_1", "et_e0_2"],
    highlight=["wt_s0"],
    tip="两塔间留出 6 格宽通道 —— 散场时也不会拥堵。",
)
b.step(
    "西塔二层: 6 片围壁对缝叠上一层墙顶。",
    ["wt_s1", "wt_n1", "wt_w1_1", "wt_w1_2", "wt_e1_1", "wt_e1_2"],
    highlight=["wt_s0", "wt_e0_1"],
    tip="二层墙角马上要咬住门楣横带 —— 对缝务必整齐。",
)
b.step(
    "东塔二层: 再叠 6 片, 双塔等高。",
    ["et_s1", "et_n1", "et_w1_1", "et_w1_2", "et_e1_1", "et_e1_2"],
    highlight=["et_s0", "et_w0_1"],
    tip="从二层售票窗望出去, 整条大道尽收眼底。",
)
b.step(
    "盖塔顶并插塔旗: 每塔 2 片顶板四边吸满墙顶, 塔外沿各立 1 面"
    "红旗。",
    ["wt_top_1", "wt_top_2", "et_top_1", "et_top_2",
     "flag_w", "flag_e"],
    highlight=["wt_s1", "et_s1"],
    tip="顶板锁环, 塔旗升起 —— 主场的颜色亮出来!",
)
b.step(
    "锁门楣横带: 3 片黄色长方形凌空横跨通道 —— 两端竖边吸进"
    "塔身二层墙角, 中缝彼此互吸。",
    ["band_1", "band_3", "band_5"],
    highlight=["wt_e1_1", "et_w1_1"],
    tip="重力顺竖缝剪入塔身, 不弯不吊 —— 这就是门楣的力学。",
)
b.step(
    "戴梯形檐冠: 3 片橙色梯形下底恰与横楣顶边等长贴合, 像掀起"
    "的人浪。",
    ["crown_1", "crown_3", "crown_5"],
    highlight=["band_1", "band_5"],
    tip="重心正压铰链, 力臂为零 —— 檐冠稳稳立在横带上。",
)
b.step(
    "装转闸: 2 片灰色矮墙立在通道拼缝上, 分出三条检票道。",
    ["stile_2", "stile_5"],
    highlight=["pa_2", "pb_5"],
    tip="转闸底边吸通道拼缝 —— 一人一道, 有序入场。",
)
b.step(
    "砌看台一阶前后墙: 前踢面 (y=3) 与后墙 (y=4) 各 4 片, 墙脚"
    "踩地基拼缝。",
    [f"t1_f_{x0}" for x0 in (2, 3, 4, 5)]
    + [f"t1_w_{x0}" for x0 in (2, 3, 4, 5)],
    highlight=["sa_2", "sa_5"],
    tip="看台座板要前后双支座 —— 单边挂着的板凳没人敢坐。",
)
b.step(
    "铺一阶座面: 4 片绿色座面南压踢面顶、北压后墙顶, 双端简支。",
    [f"t1_d_{x0}" for x0 in (2, 3, 4, 5)],
    highlight=["t1_f_2", "t1_w_5"],
    tip="座面与前后墙锁成一阶闭环 —— 前排最抢手。",
)
b.step(
    "砌二阶后墙·下层: 4 片方墙沿 y=5 线立起。",
    [f"t2_w0_{x0}" for x0 in (2, 3, 4, 5)],
    highlight=["sb_2", "sb_5"],
    tip="二阶要高出一阶整整一层 —— 先打下层。",
)
b.step(
    "砌二阶前踢面与后墙上层: 前踢面 4 片叠上一阶后墙顶 (y=4), "
    "后墙再对缝叠 4 片 (y=5)。",
    [f"t2_f_{x0}" for x0 in (2, 3, 4, 5)]
    + [f"t2_w1_{x0}" for x0 in (2, 3, 4, 5)],
    highlight=["t1_w_2", "t2_w0_2"],
    tip="上下层严格对缝, 相邻竖边互吸 —— 高墙也有闭环。",
)
b.step(
    "铺二阶座面: 4 片绿色座面南压踢面顶、北压高墙顶, 看台完工。",
    [f"t2_d_{x0}" for x0 in (2, 3, 4, 5)],
    highlight=["t2_f_2", "t2_w1_2"],
    tip="双端简支再上一层 —— 从这里看球, 整个球场一览无余。",
)
b.step(
    "插满旗帜: 一阶 1 面、二阶 2 面观众旗, 大道两侧 2 根场旗杆 "
    "—— 检票入场, 比赛马上开始!",
    ["fan_1", "fan_2", "fan_3", "pole_w", "pole_e"],
    highlight=["t1_d_3", "t2_d_2"],
    tip="旗帜底边整边吸座面沿边与大道拼缝 —— 主队加油!",
)

b.finalize(
    model_id="stadium_gate_01",
    name="体育场大门",
    name_en="Stadium Gate 01",
    description=(
        "全库第一座体育场入口: 两座双层票务塔夹着六格宽观众通道, 塔间"
        "三片长方形门楣横带凌空锁定 (双端竖边吸进塔身墙角, 重力纯剪"
        "传入塔身), 横带顶上三片梯形檐冠像掀起的人浪; 通道里双转闸"
        "分流, 大门身后两阶看台逐级退台, 座面与墙顶层层锁环, 台上"
        "观众旗迎风招展 —— 检票入场, 比赛马上开始!"
    ),
    difficulty=4,
    tags=["城市生活", "体育场", "大门", "看台", "进阶"],
    min_pieces=100,
    min_steps=18,
)
