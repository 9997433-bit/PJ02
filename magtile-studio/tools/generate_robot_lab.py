#!/usr/bin/env python3
"""生成模型 data/models/robot_lab_01.json (机器人检修实验室)。

科幻/实验室主题 1/4: 全库第一座梳状充电坞实验室 —— 与 robot_01
(独立人形机器人) 和 robot_arm_01 (龙门机械臂工位) 的结构逻辑刻意
区分: 招牌是一排"梳状"充电坞 —— 四片翼墙 (梳齿) 与后墙隔出三个
1x1 坞位, 坞口各嵌一片彩色窗格方充电门, 门-翼墙-后墙-顶板锁成
三连箱体 (每片顶板同时压两齿一墙一门, 四边受力); 中坞顶板上
等边四坡扫描穹顶自锁收头; 场地中央一台待检机器人立在检测台上:
箱式躯干四角竖边互吸闭环, 蓝色窗格方面部朝南, 头顶等边四坡
头盔, 两条直角三角工具臂垂直边吸躯干竖边、水平边吸地坪拼缝
(双边受力零悬挑); 旁边双柱工作台双端受力如桥, 台面上立着待装
零件 —— 检修开始!

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 坞口朝南):
  - 实验室地坪 7x5: 方板 + 长板混铺, 拼缝对准全部墙线      26 片
  - 充电坞: 后墙 x3 + 翼墙 (梳齿) x4 + 充电门 x3 + 顶板 x3  13 片
  - 扫描穹顶: 中坞顶板上等边四坡锥 x4 (锥尖 1.71)            4 片
  - 信号天线: 等边三角 x2 (骑顶板北沿与后墙顶双缝)           2 片
  - 待检机器人: 躯干墙环 x4 + 盖板 x1 + 头盔四坡 x4          9 片
  - 工具臂: 直角三角斜撑 x2 (吸躯干竖边 + 地坪拼缝)          2 片
  - 工作台: 立柱 x2 + 台面 x2 + 待装零件三角 x1              5 片
  - 诊断屏 x1 + 安全围栏 x2                                  3 片
  合计 64 片, 13 个教程步骤, 5 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (R1~R8 全绿, strict 档零警告):
  - 梳齿翼墙底边吸地坪拼缝、后端竖边吸后墙竖边 (双边受力);
    顶板四边分别压两齿顶、后墙顶与充电门顶, 处处成环;
  - 机器人躯干 1x1 墙环四角竖边互吸, 盖板四边压墙顶,
    头盔四棱两两自锁; 工具臂直角边双吸 (竖边 + 地缝);
  - 全场最高点 1.87 (< 2.5), 不触发 R8 高层检查; 无悬挑无吊挂。

用法: python3 tools/generate_robot_lab.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

FLOOR = "gray"      # 实验室地坪
PAD = "cyan"        # 检测台 / 坞位地垫
LANE = "yellow"     # 安全通道
WALL = "gray"       # 坞体墙
DOCK_R = "red"      # 充电门三色
DOCK_B = "blue"
DOCK_G = "green"
GLASS = "clear"     # 扫描穹顶
BOT = "gray"        # 机器人机体
CORE = "yellow"     # 能量核心
FACE = "blue"       # 面部屏幕 / 头盔
ARM = "orange"      # 工具臂
BENCH = "purple"    # 工作台立柱
PART = "red"        # 待装零件
SCREEN = "green"    # 诊断屏
FENCE = "yellow"    # 安全围栏

# =================================================================
# 1. 地坪 (x [0,7], y [0,5]): 拼缝对准坞墙 / 机器人 / 工作台脚线
# =================================================================
b.flat("g0_a", 0, 0, 0.0, FLOOR)
b.flat("g0_b", 1, 0, 0.0, FLOOR)
b.flat("g0_c", 2, 0, 0.0, FLOOR)
b.flat_rect("g0_d", 3, 0, 0.0, FLOOR)
b.flat("g0_e", 5, 0, 0.0, FLOOR)
b.flat("g0_f", 6, 0, 0.0, FLOOR)

b.flat("g1_a", 0, 1, 0.0, FLOOR)
b.flat("g1_b", 1, 1, 0.0, PAD)        # 机器人检测台
b.flat("g1_c", 2, 1, 0.0, FLOOR)
b.flat_rect("g1_d", 3, 1, 0.0, FLOOR)
b.flat("g1_e", 5, 1, 0.0, FLOOR)      # 工作台脚位
b.flat("g1_f", 6, 1, 0.0, FLOOR)

b.flat_rect("g2_a", 0, 2, 0.0, LANE)  # 安全通道
b.flat("g2_b", 2, 2, 0.0, LANE)
b.flat("g2_c", 3, 2, 0.0, LANE)
b.flat("g2_d", 4, 2, 0.0, LANE)
b.flat_rect("g2_e", 5, 2, 0.0, LANE)

b.flat_rect("g3_a", 0, 3, 0.0, FLOOR)
b.flat("g3_b", 2, 3, 0.0, PAD)        # 坞位地垫 x3
b.flat("g3_c", 3, 3, 0.0, PAD)
b.flat("g3_d", 4, 3, 0.0, PAD)
b.flat_rect("g3_e", 5, 3, 0.0, FLOOR)

b.flat_rect("g4_a", 0, 4, 0.0, FLOOR)
b.flat_rect("g4_b", 2, 4, 0.0, FLOOR)
b.flat_rect("g4_c", 4, 4, 0.0, FLOOR)
b.flat("g4_d", 6, 4, 0.0, FLOOR)

# =================================================================
# 2. 梳状充电坞 (x [2,5], y [3,4]): 后墙 + 翼墙梳齿 + 彩色充电门
# =================================================================
b.wall_ns("bay_r1", 2, 4.0, 0, WALL)   # 后墙 (y=4)
b.wall_ns("bay_r2", 3, 4.0, 0, WALL)
b.wall_ns("bay_r3", 4, 4.0, 0, WALL)
b.wall_ew("fin1", 2.0, 3, 0, WALL)     # 梳齿翼墙 (x=2..5)
b.wall_ew("fin2", 3.0, 3, 0, WALL)
b.wall_ew("fin3", 4.0, 3, 0, WALL)
b.wall_ew("fin4", 5.0, 3, 0, WALL)
b.add("dock1", "window_square", (2.5, 3.0, 0.5), (90, 0, 0), DOCK_R)
b.add("dock2", "window_square", (3.5, 3.0, 0.5), (90, 0, 0), DOCK_B)
b.add("dock3", "window_square", (4.5, 3.0, 0.5), (90, 0, 0), DOCK_G)

# 顶板 (z=1): 每片同时压两齿顶、后墙顶与充电门顶 (四边受力)
b.flat("deck1", 2, 3, 1.0, WALL)
b.flat("deck2", 3, 3, 1.0, WALL)
b.flat("deck3", 4, 3, 1.0, WALL)

# 扫描穹顶 (中坞顶板) + 信号天线 (骑顶板北沿/后墙顶双缝)
DOME = b.hat4("dome", 3, 3, 1.0, GLASS, shape="equilateral_triangle")
b.crest_ns("ant1", 2, 4.0, 1.0, DOCK_R)
b.crest_ns("ant2", 4, 4.0, 1.0, DOCK_R)

# =================================================================
# 3. 待检机器人 (x [1,2], y [1,2]): 箱式躯干 + 头盔 + 工具臂
# =================================================================
b.add("rb_face", "window_square", (1.5, 1.0, 0.5), (90, 0, 0), FACE)
b.wall_ns("rb_n", 1, 2.0, 0, BOT)
b.wall_ew("rb_w", 1.0, 1, 0, BOT)
b.wall_ew("rb_e", 2.0, 1, 0, CORE)     # 能量核心侧板
b.flat("rb_cap", 1, 1, 1.0, BOT)
HEAD = b.hat4("rb_head", 1, 1, 1.0, FACE, shape="equilateral_triangle")
b.brace("rb_arm_w", (1, 1, 0), "-x", ARM)
b.brace("rb_arm_e", (2, 1, 0), "+x", ARM)

# =================================================================
# 4. 工作台 (x [5,7], y [1,2]) + 诊断屏 + 安全围栏
# =================================================================
b.wall_ew("wb_w", 5.0, 1, 0, BENCH)
b.wall_ew("wb_e", 6.0, 1, 0, BENCH)
b.flat("wb_top1", 5, 1, 1.0, WALL)     # 台面双端受力如桥
b.flat("wb_top2", 6, 1, 1.0, WALL)
b.crest_ew("wb_part", 6.0, 1, 1.0, PART)   # 台面拼缝上的待装零件
b.add("console", "window_square", (3.5, 2.0, 0.5), (90, 0, 0), SCREEN)
b.wall_ns("fence1", 5, 0.0, 0, FENCE)
b.wall_ns("fence2", 6, 0.0, 0, FENCE)

# =================================================================
# 教程步骤 (13 步)
# =================================================================
b.step(
    "铺南侧地坪 (y [0,1]): 6 片, 实验室从门口铺起。",
    ["g0_a", "g0_b", "g0_c", "g0_d", "g0_e", "g0_f"],
    tip="灰色是通行区 —— 所有设备脚线都会压在拼缝上。",
)
b.step(
    "铺检测排地坪 (y [1,2]): 6 片, 青色检测台就位。",
    ["g1_a", "g1_b", "g1_c", "g1_d", "g1_e", "g1_f"],
    highlight=["g0_b"],
    tip="青色方板是机器人的检测台, 右侧两格留给工作台。",
)
b.step(
    "铺安全通道与坞位地垫 (y [2,4]): 10 片。",
    ["g2_a", "g2_b", "g2_c", "g2_d", "g2_e",
     "g3_a", "g3_b", "g3_c", "g3_d", "g3_e"],
    highlight=["g1_b"],
    tip="黄色横排是安全通道, 三片青色地垫就是三个充电坞位。",
)
b.step(
    "铺北侧地坪 (y [4,5]): 4 片, 场地合拢。",
    ["g4_a", "g4_b", "g4_c", "g4_d"],
    highlight=["g3_b"],
    tip="7x5 场地铺满, 坞体后墙将立在这排拼缝上。",
)
b.step(
    "立充电坞骨架: 后墙 3 片 + 梳齿翼墙 4 片。",
    ["bay_r1", "bay_r2", "bay_r3", "fin1", "fin2", "fin3", "fin4"],
    highlight=["g3_b", "g3_c", "g3_d"],
    tip="四片翼墙像梳齿一样隔出三个坞位, 后端竖边吸住后墙竖边。",
)
b.step(
    "嵌三色充电门: 红 / 蓝 / 绿窗格方封住坞口。",
    ["dock1", "dock2", "dock3"],
    highlight=["fin1", "fin4"],
    tip="充电门竖边与两侧梳齿互吸 —— 三个坞位各自闭环。",
)
b.step(
    "盖坞顶板: 3 片, 每片同时压两齿一墙一门。",
    ["deck1", "deck2", "deck3"],
    highlight=["dock1", "dock3"],
    tip="顶板四边全部受力, 轻推整排充电坞应一起联动。",
)
b.step(
    "起扫描穹顶: 中坞顶板上 4 片透明等边锥自锁。",
    DOME,
    highlight=["deck2"],
    tip="四条斜棱两两互吸 —— 穹顶里是坞位的扫描探头。",
)
b.step(
    "立信号天线与诊断屏: 顶板北沿骑 2 片红三角, 通道边立绿屏。",
    ["ant1", "ant2", "console"],
    highlight=["deck1", "deck3"],
    tip="天线底边同时吸顶板北沿与后墙顶 —— 一缝双吸。",
)
b.step(
    "立机器人躯干: 蓝色面部朝南, 黄色能量核心朝工作台。",
    ["rb_face", "rb_n", "rb_w", "rb_e"],
    highlight=["g1_b"],
    tip="躯干四角竖边互吸闭环 —— 这是站得稳的关键。",
)
b.step(
    "盖肩板、戴头盔: 盖板压四墙顶, 4 片蓝色等边锥锁成头。",
    ["rb_cap"] + HEAD,
    highlight=["rb_face"],
    tip="先盖肩板再拼头盔, 头盔四棱自锁成环。",
)
b.step(
    "装工具臂、立工作台柱: 直角三角竖边吸躯干、横边吸地缝。",
    ["rb_arm_w", "rb_arm_e", "wb_w", "wb_e"],
    highlight=["rb_face", "g1_e"],
    tip="工具臂两条直角边都被吸住 —— 零悬挑, 双边受力。",
)
b.step(
    "铺台面、放零件、围围栏 —— 机器人实验室开工!",
    ["wb_top1", "wb_top2", "wb_part", "fence1", "fence2"],
    highlight=["wb_w", "wb_e"],
    tip="台面双端压柱顶如桥, 红色零件立在台面拼缝上等待安装。",
)

b.finalize(
    model_id="robot_lab_01",
    name="机器人检修实验室",
    name_en="Robot Lab 01",
    description=(
        "全库第一座梳状充电坞实验室: 四片翼墙与后墙隔出三个 1x1 坞位, "
        "坞口嵌红蓝绿三色窗格方充电门, 门-齿-墙-顶板锁成三连箱体, "
        "中坞顶上透明等边四坡扫描穹顶自锁; 场地中央箱式躯干机器人立在"
        "检测台上, 蓝色面屏朝南、头顶四坡头盔, 两条直角三角工具臂"
        "竖边吸躯干、横边吸地缝 (双边受力零悬挑); 双柱工作台双端受力"
        "如桥, 台面拼缝立着待装零件 —— 充电、扫描、检修一站完成。"
    ),
    difficulty=3,
    tags=["机器人", "实验室", "科技", "充电坞", "进阶"],
    min_pieces=64,
    min_steps=13,
)
