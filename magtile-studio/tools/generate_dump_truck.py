#!/usr/bin/env python3
"""生成模型 data/models/dump_truck_01.json (自卸卡车).

采石场工程主题: 全库第一辆正在卸料的自卸卡车 —— 黄色矿用卡车
停在采石场里, 车斗底板绕尾梁铰链抬起 45 度、尾门向后甩开 60 度,
一斗碎石刚倾泻到车尾 (四坡碎石堆+两簇石尖); 场地北缘是两级
台阶式采石岩壁, 壁顶橙色矿石嶙峋, 出口立限速警示牌与红色雪糕筒。
与消防车 (箱形器材舱+云梯) 完全不同的载具结构: 自卸车的核心是
"尾梁桥 + 双铰链斗板" —— 尾梁长板双端简支在斗侧板顶上, 再从它
的两条长边分别铰出抬起的斗底板与甩开的尾门。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 车头朝西):
  - 采石场地坪 4 排 (南 3 排长板+方板, 北排 8 方板)        23 片
  - 车轮底座 x4 + 底盘长板 x4                               8 片
  - 驾驶室: 挡风 x2 + 斗前壁 x2 + 侧墙 x2 + 车门窗 x2
    + 舱顶方板 x4 + 排气管 + 警灯                          14 片
  - 车斗: 侧板 x4 + 尾梁长板 + 45 度抬起斗底板 + 60 度尾门  7 片
  - 碎石堆: 等边四坡堆 x4 + 石尖 x2                         6 片
  - 采石岩壁: 一级 x6 + 二级 x3 + 矿石尖 x3                12 片
  - 警示牌 (方板+红三角) + 雪糕筒 x2                        4 片
  合计 74 片, 18 个教程步骤, 6 种磁力片形状 (CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, 常规+strict 双档):
  - 尾梁长板双端简支: 两条短边分别整边压南北斗侧板顶, 是
    斗板与尾门共同的受力桥;
  - 斗底板绕尾梁西长边铰链抬起 45 度: 质量 60g x 水平力臂
    cos45 x 0.5 = 21.2 < 双倍长度铰链预算 35 (strict 档);
  - 尾门绕尾梁东长边向下甩开 60 度: 悬挂力矩 60 x 0.25 = 15
    < 35, 尾门尖端 z=1.13 高于碎石尖 0.87, 互不相碰;
  - 碎石四坡堆 (等边) 斜棱两两互吸自锁, 底边各吸一条地坪缝;
  - 斗前壁即驾驶室后壁 (一墙两用), 底边整边吸底盘长板短边。

用法: python3 tools/generate_dump_truck.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

YARD = "gray"       # 采石场地坪
BELT = "orange"     # 岩壁下碎石带
WHEEL = "gray"
CHASSIS = "gray"
BODY = "yellow"     # 矿用卡车黄
GLASS = "clear"
BED = "orange"      # 斗底板/尾门内衬
GRAVEL_A = "gray"
GRAVEL_B = "orange"
ROCK = "gray"
ORE = "orange"

# =================================================================
# 1. 采石场地坪: 南 3 排 [0,8]x[0,3] + 北碎石带 [0,8]x[3,4]
# =================================================================
for row, y in (("r0", 0), ("r1", 1), ("r2", 2)):
    b.flat_rect(f"{row}_a", 0, y, 0.0, YARD)
    b.flat_rect(f"{row}_b", 2, y, 0.0, YARD)
    b.flat_rect(f"{row}_c", 4, y, 0.0, YARD)
    b.flat(f"{row}_d", 6, y, 0.0, YARD)
    b.flat(f"{row}_e", 7, y, 0.0, YARD)
for x0 in range(8):
    b.flat(f"belt_{x0}", x0, 3, 0.0, BELT)

# =================================================================
# 2. 车轮底座 x4 + 底盘 z=1 (4x2 长板, 车头朝西)
# =================================================================
b.add("wb_fs", "wheel_base", (3.0, 1.0, 0.5), (90, 0, 0), WHEEL)
b.add("wb_fn", "wheel_base", (3.0, 3.0, 0.5), (90, 0, 0), WHEEL)
b.add("wb_rs", "wheel_base", (5.0, 1.0, 0.5), (90, 0, 0), WHEEL)
b.add("wb_rn", "wheel_base", (5.0, 3.0, 0.5), (90, 0, 0), WHEEL)
b.flat_rect("ch_fs", 2, 1, 1.0, CHASSIS)
b.flat_rect("ch_fn", 2, 2, 1.0, CHASSIS)
b.flat_rect("ch_rs", 4, 1, 1.0, CHASSIS)
b.flat_rect("ch_rn", 4, 2, 1.0, CHASSIS)

# =================================================================
# 3. 驾驶室 [2,4]x[1,3] (z1..2): 挡风 + 斗前壁 + 侧墙/车门窗 + 舱顶
# =================================================================
b.wall_ew("cb_gs", 2.0, 1, 1, GLASS)               # 车头挡风
b.wall_ew("cb_gn", 2.0, 2, 1, GLASS)
b.wall_ew("cb_hs", 4.0, 1, 1, BODY)                # 斗前壁 (兼驾驶室后壁)
b.wall_ew("cb_hn", 4.0, 2, 1, BODY)
b.wall_ns("cb_s2", 2, 1.0, 1, BODY)                # 侧墙 (前半)
b.wall_ns("cb_n2", 2, 3.0, 1, BODY)
b.add("cb_ds", "window_square", (3.5, 1.0, 1.5), (90, 0, 0), GLASS)   # 车门窗
b.add("cb_dn", "window_square", (3.5, 3.0, 1.5), (90, 0, 0), GLASS)
b.flat("cb_r1", 2, 1, 2.0, BODY)                   # 舱顶方板 x4
b.flat("cb_r2", 3, 1, 2.0, BODY)
b.flat("cb_r3", 2, 2, 2.0, BODY)
b.flat("cb_r4", 3, 2, 2.0, BODY)
b.spire_ns("stack", 2, 3.0, 2.0, "gray")           # 排气管高塔尖
b.crest_ns("beacon", 3, 1.0, 2.0, "orange")        # 舱顶警灯

# =================================================================
# 4. 车斗 [4,6]x[1,3]: 侧板 + 尾梁桥 + 45 度斗底板 + 60 度尾门
# =================================================================
b.wall_ns("bx_s4", 4, 1.0, 1, BODY)                # 南斗侧板
b.wall_ns("bx_s5", 5, 1.0, 1, BODY)
b.wall_ns("bx_n4", 4, 3.0, 1, BODY)                # 北斗侧板
b.wall_ns("bx_n5", 5, 3.0, 1, BODY)
b.flat_rect("bx_beam", 5, 1, 2.0, BODY, axis="y")  # 尾梁: 双端压侧板顶
b.place_edge("bx_floor", "rectangle", 0,           # 斗底板抬起 45 度
             (5.0, 1.0, 2.0), (5.0, 3.0, 2.0),
             (-0.707107, 0.0, 0.707107), BED)
b.place_edge("bx_gate", "rectangle", 0,            # 尾门向后甩开 60 度
             (6.0, 3.0, 2.0), (6.0, 1.0, 2.0),
             (0.5, 0.0, -0.866025), BED)

# =================================================================
# 5. 碎石堆 [6,8]x[1,3]: 等边四坡堆 + 两簇石尖
# =================================================================
b.hat4("gravel", 7, 1, 0.0, GRAVEL_A, shape="equilateral_triangle")
b.crest_ns("gv_a", 6, 2.0, 0.0, GRAVEL_B)          # 地坪缝上的石尖
b.crest_ew("gv_b", 7.0, 2, 0.0, GRAVEL_B)

# =================================================================
# 6. 采石岩壁 y=4 (两级台阶) + 壁顶矿石
# =================================================================
for x0 in range(6):
    b.wall_ns(f"rk_a{x0}", x0, 4.0, 0, ROCK)       # 一级岩壁 x[0,6]
for x0 in range(1, 4):
    b.wall_ns(f"rk_b{x0}", x0, 4.0, 1, ROCK)       # 二级岩壁 x[1,4]
b.crest_ns("ore_1", 1, 4.0, 2.0, ORE)              # 壁顶矿石尖
b.crest_ns("ore_2", 3, 4.0, 2.0, ORE)
b.crest_ns("ore_3", 4, 4.0, 1.0, ORE)

# =================================================================
# 7. 出口警示牌 + 雪糕筒
# =================================================================
b.wall_ns("sign", 7, 3.0, 0, "yellow")             # 警示牌立在碎石带边
b.crest_ns("sign_top", 7, 3.0, 1.0, "red")
b.crest_ew("cone_a", 6.0, 0, 0.0, "red")           # 卸料区雪糕筒
b.crest_ew("cone_b", 7.0, 0, 0.0, "red")

# =================================================================
# 教程步骤 (18 步)
# =================================================================
b.step(
    "南场界: 3 条灰色长板+2 片方板铺出采石场第一排, 长板拼缝"
    "就是车轮的吸附线。",
    ["r0_a", "r0_b", "r0_c", "r0_d", "r0_e"],
)
b.step(
    "运输道: 同板序再铺一排 —— 自卸卡车正压着这排作业。",
    ["r1_a", "r1_b", "r1_c", "r1_d", "r1_e"],
    highlight=["r0_b", "r0_c"],
)
b.step(
    "第三排合拢, 场地成形。",
    ["r2_a", "r2_b", "r2_c", "r2_d", "r2_e"],
    highlight=["r1_a", "r1_e"],
)
b.step(
    "碎石带: 岩壁脚下用 8 片橙色方板铺一排 —— 每格边线都是"
    "岩壁的地基缝。",
    ["belt_0", "belt_1", "belt_2", "belt_3", "belt_4", "belt_5",
     "belt_6", "belt_7"],
    highlight=["r2_d", "r2_e"],
    tip="这一排必须用方板不用长板: 岩壁每片墙都要独占一条单位边。",
)
b.step(
    "一级岩壁: 6 片灰色方墙沿碎石带北缘立起, 底边整边吸格边, "
    "相邻竖边互吸成排。",
    ["rk_a0", "rk_a1", "rk_a2", "rk_a3", "rk_a4", "rk_a5"],
    highlight=["belt_0", "belt_5"],
)
b.step(
    "二级岩壁与矿石: 中段再退台叠 3 片方墙, 壁顶与坡口立 3 簇"
    "橙色矿石尖 —— 采石面完工。",
    ["rk_b1", "rk_b2", "rk_b3", "ore_1", "ore_2", "ore_3"],
    highlight=["rk_a1", "rk_a4"],
)
b.step(
    "四只车轮: 两对车轮底座立在 x=2~4 与 4~6 拼缝上, 底边整边"
    "咬住地坪缝。",
    ["wb_fs", "wb_fn", "wb_rs", "wb_rn"],
    highlight=["r0_b", "r1_c"],
)
b.step(
    "底盘: 4 片灰色长板长边整边压轮组顶, 4x2 底盘架空。",
    ["ch_fs", "ch_fn", "ch_rs", "ch_rn"],
    highlight=["wb_fs", "wb_rn"],
)
b.step(
    "驾驶室前后壁: 车头 x=2 两片透明挡风、x=4 两片黄色斗前壁"
    "竖立, 底边整边吸底盘长板短边。",
    ["cb_gs", "cb_gn", "cb_hs", "cb_hn"],
    highlight=["ch_fs", "ch_rs"],
    tip="斗前壁一墙两用: 朝西是驾驶室后壁, 朝东就是车斗的前挡。",
)
b.step(
    "侧墙与车门窗: 前半黄色方墙、后半透明窗格方车门窗, 竖边"
    "与前后壁互吸成链。",
    ["cb_s2", "cb_n2", "cb_ds", "cb_dn"],
    highlight=["cb_gs", "cb_hs"],
)
b.step(
    "舱顶: 4 片黄色方板盖上 z=2, 四边同时压挡风顶、侧墙顶与"
    "斗前壁顶 —— 驾驶室锁成箱形环。",
    ["cb_r1", "cb_r2", "cb_r3", "cb_r4"],
    highlight=["cb_s2", "cb_hn"],
)
b.step(
    "排气管与警灯: 舱顶北沿立灰色瘦高排气管, 南沿立橙色警灯"
    "三角。",
    ["stack", "beacon"],
    highlight=["cb_r3", "cb_r2"],
)
b.step(
    "车斗侧板: 南北各 2 片黄色方墙接在斗前壁后, 竖边逐片互吸"
    "围出斗腔。",
    ["bx_s4", "bx_s5", "bx_n4", "bx_n5"],
    highlight=["cb_hs", "cb_hn"],
)
b.step(
    "尾梁桥: 1 条黄色长板横跨斗尾, 两条短边分别整边压南北侧板"
    "顶 —— 双端简支, 它是斗板与尾门共同的铰链座。",
    ["bx_beam"],
    highlight=["bx_s5", "bx_n5"],
)
b.step(
    "抬斗! 斗底板绕尾梁西长边铰链抬起 45 度 —— 力矩 21 < 预算 "
    "35, 这就是自卸卡车卸料的经典仰角。",
    ["bx_floor"],
    highlight=["bx_beam"],
    tip="斗底板长边整边吸尾梁长边, 斗口朝后下方 —— 碎石全滑出去了。",
)
b.step(
    "尾门甩开: 尾门绕尾梁东长边向下甩开 60 度, 悬在车尾上方 "
    "(悬挂力矩 15 < 35)。",
    ["bx_gate"],
    highlight=["bx_beam"],
)
b.step(
    "碎石堆: 车尾地面 4 片等边三角四坡自锁成碎石堆, 旁边两簇"
    "橙色石尖立在地坪缝上 —— 一斗碎石卸完!",
    ["gravel_s", "gravel_e", "gravel_n", "gravel_w", "gv_a", "gv_b"],
    highlight=["r1_e", "bx_gate"],
)
b.step(
    "场地收尾: 出口立黄色警示牌 (顶红三角), 卸料区摆 2 只红色"
    "雪糕筒 —— 采石场作业中, 注意安全!",
    ["sign", "sign_top", "cone_a", "cone_b"],
    highlight=["belt_7", "r0_d"],
)

b.finalize(
    model_id="dump_truck_01",
    name="自卸卡车",
    name_en="Dump Truck 01",
    description=(
        "全库第一辆正在卸料的自卸卡车: 黄色矿用卡车两对车轮底座托起 "
        "4x2 底盘, 驾驶室透明挡风+窗格方车门窗锁成箱形环, 斗前壁一墙"
        "两用; 车斗的核心是尾梁桥 —— 长板双端简支在斗侧板顶上, 斗底板"
        "绕它的西长边铰链抬起 45 度 (力矩 21 < 35), 尾门绕东长边向下"
        "甩开 60 度 (悬挂力矩 15 < 35), 一斗碎石刚倾泻到车尾 —— 等边"
        "四坡碎石堆+两簇石尖; 北缘两级台阶采石岩壁顶着橙色矿石, 出口"
        "警示牌与雪糕筒就位 —— 倒车, 请注意!"
    ),
    difficulty=3,
    tags=["自卸卡车", "工程", "载具", "采石场", "车轮底座"],
    min_pieces=70,
    min_steps=18,
)
