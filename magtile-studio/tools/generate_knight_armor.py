#!/usr/bin/env python3
"""生成模型 data/models/knight_armor_01.json (军械库骑士铠甲)。

中世纪/城堡主题: 全库第一套陈列铠甲 —— 与 robot_01 (充电底座 +
箱式塔腿 + 臂柱肩桥的人形机器人) 的结构逻辑刻意区分: 本作是
军械库里的展品, 主角是 "拱式腿甲 + 垂挂臂甲": 双腿是两片单墙
胫甲, 髋甲方板双端搭在腿顶如拱桥 (基座-左腿-髋-右腿锁成拱环,
剪断任一条铰链力都能绕行), 两只直角三角铁靴一前一后错步咬住
台缝与腿身 (造型即斜撑); 两片臂甲从肩甲两侧竖边向外垂挂 30 度
(受拉悬挂 30g / 力矩 7.5, 双双远低于预算); 胸口窗格方透视胸甲、
头盔窗格方面罩, 盔顶等腰四坡红缨冲天 (缨尖 5.94); 身旁 120g
大方片巨盾后仰 65 度倚地而立, 北墙兵器架双柱各挑一柄等腰长剑,
两座壁炬照亮红毯。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 铠甲面南):
  - 军械库地面 (x [0,5], y [0,4]): 4 行 (红毯迎门)             12 片
  - 陈列基座 (x [1,2], y [1,3], z 0..1): 墙环 x6 + 台面 x2
    + 绶带旗 x3                                                11 片
  - 腿甲: 单墙胫甲 x2 + 直角三角铁靴 x2 (一前一后错步)           4 片
  - 髋甲: 方板双端搭腿顶 (拱桥)                                  1 片
  - 胸甲 (z 2..3): 1x1 墙环 x4 (胸口窗格方 x1)                   4 片
  - 肩甲: 方板压胸甲顶                                           1 片
  - 臂甲: 方片 x2 自肩甲两侧竖边外垂 30 度                        2 片
  - 头盔 (z 3..4): 1x1 墙环 x4 (窗格方面罩 x1)
    + 等腰四坡红缨 x4 (缨尖 5.94)                                8 片
  - 巨盾: 大方片 x1 后仰 65 度倚地                                1 片
  - 兵器架: 立柱 x2 + 等腰长剑 x2                                 4 片
  - 壁炬 x2: 等边四坡锥各 4 片                                    8 片
  合计 56 片, 12 个教程步骤, 7 种磁力片形状 (全部 CORE-9 之内)。

物理规则要点 (通过 R1~R8 全部校验, strict 档同样全绿):
  - 拱式腿甲: 基座-左腿-髋甲-右腿构成闭合环, 髋甲不是悬挑;
    铁靴两条直角边分别咬台缝与腿身竖边, 拱脚再加一道保险;
  - 臂甲顶边一线双吸 (肩甲侧边 + 胸甲墙顶): 悬重 30g << 168g,
    外摆力矩 30 x 0.5 x sin30 = 7.5 << 35 (strict 档);
  - 巨盾 (120g) 底边骑地面拼缝 (一线双吸, 接触总长 4):
    后仰力矩 120 x cos65 x 1.0 = 50.7 < 17.5 x 4 = 70 (strict 档);
  - 长剑底边整边骑立柱顶边, 重心正压铰链线, 力矩为零;
  - 胸甲/头盔墙环四角互吸, 红缨四棱自锁 —— 无单点失效。

用法: python3 tools/generate_knight_armor.py  (在 magtile-studio 目录下运行)
"""

import math

from magtile_gen import ModelBuilder

b = ModelBuilder()

FLOOR = "gray"      # 军械库石板地
CARPET = "red"      # 红毯
PLINTH = "blue"     # 陈列基座
RIBBON = "blue"     # 绶带旗
ARMOR = "gray"      # 铠甲银灰
CHEST = "clear"     # 窗格方胸甲
VISOR = "clear"     # 窗格方面罩
PLUME = "red"       # 盔缨
SHIELD = "blue"     # 巨盾
RACK = "gray"       # 兵器架立柱
SWORD = "clear"     # 长剑
TORCH = "orange"    # 壁炬

ARM_SWING = 30.0    # 臂甲外摆角 (自竖直)
SHIELD_TILT = 65.0  # 巨盾后仰角 (自水平)
SIN_A = round(math.sin(math.radians(ARM_SWING)), 6)
COS_A = round(math.cos(math.radians(ARM_SWING)), 6)
COS_S = round(math.cos(math.radians(SHIELD_TILT)), 6)
SIN_S = round(math.sin(math.radians(SHIELD_TILT)), 6)

# =================================================================
# 1. 军械库地面 (x [0,5], y [0,4]): 每行 方 + 长板 x2, 拼缝 x=1/3
# =================================================================
for r in range(4):
    b.flat(f"fl{r}_a", 0, r, 0.0, FLOOR)
    b.flat_rect(f"fl{r}_b", 1, r, 0.0, CARPET if r == 0 else FLOOR)
    b.flat_rect(f"fl{r}_c", 3, r, 0.0, FLOOR)

# =================================================================
# 2. 陈列基座 (x [1,2], y [1,3], z 0..1): 墙环 + 台面 + 绶带旗
# =================================================================
b.wall_ns("pl_s", 1, 1.0, 0, PLINTH)
b.wall_ns("pl_n", 1, 3.0, 0, PLINTH)
for y in (1, 2):
    b.wall_ew(f"pl_w_{y}", 1.0, y, 0, PLINTH)
    b.wall_ew(f"pl_e_{y}", 2.0, y, 0, PLINTH)
b.flat("pt_1", 1, 1, 1.0, PLINTH)
b.flat("pt_2", 1, 2, 1.0, PLINTH)
b.crest_ew("rib_w", 1.0, 2, 1.0, RIBBON)
b.crest_ew("rib_e", 2.0, 2, 1.0, RIBBON)
b.crest_ns("pn_n", 1, 3.0, 1.0, RIBBON)

# =================================================================
# 3. 腿甲 + 错步铁靴 + 髋甲 (拱桥): 基座-左腿-髋-右腿闭合成环
# =================================================================
b.wall_ew("leg_w", 1.0, 1, 1, ARMOR)
b.wall_ew("leg_e", 2.0, 1, 1, ARMOR)
b.brace("sab_w", (1.0, 1.0, 1.0), "+x", ARMOR)   # 前脚 (y=1 面)
b.brace("sab_e", (2.0, 2.0, 1.0), "-x", ARMOR)   # 后脚 (y=2 面)
b.flat("hip", 1, 1, 2.0, ARMOR)

# =================================================================
# 4. 胸甲 (z 2..3, [1,2]x[1,2]): 1x1 墙环, 胸口窗格方
# =================================================================
b.add("chest", "window_square", (1.5, 1.0, 2.5), (90, 0, 0), CHEST)
b.wall_ns("back", 1, 2.0, 2, ARMOR)
b.wall_ew("tw", 1.0, 1, 2, ARMOR)
b.wall_ew("te", 2.0, 1, 2, ARMOR)

# =================================================================
# 5. 肩甲 + 垂挂臂甲: 臂甲自肩甲两侧竖边外垂 30 度
# =================================================================
b.flat("shoulder", 1, 1, 3.0, ARMOR)
b.place_edge("arm_w", "square", 0,
             (1.0, 1.0, 3.0), (1.0, 2.0, 3.0), (-SIN_A, 0.0, -COS_A), ARMOR)
b.place_edge("arm_e", "square", 0,
             (2.0, 1.0, 3.0), (2.0, 2.0, 3.0), (SIN_A, 0.0, -COS_A), ARMOR)

# =================================================================
# 6. 头盔 (z 3..4, [1,2]x[1,2]) + 等腰四坡红缨
# =================================================================
b.add("hm_visor", "window_square", (1.5, 1.0, 3.5), (90, 0, 0), VISOR)
b.add("hm_n", "square", (1.5, 2.0, 3.5), (90, 0, 0), ARMOR)
b.add("hm_w", "square", (1.0, 1.5, 3.5), (90, 0, 90), ARMOR)
b.add("hm_e", "square", (2.0, 1.5, 3.5), (90, 0, 90), ARMOR)
PLUME_IDS = b.hat4("plume", 1, 1, 4.0, PLUME)

# =================================================================
# 7. 巨盾 (后仰 65 度倚地) + 兵器架双柱双剑 + 壁炬
# =================================================================
b.place_edge("shield", "large_square", 0,
             (3.0, 1.0, 0.0), (5.0, 1.0, 0.0), (0.0, -COS_S, SIN_S), SHIELD)
b.wall_ns("rk_p1", 3, 4.0, 0, RACK)
b.wall_ns("rk_p2", 4, 4.0, 0, RACK)
b.spire_ns("sword_w", 3, 4.0, 1.0, SWORD)
b.spire_ns("sword_e", 4, 4.0, 1.0, SWORD)
TORCH_A = b.hat4("torch_a", 0, 0, 0.0, TORCH, shape="equilateral_triangle")
TORCH_B = b.hat4("torch_b", 0, 3, 0.0, TORCH, shape="equilateral_triangle")

# =================================================================
# 教程步骤 (12 步)
# =================================================================
b.step(
    "铺军械库地面南半 (y [0,2]): 6 片, 红毯迎门。",
    ["fl0_a", "fl0_b", "fl0_c", "fl1_a", "fl1_b", "fl1_c"],
    tip="x=1 与 x=3 的拼缝是基座墙脚 —— 展品位置从地面定下。",
)
b.step(
    "铺地面北半 (y [2,4]): 6 片, 军械库合拢。",
    ["fl2_a", "fl2_b", "fl2_c", "fl3_a", "fl3_b", "fl3_c"],
    highlight=["fl1_b"],
    tip="北墙边留给兵器架 —— 剑与甲隔馆相望。",
)
b.step(
    "砌陈列基座墙环: 6 片蓝墙踩拼缝, 四角竖边互吸。",
    ["pl_s", "pl_w_1", "pl_w_2", "pl_n", "pl_e_2", "pl_e_1"],
    highlight=["fl1_b", "fl2_b"],
    tip="基座 1x2 进深 —— 铠甲站前半, 后半留展台余地。",
)
b.step(
    "铺基座台面并挂绶带旗: 2 片台面 + 两侧绶带 + 北沿锦旗。",
    ["pt_1", "pt_2", "rib_w", "rib_e", "pn_n"],
    highlight=["pl_s", "pl_n"],
    tip="台面每片同时压三段墙顶; 旗与绶带重心正压铰链。",
)
b.step(
    "立腿甲与错步铁靴: 两片胫甲踩台缝, 直角三角铁靴一前一后。",
    ["leg_w", "leg_e", "sab_w", "sab_e"],
    highlight=["pt_1"],
    tip="铁靴两条直角边分别吸台缝与腿身竖边 —— 造型即斜撑。",
)
b.step(
    "架髋甲 + 合胸甲: 髋甲方板双端搭腿顶如拱桥, 再围 1x1 胸环。",
    ["hip", "tw", "te", "chest", "back"],
    highlight=["leg_w", "leg_e"],
    tip="基座-左腿-髋-右腿锁成拱环; 胸口窗格方是透气的胸甲。",
)
b.step(
    "压肩甲、垂臂甲: 肩甲方板压胸甲顶, 两片臂甲外垂 30 度。",
    ["shoulder", "arm_w", "arm_e"],
    highlight=["chest", "te"],
    tip="臂甲顶边一线双吸 (肩甲侧边 + 胸甲墙顶), 悬重仅 30g。",
)
b.step(
    "扣头盔: 4 片墙环踩肩甲, 南面窗格方面罩。",
    ["hm_visor", "hm_n", "hm_w", "hm_e"],
    highlight=["shoulder"],
    tip="面罩后面空无一人 —— 这就是陈列铠甲的神秘。",
)
b.step(
    "插盔缨: 4 片等腰四坡红缨冲天, 缨尖 5.94 全馆最高。",
    PLUME_IDS,
    highlight=["hm_visor", "hm_n"],
    tip="四条斜棱两两互吸自锁 —— 红缨一立, 威风凛凛。",
)
b.step(
    "立兵器架: 双柱贴北墙, 两柄等腰长剑整边骑上柱顶。",
    ["rk_p1", "rk_p2", "sword_w", "sword_e"],
    highlight=["fl3_c"],
    tip="剑刃重心正压柱顶铰链线, 力矩为零 —— 稳稳当当。",
)
b.step(
    "倚巨盾: 大方片后仰 65 度靠在红毯东侧, 底边骑地面拼缝。",
    ["shield"],
    highlight=["fl0_c", "fl1_c"],
    tip="底边一线双吸 (接触总长 4), 后仰力矩 50.7 < 预算 70。",
)
b.step(
    "点壁炬 x2 —— 军械库骑士铠甲布展完成!",
    TORCH_A + TORCH_B,
    highlight=["fl0_a", "fl3_a"],
    tip="壁炬四棱自锁; 火光里, 铠甲的影子投在红毯上。",
)

b.finalize(
    model_id="knight_armor_01",
    name="军械库骑士铠甲",
    name_en="Knight Armor 01",
    description=(
        "全库第一套陈列铠甲: 拱式腿甲 (基座-左腿-髋甲-右腿闭合"
        "成环, 髋甲双端搭腿顶不是悬挑) + 直角三角铁靴一前一后"
        "错步 (造型即斜撑); 两片臂甲自肩甲两侧竖边外垂 30 度"
        " (受拉悬挂 30g / 力矩 7.5 双双远低于预算); 胸口与面罩"
        "两扇窗格方, 盔顶等腰四坡红缨冲天 (5.94 全馆最高);"
        " 身旁 120g 大方片巨盾后仰 65 度倚地 (力矩 50.7 < 一线"
        "双吸预算 70), 兵器架双柱各挑一柄等腰长剑, 双壁炬照亮"
        "红毯。拱环传力、垂挂臂甲、斜倚巨盾 —— 三个静力学新"
        "姿势一课学会。"
    ),
    difficulty=3,
    tags=["中世纪", "骑士", "铠甲", "军械库", "进阶"],
    min_pieces=54,
    min_steps=12,
)
