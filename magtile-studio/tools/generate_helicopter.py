#!/usr/bin/env python3
"""生成模型 data/models/helicopter_01.json (救援直升机)。

第四批模型 ⑧: 应急救援主题 —— 全库第一架旋翼飞行器:
灰色停机坪拼出黄色 H 标, 双滑橇墙立在坪面上驮起 3x4 箱式
机舱, 机头两层透明风挡; 尾梁不是悬挑 —— 两条长方形从机舱
东墙顶接力到尾撑柱顶, 双端受力如桥; 舱顶正中立 1x1 旋翼塔,
桨毂盖顶后四片桨叶向四方平挑 (每片力矩 10 <= 预算 20);
尾鳍立在尾梁末端, 尾旋翼收顶, 机头探照灯与红绿航行灯
点亮 —— 救援直升机随时起飞。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 停机坪: 7x3 平铺 (含黄色 H 标 7 片)                    21 片
  - 双滑橇: 南北各 3 片墙 (z 0..1)                           6 片
  - 舱底: 3x3 平铺 (z=1)                                    9 片
  - 舱墙: 12 片 x 2 层 (z 1..3, 机头透明风挡)               24 片
  - 舱顶: 3x3 平铺 (z=3)                                    9 片
  - 尾撑柱: 2 片叠柱 (x=8, z 0..2)                           2 片
  - 尾梁: 2 条长方形 (z=2, 双端受力)                         2 片
  - 尾鳍 + 尾旋翼: 各 1 片                                   2 片
  - 旋翼塔: 1x1 墙环 (z 3..4)                                4 片
  - 桨毂 + 四片桨叶 (z=4)                                    5 片
  - 探照灯 + 红绿航行灯: 3 片                                3 片
  合计 87 片, 18 个教程步骤, 3 种磁力片形状。

几何要点:
  - 尾梁两条长方形短边接力: 西端吸机舱东墙上下环夹缝, 东端
    落尾撑柱顶 —— 尾梁是双端受力桥, 不是悬挑;
  - 桨叶每片单边吸桨毂/舱顶沿, 质心距铰链 0.5, 力矩 10 恰在
    预算之内 —— 四片对称出挑, 重心仍在旋翼塔正中;
  - 航行灯三角与桨叶错高零重叠 (灯尖 3.87 < 桨叶平面 4.0)。

用法: python3 tools/generate_helicopter.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

# =================================================================
# 1. 停机坪 (z=0): 7x3 平铺, 黄色 H 标 (x3/x5 两竖 + x4 中横)
# =================================================================
H_MARK = {(3, 0), (3, 1), (3, 2), (5, 0), (5, 1), (5, 2), (4, 1)}
for x in range(1, 8):
    for y in range(3):
        color = "yellow" if (x, y) in H_MARK else "gray"
        b.flat(f"pad_{x}_{y}", x, y, 0.0, color)

# =================================================================
# 2. 双滑橇 (z 0..1): 南北各 3 片墙立在坪面上
# =================================================================
for x in (1, 2, 3):
    b.wall_ns(f"skid_s_{x}", x, 0.0, 0, "gray")
for x in (1, 2, 3):
    b.wall_ns(f"skid_n_{x}", x, 3.0, 0, "gray")

# =================================================================
# 3. 机舱 (x 1..4, y 0..3, z 1..3): 舱底 + 双层舱墙 + 舱顶
# =================================================================
for x in (1, 2, 3):
    for y in (0, 1, 2):
        b.flat(f"cf_{x}_{y}", x, y, 1.0, "red")
for lv in (1, 2):
    for x in (1, 2, 3):
        b.wall_ns(f"cw_s{lv}_{x}", x, 0.0, lv, "red")
    for x in (1, 2, 3):
        b.wall_ns(f"cw_n{lv}_{x}", x, 3.0, lv, "red")
    for y in (0, 1, 2):
        b.wall_ew(f"cw_w{lv}_{y}", 1.0, y, lv, "clear")   # 透明风挡
    for y in (0, 1, 2):
        b.wall_ew(f"cw_e{lv}_{y}", 4.0, y, lv, "red")
for x in (1, 2, 3):
    for y in (0, 1, 2):
        b.flat(f"cr_{x}_{y}", x, y, 3.0, "red")

# =================================================================
# 4. 尾部: 尾撑柱 + 尾梁 (双端受力) + 尾鳍 + 尾旋翼
# =================================================================
b.wall_ew("tcol_0", 8.0, 1, 0, "gray")
b.wall_ew("tcol_1", 8.0, 1, 1, "gray")
b.flat_rect("boom_w", 4, 1, 2.0, "gray", axis="x")        # x 4..6
b.flat_rect("boom_e", 6, 1, 2.0, "gray", axis="x")        # x 6..8
b.wall_ew("tfin", 8.0, 1, 2, "red")
b.crest_ew("trot", 8.0, 1, 3.0, "gray")

# =================================================================
# 5. 旋翼塔 (x 2..3, y 1..2, z 3..4) + 桨毂 + 四片桨叶 (z=4)
# =================================================================
b.wall_ns("mast_s", 2, 1.0, 3, "gray")
b.wall_ns("mast_n", 2, 2.0, 3, "gray")
b.wall_ew("mast_w", 2.0, 1, 3, "gray")
b.wall_ew("mast_e", 3.0, 1, 3, "gray")
b.flat("hub", 2, 1, 4.0, "gray")
b.flat("blade_w", 1, 1, 4.0, "gray")
b.flat("blade_e", 3, 1, 4.0, "gray")
b.flat("blade_s", 2, 0, 4.0, "gray")
b.flat("blade_n", 2, 2, 4.0, "gray")

# =================================================================
# 6. 探照灯 + 红绿航行灯 (舱顶沿口, 灯尖 3.87 < 桨叶平面 4.0)
# =================================================================
b.crest_ew("spot", 1.0, 1, 3.0, "yellow")                 # 机头探照灯
b.crest_ns("nav_s", 1, 0.0, 3.0, "red")                   # 左舷红灯
b.crest_ns("nav_n", 1, 3.0, 3.0, "green")                 # 右舷绿灯

# =================================================================
# 教程步骤 (18 步)
# =================================================================
b.step(
    "铺停机坪西半: 12 片正方形, 黄色 H 标的第一竖已就位。",
    [f"pad_{x}_{y}" for x in (1, 2, 3, 4) for y in (0, 1, 2)],
    tip="灰底黄标 —— H 是直升机停机坪的国际标志。",
)
b.step(
    "铺停机坪东半: 再 9 片, H 标合拢, 坪面到位。",
    [f"pad_{x}_{y}" for x in (5, 6, 7) for y in (0, 1, 2)],
    highlight=["pad_4_1"],
    tip="东半坪面还要驮尾撑柱 —— 停机坪就是全机的地基。",
)
b.step(
    "立南滑橇: 3 片灰色墙沿坪面南沿立起。",
    ["skid_s_1", "skid_s_2", "skid_s_3"],
    highlight=["pad_1_0"],
    tip="滑橇底边整边吸坪面边沿, 竖边逐片互锁。",
)
b.step(
    "立北滑橇: 北沿再立 3 片, 双橇平行如雪橇。",
    ["skid_n_1", "skid_n_2", "skid_n_3"],
    highlight=["skid_s_1"],
    tip="双滑橇驮起整个机舱 —— 落地缓冲全靠它。",
)
b.step(
    "架舱底: 9 片红色正方形拼成 3x3, 南北沿骑上滑橇顶。",
    [f"cf_{x}_{y}" for x in (1, 2, 3) for y in (0, 1, 2)],
    highlight=["skid_s_1", "skid_n_3"],
    tip="舱底边沿吸橇顶边, 中央拼缝互吸成网。",
)
b.step(
    "围舱墙下环南北: 6 片立上舱底边沿。",
    ["cw_s1_1", "cw_s1_2", "cw_s1_3", "cw_n1_1", "cw_n1_2", "cw_n1_3"],
    highlight=["cf_1_0", "cf_3_2"],
    tip="南北舱墙夹住舱底 —— 机身开始成形。",
)
b.step(
    "封舱墙下环西东: 机头 3 片透明风挡, 机尾 3 片红墙。",
    ["cw_w1_0", "cw_w1_1", "cw_w1_2", "cw_e1_0", "cw_e1_1", "cw_e1_2"],
    highlight=["cw_s1_1", "cw_n1_3"],
    tip="透明风挡朝西 —— 飞行员的视野从这里展开。",
)
b.step(
    "叠舱墙上环南北: 6 片对缝叠上下环。",
    ["cw_s2_1", "cw_s2_2", "cw_s2_3", "cw_n2_1", "cw_n2_2", "cw_n2_3"],
    highlight=["cw_s1_1"],
    tip="上下对缝, 机舱长到两层高。",
)
b.step(
    "封舱墙上环西东: 风挡再加一层, 机尾墙顶等着接尾梁。",
    ["cw_w2_0", "cw_w2_1", "cw_w2_2", "cw_e2_0", "cw_e2_1", "cw_e2_2"],
    highlight=["cw_w1_1", "cw_e1_1"],
    tip="东墙上下环的夹缝就是尾梁的西支点。",
)
b.step(
    "盖舱顶西列: 6 片红色正方形压住墙顶。",
    [f"cr_{x}_{y}" for x in (1, 2) for y in (0, 1, 2)],
    highlight=["cw_w2_1"],
    tip="舱顶每片都吸墙顶边 —— 旋翼塔就立在它上面。",
)
b.step(
    "盖舱顶东列: 再 3 片, 机舱封顶。",
    ["cr_3_0", "cr_3_1", "cr_3_2"],
    highlight=["cr_2_1"],
    tip="舱顶合拢, 机舱成为一只封闭的抗弯箱。",
)
b.step(
    "立尾撑柱: 2 片灰色立板在坪面东沿叠到 z=2。",
    ["tcol_0", "tcol_1"],
    highlight=["pad_7_1"],
    tip="尾撑柱是尾梁的东支点 —— 先立柱, 再架梁。",
)
b.step(
    "合龙尾梁: 2 条灰色长方形从机舱东墙接力到尾撑柱顶。",
    ["boom_w", "boom_e"],
    highlight=["cw_e1_1", "cw_e2_1", "tcol_1"],
    tip="尾梁双端受力如桥, 跨中只有一道短边接缝。",
)
b.step(
    "立尾鳍收尾旋翼: 尾鳍立在尾梁末端, 灰色尾旋翼收顶。",
    ["tfin", "trot"],
    highlight=["boom_e", "tcol_1"],
    tip="尾鳍与尾撑柱上下同面对缝 —— 尾迹从这里划出去。",
)
b.step(
    "立旋翼塔: 4 片灰色墙在舱顶正中围成 1x1 方筒。",
    ["mast_s", "mast_n", "mast_w", "mast_e"],
    highlight=["cr_2_1"],
    tip="塔底整边吸舱顶拼缝, 转角互锁 —— 主轴基座务必扎实。",
)
b.step(
    "盖桨毂接南北桨叶: 桨毂扣住塔顶, 南北桨叶平挑出去。",
    ["hub", "blade_s", "blade_n"],
    highlight=["mast_s", "mast_n"],
    tip="每片桨叶质心距铰链 0.5, 力矩 10 恰在预算之内。",
)
b.step(
    "接东西桨叶: 四叶成十字, 重心仍在旋翼塔正中。",
    ["blade_w", "blade_e"],
    highlight=["hub"],
    tip="四片对称出挑互相平衡 —— 旋翼十字就位。",
)
b.step(
    "点亮机头灯组: 探照灯居中, 左舷红灯右舷绿灯 —— 救援"
    "直升机随时起飞!",
    ["spot", "nav_s", "nav_n"],
    highlight=["cr_1_1", "blade_w"],
    tip="灯尖 3.87 低于桨叶平面 4.0, 错高零重叠 —— 旋翼转起来!",
)

b.finalize(
    model_id="helicopter_01",
    name="救援直升机",
    name_en="Rescue Helicopter 01",
    description=(
        "应急救援主题: 全库第一架旋翼飞行器 —— 灰色停机坪拼出黄色 "
        "H 标, 双滑橇墙驮起 3x4 双层箱式机舱, 机头两层透明风挡; "
        "尾梁不是悬挑: 两条长方形短边接力, 西端吸进机舱东墙上下环"
        "夹缝, 东端落在尾撑柱顶 —— 双端受力如桥; 舱顶正中 1x1 旋翼"
        "塔戴桨毂, 四片桨叶向四方平挑 (每片力矩 10 恰在预算内, "
        "四叶对称互衡); 尾鳍立尾梁末端收尾旋翼, 机头探照灯与红绿"
        "航行灯错高点亮 (灯尖 3.87 < 桨叶平面 4.0) —— 随时起飞。"
    ),
    difficulty=4,
    tags=["交通", "直升机", "救援", "飞行器", "应急"],
    min_pieces=85,
    min_steps=18,
)
