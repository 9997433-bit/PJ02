#!/usr/bin/env python3
"""生成模型 data/models/desk_organizer_01.json (书桌整理站)。

实用功能主题开篇之作 (CONTENT_STRATEGY.md 主题矩阵中该主题此前为空):
反幼稚规则 J5 明令禁止"四片围一圈是笔筒"的敷衍实用件 —— 本作用
一整块 6x3 桌面底板把五个真功能位组织成一座"文具指挥站": 双层
笔筒塔、30 度斜躺手机架、回形针小盘、照片窗格框、双墙信件槽,
外加便签板与多肉小盆栽 —— 搭完就能立刻投入使用的收纳作品。

结构总览 (世界单位: 1.0 = 正方形磁力片边长, 使用者坐在南侧):
  - 桌面底板 (x [0,6], y [0,3]): 黄橙棋盘格方板               18 片
  - 回形针盘 (x [0,1], y [0,1], z 0..1): 青色四墙开顶小盒 +
    一支清色瘦高"钢笔"立在盘沿 (笔尖 3.0)                       5 片
  - 笔筒塔 (x [0,1], y [2,3], z 0..2): 蓝色四墙两层开顶深筒 +
    筒沿一株绿色多肉盆栽                                        9 片
  - 手机架 (x [2,4]): 紫色两片靠背立在 y=2 拼缝 + 橙色 30 度
    斜躺坡道 (顶边吸靠背顶, 坡尾落桌板) + 两片直角斜撑锁背       5 片
  - 展示区 (x [4,6]): 粉色照片窗格框 (框顶红色顶花三角) +
    黄色便签板 (竖长方形一次骑住两条单位拼缝)                    3 片
  - 信件槽 (x [4,6], y [0,1]): 两道绿色立墙夹出一格投信位        2 片
  合计 42 片, 10 个教程步骤, 6 种磁力片形状 (全部 CORE-9 之内)。

招牌技法: 30 度坡道不当滚珠道用, 翻身成手机斜躺架 —— 顶边吸靠背、
坡尾落桌板, 手机躺上去的角度正好是看视频的角度。

物理规则要点 (validate 常规 + strict 双档零警告):
  - 全部立件墙脚踩桌板拼缝或沿口, 整边吸合;
  - 手机坡道顶边整边吸靠背顶沿, 坡尾自身落地, 零悬挑;
    靠背两端直角斜撑双边吸合 (竖边吸靠背端缝, 横边吸桌板拼缝),
    靠背-斜撑-桌板锁成门式框架, 手机放上去也不晃;
  - 便签板 (长 2 竖长方形) 底边一次骑住两条单位拼缝
    (长短边搭配规则), 与靠背东端竖边互咬;
  - 笔筒/纸盘为开顶墙环, 四角竖边互咬闭环, 顶上不封 ——
    笔和回形针要放得进去。

用法: python3 tools/generate_desk_organizer.py  (在 magtile-studio 目录下运行)
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from magtile_gen import ModelBuilder  # noqa: E402

b = ModelBuilder()

DESK_A = "yellow"   # 桌面棋盘格
DESK_B = "orange"
TRAY = "cyan"       # 回形针盘
PEN = "clear"       # 钢笔
CUP = "blue"        # 笔筒塔
PLANT = "green"     # 多肉盆栽
BACK = "purple"     # 手机架靠背
RAMP = "orange"     # 手机坡道
BRACE = "gray"      # 斜撑
FRAME = "pink"      # 照片框
BOARD = "yellow"    # 便签板
CLIP = "red"        # 便签夹
RACK = "green"      # 信件槽


def wall_ns_t(tid, tile_type, x0, y, z0, color):
    b.add(tid, tile_type, (x0 + 0.5, y, z0 + 0.5), (90, 0, 0), color)


# =================================================================
# 1. 桌面底板 (x [0,6], y [0,3]): 黄橙棋盘格
# =================================================================
for j in range(3):
    for i in range(6):
        b.flat(f"desk_{i}_{j}", i, j, 0.0, DESK_A if (i + j) % 2 == 0 else DESK_B)

# =================================================================
# 2. 回形针盘 (x [0,1], y [0,1]) + 钢笔
# =================================================================
b.wall_ns("tray_s", 0, 0.0, 0, TRAY)
b.wall_ns("tray_n", 0, 1.0, 0, TRAY)
b.wall_ew("tray_w", 0.0, 0, 0, TRAY)
b.wall_ew("tray_e", 1.0, 0, 0, TRAY)
b.spire_ns("pen", 0, 1.0, 1.0, PEN)           # 钢笔立在盘沿 (北墙顶)

# =================================================================
# 3. 笔筒塔 (x [0,1], y [2,3], z 0..2): 两层开顶深筒
# =================================================================
for lv in range(2):
    b.wall_ns(f"cup{lv}_s", 0, 2.0, lv, CUP)
    b.wall_ns(f"cup{lv}_n", 0, 3.0, lv, CUP)
    b.wall_ew(f"cup{lv}_w", 0.0, 2, lv, CUP)
    b.wall_ew(f"cup{lv}_e", 1.0, 2, lv, CUP)
b.crest_ns("plant", 0, 3.0, 2.0, PLANT)       # 多肉盆栽立在筒沿

# =================================================================
# 4. 手机架 (x [2,4]): 靠背 + 30 度斜躺坡道 + 双斜撑
# =================================================================
b.wall_ns("back_w", 2, 2.0, 0, BACK)
b.wall_ns("back_e", 3, 2.0, 0, BACK)
b.brace("back_brace_w", (2.0, 2.0, 0.0), "+y", BRACE)
b.brace("back_brace_e", (4.0, 2.0, 0.0), "+y", BRACE)
b.ramp("phone_ramp", "-y", 2.0, 2, 1.0, RAMP)  # 顶边吸靠背顶, 坡尾落桌板

# =================================================================
# 5. 展示区: 照片框 + 便签板 + 便签夹
# =================================================================
wall_ns_t("frame", "window_square", 4, 3.0, 0, FRAME)   # 照片框立在北沿
b.crest_ns("clip", 4, 3.0, 1.0, CLIP)                   # 相框顶花立在框顶
b.lintel_ns("board", 4, 2.0, 0, BOARD)                  # 便签板骑 y=2 双缝

# =================================================================
# 6. 信件槽 (x [4,6] 区, y [0,1]): 两道立墙夹一格
# =================================================================
b.wall_ew("rack_w", 5.0, 0, 0, RACK)
b.wall_ew("rack_e", 6.0, 0, 0, RACK)

# =================================================================
# 教程步骤 (10 步)
# =================================================================
b.step(
    "铺桌面底板第一排 (靠自己这排): 六片黄橙相间的方板从左到右吸成一条。",
    [f"desk_{i}_0" for i in range(6)],
    tip="底板是整个整理站的地基, 拼缝对齐了, 上面的每个功能位才有得吸。",
)
b.step(
    "铺第二排底板: 再来六片, 与第一排行行整边互吸。",
    [f"desk_{i}_1" for i in range(6)],
    highlight=["desk_0_0"],
    tip="棋盘格颜色错开铺, 一眼就能看出哪片没对齐。",
)
b.step(
    "铺第三排底板: 桌面完工, 6x3 的大底板轻推应整体滑动。",
    [f"desk_{i}_2" for i in range(6)],
    highlight=["desk_0_1"],
    tip="底板越大越稳 —— 这就是整理站不怕碰的秘密。",
)
b.step(
    "左前角围回形针盘: 四片青色方板合围开顶小盒, 一支清色钢笔立在盘沿。",
    ["tray_s", "tray_e", "tray_n", "tray_w", "pen"],
    highlight=["desk_0_0"],
    tip="盒口不封顶 —— 回形针、橡皮擦都从上面丢进去。",
)
b.step(
    "左后角起笔筒塔第一层: 四片蓝色方板合围, 墙脚踩住底板拼缝。",
    ["cup0_s", "cup0_e", "cup0_n", "cup0_w"],
    highlight=["desk_0_2"],
    tip="笔筒要装长铅笔, 所以要盖两层 —— 这只是第一层。",
)
b.step(
    "笔筒塔加高第二层: 再来四片上下边完整贴合, 筒沿放一株绿色多肉。",
    ["cup1_s", "cup1_e", "cup1_n", "cup1_w", "plant"],
    highlight=["cup0_s"],
    tip="两层深筒笔不歪 —— 多肉是整理站的镇桌之宝。",
)
b.step(
    "立手机架靠背: 两片紫色方板踩上 y=2 拼缝, 两端各锁一片直角斜撑。",
    ["back_w", "back_e", "back_brace_w", "back_brace_e"],
    highlight=["desk_2_1", "desk_3_1"],
    tip="斜撑竖边吸靠背端缝、横边吸桌板拼缝 —— 靠背从此推不倒。",
)
b.step(
    "搭手机坡道: 橙色长板顶边整边吸住靠背顶沿, 坡尾自然落在桌板上。",
    ["phone_ramp"],
    highlight=["back_w", "back_e"],
    tip="30 度斜躺角正好是看视频的角度 —— 手机放上去试试!",
)
b.step(
    "布置展示区: 粉色照片窗格框立在北沿, 框顶点一片红色顶花, 黄色便签板骑住双拼缝。",
    ["frame", "clip", "board"],
    highlight=["back_e", "desk_4_2"],
    tip="便签板底边一次吸住两条拼缝, 还和靠背手拉手 —— 长片就要这样用。",
)
b.step(
    "装信件槽收尾: 两道绿色立墙夹出一格投信位 —— 整理站开张!",
    ["rack_w", "rack_e"],
    highlight=["desk_4_0", "desk_5_0"],
    tip="信、卡片、课程表都插这里 —— 明天的你会感谢今天搭好它的你。",
)

b.finalize(
    model_id="desk_organizer_01",
    name="书桌整理站",
    name_en="Desk Organizer Station 01",
    description=(
        "实用功能开篇: 不是玩具, 是真能用的桌面收纳站 —— 6x3 黄橙棋盘底板上"
        "组织起五个功能位: 两层深的蓝色笔筒塔 (筒沿养着多肉), 30 度斜躺手机架"
        " (坡道顶边吸靠背、坡尾落桌板, 角度正好看视频), 青色回形针小盘, 顶着"
        "红花的粉色照片窗格框, 以及双墙信件槽; 黄色便签板一次骑住两条拼缝, "
        "还与靠背手拉手。搭完的第一件事: 把自己的铅笔和手机请上去。"
    ),
    difficulty=2,
    tags=["实用功能", "书桌", "收纳", "手机架", "文具"],
    min_pieces=42,
    min_steps=10,
)
