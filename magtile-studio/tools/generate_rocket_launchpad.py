#!/usr/bin/env python3
"""生成模型 data/models/rocket_launchpad_01.json (火箭发射台 · 分级对接)。

技法: T16 分体对接 (主) + T01 盒式框架 + T14 斜撑加固; 范式 module_dock。
招牌技法: 火箭按"一级 -> 二级 -> 整流罩"在发射架上逐级对接, 勤务塔
最后伸出摆渡桥与整流罩级间对接 —— 教程复刻真实火箭的垂直总装流程。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  模块 A 发射架: 3x3 盒式基座 (T01) + 台面 + 东西两条 30 度导流坡道  29 片
  模块 B 火箭:   台面中央 1x1 双级箭体 + 四片直角三角尾翼 (T14 斜撑,
                双边整边吸合) + 等腰四坡整流罩 (斜棱自锁成环)         16 片
  模块 C 勤务塔: 发射架北墙上共享一片墙起塔, 1x1 塔身四层 +
                塔顶平台与天线塔尖                                    17 片
  模块 D 摆渡桥: 1 片平板同时整边吸住火箭二级顶缘与塔身 —— 全模型
                最关键的一次"对接", 把塔与箭锁成大环                   1 片
  模块 E 罐区:   东侧地坪外接 2 座 1x1 燃料罐, 等边四坡穹顶            16 片
  外加环形地坪 9 片; 合计 82 片, 18 个教程步骤。

物理规则要点 (通过 R1~R8 全部校验):
  - 发射台面四周整边压在盒式墙顶上, 中央台面片四邻互吸 (R7b: 封顶
    前后中央上方始终开敞, 13 向射线可达);
  - 尾翼直角边分别吸台面接缝与箭体竖棱, 四片风车形布置 —— 火箭
    根部四个方向都有三角斜撑闭环;
  - 导流坡道顶边整边吸台面沿, 坡尾自然落地 (滚珠塔同款);
  - 摆渡桥南缘吸箭体北顶缘、北缘吸塔身墙顶, 双边整边吸合零悬挑;
  - 整流罩与罐顶穹顶均为四片锥顶, 斜棱两两互吸自锁 (摩天大楼金顶
    同款), 对角顺序合拢。

坐标约定与 C++ 端一致: 旋转为欧拉角 (度), R = Rz * Ry * Rx。
用法: python3 tools/generate_rocket_launchpad.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

mb = ModelBuilder()

# =================================================================
# 模块 A: 发射架 —— 3x3 盒式基座 (x 1..4, y 1..4) + 台面 + 导流坡道
# =================================================================
for i, x0 in enumerate(range(1, 4)):
    mb.wall_ns(f"m_s_{i}", x0, 1.0, 0, "gray")    # 南墙 y=1
    mb.wall_ns(f"m_n_{i}", x0, 4.0, 0, "gray")    # 北墙 y=4
for i, y0 in enumerate(range(1, 4)):
    mb.wall_ew(f"m_w_{i}", 1.0, y0, 0, "gray")    # 西墙 x=1
    mb.wall_ew(f"m_e_{i}", 4.0, y0, 0, "gray")    # 东墙 x=4

# ---- 环形地坪 (南排 + 西列 + 东列, 均吸墙底边) ---------------------
for i, x0 in enumerate(range(1, 4)):
    mb.flat(f"ap_s_{i}", x0, 0, 0.0, "green")
for i, y0 in enumerate(range(1, 4)):
    mb.flat(f"ap_w_{i}", 0, y0, 0.0, "green")
    mb.flat(f"ap_e_{i}", 4, y0, 0.0, "green")

# ---- 发射台面 (3x3, z=1): 周边压墙顶, 中央片最后落位 ----------------
DECK_ORDER = [(1, 1), (2, 1), (3, 1), (1, 2), (3, 2), (1, 3), (2, 3), (3, 3),
              (2, 2)]
for x0, y0 in DECK_ORDER:
    mb.flat(f"deck_{x0}_{y0}", x0, y0, 1.0, "yellow")

# ---- 导流坡道: 台面东西沿口向外放坡, 坡尾落地 ----------------------
mb.ramp("deflector_e", "+x", 4.0, 2, 1.0, "orange")
mb.ramp("deflector_w", "-x", 1.0, 2, 1.0, "orange")

# =================================================================
# 模块 B: 火箭 —— 台面中央 [2,3]x[2,3] 双级箭体 + 尾翼 + 整流罩
# =================================================================
for stage, z0, color in (("1", 1, "red"), ("2", 2, "cyan")):
    mb.wall_ns(f"r{stage}_s", 2, 2.0, z0, color)
    mb.wall_ns(f"r{stage}_n", 2, 3.0, z0, color)
    mb.wall_ew(f"r{stage}_w", 2.0, 2, z0, color)
    mb.wall_ew(f"r{stage}_e", 3.0, 2, z0, color)

# ---- 尾翼: 直角三角形风车形布置, 竖边吸箭体竖棱、横边吸台面接缝 ----
mb.brace("fin_sw", (2.0, 2.0, 1.0), "-x", "red")
mb.brace("fin_se", (3.0, 2.0, 1.0), "-y", "red")
mb.brace("fin_ne", (3.0, 3.0, 1.0), "+x", "red")
mb.brace("fin_nw", (2.0, 3.0, 1.0), "+y", "red")

# ---- 整流罩: 等腰四坡锥顶, 斜棱两两自锁 (apex z=3.866) -------------
FAIRING = mb.hat4("fairing", 2, 2, 3.0, "purple")

# =================================================================
# 模块 C: 勤务塔 —— 与发射架共享北墙中片起塔, 1x1 塔身 [2,3]x[4,5]
# =================================================================
mb.wall_ew("t0_w", 2.0, 4, 0, "blue")     # 底层其余三面 (南面共享 m_n_1)
mb.wall_ew("t0_e", 3.0, 4, 0, "blue")
mb.wall_ns("t0_n", 2, 5.0, 0, "blue")
for lv in (1, 2, 3):
    mb.wall_ns(f"t{lv}_s", 2, 4.0, lv, "blue")
    mb.wall_ns(f"t{lv}_n", 2, 5.0, lv, "blue")
    mb.wall_ew(f"t{lv}_w", 2.0, 4, lv, "blue")
    mb.wall_ew(f"t{lv}_e", 3.0, 4, lv, "blue")
mb.flat("t_cap", 2, 4, 4.0, "yellow")             # 塔顶平台
mb.spire_ns("t_antenna", 2, 4.0, 4.0, "red")      # 天线塔尖

# ---- 模块 D: 摆渡桥 —— 南缘吸箭体二级顶缘, 北缘吸塔身墙顶 ----------
mb.flat("crew_arm", 2, 3, 3.0, "yellow")

# =================================================================
# 模块 E: 罐区 —— 东侧地坪外接 2 座 1x1 燃料罐 + 等边四坡穹顶
# =================================================================
for tag, y0 in (("a", 1), ("b", 3)):
    mb.wall_ns(f"tk{tag}_s", 5, float(y0), 0, "cyan")
    mb.wall_ns(f"tk{tag}_n", 5, float(y0 + 1), 0, "cyan")
    mb.wall_ew(f"tk{tag}_w", 5.0, y0, 0, "cyan")
    mb.wall_ew(f"tk{tag}_e", 6.0, y0, 0, "cyan")
TANK_A_DOME = mb.hat4("tka_dome", 5, 1, 1.0, "yellow",
                      shape="equilateral_triangle")
TANK_B_DOME = mb.hat4("tkb_dome", 5, 3, 1.0, "yellow",
                      shape="equilateral_triangle")

# =================================================================
# 教程步骤 (18 步): 按模块分章 —— 发射架 -> 火箭逐级对接 -> 勤务塔 ->
# 摆渡桥对接 -> 罐区
# =================================================================
mb.step(
    "发射架·南墙与西墙: 沿 3x3 基座轮廓立 6 片灰色墙 (南面 y=1, 西面 x=1), "
    "转角竖边互吸。",
    ["m_s_0", "m_s_1", "m_s_2", "m_w_0", "m_w_1", "m_w_2"],
    tip="发射架是标准盒式框架 (T01) —— 火箭的全部重量将沿墙面直下。",
)
mb.step(
    "发射架·北墙与东墙: 补齐另外两面各 3 片, 3x3 盒式基座合围。",
    ["m_n_0", "m_n_1", "m_n_2", "m_e_0", "m_e_1", "m_e_2"],
    highlight=["m_s_0", "m_w_0"],
    tip="北墙中片 (x 2..3) 之后还要兼作勤务塔的第一层南墙, 务必对正。",
)
mb.step(
    "环形地坪: 基座南、西、东三面各铺 3 片绿色地坪, 地坪边吸墙底。",
    ["ap_s_0", "ap_s_1", "ap_s_2",
     "ap_w_0", "ap_w_1", "ap_w_2", "ap_e_0", "ap_e_1", "ap_e_2"],
    highlight=["m_s_1", "m_w_1", "m_e_1"],
    tip="北面不铺 —— 那里是勤务塔的位置。",
)
mb.step(
    "发射台面: 3x3 共 9 片黄色台面封顶, 先铺四周 8 片压住墙顶, 中央 1 片"
    "最后落位。",
    [f"deck_{x0}_{y0}" for x0, y0 in DECK_ORDER],
    highlight=["m_s_1", "m_n_1"],
    tip="中央片四条边同时吸住四邻 —— 上方完全开敞, 手从正上方放入即可。",
)
mb.step(
    "导流坡道: 台面东西沿口各挂 1 片橙色 30 度坡道, 坡尾自然落地 —— "
    "点火时烈焰就沿它导向两侧。",
    ["deflector_e", "deflector_w"],
    highlight=["deck_3_2", "deck_1_2"],
    tip="坡道顶边与台面沿口整边贴合, 坡尾不需要任何支撑。",
)
mb.step(
    "火箭一级对接: 台面正中 [2,3]x[2,3] 立起 4 片红色一级箭体, "
    "底边吸台面接缝, 转角竖棱互吸。",
    ["r1_s", "r1_e", "r1_n", "r1_w"],
    highlight=["deck_2_2"],
    tip="箭体立在台面网格线上, 四周各留一圈台面 —— 那是尾翼的位置。",
)
mb.step(
    "尾翼斜撑: 4 片红色直角三角形按风车形绕箭体一圈, 竖边吸箭体竖棱、"
    "横边吸台面接缝 —— T14 斜撑不是装饰, 每片都双边整边吸合。",
    ["fin_sw", "fin_se", "fin_ne", "fin_nw"],
    highlight=["r1_s", "r1_e"],
    tip="风车形让四个方向都有三角闭环, 箭体根部从此纹丝不动。",
)
mb.step(
    "火箭二级对接: 4 片青色二级箭体整边压上一级顶缘 —— 第二次级间对接。",
    ["r2_s", "r2_e", "r2_n", "r2_w"],
    highlight=["r1_s", "r1_n"],
    tip="上下两级完全对齐, 磁条整边贴合吸力才最强。",
)
mb.step(
    "整流罩合拢: 4 片紫色等腰三角形在二级顶收成锥形整流罩, 按对角顺序"
    "合拢, 四条斜棱两两互吸自锁成环。",
    FAIRING,
    highlight=["r2_s", "r2_e"],
    tip="最后一片要同时吸住两条斜棱 —— 慢慢按下去听到双'嗒'才算到位。",
)
mb.step(
    "勤务塔基座: 发射架北墙中片兼作塔身南面, 补 3 片蓝色墙围出 1x1 塔基 "
    "[2,3]x[4,5]。",
    ["t0_w", "t0_e", "t0_n"],
    highlight=["m_n_1"],
    tip="共享墙是模块间的第一处对接面 —— 塔与发射架从地基起就是一体。",
)
mb.step(
    "勤务塔第 2 层: 塔身四面各 1 片, 整边压在塔基墙顶上。",
    ["t1_s", "t1_w", "t1_e", "t1_n"],
    highlight=["t0_n", "t0_w"],
    tip="从这层起塔身高过发射台面, 注意扶稳下层再放片。",
)
mb.step(
    "勤务塔第 3 层: 再上一层 4 片, 塔身与火箭二级同高。",
    ["t2_s", "t2_w", "t2_e", "t2_n"],
    highlight=["t1_s", "t1_e"],
    tip="塔身与箭体之间始终留 1 格净空 —— 那是摆渡桥的跨度。",
)
mb.step(
    "勤务塔第 4 层: 塔身升到 4 层, 高过整流罩根部。",
    ["t3_s", "t3_w", "t3_e", "t3_n"],
    highlight=["t2_s", "t2_n"],
    tip="高塔单手扶稳、另一手放片, 一次一面墙。",
)
mb.step(
    "塔顶平台与天线: 1 片黄色平台封顶, 平台南沿立 1 根红色天线塔尖。",
    ["t_cap", "t_antenna"],
    highlight=["t3_s", "t3_n"],
    tip="天线是全模型最高点 (约 5 格) —— 发射场的避雷针。",
)
mb.step(
    "摆渡桥对接: 1 片黄色平板横跨塔身与火箭之间的净空 —— 南缘整边吸住"
    "二级箭体北顶缘, 北缘整边吸住塔身第 3 层墙顶。这一次对接把火箭、"
    "摆渡桥、勤务塔、发射架锁成一个大环!",
    ["crew_arm"],
    highlight=["r2_n", "t2_s"],
    tip="两edge同时对缝再水平压下; 对接完成后轻推塔身, 全场应整体联动。",
)
mb.step(
    "燃料罐 A 罐体: 东侧地坪外立 4 片青色罐壁 [5,6]x[1,2], 西壁吸住地坪边。",
    ["tka_w", "tka_s", "tka_n", "tka_e"],
    highlight=["ap_e_0"],
    tip="罐区与导流坡道错开一格 —— 烈焰导向的正是两罐之间的空档。",
)
mb.step(
    "燃料罐 A 穹顶: 4 片黄色等边三角形对角合拢成罐顶穹顶。",
    TANK_A_DOME,
    highlight=["tka_s", "tka_e"],
    tip="与整流罩同款自锁锥顶, 只是换成了等边三角形的矮穹顶。",
)
mb.step(
    "燃料罐 B: 第二座燃料罐 [5,6]x[3,4] 一次装完 —— 4 片罐壁 + 4 片穹顶, "
    "发射场落成, 倒计时开始!",
    ["tkb_w", "tkb_s", "tkb_n", "tkb_e"] + TANK_B_DOME,
    highlight=["tka_s"],
    tip="两座罐关于导流坡道对称; 摆渡桥撤开的那天, 就是点火的日子。",
)

mb.finalize(
    model_id="rocket_launchpad_01",
    name="火箭发射台",
    name_en="Rocket Launchpad 01",
    description=(
        "分体对接的垂直总装现场: 3x3 盒式发射架托起双级火箭, 一级、二级、"
        "整流罩逐级对接, 四片直角三角尾翼风车形双边吸合锁住箭体根部; "
        "勤务塔与发射架共享一片墙拔地四层, 塔顶平台伸出摆渡桥与二级箭体"
        "整边对接, 把塔-桥-箭-架锁成大环; 东西导流坡道落地, 罐区双燃料罐"
        "等边穹顶收尾 —— 教程完整复刻真实火箭的发射准备流程。"
    ),
    difficulty=4,
    tags=["火箭", "航天", "发射台", "模块对接", "盒式框架"],
    min_pieces=50,
    min_steps=18,
)
