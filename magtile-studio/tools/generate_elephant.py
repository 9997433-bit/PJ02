#!/usr/bin/env python3
"""生成模型 data/models/elephant_01.json (大象)。

第四批模型 ⑦: 野生动物主题 —— 全库第一只长鼻动物:
四腿方柱踩着草原垫, 3x3 箱式身躯双层围墙; 头颅是抬高一层的
2x3 方箱, 头盘不是悬挑 —— 东沿骑在身躯前墙顶, 西沿中央落在
直通地面的象鼻柱顶上, 双端受力如桥; 两片粉色大耳从头环底边
垂挂下来, 侧竖边再吸身躯前墙一道; 一对透明象牙沿 30 度翘出,
尾巴在背板东沿翘起 —— 长鼻着地, 稳如泰山。

结构总览 (世界单位: 1.0 = 正方形磁力片边长):
  - 草原垫: 6x3 绿色平铺                                   18 片
  - 四腿: 4 根方柱 (z 0..1)                                 4 片
  - 身躯底盘: 3x3 平铺 (四角骑腿顶)                          9 片
  - 身躯围墙: 12 片 x 2 层 (z 1..3)                        24 片
  - 背板: 3x3 平铺 (z=3)                                    9 片
  - 象鼻柱: 3 片叠柱 (x=0 中线, z 0..3)                      3 片
  - 头盘: 2x3 平铺 (z=3, 东骑身躯西沿, 西中落鼻柱)            6 片
  - 头环: 10 片围墙 (z 3..4)                                10 片
  - 头顶: 3 条长方形横盖 (z=4, 短边接墙顶)                   3 片
  - 大耳: 每侧 2 片粉色垂挂 (z 2..3)                         4 片
  - 象牙: 2 片透明垂挂 + 尾巴 1 片 + 草丛 2 片               5 片
  合计 95 片, 18 个教程步骤, 3 种磁力片形状。

几何要点:
  - 头盘双端受力: 东沿三片吸身躯西墙顶+背板西沿 (T 形双吸),
    西沿中央一片落在象鼻柱顶 —— 头颅前伸却零悬挑;
  - 大耳顶边同时吸头环底边 (共面) 与头盘南北沿 (垂直), 侧竖边
    再吸身躯前墙竖边, 一片耳朵三向受力;
  - 象牙垂直下挂零重力力矩: 顶边共面吸额头墙底、垂直吸头盘
    西沿, 侧竖边再吸象鼻柱 —— 三向受力不是悬挑。

用法: python3 tools/generate_elephant.py  (在 magtile-studio 目录下运行)
"""

from magtile_gen import ModelBuilder

b = ModelBuilder()

# =================================================================
# 1. 草原垫 (z=0): 6x3 绿色平铺 (x 0..6, y 0..3)
# =================================================================
for x in range(6):
    for y in range(3):
        b.flat(f"pad_{x}_{y}", x, y, 0.0, "green")

# =================================================================
# 2. 四腿 (z 0..1): 方柱踩着草原垫南北沿
# =================================================================
b.wall_ns("leg_fs", 2, 0.0, 0, "gray")    # 前南腿
b.wall_ns("leg_fn", 2, 3.0, 0, "gray")    # 前北腿
b.wall_ns("leg_rs", 4, 0.0, 0, "gray")    # 后南腿
b.wall_ns("leg_rn", 4, 3.0, 0, "gray")    # 后北腿

# =================================================================
# 3. 身躯 (x 2..5, y 0..3, z 1..3): 底盘 + 双层围墙 + 背板
# =================================================================
for x in (2, 3, 4):
    for y in (0, 1, 2):
        b.flat(f"blly_{x}_{y}", x, y, 1.0, "gray")
for lv in (1, 2):
    for x in (2, 3, 4):
        b.wall_ns(f"bd_s{lv}_{x}", x, 0.0, lv, "gray")
    for x in (2, 3, 4):
        b.wall_ns(f"bd_n{lv}_{x}", x, 3.0, lv, "gray")
    for y in (0, 1, 2):
        b.wall_ew(f"bd_w{lv}_{y}", 2.0, y, lv, "gray")
    for y in (0, 1, 2):
        b.wall_ew(f"bd_e{lv}_{y}", 5.0, y, lv, "gray")
for x in (2, 3, 4):
    for y in (0, 1, 2):
        b.flat(f"back_{x}_{y}", x, y, 3.0, "gray")

# =================================================================
# 4. 象鼻柱 (x=0 中线, z 0..3): 3 片叠柱直通地面
# =================================================================
for lv in (0, 1, 2):
    b.wall_ew(f"trunk_{lv}", 0.0, 1, lv, "gray")

# =================================================================
# 5. 头颅 (x 0..2, y 0..3, z 3..4): 头盘 + 头环 + 头顶
# =================================================================
for x in (0, 1):
    for y in (0, 1, 2):
        b.flat(f"hd_{x}_{y}", x, y, 3.0, "gray")
for x in (0, 1):
    b.wall_ns(f"hr_s_{x}", x, 0.0, 3, "gray")
for x in (0, 1):
    b.wall_ns(f"hr_n_{x}", x, 3.0, 3, "gray")
for y in (0, 1, 2):
    b.wall_ew(f"hr_w_{y}", 0.0, y, 3, "gray")
for y in (0, 1, 2):
    b.wall_ew(f"hr_e_{y}", 2.0, y, 3, "gray")
for y in (0, 1, 2):
    b.flat_rect(f"ht_{y}", 0, y, 4.0, "gray", axis="x")

# =================================================================
# 6. 大耳 (z 2..3): 每侧 2 片粉色垂挂在头环底边下
# =================================================================
for x in (0, 1):
    b.wall_ns(f"ear_s_{x}", x, 0.0, 2, "pink")
for x in (0, 1):
    b.wall_ns(f"ear_n_{x}", x, 3.0, 2, "pink")

# =================================================================
# 7. 象牙 (垂挂在象鼻两侧) + 尾巴 + 草丛
# =================================================================
b.wall_ew("tusk_s", 0.0, 0, 2, "clear")
b.wall_ew("tusk_n", 0.0, 2, 2, "clear")
b.crest_ew("tail", 5.0, 1, 3.0, "gray")
b.crest_ns("tuft_w", 0, 0.0, 0.0, "green")
b.crest_ns("tuft_e", 5, 0.0, 0.0, "green")

# =================================================================
# 教程步骤 (18 步)
# =================================================================
b.step(
    "铺西半草原: 9 片绿色正方形铺出象鼻落脚的空地。",
    [f"pad_{x}_{y}" for x in (0, 1, 2) for y in (0, 1, 2)],
    tip="大象要来了 —— 草原垫是全身连通的根基。",
)
b.step(
    "铺东半草原: 再 9 片, 6x3 草原合拢。",
    [f"pad_{x}_{y}" for x in (3, 4, 5) for y in (0, 1, 2)],
    highlight=["pad_2_1"],
    tip="两半草原长边互吸, 四条腿就踩在草沿上。",
)
b.step(
    "立四腿: 4 根灰色方柱站上草原南北沿。",
    ["leg_fs", "leg_fn", "leg_rs", "leg_rn"],
    highlight=["pad_2_0", "pad_4_2"],
    tip="柱底整边吸草沿 —— 象腿如柱, 一步一响。",
)
b.step(
    "架身躯底盘: 9 片正方形拼成 3x3, 四角骑上腿顶。",
    [f"blly_{x}_{y}" for x in (2, 3, 4) for y in (0, 1, 2)],
    highlight=["leg_fs", "leg_rn"],
    tip="底盘四角各吸一根腿顶边, 中央拼缝互吸成网。",
)
b.step(
    "围身躯下环南墙: 3 片立上底盘南沿。",
    ["bd_s1_2", "bd_s1_3", "bd_s1_4"],
    highlight=["blly_2_0"],
    tip="墙底整边吸底盘边沿, 竖边逐片互锁。",
)
b.step(
    "围身躯下环北墙: 北沿再立 3 片。",
    ["bd_n1_2", "bd_n1_3", "bd_n1_4"],
    highlight=["blly_2_2"],
    tip="南北墙夹住底盘 —— 象身开始鼓起来。",
)
b.step(
    "封身躯下环西东墙: 前胸后臀各 3 片, 下环成筒。",
    ["bd_w1_0", "bd_w1_1", "bd_w1_2", "bd_e1_0", "bd_e1_1", "bd_e1_2"],
    highlight=["bd_s1_2", "bd_n1_4"],
    tip="转角竖边互吸, 空心方筒抗弯远胜单片墙。",
)
b.step(
    "叠身躯上环南墙: 3 片对缝叠上下环。",
    ["bd_s2_2", "bd_s2_3", "bd_s2_4"],
    highlight=["bd_s1_2"],
    tip="上下对缝, 象身长到两层高。",
)
b.step(
    "叠身躯上环北墙: 北面同样叠 3 片。",
    ["bd_n2_2", "bd_n2_3", "bd_n2_4"],
    highlight=["bd_n1_2"],
    tip="两层围墙的身躯 —— 大象的分量感就在这里。",
)
b.step(
    "封身躯上环西东墙: 再 6 片, 身躯方筒到顶。",
    ["bd_w2_0", "bd_w2_1", "bd_w2_2", "bd_e2_0", "bd_e2_1", "bd_e2_2"],
    highlight=["bd_w1_0", "bd_e1_2"],
    tip="前胸墙顶将来要驮头盘 —— 这是头颅的东支点。",
)
b.step(
    "盖背板: 9 片正方形压住身躯墙顶。",
    [f"back_{x}_{y}" for x in (2, 3, 4) for y in (0, 1, 2)],
    highlight=["bd_s2_2"],
    tip="背板每片都吸墙顶边, 象背从此能驮东西。",
)
b.step(
    "立象鼻柱: 3 片灰色立板在正前方中线叠到 z=3。",
    ["trunk_0", "trunk_1", "trunk_2"],
    highlight=["pad_0_1"],
    tip="象鼻直通地面 —— 它是头颅的西支点, 不只是鼻子。",
)
b.step(
    "架头盘: 6 片正方形东沿骑身躯前墙顶, 西沿中央落鼻柱顶。",
    ["hd_1_0", "hd_1_1", "hd_1_2", "hd_0_1", "hd_0_0", "hd_0_2"],
    highlight=["bd_w2_1", "trunk_2", "back_2_1"],
    tip="头盘双端受力如桥 —— 头颅前伸却零悬挑。",
)
b.step(
    "围头环南北墙: 4 片立上头盘南北沿。",
    ["hr_s_0", "hr_s_1", "hr_n_0", "hr_n_1"],
    highlight=["hd_0_0", "hd_1_2"],
    tip="头环底边就是大耳的挂点, 先立墙后挂耳。",
)
b.step(
    "封头环西东墙: 额头 3 片, 后脑 3 片, 头环成筒。",
    ["hr_w_0", "hr_w_1", "hr_w_2", "hr_e_0", "hr_e_1", "hr_e_2"],
    highlight=["hr_s_0", "hr_n_1"],
    tip="后脑墙立在头盘与背板的接缝上, 头身锁成一体。",
)
b.step(
    "盖头顶: 3 条灰色长方形横盖头环, 短边搭在东西墙顶。",
    ["ht_0", "ht_1", "ht_2"],
    highlight=["hr_w_1", "hr_e_1"],
    tip="长板两端短边各吸一面墙顶 —— 头顶也是双端受力。",
)
b.step(
    "挂粉色大耳: 每侧 2 片从头环底边垂挂, 侧竖边再吸前胸墙。",
    ["ear_s_0", "ear_s_1", "ear_n_0", "ear_n_1"],
    highlight=["hr_s_0", "bd_s2_2"],
    tip="耳顶边共面吸头环底边、垂直吸头盘沿 —— 一片耳朵三向受力。",
)
b.step(
    "挂象牙翘尾巴: 2 片透明象牙贴着象鼻两侧垂挂, 尾巴在背板"
    "东沿翘起, 两丛草点缀脚边 —— 大象登场!",
    ["tusk_s", "tusk_n", "tail", "tuft_w", "tuft_e"],
    highlight=["trunk_2", "hd_0_0", "back_4_1"],
    tip="象牙垂直下挂零力矩, 顶边双吸+侧边吸鼻柱 —— 长鼻着地, 稳如泰山。",
)

b.finalize(
    model_id="elephant_01",
    name="大象",
    name_en="Elephant 01",
    description=(
        "野生动物主题: 全库第一只长鼻动物 —— 四腿方柱踩草原垫, "
        "3x3 箱式身躯双层围墙; 头颅是抬高一层的 2x3 方箱, 头盘"
        "双端受力如桥: 东沿骑身躯前墙顶 (与背板西沿 T 形双吸), "
        "西沿中央落在直通地面的象鼻柱顶 —— 头颅前伸却零悬挑; "
        "两片粉色大耳从头环底边垂挂, 顶边共面+垂直双吸、侧竖边"
        "再吸前胸墙, 一片耳朵三向受力; 一对透明象牙沿 30 度翘出, "
        "尾巴在背板东沿翘起 —— 长鼻着地, 稳如泰山。"
    ),
    difficulty=4,
    tags=["动物", "大象", "野生动物", "草原"],
    min_pieces=90,
    min_steps=18,
)
